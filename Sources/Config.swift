    /// Главная сайта: корень или «/<регион>/<язык>/» (kliko.kz/kz/ru/) без параметров. Её место занимает нативная лента.
    static func главная(_ u: URL) -> Bool {
        guard свой(u) != nil else { return false }
        let ч = URLComponents(url: u, resolvingAgainstBaseURL: true)
        guard (ч?.query ?? "").isEmpty else { return false }      // ?bye=1 после выхода и прочее — не трогаем
        return u.path.isEmpty || u.path.range(of: "^/([a-z]{2}/[a-z]{2}/?)?$", options: .regularExpression) != nil
    }

    /// Абсолютный URL для картинок/относительных путей из API.
    static func url(_ path: String) -> URL? {
        let p = path.trimmingCharacters(in: .whitespaces)
        if p.isEmpty { return nil }
        if p.hasPrefix("http://") || p.hasPrefix("https://") { return URL(string: p) }
        return URL(string: p, relativeTo: apiBase)
    }

    /// Страница сайта под языком телефона: «/kz/<язык>/<хвост>» — так сайт сам ссылается на свои страницы (выбор языка в
    /// шапке главной: /kz/ru/, /kz/kz/, /kz/en/, /kz/ar/; «Разместить» — /kz/ru/cabinet?go=add). Язык — тот же, что у
    /// текстов приложения: казахский телефона на сайте — «kz», прочие, кроме английского и арабского, — русский.
    static func страницаСайта(_ хвост: String) -> URL? {
        let язык = String((Locale.preferredLanguages.first ?? "ru").prefix(2))
        let код: String
        switch язык {
        case "kk": код = "kz"
        case "en", "ar": код = язык
        default: код = "ru"
        }
        return url("/kz/\(код)/" + хвост)
    }


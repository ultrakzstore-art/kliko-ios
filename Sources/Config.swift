import Foundation

/// Точка конфигурации. Меняй apiBase, если домен/стейдж другой.
enum Config {
    /// Базовый URL продакшена. Все запросы идут сюда (URLSession сам держит cookie-сессию).
    static let apiBase = URL(string: "https://kliko.kz")!

    /// Нативная лента вместо главной сайта (этап 1 перехода на SwiftUI, 25.09.2026). false — приложение снова
    /// целиком веб-обёртка с превью ленты на запуске, как в 1.7: рубильник на случай, если лента API подведёт.
    static let нативнаяЛента = true
    /// Нативная карточка объявления из ленты (этап 2, 25.09.2026). false — нажатие в ленте открывает страницу сайта.
    static let нативнаяКарточка = true
    /// Нативный чат: список диалогов и переписка (этап 3, 25.09.2026). false — значок сообщений в ленте не показывается.
    static let нативныйЧат = true
    /// Писать сообщения из приложения (dm.php send/open с куками веб-сессии и CSRF страницы). Включено для проверки
    /// на живом сайте (владелец 25.09.2026: «первый вариант, запусти сборку с отправкой»). Не дошло — false: переписка
    /// останется в приложении, а ответ снова пойдёт через сайт («Ответить на сайте»).
    static let нативныйЧатОтправка = true
    /// Нижние вкладки: Лента, Сообщения, (Разместить), Кабинет (этап 4, 25.09.2026). false — лента одна, сообщения и
    /// кабинет — кнопками в её шапке, как на этапе 3.
    static let нижниеВкладки = true
    /// Страница подачи объявления на сайте — вкладка «Разместить». nil — вкладки нет: адрес страницы в приложении не
    /// записан, а угаданный адрес, ведущий в 404, хуже отсутствующей кнопки.
    static let адресПодачи: String? = nil
    /// Избранное: сердечко на карточке и в объявлении, вкладка «Избранное» (этап 5, 25.09.2026). Хранится на телефоне:
    /// API избранного на сайте приложению неизвестно, а угаданный адрес хуже никакого. false — ни сердечек, ни вкладки.
    static let избранное = true
    /// Недавнее: полоса «Вы смотрели» над лентой и история поиска подсказками под полем (этап 6, 25.09.2026). Тоже на
    /// телефоне и по той же причине, что избранное. false — ни полосы, ни подсказок, и на диск ничего не пишется.
    static let недавние = true
    /// Похожие объявления внизу карточки: тот же раздел из api/listings.php (cat=, per=12), до 10 штук (этап 7,
    /// 25.09.2026). На телефон ничего не пишет. false — полосы нет, и лишнего запроса к ленте тоже.
    static let похожие = true
    /// Пуши и ссылки сайта открывают нативные экраны (этап 8, 25.09.2026): /marketplace?item= — карточку во вкладке
    /// «Лента», /cabinet.php?s=messages — вкладку «Сообщения». Только входы снаружи (пуш, kliko://, универсальная
    /// ссылка) и только при нижних вкладках; прочие адреса — сайтом. false — всё снаружи снова ведёт на сайт.
    static let нативныеСсылки = true

    /// Главная сайта: корень или «/<регион>/<язык>/» (kliko.kz/kz/ru/) без параметров. Её место занимает нативная лента.
    static func главная(_ u: URL) -> Bool {
        guard свой(u) != nil else { return false }
        let ч = URLComponents(url: u, resolvingAgainstBaseURL: true)
        guard (ч?.query ?? "").isEmpty else { return false }      // ?bye=1 после выхода и прочее — не трогаем
        return u.path.isEmpty || u.path.range(of: "^/([a-z]{2}/[a-z]{2}/?)?$", options: .regularExpression) != nil
    }

    /// Абсолютный URL для картинок/относительных путей из API.
    static func url(_ path: String) -> URL? {
        let p = path.trimmingCharacters(in: .whitespaces)
        if p.isEmpty { return nil }
        if p.hasPrefix("http://") || p.hasPrefix("https://") { return URL(string: p) }
        return URL(string: p, relativeTo: apiBase)
    }

    /// Своя схема приложения: kliko://open?u=<полный адрес страницы>. Регистрирует CFBundleURLTypes (project.yml).
    static let scheme = "kliko"

    /// Домены, которые нам разрешено открывать. www — на случай ссылки со старой визитки: сайт сам перебросит.
    private static let свои: Set<String> = ["kliko.kz", "www.kliko.kz"]

    /// Адрес нашего домена или nil.
    private static func свой(_ u: URL) -> URL? {
        guard let h = u.host?.lowercased(), свои.contains(h) else { return nil }
        guard let s = u.scheme?.lowercased(), s == "https" || s == "http" else { return nil }
        return u
    }

    /**
     Внешняя ссылка → страница, которую грузим в WebView.

     Приходят три вида:
       · универсальная ссылка (`applinks:kliko.kz`) — уже https нашего домена, iOS проверила домен за нас;
       · `widgetURL` плашки сделки — тоже https нашего домена;
       · `kliko://open?u=<адрес>` — кнопка «Открыть в приложении» на самом сайте.

     🔴 ПРОВЕРЯЕМ ДОМЕН, А НЕ ВЕРИМ НА СЛОВО. Схему kliko:// может вызвать кто угодно — страница в Safari,
     письмо, чужая программа. Без проверки вызов `kliko://open?u=https://чужой.сайт` открыл бы чужую страницу
     ВНУТРИ нашей обёртки, где живут куки сессии: чужой скрипт оказался бы на одном экране с кабинетом.
     Адрес не наш — не открываем ничего (nil), а не «на всякий случай главную»: молчание честнее подмены.
     */
    static func deepLink(_ u: URL) -> URL? {
        if let s = u.scheme?.lowercased(), s == "https" || s == "http" { return свой(u) }
        guard u.scheme?.lowercased() == scheme else { return nil }
        let части = URLComponents(url: u, resolvingAgainstBaseURL: false)
        guard let цель = части?.queryItems?.first(where: { $0.name == "u" })?.value, !цель.isEmpty else {
            return apiBase                      // kliko:// без адреса — просто «открой приложение»
        }
        guard let адрес = URL(string: цель) else { return nil }
        return свой(адрес)
    }
}

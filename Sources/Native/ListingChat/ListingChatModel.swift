 Гостю, как и чату этапа 3, запрос не шлём: сразу окно входа. Всё — в памяти экрана: ушёл с экрана — ничего не осталось.

 ПИШЕМ ПРОДАВЦУ (владелец, прогулка новичка, пункт 2 — сознательно не как у сайта):

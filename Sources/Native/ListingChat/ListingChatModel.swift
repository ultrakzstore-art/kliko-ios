     не в сети, отвечает помощник Kliko» — пока продавец не на связи и не в чате;
   · «Позвать продавца» нет: первое сообщение покупателя в этом чате само уходит с force_escalate — продавец получает
     уведомление (как mkChatCallSeller), без лишнего сообщения в переписке;

import SwiftUI
import UIKit

/**
 НИЖНИЕ ВКЛАДКИ — ЭТАП 4 ПЕРЕХОДА НА SWIFTUI (владелец 25.09.2026: «давай следующий этап» → «Нижние вкладки»).

 Лента и Сообщения — настоящие вкладки: нативные экраны со своей навигацией, каждая помнит, где человек остановился.
 Разместить и Кабинет — пока страницы сайта: нажатие открывает страницу в веб-обёртке, а выбранной остаётся прежняя
 вкладка. Вернулся человек со страницы на главную — он снова в ленте (RootWebView прячет и показывает этот слой).
 С этапа 9 Кабинет — тоже настоящая вкладка (CabinetView, Config.нативныйКабинет); страницы кабинета открывает она.

 🔴 НА СТРАНИЦАХ САЙТА ПАНЕЛИ НЕТ. Внутри страницы у сайта своя нижняя навигация; вторая, нативная, над ней — это
 две панели друг над другом и половина экрана под кнопками. Поэтому вкладки живут только на нативных экранах, а
 на сайте человек ходит его навигацией, и «Главная» сайта возвращает его сюда.

 Счётчик на «Сообщениях» — непрочитанные из dm.php list: при показе вкладок, при возврате со страницы сайта и раз в
 минуту, пока приложение на экране. С этапа 11 то же число — на иконке приложения (ЗначокПриложения). С этапа 38
 (Config.чатОбъявления) к нему добавлены лиды — chat.php?action=leads, как у нижней панели сайта (ChatListModel).
 */
struct NativeTabsView: View {
    enum Вкладка: Hashable { case лента, избранное, сообщения, разместить, кабинет }

    @ObservedObject private var мост = WebBridge.shared
    /// Пуш и ссылки сайта (этап 8): куда вести — объявление в ленте или сообщения.
    @ObservedObject private var маршрут = NativeRouter.shared
    /// Этап 42: мастер подачи и правки — поверх вкладок (камера панели, «+ Добавить объявление», «Изменить», ссылки).
    @ObservedObject private var подача = ПодачаОкно.shared
    @StateObject private var чаты = ChatListModel()
    @State private var вкладка: Вкладка = .лента
    /// Стеки ленты и сообщений — здесь, а не внутри вкладок, чтобы ссылка могла положить в них экран (этап 8).
    /// Избранного — тоже: быстрое действие с иконки (этап 10) возвращает его к списку.
    @State private var путьЛенты = NavigationPath()
    @State private var путьСообщений = NavigationPath()
    @State private var путьИзбранного = NavigationPath()
    /// Стек кабинета — с путём, как остальные: по нему видно, открыто ли что-то поверх (панель сайта прячется).
    @State private var путьКабинета = NavigationPath()
    /// Поле поиска ленты активно — быстрое действие «Поиск» с иконки (этап 10) ставит true, «Отменить» в поле — false.
    @State private var поискЛенты = false
    /// «Поиск» с иконки пришёл, а поле трогать рано: на экране замок Face ID или страница сайта. Ждём их ухода.
    @State private var поискЖдёт = false
    /// Сохранённый поиск для ленты (этап 12: уведомление о новых, строка кабинета). Лента подставит его и обнулит.
    @State private var найтиВЛенте: ИскомоеЛенты? = nil
    /// Объявление в правой колонке ленты на iPad (этап 14) — здесь, чтобы ссылка могла выбрать его, а не класть в стек.
    @State private var выбранноеВЛенте: Listing? = nil
    /// Широкое окно iPad — лента в две колонки (ДвеКолонки.включены), и объявление из ссылки встаёт в правую.
    @Environment(\.horizontalSizeClass) private var ширинаОкна
    @ObservedObject private var замок = AppLock.shared
    @Environment(\.scenePhase) private var фаза
    /// TestFlight 1.10: общее состояние входа — вошёл или вышел человек, чат и заявки перечитываются сразу.
    @ObservedObject private var сессия = СессияПриложения.shared
    /// Лента на главной или в разделе — подпись первой кнопки панели сайта (этап 27).
    @ObservedObject private var вид = ВидСайта.shared
    /// Клавиатура на экране — панель сайта (этап 27) под ней прячется.
    @State private var клавиатура = false
    /// TestFlight 1.10: окно «Категории» панели на главной (ЛистКатегорийСайта) и что сделать, когда оно закроется.
    @State private var листКатегорий = false
    @State private var послеЛистаКатегорий: ДействиеЛистаКатегорий? = nil

    let открыть: (URL) -> Void
    let открытьСайт: () -> Void

    var body: some View {
        Group {
            /* Этап 27: нижняя панель как на сайте вместо системных вкладок. Выключен вид — системные вкладки этапа 4. */
            if Config.дизайнКакНаСайте {
                вкладкиСайта
            } else {
                вкладкиСистемы
            }
        }
        /* Разместить и Кабинет (без нативного кабинета) — не экраны, а переходы на сайт: открываем страницу и
           оставляем выбранной прежнюю вкладку, чтобы по возвращении человек был там, где был. */
        .onChange(of: вкладка) { было, стало in
            switch стало {
            case .разместить:
                вкладка = было
                if let путь = Config.адресПодачи, let u = Config.url(путь) { открыть(u) }
            case .кабинет:
                if !Config.нативныйКабинет {
                    вкладка = было
                    if let u = Config.url("/cabinet.php") { открыть(u) }
                }
            default:
                break
            }
        }
        /* Вернулся со страницы сайта на главную — в ленту: «Главная» сайта ведёт на главную, а главная здесь — лента.
           Слой вернула ссылка снаружи (этап 8) — вкладку выберет она. */
        .onChange(of: мост.лентаВидна) { _, видна in
            guard видна else { return }
            if маршрут.цель == nil { вкладка = .лента }
            открытьПоиск()
            Task { await обновитьСчётчик() }
        }
        .onChange(of: замокНаЭкране) { _, наЭкране in
            if !наЭкране { открытьПоиск() }
        }
        /* Ссылка снаружи (этап 8) — в следующем такте: вместе с целью мост мог вернуть слой на экран, а в каком порядке
           SwiftUI позовёт два onChange, он не обещает; обработчик выше иначе мог бы перебить вкладку лентой. */
        .onChange(of: маршрут.цель) { _, новая in
            guard новая != nil else { return }
            Task { @MainActor in принятьСсылку() }
        }
        /* Этап 11: после каждой сверки списка с сайтом — число на иконку (Config.значокНепрочитанных). */
        .onChange(of: чаты.сверка) { _, _ in
            ЗначокПриложения.поставить(чаты.непрочитано)
        }
        /* Холодный старт по пушу или ссылке: цель пришла раньше, чем вкладки появились. */
        .onAppear { принятьСсылку() }
        /* TestFlight 1.10: человек сменился (вход, выход, другой аккаунт) — экраны гостя «Войдите» и число
           непрочитанных перечитываются, не дожидаясь следующего показа. Возврат в приложение — сверка входа. */
        .onChange(of: сессия.смена) { _, _ in
            Task { await послеСменыЧеловека() }
        }
        .onChange(of: фаза) { _, стала in
            if стала == .active { СессияПриложения.shared.запросить() }
        }
        /* Этап 42: мастер подачи на весь экран — как #add-screen сайта, без панели и вкладок под ним. */
        .fullScreenCover(item: $подача.цель) { цель in
            ЭкранПодачи(цель: цель, открыть: открыть)
        }
        /* Вход, «Стать продавцом», удаление аккаунта, обращение в поддержку — листом поверх вкладок, а не страницей
           сайта (ОкнаПриложения). */
        .modifier(СлойОконПриложения(открыть: открыть))
        /* Этап 25: светлые часы над зелёной шапкой — только пока выбрана лента (ВидСайта, SceneDelegate). */
        .onChange(of: вкладка) { _, стало in ВидСайта.shared.вкладкаЛенты = стало == .лента }
        .task {
            guard Config.нативныйЧат else { return }
            while !Task.isCancelled {
                await обновитьСчётчик()
                /* Этап 45: у кабинета сайта число «Чата» сверяется раз в 12 с (loadLeadsBadge), пока вкладка видна;
                   без инбокса кабинета — прежняя минута. */
                let пауза: UInt64 = Config.нативныеСообщенияКабинета ? 12_000_000_000 : 60_000_000_000
                try? await Task.sleep(nanoseconds: пауза)
            }
        }
    }

    // MARK: - Панель как на сайте (этап 27)

    /**
     Вкладки без TabView: системную панель TabView не перекрасить в панель сайта, а спрятать её надёжно на каждом экране
     стека нельзя (.toolbar(.hidden, for: .tabBar) держится только у того экрана, где задан). Поэтому экраны лежат
     стопкой, а панель — слоем снизу поверх них. Место под неё оставляет корень каждой вкладки (оставитьМестоПодПанелью).

     Владелец 25.09.2026, проверка на телефоне, сборка 33: до этого панель была вставкой снизу (safeAreaInset) на всю
     стопку — экран, положенный в стек, её не получал, и панель закрывала поле ввода переписки. Теперь над любым экраном
     поверх корня вкладки панели нет (открытоПоверх), как у сайта: внутри чата и объявления нижней навигации нет.

     Лента не уходит из дерева, её только прячут — как прежняя вкладка, она помнит прокрутку, поиск и открытую карточку.
     Избранное, сообщения и кабинет создаются при выборе, как системная вкладка при показе: их списки перечитываются при
     каждом открытии (.task), а стеки избранного и сообщений живут здесь (путьИзбранного, путьСообщений) и не теряются.
     */
    private var вкладкиСайта: some View {
        ZStack {
            NativeFeedView(открыть: открыть, открытьСайт: открытьСайт, путь: $путьЛенты, поиск: $поискЛенты,
                           найти: $найтиВЛенте, выбранное: $выбранноеВЛенте)
                .environment(\.стекСайта, .лента)
                .environment(\.местоПодПанельюСайта, местоПодПанелью)
                .opacity(вкладка == .лента ? 1 : 0)
                .allowsHitTesting(вкладка == .лента)
                .accessibilityHidden(вкладка != .лента)
            if вкладка == .избранное && Config.избранное {
                NavigationStack(path: $путьИзбранного) {
                    FavoritesView(открыть: открыть, вЛенту: { вкладка = .лента })
                        .оставитьМестоПодПанелью(местоПодПанелью)
                        .navigationDestination(for: Listing.self) { товар in
                            ListingDetailView(товар: товар, открыть: открыть)
                        }
                        .чатМаршруты(открыть: открыть)
                }
                .environment(\.стекСайта, .избранное)
            }
            if вкладка == .сообщения && Config.нативныйЧат {
                NavigationStack(path: $путьСообщений) {
                    ChatListView(модель: чаты, открыть: открыть)
                        .оставитьМестоПодПанелью(местоПодПанелью)
                        .чатМаршруты(открыть: открыть)
                }
            }
            if вкладка == .кабинет && Config.нативныйКабинет {
                NavigationStack(path: $путьКабинета) {
                    CabinetView(открыть: открыть)
                        .оставитьМестоПодПанелью(местоПодПанелью)
                }
            }
        }
        .tint(Theme.акцент)
        /* Слой, а не вставка (владелец 25.09.2026, проверка на телефоне, сборка 33): безопасную зону стопки не меняем —
           место под панель оставляют корни вкладок, а экраны поверх корня панель не закрывает, её там нет. Рамка стопки
           кончается над домашней полосой — панель встаёт туда же, где стояла вставкой, фон уходит до края экрана. */
        .overlay(alignment: .bottom) {
            if панельВидна {
                НижняяПанельСайта(выбран: пунктПанели, главная: вид.главная, непрочитано: чаты.непрочитано,
                                  показатьИзбранное: Config.избранное,
                                  выбрать: { пункт in нажатьПанель(пункт) },
                                  камера: камераПанели)
            }
        }
        /* Этап 28: страница объявления сверху выбранной вкладки и её фото под часами — часы светлые (SceneDelegate). */
        .onChange(of: карточкаВкладки?.фотоПодЧасами ?? false, initial: true) { _, светлые in
            if вид.фотоПодЧасами != светлые { вид.фотоПодЧасами = светлые }
        }
        .onReceive(NotificationCenter.default.publisher(for: UIResponder.keyboardWillShowNotification)) { уведомление in
            клавиатура = КлавиатураНаЭкране.видна(уведомление)
        }
        .onReceive(NotificationCenter.default.publisher(for: UIResponder.keyboardWillHideNotification)) { _ in
            клавиатура = false
        }
        .sheet(isPresented: $листКатегорий, onDismiss: { выполнитьПослеЛистаКатегорий() }) {
            ЛистКатегорийСайта(карта: Config.картаОбъявлений, выбрать: { действие in
                послеЛистаКатегорий = действие
                листКатегорий = false
            })
        }
    }

    /// Выбор в окне «Категории» — после того, как лист уехал: карта в стек ленты, раздел — в ленту, страница — сайтом.
    private func выполнитьПослеЛистаКатегорий() {
        guard let действие = послеЛистаКатегорий else { return }
        послеЛистаКатегорий = nil
        switch действие {
        case .карта:
            вкладка = .лента
            путьЛенты.append(КартаЦель.объявления)
        case .раздел(let ключ):
            if ключ == "jobs" {
                if let адрес = Config.страницаСайта("?cat=jobs") { открыть(адрес) }
            } else {
                вкладка = .лента
                найтиВЛенте = ИскомоеЛенты(текст: "", раздел: ключ)
            }
        case .страница(let адрес):
            открыть(адрес)
        }
    }

    /**
     Панель сайта на экране: нет клавиатуры и над корнем выбранной вкладки ничего не открыто. Этап 29: на странице
     объявления панели нет — там своя, «Связаться» со звонком и WhatsApp (как у сайта: .ulx-bbar прячется, пока открыто
     объявление); с исправлений с телефона (сборка 33) так же — в переписке и на любом экране поверх корня.
     */
    private var панельВидна: Bool {
        !клавиатура && !открытоПоверх && карточкаВкладки == nil
    }

    /// Место внизу корня вкладки под панелью: пока клавиатура на экране, панели нет — и места не нужно.
    private var местоПодПанелью: CGFloat {
        клавиатура ? 0 : НижняяПанельСайта.высота
    }

    /**
     Над корнем выбранной вкладки открыт экран (владелец 25.09.2026, проверка на телефоне, сборка 33: панель стояла над
     перепиской и закрывала поле ввода). Смотрим путь стека: он меняется в момент нажатия и возврата и знает о каждом
     NavigationLink(value:) — переписка, объявление, похожие, продавец, сравнение из ряда. Отметка страницы объявления
     (onAppear/onDisappear) здесь не годится: объявление «исчезает», когда поверх него кладут переписку «Связаться», и
     панель вернулась бы над чатом. Экран без пути (сравнение избранного) отмечается сам — ВидСайта.поверх.

     iPad в две колонки: путь ленты — стек правой колонки. Выбранное объявление — её корень, панель остаётся; открыли
     поверх него переписку или похожие — панель прячется, как на iPhone: иначе она закрыла бы поле ввода и там.
     */
    private var открытоПоверх: Bool {
        switch вкладка {
        case .лента:
            return !путьЛенты.isEmpty || вид.поверх.values.contains(.лента)
        case .избранное:
            return !путьИзбранного.isEmpty || вид.поверх.values.contains(.избранное)
        case .сообщения:
            return !путьСообщений.isEmpty
        case .кабинет:
            return !путьКабинета.isEmpty
        case .разместить:
            return false
        }
    }

    /**
     Страница объявления как на сайте сверху стека выбранной вкладки (этапы 28–29) или nil. Лента в две колонки iPad
     (этап 14) не в счёт: там объявление — правая колонка рядом с лентой, а не экран поверх неё, и панель остаётся.
     Ленту при уходе на другую вкладку только прячут — её страница остаётся «на экране», поэтому смотрим стек вкладки.
     */
    private var карточкаВкладки: КарточкаНаЭкране? {
        let стек: СтекСайта
        switch вкладка {
        case .лента:
            guard !ДвеКолонки.включены(ширинаОкна) else { return nil }
            стек = .лента
        case .избранное:
            стек = .избранное
        default:
            return nil
        }
        return вид.карточки.values.first { $0.стек == стек }
    }

    /// Выбранный пункт панели — по вкладке. «Разместить» — не экран, пункта у него нет.
    private var пунктПанели: НижняяПанельСайта.Пункт? {
        switch вкладка {
        case .лента: return .категории
        case .избранное: return .избранное
        case .сообщения: return .чат
        case .кабинет: return .кабинет
        case .разместить: return nil
        }
    }

    /// Камера — мастер подачи (этап 42, Config.нативнаяПодача), без него — страница подачи на сайте в той же обёртке.
    /// Адреса нет — кнопки нет.
    private var камераПанели: (() -> Void)? {
        if Config.нативнаяПодача {
            return { _ = ПодачаОкно.shared.открыть(.новое) }
        }
        guard let хвост = Config.подачаНаСайте, let адрес = Config.страницаСайта(хвост) else { return nil }
        let открытьСтраницу = открыть
        return { открытьСтраницу(адрес) }
    }

    /**
     Нажатие на панели. Повторное нажатие выбранного пункта — к началу его стека, как у системных вкладок. Первая кнопка
     на ленте — как «Категории»/«Главная» сайта: открыто что-то поверх — назад к ленте, лента в разделе или поиске — на
     главную (сохранённый поиск «пусто» через тот же вход, что уведомление этапа 12).
     */
    private func нажатьПанель(_ пункт: НижняяПанельСайта.Пункт) {
        switch пункт {
        case .категории:
            if вкладка != .лента {
                вкладка = .лента
            } else if !путьЛенты.isEmpty {
                путьЛенты = NavigationPath()
            } else if !вид.главная {
                найтиВЛенте = ИскомоеЛенты(текст: "", раздел: "")
            } else {
                /* TestFlight 1.10: на главной «Категории» — окно категорий, как mhCats сайта (карта, разделы, справка). */
                листКатегорий = true
            }
        case .избранное:
            if вкладка == .избранное { путьИзбранного = NavigationPath() } else { вкладка = .избранное }
        case .чат:
            guard Config.нативныйЧат else {
                if let u = Config.url("/cabinet.php?s=messages") { открыть(u) }
                return
            }
            if вкладка == .сообщения { путьСообщений = NavigationPath() } else { вкладка = .сообщения }
        case .кабинет:
            /* Без нативного кабинета onChange ниже вернёт прежнюю вкладку и откроет /cabinet.php, как на этапе 4. */
            if вкладка == .кабинет { путьКабинета = NavigationPath() } else { вкладка = .кабинет }
        }
    }

    private var вкладкиСистемы: some View {
        TabView(selection: $вкладка) {
            NativeFeedView(открыть: открыть, открытьСайт: открытьСайт, путь: $путьЛенты, поиск: $поискЛенты,
                           найти: $найтиВЛенте, выбранное: $выбранноеВЛенте)
                .tabItem { Label(TabsText.т("feed"), systemImage: "square.grid.2x2") }
                .tag(Вкладка.лента)

            /* Этап 5: избранное — своя вкладка со своим стеком; маршруты карточки и чата те же, что у ленты. */
            if Config.избранное {
                NavigationStack(path: $путьИзбранного) {
                    FavoritesView(открыть: открыть, вЛенту: { вкладка = .лента })
                        .navigationDestination(for: Listing.self) { товар in
                            ListingDetailView(товар: товар, открыть: открыть)
                        }
                        .чатМаршруты(открыть: открыть)
                }
                .tabItem { Label(FavoritesText.т("title"), systemImage: "heart") }
                .tag(Вкладка.избранное)
            }

            if Config.нативныйЧат {
                NavigationStack(path: $путьСообщений) {
                    ChatListView(модель: чаты, открыть: открыть)
                        .чатМаршруты(открыть: открыть)
                }
                .tabItem { Label(TabsText.т("messages"), systemImage: "bubble.left.and.bubble.right") }
                .badge(чаты.непрочитано)
                .tag(Вкладка.сообщения)
            }

            if Config.адресПодачи != nil {
                Color.clear
                    .tabItem { Label(TabsText.т("post"), systemImage: "plus.circle") }
                    .tag(Вкладка.разместить)
            }

            /* Этап 9: кабинет — нативный экран настроек со своим стеком. Рубильник выключен — как на этапе 4: пустая
               вкладка, нажатие открывает /cabinet.php (onChange ниже). */
            if Config.нативныйКабинет {
                /* Этап 41: стек с путём и здесь — ссылка ?go=items кладёт в него «Мои объявления». */
                NavigationStack(path: $путьКабинета) {
                    CabinetView(открыть: открыть)
                }
                .tabItem { Label(TabsText.т("cabinet"), systemImage: "person.crop.circle") }
                .tag(Вкладка.кабинет)
            } else {
                Color.clear
                    .tabItem { Label(TabsText.т("cabinet"), systemImage: "person.crop.circle") }
                    .tag(Вкладка.кабинет)
            }
        }
        .tint(Theme.green)
    }

    /// Ссылка снаружи — на её экран, и цель обнуляем: тот же пуш второй раз экран не откроет. Объявление ложится
    /// поверх того, что было открыто в ленте, — «Назад» вернёт туда. Сообщения — к списку, а не в открытую переписку:
    /// пуш о новом сообщении, и видно его в списке.
    private func принятьСсылку() {
        guard let куда = маршрут.цель else { return }
        маршрут.цель = nil
        поискЖдёт = false             // «Поиск», ждавший замка, перебит новым входом — поле не трогаем
        switch куда {
        case .объявление(let номер):
            вкладка = .лента
            if ДвеКолонки.включены(ширинаОкна) {
                /* Этап 14: на iPad лента и карточка рядом — объявление встаёт в правую колонку вместо выбранного,
                   открытое над тем (похожие, чат) снимаем: иначе новое оказалось бы под ним. */
                путьЛенты = NavigationPath()
                выбранноеВЛенте = Listing(номер: номер)
            } else {
                путьЛенты.append(Listing(номер: номер))
            }
        case .сообщения:
            guard Config.нативныйЧат else { return }
            путьСообщений = NavigationPath()
            вкладка = .сообщения
            Task { await чаты.загрузить() }
        case .поиск:
            /* Этап 10: к корню ленты — поле поиска там. Фокус — когда поле видно (открытьПоиск). */
            путьЛенты = NavigationPath()
            вкладка = .лента
            поискЖдёт = true
            открытьПоиск()
        case .избранное:
            guard Config.избранное else { return }
            путьИзбранного = NavigationPath()
            вкладка = .избранное
        case .найти(let искомое):
            /* Этап 12: к корню ленты, а поиск подставит сама лента (NativeFeedView.применитьСнаружи) — модель у неё. */
            путьЛенты = NavigationPath()
            вкладка = .лента
            найтиВЛенте = искомое
        case .моиОбъявления:
            /* Этап 41: ?go=items — вкладка «Кабинет» и «Мои объявления» поверх неё: «Назад» ведёт в кабинет. */
            guard NativeRouter.доступна(.моиОбъявления) else { return }
            var путь = NavigationPath()
            путь.append(КабинетЦель.моиОбъявления)
            путьКабинета = путь
            вкладка = .кабинет
        case .подача:
            /* Этап 42: ?go=add — мастер подачи поверх той вкладки, где человек был. */
            _ = ПодачаОкно.shared.открыть(.новое)
        case .правка(let номер):
            _ = ПодачаОкно.shared.открыть(.правка(номер))
        case .сделки:
            /* Этап 43: ?go=deals — вкладка «Кабинет» и «Мои сделки» поверх неё: «Назад» ведёт в кабинет. */
            guard NativeRouter.доступна(.сделки) else { return }
            var путь = NavigationPath()
            путь.append(КабинетЦель.сделки)
            путьКабинета = путь
            вкладка = .кабинет
        case .сделка(let номер):
            /* Этап 43: ?deal=<id> — как у сайта (showDeals, затем openDeal): «Мои сделки», поверх — карточка. */
            guard NativeRouter.доступна(.сделка(id: номер)) else { return }
            var путь = NavigationPath()
            путь.append(КабинетЦель.сделки)
            путь.append(КабинетЦель.сделка(номер))
            путьКабинета = путь
            вкладка = .кабинет
        case .заявки:
            /* Этап 45: ?s=requests — вкладка «Кабинет» и «Заявки рядом» поверх неё. */
            guard NativeRouter.доступна(.заявки) else { return }
            var путь = NavigationPath()
            путь.append(КабинетЦель.заявки)
            путьКабинета = путь
            вкладка = .кабинет
        case .обращение(let номер):
            /* Этап 45: ?ticket=<id> — переписка по обращению поверх кабинета. */
            guard NativeRouter.доступна(.обращение(id: номер)) else { return }
            var путь = NavigationPath()
            путь.append(КабинетЦель.обращение(номер))
            путьКабинета = путь
            вкладка = .кабинет
        case .пароль:
            /* Этап 46: ?open=password — вкладка «Кабинет» и окно пароля поверх неё. */
            guard NativeRouter.доступна(.пароль) else { return }
            путьКабинета = NavigationPath()
            вкладка = .кабинет
            НастройкиМодель.shared.открытьПароль()
        case .кошелёк:
            /* Этап 47: ?go=wallet, ?payout=back — вкладка «Кабинет» и экран кошелька поверх неё (задание ссылки экран
               заберёт сам). */
            guard NativeRouter.доступна(.кошелёк) else { return }
            var путь = NavigationPath()
            путь.append(КабинетЦель.кошелёк)
            путьКабинета = путь
            вкладка = .кабинет
        case .баллы:
            /* Этап 47: ?s=points — «Баллы» поверх кабинета. */
            guard NativeRouter.доступна(.баллы) else { return }
            var путь = NavigationPath()
            путь.append(КабинетЦель.баллы)
            путьКабинета = путь
            вкладка = .кабинет
        }
    }

    /// Замок Face ID закрывает экран: поле поиска под ним фокус не получает, иначе клавиатура встала бы над замком.
    private var замокНаЭкране: Bool { замок.enabled && (замок.locked || замок.cover) }

    /// «Поиск» с иконки — поле в фокус, когда его видно: слой на экране, замка нет. Пауза — чтобы SwiftUI успел
    /// сменить вкладку и показать корень ленты: поле, которого ещё нет на экране, фокус не примет.
    private func открытьПоиск() {
        guard поискЖдёт, мост.лентаВидна, !замокНаЭкране else { return }
        поискЖдёт = false
        Task { @MainActor in
            try? await Task.sleep(nanoseconds: 400_000_000)
            поискЛенты = true
        }
    }

    /// TestFlight 1.10: после входа или выхода — список чатов (и инбокс кабинета) и «Заявки рядом».
    private func послеСменыЧеловека() async {
        if Config.нативныйЧат { await чаты.загрузить() }
        if Config.нативныеСообщенияКабинета && сессия.вошёл == true && ЗаявкиМодель.shared.нуженВход {
            await ЗаявкиМодель.shared.загрузить(ждать: false)
        }
    }

    /// Непрочитанные — только когда вкладки на экране и приложение активно: опрос из фона и из-под страницы сайта
    /// тратил бы батарею впустую.
    private func обновитьСчётчик() async {
        guard Config.нативныйЧат, мост.лентаВидна, фаза == .active else { return }
        await чаты.загрузить()
    }
}

/// Подписи вкладок на языке телефона (kk/ru/en/ar).
enum TabsText {
    static func т(_ ключ: String) -> String {
        let язык = String((Locale.preferredLanguages.first ?? "ru").prefix(2))
        let словарь = тексты[язык] ?? тексты["ru"]!
        return словарь[ключ] ?? тексты["ru"]![ключ] ?? ключ
    }

    private static let тексты: [String: [String: String]] = [
        "ru": ["feed": "Лента", "messages": "Сообщения", "post": "Разместить", "cabinet": "Кабинет"],
        "kk": ["feed": "Лента", "messages": "Хабарламалар", "post": "Жариялау", "cabinet": "Кабинет"],
        "en": ["feed": "Feed", "messages": "Messages", "post": "Sell", "cabinet": "Account"],
        "ar": ["feed": "الإعلانات", "messages": "الرسائل", "post": "انشر", "cabinet": "الحساب"]
    ]
}

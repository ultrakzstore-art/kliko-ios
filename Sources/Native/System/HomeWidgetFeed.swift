import Foundation
import WidgetKit

/**
 ВИДЖЕТ «Kliko» НА ДОМАШНЕМ ЭКРАНЕ — ЧТО ЕМУ ПИШЕТ ПРИЛОЖЕНИЕ (владелец 07.10.2026: «сделай всё, что предлагаешь»).

 Малый виджет — непрочитанные сообщения и активные сделки; средний — две-три активные сделки со статусом и доставкой.
 Снимок (СнимокВиджетаKliko, Shared/KlikoWidgetSnapshot.swift) лежит в общем контейнере App Group group.kz.kliko.app:
   · непрочитанные — там же, где число на иконке (ЗначокПриложения.поставить, после каждой сверки «Чата»);
   · сделки — из my_deals&role=both (СделкиМодель.обновитьЗначок): незакрытые, первые три, подпись статуса как в списке
     сделок, доставка — из КэшТрека (то, что уже показала карточка «Отслеживание»). Сделки старше 10 минут — сверка заново
     при следующей сверке «Чата» (без ожидания страницы: ждать: false);
   · выход из аккаунта стирает снимок (ЗначокПриложения.снять).
 Перерисовка — WidgetCenter.reloadAllTimelines(), только если содержимое правда сменилось: у WidgetKit бюджет обновлений.
 */
@MainActor
enum ВиджетKliko {
    /// Сверка сделок ради виджета уже идёт.
    private static var сверяем = false
    private static let сверятьРаз: TimeInterval = 600

    /// Непрочитанных стало столько (вошедший человек).
    static func непрочитано(_ число: Int) {
        var с = СнимокВиджетаKliko.прочитать()
        с.вошёл = true
        с.непрочитано = max(0, число)
        сохранить(с)
        guard Config.нативныеСделки, !сверяем, Date().timeIntervalSince(с.сделкиСверены) > сверятьРаз else { return }
        сверяем = true
        Task { @MainActor in
            await СделкиМодель.shared.обновитьЗначок()
            ВиджетKliko.сверяем = false
        }
    }

    /// Ответ my_deals&role=both — активные сделки в снимок.
    static func сделки(_ сырые: [Any]) {
        let все = сырые.compactMap { з -> СделкаКратко? in
            guard let d = з as? [String: Any] else { return nil }
            return СделкаКратко(d)
        }
        let активные = все.filter { !$0.закрыта }
        var с = СнимокВиджетаKliko.прочитать()
        с.вошёл = true
        с.активных = активные.count
        с.сделки = активные.prefix(3).map { сделка in
            let вид = ВидСтатусаСделки.для(сделка.статус)
            var строка = СнимокВиджетаKliko.Сделка(
                id: сделка.id,
                название: сделка.название.isEmpty ? СделкиText.т("deal_word") : сделка.название,
                статус: вид.текст,
                символ: вид.символ,
                роль: сделка.продавец ? "seller" : "buyer")
            if let трек = КэшТрека.прочитать(сделка.id), трек.содержательно {
                строка.доставка = [трек.название, трек.статус.коротко].filter { !$0.isEmpty }.joined(separator: " · ")
            }
            return строка
        }
        с.сделкиСверены = Date()
        сохранить(с)
    }

    /// Выход из аккаунта: чужие непрочитанные и сделки с домашнего экрана — долой.
    static func стереть() {
        var пусто = СнимокВиджетаKliko()
        пусто.обновлено = Date()
        if СнимокВиджетаKliko.записать(пусто) { WidgetCenter.shared.reloadAllTimelines() }
    }

    /// Запись; перерисовка — только если сменилось то, что виджет показывает (даты сверки не в счёт).
    private static func сохранить(_ новый: СнимокВиджетаKliko) {
        let прежний = СнимокВиджетаKliko.прочитать()
        var сравнить = новый
        сравнить.обновлено = прежний.обновлено
        сравнить.сделкиСверены = прежний.сделкиСверены
        var итог = новый
        let сменилось = сравнить != прежний
        итог.обновлено = сменилось ? Date() : прежний.обновлено
        СнимокВиджетаKliko.записать(итог)
        if сменилось { WidgetCenter.shared.reloadAllTimelines() }
    }
}

@MainActor
extension View {
    /// Экран стека, который можно собрать заново по номеру (объявление, сделка, переписка).
    func местоЭкрана(_ шаг: ШагМеста, вкладка: КлючВкладкиМеста? = nil) -> some View {
        modifier(ОтметкаЭкранаМеста(шаг: шаг, вкладка: вкладка))
    }

    /// Карточка ленты на экране — для места прокрутки.
    func местоВЛенте(_ номер: String) -> some View {
        modifier(ОтметкаКарточкиМеста(номер: номер))
    }

    /// Прокрутка ленты: подключить модель, вернуть отбор и прыгнуть к месту из снимка.
    func местоЛенты(модель: FeedModel, прокрутка: ScrollViewProxy) -> some View {
        modifier(ПрокруткаЛентыМеста(модель: модель, прокрутка: прокрутка))
    }

    /// Вкладки: запись при уходе в фон, глубины стеков для отметок, восстановление на запуске.
    func местоВкладок(вкладка: Binding<NativeTabsView.Вкладка>, лента: Binding<NavigationPath>,
                      избранное: Binding<NavigationPath>, сообщения: Binding<NavigationPath>,
                      кабинет: Binding<NavigationPath>, чаты: ChatListModel, двеКолонки: Bool) -> some View {
        /* Хранитель — сейчас, при построении вкладок, до их onAppear: он запоминает, была ли ссылка на запуске, раньше,
           чем принятьСсылку её заберёт. */
        _ = МестоПриложения.shared
        return modifier(МестоВкладок(вкладка: вкладка, путьЛенты: лента, путьИзбранного: избранное,
                              путьСообщений: сообщения, путьКабинета: кабинет, чаты: чаты, двеКолонки: двеКолонки))
    }
}

@MainActor
private struct ОтметкаЭкранаМеста: ViewModifier {
    let шаг: ШагМеста
    let вкладка: КлючВкладкиМеста?
    @Environment(\.глубиныМеста) var глубины

    func body(content: Content) -> some View {
        content.onAppear {
            guard let глубины else { return }
            МестоПриложения.shared.отметить(шаг, вкладка: вкладка, глубины: глубины)
        }
    }
}

@MainActor
private struct ОтметкаКарточкиМеста: ViewModifier {
    let номер: String

    func body(content: Content) -> some View {
        content
            .onAppear { МестоПриложения.shared.карточкаПоявилась(номер) }
            .onDisappear { МестоПриложения.shared.карточкаУшла(номер) }
    }
}

@MainActor
private struct ПрокруткаЛентыМеста: ViewModifier {
    let модель: FeedModel
    let прокрутка: ScrollViewProxy
    @ObservedObject var место = МестоПриложения.shared
    /// Корень ленты на экране: под открытым объявлением прокрутка подождёт возврата.
    @State var наЭкране = false

    func body(content: Content) -> some View {
        content
            .onAppear {
                наЭкране = true
                место.подключитьЛенту(модель)
                прокрутить(виден: true)
            }
            .onDisappear { наЭкране = false }
            .onChange(of: место.прокрутитьК) { _, _ in прокрутить(виден: наЭкране) }
    }

    private func прокрутить(виден: Bool) {
        guard виден, let цель = место.прокрутитьК else { return }
        место.прокрутитьК = nil
        let прокрутка = self.прокрутка
        Task { @MainActor in
            try? await Task.sleep(nanoseconds: 150_000_000)
            прокрутка.scrollTo(цель, anchor: .top)
        }
    }
}

@MainActor
private struct МестоВкладок: ViewModifier {
    @Binding var вкладка: NativeTabsView.Вкладка
    @Binding var путьЛенты: NavigationPath
    @Binding var путьИзбранного: NavigationPath
    @Binding var путьСообщений: NavigationPath
    @Binding var путьКабинета: NavigationPath
    let чаты: ChatListModel
    let двеКолонки: Bool
    @Environment(\.scenePhase) var фаза

    func body(content: Content) -> some View {
        content
            .environment(\.глубиныМеста, ГлубиныМеста(лента: путьЛенты.count, избранное: путьИзбранного.count,
                                                      сообщения: путьСообщений.count, кабинет: путьКабинета.count))
            .onAppear {
                отметитьВкладку(вкладка)
                восстановить()
            }
            .onChange(of: вкладка) { _, стала in отметитьВкладку(стала) }
            .onChange(of: путьЛенты) { было, стало in
                МестоПриложения.shared.путьСменился(.лента, было: было.count, стало: стало.count)
            }
            .onChange(of: путьИзбранного) { было, стало in
                МестоПриложения.shared.путьСменился(.избранное, было: было.count, стало: стало.count)
            }
            .onChange(of: путьСообщений) { было, стало in
                МестоПриложения.shared.путьСменился(.сообщения, было: было.count, стало: стало.count)
            }
            .onChange(of: путьКабинета) { было, стало in
                МестоПриложения.shared.путьСменился(.кабинет, было: было.count, стало: стало.count)
            }
            .onChange(of: фаза) { _, стала in
                if стала == .background {
                    МестоПриложения.shared.ушлиВФон()
                } else if стала == .inactive {
                    МестоПриложения.shared.записать()
                }
            }
    }

    private func отметитьВкладку(_ в: NativeTabsView.Вкладка) {
        if let к = МестоПриложения.ключ(в) { МестоПриложения.shared.вкладка = к }
    }

    private func восстановить() {
        let место = МестоПриложения.shared
        guard let с = место.взятьВкладки() else { return }
        switch с.вкладка {
        case .лента:
            if !двеКолонки && Config.нативнаяКарточка && путьЛенты.isEmpty {
                let путь = Self.путьОбъявлений(с.шаги)
                if !путь.isEmpty {
                    место.собрано(.лента, Array(с.шаги.prefix(путь.count)))
                    путьЛенты = путь
                }
            }
        case .избранное:
            if Config.избранное {
                вкладка = .избранное
                let путь = Self.путьОбъявлений(с.шаги)
                if Config.нативнаяКарточка && путьИзбранного.isEmpty && !путь.isEmpty {
                    место.собрано(.избранное, Array(с.шаги.prefix(путь.count)))
                    путьИзбранного = путь
                }
            }
        case .сообщения:
            if Config.нативныйЧат {
                вкладка = .сообщения
                if case .чат(let номер)? = с.шаги.first { открытьПереписку(номер) }
            }
        case .кабинет:
            if Config.нативныйКабинет {
                вкладка = .кабинет
                let путь = Self.путьКабинета(с.шаги)
                if путьКабинета.isEmpty && !путь.isEmpty {
                    место.собрано(.кабинет, Array(с.шаги.prefix(путь.count)))
                    путьКабинета = путь
                }
            }
        }
        if с.подача { место.вернутьПодачу() }
    }

    private static func путьОбъявлений(_ шаги: [ШагМеста]) -> NavigationPath {
        var путь = NavigationPath()
        for шаг in шаги.prefix(3) {
            guard case .объявление(let номер) = шаг, !номер.isEmpty else { break }
            путь.append(Listing(номер: номер))
        }
        return путь
    }

    /// «Мои объявления» или «Мои сделки» и поверх — карточка сделки. Оплата и подпись — листы, их не открываем.
    private static func путьКабинета(_ шаги: [ШагМеста]) -> NavigationPath {
        var путь = NavigationPath()
        var сделки = false
        for шаг in шаги.prefix(2) {
            switch шаг {
            case .моиОбъявления where путь.isEmpty && NativeRouter.доступна(.моиОбъявления):
                путь.append(КабинетЦель.моиОбъявления)
            case .сделки where путь.isEmpty && NativeRouter.доступна(.сделки):
                путь.append(КабинетЦель.сделки)
                сделки = true
            case .сделка(let номер) where сделки && путь.count == 1 && NativeRouter.доступна(.сделка(id: номер)):
                путь.append(КабинетЦель.сделка(номер))
            default:
                return путь
            }
        }
        return путь
    }

    /// Переписка — по номеру из списка диалогов (имя собеседника не храним): список придёт — открыть.
    private func открытьПереписку(_ номер: String) {
        let чаты = self.чаты
        let путь = $путьСообщений
        let выбранная = $вкладка
        Task { @MainActor in
            if !чаты.загружено { await чаты.загрузить() }
            guard выбранная.wrappedValue == .сообщения, путь.wrappedValue.isEmpty else { return }
            /* Этап 45: список — строки единого инбокса (их читает чаты.загрузить), диалогов dm.php в чаты.диалоги нет.
               Переписка — той же целью, что нажатие строки (переписка, лид). */
            if Config.нативныеСообщенияКабинета {
                guard let строка = ИнбоксМодель.shared.строки.first(where: { $0.номер == номер && !$0.скрыт }) else {
                    return
                }
                путь.wrappedValue.append(строка.цель)
                return
            }
            guard let диалог = чаты.диалоги.first(where: { $0.id == номер }) else { return }
            путь.wrappedValue.append(ЧатЦель.диалог(диалог))
        }
    }
}

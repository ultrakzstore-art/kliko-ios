/**
 С ТОГО ЖЕ МЕСТА (владелец: «если случайно выкинуло с приложения — с того же места начал: фиксация позиции скроллинга
 или места, где он был последний раз»).

 Система выгрузила приложение из памяти, оно упало или его смахнули — при следующем запуске (не позже 12 часов) человек
 возвращается туда, где был:
   · выбранная вкладка;
   · лента: раздел, поиск, фильтры и порядок, «все объявления», «Аренда» и место прокрутки — по номеру первой видимой
     карточки: лента показывается сразу, догружает страницы до этой карточки и один раз прыгает к ней. Карточки уже нет —
     остаёмся у верха;
   · стек выбранной вкладки там, где его дёшево и безопасно собрать по номерам: объявление (лента, избранное),
     «Мои объявления», «Мои сделки» и карточка сделки (кабинет), переписка из списка (сообщения). Листы, оплата, eGov
     и подпись не восстанавливаются никогда;
   · мастер подачи: был открыт новый — открывается снова, а его черновик (ПодачаМодель, 7 дней) спросит «Продолжить?».
 Раскладка витрины и город помнятся и без этого (@AppStorage, ВыборГорода).

 Хранится маленький снимок в UserDefaults — только номера и фильтры, без имён и переписки. Пишется при уходе в фон и не
 чаще раза в 3 секунды при изменениях (на случай падения, когда ухода в фон не бывает). Выход из аккаунта стирает его
 (ВыходНачисто). Ссылка или пуш на запуске важнее снимка — тогда ничего не восстанавливаем. Упало в первые секунды после
 восстановления — в следующий раз начинаем с чистого листа: иначе открытый экран мог бы ронять приложение по кругу.
 */

/// Вкладка в снимке.
enum КлючВкладкиМеста: String, Codable {
    case лента, избранное, сообщения, кабинет
}

/// Экран стека, который собирается заново по номеру.
enum ШагМеста: Codable, Hashable {
    case объявление(String)
    case моиОбъявления
    case сделки
    case сделка(String)
    case чат(String)
}

/// Тип детали в снимке: ключ ptype и название для чипа.
struct ТипДеталиМеста: Codable, Equatable {
    var ключ: String
    var название: String
}

/// Фильтры ленты для снимка (ФильтрыЛенты сами не Codable). Фильтры разделов — необязательные поля: снимок, записанный
/// прежней версией, читается как есть.
struct ФильтрыМеста: Codable, Equatable {
    var сортировка: String
    var ценаОт: Int?
    var ценаДо: Int?
    var состояние: String?
    var проверенные: Bool
    var сФото: Bool
    var годОт: Int?
    var годДо: Int?
    var комнаты: [String]
    var марки: [String]
    var модель: String
    var коробка: [String]
    var топливо: [String]
    /// Фильтры разделов — только ключи и значения: ступени (ключ — ДиапазонФильтра.rawValue), сделка, признаки жилья,
    /// размещение, типы деталей, техника, фасеты и числа электроники (колонка → значение справочника).
    var ступениОт: [String: Double]?
    var ступениДо: [String: Double]?
    var сделка: String?
    var признакиЖилья: [String]?
    var размещение: [String]?
    var типыДеталей: [ТипДеталиМеста]?
    var процессор: String?
    var озуОт: Int?
    var накопительОт: Int?
    var дискретная: Bool?
    var фасеты: [String: [String]]?
    var характеристикиОт: [String: String]?
    var характеристикиДо: [String: String]?

    init(_ ф: ФильтрыЛенты) {
        сортировка = ф.сортировка.rawValue
        ценаОт = ф.ценаОт
        ценаДо = ф.ценаДо
        состояние = ф.состояние?.rawValue
        проверенные = ф.толькоПроверенные
        сФото = ф.сФото
        годОт = ф.годОт
        годДо = ф.годДо
        комнаты = ф.комнаты.sorted()
        марки = ф.марки
        модель = ф.модель
        коробка = ф.коробка
        топливо = ф.топливо
        ступениОт = Self.вСнимок(ф.ступениОт)
        ступениДо = Self.вСнимок(ф.ступениДо)
        сделка = ф.сделка.isEmpty ? nil : ф.сделка
        признакиЖилья = ф.признакиЖилья.isEmpty ? nil : ф.признакиЖилья
        размещение = ф.размещение.isEmpty ? nil : ф.размещение
        типыДеталей = ф.типыДеталей.isEmpty ? nil
            : ф.типыДеталей.map { ТипДеталиМеста(ключ: $0.ключ, название: $0.название) }
        процессор = ф.процессор.isEmpty ? nil : ф.процессор
        озуОт = ф.озуОт
        накопительОт = ф.накопительОт
        дискретная = ф.дискретная ? true : nil
        let фасетыНепустые = ф.фасеты.filter { !$0.value.isEmpty }
        фасеты = фасетыНепустые.isEmpty ? nil : фасетыНепустые
        характеристикиОт = ф.характеристикиОт.isEmpty ? nil : ф.характеристикиОт
        характеристикиДо = ф.характеристикиДо.isEmpty ? nil : ф.характеристикиДо
    }

    /// Ступени — ключами-строками (rawValue): словарь с ключом-перечислением JSON пишет массивом пар.
    private static func вСнимок(_ д: [ДиапазонФильтра: Double]) -> [String: Double]? {
        guard !д.isEmpty else { return nil }
        var итог: [String: Double] = [:]
        for (к, v) in д { итог[к.rawValue] = v }
        return итог
    }

    private static func изСнимка(_ д: [String: Double]?) -> [ДиапазонФильтра: Double] {
        var итог: [ДиапазонФильтра: Double] = [:]
        for (к, v) in д ?? [:] {
            if let диапазон = ДиапазонФильтра(rawValue: к) { итог[диапазон] = v }
        }
        return итог
    }

    var фильтры: ФильтрыЛенты {
        var ф = ФильтрыЛенты()
        if let с = СортировкаЛенты(rawValue: сортировка) { ф.сортировка = с }
        ф.ценаОт = ценаОт
        ф.ценаДо = ценаДо
        ф.состояние = состояние.flatMap { СостояниеТовара(rawValue: $0) }
        ф.толькоПроверенные = проверенные
        ф.сФото = сФото
        ф.годОт = годОт
        ф.годДо = годДо
        ф.комнаты = Set(комнаты)
        ф.марки = марки
        ф.модель = модель
        ф.коробка = коробка
        ф.топливо = топливо
        ф.ступениОт = Self.изСнимка(ступениОт)
        ф.ступениДо = Self.изСнимка(ступениДо)
        ф.сделка = сделка ?? ""
        ф.признакиЖилья = признакиЖилья ?? []
        ф.размещение = размещение ?? []
        ф.типыДеталей = (типыДеталей ?? []).map { ТипДеталиФильтра(ключ: $0.ключ, название: $0.название) }
        ф.процессор = процессор ?? ""
        ф.озуОт = озуОт
        ф.накопительОт = накопительОт
        ф.дискретная = дискретная ?? false
        ф.фасеты = фасеты ?? [:]
        ф.характеристикиОт = характеристикиОт ?? [:]
        ф.характеристикиДо = характеристикиДо ?? [:]
        return ф
    }
}

/// Лента в снимке: что отобрано и где прокрутка.
struct ЛентаМеста: Codable, Equatable {
    var поиск: String
    var раздел: String
    var фильтры: ФильтрыМеста
    var все: Bool
    var аренда: Bool
    /// Номер объявления первой видимой карточки; nil — лента у верха.
    var первый: String?
    /// Её место в ленте — сколько догружать.
    var позиция: Int
}

/// Весь снимок.
struct СнимокМеста: Codable {
    var время: Double
    var вкладка: КлючВкладкиМеста
    var лента: ЛентаМеста?
    /// Стек выбранной вкладки снизу вверх — только известные шаги подряд.
    var шаги: [ШагМеста]
    /// Был открыт мастер новой подачи.
    var подача: Bool
}

/// Ключи UserDefaults — вне класса на главном потоке: их читает и стирание.
enum КлючиМеста {
    static let снимок = "kliko.place.v1"
    static let попытка = "kliko.place.try"
    /// Старше — начинаем с чистого листа.
    static let срок: TimeInterval = 12 * 3600
}

/// Глубина стека каждой вкладки — отметки экранов (местоЭкрана) по ней знают свой уровень.
struct ГлубиныМеста: Equatable {
    var лента = 0
    var избранное = 0
    var сообщения = 0
    var кабинет = 0

    func глубина(_ к: КлючВкладкиМеста) -> Int {
        switch к {
        case .лента: return лента
        case .избранное: return избранное
        case .сообщения: return сообщения
        case .кабинет: return кабинет
        }
    }
}

private struct КлючГлубинМеста: EnvironmentKey {
    static let defaultValue: ГлубиныМеста? = nil
}

extension EnvironmentValues {
    /// nil — экран не во вкладках, отмечать нечего.
    var глубиныМеста: ГлубиныМеста? {
        get { self[КлючГлубинМеста.self] }
        set { self[КлючГлубинМеста.self] = newValue }
    }
}

// MARK: - Хранитель

@MainActor
final class МестоПриложения: ObservableObject {
    static let shared = МестоПриложения()

    /// Ячейка ленты, к которой прокрутить (id ячейки). Единственное, что публикуется: прокрутка ленту не перерисовывает.
    @Published var прокрутитьК: String?

    /// Снимок прошлого запуска (годный по сроку) — читается один раз.
    private var снимокЗапуска: СнимокМеста?
    /// На запуске уже была ссылка или пуш — они важнее снимка.
    private let ссылкаБыла: Bool
    private var вкладкиВзяты = false
    private var лентаВзята = false
    /// Лента ещё догружается до места из снимка — пишем место из снимка, а не верх.
    private var лентаВПути: ЛентаМеста?

    var вкладка: КлючВкладкиМеста = .лента {
        didSet { if вкладка != oldValue { отметитьИзменение() } }
    }
    private var шаги: [КлючВкладкиМеста: [Int: ШагМеста]] = [:]
    /// Стек, собранный восстановлением: нижние экраны при установке пути разом onAppear не получают — отмечаем их сами.
    private var предзапись: [КлючВкладкиМеста: [ШагМеста]] = [:]
    private weak var модельЛенты: FeedModel?
    /// Карточки ленты на экране: номер → сколько ячеек (одно объявление бывает в золотом месте и в обычном).
    private var видимые: [String: Int] = [:]
    private var первый: String?
    private var позиция = 0
    private var отложеннаяЗапись: Task<Void, Never>?

    private init() {
        ссылкаБыла = NativeRouter.shared.цель != nil
        let хранилище = UserDefaults.standard
        /* Прошлый запуск упал сразу после восстановления — не повторяем. */
        if хранилище.object(forKey: КлючиМеста.попытка) != nil {
            хранилище.removeObject(forKey: КлючиМеста.попытка)
            снимокЗапуска = nil
            return
        }
        guard let данные = хранилище.data(forKey: КлючиМеста.снимок),
              let снимок = try? JSONDecoder().decode(СнимокМеста.self, from: данные),
              Date().timeIntervalSince1970 - снимок.время < КлючиМеста.срок else {
            снимокЗапуска = nil
            return
        }
        снимокЗапуска = снимок
    }

    /// Выход из аккаунта: снимок и отметки прочь.
    static func стереть() {
        UserDefaults.standard.removeObject(forKey: КлючиМеста.снимок)
        UserDefaults.standard.removeObject(forKey: КлючиМеста.попытка)
        let место = МестоПриложения.shared
        место.снимокЗапуска = nil
        место.лентаВПути = nil
        место.шаги = [:]
    }

    private var годный: СнимокМеста? {
        guard !ссылкаБыла, NativeRouter.shared.цель == nil else { return nil }
        return снимокЗапуска
    }

    /// Отметка «восстанавливаем»: живём дольше 6 секунд — снимаем.
    private func отметитьПопытку() {
        UserDefaults.standard.set(Date().timeIntervalSince1970, forKey: КлючиМеста.попытка)
        Task { @MainActor in
            try? await Task.sleep(nanoseconds: 6_000_000_000)
            UserDefaults.standard.removeObject(forKey: КлючиМеста.попытка)
        }
    }

    // MARK: Вкладки и стеки

    /// Снимок для вкладок — один раз за запуск и только если есть что восстанавливать.
    func взятьВкладки() -> СнимокМеста? {
        guard !вкладкиВзяты else { return nil }
        вкладкиВзяты = true
        guard let с = годный, с.вкладка != .лента || !с.шаги.isEmpty || с.подача else { return nil }
        отметитьПопытку()
        return с
    }

    /// Экран стека показался на глубине своей вкладки. вкладка nil — переписка: считаем её, только пока открыты
    /// «Сообщения» (маршруты чата общие у всех стеков).
    func отметить(_ шаг: ШагМеста, вкладка своя: КлючВкладкиМеста?, глубины: ГлубиныМеста) {
        let к: КлючВкладкиМеста
        if let своя {
            к = своя
        } else if вкладка == .сообщения {
            к = .сообщения
        } else {
            return
        }
        let уровень = глубины.глубина(к)
        guard уровень > 0, шаги[к]?[уровень] != шаг else { return }
        шаги[к, default: [:]][уровень] = шаг
        отметитьИзменение()
    }

    /// Путь вкладки сменился: назад — убрать то, что выше; один шаг вперёд — отметит новый экран; иначе путь заменили
    /// целиком (ссылка, «к началу») — прежние отметки не про него.
    func путьСменился(_ к: КлючВкладкиМеста, было: Int, стало: Int) {
        var карта = шаги[к] ?? [:]
        if стало < было {
            карта = карта.filter { $0.key <= стало }
        } else if стало != было + 1 {
            карта = [:]
        }
        if let собранный = предзапись.removeValue(forKey: к), собранный.count == стало {
            for (i, шаг) in собранный.enumerated() { карта[i + 1] = шаг }
        }
        шаги[к] = карта
        отметитьИзменение()
    }

    /// Восстановление положило в путь вкладки эти экраны.
    func собрано(_ к: КлючВкладкиМеста, _ стек: [ШагМеста]) {
        предзапись[к] = стек
    }

    private func стек(_ к: КлючВкладкиМеста) -> [ШагМеста] {
        guard let карта = шаги[к] else { return [] }
        var итог: [ШагМеста] = []
        var уровень = 1
        while let шаг = карта[уровень], итог.count < 4 {
            итог.append(шаг)
            уровень += 1
        }
        return итог
    }

    /// Мастер подачи был открыт и черновик жив — открыть его снова (сам спросит «Продолжить?»).
    func вернутьПодачу() {
        guard Config.нативнаяПодача, ПодачаМодель.прочитатьЧерновик() != nil else { return }
        Task { @MainActor in
            try? await Task.sleep(nanoseconds: 700_000_000)
            guard ПодачаОкно.shared.цель == nil else { return }
            ПодачаОкно.shared.открыть(.новое)
        }
    }

    // MARK: Лента

    /// Лента на экране: запомнить модель; первый раз за запуск — вернуть отбор и место из снимка.
    func подключитьЛенту(_ модель: FeedModel) {
        модельЛенты = модель
        guard !лентаВзята else { return }
        лентаВзята = true
        guard let л = годный?.лента else { return }
        let ф = л.фильтры.фильтры
        let какЕсть = л.поиск.isEmpty && л.раздел.isEmpty && ф == ФильтрыЛенты() && !л.все && !л.аренда
        let прокрутка = л.первый != nil && л.позиция >= 2
        guard !какЕсть || прокрутка else { return }
        отметитьПопытку()
        if !какЕсть {
            if л.аренда {
                модель.выбратьАренду()
                if !л.раздел.isEmpty { модель.выбратьРаздел(л.раздел) }
                if !л.поиск.isEmpty {
                    модель.поиск = л.поиск
                    модель.искать()
                }
            } else {
                модель.применить(ИскомоеЛенты(текст: л.поиск, раздел: л.раздел))
            }
            модель.применитьФильтры(ф)
            if л.все { модель.показатьВсе() }
        }
        guard let цель = л.первый, прокрутка else { return }
        лентаВПути = л
        Task { @MainActor in
            await self.дотянуть(модель, до: цель, позиция: л.позиция)
            self.лентаВПути = nil
        }
    }

    /// Ждём выдачу, догружаем страницы до карточки и просим прокрутку. Человек уже листает сам — не мешаем.
    private func дотянуть(_ модель: FeedModel, до цель: String, позиция: Int) async {
        let начало = Date()
        var подгрузок = 0
        while Date().timeIntervalSince(начало) < 25 {
            try? await Task.sleep(nanoseconds: 250_000_000)
            if модель.грузим || модель.сДиска || !модель.ответПришёл { continue }
            if модель.ошибка != nil { return }
            if self.позиция > 6 && self.первый != цель { return }
            let ячейки = модель.видимыеЯчейки
            if let ячейка = ячейки.first(where: { $0.товар.id == цель }) {
                прокрутитьК = ячейка.id
                return
            }
            guard модель.можноЕщё, подгрузок < 12, ячейки.count < позиция + 96,
                  let последняя = модель.лента.last?.товар else { return }
            подгрузок += 1
            модель.дальше(после: последняя)
            /* Дать подгрузке начаться, чтобы не попросить ту же страницу дважды. */
            var ждали = 0
            while !модель.грузим && ждали < 10 {
                try? await Task.sleep(nanoseconds: 100_000_000)
                ждали += 1
            }
        }
    }

    func карточкаПоявилась(_ номер: String) {
        видимые[номер, default: 0] += 1
        пересчитатьПервый()
    }

    /// Ушла — только из счёта: первую пересчитает следующее появление. Иначе, пока карточки по одной уходят под
    /// открытое объявление, «первой» стала бы случайная из оставшихся.
    func карточкаУшла(_ номер: String) {
        guard let n = видимые[номер] else { return }
        видимые[номер] = n > 1 ? n - 1 : nil
    }

    private func пересчитатьПервый() {
        guard let модель = модельЛенты else { return }
        for (i, ячейка) in модель.видимыеЯчейки.enumerated() where видимые[ячейка.товар.id] != nil {
            if первый != ячейка.товар.id || позиция != i {
                первый = ячейка.товар.id
                позиция = i
                отметитьИзменение()
            }
            return
        }
    }

    private func текущаяЛента() -> ЛентаМеста? {
        if let лентаВПути { return лентаВПути }
        guard let м = модельЛенты else { return снимокЗапуска?.лента }
        /* Первая видимая — из этой выдачи; сменили отбор, а новой ещё не видели — без прокрутки. */
        var номер: String? = nil
        var место = 0
        if let первый {
            let ячейки = м.видимыеЯчейки
            if позиция < ячейки.count, ячейки[позиция].товар.id == первый {
                номер = первый
                место = позиция
            } else if let i = ячейки.firstIndex(where: { $0.товар.id == первый }) {
                номер = первый
                место = i
            }
        }
        return ЛентаМеста(поиск: м.действующее.текст, раздел: м.раздел, фильтры: ФильтрыМеста(м.фильтры),
                          все: м.все, аренда: м.аренда, первый: номер, позиция: место)
    }

    // MARK: Запись

    /// Не чаще раза в 3 секунды: прокрутка шлёт появления карточек подряд.
    private func отметитьИзменение() {
        guard отложеннаяЗапись == nil else { return }
        отложеннаяЗапись = Task { @MainActor [weak self] in
            try? await Task.sleep(nanoseconds: 3_000_000_000)
            guard !Task.isCancelled, let self else { return }
            self.отложеннаяЗапись = nil
            self.записать()
        }
    }

    func записать() {
        отложеннаяЗапись?.cancel()
        отложеннаяЗапись = nil
        let снимок = СнимокМеста(время: Date().timeIntervalSince1970, вкладка: вкладка, лента: текущаяЛента(),
                                 шаги: стек(вкладка), подача: ПодачаОкно.shared.цель == .новое)
        guard let данные = try? JSONEncoder().encode(снимок) else { return }
        UserDefaults.standard.set(данные, forKey: КлючиМеста.снимок)
    }

    /// Дожили до фона — восстановление не уронило приложение: отметку попытки снять.
    func ушлиВФон() {
        UserDefaults.standard.removeObject(forKey: КлючиМеста.попытка)
        записать()
    }

    static func ключ(_ в: NativeTabsView.Вкладка) -> КлючВкладкиМеста? {
        switch в {
        case .лента: return .лента
        case .избранное: return .избранное
        case .сообщения: return .сообщения
        case .кабинет: return .кабинет
        case .разместить: return nil
        }
    }
}


import UserNotifications

/**
 ЧИСЛО НА ИКОНКЕ — ЭТАП 11 ПЕРЕХОДА НА SWIFTUI (владелец 25.09.2026: «5–7 этапов наперёд»).

 На иконке приложения — сколько непрочитанных сообщений: то же число, что на вкладке «Сообщения» (dm.php list).
 Ставят его вкладки (NativeTabsView) после каждой сверки списка с сервером, а не только когда число поменялось: пуш
 сайта мог поставить на иконку своё. Нового адреса на сервере нет.

 Только если человек разрешил наклейки уведомлений (badgeSetting). Запретил — иконку не трогаем.

 🔴 ВЫХОД СНИМАЕТ ЧИСЛО. Непрочитанные ушедшего не должны висеть на иконке у следующего (WebContainer, bye=1). Ответ
 системы о разрешении приходит не сразу, поэтому у каждой просьбы номер: число, опоздавшее за выходом, не вернёт на
 иконку чужие непрочитанные.
 */
@MainActor
enum ЗначокПриложения {
    /// Номер последней просьбы — поставить или снять.
    private static var поколение = 0
    /// Ставили ли мы на иконку число — чтобы при выключенном рубильнике убрать только своё, а не число из пуша.
    private static let ключ = "klikoBadgeSet"

    /// Непрочитанных стало столько — на иконку, если рубильник включён и наклейки разрешены.
    static func поставить(_ число: Int) {
        guard Config.значокНепрочитанных else { return }
        поколение += 1
        let номер = поколение
        let сколько = max(0, число)
        Task { @MainActor in
            let можно = await ЗначокПриложения.наклейкиРазрешены()
            guard можно, номер == ЗначокПриложения.поколение else { return }
            UNUserNotificationCenter.current().setBadgeCount(сколько) { _ in }
            UserDefaults.standard.set(сколько > 0, forKey: ЗначокПриложения.ключ)
        }
    }

    /// Выход из аккаунта — число с иконки долой, чьё бы оно ни было: наше или из пуша сайта.
    static func снять() {
        поколение += 1
        UNUserNotificationCenter.current().setBadgeCount(0) { _ in }
        UserDefaults.standard.removeObject(forKey: ключ)
    }

    /// Запуск с выключенным рубильником: число, которое ставили прежние запуски, убираем, а не ждём выхода.
    static func прибрать() {
        guard !Config.значокНепрочитанных, UserDefaults.standard.bool(forKey: ключ) else { return }
        снять()
    }

    /// Разрешил ли человек наклейки на иконке — спрашиваем систему каждый раз: в Настройках их могли выключить.
    nonisolated private static func наклейкиРазрешены() async -> Bool {
        await withCheckedContinuation { продолжение in
            UNUserNotificationCenter.current().getNotificationSettings { настройки in
                продолжение.resume(returning: настройки.badgeSetting == .enabled)
            }
        }
    }
}

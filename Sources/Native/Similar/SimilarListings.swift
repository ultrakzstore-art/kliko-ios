import Foundation

/**
 ПОХОЖИЕ ОБЪЯВЛЕНИЯ — ЭТАП 7 ПЕРЕХОДА НА SWIFTUI (владелец 25.09.2026: «5–7 этапов наперёд»): полоса внизу карточки.

 Отдельного API «похожих» приложение не знает, поэтому берём ту же ленту, что на главной: GET /api/listings.php с
 cat=<раздел объявления> и per=12, сортировка та же (reco). Из ответа выкидываем само объявление и повторы, показываем
 до 10. Раздела нет, запрос не прошёл или никого не осталось — полосы нет вовсе: пустая «Похожие» хуже никакой.

 🔴 ЧУЖОЙ РАЗДЕЛ ОТСЕКАЕМ. Не узнал сервер раздел — он мог бы молча отдать общую ленту, и «похожими» стали бы
 случайные объявления. Поэтому объявление, у которого в ответе свой раздел и он другой, не показываем; без раздела в
 ответе — верим фильтру сервера.

 На телефон ничего не пишется: полоса живёт, пока открыта карточка, и стирать при выходе нечего.

 Этап 32: запрос несёт и выбранный город (ListingsAPI.Запрос.где) — похожие из того же места, что лента.
 */
enum Похожие {
    /// Просим с запасом: одно из них — само объявление, а часть может оказаться из чужого раздела.
    static let просить = 12
    static let показать = 10

    /// Что видно внизу карточки.
    enum Состояние {
        /// Раздела нет, запрос не удался — полосы нет.
        case нет
        /// Запрос в пути — заготовки карточек.
        case грузим
        /// Пришло для этого раздела. Пусто — полосы нет, и за тем же разделом второй раз не ходим.
        case готово(раздел: String, товары: [Listing])
    }

    /// Похожие на объявление `id` из раздела `раздел`: не больше `показать`, без него самого и без повторов.
    static func загрузить(раздел: String, кроме id: String) async throws -> [Listing] {
        var запрос = ListingsAPI.Запрос()
        запрос.per = просить
        запрос.cat = раздел
        let ответ = try await ListingsAPI.загрузить(запрос)
        let нужный = раздел.lowercased()
        var виденные: Set<String> = [id]
        let подходящие = ответ.страница.items.filter { т in
            guard виденные.insert(т.id).inserted else { return false }
            guard let свой = т.категория else { return true }
            return свой.lowercased() == нужный
        }
        return Array(подходящие.prefix(показать))
    }
}

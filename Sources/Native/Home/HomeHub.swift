// MARK: - Мерцание заготовки

/**
 Мерцание заготовки ряда: прозрачность 1 → 0,6 → 1 за 1,4 с (easeInOut 0,7 с туда и обратно, повторяется), как прежние
 0,8 ± 0,2. Содержимое строится один раз: повторяющаяся анимация прозрачности идёт в отрисовке, body ряда (прокрутка,
 ленивый стек) не пересчитывается на каждом кадре, как было с TimelineView 20 к/с.

 Анимация привязана только к прозрачности (.animation(_:body:), iOS 17), а не ко всему, что меняется в том же кадре:
 сдвиг и подъём самой заготовки (ПодъёмСайта, появление поля поиска) в повтор не попадают — иначе карточки «плавали» бы
 (об этом — СкелетЛенты, FeedSkeleton.swift). Заготовки рядов мерцают каждая своей анимацией, но стартуют в одном кадре
 и идут в такт; полоса переноса магазина между ними не мерцает. При «Уменьшении движения» и в лёгком режиме — ровно 0,8.
 */
struct МерцаниеЗаготовки<Содержимое: View>: View {
    private let содержимое: Содержимое
    /// Мерцание запущено: прозрачность идёт к 0,6 и обратно.
    @State private var тускло = false
    @Environment(\.accessibilityReduceMotion) private var безДвижения
    /// Лёгкий режим (DeviceMode.swift): XR, SE 2, энергосбережение, нагрев — ровная заливка.
    @ObservedObject private var режим = РежимУстройства.shared

    init(@ViewBuilder содержимое: () -> Содержимое) {
        self.содержимое = содержимое()
    }

    var body: some View {
        if безДвижения || режим.лёгкий {
            содержимое
                .opacity(0.8)
        } else {
            содержимое
                .animation(Self.мерцание) { вид in
                    вид.opacity(тускло ? 0.6 : 1)
                }
                .onAppear { тускло = true }
                .onDisappear { тускло = false }
        }
    }

    /// 0,7 с к 0,6 и столько же обратно — период 1,4 с, как у прежнего мерцания.
    private static var мерцание: Animation {
        .easeInOut(duration: 0.7).repeatForever(autoreverses: true)
    }
}

// MARK: - Каркас карточки вакансии

/**
 Каркас карточки вакансии ряда «Работа» — высота КарточкаВакансииГлавной (SiteCards.swift) один в один: отступы 12, между
 строками 4; место «★ ТОП» (24), название 15/heavy на две строки, зарплата 15/heavy, компания 14/semibold, подпись 12 на
 две строки, кнопка «Откликнуться» 36; не ниже 176. Кегли растут с «Размером текста», как у карточки (@ScaledMetric от
 .subheadline), «Размер текста» — не дальше .xxLarge. Строки — невидимые пробелы; поверх по центру — содержимое.

 Нужен плитке «Смотреть все» в конце ряда «Работа»: у вакансий нет фото, и каркас карточки объявления
 (ЗаготовкаКарточкиСайта, фото 4:3) торчал бы ниже них.
 */
struct КаркасВакансииГлавной<Содержимое: View>: View {
    private let содержимое: Содержимое
    /// Кегли карточки вакансии в пикселях сайта, растущие с «Размером текста» (как КарточкаВакансииГлавной.сотня).
    @ScaledMetric(relativeTo: .subheadline) private var сотня: CGFloat = 100

    init(@ViewBuilder содержимое: () -> Содержимое) {
        self.содержимое = содержимое()
    }

    var body: some View {
        VStack(alignment: .leading, spacing: 4) {
            МеткаТопГлавной()
            строка(15, .heavy, строк: 2)
            строка(15, .heavy, строк: 1)
            строка(14, .semibold, строк: 1)
            строка(12, .regular, строк: 2)
            Spacer(minLength: 0)
            Color.clear
                .frame(height: 36)
        }
        .hidden()
        .padding(12)
        .frame(maxWidth: .infinity, minHeight: 176, alignment: .topLeading)
        .overlay { содержимое }
        .dynamicTypeSize(...DynamicTypeSize.xxLarge)
    }

    /// Строка карточки: невидимый пробел нужного кегля на `строк` строк.
    private func строка(_ пикселей: CGFloat, _ вес: Font.Weight, строк: Int) -> some View {
        Text(" ")
            .font(.system(size: пикселей * сотня / 100, weight: вес))
            .lineLimit(строк, reservesSpace: true)
    }
}

// MARK: - Каркас карточки ряда

/**
 Каркас карточки ряда — геометрия ListingCard.карточкаСайта один в один (NativeFeedView.swift): фото 4:3 во всю ширину
 (наШиринуКарточки), тело — отступы 12 по бокам, 10 сверху, 12 снизу, между строками 4: строка цены кеглем 19, название
 кеглем 13 на две строки (при крупном тексте — на три), строка фактов кеглем 11 (+2 сверху), подвал кеглем 11 (+10 и +6
 сверху); скругление 18, поверхность и рамка линии; «Размер текста» — не дальше третьего крупного. Кегли растут с
 размером текста, как у карточки (@ScaledMetric от .body). Строки — невидимые пробелы нужного шрифта, поэтому высота
 каркаса равна высоте карточки при любом размере текста.

 Без своего содержимого — заготовка ряда: фото залито линией, вместо строк — полоски постоянной ширины (цена 80 × 14,
 название 120 × 11, факты 64 × 10, подвал 56 × 10). С содержимым (фото и тело) — плитка «Смотреть все» в конце ряда.
 */
struct ЗаготовкаКарточкиСайта<Фото: View, Тело: View>: View {
    /// Полоски заготовки и линия подвала — только у заготовки ряда.
    private let полоски: Bool
    private let фото: Фото
    private let тело: Тело
    @Environment(\.dynamicTypeSize) private var размерТекста
    /// Кегли карточки в пикселях сайта, растущие с «Размером текста»: 100 при обычном (как ListingCard.сотня).
    @ScaledMetric(relativeTo: .body) private var сотня: CGFloat = 100

    /// Каркас со своим содержимым: `фото` — во всю область фото 4:3, `тело` — по центру тела.
    init(@ViewBuilder фото: () -> Фото, @ViewBuilder тело: () -> Тело) {
        self.полоски = false
        self.фото = фото()
        self.тело = тело()
    }

    fileprivate init(полоски: Bool, фото: Фото, тело: Тело) {
        self.полоски = полоски
        self.фото = фото
        self.тело = тело
    }

    var body: some View {
        VStack(alignment: .leading, spacing: 0) {
            Color.clear
                .наШиринуКарточки(3 / 4)
                .overlay { фото }
                .clipped()
            каркасТела
                .overlay { тело }
        }
        .вВысотуРядаСетки()
        .background(Theme.поверхность)
        .clipShape(RoundedRectangle(cornerRadius: Theme.Радиус.lg, style: .continuous))
        .overlay {
            RoundedRectangle(cornerRadius: Theme.Радиус.lg, style: .continuous)
                .strokeBorder(Theme.линия, lineWidth: 1)
                .allowsHitTesting(false)
        }
        .contentShape(RoundedRectangle(cornerRadius: Theme.Радиус.lg, style: .continuous))
        .dynamicTypeSize(...DynamicTypeSize.accessibility3)
    }

    private var крупныйТекст: Bool { размерТекста.isAccessibilitySize }

    private func кегль(_ пикселей: CGFloat) -> CGFloat { пикселей * сотня / 100 }

    /// Тело карточки — те же строки и отступы, что ListingCard.телоСайта; строки держат место невидимым пробелом.
    private var каркасТела: some View {
        VStack(alignment: .leading, spacing: 4) {
            полоска(80, 14)
                .вСтрокуКарточки(.system(size: кегль(19), weight: .heavy))
            Text(" ")
                .font(.system(size: кегль(13), weight: .medium))
                .lineLimit(крупныйТекст ? 3 : 2, reservesSpace: true)
                .hidden()
                .frame(maxWidth: .infinity, alignment: .leading)
                .overlay(alignment: .topLeading) {
                    полоска(120, 11)
                        .padding(.top, 2)
                }
            СтрокаФактовВитрины(факты: [], кегль: кегль(11))
                .overlay(alignment: .leading) { полоска(64, 10) }
                .padding(.top, 2)
            подвал
                .padding(.top, 6)
                .frame(maxHeight: .infinity, alignment: .bottom)
        }
        .padding(.horizontal, 12)
        .padding(.top, 10)
        .padding(.bottom, 12)
    }

    /// Подвал — строка кеглем 11 под линией (ListingCard.подвалСайта: +10 сверху).
    private var подвал: some View {
        полоска(56, 10)
            .вСтрокуКарточки(.system(size: кегль(11)))
            .padding(.top, 10)
            .overlay(alignment: .top) {
                if полоски {
                    Rectangle()
                        .fill(Theme.линия)
                        .frame(height: 1)
                }
            }
    }

    /// Полоска заготовки постоянной ширины, скругление 6; у «Смотреть все» её нет.
    @ViewBuilder
    private func полоска(_ ширина: CGFloat, _ высота: CGFloat) -> some View {
        if полоски {
            RoundedRectangle(cornerRadius: Theme.Радиус.xxs, style: .continuous)
                .fill(Theme.линия)
                .frame(width: ширина, height: высота)
        }
    }
}

extension ЗаготовкаКарточкиСайта where Фото == Color, Тело == EmptyView {
    /// Заготовка карточки ряда: фото залито линией, полоски вместо строк.
    init() {
        self.init(полоски: true, фото: Theme.линия, тело: EmptyView())
    }
}

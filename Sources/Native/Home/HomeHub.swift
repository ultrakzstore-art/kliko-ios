/**
 «ТИХАЯ ВИТРИНА» — ДВИЖЕНИЕ И ЗАГОТОВКИ ВЕРХА ГЛАВНОЙ (владелец 14.10.2026: «упростить и улучшить главную»,
 «мощная анимированная подача», «летает на всех девайсах»).

 Новая раскладка главной (SiteHome.swift, NativeFeedView.главнаяСайта): под шапкой сетка разделов 4 × 2 (СеткаРазделов),
 полоса «Безопасная сделка» (ПолосаГлавной) и сразу ряды объявлений. Здесь — то, что нужно им сверх SiteHome.swift:

   · ПодъёмСайта — общий подъём с проявлением (mhRise сайта): прозрачность 0 → 1, сдвиг вниз → 0, масштаб → 1, за
     0,36 с по cubic-bezier(.2, .8, .2, 1) с задержкой. Тот же рисунок, что у экрана «Категории» (его закрытый
     ПодъёмКатегорийСайта живёт в CategoriesSheet.swift — чужой файл, не трогаем);
   · ВходГлавной — вход главной один раз за запуск: ячейки сетки волной (0,02 с на ячейку, сдвиг 12, масштаб 0,96),
     полоса (0,08 с), первый ряд (0,1 с), затем щит гаранта один раз «подпрыгивает». Старт — в момент ухода загрузочного
     экрана запуска (RootWebView ставит WebBridge.splashDone): подъём идёт вместе с его угасанием, без паузы (скорость,
     16.10.2026: прежде ждали ещё 0,45 с, а ряды — 0,38 с); запасной старт — через 9 с, если ухода так и не было. Лента
     открылась уже после заставки — вход сразу. Возврат на главную из раздела или объявления — без входа; при
     «Уменьшении движения» и в лёгком режиме (РежимУстройства) входа нет;
   · ЗаготовкаКарточкиСайта — каркас карточки ряда той же геометрии, что ListingCard.карточкаСайта (фото 4:3, тело
     10 / 12 / 12, цена 19, название в две строки, факты, подвал): заготовка ряда до ответа home=1 и плитка «Смотреть
     все» в конце ряда — ровно той высоты, что карточки, и при смене заготовки на ряды ничего не сдвигается;
   · КаркасВакансииГлавной — то же для ряда «Работа»: высота КарточкаВакансииГлавной (SiteCards.swift), плитка
     «Смотреть все» в конце ряда вакансий — их высоты, а не высоты карточки объявления с фото;
   · МерцаниеЗаготовки — мерцание заготовки ряда одной повторяющейся анимацией прозрачности (1 → 0,6 → 1 за 1,4 с),
     привязанной только к прозрачности: содержимое строится один раз, кадры считает отрисовка, а не body; при
     «Уменьшении движения» и в лёгком режиме (РежимУстройства) — ровно 0,8.

 Только прозрачность, сдвиг и масштаб — без размытия, материалов и теней; бесконечное — только мерцание заготовки, пока
 ждём ответ home=1: на iPhone XR — 60 к/с.
 */

// MARK: - Подъём

extension ДвижениеСайта {
    /// Подъём с проявлением (mhRise сайта): 0,36 с, cubic-bezier(.2, .8, .2, 1). При «Уменьшении движения» — сразу.
    static var подъём: Animation? { мягко(.timingCurve(0.2, 0.8, 0.2, 1, duration: 0.36)) }
}

/// Подъём на `сдвиг` pt с проявлением и масштабом от `масштаб` к 1 — с задержкой `задержка`, когда `видно` стало true.
struct ПодъёмСайта: ViewModifier {
    let видно: Bool
    let задержка: Double
    let сдвиг: CGFloat
    let масштаб: CGFloat

    init(видно: Bool, задержка: Double = 0, сдвиг: CGFloat = 16, масштаб: CGFloat = 1) {
        self.видно = видно
        self.задержка = задержка
        self.сдвиг = сдвиг
        self.масштаб = масштаб
    }

    func body(content: Content) -> some View {
        content
            .opacity(видно ? 1 : 0)
            .offset(y: видно ? 0 : сдвиг)
            .scaleEffect(видно ? 1 : масштаб)
            .animation(ДвижениеСайта.подъём?.delay(задержка), value: видно)
    }
}


    private static func vesa(_ н: String, _ набор: inout НаборСтандартов) {
        var шаблоны: [String] = []
        let явные = все(регVesa, н).map { $0[1] + "x" + $0[2] }
        let голые = пары(н).map { String($0.0) + "x" + String($0.1) }
        for ш in явные + голые where КаталогСтандартов.шаблоныVESA.contains(ш) && !шаблоны.contains(ш) {
            шаблоны.append(ш)
        }
        let предел = первое(регДоVesa, н).map { $0[1] + "x" + $0[2] }
        guard !шаблоны.isEmpty || предел != nil else { return }
        let наибольший = (шаблоны + [предел].compactMap { $0 }).max { площадь($0) < площадь($1) } ?? ""
        набор[.vesa, КлючСтандарта.шаблон] = наибольший
        if шаблоны.count >= 2 {
            // «100x100–400x400» и списки: от наименьшего до наибольшего.
            let наименьший = шаблоны.min { площадь($0) < площадь($1) } ?? наибольший
            набор[.vesa, КлючСтандарта.шаблоны] = наименьший + ".." + наибольший
        } else if предел != nil {
            набор[.vesa, КлючСтандарта.шаблоны] = "75x75.." + наибольший
        } else {
            набор[.vesa, КлючСтандарта.шаблоны] = наибольший
        }
        if let кг = все(регКг, н).compactMap({ Int($0[1]) }).filter({ (5...150).contains($0) }).max() {
            набор[.vesa, КлючСтандарта.доКг] = String(кг)
        }
        if let г = первое(регДиагонали, н), let низ = Int(г[1]), let верх = Int(г[2]), низ < верх,
           (13...120).contains(низ) {
            набор[.vesa, КлючСтандарта.диагональОт] = String(низ)
            набор[.vesa, КлючСтандарта.диагональДо] = String(верх)
        }
    }

    /// Площадь шаблона «400x300» — для «наибольшего».
    static func площадь(_ шаблон: String) -> Double {
        guard let пара = КаталогСтандартов.пара(шаблон) else { return 0 }
        return пара.0 * пара.1
    }


    private static func сокет(_ н: String, _ набор: inout НаборСтандартов) {
        if let г = первое(регLGA, н) {
            набор[.сокет, КлючСтандарта.сокет] = "LGA" + г[1]
        } else if let г = первое(регAM, н) {
            набор[.сокет, КлючСтандарта.сокет] = "AM" + г[1]
        }
        for г in все(регЧипсет, н) {
            let чипсет = г[1].uppercased() + (г[2].isEmpty ? "" : "E")
            guard let поЧипсету = КаталогСтандартов.сокет(чипсета: чипсет) else { continue }
            набор[.сокет, КлючСтандарта.чипсет] = чипсет
            if набор[.сокет, КлючСтандарта.сокет] == nil { набор[.сокет, КлючСтандарта.сокет] = поЧипсету }
            // Плата: какую память берёт (DDR4 или DDR5) — для сверки с моей; GDDR видеокарты не в счёт, оба — не знаем.
            let безКарт = н.replacingOccurrences(of: "gddr", with: " ")
            let ddr4 = безКарт.contains("ddr4"), ddr5 = безКарт.contains("ddr5")
            if ddr4 != ddr5 { набор[.сокет, КлючСтандарта.поколение] = ddr5 ? "DDR5" : "DDR4" }
            if г[3] == "m" { набор[.формаПлаты, КлючСтандарта.форма] = "Micro-ATX" }
            if г[3] == "i" { набор[.формаПлаты, КлючСтандарта.форма] = "Mini-ITX" }
            break
        }
        if let цп = процессор(н) {
            набор[.сокет, КлючСтандарта.процессор] = цп.имя
            if набор[.сокет, КлючСтандарта.сокет] == nil { набор[.сокет, КлючСтандарта.сокет] = цп.сокет }
        }
    }

    /// Процессор по модели: «Ryzen 5 5600» → AM4, «i5-12400F» → LGA1700; ноутбучные (H, U, HS, HX, P) — BGA.
    static func процессор(_ н: String) -> (имя: String, сокет: String)? {
        if let г = первое(регRyzen, н), let серия = Int(г[2]) {
            let имя = "Ryzen " + г[1] + " " + г[2] + г[3] + г[4].uppercased()
            let ноутбук = г[4].contains("h") || г[4].contains("u")
            if ноутбук { return (имя, "BGA") }
            if (1...5).contains(серия) { return (имя, "AM4") }
            if (7...9).contains(серия) { return (имя, "AM5") }
            return nil
        }
        if let г = первое(регUltra, н) {
            let имя = "Core Ultra " + г[1] + " " + г[2] + г[3] + г[4].uppercased()
            return (имя, г[2] == "2" && !г[4].contains("h") && !г[4].contains("v") ? "LGA1851" : "BGA")
        }
        if let г = первое(регCore, н) {
            let номер = г[2]
            let поколение = Int(номер.count == 5 ? String(номер.prefix(2)) : String(номер.prefix(1))) ?? 0
            let суффикс = г[3]
            let имя = "Core i" + г[1] + "-" + номер + суффикс.uppercased()
            // Четыре цифры с «1» впереди — ноутбучные 10–11-го поколения («1065G7», «1135G7»); H, U, P, Y — ноутбук.
            let ноутбук = (номер.count == 4 && номер.hasPrefix("1"))
                || ["h", "u", "p", "y"].contains(where: { суффикс.contains($0) })
            if ноутбук { return (имя, "BGA") }
            switch поколение {
            case 6...9: return (имя, "LGA1151")
            case 10...11: return (имя, "LGA1200")
            case 12...14: return (имя, "LGA1700")
            default: return nil
            }
        }
        return nil
    }

    private static func формаИКорпус(_ н: String, _ семьи: Set<СемьяСтандарта>, _ набор: inout НаборСтандартов) {
        if набор[.формаПлаты, КлючСтандарта.форма] == nil {
            let форма: String?
            if есть(н, ["e-atx", "eatx"]) {
                форма = "E-ATX"
            } else if есть(н, ["micro-atx", "micro atx", "matx", "m-atx", "uatx", "µatx", "microatx"]) {
                форма = "Micro-ATX"
            } else if н.contains("mini-dtx") {
                форма = "Mini-DTX"
            } else if есть(н, ["mini-itx", "mini itx", "itx"]) {
                форма = "Mini-ITX"
            } else if н.contains("atx") {
                форма = "ATX"
            } else {
                форма = nil
            }
            набор[.формаПлаты, КлючСтандарта.форма] = форма
        }
        if семьи.contains(.корпус), let г = первое(регКорпусКарта, н), let мм = Int(г[1]), (150...500).contains(мм) {
            набор[.корпус, КлючСтандарта.длинаКарты] = String(мм)
        }
    }


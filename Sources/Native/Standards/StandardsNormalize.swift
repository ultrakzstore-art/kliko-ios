    /// Короткая подпись семьи: «DDR4 · SO-DIMM · 16 ГБ · 3200», «160×200», «VESA 400×400 · до 50 кг».
    static func подпись(_ набор: НаборСтандартов, _ семья: СемьяСтандарта) -> String {
        typealias К = КлючСтандарта
        let т = СтандартыText.т
        var части: [String] = []
        func добавить(_ поле: String, _ преобразовать: (String) -> String = { $0 }) {
            if let з = набор[семья, поле] { части.append(преобразовать(з)) }
        }
        switch семья {
        case .спальноеМесто: добавить(К.размер, КаталогСтандартов.показ)
        case .матрас:
            добавить(К.размер, КаталогСтандартов.показ)
            добавить(К.высотаМатраса) { "h " + $0 + " " + т("u_cm") }
        case .бельё:
            добавить(К.комплект) { т("set_" + $0) }
            добавить(К.наРезинке) { КаталогСтандартов.показ($0) }
            добавить(К.пододеяльник, КаталогСтандартов.показ)
        case .шторы:
            if let ш = набор[семья, К.ширина], let в = набор[семья, К.высота] {
                части.append(ш + "×" + в + " " + т("u_cm"))
            } else {
                добавить(К.высота) { $0 + " " + т("u_cm") }
            }
        case .цоколь: добавить(К.цоколь)
        case .vesa:
            добавить(К.шаблон) { "VESA " + КаталогСтандартов.показ($0) }
            добавить(К.доКг) { String(format: т("u_upto_kg"), $0) }
        case .память:
            добавить(К.поколение)
            добавить(К.форма) { $0 == "soldered" ? т("ram_soldered_short") : $0 }
            if let гб = набор[семья, К.гб] {
                части.append((набор.сколько > 1 ? String(набор.сколько) + "×" : "") + гб + " " + т("u_gb"))
            }
            добавить(К.частота)
        case .накопитель:
            добавить(К.форма) { $0.hasPrefix("22") ? "M.2 " + $0 : $0 + "″" }
            добавить(К.протокол) { $0 == "nvme" ? "NVMe" : "SATA" }
            добавить(К.pcie) { "PCIe " + $0 + ".0" }
            добавить(К.тб) { ($0.hasPrefix("0.") ? ЧислаАвтоподбора.ч((Double($0) ?? 0) * 1000, знаков: 0) + " " + т("u_gb")
                              : $0 + " " + т("u_tb")) }
        case .видеокарта:
            добавить(К.чип)
            добавить(К.памятьКарты) { $0 + " " + т("u_gb") }
            добавить(К.длина) { $0 + " " + т("u_mm") }
        case .блокПитания:
            добавить(К.ватт) { $0 + " " + т("u_w") }
            добавить(К.сертификат)
            добавить(К.форма)
        case .сокет:
            добавить(К.сокет)
            добавить(К.чипсет)
        case .формаПлаты: добавить(К.форма)
        case .корпус: добавить(К.длинаКарты) { String(format: т("u_gpu_upto"), $0) }
        case .проём, .потолок, .диагональ, .расходник, .размер:
            части = набор.поля(семья).sorted { $0.key < $1.key }.map(\.value)
        }
        return части.joined(separator: " · ")
    }

    /// Запрос поиска по стандарту — латиницей, как пишут продавцы: «DDR4 SO-DIMM 16GB 3200», «лампа E27».
    static func запрос(_ набор: НаборСтандартов, _ семья: СемьяСтандарта) -> String {
        typealias К = КлючСтандарта
        let п = набор.поля(семья)
        switch семья {
        case .память:
            return [п[К.поколение], п[К.форма] == "soldered" ? nil : п[К.форма], п[К.гб].map { $0 + "GB" }]
                .compactMap { $0 }.joined(separator: " ")
        case .накопитель:
            let форма = п[К.форма].map { $0.hasPrefix("22") ? "M.2 " + $0 : $0 + "\"" }
            return [форма, п[К.протокол]?.uppercased(), п[К.тб].map { $0 + "TB" }].compactMap { $0 }.joined(separator: " ")
        case .видеокарта: return п[К.чип] ?? ""
        case .блокПитания: return п[К.ватт].map { СтандартыText.т("q_psu") + " " + $0 + "W" } ?? ""
        case .цоколь: return п[К.цоколь].map { СтандартыText.т("q_lamp") + " " + $0 } ?? ""
        case .vesa: return п[К.шаблон].map { СтандартыText.т("q_mount") + " VESA " + $0 } ?? ""
        case .спальноеМесто, .матрас: return п[К.размер].map { СтандартыText.т("q_mattress") + " " + $0 } ?? ""
        case .бельё:
            if let р = п[К.наРезинке] { return СтандартыText.т("q_fitted") + " " + р }
            return п[К.комплект].map { СтандартыText.т("q_bedding") + " " + СтандартыText.т("set_" + $0) } ?? ""
        case .сокет: return п[К.сокет].map { "socket " + $0 } ?? ""
        default: return подпись(набор, семья)
        }
    }
}

// MARK: - Итог разбора объявления

/// Разбор объявления: значения, откуда каждая семья (худший источник её главных полей), чипы на выбор и цвета.
struct РазборСтандартовОбъявления: Equatable, Sendable {
    var набор = НаборСтандартов(источник: .продавец)
    var откуда: [СемьяСтандарта: ИсточникСтандарта] = [:]
    var кандидаты: [СемьяСтандарта: [String]] = [:]
    var цвета: [ЦветСтандарта] = []

    init() {}

    /// Лучший уровень, который даёт эта семья объявления: из текста, выведенного и без главных полей — «Проверьте».
    func потолок(_ семья: СемьяСтандарта) -> УровеньСтандарта {
        guard набор.полная(семья) else { return .проверить }
        return (откуда[семья] ?? .текст).потолок
    }

    var пусто: Bool { набор.пусто && кандидаты.isEmpty }

    /// Принять слой: недостающие поля; семья помнит худший источник своих главных полей.
    mutating func принять(_ слой: НаборСтандартов, источник: ИсточникСтандарта) {
        for семья in слой.семьи {
            for (поле, значение) in слой.поля(семья) where набор[семья, поле] == nil {
                набор[семья, поле] = значение
                guard семья.главные.contains(поле) else { continue }
                let было = откуда[семья]
                if было == nil || (было?.потолок ?? .подходит) < источник.потолок { откуда[семья] = источник }
            }
            if откуда[семья] == nil { откуда[семья] = источник }
        }
        if набор.сколько == 1 && слой.сколько > 1 { набор.сколько = слой.сколько }
    }
}

    private static func память(_ н: String, _ набор: inout НаборСтандартов) {
        var частота: Int? = nil
        if let г = первое(регPC, н) {
            let ключ = "pc" + г[1] + "-" + г[2]
            if let имя = КаталогСтандартов.pcИмена[ключ] {
                набор[.память, КлючСтандарта.поколение] = имя.поколение
                частота = имя.частота
            } else if let ч = Int(г[2]), КаталогСтандартов.частотыПамяти.contains(ч) {
                набор[.память, КлючСтандарта.поколение] = "DDR" + г[1]
                частота = ч
            }
            switch г[4] {
            case "s": набор[.память, КлючСтандарта.форма] = "SO-DIMM"
            case "u": набор[.память, КлючСтандарта.форма] = "DIMM"
            case "r": набор[.память, КлючСтандарта.видПамяти] = "RDIMM"
            default: break
            }
        }
        if let г = первое(регПоколение, н) {
            var п = (г[1].isEmpty ? "" : "LP") + "DDR" + г[2]
            if г[3] == "l" { п += "L" }
            if г[3] == "x" { п += "X" }
            if КаталогСтандартов.поколенияПамяти.contains(п) { набор[.память, КлючСтандарта.поколение] = п }
            if let ч = Int(г[4]), КаталогСтандартов.частотыПамяти.contains(ч) { частота = частота ?? ч }
        }
        if набор[.память, КлючСтандарта.форма] == nil {
            if есть(н, ["so-dimm", "sodimm", "so dimm", "содимм", "содим", "ноутбукқа арналған", "для ноутбук",
                        "ноутбучн", "laptop"]) {
                набор[.память, КлючСтандарта.форма] = "SO-DIMM"
            } else if н.contains("camm") {
                набор[.память, КлючСтандарта.форма] = "CAMM2"
            } else if есть(н, ["udimm", "dimm", "димм", "для пк", "для компьютер", "десктоп", "desktop"]) {
                набор[.память, КлючСтандарта.форма] = "DIMM"
            }
        }
        if набор[.память, КлючСтандарта.поколение].map({ КаталогСтандартов.распаянныеПоколения.contains($0) }) == true {
            набор[.память, КлючСтандарта.форма] = "soldered"
        }
        if н.contains("lrdimm") {
            набор[.память, КлючСтандарта.видПамяти] = "LRDIMM"
        } else if есть(н, ["rdimm", "registered", "reg ecc", "серверн"]) {
            набор[.память, КлючСтандарта.видПамяти] = "RDIMM"
        } else if н.contains("ecc") {
            набор[.память, КлючСтандарта.видПамяти] = "ECC UDIMM"
        }
        if let г = первое(регКит, н), let штук = Int(г[1]), let гб = Int(г[2]),
           КаталогСтандартов.объёмыМодуля.contains(гб) {
            набор[.память, КлючСтандарта.гб] = String(гб)
            набор.сколько = штук
        } else if let гб = все(регГБ, н).compactMap({ Int($0[1]) })
                    .first(where: { КаталогСтандартов.объёмыМодуля.contains($0) }) {
            набор[.память, КлючСтандарта.гб] = String(гб)
        }
        if частота == nil, let г = первое(регЧастота, н), let ч = Int(г[1]) { частота = ч }
        if частота == nil {
            частота = все(регЧисло4, н).compactMap { Int($0[1]) }
                .first { КаталогСтандартов.частотыПамяти.contains($0) }
        }
        if let частота { набор[.память, КлючСтандарта.частота] = String(частота) }
    }


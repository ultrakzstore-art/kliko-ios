import Foundation

/**
 СТАНДАРТЫ — НОРМАЛИЗАЦИЯ И РАЗБОР ОБЪЯВЛЕНИЯ (docs/STANDARDS.md §2.4, §5 «Из названия»; каталог — normalize, aliases).

 Нормализация — одна функция у сайта и приложения: строчные, «ё» = «е» → кириллица-двойник → латиница в кодах, которые
 начинаются с буквы («Е27» → e27, «АМ4» → am4; «500вт» и «80см» не трогаются) → «х», «×», «*» между цифрами → x →
 запятая между цифрами → точка. Не двойники («ддр4», «содимм», «гх53») — синонимами семьи.

 Семьи объявления — по разделу (cats каталога) и словам названия (keywords), как вид товара у КаталогРазмеров; в
 разделах «ноутбуки», «компьютеры», «телефоны» детали ПК не ищутся (там «16 ГБ DDR4» — память самого ноутбука).

 Образцы «строка → результат»:
   «Kingston 16GB DDR4 3200 SODIMM»            → ram_module: DDR4 · SO-DIMM · 16 · 3200
   «Комплект 2х8гб ддр4 3200 для ПК»            → ram_module: DDR4 · DIMM · 8 · 3200, qty 2
   «PC4-3200AA-SA2 8GB»                         → ram_module: DDR4 · SO-DIMM · 8 · 3200
   «Samsung 980 Pro 1TB M.2 NVMe PCIe 4.0»      → m2_ssd: 2280 (из текста) · nvme · 4 · 1
   «MSI RTX 4060 Ventus 2X 8GB, длина 199 мм»   → gpu_card: RTX 4060 · 8 · 199
   «Блок питания DeepCool 650W 80+ Gold»        → psu: 650 · 80+ Gold
   «Материнская плата B550M DS3H»               → cpu_socket: AM4 · B550; board_form: Micro-ATX
   «Лампа LED Е27 9Вт тёплая»                   → lamp_base: E27
   «Кронштейн VESA 400x400 до 50 кг 32–70″»     → vesa: 400x400 · 50 · 32…70
   «Матрас 160х200 независимые пружины, h 22»   → bed_size: 160x200; mattress: 22 · independent_springs
   «Кровать полуторка»                           → bed_size: 140x200
   «Кровать двуспальная»                         → кандидаты 160x200 · 180x200 · 140x200 (значения нет)
   «Простыня на резинке 160x200 борт 25»        → bedding: fitted 160x200 · 25
   «Рулонная штора 60х160»                       → curtain: blind · 60 · 160
 Всё — на телефоне, без сети; зовут сверка (StandardsMatch.swift), «Для вас» и «Добавить из моих покупок».
 */
enum РазборСтандартов {

    // MARK: - Нормализация

    /// Кириллица-двойник → латиница.
    private static let двойникиБукв: [Character: Character] = [
        "а": "a", "в": "b", "е": "e", "к": "k", "м": "m", "н": "h", "о": "o", "р": "p", "с": "c", "т": "t", "х": "x",
        "у": "y"
    ]

    private static let регX = рег(#"(?<=\d)\s*[xх×*]\s*(?=\d)"#)
    private static let регЗапятая = рег(#"(?<=\d),(?=\d)"#)
    private static let регПробелы = рег(#"[ \t]+"#)

    /// Нормальная форма текста для разбора.
    static func нормально(_ текст: String) -> String {
        var s = текст.lowercased().replacingOccurrences(of: "ё", with: "е")
        s = латиницаВКодах(s)
        s = заменить(регX, s, "x")
        s = заменить(регЗапятая, s, ".")
        s = заменить(регПробелы, s, " ")
        return s
    }

    private static func кириллица(_ знак: Character) -> Bool {
        знак.unicodeScalars.contains { (0x0400...0x04FF).contains($0.value) }
    }

    /// Код, который начинается с буквы-двойника и содержит цифру («е27», «ам4», «ет45»), — латиницей.
    private static func латиницаВКодах(_ s: String) -> String {
        var итог = ""
        итог.reserveCapacity(s.count)
        var слово = ""
        func сбросить() {
            if let первая = слово.first, двойникиБукв[первая] != nil, слово.contains(where: \.isNumber),
               слово.allSatisfy({ !кириллица($0) || двойникиБукв[$0] != nil }) {
                итог += String(слово.map { двойникиБукв[$0] ?? $0 })
            } else {
                итог += слово
            }
            слово = ""
        }
        for знак in s {
            if знак.isLetter || знак.isNumber {
                слово.append(знак)
            } else {
                сбросить()
                итог.append(знак)
            }
        }
        сбросить()
        return итог
    }

    // MARK: - Регулярные выражения

    private static func рег(_ шаблон: String) -> NSRegularExpression? {
        try? NSRegularExpression(pattern: шаблон, options: [.caseInsensitive])
    }

    /// Все совпадения: группы по номеру (0 — целиком); группа не участвовала — пусто.
    private static func все(_ р: NSRegularExpression?, _ s: String) -> [[String]] {
        guard let р else { return [] }
        let ns = s as NSString
        return р.matches(in: s, range: NSRange(location: 0, length: ns.length)).map { совпадение in
            (0..<совпадение.numberOfRanges).map { номер in
                let место = совпадение.range(at: номер)
                return место.location == NSNotFound ? "" : ns.substring(with: место)
            }
        }
    }

    private static func первое(_ р: NSRegularExpression?, _ s: String) -> [String]? {
        guard let р else { return nil }
        let ns = s as NSString
        guard let совпадение = р.firstMatch(in: s, range: NSRange(location: 0, length: ns.length)) else { return nil }
        return (0..<совпадение.numberOfRanges).map { номер in
            let место = совпадение.range(at: номер)
            return место.location == NSNotFound ? "" : ns.substring(with: место)
        }
    }

    private static func заменить(_ р: NSRegularExpression?, _ s: String, _ на: String) -> String {
        guard let р else { return s }
        return р.stringByReplacingMatches(in: s, range: NSRange(location: 0, length: (s as NSString).length),
                                          withTemplate: на)
    }

    private static func есть(_ s: String, _ слова: [String]) -> Bool {
        слова.contains { s.contains($0) }
    }

    // MARK: - Семьи по разделу и словам

    /// Разделы, где «16 ГБ DDR4» и «SSD 512» — свойства самой вещи, а не деталь на продажу.
    private static let разделыЦелыхУстройств: Set<String> = ["laptops", "desktops", "all-in-one", "phones-tablets",
                                                             "consoles"]

    private static let словаКровати = ["кровать", "кровати", "матрас", "матрац", "топпер", "наматрасник", "төсек",
                                       "кереует", "төсеніш", "mattress", "bed "]
    private static let словаБелья = ["постельн", "пододеяльник", "простын", "наволочк", "одеял", "подушк", "көрпе",
                                     "жастық", "төсек жабдығы", "bedding", "duvet"]
    private static let словаШтор = ["штор", "тюль", "портьер", "жалюзи", "рулонн", "римск", "плиссе", "рольштор",
                                    "перде", "curtain", "blind"]
    private static let словаЛамп = ["лампа", "лампы", "лампочк", "шам ", "цоколь", "led bulb", "светодиодн"]
    private static let словаКронштейна = ["кронштейн", "крепление для тв", "крепление для телевизор",
                                          "крепление телевизор", "крепление для монитор", "ілгіш", "tv mount",
                                          "vesa"]
    private static let словаПамяти = ["оператив", "озу", "ddr", "ддр", "sodimm", "so-dimm", "содимм", "жедел жады",
                                      " ram ", "dimm"]
    private static let словаНакопителя = ["ssd", "nvme", "m.2", "м.2", "накопител", "жинақтағыш", "hdd", "жестк",
                                          "жесткий диск"]
    private static let словаВидеокарты = ["видеокарт", "бейнекарта", "rtx", "gtx", "radeon", "geforce", "rx 6",
                                          "rx 7", "rx 9"]
    private static let словаБП = ["блок питания", "бп ", "қуат блогы", "psu", "power supply"]
    private static let словаСокета = ["процессор", "материнск", "аналық плата", "ryzen", "core i", "core ultra",
                                      "сокет", "socket", "lga", "am4", "am5"]
    private static let словаКорпуса = ["корпус для пк", "корпус пк", "компьютерный корпус", "pc case", "корпус atx",
                                       "корпус matx", "корпус micro", "корпус mini"]

    /// Семьи, которые стоит искать в объявлении раздела с таким названием. Пусто — сверять нечего.
    static func семьи(раздел: String?, название: String) -> Set<СемьяСтандарта> {
        let н = " " + нормально(название) + " "
        var итог = Set<СемьяСтандарта>()
        let внутри: (Set<String>) -> Bool = { РазделыСайта.внутри(раздел, $0) }
        if внутри(["beds", "kids-beds"]) || есть(н, словаКровати) {
            итог.insert(.спальноеМесто)
            итог.insert(.матрас)
        }
        if внутри(["bedding"]) || есть(н, словаБелья) { итог.insert(.бельё) }
        if внутри(["curtains"]) || есть(н, словаШтор) { итог.insert(.шторы) }
        if (внутри(["lamps", "chandeliers", "lighting"]) || есть(н, словаЛамп)) && !н.contains("переходник") {
            итог.insert(.цоколь)
        }
        // Кронштейн, а не сам телевизор: в разделах ТВ и мониторов — только со словом «кронштейн».
        let кронштейн = есть(н, словаКронштейна)
        if (кронштейн && !внутри(["tv", "monitors"])) || (внутри(["tv-audio", "monitors"]) && н.contains("кронштейн")) {
            итог.insert(.vesa)
        }
        guard !внутри(разделыЦелыхУстройств) else { return итог }
        // GDDR видеокарты и DDR в названии платы или процессора — не модуль памяти (тип памяти платы — в сокете).
        if (внутри(["ram"]) || есть(н, словаПамяти)) && !внутри(["gpu", "motherboards", "cpu"]) && !н.contains("gddr") {
            итог.insert(.память)
        }
        if внутри(["ssd-hdd"]) || есть(н, словаНакопителя) { итог.insert(.накопитель) }
        if внутри(["gpu"]) || есть(н, словаВидеокарты) { итог.insert(.видеокарта) }
        if внутри(["power-supplies"]) || (есть(н, словаБП) && !есть(н, ["ноутбук", "laptop", "зарядк"])) {
            итог.insert(.блокПитания)
        }
        if внутри(["cpu", "motherboards"]) || есть(н, словаСокета) { итог.insert(.сокет) }
        if внутри(["motherboards", "pc-cases"]) || н.contains("материнск") || н.contains("аналық плата") {
            итог.insert(.формаПлаты)
        }
        if внутри(["pc-cases"]) || есть(н, словаКорпуса) {
            итог.insert(.корпус)
            итог.insert(.формаПлаты)
        }
        return итог
    }

    // MARK: - Объявление

    /// Строка «Параметры: …» описания (договор §5: пока сервер не хранит std) — слово продавца. Нет — пусто.
    static func строкаПараметров(_ описание: String) -> String {
        for строка in описание.split(whereSeparator: \.isNewline).suffix(12) {
            let т = строка.trimmingCharacters(in: .whitespaces)
            let нижняя = т.lowercased()
            for начало in ["параметры:", "параметрлер:", "parameters:", "specs:", "المواصفات:"] where нижняя.hasPrefix(начало) {
                return String(т.dropFirst(начало.count)).trimmingCharacters(in: .whitespaces)
            }
        }
        return ""
    }

    /**
     Разбор объявления: поле std (пачка 83, docs/SERVER_NEW_FOR_MINE.md §1.1: магазины и подача кладут стандарты полями)
     — первым слоем, с источником из std_src; дальше характеристики и строка «Параметры: …» — слово продавца; стандарт,
     прямо названный в названии, — тоже (источник «title»); свободный текст описания дополняет только недостающее и не
     поднимает выше «Проверьте».
     */
    static func разобрать(_ товар: Listing) -> РазборСтандартовОбъявления {
        let описание = String((товар.описание ?? "").prefix(1500))
        let параметры = строкаПараметров(описание)
        let пункты: [(String, String)] = товар.характеристики.isEmpty
            ? товар.характеристикиКарточки.filter { !$0.образец }.map { ($0.ключ, $0.значение) }
            : товар.характеристики.map { ($0.ключ, $0.значение) }
        let характеристики = пункты.map { $0.0 + ": " + $0.1 }.joined(separator: "\n")
        var итог = РазборСтандартовОбъявления()
        итог.цвета = цвета(характеристикЦвета(пункты) + " " + товар.title)
        /* Поле std: семьи — какие прислал сервер (у раздела их можно и не угадать), значения — каноном каталога. */
        if let поля = товар.стандартыПолей, !поля.пусто {
            итог.принять(поля, источник: поля.источник)
        }
        let нужные = семьи(раздел: товар.категория, название: товар.title + " " + параметры)
        guard !нужные.isEmpty else { return итог }
        let слои: [(String, ИсточникСтандарта)] = [
            (характеристики + "\n" + параметры, .продавец),
            (товар.title, .название),
            (описание, .текст)
        ]
        for (текст, источник) in слои where !текст.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            let слой = разобрать(текст: текст, семьи: нужные, источник: источник)
            итог.принять(слой.набор, источник: источник)
            for (семья, варианты) in слой.кандидаты where итог.кандидаты[семья] == nil {
                итог.кандидаты[семья] = варианты
            }
        }
        return итог
    }

    /// Значение пункта «Цвет» характеристик.
    private static func характеристикЦвета(_ пункты: [(String, String)]) -> String {
        пункты.filter { ["цвет", "түсі", "colour", "color", "اللون"].contains($0.0.lowercased()) }
            .map(\.1).joined(separator: " ")
    }

    /// Разбор текста по семьям: набор и неоднозначные слова (чипы на выбор).
    static func разобрать(текст: String, семьи: Set<СемьяСтандарта>,
                          источник: ИсточникСтандарта) -> (набор: НаборСтандартов, кандидаты: [СемьяСтандарта: [String]]) {
        let н = " " + нормально(текст) + " "
        var набор = НаборСтандартов(источник: источник)
        var кандидаты: [СемьяСтандарта: [String]] = [:]
        if семьи.contains(.спальноеМесто) {
            let место = спальноеМесто(н)
            набор[.спальноеМесто, КлючСтандарта.размер] = место.место
            if место.место == nil, !место.кандидаты.isEmpty { кандидаты[.спальноеМесто] = место.кандидаты }
            if семьи.contains(.матрас), есть(н, ["матрас", "матрац", "топпер", "наматрасник", "төсеніш", "mattress"]) {
                набор[.матрас, КлючСтандарта.размер] = место.место
                матрас(н, &набор)
            }
        }
        if семьи.contains(.бельё) { бельё(н, &набор) }
        if семьи.contains(.шторы) { шторы(н, &набор) }
        if семьи.contains(.цоколь) { цоколь(н, &набор) }
        if семьи.contains(.vesa) { vesa(н, &набор) }
        if семьи.contains(.память) { память(н, &набор) }
        if семьи.contains(.накопитель) { накопитель(н, &набор) }
        if семьи.contains(.видеокарта) { видеокарта(н, &набор) }
        if семьи.contains(.блокПитания) { блокПитания(н, &набор) }
        if семьи.contains(.сокет) { сокет(н, &набор) }
        if семьи.contains(.формаПлаты) || семьи.contains(.корпус) { формаИКорпус(н, семьи, &набор) }
        return (набор, кандидаты)
    }

    // MARK: - Кровать и матрас

    private static let регПара = рег(#"(?<![\d.])(\d{2,4})\s?x\s?(\d{2,4})(?![\d.])"#)

    /// Пары «ШxД» текста, по порядку (числа без единиц).
    private static func пары(_ н: String) -> [(Int, Int)] {
        все(регПара, н).compactMap { г in
            guard let а = Int(г[1]), let б = Int(г[2]) else { return nil }
            return (а, б)
        }
    }

    /// Спальное место: «160x200» (Д×Ш переставляется); слово рынка — значение или кандидаты.
    static func спальноеМесто(_ н: String) -> (место: String?, кандидаты: [String]) {
        for (а, б) in пары(н) {
            var ш = min(а, б), д = max(а, б)
            // Миллиметры: «1600х2000».
            if ш >= 600 && д >= 1200 {
                ш /= 10
                д /= 10
            }
            guard (60...200).contains(ш), (120...213).contains(д), ш < д else { continue }
            return (String(ш) + "x" + String(д), [])
        }
        for (слово, место) in КаталогСтандартов.синонимыСпальныхМест where н.contains(слово) {
            return (место, [])
        }
        for (слово, варианты) in КаталогСтандартов.неоднозначныеСпальныеМеста where н.contains(слово) {
            return (nil, варианты)
        }
        return (nil, [])
    }

    private static let регВысотаМатраса = рег(#"(?:высот\S*|(?<![a-zа-я])h)\s*[=:]?\s*(\d{1,2})\s?(?:см|cm)?(?![\d])"#)

    private static func матрас(_ н: String, _ набор: inout НаборСтандартов) {
        if let г = первое(регВысотаМатраса, н), let см = Int(г[1]), КаталогСтандартов.высотыМатраса.contains(см) {
            набор[.матрас, КлючСтандарта.высотаМатраса] = String(см)
        }
        let виды: [(String, [String])] = [
            ("independent_springs", ["независим", "pocket", "тәуелсіз"]), ("bonnel", ["боннел", "bonnel"]),
            ("latex", ["латекс", "latex"]), ("coconut", ["кокос", "coconut"]),
            ("topper", ["топпер", "topper", "наматрасник"]), ("foam", ["беспружин", "пена", "foam", "memory"])
        ]
        if let вид = виды.first(where: { есть(н, $0.1) }) {
            набор[.матрас, КлючСтандарта.видМатраса] = вид.0
        }
    }

    // MARK: - Бельё

    private static let регБорт = рег(#"(?:борт\S*|бортик\S*)\s*(?:высот\S*)?\s*(?:до)?\s*(\d{2})\s?(?:см|cm)?"#)
    private static let регПододеяльник = рег(#"пододеяльник\S*\s*:?\s*(\d{3}x\d{3})"#)
    private static let регНаволочка = рег(#"наволочк\S*\s*:?\s*(?:\d\s?шт\S*\s*)?(\d{2}x\d{2})"#)

    private static func бельё(_ н: String, _ набор: inout НаборСтандартов) {
        let комплекты: [(String, [String])] = [
            ("euro", ["евро", "euro"]), ("family", ["семейн", "family", "отбасылық"]),
            ("1.5", ["1.5-сп", "1.5 сп", "полуторн", "бір жарым"]), ("2", ["2-сп", "2 сп", "двуспальн", "екі кісілік"])
        ]
        if let к = комплекты.first(where: { есть(н, $0.1) }) {
            набор[.бельё, КлючСтандарта.комплект] = к.0
        }
        if есть(н, ["на резинке", "натяжн", "fitted", "резеңке"]) {
            if case let (а, б)? = пары(н).first(where: { min($0.0, $0.1) >= 60 && max($0.0, $0.1) <= 213 }) {
                набор[.бельё, КлючСтандарта.наРезинке] = String(min(а, б)) + "x" + String(max(а, б))
            }
            if let г = первое(регБорт, н), let см = Int(г[1]), (10...45).contains(см) {
                набор[.бельё, КлючСтандарта.борт] = String(см)
            }
        }
        if let г = первое(регПододеяльник, н) { набор[.бельё, КлючСтандарта.пододеяльник] = г[1] }

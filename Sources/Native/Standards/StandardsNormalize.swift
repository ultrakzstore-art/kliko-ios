    /// Цвета текста — до двух, по порядку появления.
    static func цвета(_ текст: String) -> [ЦветСтандарта] {
        let н = текст.lowercased().replacingOccurrences(of: "ё", with: "е")
        let слова = н.split { !($0.isLetter || $0 == "-") }.map(String.init)
        var итог: [ЦветСтандарта] = []
        for слово in слова {
            let цвет = целыеСловаЦветов[слово] ?? словаЦветов.first(where: { слово.hasPrefix($0.0) })?.1
            guard let цвет, !итог.contains(цвет) else { continue }
            итог.append(цвет)
            if итог.count >= 2 { break }
        }
        return итог
    }


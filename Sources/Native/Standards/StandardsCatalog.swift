    /// «160x200» → (160, 200); не пара чисел — nil.
    static func пара(_ строка: String?) -> (Double, Double)? {
        guard let строка else { return nil }
        let части = строка.lowercased().split(separator: "x")
        guard части.count == 2, let а = Double(части[0]), let б = Double(части[1]), а > 0, б > 0 else { return nil }
        return (а, б)
    }

    /// (160, 200) → «160x200»; без лишних нулей.
    static func канон(_ а: Double, _ б: Double) -> String {
        ЧислаАвтоподбора.ч(а) + "x" + ЧислаАвтоподбора.ч(б)
    }


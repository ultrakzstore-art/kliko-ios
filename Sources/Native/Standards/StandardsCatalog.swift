        if let tgp = чип.flatMap({ tgpПоЧипу[$0] }) {
            расчёт = Int((Double((tdpПроцессора ?? 65) + tgp + 100) * 1.3).rounded(.up))
        }
        guard let нужно = [рекомендация, расчёт].compactMap({ $0 }).max() else { return nil }
        return рядНужногоБП.first { $0 >= нужно } ?? рядНужногоБП.last
    }

    /// Ступень ряда ниже данной (для «на одну ступень ниже — Проверьте»).
    static func ступеньНиже(_ ватт: Int) -> Int? {
        рядНужногоБП.last { $0 < ватт }
    }


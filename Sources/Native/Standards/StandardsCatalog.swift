// MARK: - Цвета

/**
 Палитра из 16 ключей (docs/SERVER_CIRCLE.md §11.2, rules.colors): чип вещи гардероба, палитра комнаты, цвет из
 названия объявления. «Цвет сам» — ближайший к среднему цвету вырезанной вещи (считает экран на телефоне, сюда — только
 числа). Сочетания — для «с чем носить» и порядка подборки дома: стиль и цвет никогда не отсекают, только упорядочивают.
 */
enum ЦветСтандарта: String, CaseIterable, Codable, Sendable, Identifiable {
    case чёрный = "black"
    case белый = "white"
    case серый = "grey"
    case бежевый = "beige"
    case коричневый = "brown"
    case красный = "red"
    case оранжевый = "orange"
    case жёлтый = "yellow"
    case зелёный = "green"
    case синий = "blue"
    case тёмноСиний = "navy"
    case фиолетовый = "purple"
    case розовый = "pink"
    case золотой = "gold"
    case серебристый = "silver"
    case разноцветный = "multi"

    var id: String { rawValue }

    /// Чип цвета; у «разноцветного» своего нет.
    var hex: UInt32? {
        switch self {
        case .чёрный: return 0x111111
        case .белый: return 0xFFFFFF
        case .серый: return 0x9CA3AF
        case .бежевый: return 0xE8D9C0
        case .коричневый: return 0x7B4A2D
        case .красный: return 0xD92D20
        case .оранжевый: return 0xF79009
        case .жёлтый: return 0xFACC15
        case .зелёный: return 0x16A34A
        case .синий: return 0x2563EB
        case .тёмноСиний: return 0x1E2A55
        case .фиолетовый: return 0x7C3AED
        case .розовый: return 0xEC4899
        case .золотой: return 0xC9A227
        case .серебристый: return 0xC0C0C0
        case .разноцветный: return nil
        }
    }

    /// «Чёрный», «Тёмно-синий» на языке приложения.
    var название: String { СтандартыText.т("col_" + rawValue) }

    /// Заливка чипа; «разноцветный» — серый (экран рисует ему радугу сам).
    var краска: Color { Color(uiColor: Theme.hex(hex ?? 0x9CA3AF)) }

    /// Светлый чип — обводка и тёмная галочка.
    var светлый: Bool { [.белый, .бежевый, .жёлтый, .серебристый].contains(self) }

    /// Нейтральные идут со всем.
    var нейтральный: Bool { [.чёрный, .белый, .серый, .бежевый, .тёмноСиний].contains(self) }

    /// Пары, которые носят вместе (кроме нейтральных и одного цвета), — без порядка.
    private static let пары: Set<String> = [
        "beige|brown", "beige|green", "blue|white", "brown|green", "blue|brown", "beige|blue", "navy|red",
        "black|red", "grey|pink", "navy|pink", "grey|yellow", "navy|yellow", "grey|purple", "black|gold",
        "gold|navy", "gold|white", "black|silver", "grey|silver", "silver|white", "blue|silver", "navy|orange",
        "blue|orange", "beige|orange", "green|navy", "brown|orange", "beige|pink", "brown|yellow"
    ]

    /// Сочетается ли с другим: нейтральный, тот же или известная пара; «разноцветный» — только с нейтральными.
    func сочетается(с другим: ЦветСтандарта) -> Bool {
        if self == другим { return self != .разноцветный }
        if нейтральный || другим.нейтральный { return true }
        if self == .разноцветный || другим == .разноцветный { return false }
        let ключ = [rawValue, другим.rawValue].sorted().joined(separator: "|")
        return Self.пары.contains(ключ)
    }

    /// Цвета, с которыми носят этот, — порядком палитры (сам — первым).
    var подходящие: [ЦветСтандарта] {
        [self] + Self.allCases.filter { $0 != self && сочетается(с: $0) }
    }

    /**
     Ближайший цвет палитры к среднему цвету вещи (sRGB, 0…1): взвешенное расстояние «redmean» (ближе к глазу, чем
     простое). Золотой и серебристый сами не ставятся — металл по фото не отличить от жёлтого и серого.
     */
    static func ближайший(красный: Double, зелёный: Double, синий: Double) -> ЦветСтандарта {
        let r = min(255, max(0, красный * 255)), g = min(255, max(0, зелёный * 255)), b = min(255, max(0, синий * 255))
        var лучший = ЦветСтандарта.серый
        var меньше = Double.greatestFiniteMagnitude
        for цвет in allCases where цвет != .разноцветный && цвет != .золотой && цвет != .серебристый {
            guard let h = цвет.hex else { continue }
            let r2 = Double((h >> 16) & 0xFF), g2 = Double((h >> 8) & 0xFF), b2 = Double(h & 0xFF)
            let rm = (r + r2) / 2
            let dr = r - r2, dg = g - g2, db = b - b2
            /* Три слагаемых с явным типом: одна длинная формула с литералами — риск проверки типов (Double и CGFloat). */
            let частьR: Double = (2 + rm / 256) * dr * dr
            let частьG: Double = 4 * dg * dg
            let частьB: Double = (2 + (255 - rm) / 256) * db * db
            let d: Double = частьR + частьG + частьB
            if d < меньше {
                меньше = d
                лучший = цвет
            }
        }
        return лучший
    }

    /// Ключи цвета из ответа или файла: незнакомые отброшены, без повторов, не больше предела.
    static func из(_ ключи: [String], предел: Int = 2) -> [ЦветСтандарта] {
        var итог: [ЦветСтандарта] = []
        for ключ in ключи {
            guard let ц = ЦветСтандарта(rawValue: ключ), !итог.contains(ц) else { continue }
            итог.append(ц)
            if итог.count >= предел { break }
        }
        return итог
    }
}

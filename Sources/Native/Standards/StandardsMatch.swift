import Foundation

/**
 СТАНДАРТЫ — СВЕРКА «МОЁ ↔ ОБЪЯВЛЕНИЕ» (docs/STANDARDS.md §2.5, §4, §6.1; каталог — match, need).

 Дом: спальное место и матрас ↔ кровать (±1 см — подходит, 2–3 — проверьте, больше — нет); бельё ↔ кровать, матрас,
 одеяло (простыня на резинке — по месту и борту, пододеяльник ±5 см); жалюзи и рулонные шторы ↔ окно (±1 см), шторы ↔
 потолок (ориентир, не выше «Проверьте»); кронштейн ↔ ТВ на стене (шаблон VESA в шаблонах кронштейна, меньше
 наименьшего — пластина-переходник, вес не больше предела); лампа ↔ цоколи дома (тот же — подходит, E14↔E27 и
 GU10→E27 — переходник); мебель и техника по габаритам ↔ дверь и лифт («пройдёт ли»: два меньших габарита с запасом
 2 см, только наклоном — проверьте).

 Компьютер (каждый из «Моего», лучший — итогом): ОЗУ — поколение и форма точно, частота «на скорости старого»,
 распаяно и RDIMM — нет, слоты и максимум — проверьте; накопитель — длина слота (короче — стойка), NVMe / SATA точно,
 PCIe — на скорости слота, 2.5″ — отсек; видеокарта — длина против корпуса − 10 мм, БП против рекомендации чипа (и
 эвристики Kliko psu_need), урезанная шина на старой плате — подходит с пометкой; блок питания — ватты против нужного,
 SFX в ATX — рамка; процессор и плата — сокет точно, BIOS — проверьте, форм-фактор платы не больше корпуса.

 Итог — худший пункт, с причинами в цифрах, и не выше потолка источника объявления (РазборСтандартовОбъявления.потолок).
 Нет нужного в «Моём» — «Неизвестно» с одним вопросом (или nil, если раздел пуст совсем: зовёт заполнить вызывающий).
 Чистые функции, без сети и главной нити.
 */
enum СверкаСтандартов {
    typealias К = КлючСтандарта

    private static func т(_ ключ: String) -> String { СтандартыText.т(ключ) }
    private static func ф(_ ключ: String, _ аргументы: String...) -> String {
        String(format: т(ключ), arguments: аргументы.map { $0 as CVarArg })
    }
    private static func ч(_ x: Double) -> String { ЧислоМоего.ч(x) }

    // MARK: - Вход

    /// Все итоги объявления против «Моего» — по семьям, которые нашлись; лучший — первым.
    static func сверить(_ товар: Listing, моё: ЗаписьМоего) -> [ИтогСверкиСтандарта] {
        сверить(РазборСтандартов.разобрать(товар), габариты: товар.габаритыПолей, раздел: товар.категория, моё: моё)
    }

    static func сверить(_ разбор: РазборСтандартовОбъявления, габариты: [String: Double], раздел: String?,
                        моё: ЗаписьМоего) -> [ИтогСверкиСтандарта] {
        guard Config.стандарты else { return [] }
        let н = разбор.набор
        var итоги: [ИтогСверкиСтандарта] = []
        let дом = моё.дом
        if н.есть(.спальноеМесто) || разбор.кандидаты[.спальноеМесто] != nil, let и = кровать(разбор, дом) {
            итоги.append(и)
        }
        if н.есть(.бельё), let и = бельё(разбор, дом) { итоги.append(и) }
        if н.есть(.шторы), let и = шторы(разбор, дом) { итоги.append(и) }
        if н.есть(.vesa), let и = кронштейн(разбор, моё) { итоги.append(и) }
        if н.есть(.цоколь), let и = лампа(разбор, дом) { итоги.append(и) }
        if РазделыСайта.внутри(раздел, разделыПроёма), let и = пройдёт(габариты: габариты, дом: дом) { итоги.append(и) }
        if !моё.компьютеры.isEmpty {
            let семьиПК: [СемьяСтандарта] = [.память, .накопитель, .видеокарта, .блокПитания, .сокет]
            for семья in семьиПК where н.есть(семья) {
                if let и = лучшийКомпьютер(семья, разбор, моё.компьютеры) { итоги.append(и) }
            }
            if !н.есть(.сокет), н.есть(.формаПлаты), let и = лучшийКомпьютер(.формаПлаты, разбор, моё.компьютеры) {
                итоги.append(и)
            }
        }
        return итоги.sorted { $0.уровень < $1.уровень }
    }

    /// Разделы, где есть смысл «Пройдёт ли в дверь и лифт?» (cats семьи opening).
    static let разделыПроёма: Set<String> = ["furniture", "fridges", "washing-machines", "dishwashers", "stoves",
                                             "air-conditioners", "treadmills"]

    /// Итог из пунктов: худший пункт, не выше потолка семьи объявления.
    private static func итог(_ семья: СемьяСтандарта, _ разбор: РазборСтандартовОбъявления,
                             _ пункты: [ПунктСверкиСтандарта], заголовки: [УровеньСтандарта: String],
                             почему: String, деталь: String? = nil, куда: String? = nil) -> ИтогСверкиСтандарта {
        let худший = УровниСтандарта.худший(пункты.map(\.уровень))
        let уровень = худший == .неизвестно ? худший : УровниСтандарта.неВыше(худший, разбор.потолок(семья))
        let заголовок = заголовки[уровень] ?? заголовки[.проверить] ?? т("st_check_pc")
        let упорядоченные = пункты.sorted { $0.уровень > $1.уровень }
        return ИтогСверкиСтандарта(семья: семья, уровень: уровень, заголовок: заголовок, почему: почему,
                                   пункты: упорядоченные, деталь: уровень == .доработка ? деталь : nil, куда: куда)
    }

    // MARK: - Кровать и матрас

    /// Разница двух «ШxД», см: наибольшая по сторонам; не пары — nil.
    static func разница(_ а: String?, _ б: String?) -> Double? {
        guard let п1 = КаталогСтандартов.пара(а), let п2 = КаталогСтандартов.пара(б) else { return nil }
        return max(abs(п1.0 - п2.0), abs(п1.1 - п2.1))
    }

    /// Допуск спального места: ±1 — подходит, 2–3 — проверьте, больше — нет.
    static func уровеньМеста(_ d: Double) -> УровеньСтандарта {
        d <= 1 ? .подходит : (d <= 3 ? .проверить : .неПодходит)
    }

    static func кровать(_ разбор: РазборСтандартовОбъявления, _ дом: ДомМоего) -> ИтогСверкиСтандарта? {
        let мои = дом.кровати.filter { $0.место != nil }
        guard !мои.isEmpty else { return nil }
        let заголовки: [УровеньСтандарта: String] = [.подходит: т("st_bed_ok"), .проверить: т("st_bed_check"),
                                                     .неПодходит: т("st_bed_bad")]
        let найденное = разбор.набор[.спальноеМесто, К.размер] ?? разбор.набор[.матрас, К.размер]
        guard let его = найденное else {
            // «Двуспальная» — значения нет: если моя кровать среди вариантов — «проверьте», иначе молчим.
            guard let варианты = разбор.кандидаты[.спальноеМесто],
                  let моя = мои.first(where: { варианты.contains($0.место ?? "") }), let место = моя.место else { return nil }
            let пункт = ПунктСверкиСтандарта(К.размер, .проверить, ф("st_bed_ask", КаталогСтандартов.показ(место)))
            return итог(.спальноеМесто, разбор, [пункт], заголовки: заголовки, почему: пункт.текст,
                        куда: дом.имяКомнаты(моя.комната))
        }
        var лучший: (ИтогСверкиСтандарта, Double)? = nil
        for моя in мои {
            guard let место = моя.место, let d = разница(его, место) else { continue }
            var пункты = [ПунктСверкиСтандарта(К.размер, уровеньМеста(d), ф("st_bed_sub", КаталогСтандартов.показ(его),
                                                                                КаталогСтандартов.показ(место)))]
            if let высота = разбор.набор.целое(.матрас, К.высотаМатраса), let своя = моя.матрасВысота,
               abs(высота - своя) >= 5 {
                пункты.append(ПунктСверкиСтандарта(К.высотаМатраса, .проверить,
                                                   ф("st_mattress_h", String(высота), String(своя))))
            }
            let и = итог(.спальноеМесто, разбор, пункты, заголовки: заголовки, почему: пункты[0].текст,
                         куда: дом.имяКомнаты(моя.комната))
            if лучший == nil || и.уровень < лучший!.0.уровень || (и.уровень == лучший!.0.уровень && d < лучший!.1) {
                лучший = (и, d)
            }
        }
        return лучший?.0
    }

    // MARK: - Бельё

    static func бельё(_ разбор: РазборСтандартовОбъявления, _ дом: ДомМоего) -> ИтогСверкиСтандарта? {
        let н = разбор.набор
        let мои = дом.кровати.filter { $0.место != nil || $0.одеяло != nil || $0.подушки != nil }
        guard !мои.isEmpty else { return nil }
        var лучший: ИтогСверкиСтандарта? = nil
        for моя in мои {
            var пункты: [ПунктСверкиСтандарта] = []
            if let резинка = н[.бельё, К.наРезинке] {
                guard let место = моя.место, let d = разница(резинка, место) else { continue }
                пункты.append(ПунктСверкиСтандарта(К.наРезинке, уровеньМеста(d),
                                                   ф("st_bed_sub", КаталогСтандартов.показ(резинка),
                                                     КаталогСтандартов.показ(место))))
                if let борт = н.целое(.бельё, К.борт), let матрас = моя.матрасВысота {
                    let хватит = борт >= матрас
                    пункты.append(ПунктСверкиСтандарта(К.борт, хватит ? .подходит : .неПодходит,
                                                       ф(хватит ? "st_fitted_side_ok" : "st_fitted_side_bad",
                                                         String(борт), String(матрас))))
                }
            } else if let пододеяльник = н[.бельё, К.пододеяльник]
                        ?? н[.бельё, К.комплект].flatMap({ КаталогСтандартов.комплект($0)?.пододеяльник }) {
                if let одеяло = моя.одеяло, let d = разница(пододеяльник, одеяло) {
                    пункты.append(ПунктСверкиСтандарта(К.пододеяльник, d <= 5 ? .подходит : .неПодходит,
                                                       ф("st_duvet_sub", КаталогСтандартов.показ(пододеяльник),
                                                         КаталогСтандартов.показ(одеяло))))
                } else if let ширина = моя.ширина, let комплект = н[.бельё, К.комплект] {
                    let обычный = КаталогСтандартов.комплектОбычно(ширинаМеста: ширина)
                    пункты.append(ПунктСверкиСтандарта(К.комплект, .проверить,
                                                       ф("st_set_usual", КаталогСтандартов.показ(моя.место ?? ""),
                                                         т("set_" + обычный)) + (комплект == обычный ? " ✓" : "")))
                } else {
                    пункты.append(ПунктСверкиСтандарта(К.одеяло, .неизвестно, т("st_duvet_need")))
                }
            } else if let наволочка = н[.бельё, К.наволочка], let подушки = моя.подушки,
                      let d = разница(наволочка, подушки) {
                пункты.append(ПунктСверкиСтандарта(К.наволочка, d <= 2 ? .подходит : .неПодходит,
                                                   ф("st_pillow_sub", КаталогСтандартов.показ(наволочка),
                                                     КаталогСтандартов.показ(подушки))))
            } else if let одеяло = н[.бельё, К.одеяло], let своё = моя.одеяло, let d = разница(одеяло, своё) {
                пункты.append(ПунктСверкиСтандарта(К.одеяло, d <= 5 ? .подходит : .проверить,
                                                   ф("st_duvet_sub", КаталогСтандартов.показ(одеяло),
                                                     КаталогСтандартов.показ(своё))))
            }
            guard !пункты.isEmpty else { continue }
            let заголовки: [УровеньСтандарта: String] = [.подходит: т("st_linen_ok"), .проверить: т("st_linen_check"),
                                                         .неПодходит: т("st_linen_bad"), .неизвестно: т("st_duvet_need")]
            let и = итог(.бельё, разбор, пункты, заголовки: заголовки, почему: пункты.sorted { $0.уровень > $1.уровень }[0].текст,
                         куда: дом.имяКомнаты(моя.комната))
            if лучший == nil || и.уровень < лучший!.уровень { лучший = и }
        }
        return лучший
    }

    // MARK: - Окна и шторы

    static func шторы(_ разбор: РазборСтандартовОбъявления, _ дом: ДомМоего) -> ИтогСверкиСтандарта? {
        let н = разбор.набор
        let жалюзи = н[.шторы, К.видШтор] == "blind"
        guard let высота = н.целое(.шторы, К.высота) else { return nil }
        if жалюзи {
            guard let ширина = н.целое(.шторы, К.ширина) else { return nil }
            let окна = дом.окна.filter(\.заполнено)
            guard !окна.isEmpty else { return nil }
            let заголовки: [УровеньСтандарта: String] = [.подходит: т("st_blind_ok"), .проверить: т("st_blind_check"),
                                                         .неПодходит: т("st_blind_bad")]
            var лучший: ИтогСверкиСтандарта? = nil
            for окно in окна {
                guard let ш = окно.ширина, let в = окно.высота else { continue }
                let dw = Double(abs(ширина - ш))
                var пункты = [ПунктСверкиСтандарта(К.ширина, уровеньМеста(dw),
                                                   ф("st_blind_sub", String(ширина) + "×" + String(высота),
                                                     String(ш) + "×" + String(в)))]
                if высота + 1 < в {
                    пункты.append(ПунктСверкиСтандарта(К.высота, .проверить, ф("st_blind_short", String(высота),
                                                                              String(в))))
                }
                if окно.примерно {
                    пункты.append(ПунктСверкиСтандарта("approx", .проверить, т("st_measure_approx")))
                }
                let и = итог(.шторы, разбор, пункты, заголовки: заголовки, почему: пункты[0].текст,
                             куда: дом.имяКомнаты(окно.комната))
                if лучший == nil || и.уровень < лучший!.уровень { лучший = и }
            }
            return лучший
        }
        guard let потолок = дом.потолок else { return nil }
        let запас = потолок - высота
        let уровень: УровеньСтандарта = запас < 0 ? .неПодходит : .проверить
        let пункт = ПунктСверкиСтандарта(К.высота, уровень, ф("st_curtain_sub", String(высота), String(потолок)))
        let заголовки: [УровеньСтандарта: String] = [.проверить: КаталогСтандартов.отступШтор.contains(запас)
                                                         ? т("st_curtain_ok") : т("st_curtain_check"),
                                                     .неПодходит: т("st_curtain_bad")]
        return итог(.шторы, разбор, [пункт], заголовки: заголовки, почему: пункт.текст)
    }

    // MARK: - Кронштейн VESA

    /// Шаблон «400x300» → (400, 300).
    private static func стороны(_ шаблон: String?) -> (Double, Double)? { КаталогСтандартов.пара(шаблон) }

    /// Экраны «Моего» для кронштейна: ТВ на стене и ТВ, мониторы «Моих устройств» (VESA по диагонали — примерно).
    private static func экраны(_ моё: ЗаписьМоего) -> [(шаблон: String, примерно: Bool, вес: Double?, диагональ: Double?,
                                                      комната: UUID?)] {
        var итог: [(шаблон: String, примерно: Bool, вес: Double?, диагональ: Double?, комната: UUID?)] = []
        for э in моё.дом.экраны {
            guard let ш = э.шаблонДляСверки else { continue }
            итог.append((ш.шаблон, ш.примерно, э.вес, э.диагональ, э.комната))
        }
        let связанные = Set(моё.дом.экраны.compactMap(\.устройство))
        for у in моё.экраны where !связанные.contains(у.id) {
            guard let д = у.диагональ else { continue }
            итог.append((КаталогСтандартов.vesaОбычно(диагональ: д), true, nil, д, nil))
        }
        return итог
    }

    static func кронштейн(_ разбор: РазборСтандартовОбъявления, _ моё: ЗаписьМоего) -> ИтогСверкиСтандарта? {
        let н = разбор.набор
        guard let наибольший = н[.vesa, К.шаблон], let верх = стороны(наибольший) else { return nil }
        let мои = экраны(моё)
        guard !мои.isEmpty else { return nil }
        let список = н[.vesa, К.шаблоны] ?? наибольший
        let диапазон = список.contains("..")
        let низ = диапазон ? стороны(String(список.split(separator: ".").first ?? "")) ?? верх : верх
        let заголовки: [УровеньСтандарта: String] = [.подходит: т("st_vesa_ok"), .доработка: т("st_vesa_adapt"),
                                                     .проверить: т("st_vesa_check"), .неПодходит: т("st_vesa_bad")]
        var лучший: ИтогСверкиСтандарта? = nil
        for экран in мои {
            guard let мой = стороны(экран.шаблон) else { continue }
            let текст = ф("st_vesa_sub", КаталогСтандартов.показ(наибольший), КаталогСтандартов.показ(экран.шаблон))
            let уровень: УровеньСтандарта
            if мой.0 > верх.0 || мой.1 > верх.1 {
                уровень = .неПодходит
            } else if диапазон {
                уровень = (мой.0 >= низ.0 && мой.1 >= низ.1) ? .подходит : .доработка
            } else {
                уровень = (мой.0 == верх.0 && мой.1 == верх.1) ? .подходит : .проверить
            }
            var пункты = [ПунктСверкиСтандарта(К.шаблон, уровень, текст)]
            if экран.примерно {
                пункты.append(ПунктСверкиСтандарта("approx", .проверить, т("st_vesa_approx")))
            }
            if let предел = н.число(.vesa, К.доКг), let вес = экран.вес {
                let выдержит = вес <= предел
                пункты.append(ПунктСверкиСтандарта(К.доКг, выдержит ? .подходит : .неПодходит,
                                                   ф(выдержит ? "st_vesa_kg_ok" : "st_vesa_kg_bad", ч(предел), ч(вес))))
            }
            if let от = н.число(.vesa, К.диагональОт), let до = н.число(.vesa, К.диагональДо), let д = экран.диагональ,
               !(от...до).contains(д) {
                пункты.append(ПунктСверкиСтандарта(К.диагональ, .проверить,
                                                   ф("st_vesa_diag", ч(от), ч(до), ч(д))))
            }
            let и = итог(.vesa, разбор, пункты, заголовки: заголовки, почему: текст, деталь: т("st_vesa_plate"),
                         куда: моё.дом.имяКомнаты(экран.комната))
            if лучший == nil || и.уровень < лучший!.уровень { лучший = и }
        }
        return лучший
    }

    // MARK: - Лампы

    static func лампа(_ разбор: РазборСтандартовОбъявления, _ дом: ДомМоего) -> ИтогСверкиСтандарта? {
        guard let его = разбор.набор[.цоколь, К.цоколь] else { return nil }
        let мои = дом.цоколи
        guard !мои.isEmpty else { return nil }
        /* По шагам с явными типами: цепочка sorted (тернарный по кортежам), prefix, map, joined тяжела для
           проверки типов.
           Порядок прежний: больше ламп — раньше, при равенстве — по алфавиту. */
        let порядокЦоколей: [(key: String, value: Int)] = мои.sorted {
            (а: (key: String, value: Int), б: (key: String, value: Int)) -> Bool in
            if а.value != б.value { return а.value > б.value }
            return а.key < б.key
        }
        var частиСводки: [String] = []
        for пара in порядокЦоколей.prefix(3) {
            частиСводки.append(пара.key + " ×" + String(пара.value))
        }
        let сводка: String = частиСводки.joined(separator: " · ")
        let заголовки: [УровеньСтандарта: String] = [.подходит: т("st_lamp_ok"), .доработка: т("st_lamp_adapt"),
                                                     .проверить: т("st_lamp_check"), .неПодходит: т("st_lamp_bad")]
        if let сколько = мои[его] {
            var пункты = [ПунктСверкиСтандарта(К.цоколь, .подходит, ф("st_lamp_sub", его, его + " ×" + String(сколько)))]
            if КаталогСтандартов.цоколь(его)?.вольт == 12 {
                пункты.append(ПунктСверкиСтандарта(К.вольт, .подходит, ф("st_lamp_12v", его)))
            }
            let комната = дом.лампы.first { $0.цоколь == его }?.комната
            return итог(.цоколь, разбор, пункты, заголовки: заголовки, почему: пункты[0].текст,
                        куда: дом.имяКомнаты(комната))
        }
        if let патрон = мои.keys.sorted().first(where: { КаталогСтандартов.переходник(патрон: $0, лампа: его) != nil }),
           let переходник = КаталогСтандартов.переходник(патрон: патрон, лампа: его) {
            let деталь = ф("st_adapter", переходник)
            let пункт = ПунктСверкиСтандарта(К.цоколь, .доработка, ф("st_lamp_sub", его, сводка))
            return итог(.цоколь, разбор, [пункт], заголовки: заголовки, почему: деталь, деталь: деталь)
        }
        let пункт = ПунктСверкиСтандарта(К.цоколь, .неПодходит, ф("st_lamp_sub", его, сводка))
        return итог(.цоколь, разбор, [пункт], заголовки: заголовки, почему: пункт.текст)
    }

    // MARK: - Пройдёт ли в дверь и лифт

    /**
     Вещь с габаритами dim_w, dim_h, dim_d (см) против пути в дом — та же сверка, что карточка «Пройдёт ли?» экрана дома
     (ПройдётЛиМоего, MyThingsHomePass.swift): лестница с поворотом, лучший из лифтов, этаж, «впритык», «примерно».
     Плашка объявления, чип «Для моего» и «Для вас» отвечают так же, как экран дома. Пути нет — nil.
     */
    static func пройдёт(габариты: [String: Double], дом: ДомМоего) -> ИтогСверкиСтандарта? {
        ПройдётЛиМоего.проверить(габариты: габариты, дом: дом)?.итогСверки
    }

    // MARK: - Компьютер

    /// Лучший итог семьи среди компьютеров «Моего» (подходящий — раньше, при равенстве — главный).
    private static func лучшийКомпьютер(_ семья: СемьяСтандарта, _ разбор: РазборСтандартовОбъявления,
                                        _ компьютеры: [КомпьютерМоего]) -> ИтогСверкиСтандарта? {
        var лучший: ИтогСверкиСтандарта? = nil
        for к in компьютеры {
            let найдено: ИтогСверкиСтандарта?
            switch семья {
            case .память: найдено = память(разбор, к)
            case .накопитель: найдено = накопитель(разбор, к)
            case .видеокарта: найдено = видеокарта(разбор, к)
            case .блокПитания: найдено = блокПитания(разбор, к)
            case .сокет: найдено = сокет(разбор, к)
            case .формаПлаты: найдено = плата(разбор, к)
            default: найдено = nil
            }
            guard let и = найдено else { continue }
            if лучший == nil || и.уровень < лучший!.уровень { лучший = и }
        }
        return лучший
    }

    /// Заголовки итога для компьютера: «Подходит вашему ноутбуку ✓» и так далее.
    private static func заголовкиПК(_ к: КомпьютерМоего, деталь: String? = nil) -> [УровеньСтандарта: String] {
        let ноутбук = к.вид == .ноутбук
        return [.подходит: т(ноутбук ? "st_ok_laptop" : "st_ok_desktop"),
                .доработка: деталь.map { ф("st_adapt_pc", $0) } ?? т("st_check_pc"),
                .неизвестно: т("st_unknown_pc"),
                .проверить: т("st_check_pc"),
                .неПодходит: т(ноутбук ? "st_bad_laptop" : "st_bad_desktop")]
    }

    private static func итогПК(_ семья: СемьяСтандарта, _ разбор: РазборСтандартовОбъявления, _ к: КомпьютерМоего,
                               _ пункты: [ПунктСверкиСтандарта], деталь: String? = nil) -> ИтогСверкиСтандарта {
        let худший = пункты.max { $0.уровень < $1.уровень }
        // «Почему» — худший пункт; всё подходит — первый (главное: «DDR4 SO-DIMM ✓», «станет 16 ГБ»).
        let почему = (худший?.уровень == .подходит ? пункты.last?.текст : худший?.текст) ?? ""
        return итог(семья, разбор, пункты, заголовки: заголовкиПК(к, деталь: деталь), почему: почему, деталь: деталь,
                    куда: к.заголовок)
    }

    /// ОЗУ (ram_fit): поколение и форма — точно; распаяно и RDIMM — нет; частота — на скорости старого; слоты и
    /// максимум — проверьте.
    static func память(_ разбор: РазборСтандартовОбъявления, _ к: КомпьютерМоего) -> ИтогСверкиСтандарта? {
        let н = разбор.набор
        guard н.есть(.память) else { return nil }
        let м = к.память
        var пункты: [ПунктСверкиСтандарта] = []
        if м.всяРаспаяна {
            return итогПК(.память, разбор, к, [ПунктСверкиСтандарта("soldered", .неПодходит, т("st_ram_soldered"))])
        }
        guard let моёПоколение = м.поколение, let мояФорма = м.форма else {
            return итогПК(.память, разбор, к, [ПунктСверкиСтандарта(К.поколение, .неизвестно, т("st_ram_need"))])
        }
        if let п = н[.память, К.поколение] {
            let а = КаталогСтандартов.основа(поколения: п), б = КаталогСтандартов.основа(поколения: моёПоколение)
            if а != б {
                пункты.append(ПунктСверкиСтандарта(К.поколение, .неПодходит, ф("st_ram_gen_bad", п, моёПоколение)))
            } else if п != моёПоколение {
                пункты.append(ПунктСверкиСтандарта(К.поколение, .проверить, т("st_ram_ddr3l")))
            } else {
                пункты.append(ПунктСверкиСтандарта(К.поколение, .подходит, п + " ✓"))
            }
        } else {
            пункты.append(ПунктСверкиСтандарта(К.поколение, .проверить, т("st_ram_gen_unknown")))
        }
        if let форма = н[.память, К.форма] {
            if форма == "soldered" {
                пункты.append(ПунктСверкиСтандарта(К.форма, .неПодходит, т("st_ram_soldered_item")))
            } else if форма != мояФорма {
                пункты.append(ПунктСверкиСтандарта(К.форма, .неПодходит, ф("st_ram_form_bad", форма, мояФорма)))
            } else {
                пункты.append(ПунктСверкиСтандарта(К.форма, .подходит, форма + " ✓"))
            }
        } else {
            пункты.append(ПунктСверкиСтандарта(К.форма, .проверить, т("st_ram_form_unknown")))
        }
        if let вид = н[.память, К.видПамяти], вид == "RDIMM" || вид == "LRDIMM" {
            пункты.append(ПунктСверкиСтандарта(К.видПамяти, .неПодходит, ф("st_ram_rdimm", вид)))
        }
        if let частота = н.целое(.память, К.частота), let моя = м.частота, частота != моя {
            let текст = частота > моя ? ф("st_ram_faster", String(моя)) : ф("st_ram_slower", String(частота))
            пункты.append(ПунктСверкиСтандарта(К.частота, .подходит, текст))
        }
        let штук = max(1, н.сколько)
        if let свободно = м.свободно, свободно < штук {
            пункты.append(ПунктСверкиСтандарта("slots", .проверить, т("st_ram_slots_full")))
        } else if let гб = н.целое(.память, К.гб) {
            let станет = (м.всего ?? 0) + гб * штук
            if let максимум = м.максимум, станет > максимум {
                пункты.append(ПунктСверкиСтандарта("max", .проверить, ф("st_ram_max", String(максимум))))
            } else if м.всего != nil {
                пункты.append(ПунктСверкиСтандарта("total", .подходит, ф("st_ram_will", String(станет))))
            }
        }
        return итогПК(.память, разбор, к, пункты)
    }

    /// Накопитель (m2_fit): длина не больше слота (короче — стойка), NVMe / SATA точно, поколение — на скорости слота;
    /// 2.5″ — отсек.
    static func накопитель(_ разбор: РазборСтандартовОбъявления, _ к: КомпьютерМоего) -> ИтогСверкиСтандарта? {
        let н = разбор.набор
        guard let форма = н[.накопитель, К.форма] else { return nil }
        var пункты: [ПунктСверкиСтандарта] = []
        var деталь: String? = nil
        if let длина = КаталогСтандартов.длинаM2(форма) {
            guard !к.слотыM2.isEmpty else {
                return итогПК(.накопитель, разбор, к, [ПунктСверкиСтандарта("slot", .неизвестно, т("st_ssd_need"))])
            }
            let слот = к.свободныйM2 ?? к.слотыM2[0]
            if к.свободныйM2 == nil {
                пункты.append(ПунктСверкиСтандарта("busy", .проверить, т("st_ssd_busy")))
            }
            let слотДлина = КаталогСтандартов.длинаM2(слот.длина) ?? 80
            if длина > слотДлина {
                пункты.append(ПунктСверкиСтандарта(К.форма, .неПодходит, ф("st_ssd_len_bad", форма, слот.длина)))
            } else if длина < слотДлина {
                деталь = ф("st_ssd_len_adapt", форма)
                пункты.append(ПунктСверкиСтандарта(К.форма, .доработка, ф("st_ssd_len_ok", форма, слот.длина)))
            } else {
                пункты.append(ПунктСверкиСтандарта(К.форма, .подходит, ф("st_ssd_len_ok", форма, слот.длина)))
            }
            if let протокол = н[.накопитель, К.протокол], слот.протокол != "both", протокол != слот.протокол {
                пункты.append(ПунктСверкиСтандарта(К.протокол, .неПодходит,
                                                   ф("st_ssd_proto_bad", протокол.uppercased(), слот.протокол.uppercased())))
            } else if н[.накопитель, К.протокол] == nil {
                пункты.append(ПунктСверкиСтандарта(К.протокол, .проверить, т("st_ssd_proto_unknown")))
            }
            if let его = н.целое(.накопитель, К.pcie), let свой = слот.pcie, его > свой {
                пункты.append(ПунктСверкиСтандарта(К.pcie, .подходит, ф("st_ssd_speed", String(свой))))
            }
        } else if форма == "2.5" || форма == "3.5" {
            if форма == "3.5" && к.вид == .ноутбук {
                пункты.append(ПунктСверкиСтандарта("bay", .неПодходит, ф("st_ssd_bay_bad", форма)))
            } else if форма == "3.5" {
                // Отсеков 3.5″ в модели нет: отсек 2.5″ диску 3.5″ не годится — у настольного «проверьте».
                пункты.append(ПунктСверкиСтандарта("bay", .проверить, т("st_ssd_bay35_check")))
            } else if let отсеков = к.отсеков25 {
                // Занятые отсеки — дисками 2.5″, уже стоящими в компьютере (как считает «Можно улучшить»).
                let занято = к.накопители.filter { $0.форма == "2.5" }.count
                if отсеков > занято {
                    пункты.append(ПунктСверкиСтандарта("bay", .подходит, т("st_ssd_bay_ok")))
                } else if отсеков > 0 {
                    пункты.append(ПунктСверкиСтандарта("bay", .проверить, т("st_ssd_bay_busy")))
                } else {
                    пункты.append(ПунктСверкиСтандарта("bay", .неПодходит, ф("st_ssd_bay_bad", форма)))
                }
            } else {
                пункты.append(ПунктСверкиСтандарта("bay", .проверить, т("st_ssd_bay_check")))
            }
        } else {
            return nil
        }
        return итогПК(.накопитель, разбор, к, пункты, деталь: деталь)
    }

    /// Платформа даёт PCIe 3.0 (видеокарта с урезанной шиной теряет часть скорости).
    private static func старыйPCIe(_ к: КомпьютерМоего) -> Bool {
        guard let сокет = к.сокетДляСверки else { return false }
        if сокет == "AM4" { return !["B550", "X570", "A620"].contains(к.чипсет ?? "") }
        return сокет == "LGA1151" || сокет == "LGA1200"
    }

    /// Видеокарта (gpu_fit): в ноутбук — нет; длина против корпуса − 10 мм; БП против рекомендации чипа.
    static func видеокарта(_ разбор: РазборСтандартовОбъявления, _ к: КомпьютерМоего) -> ИтогСверкиСтандарта? {
        let н = разбор.набор
        guard н.есть(.видеокарта) else { return nil }
        if к.вид == .ноутбук {
            return итогПК(.видеокарта, разбор, к, [ПунктСверкиСтандарта("laptop", .неПодходит, т("st_gpu_laptop"))])
        }
        var пункты: [ПунктСверкиСтандарта] = []
        var деталь: String? = nil
        let длина = н.целое(.видеокарта, К.длина)
        if let предел = к.корпус.длинаКарты {
            if let длина {
                if длина <= предел - 10 {
                    пункты.append(ПунктСверкиСтандарта(К.длина, .подходит, ф("st_gpu_len_ok", String(длина), String(предел))))
                } else if длина <= предел {
                    пункты.append(ПунктСверкиСтандарта(К.длина, .проверить, ф("st_gpu_len_tight", String(длина),
                                                                                String(предел))))
                } else {
                    пункты.append(ПунктСверкиСтандарта(К.длина, .неПодходит, ф("st_gpu_len_bad", String(длина),
                                                                                 String(предел))))
                }
            } else {
                пункты.append(ПунктСверкиСтандарта(К.длина, .проверить, т("st_gpu_len_unknown")))
            }
        } else {
            пункты.append(ПунктСверкиСтандарта("case", .неизвестно, т("st_gpu_case_need")))
        }
        let чип = н[.видеокарта, К.чип]
        if let нужно = КаталогСтандартов.нужноБП(чип: чип, tdpПроцессора: к.tdp) {
            if let есть = к.бп.ватт {
                if есть >= нужно {
                    пункты.append(ПунктСверкиСтандарта("psu", .подходит, ф("st_gpu_psu_ok", String(есть), String(нужно))))
                } else if let ниже = КаталогСтандартов.ступеньНиже(нужно), есть >= ниже {
                    пункты.append(ПунктСверкиСтандарта("psu", .проверить, ф("st_gpu_psu_check", String(есть), String(нужно))))
                } else {
                    пункты.append(ПунктСверкиСтандарта("psu", .неПодходит, ф("st_gpu_psu_bad", String(нужно), String(есть))))
                }
            } else {
                пункты.append(ПунктСверкиСтандарта("psu", .неизвестно, т("st_gpu_psu_need")))
            }
        }
        if let чип, let линий = КаталогСтандартов.линииКарт[чип], старыйPCIe(к) {
            пункты.append(ПунктСверкиСтандарта(К.pcie, .подходит, ф("st_gpu_pcie_slow", String(линий))))
        }
        if н[.видеокарта, К.питание] == "12V-2x6" {
            деталь = т("st_gpu_12v")
            пункты.append(ПунктСверкиСтандарта(К.питание, .доработка, деталь ?? ""))
        }
        return итогПК(.видеокарта, разбор, к, пункты, деталь: деталь)
    }

    /// Блок питания (psu_need): ватты против нужного (видеокарта и процессор «Моего»), форма — против корпуса.
    static func блокПитания(_ разбор: РазборСтандартовОбъявления, _ к: КомпьютерМоего) -> ИтогСверкиСтандарта? {
        let н = разбор.набор
        guard let ватт = н.целое(.блокПитания, К.ватт) else { return nil }
        if к.вид == .ноутбук {
            return итогПК(.блокПитания, разбор, к, [ПунктСверкиСтандарта("laptop", .неПодходит, т("st_psu_laptop"))])
        }
        var пункты: [ПунктСверкиСтандарта] = []
        var деталь: String? = nil
        if let нужно = КаталогСтандартов.нужноБП(чип: к.видеокарта.чип, tdpПроцессора: к.tdp) {
            if ватт >= нужно {
                пункты.append(ПунктСверкиСтандарта(К.ватт, .подходит, ф("st_psu_w_ok", String(ватт), String(нужно))))
            } else if let ниже = КаталогСтандартов.ступеньНиже(нужно), ватт >= ниже {
                пункты.append(ПунктСверкиСтандарта(К.ватт, .проверить, ф("st_psu_w_check", String(ватт), String(нужно))))
            } else {
                пункты.append(ПунктСверкиСтандарта(К.ватт, .неПодходит, ф("st_psu_w_bad", String(ватт), String(нужно))))
            }
        } else if let свой = к.бп.ватт {
            let неСлабее = ватт >= свой
            пункты.append(ПунктСверкиСтандарта(К.ватт, неСлабее ? .подходит : .проверить,
                                               ф(неСлабее ? "st_psu_not_weaker" : "st_psu_weaker", String(ватт), String(свой))))
        } else {
            пункты.append(ПунктСверкиСтандарта(К.ватт, .неизвестно, т("st_gpu_psu_need")))
        }
        let форма = н[.блокПитания, К.форма]
        let своя = к.бп.форма ?? "ATX"
        if let форма, форма.hasPrefix("SFX"), своя == "ATX" {
            деталь = т("st_psu_sfx")
            пункты.append(ПунктСверкиСтандарта(К.форма, .доработка, деталь ?? ""))
        } else if форма == "ATX", своя.hasPrefix("SFX") {
            пункты.append(ПунктСверкиСтандарта(К.форма, .неПодходит, т("st_psu_atx_in_sfx")))
        }
        return итогПК(.блокПитания, разбор, к, пункты, деталь: деталь)
    }

    /// Процессор, плата, кулер (cpu_socket): сокет точно, BIOS — проверьте; у платы — и форм-фактор против корпуса.
    static func сокет(_ разбор: РазборСтандартовОбъявления, _ к: КомпьютерМоего) -> ИтогСверкиСтандарта? {
        let н = разбор.набор
        guard let его = н[.сокет, К.сокет] else { return nil }
        if к.вид == .ноутбук {
            return итогПК(.сокет, разбор, к, [ПунктСверкиСтандарта("laptop", .неПодходит, т("st_socket_laptop"))])
        }
        guard let мой = к.сокетДляСверки else {
            return итогПК(.сокет, разбор, к, [ПунктСверкиСтандарта(К.сокет, .неизвестно, т("st_socket_need"))])
        }
        var пункты: [ПунктСверкиСтандарта] = []
        var деталь: String? = nil
        if его != мой {
            пункты.append(ПунктСверкиСтандарта(К.сокет, .неПодходит, ф("st_socket_bad", его, мой)))
        } else {
            пункты.append(ПунктСверкиСтандарта(К.сокет, .подходит, ф("st_socket_ok", его)))
            /* Процессор новее платы: Ryzen 5000 на старых AM4, Core 13–14 на 600-й серии — BIOS. Объявление процессора
               сверяем с моим чипсетом, объявление платы — с моим процессором; кулер (ни того, ни другого) — только сокет. */
            let егоЧипсет = н[.сокет, К.чипсет]
            let егоПроцессор = н[.сокет, К.процессор]
            let мойПроцессор = РазборСтандартов.процессор(РазборСтандартов.нормально(к.процессор))?.имя ?? к.процессор
            let процессор = (егоПроцессор ?? (егоЧипсет != nil ? мойПроцессор : "")).lowercased()
            let чипсет = (егоЧипсет ?? к.чипсет ?? "").uppercased()
            let ryzen5000 = процессор.hasPrefix("ryzen") && процессор.split(separator: " ").count >= 3
                && процессор.split(separator: " ")[2].hasPrefix("5")
            let core1314 = процессор.contains("-13") || процессор.contains("-14")
            if (его == "AM4" && ryzen5000 && КаталогСтандартов.чипсетыСТребованиемBIOS.contains(чипсет))
                || (его == "LGA1700" && core1314 && КаталогСтандартов.чипсетыLGA1700Старые.contains(чипсет)) {
                пункты.append(ПунктСверкиСтандарта("bios", .проверить, т("st_socket_bios")))
            }
            if его == "LGA1151", егоПроцессор != nil || егоЧипсет != nil,
               let пункт = поколениеLGA1151(процессор: процессор, чипсет: чипсет) {
                пункты.append(пункт)
            }
            // Плата под другую память (DDR5 при моей DDR4) — встанет, но нужна новая память.
            if егоЧипсет != nil, let егоПамять = н[.сокет, К.поколение], let моя = к.память.поколение,
               КаталогСтандартов.основа(поколения: егоПамять) != КаталогСтандартов.основа(поколения: моя) {
                деталь = ф("st_board_mem_part", егоПамять)
                пункты.append(ПунктСверкиСтандарта("board_mem", .доработка, ф("st_board_mem_bad", егоПамять, моя)))
            }
        }
        if let форма = н[.формаПлаты, К.форма], let корпус = к.корпус.плата,
           let р1 = КаталогСтандартов.ранг(формы: форма), let р2 = КаталогСтандартов.ранг(формы: корпус) {
            пункты.append(ПунктСверкиСтандарта(К.форма, р1 <= р2 ? .подходит : .неПодходит,
                                               ф(р1 <= р2 ? "st_board_ok" : "st_board_bad", форма, корпус)))
        }
        return итогПК(.сокет, разбор, к, пункты, деталь: деталь)
    }

    /**
     LGA1151 двух поколений: Core 6–7-го — только на платах 100/200-й серии, 8–9-го — только на 300-й (это не BIOS,
     а разные платы). Не сходится — «не подходит»; поколения или чипсета не знаем — «проверьте»; сходится — nil.
     */
    private static func поколениеLGA1151(процессор: String, чипсет: String) -> ПунктСверкиСтандарта? {
        let плата: Bool? = КаталогСтандартов.чипсетыLGA1151Старые.contains(чипсет) ? true
            : (КаталогСтандартов.сокет(чипсета: чипсет) == "LGA1151" ? false : nil)
        guard let ген = поколениеCore(процессор), let старая = плата else {
            return ПунктСверкиСтандарта("cpu_gen", .проверить, т("st_socket_gen_check"))
        }
        guard старая != (ген <= 7) else { return nil }
        return ПунктСверкиСтандарта("cpu_gen", .неПодходит, ф("st_socket_gen_bad", String(ген), чипсет))
    }

    /// Поколение Core i3–i9 по четырёхзначному номеру («core i5-9400f» → 9); иное — nil.
    private static func поколениеCore(_ имя: String) -> Int? {
        guard let найдено = имя.range(of: #"i[3579]-[0-9]{4}(?![0-9])"#, options: .regularExpression) else { return nil }
        return имя[найдено].dropFirst(3).first?.wholeNumberValue
    }

    /// Плата без сокета в названии: форм-фактор против корпуса.
    static func плата(_ разбор: РазборСтандартовОбъявления, _ к: КомпьютерМоего) -> ИтогСверкиСтандарта? {
        guard к.вид == .настольный, let форма = разбор.набор[.формаПлаты, К.форма], let корпус = к.корпус.плата,
              let р1 = КаталогСтандартов.ранг(формы: форма), let р2 = КаталогСтандартов.ранг(формы: корпус) else { return nil }
        let пункт = ПунктСверкиСтандарта(К.форма, р1 <= р2 ? .подходит : .неПодходит,
                                         ф(р1 <= р2 ? "st_board_ok" : "st_board_bad", форма, корпус))
        return итогПК(.формаПлаты, разбор, к, [пункт])
    }

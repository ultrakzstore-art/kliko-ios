import Foundation

/**
 СОХРАНЁННЫЕ ПОИСКИ — ЭТАП 12 ПЕРЕХОДА НА SWIFTUI (владелец 25.09.2026: «давай следующие этапы»).

 Колокольчик в шапке ленты сохраняет то, что сейчас в ней искали: текст поиска, раздел или оба сразу. Список — в
 кабинете, там же удаляют. Фоновая проверка (ПроверкаПоисков) раз в час или реже берёт первую страницу выдачи
 каждого поиска и присылает одно уведомление о новых объявлениях.

 🔴 ХРАНИТСЯ НА ТЕЛЕФОНЕ, как избранное (этап 5) и недавнее (этап 6): API подписок на поиск у сайта приложению
 неизвестно, а угаданный адрес хуже никакого. Поэтому и проверяет телефон сам, а не сервер пушем. С сайтом не
 сходится и на другой телефон не переезжает.

 Не больше 20 поисков, свежие сверху, без повторов: тот же текст в другом регистре и тот же раздел — один поиск.
 Стирается при выходе из аккаунта (WebContainer, bye=1) вместе с расписанием проверки и её уведомлением.

 Этап 36 (владелец 25.09.2026, Config.подпискиССайтом): API подписок стал известен (subs.php в js/marketplace.min.js), и
 у вошедшего список — это подписки его аккаунта вместе с поисками телефона. Колокольчик и «Удалить» по-прежнему меняют
 список сразу, а на сайт то же несёт СинхронПодписок (add и remove по одному, откат при отказе); список с сайта ложится
 сюда через принятьССайта. У подписки с сайта есть номер (серверный) и свой город (город): проверяется она по нему, а не
 по выбору на телефоне. Поиск без номера — только на этом телефоне (гость или сохранён до входа): сам на сайт не уходит.
 Подписок с сайта может быть больше двадцати — список держит до пределССайта, проверка берёт по двадцать за раз.
 */
@MainActor
final class SavedSearchStore: ObservableObject {
    static let shared = SavedSearchStore()

    /// Потолок списка. Двадцать поисков — двадцать запросов на каждую фоновую проверку; больше — уже не «следить за
    /// нужным», а второй поиск по всему сайту.
    static let предел = 20
    /// Сколько номеров помнить на поиск. Лента сортирована «рекомендациями» (sort=reco), и первая страница между
    /// проверками перетасовывается: помним с запасом, чтобы вернувшееся на неё старое не выдавать за новое.
    static let памятьНомеров = 200
    /// Этап 36: потолок списка вместе с подписками сайта — их заводят и на сайте, и на другом телефоне. Новый поиск с
    /// телефона по-прежнему упирается в предел, а фоновая проверка берёт не больше предела за раз (дляПроверки).
    static let пределССайта = 50

    /// Сохранённые поиски, свежие сверху, — раздел кабинета и колокольчик ленты.
    @Published private(set) var поиски: [СохранённыйПоиск] = []

    private init() {
        var чистые: [СохранённыйПоиск] = []
        for запись in СохранённыеПоискиФайл.прочитать() where !запись.искомое.пустое {
            /* Этап 36: одинаковый поиск в разных городах — две подписки сайта, а не повтор. */
            guard !чистые.contains(where: { $0.искомое.тоЖе(запись.искомое) && $0.город == запись.город }) else { continue }
            чистые.append(запись)
        }
        поиски = Array(чистые.prefix(Self.пределССайта))
    }

    /// Сохранён ли поиск ленты. Этап 36: подписка сайта — только в своём городе (mkSubFind сайта сверяет и city);
    /// поиск телефона, без своего города, — в любом.
    func есть(_ искомое: ИскомоеЛенты) -> Bool {
        let город = Self.городЛенты
        return поиски.contains { $0.искомое.тоЖе(искомое) && $0.подходит(город) }
    }

    /// Город ленты для подписки — mkSt.city сайта: название города или пусто (вся страна или область). Этап 36.
    static var городЛенты: String { ВыборГорода.shared.где.город }

    /// Этап 36: поиски на одну фоновую проверку — не больше предела, давно проверенные первыми: подписок с сайта бывает
    /// больше двадцати, и за несколько проверок очередь доходит до каждой.
    var дляПроверки: [СохранённыйПоиск] {
        guard поиски.count > Self.предел else { return поиски }
        let порядок = поиски.sorted { ($0.проверен ?? .distantPast) < ($1.проверен ?? .distantPast) }
        return Array(порядок.prefix(Self.предел))
    }

    /// Сохранить поиск наверх списка. `видели` — номера выдачи, которая сейчас на экране: о них человек знает, и
    /// первая проверка сравнит с ними. nil — выдача по этому поиску ещё не пришла; тогда первая проверка только
    /// запомнит номера и промолчит, а не объявит новой всю первую страницу.
    /// false — список полон: молча вытеснять старый поиск нельзя, человек перестал бы получать о нём уведомления.
    @discardableResult
    func добавить(_ искомое: ИскомоеЛенты, названиеРаздела: String?, видели: [String]?) -> Bool {
        guard !искомое.пустое, !есть(искомое) else { return true }
        let город = Self.городЛенты
        /* Этап 36: снятие этого поиска ещё не ушло на сайт, а колокольчик нажали снова — вернуть прежний, с его номером
           подписки и виденным; на сайт не уходит ни то, ни другое. */
        if Config.подпискиССайтом, let прежний = СинхронПодписок.shared.вернутьНеОтправленное(искомое, город: город) {
            var новые = поиски
            новые.insert(прежний, at: 0)
            применить(новые)
            return true
        }
        guard поиски.count < Self.предел else { return false }
        var запись = СохранённыйПоиск(искомое: искомое, названиеРаздела: названиеРаздела)
        if let видели {
            запись.видели = Self.сжать(видели)
            запись.отсчёт = true
        }
        var новые = поиски
        новые.insert(запись, at: 0)
        применить(новые)
        /* Этап 36: вошедшему — то же на сайт (subs.php?action=add) с городом ленты; не вышло — поиск уйдёт из списка. */
        if Config.подпискиССайтом { СинхронПодписок.shared.сохранили(запись, город: город) }
        return true
    }

    /// Колокольчик нажали второй раз — поиск из списка.
    func убрать(_ искомое: ИскомоеЛенты) {
        let город = Self.городЛенты
        let снятые = поиски.enumerated().filter { $0.element.искомое.тоЖе(искомое) && $0.element.подходит(город) }
        guard !снятые.isEmpty else { return }
        let номера = Set(снятые.map { $0.element.id })
        применить(поиски.filter { !номера.contains($0.id) })
        сообщитьОСнятии(снятые)
    }

    /// Свайп «Удалить» в кабинете.
    func убрать(места: IndexSet) {
        let снятые = поиски.enumerated().filter { места.contains($0.offset) }
        guard !снятые.isEmpty else { return }
        применить(поиски.enumerated().filter { !места.contains($0.offset) }.map(\.element))
        сообщитьОСнятии(снятые)
    }

    // MARK: - Вместе с сайтом (этап 36)

    /// Снятые поиски — СинхронПодписок: у подписки сайта уйдёт remove, поиск телефона сайта не касается.
    private func сообщитьОСнятии(_ снятые: [(offset: Int, element: СохранённыйПоиск)]) {
        guard Config.подпискиССайтом else { return }
        for снятый in снятые {
            СинхронПодписок.shared.убрали(снятый.element, место: снятый.offset)
        }
    }

    /// add на сайт прошёл: у поиска теперь номер подписки и город, с которым её завели. false — поиска на телефоне уже
    /// нет (сняли, пока шёл запрос).
    @discardableResult
    func привязать(_ id: String, серверный: String, город: String) -> Bool {
        guard let место = поиски.firstIndex(where: { $0.id == id }) else { return false }
        var новые = поиски
        новые[место].серверный = серверный
        новые[место].город = город
        применить(новые)
        return true
    }

    /// Сайт не сохранил — поиск уходит из списка, как не сохранённый: на экране снова то же, что на сайте.
    func снятьНеСохранённый(_ id: String) {
        guard поиски.contains(where: { $0.id == id }) else { return }
        применить(поиски.filter { $0.id != id })
    }

    /// Сайт не снял — поиск снова на своём месте. Такой же уже есть (колокольчик нажали снова) — второй не ставим.
    func вернуть(_ запись: СохранённыйПоиск, место: Int) {
        guard !поиски.contains(where: { $0.id == запись.id }) else { return }
        let повтор = поиски.contains { п in
            п.искомое.тоЖе(запись.искомое) && (п.город == nil || запись.город == nil || п.город == запись.город)
        }
        guard !повтор else { return }
        var новые = поиски
        новые.insert(запись, at: min(max(0, место), новые.count))
        применить(новые)
    }

    /**
     Подписки-поиски из subs.php?action=list → список телефона, как _mkSubs сайта:
       · подписка, чей номер уже есть, остаётся с виденным и отметками проверки (город — сайта);
       · поиск телефона без номера с тем же искомым и подходящим городом становится этой подпиской — без записи на сайт;
       · прочие подписки — новыми поисками сверху, без точки отсчёта: первая проверка только запомнит выдачу и промолчит;
       · поиск с номером, которого на сайте больше нет (сняли на сайте или на другом телефоне), уходит;
       · поиски без номера остаются — они только на телефоне.
     `неТрогать` — поиски, чей add ещё ждёт очереди: их не сводим с подписками сайта.
     */
    func принятьССайта(_ подписки: [ПодпискиСайта.Подписка], неТрогать: Set<String>) {
        var обновлённые = поиски
        var новые: [СохранённыйПоиск] = []
        var сведённые = Set<String>()
        for подписка in подписки {
            if let место = обновлённые.firstIndex(where: { $0.серверный == подписка.id }) {
                обновлённые[место].город = подписка.город
                сведённые.insert(обновлённые[место].id)
                continue
            }
            let искомое = подписка.искомое
            let своё = обновлённые.firstIndex { п in
                п.серверный == nil && !неТрогать.contains(п.id) && !сведённые.contains(п.id)
                    && п.искомое.тоЖе(искомое) && п.подходит(подписка.город)
            }
            if let место = своё {
                обновлённые[место].серверный = подписка.id
                обновлённые[место].город = подписка.город
                сведённые.insert(обновлённые[место].id)
                continue
            }
            guard !искомое.пустое else { continue }
            var запись = СохранённыйПоиск(искомое: искомое, названиеРаздела: Self.имяРаздела(искомое.раздел))
            запись.серверный = подписка.id
            запись.город = подписка.город
            новые.append(запись)
        }
        let наСайте = Set(подписки.map(\.id))
        обновлённые.removeAll { п in
            guard let номер = п.серверный else { return false }
            return !наСайте.contains(номер) && !неТрогать.contains(п.id)
        }
        let итог = Array((новые + обновлённые).prefix(Self.пределССайта))
        if итог != поиски { применить(итог) }
    }

    /// Название раздела подписки с сайта — с полосы разделов ленты (FeedSnapshot) или из текстов страницы объявления
    /// («root_<раздел>»); нет — nil, и в названии поиска будет ключ.
    private static func имяРаздела(_ ключ: String) -> String? {
        guard !ключ.isEmpty else { return nil }
        if let строка = FeedStore.разделыНаЗапуске.first(where: { $0.k == ключ }) { return строка.название }
        let корень = ListingPageText.т("root_" + ключ)
        return корень == "root_" + ключ ? nil : корень
    }

    /**
     Итог фоновой проверки: первая страница выдачи по номеру поиска → сколько в ней новых. Новые — номера, которых
     этот поиск ещё не видел; они же с этой минуты — виденные, и следующая проверка о них не скажет.

     Поиск, удалённый, пока шли запросы, пропускаем: ни записи, ни уведомления о нём. Поиск без точки отсчёта
     (сохранён, пока выдача не пришла) в этот раз только запоминает номера.
     */
    func отметитьПроверку(_ выдачи: [String: [String]], когда: Date = Date()) -> [String: Int] {
        guard !выдачи.isEmpty else { return [:] }
        var новые = поиски
        var итог: [String: Int] = [:]
        for место in новые.indices {
            guard let номера = выдачи[новые[место].id] else { continue }
            var запись = новые[место]
            if запись.отсчёт {
                итог[запись.id] = Set(номера).subtracting(запись.видели).count
            }
            запись.видели = Self.сжать(номера + запись.видели)
            запись.отсчёт = true
            запись.проверен = когда
            новые[место] = запись
        }
        if новые != поиски { применить(новые) }
        return итог
    }

    /// Сменили город (этап 32): выдача каждого поиска теперь из другого места, и её первая страница целиком «не виденная».
    /// Следующая проверка только запомнит номера и промолчит — как у поиска, сохранённого до ответа ленты; иначе смена
    /// города обернулась бы уведомлением «N новых» по каждому поиску.
    ///
    /// Этап 36: подписки сайта со своим городом смена города ленты не касается — их выдача та же.
    func новаяТочкаОтсчёта() {
        guard поиски.contains(where: { $0.отсчёт && $0.город == nil }) else { return }
        var новые = поиски
        for место in новые.indices where новые[место].город == nil { новые[место].отсчёт = false }
        применить(новые)
    }

    /// Выход из аккаунта: что искал ушедший, следующему не показываем и не проверяем.
    func стереть() {
        поиски = []
        СохранённыеПоискиФайл.стереть()
        ПроверкаПоисков.отменить()
    }

    // MARK: - Внутреннее

    /// Номера без пустых и повторов, в прежнем порядке (свежие первыми), не больше памяти поиска.
    private static func сжать(_ номера: [String]) -> [String] {
        var встречены = Set<String>()
        let чистые = номера.filter { !$0.isEmpty && встречены.insert($0).inserted }
        return Array(чистые.prefix(памятьНомеров))
    }

    private func применить(_ новые: [СохранённыйПоиск]) {
        поиски = новые
        СохранённыеПоискиФайл.записать(новые)
    }
}

/// Что искать в ленте: отправленный текст (q=) и раздел (cat=, ключ вроде «transport»). Пустое — вся лента.
/// Одно и то же у ленты (FeedModel.действующее), у сохранённого поиска и у роутера ссылок (NativeRouter.Цель.найти).
///
/// Этап 33 (владелец 25.09.2026): и цена с состоянием — pmin, pmax (целые ₸) и cond ("new", "used" или пусто), ровно то,
/// что сайт кладёт в сохранённый поиск (subs.php?action=add в mkSaveSearch). Прочие фильтры ленты (сортировка,
/// «Проверенные», фото, год, комнаты) сайт в поиск не сохраняет — и мы тоже. В файле прежней версии этих полей нет —
/// тогда их просто нет и в поиске.
struct ИскомоеЛенты: Codable, Hashable, Sendable {
    var текст: String
    var раздел: String
    /// pmin; nil — без нижней границы.
    var ценаОт: Int?
    /// pmax; nil — без верхней границы.
    var ценаДо: Int?
    /// cond: "new", "used" или пусто — любое.
    var состояние: String

    enum CodingKeys: String, CodingKey {
        case текст = "q"
        case раздел = "cat"
        case ценаОт = "pmin"
        case ценаДо = "pmax"
        case состояние = "cond"
    }

    init(текст: String, раздел: String, ценаОт: Int? = nil, ценаДо: Int? = nil, состояние: String = "") {
        self.текст = текст.trimmingCharacters(in: .whitespacesAndNewlines)
        self.раздел = раздел.trimmingCharacters(in: .whitespacesAndNewlines)
        /* Как mkSaveSearch сайта: ноль — «границы нет», состояние — только new или used. */
        self.ценаОт = ценаОт.flatMap { $0 > 0 ? $0 : nil }
        self.ценаДо = ценаДо.flatMap { $0 > 0 ? $0 : nil }
        self.состояние = состояние == "new" || состояние == "used" ? состояние : ""
    }

    init(from decoder: Decoder) throws {
        let c = try decoder.container(keyedBy: CodingKeys.self)
        self.init(текст: (try? c.decode(String.self, forKey: .текст)) ?? "",
                  раздел: (try? c.decode(String.self, forKey: .раздел)) ?? "",
                  ценаОт: ИскомоеЛенты.число(c, .ценаОт),
                  ценаДо: ИскомоеЛенты.число(c, .ценаДо),
                  состояние: (try? c.decodeIfPresent(String.self, forKey: .состояние)) ?? "")
    }

    /// Граница цены из файла: число, а если его когда-то записали строкой, — строка с числом. Не разобралась — nil.
    private static func число(_ c: KeyedDecodingContainer<CodingKeys>, _ ключ: CodingKeys) -> Int? {
        if let n = try? c.decode(Int.self, forKey: ключ) { return n }
        if let строка = try? c.decode(String.self, forKey: ключ) { return Int(строка) }
        return nil
    }

    var пустое: Bool { текст.isEmpty && раздел.isEmpty && ценаОт == nil && ценаДо == nil && состояние.isEmpty }

    /// Тот же поиск: текст без учёта регистра, раздел, цена и состояние — точно. «iPhone» и «iphone» — один поиск, а не
    /// два уведомления.
    func тоЖе(_ другое: ИскомоеЛенты) -> Bool {
        раздел == другое.раздел && текст.caseInsensitiveCompare(другое.текст) == .orderedSame
            && ценаОт == другое.ценаОт && ценаДо == другое.ценаДо && состояние == другое.состояние
    }
}

/// Сохранённый поиск на диске. Новые поля — только необязательные, иначе файл прежней версии не разберётся.
struct СохранённыйПоиск: Codable, Identifiable, Equatable, Sendable {
    let id: String
    var искомое: ИскомоеЛенты
    /// Название раздела на языке человека — с полосы разделов ленты в момент сохранения (FeedSnapshot): ключ
    /// «transport» в уведомлении читать неприятно. nil — названия не было, показываем ключ.
    var названиеРаздела: String?
    var создан: Date
    /// Номера объявлений, которые этот поиск уже видел: выдача при сохранении и первая страница каждой проверки.
    /// Свежие первыми, не больше SavedSearchStore.памятьНомеров.
    var видели: [String]
    /// Есть точка отсчёта — с чем сравнивать. Нет — первая проверка только запоминает номера.
    var отсчёт: Bool
    /// Когда проверяли последний раз — подпись в кабинете. nil — ещё не проверяли.
    var проверен: Date?
    /// Этап 36: номер подписки на сайте (id из subs.php). nil — поиск только на этом телефоне.
    var серверный: String?
    /// Этап 36: город подписки сайта (city: название или пусто — вся страна). nil — своего города нет, поиск идёт за
    /// выбором города на телефоне, как на этапах 12–35.
    var город: String?

    enum CodingKeys: String, CodingKey {
        case id
        case искомое = "search"
        case названиеРаздела = "catName"
        case создан = "created"
        case видели = "seen"
        case отсчёт = "baseline"
        case проверен = "checked"
        case серверный = "subId"
        case город = "city"
    }

    init(искомое: ИскомоеЛенты, названиеРаздела: String?) {
        id = UUID().uuidString
        self.искомое = искомое
        self.названиеРаздела = названиеРаздела
        создан = Date()
        видели = []
        отсчёт = false
        проверен = nil
        серверный = nil
        город = nil
    }

    init(from decoder: Decoder) throws {
        let c = try decoder.container(keyedBy: CodingKeys.self)
        id = try c.decode(String.self, forKey: .id)
        искомое = try c.decode(ИскомоеЛенты.self, forKey: .искомое)
        названиеРаздела = try? c.decodeIfPresent(String.self, forKey: .названиеРаздела)
        создан = (try? c.decode(Date.self, forKey: .создан)) ?? Date()
        видели = (try? c.decode([String].self, forKey: .видели)) ?? []
        отсчёт = (try? c.decode(Bool.self, forKey: .отсчёт)) ?? false
        проверен = try? c.decodeIfPresent(Date.self, forKey: .проверен)
        серверный = try? c.decodeIfPresent(String.self, forKey: .серверный)
        город = try? c.decodeIfPresent(String.self, forKey: .город)
    }

    /// Подходит ли поиск ленте в этом городе: свой город есть только у подписки сайта (этап 36), без него — любой.
    func подходит(_ городЛенты: String) -> Bool {
        город == nil || город == городЛенты
    }

    /// Как поиск называется в кабинете и в уведомлении: «iPhone 15», «Транспорт» или «iPhone 15 · Электроника»; с этапа
    /// 33 — и цена с состоянием: «iPhone 15 · Электроника · от 300 000 ₸ · Б/У».
    var название: String {
        var имяРаздела = искомое.раздел
        if let имя = названиеРаздела, !имя.isEmpty { имяРаздела = имя }
        var части: [String] = []
        if !искомое.текст.isEmpty { части.append(искомое.текст) }
        if !имяРаздела.isEmpty { части.append(имяРаздела) }
        части.append(contentsOf: искомое.подписиФильтров)
        /* Этап 36: и город подписки сайта — последним, как mkSubChipLabel. */
        if let свой = город, !свой.isEmpty { части.append(свой) }
        return части.joined(separator: " · ")
    }
}

/**
 ФАЙЛ СОХРАНЁННЫХ ПОИСКОВ: один JSON в Application Support, вне резервной копии — как избранное (ИзбранноеФайл).

 Пишем не на главном потоке, но по порядку: одна последовательная очередь, чтобы стирание при выходе не обогнало
 последнюю запись. Фоновая проверка перед закрытием задания дожидается записи (дождаться()): иначе iOS усыпила бы
 приложение раньше, чем номера лягут на диск, и те же объявления пришли бы новыми ещё раз.
 */
enum СохранённыеПоискиФайл {
    private static let очередь = DispatchQueue(label: "kz.kliko.saved-search", qos: .utility)

    private static var адрес: URL? {
        try? FileManager.default.url(for: .applicationSupportDirectory, in: .userDomainMask,
                                     appropriateFor: nil, create: true)
            .appendingPathComponent("kliko-saved-searches.json")
    }

    /// Запись, которая не разобралась, пропускаем, а не теряем весь список.
    private struct Любой: Decodable {
        let запись: СохранённыйПоиск?
        init(from decoder: Decoder) throws { запись = try? СохранённыйПоиск(from: decoder) }
    }

    static func прочитать() -> [СохранённыйПоиск] {
        guard let файл = адрес,
              let данные = try? Data(contentsOf: файл),
              let список = try? JSONDecoder().decode([Любой].self, from: данные) else { return [] }
        return список.compactMap(\.запись)
    }

    static func записать(_ список: [СохранённыйПоиск]) {
        guard let файл = адрес, let данные = try? JSONEncoder().encode(список) else { return }
        очередь.async {
            do {
                try данные.write(to: файл, options: .atomic)
                var значения = URLResourceValues()
                значения.isExcludedFromBackup = true
                var изменяемый = файл
                try? изменяемый.setResourceValues(значения)
            } catch {
                // Диск полон — список есть до конца запуска; следующее изменение попробует снова.
            }
        }
    }

    /// Дождаться записей, поставленных раньше: очередь последовательная, и этот блок выполнится после них.
    static func дождаться() async {
        await withCheckedContinuation { (готово: CheckedContinuation<Void, Never>) in
            очередь.async { готово.resume() }
        }
    }

    static func стереть() {
        guard let файл = адрес else { return }
        очередь.async { try? FileManager.default.removeItem(at: файл) }
    }
}

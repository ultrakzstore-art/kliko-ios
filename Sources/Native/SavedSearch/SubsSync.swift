    /// Поиск из кабинета — лента с ним; у подписки сайта сначала её город (mkFavSubApply: mkSt.city = e.city).
    static func открыть(_ поиск: СохранённыйПоиск) {
        if let городПодписки = поиск.город { перейтиВ(городПодписки) }

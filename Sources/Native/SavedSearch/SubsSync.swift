/**
 ПОДПИСКИ ВМЕСТЕ С САЙТОМ — ЭТАП 36 (владелец 25.09.2026: «почти 100% похоже на сайт»).

 Витрина сайта (js/marketplace.min.js: mkSubsLoad, mkSaveSearch, mkSubToggle, mkFavSubRemove, mkSellerActionsSync,
 mkFollowToggle, mkFavSubUnfollow) держит подписки вошедшего на сервере — и сохранённые поиски, и продавцов — и ходит за
 ними так (адрес от _MKB = "/", куки веб-сессии, csrf полем JSON):
   · GET  subs.php?action=list  → {ok, subs[{id, keyword, category, city, seller_id?, seller_name?}]} — подписка на
     продавца лежит там же, у неё есть seller_id;
   · POST subs.php?action=add    {csrf, keyword, category, city, pmin, pmax, cond} → {ok, id, exists} (mkSaveSearch);
   · POST subs.php?action=remove {id, csrf} → {ok};
   · GET  subs.php?action=status&seller_id=<id> → {ok, following, blocked, followers};
   · POST subs.php?action=follow {seller_id, seller_name, csrf} → {ok, followers}; unfollow {seller_id, csrf}.
 Приложение делает то же самое. Куки — SiteSession.куки(), токен и «вошёл» — SiteSession.состояние(), как у избранного
 (этап 35). block/unblock и жалобы здесь не трогаем — это не подписки. Этап 37: blocked из ответа status отдаём «⋮»
 продавца (ДействияСПродавцом, Native/Seller) — второй раз status ради него не спрашиваем.

 ПРАВИЛА ЗАПИСИ. На сайт пишется только по нажатию: колокольчик ленты (add или remove), «Удалить» в кабинете (remove),
 «Подписаться на продавца» и «Отписаться» (follow, unfollow). Сами по себе ничего не уходят: поиски, сохранённые без
 входа, на сайт не переносятся (массовой записи нет). Нажатие меняет экран сразу, как у сайта; сайт отказал или нет связи —
 всё возвращается, а внизу его текст ошибки (плашка как у избранного, .mk-toast). Обращения идут по одному в порядке
 нажатий; два нажатия на одно и то же, пока первое не ушло, гасят друг друга — на сайте ничего не меняется. Повторов нет.

 ЧТЕНИЕ. Список — при открытии раздела «Сохранённые поиски» в кабинете (не чаще раза в 10 с), при возврате в приложение,
 первой загрузке страницы и возврате со страницы сайта (раз в 60 с), только у вошедшего. Статус продавца — при показе его
 карточки в объявлении, не чаще раза в минуту на продавца (у гостя тоже: это чтение, и число подписчиков видно всем).

 ГОСТЬ — как на этапе 12: колокольчик сохраняет поиск на телефоне. «Подписаться на продавца» гостю — «Войдите в
 кабинет, чтобы подписаться» с «Войти», как у сайта.
 */
enum ПодпискиСайта {
    enum Итог: Equatable, Sendable {
        /// ok: true — что пришло.
        case готово(Ответ)
        /// need/error «auth» (и need_reg), 401/403 — показать вход.
        case нуженВход
        /// need/error «verify» — нужна верификация.
        case нужнаВерификация
        /// error «csrf» — токен страницы устарел.
        case защита
        /// Иной отказ: текст сайта для человека (ulxErr) или nil.
        case отказ(String?)
        case сеть
    }

    /// Поля ответа ok: true. Чего не пришло — nil (и false у exists).
    struct Ответ: Equatable, Sendable {
        /// list: subs[]; nil — поля нет или оно не того вида: такой ответ список не меняет.
        var подписки: [Подписка]? = nil
        /// add: номер новой подписки.
        var id: String? = nil
        /// add: exists — такая подписка уже была.
        var уже = false
        /// status: following.
        var подписан: Bool? = nil
        /// status, follow, unfollow: followers.
        var подписчиков: Int? = nil
        /// status: blocked — продавец заблокирован этим человеком (этап 37, «Заблокировать» / «Разблокировать» в «⋮»).
        var заблокирован: Bool? = nil
    }

    /// Одна запись subs[]. Поиск — keyword, category, city (и pmin, pmax, cond, если сайт их отдаёт); продавец — seller_id.
    struct Подписка: Equatable, Sendable {
        let id: String
        let текст: String
        let раздел: String
        /// Город названием; пусто — вся страна.
        let город: String
        let ценаОт: Int?
        let ценаДо: Int?
        let состояние: String
        /// seller_id; nil — это поиск.
        let продавец: String?
        let имяПродавца: String?

        var искомое: ИскомоеЛенты {
            ИскомоеЛенты(текст: текст, раздел: раздел, ценаОт: ценаОт, ценаДо: ценаДо, состояние: состояние)
        }
    }

    private static let сессия: URLSession = {
        let c = URLSessionConfiguration.default
        c.httpAdditionalHeaders = ["Accept": "application/json"]
        c.timeoutIntervalForRequest = 15
        c.httpShouldSetCookies = false        // куки — из WebKit (SiteSession), своих не заводим
        c.httpCookieStorage = nil
        c.requestCachePolicy = .reloadIgnoringLocalCacheData   // подписки — всегда свежие
        return URLSession(configuration: c)
    }()

    /// GET subs.php?action=list.
    static func список() async -> Итог {
        await получить([URLQueryItem(name: "action", value: "list")])
    }

    /// GET subs.php?action=status&seller_id=<id>.
    static func статус(продавца продавец: String) async -> Итог {
        await получить([URLQueryItem(name: "action", value: "status"), URLQueryItem(name: "seller_id", value: продавец)])
    }

    /// POST subs.php?action=add — ровно тело mkSaveSearch сайта: цены — целые, ноль — «без границы»; cond — new, used
    /// или пусто.
    static func добавить(_ искомое: ИскомоеЛенты, город: String, csrf: String) async -> Итог {
        let ценаОт: Int = искомое.ценаОт ?? 0
        let ценаДо: Int = искомое.ценаДо ?? 0
        let тело: [String: Any] = ["csrf": csrf, "keyword": искомое.текст, "category": искомое.раздел, "city": город,
                                   "pmin": ценаОт, "pmax": ценаДо, "cond": искомое.состояние]
        return await отправить("add", тело: тело)
    }

    /// POST subs.php?action=remove {id, csrf}.
    static func убрать(_ номер: String, csrf: String) async -> Итог {
        await отправить("remove", тело: ["id": номер, "csrf": csrf])
    }

    /// POST subs.php?action=follow {seller_id, seller_name, csrf} — тело mkFollowToggle.
    static func подписаться(_ продавец: String, имя: String, csrf: String) async -> Итог {
        await отправить("follow", тело: ["seller_id": продавец, "seller_name": имя, "csrf": csrf])
    }

    /// POST subs.php?action=unfollow {seller_id, csrf} — тело mkFavSubUnfollow.
    static func отписаться(_ продавец: String, csrf: String) async -> Итог {
        await отправить("unfollow", тело: ["seller_id": продавец, "csrf": csrf])
    }

    // MARK: - Транспорт

    private static func ссылка(_ поля: [URLQueryItem]) -> URL? {
        var ч = URLComponents(url: Config.apiBase.appendingPathComponent("subs.php"), resolvingAgainstBaseURL: false)
        ч?.queryItems = поля
        return ч?.url
    }

    private static func получить(_ поля: [URLQueryItem]) async -> Итог {
        guard let адрес = ссылка(поля) else { return .отказ(nil) }
        var запрос = URLRequest(url: адрес)
        запрос.httpShouldHandleCookies = false
        for (имя, значение) in await SiteSession.куки() { запрос.setValue(значение, forHTTPHeaderField: имя) }
        return await выполнить(запрос)
    }

    private static func отправить(_ действие: String, тело: [String: Any]) async -> Итог {
        guard let адрес = ссылка([URLQueryItem(name: "action", value: действие)]),
              let данные = try? JSONSerialization.data(withJSONObject: тело) else { return .отказ(nil) }
        var запрос = URLRequest(url: адрес)
        запрос.httpMethod = "POST"
        запрос.httpShouldHandleCookies = false
        запрос.setValue("application/json", forHTTPHeaderField: "Content-Type")
        /* Origin не подставляем (владелец: без поддельных Origin/Referer): subs.php источник не проверяет. */
        for (имя, значение) in await SiteSession.куки() { запрос.setValue(значение, forHTTPHeaderField: имя) }
        запрос.httpBody = данные
        return await выполнить(запрос)
    }

    private static func выполнить(_ запрос: URLRequest) async -> Итог {
        let данные: Data
        let ответ: URLResponse
        do { (данные, ответ) = try await сессия.data(for: запрос) } catch { return .сеть }
        let код = (ответ as? HTTPURLResponse)?.statusCode ?? 200
        /* JSON разбираем и при 4xx: сайт объясняет отказ полями need/error, а не кодом. */
        guard let поля = (try? JSONSerialization.jsonObject(with: данные)) as? [String: Any] else {
            return (код == 401 || код == 403) ? .нуженВход : .отказ(nil)
        }
        return разобрать(поля, код: код)
    }

    /// Ответ сайта → итог. ok — поля ответа; отказ — по тем же правилам, что у избранного (ИзбранноеСайта.разобрать:
    /// auth — вход, verify — верификация, csrf — защита, иначе текст error, если это не машинный код, — ulxErr сайта).
    static func разобрать(_ поля: [String: Any], код: Int) -> Итог {
        if да(поля["ok"]) {
            var ответ = Ответ()
            ответ.подписки = подписки(поля["subs"])
            ответ.id = строка(поля["id"])
            ответ.уже = да(поля["exists"])
            if let значение = поля["following"], !(значение is NSNull) { ответ.подписан = да(значение) }
            ответ.подписчиков = целое(поля["followers"])
            if let значение = поля["blocked"], !(значение is NSNull) { ответ.заблокирован = да(значение) }
            return .готово(ответ)
        }
        switch ИзбранноеСайта.разобрать(поля, код: код) {
        case .список:                  return .отказ(nil)
        case .нуженВход:               return .нуженВход
        case .нужнаВерификация:        return .нужнаВерификация
        case .защита:                  return .защита
        case .отказ(let текст):        return .отказ(текст)
        case .сеть:                    return .сеть
        }
    }

    /// subs[] — массив записей; PHP с дырами в ключах отдаёт его объектом {"0":…,"2":…} — берём по порядку ключей. Запись
    /// без id пропускаем. Не массив и не объект — nil.
    static func подписки(_ значение: Any?) -> [Подписка]? {
        let сырые: [Any]
        if let массив = значение as? [Any] {
            сырые = массив
        } else if let словарь = значение as? [String: Any] {
            let ключи = словарь.keys.sorted { (Int($0) ?? Int.max) < (Int($1) ?? Int.max) }
            сырые = ключи.compactMap { словарь[$0] }
        } else {
            return nil
        }
        var итог: [Подписка] = []
        for элемент in сырые {
            guard let запись = элемент as? [String: Any], let номер = строка(запись["id"]) else { continue }
            /* Как !t.seller_id у сайта: пусто или ноль — это поиск. */
            let продавец = строка(запись["seller_id"]).flatMap { $0 == "0" ? nil : $0 }
            итог.append(Подписка(id: номер,
                                 текст: строка(запись["keyword"]) ?? "",
                                 раздел: строка(запись["category"]) ?? "",
                                 город: строка(запись["city"]) ?? "",
                                 ценаОт: целое(запись["pmin"]),
                                 ценаДо: целое(запись["pmax"]),
                                 состояние: строка(запись["cond"]) ?? "",
                                 продавец: продавец,
                                 имяПродавца: строка(запись["seller_name"])))
        }
        return итог
    }

    private static func да(_ значение: Any?) -> Bool {
        if let b = значение as? Bool { return b }
        if let n = значение as? NSNumber { return n.intValue != 0 }
        if let s = значение as? String { return s == "1" || s.lowercased() == "true" }
        return false
    }

    private static func строка(_ значение: Any?) -> String? {
        if let s = значение as? String {
            let t = s.trimmingCharacters(in: .whitespacesAndNewlines)
            return t.isEmpty ? nil : t
        }
        if let n = значение as? NSNumber { return n.stringValue }
        return nil
    }

    private static func целое(_ значение: Any?) -> Int? {
        if let n = значение as? NSNumber { return n.intValue }
        if let s = значение as? String { return Int(s.trimmingCharacters(in: .whitespacesAndNewlines)) }
        return nil
    }
}

/// Подписки вошедшего — с сайтом: очередь обращений, сверка списка, статус продавцов, откат и сообщение об ошибке
/// (см. шапку файла).
@MainActor
final class СинхронПодписок: ObservableObject {
    static let shared = СинхронПодписок()

    /// Подписка на продавца из списка сайта.
    struct Продавец: Identifiable, Equatable {
        /// seller_id.
        let id: String
        /// seller_name; пусто — «Продавец».
        let имя: String
    }

    /// Что известно о продавце в этот запуск — из status, follow/unfollow или нажатия.
    struct ОПродавце: Equatable {
        var подписан: Bool
        var подписчиков: Int?
        /// Когда узнали: status не чаще раза в минуту на продавца.
        var когда: Date
    }

    /// Сообщение внизу экрана — как toast сайта (та же плашка, что у избранного).
    @Published private(set) var сообщение: СинхронИзбранного.Сообщение?
    /// Вошедший, и список с сайта в этот запуск уже пришёл — подписи кабинета «в вашем аккаунте».
    @Published private(set) var связано = false
    /// Подписки на продавцов — раздел кабинета.
    @Published private(set) var продавцы: [Продавец] = []
    @Published private(set) var оПродавцах: [String: ОПродавце] = [:]
    /// Номер вошедшего — на своей карточке продавца кнопки подписки нет, как у сайта.
    @Published private(set) var мой: String?

    private struct Добавление {
        let запись: СохранённыйПоиск
        /// Город ленты в момент нажатия — с ним подписка уходит на сайт.
        let город: String
    }

    private struct Снятие {
        let запись: СохранённыйПоиск
        /// Место в списке — вернуть туда, если сайт откажет.
        let место: Int
    }

    private struct НажатиеПродавца {
        let продавец: String
        let имя: String
        let подписаться: Bool
        /// Что было известно до нажатия — вернуть, если сайт откажет.
        let было: ОПродавце?
        /// Место в списке продавцов до нажатия; nil — его там не было.
        let строка: Int?
    }

    private enum Работа {
        /// list; пауза — сколько секунд после прошлой сверки её пропускать.
        case сверка(TimeInterval)
        case добавить(Добавление)
        case убрать(Снятие)
        case продавец(НажатиеПродавца)

        var этоСверка: Bool {
            switch self {
            case .сверка: return true
            case .добавить, .убрать, .продавец: return false
            }
        }

        var добавление: Добавление? {
            switch self {
            case .добавить(let д): return д
            case .сверка, .убрать, .продавец: return nil
            }
        }

        var снятие: Снятие? {
            switch self {
            case .убрать(let с): return с
            case .сверка, .добавить, .продавец: return nil
            }
        }

        var нажатие: НажатиеПродавца? {
            switch self {
            case .продавец(let н): return н
            case .сверка, .добавить, .убрать: return nil
            }
        }
    }

    /// Что писать при отказе — у сайта для каждого действия своя строка.
    private enum Действие {
        case сохранение
        case снятие
        case продавец
    }

    /// Можно ли писать на сайт и с каким токеном.
    private enum Доступ {
        case токен(String)
        /// Страница сказала: гость.
        case гость
        /// Страница не ответила, и вошедшим его в этот запуск не видели.
        case неизвестно
        /// Вошёл, а токена на странице нет.
        case безТокена
    }

    private var очередь: [Работа] = []
    private var работаем = false
    /// Когда последний раз спрашивали список. nil — в этот запуск ещё не спрашивали.
    private var последняяСверка: Date?
    /// Что страница сказала в последний раз: вошёл, гость или nil — ещё не знаем.
    private var последнийВход: Bool?
    /// Токен вошедшего, виденный в этот запуск (только в памяти), — как у избранного.
    private var последнийТокен: String?
    /// Растёт при выходе: ответ, пришедший после него, — чужой, его не применяем.
    private var поколение = 0
    /// Поиск, чей add сейчас в пути: снять его на сайте можно будет, когда придёт номер.
    private var добавлениеВПути: String?
    /// Номер и город подписки, пришедшие, когда поиск на телефоне уже сняли, — для remove, стоящего следом.
    private var номераСнятых: [String: (номер: String, город: String)] = [:]
    /// Продавцы, чей follow/unfollow в пути, — status их не перебивает.
    private var продавцыВПути: Set<String> = []
    /// status в пути — второй раз не просим.
    private var статусыВПути: Set<String> = []

    private init() {}

    private var поискиВключены: Bool { Config.подпискиССайтом && Config.сохранённыеПоиски }

    // MARK: - Снаружи: сверка

    /// Сверить список с сайтом, если с прошлого запроса прошло не меньше `пауза` секунд. Одна сверка в очереди — вторую
    /// не ставим.
    func сверить(пауза: TimeInterval) {
        guard Config.подпискиССайтом else { return }
        guard !очередь.contains(where: { $0.этоСверка }) else { return }
        поставить(.сверка(пауза))
    }

    // MARK: - Снаружи: поиски (SavedSearchStore)

    /// Колокольчик сохранил поиск — SavedSearchStore уже поставил его в список; `город` — город ленты для subs.php.
    func сохранили(_ запись: СохранённыйПоиск, город: String) {
        guard поискиВключены else { return }
        поставить(.добавить(Добавление(запись: запись, город: город)))
    }

    /// Поиск сняли на телефоне (колокольчик или «Удалить»), `место` — где он стоял.
    func убрали(_ запись: СохранённыйПоиск, место: Int) {
        guard поискиВключены else { return }
        /* Его add ещё не ушёл — гасят друг друга: на сайте ничего не меняется. */
        if let i = очередь.firstIndex(where: { $0.добавление?.запись.id == запись.id }) {
            очередь.remove(at: i)
            return
        }
        /* Поиск только на телефоне и его add не в пути — сайту снимать нечего. */
        guard запись.серверный != nil || добавлениеВПути == запись.id else { return }
        поставить(.убрать(Снятие(запись: запись, место: место)))
    }

    /// Колокольчик нажали снова, пока снятие того же поиска ещё ждёт очереди: снятие не отправляем, а поиск — прежний
    /// (с номером подписки и виденным). nil — такого снятия нет.
    func вернутьНеОтправленное(_ искомое: ИскомоеЛенты, город: String) -> СохранённыйПоиск? {
        guard поискиВключены else { return nil }
        let найдено = очередь.firstIndex { работа in
            guard let с = работа.снятие else { return false }
            return с.запись.искомое.тоЖе(искомое) && с.запись.подходит(город)
        }
        guard let место = найдено, let снятие = очередь[место].снятие else { return nil }
        очередь.remove(at: место)
        var запись = снятие.запись
        if запись.серверный == nil, let пришедший = номераСнятых.removeValue(forKey: запись.id) {
            запись.серверный = пришедший.номер
            запись.город = пришедший.город
        }
        return запись
    }

    // MARK: - Снаружи: продавцы

    func подписан(на продавец: String) -> Bool {
        if let известно = оПродавцах[продавец] { return известно.подписан }
        return продавцы.contains { $0.id == продавец }
    }

    /// Число подписчиков из status или follow; nil — сайт в этот запуск не говорил.
    func подписчиков(_ продавец: String) -> Int? {
        оПродавцах[продавец]?.подписчиков
    }

    /// Карточка продавца на экране — status, как mkSellerActionsSync: подписан ли и сколько подписчиков. Не чаще раза в
    /// минуту на продавца; ответ не перебивает нажатие, которое ещё в пути или в очереди. Отказ и обрыв — молча.
    func узнать(продавца продавец: String) {
        guard Config.подпискиССайтом, !продавец.isEmpty, !статусыВПути.contains(продавец) else { return }
        if let известно = оПродавцах[продавец], Date().timeIntervalSince(известно.когда) < 60 { return }
        статусыВПути.insert(продавец)
        let взятое = поколение
        Task {
            let страница = await SiteSession.состояние()
            if взятое == self.поколение {
                self.запомнитьВход(страница.вошёл, пользователь: страница.пользователь)
            }
            let итог = await ПодпискиСайта.статус(продавца: продавец)
            self.статусыВПути.remove(продавец)
            guard взятое == self.поколение, case .готово(let ответ) = итог else { return }
            /* Этап 37: blocked того же ответа — «⋮» продавца (mkSetBlockBtn сайта), даже если нажатие подписки в пути. */
            if let блок = ответ.заблокирован { ДействияСПродавцом.shared.статусСайта(продавец, заблокирован: блок) }
            guard !self.продавцыВПути.contains(продавец), !self.вОчереди(продавец) else { return }
            let прежнее = self.оПродавцах[продавец]
            var новое = прежнее ?? ОПродавце(подписан: self.подписан(на: продавец), подписчиков: nil, когда: Date())
            if let следит = ответ.подписан { новое.подписан = следит }
            if let число = ответ.подписчиков { новое.подписчиков = max(0, число) }
            новое.когда = Date()
            self.оПродавцах[продавец] = новое
        }
    }

    /**
     «Подписаться на продавца» / «Вы подписаны» — mkFollowToggle: кнопка меняется сразу и сразу плашка «Подписались —
     сообщим…» или «Вы отписались…»; сайт откажет — кнопка вернётся и плашка скажет почему. Гостю — «Войдите в кабинет,
     чтобы подписаться» с «Войти», без запроса. Прошлое нажатие на того же продавца ещё не ушло — гасят друг друга.
     */
    func нажали(продавца продавец: String, имя: String) {
        guard Config.подпискиССайтом, !продавец.isEmpty else { return }
        if последнийВход == false {
            показать(.нуженВход, действие: .продавец)
            return
        }
        let станет = !подписан(на: продавец)
        показать(текст: SubsText.т(станет ? "fol_done" : "fol_undone"), войти: false)
        if let место = очередь.firstIndex(where: { $0.нажатие?.продавец == продавец }),
           let прежнее = очередь[место].нажатие {
            очередь.remove(at: место)
            вернуть(прежнее)
            return
        }
        let было = оПродавцах[продавец]
        let строка = продавцы.firstIndex { $0.id == продавец }
        var новое = было ?? ОПродавце(подписан: станет, подписчиков: nil, когда: Date())
        новое.подписан = станет
        новое.когда = Date()
        оПродавцах[продавец] = новое
        if станет {
            if строка == nil { продавцы.insert(Продавец(id: продавец, имя: имя), at: 0) }
        } else if let место = строка {
            продавцы.remove(at: место)
        }
        поставить(.продавец(НажатиеПродавца(продавец: продавец, имя: имя, подписаться: станет, было: было,
                                            строка: строка)))
    }

    /// Смахнули «Отписаться» в кабинете.
    func отписаться(_ продавец: Продавец) {
        guard подписан(на: продавец.id) else {
            продавцы.removeAll { $0.id == продавец.id }
            return
        }
        нажали(продавца: продавец.id, имя: продавец.имя)
    }


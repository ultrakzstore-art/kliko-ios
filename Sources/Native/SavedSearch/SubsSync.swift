    /// Город подписки — ленте, если он другой: как выбор в листе «Где ищете?» (этап 32). Пусто — вся страна; город, которого
    /// нет в справочнике, лист сам сведёт ко всей стране.
    static func перейтиВ(_ город: String) {
        guard Config.подпискиССайтом, Config.выборГорода else { return }
        let выбор = ВыборГорода.shared
        guard выбор.где.город != город else { return }
        if город.isEmpty {
            выбор.выбрать(ГдеИскать(), запомнить: nil)
        } else {
            выбор.выбрать(ГдеИскать(город: город), запомнить: НедавнееМесто(вид: .город, значение: город))
        }
    }

    /// Страница продавца на сайте — ссылка его подписки в блоке сайта (APP_L + "/seller.php?id=").
    static func страницаПродавца(_ продавец: String) -> URL? {
        let номер = продавец.addingPercentEncoding(withAllowedCharacters: .alphanumerics) ?? продавец
        return Config.страницаСайта("seller.php?id=" + номер)
    }

    // MARK: - Очередь

    private func вОчереди(_ продавец: String) -> Bool {
        очередь.contains { $0.нажатие?.продавец == продавец }
    }

    private func поставить(_ работа: Работа) {
        очередь.append(работа)
        guard !работаем else { return }
        работаем = true
        Task { await self.разобрать() }
    }

    private func разобрать() async {
        while !очередь.isEmpty {
            let работа = очередь.removeFirst()
            switch работа {
            case .сверка(let пауза):
                await сверитьССайтом(пауза)
            case .добавить(let добавление):
                await отправитьДобавление(добавление)
            case .убрать(let снятие):
                await отправитьСнятие(снятие)
            case .продавец(let нажатие):
                await отправитьНажатие(нажатие)
            }
        }
        работаем = false
    }

    /// Токен для записи. nil — пока спрашивали страницу, человек вышел.
    private func доступ(_ взятое: Int) async -> Доступ? {
        let страница = await SiteSession.состояние()
        guard взятое == поколение else { return nil }
        запомнитьВход(страница.вошёл, пользователь: страница.пользователь)
        switch страница.вошёл {
        case .some(false):
            return .гость
        case .none:
            /* Страница переходит или грузится: вошедшим его в этот запуск уже видели — его же токен, у сессии он один. */
            if последнийВход == true, let прежний = последнийТокен { return .токен(прежний) }
            return .неизвестно
        case .some(true):
            guard let токен = страница.csrf else { return .безТокена }
            последнийТокен = токен
            return .токен(токен)
        }
    }

    private func запомнитьВход(_ вошёл: Bool?, пользователь: String?) {
        guard let известно = вошёл else { return }
        последнийВход = известно
        if известно {
            if let номер = пользователь, мой != номер { мой = номер }
        } else {
            последнийТокен = nil
            if мой != nil { мой = nil }
            if связано { связано = false }
        }
    }

    // MARK: - Сверка

    private func сверитьССайтом(_ пауза: TimeInterval) async {
        if let прошлая = последняяСверка, Date().timeIntervalSince(прошлая) < пауза { return }
        let взятое = поколение
        let страница = await SiteSession.состояние()
        guard взятое == поколение else { return }
        запомнитьВход(страница.вошёл, пользователь: страница.пользователь)
        guard страница.вошёл == true else { return }
        if let токен = страница.csrf { последнийТокен = токен }
        последняяСверка = Date()
        let итог = await ПодпискиСайта.список()
        guard взятое == поколение else { return }
        switch итог {
        case .готово(let ответ):
            /* ok без subs[] нужного вида — список не трогаем: лучше прежний, чем пустой. */
            if let все = ответ.подписки { принять(все) }
        case .нуженВход:
            запомнитьВход(false, пользователь: nil)
        case .нужнаВерификация, .защита, .отказ, .сеть:
            break
        }
    }

    /// Список с сайта — поиски в SavedSearchStore, продавцы — сюда. Ещё не отправленные нажатия список не отменяет: на
    /// экране они уже есть.
    private func принять(_ все: [ПодпискиСайта.Подписка]) {
        var ждутДобавления = Set<String>()
        var снимаемые = Set<String>()
        for работа in очередь {
            if let д = работа.добавление { ждутДобавления.insert(д.запись.id) }
            if let с = работа.снятие {
                if let номер = с.запись.серверный {
                    снимаемые.insert(номер)
                } else if let пришедший = номераСнятых[с.запись.id] {
                    снимаемые.insert(пришедший.номер)
                }
            }
        }
        if Config.сохранённыеПоиски {
            let поиски = все.filter { $0.продавец == nil && !снимаемые.contains($0.id) }
            SavedSearchStore.shared.принятьССайта(поиски, неТрогать: ждутДобавления)
        }

        var итог: [Продавец] = []
        var виденные = Set<String>()
        for подписка in все {
            guard let продавец = подписка.продавец, виденные.insert(продавец).inserted else { continue }
            итог.append(Продавец(id: продавец, имя: подписка.имяПродавца ?? ""))
        }
        for работа in очередь {
            guard let н = работа.нажатие else { continue }
            if н.подписаться {
                if !итог.contains(where: { $0.id == н.продавец }) {
                    итог.insert(Продавец(id: н.продавец, имя: н.имя), at: 0)
                }
            } else {
                итог.removeAll { $0.id == н.продавец }
            }
        }
        /* Что раньше сказал status, — по свежему списку, кроме продавцов с нажатием в пути или в очереди. */
        let подписаны = Set(итог.map(\.id))
        var известное = оПродавцах
        for (продавец, о) in оПродавцах where !продавцыВПути.contains(продавец) && !вОчереди(продавец) {
            var свежее = о
            свежее.подписан = подписаны.contains(продавец)
            известное[продавец] = свежее
        }
        if известное != оПродавцах { оПродавцах = известное }
        if итог != продавцы { продавцы = итог }
        if !связано { связано = true }
    }

    // MARK: - Поиски

    private func отправитьДобавление(_ д: Добавление) async {
        let взятое = поколение
        guard let можно = await доступ(взятое) else { return }
        let csrf: String
        switch можно {
        case .токен(let токен):
            csrf = токен
        case .гость, .неизвестно:
            return                                  // гость — поиск на телефоне, как на этапе 12
        case .безТокена:
            откатитьДобавление(д, итог: .защита)
            return
        }
        добавлениеВПути = д.запись.id
        let итог = await ПодпискиСайта.добавить(д.запись.искомое, город: д.город, csrf: csrf)
        добавлениеВПути = nil
        guard взятое == поколение else { return }
        switch итог {
        case .готово(let ответ):
            if let номер = ответ.id {
                if !SavedSearchStore.shared.привязать(д.запись.id, серверный: номер, город: д.город) {
                    номераСнятых[д.запись.id] = (номер: номер, город: д.город)
                }
            } else {
                /* «Вы уже подписаны на это» без номера — номер скажет список: поиск сведётся с подпиской сам. */
                последняяСверка = nil
                сверить(пауза: 0)
            }
        case .нуженВход:
            запомнитьВход(false, пользователь: nil)
            откатитьДобавление(д, итог: итог)
        case .нужнаВерификация, .защита, .отказ, .сеть:
            откатитьДобавление(д, итог: итог)
        }
    }

    /// Сайт не сохранил — поиск уходит из списка. Его уже сняли на телефоне (remove ждёт очереди) — снимать нечего.
    private func откатитьДобавление(_ д: Добавление, итог: ПодпискиСайта.Итог) {
        if let место = очередь.firstIndex(where: { $0.снятие?.запись.id == д.запись.id }) {
            очередь.remove(at: место)
        } else {
            SavedSearchStore.shared.снятьНеСохранённый(д.запись.id)
        }
        показать(итог, действие: .сохранение)
    }

    private func отправитьСнятие(_ с: Снятие) async {
        let пришедший = номераСнятых.removeValue(forKey: с.запись.id)
        guard let номер = с.запись.серверный ?? пришедший?.номер else { return }
        let взятое = поколение
        guard let можно = await доступ(взятое) else { return }
        let csrf: String
        switch можно {
        case .токен(let токен):
            csrf = токен
        case .гость:
            откатитьСнятие(с, номер: номер, город: пришедший?.город, итог: .нуженВход)
            return
        case .неизвестно:
            откатитьСнятие(с, номер: номер, город: пришедший?.город, итог: .сеть)
            return
        case .безТокена:
            откатитьСнятие(с, номер: номер, город: пришедший?.город, итог: .защита)
            return
        }
        let итог = await ПодпискиСайта.убрать(номер, csrf: csrf)
        guard взятое == поколение else { return }
        switch итог {
        case .готово:
            break
        case .нуженВход:
            запомнитьВход(false, пользователь: nil)
            откатитьСнятие(с, номер: номер, город: пришедший?.город, итог: итог)
        case .нужнаВерификация, .защита, .отказ, .сеть:
            откатитьСнятие(с, номер: номер, город: пришедший?.город, итог: итог)
        }
    }

    /// Сайт не снял — поиск снова на своём месте, с номером подписки.
    private func откатитьСнятие(_ с: Снятие, номер: String, город: String?, итог: ПодпискиСайта.Итог) {
        var запись = с.запись
        if запись.серверный == nil {
            запись.серверный = номер
            if let пришедшийГород = город { запись.город = пришедшийГород }
        }
        SavedSearchStore.shared.вернуть(запись, место: с.место)
        показать(итог, действие: .снятие)
    }

    // MARK: - Продавцы

    private func отправитьНажатие(_ н: НажатиеПродавца) async {
        let взятое = поколение
        guard let можно = await доступ(взятое) else { return }
        let csrf: String
        switch можно {
        case .токен(let токен):
            csrf = токен
        case .гость:
            откатить(н, итог: .нуженВход)
            return
        case .неизвестно:
            откатить(н, итог: .сеть)
            return
        case .безТокена:
            откатить(н, итог: .защита)
            return
        }
        продавцыВПути.insert(н.продавец)
        let итог: ПодпискиСайта.Итог
        if н.подписаться {
            итог = await ПодпискиСайта.подписаться(н.продавец, имя: н.имя, csrf: csrf)
        } else {
            итог = await ПодпискиСайта.отписаться(н.продавец, csrf: csrf)
        }
        продавцыВПути.remove(н.продавец)
        guard взятое == поколение else { return }
        switch итог {
        case .готово(let ответ):
            /* Как mkSellerFolSet: число подписчиков — из ответа. */
            if let число = ответ.подписчиков, var о = оПродавцах[н.продавец] {
                о.подписчиков = max(0, число)
                оПродавцах[н.продавец] = о
            }
        case .нуженВход:
            запомнитьВход(false, пользователь: nil)
            откатить(н, итог: итог)
        case .нужнаВерификация, .защита, .отказ, .сеть:
            откатить(н, итог: итог)
        }
    }

    /// Сайт не записал. Следующее нажатие на того же продавца уже ждёт очереди — значит, на экране уже то, что на сайте:
    /// его просто не отправляем. Иначе — как было до нажатия.
    private func откатить(_ н: НажатиеПродавца, итог: ПодпискиСайта.Итог) {
        if let место = очередь.firstIndex(where: { $0.нажатие?.продавец == н.продавец }) {
            очередь.remove(at: место)
        } else {
            вернуть(н)
        }
        показать(итог, действие: .продавец)
    }

    /// Экран — как до нажатия: что знали о продавце и его строка в списке.
    private func вернуть(_ н: НажатиеПродавца) {
        оПродавцах[н.продавец] = н.было
        продавцы.removeAll { $0.id == н.продавец }
        if let место = н.строка {
            продавцы.insert(Продавец(id: н.продавец, имя: н.имя), at: min(место, продавцы.count))
        }
    }

    // MARK: - Сообщение

    /// Текст отказа словами сайта: вход — с «Войти» (mkToastAct), иначе текст error сайта или строка действия.
    private func показать(_ итог: ПодпискиСайта.Итог, действие: Действие) {
        let текст: String
        var сКнопкой = false
        switch итог {
        case .готово:
            return
        case .нуженВход:
            текст = SubsText.т(действие == .снятие ? "err_login" : "err_login_sub")
            сКнопкой = true
        case .нужнаВерификация:
            текст = SubsText.т("err_verify")
        case .защита:
            текст = SubsText.т("err_csrf")
        case .сеть:
            текст = SubsText.т("err_net")
        case .отказ(let сайта):
            switch действие {
            case .сохранение: текст = сайта ?? SubsText.т("err_save")
            case .снятие:     текст = SubsText.т("err_unsub")
            case .продавец:   текст = сайта ?? SubsText.т("err_failed")
            }
        }
        показать(текст: текст, войти: сКнопкой)
    }

    /// Плашка внизу: 2,6 с, как toast(…, 2600) сайта у подписки на продавца; с «Войти» — 5 с.
    private func показать(текст: String, войти: Bool) {
        let новое = СинхронИзбранного.Сообщение(текст: текст, войти: войти)
        сообщение = новое
        UIAccessibility.post(notification: .announcement, argument: текст)
        let срок: UInt64 = войти ? 5_000_000_000 : 2_600_000_000
        Task {
            try? await Task.sleep(nanoseconds: срок)
            if self.сообщение?.id == новое.id { self.сообщение = nil }
        }
    }
}

// MARK: - Слой над нативными экранами

extension View {
    /**
     Этап 36: слой подписок вместе с сайтом над нативными экранами (RootWebView) — сообщение внизу и сверка списка при
     возврате в приложение, первой загрузке страницы и возврате со страницы сайта (вход там же). Рубильник выключен —
     ничего не делает. Обёрткой, как слой избранного (СлойИзбранногоССайтом).
     */
    @MainActor
    func подпискиССайтом() -> some View {
        СлойПодписокССайтом(self)
    }
}

struct СлойПодписокССайтом<Содержимое: View>: View {
    let содержимое: Содержимое
    @ObservedObject private var синхрон = СинхронПодписок.shared
    @ObservedObject private var мост = WebBridge.shared
    @Environment(\.scenePhase) private var фаза

    init(_ содержимое: Содержимое) {
        self.содержимое = содержимое
    }

    var body: some View {
        if Config.подпискиССайтом {
            содержимое
                .overlay(alignment: .bottom) { плашка }
                .onChange(of: фаза) { _, стала in
                    if стала == .active { синхрон.сверить(пауза: 60) }
                }
                .onChange(of: мост.isLoaded) { _, загружена in
                    if загружена { синхрон.сверить(пауза: 60) }
                }
                .onChange(of: мост.лентаВидна) { _, видна in
                    if видна { синхрон.сверить(пауза: 60) }
                }
        } else {
            содержимое
        }
    }

    /// Та же плашка и то же место, что у избранного: над нижней панелью и пилюлей «Связаться», только поверх нативного
    /// слоя.
    private var плашка: some View {
        ZStack(alignment: .bottom) {
            if let сообщение = синхрон.сообщение, мост.лентаВидна {
                ПлашкаИзбранного(сообщение: сообщение, войти: { синхрон.войти() })
                    .frame(maxWidth: 520)
                    .padding(.horizontal, 16)
                    .padding(.bottom, 88)
                    .transition(.opacity.combined(with: .move(edge: .bottom)))
                    .id(сообщение.id)
            }
        }
        .animation(ДвижениеСайта.смена, value: синхрон.сообщение?.id)
    }
}

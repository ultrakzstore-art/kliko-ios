import SwiftUI
import UIKit
import RealityKit
import Combine

/**
 «ПОМЕСТИТСЯ ЛИ?» — РЕЖИМ «ВЕЩЬ» (владелец 14.10.2026: «3D-обзор надо сделать за счёт ИИ — 5 разных фото, и ИИ сам
 собрал 3D любой вещи или авто»; раньше: «чтобы по-настоящему по камере показывал объект в примерке»).

 Переключатель окна теперь «Вещь / Коробка / Линейка» (РежимГабаритов, FitBoxRuler.swift); «Вещь» — первым и по
 умолчанию, если у объявления есть 3D-модель, ракурсы или хоть одно фото (ВещьГабаритов.доступна). Вещь стоит в той же
 сессии AR, в том же корпусе, что и коробка (МодельГабаритов, FitBoxAR.swift): касание пола ставит, два пальца крутят,
 палец двигает, «Прижать к стене», подписи размеров у рёбер и «Снимок» — всё общее. Пока вещь готовится или не
 вышла — на её месте коробка тех же размеров (честный габарит, а не пустота).

 Что встаёт на пол, по порядку:
   · у объявления есть 3D-модель ИИ (model3d.usdz, МодельОбъёмаОбъявления, Listing3DModel.swift) — USDZ берётся точкой
     «просмотра» МодельОбъёмаОбъявления.файлМодели(_:) (кэш на диске Caches с пределом 200 МБ, своя сессия, отмена задачи
     обрывает загрузку) и открывается RealityKit'ом (Entity.loadAsync, iOS 13+) — в настоящем размере (СборкаВещиГабаритов);
     подпись «3D-модель ИИ» и честно: «3D-модель создана ИИ по фото — детали могут отличаться»;
   · модели нет или она не открылась — «стойка»: вырезанное фото вещи настоящих ширины и высоты, боковины глубины в
     цвет вещи, тень (ПодготовкаВещиГабаритов, FitBoxItemImage.swift); подпись «Фото вещи в реальном размере»;
   · и фото не вырезалось — коробка, «Вещь с фото не вырезалась — показана коробка».
 Размеры — те же, что у коробки (объявление или лист «Укажите размеры»); нет размеров в объявлении, а в model3d есть все
 три — берутся они (размерыМодели).

 Загрузка идёт, только пока окно на виду и выбрана «Вещь»: ушли с экрана — задача отменяется (загрузка модели и вырезка
 обрываются), вернулись — начинается снова; переключили на «Коробку» или «Линейку» — то же (пауза), готовое остаётся;
 закрыли окно — отпускается всё (отменить()). Лёгкий режим (РежимУстройства.лёгкий): модель больше 40 МБ не качается и
 не открывается — сразу «стойка»; текстура стойки 512 px. Всё здесь — на главной нити; вырезка — в Task.detached,
 текстуры — generateAsync.
 */
extension Config {
    /// Режим «Вещь» в «Поместится ли?»: фото вещи или 3D-модель ИИ в настоящем размере. false — «Коробка / Линейка».
    static let габаритыВещь = true
}

@MainActor
final class ВещьГабаритов: ObservableObject {
    enum Состояние: Equatable {
        /// Ещё не начинали (или поставили на паузу).
        case ждём
        case грузимМодель
        case вырезаем
        /// Готова 3D-модель.
        case модель
        /// Готова «стойка» с фото.
        case фото
        /// Ни модели, ни вырезки — на месте вещи коробка.
        case нет
    }

    @Published private(set) var состояние: Состояние = .ждём
    /// 3D-модель у объявления была, но не открылась — стоит фото (честная пометка).
    @Published private(set) var модельНеВышла = false

    /// Есть из чего строить вещь: 3D-модель, ракурсы или хоть одно фото (и рубильник включён).
    let доступна: Bool
    /// Модель габаритов: вещь готова или не вышла — пересобрать то, что стоит в корпусе.
    var приГотовности: (() -> Void)? = nil

    private let объём: МодельОбъёмаОбъявления?
    /// Главное фото и ещё два: на первом может быть человек или пёстрый фон.
    private let фото: [URL]
    private let лёгкий: Bool

    private var задача: Task<Void, Never>? = nil
    /// Номер загрузки: ответ отменённой (пауза, новый запуск) не перепишет состояние.
    private var поколение = 0
    private var шаблон: Entity? = nil
    private var лицо: TextureResource? = nil
    private var спина: TextureResource? = nil
    /// Ширина вырезки к высоте.
    private var пропорция: CGFloat = 1
    private var цвет = UIColor(white: 0.5, alpha: 1)
    private var тень: TextureResource? = nil
    private var теньГотова = false
    private var запрос: AnyCancellable? = nil
    private var ожидание: CheckedContinuation<Entity, Error>? = nil

    init(товар: Listing, включена: Bool = true) {
        let объём = Config.объёмОбъявления ? товар.модельОбъёма : nil
        let фото = Array(товар.фотоАдреса.prefix(3))
        self.объём = объём
        self.фото = фото
        лёгкий = РежимУстройства.shared.лёгкий
        let естьОбъём = объём.map { $0.есть3D || !$0.ракурсы.isEmpty } ?? false
        доступна = включена && Config.габаритыВещь && (естьОбъём || !фото.isEmpty)
    }

    /// Все три размера из model3d (w_cm, h_cm, d_cm) — когда объявление надёжных размеров не дало.
    static func размерыМодели(_ товар: Listing) -> ГабаритыВещи? {
        guard Config.габаритыВещь, Config.объёмОбъявления, let г = товар.модельОбъёма?.габаритыСм else { return nil }
        let итог = ГабаритыВещи(ширина: г.ширина, высота: г.высота, глубина: г.глубина)
        return итог.годны ? итог : nil
    }

    private func т(_ ключ: String) -> String { ВещьГабаритовText.т(ключ) }

    // MARK: Что показать

    var готова: Bool { состояние == .модель || состояние == .фото }

    var грузится: Bool { состояние == .ждём || состояние == .грузимМодель || состояние == .вырезаем }

    /// Подпись плашки: что сейчас стоит на полу (или готовится).
    var подпись: String {
        switch состояние {
        case .ждём:
            return т(объём?.есть3D == true ? "fi_loading_model" : "fi_loading_photo")
        case .грузимМодель:
            return т("fi_loading_model")
        case .вырезаем:
            return т("fi_loading_photo")
        case .модель:
            return т(объём?.созданаИИ == false ? "fi_model_3d" : "fi_model")
        case .фото:
            return т("fi_photo")
        case .нет:
            return т("fi_failed")
        }
    }

    var значок: String {
        switch состояние {
        case .модель: return "cube.fill"
        case .фото: return "photo"
        case .нет: return "exclamationmark.triangle"
        case .ждём, .грузимМодель, .вырезаем: return "hourglass"
        }
    }

    /// Честная пометка под плашкой: модель ИИ — «детали могут отличаться»; фото — что это плоская стойка.
    var пометка: String? {
        switch состояние {
        case .модель:
            return объём?.созданаИИ == false ? nil : т("fi_ai_note")
        case .фото:
            return модельНеВышла ? т("fi_model_fallback") : т("fi_photo_note")
        case .ждём, .грузимМодель, .вырезаем, .нет:
            return nil
        }
    }

    /// Хвост плашки снимка («Kliko.kz · 60 × 85 × 55 см · 3D-модель ИИ»): снимок уходит дальше — пусть видно, что это.
    var хвостСнимка: String? {
        switch состояние {
        case .модель, .фото: return подпись
        case .ждём, .грузимМодель, .вырезаем, .нет: return nil
        }
    }

    // MARK: Загрузка

    /// Начать готовить вещь (окно на виду, выбрана «Вещь»). Уже готова, уже грузится или не вышла — ничего.
    func подготовить() {
        guard доступна, задача == nil, состояние == .ждём else { return }
        поколение += 1
        let своё = поколение
        состояние = объём?.есть3D == true ? .грузимМодель : .вырезаем
        задача = Task { @MainActor [weak self] in
            await self?.загрузить(своё)
        }
    }

    /// Окно ушло с экрана: загрузку и вырезку оборвать; готовое остаётся.
    func пауза() {
        guard let задача else { return }
        задача.cancel()
        self.задача = nil
        поколение += 1
        отдатьЗагрузку(.failure(CancellationError()))
        if !готова && состояние != .нет { состояние = .ждём }
    }

    /// Окно закрыли насовсем: всё отпустить (модель, текстуры, обратный вызов).
    func отменить() {
        пауза()
        приГотовности = nil
        шаблон = nil
        лицо = nil
        спина = nil
        тень = nil
        теньГотова = false
        if состояние != .ждём { состояние = .ждём }
    }

    private func загрузить(_ своё: Int) async {
        if let м = объём, м.есть3D {
            let сущность = await загрузитьМодель(м)
            guard своё == поколение, !Task.isCancelled else { return }
            if let сущность {
                шаблон = сущность
                закончить(.модель)
                return
            }
            модельНеВышла = true
            состояние = .вырезаем
        }
        let готово = await вырезка(своё)
        guard своё == поколение, !Task.isCancelled else { return }
        guard let готово else {
            закончить(.нет)
            return
        }
        /* Текстуры — по одной и не на главной нити: кадр камеры не дёргается, когда встаёт стойка. */
        let лицо = await СборкаВещиГабаритов.текстураВФоне(готово.лицо)
        guard своё == поколение, !Task.isCancelled else { return }
        guard let лицо else {
            закончить(.нет)
            return
        }
        let спина = await СборкаВещиГабаритов.текстураВФоне(готово.спина)
        guard своё == поколение, !Task.isCancelled else { return }
        self.лицо = лицо
        self.спина = спина
        пропорция = CGFloat(готово.лицо.width) / CGFloat(max(1, готово.лицо.height))
        цвет = UIColor(red: готово.красный, green: готово.зелёный, blue: готово.синий, alpha: 1)
        закончить(.фото)
    }

    private func закончить(_ итог: Состояние) {
        задача = nil
        состояние = итог
        let весть: String
        switch итог {
        case .модель: весть = т("fi_ready_model")
        case .фото: весть = т(модельНеВышла ? "fi_model_fallback" : "fi_ready_photo")
        case .ждём, .грузимМодель, .вырезаем, .нет: весть = т("fi_failed")
        }
        UIAccessibility.post(notification: .announcement, argument: весть)
        приГотовности?()
    }

    /**
     Лёгкий режим (слабое железо, экономия заряда, нагрев): модель больше этого не качается без спроса и не поднимается
     целиком в память посреди идущей сессии AR — сразу «стойка» из фото (с честной пометкой, что модель не встала).
     */
    private static let пределМоделиЛёгкий: Int64 = 40 * 1024 * 1024

    /// USDZ через точку «просмотра» (кэш на диске) и RealityKit. Не вышло — nil; негодный файл — с диска вон.
    private func загрузитьМодель(_ м: МодельОбъёмаОбъявления) async -> Entity? {
        let предел: Int64? = лёгкий ? Self.пределМоделиЛёгкий : nil
        guard let файл = await МодельОбъёмаОбъявления.файлМодели(м, предел: предел), !Task.isCancelled else {
            return nil
        }
        do {
            return try await открыть(файл)
        } catch {
            guard !Task.isCancelled, !(error is CancellationError) else { return nil }
            /* RealityKit файл не открыл — он негодный: убрать с диска, чтобы в следующий раз скачался заново. */
            if let адрес = м.usdz { await КэшОбъёма.shared.забыть(адрес, расширение: "usdz") }
            return nil
        }
    }

    /// Вырезка для «стойки»: ракурс «спереди» из 3D-обзора, потом фото объявления по порядку.
    private func вырезка(_ своё: Int) async -> ПодготовкаВещиГабаритов.Готово? {
        let сторона = лёгкий ? 512 : 1024
        if let первый = объём?.ракурсы.first,
           let файл = try? await КэшОбъёма.shared.файл(первый, прогресс: nil) {
            guard своё == поколение, !Task.isCancelled else { return nil }
            let итог = await вФоне { ПодготовкаВещиГабаритов.изФайла(файл, сторона: сторона) }
            if case .готово(let готово) = итог { return готово }
        }
        for адрес in фото {
            guard своё == поколение, !Task.isCancelled else { return nil }
            guard let картинка = await КартинкиЛенты.shared.загрузить(адрес, пикселей: 1024, заполнить: false) else {
                continue
            }
            guard своё == поколение, !Task.isCancelled else { return nil }
            let ящик = ПодготовкаВещиГабаритов.Фото(картинка: картинка)
            let итог = await вФоне { ПодготовкаВещиГабаритов.изФото(ящик.картинка, сторона: сторона) }
            if case .готово(let готово) = итог { return готово }
        }
        return nil
    }

    /// Работа не на главной нити; отмена задачи доходит и до неё (сама в detached она не передаётся).
    private func вФоне(_ работа: @escaping @Sendable () -> ПодготовкаВещиГабаритов.Итог) async
        -> ПодготовкаВещиГабаритов.Итог {
        let фоновая = Task.detached(priority: .userInitiated) { работа() }
        return await withTaskCancellationHandler {
            await фоновая.value
        } onCancel: {
            фоновая.cancel()
        }
    }

    /// Entity.loadAsync (iOS 13+) — не на главной нити; ответ — на главную. Отмена задачи отпускает ожидание сразу.
    private func открыть(_ файл: URL) async throws -> Entity {
        try await withTaskCancellationHandler {
            try await withCheckedThrowingContinuation { (продолжить: CheckedContinuation<Entity, Error>) in
                отдатьЗагрузку(.failure(CancellationError()))
                ожидание = продолжить
                запрос = Entity.loadAsync(contentsOf: файл)
                    .receive(on: DispatchQueue.main)
                    .sink(receiveCompletion: { [weak self] итог in
                        guard case .failure(let ошибка) = итог else { return }
                        MainActor.assumeIsolated {
                            guard let self else { return }
                            self.отдатьЗагрузку(.failure(ошибка))
                        }
                    }, receiveValue: { [weak self] сущность in
                        MainActor.assumeIsolated {
                            guard let self else { return }
                            self.отдатьЗагрузку(.success(сущность))
                        }
                    })
            }
        } onCancel: { [weak self] in
            Task { @MainActor [weak self] in self?.отдатьЗагрузку(.failure(CancellationError())) }
        }
    }

    private func отдатьЗагрузку(_ итог: Result<Entity, Error>) {
        запрос?.cancel()
        запрос = nil
        guard let продолжить = ожидание else { return }
        ожидание = nil
        продолжить.resume(with: итог)
    }

    // MARK: Сцена

    /**
     Сущность вещи для корпуса (начало — центр дна, лицо — +z): 3D-модель или «стойка» по размерам `габариты`. Не готова
     или не вышла — nil (в корпусе остаётся коробка). Каждый вызов — новая сущность: модель — копия загруженной (сетки и
     текстуры общие), стойка — из готовых текстур.
     */
    func собрать(_ габариты: ГабаритыВещи) -> Entity? {
        if !теньГотова {
            тень = СборкаВещиГабаритов.текстураТени()
            теньГотова = true
        }
        switch состояние {
        case .модель:
            guard let шаблон else { return nil }
            return СборкаВещиГабаритов.модель(шаблон, габариты: габариты, своиРазмеры: объём?.размерыИзвестны ?? false,
                                              тень: тень, лёгкий: лёгкий)
        case .фото:
            guard let лицо else { return nil }
            return СборкаВещиГабаритов.стойка(лицо: лицо, спина: спина, пропорция: пропорция, цвет: цвет,
                                              габариты: габариты, тень: тень)
        case .ждём, .грузимМодель, .вырезаем, .нет:
            return nil
        }
    }
}

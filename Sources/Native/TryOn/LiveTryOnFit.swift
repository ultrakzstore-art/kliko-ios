/**
 ЖИВАЯ ПРИМЕРКА — ПОСАДКА ВЕЩИ (владелец 13.10.2026: «нужнее охват всего»).

 Точки Vision (доли кадра) → экран: кадр заполняет экран по меньшему масштабу и режется по краям, как превью
 (resizeAspectFill). Дальше всё — в точках экрана, в системе «линии глаз»: e — от левого глаза к правому, «вниз» —
 перпендикуляр к ней. d — расстояние между зрачками (при повороте головы — делённое на косинус поворота).

   очки      центр между зрачками; ширина ≈ 2,1 d (или ширина оправы из характеристик : 63 мм); угол — линии глаз;
             при повороте головы сжимаются по ширине (косинус поворота);
   убор      нижний край — на лбу: брови и ещё 0,55 d вверх; ширина — ширина головы × 1,2;
   серьги    у мочек: крайние точки контура лица на уровне кончика носа, чуть наружу и вниз; парой, зеркально; висят
             почти отвесно; при сильном повороте дальняя гаснет;
   колье     верх — под подбородком (самая нижняя точка контура и 0,45 d вниз); ширина — по лицу;
   часы      на запястье, чуть к локтю; ширина корпуса ≈ 0,62 ширины ладони (или диаметр из характеристик : 68 мм);
             ремешок дальше обхвата руки гаснет;
   браслет   там же; круг с фото сжат вдоль руки — видна полоса поперёк запястья;
   кольцо    на безымянном пальце между пястным суставом и следующим, поперёк пальца.
 Дрожь гасит экспоненциальное сглаживание; большие скачки (другое лицо, рука) — без сглаживания. Ручная подгонка
 (щипок, поворот, сдвиг) кладётся поверх посадки и живёт до закрытия экрана.
 */
struct РасположениеВещиЖивой: Equatable, Sendable {
    /// Точка экрана, куда ложится якорь картинки.
    var центр: CGPoint
    /// Ширина картинки на экране, точки.
    var ширина: CGFloat
    /// Поворот по часовой стрелке, радианы.
    var угол: Double
    /// Какая точка картинки лежит в центре (доли картинки, 0…1).
    var якорь: CGPoint
    /// Сжатие картинки по её осям (поворот головы, браслет вдоль руки, кольцо вдоль пальца).
    var сжатие: CGSize = CGSize(width: 1, height: 1)
    /// Видимая длина по высоте картинки (ремешок часов дальше обхвата руки гаснет); nil — вся картинка.
    var предел: CGFloat? = nil
    /// Прозрачность: дальняя серьга при повороте головы гаснет.
    var видимость: Double = 1

    var якорьЕдиницы: UnitPoint { UnitPoint(x: якорь.x, y: якорь.y) }

    /// Подгонка поверх посадки. зеркально — вторая серьга: сдвиг по ширине и поворот — в другую сторону. сдвигЭкрана —
    /// живой сдвиг пальцем, ещё не принятый (в точках экрана).
    func сПодгонкой(_ п: ПодгонкаЖивойПримерки, зеркально: Bool, сдвигЭкрана: CGSize = .zero) -> РасположениеВещиЖивой {
        var р = self
        let ш = ширина * п.масштаб
        let сx = (зеркально ? -п.сдвиг.width : п.сдвиг.width) * ш
        let сy = п.сдвиг.height * ш
        let кос = CGFloat(cos(угол))
        let син = CGFloat(sin(угол))
        let живойX = зеркально ? -сдвигЭкрана.width : сдвигЭкрана.width
        р.центр = CGPoint(x: центр.x + сx * кос - сy * син + живойX,
                          y: центр.y + сx * син + сy * кос + сдвигЭкрана.height)
        р.ширина = ш
        р.угол = угол + (зеркально ? -п.поворот : п.поворот)
        if let предел { р.предел = предел * п.масштаб }
        return р
    }

    /// Шаг сглаживания к новому положению: доля пути (0…1). Угол — по кратчайшей дуге.
    func плавно(к новое: РасположениеВещиЖивой, доля: CGFloat) -> РасположениеВещиЖивой {
        let скачок = hypot(новое.центр.x - центр.x, новое.центр.y - центр.y)
        if скачок > max(новое.ширина, 40) * 0.6 { return новое }
        var р = новое
        func к(_ а: CGFloat, _ б: CGFloat) -> CGFloat { а + (б - а) * доля }
        р.центр = CGPoint(x: к(центр.x, новое.центр.x), y: к(центр.y, новое.центр.y))
        р.ширина = к(ширина, новое.ширина)
        var разница = новое.угол - угол
        while разница > .pi { разница -= 2 * .pi }
        while разница < -.pi { разница += 2 * .pi }
        р.угол = угол + разница * Double(доля)
        р.сжатие = CGSize(width: к(сжатие.width, новое.сжатие.width), height: к(сжатие.height, новое.сжатие.height))
        if let было = предел, let стало = новое.предел { р.предел = к(было, стало) }
        р.видимость = видимость + (новое.видимость - видимость) * Double(доля)
        return р
    }
}

/// Ручная подгонка на сеанс: масштаб, поворот (радианы) и сдвиг в долях ширины вещи (вдоль её осей).
struct ПодгонкаЖивойПримерки: Equatable, Sendable {
    var масштаб: CGFloat = 1
    var поворот: Double = 0
    var сдвиг: CGSize = .zero

    var исходная: Bool { self == ПодгонкаЖивойПримерки() }
}

/// Что сейчас с вещью на экране — для подсказок.
enum СостояниеСлеженияЖивой: Equatable, Sendable {
    /// Камера только запускается.
    case ищем
    case есть
    case нетЛица
    case лицоДалеко
    case нетРуки
}

// MARK: - Посадка

enum ПосадкаЖивойПримерки {
    /// Доля кадра → точка экрана (кадр заполняет экран, края режутся — как у превью).
    static func наЭкран(_ доля: CGPoint, кадр: CGSize, экран: CGSize) -> CGPoint {
        guard кадр.width > 0, кадр.height > 0 else { return .zero }
        let м = max(экран.width / кадр.width, экран.height / кадр.height)
        let сx = (экран.width - кадр.width * м) / 2
        let сy = (экран.height - кадр.height * м) / 2
        return CGPoint(x: доля.x * кадр.width * м + сx, y: доля.y * кадр.height * м + сy)
    }

    /// Итог посадки кадра: положения вещей (у серёг — два) или почему вещи нет.
    enum Итог {
        case есть([РасположениеВещиЖивой])
        case нет(СостояниеСлеженияЖивой)
    }

    static func посадить(_ вид: ВидЖивойПримерки, _ н: НаблюдениеЖивойПримерки, экран: CGSize,
                         мм: Double?) -> Итог {
        guard экран.width > 1, экран.height > 1 else { return .нет(.ищем) }
        if вид.лицо {
            guard let лицо = н.лицо else { return .нет(.нетЛица) }
            return наЛицо(вид, лицо, кадр: н.размер, экран: экран, мм: мм)
        }
        guard let рука = н.рука else { return .нет(.нетРуки) }
        return наРуку(вид, рука, кадр: н.размер, экран: экран, мм: мм)
    }

    // MARK: Лицо

    private static func наЛицо(_ вид: ВидЖивойПримерки, _ лицо: ЛицоЖивойПримерки, кадр: CGSize, экран: CGSize,
                               мм: Double?) -> Итог {
        func т(_ доля: CGPoint) -> CGPoint { наЭкран(доля, кадр: кадр, экран: экран) }
        let л = т(лицо.глазСлева)
        let п = т(лицо.глазСправа)
        let d0 = hypot(п.x - л.x, п.y - л.y)
        guard d0 > 4 else { return .нет(.нетЛица) }
        let поворот = лицо.поворот ?? 0
        if abs(поворот) > 0.75 { return .нет(.нетЛица) }
        if d0 < min(экран.width, экран.height) * 0.05 { return .нет(.лицоДалеко) }
        let кос = CGFloat(max(0.55, cos(поворот)))
        let d = d0 / кос
        let α = atan2(Double(п.y - л.y), Double(п.x - л.x))
        let e = CGPoint(x: CGFloat(cos(α)), y: CGFloat(sin(α)))
        let вниз = CGPoint(x: -e.y, y: e.x)
        let глаза = CGPoint(x: (л.x + п.x) / 2, y: (л.y + п.y) / 2)
        func s(_ точка: CGPoint) -> CGFloat { (точка.x - глаза.x) * e.x + (точка.y - глаза.y) * e.y }
        func t(_ точка: CGPoint) -> CGFloat { (точка.x - глаза.x) * вниз.x + (точка.y - глаза.y) * вниз.y }
        func из(_ s: CGFloat, _ t: CGFloat) -> CGPoint {
            CGPoint(x: глаза.x + e.x * s + вниз.x * t, y: глаза.y + e.y * s + вниз.y * t)
        }
        let контур = лицо.контур.map(т)
        let нос = лицо.нос.map(т)
        let ширинаЛица: CGFloat = {
            guard контур.count > 2, let мин = контур.map(s).min(), let макс = контур.map(s).max() else { return 2.2 * d }
            return max(1.6 * d, (макс - мин) / кос)
        }()

        switch вид {
        case .очки:
            let множитель = мм.map { CGFloat(min(2.6, max(1.7, $0 / 63))) } ?? 2.1
            return .есть([РасположениеВещиЖивой(центр: из(0, 0.03 * d), ширина: d * множитель, угол: α,
                                                якорь: CGPoint(x: 0.5, y: 0.5),
                                                сжатие: CGSize(width: кос, height: 1))])
        case .шапка:
            let брови = лицо.брови.map(т).map(t)
            let линияБровей = брови.isEmpty ? -0.38 * d : брови.reduce(0, +) / CGFloat(брови.count)
            let ширина = max(ширинаЛица * 1.05, 2.3 * d) * 1.2
            return .есть([РасположениеВещиЖивой(центр: из(0, линияБровей - 0.55 * d), ширина: ширина, угол: α,
                                                якорь: CGPoint(x: 0.5, y: 0.9))])
        case .серьги:
            let уровень = (нос.map(t).max() ?? 0.75 * d) + 0.1 * d
            let носS = нос.isEmpty ? 0 : нос.map(s).reduce(0, +) / CGFloat(нос.count)
            let левый = край(контур, слева: true, уровень: уровень, s: s, t: t) ?? (-ширинаЛица * кос / 2)
            let правый = край(контур, слева: false, уровень: уровень, s: s, t: t) ?? (ширинаЛица * кос / 2)
            let доЛевого = max(1, носS - левый)
            let доПравого = max(1, правый - носS)
            /* Голову повернули — до дальнего уха от носа на экране близко: эту серьгу прячем. */
            let видимостьЛевой: Double = доЛевого < доПравого * 0.45 ? 0 : 1
            let видимостьПравой: Double = доПравого < доЛевого * 0.45 ? 0 : 1
            let ширина = 0.32 * d
            let наклон = α * 0.25
            let низ = уровень + 0.12 * d
            return .есть([
                РасположениеВещиЖивой(центр: из(левый - 0.12 * d, низ), ширина: ширина, угол: наклон,
                                      якорь: CGPoint(x: 0.5, y: 0.04), видимость: видимостьЛевой),
                РасположениеВещиЖивой(центр: из(правый + 0.12 * d, низ), ширина: ширина, угол: наклон,
                                      якорь: CGPoint(x: 0.5, y: 0.04), видимость: видимостьПравой)
            ])
        case .колье:
            let подбородок = контур.map(t).max() ?? 1.65 * d
            let ширина = max(ширинаЛица * 0.95, 2.0 * d)
            return .есть([РасположениеВещиЖивой(центр: из(0, подбородок + 0.45 * d), ширина: ширина, угол: α * 0.5,
                                                якорь: CGPoint(x: 0.5, y: 0.02))])
        case .часы, .браслет, .кольцо:
            return .нет(.нетЛица)
        }
    }

    /// Место края лица (по оси e) на высоте `уровень`: между двумя точками контура этой стороны, выше и ниже уровня.
    private static func край(_ контур: [CGPoint], слева: Bool, уровень: CGFloat, s: (CGPoint) -> CGFloat,
                             t: (CGPoint) -> CGFloat) -> CGFloat? {
        let сторона = контур
            .map { (s: s($0), t: t($0)) }
            .filter { слева ? $0.s < 0 : $0.s > 0 }
            .sorted { $0.t < $1.t }
        guard !сторона.isEmpty else { return nil }
        if let выше = сторона.last(where: { $0.t <= уровень }), let ниже = сторона.first(where: { $0.t > уровень }) {
            let доля = (уровень - выше.t) / max(0.001, ниже.t - выше.t)
            return выше.s + (ниже.s - выше.s) * доля
        }
        return сторона.min(by: { abs($0.t - уровень) < abs($1.t - уровень) })?.s
    }

    // MARK: Рука

    private static func наРуку(_ вид: ВидЖивойПримерки, _ рука: РукаЖивойПримерки, кадр: CGSize, экран: CGSize,
                               мм: Double?) -> Итог {
        func т(_ доля: CGPoint) -> CGPoint { наЭкран(доля, кадр: кадр, экран: экран) }
        let запястье = т(рука.запястье)
        let указательный = т(рука.указательный)
        let средний = т(рука.средний)
        let мизинец = т(рука.мизинец)
        let ладонь = hypot(указательный.x - мизинец.x, указательный.y - мизинец.y)
        let длина = hypot(средний.x - запястье.x, средний.y - запястье.y)
        guard ладонь > 6, длина > 6 else { return .нет(.нетРуки) }
        if ладонь < min(экран.width, экран.height) * 0.1 { return .нет(.нетРуки) }
        /* Направление руки — от запястья к пальцам; правый край картинки (заводная головка) смотрит к пальцам. */
        let к = CGPoint(x: (средний.x - запястье.x) / длина, y: (средний.y - запястье.y) / длина)
        let угол = atan2(Double(к.y), Double(к.x))
        switch вид {
        case .часы:
            let доля = мм.map { CGFloat(min(1.0, max(0.4, $0 / 68))) } ?? 0.62
            let центр = CGPoint(x: запястье.x - к.x * длина * 0.3, y: запястье.y - к.y * длина * 0.3)
            return .есть([РасположениеВещиЖивой(центр: центр, ширина: ладонь * доля, угол: угол,
                                                якорь: CGPoint(x: 0.5, y: 0.5), предел: ладонь * 1.05)])
        case .браслет:
            let центр = CGPoint(x: запястье.x - к.x * длина * 0.22, y: запястье.y - к.y * длина * 0.22)
            return .есть([РасположениеВещиЖивой(центр: центр, ширина: ладонь * 0.95, угол: угол,
                                                якорь: CGPoint(x: 0.5, y: 0.5), сжатие: CGSize(width: 0.4, height: 1),
                                                предел: ладонь * 1.1)])
        case .кольцо:
            guard let основаниеД = рука.безымянный, let суставД = рука.безымянныйСустав else { return .нет(.нетРуки) }
            let основание = т(основаниеД)
            let сустав = т(суставД)
            let палец = hypot(сустав.x - основание.x, сустав.y - основание.y)
            guard палец > 3 else { return .нет(.нетРуки) }
            let ф = CGPoint(x: (сустав.x - основание.x) / палец, y: (сустав.y - основание.y) / палец)
            let центр = CGPoint(x: основание.x + (сустав.x - основание.x) * 0.4,
                                y: основание.y + (сустав.y - основание.y) * 0.4)
            /* Верх картинки (камень) — к кончику пальца, ширина — поперёк пальца. */
            return .есть([РасположениеВещиЖивой(центр: центр, ширина: ладонь * 0.34,
                                                угол: atan2(Double(ф.x), Double(-ф.y)),
                                                якорь: CGPoint(x: 0.5, y: 0.5), сжатие: CGSize(width: 1, height: 0.6))])
        case .очки, .шапка, .серьги, .колье:
            return .нет(.нетРуки)
        }
    }
}

// MARK: - Слежение

/**
 Положения вещи на экране — 15 раз в секунду. Отдельный объект, чтобы частые обновления перерисовывали только слой вещи,
 а не весь экран. Потеряли лицо или руку на 6 кадров подряд (около 0,4 с) — вещь гаснет, экран получает причину для
 подсказки (приСмене — только при смене состояния).
 */
@MainActor
final class СлежениеЖивойПримерки: ObservableObject {
    @Published private(set) var положения: [РасположениеВещиЖивой] = []
    @Published private(set) var видно = false
    /// Номер обновления — по нему слой вещи плавно доводит её между кадрами анализа.
    @Published private(set) var номер = 0

    let вид: ВидЖивойПримерки
    let мм: Double?
    /// Размер слоя вещи (во весь экран), точки. Пишет слой.
    var размерЭкрана: CGSize = .zero
    var приСмене: (@MainActor (СостояниеСлеженияЖивой) -> Void)? = nil

    private(set) var состояние: СостояниеСлеженияЖивой = .ищем
    private var промахи = 0

    init(вид: ВидЖивойПримерки, мм: Double?) {
        self.вид = вид
        self.мм = мм
    }

    func принять(_ н: НаблюдениеЖивойПримерки) {
        switch ПосадкаЖивойПримерки.посадить(вид, н, экран: размерЭкрана, мм: мм) {
        case .есть(let новые):
            if видно && положения.count == новые.count {
                положения = zip(положения, новые).map { $0.плавно(к: $1, доля: 0.45) }
            } else {
                положения = новые
            }
            номер &+= 1
            промахи = 0
            if !видно { видно = true }
            сменить(.есть)
        case .нет(let почему):
            промахи += 1
            guard промахи >= 6 else { return }
            if видно { видно = false }
            сменить(почему)
        }
    }

    /// Камеру остановили (фон, снимок на экране): вещь гаснет, счёт — заново.
    func сброс() {
        промахи = 0
        if видно { видно = false }
        сменить(.ищем)
    }

    private func сменить(_ новое: СостояниеСлеженияЖивой) {
        guard новое != состояние else { return }
        состояние = новое
        приСмене?(новое)
    }
}

/// Разболтовка: число отверстий крепления и диаметр окружности, на которой они стоят (PCD, мм) — «5×114.3».
struct РазболтовкаАвтоподбора: Hashable, Codable, Sendable {
    var отверстий: Int
    var pcd: Double

    init(отверстий: Int, pcd: Double) {
        self.отверстий = отверстий
        self.pcd = pcd
    }

    /// Стандартные PCD: дробные бывают только такие (114.3 — это 4,5 дюйма, 139.7 — 5,5 дюйма).
    private static let стандартные: [Double] = [98, 100, 105, 108, 110, 112, 114.3, 115, 118, 120, 120.65, 127, 130,
                                                135, 139.7, 150, 160, 165.1, 170, 180, 205]

    /// Правдоподобная разболтовка: 3–10 отверстий, PCD — стандартный или целый от 90 до 210.
    static func годная(отверстий: Int, pcd: Double) -> Bool {
        guard (3...10).contains(отверстий), (90...210).contains(pcd) else { return false }
        if стандартные.contains(where: { abs($0 - pcd) < 0.36 }) { return true }
        return pcd == pcd.rounded()
    }

    /// Совпадает с другой (с допуском на запись 120.65 ↔ 120.7).
    func совпадает(_ другая: РазболтовкаАвтоподбора) -> Bool {
        отверстий == другая.отверстий && abs(pcd - другая.pcd) < 0.36
    }

    /// «5×114.3».
    var подпись: String { String(отверстий) + "×" + ЧислаАвтоподбора.ч(pcd, знаков: 2) }

    /// Из того, что набрал человек: «5x114.3», «5/114,3», «5-114.3», «5 114.3». nil — не похоже.
    static func изВвода(_ строка: String) -> РазболтовкаАвтоподбора? {
        let текст = ПарсерАвтоподбора.pcdИзЗначения(ПарсерАвтоподбора.нормально(строка))
        if let первая = ПарсерАвтоподбора.разболтовки(текст).first { return первая }
        let образец = #"(?<![0-9.])([3-9]|10)\D{1,3}(\d{2,3}(?:\.\d{1,2})?)(?![0-9])"#
        guard let г = ПарсерАвтоподбора.группы(образец, текст).first, г.count == 3,
              let о = ПарсерАвтоподбора.число(г[1]), let p = ПарсерАвтоподбора.число(г[2]),
              годная(отверстий: Int(о), pcd: p) else { return nil }
        return РазболтовкаАвтоподбора(отверстий: Int(о), pcd: p)
    }
}

/// Параметры диска. Не указано продавцом — nil.
struct ДискАвтоподбора: Hashable, Sendable {
    /// Посадочный диаметр, дюймы (R17).
    var диаметр: Double? = nil
    /// Ширина обода, дюймы (7.5J).
    var ширина: Double? = nil
    /// Разболтовки: у мультиразболтовки их две («5x100/114.3»).
    var разболтовки: [РазболтовкаАвтоподбора] = []
    /// Вылет, мм (ET45; бывает отрицательным).
    var et: Double? = nil
    /// Центральное отверстие, мм (DIA 67.1).
    var dia: Double? = nil

    /// Есть хоть что-то, кроме диаметра, — по нему видно, что это диск, а не шина.
    var естьКрепёж: Bool { !разболтовки.isEmpty || et != nil || dia != nil || ширина != nil }

    var пустой: Bool { диаметр == nil && !естьКрепёж }
}

/// Что продаётся: одни шины, одни диски или колёса в сборе (диски с шинами).
enum ВидТовараАвтоподбора: String, CaseIterable, Hashable, Sendable {
    case шины
    case диски
    case колёса

    var название: String {
        switch self {
        case .шины: return АвтоподборText.т("af_kind_tires")
        case .диски: return АвтоподборText.т("af_kind_rims")
        case .колёса: return АвтоподборText.т("af_kind_wheels")
        }
    }
}

/// «Подходит к марке… Модель… Годы с… по…» из характеристик — то, что продавец сам написал о машине.
struct ОтметкаПродавцаАвтоподбора: Hashable, Sendable {
    var марка = ""
    var модель = ""
    var годС = 0
    var годПо = 0

    /// Без марки «Модель» ничего не значит: у шин так бывает назван протектор («X-Ice North 4»).
    var пустая: Bool { марка.isEmpty }

    /// «Toyota Camry, 2012–2017».
    var подпись: String {
        var текст = [марка, модель].filter { !$0.isEmpty }.joined(separator: " ")
        if годС > 0 && годПо > 0 {
            текст += ", " + String(годС) + "–" + String(годПо)
        } else if годС > 0 {
            текст += ", " + String(годС) + "+"
        }
        return текст
    }
}


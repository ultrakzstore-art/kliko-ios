/// Всё, что удалось понять о товаре. Человек может поправить (ПараметрыТовараАвтоподбора) — тогда правка, а не разбор.
struct РазборАвтоподбора: Hashable, Sendable {
    /// nil — не поняли, шины это или диски.
    var вид: ВидТовараАвтоподбора? = nil
    /// Размеры шин: обычно один, у разноширокого комплекта — два.
    var шины: [РазмерШиныАвтоподбора] = []
    /// Посадочный диаметр шины, если полного размера нет («шины R17»).
    var диаметрШины: Double? = nil
    var сезон: СезонАвтоподбора? = nil
    var диск = ДискАвтоподбора()
    var продавец = ОтметкаПродавцаАвтоподбора()

    /// Ничего полезного: ни размера шин, ни параметров диска.
    var пустой: Bool { шины.isEmpty && диаметрШины == nil && диск.пустой }

    /// Диаметр диска для сверки: свой, у колёс в сборе — посадка шины.
    var диаметрДиска: Double? { диск.диаметр ?? (вид == .колёса ? шины.first?.диаметр : nil) }

    /**
     Разбор объявления: сначала поля parts (пачка 83: мастер подачи и магазины кладут шину и диск полями — kind, width,
     profile, diameter, season · diameter, width_j, pcd, et, dia; docs/SERVER_NEW_FOR_MINE.md §1.1), потом характеристики
     по названиям пунктов (надёжнее текста), потом образцы в названии и значениях характеристик, и только для того, что
     осталось пустым, — в описании (там бывает «стояли 205/55 R16» о другом).
     */
    static func из(_ товар: Listing) -> РазборАвтоподбора {
        typealias П = ПарсерАвтоподбора
        var р = РазборАвтоподбора()
        var ширинаШины: Double? = nil
        var профиль: Double? = nil
        var общийДиаметр: Double? = nil
        var отверстий: Int? = nil
        var pcdБезОтверстий: Double? = nil
        let видЗапчасти: String = р.принять(товар.запчастьПолей)

        for пункт in товар.характеристики {
            let ключ = П.нормально(пункт.ключ)
            let значение = П.нормально(пункт.значение)
            let ч = П.первоеЧисло(значение)
            switch П.видКлюча(ключ) {
            case .pcd:
                let свои = П.разболтовки(П.pcdИзЗначения(значение))
                if свои.isEmpty, let ч, (90...210).contains(ч) {
                    pcdБезОтверстий = ч
                }
                for р1 in свои where !р.диск.разболтовки.contains(where: { $0.совпадает(р1) }) {
                    р.диск.разболтовки.append(р1)
                }
            case .dia:
                if р.диск.dia == nil, let ч, (50...175).contains(ч) { р.диск.dia = ч }
            case .et:
                if р.диск.et == nil, let ч = П.числоСоЗнаком(значение), (-65...80).contains(ч) { р.диск.et = ч }
            case .отверстия:
                if let ч, (3...10).contains(ч), ч == ч.rounded() { отверстий = Int(ч) }
            case .профиль:
                /* «Ширина профиля» — это ширина шины (225), «высота профиля» — профиль (45). */
                if let ч, РазмерШиныАвтоподбора.профили.contains(ч) {
                    профиль = ч
                } else if let ч, РазмерШиныАвтоподбора.ширины.contains(ч) {
                    ширинаШины = ч
                }
            case .ширина:
                if let ч, РазмерШиныАвтоподбора.ширины.contains(ч) {
                    ширинаШины = ч
                } else if let ч, (3.5...13).contains(ч), р.диск.ширина == nil {
                    р.диск.ширина = ч
                }
            case .диаметр:
                if let ч, РазмерШиныАвтоподбора.диаметры.contains(ч) { общийДиаметр = ч }
            case .сезон:
                if р.сезон == nil { р.сезон = П.сезон(значение) }
            case .марка:
                р.продавец.марка = пункт.значение.trimmingCharacters(in: .whitespacesAndNewlines)
            case .модель:
                р.продавец.модель = пункт.значение.trimmingCharacters(in: .whitespacesAndNewlines)
            case .годС:
                if let ч, (1950...2100).contains(ч) { р.продавец.годС = Int(ч) }
            case .годПо:
                if let ч, (1950...2100).contains(ч) { р.продавец.годПо = Int(ч) }
            case .прочее:
                break
            }
        }
        if р.диск.разболтовки.isEmpty, let о = отверстий, let p = pcdБезОтверстий,
           РазболтовкаАвтоподбора.годная(отверстий: о, pcd: p) {
            р.диск.разболтовки.append(РазболтовкаАвтоподбора(отверстий: о, pcd: p))
        }
        if let ш = ширинаШины, let п = профиль, let д = общийДиаметр {
            let размер = РазмерШиныАвтоподбора(ширина: ш, профиль: п, диаметр: д)
            if размер.годный && !р.шины.contains(размер) { р.шины.append(размер) }
        }

        let название = П.нормально(товар.title)
        let значения = П.нормально(товар.характеристики.map { $0.значение }.joined(separator: " ; "))
        let описание = П.нормально(String((товар.описание ?? "").prefix(3000)))
        /* Строка подачи «Размер шин: 205/55 R16» или «Диски: R16 6.5J ET45 5x114.3 DIA 67.1» (её пишет приложение в
           конец описания, Posting/PostingSizeWheels.swift) — числа самого продавца: сразу после характеристик, раньше
           названия, и даже если описание длиннее 3000 знаков. */
        let строкиПодачи = П.нормально(СтрокиКолёсПодачи.своиСтроки(товар.описание ?? ""))
        р.дополнить(строкиПодачи)
        р.дополнить(название)
        р.дополнить(значения)
        р.дополнить(описание)

        /* Шины, диски или колёса в сборе. ПризнакиДисков: false — одни шины (так решил и хаб), true — диски. */
        let весь = название + " ; " + значения + " ; " + описание + " ; " + строкиПодачи
        let признак = ПризнакиДисков.диски(товар)
        let словаКолёс = П.естьСлова(весь, ["колес", "в сборе", "на дисках", "с резиной", "с шинами", "дөңгелек",
                                            "wheels with", "wheel and tire", "wheels and tires", "tyres on"])
        /* Вид из parts.kind — выбор продавца в мастере («Шины | Диски»): он надёжнее признаков текста. */
        if видЗапчасти == "tire" && !р.шины.isEmpty {
            р.вид = .шины
        } else if видЗапчасти == "wheel" && !р.диск.пустой {
            р.вид = !р.шины.isEmpty && словаКолёс ? .колёса : .диски
        } else if признак == false {
            р.вид = .шины
        } else if признак == true || р.диск.естьКрепёж {
            р.вид = !р.шины.isEmpty && словаКолёс ? .колёса : .диски
        } else if !р.шины.isEmpty {
            р.вид = .шины
        } else {
            р.вид = nil
        }

        switch р.вид {
        case .шины:
            /* «R17» в объявлении шин — посадка шины, а не диск. */
            р.диаметрШины = р.шины.first?.диаметр ?? общийДиаметр ?? р.диск.диаметр
            р.диск = ДискАвтоподбора()
        case .диски, .колёса:
            /* Пункт «Диаметр» характеристик надёжнее «R17» из названия (дополнить успел заполнить поле раньше). */
            р.диск.диаметр = общийДиаметр ?? р.диск.диаметр ?? р.шины.first?.диаметр
            if р.вид == .диски && р.шины.count > 1 { р.шины = Array(р.шины.prefix(1)) }
        case nil:
            р.диаметрШины = общийДиаметр
        }
        return р
    }

    /**
     Поля parts (мастер подачи, магазины): шина — width, profile, diameter, season; диск — diameter, width_j, pcd, et,
     dia. Неправдоподобное — мимо (дальше дополнят характеристики и текст). Возвращает kind строчными: "tire", "wheel"
     или пусто.
     */
    mutating func принять(_ поля: [String: String]) -> String {
        typealias П = ПарсерАвтоподбора
        guard !поля.isEmpty else { return "" }
        func числоПоля(_ ключ: String) -> Double? {
            guard let сырое = поля[ключ] else { return nil }
            return П.первоеЧисло(П.нормально(сырое))
        }
        let видПолей: String = (поля["kind"] ?? "").trimmingCharacters(in: .whitespaces).lowercased()
        if let ш = числоПоля("width"), let п = числоПоля("profile"), let д = числоПоля("diameter") {
            let размер = РазмерШиныАвтоподбора(ширина: ш, профиль: п, диаметр: д)
            if размер.годный && !шины.contains(размер) { шины.append(размер) }
        }
        if сезон == nil, let сырое = поля["season"] { сезон = Self.сезонПоля(сырое) }
        /* Диск — у вида wheel или когда вид не назван и полей шины нет («diameter» шины — посадка, не диск). */
        guard видПолей == "wheel" || (видПолей.isEmpty && поля["profile"] == nil) else { return видПолей }
        if let д = числоПоля("diameter"), РазмерШиныАвтоподбора.диаметры.contains(д) { диск.диаметр = д }
        if let j = числоПоля("width_j"), (3.5...13).contains(j) { диск.ширина = j }
        if let сырое = поля["pcd"] {
            let найдено: [РазболтовкаАвтоподбора] = П.разболтовки(П.pcdИзЗначения(П.нормально(сырое)))
            for болты in найдено where !диск.разболтовки.contains(where: { $0.совпадает(болты) }) {
                диск.разболтовки.append(болты)
            }
        }
        if let сырое = поля["et"], let et = П.числоСоЗнаком(П.нормально(сырое)), (-65...80).contains(et) { диск.et = et }
        if let dia = числоПоля("dia"), (50...175).contains(dia) { диск.dia = dia }
        return видПолей
    }

    /// Сезон из parts.season: ключ семьи tyre_season («winter_studded») или подпись варианта мастера («Зимние»).
    static func сезонПоля(_ значение: String) -> СезонАвтоподбора? {
        let ключ: String = значение.trimmingCharacters(in: .whitespacesAndNewlines).lowercased()
        switch ключ {
        case "summer": return .лето
        case "winter_studded", "studded": return .зимаШипы
        case "winter_friction", "friction", "studless": return .зимаЛипучка
        case "winter": return .зима
        case "all_season", "all-season", "allseason": return .всесезон
        default: return ПарсерАвтоподбора.сезон(ПарсерАвтоподбора.нормально(значение))
        }
    }

    /// Дополнить пустые поля образцами из текста (уже нормального, ПарсерАвтоподбора.нормально).
    mutating func дополнить(_ текст: String) {
        typealias П = ПарсерАвтоподбора
        guard !текст.isEmpty else { return }
        if шины.isEmpty { шины = Array(П.размерыШин(текст).prefix(2)) }
        if диск.разболтовки.isEmpty { диск.разболтовки = П.разболтовки(текст) }
        if диск.et == nil { диск.et = П.вылет(текст) }
        if диск.dia == nil { диск.dia = П.отверстие(текст) }
        if диск.ширина == nil { диск.ширина = П.ширинаОбода(текст) }
        if диск.диаметр == nil { диск.диаметр = П.диаметрОбода(текст) }
        if сезон == nil { сезон = П.сезон(текст) }
    }
}

// MARK: - Образцы

/// Разбор строк: нормальная запись, образцы шин и дисков, числа. Без состояния — можно звать откуда угодно.
enum ПарсерАвтоподбора {
    enum ВидКлючаАвтоподбора {
        case pcd, dia, et, отверстия, профиль, ширина, диаметр, сезон, марка, модель, годС, годПо, прочее
    }

    /**
     Нормальная запись: строчные буквы, «ё» → «е», знаки умножения и русская «х» → латинская «x», дюймы — одной кавычкой,
     запятая между цифрами → точка («114,3» → «114.3»; «5x100,5x112» — не трогаем: после запятой идёт разболтовка).
     */
    static func нормально(_ строка: String) -> String {
        var т = строка.lowercased()
        let замены: [(String, String)] = [("ё", "е"), ("×", "x"), ("х", "x"), ("*", "x"), ("\u{00A0}", " "),
                                          ("\u{202F}", " "), ("″", "\""), ("”", "\""), ("“", "\""), ("''", "\""),
                                          ("−", "-"), ("–", "-"), ("—", "-")]
        for (было, стало) in замены { т = т.replacingOccurrences(of: было, with: стало) }
        т = т.replacingOccurrences(of: #"(\d),(\d{1,2})(?![0-9x])"#, with: "$1.$2", options: .regularExpression)
        return т
    }

    /// Все совпадения образца: [вся строка, группа 1, группа 2…]; не совпавшая группа — пустая строка.
    static func группы(_ образец: String, _ текст: String) -> [[String]] {
        guard let выражение = try? NSRegularExpression(pattern: образец, options: []) else { return [] }
        let весь = NSRange(текст.startIndex..<текст.endIndex, in: текст)
        return выражение.matches(in: текст, options: [], range: весь).map { совпадение in
            (0..<совпадение.numberOfRanges).map { номер in
                let место = совпадение.range(at: номер)
                guard место.location != NSNotFound, let диапазон = Range(место, in: текст) else { return "" }
                return String(текст[диапазон])
            }
        }
    }

    /// «114.3» → 114.3; «+45» → 45; пусто или не число — nil.
    static func число(_ строка: String?) -> Double? {
        guard var с = строка?.trimmingCharacters(in: .whitespaces), !с.isEmpty else { return nil }
        if с.hasPrefix("+") { с.removeFirst() }
        guard let значение = Double(с.replacingOccurrences(of: ",", with: ".")), значение.isFinite else { return nil }
        return значение
    }

    /// Первое число строки без знака: «67.1 мм» → 67.1.
    static func первоеЧисло(_ строка: String) -> Double? {
        guard let место = строка.range(of: #"\d+(?:\.\d+)?"#, options: .regularExpression) else { return nil }
        return число(String(строка[место]))
    }

    /// Первое число со знаком: «-10» → −10, «+35» → 35.
    static func числоСоЗнаком(_ строка: String) -> Double? {
        guard let место = строка.range(of: #"[+-]?\s?\d+(?:\.\d+)?"#, options: .regularExpression) else { return nil }
        return число(String(строка[место]).replacingOccurrences(of: " ", with: ""))
    }

    /// Число, которое набрал человек: «67,1» → 67.1.
    static func числоВвода(_ строка: String) -> Double? {
        числоСоЗнаком(нормально(строка))
    }

    /// Вылет из ввода: «45» → 45…45, «35-45» или «35…45» → 35…45, «-5» → −5…−5.
    static func вылетВвода(_ строка: String) -> ClosedRange<Double>? {
        let текст = нормально(строка).replacingOccurrences(of: "…", with: "..")
        let образец = #"([+-]?\d{1,3}(?:\.\d)?)\s{0,2}(?:-|\.\.|/|до|to)\s{0,2}([+-]?\d{1,3}(?:\.\d)?)"#
        if let г = группы(образец, текст).first, г.count == 3, let а = число(г[1]), let б = число(г[2]) {
            let низ = min(а, б)
            let верх = max(а, б)
            guard (-65...80).contains(низ), (-65...80).contains(верх) else { return nil }
            return низ...верх
        }
        guard let одно = числоСоЗнаком(текст), (-65...80).contains(одно) else { return nil }
        return одно...одно
    }

    /// Есть ли в тексте хоть одно из слов (подстрокой). Текст уже нормальный — слова приводим так же: русская «х» в
    /// нормальной записи стала латинской, иначе «подходит» и «на дисках» не совпали бы никогда.
    static func естьСлова(_ текст: String, _ слова: [String]) -> Bool {
        слова.contains { текст.contains(нормально($0)) }
    }

    /// Целое слово латиницей или кириллицей: «dia» в «ступица (dia)», но не в «diameter».
    private static func слово(_ ключ: String, _ слово: String) -> Bool {
        ключ.range(of: "(^|[^a-zа-я])" + слово + "([^a-zа-я]|$)", options: .regularExpression) != nil
    }

    /// О чём пункт характеристик — по корням слов (ru, kk, en). Порядок важен: «центральное отверстие» — это DIA, а не
    /// число отверстий; «Diameter» — диаметр, а не DIA.
    static func видКлюча(_ ключ: String) -> ВидКлючаАвтоподбора {
        /* Ключи полей подачи (tyre_* · rim_*, Posting/PostingSizeWheels.swift) — если сервер отдаст их как есть. */
        switch ключ.trimmingCharacters(in: .whitespacesAndNewlines) {
        case "tyre_w", "rim_j": return .ширина
        case "tyre_h": return .профиль
        case "tyre_r", "rim_r": return .диаметр
        case "rim_et": return .et
        case "rim_pcd": return .pcd
        case "rim_dia": return .dia
        default: break
        }
        if естьСлова(ключ, ["pcd", "разболтов", "сверловк", "расположени", "bolt pattern", "болттар"]) { return .pcd }
        if слово(ключ, "dia") || слово(ключ, "цо") || естьСлова(ключ, ["ступиц", "центральн", "центровочн", "hub", "bore"]) {
            return .dia
        }
        if слово(ключ, "et") || слово(ключ, "ет") || естьСлова(ключ, ["вылет", "offset", "шығыңқы"]) { return .et }
        if естьСлова(ключ, ["отверсти", "болтов", "holes", "lug", "тесік"]) { return .отверстия }
        if естьСлова(ключ, ["профил", "profile", "высот", "биіктіг", "aspect"]) { return .профиль }
        if естьСлова(ключ, ["ширин", "width", "ені"]) { return .ширина }
        if естьСлова(ключ, ["диаметр", "diameter", "радиус", "посадочн", "rim size", "диаметрі"]) || ключ == "r" {
            return .диаметр
        }
        if естьСлова(ключ, ["сезон", "season", "маусым"]) { return .сезон }
        if естьСлова(ключ, ["подходит", "fits", "fit to", "сәйкес", "для марки", "марка авто", "арналған"]) { return .марка }
        let чистый = ключ.trimmingCharacters(in: .whitespacesAndNewlines)
        if ["модель", "model", "үлгі", "модели", "модель авто"].contains(чистый) { return .модель }
        if (чистый.hasPrefix("год") && чистый.contains(" с")) || естьСлова(чистый, ["years from", "year from", "жылдан"]) {
            return .годС
        }
        if ["по", "to", "until", "дейін"].contains(чистый) { return .годПо }
        return .прочее
    }

    /// Значение пункта «Разболтовка»: «5/114.3» и «5-114.3» там тоже значат разболтовку.
    static func pcdИзЗначения(_ текст: String) -> String {
        текст.replacingOccurrences(of: #"(?<![0-9.])([3-9]|10)\s{0,2}[/-]\s{0,2}(\d{2,3})"#, with: "$1x$2",
                                   options: .regularExpression)
    }

    /// Размеры шин: «225/45 r17», «225/45/17», «225/45zr17», «225/45-17», «225/45 р17».
    static func размерыШин(_ текст: String) -> [РазмерШиныАвтоподбора] {
        let образец = #"(?<![0-9.])(1[2-9][05]|2[0-9][05]|3[0-5][05])\s{0,3}/\s{0,3}([2-9][05])\s{0,3}[/-]?\s{0,3}(?:z?[rр])?\s{0,3}(1[2-9]|2[0-6])(\.5)?(?![0-9])"#
        var итог: [РазмерШиныАвтоподбора] = []
        for г in группы(образец, текст) where г.count >= 4 {
            guard let ш = число(г[1]), let п = число(г[2]), var д = число(г[3]) else { continue }
            if г.count > 4, !г[4].isEmpty { д += 0.5 }
            let размер = РазмерШиныАвтоподбора(ширина: ш, профиль: п, диаметр: д)
            if размер.годный && !итог.contains(размер) { итог.append(размер) }
        }
        return итог
    }

    /// Разболтовки: «5x114.3», «pcd 5x112», мультиразболтовка «5x100/114.3» и «5x100/5x112». Число штук перед
    /// размером шины — не разболтовка: в «4x205/55 r16» после «205» идёт остаток размера «/55 r16» — такое пропускаем
    /// (а «5x108/65.1» с DIA после косой — разболтовка).
    static func разболтовки(_ текст: String) -> [РазболтовкаАвтоподбора] {
        let образец = #"(?<![0-9.])([3-9]|10)\s{0,2}x\s{0,2}(\d{2,3}(?:\.\d{1,2})?)(?![0-9])(?!\s{0,3}/\s{0,3}[2-9][05]\s{0,3}[/-]?\s{0,3}(?:z?[rр])?\s{0,3}(?:1[2-9]|2[0-6])(?![0-9]))((?:\s{0,2}/\s{0,2}(?:(?:[3-9]|10)\s{0,2}x\s{0,2})?\d{2,3}(?:\.\d{1,2})?(?![0-9]))*)"#
        var итог: [РазболтовкаАвтоподбора] = []
        func добавить(_ отверстий: Int, _ pcd: Double) {
            guard РазболтовкаАвтоподбора.годная(отверстий: отверстий, pcd: pcd) else { return }
            let новая = РазболтовкаАвтоподбора(отверстий: отверстий, pcd: pcd)
            if !итог.contains(where: { $0.совпадает(новая) }) { итог.append(новая) }
        }
        for г in группы(образец, текст) where г.count >= 3 {
            guard let о = число(г[1]), let p = число(г[2]) else { continue }
            добавить(Int(о), p)
            guard г.count > 3, !г[3].isEmpty else { continue }
            /* Хвост мультиразболтовки: «/114.3» — с тем же числом отверстий, «/4x108» — со своим. */
            for часть in г[3].split(separator: "/") {
                let кусок = String(часть).trimmingCharacters(in: .whitespaces)
                let пары = кусок.split(separator: "x").map { String($0).trimmingCharacters(in: .whitespaces) }
                if пары.count == 2, let о2 = число(пары[0]), let p2 = число(пары[1]) {
                    добавить(Int(о2), p2)
                } else if let p2 = число(кусок) {
                    добавить(Int(о), p2)
                }
            }
        }
        return итог
    }

    /// Вылет: «et45», «ет 35», «et-10», «вылет (et) 45», «offset 40».
    static func вылет(_ текст: String) -> Double? {
        let образцы = [
            #"(?<![a-zа-я])(?:et|ет)\s{0,2}[:=]?\s{0,2}([+-]?\d{1,3}(?:\.\d)?)(?![0-9])"#,
            #"(?:вылет|offset|шығыңқылық)[^0-9+-]{0,12}([+-]?\d{1,3}(?:\.\d)?)(?![0-9])"#
        ]
        for образец in образцы {
            for г in группы(образец, текст) where г.count == 2 {
                if let ч = число(г[1]), (-65...80).contains(ч) { return ч }
            }
        }
        return nil
    }

    /// Центральное отверстие: «dia 67.1», «цо 60.1», «d67.1», «ступица 66.6», «центральное отверстие 57.1».
    static func отверстие(_ текст: String) -> Double? {
        let образцы = [
            #"(?<![a-zа-я])(?:dia|цо|ц\.о\.|cb|d(?=\d))\s{0,2}[:=]?\s{0,2}(\d{2,3}(?:\.\d{1,2})?)(?![0-9])"#,
            #"(?:ступиц|центральн|центровочн|hub|bore)[^0-9]{0,24}(\d{2,3}(?:\.\d{1,2})?)(?![0-9])"#
        ]
        for образец in образцы {
            for г in группы(образец, текст) where г.count == 2 {
                if let ч = число(г[1]), (50...175).contains(ч) { return ч }
            }
        }
        return nil
    }

    /// Посадочный диаметр диска: «r17», «r22.5», «17"», «17 дюймов», «17x7.5», «7.5x17». Вторая группа — «.5»
    /// (грузовые 17.5, 19.5, 22.5).
    static func диаметрОбода(_ текст: String) -> Double? {
        let образцы = [
            #"(?<![a-zа-я0-9])z?[rр]\s{0,2}(1[2-9]|2[0-6])(\.5)?(?![0-9])"#,
            #"(?<![0-9.])(1[2-9]|2[0-6])(\.5)?\s{0,2}(?:"|дюйм|inch)"#,
            #"(?<![0-9.a-zа-я])(1[2-9]|2[0-6])\s{0,2}x\s{0,2}(?:[4-9]|1[0-3])(?:\.[05])?\s{0,2}j?(?![0-9])"#,
            #"(?<![0-9.])(?:(?:[4-9]|1[0-3])\.[05]|(?:[4-9]|1[0-3])(?:\.[05])?\s?j)\s{0,2}x\s{0,2}(1[2-9]|2[0-6])(?![0-9.])"#
        ]
        for образец in образцы {
            for г in группы(образец, текст) where г.count >= 2 {
                guard var ч = число(г[1]) else { continue }
                if г.count > 2, !г[2].isEmpty { ч += 0.5 }
                if РазмерШиныАвтоподбора.диаметры.contains(ч) { return ч }
            }
        }
        return nil
    }

    /// Ширина обода: «7.5j», «7j», «17x7.5», «7.5x17».
    static func ширинаОбода(_ текст: String) -> Double? {
        let образцы = [
            #"(?<![0-9.])((?:[4-9]|1[0-3])(?:\.[05])?)\s?j(?![a-wyz])"#,
            #"(?<![0-9.a-zа-я])(?:1[2-9]|2[0-6])\s{0,2}x\s{0,2}((?:[4-9]|1[0-3])(?:\.[05])?)\s{0,2}j?(?![0-9])"#,
            #"(?<![0-9.])((?:[4-9]|1[0-3])\.[05])\s{0,2}x\s{0,2}(?:1[2-9]|2[0-6])(?![0-9.])"#
        ]
        for образец in образцы {
            for г in группы(образец, текст) where г.count == 2 {
                if let ч = число(г[1]), (3.5...13).contains(ч) { return ч }
            }
        }
        return nil
    }

    /// Сезон по словам. «Нешипованные» — раньше «шипованных»: в нём то же слово.
    static func сезон(_ текст: String) -> СезонАвтоподбора? {
        if естьСлова(текст, ["нешип", "липучк", "фрикцион", "friction", "studless", "non-studded", "шипсіз"]) {
            return .зимаЛипучка
        }
        if естьСлова(текст, ["шипован", "шипы", "шипами", "studded", "шипті"]) { return .зимаШипы }
        if естьСлова(текст, ["всесезон", "all season", "all-season", "allseason", "барлық маусым"]) { return .всесезон }
        if естьСлова(текст, ["зимн", "winter", "қысқы"]) { return .зима }
        if естьСлова(текст, ["летн", "summer", "жазғы"]) { return .лето }
        return nil
    }
}

// MARK: - Числа

/// Запись чисел в окне: точка, без лишних нулей («114.3», «17», «7.5»); знак — «+» и «−».
enum ЧислаАвтоподбора {
    static func ч(_ x: Double, знаков: Int = 1) -> String {
        guard x.isFinite else { return "—" }
        let множитель = pow(10, Double(max(0, знаков)))
        let округлённое = (x * множитель).rounded() / множитель
        if округлённое == округлённое.rounded() { return String(Int(округлённое)) }
        var строка = String(format: "%." + String(max(0, знаков)) + "f", locale: Locale(identifier: "en_US_POSIX"),
                            округлённое)
        while строка.hasSuffix("0") { строка.removeLast() }
        if строка.hasSuffix(".") { строка.removeLast() }
        return строка
    }

    /// «+1.2», «−0.8», «0».
    static func соЗнаком(_ x: Double, знаков: Int = 1) -> String {
        let строка = ч(abs(x), знаков: знаков)
        if строка == "0" { return "0" }
        return (x > 0 ? "+" : "−") + строка
    }
}

/// Размер шины: ширина (мм), профиль (высота боковины в % от ширины), посадочный диаметр (дюймы).
struct РазмерШиныАвтоподбора: Hashable, Codable, Sendable {
    var ширина: Double
    var профиль: Double
    var диаметр: Double

    init(ширина: Double, профиль: Double, диаметр: Double) {
        self.ширина = ширина
        self.профиль = профиль
        self.диаметр = диаметр
    }

    static let ширины: ClosedRange<Double> = 125...355
    static let профили: ClosedRange<Double> = 25...95
    static let диаметры: ClosedRange<Double> = 12...26

    /// Все три числа правдоподобны.
    var годный: Bool {
        Self.ширины.contains(ширина) && Self.профили.contains(профиль) && Self.диаметры.contains(диаметр)
    }

    /// Высота боковины, мм.
    var боковина: Double { ширина * профиль / 100 }

    /// Внешний диаметр колеса, мм: обод и две боковины.
    var внешний: Double { диаметр * 25.4 + 2 * боковина }

    /// «225/45 R17».
    var подпись: String {
        ЧислаАвтоподбора.ч(ширина) + "/" + ЧислаАвтоподбора.ч(профиль) + " R" + ЧислаАвтоподбора.ч(диаметр)
    }

    /// Размер из того, что набрал человек: «205/55 R16», «205/55/16», «205 55 16». nil — не похоже на размер.
    static func изВвода(_ строка: String) -> РазмерШиныАвтоподбора? {
        let текст = ПарсерАвтоподбора.нормально(строка)
        if let первый = ПарсерАвтоподбора.размерыШин(текст).first { return первый }
        let образец = #"(?<![0-9.])(\d{3})\D{1,4}(\d{2})\D{0,4}(\d{2}(?:\.5)?)(?![0-9])"#
        guard let г = ПарсерАвтоподбора.группы(образец, текст).first, г.count == 4,
              let ш = ПарсерАвтоподбора.число(г[1]), let п = ПарсерАвтоподбора.число(г[2]),
              let д = ПарсерАвтоподбора.число(г[3]) else { return nil }
        let размер = РазмерШиныАвтоподбора(ширина: ш, профиль: п, диаметр: д)
        return размер.годный ? размер : nil
    }
}


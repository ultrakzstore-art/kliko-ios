    // MARK: Коробка

    /// Поставить коробку (или переставить) туда, куда смотрит точка экрана.
    private func поставить(в точка: CGPoint) {
        guard габариты != nil else { return }
        if наСтоле {
            поставитьНаСтол(точка)
            return
        }
        if let корпус {
            guard let место = точкаНаПолу(точка) ?? точкаНаПлоскости(точка, высота: корпус.position.y) else {
                показать(т("fb_no_floor"))
                return
            }
            /* Касание по самой коробке — не перестановка. */
            let местная = корпус.convert(position: место, from: nil)
            if let г = габариты, abs(местная.x) < вСцене(г).x / 2, abs(местная.z) < вСцене(г).z / 2 { return }
            if прижато {
                прижато = false
                стенаПрижатия = nil
            }
            передвинуть(в: место)
            return
        }
        guard let место = точкаНаПолу(точка) else {
            показать(т("fb_no_floor"))
            return
        }
        построить(на: место)
    }

    /**
     Настольная вещь: ещё не стоит — в рамку прицела (центр экрана); там пусто, далеко или пол, а под пальцем стол
     рядом — в точку касания. Стоит — касание в стороне переставляет туда (и на другой стол). Дальше 1,8 м от камеры не
     ставим — «Подойдите ближе к столу»: иначе вещь встаёт крошкой где-то на полу. Похоже на пол — только вторым
     касанием за 2 с (осознанно), и при перестановке тоже.
     */
    private func поставитьНаСтол(_ точка: CGPoint) {
        guard let вид, let габариты else { return }
        let глаз = вид.cameraTransform.translation
        let центр = CGPoint(x: вид.bounds.midX, y: вид.bounds.midY)
        let попадания = (корпус == nil ? [центр, точка] : [точка]).compactMap { попаданиеСтола($0) }
        func рядом(_ п: ПопаданиеГабаритов) -> Bool { simd_distance(глаз, п.точка) <= Self.ближеСтола }
        let лучшее = попадания.first(where: { рядом($0) && $0.какСтол })
            ?? попадания.first(where: { рядом($0) }) ?? попадания.first
        guard let попадание = лучшее else {
            показать(т("fb_no_floor"))
            return
        }
        /* Касание по самой вещи — не перестановка (и не «ближе» и не «это пол»). */
        if let корпус {
            let местная = корпус.convert(position: попадание.точка, from: nil)
            let р = вСцене(габариты)
            if abs(местная.x) < р.x / 2, abs(местная.z) < р.z / 2 { return }
        }
        guard рядом(попадание) else {
            /* Пилюля прицела уже говорит «Подойдите ближе к столу» — на экране второй раз не повторяем, только
               голосом. */
            if прицел == .далеко {
                UIAccessibility.post(notification: .announcement, argument: ГабаритыText.т("fb_closer_desk"))
            } else {
                показать(ГабаритыText.т("fb_closer_desk"))
            }
            return
        }
        if !попадание.какСтол {
            let сейчас = CACurrentMediaTime()
            guard let прежнее = касаниеПола, сейчас - прежнее <= Self.второеКасание else {
                касаниеПола = сейчас
                показать(ГабаритыText.т("fb_desk_floor_again"))
                return
            }
        }
        касаниеПола = nil
        guard корпус != nil else {
            построить(на: попадание.точка)
            return
        }
        передвинуть(в: попадание.точка)
    }

    /// «Поставить на стол заново»: вещь снять (без «Вещь убрана» и без отклика — его даёт кнопка), прицел снова на
    /// поверхности — касание или полторы секунды на месте.
    func поставитьЗаново() {
        guard наСтоле, корпус != nil else { return }
        снятьКорпус()
        автоМожно = true
        касаниеПола = nil
        UIAccessibility.post(notification: .announcement, argument: ГабаритыText.т("fb_desk_again"))
    }

    func поставитьВЦентр() {
        guard let вид else { return }
        поставить(в: CGPoint(x: вид.bounds.midX, y: вид.bounds.midY))
    }

    /// Повернуть на 15° (VoiceOver).
    func повернуть(влево: Bool) {
        guard let корпус else { return }
        отпуститьСтену()
        угол += (влево ? 1 : -1) * Float.pi / 12
        корпус.orientation = simd_quatf(angle: угол, axis: SIMD3<Float>(0, 1, 0))
    }

    func убрать() {
        guard корпус != nil else { return }
        снятьКорпус()
        /* Убрали сами — сама вещь больше не встанет (только касанием или «Поставить на стол заново»). */
        автоМожно = false
        ОткликСайта.выбор()
        UIAccessibility.post(notification: .announcement, argument: т("fb_removed"))
    }

    /// Корпус со сцены долой: подписи гаснут, этап — снова «можно ставить» (или «ищем пол»). Без отклика и озвучки — их
    /// даёт тот, кто зовёт.
    private func снятьКорпус() {
        guard let корпус else { return }
        корпус.removeFromParent()
        self.корпус = nil
        рост = nil
        ростВещи = nil
        прижато = false
        стенаПрижатия = nil
        показатьПодписи(false)
        этап = полы.isEmpty ? .ищемПол : .можноСтавить
        началоУверенности = nil
    }

    private func построить(на место: SIMD3<Float>) {
        guard let корень, let габариты else { return }
        let корпус = Entity()
        корпус.position = место
        угол = уголКамере(место)
        корпус.orientation = simd_quatf(angle: угол, axis: SIMD3<Float>(0, 1, 0))
        let рост = КоробкаГабаритов.собрать(габариты.метры)
        корпус.addChild(рост)
        let ростВещи = вещь.собрать(габариты)
        if let ростВещи { корпус.addChild(ростВещи) }
        корень.addChild(корпус)
        self.корпус = корпус
        self.рост = рост
        self.ростВещи = ростВещи
        автоМожно = false
        началоУверенности = nil
        рамкаПрицела?.isEnabled = false
        обновитьКорпус()
        этап = .стоит
        вырастить(видимыйРост ?? рост)
        UIImpactFeedbackGenerator(style: .medium).impactOccurred()
        /* На столе — «Так будет на вашем столе — размер настоящий» и на экране, а не только для VoiceOver. */
        if наСтоле {
            показать(т("fb_placed_done"))
        } else {
            UIAccessibility.post(notification: .announcement, argument: т("fb_placed_done"))
        }
    }

    /// Размеры сменились — коробка и вещь новые, на том же месте и с тем же поворотом.
    private func перестроить() {
        guard let корпус, let габариты else { return }
        рост?.removeFromParent()
        let новый = КоробкаГабаритов.собрать(габариты.метры)
        корпус.addChild(новый)
        рост = новый
        ростВещи?.removeFromParent()
        ростВещи = вещь.собрать(габариты)
        if let ростВещи { корпус.addChild(ростВещи) }
        обновитьКорпус()
        обновитьТекстыПодписей()
        if прижато, let ид = стенаПрижатия, let стена = стены[ид] {
            прижать(к: стена, плавно: false)
        }
        вырастить(видимыйРост ?? новый)
    }

    // MARK: Вещь

    /// Что видно в корпусе: в «Вещи» — вещь, а пока её нет — коробка; в «Коробке» — коробка; в линейке — ничего.
    private func обновитьКорпус() {
        корпус?.isEnabled = режим != .линейка
        let вещьВидна = режим == .вещь && ростВещи != nil
        ростВещи?.isEnabled = вещьВидна
        рост?.isEnabled = !вещьВидна
        /* Телефон или планшет лежит (или ноутбук, записанный Ш×Г×В), коробка стоит — подписи рёбер меняются местами. */
        обновитьТекстыПодписей()
    }

    /// Видна (или встанет) 3D-форма телефона или планшета экраном вверх, или ноутбука, записанного Ш×Г×В: в сцене высота
    /// из объявления — вглубь, толщина — вверх (ФормаВещиГабаритов.переставлена).
    private var лёжа: Bool {
        guard режим == .вещь, корпус == nil || ростВещи != nil else { return false }
        return вещь.лёжа(габариты)
    }

    /// Размеры того, что видно в корпусе (или встанет), в метрах сцены: x — вдоль лица, y — вверх, z — вглубь.
    private func вСцене(_ г: ГабаритыВещи) -> SIMD3<Float> {
        let р = г.метры
        return лёжа ? SIMD3<Float>(р.x, р.z, р.y) : р
    }

    /// Видимая часть корпуса — её «выращивать».
    private var видимыйРост: Entity? {
        режим == .вещь ? (ростВещи ?? рост) : рост
    }

    /// Вещь готова (3D-модель или фото) или не вышла: корпус уже стоит — положить её туда (не вышла — остаётся коробка).
    private func вещьГотова() {
        guard let корпус, let габариты else { return }
        ростВещи?.removeFromParent()
        ростВещи = вещь.собрать(габариты)
        if let ростВещи { корпус.addChild(ростВещи) }
        обновитьКорпус()
        if режим == .вещь, let ростВещи { вырастить(ростВещи) }
    }

    private func передвинуть(в место: SIMD3<Float>) {
        guard let корпус else { return }
        var цель = корпус.transform
        цель.translation = место
        if тихо {
            корпус.transform = цель
        } else {
            _ = корпус.move(to: цель, relativeTo: корпус.parent, duration: 0.25, timingFunction: .easeInOut)
        }
    }

    /// «Вырастание» снизу вверх: масштаб по высоте от 2 % до 100 %; подписи — когда выросла.
    private func вырастить(_ рост: Entity) {
        показатьПодписи(false)
        задачаПодписей?.cancel()
        if тихо {
            рост.scale = SIMD3<Float>(1, 1, 1)
            показатьПодписи(true)
            return
        }
        рост.scale = SIMD3<Float>(1, 0.02, 1)
        var цель = рост.transform
        цель.scale = SIMD3<Float>(1, 1, 1)
        _ = рост.move(to: цель, relativeTo: рост.parent, duration: 0.55, timingFunction: .easeOut)
        задачаПодписей = Task { @MainActor [weak self] in
            try? await Task.sleep(nanoseconds: 520_000_000)
            guard !Task.isCancelled else { return }
            self?.показатьПодписи(true)
        }
    }

    /// Угол поворота вокруг вертикали, при котором лицо коробки (+z) смотрит на камеру.
    private func уголКамере(_ место: SIMD3<Float>) -> Float {
        guard let вид else { return 0 }
        let камера = вид.cameraTransform.translation
        let dx = камера.x - место.x
        let dz = камера.z - место.z
        guard abs(dx) + abs(dz) > 0.0001 else { return 0 }
        return atan2(dx, dz)
    }

    // MARK: Пол и луч

    /// Точка на горизонтальной плоскости ARKit (пол, стол) под точкой экрана.
    private func точкаНаПолу(_ точка: CGPoint) -> SIMD3<Float>? {
        #if targetEnvironment(simulator)
        return nil
        #else
        guard let вид else { return nil }
        let попадание = вид.raycast(from: точка, allowing: .existingPlaneGeometry, alignment: .horizontal).first
            ?? вид.raycast(from: точка, allowing: .estimatedPlane, alignment: .horizontal).first
        guard let попадание else { return nil }
        let столбец = попадание.worldTransform.columns.3
        return SIMD3<Float>(столбец.x, столбец.y, столбец.z)
        #endif
    }

    /**
     Настольная вещь: что под точкой экрана. Луч — по найденным плоскостям ARKit и по прикидке, только горизонтали;
     прикидка ближе найденной плоскости больше чем на 5 см — между камерой и ней что-то стоит (стол над найденным
     полом): берём прикидку, поверхность выше пола главнее. Потолок и всё выше камеры — мимо. Точно стол (вещь встанет
     сама): ARKit узнал стол; или не узнал пол, а поверхность выше самой низкой горизонтали на 30 см. Похоже на стол (для
     касания и зелёной рамки): точно стол; или пол не узнан, ниже горизонталей нет, а камера выше меньше чем на метр —
     сидя так выглядит и пол, поэтому сама вещь туда не встаёт.
     */
    private func попаданиеСтола(_ точка: CGPoint) -> ПопаданиеГабаритов? {
        #if targetEnvironment(simulator)
        return nil
        #else
        guard let вид else { return nil }
        let глаз = вид.cameraTransform.translation
        func место(_ попадание: ARRaycastResult) -> SIMD3<Float> {
            let столбец = попадание.worldTransform.columns.3
            return SIMD3<Float>(столбец.x, столбец.y, столбец.z)
        }
        func годно(_ попадание: ARRaycastResult) -> Bool { место(попадание).y < глаз.y - 0.1 }
        let точное = вид.raycast(from: точка, allowing: .existingPlaneGeometry, alignment: .horizontal)
            .first(where: годно)
        let прикидка = вид.raycast(from: точка, allowing: .estimatedPlane, alignment: .horizontal)
            .first(where: годно)
        var лучшее = точное ?? прикидка
        if let точное, let прикидка,
           simd_distance(место(прикидка), глаз) < simd_distance(место(точное), глаз) - 0.05 {
            лучшее = прикидка
        }
        guard let выбор = лучшее else { return nil }
        let итог = место(выбор)
        var стол = false
        var пол = false
        if ARPlaneAnchor.isClassificationSupported, let плоскость = выбор.anchor as? ARPlaneAnchor {
            switch плоскость.classification {
            case .table: стол = true
            case .floor: пол = true
            default: break
            }
        }
        let надПолом = горизонтали.values.min().map { итог.y - $0 > 0.3 } ?? false
        let точноСтол = !пол && (стол || надПолом)
        let какСтол = точноСтол || (!пол && глаз.y - итог.y < 1.0)
        return ПопаданиеГабаритов(точка: итог, уверенно: выбор.target == .existingPlaneGeometry, какСтол: какСтол,
                                  точноСтол: точноСтол)
        #endif
    }

    /// Луч из точки экрана до горизонтали на высоте `высота` — сдвиг пальцем по тому же полу, без запросов ARKit.
    private func точкаНаПлоскости(_ точка: CGPoint, высота: Float) -> SIMD3<Float>? {
        guard let вид, let луч = вид.ray(through: точка) else { return nil }
        let н = луч.direction
        guard н.y < -0.0001 else { return nil }
        let путь = (высота - луч.origin.y) / н.y
        guard путь > 0, путь < 20 else { return nil }
        return луч.origin + н * путь
    }

    // MARK: Прицел (настольная вещь)

    /// Рамка прицела: четыре тонких бруска единичной длины (длину даёт масштаб) и точка в центре; спрятана, пока не
    /// нужна.
    private func собратьПрицел(в корень: AnchorEntity) {
        let рамка = Entity()
        рамка.isEnabled = false
        let материал = Self.материалПрицела(false)
        let поперёк = MeshResource.generateBox(width: 1, height: 0.002, depth: 0.006)
        let вглубь = MeshResource.generateBox(width: 0.006, height: 0.002, depth: 1)
        var части: [ModelEntity] = []
        for сетка in [поперёк, поперёк, вглубь, вглубь] {
            let брусок = ModelEntity(mesh: сетка, materials: [материал])
            рамка.addChild(брусок)
            части.append(брусок)
        }
        /* Скругление — 45 % стороны, как у брусков формы (FitBoxItemShape.swift): ровно половина — на краю сетки. */
        let точка = ModelEntity(mesh: .generatePlane(width: 0.024, depth: 0.024, cornerRadius: 0.024 * 0.45),
                                materials: [материал])
        точка.position = SIMD3<Float>(0, 0.001, 0)
        рамка.addChild(точка)
        части.append(точка)
        корень.addChild(рамка)
        рамкаПрицела = рамка
        частиПрицела = части
        размерРамки = SIMD2<Float>(0, 0)
        рамкаЗелёная = false
    }

    /// Белая полупрозрачная — прикидка, далеко или пол; зелёная — найденная плоскость рядом, похожая на стол.
    private static func материалПрицела(_ зелёная: Bool) -> UnlitMaterial {
        var м = UnlitMaterial(color: зелёная ? КоробкаГабаритов.зелёный : .white)
        м.blending = .transparent(opacity: .init(floatLiteral: зелёная ? 0.95 : 0.6))
        return м
    }

    /**
     Каждый кадр (луч ARKit — через кадр): рамка основания вещи в настоящий размер на поверхности под центром экрана,
     лицом к человеку. Точный стол (найденная плоскость, ARKit узнал стол или ниже есть пол) рядом полторы секунды почти
     на одном месте (сдвиг меньше 15 см) — вещь встаёт сама; пока открыт лист размеров — нет.
     */
    private func обновитьПрицел() {
        guard let рамка = рамкаПрицела else { return }
        let ждёт = режим != .линейка && корпус == nil && габариты != nil
        guard ждёт, идёт, камера == .идёт, слежение == .норма, let вид, вид.bounds.width > 0, let габариты else {
            спрятатьПрицел(рамка, ждёт ? .ищет : .нет)
            return
        }
        кадрПрицела &+= 1
        guard кадрПрицела % 2 == 0 else { return }
        guard let попадание = попаданиеСтола(CGPoint(x: вид.bounds.midX, y: вид.bounds.midY)) else {
            спрятатьПрицел(рамка, .ищет)
            return
        }
        let цель = попадание.точка
        var место = цель
        if рамка.isEnabled, let прежняя = точкаПрицела, simd_distance(прежняя, цель) < 0.25 {
            место = прежняя + (цель - прежняя) * 0.5
        }
        точкаПрицела = место
        /* Порог «далеко» с запасом 10 см на обратный путь — подсказка не мигает на границе. */
        let до = simd_distance(вид.cameraTransform.translation, цель)
        let далеко = до > (прицел == .далеко ? Self.ближеСтола - 0.1 : Self.ближеСтола)
        let р = вСцене(габариты)
        задатьРамку(SIMD2<Float>(р.x, р.z))
        перекраситьРамку(попадание.уверенно && попадание.какСтол && !далеко)
        рамка.position = место + SIMD3<Float>(0, 0.002, 0)
        рамка.orientation = simd_quatf(angle: уголКамере(место), axis: SIMD3<Float>(0, 1, 0))
        if !рамка.isEnabled { рамка.isEnabled = true }

        /* Пол — главнее «далеко»: подходить ближе к полу незачем. */
        var новое: ПрицелГабаритов = !попадание.какСтол ? .пол : (далеко ? .далеко : .есть)
        if автоМожно && !листРазмеров && !далеко && попадание.уверенно && попадание.точноСтол {
            let сейчас = CACurrentMediaTime()
            if let начало = началоУверенности, simd_distance(начало.место, цель) < 0.15 {
                if сейчас - начало.время >= Self.ждатьСтол {
                    встатьСамой(цель)
                    return
                }
            } else {
                началоУверенности = (время: сейчас, место: цель)
            }
            новое = .ставим
        } else {
            началоУверенности = nil
        }
        if прицел != новое { прицел = новое }
    }

    /// Вещь встаёт сама — не посреди обновления сцены, а следующим шагом главной нити (и только если ещё не стоит).
    private func встатьСамой(_ место: SIMD3<Float>) {
        автоМожно = false
        началоУверенности = nil
        Task { @MainActor [weak self] in
            guard let self, self.корпус == nil, self.габариты != nil, self.режим != .линейка, self.идёт else { return }
            /* Лист размеров открылся в этот же миг — вещь не ставим, но встать сама она ещё может (после листа). */
            guard !self.листРазмеров else {
                self.автоМожно = true
                return
            }
            self.построить(на: место)
        }
    }

    private func спрятатьПрицел(_ рамка: Entity, _ состояние: ПрицелГабаритов) {
        if рамка.isEnabled { рамка.isEnabled = false }
        точкаПрицела = nil
        началоУверенности = nil
        if прицел != состояние { прицел = состояние }
    }

    /// Рамка по основанию вещи (ширина × глубина, м): бруски — по краям, длина — масштабом.
    private func задатьРамку(_ размер: SIMD2<Float>) {
        guard размер != размерРамки, частиПрицела.count == 5 else { return }
        размерРамки = размер
        let ш = max(размер.x, 0.02)
        let г = max(размер.y, 0.02)
        let т: Float = 0.006
        let п = частиПрицела
        п[0].scale = SIMD3<Float>(ш + т, 1, 1)
        п[0].position = SIMD3<Float>(0, 0.001, г / 2)
        п[1].scale = SIMD3<Float>(ш + т, 1, 1)
        п[1].position = SIMD3<Float>(0, 0.001, -г / 2)
        п[2].scale = SIMD3<Float>(1, 1, г + т)
        п[2].position = SIMD3<Float>(-ш / 2, 0.001, 0)
        п[3].scale = SIMD3<Float>(1, 1, г + т)
        п[3].position = SIMD3<Float>(ш / 2, 0.001, 0)
    }

    private func перекраситьРамку(_ зелёная: Bool) {
        guard рамкаЗелёная != зелёная else { return }
        рамкаЗелёная = зелёная
        let материал = Self.материалПрицела(зелёная)
        for часть in частиПрицела { часть.model?.materials = [материал] }
    }

    // MARK: Стена

    func переключитьСтену() {
        guard let корпус else { return }
        if прижато {
            отпуститьСтену()
            ОткликСайта.выбор()
            return
        }
        guard let найдена = ближайшаяСтена(к: корпус.position) else {
            показать(т("fb_wall_far"))
            return
        }
        стенаПрижатия = найдена.ид
        прижато = true
        прижать(к: найдена.стена, плавно: true)
        ОткликСайта.выбор()
        UIAccessibility.post(notification: .announcement, argument: т("fb_wall_on"))
    }

    private func отпуститьСтену() {
        guard прижато else { return }
        прижато = false
        стенаПрижатия = nil
    }

    /// Горизонтальная нормаль стены в сторону точки `к` (в комнату); стена почти горизонтальна — nil.
    private func нормаль(_ стена: ПлоскостьГабаритов, к точка: SIMD3<Float>) -> SIMD3<Float>? {
        var н = SIMD3<Float>(стена.нормаль.x, 0, стена.нормаль.z)
        let длина = simd_length(н)
        guard длина > 0.3 else { return nil }
        н /= длина
        var сторона = точка - стена.точка
        if abs(simd_dot(сторона, н)) < 0.02, let вид {
            сторона = вид.cameraTransform.translation - стена.точка
        }
        if simd_dot(сторона, н) < 0 { н = -н }
        return н
    }

    /// Ближайшая стена не дальше 3 м от коробки и не в стороне от найденного куска больше чем на метр.
    private func ближайшаяСтена(к точка: SIMD3<Float>) -> (ид: UUID, стена: ПлоскостьГабаритов)? {
        var лучшая: (ид: UUID, стена: ПлоскостьГабаритов)? = nil
        var наименьшее: Float = 3
        for (ид, стена) in стены {
            guard let н = нормаль(стена, к: точка) else { continue }
            let от = точка - стена.точка
            let до = abs(simd_dot(от, н))
            let вдоль = от - н * simd_dot(от, н)
            let вбок = simd_length(SIMD3<Float>(вдоль.x, 0, вдоль.z))
            guard вбок < стена.ширина / 2 + 1, до < наименьшее else { continue }
            наименьшее = до
            лучшая = (ид: ид, стена: стена)
        }
        return лучшая
    }

    /// Развернуть коробку спиной к стене и поставить вплотную (полсантиметра зазора).
    private func прижать(к стена: ПлоскостьГабаритов, плавно: Bool) {
        guard let корпус, let габариты, let н = нормаль(стена, к: корпус.position) else { return }
        угол = atan2(н.x, н.z)
        let место = кСтене(корпус.position, стена: стена, нормаль: н, глубина: габариты.метры.z)
        let цель = Transform(scale: корпус.scale, rotation: simd_quatf(angle: угол, axis: SIMD3<Float>(0, 1, 0)),
                             translation: место)
        if плавно && !тихо {
            _ = корпус.move(to: цель, relativeTo: корпус.parent, duration: 0.3, timingFunction: .easeInOut)
        } else {
            корпус.transform = цель
        }
    }

    private func кСтене(_ место: SIMD3<Float>, стена: ПлоскостьГабаритов, нормаль н: SIMD3<Float>,
                        глубина: Float) -> SIMD3<Float> {
        let до = simd_dot(место - стена.точка, н)
        var итог = место - н * (до - глубина / 2 - 0.005)
        итог.y = место.y
        return итог
    }

    // MARK: Жесты

    private func добавитьЖесты(_ вид: ARView) {
        let касание = UITapGestureRecognizer(target: self, action: #selector(жестКасания(_:)))
        let тяга = UIPanGestureRecognizer(target: self, action: #selector(жестТяги(_:)))
        тяга.maximumNumberOfTouches = 1
        тяга.delegate = self
        let вращение = UIRotationGestureRecognizer(target: self, action: #selector(жестВращения(_:)))
        вращение.delegate = self
        вид.addGestureRecognizer(касание)
        вид.addGestureRecognizer(тяга)
        вид.addGestureRecognizer(вращение)
    }

    @objc(klikoFitBoxTap:)
    private func жестКасания(_ жест: UITapGestureRecognizer) {
        guard режим != .линейка, let вид, жест.state == .ended else { return }
        поставить(в: жест.location(in: вид))
    }

    @objc(klikoFitBoxPan:)
    private func жестТяги(_ жест: UIPanGestureRecognizer) {
        guard режим != .линейка, let вид, let корпус else { return }
        let пол = корпус.position.y
        let точка = жест.location(in: вид)
        switch жест.state {
        case .began:
            guard let место = точкаНаПлоскости(точка, высота: пол) else {
                тянем = false
                return
            }
            сдвиг = корпус.position - место
            сдвиг.y = 0
            тянем = true
        case .changed:
            guard тянем, let место = точкаНаПлоскости(точка, высота: пол) else { return }
            var новое = место + сдвиг
            новое.y = пол
            if прижато, let ид = стенаПрижатия, let стена = стены[ид], let габариты,
               let н = нормаль(стена, к: корпус.position) {
                новое = кСтене(новое, стена: стена, нормаль: н, глубина: габариты.метры.z)
            }
            корпус.position = новое
        default:
            тянем = false
        }
    }

    @objc(klikoFitBoxRotate:)
    private func жестВращения(_ жест: UIRotationGestureRecognizer) {
        guard режим != .линейка, let корпус else { return }
        switch жест.state {
        case .began:
            отпуститьСтену()
            уголНачала = угол
        case .changed:
            угол = уголНачала - Float(жест.rotation)
            корпус.orientation = simd_quatf(angle: угол, axis: SIMD3<Float>(0, 1, 0))
        default:
            break
        }
    }

    // MARK: Подписи у рёбер

    private func обновитьТекстыПодписей() {
        guard let г = габариты, подписи.count == 3 else { return }
        let см = т("fb_cm")
        func подпись(_ ключ: String, _ значение: Double) -> String {
            т(ключ) + " " + ГабаритыВещи.число(значение) + " " + см
        }
        /* Подписи — у ребра вдоль лица, у вертикального и у ребра вглубь; лёжа вверх — толщина, вглубь — высота (буквы —
           как в объявлении, числа — по месту в сцене). */
        let лёжа = self.лёжа
        подписи[0].текст = подпись("fb_w_short", г.ширина)
        подписи[1].текст = лёжа ? подпись("fb_d_short", г.глубина) : подпись("fb_h_short", г.высота)
        подписи[2].текст = лёжа ? подпись("fb_h_short", г.высота) : подпись("fb_d_short", г.глубина)
    }

    private func показатьПодписи(_ показ: Bool) {
        /* В линейке подписи коробки (и вещи) не видны, даже если «вырастание» досчиталось уже после смены режима. */
        let да = показ && режим != .линейка
        подписиВидны = да
        let подписи = self.подписи
        if да && !тихо {
            UIView.animate(withDuration: 0.25) {
                for подпись in подписи { подпись.alpha = 1 }
            }
        } else {
            for подпись in подписи { подпись.alpha = да ? 1 : 0 }
        }
    }

    /// Каждый кадр сцены: прицел настольной вещи; три точки у рёбер ближнего к камере угла — на экран.
    private func кадр() {
        обновитьПрицел()
        guard подписиВидны, let вид, let корпус, let габариты, подписи.count == 3 else { return }
        let р = вСцене(габариты)
        let камера = вид.cameraTransform.translation
        let центр = корпус.position
        let поворот = корпус.orientation
        var ближний = (x: Float(1), z: Float(1))
        var наименьшее = Float.greatestFiniteMagnitude
        for x in [Float(-1), 1] {
            for z in [Float(-1), 1] {
                let точка = центр + поворот.act(SIMD3<Float>(x * р.x / 2, 0, z * р.z / 2))
                let до = simd_distance(точка, камера)
                if до < наименьшее {
                    наименьшее = до
                    ближний = (x: x, z: z)
                }
            }
        }
        let отступ: Float = 0.05
        let местные = [
            SIMD3<Float>(0, 0.02, ближний.z * (р.z / 2 + отступ)),
            SIMD3<Float>(ближний.x * (р.x / 2 + отступ), р.y / 2, ближний.z * (р.z / 2 + отступ)),
            SIMD3<Float>(ближний.x * (р.x / 2 + отступ), 0.02, 0)
        ]
        let поле = вид.bounds.insetBy(dx: -30, dy: -30)
        for (номер, местная) in местные.enumerated() {
            let подпись = подписи[номер]
            подпись.следить()
            if let наЭкране = вид.project(центр + поворот.act(местная)), поле.contains(наЭкране) {
                подпись.center = наЭкране
                if подпись.isHidden { подпись.isHidden = false }
            } else if !подпись.isHidden {
                подпись.isHidden = true
            }
        }
    }

    // MARK: Снимок

    func снять() {
        guard let вид, !снимаем, корпус != nil else { return }
        снимаем = true
        вид.snapshot(saveToHDR: false) { [weak self] картинка in
            guard let self else { return }
            Task { @MainActor in
                self.снимокПришёл(картинка)
            }
        }
    }

    /**
     На главной нити — только лёгкое: подписи у рёбер маленькими картинками и их места (слой UIView рисуется только
     здесь). Склейка во весь экран в пикселях и плашка с текстом — в фоне (UIGraphicsImageRenderer потокобезопасен).
     */
    private func снимокПришёл(_ картинка: UIImage?) {
        guard let картинка, let вид, картинка.size.width > 0, вид.bounds.width > 0 else {
            снимаем = false
            показать(т("fb_shot_fail"))
            return
        }
        let к = картинка.size.width / вид.bounds.width
        let видимые = подписи.filter { !$0.isHidden && $0.alpha > 0.01 }
        let метки: [(картинка: UIImage, место: CGRect)] = видимые.map { подпись in
            let формат = UIGraphicsImageRendererFormat()
            формат.scale = картинка.scale * к
            формат.opaque = false
            let малая = UIGraphicsImageRenderer(size: подпись.bounds.size, format: формат).image { холст in
                подпись.layer.render(in: холст.cgContext)
            }
            let м = подпись.frame
            return (малая, CGRect(x: м.minX * к, y: м.minY * к, width: м.width * к, height: м.height * к))
        }
        var строка = габариты.map { "Kliko.kz · " + $0.строка + " " + т("fb_cm") } ?? "Kliko.kz"
        /* В кадре вещь (а не коробка): снимок уйдёт дальше — на плашке сказано, что это «3D-модель ИИ» или фото. */
        var озвучка: String? = nil
        if режим == .вещь, ростВещи != nil {
            if let хвост = вещь.хвостСнимка { строка += " · " + хвост }
            озвучка = габариты.map { ВещьГабаритовText.т("fi_shot_img", $0.озвучка) }
        }
        let итоговая = строка
        let озвучкаСнимка = озвучка
        Task { @MainActor [weak self] in
            let готовая = await Task.detached(priority: .userInitiated) { () -> UIImage in
                МодельГабаритов.собрать(картинка, метки: метки, строка: итоговая, к: к)
            }.value
            guard let self else { return }
            self.снимаем = false
            guard self.виден else { return }
            ОткликСайта.успех()
            self.снимок = СнимокГабаритов(картинка: готовая, озвучка: озвучкаСнимка)
        }
    }

    /// Кадр + подписи у рёбер (или у отрезков линейки) + плашка «Kliko.kz · …» внизу. Не на главной нити.
    nonisolated static func собрать(_ кадр: UIImage, метки: [(картинка: UIImage, место: CGRect)],
                                    строка: String, к: CGFloat) -> UIImage {
        let размер = кадр.size
        let формат = UIGraphicsImageRendererFormat()
        формат.scale = кадр.scale
        формат.opaque = true
        return UIGraphicsImageRenderer(size: размер, format: формат).image { _ in
            кадр.draw(in: CGRect(origin: .zero, size: размер))
            for метка in метки {
                метка.картинка.draw(in: метка.место)
            }
            let шрифт = UIFont.systemFont(ofSize: 15 * к, weight: .bold)
            let текст = NSAttributedString(string: строка, attributes: [
                .font: шрифт,
                .foregroundColor: UIColor.white
            ])
            /* Строка линейки со сравнением («Kliko.kz · Ниша 1 м 25 см · вещь (ширина) 1 м 30 см · не хватает 5 см ✗»)
               шире кадра телефона: плашка не шире кадра, текст переносится — итог справа не уходит за край. */
            let отступ = 16 * к
            let предел = max(отступ, размер.width - отступ * 2 - отступ * 1.2)
            let варианты: NSStringDrawingOptions = [.usesLineFragmentOrigin, .usesFontLeading]
            let поле = текст.boundingRect(with: CGSize(width: предел, height: .greatestFiniteMagnitude),
                                          options: варианты, context: nil).integral
            let плашка = CGRect(x: отступ, y: размер.height - поле.height - отступ * 2.4,
                                width: поле.width + отступ * 1.2, height: поле.height + отступ * 0.8)
            UIColor(white: 0, alpha: 0.55).setFill()
            UIBezierPath(roundedRect: плашка, cornerRadius: min(плашка.height / 2, отступ * 1.2)).fill()
            текст.draw(with: CGRect(x: плашка.minX + отступ * 0.6, y: плашка.minY + отступ * 0.4, width: поле.width,
                                    height: поле.height),
                       options: варианты, context: nil)
        }
    }
}

// MARK: - Делегат сессии

extension МодельГабаритов: ARSessionDelegate {
    nonisolated func session(_ session: ARSession, didAdd anchors: [ARAnchor]) {
        let плоскости = Self.плоскости(anchors)
        guard !плоскости.isEmpty else { return }
        Task { @MainActor [weak self] in
            self?.плоскостиПришли(плоскости, убрать: [])
        }
    }

    nonisolated func session(_ session: ARSession, didUpdate anchors: [ARAnchor]) {
        let плоскости = Self.плоскости(anchors)
        guard !плоскости.isEmpty else { return }
        Task { @MainActor [weak self] in
            self?.плоскостиПришли(плоскости, убрать: [])
        }
    }

    nonisolated func session(_ session: ARSession, didRemove anchors: [ARAnchor]) {
        let ид = anchors.compactMap { ($0 as? ARPlaneAnchor)?.identifier }
        guard !ид.isEmpty else { return }
        Task { @MainActor [weak self] in
            self?.плоскостиПришли([], убрать: ид)
        }
    }

    nonisolated func session(_ session: ARSession, cameraDidChangeTrackingState camera: ARCamera) {
        let слежение = Self.слежение(camera.trackingState)
        Task { @MainActor [weak self] in
            self?.слежениеПришло(слежение)
        }
    }

    nonisolated func session(_ session: ARSession, didFailWithError error: Error) {
        let запрет = (error as? ARError)?.code == .cameraUnauthorized
        Task { @MainActor [weak self] in
            self?.сбойСессии(запрет: запрет)
        }
    }

    nonisolated func sessionWasInterrupted(_ session: ARSession) {
        Task { @MainActor [weak self] in
            self?.сессияПрервана(true)
        }
    }

    nonisolated func sessionInterruptionEnded(_ session: ARSession) {
        Task { @MainActor [weak self] in
            self?.сессияПрервана(false)
        }
    }

    /// Плоскости из якорей — значениями (сами якоря наружу не уходят).
    nonisolated private static func плоскости(_ якоря: [ARAnchor]) -> [ПлоскостьГабаритов] {
        якоря.compactMap { якорь -> ПлоскостьГабаритов? in
            guard let плоскость = якорь as? ARPlaneAnchor else { return nil }
            let м = плоскость.transform
            let ц = м * SIMD4<Float>(плоскость.center.x, плоскость.center.y, плоскость.center.z, 1)
            /* Стол — по классификации ARKit (A12 и новее); где её нет — горизонталь как горизонталь. */
            var стол = false
            if ARPlaneAnchor.isClassificationSupported, case .table = плоскость.classification { стол = true }
            return ПлоскостьГабаритов(ид: плоскость.identifier,
                                      стена: плоскость.alignment == .vertical,
                                      точка: SIMD3<Float>(ц.x, ц.y, ц.z),
                                      нормаль: SIMD3<Float>(м.columns.1.x, м.columns.1.y, м.columns.1.z),
                                      ширина: плоскость.planeExtent.width,
                                      стол: стол)
        }
    }

    nonisolated private static func слежение(_ состояние: ARCamera.TrackingState) -> СлежениеГабаритов {
        switch состояние {
        case .normal:
            return .норма
        case .notAvailable:
            return .нет
        case .limited(let причина):
            switch причина {
            case .initializing: return .запуск
            case .excessiveMotion: return .быстро
            case .insufficientFeatures: return .мало
            case .relocalizing: return .возврат
            @unknown default: return .мало
            }
        @unknown default:
            return .нет
        }
    }
}


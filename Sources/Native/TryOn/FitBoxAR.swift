/**
 «ПОМЕСТИТСЯ ЛИ?» — СЦЕНА AR С КОРОБКОЙ НАСТОЯЩИХ РАЗМЕРОВ (владелец 13.10.2026: «нужнее охват всего»).

 Без 3D-модели и без сервера: RealityKit ARView с ARWorldTrackingConfiguration ищет пол (и стены — для «Прижать к
 стене», Config.габаритыСтена). Касание пола ставит коробку размеров из объявления (ГабаритыВещи, FitBoxSize.swift):
 полупрозрачная зелёная, с яркими рёбрами и тенью-следом на полу, лицом к человеку. Появляется «вырастанием» снизу
 вверх (при «Уменьшении движения» — сразу). Два пальца — поворот вокруг вертикали, один палец — сдвиг по полу, касание
 пола в стороне — переставить туда. Подписи размеров («Ш 60 см», «В 85 см», «Г 55 см») — у трёх рёбер ближнего к
 камере угла: точки рёбер каждый кадр переводятся на экран (ARView.project), подписи — обычные UIView поверх сцены
 (крупный шрифт — по «Размеру текста»).

 «Прижать к стене»: коробка разворачивается задней стороной к ближайшей найденной стене и встаёт вплотную; сдвиг тогда
 идёт вдоль стены, поворот пальцами — отпускает. «Снимок» — ARView.snapshot, поверх него рисуются подписи и строка
 «Kliko.kz · размеры».

 «На столе» (владелец 14.10.2026: «например ноутбук 3D на столе»): у настольных вещей (ГабаритыВещи.разделыСтола —
 ноутбуки, мониторы, планшеты, колонки, приставки, микроволновки…) подсказки и заголовок — про стол (ГабаритыText
 .дляСтола), а когда ARKit узнаёт стол (классификация плоскости .table), один раз звучит «Стол найден».

 «На столе» по-настоящему (владелец 16.10.2026, скрин TestFlight: ноутбук 36 × 2 × 25 см встал плоской картинкой где-то
 далеко на полу — «алгоритм 3D AR и реальность не проработан — добей»): у настольной вещи посреди экрана — прицел, рамка
 основания вещи в настоящий размер прямо на поверхности, лицом к человеку (ПрицелГабаритов). Луч — по найденным
 плоскостям ARKit и по прикидке (.estimatedPlane), только горизонтали; прикидка заметно ближе найденной плоскости — между
 камерой и полом стол, который ARKit ещё не дособрал: берём её (поверхность выше пола главнее). Рамка зеленеет на
 найденной плоскости не дальше 1,8 м, похожей на стол; дальше — «Подойдите ближе к столу», и касание вещь туда не
 ставит. Похоже на пол (ARKit узнал пол, или поверхность на уровне самой низкой горизонтали и больше метра ниже камеры)
 — рамка белая, «Это пол — наведите на стол»; касание ставит туда только вторым за 2 с (осознанно: колонку или
 системный блок ставят и на пол) — и при первой постановке, и при перестановке. Касание до постановки ставит вещь в
 рамку прицела; там пусто, далеко или пол, а под пальцем стол рядом — в точку пальца. Сама вещь встаёт только на точный
 стол (ARKit узнал стол, или ниже есть горизонталь — пол): полторы секунды под прицелом почти на одном месте (до первой
 постановки и после «Поставить на стол заново»; после «Убрать» и пока открыт лист размеров — нет). Прикидка «меньше
 метра ниже камеры» — только для касания: сидя пол тоже ближе метра, а свежую плоскость ARKit ещё не пометил. Стены у
 настольной вещи ищутся только в линейке (замер ниши и полки; без лидара смена режима перенастраивает сессию),
 «Прижать к стене» нет — вместо неё «Поставить на стол заново». Сдвиг одним пальцем — по той же поверхности, поворот —
 двумя; щипка нет: размер настоящий. Вещь — 3D-форма по размерам (FitBoxItemShape.swift) или 3D-модель ИИ; свет —
 карта окружения ARKit (не в лёгком режиме) и своя лампа у вещи.

 Сессия идёт, только пока экран на виду и приложение не в фоне (ЭкранГабаритов зовёт появился/ушёл/вФон/изФона).
 Делегат сессии приходит на главную очередь; из него наружу — только значения (ПлоскостьГабаритов), самих ARFrame не
 держим и не копируем. В симуляторе ARKit не работает, а часть API ARView в нём не собирается — эти места под
 #if !targetEnvironment(simulator); кнопки там и нет (ОкноГабаритов.доступно).

 Линейка (владелец 14.10.2026, FitBoxRuler.swift): режим «Линейка» живёт в той же сессии и том же ARView — модель
 только прячет коробку и её подписи (жесты коробки в линейке молчат: точки ставит «+»), пересылает линейке слежение,
 размеры и сброс сцены. На устройствах с лидаром смена режима перенастраивает сессию (линейке — глубина и сетка сцены).

 Вещь (владелец 14.10.2026: «3D-обзор надо сделать за счёт ИИ», FitBoxItem.swift): режим «Вещь» — первый и по
 умолчанию, если у объявления есть фото или 3D-модель (ВещьГабаритов.доступна). Вещь — вторая сущность в том же корпусе
 (ростВещи рядом с ростом коробки): те же касание, жесты, стена, подписи и снимок. В «Вещи» видна вещь, а пока она не
 готова или не вышла — коробка; в «Коробке» — коробка. Готовит вещь (3D-модель или «стойку» из фото) ВещьГабаритов —
 только пока окно на виду и выбрана «Вещь»; готово — вещьГотова() кладёт её в корпус.
 */

/// Плоскость ARKit значениями — из делегата сессии на главную нить.
struct ПлоскостьГабаритов: Sendable {
    let ид: UUID
    let стена: Bool
    /// Центр плоскости в мире.
    let точка: SIMD3<Float>
    /// Нормаль (ось y якоря плоскости).
    let нормаль: SIMD3<Float>
    /// Ширина найденного куска, м.
    let ширина: Float
    /// ARKit узнал в плоскости стол (ARPlaneAnchor.classification == .table; на устройствах без классификации — нет).
    var стол: Bool = false
}

/// Прицел настольной вещи: что сейчас под центром экрана.
enum ПрицелГабаритов: Equatable, Sendable {
    /// Прицела нет: вещь не настольная или уже стоит, линейка, нет размеров.
    case нет
    /// Под прицелом поверхности нет (или камера ещё не видит мир).
    case ищет
    /// Поверхность дальше 1,8 м — «Подойдите ближе к столу».
    case далеко
    /// Похоже на пол — «Это пол — наведите на стол» (касание ставит туда только вторым, осознанно).
    case пол
    /// Поверхность рядом: касание поставит вещь в рамку.
    case есть
    /// Уверенный стол рядом: ещё миг — и вещь встанет сама.
    case ставим
}

/// Что под точкой экрана у настольной вещи: точка в мире, найденная ли это плоскость ARKit (а не прикидка), похоже ли
/// на стол (не пол — для касания и цвета рамки) и точно ли стол (для «встанет сама»).
fileprivate struct ПопаданиеГабаритов {
    let точка: SIMD3<Float>
    let уверенно: Bool
    let какСтол: Bool
    let точноСтол: Bool
}

/// Как ARKit видит мир.
enum СлежениеГабаритов: Equatable, Sendable {
    case запуск
    case норма
    case быстро
    case мало
    case возврат
    case нет
}

/// Готовый снимок с коробкой или с отрезками линейки.
struct СнимокГабаритов: Identifiable {
    let id = UUID()
    let картинка: UIImage
    /// Подпись картинки для VoiceOver; nil — по размерам коробки (ЛистСнимкаГабаритов).
    var озвучка: String? = nil
}

@MainActor
final class МодельГабаритов: NSObject, ObservableObject {
    enum Этап: Equatable {
        case ищемПол
        case можноСтавить
        case стоит
    }

    enum Камера: Equatable {
        case ждём
        case идёт
        case пауза
        case запрещена
        case сбой
    }

    let товар: Listing
    let найдено: НайденныеГабариты
    /// «Измерить в AR» из подачи (ОкноГабаритов.открытьЗамер): только линейка, без коробки и сравнения; «Готово» отдаёт
    /// первые три отрезка как ширину, высоту и глубину вещи.
    let замерВещи: Bool
    /// Настольная вещь (ноутбук, монитор, колонка… — ГабаритыВещи.разделыСтола): подсказки про стол, а не про пол.
    /// Ставится она на горизонталь ARKit — стол или тумбу; на пол — только вторым касанием (осознанно).
    let наСтоле: Bool

    /// Размеры коробки; nil — ещё не указали (открыт лист размеров).
    @Published private(set) var габариты: ГабаритыВещи? = nil
    @Published var листРазмеров = false
    /// Лист снимка: пока он открыт, сессия на паузе (неподвижная картинка, а камера и поиск плоскостей тратили бы
    /// батарею); закрыли — снова идёт, без сброса (коробка на месте).
    @Published var снимок: СнимокГабаритов? = nil {
        didSet {
            guard (снимок == nil) != (oldValue == nil) else { return }
            if снимок == nil { запустить() } else { остановить() }
        }
    }
    @Published private(set) var этап: Этап = .ищемПол
    @Published private(set) var слежение: СлежениеГабаритов = .запуск
    @Published private(set) var камера: Камера = .ждём
    @Published private(set) var естьСтена = false
    @Published private(set) var прижато = false
    @Published private(set) var снимаем = false
    /// Короткое сообщение поверх камеры (сама гаснет).
    @Published private(set) var сообщение: String? = nil
    /// Вещь, коробка или линейка (переключатель сверху).
    @Published private(set) var режим: РежимГабаритов = .коробка
    /// Линейка AR — в той же сессии (FitBoxRuler.swift).
    let линейка: ЛинейкаГабаритов
    /// Вещь — 3D-модель или фото «стойкой» в том же корпусе, что и коробка (FitBoxItem.swift).
    let вещь: ВещьГабаритов
    /// Прицел настольной вещи (что под центром экрана) — для подсказки; .нет — прицела нет.
    @Published private(set) var прицел: ПрицелГабаритов = .нет
    /// Свет окружения AR (карта окружения ARKit): нужен 3D-модели и 3D-форме вещи; «стойке», окну без вещи и лёгкому
    /// режиму — нет (у вещи там своя яркая лампа, а стойка, коробка и линейка светятся сами).
    private let светОкружения: Bool

    private(set) var вид: ARView?
    private var корень: AnchorEntity?
    /// Положение и поворот коробки (дитя корня в начале мира).
    private var корпус: Entity?
    /// Сама коробка: её масштаб по высоте — «вырастание».
    private var рост: Entity?
    /// Вещь в том же корпусе (СборкаВещиГабаритов); nil — не готова или не вышла.
    private var ростВещи: Entity?
    private var подписи: [ПодписьРебраГабаритов] = []
    private var подписиВидны = false
    private var подписка: (any Cancellable)?
    private var стены: [UUID: ПлоскостьГабаритов] = [:]
    private var полы: Set<UUID> = []
    /// «Стол найден» уже сказали (настольная вещь; сброс сцены — заново).
    private var столНайден = false
    private var стенаПрижатия: UUID? = nil
    private var виден = false
    /// Окно закрывают насовсем (✕): при уходе с экрана — разобрать ARView, а не только поставить паузу.
    private var закрывается = false
    private var вФоне = false
    private var идёт = false
    private var первыйЗапуск = true
    private var угол: Float = 0
    private var уголНачала: Float = 0
    private var сдвиг = SIMD3<Float>(0, 0, 0)
    private var тянем = false
    private var задачаСообщения: Task<Void, Never>? = nil
    private var задачаПодписей: Task<Void, Never>? = nil
    /// Высоты найденных горизонталей, что смотрят вверх: самая низкая — похоже, пол.
    private var горизонтали: [UUID: Float] = [:]
    /// Рамка прицела настольной вещи (дитя корня) и её части: четыре бруска по краям основания и точка в центре.
    private var рамкаПрицела: Entity? = nil
    private var частиПрицела: [ModelEntity] = []
    /// Размер рамки (ширина и глубина основания, м) и цвет — меняются только когда сменились.
    private var размерРамки = SIMD2<Float>(0, 0)
    private var рамкаЗелёная: Bool? = nil
    /// Где рамка сейчас (сглаживание дрожи луча).
    private var точкаПрицела: SIMD3<Float>? = nil
    private var кадрПрицела = 0
    /// Когда и где поверхность под прицелом стала уверенным столом: полторы секунды почти на месте — вещь встаёт сама.
    private var началоУверенности: (время: CFTimeInterval, место: SIMD3<Float>)? = nil
    /// Встать самой можно: до первой постановки и после «Поставить на стол заново»; после «Убрать» — только касанием.
    private var автоМожно = true
    /// Когда коснулись поверхности, похожей на пол: второе касание за 2 с ставит туда (осознанно).
    private var касаниеПола: CFTimeInterval? = nil
    /// Дальше этого от камеры, м, настольную вещь не ставим: «Подойдите ближе к столу».
    private static let ближеСтола: Float = 1.8
    /// Сколько секунд уверенный стол должен быть под прицелом, чтобы вещь встала сама.
    private static let ждатьСтол: CFTimeInterval = 1.5
    /// За сколько секунд второе касание пола ставит вещь на пол.
    private static let второеКасание: CFTimeInterval = 2

    init(товар: Listing, найдено: НайденныеГабариты, замерВещи: Bool = false) {
        self.товар = товар
        self.найдено = найдено
        self.замерВещи = замерВещи
        наСтоле = !замерВещи && ГабаритыВещи.наСтоле(товар.категория)
        линейка = ЛинейкаГабаритов(замерВещи: замерВещи)
        let новаяВещь = ВещьГабаритов(товар: товар, включена: !замерВещи)
        вещь = новаяВещь
        светОкружения = новаяВещь.нуженСвет && !РежимУстройства.shared.лёгкий
        super.init()
        if замерВещи {
            режим = .линейка
        } else {
            /* Надёжных размеров в объявлении нет, а в 3D-модели все три есть — берём их (FitBoxItem.swift). */
            габариты = найдено.надёжно ? найдено.полные : ВещьГабаритов.размерыМодели(товар)
            линейка.задатьГабариты(габариты)
            if вещь.доступна { режим = .вещь }
            вещь.приГотовности = { [weak self] in
                self?.вещьГотова()
            }
        }
    }

    /// Строки коробки; в режиме «Вещь» — «вещь» вместо «коробки» (ВещьГабаритовText.вместоКоробки); у настольной вещи —
    /// «стол» вместо «пола», где такая строка есть (ГабаритыText.дляСтола).
    private func т(_ ключ: String) -> String {
        if наСтоле, let своя = ГабаритыText.дляСтола(ключ) { return своя }
        return режим == .вещь ? ВещьГабаритовText.вместоКоробки(ключ) : ГабаритыText.т(ключ)
    }

    private var тихо: Bool { UIAccessibility.isReduceMotionEnabled || ДвижениеСайта.тихо }

    // MARK: Жизнь экрана

    func появился() {
        виден = true
        if режим == .вещь { вещь.подготовить() }
        /* Линейке размеры вещи не нужны (замер для подачи, ниша без размеров) — камера сразу. */
        guard габариты == nil && режим != .линейка else {
            запустить()
            return
        }
        /* Размеров нет или они сомнительны — сначала лист (когда окно доедет: лист поверх едущего окна не встаёт). */
        Task { @MainActor [weak self] in
            try? await Task.sleep(nanoseconds: 450_000_000)
            guard let self, self.виден, self.габариты == nil, self.режим != .линейка, !self.листРазмеров else { return }
            self.листРазмеров = true
        }
    }

    func ушёл() {
        виден = false
        остановить()
        вещь.пауза()
        задачаСообщения?.cancel()
        задачаПодписей?.cancel()
        if закрывается { разобрать() }
    }

    /// Окно закрывают (✕ или лист размеров закрыт без размеров) — после ухода с экрана всё разобрать.
    func закрываем() {
        закрывается = true
    }

    /**
     ARView, подписка на кадры сцены, делегат сессии, жесты и подписи — отпустить сразу, не дожидаясь деинициализатора
     модели: у ARView бывает, что он держит Metal и сессию дольше нужного, а каждое открытие окна создаёт новый.
     */
    private func разобрать() {
        подписка?.cancel()
        подписка = nil
        линейка.отключить()
        вещь.отменить()
        ростВещи = nil
        guard let вид else { return }
        #if !targetEnvironment(simulator)
        вид.session.delegate = nil
        #endif
        for жест in вид.gestureRecognizers ?? [] { вид.removeGestureRecognizer(жест) }
        if let корень { вид.scene.removeAnchor(корень) }
        for подпись in подписи { подпись.removeFromSuperview() }
        подписи = []
        подписиВидны = false
        корпус = nil
        рост = nil
        корень = nil
        рамкаПрицела = nil
        частиПрицела = []
        рамкаЗелёная = nil
        точкаПрицела = nil
        началоУверенности = nil
        self.вид = nil
    }

    func вФон() {
        guard виден else { return }
        вФоне = true
        остановить()
    }

    func изФона() {
        guard виден, вФоне else { return }
        вФоне = false
        /* Вернулись из Настроек — камеру могли разрешить: пробуем заново (запрещена по-прежнему — снова заглушка). */
        if камера == .запрещена {
            камера = .ждём
            первыйЗапуск = true
        }
        запустить()
    }

    /// Новые размеры из листа: коробка, если стоит, перестраивается; сессия — запускается.
    func задать(_ новые: ГабаритыВещи) {
        let прежние = габариты
        габариты = новые
        линейка.задатьГабариты(новые)
        if корпус != nil && прежние != новые { перестроить() }
        запустить()
    }

    func повторить() {
        камера = .ждём
        первыйЗапуск = true
        идёт = false
        запустить()
    }

    /**
     Перед запуском с .resetTracking (после сбоя сессии, после разрешения камеры): начало мира переедет к телефону —
     старая коробка с подписями повисла бы в случайном месте, а найденные пол и стены уже не те. Всё — с начала.
     */
    private func сброситьСцену() {
        задачаПодписей?.cancel()
        корпус?.removeFromParent()
        корпус = nil
        рост = nil
        ростВещи = nil
        показатьПодписи(false)
        полы.removeAll()
        горизонтали.removeAll()
        столНайден = false
        стены.removeAll()
        /* Настольной вещи — снова прицел и «встанет сама». */
        автоМожно = true
        касаниеПола = nil
        началоУверенности = nil
        точкаПрицела = nil
        рамкаПрицела?.isEnabled = false
        линейка.сброситьСцену()
        прижато = false
        стенаПрижатия = nil
        if естьСтена { естьСтена = false }
        if этап != .ищемПол { этап = .ищемПол }
    }


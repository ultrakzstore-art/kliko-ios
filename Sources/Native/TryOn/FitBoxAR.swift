    /// Режим сменился на идущей сессии: с лидаром (сетка сцены линейке) или у настольной вещи (стены линейке) — та же
    /// сессия с новой настройкой (без сброса, якоря на месте; формат видео без лидара тот же в обоих режимах).
    private func перенастроить() {
        guard идёт, ЛинейкаГабаритов.лидар || наСтоле else { return }
        #if !targetEnvironment(simulator)
        вид?.session.run(настройкаСессии(), options: [])
        #endif
    }

    // MARK: Режим

    /**
     «Вещь / Коробка / Линейка»: одна сессия на все режимы. Вещь и коробка — один корпус (место и поворот общие); в
     линейке корпус прячется (место и поворот помнит), подписи его гаснут; отрезки линейки в вещи и коробке — тоже.
     Касания по сцене в линейке корпус не двигают.
     */
    func сменитьРежим(_ новый: РежимГабаритов) {
        guard новый != режим, !замерВещи else { return }
        switch новый {
        case .линейка: guard Config.габаритыЛинейка else { return }
        case .вещь: guard вещь.доступна else { return }
        case .коробка: break
        }
        let линейкаБыла = режим == .линейка
        let вещьБыла = режим == .вещь
        режим = новый
        let сКорпусом = новый != .линейка
        обновитьКорпус()
        показатьПодписи(сКорпусом && этап == .стоит)
        линейка.включить(!сКорпусом)
        /* Сессию перенастраивает только вход в линейку и выход из неё (вещи и коробке настройка одна): с лидаром —
           сетка сцены, у настольной вещи — стены. */
        if линейкаБыла != (новый == .линейка) { перенастроить() }
        if новый == .вещь { вещь.подготовить() }
        /* Ушли из «Вещи» — загрузка модели и вырезка стоят (готовое остаётся), вернутся — начнутся снова. */
        if вещьБыла && новый != .вещь { вещь.пауза() }
        /* Линейка без размеров вещи: камера могла ещё не идти (лист размеров закрыли пустым). */
        запустить()
        ОткликСайта.выбор()
        let весть: String
        switch новый {
        case .вещь: весть = ВещьГабаритовText.т("fi_mode_on")
        case .коробка: весть = ЛинейкаГабаритовText.т("fr_mode_box_on")
        case .линейка: весть = ЛинейкаГабаритовText.т("fr_mode_ruler_on")
        }
        UIAccessibility.post(notification: .announcement, argument: весть)
        /* В вещь и коробку без размеров — сначала лист размеров (закроют пустым — обратно в линейку, безРазмеров()). */
        if сКорпусом && габариты == nil { листРазмеров = true }
    }

    /**
     Лист размеров закрыли, а размеров нет: коробку ставить не с чего, но линейке они не нужны — окно остаётся в режиме
     линейки (померить нишу или проём). false — линейки нет (рубильник, нет AR): окно закрывают.
     */
    func безРазмеров() -> Bool {
        guard Config.габаритыЛинейка, ОкноГабаритов.доступно, габариты == nil else { return false }
        if режим == .линейка {
            запустить()
        } else {
            сменитьРежим(.линейка)
            показать(ЛинейкаГабаритовText.т("fr_no_dims"))
        }
        return true
    }

    /// «Снимок» в линейке: кадр с отрезками — в тот же лист снимка (сессия на паузе, пока он открыт).
    func снятьЛинейку() {
        guard режим == .линейка else { return }
        линейка.снять { [weak self] готовый in
            guard let self else { return }
            guard let готовый else {
                self.показать(self.т("fb_shot_fail"))
                return
            }
            guard self.виден else { return }
            ОткликСайта.успех()
            self.снимок = готовый
        }
    }

    private func остановить() {
        guard идёт else { return }
        идёт = false
        #if !targetEnvironment(simulator)
        вид?.session.pause()
        #endif
    }

    fileprivate func плоскостиПришли(_ новые: [ПлоскостьГабаритов], убрать: [UUID]) {
        for плоскость in новые {
            if плоскость.стена {
                стены[плоскость.ид] = плоскость
            } else {
                полы.insert(плоскость.ид)
                if плоскость.нормаль.y > 0.5 { горизонтали[плоскость.ид] = плоскость.точка.y }
            }
        }
        /* Настольная вещь: ARKit узнал стол — скажем об этом один раз, пока вещь ещё не стоит. */
        if наСтоле && !столНайден && режим != .линейка && новые.contains(where: { $0.стол && !$0.стена }) {
            столНайден = true
            if этап != .стоит { показать(т("fb_desk_found")) }
        }
        for ид in убрать {
            стены[ид] = nil
            полы.remove(ид)
            горизонтали[ид] = nil
        }
        if этап == .ищемПол && !полы.isEmpty {
            этап = .можноСтавить
            if режим != .линейка { UIAccessibility.post(notification: .announcement, argument: т("fb_tap")) }
        }
        let стена = Config.габаритыСтена && !стены.isEmpty
        if стена != естьСтена { естьСтена = стена }
    }


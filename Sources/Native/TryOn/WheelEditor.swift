import SwiftUI

/**
 ПАРАМЕТРЫ КОЛЁС «ПРЯМ ПО ДИСКУ» — СБОРКА (владелец 16.10.2026, скрин «Параметры колёс»: пустые поля с подсказками
 «205/55 R16», «5x114.3», «67.1», «45», «17» → «стандартизация должна быть необычной, а прям по диску + камерой узнать
 размеры… выбор по стандартам… Шаблоны, чтобы были доступны»).

 Сверху вниз: шаблоны (ШаблоныКолеса — штатные машины, популярные наборы, сканер), плашка «Считали с шины: … —
 проверьте», живой диск (ЖивойДискКолеса) с лентой частей и панель выбранной части (ПанельКолеса), внизу которой —
 «Ввести вручную»: прежнее поле экрана. Значения — привязка экрана (ЗначенияКолеса): экран сам переводит их в свои строки
 или поля (СтрокиКолеса; подача — PostingSizeWheels.swift), так что данные, проверка и сохранение — прежние.
 Где стоит: «Моё» → гараж → машина (ПараметрыКолёсМоего), «Подойдут ли?» — машина и товар (ПараметрыМашиныАвтоподбора,
 ПараметрыТовараАвтоподбора), подача шин и дисков (БлокШинДисковПодачи).

 Сканер (СканерКолёс, WheelScan.swift) отдаёт маркировку (МаркировкаКолеса, WheelScanParse.swift): понятое ложится в
 значения, считанные части коротко вспыхивают, выбирается первая из них, а плашка просит проверить.
 */
struct РедакторКолеса<Ручной: View>: View {
    @Binding var значения: ЗначенияКолеса
    let состав: СоставКолеса
    let машина: МашинаАвтоподбора?
    /// «Популярные наборы» над диском (в подаче — нет: там свои образцы каталога).
    let наборы: Bool
    let ручной: (ЧастьКолеса) -> Ручной
    @State private var часть: ЧастьКолеса
    @State private var черновик = ЧерновикШины()
    @State private var вспышка: Set<ЧастьКолеса> = []
    @State private var скан: ЗаметкаКолеса? = nil

    init(значения: Binding<ЗначенияКолеса>, состав: СоставКолеса, машина: МашинаАвтоподбора? = nil,
         наборы: Bool = true, @ViewBuilder ручной: @escaping (ЧастьКолеса) -> Ручной) {
        _значения = значения
        self.состав = состав
        self.машина = машина
        self.наборы = наборы
        self.ручной = ручной
        _часть = State(initialValue: состав.части.first ?? .шина)
    }

    private func т(_ ключ: String) -> String { КолёсаText.т(ключ) }

    var body: some View {
        /* Значения читаются один раз на кадр: у экранов со строками это разбор всех полей, а чипов на панели — десятки. */
        let з = значения
        return VStack(alignment: .leading, spacing: 14) {
            if ШаблоныКолеса.естьЧтоПоказать(состав, машина: машина, наборы: наборы) {
                ШаблоныКолеса(значения: з, состав: состав, машина: машина, наборы: наборы, задать: { новые in
                    значения = новые
                }, сканировать: { что in
                    сканировать(что)
                })
            }
            if let скан {
                плашка(скан)
                    .transition(.opacity)
            }
            диск(з)
            ПанельКолеса(часть: часть, значения: з, черновик: $черновик, состав: состав, задать: { новые in
                значения = новые
            }, ручной: {
                ручной(часть)
            })
            .id(часть)
            .transition(.opacity)
        }
        .animation(ДвижениеСайта.смена, value: часть)
        .animation(ДвижениеСайта.появление, value: скан)
        .onChange(of: з.шина) { _, новая in
            if новая != nil && !черновик.пустой { черновик = ЧерновикШины() }
        }
        .onChange(of: состав) { _, новый in
            if !новый.есть(часть), let первая = новый.части.first { часть = первая }
        }
    }

    private func диск(_ з: ЗначенияКолеса) -> some View {
        let форма = RoundedRectangle(cornerRadius: Theme.Радиус.lg, style: .continuous)
        return VStack(spacing: 12) {
            ЖивойДискКолеса(значения: з, черновик: черновик, состав: состав, выбрана: часть,
                            вспышка: вспышка) { новая in
                выбрать(новая)
            }
            ЛентаЧастейКолеса(части: состав.части, значения: з, черновик: черновик, выбрана: часть) { новая in
                выбрать(новая)
            }
            Text(т("wh_tap_hint"))
                .font(.caption)
                .foregroundStyle(Theme.текстВторой)
                .multilineTextAlignment(.center)
                .frame(maxWidth: .infinity)
                .fixedSize(horizontal: false, vertical: true)
        }
        .padding(.vertical, 16)
        .padding(.horizontal, 12)
        .background(Theme.поверхность, in: форма)
        .overlay { форма.strokeBorder(Theme.линия, lineWidth: 1) }
    }

    private func выбрать(_ новая: ЧастьКолеса) {
        guard новая != часть else { return }
        ОткликСайта.выбор()
        часть = новая
    }

    private func плашка(_ заметка: ЗаметкаКолеса) -> some View {
        HStack(alignment: .top, spacing: 4) {
            ПлашкаКолеса(текст: заметка.текст, хорошо: заметка.хорошо)
            Button {
                скан = nil
            } label: {
                Image(systemName: "xmark")
                    .font(.footnote.weight(.bold))
                    .foregroundStyle(Theme.текстВторой)
                    .frame(width: 44, height: 44)
                    .contentShape(Rectangle())
            }
            .buttonStyle(.plain)
            .accessibilityLabel(т("wh_close"))
        }
    }

    // MARK: Сканер

    private func сканировать(_ что: ЧтоСканироватьКолеса) {
        ОткликСайта.выбор()
        СканерКолёс.открыть(что: что) { маркировка in
            принять(маркировка, что: что)
        }
    }

    /// Считанное — в значения: только правдоподобное и только части этого экрана. Другой R диска — как выбор R на ободе.
    private func принять(_ м: МаркировкаКолеса, что: ЧтоСканироватьКолеса) {
        var н = значения
        var черн = черновик
        var части: [ЧастьКолеса] = []
        var найдено: [String] = []
        if состав.шина, let ш = м.шина {
            let размер = РазмерШиныАвтоподбора(ширина: Double(ш.ширина), профиль: Double(ш.профиль), диаметр: ш.диаметр)
            if размер.годный {
                н.задатьШину(размер)
                if состав.диаметр { н.диаметр = размер.диаметр }
                черн = ЧерновикШины()
                части.append(.шина)
                найдено.append(размер.подпись)
            }
        }
        if let r = м.диаметрДиска, РазмерШиныАвтоподбора.диаметры.contains(r), состав.есть(.обод) {
            let подбор = н.сменитьДиаметр(r, состав: состав, черновик: &черн)
            части.append(.обод)
            найдено.append("R" + ЧислаАвтоподбора.ч(r))
            /* Другой R диска меняет и шину (у машины — на подобранную того же внешнего диаметра): не молча — шина
               вспыхивает, а в плашке «было → стало». */
            let была = подбор?.было ?? значения.шина
            if let новая = н.шина, новая != была, !части.contains(.шина) {
                части.append(.шина)
                найдено.append((была.map { $0.подпись + " → " } ?? "") + новая.подпись)
            }
        }
        if состав.ширинаJ, let j = м.ширинаJ, (3.5...13).contains(j) {
            н.ширинаJ = j
            if !части.contains(.обод) { части.append(.обод) }
            найдено.append(ЧислаАвтоподбора.ч(j) + "J")
        }
        if состав.et, let вылет = м.вылет, (-65...80).contains(вылет) {
            н.et = Double(вылет)...Double(вылет)
            части.append(.вылет)
            найдено.append("ET" + String(вылет))
        }
        if состав.pcd, let строка = м.pcd, let р = РазболтовкаАвтоподбора.изВвода(строка) {
            н.pcd = р
            части.append(.болты)
            найдено.append(р.подпись)
        }
        if состав.dia, let dia = м.ступица, (50...175).contains(dia) {
            н.dia = dia
            части.append(.центр)
            найдено.append("DIA " + ЧислаАвтоподбора.ч(dia, знаков: 2))
        }
        guard let первая = части.first else {
            ОткликСайта.предупреждение()
            скан = ЗаметкаКолеса(текст: т("wh_scan_none"), хорошо: false)
            return
        }
        ОткликСайта.успех()
        черновик = черн
        значения = н
        часть = первая
        скан = ЗаметкаКолеса(текст: String(format: т(что == .шина ? "wh_scanned_tire" : "wh_scanned_rim"),
                                           найдено.joined(separator: " · ")), хорошо: true)
        вспышка = Set(части)
        Task { @MainActor in
            try? await Task.sleep(nanoseconds: 2_400_000_000)
            вспышка = []
        }
    }
}

/// Плашка над диском: что считал сканер («проверьте») или почему не считал.
struct ЗаметкаКолеса: Equatable {
    let текст: String
    let хорошо: Bool
}

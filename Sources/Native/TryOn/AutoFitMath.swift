   · ширина обода — только если справочник знает штатные пределы.
 Шины: посадка R — к штатным дискам; размер против штатного — разница внешнего диаметра в %, ошибка спидометра при
 100 км/ч, изменение клиренса в мм; норма ±3 % — «подходит», больше — предупреждение; шире штатной на 20 мм — проверить
 арку. Колёса в сборе — диски и шины вместе (посадку проверяет диаметр диска).

 Итог — худший пункт: «Подходят ✓», «Подойдут с проставками / кольцами», «Не хватает данных» (чего — у продавца или в
 параметрах машины), «Подойдут, но проверьте», «Не подходят».
 */

// MARK: - Уровни и пункты

/// Насколько подходит пункт и весь товар. Порядок — от лучшего к худшему: итог — наибольший.
enum УровеньАвтоподбора: Int, Comparable, Sendable {
    case подходит = 0
    case доработка = 1
    case неизвестно = 2
    case проверить = 3
    case неПодходит = 4

    static func < (а: УровеньАвтоподбора, б: УровеньАвтоподбора) -> Bool { а.rawValue < б.rawValue }

    /// Слово для VoiceOver в начале строки пункта.
    var слово: String {
        switch self {
        case .подходит: return АвтоподборText.т("af_lvl_ok")
        case .доработка: return АвтоподборText.т("af_lvl_parts")
        case .неизвестно: return АвтоподборText.т("af_lvl_unknown")
        case .проверить: return АвтоподборText.т("af_lvl_check")
        case .неПодходит: return АвтоподборText.т("af_lvl_bad")
        }
    }
}

/// Чего не хватает для пункта «неизвестно»: в объявлении (спросить продавца) или в параметрах машины (дополнить самому).
enum ПробелАвтоподбора: Hashable, Sendable {
    case товар
    case машина
}

/// Какая деталь нужна для «Подойдут с …».
enum ДетальАвтоподбора: Hashable, Sendable {
    case кольца
    case проставки
}

/// Пункт сверки: заголовок («Вылет (ET)»), короткое имя для итога («вылет»), уровень и объяснение.
struct ПунктАвтоподбора: Identifiable, Hashable, Sendable {
    let id: String
    let уровень: УровеньАвтоподбора
    let заголовок: String
    let короткое: String
    let текст: String
    var пробел: ПробелАвтоподбора? = nil
    var деталь: ДетальАвтоподбора? = nil
}

// MARK: - Сравнение шин

/// Две шины рядом: что изменится, если вместо «было» поставить «стало». Скорость — сколько на самом деле, когда
/// спидометр (откалиброванный под «было») показывает своё.
struct СравнениеШинАвтоподбора: Hashable, Sendable {
    let было: РазмерШиныАвтоподбора
    let стало: РазмерШиныАвтоподбора

    /// Норма отличия внешнего диаметра, %.
    static let норма: Double = 3

    /// Разница внешнего диаметра, мм.
    var разницаМм: Double { стало.внешний - было.внешний }

    /// Разница внешнего диаметра, %.
    var процент: Double { было.внешний > 0 ? разницаМм / было.внешний * 100 : 0 }

    /// В пределах ±3 %.
    var вНорме: Bool { abs(процент) <= Self.норма + 0.005 }

    /// Настоящая скорость при показаниях спидометра.
    func скорость(_ поСпидометру: Double) -> Double {
        было.внешний > 0 ? поСпидометру * стало.внешний / было.внешний : поСпидометру
    }

    /// Изменение клиренса, мм: ось поднимается на половину разницы диаметров.
    var клиренс: Double { разницаМм / 2 }

    /// Разница ширины, мм.
    var ширина: Double { стало.ширина - было.ширина }
}

// MARK: - Итог

struct ВердиктАвтоподбора: Equatable, Sendable {
    let уровень: УровеньАвтоподбора
    let заголовок: String
    let подпись: String
    let пункты: [ПунктАвтоподбора]
    let сравнение: СравнениеШинАвтоподбора?
    /// Есть пункты «неизвестно» по машине — окно предложит дополнить её параметры.
    let нужныПараметрыМашины: Bool
}

// MARK: - Сверка

enum СверкаАвтоподбора {
    /// Допуск вылета вокруг штатного, мм.
    static let допускВылета: Double = 5
    /// Проставки, которые продают: подбираем ближайшую.
    static let проставки: [Double] = [3, 5, 8, 10, 12, 15, 20, 25]

    private static func т(_ ключ: String) -> String { АвтоподборText.т(ключ) }

    private static func ф(_ ключ: String, _ аргументы: String...) -> String {
        String(format: т(ключ), arguments: аргументы.map { $0 as CVarArg })
    }

    private static func ч(_ x: Double, знаков: Int = 1) -> String { ЧислаАвтоподбора.ч(x, знаков: знаков) }

    /**
     Итог товара для машины. размер — какой размер шин из объявления сверяем (их бывает два); штатный — с каким штатным
     размером машины сравниваем. nil — не поняли, шины это или диски, или сверять нечего.
     */
    static func вердикт(разбор р: РазборАвтоподбора, размер: РазмерШиныАвтоподбора?,
                        штатный: РазмерШиныАвтоподбора?, посадка п: ПосадкаАвтоподбора) -> ВердиктАвтоподбора? {
        guard let вид = р.вид else { return nil }
        var пункты: [ПунктАвтоподбора] = []
        var сравнение: СравнениеШинАвтоподбора? = nil
        switch вид {
        case .диски:
            пункты = дисков(р.диск, диаметр: р.диаметрДиска, посадка: п)
        case .колёса:
            пункты = дисков(р.диск, диаметр: р.диаметрДиска, посадка: п)
            let шины = шин(размер, диаметр: nil, посадка: п, штатный: штатный, проверятьПосадку: false)
            пункты += шины.пункты
            сравнение = шины.сравнение
        case .шины:
            let шины = шин(размер, диаметр: р.диаметрШины, посадка: п, штатный: штатный, проверятьПосадку: true)
            пункты = шины.пункты
            сравнение = шины.сравнение
        }
        guard let худший = пункты.map(\.уровень).max() else { return nil }
        return ВердиктАвтоподбора(уровень: худший, заголовок: заголовок(худший, пункты), подпись: подпись(худший, пункты),
                                  пункты: пункты, сравнение: сравнение,
                                  нужныПараметрыМашины: пункты.contains { $0.пробел == .машина })
    }

    private static func заголовок(_ уровень: УровеньАвтоподбора, _ пункты: [ПунктАвтоподбора]) -> String {
        switch уровень {
        case .подходит:
            return т("af_v_ok")
        case .доработка:
            let кольца = пункты.contains { $0.деталь == .кольца }
            let проставки = пункты.contains { $0.деталь == .проставки }
            if кольца && проставки { return т("af_v_both") }
            return т(кольца ? "af_v_rings" : "af_v_spacers")
        case .неизвестно:
            return т("af_v_unknown")
        case .проверить:
            return т("af_v_check")
        case .неПодходит:
            return т("af_v_bad")
        }
    }

    private static func подпись(_ уровень: УровеньАвтоподбора, _ пункты: [ПунктАвтоподбора]) -> String {
        func имена(_ условие: (ПунктАвтоподбора) -> Bool) -> String {
            пункты.filter(условие).map(\.короткое).joined(separator: ", ")
        }
        switch уровень {
        case .подходит:
            return т("af_vs_ok")
        case .доработка:
            let кольца = пункты.contains { $0.деталь == .кольца }
            let проставки = пункты.contains { $0.деталь == .проставки }
            if кольца && проставки { return т("af_vs_both") }
            return т(кольца ? "af_vs_rings" : "af_vs_spacers")
        case .неизвестно:
            var строки: [String] = []
            let совпало = имена { $0.уровень == .подходит }
            if !совпало.isEmpty { строки.append(ф("af_vs_matched", совпало)) }
            let уПродавца = имена { $0.уровень == .неизвестно && $0.пробел == .товар }
            if !уПродавца.isEmpty { строки.append(ф("af_vs_ask_seller", уПродавца)) }
            let уМашины = имена { $0.уровень == .неизвестно && $0.пробел == .машина }
            if !уМашины.isEmpty { строки.append(ф("af_vs_add_car", уМашины)) }
            return строки.joined(separator: "\n")
        case .проверить:
            return т("af_vs_check")
        case .неПодходит:
            return ф("af_vs_bad", имена { $0.уровень == .неПодходит })
        }
    }

    // MARK: Диски

    static func дисков(_ д: ДискАвтоподбора, диаметр: Double?, посадка п: ПосадкаАвтоподбора) -> [ПунктАвтоподбора] {
        var итог = [разболтовка(д.разболтовки, машина: п.разболтовка), отверстие(д.dia, машина: п.dia),
                    вылет(д.et, посадка: п), диаметрДиска(диаметр, посадка: п)]
        if let ширина = ширинаОбода(д.ширина, посадка: п) { итог.append(ширина) }
        return итог
    }

    private static func разболтовка(_ диска: [РазболтовкаАвтоподбора],
                                    машина: РазболтовкаАвтоподбора?) -> ПунктАвтоподбора {
        let заголовок = т("af_row_pcd")
        let короткое = т("af_n_pcd")
        guard let машина else {
            return ПунктАвтоподбора(id: "pcd", уровень: .неизвестно, заголовок: заголовок, короткое: короткое,
                                    текст: т("af_pcd_car_unknown"), пробел: .машина)
        }
        guard let первая = диска.first else {
            return ПунктАвтоподбора(id: "pcd", уровень: .неизвестно, заголовок: заголовок, короткое: короткое,
                                    текст: т("af_pcd_item_unknown"), пробел: .товар)
        }
        if let та = диска.first(where: { $0.совпадает(машина) }) {
            let текст = диска.count > 1 ? ф("af_pcd_ok_multi", та.подпись) : ф("af_pcd_ok", та.подпись)
            return ПунктАвтоподбора(id: "pcd", уровень: .подходит, заголовок: заголовок, короткое: короткое, текст: текст)
        }
        let ближняя = диска.first(where: { $0.отверстий == машина.отверстий }) ?? первая
        let текст: String
        if ближняя.отверстий != машина.отверстий {
            текст = ф("af_pcd_holes", ближняя.подпись, машина.подпись)
        } else if abs(ближняя.pcd - машина.pcd) <= 2.5 {
            текст = ф("af_pcd_close", ближняя.подпись, машина.подпись, ч(abs(ближняя.pcd - машина.pcd), знаков: 2))
        } else {
            текст = ф("af_pcd_bad", ближняя.подпись, машина.подпись)
        }
        return ПунктАвтоподбора(id: "pcd", уровень: .неПодходит, заголовок: заголовок, короткое: короткое, текст: текст)
    }

    private static func отверстие(_ диска: Double?, машина: Double?) -> ПунктАвтоподбора {
        let заголовок = т("af_row_dia")
        let короткое = т("af_n_dia")
        guard let машина else {
            return ПунктАвтоподбора(id: "dia", уровень: .неизвестно, заголовок: заголовок, короткое: короткое,
                                    текст: т("af_dia_car_unknown"), пробел: .машина)
        }
        guard let диска else {
            return ПунктАвтоподбора(id: "dia", уровень: .неизвестно, заголовок: заголовок, короткое: короткое,
                                    текст: т("af_dia_item_unknown"), пробел: .товар)
        }
        let разница = диска - машина
        if abs(разница) <= 0.15 {
            return ПунктАвтоподбора(id: "dia", уровень: .подходит, заголовок: заголовок, короткое: короткое,
                                    текст: ф("af_dia_ok", ч(диска, знаков: 2)))
        }
        if разница > 0 {
            return ПунктАвтоподбора(id: "dia", уровень: .доработка, заголовок: заголовок, короткое: короткое,
                                    текст: ф("af_dia_ring", ч(диска, знаков: 2), ч(машина, знаков: 2)),
                                    деталь: .кольца)
        }
        return ПунктАвтоподбора(id: "dia", уровень: .неПодходит, заголовок: заголовок, короткое: короткое,
                                текст: ф("af_dia_small", ч(диска, знаков: 2), ч(машина, знаков: 2)))
    }

    /// Штатный вылет строкой: «ET45» или «ET35…45».
    static func штатныйВылет(_ п: ПосадкаАвтоподбора) -> String? {
        guard let низ = п.etMin ?? п.etMax, let верх = п.etMax ?? п.etMin else { return nil }
        if abs(верх - низ) < 0.01 { return "ET" + ЧислаАвтоподбора.ч(низ) }
        return "ET" + ЧислаАвтоподбора.ч(min(низ, верх)) + "…" + ЧислаАвтоподбора.ч(max(низ, верх))
    }

    private static func вылет(_ et: Double?, посадка п: ПосадкаАвтоподбора) -> ПунктАвтоподбора {
        let заголовок = т("af_row_et")
        let короткое = т("af_n_et")
        guard let а = п.etMin ?? п.etMax, let б = п.etMax ?? п.etMin, let штатно = штатныйВылет(п) else {
            return ПунктАвтоподбора(id: "et", уровень: .неизвестно, заголовок: заголовок, короткое: короткое,
                                    текст: т("af_et_car_unknown"), пробел: .машина)
        }
        guard let et else {
            return ПунктАвтоподбора(id: "et", уровень: .неизвестно, заголовок: заголовок, короткое: короткое,
                                    текст: т("af_et_item_unknown"), пробел: .товар)
        }
        let низ = min(а, б)
        let верх = max(а, б)
        let своё = ч(et)
        func пункт(_ уровень: УровеньАвтоподбора, _ текст: String,
                   деталь: ДетальАвтоподбора? = nil) -> ПунктАвтоподбора {
            ПунктАвтоподбора(id: "et", уровень: уровень, заголовок: заголовок, короткое: короткое, текст: текст,
                             деталь: деталь)
        }
        if et >= низ - 0.01 && et <= верх + 0.01 {
            return пункт(.подходит, ф("af_et_ok", своё, штатно))
        }
        if et > верх {
            /* Вылет больше — колесо сидит глубже в арке, ближе к подвеске и тормозам. Проставка выносит его наружу. */
            let d = et - верх
            if d <= допускВылета { return пункт(.подходит, ф("af_et_tol", своё, ч(d), штатно)) }
            if d <= 25 {
                let нужна = проставки.min(by: { abs($0 - d) < abs($1 - d) }) ?? d
                return пункт(.доработка, ф("af_et_deep_spacer", своё, штатно, ч(d), ч(нужна)), деталь: .проставки)
            }
            return пункт(.неПодходит, ф("af_et_deep_bad", своё, штатно, ч(d)))
        }
        /* Вылет меньше — колесо выходит наружу, к краю арки; проставки тут не помогут. */
        let d = низ - et
        if d <= допускВылета { return пункт(.подходит, ф("af_et_tol", своё, ч(d), штатно)) }
        if d <= 15 { return пункт(.проверить, ф("af_et_out", своё, штатно, ч(d))) }
        return пункт(.неПодходит, ф("af_et_out_bad", своё, штатно, ч(d)))
    }

    /// Штатные диаметры строкой: «R16, R17, R18».
    static func списокДиаметров(_ диаметры: [Double]) -> String {
        диаметры.map { "R" + ЧислаАвтоподбора.ч($0) }.joined(separator: ", ")
    }

    private static func диаметрДиска(_ r: Double?, посадка п: ПосадкаАвтоподбора) -> ПунктАвтоподбора {
        let заголовок = т("af_row_diam")
        let короткое = т("af_n_diam")
        let штатные = п.штатныеДиаметры
        guard let наименьший = штатные.first, let наибольший = штатные.last else {
            return ПунктАвтоподбора(id: "diam", уровень: .неизвестно, заголовок: заголовок, короткое: короткое,
                                    текст: т("af_diam_car_unknown"), пробел: .машина)
        }
        guard let r else {
            return ПунктАвтоподбора(id: "diam", уровень: .неизвестно, заголовок: заголовок, короткое: короткое,
                                    текст: т("af_diam_item_unknown"), пробел: .товар)
        }
        let список = списокДиаметров(штатные)
        if r >= наименьший - 0.01 && r <= наибольший + 0.01 {
            return ПунктАвтоподбора(id: "diam", уровень: .подходит, заголовок: заголовок, короткое: короткое,
                                    текст: ф("af_diam_ok", ч(r), список))
        }
        let ключ = r > наибольший ? "af_diam_big" : "af_diam_small"
        return ПунктАвтоподбора(id: "diam", уровень: .проверить, заголовок: заголовок, короткое: короткое,
                                текст: ф(ключ, ч(r), список))
    }

    private static func ширинаОбода(_ ширина: Double?, посадка п: ПосадкаАвтоподбора) -> ПунктАвтоподбора? {
        guard let ширина, let а = п.ширинаMin ?? п.ширинаMax, let б = п.ширинаMax ?? п.ширинаMin else { return nil }
        let низ = min(а, б)
        let верх = max(а, б)
        let штатно = abs(верх - низ) < 0.01 ? ч(низ) + "J" : ч(низ) + "…" + ч(верх) + "J"
        let заголовок = т("af_row_width")
        let короткое = т("af_n_width")
        if ширина >= низ - 0.5 && ширина <= верх + 0.5 {
            return ПунктАвтоподбора(id: "width", уровень: .подходит, заголовок: заголовок, короткое: короткое,
                                    текст: ф("af_width_ok", ч(ширина), штатно))
        }
        return ПунктАвтоподбора(id: "width", уровень: .проверить, заголовок: заголовок, короткое: короткое,
                                текст: ф("af_width_bad", ч(ширина), штатно))
    }

    // MARK: Шины

    private static func шин(_ размер: РазмерШиныАвтоподбора?, диаметр: Double?, посадка п: ПосадкаАвтоподбора,
                            штатный: РазмерШиныАвтоподбора?,
                            проверятьПосадку: Bool) -> (пункты: [ПунктАвтоподбора], сравнение: СравнениеШинАвтоподбора?) {
        var итог: [ПунктАвтоподбора] = []
        if проверятьПосадку {
            итог.append(посадкаШины(размер?.диаметр ?? диаметр, посадка: п))
        }
        guard let размер else {
            итог.append(ПунктАвтоподбора(id: "size", уровень: .неизвестно, заголовок: т("af_row_size"),
                                         короткое: т("af_n_size"), текст: т("af_size_item_unknown"), пробел: .товар))
            return (итог, nil)
        }
        if п.шины.contains(размер) {
            итог.append(ПунктАвтоподбора(id: "size", уровень: .подходит, заголовок: т("af_row_size"),
                                         короткое: т("af_n_size"), текст: ф("af_size_stock", размер.подпись)))
        }
        guard let штатный else {
            итог.append(ПунктАвтоподбора(id: "outer", уровень: .неизвестно, заголовок: т("af_row_outer"),
                                         короткое: т("af_n_stock"), текст: т("af_outer_car_unknown"),
                                         пробел: .машина))
            return (итог, nil)
        }
        let с = СравнениеШинАвтоподбора(было: штатный, стало: размер)
        let уровень: УровеньАвтоподбора = с.вНорме ? .подходит : .проверить
        let процент = ЧислаАвтоподбора.соЗнаком(с.процент) + "%"
        let норма = "±" + ч(СравнениеШинАвтоподбора.норма) + "%"
        итог.append(ПунктАвтоподбора(id: "outer", уровень: уровень, заголовок: т("af_row_outer"),
                                     короткое: т("af_n_outer"),
                                     текст: ф(с.вНорме ? "af_outer_ok" : "af_outer_bad", ч(размер.внешний, знаков: 0),
                                              ч(штатный.внешний, знаков: 0), штатный.подпись, процент, норма)))
        итог.append(ПунктАвтоподбора(id: "speedo", уровень: уровень, заголовок: т("af_row_speedo"),
                                     короткое: т("af_n_speedo"), текст: ф("af_speedo", ч(с.скорость(100)))))
        let клиренс: String
        if abs(с.клиренс) < 0.5 {
            клиренс = т("af_clear_same")
        } else {
            клиренс = ф(с.клиренс > 0 ? "af_clear_up" : "af_clear_down", ч(abs(с.клиренс), знаков: 0))
        }
        итог.append(ПунктАвтоподбора(id: "clear", уровень: уровень, заголовок: т("af_row_clear"),
                                     короткое: т("af_n_clear"), текст: клиренс))
        if с.ширина > 20 {
            итог.append(ПунктАвтоподбора(id: "wide", уровень: .проверить, заголовок: т("af_row_tire_width"),
                                         короткое: т("af_n_tire_width"), текст: ф("af_wide", ч(с.ширина, знаков: 0))))
        }
        return (итог, с)
    }

    private static func посадкаШины(_ r: Double?, посадка п: ПосадкаАвтоподбора) -> ПунктАвтоподбора {
        let заголовок = т("af_row_seat")
        let короткое = т("af_n_seat")
        let штатные = п.штатныеДиаметры
        guard let r else {
            return ПунктАвтоподбора(id: "seat", уровень: .неизвестно, заголовок: заголовок, короткое: короткое,
                                    текст: т("af_seat_item_unknown"), пробел: .товар)
        }
        guard !штатные.isEmpty else {
            return ПунктАвтоподбора(id: "seat", уровень: .неизвестно, заголовок: заголовок, короткое: короткое,
                                    текст: т("af_seat_car_unknown"), пробел: .машина)
        }
        if штатные.contains(where: { abs($0 - r) < 0.01 }) {
            return ПунктАвтоподбора(id: "seat", уровень: .подходит, заголовок: заголовок, короткое: короткое,
                                    текст: ф("af_seat_ok", ч(r)))
        }
        return ПунктАвтоподбора(id: "seat", уровень: .проверить, заголовок: заголовок, короткое: короткое,
                                текст: ф("af_seat_other", ч(r), списокДиаметров(штатные)))
    }

    /**
     С каким штатным размером сравнивать шину товара: с тем же посадочным диаметром, а если такого нет — ближайший по
     внешнему диаметру. Нет ни одного штатного — nil.
     */
    static func штатныйДля(_ размер: РазмерШиныАвтоподбора?, из штатных: [РазмерШиныАвтоподбора]) -> РазмерШиныАвтоподбора? {
        guard let первый = штатных.first else { return nil }
        guard let размер else { return первый }
        if let тот = штатных.first(where: { $0 == размер }) { return тот }
        let тотЖеДиаметр = штатных.filter { abs($0.диаметр - размер.диаметр) < 0.01 }
        let выбор = тотЖеДиаметр.isEmpty ? штатных : тотЖеДиаметр
        return выбор.min(by: { abs($0.внешний - размер.внешний) < abs($1.внешний - размер.внешний) }) ?? первый
    }

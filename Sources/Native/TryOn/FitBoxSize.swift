// MARK: - Размеры

/// Размеры коробки в сантиметрах: ширина — вдоль лицевой стороны, высота — от пола, глубина — от лица к спинке.
struct ГабаритыВещи: Equatable, Sendable {
    var ширина: Double
    var высота: Double
    var глубина: Double

    /// Разумные пределы одного размера, см: от полусантиметра (ковёр) до 10 м.
    static let пределы: ClosedRange<Double> = 0.5...1000

    var годны: Bool {
        Self.пределы.contains(ширина) && Self.пределы.contains(высота) && Self.пределы.contains(глубина)
    }

    /// В метрах для сцены: x — ширина, y — высота, z — глубина.
    var метры: SIMD3<Float> {
        SIMD3<Float>(Float(ширина / 100), Float(высота / 100), Float(глубина / 100))
    }

    /// Число для подписи: целое — без дробной части, иначе одна цифра после запятой (у ru и kk — запятая).
    static func число(_ см: Double) -> String {
        let округлено = (см * 10).rounded() / 10
        if округлено == округлено.rounded() { return String(Int(округлено)) }
        let текст = String(format: "%.1f", округлено)
        let язык = ПримерочнаяText.язык
        return язык == "ru" || язык == "kk" ? текст.replacingOccurrences(of: ".", with: ",") : текст
    }

    /// «60 × 85 × 55» — ширина, высота, глубина.
    var строка: String {
        Self.число(ширина) + " × " + Self.число(высота) + " × " + Self.число(глубина)
    }
}

/// Откуда размеры.
enum ИсточникГабаритов: Equatable, Sendable {
    /// Из характеристик объявления.
    case характеристики
    /// Из описания или названия: кусок текста, где нашли.
    case описание(String)
    /// Примерно — по диагонали экрана в дюймах.
    case диагональ(Double)
    /// Не нашли.
    case нет
}

/// Что нашли в объявлении. Любое поле может быть пустым — его допишет человек.
struct НайденныеГабариты: Equatable, Sendable {
    var ширина: Double? = nil
    var высота: Double? = nil
    var глубина: Double? = nil
    /// Можно ставить коробку сразу, не спрашивая: все три из характеристик, порядок и единицы ясны.
    var надёжно = false
    var источник: ИсточникГабаритов = .нет

    /// Все три размера и в пределах — иначе nil.
    var полные: ГабаритыВещи? {
        guard let ш = ширина, let в = высота, let г = глубина else { return nil }
        let итог = ГабаритыВещи(ширина: ш, высота: в, глубина: г)
        return итог.годны ? итог : nil
    }

    /// Хоть что-то нашли.
    var пусто: Bool { ширина == nil && высота == nil && глубина == nil }
}

// MARK: - Разбор

enum РазборГабаритов {
    /// Что берём из объявления — одни значения: разбор можно звать где угодно.
    struct Исходник: Sendable {
        struct Пара: Sendable {
            let ключ: String
            let значение: String
        }

        var раздел: String?
        var название: String
        var описание: String
        var характеристики: [Пара]
        /// Плоское поле storage: у телевизоров и мониторов сайт кладёт туда диагональ, у мебели — «Размер».
        var накопитель: String?

        init(раздел: String?, название: String, описание: String, характеристики: [Пара], накопитель: String?) {
            self.раздел = раздел
            self.название = название
            self.описание = описание
            self.характеристики = характеристики
            self.накопитель = накопитель
        }

        init(_ товар: Listing) {
            раздел = товар.категория
            название = товар.title
            /* Описание бывает длинным — размеры, если есть, обычно в начале. */
            описание = String((товар.описание ?? "").prefix(4000))
            характеристики = товар.характеристики.map { Пара(ключ: $0.ключ, значение: $0.значение) }
            накопитель = товар.storageСтрокой
        }
    }

    static func найти(_ товар: Listing) -> НайденныеГабариты {
        разобрать(Исходник(товар))
    }

    static func разобрать(_ и: Исходник) -> НайденныеГабариты {
        let рамки = Self.рамки(и.раздел)
        let ковёр = РазделыСайта.внутри(и.раздел, ["carpets"])
        var замер = изХарактеристик(и, рамки: рамки)
        var источник: ИсточникГабаритов = замер == nil ? .нет : .характеристики

        if !(замер?.полный ?? false) {
            for текст in [и.описание, и.название] where !текст.isEmpty {
                guard let найденное = изТекста(текст, рамки: рамки, раздел: и.раздел) else { continue }
                let замерТекста = найденное.замер
                if var прежний = замер {
                    let было = прежний.сколько
                    прежний.дополнить(замерТекста)
                    if прежний.сколько > было {
                        прежний.надёжно = false
                        источник = .описание(найденное.кусок)
                    }
                    замер = прежний
                } else {
                    var новый = замерТекста
                    новый.надёжно = false
                    замер = новый
                    источник = .описание(найденное.кусок)
                }
                break
            }
        }

        /* Ковёр: два размера — это ширина и длина, высоту берём за сантиметр. */
        if ковёр, var з = замер, з.высота == nil, з.ширина != nil, з.глубина != nil {
            з.высота = 1
            замер = з
        }

        if замер == nil || замер?.пусто == true,
           Config.габаритыПоДиагонали,
           РазделыСайта.внутри(и.раздел, ["tv", "monitors"]),
           let оценка = поДиагонали(и) {
            return оценка
        }

        guard let итог = замер else { return НайденныеГабариты() }
        var найдено = НайденныеГабариты(ширина: итог.ширина, высота: итог.высота, глубина: итог.глубина)
        найдено.источник = источник
        найдено.надёжно = итог.надёжно && источник == .характеристики && найдено.полные != nil
        return найдено
    }

    // MARK: Замер

    private enum Роль {
        case ширина, высота, глубина, длина
    }

    private enum Единица {
        case мм, см, м

        var множитель: Double {
            switch self {
            case .мм: return 0.1
            case .см: return 1
            case .м: return 100
            }
        }
    }

    /// Найденное в одном месте, уже в сантиметрах.
    private struct Замер {
        var ширина: Double? = nil
        var высота: Double? = nil
        var глубина: Double? = nil
        var надёжно = true

        var сколько: Int { [ширина, высота, глубина].compactMap { $0 }.count }
        var полный: Bool { сколько == 3 }
        var пусто: Bool { сколько == 0 }

        /// Пустые поля — из другого замера.
        mutating func дополнить(_ другой: Замер) {
            if ширина == nil { ширина = другой.ширина }
            if высота == nil { высота = другой.высота }
            if глубина == nil { глубина = другой.глубина }
        }
    }

    /// Сырое значение до единиц: роль, число и единица, если её назвали.
    private struct Сырое {
        let роль: Роль
        let число: Double
        let единица: Единица?
    }

    /// Разумные размеры раздела, см: наибольший допустимый и наименьший «самый большой размер» вещи.
    private struct Рамки {
        let наибольший: Double
        let малый: Double
    }

    private static let таблицаРамок: [(раздел: String, наибольший: Double, малый: Double)] = [
        ("microwaves", 90, 25), ("monitors", 130, 25), ("dishwashers", 100, 35), ("washing-machines", 110, 45),
        ("stoves", 130, 35), ("water-heaters", 200, 25), ("air-conditioners", 200, 30), ("fridges", 230, 40),
        ("tv", 250, 35), ("home-theater", 250, 15), ("carpets", 1000, 40), ("treadmills", 260, 70),
        ("exercise-bikes", 200, 50), ("gaming-chairs", 200, 40), ("aquariums", 300, 15),
        ("kids-furniture", 300, 25), ("furniture", 600, 25)
    ]

    private static func рамки(_ раздел: String?) -> Рамки {
        for запись in таблицаРамок where РазделыСайта.внутри(раздел, [запись.раздел]) {
            return Рамки(наибольший: запись.наибольший, малый: запись.малый)
        }
        return Рамки(наибольший: 600, малый: 10)
    }

    /**
     Сырые значения → сантиметры. Единица названа — берём её; не названа — пробуем см, мм и м и оставляем толкования,
     при которых все размеры в пределах раздела, а самый большой — не меньше «малого». Одно толкование — надёжно;
     несколько — берём сантиметры (или первое подошедшее), но «сомнительно»; ни одного — nil.
     */
    private static func вСантиметры(_ сырые: [Сырое], рамки: Рамки) -> Замер? {
        guard !сырые.isEmpty else { return nil }
        func перевод(_ догадка: Единица) -> [Double] {
            сырые.map { $0.число * ($0.единица ?? догадка).множитель }
        }
        func годится(_ значения: [Double]) -> Bool {
            let вПределах = значения.allSatisfy { $0 >= 0.5 && $0 <= рамки.наибольший }
            return вПределах && наибольшийНеМал(значения, рамки: рамки)
        }
        let безЕдиниц = сырые.contains { $0.единица == nil }
        var подошли: [[Double]] = []
        for догадка in безЕдиниц ? [Единица.см, .мм, .м] : [Единица.см] {
            let значения = перевод(догадка)
            if годится(значения) { подошли.append(значения) }
        }
        guard let выбранные = подошли.first else { return nil }
        var замер = Замер()
        замер.надёжно = подошли.count == 1
        for (номер, сырое) in сырые.enumerated() {
            let см = (выбранные[номер] * 10).rounded() / 10
            switch сырое.роль {
            case .ширина: if замер.ширина == nil { замер.ширина = см }
            case .высота: if замер.высота == nil { замер.высота = см }
            case .глубина: if замер.глубина == nil { замер.глубина = см }
            case .длина: break
            }
        }
        /* Длина — длинная горизонтальная сторона: в ширину; прежняя ширина тогда — глубина (Д×Ш×В у диванов). */
        if let номер = сырые.firstIndex(where: { $0.роль == .длина }) {
            let длина = (выбранные[номер] * 10).rounded() / 10
            if замер.ширина == nil {
                замер.ширина = длина
            } else if замер.глубина == nil {
                замер.глубина = замер.ширина
                замер.ширина = длина
            }
        }
        return замер
    }

    /// Самый большой размер не меньше «малого» раздела: 60×85×55 мм — не стиральная машина.
    private static func наибольшийНеМал(_ значения: [Double], рамки: Рамки) -> Bool {
        guard значения.count >= 2, let наибольшее = значения.max() else { return true }
        return наибольшее >= рамки.малый
    }


    /// Слова строки (только буквы), в нижнем регистре.
    private static func слова(_ текст: String) -> [String] {
        текст.lowercased().split(whereSeparator: { !$0.isLetter }).map(String.init)
    }

    private static func естьНачало(_ слова: [String], _ начала: [String]) -> Bool {
        слова.contains { слово in начала.contains { слово.hasPrefix($0) } }
    }

    private static func рольПоля(_ слова: [String]) -> Роль? {
        for (роль, начала) in словаРолей where естьНачало(слова, начала) { return роль }
        return nil
    }

    private static func изХарактеристик(_ и: Исходник, рамки: Рамки) -> Замер? {
        var отдельные: [Сырое] = []
        var составной: (сырые: [Сырое], надёжно: Bool)? = nil
        var пары = и.характеристики
        /* Плоское storage: у мебели сайт кладёт туда «Размер» — берём, только если specs пусты. */
        if пары.isEmpty, let накопитель = и.накопитель, !РазделыСайта.внутри(и.раздел, ["tv", "monitors"]) {
            пары.append(Исходник.Пара(ключ: "Размер", значение: накопитель))
        }
        for пара in пары {
            let имя = пара.ключ
            let словаИмени = слова(имя)
            guard !естьНачало(словаИмени, чужиеСлова) else { continue }
            let единицаИмени = единица(имя)
            let габариты = естьНачало(словаИмени, словаГабаритов)
            let роль = рольПоля(словаИмени)
            let порядок = порядокБукв(имя) ?? порядокСлов(словаИмени) ?? порядокБукв(пара.значение)
            /* «Габариты», «Размер», «Ш×В×Г» — все размеры в одном значении. Не вышло, а поле про один размер
               («Габаритная ширина: 60 см») — читаем как отдельное. Незнакомые поля («Мощность: 2 x 50 Вт»)
               не трогаем. */
            if габариты || порядок != nil,
               let найдено = составное(пара.значение, порядок: порядок, единица: единицаИмени, раздел: и.раздел) {
                if составной == nil || (составной?.сырые.count ?? 0) < найдено.сырые.count {
                    составной = найдено
                }
                continue
            }
            guard let роль, !отдельные.contains(where: { $0.роль == роль }),
                  let первое = первоеЧисло(пара.значение) else { continue }
            отдельные.append(Сырое(роль: роль, число: первое.число, единица: первое.единица ?? единицаИмени))
        }

        var итог: Замер? = nil
        if !отдельные.isEmpty {
            итог = вСантиметры(отдельные, рамки: рамки)
        }
        if let составной, let изСоставного = вСантиметры(составной.сырые, рамки: рамки) {
            if var прежний = итог {
                if !прежний.полный {
                    let было = прежний.сколько
                    прежний.дополнить(изСоставного)
                    if прежний.сколько > было {
                        прежний.надёжно = прежний.надёжно && изСоставного.надёжно && составной.надёжно
                    }
                    итог = прежний
                }
            } else {
                var новый = изСоставного
                новый.надёжно = новый.надёжно && составной.надёжно
                итог = новый
            }
        }
        if let з = итог, з.пусто { return nil }
        return итог
    }

    // MARK: Числа, единицы, порядок

    /// Число: «60», «0,55», «2.2».
    private static let образецЧисла = "(\\d{1,5}(?:[.,]\\d{1,2})?)"
    /// Необязательная единица сразу после числа: мм, см, м (не начало слова «мебель»).
    private static let образецЕдиницы = "(?:\\s*(мм|mm|см|cm|м|m)(?![\\p{L}\\d²]))?"
    /// Разделитель размеров: x, х (кириллица), ×, *.
    private static let образецРаздела = "\\s*[xх×*]\\s*"

    /// «60×85×55 см», «600 x 850 x 550мм», «1,8 х 2 м», «190×110».
    private static var образецСоставного: String {
        "(?<![\\d.,])" + образецЧисла + образецЕдиницы + образецРаздела + образецЧисла + образецЕдиницы
            + "(?:" + образецРаздела + образецЧисла + образецЕдиницы + ")?"
    }

    /// То же, но разделитель может быть и косой.
    private static var образецСоставногоКосая: String {
        let раздел = "\\s*[/xх×*]\\s*"
        return "(?<![\\d.,/])" + образецЧисла + образецЕдиницы + раздел + образецЧисла + образецЕдиницы
            + "(?:" + раздел + образецЧисла + образецЕдиницы + ")?"
    }

    private static func единица(_ текст: String) -> Единица? {
        let т = текст.lowercased()
        func есть(_ образец: String) -> Bool {
            т.range(of: образец, options: .regularExpression) != nil
        }
        if есть("(?<![\\p{L}])(мм|mm|миллиметр\\p{L}*)(?![\\p{L}])") { return .мм }
        if есть("(?<![\\p{L}])(см|cm|сантиметр\\p{L}*)(?![\\p{L}])") { return .см }
        if есть("(?<![\\p{L}])(м|m|метр\\p{L}*)(?![\\p{L}²])") { return .м }
        return nil
    }

    private static func единица(кода код: String?) -> Единица? {
        /* Строка, а не String?: образец-литерал с необязательным значением компилятор не сопоставляет. */
        switch (код ?? "").lowercased() {
        case "мм", "mm": return .мм
        case "см", "cm": return .см
        case "м", "m": return .м
        default: return nil
        }
    }

    private static func число(_ текст: String?) -> Double? {
        guard let текст else { return nil }
        return Double(текст.replacingOccurrences(of: ",", with: "."))
    }

    /// Первое число строки и единица сразу после него. Единица где-то в строке — только когда число в ней одно:
    /// в «55" (140 см)» и «60 (с ручкой 650 мм)» она про другое число.
    private static func первоеЧисло(_ текст: String) -> (число: Double, единица: Единица?)? {
        let все = совпадения(образецЧисла + образецЕдиницы, в: текст)
        guard let с = все.first, let значение = число(с.группы[1]) else { return nil }
        let своя = единица(кода: с.группы[2])
        return (число: значение, единица: своя ?? (все.count == 1 ? единица(текст) : nil))
    }

    /// Порядок по словам названия поля: «Высота x Ширина x Глубина», «Ширина/Высота/Глубина, см» — две роли и больше.
    private static func порядокСлов(_ слова: [String]) -> [Роль]? {
        var роли: [Роль] = []
        for слово in слова {
            guard let роль = словаРолей.first(where: { пара in пара.1.contains { слово.hasPrefix($0) } })?.0,
                  !роли.contains(роль) else { continue }
            роли.append(роль)
        }
        return роли.count >= 2 ? роли : nil
    }

    /// Порядок по буквам: «Ш×В×Г», «ДхШхВ», «W x H x D», «Ш/Г/В».
    private static func порядокБукв(_ текст: String) -> [Роль]? {
        let образец = "(?<![\\p{L}])([швгдwhdl])\\s*[/xх×*]\\s*([швгдwhdl])(?:\\s*[/xх×*]\\s*([швгдwhdl]))?(?![\\p{L}])"
        guard let с = совпадения(образец, в: текст.lowercased()).first else { return nil }
        let роли = с.группы.dropFirst().compactMap { буква -> Роль? in
            guard let буква, let первая = буква.first else { return nil }
            switch первая {
            case "ш", "w": return .ширина
            case "в", "h": return .высота
            case "г", "d": return .глубина
            case "д", "l": return .длина
            default: return nil
            }
        }
        /* Две одинаковые буквы — это не порядок. */
        guard роли.count >= 2 else { return nil }
        for (номер, роль) in роли.enumerated() where роли[(номер + 1)...].contains(роль) { return nil }
        return роли
    }

    /// Значение «60×85×55 см» → сырые по ролям. порядок — буквы, если известны; единица — из названия поля.
    private static func составное(_ значение: String, порядок: [Роль]?, единица единицаИмени: Единица?,
                                 раздел: String?) -> (сырые: [Сырое], надёжно: Bool)? {
        /* Через косую («60/85/55») — только когда порядок назван буквами или словами поля: в свободном тексте косая
           бывает чем угодно. */
        let через = порядок == nil ? nil : совпадения(образецСоставногоКосая, в: значение).first
        guard let с = совпадения(образецСоставного, в: значение).first ?? через else { return nil }
        return сырыеСоставного(с, порядок: порядок, единица: единицаИмени ?? единица(значение), раздел: раздел)
    }

    private static func сырыеСоставного(_ с: Совпадение, порядок: [Роль]?, единица общая: Единица?,
                                       раздел: String?) -> (сырые: [Сырое], надёжно: Bool)? {
        var числа: [Double] = []
        var единицы: [Единица?] = []
        for номер in [1, 3, 5] {
            guard let значение = число(с.группы[номер]) else { continue }
            числа.append(значение)
            единицы.append(единица(кода: с.группы[номер + 1]))
        }
        guard числа.count >= 2 else { return nil }
        /* Единица у последнего числа — на все («60×85×55 см»). */
        let последняя = единицы.compactMap { $0 }.last ?? общая
        var роли: [Роль]
        var надёжно = true
        if let порядок, порядок.count >= числа.count {
            роли = Array(порядок.prefix(числа.count))
        } else if числа.count == 3 {
            надёжно = false
            роли = [.ширина, .высота, .глубина]
            /* Холодильник и шкаф — самое большое обычно высота: «60×65×185» — это Ш×Г×В. */
            if РазделыСайта.внутри(раздел, ["fridges", "wardrobes"]),
               let наибольший = числа.indices.max(by: { числа[$0] < числа[$1] }), наибольший != 1 {
                роли = [.ширина, .глубина]
                роли.insert(.высота, at: наибольший)
            }
        } else {
            /* Два числа без букв: ширина и глубина (ковёр, кровать, «Размер 190×110» у мебели). */
            надёжно = РазделыСайта.внутри(раздел, ["carpets"])
            роли = [.ширина, .глубина]
        }
        let сырые = числа.indices.map { номер in
            Сырое(роль: роли[номер], число: числа[номер], единица: единицы[номер] ?? последняя)
        }
        return (сырые, надёжно)
    }

    // MARK: Описание и название

    /**
     Размеры в свободном тексте. Сначала «ширина 60 см, высота 85…» (слово и число рядом), потом «60×85×55» — но только
     если рядом «габариты», «размер», буквы порядка, названа единица или в тексте уже есть размер словом («Стол 120x80,
     высота 75 см»), и не про экран, упаковку, нишу, спальное место. Размеры словом важнее чисел через «×».
     Возвращает замер и кусок текста вокруг найденного — показать человеку, откуда взяли.
     */
    private static func изТекста(_ текст: String, рамки: Рамки, раздел: String?) -> (замер: Замер, кусок: String)? {
        var сырые: [Сырое] = []
        var кусок: Range<String.Index>? = nil
        let образецСлов = "(?<![\\p{L}])(ширин|высот|глубин|длин|width|height|depth|length)\\p{L}*\\s*[:\\-–—=]?\\s*"
            + "(?:около|примерно|~|до)?\\s*" + образецЧисла + образецЕдиницы
        for с in совпадения(образецСлов, в: текст) {
            guard !чужоеРядом(текст, перед: с.место.lowerBound),
                  let слово = с.группы[1]?.lowercased(),
                  let значение = число(с.группы[2]) else { continue }
            let роль: Роль
            if слово.hasPrefix("ширин") || слово == "width" {
                роль = .ширина
            } else if слово.hasPrefix("высот") || слово == "height" {
                роль = .высота
            } else if слово.hasPrefix("глубин") || слово == "depth" {
                роль = .глубина
            } else {
                роль = .длина
            }
            guard !сырые.contains(where: { $0.роль == роль }) else { continue }
            сырые.append(Сырое(роль: роль, число: значение, единица: единица(кода: с.группы[3])))
            кусок = кусок.map { min($0.lowerBound, с.место.lowerBound)..<max($0.upperBound, с.место.upperBound) }
                ?? с.место
        }
        let изСлов = сырые.isEmpty ? nil : вСантиметры(сырые, рамки: рамки)
        if сырые.count >= 2, let изСлов, let кусок {
            return (замер: изСлов, кусок: вырезка(текст, кусок))
        }

        for с in совпадения(образецСоставного, в: текст) {
            guard !чужоеРядом(текст, перед: с.место.lowerBound), !экранПосле(текст, после: с.место.upperBound) else {
                continue
            }
            let начало = текст.index(с.место.lowerBound, offsetBy: -40, limitedBy: текст.startIndex) ?? текст.startIndex
            let перед = String(текст[начало..<с.место.lowerBound])
            let порядок = порядокБукв(перед)
            let естьЕдиница = с.группы[2] != nil || с.группы[4] != nil || с.группы[6] != nil
            let словаПеред = слова(перед)
            guard порядок != nil || естьЕдиница || естьНачало(словаПеред, словаГабаритов) || изСлов != nil else {
                continue
            }
            guard let найдено = сырыеСоставного(с, порядок: порядок, единица: nil, раздел: раздел),
                  let изЧисел = вСантиметры(найдено.сырые, рамки: рамки) else { continue }
            var замер = изЧисел
            var место = с.место
            if let изСлов, let кусок {
                замер = изСлов
                замер.дополнить(изЧисел)
                место = min(кусок.lowerBound, место.lowerBound)..<max(кусок.upperBound, место.upperBound)
            }
            return (замер: замер, кусок: вырезка(текст, место))
        }
        /* Один размер словом — хоть он: остальные допишет человек. */
        if let изСлов, let кусок {
            return (замер: изСлов, кусок: вырезка(текст, кусок))
        }
        return nil
    }

    /// Перед местом (до 30 знаков) — слова про часть вещи, упаковку, экран.
    private static func чужоеРядом(_ текст: String, перед место: String.Index) -> Bool {
        let начало = текст.index(место, offsetBy: -30, limitedBy: текст.startIndex) ?? текст.startIndex
        return естьНачало(слова(String(текст[начало..<место])), чужиеСлова)
    }

    /// Сразу после чисел — «px», «пикс», «dpi», «Гц», «p»: это разрешение, а не размеры.
    private static func экранПосле(_ текст: String, после место: String.Index) -> Bool {
        let конец = текст.index(место, offsetBy: 8, limitedBy: текст.endIndex) ?? текст.endIndex
        let хвост = String(текст[место..<конец]).lowercased().trimmingCharacters(in: .whitespaces)
        return ["px", "пикс", "dpi", "гц", "hz", "p ", "p,", "p."].contains { хвост.hasPrefix($0) } || хвост == "p"
    }

    /// Кусок текста вокруг найденного: до 40 знаков с каждой стороны, в одну строку, с многоточиями.
    private static func вырезка(_ текст: String, _ место: Range<String.Index>) -> String {
        let начало = текст.index(место.lowerBound, offsetBy: -40, limitedBy: текст.startIndex) ?? текст.startIndex
        let конец = текст.index(место.upperBound, offsetBy: 40, limitedBy: текст.endIndex) ?? текст.endIndex
        let середина = String(текст[начало..<конец])
            .components(separatedBy: .whitespacesAndNewlines)
            .filter { !$0.isEmpty }
            .joined(separator: " ")
        return (начало > текст.startIndex ? "…" : "") + середина + (конец < текст.endIndex ? "…" : "")
    }

    // MARK: Диагональ

    /**
     Телевизор и монитор: экран по диагонали (16:9; 21:9 и 32:9 — по разрешению или названию), плюс рамка, подставка и
     её глубина. Это оценка — всегда «примерно», лист с размерами открывается.
     */
    private static func поДиагонали(_ и: Исходник) -> НайденныеГабариты? {
        var дюймы: Double? = nil
        for пара in и.характеристики where естьНачало(слова(пара.ключ), ["диагон", "diagonal"]) {
            if let первое = первоеЧисло(пара.значение) {
                дюймы = первое.единица == .см ? первое.число / 2.54 : первое.число
                break
            }
        }
        if дюймы == nil, let накопитель = и.накопитель, let первое = первоеЧисло(накопитель) {
            дюймы = первое.число
        }
        if дюймы == nil {
            let образец = "(?<![\\d.,])(\\d{2,3}(?:[.,]\\d)?)\\s*(?:\"|″|”|''|-?\\s*дюйм|inch|in(?![\\p{L}]))"
            for текст in [и.название, и.описание] {
                if let с = совпадения(образец, в: текст).first, let значение = число(с.группы[1]) {
                    дюймы = значение
                    break
                }
            }
        }
        guard let дюймы, (15...120).contains(дюймы) else { return nil }
        let монитор = РазделыСайта.внутри(и.раздел, ["monitors"])
        let всё = (и.характеристики.map { $0.значение }.joined(separator: " ") + " " + и.название).lowercased()
        func есть(_ образец: String) -> Bool { всё.range(of: образец, options: .regularExpression) != nil }
        let стороны: (Double, Double)
        if есть("5120|3840\\s*[xх×]\\s*1080|32:9") {
            стороны = (32, 9)
        } else if есть("3440|2560\\s*[xх×]\\s*1080|21:9|ultrawide|uwqhd") {
            стороны = (21, 9)
        } else {
            стороны = (16, 9)
        }
        let гипотенуза = (стороны.0 * стороны.0 + стороны.1 * стороны.1).squareRoot()
        let см = дюймы * 2.54
        let экранШ = см * стороны.0 / гипотенуза
        let экранВ = см * стороны.1 / гипотенуза
        var найдено = НайденныеГабариты()
        найдено.ширина = (экранШ * 1.02 + 1.5).rounded()
        найдено.высота = (экранВ * 1.04 + (монитор ? 14 : 8)).rounded()
        найдено.глубина = монитор ? 22 : max(20, (дюймы * 0.45).rounded())
        найдено.надёжно = false
        найдено.источник = .диагональ(дюймы)
        return найдено
    }

    // MARK: Поиск

    private struct Совпадение {
        /// Группы: 0 — всё совпадение; нет группы — nil.
        let группы: [String?]
        let место: Range<String.Index>
    }

    private static func совпадения(_ образец: String, в текст: String) -> [Совпадение] {
        guard !текст.isEmpty,
              let выражение = try? NSRegularExpression(pattern: образец, options: [.caseInsensitive]) else { return [] }
        let весь = NSRange(текст.startIndex..<текст.endIndex, in: текст)
        return выражение.matches(in: текст, options: [], range: весь).compactMap { с in
            guard let место = Range(с.range, in: текст) else { return nil }
            let группы: [String?] = (0..<с.numberOfRanges).map { номер in
                let диапазон = с.range(at: номер)
                guard диапазон.location != NSNotFound, let кусок = Range(диапазон, in: текст) else { return nil }
                return String(текст[кусок])
            }
            return Совпадение(группы: группы, место: место)
        }
    }

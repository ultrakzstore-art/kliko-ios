/// Популярный набор крепежа: разболтовка, отверстие и обычные диаметры — по маркам.
struct НаборКолёс: Identifiable, Equatable, Sendable {
    let pcd: РазболтовкаАвтоподбора
    let dia: Double
    let rОт: Double
    let rДо: Double
    /// Марки и модели — как пишут сами производители.
    let марки: String

    var id: String { СтандартыКолёс.строкаPCD(pcd) + "|" + ЧислаАвтоподбора.ч(dia, знаков: 2) }

    /// «5×114.3 · 67.1».
    var верх: String { pcd.подпись + " · " + ЧислаАвтоподбора.ч(dia, знаков: 2) }

    /// «R16–R18 · Hyundai, Kia»; один диаметр — «R16 · GAZelle».
    var низ: String {
        let от = ЧислаАвтоподбора.ч(rОт)
        let до = ЧислаАвтоподбора.ч(rДо)
        return (от == до ? "R" + от : "R" + от + "–R" + до) + " · " + марки
    }
}


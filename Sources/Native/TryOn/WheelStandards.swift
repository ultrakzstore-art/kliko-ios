    static func популярныеШины(r: Double) -> [РазмерШиныАвтоподбора] {
        var итог: [РазмерШиныАвтоподбора] = []
        for размер in шиныКаталога where abs(размер.диаметр - r) < 0.01 && !итог.contains(размер) {
            итог.append(размер)
        }
        let ключ = шиныПоR.keys.first { abs($0 - r) < 0.01 }
        for пара in ключ.flatMap({ шиныПоR[$0] }) ?? [] {
            let размер = РазмерШиныАвтоподбора(ширина: пара.0, профиль: пара.1, диаметр: r)
            if размер.годный && !итог.contains(размер) { итог.append(размер) }
        }
        return итог
    }

    /**
     Шина под другой диаметр диска — того же внешнего диаметра («плюс-сайзинг»): из популярных под новый R и из той же
     ширины (±10, +20 мм) со всеми профилями — ближайшая по внешнему диаметру; при разнице до 3 мм — популярная и ближе
     по ширине. Тот же R — та же шина.
     */
    static func шинаПодДиаметр(_ шина: РазмерШиныАвтоподбора, r: Double) -> РазмерШиныАвтоподбора {
        guard abs(шина.диаметр - r) > 0.01 else { return шина }
        let популярные = популярныеШины(r: r)
        var кандидаты = популярные
        for сдвиг in [-10.0, 0, 10, 20] {
            let ширина = шина.ширина + сдвиг
            guard ширины.contains(where: { abs($0 - ширина) < 0.01 }) else { continue }
            for профиль in профили {
                let размер = РазмерШиныАвтоподбора(ширина: ширина, профиль: профиль, диаметр: r)
                if размер.годный && !кандидаты.contains(размер) { кандидаты.append(размер) }
            }
        }
        let цель = шина.внешний
        let лучший = кандидаты.min { а, б in
            let да = abs(а.внешний - цель)
            let дб = abs(б.внешний - цель)
            if abs(да - дб) > 3 { return да < дб }
            let па = популярные.contains(а)
            let пб = популярные.contains(б)
            if па != пб { return па }
            return abs(а.ширина - шина.ширина) < abs(б.ширина - шина.ширина)
        }
        return лучший ?? РазмерШиныАвтоподбора(ширина: шина.ширина, профиль: шина.профиль, диаметр: r)
    }

    /// Обычная ширина обода под шину, J: у низкого профиля обод шире. Примерно, по таблицам ETRTO — для подсказки.
    static func ободДляШины(_ шина: РазмерШиныАвтоподбора) -> ClosedRange<Double> {
        let низ: Double
        let верх: Double
        if шина.профиль <= 40 {
            низ = 0.82
            верх = 1.0
        } else if шина.профиль <= 50 {
            низ = 0.78
            верх = 0.95
        } else {
            низ = 0.70
            верх = 0.90
        }
        let а = половинка(шина.ширина * низ / 25.4)
        let б = половинка(шина.ширина * верх / 25.4)
        return min(а, б)...max(а, б)
    }

    /// До ближайшей половинки: 7.26 → 7.5.
    private static func половинка(_ x: Double) -> Double { (x * 2).rounded() / 2 }

    /// Отверстия, с которыми эта разболтовка встречается в наборах; нет — пусто.
    static func ступицыДля(_ pcd: РазболтовкаАвтоподбора) -> [Double] {
        var итог: [Double] = []
        for н in наборы where н.pcd.совпадает(pcd) && !итог.contains(н.dia) { итог.append(н.dia) }
        return итог
    }

    // MARK: Запись

    /// «5x114.3» — так PCD пишется в полях (как СтрокиКолёсПодачи.pcd).
    static func строкаPCD(_ р: РазболтовкаАвтоподбора) -> String {
        String(р.отверстий) + "x" + ЧислаАвтоподбора.ч(р.pcd, знаков: 2)
    }

    /// Вылет в поле: «45» или «35-45».
    static func строкаВылета(_ et: ClosedRange<Double>) -> String {
        let низ = ЧислаАвтоподбора.ч(et.lowerBound)
        let верх = ЧислаАвтоподбора.ч(et.upperBound)
        return низ == верх ? низ : низ + "-" + верх
    }

    /// Вылет для глаз: «ET45», «ET35…45».
    static func подписьВылета(_ et: ClosedRange<Double>) -> String {
        let низ = ЧислаАвтоподбора.ч(et.lowerBound)
        let верх = ЧислаАвтоподбора.ч(et.upperBound)
        return низ == верх ? "ET" + низ : "ET" + низ + "…" + верх
    }

    /// Обод для глаз: «R16 · 7J», «R16», «7J»; ничего — nil.
    static func подписьОбода(r: Double?, j: Double?) -> String? {
        let части = [r.map { "R" + ЧислаАвтоподбора.ч($0) }, j.map { ЧислаАвтоподбора.ч($0) + "J" }].compactMap { $0 }
        return части.isEmpty ? nil : части.joined(separator: " · ")
    }

    // MARK: Проверка

    private static func естьВ(_ список: [Double], _ x: Double, допуск: Double = 0.01) -> Bool {
        список.contains { abs($0 - x) < допуск }
    }

    /**
     Значение части выбрано (или набрано), но такого стандарта нет — «редкое, проверьте». Не запрет: бывают и
     нестандартные размеры, сохранять их можно.
     */
    static func редкое(_ часть: ЧастьКолеса, _ з: ЗначенияКолеса) -> Bool {
        switch часть {
        case .шина:
            if let ш = з.ширинаШины, !естьВ(ширины, ш) { return true }
            if let п = з.профиль, !естьВ(профили, п) { return true }
            if let r = з.диаметрШины, !естьВ(диаметры + грузовые, r) { return true }
            return false
        case .обод:
            if let r = з.диаметр, !естьВ(диаметры + грузовые, r) { return true }
            if let j = з.ширинаJ, !естьВ(шириныОбода, j) { return true }
            return false
        case .болты:
            guard let pcd = з.pcd else { return false }
            return !разболтовки.contains { $0.совпадает(pcd) }
        case .центр:
            guard let dia = з.dia else { return false }
            return !естьВ(ступицы, dia, допуск: 0.06)
        case .вылет:
            guard let et = з.et else { return false }
            return et.lowerBound < вылеты.lowerBound || et.upperBound > вылеты.upperBound
        }
    }

    /// Шина и диск разного диаметра — на такой диск эта шина не сядет.
    static func разныйДиаметр(_ з: ЗначенияКолеса) -> Bool {
        guard let диска = з.диаметр, let шины = з.диаметрШины else { return false }
        return abs(диска - шины) > 0.01
    }

    /// Обод вне обычного для шины — подсказка, а не запрет.
    static func ободНеДляШины(_ з: ЗначенияКолеса) -> Bool {
        guard let шина = з.шина, let j = з.ширинаJ else { return false }
        let обычно = ободДляШины(шина)
        return j < обычно.lowerBound - 0.01 || j > обычно.upperBound + 0.01
    }
}

/// Часть живого диска: касание по ней открывает свой выбор.
enum ЧастьКолеса: String, CaseIterable, Hashable, Sendable, Identifiable {
    /// Размер шины: ширина, профиль, R.
    case шина
    /// Обод: посадочный диаметр R и ширина J.
    case обод
    /// Разболтовка PCD: болты по кругу.
    case болты
    /// Центральное отверстие DIA.
    case центр
    /// Вылет ET — схема сбоку.
    case вылет

    var id: String { rawValue }
}

/// Какие поля есть у экрана: у машины — шины, PCD, DIA, ET; у товара — по виду; у подачи — шины или диски.
struct СоставКолеса: Equatable, Sendable {
    var шина = false
    /// Свой посадочный диаметр диска (у машины «Подойдут ли?» его нет — R берётся из шины).
    var диаметр = false
    var ширинаJ = false
    var pcd = false
    var dia = false
    var et = false
    /// Вылет пределами «35-45» (штатный у машины), а не одним числом.
    var диапазонET = false
    /// Машина: другой диаметр диска подбирает шину того же внешнего диаметра (у товара и подачи — меняет только R).
    var подборШины = false

    /// Части в порядке «снаружи внутрь»: обод есть всегда, когда есть шина или диск.
    var части: [ЧастьКолеса] {
        var итог: [ЧастьКолеса] = []
        if шина { итог.append(.шина) }
        if шина || диаметр || ширинаJ { итог.append(.обод) }
        if pcd { итог.append(.болты) }
        if dia { итог.append(.центр) }
        if et { итог.append(.вылет) }
        return итог
    }

    func есть(_ часть: ЧастьКолеса) -> Bool { части.contains(часть) }

    /// Есть хоть одна часть диска (для «Сканировать диск» и наборов).
    var естьДиск: Bool { диаметр || ширинаJ || pcd || dia || et }
}

// MARK: - Значения

/// Что выбрано на живом диске. Неизвестное — nil. Шина бывает выбрана частями (ширина без профиля) — у экранов со
/// строкой «205/55 R16» неполная шина живёт в черновике редактора (ЧерновикШины).
struct ЗначенияКолеса: Equatable, Sendable {
    var ширинаШины: Double? = nil
    var профиль: Double? = nil
    var диаметрШины: Double? = nil
    /// Посадочный диаметр диска, R.
    var диаметр: Double? = nil
    /// Ширина обода, J.
    var ширинаJ: Double? = nil
    var pcd: РазболтовкаАвтоподбора? = nil
    var dia: Double? = nil
    var et: ClosedRange<Double>? = nil

    init() {}

    /// Полный и правдоподобный размер шины; иначе nil.
    var шина: РазмерШиныАвтоподбора? {
        guard let ш = ширинаШины, let п = профиль, let д = диаметрШины else { return nil }
        let размер = РазмерШиныАвтоподбора(ширина: ш, профиль: п, диаметр: д)
        return размер.годный ? размер : nil
    }

    var шинаПустая: Bool { ширинаШины == nil && профиль == nil && диаметрШины == nil }

    mutating func задатьШину(_ размер: РазмерШиныАвтоподбора?) {
        ширинаШины = размер?.ширина
        профиль = размер?.профиль
        диаметрШины = размер?.диаметр
    }

    /// Диаметр для рисунка: диска, а нет его — шины.
    var r: Double? { диаметр ?? диаметрШины }

    /// Шина по частям вместе с черновиком: что выбрано здесь — главнее, недостающее — из черновика, R — и от диска.
    func трио(_ черновик: ЧерновикШины) -> ЧерновикШины {
        ЧерновикШины(ширина: ширинаШины ?? черновик.ширина, профиль: профиль ?? черновик.профиль,
                     r: диаметрШины ?? черновик.r ?? диаметр)
    }

    /**
     Другой диаметр диска: R диска и шины меняются вместе (шина другого R на этот диск не сядет). У машины
     (состав.подборШины) полная шина заменяется ближайшей того же внешнего диаметра — её и возвращаем; у товара и подачи
     у шины меняется только R. Черновик шины идёт следом.
     */
    mutating func сменитьДиаметр(_ r: Double, состав: СоставКолеса,
                                 черновик: inout ЧерновикШины) -> ПодборШиныКолеса? {
        let было = трио(черновик)
        if состав.диаметр { диаметр = r }
        guard состав.шина else { return nil }
        var подбор: ПодборШиныКолеса? = nil
        if состав.подборШины, let прежняя = было.полный, abs(прежняя.диаметр - r) > 0.01 {
            let новая = СтандартыКолёс.шинаПодДиаметр(прежняя, r: r)
            задатьШину(новая)
            подбор = ПодборШиныКолеса(было: прежняя, стало: новая)
        } else {
            ширинаШины = было.ширина
            профиль = было.профиль
            диаметрШины = r
        }
        черновик = ЧерновикШины(ширина: ширинаШины, профиль: профиль, r: r)
        return подбор
    }
}

/// Шина, подобранная под другой диаметр диска: какая была и какая стала.
struct ПодборШиныКолеса: Equatable, Sendable {
    let было: РазмерШиныАвтоподбора
    let стало: РазмерШиныАвтоподбора

    /// Разница внешнего диаметра, % (как в калькуляторе «Подойдут ли?»).
    var процент: Double { СравнениеШинАвтоподбора(было: было, стало: стало).процент }
}

/// Шина, выбранная не до конца: ширина, профиль и R по отдельности.
struct ЧерновикШины: Equatable, Sendable {
    var ширина: Double? = nil
    var профиль: Double? = nil
    var r: Double? = nil

    init(ширина: Double? = nil, профиль: Double? = nil, r: Double? = nil) {
        self.ширина = ширина
        self.профиль = профиль
        self.r = r
    }

    var пустой: Bool { ширина == nil && профиль == nil && r == nil }

    var полный: РазмерШиныАвтоподбора? {
        guard let ширина, let профиль, let r else { return nil }
        let размер = РазмерШиныАвтоподбора(ширина: ширина, профиль: профиль, диаметр: r)
        return размер.годный ? размер : nil
    }

    /// «205/55 R16», а невыбранное — прочерком: «205/— R—».
    var подпись: String {
        let ш: String = ширина.map { ЧислаАвтоподбора.ч($0) } ?? "—"
        let п: String = профиль.map { ЧислаАвтоподбора.ч($0) } ?? "—"
        let д: String = r.map { ЧислаАвтоподбора.ч($0) } ?? "—"
        return ш + "/" + п + " R" + д
    }
}

/// Строки полей ввода ↔ значения диска: «205/55 R16», «17», «7.5», «5x114.3», «67.1», «45» или «35-45». Разбор — тот же,
/// что у полей «Подойдут ли?» (ВводАвтоподбора), так что сохранение и проверка остаются прежними.
struct СтрокиКолеса: Equatable {
    var шины = ""
    var диаметр = ""
    var ширина = ""
    var pcd = ""
    var dia = ""
    var et = ""

    init(шины: String = "", диаметр: String = "", ширина: String = "", pcd: String = "", dia: String = "",
         et: String = "") {
        self.шины = шины
        self.диаметр = диаметр
        self.ширина = ширина
        self.pcd = pcd
        self.dia = dia
        self.et = et
    }

    var значения: ЗначенияКолеса {
        var з = ЗначенияКолеса()
        з.задатьШину(ВводАвтоподбора.шины(шины).размер)
        з.диаметр = ВводАвтоподбора.диаметр(диаметр).диаметр
        з.ширинаJ = ВводАвтоподбора.ширина(ширина).ширина
        з.pcd = ВводАвтоподбора.pcd(pcd).разболтовка
        з.dia = ВводАвтоподбора.dia(dia).dia
        з.et = ВводАвтоподбора.et(et).вылет
        return з
    }

    /// Новые значения → строки. Меняется только строка, чьё значение стало другим: набранное «67,1» не переписывается
    /// в «67.1», а непонятное — не стирается, пока его не тронули. Неполная шина в строку не попадает.
    mutating func принять(_ н: ЗначенияКолеса) {
        typealias Ч = ЧислаАвтоподбора
        let было = значения
        if н.шина != было.шина {
            if let размер = н.шина {
                шины = размер.подпись
            } else if н.шинаПустая {
                шины = ""
            }
        }
        if н.диаметр != было.диаметр { диаметр = н.диаметр.map { Ч.ч($0) } ?? "" }
        if н.ширинаJ != было.ширинаJ { ширина = н.ширинаJ.map { Ч.ч($0) } ?? "" }
        if н.pcd != было.pcd { pcd = н.pcd.map { СтандартыКолёс.строкаPCD($0) } ?? "" }
        if н.dia != было.dia { dia = н.dia.map { Ч.ч($0, знаков: 2) } ?? "" }
        if н.et != было.et { et = н.et.map { СтандартыКолёс.строкаВылета($0) } ?? "" }
    }
}


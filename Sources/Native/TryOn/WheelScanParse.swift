// MARK: - Что прочитали

/// Маркировка колеса, прочитанная камерой: шина — с боковины, остальное — с внутренней стороны диска. Не прочитали — nil.
struct МаркировкаКолеса: Equatable, Sendable {
    /// Размер шины «205/55 R16»: ширина (мм), профиль (% от ширины), посадочный диаметр (дюймы; бывает 17.5).
    struct ШинаМаркировки: Equatable, Hashable, Sendable {
        let ширина: Int
        let профиль: Int
        let диаметр: Double
    }

    var шина: ШинаМаркировки?
    /// Посадочный диаметр диска, дюймы (R16).
    var диаметрДиска: Double?
    /// Ширина обода, дюймы (6.5J).
    var ширинаJ: Double?
    /// Вылет, мм (ET45; бывает отрицательным).
    var вылет: Int?
    /// Разболтовка «5x114.3»: число отверстий, латинская x, PCD с точкой.
    var pcd: String?
    /// Центральное отверстие, мм (DIA 67.1).
    var ступица: Double?

    /// Ничего не прочитали.
    var пусто: Bool {
        шина == nil && диаметрДиска == nil && ширинаJ == nil && вылет == nil && pcd == nil && ступица == nil
    }
}

/// Одно поле маркировки — для чипов сканера: что нашли, что ещё ищем, что человек убрал.
enum ПолеМаркировкиКолеса: CaseIterable, Hashable, Sendable {
    case шина
    case диаметр
    case ширина
    case вылет
    case разболтовка
    case ступица
}

extension МаркировкаКолеса {
    /// Какие поля ищет сканер: на боковине шины — только размер, на диске — всё, кроме размера шины.
    static func поля(_ что: ЧтоСканироватьКолеса) -> [ПолеМаркировкиКолеса] {
        switch что {
        case .шина: return [.шина]
        case .диск: return [.диаметр, .ширина, .вылет, .разболтовка, .ступица]
        }
    }

    /// Только то, что ищут: «205/55 R16» с соседней шины при сканировании диска не нужен, и наоборот.
    func для(_ что: ЧтоСканироватьКолеса) -> МаркировкаКолеса {
        var итог = МаркировкаКолеса()
        for поле in Self.поля(что) { итог.взять(поле, из: self) }
        return итог
    }

    func есть(_ поле: ПолеМаркировкиКолеса) -> Bool {
        подпись(поле) != nil
    }

    /// Запись поля, как на самом колесе: «205/55 R16», «R16», «6.5J», «ET45», «5x114.3», «DIA 67.1»; нет — nil.
    func подпись(_ поле: ПолеМаркировкиКолеса) -> String? {
        typealias Р = РазборМаркировкиКолеса
        switch поле {
        case .шина:
            guard let ш = шина else { return nil }
            return String(ш.ширина) + "/" + String(ш.профиль) + " R" + Р.число(ш.диаметр)
        case .диаметр:
            return диаметрДиска.map { "R" + Р.число($0) }
        case .ширина:
            return ширинаJ.map { Р.число($0) + "J" }
        case .вылет:
            return вылет.map { "ET" + String($0) }
        case .разболтовка:
            return pcd
        case .ступица:
            return ступица.map { "DIA " + Р.число($0) }
        }
    }

    /// Убрать поле (прочитано неверно).
    mutating func убрать(_ поле: ПолеМаркировкиКолеса) {
        switch поле {
        case .шина: шина = nil
        case .диаметр: диаметрДиска = nil
        case .ширина: ширинаJ = nil
        case .вылет: вылет = nil
        case .разболтовка: pcd = nil
        case .ступица: ступица = nil
        }
    }

    /// Переложить одно поле из другой маркировки.
    fileprivate mutating func взять(_ поле: ПолеМаркировкиКолеса, из другой: МаркировкаКолеса) {
        switch поле {
        case .шина: шина = другой.шина
        case .диаметр: диаметрДиска = другой.диаметрДиска
        case .ширина: ширинаJ = другой.ширинаJ
        case .вылет: вылет = другой.вылет
        case .разболтовка: pcd = другой.pcd
        case .ступица: ступица = другой.ступица
        }
    }
}

// MARK: - Разбор строк

/// Разбор строк, прочитанных камерой. Без состояния: образцы собраны один раз, звать можно с любой нити.
enum РазборМаркировкиКолеса {
    /// Строки одного кадра (или одной надписи) → маркировка. Пусто — ничего похожего на маркировку колеса.
    static func разобрать(_ строки: [String]) -> МаркировкаКолеса {
        var итог = МаркировкаКолеса()
        let чистые = строки.map { нормально($0) }.filter { !$0.trimmingCharacters(in: .whitespaces).isEmpty }
        for строка in чистые { дополнить(&итог, из: строка) }
        if чистые.count > 1 { дополнить(&итог, из: чистые.joined(separator: " ")) }
        return итог
    }

    /// Число без лишних нулей, с точкой: 16 → «16», 6.5 → «6.5», 120.65 → «120.65».
    static func число(_ x: Double) -> String {
        guard x.isFinite else { return "—" }
        let округлено = (x * 100).rounded() / 100
        if округлено == округлено.rounded() { return String(Int(округлено)) }
        var строка = String(format: "%.2f", locale: Locale(identifier: "en_US_POSIX"), округлено)
        while строка.hasSuffix("0") { строка.removeLast() }
        if строка.hasSuffix(".") { строка.removeLast() }
        return строка
    }

    // MARK: Нормальная запись

    /// Знаки и кириллица, похожая на латиницу. «½» — бывает в ширине обода («6½J»).
    private static let замены: [Character: String] = [
        "×": "x", "✕": "x", "*": "x", "–": "-", "—": "-", "−": "-", "\u{00A0}": " ", "\u{202F}": " ",
        "″": "\"", "”": "\"", "“": "\"", "⌀": "Ø", "ø": "Ø", "½": ".5",
        "А": "A", "В": "B", "Е": "E", "К": "K", "М": "M", "Н": "H", "О": "O", "Р": "P", "С": "C", "Т": "T",
        "Х": "X", "У": "Y", "І": "I", "а": "a", "е": "e", "о": "o", "р": "p", "с": "c", "х": "x", "у": "y", "і": "i"
    ]

    /// Буквы, которые распознавание путает с цифрами.
    private static let путаница: [Character: Character] = ["O": "0", "o": "0", "I": "1", "l": "1", "S": "5", "s": "5"]

    /// Слова из одних «путаных» букв, которые сами по себе что-то значат («IS45» — вылет, не «1545»).
    private static let своиСлова: Set<String> = ["IS"]

    private static func цифра(_ знак: Character) -> Bool {
        знак.isASCII && знак.isNumber
    }

    /**
     Нормальная запись строки: знаки и кириллица — латиницей, путаные буквы вплотную к цифре — цифрами, запятая между
     цифрами — точкой, всё заглавными; DOT-код убран целиком (в нём недели и годы выпуска, а не размеры).
     */
    static func нормально(_ строка: String) -> String {
        var знаки: [Character] = []
        знаки.reserveCapacity(строка.count)
        for знак in строка {
            if let замена = замены[знак] {
                знаки.append(contentsOf: замена)
            } else {
                знаки.append(знак)
            }
        }
        /* Путаные буквы: до трёх проходов, чтобы «2OO» стало «200» (вторая O стоит вплотную к уже исправленной). */
        for _ in 0..<3 {
            var исправлено = false
            for номер in знаки.indices {
                guard let цифраВместо = путаница[знаки[номер]] else { continue }
                var начало = номер
                while начало > 0 && знаки[начало - 1].isLetter { начало -= 1 }
                var конец = номер + 1
                while конец < знаки.count && знаки[конец].isLetter { конец += 1 }
                if своиСлова.contains(String(знаки[начало..<конец]).uppercased()) { continue }
                let слева = номер > 0 && цифра(знаки[номер - 1])
                let справа = номер + 1 < знаки.count && цифра(знаки[номер + 1])
                guard слева || справа else { continue }
                знаки[номер] = цифраВместо
                исправлено = true
            }
            if !исправлено { break }
        }
        var текст = String(знаки)
        текст = текст.replacingOccurrences(of: #"(\d),(\d)"#, with: "$1.$2", options: .regularExpression)
        текст = текст.uppercased()
        /* Слово DOT-кода не стоит вплотную к дроби: «… 3519 205/55R16» — 205 уже размер шины, его не съедаем. */
        текст = текст.replacingOccurrences(of: #"(?<![A-Z])DOT(?:\s{1,2}[A-Z0-9]{2,5}(?![A-Z0-9/\\|])){1,4}"#,
                                           with: " ", options: .regularExpression)
        return текст
    }

    // MARK: Образцы

    private static func образец(_ шаблон: String) -> NSRegularExpression? {
        try? NSRegularExpression(pattern: шаблон, options: [])
    }

    /// Шина: «205/55 R16», «LT265/70R17», «205 55 ZR16», «195/65R15C». Группы: ширина, профиль, диаметр, «.5».
    private static let образецШины = образец(
        #"(?<![0-9.])(?:LT|ST|P|T)?\s?([1-3][0-9][05])\s{0,2}(?:[/\\|]|\s)\s{0,2}([2-9][05])\s{0,2}(?:Z\s?)?R\s{0,2}(1[2-9]|2[0-6])(\.5)?(?![0-9])"#)
    /// Обод «6.5JX16», «7J 17», «7JJ17»: ширина, диаметр, «.5».
    private static let образецОбода = образец(
        #"(?<![0-9.])(\d{1,2}(?:\.\d)?)\s?J{1,2}\s{0,2}X?\s{0,2}(1[2-9]|2[0-6])(\.5)?(?![0-9])"#)
    /// Обод «16X6.5J», «16X7»: диаметр, «.5», ширина.
    private static let образецОбодаНаоборот = образец(
        #"(?<![0-9.])(1[2-9]|2[0-6])(\.5)?\s{0,2}X\s{0,2}(\d{1,2}(?:\.\d)?)\s?(?:J{1,2})?(?![0-9.])"#)
    /// Обод без J шириной вперёд «7.5X17», «6X15»: ширина, диаметр, «.5» (ширина меньше диаметра — не разболтовка).
    private static let образецОбодаШиринойВперёд = образец(
        #"(?<![0-9.])(\d{1,2}(?:\.\d)?)\s{0,2}X\s{0,2}(1[2-9]|2[0-6])(\.5)?(?![0-9.])"#)
    /// Ширина обода сама по себе: «6.5J».
    private static let образецШириныОбода = образец(#"(?<![0-9.])(\d{1,2}(?:\.\d)?)\s?J{1,2}(?![A-WYZ0-9])"#)
    /// Диаметр сам по себе: «R16», «16"», «16 INCH».
    private static let образцыДиаметра = [
        образец(#"(?<![0-9A-Z.])R\s?(1[2-9]|2[0-6])(\.5)?(?![0-9])"#),
        образец(#"(?<![0-9.])(1[2-9]|2[0-6])(\.5)?\s?(?:"|INCH)"#)
    ]
    /// Вылет: «ET45», «ET 45», «IS45», «ET-10», «OFFSET 40». Группы: знак, число.
    private static let образецВылета = образец(
        #"(?<![A-Z])(?:ET|IS|OFFSET|INSET)\s{0,2}[:=]?\s{0,2}([+-])?\s?(\d{1,3})(?:\.\d)?(?![0-9])"#)
    /// Разболтовка «5X114.3» и через дробь «5/114.3» (наклейки, коробки): отверстий, PCD. Дробь шины «205/55» и
    /// индексов «102/100» не подходит: перед числом отверстий не бывает цифры.
    private static let образецРазболтовки = образец(
        #"(?<![0-9.])(10|[3-9])\s{0,2}[X/]\s{0,2}(\d{2,3}(?:\.\d{1,2})?)(?![0-9])"#)
    /// «PCD 114.3» и «PCD114.3X5»: PCD, отверстий (если есть).
    private static let образецPCD = образец(
        #"(?<![A-Z])PCD\s{0,2}[:=]?\s{0,2}(\d{2,3}(?:\.\d{1,2})?)(?:\s{0,2}X\s{0,2}(10|[3-9])(?![0-9]))?"#)
    /// Число отверстий: «5H», «5 HOLES». Метка горба «H2» и ширина обода «16X7 H» — не отверстия.
    private static let образецОтверстий = образец(#"(?<![0-9.X])(10|[3-9])\s{0,2}(?:HOLES?|H)(?![A-Z0-9])"#)
    /// Центральное отверстие: «CB67.1», «DIA 67.1», «HB 67.1», «ЦО 66.6», «D67.1»; «Ø67.1» (Ø читается и как 0 или O).
    private static let образцыОтверстия = [
        образец(#"(?<![A-Z])(?:CB|DIA|HB|CH|BORE|ЦO|Ц0|D(?=\d{2,3}\.\d))\s{0,2}[:=.]?\s{0,2}(\d{2,3}(?:\.\d{1,2})?)(?![0-9])"#),
        образец(#"(?:Ø|(?<![0-9A-Z.])[O0](?=\s?\d{2,3}\.\d))\s?(\d{2,3}(?:\.\d{1,2})?)(?![0-9])"#)
    ]

    /// Все совпадения: [вся строка, группа 1, …]; не совпавшая группа — nil.
    private static func совпадения(_ выражение: NSRegularExpression?, _ текст: String) -> [[String?]] {
        guard let выражение else { return [] }
        let весь = NSRange(текст.startIndex..<текст.endIndex, in: текст)
        return выражение.matches(in: текст, options: [], range: весь).map { совпадение in
            (0..<совпадение.numberOfRanges).map { номер -> String? in
                let место = совпадение.range(at: номер)
                guard место.location != NSNotFound, let диапазон = Range(место, in: текст) else { return nil }
                return String(текст[диапазон])
            }
        }
    }

    /// Группа как число: «114.3» → 114.3; нет группы — nil.
    private static func ч(_ группы: [String?], _ номер: Int) -> Double? {
        guard номер < группы.count, let строка = группы[номер], let значение = Double(строка),
              значение.isFinite else { return nil }
        return значение
    }

    /// Есть ли непустая группа (например, «.5» диаметра).
    private static func есть(_ группы: [String?], _ номер: Int) -> Bool {
        номер < группы.count && !(группы[номер] ?? "").isEmpty
    }

    // MARK: Пределы

    /// Стандартные PCD: дробные бывают только такие (114.3 — это 4,5 дюйма, 139.7 — 5,5 дюйма).
    private static let стандартныеPCD: [Double] = [98, 100, 105, 108, 110, 112, 114.3, 115, 118, 120, 120.65, 127, 130,
                                                   135, 139.7, 150, 160, 165.1, 170, 180, 205]

    private static func годнаяРазболтовка(_ отверстий: Int, _ pcd: Double) -> Bool {
        guard (3...10).contains(отверстий), (90...210).contains(pcd) else { return false }
        if стандартныеPCD.contains(where: { abs($0 - pcd) < 0.36 }) { return true }
        return pcd == pcd.rounded()
    }

    private static func годнаяШирина(_ ширина: Double) -> Bool {
        (3.5...13).contains(ширина) && (ширина * 2).rounded() == ширина * 2
    }

    private static func годныйДиаметр(_ диаметр: Double) -> Bool {
        (12...26.5).contains(диаметр)
    }

    /// Разболтовка записью договора: «5x114.3». PCD ближе миллиметра к стандарту — стандарт: распознавание теряет
    /// дробную часть («6X139» — это 6x139.7, «5X114» — 5x114.3).
    private static func записьРазболтовки(_ отверстий: Int, _ pcd: Double) -> String {
        String(отверстий) + "x" + число(кСтандарту(pcd))
    }

    private static func кСтандарту(_ pcd: Double) -> Double {
        guard let ближний = стандартныеPCD.min(by: { abs($0 - pcd) < abs($1 - pcd) }), abs(ближний - pcd) < 1 else {
            return pcd
        }
        return ближний
    }

    // MARK: Поля

    /// Дополнить пустые поля тем, что нашлось в одной нормальной строке.
    private static func дополнить(_ м: inout МаркировкаКолеса, из текст: String) {
        if м.шина == nil { м.шина = шина(текст) }
        if м.ширинаJ == nil || м.диаметрДиска == nil, let запись = обод(текст) {
            if м.ширинаJ == nil { м.ширинаJ = запись.ширина }
            if м.диаметрДиска == nil { м.диаметрДиска = запись.диаметр }
        }
        if м.ширинаJ == nil { м.ширинаJ = ширинаОбода(текст) }
        if м.диаметрДиска == nil { м.диаметрДиска = диаметр(текст) }
        if м.вылет == nil { м.вылет = вылет(текст) }
        if м.pcd == nil { м.pcd = разболтовка(текст) }
        if м.ступица == nil { м.ступица = отверстие(текст) }
    }

    private static func шина(_ текст: String) -> МаркировкаКолеса.ШинаМаркировки? {
        for г in совпадения(образецШины, текст) {
            guard let ш = ч(г, 1), let п = ч(г, 2), var д = ч(г, 3) else { continue }
            if есть(г, 4) { д += 0.5 }
            guard (125...355).contains(ш), (25...95).contains(п), годныйДиаметр(д) else { continue }
            return МаркировкаКолеса.ШинаМаркировки(ширина: Int(ш), профиль: Int(п), диаметр: д)
        }
        return nil
    }

    /// Ширина и диаметр одной записью: «6.5JX16» или «16X6.5J».
    private static func обод(_ текст: String) -> (ширина: Double, диаметр: Double)? {
        for г in совпадения(образецОбода, текст) {
            guard let ш = ч(г, 1), var д = ч(г, 2) else { continue }
            if есть(г, 3) { д += 0.5 }
            if годнаяШирина(ш) && годныйДиаметр(д) { return (ширина: ш, диаметр: д) }
        }
        for г in совпадения(образецОбодаНаоборот, текст) {
            guard var д = ч(г, 1), let ш = ч(г, 3) else { continue }
            if есть(г, 2) { д += 0.5 }
            if годнаяШирина(ш) && годныйДиаметр(д) { return (ширина: ш, диаметр: д) }
        }
        for г in совпадения(образецОбодаШиринойВперёд, текст) {
            guard let ш = ч(г, 1), var д = ч(г, 2) else { continue }
            if есть(г, 3) { д += 0.5 }
            if ш < д && годнаяШирина(ш) && годныйДиаметр(д) { return (ширина: ш, диаметр: д) }
        }
        return nil
    }

    private static func ширинаОбода(_ текст: String) -> Double? {
        for г in совпадения(образецШириныОбода, текст) {
            if let ш = ч(г, 1), годнаяШирина(ш) { return ш }
        }
        return nil
    }

    private static func диаметр(_ текст: String) -> Double? {
        for выражение in образцыДиаметра {
            for г in совпадения(выражение, текст) {
                guard var д = ч(г, 1) else { continue }
                if есть(г, 2) { д += 0.5 }
                if годныйДиаметр(д) { return д }
            }
        }
        return nil
    }

    private static func вылет(_ текст: String) -> Int? {
        for г in совпадения(образецВылета, текст) {
            guard let модуль = ч(г, 2) else { continue }
            let значение = Int(модуль) * (г.count > 1 && г[1] == "-" ? -1 : 1)
            if (-65...80).contains(значение) { return значение }
        }
        return nil
    }

    private static func разболтовка(_ текст: String) -> String? {
        for г in совпадения(образецРазболтовки, текст) {
            guard let о = ч(г, 1), let p = ч(г, 2), годнаяРазболтовка(Int(о), p) else { continue }
            return записьРазболтовки(Int(о), p)
        }
        /* «PCD 114.3» — отверстия рядом («PCD114.3X5») или отдельной надписью («5H», «5 HOLES»). */
        for г in совпадения(образецPCD, текст) {
            guard let p = ч(г, 1) else { continue }
            var отверстий = ч(г, 2).map { Int($0) }
            if отверстий == nil, let найдено = совпадения(образецОтверстий, текст).first, let о = ч(найдено, 1) {
                отверстий = Int(о)
            }
            if let о = отверстий, годнаяРазболтовка(о, p) { return записьРазболтовки(о, p) }
        }
        return nil
    }

    private static func отверстие(_ текст: String) -> Double? {
        for выражение in образцыОтверстия {
            for г in совпадения(выражение, текст) {
                if let д = ч(г, 1), (50...175).contains(д) { return д }
            }
        }
        return nil
    }
}

// MARK: - Голоса кадров

/**
 Сбор прочитанного за много кадров. Живая камера читает одну надпись десятки раз, и раз в сколько-то кадров — с ошибкой
 («205/56 R16»); у каждого поля побеждает значение, прочитанное чаще (при равенстве — прочитанное раньше). Убранное
 человеком значение («прочитано неверно») больше не принимается — следующее прочитанное займёт его место.
 */
struct СборМаркировкиКолеса: Sendable {
    private struct Голоса: Sendable {
        var число: Int
        var первый: Int
    }

    private var шины: [МаркировкаКолеса.ШинаМаркировки: Голоса] = [:]
    private var диаметры: [Double: Голоса] = [:]
    private var ширины: [Double: Голоса] = [:]
    private var вылеты: [Int: Голоса] = [:]
    private var разболтовки: [String: Голоса] = [:]
    private var отверстия: [Double: Голоса] = [:]
    /// Убранные человеком значения — записью поля («205/55 R16», «ET45»).
    private var убранные: Set<String> = []
    private var шаг = 0

    init() {}

    /// Добавить прочитанное; вес — сколько голосов (нажатие на надпись и снимок весят больше одного кадра).
    mutating func добавить(_ м: МаркировкаКолеса, вес: Int = 1) {
        guard !м.пусто else { return }
        шаг += 1
        let голоса = max(1, вес)
        let по = шаг
        /* Копия убранных: вложенная функция не трогает self, пока поле словаря отдано ей на изменение. */
        let убраны = убранные
        func отдать<К: Hashable>(_ значение: К?, _ поле: ПолеМаркировкиКолеса, _ словарь: inout [К: Голоса]) {
            guard let значение, let запись = м.подпись(поле), !убраны.contains(поле.ключ(запись)) else { return }
            if var были = словарь[значение] {
                были.число += голоса
                словарь[значение] = были
            } else {
                словарь[значение] = Голоса(число: голоса, первый: по)
            }
        }
        отдать(м.шина, .шина, &шины)
        отдать(м.диаметрДиска, .диаметр, &диаметры)
        отдать(м.ширинаJ, .ширина, &ширины)
        отдать(м.вылет, .вылет, &вылеты)
        отдать(м.pcd, .разболтовка, &разболтовки)
        отдать(м.ступица, .ступица, &отверстия)
    }

    /// Человек убрал поле: нынешнее значение больше не принимается, голоса поля обнуляются.
    mutating func убрать(_ поле: ПолеМаркировкиКолеса) {
        if let запись = итог.подпись(поле) { убранные.insert(поле.ключ(запись)) }
        switch поле {
        case .шина: шины = [:]
        case .диаметр: диаметры = [:]
        case .ширина: ширины = [:]
        case .вылет: вылеты = [:]
        case .разболтовка: разболтовки = [:]
        case .ступица: отверстия = [:]
        }
    }

    /// Победители по каждому полю.
    var итог: МаркировкаКолеса {
        var м = МаркировкаКолеса()
        м.шина = Self.лучший(шины)
        м.диаметрДиска = Self.лучший(диаметры)
        м.ширинаJ = Self.лучший(ширины)
        м.вылет = Self.лучший(вылеты)
        м.pcd = Self.лучший(разболтовки)
        м.ступица = Self.лучший(отверстия)
        return м
    }

    private static func лучший<К: Hashable>(_ словарь: [К: Голоса]) -> К? {
        словарь.max { а, б in
            if а.value.число != б.value.число { return а.value.число < б.value.число }
            return а.value.первый > б.value.первый
        }?.key
    }
}

private extension ПолеМаркировкиКолеса {
    /// Ключ убранного значения: поле и запись («шина:205/55 R16»).
    func ключ(_ запись: String) -> String {
        String(describing: self) + ":" + запись
    }
}

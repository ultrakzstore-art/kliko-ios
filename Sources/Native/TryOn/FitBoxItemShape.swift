import UIKit
import RealityKit
import simd

/**
 «ПОМЕСТИТСЯ ЛИ?» — РЕЖИМ «ВЕЩЬ»: 3D-ФОРМА ПО РАЗМЕРАМ (владелец 16.10.2026, скрин TestFlight «Как будет на столе? ·
 Игровой premium-ноутбук · 36 × 2 × 25 см»: ноутбук стоял плоской картинкой-«стойкой» высотой 2 см где-то далеко на полу
 — «алгоритм 3D AR и реальность не проработан — добей»).

 3D-модели ИИ (model3d) у объявления нет или она не открылась — вещь больше не «стойка» с фото, а форма по виду товара и
 размерам из объявления (сантиметры → метры, 1:1), собранная из скруглённых брусков RealityKit:
   · ноутбук — основание Ш×Т×Г (толщина — высота из объявления, 0,6–5 см, иначе 2 см; записано Ш×Г×В, как у
     производителей, — толщина третья, переставлена) тёмного металла, клавиатура темнее, тачпад; крышка той же ширины
     и глубины толщиной 6 мм на петле у задней кромки, открыта на 110°; на её внутренней стороне — экран: тёмное стекло
     и заставка (тёмный градиент с бликом, ПодготовкаВещиГабаритов.заставка) — не фото товара: на нём обычно вещь
     целиком, и на экране ноутбука стоял бы ещё один ноутбук;
   · монитор, телевизор, моноблок — панель (16:9 по ширине, но не выше 85 % высоты из объявления — снизу подставка)
     толщиной 1,2–4 см с заставкой на экране, тонкая ножка и плоское основание;
   · планшет и телефон — плитка лежит на столе экраном вверх (в сцене высота из объявления — вглубь, толщина — вверх);
   · коробчатые (колонка, саундбар, микроволновка, приставка, принтер, системный блок, прочая настольная техника) —
     скруглённая коробка Ш×В×Г, на передней грани фото (вырезка, если вышла), остальные грани — светлые или тёмные по
     средней яркости фото;
   · мебель и прочее крупное — по-прежнему «стойка» (FitBoxItemScene.swift).
 Под формой — мягкая подложка-тень: прямоугольник с размытыми краями чуть больше основания (ПодготовкаВещиГабаритов
 .подложка, FitBoxItemImage.swift). Металл и пластик — SimpleMaterial (свет — окружение AR и своя лампа сверху),
 заставка и фото — UnlitMaterial: экран светится сам. Текстуры готовит ВещьГабаритов не на главной нити
 (FitBoxItem.swift); здесь — только сборка из готового. Начало — центр дна, лицо (+z) — к человеку, как у коробки: те же
 жесты, подписи и снимок.
 */
enum ФормаВещиГабаритов: Equatable, Sendable {
    case ноутбук
    /// Монитор, телевизор, моноблок: панель на подставке.
    case экран
    /// Планшет, телефон: лежит экраном вверх.
    case плитка
    /// Колонка, микроволновка, приставка, принтер…: коробка с фото спереди.
    case коробка
    /// Мебель и прочее: «стойка» с фото, как раньше.
    case стойка

    /// Форма строится сама по размерам (фото — только на экран или переднюю грань); «стойке» без фото не из чего.
    var объёмная: Bool { self != .стойка }

    static func по(_ товар: Listing) -> ФормаВещиГабаритов {
        по(раздел: товар.категория, название: товар.title)
    }

    /// По разделу сайта, а в общем разделе — по виду товара из каталога шаблонов размеров (слова названия,
    /// КаталогРазмеров, Posting/PostingSizeTemplates.swift). Прочая настольная вещь — коробка; не настольная — стойка.
    static func по(раздел: String?, название: String) -> ФормаВещиГабаритов {
        let р = раздел ?? ""
        func внутри(_ разделы: Set<String>) -> Bool { РазделыСайта.внутри(р, разделы) }
        if внутри(["laptops"]) { return .ноутбук }
        if внутри(["monitors", "tv", "all-in-one"]) { return .экран }
        if внутри(["tablets", "smartphones"]) { return .плитка }
        if внутри(["consoles", "speakers", "microwaves", "printers", "scanners", "cash-registers", "pc-cases"]) {
            return .коробка
        }
        let вид = КаталогРазмеров.вид(раздел: р, название: название, виды: КаталогРазмеров.встроенные,
                                      внутри: { РазделыСайта.внутри($0, $1) })
        switch вид?.ключ ?? "" {
        case "laptop":
            return .ноутбук
        case "monitor", "tv":
            return .экран
        case "tablet", "phone":
            return .плитка
        case "desktop":
            let имя = КаталогРазмеров.нормально(название)
            return ["моноблок", "imac", "all-in-one"].contains(where: { имя.contains($0) }) ? .экран : .коробка
        case "console", "speaker", "soundbar", "microwave", "oven":
            return .коробка
        default:
            return ГабаритыВещи.наСтоле(р) ? .коробка : .стойка
        }
    }

    /**
     В сцене y и z меняются местами. Плитка из объявления стоя (Ш×В×Г, Г — толщина, как в шаблонах размеров) — лёжа.
     Ноутбук: высота больше 5 см, а глубина не больше — записали Ш×Г×В, как пишут производители («35,7 × 24,2 × 1,8
     см»), а разбор без букв прочёл Ш×В×Г; толщина — третья.
     */
    func переставлена(_ р: SIMD3<Float>) -> Bool {
        switch self {
        case .плитка: return р.y > р.z
        case .ноутбук: return р.y > 0.05 && р.z <= 0.05
        case .экран, .коробка, .стойка: return false
        }
    }

    /// Размеры в сцене, м: x — вдоль лица, y — вверх, z — вглубь.
    func вСцене(_ р: SIMD3<Float>) -> SIMD3<Float> {
        переставлена(р) ? SIMD3<Float>(р.x, р.z, р.y) : р
    }
}

/// Сборка 3D-формы вещи (см. ФормаВещиГабаритов). Только главная нить; текстуры приходят готовыми.
@MainActor
enum СборкаФормыГабаритов {
    /// Что нужно форме, кроме размеров.
    struct Отделка {
        /// Заставка на экран (ноутбук, монитор, плитка) или фото на переднюю грань (коробка); nil — тёмный экран, ровная
        /// грань.
        var фото: TextureResource? = nil
        /// Ширина фото к высоте.
        var пропорция: Float = 1
        /// Картинка — заставка экрана: на всё стекло (со скруглением стекла), а не вписана по пропорции.
        var наВесьЭкран = false
        /// Фото светлое — коробка светлая.
        var светлая = false
        /// Мягкая подложка-тень (ПодготовкаВещиГабаритов.подложка); nil — круглая тень стойки или ровное пятно.
        var подложка: TextureResource? = nil
        var тень: TextureResource? = nil
        /// Лёгкий режим: света окружения AR нет — металл почти матовый, своя лампа ярче.
        var лёгкий = false
    }

    /// Доля стороны подложки, где тень ровная (ПодготовкаВещиГабаритов.подложка): дальше — плавно к нулю.
    static let ядроПодложки: Float = 0.72

    static func собрать(_ форма: ФормаВещиГабаритов, габариты: ГабаритыВещи, отделка о: Отделка) -> Entity {
        let рост = Entity()
        let с = форма.вСцене(габариты.метры)
        switch форма {
        case .ноутбук:
            ноутбук(с, о, в: рост)
        case .экран:
            монитор(с, о, в: рост)
        case .плитка:
            плитка(с, о, в: рост)
        case .коробка, .стойка:
            коробка(с, о, в: рост)
        }
        рост.addChild(подложка(ширина: max(с.x, 0.03), глубина: max(с.z, 0.03), о))
        СборкаВещиГабаритов.осветить(рост, высота: max(0.3, с.y), лёгкий: о.лёгкий)
        return рост
    }

    // MARK: Виды

    /// Ноутбук открыт на 110°: основание, клавиатура и тачпад, крышка на петле у задней кромки, экран на крышке. р — уже
    /// в сцене (Ш×Г×В из объявления переставлен: y — толщина, z — глубина).
    private static func ноутбук(_ р: SIMD3<Float>, _ о: Отделка, в рост: Entity) {
        let ш = max(р.x, 0.1)
        let г = max(р.z, 0.08)
        /* Толщина закрытого ноутбука — высота в сцене; больше 5 см (и глубина тоже больше) — это высота открытого: тогда
           2 см. */
        let т: Float = р.y >= 0.006 && р.y <= 0.05 ? р.y : 0.02
        let крышкаТ: Float = 0.006
        let корпус = металл(0.24, шершавость: 0.38, металличность: 0.55, о)
        let основание = брусок(ш, т, г, скругление: 0.008, корпус)
        основание.position = SIMD3<Float>(0, т / 2, 0)
        рост.addChild(основание)

        /* Клавиатура ближе к петле и тачпад у переднего края — чуть темнее и чуть светлее корпуса. */
        let клавиши = ModelEntity(mesh: .generatePlane(width: ш * 0.86, depth: г * 0.46, cornerRadius: 0.004),
                                  materials: [металл(0.09, шершавость: 0.85, металличность: 0, о)])
        клавиши.position = SIMD3<Float>(0, т + 0.0008, -г * 0.2)
        рост.addChild(клавиши)
        let тачпад = ModelEntity(mesh: .generatePlane(width: ш * 0.32, depth: г * 0.26, cornerRadius: 0.006),
                                 materials: [металл(0.3, шершавость: 0.3, металличность: 0.3, о)])
        тачпад.position = SIMD3<Float>(0, т + 0.0008, г * 0.31)
        рост.addChild(тачпад)

        /* Крышка в своей системе стоит (вверх — +y, лицо экрана — +z) низом на петле; петля у задней кромки основания
           отклоняет её назад на 20° — открыто на 110°. */
        let петля = Entity()
        петля.position = SIMD3<Float>(0, т, -г / 2 + крышкаТ)
        петля.orientation = simd_quatf(angle: -20 * Float.pi / 180, axis: SIMD3<Float>(1, 0, 0))
        let крышка = брусок(ш, г, крышкаТ, скругление: 0.003, корпус)
        крышка.position = SIMD3<Float>(0, г / 2, -крышкаТ / 2)
        петля.addChild(крышка)
        let бок = min(Float(0.012), ш * 0.03)
        экран(на: петля, центр: SIMD3<Float>(0, г / 2 + 0.004, 0), ширина: ш - бок * 2, высота: г - 0.026, о)
        рост.addChild(петля)
    }

    /// Монитор или телевизор на подставке: основание, ножка, панель с экраном.
    private static func монитор(_ р: SIMD3<Float>, _ о: Отделка, в рост: Entity) {
        let ш = max(р.x, 0.1)
        let в = max(р.y, 0.08)
        let г = max(р.z, 0.05)
        /* Панель 16:9 по ширине, но не выше 85 % высоты из объявления: ниже — подставка. */
        let панельВ = max(0.05, min(в * 0.85, ш * 9 / 16))
        let подъём = в - панельВ
        let панельТ = min(max(г * 0.12, 0.012), 0.04)
        let корпус = металл(0.07, шершавость: 0.45, металличность: 0.35, о)
        let ножкаЗ = -г * 0.2

        let основание = брусок(min(max(ш * 0.32, 0.14), 0.5), 0.012, г * 0.85, скругление: 0.005, корпус)
        основание.position = SIMD3<Float>(0, 0.006, 0)
        рост.addChild(основание)
        let ножкаВ = подъём + панельВ * 0.4
        let ножка = брусок(min(max(ш * 0.07, 0.03), 0.09), ножкаВ, 0.02, скругление: 0.006, корпус)
        ножка.position = SIMD3<Float>(0, ножкаВ / 2, ножкаЗ)
        рост.addChild(ножка)

        let панель = брусок(ш, панельВ, панельТ, скругление: 0.004, корпус)
        let лицоЗ = ножкаЗ + 0.01 + панельТ
        панель.position = SIMD3<Float>(0, подъём + панельВ / 2, лицоЗ - панельТ / 2)
        рост.addChild(панель)
        let рамка: Float = ш > 0.9 ? 0.012 : 0.008
        экран(на: рост, центр: SIMD3<Float>(0, подъём + панельВ / 2, лицоЗ), ширина: ш - рамка * 2,
              высота: панельВ - рамка * 2, о)
    }

    /// Планшет или телефон лежит экраном вверх: с — уже в сцене (x — ширина, y — толщина, z — длина).
    private static func плитка(_ с: SIMD3<Float>, _ о: Отделка, в рост: Entity) {
        let ш = max(с.x, 0.03)
        let т = max(с.y, 0.004)
        let д = max(с.z, 0.05)
        let тело = брусок(ш, т, д, скругление: 0.004, металл(0.16, шершавость: 0.4, металличность: 0.5, о))
        тело.position = SIMD3<Float>(0, т / 2, 0)
        рост.addChild(тело)
        /* Экран — та же вертикальная плоскость, что у монитора, положенная лицом вверх: верх картинки — от человека. */
        let лёжа = Entity()
        лёжа.position = SIMD3<Float>(0, т, 0)
        лёжа.orientation = simd_quatf(angle: -Float.pi / 2, axis: SIMD3<Float>(1, 0, 0))
        рост.addChild(лёжа)
        let поле = min(ш, д) * 0.045
        экран(на: лёжа, центр: SIMD3<Float>(0, 0, 0), ширина: ш - поле * 2, высота: д - поле * 2, о,
              скругление: min(ш, д) * 0.08)
    }

    /// Коробчатая вещь: скруглённая коробка, фото на передней грани, цвет — по яркости фото.
    private static func коробка(_ р: SIMD3<Float>, _ о: Отделка, в рост: Entity) {
        let ш = max(р.x, 0.02)
        let в = max(р.y, 0.02)
        let г = max(р.z, 0.02)
        var грань = SimpleMaterial(color: UIColor(white: о.светлая ? 0.86 : 0.13, alpha: 1), roughness: 0.55,
                                   isMetallic: false)
        грань.metallic = .float(0.05)
        let тело = брусок(ш, в, г, скругление: min(Float(0.012), min(ш, min(в, г)) * 0.08), грань)
        тело.position = SIMD3<Float>(0, в / 2, 0)
        рост.addChild(тело)
        guard let фото = о.фото else { return }
        let размер = вписать(пропорция: о.пропорция, ширина: ш * 0.9, высота: в * 0.9)
        let лицо = ModelEntity(mesh: .generatePlane(width: размер.x, height: размер.y),
                               materials: [снимок(фото, яркость: 0.92)])
        лицо.position = SIMD3<Float>(0, в / 2, г / 2 + 0.0012)
        рост.addChild(лицо)
    }

    // MARK: Части

    /// Экран на лицевой (+z) стороне: тёмное блестящее стекло и на нём заставка во всё стекло (или фото по центру без
    /// искажения). центр — середина стекла на плоскости лица панели.
    private static func экран(на панель: Entity, центр: SIMD3<Float>, ширина: Float, высота: Float, _ о: Отделка,
                              скругление: Float = 0) {
        let ш = max(ширина, 0.01)
        let в = max(высота, 0.01)
        var стеклоМ = SimpleMaterial(color: UIColor(white: 0.03, alpha: 1), roughness: 0.12, isMetallic: false)
        стеклоМ.metallic = .float(0)
        let r = min(скругление, min(ш, в) * 0.45)
        let стекло = ModelEntity(mesh: .generatePlane(width: ш, height: в, cornerRadius: r), materials: [стеклоМ])
        стекло.position = центр + SIMD3<Float>(0, 0, 0.0006)
        панель.addChild(стекло)
        guard let фото = о.фото else { return }
        let размер = о.наВесьЭкран ? SIMD2<Float>(ш, в)
            : вписать(пропорция: о.пропорция, ширина: ш * 0.97, высота: в * 0.97)
        let картинка = ModelEntity(mesh: .generatePlane(width: размер.x, height: размер.y,
                                                        cornerRadius: о.наВесьЭкран ? r : 0),
                                   materials: [снимок(фото, яркость: 1)])
        картинка.position = центр + SIMD3<Float>(0, 0, 0.0012)
        панель.addChild(картинка)
    }

    /// Мягкая подложка-тень: ядро текстуры — ровно основание вещи, края — плавно наружу. Текстуры нет — круглая тень
    /// стойки, нет и её — ровное полупрозрачное пятно.
    private static func подложка(ширина: Float, глубина: Float, _ о: Отделка) -> Entity {
        let след: ModelEntity
        if let текстура = о.подложка ?? о.тень {
            var м = UnlitMaterial()
            м.color = .init(tint: .white, texture: .init(текстура))
            м.blending = .transparent(opacity: .init(floatLiteral: 1))
            let k: Float = о.подложка != nil ? 1 / ядроПодложки : 1.35
            след = ModelEntity(mesh: .generatePlane(width: ширина * k, depth: глубина * k), materials: [м])
        } else {
            var м = UnlitMaterial(color: .black)
            м.blending = .transparent(opacity: .init(floatLiteral: 0.2))
            след = ModelEntity(mesh: .generatePlane(width: ширина + 0.02, depth: глубина + 0.02, cornerRadius: 0.01),
                               materials: [м])
        }
        след.position = SIMD3<Float>(0, 0.0015, 0)
        return след
    }

    /// Скруглённый брусок: скругление не больше 45 % самой малой стороны (иначе сетка ломается).
    private static func брусок(_ ш: Float, _ в: Float, _ г: Float, скругление: Float,
                               _ материал: any Material) -> ModelEntity {
        let r = max(0, min(скругление, min(ш, min(в, г)) * 0.45))
        return ModelEntity(mesh: .generateBox(width: ш, height: в, depth: г, cornerRadius: r), materials: [материал])
    }

    /// Металл или пластик: белизна 0…1. В лёгком режиме (нет карты окружения) металл почти матовый — иначе он чёрный.
    private static func металл(_ белизна: CGFloat, шершавость: Float, металличность: Float,
                               _ о: Отделка) -> SimpleMaterial {
        var м = SimpleMaterial(color: UIColor(white: белизна, alpha: 1), roughness: .float(шершавость),
                               isMetallic: false)
        м.metallic = .float(о.лёгкий ? металличность * 0.3 : металличность)
        return м
    }

    /// Фото на экране или грани: светится само (UnlitMaterial), прозрачность вырезки сохраняется.
    private static func снимок(_ текстура: TextureResource, яркость: CGFloat) -> UnlitMaterial {
        var м = UnlitMaterial()
        м.color = .init(tint: UIColor(white: яркость, alpha: 1), texture: .init(текстура))
        м.blending = .transparent(opacity: .init(floatLiteral: 1))
        return м
    }

    /// Фото в рамке ш×в без искажения, по центру.
    private static func вписать(пропорция: Float, ширина: Float, высота: Float) -> SIMD2<Float> {
        let п = max(0.05, пропорция)
        if ширина / max(высота, 0.000_1) > п { return SIMD2<Float>(высота * п, высота) }
        return SIMD2<Float>(ширина, ширина / п)
    }
}

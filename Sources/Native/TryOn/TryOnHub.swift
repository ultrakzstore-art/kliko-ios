// MARK: - Способы

/// Способ примерить или проверить товар. Порядок случаев — порядок кнопок: сначала телефон, потом ИИ.
enum СпособПримерки: String, CaseIterable, Identifiable, Sendable {
    case живая
    case габариты
    case авто
    case ии
    case комната
    case машина

    var id: String { rawValue }

    /// Вид ИИ-примерки (kind на сервере); nil — способ работает только на телефоне.
    var видИИ: ВидИИПримерки? {
        switch self {
        case .ии: return .человек
        case .комната: return .комната
        case .машина: return .машина
        case .живая, .габариты, .авто: return nil
        }
    }

    /// Способ ходит на сервер (ИИ рисует картинку).
    var наСервере: Bool { видИИ != nil }

    private func т(_ ключ: String) -> String { ХабПримеркиText.т(ключ) }

    var заголовок: String {
        switch self {
        case .ии: return ПримерочнаяText.т("to_btn")
        case .живая: return т("th_live")
        case .габариты: return т("th_fit")
        case .авто: return т("th_auto")
        case .комната: return т("th_room")
        case .машина: return т("th_car")
        }
    }

    /// Заголовок для объявления: у настольной вещи «Поместится ли?» — «Посмотреть на столе».
    func заголовокДля(_ товар: Listing) -> String {
        self == .габариты && ГабаритыВещи.наСтоле(товар.категория) ? т("th_fit_desk") : заголовок
    }

    /// Подсказка VoiceOver для объявления: у настольной вещи — «наведите на стол».
    func подсказкаДля(_ товар: Listing) -> String {
        self == .габариты && ГабаритыВещи.наСтоле(товар.категория) ? т("th_fit_hint_desk") : подсказка
    }

    /// Подпись под заголовком большой кнопки. У «Подойдут ли?» — по тому, шины это или диски; у «Поместится ли?» —
    /// на полу или на столе.
    func подпись(_ товар: Listing) -> String {
        switch self {
        case .ии: return ПримерочнаяText.т("to_btn_sub")
        case .живая: return т("th_live_sub")
        case .габариты: return т(ГабаритыВещи.наСтоле(товар.категория) ? "th_fit_sub_desk" : "th_fit_sub")
        case .авто:
            switch ПризнакиДисков.диски(товар) {
            case .some(true): return т("th_auto_sub_rims")
            case .some(false): return т("th_auto_sub_tires")
            case .none: return т("th_auto_sub")
            }
        case .комната: return т("th_room_sub")
        case .машина: return т("th_car_sub")
        }
    }

    /// Подсказка VoiceOver: что произойдёт по нажатию.
    var подсказка: String {
        switch self {
        case .ии: return ПримерочнаяText.т("to_btn_hint")
        case .живая: return т("th_live_hint")
        case .габариты: return т("th_fit_hint")
        case .авто: return т("th_auto_hint")
        case .комната: return т("th_room_hint")
        case .машина: return т("th_car_hint")
        }
    }

    /// Значок кнопки (SF Symbols, есть в iOS 17). У живой — значок вида вещи (очки, часы…) из LiveTryOnKinds.swift.
    func значок(_ товар: Listing) -> String {
        switch self {
        case .ии: return "tshirt.fill"
        case .живая: return ВидЖивойПримерки.для(товар)?.значок ?? "camera.viewfinder"
        case .габариты: return ГабаритыВещи.наСтоле(товар.категория) ? "laptopcomputer" : "cube.transparent"
        case .авто: return "checklist"
        case .комната: return "sofa.fill"
        case .машина: return "car.side.fill"
        }
    }
}

// MARK: - Вид ИИ-примерки

/**
 Что рисует ИИ — поле kind в start (docs/SERVER_TRYON.md): человек в вещи (person), машина с этими дисками (car),
 комната с этой вещью (room). От вида зависят контур и советы камеры, подписи шагов и что значит «люди в кадре»: у
 человека это хорошо, у машины и комнаты людей быть не должно (сервер их размоет или откажет).
 */
enum ВидИИПримерки: String, CaseIterable, Sendable {
    case человек = "person"
    case машина = "car"
    case комната = "room"

    private func п(_ ключ: String) -> String { ПримерочнаяText.т(ключ) }
    private func х(_ ключ: String) -> String { ХабПримеркиText.т(ключ) }

    /// Людей в кадре быть не должно (машина, комната).
    var безЛюдей: Bool { self != .человек }

    /// Заголовок камеры и окна.
    var заголовок: String {
        switch self {
        case .человек: return п("to_title")
        case .машина: return х("th_car")
        case .комната: return х("th_room")
        }
    }

    /// Подсказка над затвором.
    var подсказкаКамеры: String {
        switch self {
        case .человек: return п("to_cam_hint")
        case .машина: return х("th_cam_car")
        case .комната: return х("th_cam_room")
        }
    }

    /// Три совета фишками над камерой: значок и слово.
    var советы: [(значок: String, текст: String)] {
        switch self {
        case .человек:
            return [("figure.stand", п("to_tip_full")), ("sun.max.fill", п("to_tip_light")), ("square.fill", п("to_tip_bg"))]
        case .машина:
            return [("car.side", х("th_tip_side")), ("circle.circle", х("th_tip_wheels")),
                    ("sun.max.fill", п("to_tip_light"))]
        case .комната:
            return [("rectangle.portrait", х("th_tip_corner")), ("sun.max.fill", п("to_tip_light")),
                    ("person.crop.circle.badge.xmark", х("th_tip_nopeople"))]
        }
    }

    /// Камеры нет — что выбрать из галереи.
    var безКамеры: String {
        switch self {
        case .человек: return п("to_no_cam_hint")
        case .машина: return х("th_no_cam_car")
        case .комната: return х("th_no_cam_room")
        }
    }

    /// Значок заглушки камеры.
    var значок: String {
        switch self {
        case .человек: return "figure.stand"
        case .машина: return "car.side"
        case .комната: return "sofa"
        }
    }

    /// Заголовок шага «Ваше фото».
    var заголовокПроверки: String {
        switch self {
        case .человек: return п("to_check_t")
        case .машина: return х("th_check_car")
        case .комната: return х("th_check_room")
        }
    }

    /// Заголовок полосы «какое фото вещи».
    var заголовокФотоВещи: String {
        switch self {
        case .человек: return п("to_item_t")
        case .машина: return х("th_item_t_car")
        case .комната: return х("th_item_t_room")
        }
    }

    /// Подпись фото вещи в углу снимка (VoiceOver).
    var подписьВещи: String {
        self == .машина ? х("th_item_car") : п("to_item")
    }

    /**
     Отметка под снимком по Vision на телефоне (только подсказка, решает сервер): люди — найдены ли люди. У человека
     «есть» — хорошо; у машины и комнаты — предупреждение «лучше переснять без людей».
     */
    func отметка(люди: Bool) -> (хорошо: Bool, текст: String) {
        switch self {
        case .человек: return (люди, п(люди ? "to_human_ok" : "to_human_no"))
        case .машина, .комната: return (!люди, х(люди ? "th_people_yes" : "th_people_no"))
        }
    }

    /// Для экранов ожидания и итога (TryOnWait.swift, TryOnResult.swift): заголовок ожидания.
    var заголовокОжидания: String {
        switch self {
        case .человек: return п("to_wait_t")
        case .машина: return х("th_wait_car")
        case .комната: return х("th_wait_room")
        }
    }

    /// Метки шторки итога: «Вы / В вещи» у человека, «Было / Стало» у машины и комнаты.
    var подписьДо: String { self == .человек ? п("to_you") : х("th_before") }
    var подписьПосле: String { self == .человек ? п("to_in_item") : х("th_after") }
    /// VoiceOver шторки: что сравниваем и сколько видно исходного фото (формат с %d).
    var сравнениеA11y: String { self == .человек ? п("to_compare_a11y") : х("th_compare_a11y") }
    var сравнениеЗначение: String { self == .человек ? п("to_compare_value") : х("th_compare_value") }

    /// Пометка под итогом: картинку сделал ИИ.
    var примечаниеИтога: String {
        switch self {
        case .человек: return п("to_result_note")
        case .машина: return х("th_note_car")
        case .комната: return х("th_note_room")
        }
    }
}

// MARK: - Какие способы у объявления

/**
 Какие способы у объявления — по разделу (ключи дерева сайта, РазделыСайта), рубильникам и ответу сервера. Разделы ИИ
 (одежда, машина, комната) — в РазделыПримерочной (TryOnAPI.swift), сервер может заменить их списками sections.
 */
@MainActor
enum ПодборПримерки {
    /// Живая примерка в камере: очки, головные уборы, серьги, колье, часы и смарт-часы, браслеты, кольца (и общие
    /// разделы украшений и аксессуаров — там вид угадывается по названию). Список ведёт сама живая примерка
    /// (ВидЖивойПримерки, LiveTryOnKinds.swift); решает по объявлению ОкноЖивойПримерки.подходит.
    static var разделыЖивой: Set<String> { ВидЖивойПримерки.всеРазделы }
    /// «Поместится ли?» на полу: вся мебель (и детская), крупная техника, телевизоры, ковры, тренажёры, аквариумы,
    /// велосипеды, самокаты и коляски (у них в подаче есть шаблоны размеров — PostingSizeTemplates.swift).
    static let разделыГабаритов: Set<String> = [
        "furniture", "kids-furniture", "fridges", "washing-machines", "dishwashers", "stoves",
        "air-conditioners", "water-heaters", "tv", "home-theater", "carpets", "treadmills",
        "exercise-bikes", "gaming-chairs", "aquariums", "bicycles", "kids-bikes-scooters", "e-scooters", "strollers"
    ]
    /// «Поместится ли?» на столе (владелец 14.10.2026: «например ноутбук 3D на столе»): ноутбуки, мониторы, моноблоки,
    /// системные блоки, принтеры, планшеты, телефоны, приставки, колонки, микроволновки и мелкая техника — подсказки
    /// AR про стол (FitBoxAR.swift). Список — ГабаритыВещи.разделыСтола (FitBoxSize.swift): его читают и вне главной нити.
    static var разделыСтола: Set<String> { ГабаритыВещи.разделыСтола }
    /// «Подойдут ли?»: шины и диски (один раздел сайта на оба).
    static let разделыАвто: Set<String> = ["tires-wheels"]

    /**
     Способы объявления по порядку кнопок. подтверждённые — только те, что можно нажать сейчас (ИИ — после on:true в
     info); иначе — все, что могут появиться (ИИ — без сети: рубильник, сервер не отказал, раздел и фото). Второе —
     для КнопкаПримерочной.есть и для решения, спрашивать ли сервер.
     */
    static func способы(_ товар: Listing, подтверждённые: Bool) -> [СпособПримерки] {
        let готовность = ГотовностьПримерочной.shared
        return СпособПримерки.allCases.filter { способ in
            доступен(способ, товар: товар, подтверждён: подтверждённые, готовность: готовность)
        }
    }

    private static func доступен(_ способ: СпособПримерки, товар: Listing, подтверждён: Bool,
                                 готовность: ГотовностьПримерочной) -> Bool {
        let раздел = товар.категория
        switch способ {
        case .живая:
            return Config.живаяПримерка && ОкноЖивойПримерки.подходит(товар)
        case .габариты:
            /* Владелец 17.10.2026: пока под ценой стоит строка «На столе · 3D» (SiteListingLook.swift), «Поместится
               ли?» — капсулой в ней, второго входа в то же окно в блоке примерки нет. */
            return габаритыВозможны(товар) && !СмотретьВещьОбъявления.включено
        case .авто:
            /* Пачка 83, D2: пока под ценой стоит строка «Подойдут ли?» (SiteListingTyreFit.swift), второго входа в то
               же окно в блоке примерки нет. */
            return Config.автоПодбор && РазделыСайта.внутри(раздел, разделыАвто) && !ПодойдутЛиОбъявления.стоит(товар)
        case .ии, .комната, .машина:
            guard let вид = способ.видИИ else { return false }
            /* Шины без дисков на машину не «наденешь» — только диски или колёса в сборе (не знаем — не мешаем). */
            if вид == .машина && ПризнакиДисков.диски(товар) == false { return false }
            return подтверждён ? готовность.можно(товар, вид: вид) : готовность.возможно(товар, вид: вид)
        }
    }

    /// «Поместится ли?» у объявления вообще: рубильник, AR на устройстве и раздел (на полу или на столе). Нет AR
    /// (симулятор, Mac, старый iPad) — входа нет, а не заглушка «AR нет» по нажатию. Его спрашивают и блок примерки, и
    /// строка «На столе · 3D» (СмотретьВещьОбъявления, SiteListingLook.swift).
    static func габаритыВозможны(_ товар: Listing) -> Bool {
        Config.габаритыAR && ОкноГабаритов.доступно
            && РазделыСайта.внутри(товар.категория, разделыГабаритов.union(разделыСтола))
    }

    /// Открыть окно способа поверх страницы. номерФото — фото галереи на экране (его и примеряем).
    static func открыть(_ способ: СпособПримерки, товар: Listing, номерФото: Int) {
        let всего = товар.фотоАдреса.count
        let фото = всего > 0 ? min(max(0, номерФото), всего - 1) : 0
        switch способ {
        case .ии:
            ОкноПримерочной.открыть(товар: товар, номерФото: фото, вид: .человек)
        case .комната:
            ОкноПримерочной.открыть(товар: товар, номерФото: фото, вид: .комната)
        case .машина:
            ОкноПримерочной.открыть(товар: товар, номерФото: фото, вид: .машина)
        case .живая:
            ОкноЖивойПримерки.открыть(товар: товар, фото: фото)
        case .габариты:
            ОкноГабаритов.открыть(товар: товар)
        case .авто:
            ОкноАвтоПодбора.открыть(товар: товар)
        }
    }
}

// MARK: - Шины или диски

/**
 В разделе «Шины и диски» (tires-wheels) у сайта один ключ на всё. Диски от шин отличаем по названию, а если по нему не
 понять — по характеристикам: «диск», «литые», «кованые», «штампы», «разболтовка», «вылет», PCD «5x114.3», ширина
 «7.5J», «ET45», «колёса» (в сборе — значит, с дисками) — диски; «шины», «резина», «покрышки», размер «205/55 R16» без
 признаков дисков — одни шины. Название — первым: у шин в характеристиках бывает «посадочный диаметр диска».
 */
enum ПризнакиДисков {
    private static let словаДисков = ["диск", "литы", "кован", "штамп", "разболтовк", "вылет", "pcd", "колёс", "колес",
                                      "дискі"]
    /// «Профиль» и «Остаток протектора» — пункты формы подачи шин (у дисков их нет).
    private static let словаШин = ["шин", "резин", "покрышк", "tire", "tyre", "профил", "протектор"]
    /// PCD «5x114.3», «4х100», «5×112»; ширина обода «7.5J», «7J»; вылет «ET45», «ET 35». После PCD не должен идти
    /// профиль шины: «4х205/55 R16» — это четыре шины 205/55, а не разболтовка 4×205.
    private static let образцыДисков = [
        "\\b[3-8]\\s*[xх×*]\\s*[0-9]{2,3}([.,][0-9])?\\b(?!\\s*/\\s*[2-9][05]\\s*[/-]?\\s*z?[rр]?\\s*[0-9]{2}(?![0-9]))",
        "\\b[0-9]{1,2}([.,][05])?\\s*j\\b",
        "\\bet\\s*-?[0-9]{1,3}\\b"
    ]
    /// Размер шины «205/55 R16», «195/65r15», «225/45ZR17», «225/45/17», «225/45-17» (и «4х205/55 R16» — перед ним
    /// может стоять число штук, поэтому слева не граница слова, а «не цифра»).
    private static let образецШины = "(?<![0-9.])[0-9]{3}\\s*/\\s*[0-9]{2}\\s*[/-]?\\s*z?[rр]?\\s*[0-9]{2}"

    /// true — диски (или колёса в сборе); false — одни шины; nil — не понять. Последнее слово — за строкой подачи в
    /// описании («Диски: R16 …» или «Размер шин: 205/55 R16», Posting/PostingSizeWheels.swift).
    static func диски(_ товар: Listing) -> Bool? {
        guard РазделыСайта.внутри(товар.категория, ["tires-wheels"]) else { return nil }
        if let поНазванию = оценка(товар.title) { return поНазванию }
        let характеристики = товар.характеристики.map { $0.ключ + " " + $0.значение }.joined(separator: " ")
        if let поХарактеристикам = оценка(характеристики) { return поХарактеристикам }
        let строки = СтрокиКолёсПодачи.своиСтроки(товар.описание ?? "")
        if строки.contains(СтрокиКолёсПодачи.началоДисков) { return true }
        if строки.contains(СтрокиКолёсПодачи.началоШин) { return false }
        return nil
    }

    /// Шины или диски по названию (для подачи, где объявления ещё нет): true — диски, false — шины, nil — не понять.
    static func поНазванию(_ название: String) -> Bool? {
        оценка(название)
    }

    private static func оценка(_ исходный: String) -> Bool? {
        /* «шины без дисков», «без дисков» — не признак дисков. */
        let текст = исходный.lowercased().replacingOccurrences(of: "без диск", with: " ")
        guard !текст.isEmpty else { return nil }
        let естьДиски = словаДисков.contains { текст.contains($0) }
            || образцыДисков.contains { текст.range(of: $0, options: .regularExpression) != nil }
        if естьДиски { return true }
        let естьШины = словаШин.contains { текст.contains($0) }
            || текст.range(of: образецШины, options: .regularExpression) != nil
        return естьШины ? false : nil
    }
}

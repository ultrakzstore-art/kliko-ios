import Foundation

/**
 «ДЛЯ ВАС» — СЕЗОН: ПОРЯДОК ПОЛОК И КАРТОЧЕК (пачка 83; docs/SERVER_NEW_FOR_MINE.md §4).

 Сезон только меняет порядок — без отдельных запросов и без push (решение владельца, docs/STANDARDS.md §13). Встроенные
 правила — те же, что §4.2: зимние шины 01.10–30.11 (зимние первыми), летние 15.03–15.05 (летние первыми), школа
 01.08–31.08, кондиционеры 01.05–31.05, верхняя одежда 15.09–30.11, отопление 01.10–31.12, велосипеды 01.04–31.05, зимний
 спорт 15.11–31.01. Даты — по поясу Asia/Almaty (Казахстан с 01.03.2024 — один пояс UTC+5), включительно; «с» позже «по»
 — через Новый год.

 Вес правила 1…5. Полка (группа запросов «Для вас») поднимается на столько ступеней, если её раздел — из разделов
 правила, их потомок или предок (outerwear поднимает полку mens-clothing). Внутри полки первыми идут объявления из этих
 разделов, а у правила со стандартом (сезон шин) — только подходящие под него: зимой — зимние шины, весной — летние.

 Правила сервера (§4.1, ключ season_rules, по умолчанию выключен) ставит ForYouSeasonServer.swift — вместо встроенных,
 с датами города (geo); нет их — встроенные. Читать можно с любой нити (замок): сверка «Для вас» идёт не на главной.
 */

// MARK: - Правило

struct ПравилоСезонаДляВас: Hashable, Sendable {
    let ключ: String
    /// Начало и конец — месяц × 100 + число (1001 — 1 октября), включительно.
    let с: Int
    let по: Int
    /// Вес 1…5.
    let вес: Int
    let разделы: [String]
    /// Сезоны шин стандарта tyre_season («winter_studded», «winter_friction»); пусто — правило без стандарта.
    let сезоныШин: Set<String>

    init(_ ключ: String, с: Int, по: Int, вес: Int, разделы: [String], сезоныШин: Set<String> = []) {
        self.ключ = ключ
        self.с = с
        self.по = по
        self.вес = max(1, min(5, вес))
        self.разделы = разделы
        self.сезоныШин = сезоныШин
    }

    /// То же правило со своими датами (geo сервера — свои даты города).
    func сДатами(с новоеС: Int, по новоеПо: Int) -> ПравилоСезонаДляВас {
        ПравилоСезонаДляВас(ключ, с: новоеС, по: новоеПо, вес: вес, разделы: разделы, сезоныШин: сезоныШин)
    }

    /// Действует в этот день (месяц × 100 + число).
    func действует(_ день: Int) -> Bool {
        if с <= по { return день >= с && день <= по }
        return день >= с || день <= по
    }

    /// Раздел полки — из разделов правила, их потомок или предок.
    func касается(_ раздел: String) -> Bool {
        guard !раздел.isEmpty else { return false }
        if РазделыСайта.внутри(раздел, Set(разделы)) { return true }
        for свой in разделы where РазделыСайта.внутри(свой, [раздел]) { return true }
        return false
    }
}

// MARK: - Сезон

enum СезонДляВас {
    /// Пояс дат правил.
    static let пояс: TimeZone = TimeZone(identifier: "Asia/Almaty") ?? TimeZone(secondsFromGMT: 5 * 3600) ?? .current

    /// Правила §4.2 — те же, что у сервера по умолчанию; веса «предложений» — 2.
    static let встроенные: [ПравилоСезонаДляВас] = [
        ПравилоСезонаДляВас("tyres_winter", с: 1001, по: 1130, вес: 3, разделы: ["tires-wheels", "tire-service"],
                            сезоныШин: ["winter_studded", "winter_friction"]),
        ПравилоСезонаДляВас("tyres_summer", с: 315, по: 515, вес: 3, разделы: ["tires-wheels", "tire-service"],
                            сезоныШин: ["summer"]),
        ПравилоСезонаДляВас("school", с: 801, по: 831, вес: 2,
                            разделы: ["school-supplies", "school-backpacks", "school-stationery", "school-uniform",
                                      "school-books"]),
        ПравилоСезонаДляВас("ac", с: 501, по: 531, вес: 2, разделы: ["air-conditioners"]),
        ПравилоСезонаДляВас("outerwear", с: 915, по: 1130, вес: 2,
                            разделы: ["mens-outerwear", "womens-outerwear", "kids-outerwear"]),
        ПравилоСезонаДляВас("heating", с: 1001, по: 1231, вес: 2, разделы: ["heating-cooling"]),
        ПравилоСезонаДляВас("bikes", с: 401, по: 531, вес: 2, разделы: ["bicycles"]),
        ПравилоСезонаДляВас("winter_sport", с: 1115, по: 131, вес: 2,
                            разделы: ["skis", "snowboards", "ice-skates", "winter-sport"])
    ]

    private static let замок = NSLock()
    /// Правила сервера; nil — встроенные. Читаются и пишутся только под замком.
    private static var сервера: [ПравилоСезонаДляВас]? = nil
    /// Свои даты города от сервера: город → ключ правила → [с, по].
    private static var датыГородов: [String: [String: [Int]]] = [:]

    /// Поставить правила сервера (nil — снять, работают встроенные).
    static func поставитьСервера(_ правила: [ПравилоСезонаДляВас]?, гео: [String: [String: [Int]]]) {
        замок.lock()
        сервера = правила
        датыГородов = правила == nil ? [:] : гео
        замок.unlock()
    }

    /// День года по поясу правил: месяц × 100 + число.
    static func день(_ дата: Date) -> Int {
        var календарь = Calendar(identifier: .gregorian)
        календарь.timeZone = пояс
        let части: DateComponents = календарь.dateComponents([.month, .day], from: дата)
        let месяц: Int = части.month ?? 1
        let число: Int = части.day ?? 1
        return месяц * 100 + число
    }

    /// Действующие сегодня правила: сервера (если есть) или встроенные; у города — свои даты из geo сервера.
    static func действующие(_ дата: Date = Date(), город: String = "") -> [ПравилоСезонаДляВас] {
        замок.lock()
        let свои: [ПравилоСезонаДляВас]? = сервера
        let гео: [String: [String: [Int]]] = датыГородов
        замок.unlock()
        let правила: [ПравилоСезонаДляВас] = свои ?? встроенные
        let местные: [String: [Int]] = город.isEmpty ? [:] : (гео[город] ?? [:])
        let сегодня: Int = день(дата)
        var итог: [ПравилоСезонаДляВас] = []
        for правило in правила {
            var своё: ПравилоСезонаДляВас = правило
            if let даты = местные[правило.ключ], даты.count == 2 {
                своё = правило.сДатами(с: даты[0], по: даты[1])
            }
            if своё.действует(сегодня) { итог.append(своё) }
        }
        return итог
    }

    /// Вес раздела полки: наибольший среди правил, которых он касается; 0 — не в сезоне.
    static func вес(раздела раздел: String, _ правила: [ПравилоСезонаДляВас]) -> Int {
        var итог = 0
        for правило in правила where правило.вес > итог && правило.касается(раздел) {
            итог = правило.вес
        }
        return итог
    }

    /**
     Вес карточки: объявление из разделов правила; у правила со стандартом (сезон шин) — только подходящее под него
     (сезон — из parts.season, иначе из названия). 0 — порядок по свежести, как без сезона.
     */
    static func вес(_ товар: Listing, _ правила: [ПравилоСезонаДляВас]) -> Int {
        guard !правила.isEmpty, let раздел = товар.категория, !раздел.isEmpty else { return 0 }
        var итог = 0
        var сезон: String? = nil
        var искали = false
        for правило in правила where правило.вес > итог {
            guard РазделыСайта.внутри(раздел, Set(правило.разделы)) else { continue }
            if !правило.сезоныШин.isEmpty {
                if !искали {
                    сезон = сезонШины(товар)
                    искали = true
                }
                guard let найден = сезон, подходит(найден, правило.сезоныШин) else { continue }
            }
            итог = правило.вес
        }
        return итог
    }

    /// «Зимние» без уточнения подходят под любой зимний сезон правила.
    private static func подходит(_ сезон: String, _ нужные: Set<String>) -> Bool {
        if нужные.contains(сезон) { return true }
        guard сезон == "winter" else { return false }
        return нужные.contains("winter_studded") || нужные.contains("winter_friction")
    }

    /// Сезон шин объявления ключом tyre_season: parts.season, иначе название; не понятно — nil.
    static func сезонШины(_ товар: Listing) -> String? {
        var сезон: СезонАвтоподбора? = nil
        if let поле = товар.запчастьПолей["season"] { сезон = РазборАвтоподбора.сезонПоля(поле) }
        if сезон == nil { сезон = ПарсерАвтоподбора.сезон(ПарсерАвтоподбора.нормально(товар.title)) }
        guard let сезон else { return nil }
        switch сезон {
        case .лето: return "summer"
        case .зимаШипы: return "winter_studded"
        case .зимаЛипучка: return "winter_friction"
        case .зима: return "winter"
        case .всесезон: return "all_season"
        }
    }

    // MARK: Поднять

    private struct Место {
        let номер: Int
        let вес: Int
        var ключ: Int { номер - вес }
    }

    /// Поднять элементы на их вес ступеней: равные места — поднятый раньше, дальше — прежний порядок.
    static func поднять<Элемент>(_ список: [Элемент], по оценка: (Элемент) -> Int) -> [Элемент] {
        var места: [Место] = []
        for (номер, элемент) in список.enumerated() {
            let w: Int = оценка(элемент)
            места.append(Место(номер: номер, вес: max(0, w)))
        }
        guard места.contains(where: { (м: Место) -> Bool in м.вес > 0 }) else { return список }
        let порядок: [Место] = места.sorted { (а: Место, б: Место) -> Bool in
            if а.ключ != б.ключ { return а.ключ < б.ключ }
            if а.вес != б.вес { return а.вес > б.вес }
            return а.номер < б.номер
        }
        var итог: [Элемент] = []
        for м in порядок { итог.append(список[м.номер]) }
        return итог
    }
}

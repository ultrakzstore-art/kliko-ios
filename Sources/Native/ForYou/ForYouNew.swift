import Foundation

/**
 «ДЛЯ ВАС · 3 НОВЫХ» — ЧТО НОВОГО С ПРОШЛОГО ПРОСМОТРА (пачка 83; docs/SERVER_NEW_FOR_MINE.md §9, «Дофамин без тёмных
 паттернов»).

 Телефон помнит номера показанных находок — только номера объявлений, до 500 последних — и разделы, которые уже видел.
 Файл foryou-seen.json лежит в папке «Моего» (Application Support/MyThings, вне резервной копии, ФайлыМоего) и
 стирается вместе с ним — «Удалить всё «Моё»» и выход (МоёХранилище.стереть зовёт забыть()). На сервер не уходит ничего.

 Новые — подходящие («подходит» и «нужна деталь»), которых не было в прошлых показах; «Проверьте» новыми не считаются.
 Раздел, которого телефон ещё не видел (первый запуск, новое в «Моём»), — точка отсчёта: его находки сразу «показаны»,
 без «48 новых». Новые идут первыми — в полке, на экране и в рядах «Подходит вам»; «N новых» — в заголовке полки и
 шапке ряда; на экране — чип «Новые». Показанными новинки становятся, когда открыт экран «Для вас» (всё, что на нём)
 или когда ряд «Подходит вам» ушёл с экрана (его карточки). Полка на главной сама ничего «показанным» не делает: счётчик
 живёт, пока человек не заглянет.

 Push fit_new (§3.5, MyThingsWatch.swift): его номера ids — первыми среди загруженного обычным путём, 6 часов; отдельно
 по ним ничего не догружается.
 */
@MainActor
final class НовинкиДляВас: ObservableObject {
    static let shared = НовинкиДляВас()

    /// Сколько номеров помнить.
    static let предел = 500
    /// Разделов — не больше (их всего несколько десятков у «Моего»).
    static let пределРазделов = 100
    static let имяФайла = "foryou-seen.json"
    /// Номера push ставятся первыми столько, с.
    static let срокПуша: TimeInterval = 6 * 3600

    private struct Файл: Codable {
        var ids: [String] = []
        var cats: [String] = []
    }

    /// Новые, которые были на открытом экране «Для вас» в этот показ, — чип «Новые» (снимается, когда экран закрыт).
    @Published private(set) var новыеЭкрана: Set<String> = []

    private var прочитано = false
    private var виденные: [String] = []
    private var видели: Set<String> = []
    private var разделы: Set<String> = []
    private var пуш: [String] = []
    private var пушКогда = Date.distantPast
    private var экранОткрыт = false

    private init() {}

    /// Файл — один раз, при первой надобности (полка «Моё» читает через 2,5 с после запуска).
    private func подготовить() {
        guard !прочитано else { return }
        прочитано = true
        guard let данные = ФайлыМоего.прочитатьМалый(Self.имяФайла),
              let файл = try? JSONDecoder().decode(Файл.self, from: данные) else { return }
        виденные = Array(файл.ids.suffix(Self.предел))
        видели = Set(виденные)
        разделы = Set(файл.cats.prefix(Self.пределРазделов))
    }

    private func записать() {
        let файл = Файл(ids: виденные, cats: разделы.sorted())
        guard let данные = try? JSONEncoder().encode(файл) else { return }
        ФайлыМоего.записатьМалый(Self.имяФайла, данные)
    }

    /// Отметить показанным; true — раньше его не было.
    @discardableResult
    private func отметить(_ номер: String) -> Bool {
        guard !номер.isEmpty, видели.insert(номер).inserted else { return false }
        виденные.append(номер)
        if виденные.count > Self.предел {
            let лишних: Int = виденные.count - Self.предел
            for старый in виденные.prefix(лишних) { видели.remove(старый) }
            виденные.removeFirst(лишних)
        }
        return true
    }

    private static func подходящая(_ находка: НаходкаДляВас) -> Bool {
        находка.уровень <= .доработка
    }

    /// Новая ли находка: подходящая и ещё не показанная (или новая на открытом сейчас экране).
    func новая(_ находка: НаходкаДляВас) -> Bool {
        guard Self.подходящая(находка) else { return false }
        return !видели.contains(находка.id) || новыеЭкрана.contains(находка.id)
    }

    /**
     Новая выдача полки или ряда: точка отсчёта для разделов, которых телефон ещё не видел; открыт экран — новое сразу
     становится показанным (и помнится для чипа «Новые»). Возвращает порядок показа: номера push, новые, остальные.
     */
    func учесть(_ находки: [НаходкаДляВас], разделы загружены: Set<String>) -> [НаходкаДляВас] {
        подготовить()
        var изменилось = false
        let незнакомые: Set<String> = загружены.subtracting(разделы)
        if !незнакомые.isEmpty, разделы.count < Self.пределРазделов {
            for находка in находки where незнакомые.contains(находка.раздел) {
                if отметить(находка.id) { изменилось = true }
            }
            разделы.formUnion(незнакомые)
            изменилось = true
        }
        if экранОткрыт {
            var экрана: Set<String> = новыеЭкрана
            for находка in находки where Self.подходящая(находка) && !видели.contains(находка.id) {
                экрана.insert(находка.id)
                if отметить(находка.id) { изменилось = true }
            }
            if экрана != новыеЭкрана { новыеЭкрана = экрана }
        }
        if изменилось { записать() }
        return упорядочить(находки)
    }

    /// Показанные номера — для фоновой сверки ряда «Подходит вам» (новые — впереди).
    func снимок() -> Set<String> {
        подготовить()
        return видели
    }

    /// Сколько новых среди находок.
    func сколькоНовых(_ находки: [НаходкаДляВас]) -> Int {
        var итог = 0
        for находка in находки where Self.подходящая(находка) && !видели.contains(находка.id) { итог += 1 }
        return итог
    }

    /// Порядок показа: номера push (6 часов, в их порядке), потом новые, потом остальные — каждые в прежнем порядке.
    func упорядочить(_ находки: [НаходкаДляВас]) -> [НаходкаДляВас] {
        let свежийПуш: Bool = Date().timeIntervalSince(пушКогда) < Self.срокПуша
        var первые: [НаходкаДляВас] = []
        if свежийПуш && !пуш.isEmpty {
            var поНомеру: [String: НаходкаДляВас] = [:]
            for находка in находки where поНомеру[находка.id] == nil { поНомеру[находка.id] = находка }
            for номер in пуш {
                if let находка = поНомеру[номер] { первые.append(находка) }
            }
        }
        let взяты: Set<String> = Set(первые.map { (н: НаходкаДляВас) -> String in н.id })
        var новые: [НаходкаДляВас] = []
        var прочие: [НаходкаДляВас] = []
        for находка in находки where !взяты.contains(находка.id) {
            if новая(находка) {
                новые.append(находка)
            } else {
                прочие.append(находка)
            }
        }
        return первые + новые + прочие
    }

    /// Ряд «Подходит вам» ушёл с экрана: его подходящие карточки — показаны.
    func показаны(_ находки: [НаходкаДляВас]) {
        подготовить()
        var изменилось = false
        for находка in находки where Self.подходящая(находка) {
            if отметить(находка.id) { изменилось = true }
        }
        guard изменилось else { return }
        записать()
        ПодборкаДляВас.shared.пересчитатьНовые()
    }

    /// Экран «Для вас» открыт: всё новое на нём — показано (чип «Новые» помнит, что было новым); закрыт — чип снят.
    func экран(открыт: Bool, находки: [НаходкаДляВас]) {
        подготовить()
        экранОткрыт = открыт
        guard открыт else {
            if !новыеЭкрана.isEmpty { новыеЭкрана = [] }
            return
        }
        var экрана: Set<String> = новыеЭкрана
        var изменилось = false
        for находка in находки where Self.подходящая(находка) && !видели.contains(находка.id) {
            экрана.insert(находка.id)
            if отметить(находка.id) { изменилось = true }
        }
        if экрана != новыеЭкрана { новыеЭкрана = экрана }
        if изменилось { записать() }
    }

    /// Номера push fit_new — первыми среди загруженного, 6 часов (до 20, как присылает сервер).
    func изПуша(_ номера: [String]) {
        guard !номера.isEmpty else { return }
        пуш = Array(номера.prefix(20))
        пушКогда = Date()
    }

    /// «Удалить всё «Моё»» и выход: забыть всё (файл стирается вместе с папкой «Моего»).
    func забыть() {
        прочитано = true
        виденные = []
        видели = []
        разделы = []
        пуш = []
        пушКогда = .distantPast
        if !новыеЭкрана.isEmpty { новыеЭкрана = [] }
    }
}

/// Группа полки — чип экрана «Для вас»; профиль сверки к ней сводится.
enum ГруппаДляВас: String, CaseIterable, Identifiable, Sendable {
    case машина = "car"
    case устройства = "devices"
    case дом = "home"
    case компьютер = "pc"
    case одежда = "wear"

    var id: String { rawValue }

    init(_ профиль: ИтогСовместимостиМоего.Профиль) {
        switch профиль {
        case .машина: self = .машина
        case .телефон, .ноутбук: self = .устройства
        case .дом: self = .дом
        case .компьютер: self = .компьютер
        case .размер: self = .одежда
        }
    }

    var название: String { ДляВасText.т("fv_g_" + rawValue) }

    var значок: String {
        switch self {
        case .машина: return "car.fill"
        case .устройства: return "iphone"
        case .дом: return "house.fill"
        case .компьютер: return "desktopcomputer"
        case .одежда: return "tshirt.fill"
        }
    }
}

/// Объявление полки: сверка на телефоне и причина для плашки.
struct НаходкаДляВас: Identifiable, Equatable {
    let товар: Listing
    /// .подходит или .доработка; .проверить — только в ряду «Проверьте», когда точных нет (пачка 83: вещь нужного
    /// вида, но размер или параметры не указаны — ПодборДляВас.заменаПроверкой), — без галочки, своим цветом плашки.
    let уровень: УровеньАвтоподбора
    /// Плашка под карточкой: «Для вашей Camry», «Ваш размер M», «Для кровати 160×200».
    let причина: String
    /// С чем сверили и почему — строка экрана целиком («160×200 — ваша 160×200 · Спальня»).
    let подробно: String
    /// Нужная деталь у «доработки» («переходник E14 → E27»).
    let деталь: String?
    /// Цвет моего гардероба, с которым вещь сочетается (только одежда).
    let цвет: ЦветСтандарта?
    let группа: ГруппаДляВас
    /// Раздел запроса — в ряду главной не больше трёх с одного.
    let раздел: String

    var id: String { товар.id }
}

// MARK: - Подбор: чистые функции

enum ПодборДляВас {
    static let пределЗапросов = 6
    /// Лёгкий режим (РежимУстройства): меньше запросов и карточек.
    static let пределЗапросовЛёгкий = 3
    static let наСтраницу = 48
    static let наСтраницуЛёгкий = 24
    static let вРяду = 12
    static let сРазделаВРяду = 3
    static let пределНаходок = 200
    /// Ряд «Проверьте» (точных нет): не больше стольких, с раздела — не больше двух.
    static let вРядуПроверки = 6
    static let сРазделаПроверки = 2
    /// Сколько живёт ответ раздела.
    static let срок: TimeInterval = 15 * 60

    /// Ряд главной для полки: ключ — только для краски точки в заголовке (РядГлавной).
    static var разделГлавной: РазделГлавной { РазделГлавной(ключ: "for-you", краска: 0x16A34A) }

    private static func ф(_ ключ: String, _ аргумент: String) -> String {
        String(format: СтандартыText.т(ключ), аргумент)
    }

    /**
     «Моё» для сверки: где в мерках нет размера вида, а в гардеробе есть вещи этого вида с размером, — самый частый размер
     гардероба (по одному на вид). Только в памяти: запись «Моего» не меняется.
     */
    static func моёДляСверки(_ моё: ЗаписьМоего) -> ЗаписьМоего {
        let свои = Set(моё.тело.размеры.map(\.вид))
        var счёт: [String: Int] = [:]
        var образцы: [String: РазмерМоего] = [:]
        for вещь in моё.гардероб.вещи {
            guard let размер = вещь.размер, !свои.contains(размер.вид) else { continue }
            let ключ = размер.вид.rawValue + "|" + размер.система + "|" + размер.значение + "|" + размер.значение2
            счёт[ключ, default: 0] += 1
            if образцы[ключ] == nil { образцы[ключ] = размер }
        }
        guard !счёт.isEmpty else { return моё }
        var итог = моё
        var взяты = Set<ВидРазмераМоего>()
        let порядок = счёт.sorted { $0.value == $1.value ? $0.key < $1.key : $0.value > $1.value }
        for пара in порядок {
            guard let размер = образцы[пара.key], !взяты.contains(размер.вид) else { continue }
            взяты.insert(размер.вид)
            итог.тело.размеры.append(размер)
        }
        return итог
    }

    /**
     Запросы полки: ПодборМоего и свои (стёкла и плёнки под телефон, сумки и рюкзаки под ноутбук), по одному на раздел, по
     кругу групп — сначала первый запрос каждой группы, потом второй; не больше предела. Сезон (пачка 83,
     ForYouSeason.swift) поднимает группу на вес правила её разделов: в октябре машина (зимние шины) и одежда (верхняя)
     — раньше дома.
     */
    static func запросы(_ моё: ЗаписьМоего, предел: Int, сезон: [ПравилоСезонаДляВас] = []) -> [ЗапросПодбораМоего] {
        guard Config.моё, предел > 0 else { return [] }
        var все = ПодборМоего.запросы(моё, предел: 12)
        if let телефон = моё.телефон, !телефон.модель.trimmingCharacters(in: .whitespaces).isEmpty {
            все.append(ЗапросПодбораМоего(профиль: .телефон, раздел: "phone-accessories", запрос: "",
                                          причина: ф("fy_phone", телефон.модель)))
        }
        if let диагональ = СовместимостьМоего.диагональНоутбука(моё) {
            let причина = ДляВасText.ф("fv_laptop", ЧислоМоего.дюймы(диагональ))
            for раздел in ["backpacks", "handbags"] {
                все.append(ЗапросПодбораМоего(профиль: .ноутбук, раздел: раздел, запрос: "", причина: причина))
            }
        }
        var очередь: [ГруппаДляВас: [ЗапросПодбораМоего]] = [:]
        var порядок: [ГруппаДляВас] = []
        var разделы = Set<String>()
        for запрос in все where разделы.insert(запрос.раздел).inserted {
            let группа = ГруппаДляВас(запрос.профиль)
            if очередь[группа] == nil { порядок.append(группа) }
            очередь[группа, default: []].append(запрос)
        }
        if !сезон.isEmpty {
            let свои: [ГруппаДляВас: [ЗапросПодбораМоего]] = очередь
            порядок = СезонДляВас.поднять(порядок) { (группа: ГруппаДляВас) -> Int in
                var наибольший = 0
                for запрос in свои[группа] ?? [] {
                    let вРазделе: Int = СезонДляВас.вес(раздела: запрос.раздел, сезон)
                    наибольший = max(наибольший, вРазделе)
                }
                return наибольший
            }
        }
        var итог: [ЗапросПодбораМоего] = []
        var шаг = 0
        while итог.count < предел {
            var взяли = false
            for группа in порядок where итог.count < предел {
                guard let список = очередь[группа], шаг < список.count else { continue }
                итог.append(список[шаг])
                взяли = true
            }
            guard взяли else { break }
            шаг += 1
        }
        return итог
    }

    /// Ключ набора разделов: сменился — есть что догрузить.
    static func отпечаток(_ запросы: [ЗапросПодбораМоего]) -> String {
        Set(запросы.map(\.раздел)).sorted().joined(separator: ",")
    }

    // MARK: Сверка

    /// Семьи стандарта, ради которых запрос в разделе (причина запроса годится только им).
    private static func семьи(раздела раздел: String) -> Set<СемьяСтандарта> {
        switch раздел {
        case "bedding": return [.бельё, .спальноеМесто, .матрас]
        case "beds": return [.спальноеМесто, .матрас]
        case "lighting": return [.цоколь]
        case "tv-audio": return [.vesa]
        case "curtains": return [.шторы]
        case "ram": return [.память]
        case "ssd-hdd": return [.накопитель]
        case "gpu": return [.видеокарта]
        default: return []
        }
    }

    /// Раздел шире запроса: в «ТВ и аудио» ищем кронштейн, а не телевизор того же VESA; в «Кроватях» — матрас, а не
    /// каркас; в «Свете» — лампы, а не люстру, — нужно слово в названии.
    private static let словаРаздела: [String: [String]] = [
        "tv-audio": ["кронштейн", "креплен", "крепеж", "mount", "bracket", "ілгіш"],
        "beds": ["матрас", "матрац", "топпер", "наматрасник", "mattress", "topper", "төсеніш"],
        "lighting": ["ламп", "bulb", "шам "]
    ]

    private struct Кандидат {
        let находка: НаходкаДляВас
        let свежесть: Int
        let номер: Int
        /// Вес сезона карточки (ForYouSeason.swift): в сезон — выше свежих не в сезон.
        let балл: Int
    }

    /// Итог сверки: точные («подходит», «нужна деталь») и запас «Проверьте» — вещи нужного вида, где сверить не по чему.
    struct СверкаДляВас {
        var точные: [НаходкаДляВас] = []
        var проверить: [НаходкаДляВас] = []
    }

    /// Профили, у которых «размер не указан» имеет смысл (шины, одежда, дом, компьютер) — у чехлов и сумок запаса нет.
    private static func естьЗапас(_ профиль: ИтогСовместимостиМоего.Профиль) -> Bool {
        switch профиль {
        case .машина, .размер, .дом, .компьютер: return true
        case .телефон, .ноутбук: return false
        }
    }

    /// Порядок кандидатов: сезон выше, потом свежие (fresh_ts, иначе created_ts), потом порядок ответа.
    private static func раньше(_ а: Кандидат, _ б: Кандидат) -> Bool {
        if а.балл != б.балл { return а.балл > б.балл }
        if а.свежесть != б.свежесть { return а.свежесть > б.свежесть }
        return а.номер < б.номер
    }

    /**
     Уровень с поправкой на сервер: fit_match (если подбор шёл на сервере, §2.2) — уровень не лучше его: в нём учтено
     доверие к продавцу, которого телефон не видит.
     */
    private static func худший(_ свой: УровеньАвтоподбора, _ товар: Listing,
                               _ профиль: ИтогСовместимостиМоего.Профиль) -> УровеньАвтоподбора {
        guard let сервер = товар.уровеньСервера else { return свой }
        let вид: String = ОтборСервераДляВас.вид(профиль) ?? "std"
        guard let его = сервер.уровень(вид) else { return свой }
        return max(свой, его)
    }

    /**
     Сверка загруженных страниц: только «подходит» и «нужна деталь», без своего (я — номер вошедшего), без ТОП-вставок
     и снятого, без повторов; в сезон — сезонное первым, дальше свежие сверху (fresh_ts, иначе created_ts, иначе порядок
     ответа). Чистая функция — зовётся не на главной нити.
     */
    static func сверить(_ страницы: [String: [Listing]], запросы: [ЗапросПодбораМоего], моё: ЗаписьМоего,
                        я: String, сезон: [ПравилоСезонаДляВас] = []) -> [НаходкаДляВас] {
        let сверка: СверкаДляВас = сверитьВсё(страницы, запросы: запросы, моё: моё, я: я, сезон: сезон)
        return сверка.точные
    }

    /**
     Сверка с запасом (пачка 83: на живых данных в ленте мало размеров — описание обрезано, — и ряды выходили пустыми):
     точные — как сверить; запас «Проверьте» — вещи раздела запроса (со словом раздела, без детского), в которых
     сверить не по чему (размера или параметров нет) или сверка сама говорит «проверьте». Приглашение заполнить «Моё» и
     «не подходит» — не запас. Чистая функция — зовётся не на главной нити.
     */
    static func сверитьВсё(_ страницы: [String: [Listing]], запросы: [ЗапросПодбораМоего], моё: ЗаписьМоего,
                           я: String, сезон: [ПравилоСезонаДляВас] = []) -> СверкаДляВас {
        var видели = Set<String>()
        var кандидаты: [Кандидат] = []
        var запас: [Кандидат] = []
        var номер = 0
        for запрос in запросы {
            guard let товары = страницы[запрос.раздел] else { continue }
            let слова = словаРаздела[запрос.раздел]
            for товар in товары {
                номер += 1
                guard видели.insert(товар.id).inserted, товар.активно, товар.слот != "top" else { continue }
                if !я.isEmpty, товар.продавецID == я { continue }
                if let слова {
                    let название = товар.title.lowercased().replacingOccurrences(of: "ё", with: "е")
                    guard слова.contains(where: { название.contains($0) }) else { continue }
                }
                let свежесть: Int = товар.свежесть > 0 ? товар.свежесть : товар.созданоСекунд
                let балл: Int = СезонДляВас.вес(товар, сезон)
                let оценка: ИтогСовместимостиМоего? = СовместимостьМоего.оценить(товар, моё: моё)
                if let находка = поУровнюСервера(товар, оценка, запрос, моё) {
                    кандидаты.append(Кандидат(находка: находка, свежесть: свежесть, номер: номер, балл: балл))
                    continue
                }
                if let оценка, let свой = оценка.уровень {
                    let уровень: УровеньАвтоподбора = худший(свой, товар, оценка.профиль)
                    if уровень <= .доработка {
                        let группа = ГруппаДляВас(оценка.профиль)
                        let находка = НаходкаДляВас(товар: товар, уровень: уровень,
                                                    причина: причина(оценка, запрос, моё),
                                                    подробно: оценка.подпись,
                                                    деталь: оценка.стандарт?.деталь,
                                                    цвет: группа == .одежда ? кГардеробу(товар, моё.гардероб) : nil,
                                                    группа: группа, раздел: запрос.раздел)
                        кандидаты.append(Кандидат(находка: находка, свежесть: свежесть, номер: номер, балл: балл))
                        continue
                    }
                    guard уровень == .неизвестно || уровень == .проверить, оценка.профиль == запрос.профиль else {
                        continue
                    }
                    /* Своя причина сверки («Отличается на полразмера», «Не хватает данных») — если уровень её; сервер
                       опустил «подходит» до «проверьте» — честное общее «уточните у продавца». */
                    let своя: String = оценка.заголовок.replacingOccurrences(of: " ✓", with: "")
                        .trimmingCharacters(in: .whitespaces)
                    let слово: String? = свой == уровень ? своя : nil
                    let находка = проверка(товар, запрос, моё, причина: слово, подробно: оценка.подпись)
                    запас.append(Кандидат(находка: находка, свежесть: свежесть, номер: номер, балл: балл))
                    continue
                }
                /* Приглашение (в «Моём» нет нужного) — не запас: «размер не указан» тогда неправда. */
                guard оценка == nil, естьЗапас(запрос.профиль),
                      !РазделыСайта.внутри(товар.категория, СовместимостьМоего.разделыДетские) else { continue }
                let находка = проверка(товар, запрос, моё, причина: nil, подробно: "")
                запас.append(Кандидат(находка: находка, свежесть: свежесть, номер: номер, балл: балл))
            }
        }
        let порядок: [Кандидат] = кандидаты.sorted { (а: Кандидат, б: Кандидат) -> Bool in раньше(а, б) }
        let порядокЗапаса: [Кандидат] = запас.sorted { (а: Кандидат, б: Кандидат) -> Bool in раньше(а, б) }
        var итог = СверкаДляВас()
        итог.точные = порядок.prefix(пределНаходок).map { (к: Кандидат) -> НаходкаДляВас in к.находка }
        итог.проверить = порядокЗапаса.prefix(пределНаходок).map { (к: Кандидат) -> НаходкаДляВас in к.находка }
        return итог
    }

    /**
     Пачка 84: страница пришла с отбором сервера (POST с fit_*), телефону сверить не по чему — в ленте нет полей или
     описание обрезано (оценки нет или «не хватает данных»), — а сервер по присланным значениям сказал «подходит» или
     «нужна деталь»: уровень сервера, причина — запроса («Для кровати 160×200», у машины — «Для вашей Camry»), деталь —
     словами телефона. Своя оценка есть — решает она (с потолком сервера, СовместимостьМоего.оценить). Детское — нет.
     */
    private static func поУровнюСервера(_ товар: Listing, _ оценка: ИтогСовместимостиМоего?,
                                        _ запрос: ЗапросПодбораМоего, _ моё: ЗаписьМоего) -> НаходкаДляВас? {
        guard let сервер = товар.уровеньСервера, let его = сервер.уровень(профиля: запрос.профиль),
              его <= .доработка else { return nil }
        if let оценка {
            guard оценка.профиль == запрос.профиль, оценка.уровень == .неизвестно else { return nil }
        }
        guard !РазделыСайта.внутри(товар.категория, СовместимостьМоего.разделыДетские) else { return nil }
        let группа = ГруппаДляВас(запрос.профиль)
        var текст: String = запрос.причина
        if запрос.профиль == .машина, let машина = моё.главнаяМашина { текст = ф("fy_car", имяМашины(машина)) }
        let деталь: String? = его == .доработка ? сервер.показДетали : nil
        let цвет: ЦветСтандарта? = группа == .одежда ? кГардеробу(товар, моё.гардероб) : nil
        return НаходкаДляВас(товар: товар, уровень: его, причина: текст, подробно: "", деталь: деталь, цвет: цвет,
                             группа: группа, раздел: запрос.раздел)
    }

    /// Находка «Проверьте»: своя причина сверки («Отличается на полразмера») или честное «Размер не указан — уточните у
    /// продавца» («Параметры не указаны» у дома и компьютера, кроме постели и штор, где тоже размер).
    private static func проверка(_ товар: Listing, _ запрос: ЗапросПодбораМоего, _ моё: ЗаписьМоего,
                                 причина своя: String?, подробно: String) -> НаходкаДляВас {
        let группа = ГруппаДляВас(запрос.профиль)
        var размерный: Bool = запрос.профиль == .машина || запрос.профиль == .размер
        if ["bedding", "beds", "curtains"].contains(запрос.раздел) { размерный = true }
        var текст: String = НовинкиМоегоText.т(размерный ? "nm_check_size" : "nm_check_params")
        if let своя, !своя.isEmpty { текст = своя }
        let цвет: ЦветСтандарта? = группа == .одежда ? кГардеробу(товар, моё.гардероб) : nil
        return НаходкаДляВас(товар: товар, уровень: .проверить, причина: текст, подробно: подробно, деталь: nil,
                             цвет: цвет, группа: группа, раздел: запрос.раздел)
    }

    /**
     Ряд «Проверьте» вместо пустого: до шести вещей нужного вида (группа — только своя, если задана), в порядке сверки.
     С раздела — поровну на всех: один раздел (машина — только шины, один размер обуви) — все шесть, два — по три, три и
     больше — по два. Уровень «Проверьте» — без галочки и своим цветом плашки.
     */
    static func заменаПроверкой(_ сверка: СверкаДляВас, группа: ГруппаДляВас? = nil,
                                предел: Int = вРядуПроверки) -> [НаходкаДляВас] {
        let свои: [НаходкаДляВас] = сверка.проверить.filter { (н: НаходкаДляВас) -> Bool in
            группа == nil || н.группа == группа
        }
        let разделыСвоих: Set<String> = Set(свои.map { (н: НаходкаДляВас) -> String in н.раздел })
        let разделов: Int = max(1, разделыСвоих.count)
        let доля: Int = (предел + разделов - 1) / разделов
        let наРаздел: Int = max(сРазделаПроверки, доля)
        var сРаздела: [String: Int] = [:]
        var итог: [НаходкаДляВас] = []
        for находка in свои {
            let уже: Int = сРаздела[находка.раздел, default: 0]
            guard уже < наРаздел else { continue }
            сРаздела[находка.раздел] = уже + 1
            итог.append(находка)
            if итог.count >= предел { break }
        }
        return итог
    }

    /// Ряд главной: по свежести, не больше трёх с раздела («по кругу не больше 3 на вещь»), не больше двенадцати.
    static func ряд(_ находки: [НаходкаДляВас]) -> [НаходкаДляВас] {
        var сРаздела: [String: Int] = [:]
        var итог: [НаходкаДляВас] = []
        for находка in находки {
            let уже = сРаздела[находка.раздел, default: 0]
            guard уже < сРазделаВРяду else { continue }
            сРаздела[находка.раздел] = уже + 1
            итог.append(находка)
            if итог.count >= вРяду { break }
        }
        return итог
    }

    /**
     Причина на плашке: у запроса того же профиля — его причина («Для кровати 160×200»), у машины — короче, моделью
     («Для вашей Camry»); стандарт не той семьи, ради которой запрос, или другой профиль — заголовок самой сверки
     без галочки («Подходит к вашим светильникам»).
     */
    private static func причина(_ оценка: ИтогСовместимостиМоего, _ запрос: ЗапросПодбораМоего,
                                _ моё: ЗаписьМоего) -> String {
        if оценка.профиль == запрос.профиль {
            if запрос.профиль == .машина, let машина = моё.главнаяМашина { return ф("fy_car", имяМашины(машина)) }
            guard let стандарт = оценка.стандарт else { return запрос.причина }
            /* «Нужна деталь» — не «как у вас»: заголовок сверки («Подойдёт с переходником»). Причина запроса дома
               называет одно моё значение (E27, 160×200) — верна, только если оно у меня одно, иначе сошлось с другим. */
            if стандарт.уровень == .подходит, семьи(раздела: запрос.раздел).contains(стандарт.семья),
               запрос.профиль != .дом || одноЗначение(стандарт.семья, моё.дом) {
                return запрос.причина
            }
        }
        return оценка.заголовок.replacingOccurrences(of: " ✓", with: "").trimmingCharacters(in: .whitespaces)
    }

    /// Дом: у меня одно значение семьи — один цоколь, один размер кровати; VESA и окна — не проверяем, всегда заголовок.
    private static func одноЗначение(_ семья: СемьяСтандарта, _ дом: ДомМоего) -> Bool {
        switch семья {
        case .цоколь: return дом.цоколи.count == 1
        case .спальноеМесто, .матрас, .бельё: return Set(дом.кровати.compactMap(\.место)).count == 1
        default: return false
        }
    }

    /// Машина коротко: модель («Camry»), иначе своё название, иначе заголовок.
    static func имяМашины(_ машина: МашинаМоего) -> String {
        if let авто = машина.авто, !авто.модель.trimmingCharacters(in: .whitespaces).isEmpty { return авто.модель }
        let своё = машина.имя.trimmingCharacters(in: .whitespacesAndNewlines)
        return своё.isEmpty ? машина.заголовок : своё
    }

    /// Цвет моего гардероба, с которым сочетается вещь объявления (цвет — из названия и описания); нет — nil.
    static func кГардеробу(_ товар: Listing, _ гардероб: ГардеробМоего) -> ЦветСтандарта? {
        let мои = Array(гардероб.частыеЦвета.prefix(4))
        guard !мои.isEmpty else { return nil }
        guard let цвет = РазборСтандартов.цвета(товар.title + " " + (товар.описание ?? "")).first else { return nil }
        if let пара = мои.first(where: { $0 != цвет && $0.сочетается(с: цвет) }) { return пара }
        return мои.contains(цвет) ? цвет : nil
    }
}


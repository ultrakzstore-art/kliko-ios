 рекомендаций — по этим параметрам новинки и прочее»; docs/STANDARDS.md §6.3, docs/SERVER_MY_THINGS.md §3, §10).

 Что делает. По заполненному «Моему» собирает 3–6 запросов к ленте (ПодборМоего.запросы из MyThingsMatch.swift и свои:
 стёкла под телефон, сумки под ноутбук; размеры гардероба там, где в мерках вида нет), по кругу групп — машина,

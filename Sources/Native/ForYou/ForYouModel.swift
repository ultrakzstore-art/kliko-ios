 своё объявление, ТОП-вставка (slot top) и снятое — нет. Свежие сверху, без повторов; в ряду главной не больше трёх на
 раздел и двенадцати всего, остальное — экран «Для вас» целиком. У одежды — цвет гардероба, с которым вещь сочетается
 (ЦветСтандарта.сочетается, частыеЦвета).

 Когда в сеть. Не на запуске: «Моё» читается с диска через 2,5 с, а грузит полку сам вид — когда она подъезжает к экрану
 и ряды главной уже пришли (войти). Ответ разделов живёт 15 минут в памяти (сменился город или человек — заново); новое в
 «Моём» — сверка заново по уже загруженному сразу, в сеть — только за новыми разделами. Не прошёл раздел — повтор не
 раньше чем через минуту. Сверка — не на главной нити.

 Крючок под отбор сервером (POST fit_*) — ForYouServer.swift; по умолчанию выключен: всё сверяется здесь.

 Скрыть подборку — одним касанием: на телефоне остаётся только число разделов, при котором её скрыли; стало больше
 разделов в «Моём» — полка вернётся сама. Пустое «Моё» — полки нет вовсе, и напоминаний нет.
 */
extension Config {
    /// «Для вас» на главной: полка подходящего к «Моему». false — полки нет, «Моё» ради неё не читается, запросов нет.
    static let дляВас = true
}


// MARK: - Модель полки

/**
 Состояние полки на главной и экрана «Для вас». Наблюдают только они (ПолкаДляВас, ЭкранДляВас); «Моё» модель слушает
 подпиской, а не наблюдением вида, — главная не перерисовывается на каждую правку «Моего».
 */
@MainActor
final class ПодборкаДляВас: ObservableObject {
    static let shared = ПодборкаДляВас()

    enum Состояние: Equatable {
        /// «Моё» ещё не прочитано.
        case неизвестно
        /// Сверять не с чем (или рубильник выключен) — полки нет.
        case нечего
        /// Скрыта касанием — полки нет, пока в «Моём» не появится новый раздел.
        case скрыта
        /// Есть что искать, ответа ещё нет.
        case ждём
        /// Загружено, ничего не подошло — полки нет.
        case пусто
        case есть
    }

    @Published private(set) var состояние: Состояние = .неизвестно
    /// Все находки, свежие сверху, — экран целиком.
    @Published private(set) var находки: [НаходкаДляВас] = []
    /// Ряд главной (ПодборДляВас.ряд).
    @Published private(set) var ряд: [НаходкаДляВас] = []
    @Published private(set) var грузим = false
    /// Последняя загрузка не принесла ни одного раздела.
    @Published private(set) var неудача = false
    /// Набор разделов: сменился — виду пора позвать войти() (догрузить новое).
    @Published private(set) var ключ = ""
    /// Сколько новых с прошлого просмотра (НовинкиДляВас) — «Для вас · 3 новых».
    @Published private(set) var новых = 0
    /// Точных нет — на полке ряд «Проверьте» (размер или параметры не указаны).
    @Published private(set) var толькоПроверить = false
    /// Карточки полки уже въезжали волной в этот запуск — дальше сразу (не наблюдается).
    var волнаБыла = false

    private struct Страница {
        let товары: [Listing]
        let когда: Date
        let где: ГдеИскать
        let кто: String
        /// Отпечаток тела POST (только в памяти); «» — GET. Сменилось тело (правка «Моего») — страница устарела.
        let тело: String
    }

    /// В этот запуск значения «Моего» уходили телом POST — применил их сервер, отказал или не ответил: вступление экрана
    /// честное (fv_lead_server), а не «никуда не уходят».
    @Published private(set) var наСервере = false

    private var запросы: [ЗапросПодбораМоего] = []
    private var моё = ЗаписьМоего()
    private var страницы: [String: Страница] = [:]
    private var неудачи: [String: Date] = [:]
    private var загрузка: Task<Void, Never>? = nil
    /// Растёт с каждой загрузкой: закончилась не последняя — ссылку на последнюю не стираем.
    private var номерЗагрузки = 0
    private var сверка: Task<Void, Never>? = nil
    private var поколение = 0
    private var подписка: AnyCancellable? = nil
    private var начато = false

    /// Сколько разделов было, когда подборку скрыли, — только число: ни разделов, ни их хэшей (открытый список разделов
    /// по хэшу угадывается сразу, а UserDefaults попадает в резервную копию). «Удалить всё» в «Моём» стирает и его.
    static let ключСкрытия = "kliko.foryou.hidden_n"

    private init() {
        guard Config.дляВас && Config.моё else {
            состояние = .нечего
            return
        }
        /* Скорость: «Моё» — с диска не в первые кадры запуска, а чуть позже; до того полки нет и места она не занимает. */
        Task { @MainActor [weak self] in
            try? await Task.sleep(for: .seconds(2.5))
            self?.начать()
        }
    }

    private var предел: Int {
        РежимУстройства.сейчас ? ПодборДляВас.пределЗапросовЛёгкий : ПодборДляВас.пределЗапросов
    }

    /// Прочитать «Моё» и слушать его правки (после паузы; повторно — ничего).
    private func начать() {
        guard !начато else { return }
        начато = true
        /* Пачка 83: правила сезона с сервера (только при season_rules) и продление подписки «Новинки» (только при
           fit_subs и включённой подписке) — без ключей ни одного запроса. */
        ПравилаСезонаСервера.обновить()
        ПодпискаНовинокМоего.shared.приОткрытии()
        let хранилище = МоёХранилище.shared
        хранилище.подготовить()
        подписка = хранилище.$запись
            .dropFirst()
            .removeDuplicates()
            .debounce(for: .milliseconds(400), scheduler: RunLoop.main)
            .sink { запись in
                Task { @MainActor in ПодборкаДляВас.shared.принять(запись) }
            }
        принять(хранилище.запись)
    }

    /// Сезон сегодня (встроенные правила или сервера) — для города, выбранного в ленте.
    private var сезон: [ПравилоСезонаДляВас] {
        СезонДляВас.действующие(город: ГдеИскать.сохранённое().город)
    }

    /// Новое «Моё»: запросы заново, сверка по уже загруженному — сразу и без сети.
    private func принять(_ запись: ЗаписьМоего) {
        let дляСверки = ПодборДляВас.моёДляСверки(запись)
        let новые = ПодборДляВас.запросы(дляСверки, предел: предел, сезон: сезон)
        моё = дляСверки
        /* Подписка «Новинки» (только при fit_subs и если её включили): «Моё» сменилось — sub_put через паузу. */
        ПодпискаНовинокМоего.shared.моёСменилось()
        запросы = новые
        обновитьКлюч()
        guard !новые.isEmpty else {
            /* «Удалить всё» или пустое «Моё»: ни полки, ни загруженного. */
            загрузка?.cancel()
            загрузка = nil
            сверка?.cancel()
            поколение += 1
            страницы = [:]
            неудачи = [:]
            if грузим { грузим = false }
            поставить([])
            return
        }
        пересверить()
    }

    // MARK: Вход и загрузка

    /**
     Полка подъехала к экрану (или сменился набор разделов): ряды главной уже пришли — загрузить разделы, которых нет,
     устаревших (15 минут), другого города или другого человека. Всё свежее — ничего; уже грузим — ничего.
     */
    func войти(готово: Bool) {
        guard готово, загрузка == nil, !запросы.isEmpty, состояние != .скрыта else { return }
        /* Пачка 84: признаки подбора на сервере (rules.fit_filters, файл схемы) — до первой загрузки: от них зависят тела. */
        guard ПризнакиПодбораСервера.действующие != nil else {
            номерЗагрузки += 1
            let номер = номерЗагрузки
            загрузка = Task<Void, Never> { [weak self] in
                _ = await ПризнакиПодбораСервера.прочитать()
                guard let self else { return }
                if self.номерЗагрузки == номер { self.загрузка = nil }
                guard !Task.isCancelled else { return }
                self.обновитьКлюч()
                self.войти(готово: true)
            }
            return
        }
        let сейчас = Date()
        let где = ГдеИскать.сохранённое()
        let кто = СессияПриложения.shared.id
        let тела: [String: [String: String]] = желаемыеТела()
        let нужно = запросы.map(\.раздел).filter { раздел in
            if let была = неудачи[раздел], сейчас.timeIntervalSince(была) < 60 { return false }
            guard let страница = страницы[раздел] else { return true }
            return сейчас.timeIntervalSince(страница.когда) > ПодборДляВас.срок || страница.где != где
                || страница.кто != кто || страница.тело != ОтборСервераДляВас.отпечаток(тела[раздел])
        }
        guard !нужно.isEmpty else { return }
        номерЗагрузки += 1
        let номер = номерЗагрузки
        загрузка = Task { [weak self] in
            await self?.загрузить(нужно, где: где, кто: кто)
            /* Пока грузили, «Моё» опустело и началась другая загрузка — её ссылку не трогаем. */
            if self?.номерЗагрузки == номер { self?.загрузка = nil }
        }
    }

    /// «Потянуть вниз» на экране «Для вас»: все разделы заново (не чаще раза в полминуты).
    func обновить() async {
        guard загрузка == nil, !запросы.isEmpty else { return }
        let сейчас = Date()
        let разделы = запросы.map(\.раздел)
        let свежие = разделы.allSatisfy { раздел in
            страницы[раздел].map { сейчас.timeIntervalSince($0.когда) < 30 } ?? false
        }
        guard !свежие else { return }
        let где = ГдеИскать.сохранённое()
        let кто = СессияПриложения.shared.id
        номерЗагрузки += 1
        let номер = номерЗагрузки
        let задача = Task<Void, Never> { [weak self] in
            guard let self else { return }
            await self.загрузить(разделы, где: где, кто: кто)
        }
        загрузка = задача
        await задача.value
        if номерЗагрузки == номер { загрузка = nil }
    }

    private func загрузить(_ разделы: [String], где: ГдеИскать, кто: String) async {
        грузим = true
        defer { грузим = false }
        let наСтраницу = РежимУстройства.сейчас ? ПодборДляВас.наСтраницуЛёгкий : ПодборДляВас.наСтраницу
        _ = await ПризнакиПодбораСервера.прочитать()
        let все: [String: [String: String]] = желаемыеТела()
        let тела: [String: [String: String]] = все.filter { (пара: (key: String, value: [String: String])) -> Bool in
            разделы.contains(пара.key)
        }
        /* Приватность: полка грузится сама, без нажатия, а набор разделов собран из «Моего» — поэтому без куков, и GET, и
           POST (пачка 83–84, docs/SERVER_NEW_FOR_MINE.md §2.1): сервер не связывает набор и значения с человеком (город —
           в адресе, своё объявление отсекается на телефоне). Тело — только значения стандартов, в журнал не пишется.
           Приватность вступления: тело уходит — отметка до запроса, что бы ни ответил сервер (отказ, нет fit_applied). */
        if !тела.isEmpty {
            ПризнакиПодбораСервера.отметитьОтправку()
            if !наСервере { наСервере = true }
        }
        let ответы: [String: ОтветРазделаДляВас] = await Self.запросить(разделы, где: где, наСтраницу: наСтраницу,
                                                                         тела: тела)
        guard !Task.isCancelled else { return }
        let сейчас = Date()
        var былОтказ = false
        for раздел in разделы {
            if let ответ = ответы[раздел], let товары = ответ.товары {
                страницы[раздел] = Страница(товары: товары, когда: сейчас, где: где, кто: кто, тело: ответ.тело)
                неудачи[раздел] = nil
            } else {
                неудачи[раздел] = сейчас
            }
            if ответы[раздел]?.отказ == true { былОтказ = true }
        }
        if былОтказ {
            ПризнакиПодбораСервера.отказ()
            обновитьКлюч()
        }
        неудача = !ответы.values.contains { (о: ОтветРазделаДляВас) -> Bool in о.товары != nil }
        пересверить()
    }

    /// Тела POST разделов по нынешнему «Моему» и признакам сервера; признаков ещё нет или был отказ — пусто (GET).
    private func желаемыеТела() -> [String: [String: String]] {
        guard let объявлено = ПризнакиПодбораСервера.действующие, !объявлено.isEmpty else { return [:] }
        return ОтборСервераДляВас.тела(запросы, моё: моё, объявлено: объявлено)
    }

    /// Ключ входа: набор разделов и отпечаток тел (хэш, только в памяти) — сменилось одно из них, вид зовёт войти().
    private func обновитьКлюч() {
        let тела: [String: [String: String]] = желаемыеТела()
        var отпечатки: [String] = []
        for раздел in тела.keys.sorted() {
            отпечатки.append(раздел + "=" + ОтборСервераДляВас.отпечаток(тела[раздел]))
        }
        var новыйКлюч: String = ПодборДляВас.отпечаток(запросы)
        if !отпечатки.isEmpty {
            var хэш = Hasher()
            хэш.combine(отпечатки)
            новыйКлюч += "#" + String(хэш.finalize())
        }
        if новыйКлюч != ключ { ключ = новыйКлюч }
    }

    /**
     Первая страница каждого раздела — по запросу на раздел, параллельно; без куков. Есть тело — POST с ним; не прошёл
     — тот же раздел обычным GET (§2.3: «прежний путь»); прошёл, но без fit_applied (сервер тело не применил) — это та
     же лента, что у GET: берётся как есть, без повтора.
     */
    nonisolated private static func запросить(_ разделы: [String], где: ГдеИскать,
                                              наСтраницу: Int, тела: [String: [String: String]]) async
        -> [String: ОтветРазделаДляВас] {
        await withTaskGroup(of: ОтветРазделаДляВас.self, returning: [String: ОтветРазделаДляВас].self) { группа in
            for раздел in разделы {
                let тело = тела[раздел]
                группа.addTask {
                    var з = ListingsAPI.Запрос()
                    з.per = наСтраницу
                    з.cat = раздел
                    з.где = где
                    з.фильтры.сортировка = .новыеПодряд
                    var страница: ListingsPage? = nil
                    var отпечаток = ""
                    var отказ = false
                    if let тело {
                        страница = try? await ОтборСервераДляВас.загрузить(з, тело: тело)
                        if let пришла = страница, пришла.применёноСервером != nil {
                            отпечаток = ОтборСервераДляВас.отпечаток(тело)
                        } else {
                            отказ = true
                        }
                    }
                    if страница == nil {
                        страница = try? await ListingsAPI.загрузить(з, куки: [:]).страница
                    }
                    return ОтветРазделаДляВас(раздел: раздел, товары: страница?.items, тело: отпечаток, отказ: отказ)
                }
            }
            var итог: [String: ОтветРазделаДляВас] = [:]
            while let ответ = await группа.next() {
                итог[ответ.раздел] = ответ
            }
            return итог
        }
    }

    // MARK: Сверка и показ

    /// Сверка всех загруженных страниц не на главной нити; пришла новая правка раньше — прежний итог не ставится.
    private func пересверить() {
        поколение += 1
        let номер = поколение
        сверка?.cancel()
        guard !страницы.isEmpty else {
            поставить([])
            return
        }
        let вход = ВходСверкиДляВас(страницы: страницы.mapValues(\.товары), запросы: запросы, моё: моё,
                                    я: СессияПриложения.shared.id, сезон: сезон)
        сверка = Task { [weak self] in
            let выход = await Task.detached(priority: .userInitiated) { () -> ВыходСверкиДляВас in
                ВыходСверкиДляВас(сверка: ПодборДляВас.сверитьВсё(вход.страницы, запросы: вход.запросы, моё: вход.моё,
                                                                  я: вход.я, сезон: вход.сезон))
            }.value
            guard let self, !Task.isCancelled, номер == self.поколение else { return }
            self.поставить(выход.сверка)
        }
    }

    /// Итог сверки: точные — если есть; нет — ряд «Проверьте» (до шести вещей нужного вида), полка не пустая и не врёт.
    private func поставить(_ итог: ПодборДляВас.СверкаДляВас) {
        /* Точка отсчёта нового раздела — по всем находкам сверки, и «Проверьте» тоже: станут они потом точными (размер
           в «Моём», поля сервера) — это не «новые». */
        let все: [НаходкаДляВас] = итог.точные + итог.проверить
        let загружены: Set<String> = Set(страницы.keys)
        _ = НовинкиДляВас.shared.учесть(все, разделы: загружены)
        if итог.точные.isEmpty {
            поставить(ПодборДляВас.заменаПроверкой(итог), проверка: true)
        } else {
            поставить(итог.точные, проверка: false)
        }
    }

    /// Показ: новинки с прошлого просмотра (НовинкиДляВас) — первыми и числом в заголовке.
    private func поставить(_ новые: [НаходкаДляВас], проверка: Bool = false) {
        let загружены: Set<String> = Set(страницы.keys)
        let порядок: [НаходкаДляВас] = НовинкиДляВас.shared.учесть(новые, разделы: загружены)
        показать(порядок)
        if толькоПроверить != проверка { толькоПроверить = проверка }
        обновитьСостояние()
    }

    private func показать(_ порядок: [НаходкаДляВас]) {
        let новыйРяд = ПодборДляВас.ряд(порядок)
        if порядок != находки { находки = порядок }
        if новыйРяд != ряд {
            ряд = новыйРяд
            /* Скорость: вид карточек ряда — заранее и не на главной очереди. */
            FeedModel.видыЗаранее(новыйРяд.map(\.товар))
        }
        пересчитатьНовые()
    }

    // MARK: Новинки, экран и push

    /// Сколько новых — заново (ряд «Подходит вам» в «Моём» отметил свои карточки показанными).
    func пересчитатьНовые() {
        let число: Int = НовинкиДляВас.shared.сколькоНовых(находки)
        if число != новых { новых = число }
    }

    /// Экран «Для вас» открыли (полка, «Все ›», push): начать, если ещё нет, загрузить недостающее, новое — показано.
    func открытьЭкран() {
        guard Config.дляВас && Config.моё else { return }
        начать()
        if РубильникиНовинок.подписка { ПодпискаНовинокМоего.shared.подготовить() }
        войти(готово: true)
        НовинкиДляВас.shared.экран(открыт: true, находки: находки)
        пересчитатьНовые()
    }

    /// Экран закрыли: чип «Новые» снят, порядок — как у полки.
    func закрытьЭкран() {
        НовинкиДляВас.shared.экран(открыт: false, находки: находки)
        показать(НовинкиДляВас.shared.упорядочить(находки))
    }

    /// Push fit_new: его номера — первыми среди загруженного (отдельно не догружаются, §3.5).
    func изПуша(_ номера: [String]) {
        НовинкиДляВас.shared.изПуша(номера)
        показать(НовинкиДляВас.shared.упорядочить(находки))
    }

    private func обновитьСостояние() {
        let новое: Состояние
        if запросы.isEmpty {
            новое = .нечего
        } else if скрыта {
            новое = .скрыта
        } else if !находки.isEmpty {
            новое = .есть
        } else if запросы.allSatisfy({ страницы[$0.раздел] != nil }) {
            новое = .пусто
        } else {
            новое = .ждём
        }
        guard новое != состояние else { return }
        /* Полка появляется плавно; прочие смены — без своей анимации (у «Скрыть» она своя, снаружи). */
        if новое == .есть {
            withAnimation(ДвижениеСайта.появление) { состояние = новое }
        } else {
            состояние = новое
        }
    }

    // MARK: Скрыть

    /// Скрыта, пока разделов не больше, чем было, когда её скрыли.
    private var скрыта: Bool {
        let было = UserDefaults.standard.integer(forKey: Self.ключСкрытия)
        return было > 0 && !запросы.isEmpty && Set(запросы.map(\.раздел)).count <= было
    }

    /// «Скрыть» — одним касанием; вернётся сама, когда в «Моём» разделов станет больше.
    func скрыть() {
        UserDefaults.standard.set(Set(запросы.map(\.раздел)).count, forKey: Self.ключСкрытия)
        обновитьСостояние()
    }
}

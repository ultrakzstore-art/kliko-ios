/// Группа полки — чип экрана «Для вас»; профиль сверки к ней сводится.
enum ГруппаДляВас: String, CaseIterable, Identifiable, Sendable {
    case машина = "car"
    case устройства = "devices"
    case дом = "home"
    case компьютер = "pc"
    case одежда = "wear"

    var id: String { rawValue }

    init(_ профиль: ИтогСовместимостиМоего.Профиль) {
        switch профиль {
        case .машина: self = .машина
        case .телефон, .ноутбук: self = .устройства
        case .дом: self = .дом
        case .компьютер: self = .компьютер
        case .размер: self = .одежда
        }
    }

    var название: String { ДляВасText.т("fv_g_" + rawValue) }

    var значок: String {
        switch self {
        case .машина: return "car.fill"
        case .устройства: return "iphone"
        case .дом: return "house.fill"
        case .компьютер: return "desktopcomputer"
        case .одежда: return "tshirt.fill"
        }
    }
}

/// Объявление полки: сверка на телефоне и причина для плашки.
struct НаходкаДляВас: Identifiable, Equatable {
    let товар: Listing
    /// Только .подходит или .доработка.
    let уровень: УровеньАвтоподбора
    /// Плашка под карточкой: «Для вашей Camry», «Ваш размер M», «Для кровати 160×200».
    let причина: String
    /// С чем сверили и почему — строка экрана целиком («160×200 — ваша 160×200 · Спальня»).
    let подробно: String
    /// Нужная деталь у «доработки» («переходник E14 → E27»).
    let деталь: String?
    /// Цвет моего гардероба, с которым вещь сочетается (только одежда).
    let цвет: ЦветСтандарта?
    let группа: ГруппаДляВас
    /// Раздел запроса — в ряду главной не больше трёх с одного.
    let раздел: String

    var id: String { товар.id }
}

// MARK: - Подбор: чистые функции

enum ПодборДляВас {
    static let пределЗапросов = 6
    /// Лёгкий режим (РежимУстройства): меньше запросов и карточек.
    static let пределЗапросовЛёгкий = 3
    static let наСтраницу = 48
    static let наСтраницуЛёгкий = 24
    static let вРяду = 12
    static let сРазделаВРяду = 3
    static let пределНаходок = 200
    /// Сколько живёт ответ раздела.
    static let срок: TimeInterval = 15 * 60

    /// Ряд главной для полки: ключ — только для краски точки в заголовке (РядГлавной).
    static var разделГлавной: РазделГлавной { РазделГлавной(ключ: "for-you", краска: 0x16A34A) }

    private static func ф(_ ключ: String, _ аргумент: String) -> String {
        String(format: СтандартыText.т(ключ), аргумент)
    }

    /**
     «Моё» для сверки: где в мерках нет размера вида, а в гардеробе есть вещи этого вида с размером, — самый частый размер
     гардероба (по одному на вид). Только в памяти: запись «Моего» не меняется.
     */
    static func моёДляСверки(_ моё: ЗаписьМоего) -> ЗаписьМоего {
        let свои = Set(моё.тело.размеры.map(\.вид))
        var счёт: [String: Int] = [:]
        var образцы: [String: РазмерМоего] = [:]
        for вещь in моё.гардероб.вещи {
            guard let размер = вещь.размер, !свои.contains(размер.вид) else { continue }
            let ключ = размер.вид.rawValue + "|" + размер.система + "|" + размер.значение + "|" + размер.значение2
            счёт[ключ, default: 0] += 1
            if образцы[ключ] == nil { образцы[ключ] = размер }
        }
        guard !счёт.isEmpty else { return моё }
        var итог = моё
        var взяты = Set<ВидРазмераМоего>()
        let порядок = счёт.sorted { $0.value == $1.value ? $0.key < $1.key : $0.value > $1.value }
        for пара in порядок {
            guard let размер = образцы[пара.key], !взяты.contains(размер.вид) else { continue }
            взяты.insert(размер.вид)
            итог.тело.размеры.append(размер)
        }
        return итог
    }

    /**
     Запросы полки: ПодборМоего и свои (стёкла и плёнки под телефон, сумки и рюкзаки под ноутбук), по одному на раздел, по
     кругу групп — сначала первый запрос каждой группы, потом второй; не больше предела.
     */
    static func запросы(_ моё: ЗаписьМоего, предел: Int) -> [ЗапросПодбораМоего] {
        guard Config.моё, предел > 0 else { return [] }
        var все = ПодборМоего.запросы(моё, предел: 12)
        if let телефон = моё.телефон, !телефон.модель.trimmingCharacters(in: .whitespaces).isEmpty {
            все.append(ЗапросПодбораМоего(профиль: .телефон, раздел: "phone-accessories", запрос: "",
                                          причина: ф("fy_phone", телефон.модель)))
        }
        if let диагональ = СовместимостьМоего.диагональНоутбука(моё) {
            let причина = ДляВасText.ф("fv_laptop", ЧислоМоего.дюймы(диагональ))
            for раздел in ["backpacks", "handbags"] {
                все.append(ЗапросПодбораМоего(профиль: .ноутбук, раздел: раздел, запрос: "", причина: причина))
            }
        }
        var очередь: [ГруппаДляВас: [ЗапросПодбораМоего]] = [:]
        var порядок: [ГруппаДляВас] = []
        var разделы = Set<String>()
        for запрос in все where разделы.insert(запрос.раздел).inserted {
            let группа = ГруппаДляВас(запрос.профиль)
            if очередь[группа] == nil { порядок.append(группа) }
            очередь[группа, default: []].append(запрос)
        }
        var итог: [ЗапросПодбораМоего] = []
        var шаг = 0
        while итог.count < предел {
            var взяли = false
            for группа in порядок where итог.count < предел {
                guard let список = очередь[группа], шаг < список.count else { continue }
                итог.append(список[шаг])
                взяли = true
            }
            guard взяли else { break }
            шаг += 1
        }
        return итог
    }

    /// Ключ набора разделов: сменился — есть что догрузить.
    static func отпечаток(_ запросы: [ЗапросПодбораМоего]) -> String {
        Set(запросы.map(\.раздел)).sorted().joined(separator: ",")
    }

    // MARK: Сверка

    /// Семьи стандарта, ради которых запрос в разделе (причина запроса годится только им).
    private static func семьи(раздела раздел: String) -> Set<СемьяСтандарта> {
        switch раздел {
        case "bedding": return [.бельё, .спальноеМесто, .матрас]
        case "beds": return [.спальноеМесто, .матрас]
        case "lighting": return [.цоколь]
        case "tv-audio": return [.vesa]
        case "curtains": return [.шторы]
        case "ram": return [.память]
        case "ssd-hdd": return [.накопитель]
        case "gpu": return [.видеокарта]
        default: return []
        }
    }

    /// Раздел шире запроса: в «ТВ и аудио» ищем кронштейн, а не телевизор того же VESA; в «Кроватях» — матрас, а не
    /// каркас; в «Свете» — лампы, а не люстру, — нужно слово в названии.
    private static let словаРаздела: [String: [String]] = [
        "tv-audio": ["кронштейн", "креплен", "крепеж", "mount", "bracket", "ілгіш"],
        "beds": ["матрас", "матрац", "топпер", "наматрасник", "mattress", "topper", "төсеніш"],
        "lighting": ["ламп", "bulb", "шам "]
    ]

    private struct Кандидат {
        let находка: НаходкаДляВас
        let свежесть: Int
        let номер: Int
    }

    /**
     Сверка загруженных страниц: только «подходит» и «нужна деталь», без своего (я — номер вошедшего), без ТОП-вставок
     и снятого, без повторов; свежие сверху (fresh_ts, иначе created_ts, иначе порядок ответа). Чистая функция — зовётся
     не на главной нити.
     */
    static func сверить(_ страницы: [String: [Listing]], запросы: [ЗапросПодбораМоего], моё: ЗаписьМоего,
                        я: String) -> [НаходкаДляВас] {
        var видели = Set<String>()
        var кандидаты: [Кандидат] = []
        var номер = 0
        for запрос in запросы {
            guard let товары = страницы[запрос.раздел] else { continue }
            let слова = словаРаздела[запрос.раздел]
            for товар in товары {
                номер += 1
                guard видели.insert(товар.id).inserted, товар.активно, товар.слот != "top" else { continue }
                if !я.isEmpty, товар.продавецID == я { continue }
                if let слова {
                    let название = товар.title.lowercased().replacingOccurrences(of: "ё", with: "е")
                    guard слова.contains(where: { название.contains($0) }) else { continue }
                }
                guard let оценка = СовместимостьМоего.оценить(товар, моё: моё),
                      let уровень = оценка.уровень, уровень <= .доработка else { continue }
                let группа = ГруппаДляВас(оценка.профиль)
                let находка = НаходкаДляВас(товар: товар, уровень: уровень,
                                            причина: причина(оценка, запрос, моё),
                                            подробно: оценка.подпись,
                                            деталь: оценка.стандарт?.деталь,
                                            цвет: группа == .одежда ? кГардеробу(товар, моё.гардероб) : nil,
                                            группа: группа, раздел: запрос.раздел)
                let свежесть = товар.свежесть > 0 ? товар.свежесть : товар.созданоСекунд
                кандидаты.append(Кандидат(находка: находка, свежесть: свежесть, номер: номер))
            }
        }
        let порядок = кандидаты.sorted { $0.свежесть != $1.свежесть ? $0.свежесть > $1.свежесть : $0.номер < $1.номер }
        return Array(порядок.prefix(пределНаходок).map(\.находка))
    }

    /// Ряд главной: по свежести, не больше трёх с раздела («по кругу не больше 3 на вещь»), не больше двенадцати.
    static func ряд(_ находки: [НаходкаДляВас]) -> [НаходкаДляВас] {
        var сРаздела: [String: Int] = [:]
        var итог: [НаходкаДляВас] = []
        for находка in находки {
            let уже = сРаздела[находка.раздел, default: 0]
            guard уже < сРазделаВРяду else { continue }
            сРаздела[находка.раздел] = уже + 1
            итог.append(находка)
            if итог.count >= вРяду { break }
        }
        return итог
    }

    /**
     Причина на плашке: у запроса того же профиля — его причина («Для кровати 160×200»), у машины — короче, моделью
     («Для вашей Camry»); стандарт не той семьи, ради которой запрос, или другой профиль — заголовок самой сверки
     без галочки («Подходит к вашим светильникам»).
     */
    private static func причина(_ оценка: ИтогСовместимостиМоего, _ запрос: ЗапросПодбораМоего,
                                _ моё: ЗаписьМоего) -> String {
        if оценка.профиль == запрос.профиль {
            if запрос.профиль == .машина, let машина = моё.главнаяМашина { return ф("fy_car", имяМашины(машина)) }
            guard let стандарт = оценка.стандарт else { return запрос.причина }
            /* «Нужна деталь» — не «как у вас»: заголовок сверки («Подойдёт с переходником»). Причина запроса дома
               называет одно моё значение (E27, 160×200) — верна, только если оно у меня одно, иначе сошлось с другим. */
            if стандарт.уровень == .подходит, семьи(раздела: запрос.раздел).contains(стандарт.семья),
               запрос.профиль != .дом || одноЗначение(стандарт.семья, моё.дом) {
                return запрос.причина
            }
        }
        return оценка.заголовок.replacingOccurrences(of: " ✓", with: "").trimmingCharacters(in: .whitespaces)
    }

    /// Дом: у меня одно значение семьи — один цоколь, один размер кровати; VESA и окна — не проверяем, всегда заголовок.
    private static func одноЗначение(_ семья: СемьяСтандарта, _ дом: ДомМоего) -> Bool {
        switch семья {
        case .цоколь: return дом.цоколи.count == 1
        case .спальноеМесто, .матрас, .бельё: return Set(дом.кровати.compactMap(\.место)).count == 1
        default: return false
        }
    }

    /// Машина коротко: модель («Camry»), иначе своё название, иначе заголовок.
    static func имяМашины(_ машина: МашинаМоего) -> String {
        if let авто = машина.авто, !авто.модель.trimmingCharacters(in: .whitespaces).isEmpty { return авто.модель }
        let своё = машина.имя.trimmingCharacters(in: .whitespacesAndNewlines)
        return своё.isEmpty ? машина.заголовок : своё
    }

    /// Цвет моего гардероба, с которым сочетается вещь объявления (цвет — из названия и описания); нет — nil.
    static func кГардеробу(_ товар: Listing, _ гардероб: ГардеробМоего) -> ЦветСтандарта? {
        let мои = Array(гардероб.частыеЦвета.prefix(4))
        guard !мои.isEmpty else { return nil }
        guard let цвет = РазборСтандартов.цвета(товар.title + " " + (товар.описание ?? "")).first else { return nil }
        if let пара = мои.first(where: { $0 != цвет && $0.сочетается(с: цвет) }) { return пара }
        return мои.contains(цвет) ? цвет : nil
    }
}


/**
 ВИД КАРТОЧКИ ЛЕНТЫ — ПОСЧИТАН ОДИН РАЗ (скорость прокрутки с тысячами объявлений).

 Карточка ленты (ListingCard) раньше на каждой отрисовке заново разбирала объявление: факты вертикали (регулярные
 выражения, справочники, значки по SVG), знак доверия, цену с NumberFormatter, заголовок жилья, дату «вчера» через
 Calendar, голос VoiceOver. Отрисовок много: сдвиг геоточки или оценки пути перерисовывает все видимые карточки.
 Здесь это считается один раз на объявление и берётся из памяти. Запись верна, пока то же самое объявление (сравнение
 целиком — обновление ленты с новой ценой пересчитает) и те же условия: язык, проверки по базам, режим сделок, пауза
 гаранта и день (дата «сегодня» / «вчера»). Расстояние и время в пути не здесь — они живые.
 */
struct ВидКарточки {
    let вертикаль: ВертикальВитрины
    /// Техника и услуги — фото целиком, поля — размытая копия.
    let фотоЦеликом: Bool
    /// Значок заглушки без фото.
    let значокЗаглушки: String
    /// Обложка абсолютным адресом (разбор URL — не на каждой отрисовке).
    let обложка: URL?
    let меткаСостояния: Listing.МеткаСостояния?
    let заголовокЖилья: String?
    let адресЖилья: String
    let ценаЗаМетр: String?
    let даром: Bool
    let ценаОт: Bool
    /// Цена обычной ленты и ленты «Аренда».
    let ценаОбычная: ЦенаКарточкиСайта?
    let ценаВАренде: ЦенаКарточкиСайта?
    let фактыСетки: [ФактВитрины]
    let фактыСписка: [ФактВитрины]
    let знак: ЗнакДоверияКарточки?
    let краска: Color?
    /// Город, без него — когда добавлено.
    let местоЛенты: String
    let втораяСтрокаСписка: String?
    let голосСетки: String
    let голосСписка: String

    init(_ т: Listing) {
        let заголовок = т.заголовокЖилья
        let адрес = т.адресЖилья
        let заМетр = т.ценаЗаМетр
        let даром = т.даром
        let знак = т.знакДоверияЛенты
        let фактыСетки = т.фактыВитрины(список: false)
        let фактыСписка = т.фактыВитрины(список: true)

        вертикаль = т.вертикаль
        фотоЦеликом = т.услуга || т.вертикаль.фотоЦеликом
        обложка = т.обложка
        значокЗаглушки = т.категория == nil ? "photo" : РазделыСайта.значок(т.категория)
        меткаСостояния = т.меткаСостояния
        заголовокЖилья = заголовок
        адресЖилья = адрес
        ценаЗаМетр = заМетр
        self.даром = даром
        ценаОт = т.ценаОт
        ценаОбычная = ЦенаКарточкиСайта.для(т, режимАренды: false)
        ценаВАренде = т.forRent ? ЦенаКарточкиСайта.для(т, режимАренды: true) : ценаОбычная
        self.фактыСетки = фактыСетки
        self.фактыСписка = фактыСписка
        self.знак = знак
        краска = т.краскаМагазинаЛенты
        местоЛенты = т.местоЛенты

        /* Под названием широкой карточки: у жилья — район, и дата подачи; нечего — nil. */
        var строка: [String] = []
        if заголовок != nil { строка.append(адрес) }
        if let создано = т.создано, !т.city.isEmpty {
            let дата = Listing.датаСайта(создано, коротко: true)
            if !дата.isEmpty { строка.append(дата) }
        }
        втораяСтрокаСписка = строка.isEmpty ? nil : строка.joined(separator: " · ")

        /* Голос: товар, заголовок жилья, цена за м², «Даром», факты и знак доверия. */
        var основа = [т.голос]
        if let заголовок { основа.append(заголовок.replacingOccurrences(of: " · ", with: ", ")) }
        if let заМетр { основа.append(заМетр) }
        if даром { основа.append(ВитринаВертикалейТекст.т("free")) }
        func голос(_ факты: [ФактВитрины]) -> String {
            var части = основа
            let тексты = факты.map(\.текст)
            if !тексты.isEmpty { части.append(тексты.joined(separator: ", ")) }
            if let знак { части.append(знак.текст) }
            return части.joined(separator: ", ")
        }
        голосСетки = голос(фактыСетки)
        голосСписка = голос(фактыСписка)
    }

    /// Цена карточки: в ленте «Аренда» — цена аренды.
    func цена(режимАренды: Bool) -> ЦенаКарточкиСайта? {
        режимАренды ? ценаВАренде : ценаОбычная
    }

    /// Место в подвале: до 5 км от человека — расстояние и «рядом» (как Listing.местоСРасстоянием), иначе город или дата.
    func место(км: Double?) -> (текст: String, рядом: Bool) {
        if let км, км >= 0, км <= 5 {
            return (ГеоЛенты.подпись(км: км), true)
        }
        return (местоЛенты, false)
    }
}

/// Память видов карточек по номеру объявления: не больше предела, переполнилась — очищается целиком.
final class КэшВидаКарточек: @unchecked Sendable {
    static let shared = КэшВидаКарточек()

    /// От чего вид зависит, кроме самого объявления.
    private struct Условия: Equatable {
        let язык: String
        let проверки: Bool
        let eds: Bool
        let пауза: Bool
        let день: Int

        static var сейчас: Условия {
            let сдвиг = Double(TimeZone.current.secondsFromGMT())
            return Условия(язык: DesignText.язык, проверки: Config.проверкиПоБазам, eds: РежимСделокСайта.edsСейчас,
                           пауза: ПаузаГаранта.наПаузеСейчас,
                           день: Int(((Date().timeIntervalSince1970 + сдвиг) / 86_400).rounded(.down)))
        }
    }

    private struct Запись {
        let товар: Listing
        let условия: Условия
        let вид: ВидКарточки
    }

    private var записи: [String: Запись] = [:]
    private let замок = NSLock()
    private let предел = 1_000

    private init() {}

    /// Вид карточки: из памяти, если объявление и условия те же, иначе — посчитать и запомнить.
    func вид(_ т: Listing) -> ВидКарточки {
        let условия = Условия.сейчас
        замок.lock()
        if let запись = записи[т.id], запись.условия == условия, запись.товар == т {
            замок.unlock()
            return запись.вид
        }
        замок.unlock()
        let вид = ВидКарточки(т)
        замок.lock()
        if записи.count >= предел { записи.removeAll(keepingCapacity: true) }
        записи[т.id] = Запись(товар: т, условия: условия, вид: вид)
        замок.unlock()
        return вид
    }
}

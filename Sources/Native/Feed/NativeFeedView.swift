     Показать или убрать «Вы смотрели» над выдачей (правило mkRenderViewed: от двух карточек). Появление и уход полосы
     сдвигают всё под ней, поэтому решение ждёт верха ленты: вернулись с объявления посреди ленты — полоса появится,

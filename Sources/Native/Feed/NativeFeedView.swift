    private func следитьЗаЗагрузкой() async {
        guard модель.грузим else {
            if плашкаЗагрузки || плашкаМедленно {
                withAnimation(.easeOut(duration: 0.25)) {
                    плашкаЗагрузки = false
                    плашкаМедленно = false
                }
            }
            return
        }
        try? await Task.sleep(nanoseconds: 600_000_000)
        guard !Task.isCancelled, модель.грузим else { return }
        withAnimation(.easeOut(duration: 0.25)) { плашкаЗагрузки = true }
        try? await Task.sleep(nanoseconds: 2_400_000_000)
        guard !Task.isCancelled, модель.грузим else { return }
        плашкаМедленно = true
    }


                   когда история просмотров». Верх выдачи — обычный VStack, а не LazyVStack: у ленивого стека всё, что
                   над экраном, — прикидка высоты, и вставка «Вы смотрели» над уже прокрученной сеткой (вернулись с
                   объявления) сбивала прикидку — верх ленты оставался под шапкой, пока ленту не перезагрузят. Ленива
                   здесь только сама сетка (LazyVGrid) и ряды главной — им это не вредит: над ними ничего не прикидывается. */
                VStack(alignment: .leading, spacing: 12) {
                    Color.clear
                        .frame(height: 0)
                        .id(Self.верхЛенты)
                        .background {
                            GeometryReader { г in
                                Color.clear.preference(key: ВерхЛентыКлюч.self,
                                                       value: г.frame(in: NamedCoordinateSpace.named(Self.прокруткаЛенты)).minY)
                            }
                        }
                    if показатьИсторию { историяПоиска }
                    /* Этап 26: на главной — плитки разделов и ряды «Рекомендуем». Этап 49: как у сайта, под главной
                       ленты нет (html.mk-home прячет #mk-results, .mk-rbar, #mk-viewed) — вся лента открывается кнопкой
                       «Показать все объявления», поиском или разделом. */
                    if наГлавной {
                        LazyVStack(alignment: .leading, spacing: 12) {
                            главнаяСайта
                        }
                    } else {
                        выдачаСайта
                    }
                }
                /* Внизу подвал — он сам доходит до низа, как .ulxsf у сайта; иначе поле под последней карточкой. */
                .padding(.bottom, подвалВнизу ? 0 : 24)
                .панельСайтаПоПрокрутке()   // нижняя панель уезжает при прокрутке вниз (SiteMotion)
            }
            .coordinateSpace(NamedCoordinateSpace.named(Self.прокруткаЛенты))
            /* Где верх ленты: у самого верха — можно менять то, что над сеткой («Вы смотрели»), не сдвигая карточек под
               пальцем. Только запись в состояние — решает onChange ниже. */
            .onPreferenceChange(ВерхЛентыКлюч.self) { значение in уВерхаЛенты = значение > -40 }
            .onChange(of: уВерхаЛенты) { _, у in
                if у { решитьПолосуНедавних() }
            }
            .onChange(of: недавние.товары.map(\.id)) { _, _ in решитьПолосуНедавних() }
            .onChange(of: модель.items.count) { _, _ in решитьПолосуНедавних() }
            .onAppear { решитьПолосуНедавних() }
            /* Сменили раздел, поиск или вернулись на главную — к началу: иначе новая выдача открывалась бы с середины. */
            .onChange(of: модель.действующее) { _, _ in
                решитьПолосуНедавних(сразу: true)
                withAnimation(.easeInOut(duration: 0.25)) { прокрутка.scrollTo(Self.верхЛенты, anchor: .top) }
            }
            /* Этап 32: сменили город — тоже к началу: выдача другого места с середины прежней не открывается. */
            .onChange(of: выборГорода.где) { _, _ in
                withAnimation(.easeInOut(duration: 0.25)) { прокрутка.scrollTo(Self.верхЛенты, anchor: .top) }
            }
            /* Этап 33: сменили фильтры или порядок — тоже к началу: новая выдача с первой страницы. */
            .onChange(of: модель.фильтры) { _, _ in
                withAnimation(.easeInOut(duration: 0.25)) { прокрутка.scrollTo(Self.верхЛенты, anchor: .top) }
            }
            /* Этап 49: «Показать все объявления» и «Главная» — тоже с начала, как window.scrollTo(0, 0) у mkHomeAll. */
            .onChange(of: модель.все) { _, _ in
                прокрутка.scrollTo(Self.верхЛенты, anchor: .top)
            }
        }
        .scrollDismissesKeyboard(.immediately)
        .background(Theme.фонСтраницы)
        /* Этап 49: подгрузка — плашкой над нижней панелью, как mkLoadBar сайта (только в ленте: у главной свои ряды). */
        .overlay(alignment: .bottom) {
            if плашкаЗагрузки && !наГлавной {
                ПлашкаЗагрузкиЛенты(ещё: модель.грузимЕщё, медленно: плашкаМедленно)
                    .padding(.horizontal, 16)
                    .padding(.bottom, 10)
                    .transition(.move(edge: .bottom).combined(with: .opacity))
            }
        }
        .overlay(alignment: .bottom) {
            if let тост {

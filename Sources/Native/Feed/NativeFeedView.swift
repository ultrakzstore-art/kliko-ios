                    Text("· " + путь.текст)
                        .foregroundStyle(путь.далеко ? Theme.текстВторой : Theme.акцент)
                        .lineLimit(1)
                }
            }
            .font(.system(size: кегль(11)))
            .foregroundStyle(место.рядом ? Theme.зелёныйЯркий : Theme.текстВторой)
            .layoutPriority(1)
        }
        .вСтрокуКарточки(.system(size: кегль(11)))     // щит «Гаранта» не выше строки — низ карточек ровный
        .padding(.top, 10)

               вечная загрузка (иначе и мерцание, и VoiceOver «загружаем» по уже законченному поиску). */
            if модель.грузим || (!модель.ответПришёл && модель.ошибка == nil && !модель.сДиска) {
                /* Этап 11: серые карточки той же сетки вместо колеса. Рубильник выключен — колесо, как раньше. */
                if Config.скелетЛенты {
                    СкелетЛенты(колонки: ListingCard.сетка(размерТекста))
                } else {
                    SiteSpinner()
                        .frame(maxWidth: .infinity)
                        .padding(.top, 120)
                }
            } else if let ошибка = модель.ошибка {
                заглушкаОшибки(ошибка)
            } else if Config.дизайнКакНаСайте {
                пустаяВыдачаСайта               // этап 49: #mk-empty сайта
            } else {
                заглушка(значок: "magnifyingglass", заголовок: FeedText.т("empty"), подпись: FeedText.т("empty_sub"))
            }
        } else {
            if модель.сДиска && модель.ошибка != nil {
                Label(FeedText.т("stale"), systemImage: "clock.arrow.circlepath")
                    .font(.footnote)
                    .foregroundStyle(.secondary)
                    .padding(.horizontal, 16)
            }
            /* Этап 18: лента уточнена — сколько подходит из загруженного; нажатие — лист, крестик — сброс. */
            if модель.уточнено {
                ПолосаУточнения(видно: модель.видимые.count, загружено: модель.items.count,
                                открыть: { уточнятьПоказан = true },
                                сбросить: { модель.уточнение = УточнениеЛенты() })
                if модель.видимые.isEmpty {
                    заглушка(значок: "line.3.horizontal.decrease.circle", заголовок: RefineText.т("none"),
                             подпись: RefineText.т("none_sub"))
                }
            }
            LazyVGrid(columns: ListingCard.сетка(размерТекста), spacing: ListingCard.зазор) {
                /* Порядок витрины сайта (ЗолотойРитм): ячейки, а не объявления — одно объявление бывает и в золотом месте,
                   и в обычном. Золото карточки — по месту (ячейка.показ), открывается объявление как пришло. */
                ForEach(модель.видимыеЯчейки) { ячейка in
                    let товар = ячейка.товар
                    /* Этап 2: карточка нативная. Рубильник выключен — как на этапе 1, страница сайта. Этап 14: в две
                       колонки карточка не уводит с ленты, а открывается справа, и выбранная обведена. */
                    Group {
                        if двеКолонки {
                            Button { выбрать(товар) } label: { ListingCard(товар: ячейка.показ) }
                                .выбраннаяКарточка(выбор.wrappedValue?.id == товар.id)
                        } else if Config.нативнаяКарточка {
                            NavigationLink(value: товар) { ListingCard(товар: ячейка.показ) }
                        } else {
                            Button { if let u = товар.адрес { открыть(u) } } label: { ListingCard(товар: ячейка.показ) }
                        }
                    }
                    .buttonStyle(.plain)
                    /* Золотое место: показ (видна наполовину) и нажатие — в rank_event.php, как у сайта (FeedRank.swift). */
                    .modifier(ПоказТОП(id: товар.id, золото: ячейка.топ))
                    .simultaneousGesture(TapGesture().onEnded { ОтчётТОП.shared.нажат(товар.id) },
                                         including: ячейка.топ ? .all : .subviews)
                    .сердечкоИзбранного(товар)          // этап 5: сердечко — слоем над карточкой, не внутри ссылки
                    .поделитьсяНаКарточке(товар)        // этап 49: «Поделиться» под сердцем, как .mk-cshare сайта
                    .onAppear { модель.дальше(после: товар) }
                }
            }
            .environment(\.режимАренды, модель.аренда)     // «Аренда»: цена аренды на карточках
            .padding(.horizontal, ListingCard.поле)
            if модель.уточнено { низУточнённой }
            низЛенты
        }
    }

    /// «Ничего не нашлось» как у сайта (#mk-empty): запрос, «Сохранить поиск», «Ищу это — спросить продавцов» и
    /// «Сбросить всё» (mkReset).
    private var пустаяВыдачаСайта: some View {
        let искомое = модель.действующее
        let сохранить: (() -> Void)? = показатьСохранитьПоиск ? { переключитьСохранённый(искомое) } : nil
        return ПустаяВыдачаСайта(запрос: искомое.текст, сохранить: сохранить, сохранён: сохранённые.есть(искомое),
                                 сбросить: { модель.сброситьВсё() },
                                 спросить: { спроситьПродавцов(искомое) })
    }

    /// mkAskSellers: есть запрос — лист mkBroadcast с текстом «Ищу: …» в разделе ленты (mkSt.cat или «other»), городом
    /// выбора и точкой человека; запроса нет — строка «Напишите, что ищете…» и фокус в поле поиска, как у сайта.
    private func спроситьПродавцов(_ искомое: ИскомоеЛенты) {
        let текст = искомое.текст.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !текст.isEmpty else {
            показатьТост(ListingLocationText.т("empty_ask_need"))
            полеВФокусе = true
            return
        }
        let точка = гео.точка
        запросПродавцам = ЗапросИсполнителям(
            текст: String(format: ListingLocationText.т("empty_ask_text"), текст),
            город: Config.выборГорода ? выборГорода.где.город : "",
            широта: точка.map { String($0.широта) } ?? "",
            долгота: точка.map { String($0.долгота) } ?? "",
            раздел: искомое.раздел.isEmpty ? "other" : искомое.раздел)
    }

    /**
     Низ выдачи под уточнением (этап 18). Подходящих мало — последняя видимая карточка уже на экране и второй раз
     onAppear не получит, а подгруженная страница могла не добавить ни одной подходящей. Отметка внизу просит следующую
     страницу, когда видна и когда число загруженного сменилось (task(id:) перезапускается), — до предела пустых
     подгрузок подряд; дальше решает человек кнопкой «Искать дальше».
     */
    @ViewBuilder
    private var низУточнённой: some View {
        Color.clear
            .frame(height: 1)
            .task(id: "\(модель.items.count)/\(модель.грузим)") { модель.дальшеУточнённой() }
        if модель.пустыхПодряд >= FeedModel.пустыхПодрядПредел && модель.можноЕщё && !модель.грузим
            && модель.ошибка == nil {
            VStack(spacing: 6) {
                Text(RefineText.т("more_sub"))
                    .font(.footnote)
                    .foregroundStyle(.secondary)
                    .multilineTextAlignment(.center)
                Button(RefineText.т("more")) { модель.искатьДальше() }
                    .font(.subheadline.weight(.semibold))
            }
            .frame(maxWidth: .infinity)
            .padding(.horizontal, 24)
            .padding(.vertical, 12)
        }
    }

    @ViewBuilder
    private var низЛенты: some View {
        if модель.грузим {
            /* Этап 49: в виде сайта подгрузку показывает плашка внизу экрана (mkLoadBar), колеса под лентой у сайта нет. */
            if !Config.дизайнКакНаСайте {
                SiteSpinner().frame(maxWidth: .infinity).padding(.vertical, 16)
            }
        } else if модель.ошибка != nil {
            Button(FeedText.т("retry")) { модель.повторить() }
                .font(.subheadline.weight(.semibold))
                .frame(maxWidth: .infinity)
                .padding(.vertical, 16)
        }
    }

    private func заглушкаОшибки(_ ошибка: ListingsAPI.Ошибка) -> some View {
        /* Сеть — «нет соединения». Всё прочее (сервер ответил не тем, разбор не сошёлся) — лента API сломана, и тогда
           у человека должен быть выход: лента сайта, которая работает независимо от этого API. */
        let нетСети: Bool
        if case .сеть = ошибка { нетСети = true } else { нетСети = false }
        return VStack(spacing: 14) {
            Image(systemName: нетСети ? "wifi.slash" : "exclamationmark.triangle")
                .font(.system(size: 42))
                .foregroundStyle(.secondary)
            Text(FeedText.т(нетСети ? "offline" : "failed"))
                .font(.title3.weight(.semibold))
            Text(FeedText.т(нетСети ? "offline_sub" : "failed_sub"))
                .font(.subheadline)
                .foregroundStyle(.secondary)
                .multilineTextAlignment(.center)
            Button { модель.повторить() } label: {
                Text(FeedText.т("retry"))
                    .font(.subheadline.weight(.semibold))
                    .foregroundStyle(.white)
                    .padding(.horizontal, 26).padding(.vertical, 12)
                    .background(Theme.green, in: Capsule())
            }
            /* «Сайт» убран (владелец: всё нативно) — только «Повторить». */
        }
        .padding(30)
        .frame(maxWidth: .infinity)
        .padding(.top, 60)
    }

    private func заглушка(значок: String, заголовок: String, подпись: String) -> some View {
        VStack(spacing: 12) {
            Image(systemName: значок)
                .font(.system(size: 40))
                .foregroundStyle(.secondary)
            Text(заголовок).font(.title3.weight(.semibold))
            Text(подпись)
                .font(.subheadline)
                .foregroundStyle(.secondary)
                .multilineTextAlignment(.center)
        }
        .padding(30)
        .frame(maxWidth: .infinity)
        .padding(.top, 60)
    }
}

/// Карточка объявления в сетке ленты.
///
/// Этап 11: шрифты — стилями текста, а не точками: при обычном размере те же 16/13/12 pt, а с «Размером текста» в
/// Настройках растут, но не дальше третьего крупного для доступности. Цена в одну строку ужимается до 0,6, а не
/// обрезается многоточием; название при крупном тексте — до трёх строк, и сетка тогда в одну колонку (сетка(_:)).
/// VoiceOver читает карточку одной фразой (Listing.голос), фото — украшение.
struct ListingCard: View {
    let товар: Listing
    /// Карточка блока «VIP-объявления» главной (этап 34): .mh-vipg .mh-c сайта — золотая рамка и золотистый верх у каждой,
    /// как у ТОПа, даже без is_top; метка «★ ТОП» — по-прежнему только у ТОПа.
    let вип: Bool
    @Environment(\.dynamicTypeSize) private var размерТекста
    /// Этап 49: тема — тень карточки витрины (в тёмной у сайта своя).
    @Environment(\.colorScheme) private var схема
    /// Этап 49: кегли витрины в пикселях сайта (19, 13, 12, 11), растущие с «Размером текста»: 100 при обычном.
    @ScaledMetric(relativeTo: .body) private var сотня: CGFloat = 100
    /// Лента в режиме «Аренда» — цена аренды (ЦенаКарточкиСайта, режимАренды).
    @Environment(\.режимАренды) private var режимАренды
    /// Точка человека — расстояние вместо города до 5 км (mkVitCardHTML) и время в пути (mkEtaFill), FeedGeo.swift.
    @ObservedObject private var гео = ГеоЛенты.shared
    @ObservedObject private var пути = ОценкиПути.shared

    init(товар: Listing, вип: Bool = false) {
        self.товар = товар
        self.вип = вип
    }

    /// Золотая рамка и подложка: ТОП (.mh-c.is-top) или VIP-блок (.mh-vipg .mh-c).
    private var золотая: Bool { товар.isTop || вип }

    /// Зазор сетки: у витрины сайта — 14 (--vit-gap), у прежнего вида — 12.
    static var зазор: CGFloat { Config.дизайнКакНаСайте ? 14 : 12 }
    /// Поля сетки по бокам: у сайта — 16, у прежнего вида — 12.
    static var поле: CGFloat { Config.дизайнКакНаСайте ? 16 : 12 }

    /// Колонки сетки карточек. Обычно — по ширине экрана, от 158 pt. При крупном тексте для доступности — от 300 pt: на
    /// iPhone это одна карточка во всю ширину, иначе цене и названию в узкой карточке не хватит места.
    static func сетка(_ размер: DynamicTypeSize) -> [GridItem] {
        if размер.isAccessibilitySize {
            return [GridItem(.adaptive(minimum: 300, maximum: 520), spacing: зазор, alignment: .top)]
        }
        return [GridItem(.adaptive(minimum: 158, maximum: 260), spacing: зазор, alignment: .top)]
    }

    /// Одна карточка на всё (владелец 26.09.2026): карточка витрины сайта. Прежняя карточка этапов 1–23 убрана, чтобы в
    /// одной сетке не оказалось двух видов; ТОП и VIP отличаются только золотом (рамка, метка, подложка).
    var body: some View {
        карточкаСайта
    }

    private var крупныйТекст: Bool { размерТекста.isAccessibilitySize }

    /**
     Карточка ленты как у сайта (этап 49) — mkVitCardHTML, скин «vitrina» (по умолчанию у сайта): фото 4:3 на мятной
     подложке; слева сверху состояние (mkCond: «Б/У», «Новое», «С пробегом», «Новостройка») и «Резерв» под ним; «★ ТОП»
     золотом левее сердца; точки фото (до восьми); цена 19 px (fmtCard: от миллиона «14,5 млн ₸», «ТОРГ», старая
     зачёркнута, аренда «/сут»; нет цены — строки нет); название 13 px в две строки; строка характеристик (mkCapSpecs); низ
     за линией — знак доверия (mkVitTrust) и город с булавкой. Скругление 18, рамка линии и мягкая тень; ТОП и VIP — золотая
     рамка и золотистый верх; у магазина с фирменным цветом — полоса сверху и цена его цветом (.mk-cbrand). Сердце и
     «Поделиться» — слоями снаружи (сердечкоИзбранного, поделитьсяНаКарточке), как кнопки поверх ссылки у сайта.
     Строки держат место и пустыми — карточки в ряду сетки одной высоты, как у CSS-сетки сайта (там низ прижат книзу).
     */
    private var карточкаСайта: some View {
        VStack(alignment: .leading, spacing: 0) {
            фотоСайта
            телоСайта
        }
        .вВысотуРядаСетки()             // владелец 26.09.2026: карточки ряда сетки одной высоты, как у сайта
        .background(фонКарточкиСайта)
        .overlay(alignment: .top) {
            if let краска = краскаМагазина {
                Rectangle()
                    .fill(краска)
                    .frame(height: 3)
                    .allowsHitTesting(false)
            }
        }
        .clipShape(RoundedRectangle(cornerRadius: Theme.Радиус.lg, style: .continuous))
        .overlay {
            RoundedRectangle(cornerRadius: Theme.Радиус.lg, style: .continuous)
                .strokeBorder(золотая ? Theme.цвет(0xE4C579, 0xE4C579) : Theme.линия, lineWidth: 1)
                .allowsHitTesting(false)
        }
        .overlay {
            if золотая {        // .top-card: снаружи ещё кольцо 1,5 #d9b24c (box-shadow 0 0 0 1.5px), в обеих темах
                RoundedRectangle(cornerRadius: Theme.Радиус.lg + 0.75, style: .continuous)
                    .stroke(Theme.цвет(0xD9B24C, 0xD9B24C), lineWidth: 1.5)
                    .padding(-0.75)
                    .allowsHitTesting(false)
            }
        }
        .background { теньСайта }
        .contentShape(RoundedRectangle(cornerRadius: Theme.Радиус.lg, style: .continuous))
        .dynamicTypeSize(...DynamicTypeSize.accessibility3)
        .accessibilityElement(children: .ignore)
        .accessibilityLabel(товар.голос)
        .onAppear { ОценкиПути.shared.нужна(товар.id) }
    }

    private func кегль(_ пикселей: CGFloat) -> CGFloat { пикселей * сотня / 100 }

    /// .mk-cshot: 4:3, фото с обрезкой по центру; подложка — мятный градиент (в тёмной — тёмно-зелёный).
    private var фотоСайта: some View {
        LinearGradient(colors: [Theme.цвет(0xEEF4F0, 0x1A2A22), Theme.цвет(0xDFEAE3, 0x101914)],
                       startPoint: .top, endPoint: .bottom)
            .aspectRatio(4 / 3, contentMode: .fit)
            .overlay {
                /* Владелец 25.09.2026, проверка на телефоне, сборка 33 («лента подвисает»): не AsyncImage, а
                   КартинкаЛенты — уменьшенная до ячейки, распакованная не на главной очереди и из памяти. */
                /* Владелец 26.09.2026 (ряд «Услуги»: «монт компьютеров с…», «5 000 ₸», обрезанный кружок «K»): обложка
                   услуги — обычно баннер с надписями прямо на картинке (название, цена, аватар). Обрезка по центру
                   срезала их края, поэтому у услуг картинка целиком на мятной подложке; у прочих — по центру, как у сайта. */
                КартинкаЛенты(товар.обложка, пунктов: крупныйТекст ? 520 : 260, заполнить: !товар.услуга) {
                    Image(systemName: "photo")
                        .font(.system(size: 26))
                        .foregroundStyle(Theme.текстВторой.opacity(0.5))
                }
            }
            .clipped()
            .overlay(alignment: .topLeading) { меткиФото }
            .overlay(alignment: .topTrailing) {
                if товар.isTop {
                    меткаТопЛенты
                        .padding(.top, 8)
                        .padding(.trailing, 46)
                }
            }
            .overlay(alignment: .bottom) { точкиФото }
    }

    /// .mk-cond — (8, 8), под ним .mk-resv-badge — (8, 34).
    private var меткиФото: some View {
        ZStack(alignment: .topLeading) {
            if let метка = товар.меткаСостояния {
                меткаСостояния(метка)
                    .padding(.top, 8)
                    .padding(.leading, 8)
            }
            if товар.вРезерве {
                меткаРезерва
                    .padding(.top, 34)
                    .padding(.leading, 8)
            }
        }
    }

    /// .mk-cond: 10 px, 700, разрядка 0,04 em; новое — зелёный градиент (--mk-green2 → --mk-green), б/у и «С пробегом» —
    /// оранжевый (#e8923f → #d4761f); скругление 8.
    private func меткаСостояния(_ метка: Listing.МеткаСостояния) -> some View {
        Text(метка.текст)
            .font(.system(size: 10, weight: .bold))
            .tracking(0.4)
            .foregroundStyle(Color.white)
            .lineLimit(1)
            .padding(.horizontal, 10)
            .padding(.vertical, 4)
            .background(LinearGradient(colors: метка.новое ? Self.краскиНового : Self.краскиБУ,
                                       startPoint: .topLeading, endPoint: .bottomTrailing),
                        in: RoundedRectangle(cornerRadius: Theme.Радиус.xs, style: .continuous))
    }

    private static let краскиНового: [Color] = [Theme.акцент, Theme.цвет(0x0F5132, 0x5CD39A)]
    private static let краскиБУ: [Color] = [Color(red: 232 / 255, green: 146 / 255, blue: 63 / 255),
                                            Color(red: 212 / 255, green: 118 / 255, blue: 31 / 255)]
    /// #3a2c05 — текст золотых меток «★ ТОП» и «Резерв».
    private static let текстЗолота = Color(red: 58 / 255, green: 44 / 255, blue: 5 / 255)

    /// «Резерв» — .mk-resv-badge: жёлто-золотой градиент (#f3c34d → #e0a92e), тёмный текст и точка #7a5b06.
    private var меткаРезерва: some View {
        HStack(spacing: 6) {
            Circle()
                .fill(Color(red: 122 / 255, green: 91 / 255, blue: 6 / 255))
                .frame(width: 6, height: 6)
            Text(DesignText.т("reserved"))
                .font(.system(size: 10, weight: .bold))
                .tracking(0.2)
                .lineLimit(1)
        }
        .foregroundStyle(Self.текстЗолота)
        .padding(.leading, 8)
        .padding(.trailing, 10)
        .padding(.vertical, 4)
        .background(LinearGradient(colors: [Color(red: 243 / 255, green: 195 / 255, blue: 77 / 255),
                                            Color(red: 224 / 255, green: 169 / 255, blue: 46 / 255)],
                                   startPoint: .topLeading, endPoint: .bottomTrailing),
                    in: RoundedRectangle(cornerRadius: Theme.Радиус.xs, style: .continuous))
    }

    /// «★ ТОП» ленты — .mk-top-badge: левее сердца (46 от края), золото 135° (#e7c252 → золото сайта), тёмный текст,
    /// скругление 10. Тень — заливкой подложки (ShapeStyle.shadow), как у меток главной (сборка 33).
    private var меткаТопЛенты: some View {
        Text("★ " + FeedText.т("top"))
            .font(.system(size: 10, weight: .bold))
            .foregroundStyle(Self.текстЗолота)
            .lineLimit(1)
            .padding(.horizontal, 8)
            .padding(.vertical, 4)

                        .lineLimit(1)
                }
                .font(.system(size: кегль(11), weight: .bold))
                .foregroundStyle(Theme.зелёный2)
            }
            Spacer(minLength: 0)
            HStack(spacing: 4) {
                if место.рядом || !товар.city.isEmpty {     // булавка — у города и расстояния; без них дата, как у сайта
                    Image(systemName: "mappin")
                        .font(.system(size: кегль(10), weight: .semibold))
                }
                Text(место.текст.isEmpty ? " " : место.текст)
                    .fontWeight(место.рядом ? .bold : .regular)
                    .lineLimit(1)

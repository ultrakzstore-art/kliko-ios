                .frame(height: 1)
        }
    }

    /// Фирменный цвет магазина — полоса сверху и цена (.mk-cbrand); nil — не магазин или цвета нет.
    private var краскаМагазина: Color? { товар.краскаМагазинаЛенты }

    /// Подложка: в ТОПе и в VIP-блоке — золотистый верх (.mk-card.top-card), иначе поверхность.
    @ViewBuilder
    private var фонКарточкиСайта: some View {
        if золотая {
            LinearGradient(stops: [Gradient.Stop(color: Theme.топФон, location: 0),
                                   Gradient.Stop(color: Theme.поверхность, location: 0.55)],
                           startPoint: .top, endPoint: .bottom)
        } else {
            Theme.поверхность
        }
    }

    /// Тень — --mk-shs сайта (0 4px 14px −8px rgba(15,81,50,.3), в тёмной 0 6px 18px −10px rgba(0,0,0,.6)), у ТОПа —
    /// золотистая. Заливкой подложки той же формы (ShapeStyle.shadow), а не .shadow на карточке: такую тень не считают
    /// заново по прозрачности фото и текста каждый кадр прокрутки (сборка 33, «лента подвисает»).
    private var теньСайта: some View {
        RoundedRectangle(cornerRadius: Theme.Радиус.lg, style: .continuous)
            .fill(Theme.поверхность.shadow(.drop(color: цветТени, radius: 5, x: 0, y: 4)))
            .allowsHitTesting(false)
            .accessibilityHidden(true)
    }

    private var цветТени: Color {
        if золотая { return Color(red: 176 / 255, green: 132 / 255, blue: 24 / 255).opacity(0.28) }
        if схема == .dark { return Color.black.opacity(0.4) }
        return Color(red: 15 / 255, green: 81 / 255, blue: 50 / 255).opacity(0.16)
    }

    /// «14 900 000 ₸», аренда «5 000 ₸/сут», без цены — «Договорная» или «Цена по запросу».
    static func цена(_ т: Listing) -> String {
        if т.forRent, let день = т.rentPriceDay, день > 0 {
            return тенге(день) + FeedText.т("perday")
        }
        guard let p = т.price, p > 0 else {
            return FeedText.т(т.negotiable ? "neg" : "noprice")
        }
        return тенге(p)
    }

    /// «14 900 000 ₸».
    static func тенге(_ n: Double) -> String {
        (формат.string(from: NSNumber(value: n)) ?? String(Int(n))) + "\u{00A0}₸"
    }

    private static let формат: NumberFormatter = {
        let ф = NumberFormatter()
        ф.numberStyle = .decimal
        ф.groupingSeparator = "\u{00A0}"      // неразрывный пробел: цена не переносится посреди числа
        ф.maximumFractionDigits = 0
        return ф
    }()
}

/// Положение верха ленты в её прокрутке: 0 — у самого верха, меньше — прокручено вниз. Нет замера — «далеко».
struct ВерхЛентыКлюч: PreferenceKey {
    static let defaultValue: CGFloat = -10_000
    static func reduce(value: inout CGFloat, nextValue: () -> CGFloat) {
        value = max(value, nextValue())
    }
}

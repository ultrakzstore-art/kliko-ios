            итог.append(АктивныйФильтр(вид: .раздел, текст: раздел))
        }
        if модель.рядом {
            итог.append(АктивныйФильтр(вид: .рядом, текст: ВитринаТекст.т("near_me")))
        }
        return итог + модель.фильтры.чипы(раздела: модель.раздел)
    }


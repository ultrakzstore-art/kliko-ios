     что есть среди загруженных объявлений ленты, в порядке просмотра, до двенадцати; меньше двух — полосы нет.
     */
    private var недавниеВЛенте: [Listing] {
        let искомое = модель.действующее
        guard Config.недавние, искомое.текст.isEmpty, искомое.раздел.isEmpty || искомое.раздел == "goods",
              !недавние.товары.isEmpty else { return [] }
        var загружены: [String: Listing] = [:]
        for товар in модель.items where загружены[товар.id] == nil { загружены[товар.id] = товар }
        var итог: [Listing] = []
        for товар in недавние.товары {
            guard итог.count < 12 else { break }
            if let свежий = загружены[товар.id] { итог.append(свежий) }
        }
        return итог
    }


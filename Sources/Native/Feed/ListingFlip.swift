/**
 ЛИСТАНИЕ ОБЪЯВЛЕНИЙ НА МЕСТЕ (владелец 08.10.2026: «свайп следующего объявления — как лучше в приложении?» — «делай
 как считаешь нужным»).

 Не свайпом вбок по всей карточке: вбок у неё листаются фото, а от левого края — системное «назад». Как привычно на
 iPhone, по образцу «Почты»:
   · стрелки ˄ ˅ — предыдущее и следующее. В виде сайта — две круглые кнопки над фото перед «×», в прежнем виде — в
     панели. Есть только у объявления из списка экрана, откуда его открыли (лента со своим отбором, избранное, витрина
     продавца, «Мои объявления», выдача поиска по фото), и когда в списке больше одного; соседа нет — стрелка неактивна.
     У последнего в ленте подгружается её следующая страница;
   · внизу, после «Похожих», — «Следующее объявление»: мини-карточка, нажатие открывает его. Долистал до конца и тянет
     дальше вверх — кружок заполняется по мере натяга, на пороге щелчок и «Отпустите — следующее»; отпустил за порогом
     — следующее. Списка нет (ссылка, чат, «Похожие») или он кончился — блок предлагает первое из похожих этой
     карточки; нет и их — блока нет;
   · карточка меняется на месте: стек не растёт, «Назад» ведёт к списку. Следующее въезжает снизу, предыдущее — сверху,
     при «Уменьшении движения» — просто прозрачность. Всё состояние карточки (догрузка, похожие, фото) — заново (.id);
   · «летает»: пока смотрят текущее, полная карточка следующего и его первое фото качаются заранее — только следующее и
     один раз (ЗаготовкаСледующегоОбъявления).

 ListingDetailView — обёртка с прежним init: её создают все места открытия, источник листания — необязательный. Сама
 карточка — КарточкаОбъявленияЯдро (ListingDetailView.swift), страница как на сайте — СтраницаОбъявленияСайта
 (SiteListing.swift): стрелки и нижний блок рисует она, жест подтягивания ставит ядро (ПотянутьКСледующему).
 */

// MARK: - Откуда листать

/// Список экрана, откуда открыли объявление: по нему листают стрелки и «Следующее». Открыли по ссылке, из чата, из
/// «Похожих» — nil. Сам список обёртка берёт один раз, когда карточка встала (список(для:)): места открытия создают
/// источник на каждую свою перерисовку, а у ленты это проход по всей загруженной ленте.
struct ИсточникЛистанияОбъявлений {
    /// Объявления в порядке экрана — по запросу.
    let товары: @MainActor () -> [Listing]
    /// Следующая страница списка (лента): получает последнее известное объявление, отдаёт весь список заново; nil — не
    /// вышло. Самой функции нет — список целиком.
    let ещё: (@MainActor (Listing) async -> [Listing]?)?

    init(товары: @escaping @MainActor () -> [Listing], ещё: (@MainActor (Listing) async -> [Listing]?)? = nil) {
        self.товары = товары
        self.ещё = ещё
    }

    /// Список для открытого — в порядке экрана, без повторов (у ленты одно объявление бывает и в золотой ячейке, и в
    /// обычной); открытого в нём нет — nil: листать не по чему.
    @MainActor
    func список(для товар: Listing) -> [Listing]? {
        let все = Self.безПовторов(товары())
        return все.contains(where: { $0.id == товар.id }) ? все : nil
    }

    /// Первое появление каждого объявления — порядок экрана сохраняется.
    static func безПовторов(_ товары: [Listing]) -> [Listing] {
        var были = Set<String>()
        return товары.filter { были.insert($0.id).inserted }
    }

    /// Источник по готовому списку — если открытое в нём есть; нет — nil: листать не по чему.
    static func поСписку(_ товары: [Listing], открыто товар: Listing,
                         ещё: (@MainActor (Listing) async -> [Listing]?)? = nil) -> ИсточникЛистанияОбъявлений? {
        guard товары.contains(where: { $0.id == товар.id }) else { return nil }
        return ИсточникЛистанияОбъявлений(товары: { товары }, ещё: ещё)
    }

    /// Лента с её разделом, поиском, фильтрами и уточнением — в порядке витрины (видимыеЯчейки); у последнего —
    /// следующая страница, как при прокрутке. Ленту не перебираем здесь: открытого в ней нет — это решит список(для:).
    @MainActor
    static func лента(_ модель: FeedModel) -> ИсточникЛистанияОбъявлений {
        ИсточникЛистанияОбъявлений(товары: { [weak модель] in модель?.видимыеЯчейки.map(\.товар) ?? [] },
                                   ещё: { [weak модель] последний in
                                       guard let модель else { return nil }
                                       await модель.дальшеИДождаться(после: последний)
                                       return модель.видимыеЯчейки.map(\.товар)
                                   })
    }

    /// Избранное — в порядке экрана «Избранное».
    @MainActor
    static func избранное(открыто товар: Listing) -> ИсточникЛистанияОбъявлений? {
        поСписку(FavoritesStore.shared.товары, открыто: товар)
    }

    /// «Мои объявления» выбранной вкладки — те, что открываются карточкой (одобренные, номер годится для ?id=), строками
    /// с названием, ценой и обложкой; остальное карточка дотянет сама.
    static func мои(_ видимые: [МоёОбъявление], открыто товар: Listing) -> ИсточникЛистанияОбъявлений? {
        let строки = видимые
            .filter { $0.статус == "approved" && $0.id.range(of: "^[A-Za-z0-9_-]{1,40}$", options: .regularExpression) != nil }
            .map { строкаМоего($0) }
        return поСписку(строки, открыто: товар)
    }

    private static func строкаМоего(_ м: МоёОбъявление) -> Listing {
        var т = Listing(номер: м.id)
        т.title = м.название
        т.price = м.цена > 0 ? м.цена : nil
        т.negotiable = м.торг
        т.thumb = м.фото.isEmpty ? nil : м.фото
        т.city = м.город
        return т
    }
}

/// Что карточка (КарточкаОбъявленияЯдро) знает о соседях и как к ним перейти. Даёт обёртка ListingDetailView.
struct ЛистаниеКарточки {
    /// Стрелки ˄ ˅: открытое — из списка экрана, и в нём больше одного.
    let стрелки: Bool
    let предыдущее: Listing?
    let следующее: Listing?
    /// Открытое — последнее загруженное, а следующая страница списка ещё может прийти: «Следующее» ждёт её, а не
    /// предлагает похожее.
    let ждёмЕщё: Bool
    /// Сменить карточку на месте; true — вперёд (новая въезжает снизу), false — назад (сверху).
    let перейти: (Listing, Bool) -> Void
    /// Заранее подтянуть полную карточку и первое фото (ЗаготовкаСледующегоОбъявления).
    let прогреть: (Listing) -> Void
    /// Уже было на экране этой обёртки или есть в списке экрана: «Следующее» из похожих его не предлагает — похожие у
    /// объявлений одного раздела одни и те же (первая страница раздела), и листание качалось бы между двумя.
    let ужеБыло: (String) -> Bool
    /// Карточка с этим номером — та, что сейчас на экране. Уходящая при листании живёт до конца перехода, и её
    /// догрузка не должна перебивать Handoff новой.
    let наЭкране: (String) -> Bool
}

// MARK: - Обёртка: карточка меняется на месте

/**
 Карточка объявления с листанием. Держит текущее объявление и рисует ядро с .id(текущего): сменили — всё состояние
 карточки начинается заново, а onAppear и onDisappear ядра («Вы смотрели», Handoff, поиск iPhone, просьба оценить)
 срабатывают у каждой показанной. «С того же места» (StateRestore) отмечает то объявление, что сейчас на экране.
 */
struct ListingDetailView: View {
    /// Открыть страницу сайта в веб-обёртке.
    let открыть: (URL) -> Void
    /// Вкладка для «С того же места» (StateRestore): отмечается объявление на экране, и при листании тоже. nil — не
    /// отмечаем.
    let место: КлючВкладкиМеста?
    /// Откуда листать. Список из него берётся один раз, при первом показе (взятьСписок).
    let источник: ИсточникЛистанияОбъявлений?
    /// Карточка сменилась листанием — месту открытия, кто теперь на экране (правая колонка iPad: рамка в ленте и стек
    /// при сужении окна). nil — никому не надо.
    let приСмене: ((Listing) -> Void)?
    @State private var текущий: Listing
    /// Список экрана, откуда открыли; nil — листать не по чему (стрелок нет, «Следующее» — из похожих).
    @State private var список: [Listing]?
    @State private var ещё: (@MainActor (Listing) async -> [Listing]?)?
    /// Список из источника уже взят: возврат на экран (из похожих, из чата) его не перечитывает.
    @State private var списокВзят = false
    /// Что здесь уже показали (открытое и пролистанные): «Следующее» из похожих их не предлагает.
    @State private var показанные: Set<String>
    /// Для какой длины списка уже просили следующую страницу — второй раз за той же не ходим.
    @State private var ещёПросили = 0
    @State private var ещёИдёт = false
    /// Список кончился или следующая страница не пришла: дальше «Следующее» — из похожих.
    @State private var ещёНет = false
    /// Куда листнули последний раз: true — вперёд. От него — откуда въезжает новая карточка и куда уходит прежняя.
    @State private var вниз = true
    /// Смена направления: карточка ждёт, пока уходящая перерисуется с новым переходом (onChange ниже).
    @State private var ждёт: Listing?
    @StateObject private var заготовка = ЗаготовкаСледующегоОбъявления()

    init(товар: Listing, открыть: @escaping (URL) -> Void, листание: ИсточникЛистанияОбъявлений? = nil,
         место: КлючВкладкиМеста? = nil, приСмене: ((Listing) -> Void)? = nil) {
        _текущий = State(initialValue: товар)
        _показанные = State(initialValue: [товар.id])
        self.открыть = открыть
        self.место = место
        self.источник = листание
        self.приСмене = приСмене
    }

    var body: some View {
        ZStack {
            КарточкаОбъявленияЯдро(товар: текущий, открыть: открыть, листание: соседи)
                .modifier(МестоКарточкиЛистания(номер: текущий.id, вкладка: место))
                .id(текущий.id)
                .transition(переход)
        }
        .onAppear { взятьСписок() }
        .task(id: ключПодгрузки) { await подгрузитьЕщё() }
        /* Уходящая уже перерисована с переходом нового направления — теперь меняем. */
        .onChange(of: вниз) { _, _ in
            guard let цель = ждёт else { return }
            ждёт = nil
            сменить(на: цель)
        }
        .onDisappear { заготовка.отменить() }
    }

    /// Соседи текущего по списку экрана и переходы к ним — для ядра.
    private var соседи: ЛистаниеКарточки {
        var предыдущее: Listing? = nil
        var следующее: Listing? = nil
        var вСписке = false
        var стрелки = false
        if let список, let i = список.firstIndex(where: { $0.id == текущий.id }) {
            вСписке = true
            стрелки = список.count > 1
            if i > 0 { предыдущее = список[i - 1] }
            if i + 1 < список.count { следующее = список[i + 1] }
        }
        let ждёмЕщё = вСписке && следующее == nil && ещё != nil && !ещёНет
        let заготовка = self.заготовка
        let показанные = self.показанные
        let весьСписок = self.список
        return ЛистаниеКарточки(стрелки: стрелки, предыдущее: предыдущее, следующее: следующее, ждёмЕщё: ждёмЕщё,
                                перейти: { цель, вперёд in перейти(к: цель, вперёд: вперёд) },
                                прогреть: { цель in заготовка.прогреть(цель) },
                                ужеБыло: { номер in
                                    показанные.contains(номер)
                                        || (весьСписок?.contains(where: { $0.id == номер }) ?? false)
                                },
                                наЭкране: { номер in текущий.id == номер })
    }

    /// Список экрана — один раз, при первом показе; открытого в нём нет — листать не по чему.
    private func взятьСписок() {
        guard !списокВзят else { return }
        списокВзят = true
        guard let источник, let взятый = источник.список(для: текущий) else { return }
        список = взятый
        ещё = источник.ещё
    }

    // MARK: Переход

    private func перейти(к цель: Listing, вперёд: Bool) {
        guard цель.id != текущий.id, ждёт == nil else { return }
        /* Заготовка готова — карточка сразу полная: не ждёт сети и второй раз за ней не ходит. */
        let показать = заготовка.взять(цель) ?? цель
        ОткликСайта.выбор()
        if вперёд == вниз {
            сменить(на: показать)
        } else {
            /* Переход уходящей берётся с её последней отрисовки: сперва направление, смена — в onChange. */
            ждёт = показать
            вниз = вперёд
        }
    }

    private func сменить(на цель: Listing) {
        показанные.insert(цель.id)
        withAnimation(анимацияСмены) { текущий = цель }
        приСмене?(цель)
        /* VoiceOver: на экране другая карточка — фокус к её началу. */
        if UIAccessibility.isVoiceOverRunning {
            DispatchQueue.main.asyncAfter(deadline: .now() + 0.5) {
                UIAccessibility.post(notification: .screenChanged, argument: nil)
            }
        }
    }

    /// Пружина смены; при «Уменьшении движения» — короткое затухание (переход тогда — только прозрачность).
    private var анимацияСмены: Animation {
        ДвижениеСайта.тихо ? .easeInOut(duration: 0.2) : .spring(response: 0.42, dampingFraction: 0.88)
    }

    /// Вперёд — новая въезжает снизу, прежняя уходит вверх; назад — наоборот.
    private var переход: AnyTransition {
        if ДвижениеСайта.тихо { return .opacity }
        let снизу = AnyTransition.move(edge: .bottom).combined(with: .opacity)
        let сверху = AnyTransition.move(edge: .top).combined(with: .opacity)
        return вниз ? .asymmetric(insertion: снизу, removal: сверху) : .asymmetric(insertion: сверху, removal: снизу)
    }

    // MARK: Следующая страница списка

    private var ключПодгрузки: String { текущий.id + "#" + String(список?.count ?? 0) }

    /// Открыто одно из двух последних загруженных — следующая страница списка (лента), чтобы «Следующее» было готово.
    private func подгрузитьЕщё() async {
        guard let список, let ещё, !ещёНет, !ещёИдёт, ещёПросили != список.count,
              let i = список.firstIndex(where: { $0.id == текущий.id }), i >= список.count - 2,
              let последний = список.last else { return }
        ещёПросили = список.count
        ещёИдёт = true
        let пришло = await ещё(последний)
        ещёИдёт = false
        guard let пришло else {
            ещёНет = true
            return
        }
        let новый = ИсточникЛистанияОбъявлений.безПовторов(пришло)
        /* Список вырос и открытое в нём на месте — листаем дальше по нему; нет — он кончился. */
        if новый.count > список.count, новый.contains(where: { $0.id == текущий.id }) {
            self.список = новый
        } else {
            ещёНет = true
        }
    }
}

/// «С того же места» (StateRestore) — у объявления на экране; без вкладки не отмечаем.
private struct МестоКарточкиЛистания: ViewModifier {
    let номер: String
    let вкладка: КлючВкладкиМеста?

    @ViewBuilder
    func body(content: Content) -> some View {
        if let вкладка {
            content.местоЭкрана(.объявление(номер), вкладка: вкладка)
        } else {
            content
        }
    }
}

// MARK: - Заготовка следующего

/**
 Следующее объявление — заранее, пока смотрят текущее: тот же GET /api/listings.php?id=, что у карточки (он же кладёт её
 в память ListingsAPI.готовая), и первое фото тем же запросом, что галерея (URLSession.shared, общий кэш). Только
 следующее и один раз: сменилось следующее — прежняя заготовка отменяется.
 */
@MainActor
final class ЗаготовкаСледующегоОбъявления: ObservableObject {
    private struct Готовая {
        let товар: Listing
        let сырое: Data
        /// Поколение копий без сети (ListingDetailCache) — взятое до запроса.
        let поколение: Int
        let когда: Date
    }

    /// Чьё сейчас качается или уже лежит — второй раз за тем же не ходим.
    private var номер: String?
    private var задача: Task<Void, Never>?
    private var готовая: Готовая?

    /// Сколько заготовка свежа: дольше смотрели текущее — следующее дотянет себя само (из памяти ListingsAPI сразу).
    private static let свежесть: TimeInterval = 180
    /// Пауза перед заготовкой: сперва своя догрузка открытой карточки и её похожие.
    private static let пауза: UInt64 = 700_000_000

    func прогреть(_ цель: Listing) {
        guard номер != цель.id else { return }
        /* Её за этот запуск уже качали (смотрели или заготовили — листают туда-обратно): ядро покажет её из памяти
           ListingsAPI сразу, фото уже в кэше. Второй раз не качаем и готовую заготовку другого не выбрасываем. */
        guard ListingsAPI.готовая(цель.id) == nil else { return }
        /* Строка уже полная (лента с целым описанием, избранное): ядро за ней в сеть не пойдёт — и мы карточку не
           качаем, только первое фото; готовая заготовка другого тоже остаётся. */
        let нужнаКарточка = !цель.полная
        задача?.cancel()
        номер = цель.id
        if нужнаКарточка { готовая = nil }
        let id = цель.id
        let запасное = цель.фотоАдреса.first
        задача = Task { [weak self] in
            try? await Task.sleep(nanoseconds: ЗаготовкаСледующегоОбъявления.пауза)
            guard !Task.isCancelled else { return }
            var фото = запасное
            if нужнаКарточка {
                let взятое = ListingDetailCache.поколение
                if let ответ = try? await ListingsAPI.объявлениеСОтветом(id), ответ.товар.id == id, !Task.isCancelled {
                    self?.положить(Готовая(товар: ответ.товар, сырое: ответ.сырое, поколение: взятое, когда: Date()))
                    фото = ответ.товар.фотоАдреса.first ?? запасное
                }
            }
            guard !Task.isCancelled, let фото else { return }
            await ЗаготовкаСледующегоОбъявления.прогретьФото(фото)
        }
    }

    /// Полная карточка для перехода — если готова и свежа. Ответ — копией без сети (этап 13), как у открытой карточки,
    /// свежая цена — в избранное. Не готова — качающуюся отменяем: карточка дотянет себя сама.
    func взять(_ цель: Listing) -> Listing? {
        guard let г = готовая, г.товар.id == цель.id, Date().timeIntervalSince(г.когда) < Self.свежесть else {
            if номер == цель.id {
                задача?.cancel()
                задача = nil
                номер = nil
            }
            return nil
        }
        готовая = nil
        var полный = г.товар
        if полный.категория == nil { полный.категория = цель.категория }
        if Config.карточкиБезСети {
            КарточкиБезСети.shared.запомнить(г.сырое, id: полный.id, поколение: г.поколение, открыта: true)
        }
        if Config.избранное { FavoritesStore.shared.освежить(полный) }
        return полный
    }

    /// Карточка ушла с экрана: качающееся — прочь (вернутся — начнётся снова), готовое остаётся.
    func отменить() {
        /* Готовой может быть и другая (прогрев полной строки её не выбрасывает) — тогда качающееся всё равно прочь. */
        guard готовая?.товар.id != номер else { return }
        задача?.cancel()
        задача = nil
        номер = nil
    }

    private func положить(_ г: Готовая) {
        guard номер == г.товар.id else { return }
        готовая = г
    }

    /// Первое фото — в общий кэш тем же запросом, что СлайдФото галереи (returnCacheDataElseLoad): откроется — оттуда.
    nonisolated private static func прогретьФото(_ адрес: URL) async {
        var запрос = URLRequest(url: адрес)
        запрос.cachePolicy = .returnCacheDataElseLoad
        _ = try? await URLSession.shared.data(for: запрос)
    }
}


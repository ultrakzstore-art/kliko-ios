/**
 Натяг за низом страницы объявления. Замер даёт нижний блок (БлокСледующегоОбъявления): насколько низ содержимого
 поднялся над низом видимой части прокрутки — это резинка ScrollView, когда дальше листать некуда. Палец даёт жест
 (ПотянутьКСледующему): только пока палец на экране и жест решён как «вверх» — резинка от броска сама по себе не
 считается. Порог — 90 pt резинки (это около 200 pt пальцем); на нём щелчок, отпустили за ним — следующее.
 */
@MainActor
final class ПодтягиваниеКСледующему: ObservableObject {
    static let порог: CGFloat = 90

    /// 0…1 — насколько натянули: по ней заполняется кружок.
    @Published private(set) var доля: CGFloat = 0
    /// Натянули до порога: отпустят — откроется следующее.
    @Published private(set) var взведено = false

    /// Резинка за низом сейчас; меньше нуля — до низа ещё не долистали.
    private var перетяжка: CGFloat = -1
    /// Решено за этот жест: true — тянут вверх, false — другое (вбок, вниз), nil — ещё не решено.
    private var решено: Bool?
    /// Резинка в момент решения, за вычетом первых пунктов хода: у короткой страницы промежуток под низом есть и без
    /// натяга — он не в счёт.
    private var начало: CGFloat = 0
    /// Номер жеста: запасной сброс (жестСнят) не трогает следующий жест.
    private var номерЖеста = 0
    private var отклик: UIImpactFeedbackGenerator?

    /// Замер блока: низ видимой части минус низ содержимого.
    func замер(_ значение: CGFloat) {
        перетяжка = значение
        обновить()
    }

    /// Палец идёт: первый раз за жест решаем, вверх ли он (в основном по вертикали — вбок листаются фото и похожие).
    func палец(_ ход: CGSize) {
        if решено == nil {
            let вверх = -ход.height
            решено = вверх > 0 && вверх > abs(ход.width) * 1.4
            номерЖеста += 1
            if решено == true { начало = max(0, перетяжка - 16) }
        }
        обновить()
    }

    /// Палец отпустили: true — натянули до порога, пора открыть следующее.
    func отпустили() -> Bool {
        let открыть = решено == true && взведено
        сбросить()
        return открыть
    }

    /// Жест снят без отпускания (его забрала система) — сбросить, если onEnded так и не пришёл.
    func жестСнят() {
        let номер = номерЖеста
        Task { @MainActor [weak self] in
            try? await Task.sleep(nanoseconds: 120_000_000)
            guard let self, self.номерЖеста == номер, self.решено != nil else { return }
            self.сбросить()
        }
    }

    func сбросить() {
        решено = nil
        начало = 0
        отклик = nil
        if доля != 0 { доля = 0 }
        if взведено { взведено = false }
    }

    private func обновить() {
        guard решено == true else { return }
        let натяг = max(0, перетяжка - начало)
        /* Отклик готовим, только когда натяг правда начался: «вверх» — это и обычная прокрутка к описанию, и держать
           Taptic Engine наготове на каждом таком жесте незачем. */
        if натяг > 0 && отклик == nil {
            отклик = UIImpactFeedbackGenerator(style: .medium)
            отклик?.prepare()
        }
        let новая = min(1, натяг / Self.порог)
        if abs(новая - доля) >= 0.01 || (новая == 0 && доля != 0) || (новая == 1 && доля != 1) { доля = новая }
        /* Чуть ниже порога — ещё взведено: на границе надпись и щелчок не дрожат. */
        let теперь = взведено ? натяг >= Self.порог - 8 : натяг >= Self.порог
        guard теперь != взведено else { return }
        взведено = теперь
        if теперь { (отклик ?? UIImpactFeedbackGenerator(style: .medium)).impactOccurred() }
    }
}

/**
 Жест подтягивания — по образцу ЗакрытьСмахиваниемВниз (SiteListingPull.swift): одновременный с прокруткой, решает один
 раз за жест и мешает только себе. Вбок (фото, полоса похожих) и вниз (смахнуть к закрытию от верха) он не решается;
 прокрутка идёт как шла — натяг ей не мешает, это её же резинка. Нечего открывать — жест не ставится.
 */
struct ПотянутьКСледующему: ViewModifier {
    let подтягивание: ПодтягиваниеКСледующему
    /// Есть следующее — жест стоит.
    let включено: Bool
    let перейти: () -> Void
    @GestureState private var тянут = false

    /// Явный init: ставит ядро карточки из другого файла, а закрытое состояние жеста прячет поэлементный.
    init(подтягивание: ПодтягиваниеКСледующему, включено: Bool, перейти: @escaping () -> Void) {
        self.подтягивание = подтягивание
        self.включено = включено
        self.перейти = перейти
    }

    func body(content: Content) -> some View {
        content
            .simultaneousGesture(тянуть, including: включено ? .all : .subviews)
            .onChange(of: тянут) { _, стало in
                if !стало { подтягивание.жестСнят() }
            }
    }

    private var тянуть: some Gesture {
        DragGesture(minimumDistance: 14, coordinateSpace: .global)
            .updating($тянут) { _, идёт, _ in идёт = true }
            .onChanged { касание in подтягивание.палец(касание.translation) }
            .onEnded { _ in
                if подтягивание.отпустили() { перейти() }
            }
    }
}


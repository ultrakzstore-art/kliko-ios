/**
 «Следующее объявление» внизу карточки: линия, заголовок, мини-карточка (фото, название, цена, город) и подсказка
 «Потяните вверх или нажмите» с кружком натяга. Он же меряет натяг: низ блока — низ содержимого прокрутки.
 */
struct БлокСледующегоОбъявления: View {
    let товар: Listing
    /// Низ видимой части прокрутки в её координатах (ПрокруткаСтраницыОбъявления); nil — без подтягивания (прежний вид).
    let низВидимого: CGFloat?
    /// Без подписки: натяг меняется почти каждый кадр, и перерисовываться должна только подсказка с кружком
    /// (ПодсказкаПодтягивания), а не мини-карточка.
    let подтягивание: ПодтягиваниеКСледующему
    let открыть: () -> Void

    private static let фото: CGFloat = 76

    /// Явный init: блок создают страница сайта и ядро карточки из других файлов.
    init(товар: Listing, низВидимого: CGFloat?, подтягивание: ПодтягиваниеКСледующему, открыть: @escaping () -> Void) {
        self.товар = товар
        self.низВидимого = низВидимого
        self.подтягивание = подтягивание
        self.открыть = открыть
    }

    var body: some View {
        VStack(alignment: .leading, spacing: 0) {
            Theme.линия
                .frame(height: 1)
                .accessibilityHidden(true)
            Text(ListingPageText.т("next_title"))
                .font(.system(size: 15, weight: .heavy))
                .foregroundStyle(Theme.текст)
                .padding(.top, 16)
                .accessibilityAddTraits(.isHeader)
            Button(action: открыть) { карточка }
                .buttonStyle(НажатиеПанелиСайта(сжатие: ДвижениеСайта.сжатие))
                .padding(.top, 12)
                .accessibilityLabel(ListingPageText.т("next_title") + ": " + товар.голос)
            if низВидимого != nil {
                ПодсказкаПодтягивания(подтягивание: подтягивание)
                    .padding(.top, 14)
            }
        }
        .padding(.horizontal, 20)
        .padding(.top, 12)
        .padding(.bottom, 32)
        .background { замер }
    }

    private var карточка: some View {
        HStack(spacing: 12) {
            Theme.линия.opacity(0.4)
                .frame(width: Self.фото, height: Self.фото)
                .overlay {
                    КартинкаЛенты(товар.обложка, пунктов: Self.фото) {
                        Color.clear
                    }
                }
                .clipShape(RoundedRectangle(cornerRadius: Theme.Радиус.ms, style: .continuous))
            VStack(alignment: .leading, spacing: 4) {
                Text(товар.title)
                    .font(.system(size: 14, weight: .semibold))
                    .foregroundStyle(Theme.текст)
                    .lineLimit(2)
                    .multilineTextAlignment(.leading)
                if let цена {
                    Text(цена)
                        .font(.system(size: 15, weight: .heavy))
                        .foregroundStyle(Theme.текст)
                        .lineLimit(1)
                        .minimumScaleFactor(0.8)
                }
                if !товар.city.isEmpty {
                    Text(товар.city)
                        .font(.system(size: 12))
                        .foregroundStyle(Theme.текстВторой)
                        .lineLimit(1)
                }
            }
            Spacer(minLength: 4)
            Image(systemName: "chevron.down")
                .font(.system(size: 14, weight: .semibold))
                .foregroundStyle(Theme.текстВторой)
                .accessibilityHidden(true)
        }
        .padding(10)
        .frame(maxWidth: .infinity, alignment: .leading)
        .background(Theme.поверхность2, in: RoundedRectangle(cornerRadius: Theme.Радиус.md, style: .continuous))
        .overlay {
            RoundedRectangle(cornerRadius: Theme.Радиус.md, style: .continuous)
                .strokeBorder(Theme.линия, lineWidth: 1)
        }
        .contentShape(RoundedRectangle(cornerRadius: Theme.Радиус.md, style: .continuous))
    }

    /// Как у похожих: у услуг цены нет; аренда — за сутки; без цены — «Договорная» или «Цена по запросу».
    private var цена: String? {
        товар.услуга ? nil : ListingCard.цена(товар)
    }

    /// Натяг: низ видимой части минус низ блока (он последний в содержимом). Мельче пункта не шлём, а далеко от низа —
    /// одно и то же -1: при обычной прокрутке замер молчит.
    @ViewBuilder
    private var замер: some View {
        if let низ = низВидимого {
            GeometryReader { г in
                let перетяжка = низ - г.frame(in: NamedCoordinateSpace.named(ПрокруткаСтраницыОбъявления.имя)).maxY
                Color.clear
                    .onChange(of: max(-1, перетяжка.rounded()), initial: true) { _, стало in
                        подтягивание.замер(стало)
                    }
            }
        }
    }
}


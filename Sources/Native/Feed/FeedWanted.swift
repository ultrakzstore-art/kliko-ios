import SwiftUI

/**
 «Ищу» в поиске (пачка 83, §16 «В обе стороны»; docs/SERVER_NEW_FOR_MINE.md §16.3.8 — «Ищу» до сервера).

 Человек ищет «зимние шины 205/55r16», «матрас 160х200», «лампа е27», «кронштейн 400x400», «ddr4 sodimm» — в запросе
 узнаётся стандарт, и над выдачей (в том числе над пустой) встаёт кнопка «Ищу шины 205/55 R16». Нажатие — тот же лист
 «Ищу», что у разделов «Моего» (ИщуМоего, MyThings/MyThingsWanted.swift): что именно (если вариантов несколько), «до
 какой цены», состояние, название поиска ровно как в «Сохранённых поисках» и «Сохранить поиск».

 Польза против колокольчика «Сохранить поиск»: слово поиска — значение стандарта так, как его пишут в названиях
 («205/55 R16», а не «205/55r16» или «205 55 16»), и раздел стандарта, даже если искали во всех разделах. Это
 существующий сохранённый поиск (SavedSearchStore, subs.php у вошедшего, фоновая проверка у гостя) — новых адресов нет.
 Публичный запрос продавцам (wanted_put, §16.3.2) — только за рубильником wanted_std; ключа в белом списке настроек
 сервера в этой сборке нет, поэтому здесь его не зовём.

 Стандарта в запросе нет — кнопки нет: обычный поиск сохраняет колокольчик. Сезон и прочие слова запроса в слово поиска
 не идут: subs.php ищет по слову, и «зимние 205/55 R16» не нашло бы «Шины 205/55 R16 зимние» — подпись честно говорит
 только то, что сохранится. «Моё» здесь не читается: только то, что человек сам набрал.
 */
@MainActor
enum ИщуПоиска {
    /// Те же условия, что у «Ищу» в «Моём»: его лист, рубильник и сохранённые поиски.
    static var доступно: Bool { ИщуМоего.доступно }

    /// Последний разобранный запрос: body ленты пересчитывается часто, а разбор — регулярные выражения.
    private static var ключПамяти = ""
    private static var памятьЗапроса: ЗапросИщуМоего? = nil

    /// «Ищу» для поиска ленты: варианты по стандартам, узнанным в тексте запроса; нет — nil.
    static func запрос(_ искомое: ИскомоеЛенты) -> ЗапросИщуМоего? {
        guard доступно else { return nil }
        let текст: String = искомое.текст.trimmingCharacters(in: .whitespacesAndNewlines)
        guard текст.count >= 2, текст.count <= 120 else { return nil }
        let ключ: String = искомое.раздел + "|" + текст
        if ключ == ключПамяти { return памятьЗапроса }
        let новый: ЗапросИщуМоего? = собрать(текст, раздел: искомое.раздел)
        ключПамяти = ключ
        памятьЗапроса = новый
        return новый
    }

    private static func ф(_ ключ: String, _ аргумент: String) -> String { ИщуМоегоText.ф(ключ, аргумент) }

    private static func собрать(_ текст: String, раздел: String) -> ЗапросИщуМоего? {
        var варианты: [ВариантИщуМоего] = []
        if let шины = вариантШин(текст, раздел: раздел) { варианты.append(шины) }
        let стандарты: [ВариантИщуМоего] = вариантыСтандартов(текст, раздел: раздел)
        варианты.append(contentsOf: стандарты)
        return ЗапросИщуМоего(варианты)
    }

    /// Раздел поиска, если он внутри раздела стандарта (уже уточнён), иначе — раздел стандарта.
    private static func разделДля(_ свой: String, _ цель: String) -> String {
        let внутри: Bool = РазделыСайта.внутри(свой, [цель])
        return внутри ? свой : цель
    }

    /// Шины: размер с косой («205/55r16», «205/55 р16», «205/55-16»); в разделе шин и дисков — и «205 55 16».
    private static func вариантШин(_ текст: String, раздел: String) -> ВариантИщуМоего? {
        let нормальный: String = ПарсерАвтоподбора.нормально(текст)
        let вРазделеШин: Bool = РазделыСайта.внутри(раздел, СовместимостьМоего.разделыАвто)
        var найден: РазмерШиныАвтоподбора? = ПарсерАвтоподбора.размерыШин(нормальный).first
        if найден == nil && вРазделеШин { найден = РазмерШиныАвтоподбора.изВвода(текст) }
        guard let размер = найден, размер.годный else { return nil }
        let подпись: String = размер.подпись
        let цель: String = вРазделеШин ? раздел : "tires-wheels"
        return ВариантИщуМоего(подпись: ф("iw_tyres", подпись), раздел: цель, слово: подпись)
    }

    /**
     Стандарты дома и компьютера по словам запроса (РазборСтандартов.семьи и разбор текста — те же, что у объявлений):
     матрас по размеру спального места, простыня на резинке — бельё, цоколь — лампы, VESA — кронштейн, поколение памяти (и форма,
     если названа) — память. Слово поиска — само значение, как в «Ищу» из «Моего»: без слов языка.
     */
    private static func вариантыСтандартов(_ текст: String, раздел: String) -> [ВариантИщуМоего] {
        guard Config.стандарты else { return [] }
        let свой: String? = раздел.isEmpty ? nil : раздел
        let семьи: Set<СемьяСтандарта> = РазборСтандартов.семьи(раздел: свой, название: текст)
        guard !семьи.isEmpty else { return [] }
        let разбор = РазборСтандартов.разобрать(текст: текст, семьи: семьи, источник: .название)
        let н: НаборСтандартов = разбор.набор
        var итог: [ВариантИщуМоего] = []
        /* Размер матраса ставит разбор только при слове «матрас» (и родственных) — у «кровать 160x200» варианта нет. */
        if let место = н[.матрас, КлючСтандарта.размер] {
            let показ: String = КаталогСтандартов.показ(место)
            итог.append(ВариантИщуМоего(подпись: ф("iw_mattress", показ), раздел: разделДля(раздел, "beds"),
                                        слово: место))
        }
        if let резинка = н[.бельё, КлючСтандарта.наРезинке] {
            let показ: String = КаталогСтандартов.показ(резинка)
            итог.append(ВариантИщуМоего(подпись: ф("iw_bedding", показ), раздел: разделДля(раздел, "bedding"),
                                        слово: резинка))
        }
        if let код = н[.цоколь, КлючСтандарта.цоколь] {
            итог.append(ВариантИщуМоего(подпись: ф("iw_lamps", код), раздел: разделДля(раздел, "lighting"),
                                        слово: код))
        }
        if let шаблон = н[.vesa, КлючСтандарта.шаблон] {
            let показ: String = КаталогСтандартов.показ(шаблон)
            итог.append(ВариантИщуМоего(подпись: ф("iw_mount", показ), раздел: разделДля(раздел, "tv-audio"),
                                        слово: шаблон))
        }
        if let поколение = н[.память, КлючСтандарта.поколение] {
            var поля: [String: String] = [КлючСтандарта.поколение: поколение]
            if let форма = н[.память, КлючСтандарта.форма], форма != "soldered" { поля[КлючСтандарта.форма] = форма }
            let набор = НаборСтандартов(значения: [СемьяСтандарта.память.rawValue: поля])
            let слово: String = РазборСтандартов.запрос(набор, .память)
            итог.append(ВариантИщуМоего(подпись: ф("iw_ram", слово), раздел: разделДля(раздел, "ram"), слово: слово))
        }
        return итог
    }
}

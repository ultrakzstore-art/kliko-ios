import Foundation

/**
 СОСТОЯНИЕ НАТИВНОЙ ЛЕНТЫ: страницы, поиск, раздел, ошибки.

 Порядок запуска: сначала лента с диска (ListingsCache) — мгновенно и без сети; следом запрос свежей; пришла —
 подменяем. Не пришла, а на экране уже есть что листать, — ошибку не показываем крупно: человек листает
 вчерашнее, а внизу строка «нет связи».

 Порядок на экране (владелец 26.09.2026: «по умолчанию новые + 3 ТОП и 10 бесплатных»): сетка рисует не items, а
 `лента` — ячейки, расставленные как у сайта (ЗолотойРитм, FeedRhythm.swift): при «Новых» — золотые блоки ТОП через
 обычные по новизне, при прочих порядках — порядок сервера. Ячейки только дописываются по мере прихода страниц:
 показанное при прокрутке и перерисовке не двигается. Потянули вниз — новый посев, и ТОП-места меняются.
 */
@MainActor
final class FeedModel: ObservableObject {
    /// Всё загруженное, без повторов, в порядке ответа сервера — для «Вы смотрели», поиска, уточнения и карты.
    @Published private(set) var items: [Listing] = []
    /// Что показывает сетка: ячейки в порядке витрины сайта (ЗолотойРитм). Одно объявление бывает в двух ячейках — в
    /// золотом месте и в обычном, поэтому у ячеек свой ключ.
    @Published private(set) var лента: [ЯчейкаЛенты] = []
    @Published private(set) var грузим = false
    @Published private(set) var ошибка: ListingsAPI.Ошибка?
    /// На экране лента с диска, а не свежая.
    @Published private(set) var сДиска = false
    /// Ответ на запрос уже был — удачный или с ошибкой. Без него пустой ответ («ничего не нашлось») не отличить
    /// от «ещё грузим», и пустой поиск навсегда оставался бы серыми карточками.
    @Published private(set) var ответПришёл = false
    @Published var поиск = ""
    @Published private(set) var раздел = ""
    /// Уточнение по загруженному (этап 18): город, цена, «только новые» — отбор того, что уже пришло, только для
    /// показа. Сменили — счёт пустых подгрузок заново: новое условие заслуживает своих попыток.
    @Published var уточнение = УточнениеЛенты() {
        didSet { if уточнение != oldValue { пустыхПодряд = 0 } }
    }
    /// Подгрузки под уточнением подряд, после которых на экране не прибавилось ни одной карточки (этап 18).
    @Published private(set) var пустыхПодряд = 0
    /// Фильтры и сортировка на сервере (этап 33) — что отберёт api/listings.php. Меняют лист «Фильтры», «Сначала
    /// показывать» и чипы над выдачей; каждое изменение — выдача заново с первой страницы.
    @Published private(set) var фильтры = ФильтрыЛенты()
    /// Всего объявлений по запросу (total первой страницы) — «Показать N» в листе фильтров (этап 33). nil — не пришло.
    @Published private(set) var всего: Int?
    /// Этап 49: «Показать все объявления» — лента всех объявлений вместо главной (MH.all сайта, ?all=1). Сбрасывает его
    /// «Главная» нижней панели (mhGoHome); раздел и поиск его не трогают — как у сайта, «Все» в полосе разделов вернёт
    /// во всю ленту, а не на главную.
    @Published private(set) var все = false
    /// Режим «Аренда» (mkVertical('rent') сайта, mkSt.intent = "rent"): запрос с intent=rent, в ленте только сдаваемое,
    /// цена карточек — за сутки или месяц (FeedModes.swift).
    @Published private(set) var аренда = false
    /// «Рядом со мной» (mkSt.near сайта): лента по расстоянию от человека (FeedModes.swift). Точку даёт ГеоЛенты.
    @Published private(set) var рядом = false

    private var запрос = ListingsAPI.Запрос()
    private var естьЕщё = true
    private var задача: Task<Void, Never>?
    /// Номер последнего запроса: ответ на прежний (сменили раздел, искомое, потянули вниз) уже не про то, что на экране.
    private var поколение = 0
    /// Ритм «Новых» этой выдачи — такт, очередь ТОП и место в такте между страницами; nil — порядок не «Новые».
    private var ритм: ЗолотойРитм.Состояние?
    /// Сколько раз потянули вниз — добавка к посеву сайта (номер пятиминутки): каждое обновление меняет ТОП-места.
    private var обновлений: Int32 = 0

    init() {
        if let сохранённые = ListingsCache.прочитать() {
            items = сохранённые
            сДиска = true
            начатьЛенту(сохранённые, запрос: запрос, последняя: false)
        }
    }

    /// «Потянуть — обновить»: как перезагрузка страницы сайта — с первой страницы и с новым посевом ТОП-мест.
    func потянули() async {
        обновлений &+= 1
        await обновить()
    }

    /// Первый показ: свежая лента, если на экране пусто или лента с диска.
    func начать() async {
        guard items.isEmpty || сДиска else { return }
        await обновить()
    }

    /// Потянули вниз, сменили раздел или искомое — с первой страницы.
    func обновить() async {
        запрос.page = 1
        запрос.q = поиск.trimmingCharacters(in: .whitespacesAndNewlines)
        запрос.cat = раздел
        /* Этап 32: город — на момент первой страницы; подгрузка следующих несёт тот же, и лента не смешивает города. */
        запрос.где = ГдеИскать.сохранённое()
        /* Этап 33: фильтры и страница по 48, как у сайта; gs — от ответа этой, новой первой страницы. Рубильник
           выключен — прежний запрос: sort=reco, per=24. */
        запрос.фильтры = Config.фильтрыНаСервере ? фильтры : ФильтрыЛенты()
        запрос.per = Config.фильтрыНаСервере ? ФильтрыЛенты.наСтранице : 24
        запрос.gs = nil
        запрос.аренда = аренда
        естьЕщё = true
        await загрузить(сброс: true)
    }

    /// Сменили город или район (этап 32): выдача — другого места, с первой страницы. Уточнение по загруженному (этап 18)
    /// было про объявления прежнего места — с чистого листа.
    func сменилсяГород() {
        уточнение = УточнениеЛенты()
        перезапустить()
    }

    func выбратьРаздел(_ ключ: String) {
        /* «Все» в режиме аренды — выход из него (у сайта «Все» режим не снимает, и выйти можно только «Главной»). Прочие
           разделы режим сохраняют, как mkVertical сайта: снимает он только «Купить» (intent sale). */
        if аренда && ключ.isEmpty {
            аренда = false
            if раздел.isEmpty {
                перезапустить()
                return
            }
        }
        guard ключ != раздел else { return }
        раздел = ключ
        уточнение = УточнениеЛенты()        // этап 18: другой раздел — другие города и цены, прежний отбор не про него
        /* Этап 33: как mkResetCatFilters сайта — цена, год и комнаты были про прежний раздел; сортировка, состояние,
           «Проверенные» и «Только с фото» остаются. */
        фильтры = фильтры.дляНовогоРаздела()
        перезапустить()
    }

    func искать() {
        уточнение = УточнениеЛенты()        // этап 18: новый поиск — уточнение с чистого листа
        перезапустить()
    }

    // MARK: - Сохранённые поиски (этап 12)

    /// Что в ленте на самом деле — отправленный поиск и раздел, а не то, что набрано в поле: колокольчик «Сохранить
    /// поиск» сохраняет именно это. Меняется вместе с запросом, поэтому всегда про ту выдачу, что на экране или в пути.
    /// Этап 33: и цена с состоянием запроса — то, что сайт кладёт в сохранённый поиск (pmin, pmax, cond).
    var действующее: ИскомоеЛенты {
        let ф = запрос.фильтры
        return ИскомоеЛенты(текст: запрос.q, раздел: запрос.cat, ценаОт: ф.ценаОт, ценаДо: ф.ценаДо,
                            состояние: ф.состояние?.rawValue ?? "")
    }

    /// Главная — ни поиска, ни раздела, ни фильтров в запросе (этап 33: отобранная лента — уже выдача, как у сайта, а не
    /// главная с плитками). Сортировка главную не отменяет. Этап 49: и не «все объявления» (MH.all), и без района — у сайта
    /// district не в MH_NEUTRAL, и с районом главной нет (mkHomeWant), сразу лента.
    var наГлавной: Bool {
        !все && !запрос.аренда && действующее.пустое && запрос.фильтры.пустые && запрос.где.район.isEmpty
    }

    /// «Показать все объявления» (mkHomeAll): лента уже загружена под главной — просто показать её.
    func показатьВсе() {
        guard !все else { return }
        все = true
    }

    /// «Сбросить всё» у пустой выдачи (mkReset): поиск, раздел и фильтры — сначала; порядок и «все объявления» остаются.
    func сброситьВсё() {
        поиск = ""
        раздел = ""
        аренда = false
        рядом = false
        уточнение = УточнениеЛенты()
        var новые = ФильтрыЛенты()
        новые.сортировка = фильтры.сортировка
        фильтры = Config.фильтрыНаСервере ? новые : ФильтрыЛенты()
        перезапустить()
    }

    /// На экране — готовая выдача именно действующего поиска: ответ пришёл, без ошибки, не с диска, ничего не в пути.
    /// Тогда её номера — точка отсчёта сохранённого поиска: их человек уже видел.
    /// Этап 33: и выдача та же, что проверит фоновая проверка, — без сортировки и фильтров, которых сохранённый поиск не
    /// несёт («Проверенные», фото, год, комнаты): иначе всё, что они отсеяли, первая проверка выдала бы за новое.
    var выдачаГотова: Bool { ответПришёл && ошибка == nil && !грузим && !сДиска && запрос.фильтры.какУСохранённого }

    /// Сохранённый поиск снаружи (уведомление о новых, строка кабинета) — текст в поле и раздел разом, с первой страницы.
    /// Этап 33: и его цена с состоянием; прочие фильтры — сначала, как у ссылки на поиск сайта. «Главная» нижней панели
    /// приходит сюда же пустым поиском — и сбрасывает всё.
    func применить(_ искомое: ИскомоеЛенты) {
        поиск = искомое.текст
        раздел = искомое.раздел
        все = false                         // этап 49: «Главная» (mhGoHome) и вход снаружи — не «все объявления»
        аренда = false                      // «Главная» и сохранённый поиск — без режима аренды и «Рядом»
        рядом = false
        уточнение = УточнениеЛенты()        // этап 18
        фильтры = Config.фильтрыНаСервере ? ФильтрыЛенты(искомое: искомое).годные(для: искомое.раздел) : ФильтрыЛенты()
        перезапустить()
    }

    // MARK: - Фильтры на сервере (этап 33)

    /// Уточнение по загруженному (этап 18) — только без фильтров на сервере: они отбирают по всему сайту, и второй отбор
    /// поверх них только путал бы.
    static var уточнениеНаТелефоне: Bool { Config.уточнениеЛенты && !Config.фильтрыНаСервере }

    /// Новые фильтры из листа, «Сначала показывать» или «×» чипа. Чего у раздела нет (год, комнаты), не шлём; то же самое
    /// — не перезапрашиваем.
    func применитьФильтры(_ новые: ФильтрыЛенты) {
        guard Config.фильтрыНаСервере else { return }
        let чистые = новые.годные(для: раздел)
        guard чистые != фильтры else { return }
        фильтры = чистые
        перезапустить()
    }

    func выбратьСортировку(_ сортировка: СортировкаЛенты) {
        var новые = фильтры
        новые.сортировка = сортировка
        применитьФильтры(новые)
    }

    /// «×» на чипе над выдачей.
    func убратьФильтр(_ вид: ВидФильтра) {
        /* Поиск, раздел и «Рядом» — чипы той же строки (mkRemove сайта), но не фильтры. */
        switch вид {
        case .запрос:
            поиск = ""
            искать()
            return
        case .раздел:
            выбратьРаздел("")
            return
        case .рядом:
            задатьРядом(false)
            return
        default:
            break
        }
        var новые = фильтры
        новые.убрать(вид)
        применитьФильтры(новые)
    }

    /// «Сбросить» в листе и «Сбросить всё» у чипов: без фильтров. Порядок остаётся — mkReset сайта «Сначала показывать»
    /// не трогает; поиск, раздел и город — тоже прежние (у них свои места на экране).
    func сброситьФильтры() {
        var новые = ФильтрыЛенты()
        новые.сортировка = фильтры.сортировка
        применитьФильтры(новые)
    }

    /// Поле поиска очистили — вернуть ленту, но только если по ней уже искали: иначе лишний запрос на каждое открытие поля.
    func поискОчищен() {
        guard !запрос.q.isEmpty else { return }
        уточнение = УточнениеЛенты()        // этап 18
        перезапустить()
    }

    /// Дошли до последней карточки — следующая страница.
    ///
    /// Этап 18: под уточнением последней на экране бывает не последняя загруженная — та отсеяна и onAppear не получит.
    /// Поэтому подгрузку запускает и последняя ВИДИМАЯ карточка; иначе лента под уточнением застряла бы на первой
    /// странице. Без уточнения видимые и загруженные — одно и то же, и условие прежнее.
    func дальше(после товар: Listing) {
        guard естьЕщё, !грузим, ошибка == nil else { return }
        /* Последняя в сетке — последняя ячейка ленты (порядок витрины), а не последняя пришедшая с сервера. */
        guard товар.id == лента.last?.товар.id || (уточнено && товар.id == видимыеЯчейки.last?.товар.id) else { return }
        запрос.page += 1
        задача = Task { await загрузить(сброс: false) }
    }

    // MARK: - Уточнение по загруженному (этап 18)

    /// После стольких подгрузок подряд без единой подходящей карточки сами больше не листаем — ждём «Искать дальше»:
    /// редкий город иначе выкачал бы всю ленту сайта, страница за страницей.
    static let пустыхПодрядПредел = 3

    /// Уточнение задано (и рубильник включён, а фильтров на сервере нет — этап 33).
    var уточнено: Bool { Self.уточнениеНаТелефоне && !уточнение.пустое }

    /// Что показывать: загруженное, отобранное уточнением. Без уточнения — всё загруженное.
    var видимые: [Listing] {
        guard уточнено else { return items }
        let у = уточнение
        return items.filter { у.подходит($0) }
    }

    /// Ячейки сетки, отобранные уточнением; без уточнения — вся лента.
    var видимыеЯчейки: [ЯчейкаЛенты] {
        guard уточнено else { return лента }
        let у = уточнение
        return лента.filter { у.подходит($0.товар) }
    }

    /// Есть ли у ленты следующая страница — «Искать дальше» под уточнением без неё не нужна.
    var можноЕщё: Bool { естьЕщё }

    /// Этап 49: в пути следующая страница, а не первая — «Подгружаем ещё объявления» у плашки (mkLoadBar сайта).
    var грузимЕщё: Bool { грузим && запрос.page > 1 }

    /// Низ выдачи под уточнением на экране (отметка после сетки): подходящих мало, и последняя видимая карточка уже
    /// показана — onAppear второй раз она не получит. Подгружаем следующую страницу, пока не упёрлись в предел.
    func дальшеУточнённой() {
        guard уточнено, пустыхПодряд < Self.пустыхПодрядПредел, let последний = лента.last?.товар ?? items.last else { return }
        дальше(после: последний)
    }

    /// «Искать дальше» — человек сам просит ещё страницы, предел пустых подгрузок заново.
    func искатьДальше() {
        пустыхПодряд = 0
        guard let последний = лента.last?.товар ?? items.last else { return }
        дальше(после: последний)
    }

    private func перезапустить() {
        задача?.cancel()
        задача = Task { await обновить() }
    }

    private func загрузить(сброс: Bool) async {
        let з = запрос
        поколение += 1
        let номер = поколение
        грузим = true
        defer { if номер == поколение { грузим = false } }
        do {
            let (страница, сырое) = try await ListingsAPI.загрузить(з)
            /* Пока ехал ответ, человек сменил раздел или искомое — этот ответ уже не про то, что на экране. */
            guard номер == поколение, !Task.isCancelled else { return }
            ошибка = nil
            /* Этап 33: следующая страница — по has_more ответа, как у сайта (_mkMore = !!n.has_more); не пришёл — по
               размеру страницы, как раньше. Решаем до раскладки: последняя страница дочитывает хвост ритма. */
            if Config.фильтрыНаСервере, let ещё = страница.hasMore {
                if !ещё || страница.items.isEmpty { естьЕщё = false }
            } else if страница.items.count < з.per {
                естьЕщё = false
            }
            if сброс {
                items = страница.items
                начатьЛенту(страница.items, запрос: з, последняя: !естьЕщё)
                сДиска = false
                ответПришёл = true
                всего = страница.total
                /* Этап 33: gs первой страницы — следующим страницам этой выдачи, как window._mkGoldSnap сайта. */
                if Config.фильтрыНаСервере { запрос.gs = страница.gs }
                if з.поУмолчанию { ListingsCache.сохранить(сырое) }
            } else {
                /* Лента «рекомендаций» между запросами может сдвинуться, и объявление приедет второй раз. Два
                   одинаковых id в ForEach — это сломанная прокрутка, поэтому повторы отсекаем. */
                let были = Set(items.map(\.id))
                let виделиДо = уточнено ? видимые.count : 0
                let новые = страница.items.filter { !были.contains($0.id) }
                items.append(contentsOf: новые)
                дописатьЛенту(новые, последняя: !естьЕщё)
                /* Этап 18: под уточнением считаем подгрузки, после которых на экране ничего не прибавилось. */
                if уточнено { пустыхПодряд = видимые.count > виделиДо ? 0 : пустыхПодряд + 1 }
            }
        } catch let e as ListingsAPI.Ошибка {
            guard номер == поколение, !Task.isCancelled else { return }
            ответПришёл = true
            if сброс { всего = nil }
            ошибка = e
            if !сброс { запрос.page -= 1 }       // следующая попытка — за той же страницей
        } catch {
            guard номер == поколение, !Task.isCancelled else { return }
            ответПришёл = true
            if сброс { всего = nil }
            ошибка = .сеть
            if !сброс { запрос.page -= 1 }
        }
    }

    // MARK: - Порядок витрины (ЗолотойРитм)

    /// Первая страница выдачи: «Новые» — ритм сайта с новым посевом (номер пятиминутки плюс число обновлений) и тактом
    /// раздела; прочие порядки — порядок сервера.
    private func начатьЛенту(_ пришедшие: [Listing], запрос з: ListingsAPI.Запрос, последняя: Bool) {
        /* «Старые», «По рейтингу» и «Рядом» — порядок всего загруженного у себя, как mkRender сайта (FeedModes.swift). */
        if Self.порядокНаТелефоне(з.фильтры.сортировка, рядом: рядом) {
            ритм = nil
            лента = собратьНаТелефоне(з)
            return
        }
        let товары = Self.поРежиму(пришедшие, аренда: з.аренда)
        if з.фильтры.сортировка == .новые {
            let посев = ЗолотойРитм.посевСайта() &+ обновлений
            var состояние = ЗолотойРитм.Состояние(такт: ЗолотойРитм.Такт.для(раздела: з.cat), посев: посев)
            лента = состояние.принять(товары, последняя: последняя)
            ритм = состояние
        } else {
            ритм = nil
            лента = ЯчейкаЛенты.подряд(товары, начиная: 0, топ: Self.золотоБезРитма(з.фильтры.сортировка))
        }
    }

    /// Следующая страница — только в конец: показанные ячейки не двигаются.
    private func дописатьЛенту(_ пришедшие: [Listing], последняя: Bool) {
        if Self.порядокНаТелефоне(запрос.фильтры.сортировка, рядом: рядом) {
            лента = собратьНаТелефоне(запрос)
            return
        }
        let товары = Self.поРежиму(пришедшие, аренда: запрос.аренда)
        if var состояние = ритм {
            let новые = состояние.принять(товары, последняя: последняя)
            ритм = состояние
            if !новые.isEmpty { лента.append(contentsOf: новые) }
        } else if !товары.isEmpty {
            лента.append(contentsOf: ЯчейкаЛенты.подряд(товары, начиная: лента.count,
                                                        топ: Self.золотоБезРитма(запрос.фильтры.сортировка)))
        }
    }

    /// Золото без ритма, как у mkRender сайта: «Рекомендуемые» — место от сервера (slot:"top", без него is_top);
    /// «Дешевле» и «Дороже» — без золота (_top=false у всех).
    private static func золотоБезРитма(_ сортировка: СортировкаЛенты) -> (Listing) -> Bool {
        switch сортировка {
        case .рекомендуемые:
            return { товар in
                if let слот = товар.слот { return слот == "top" }
                return товар.isTop
            }
        case .новые, .дешевле, .дороже, .старые, .поРейтингу:
            return { _ in false }
        }
    }

    // MARK: - Аренда и «Рядом» (FeedModes.swift)

    /// Плитка «Аренда» полосы разделов — mkVertical('rent'): фильтры раздела сначала (mkResetCatFilters), раздел —
    /// «все», режим аренды, выдача с первой страницы.
    func выбратьАренду() {
        guard !аренда else { return }
        аренда = true
        раздел = ""
        уточнение = УточнениеЛенты()
        фильтры = фильтры.дляНовогоРаздела()
        перезапустить()
    }

    /// «Рядом со мной» включили или выключили (точку уже дала ГеоЛенты) — лента перестраивается из загруженного, без
    /// запроса: у сайта mkNearToggle тоже только перерисовывает (mkRender).
    func задатьРядом(_ включить: Bool) {
        guard рядом != включить else { return }
        рядом = включить
        перестроитьЛенту()
    }

    /// Точка человека сменилась, пока включено «Рядом», — расстояния другие.
    func точкаСменилась() {
        guard рядом else { return }
        перестроитьЛенту()
    }

    private func перестроитьЛенту() {
        guard !items.isEmpty else { return }
        начатьЛенту(items, запрос: запрос, последняя: !естьЕщё)
    }

    /// Повтор после ошибки внизу ленты.
    func повторить() {
        ошибка = nil
        /* Ошибку сняли сразу, а задача стартует чуть позже: без сброса на пустом экране мелькнуло бы «ничего не нашлось». */
        if items.isEmpty { ответПришёл = false }
        if items.isEmpty || запрос.page == 1 { перезапустить() }
        else {
            запрос.page += 1
            задача = Task { await загрузить(сброс: false) }
        }
    }
}

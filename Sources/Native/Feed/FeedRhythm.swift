/**
 ПОРЯДОК ВИТРИНЫ КАК НА САЙТЕ — «НОВЫЕ» С ЗОЛОТЫМ РИТМОМ (владелец 26.09.2026: «по умолчанию новые + 3 ТОП и 10
 бесплатных (даже если они топ), весомо по очереди меняется только ТОП плашки»).

 Откуда правила — js/marketplace.min.js сайта (26.09.2026):
   · порядок по умолчанию — «Новые»: <select id="mk-sort"> с <option value="date" selected>, mkSt.sort:"date";
     запрос ленты при этом несёт sort=reco (_mkApiQS в js/marketplace-feed.min.js: в карте {reco, price_asc,
     price_desc, date_asc, date_desc} значения "date" нет, и оно уходит как "reco");
   · mkRender, ветка sort=="date" (и не «Избранное»): ТОП = mkTopsSorted(всё загруженное), обычные — всё, что не
     ТОП, по g(t)=fresh_ts||created_ts от новых к старым; вместе — mkGoldRhythm(ТОП, обычные);
   · mkGoldBeat — такт: 3 ТОП, затем 10 обычных; у транспорта и недвижимости (mkRootSection раздела) — 1 и 5;
   · mkGoldRhythm — блок ТОП идёт ПЕРВЫМ, до первой обычной карточки; ТОП берутся по очереди, а кончились — по кругу
     (m % i), без повтора внутри одного блока; ТОП вовсе нет — блоков нет. Обычные кончились — оставшиеся ТОП идут
     дальше обычными местами;
   · mkTopsSorted — ТОП = is_top и не is_active:false; перемешаны mkShuffle с посевом ROTATE_SLOT (номер
     пятиминутки: floor(unix/300), сайт кладёт его в страницу), затем устойчиво по imp от меньшего к большему: ТОП,
     который показывали реже, идёт в золотое место первым. «Весов» пакетов у сайта нет — очередь ТОП задают imp
     (просмотры золотой карточки, rank_event.php) и посев пятиминутки;
   · mkShuffle — Фишер — Йетс с конца, генератор mkPRNG (ниже, бит в бит);
   · прочие порядки: «Дешевле», «Дороже» — порядок сервера, и золото с карточек снято (_top=false у всех);
     «Рекомендуемые» — ТОП там, куда их поставил сервер (slot:"top", а без него is_top).

 Отличия от сайта — по слову владельца и ради того, чтобы лента не прыгала:
   · «10 бесплатных (даже если они топ)»: обычные места — ВСЕ объявления по новизне, ТОП тоже, на своём месте по
     дате и без золота. Сайт ТОП из обычных выкидывает. Поэтому и хвост другой: когда обычные кончились, ТОП, ещё не
     бывшие в золотом месте, дочитываются золотыми блоками, а не обычными местами (обычными они уже прошли);
   · сайт при каждой подгрузке перестраивает ВСЮ ленту заново (новые ТОП со второй страницы переставляют и первую).
     Здесь ритм идёт по мере прихода страниц: показанное не двигается, такт, очередь ТОП и круг продолжаются; ТОП новой
     страницы встают в очередь после ещё не показанных; обычные новой страницы — по новизне между собой, после прежних;
   · «Потянуть — обновить» — как перезагрузка страницы сайта, но с другим посевом (номер пятиминутки плюс число
     обновлений): у сайта в ту же пятиминутку перемешивание то же, меняет порядок только imp, а владелец ждёт, что ТОП
     сменятся.
 */
enum ЗолотойРитм {

    /// Такт — mkGoldBeat: сколько ТОП подряд и сколько обычных между блоками.
    struct Такт: Equatable, Sendable {
        let топ: Int
        let обычных: Int

        /// Раздел ленты → такт: транспорт и недвижимость — {g:1, f:5}, всё прочее — {g:3, f:10}.
        static func для(раздела раздел: String) -> Такт {
            let корень = РазделыСайта.корень(раздел)
            if корень == "transport" || корень == "realty" { return Такт(топ: 1, обычных: 5) }
            return Такт(топ: 3, обычных: 10)
        }
    }

    /// Посев сайта ROTATE_SLOT — номер пятиминутки unix-времени.
    static func посевСайта(_ дата: Date = Date()) -> Int32 {
        let пятиминутка = (дата.timeIntervalSince1970 / 300).rounded(.down)
        guard пятиминутка.isFinite, abs(пятиминутка) < 1e15 else { return 1 }
        return Int32(truncatingIfNeeded: Int64(пятиминутка))
    }

    /**
     mkPRNG сайта бит в бит: t=0|t||1; t=t+1831565813|0; e=imul(t^t>>>15, 1|t); e=(e+imul(e^e>>>7, 61|e))^e;
     ((e^e>>>14)>>>0)/2^32. Всё в UInt32 с переносом: imul и «|0» — те же младшие 32 бита.
     */
    struct Генератор {
        private var t: UInt32

        init(посев: Int32) {
            t = посев == 0 ? 1 : UInt32(bitPattern: посев)
        }

        mutating func следующее() -> Double {
            t = t &+ 1_831_565_813
            var e = (t ^ (t >> 15)) &* (1 | t)
            e = (e &+ ((e ^ (e >> 7)) &* (61 | e))) ^ e
            let итог = e ^ (e >> 14)
            return Double(итог) / 4_294_967_296
        }
    }

    /// mkShuffle сайта: копия, Фишер — Йетс от последнего к первому, i = floor(rnd * (r + 1)).
    static func перемешать<T>(_ список: [T], посев: Int32) -> [T] {
        var итог = список
        guard итог.count > 1 else { return итог }
        var генератор = Генератор(посев: посев)
        var r = итог.count - 1
        while r > 0 {
            let i = min(r, Int((генератор.следующее() * Double(r + 1)).rounded(.down)))
            if i != r { итог.swapAt(r, i) }
            r -= 1
        }
        return итог
    }

    /// ТОП для золотых мест — mkTopsSorted: is_top и не снятые, без повторов, перемешаны посевом и устойчиво по imp.
    static func очередьТОП(_ товары: [Listing], посев: Int32) -> [Listing] {
        var были = Set<String>()
        var топ: [Listing] = []
        for товар in товары where товар.isTop && товар.активно && !были.contains(товар.id) {
            были.insert(товар.id)
            топ.append(товар)
        }
        let перемешанные = перемешать(топ, посев: посев)
        return перемешанные.enumerated()
            .sorted { a, b in
                if a.element.показыТопа != b.element.показыТопа { return a.element.показыТопа < b.element.показыТопа }
                return a.offset < b.offset
            }
            .map { $0.element }
    }

    /// Обычные места — все объявления по свежести (fresh_ts, иначе created_ts) от новых к старым; равные — в порядке
    /// ответа сервера.
    static func поНовизне(_ товары: [Listing]) -> [Listing] {
        товары.enumerated()
            .sorted { a, b in
                if a.element.свежесть != b.element.свежесть { return a.element.свежесть > b.element.свежесть }
                return a.offset < b.offset
            }
            .map { $0.element }
    }

    /**
     Порядок витрины «Новые» целиком — чистая функция: одинаковые объявления, такт и посев дают один и тот же порядок.

     Правила (mkGoldRhythm сайта с поправкой владельца, см. описание выше):
       1. Сначала блок из `такт.топ` ТОП-мест, потом `такт.обычных` обычных, и так по кругу.
       2. ТОП-места берут объявления по очереди `очередьТОП` (посев, затем imp); очередь кончилась — по кругу, без
          повтора внутри блока. ТОП нет — блоков нет, лента просто по новизне.
       3. Обычные места — все объявления по новизне, ТОП тоже (без золота).
       4. Обычные кончились — ТОП, ещё не бывшие в золотом месте, дочитываются золотыми блоками.
     Ключи ячеек уникальны: одно объявление может стоять и в золотом месте, и в обычном.
     */
    static func упорядочить(_ товары: [Listing], такт: Такт, посев: Int32) -> [ЯчейкаЛенты] {
        var состояние = Состояние(такт: такт, посев: посев)
        return состояние.принять(товары, последняя: true)
    }

    /**
     Тот же порядок по мере прихода страниц. Показанное не двигается: каждая страница только дописывает ячейки в конец.
     Страница кончилась посреди такта — такт ждёт следующую; новый золотой блок открывается, только когда за ним есть
     обычные (или это последняя страница). Одна и та же последовательность страниц даёт один и тот же порядок.
     */
    struct Состояние {
        let такт: Такт
        let посев: Int32
        /// Очередь ТОП (пул): уникальные, в порядке золотых мест.
        private var топ: [Listing] = []
        private var вОчередиТОП = Set<String>()
        /// Следующий ещё не бывший в золотом месте ТОП (l у сайта) и счётчик круга (m у сайта).
        private var следующийТОП = 0
        private var круг = 0
        /// Обычные, ждущие своих мест, и те, что уже приняты обычными (повтор со следующей страницы не берём).
        private var обычные: [Listing] = []
        private var вОбычных = Set<String>()
        /// Место в такте: 0..<топ — золотые, дальше — обычные.
        private var место = 0
        /// Какие номера очереди ТОП уже стоят в текущем блоке (u у сайта).
        private var вБлоке = Set<Int>()
        /// Сколько ячеек уже выдано — для уникальных ключей.
        private var выдано = 0

        init(такт: Такт, посев: Int32) {
            self.такт = Такт(топ: max(1, такт.топ), обычных: max(1, такт.обычных))
            self.посев = посев
        }

        /// Принять страницу и вернуть новые ячейки — их дописывают в конец ленты. `последняя` — страниц больше не будет:
        /// дочитать хвост.
        mutating func принять(_ товары: [Listing], последняя: Bool) -> [ЯчейкаЛенты] {
            let новыеТОП = ЗолотойРитм.очередьТОП(товары.filter { !вОчередиТОП.contains($0.id) }, посев: посев)
            for товар in новыеТОП {
                вОчередиТОП.insert(товар.id)
                топ.append(товар)
            }
            /* Владелец, TestFlight: «дубликат на витрине». Объявление ТОП, которое идёт в золотое место, в обычных
               местах не повторяется — как у сайта (mkRender: обычные — всё, что не ТОП). */
            for товар in ЗолотойРитм.поНовизне(товары) where !вОбычных.contains(товар.id) && !вОчередиТОП.contains(товар.id) {
                вОбычных.insert(товар.id)
                обычные.append(товар)
            }

            var итог: [ЯчейкаЛенты] = []
            var обычныйНомер = 0
            var шагов = 0
            let предел = (топ.count + обычные.count + 4) * (такт.топ + такт.обычных + 1)
            while шагов < предел {
                шагов += 1
                let осталосьОбычных = обычныйНомер < обычные.count
                if место < такт.топ {
                    if место == 0 {
                        /* Новый блок — только когда за ним есть обычные; на последней странице — пока есть ТОП, ещё не
                           бывшие в золоте. */
                        if !осталосьОбычных && (!последняя || следующийТОП >= топ.count) { break }
                        вБлоке = []
                    }
                    guard !топ.isEmpty else {
                        место = такт.топ
                        continue
                    }
                    var номер = -1
                    if следующийТОП < топ.count {
                        номер = следующийТОП
                        следующийТОП += 1
                    }
                    /* Очередь ТОП кончилась — золотых мест больше нет: по кругу не повторяем, чтобы одно объявление
                       не встречалось в ленте дважды. */
                    guard номер >= 0 else {
                        место = такт.топ
                        continue
                    }
                    вБлоке.insert(номер)
                    итог.append(ячейка(топ[номер], топ: true))
                    место += 1
                } else {
                    guard осталосьОбычных else {
                        /* Обычные кончились: не последняя страница — ждём следующую на том же месте такта; последняя —
                           к следующему блоку, он дочитает не бывшие в золоте ТОП. */
                        if !последняя { break }
                        место = 0
                        continue
                    }
                    итог.append(ячейка(обычные[обычныйНомер], топ: false))
                    обычныйНомер += 1
                    место += 1
                    if место >= такт.топ + такт.обычных { место = 0 }
                }
            }
            if обычныйНомер > 0 { обычные.removeFirst(обычныйНомер) }
            return итог
        }

        private mutating func ячейка(_ товар: Listing, топ: Bool) -> ЯчейкаЛенты {
            let ключ = String(выдано) + "-" + товар.id
            выдано += 1
            return ЯчейкаЛенты(id: ключ, товар: товар, топ: топ)
        }
    }
}

/// Ячейка сетки витрины: объявление и его место — золотое (ТОП) или обычное. Ключ уникален в ленте: одно объявление
/// бывает и в золотом месте, и в обычном.
struct ЯчейкаЛенты: Identifiable, Hashable {
    let id: String
    /// Объявление как пришло — его открывают, в избранное кладут и делятся им.
    let товар: Listing
    /// Стоит в ТОП-месте: золотая рамка и «★ ТОП» (_top сайта).
    let топ: Bool

    /// Что рисует карточка: то же объявление с золотом по месту, а не по is_top.
    var показ: Listing {
        var копия = товар
        копия.isTop = топ
        return копия
    }

    /// Порядок сервера без ритма (прочие порядки): ключ — номер и id, золото — по `топ`.
    static func подряд(_ товары: [Listing], начиная номер: Int, топ: (Listing) -> Bool) -> [ЯчейкаЛенты] {
        товары.enumerated().map { пара in
            ЯчейкаЛенты(id: String(номер + пара.offset) + "-" + пара.element.id, товар: пара.element,
                        топ: топ(пара.element))
        }
    }
}

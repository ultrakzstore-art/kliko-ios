/**
 ЦИФРОВЫЕ ТОВАРЫ — КЛЮЧИ И КОДЫ (ultra-site 16.10.2026, задание «Цифровые товары»; владелец 16.10.2026: «да не показывай
 цифровое» — вариант Ц1).

 На сайте появился раздел digital: игровые ключи, подарочные карты, лицензии, подписки по коду, электронные билеты. Код
 лежит в сейфе продавца и открывается покупателю в гарант-сделке (mode "digital"). Правило App Store 3.1.1: коды на
 цифровое в приложении продаются только покупкой Apple. Поэтому в приложении цифровое не подаётся, не покупается и не
 обсуждается в чате, а на сайт приложение не зовёт — ни ссылкой, ни словами.

 Что здесь:
   · Config.цифровоеВПриложении — показ цифрового в списках; в сборке выключен (Ц1). Ключ digital_show — стоп-кран, как
     у денег (RemoteSettings.swift): сервер может только выключить, а включить показ может лишь новая сборка, прошедшая
     App Review (2.3.1, 3.1.1). Окно такого объявления всегда без покупки и чата (Ц2, ПанельЦифровогоОбъявления);
   · ЦифровыеТовары.безЦифровых — одна общая функция-фильтр: её зовут разборы всех списков (ListingsPage — лента, поиск,
     похожие, витрина продавца, поиск по фото, сохранённые поиски; главная, пины карты, избранное, «Вы смотрели»).
     Объявление по номеру (?id=: ссылка, пуш, «Мои объявления») не отбрасывается — его окно без покупки (Ц2);
   · ЦифровыеТовары.цифровойРаздел — корень digital и его подразделы: вон из каталога и фильтров (пока показ выключен)
     и из подачи (всегда, Ц3);
   · digital_info и seller_digital объявления — терпимым разбором, как остальные поля Listing: не пришло, null или не
     тот вид — nil, объявление от этого не ломается;
   · СрокЦифровогоКода и Listing.можноПоделиться — актуальность (владелец 16.10.2026): «Поделиться» только у
     опубликованного с непрошедшим сроком кода (ниже, «АКТУАЛЬНОСТЬ ЦИФРОВОГО»).
 Сам код, инструкция активации и чек продавца в ленту и ?id= не приходят никогда — в приложении их нет.
 */
extension Config {
    /// Цифровые объявления в лентах, поиске, каталоге и на карте. Выключено (Ц1): отбрасываются при разборе ответа.
    static let цифровоеВПриложенииВСборке = false
    /// С учётом админки (раздел «iOS-приложение», ключ digital_show): только выключить. Выключено в сборке — выключено
    /// всегда, и настройки сервера даже не читаются.
    static var цифровоеВПриложении: Bool {
        НастройкиСервера.стопКран("digital_show", сборка: цифровоеВПриложенииВСборке)
    }
}

enum ЦифровыеТовары {
    /// Корневой раздел цифровых товаров в дереве сайта (MK_CATS).
    static let корень = "digital"
    /// mode гарант-сделки цифрового кода (escrow.php: my_deals, deal) — Ц4, DealDigital.swift.
    static let сделка = "digital"

    /// Показывать ли цифровое в списках. Читается один раз на список и только когда в нём есть цифровое.
    static var показывать: Bool { Config.цифровоеВПриложении }

    /// Общий фильтр списков: цифровые объявления — прочь, если показ выключен; порядок остальных прежний.
    static func безЦифровых(_ товары: [Listing]) -> [Listing] {
        безЦифровых(товары, объявление: { $0 })
    }

    /// Тот же фильтр для списков, где объявление лежит внутри записи (пин карты).
    static func безЦифровых<Т>(_ записи: [Т], объявление: (Т) -> Listing) -> [Т] {
        guard записи.contains(where: { объявление($0).цифровое }), !показывать else { return записи }
        return записи.filter { !объявление($0).цифровое }
    }

    /// Это объявление в списки не попадает: оно цифровое, а показ выключен.
    static func скрыто(_ товар: Listing) -> Bool {
        товар.цифровое && !показывать
    }

    /// Раздел дерева цифровой: сам корень digital или его родитель (корень записи схемы подачи) — digital. Глубже —
    /// по цепочке у того, кто строит дерево: подраздел скрытого раздела тоже скрыт.
    static func цифровойРаздел(_ ключ: String, родитель: String? = nil, корневой: String? = nil) -> Bool {
        ключ == Self.корень || родитель == Self.корень || корневой == Self.корень
    }
}

/// digital_info объявления: что за код и где он работает. Самого кода здесь нет и не будет.
struct ЦифровоеОписание: Hashable, Decodable {
    /// kind: game_key · gift_card · license · subscription · ticket; иное — как пришло.
    var вид = ""
    /// platform — машинный ключ площадки (steam, psn…); platform_name — её название для показа.
    var платформа = ""
    var названиеПлатформы = ""
    /// region — где код активируется: KZ, CIS, GLOBAL, EU, US и др.
    var регион = ""
    /// nominal — номинал как пришёл; число — без нулевой дробной части.
    var номинал = ""
    /// expires — срок действия кода как пришёл.
    var срок = ""
    /// Тот же срок разобранным (СрокЦифровогоКода) — один раз при разборе ответа, а не в каждом body. nil — срока нет
    /// или он непонятен: код считается действующим.
    var срокКода: СрокЦифровогоКода.Срок? = nil
    /// window_h — окно проверки после открытия кода, часы (1 или 24); нет — nil.
    var окноЧасов: Int? = nil

    private struct КлючЦифрового: CodingKey {
        var stringValue: String
        var intValue: Int? { nil }
        init(_ s: String) { stringValue = s }
        init?(stringValue: String) { self.stringValue = stringValue }
        init?(intValue: Int) { nil }
    }

    init(from decoder: Decoder) throws {
        let c = try decoder.container(keyedBy: КлючЦифрового.self)
        func текст(_ имя: String) -> String {
            if let s = try? c.decode(String.self, forKey: КлючЦифрового(имя)) {
                return s.trimmingCharacters(in: .whitespacesAndNewlines)
            }
            if let d = try? c.decode(Double.self, forKey: КлючЦифрового(имя)), d.isFinite, abs(d) < 1e15 {
                return d == d.rounded() ? String(Int(d)) : String(d)
            }
            return ""
        }
        вид = текст("kind")
        платформа = текст("platform")
        названиеПлатформы = текст("platform_name")
        регион = текст("region")
        номинал = текст("nominal")
        срок = текст("expires")
        срокКода = СрокЦифровогоКода.разобрать(срок)
        if let часы = Double(текст("window_h")), часы.isFinite, часы > 0, часы < 10_000 {
            окноЧасов = Int(часы)
        }
    }
}

/// seller_digital объявления: сколько у продавца цифровых продаж и споров по ним.
struct ЦифровоеПродавца: Hashable, Decodable {
    var продажи = 0
    var споры = 0

    private enum Ключи: String, CodingKey {
        case sales
        case disputes
    }

    init(from decoder: Decoder) throws {
        let c = try decoder.container(keyedBy: Ключи.self)
        func число(_ ключ: Ключи) -> Int {
            if let n = try? c.decode(Int.self, forKey: ключ) { return max(0, n) }
            if let d = try? c.decode(Double.self, forKey: ключ), d.isFinite, abs(d) < 1e12 { return max(0, Int(d)) }
            if let s = try? c.decode(String.self, forKey: ключ), let n = Int(s.trimmingCharacters(in: .whitespaces)) {
                return max(0, n)
            }
            return 0
        }
        продажи = число(.sales)
        споры = число(.disputes)
    }
}

/**
 АКТУАЛЬНОСТЬ ЦИФРОВОГО (владелец 16.10.2026: «Делиться можно, только актуальный товар»).

 Актуально — объявление опубликовано и срок кода (digital_info.expires) не прошёл. Только у такого есть «Поделиться»:
 на странице объявления (ссылкой, картинкой, в меню долгого нажатия) и в «Моих объявлениях». Неактуальное — без кнопки
 совсем, а не серой. У обычного объявления правило не действует: можноПоделиться у него всегда истинно.

 Срок — терпимым разбором, как пришёл от продавца: "YYYY-MM-DD", "YYYY-MM-DD HH:MM:SS" и ISO с «T» (время дня не
 важно), "YYYY-MM" (до конца месяца), "DD.MM.YYYY", а ещё "DD-MM-YYYY" и "MM.YYYY"; unix-число — секунды, от 1e12 —
 миллисекунды. ISO с явным поясом («Z», ±HH:MM) — миг, и последний день — день этого мига по Алматы. Пусто, непонятно
 или дата вне 2000–2100 — срока нет, код считается действующим. Код действует до конца своего дня по Алматы
 (Asia/Almaty) — так считает сайт. Разбор — числами и общим календарём, а ISO с поясом — своим ISO8601DateFormatter на
 вызов: он идёт при разборе ответа в любом потоке, а в body остаётся одно сравнение дат.
 */
enum СрокЦифровогоКода {
    /// Последний день действия кода.
    struct Срок: Hashable {
        /// Начало последнего дня действия (полночь по Алматы) — для «Действует до …».
        let день: Date
        /// Миг, с которого код уже не действует: начало следующего дня по Алматы.
        let конец: Date
    }

    /// Пояс сайта; нет его в системе — UTC+5.
    static let пояс: TimeZone = TimeZone(identifier: "Asia/Almaty") ?? TimeZone(secondsFromGMT: 5 * 3600) ?? .current

    /// Календарь в поясе Алматы. Calendar — значение: общий экземпляр читают из любого потока без замка.
    private static let календарь: Calendar = {
        var к = Calendar(identifier: .gregorian)
        к.timeZone = пояс
        return к
    }()

    /// Срок кода из строки expires; nil — срока нет или он непонятен.
    static func разобрать(_ строка: String) -> Срок? {
        let текст = строка.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !текст.isEmpty, текст.count <= 40 else { return nil }
        /* ISO с явным поясом (date('c') сайта, «Z» UTC): миг — в день по Алматы. «…T22:00:00Z» — это уже 17-е по
           Алматы, а не 16-е, как написано. Не разобралось — дальше, датой как написана. */
        if let с = мигСПоясом(текст) { return с }
        /* Дата — до пробела или «T»: время дня не важно, сравнение по концу дня. */
        let дата = текст.split(whereSeparator: { $0 == " " || $0 == "T" }).first.map { String($0) } ?? текст
        if дата.contains("-") {
            let ч = дата.split(separator: "-", omittingEmptySubsequences: false).map(String.init)
            guard ч.allSatisfy(Self.цифры) else { return nil }
            let н = ч.map { Int($0) }
            if ч.count == 3 && ч[0].count == 4 { return последнийДень(год: н[0], месяц: н[1], число: н[2]) }
            if ч.count == 2 && ч[0].count == 4 { return последнийДень(год: н[0], месяц: н[1], число: nil) }
            if ч.count == 3 && ч[2].count == 4 { return последнийДень(год: н[2], месяц: н[1], число: н[0]) }
            return nil
        }
        if дата.contains(".") {
            let ч = дата.split(separator: ".", omittingEmptySubsequences: false).map(String.init)
            if ч.allSatisfy(Self.цифры) {
                let н = ч.map { Int($0) }
                /* Не вышло — дальше: «1760000000.5» — это unix-число с дробью, а не месяц. */
                if ч.count == 3 && ч[2].count == 4,
                   let с = последнийДень(год: н[2], месяц: н[1], число: н[0]) { return с }
                if ч.count == 2 && ч[1].count == 4,
                   let с = последнийДень(год: н[1], месяц: н[0], число: nil) { return с }
            }
        }
        /* unix-число: секунды; от 1e12 — миллисекунды. Меньше 1e9 (до 2001 года) — не время, а что-то другое. */
        guard текст.allSatisfy({ $0 == "." || Self.цифры(String($0)) }), let n = Double(текст), n.isFinite,
              n >= 1e9, n < 1e14 else { return nil }
        let момент = Date(timeIntervalSince1970: n >= 1e12 ? n / 1000 : n)
        let к = календарь.dateComponents([.year, .month, .day], from: момент)
        return последнийДень(год: к.year, месяц: к.month, число: к.day)
    }

    /// ISO-миг с поясом: "…THH:MM:SSZ", "…THH:MM:SS±HH:MM", с долями секунды или без. Последний день — день этого мига
    /// по Алматы. Без «T» или без пояса — nil. Форматтер — свой на вызов: разбор идёт в любом потоке и один раз на ответ.
    private static func мигСПоясом(_ текст: String) -> Срок? {
        guard текст.contains("T"),
              текст.hasSuffix("Z") || текст.range(of: "[+-][0-9]{2}:?[0-9]{2}$", options: .regularExpression) != nil
        else { return nil }
        let формат = ISO8601DateFormatter()
        формат.formatOptions = [.withInternetDateTime, .withFractionalSeconds]
        let сДолями = формат.date(from: текст)
        формат.formatOptions = [.withInternetDateTime]
        guard let момент = сДолями ?? формат.date(from: текст) else { return nil }
        let к = календарь.dateComponents([.year, .month, .day], from: момент)
        return последнийДень(год: к.year, месяц: к.month, число: к.day)
    }

    /// Срок прошёл: сейчас уже после конца последнего дня по Алматы.
    static func истёк(_ срок: Срок, сейчас: Date = Date()) -> Bool {
        сейчас >= срок.конец
    }

    /// «31 дек», другого года — «31 дек 2027»: как даты страницы объявления (mkDate сайта, Listing.датаСайта) —
    /// месяцы ListingPageText «months» на языке приложения.
    static func словами(_ срок: Срок, сейчас: Date = Date()) -> String {
        let к = календарь.dateComponents([.year, .month, .day], from: срок.день)
        let месяцы = ListingPageText.т("months").split(separator: ",").map(String.init)
        let номер = (к.month ?? 1) - 1
        let месяц = месяцы.indices.contains(номер) ? месяцы[номер] : String(номер + 1)
        let год = к.year ?? 0
        let день = String(к.day ?? 1) + "\u{00A0}" + месяц
        return год == календарь.component(.year, from: сейчас) ? день : день + "\u{00A0}" + String(год)
    }

    /// Только цифры ASCII, хотя бы одна.
    private static func цифры(_ s: String) -> Bool {
        !s.isEmpty && s.unicodeScalars.allSatisfy { $0.value >= 48 && $0.value <= 57 }
    }

    /// Последний день: число — день месяца, nil — до конца месяца. Неверная дата — nil.
    private static func последнийДень(год: Int?, месяц: Int?, число: Int?) -> Срок? {
        guard let год, let месяц, (2000...2100).contains(год), (1...12).contains(месяц),
              let первое = календарь.date(from: DateComponents(year: год, month: месяц, day: 1)),
              let дней = календарь.range(of: .day, in: .month, for: первое)?.count else { return nil }
        let последний = число ?? дней
        guard (1...дней).contains(последний),
              let начало = календарь.date(from: DateComponents(year: год, month: месяц, day: последний)),
              let конец = календарь.date(byAdding: .day, value: 1, to: начало) else { return nil }
        return Срок(день: начало, конец: конец)
    }
}

extension Listing {
    /// Срок кода прошёл. Не цифровое, срока нет или он непонятен — false.
    var срокЦифровогоИстёк: Bool {
        guard цифровое, let срок = цифровоеОписание?.срокКода else { return false }
        return СрокЦифровогоКода.истёк(срок)
    }

    /**
     Цифровое объявление опубликовано. ?id= сервер отдаёт карточкой только одобренное (status approved), а снятое,
     проданное, архивное и в резерве — коротким ответом gone со status sold · inactive · archived · reserved; удалённого
     и непромодерированного нет вовсе. is_active: false — вышел 30-дневный срок. Заготовка по ссылке (ответа ещё нет) —
     неизвестно, значит, нет: кнопка появится, когда придёт ответ.
     */
    var цифровоеОпубликовано: Bool {
        guard активно, !заготовка else { return false }
        return статусВыдачи.isEmpty || статусВыдачи == "approved"
    }

    /// Актуально (владелец 16.10.2026): опубликовано и срок кода не прошёл.
    var цифровоеАктуально: Bool { цифровоеОпубликовано && !срокЦифровогоИстёк }

    /// «Поделиться» у этого объявления: обычное — всегда, как раньше; цифровое — только актуальное.
    var можноПоделиться: Bool { !цифровое || цифровоеАктуально }
}

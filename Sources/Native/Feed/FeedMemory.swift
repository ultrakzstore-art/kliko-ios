import Foundation

/**
 ДЛИННАЯ ЛЕНТА БЕЗ РАЗДУВАНИЯ ПАМЯТИ (скорость).

 Кто листает сотни страниц, держал бы в памяти каждое объявление целиком: описание, все фото, полные характеристики,
 поля страницы (оплата, отчёты проверок, доставка). Карточке ленты это не нужно. Правило: страницы (по размеру
 страницы запроса, 48 ячеек) дальше `дальше` страниц от той, что на экране, держат облегчённые объявления — тот же id и
 всё, что рисует карточка, без тяжёлых полей. Вернулся человек ближе `вернуть` страниц — полные подставляются обратно
 из сырого ответа сервера, который лежит на диске (Caches/feed-pages), а не в памяти. Ячейки и их ключи те же, размер
 карточек не меняется — прокрутка не прыгает; снимок «с того же места» (StateRestore) хранит только номера.

 Облегчаются только объявления, чей сырой ответ записан на диск: копия ленты с диска на запуске и прочее без файла
 остаются полными.
 */
final class ПамятьДлиннойЛенты {
    /// Дальше стольких страниц от экрана — облегчить.
    static let дальше = 8
    /// Ближе стольких — вернуть полными (с запасом, чтобы на границе не качало туда-сюда).
    static let вернуть = 6

    /// Страница (в ячейках ленты), на которой экран, — меняется, когда человек перелистнул на другую.
    var страница = -1
    /// Поколение выдачи: новая первая страница — прежние файлы и ответы из них уже не про неё.
    private(set) var поколение = 0
    /// id → номер файла с его сырым ответом.
    private(set) var файлТовара: [String: Int] = [:]
    /// Облегчённые сейчас.
    var облегчены: Set<String> = []
    /// Файлы, которые сейчас читаются, — второй раз не просить.
    var вПути: Set<Int> = []
    private var файлы: [Int: URL] = [:]
    private var счётчик = 0
    private let папка: URL

    init() {
        let кэш = FileManager.default.urls(for: .cachesDirectory, in: .userDomainMask).first
            ?? FileManager.default.temporaryDirectory
        let корень = кэш.appendingPathComponent("feed-pages", isDirectory: true)
        let своя = корень.appendingPathComponent(UUID().uuidString, isDirectory: true)
        папка = своя
        /* Файлы прошлых запусков — в мусор, не на главной очереди. */
        let имя = своя.lastPathComponent
        Task.detached(priority: .background) {
            let fm = FileManager.default
            guard let старые = try? fm.contentsOfDirectory(at: корень, includingPropertiesForKeys: nil) else { return }
            for адрес in старые where адрес.lastPathComponent != имя { try? fm.removeItem(at: адрес) }
        }
    }

    /// Новая выдача с первой страницы: всё прежнее забыть, файлы удалить.
    func забыть() {
        поколение += 1
        let старые = Array(файлы.values)
        файлы = [:]
        файлТовара = [:]
        облегчены = []
        вПути = []
        страница = -1
        guard !старые.isEmpty else { return }
        Task.detached(priority: .background) {
            for адрес in старые { try? FileManager.default.removeItem(at: адрес) }
        }
    }

    /// Сырой ответ страницы — на диск; его объявления теперь можно облегчать.
    func запомнить(_ сырое: Data, номера: [String]) {
        guard !номера.isEmpty, !сырое.isEmpty else { return }
        счётчик += 1
        let номер = счётчик
        let адрес = папка.appendingPathComponent(String(номер) + ".json")
        let каталог = папка
        файлы[номер] = адрес
        for id in номера { файлТовара[id] = номер }
        Task.detached(priority: .utility) {
            try? FileManager.default.createDirectory(at: каталог, withIntermediateDirectories: true)
            try? сырое.write(to: адрес, options: .atomic)
        }
    }

    func адрес(_ номер: Int) -> URL? { файлы[номер] }

    /// Полные объявления из файла страницы — не на главной очереди; файла нет или не разобрался — пусто.
    static func прочитать(_ адрес: URL) async -> [Listing] {
        await Task.detached(priority: .userInitiated) { () -> [Listing] in
            guard let данные = try? Data(contentsOf: адрес) else { return [] }
            return (try? ListingsAPI.разобрать(данные).items) ?? []
        }.value
    }
}

extension Listing {
    /// Облегчённая копия для далёких страниц: тот же id и всё, что рисует карточка ленты (название, цена, обложка,
    /// город, метки, строка характеристик, заявления, жильё, до восьми фото), без описания, полных характеристик и полей
    /// страницы — кроме точки на карте («Рядом»). Описание помечено обрезанным: открыли такую — карточка догрузит полную.
    var облегчённая: Listing {
        var копия = self
        копия.описание = nil
        копия.описаниеОбрезано = true
        копия.характеристики = []
        /* Адреса фото лёгкие, а по их числу карточка рисует точки (.mk-cdots, до восьми) — оставляем восемь, чтобы
           вернувшаяся облегчённая карточка не теряла точки до подмены полной. */
        if копия.фото.count > 8 { копия.фото = Array(копия.фото.prefix(8)) }
        var поля = ПоляСтраницыВида()
        поля.широта = поляВида.широта
        поля.долгота = поляВида.долгота
        копия.поляВида = поля
        return копия
    }
}

            let остаток = abs(n) % 100
            let слово = (остаток > 10 && остаток < 20) ? "объявлениям" : (остаток % 10 == 1 ? "объявлению" : "объявлениям")
            return "Применено к " + String(n) + " " + слово + "."
        }

    /// «объявлениям» (11–19 — тоже «объявлениям»).
    static func применено(_ n: Int) -> String {
        switch язык {
        case "kk": return String(n) + " хабарландыруға қолданылды."
        case "en": return n == 1 ? "Applied to 1 listing." : "Applied to " + String(n) + " listings."
        case "ar": return "طُبِّق على " + String(n) + " إعلان."

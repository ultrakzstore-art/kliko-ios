import SwiftUI
import StoreKit
import UIKit

/**
 ПРОСЬБА ОЦЕНИТЬ — ЭТАП 16 ПЕРЕХОДА НА SWIFTUI (владелец 25.09.2026: «давай следующие этапы»).

 Системное окно оценки App Store (SwiftUI @Environment(\.requestReview)) — только после удачного момента:
   · третье объявление, положенное в избранное в этой версии, — сам миг сердечка;
   · пятое открытое объявление в этой версии — когда человек закрыл карточку: досмотрел и вернулся, а не начал смотреть.
 Не чаще раза в версию, не раньше трёх дней после установки, не над страницей сайта и не под замком Face ID, и никогда
 поверх листа, фото на весь экран, «Поделиться» или диалога (ПоверхОкна). Карточка или переписка на экране — момент
 закрытия карточки не годится: человек уже занят следующим делом («Написать», похожие). Не сошлось — ждём следующего
 момента, а не просим позже невпопад.

 🔴 ПОКАЖЕТ ЛИ ОКНО, РЕШАЕТ iOS: не больше трёх раз за 365 дней на телефон, в TestFlight — никогда, а человек мог
 выключить просьбы в настройках App Store. Узнать, показалось ли окно и что поставили, приложению не дано. Поэтому «в
 этой версии уже просили» записываем в миг просьбы, а не по ответу.

 ЗАВЕРШЁННАЯ СДЕЛКА (владелец 07.10.2026): своя сделка стала «Завершена» (покупатель подтвердил получение) у человека на
 глазах — в открытой карточке сделки — тоже повод. Не после спора, возврата или отмены; не чаще раза в 120 дней (и, как
 у всех поводов, раза в версию); не раньше третьей успешной сделки, если с установки не прошло семи дней.

 ЧТО ХРАНИТСЯ — UserDefaults: дата установки, версия, в которой просили, и номера объявлений, посчитанных в этой версии
 (не больше 3 и 5). Номера — то, что человек сохранял и смотрел, поэтому при выходе (bye=1, WebContainer) стираются;
 дата и версия — о телефоне, а не о человеке, и остаются. Дату установки приложение раньше не записывало: у тех, кто
 обновился, три дня тишины отсчитываются от первого запуска сборки с этапом 16 — с запасом, а не впритык.
 */
@MainActor
final class ПросьбаОценить: ObservableObject {
    static let shared = ПросьбаОценить()

    /// Сколько объявлений положить в избранное в этой версии, чтобы сердечко стало поводом.
    static let порогИзбранного = 3
    /// Сколько объявлений открыть в этой версии, чтобы закрытие карточки стало поводом.
    static let порогОткрытых = 5
    /// Первые три дня после установки не просим: рано судить, нравится ли.
    static let тишинаПослеУстановки: TimeInterval = 3 * 24 * 60 * 60
    /// Повод «сделка завершена»: не чаще раза в 120 дней.
    static let паузаПослеПросьбы: TimeInterval = 120 * 24 * 60 * 60
    /// …и не раньше третьей успешной сделки — или семи дней с установки.
    static let порогСделок = 3
    static let неделяПослеУстановки: TimeInterval = 7 * 24 * 60 * 60

    private enum Ключ {
        static let установка = "kliko.review.installedAt"
        static let спросили = "kliko.review.askedVersion"
        static let версияСчёта = "kliko.review.countVersion"
        static let избранное = "kliko.review.favorites"
        static let открытые = "kliko.review.opened"
        static let спросилиКогда = "kliko.review.askedAt"
        static let сделки = "kliko.review.deals"
    }

    /// Номер просьбы: растёт на каждую, а слой (ОценкаВСлое) на его смену зовёт requestReview — действие окружения
    /// SwiftUI, у модели его нет.
    @Published private(set) var номерПросьбы = 0

    /// Карточек и переписок на экране (onAppear/onDisappear). Только в памяти.
    private var занято = 0
    /// Отложенная просьба: пауза после момента, чтобы не перебить анимацию сердечка или «Назад».
    private var ожидание: Task<Void, Never>?

    private init() {}

    // MARK: - Запуск и выход

    /// Первый запуск (SceneDelegate, на каждом запуске): запомнить дату установки, если её ещё нет.
    static func запомнитьУстановку() {
        let хранилище = UserDefaults.standard
        guard хранилище.object(forKey: Ключ.установка) == nil else { return }
        хранилище.set(Date(), forKey: Ключ.установка)
    }

    /// Выход из аккаунта (bye=1): номера объявлений ушедшего следующему не оставляем. Дата установки и версия просьбы —
    /// о телефоне, они остаются.
    func стереть() {
        ожидание?.cancel()
        ожидание = nil
        UserDefaults.standard.removeObject(forKey: Ключ.избранное)
        UserDefaults.standard.removeObject(forKey: Ключ.открытые)
    }

    // MARK: - Моменты

    /// Сердечко: объявление легло в избранное (FavoritesStore.переключить). Набралось — просим через полторы секунды.
    func вИзбранное(_ id: String) {
        guard Config.просьбаОценить else { return }
        guard засчитать(id, ключ: Ключ.избранное, порог: Self.порогИзбранного) >= Self.порогИзбранного else { return }
        назначить(через: 1_500_000_000, толькоСвободный: false)
    }

    /// Открыли карточку объявления (ListingDetailView; открытую по ссылке — когда дотянулась). Только счёт: просить в
    /// начале просмотра значит перебить его.
    func открыли(_ id: String) {
        guard Config.просьбаОценить else { return }
        засчитать(id, ключ: Ключ.открытые, порог: Self.порогОткрытых)
    }

    /// Карточка объявления или переписка появилась на экране.
    func делоНаЭкране() {
        занято += 1
    }

    /// Карточка или переписка ушла с экрана. Ушла карточка, а открытых набралось, — момент: просим, если через паузу на
    /// экране нет ни карточки, ни переписки (человек вернулся к списку, а не пошёл дальше).
    func делоУшло(карточка: Bool) {
        занято = max(0, занято - 1)
        guard карточка, Config.просьбаОценить, номера(Ключ.открытые).count >= Self.порогОткрытых else { return }
        назначить(через: 1_200_000_000, толькоСвободный: true)
    }

    /**
     Карточка сделки получила новое состояние (КарточкаСделкиМодель.применить); было — статус до него (nil — первый
     показ карточки). Успешную сделку считаем всегда, а просим только при переходе в «Завершена» на глазах у человека.
     */
    func сделкаЗавершена(_ сделка: Сделка, было: String?) {
        guard Config.просьбаОценить else { return }
        let успех: Set<String> = ["confirmed", "completed", "released", "done"]
        guard успех.contains(сделка.статус), сделка.причинаСпора.isEmpty, !сделка.возврат else { return }
        let успешных = засчитатьСделку(сделка.id)
        guard let было, !было.isEmpty, !успех.contains(было), было != "disputed" else { return }
        guard !сделкаРано(успешных: успешных) else { return }
        назначить(через: 2_000_000_000, толькоСвободный: false)
    }

    // MARK: - Внутреннее

    /// Повод «сделка»: просили меньше 120 дней назад — рано; иначе нужна третья успешная сделка или неделя с установки.
    private func сделкаРано(успешных: Int) -> Bool {
        let хранилище = UserDefaults.standard
        if let когда = хранилище.object(forKey: Ключ.спросилиКогда) as? Date,
           Date().timeIntervalSince(когда) < Self.паузаПослеПросьбы {
            return true
        }
        if успешных >= Self.порогСделок { return false }
        guard let установка = хранилище.object(forKey: Ключ.установка) as? Date else { return true }
        return Date().timeIntervalSince(установка) < Self.неделяПослеУстановки
    }

    /// Успешная сделка — один раз по номеру; дальше порога не копим. Возвращает, сколько набралось.
    private func засчитатьСделку(_ id: String) -> Int {
        var список = UserDefaults.standard.stringArray(forKey: Ключ.сделки) ?? []
        if !id.isEmpty && список.count < Self.порогСделок && !список.contains(id) {
            список.append(id)
            UserDefaults.standard.set(список, forKey: Ключ.сделки)
        }
        return список.count
    }

    /// Уже просили в этой версии или с установки не прошло трёх дней — не просим и не ждём.
    private var рано: Bool {
        let хранилище = UserDefaults.standard
        if хранилище.string(forKey: Ключ.спросили) == ВерсияПриложения.текущая { return true }
        guard let установка = хранилище.object(forKey: Ключ.установка) as? Date else {
            Self.запомнитьУстановку()
            return true
        }
        return Date().timeIntervalSince(установка) < Self.тишинаПослеУстановки
    }

    private func назначить(через наносекунд: UInt64, толькоСвободный: Bool) {
        guard !рано else { return }
        ожидание?.cancel()
        ожидание = Task {
            try? await Task.sleep(nanoseconds: наносекунд)
            guard !Task.isCancelled else { return }
            self.попроситьЕслиМожно(толькоСвободный: толькоСвободный)
        }
    }

    private func попроситьЕслиМожно(толькоСвободный: Bool) {
        guard Config.просьбаОценить, !рано else { return }
        if толькоСвободный && занято > 0 { return }                   // уже в новой карточке или переписке
        let замок = AppLock.shared
        guard WebBridge.shared.лентаВидна,                            // над страницей сайта не просим
              !(замок.enabled && (замок.locked || замок.cover)),      // и под замком Face ID
              UIApplication.shared.applicationState == .active,
              !ПоверхОкна.занято else { return }                     // и поверх листа, фото, «Поделиться», диалога
        UserDefaults.standard.set(ВерсияПриложения.текущая, forKey: Ключ.спросили)
        UserDefaults.standard.set(Date(), forKey: Ключ.спросилиКогда)
        номерПросьбы += 1
    }

    /// Номера, посчитанные в этой версии. Версия сменилась — счёт с нуля: «раз в версию» значит и поводы в ней свои.
    private func номера(_ ключ: String) -> [String] {
        let хранилище = UserDefaults.standard
        let версия = ВерсияПриложения.текущая
        if хранилище.string(forKey: Ключ.версияСчёта) != версия {
            хранилище.removeObject(forKey: Ключ.избранное)
            хранилище.removeObject(forKey: Ключ.открытые)
            хранилище.set(версия, forKey: Ключ.версияСчёта)
        }
        return хранилище.stringArray(forKey: ключ) ?? []
    }

    /// Засчитать объявление один раз (сердечко туда-обратно или повторное открытие — не новый повод); дальше порога
    /// номера не копим. Возвращает, сколько набралось.
    @discardableResult
    private func засчитать(_ id: String, ключ: String, порог: Int) -> Int {
        var список = номера(ключ)
        guard !id.isEmpty else { return список.count }
        if список.count < порог && !список.contains(id) {
            список.append(id)
            UserDefaults.standard.set(список, forKey: ключ)
        }
        return список.count
    }
}

/// Поверх окна приложения что-то показано: лист, фото на весь экран, «Поделиться», диалог подтверждения. Спрашиваем
/// UIKit, а не флаги экранов: листы SwiftUI — представленные контроллеры, и так видно все сразу, включая системные.
@MainActor
enum ПоверхОкна {
    static var занято: Bool {
        UIApplication.shared.connectedScenes
            .compactMap { $0 as? UIWindowScene }
            .flatMap { $0.windows }
            .contains { $0.rootViewController?.presentedViewController != nil }
    }
}

/// Слой, который исполняет просьбу: @Environment(\.requestReview) есть только у вида (RootWebView → .чтоНовогоИОценка()).
struct ОценкаВСлое<Содержимое: View>: View {
    let содержимое: Содержимое
    @ObservedObject private var просьба = ПросьбаОценить.shared
    @Environment(\.requestReview) private var оценить

    init(_ содержимое: Содержимое) {
        self.содержимое = содержимое
    }

    var body: some View {
        содержимое
            .onChange(of: просьба.номерПросьбы) { _, _ in
                оценить()
            }
    }
}

/**
 ДЕЙСТВИЯ С ПРОДАВЦОМ — ЭТАП 37 (владелец 25.09.2026: «почти 100% похоже на сайт»).

 Что заблокировано, отзывы в памяти, жалоба и блокировка с их сообщениями — одним местом, как mkBlockToggle,
 mkReportOpen / mkReportSubmit и mkSellerRevOpen сайта:
   · «Заблокировать» — только после вопроса «Заблокировать продавца?» (его задаёт экран, как mkConfirm сайта), потом
     POST subs.php?action=block; «Разблокировать» — сразу, POST unblock. Экран меняется, когда сайт ответил ok (сайт тоже
     не забегает вперёд), и внизу «Продавец заблокирован» / «Продавец разблокирован». Пока запрос в пути, второе нажатие
     на того же продавца не уходит.
   · Заблокирован ли — blocked из subs.php?action=status: его приносит СинхронПодписок (этап 36) тем же запросом, что
     «Подписаться на продавца»; подписки выключены — спрашиваем status сами, не чаще раза в минуту на продавца, только у
     вошедшего (гость никого не блокировал).
   · «Пожаловаться» — гостю, как mkReportOpen, окна нет, а внизу «Войдите, чтобы пожаловаться» с «Войти». Отправка — один
     запрос за раз, после вопроса на экране; ok — «Жалоба отправлена модераторам» или «Вы уже жаловались на это» (exists).
   · Отказ — слова сайта: «Войдите в кабинет» с «Войти» (страница cabinet.php), «Доступно после верификации», «Ошибка
     защиты, перезагрузите», «Нет соединения», текст error (ulxErr), иначе «Не удалось» / «Не удалось отправить».
 Повторов нет, само по себе на сайт не пишется ничего. Всё — только в памяти; выход (bye=1) стирает.
 */
@MainActor
final class ДействияСПродавцом: ObservableObject {
    static let shared = ДействияСПродавцом()

    /// Сообщение внизу экрана — та же плашка, что у избранного и подписок (.mk-toast сайта).
    @Published private(set) var сообщение: СинхронИзбранного.Сообщение?
    /// Что сайт сказал о продавцах в этот запуск (blocked или ответ block/unblock). Не знаем — не заблокирован.
    @Published private(set) var заблокированы: [String: Bool] = [:]
    /// block/unblock в пути — пункт «⋮» недоступен.
    @Published private(set) var блокировкаВПути: Set<String> = []
    /// Жалоба в пути — «Отправляю…», второй раз не шлём.
    @Published private(set) var жалобаВПути = false
    /// Номер вошедшего — на своём объявлении «⋮» нет, как у сайта (getMkMe() === seller_id).
    @Published private(set) var мой: String?

    private struct ЗаписьОтзывов {
        let сводка: ОтзывыПродавца.Сводка
        let когда: Date
    }

    /// Что делать, когда страница спрошена: писать с токеном, сказать «войдите» или сразу отказ.
    private enum Доступ {
        case токен(String)
        case гость
        case нет(ПодпискиСайта.Итог)
    }

    /// Отзывы, уже пришедшие в этот запуск: лист продавца открывается снова без ожидания (5 минут, до 20 продавцов).
    private var отзывы: [String: ЗаписьОтзывов] = [:]
    /// Когда сами спрашивали status (подписки выключены) — не чаще раза в минуту на продавца.
    private var статусы: [String: Date] = [:]
    private var статусыВПути: Set<String> = []
    /// Растёт при выходе: ответ, пришедший после него, — чужой, его не применяем.
    private var поколение = 0

    private init() {}

    func заблокирован(_ продавец: String) -> Bool {
        заблокированы[продавец] ?? false
    }

    // MARK: - Отзывы

    /// Отзывы из памяти, если им меньше 5 минут.
    func отзывыИзПамяти(_ продавец: String) -> ОтзывыПродавца.Сводка? {
        guard let запись = отзывы[продавец], Date().timeIntervalSince(запись.когда) < 300 else { return nil }
        return запись.сводка
    }

    /// Отзывы продавца: из памяти или GET seller_reviews.php. nil — «Не удалось загрузить отзывы».
    func загрузитьОтзывы(_ продавец: String) async -> ОтзывыПродавца.Сводка? {
        if let готовые = отзывыИзПамяти(продавец) { return готовые }
        let взятое = поколение
        let пришло = await ОтзывыПродавца.загрузить(продавец)
        guard let сводка = пришло, взятое == поколение else { return пришло }
        отзывы[продавец] = ЗаписьОтзывов(сводка: сводка, когда: Date())
        if отзывы.count > 20, let старый = отзывы.min(by: { $0.value.когда < $1.value.когда })?.key {
            отзывы[старый] = nil
        }
        return сводка
    }

    // MARK: - Заблокирован ли

    /// Карточка продавца на экране: кто вошёл (свой ли это продавец) и, если подписки выключены, — status ради blocked.
    /// С подписками status спрашивает СинхронПодписок, а blocked приходит сюда (статусСайта). Отказ и обрыв — молча.
    func узнать(продавца продавец: String) {
        guard Config.жалобы, !продавец.isEmpty else { return }
        let взятое = поколение
        Task {
            let страница = await SiteSession.состояние()
            guard взятое == self.поколение else { return }
            self.запомнить(страница)
            guard !Config.подпискиССайтом, страница.вошёл == true, !self.статусыВПути.contains(продавец) else { return }
            if let когда = self.статусы[продавец], Date().timeIntervalSince(когда) < 60 { return }
            self.статусыВПути.insert(продавец)
            self.статусы[продавец] = Date()
            let итог = await ПодпискиСайта.статус(продавца: продавец)
            guard взятое == self.поколение else { return }
            self.статусыВПути.remove(продавец)
            if case .готово(let ответ) = итог, let блок = ответ.заблокирован {
                self.статусСайта(продавец, заблокирован: блок)
            }
        }
    }

    /// blocked из ответа subs.php?action=status. Пока block/unblock этого продавца в пути, ответ status его не перебивает.
    func статусСайта(_ продавец: String, заблокирован: Bool) {
        guard Config.жалобы, !блокировкаВПути.contains(продавец) else { return }
        if заблокированы[продавец] != заблокирован { заблокированы[продавец] = заблокирован }
    }

    // MARK: - Блокировка

    /// «Заблокировать» (экран уже спросил «Заблокировать продавца?») или «Разблокировать» в «⋮» — mkBlockToggle.
    func переключитьБлокировку(_ продавец: String, имя: String) {
        guard Config.жалобы, !продавец.isEmpty, !блокировкаВПути.contains(продавец) else { return }
        let снять = заблокирован(продавец)
        блокировкаВПути.insert(продавец)
        let взятое = поколение
        Task {
            let можно = await self.доступ()
            guard взятое == self.поколение else { return }
            let итог: ПодпискиСайта.Итог
            switch можно {
            case .гость:
                self.блокировкаВПути.remove(продавец)
                self.показать(текст: SellerText.т("login_block"), войти: true)
                return
            case .нет(let отказ):
                итог = отказ
            case .токен(let токен):
                if снять {
                    итог = await ЗапросыПродавца.разблокировать(продавец, имя: имя, csrf: токен)
                } else {
                    итог = await ЗапросыПродавца.заблокировать(продавец, имя: имя, csrf: токен)
                }
            }
            guard взятое == self.поколение else { return }
            self.блокировкаВПути.remove(продавец)
            switch итог {
            case .готово:
                self.заблокированы[продавец] = !снять
                self.показать(текст: SellerText.т(снять ? "unblocked" : "blocked"), войти: false)
            case .нуженВход:
                /* Как у сайта при auth: «Войдите в кабинет» — с «Войти». */
                self.показать(текст: SellerText.т("err_login"), войти: true)
            case .нужнаВерификация, .защита, .отказ, .сеть:
                self.показать(текст: ДействияСПродавцом.текст(итог, запасной: "err_failed"), войти: false)
            }
        }
    }

    // MARK: - Жалоба

    /// «Пожаловаться» в «⋮». Гость — «Войдите, чтобы пожаловаться» с «Войти», окна нет (mkReportOpen: getMkMe()).
    /// true — открыть окно жалобы. Страница не сказала, кто это, — окно открывается: решит сайт при отправке.
    func можноЖаловаться() async -> Bool {
        guard Config.жалобы else { return false }
        let взятое = поколение
        let страница = await SiteSession.состояние()
        guard взятое == поколение else { return false }
        запомнить(страница)
        if страница.вошёл == false {
            показать(текст: SellerText.т("report_login"), войти: true)
            return false
        }
        return true
    }

    /// Отправить жалобу (экран уже спросил «Отправить жалобу?»). true — сайт принял (ok): окно закрывается, внизу
    /// «Жалоба отправлена модераторам» или «Вы уже жаловались на это». false — окно остаётся, внизу причина.
    func пожаловаться(на продавец: String, объявление: String, причина: ПричинаЖалобы,
                      комментарий: String) async -> Bool {
        guard Config.жалобы, !жалобаВПути else { return false }
        жалобаВПути = true
        let взятое = поколение
        let можно = await доступ()
        guard взятое == поколение else { return false }
        let итог: ПодпискиСайта.Итог
        switch можно {
        case .гость:
            жалобаВПути = false
            показать(текст: SellerText.т("report_login"), войти: true)
            return false
        case .нет(let отказ):
            итог = отказ
        case .токен(let токен):
            итог = await ЗапросыПродавца.пожаловаться(на: продавец, объявление: объявление, причина: причина,
                                                      комментарий: комментарий, csrf: токен)
        }
        guard взятое == поколение else { return false }
        жалобаВПути = false
        switch итог {
        case .готово(let ответ):
            показать(текст: SellerText.т(ответ.уже ? "report_exists" : "report_sent"), войти: false)
            return true
        case .нуженВход:
            показать(текст: SellerText.т("report_login"), войти: true)
            return false
        case .нужнаВерификация, .защита, .отказ, .сеть:
            показать(текст: ДействияСПродавцом.текст(итог, запасной: "report_failed"), войти: false)
            return false
        }
    }

    // MARK: - Сообщение, вход, выход

    /// Плашка внизу: 2,6 с, как toast(…, 2600) сайта; с «Войти» — 5 с. Её же зовёт окно жалобы («Выберите причину»).
    func показать(текст: String, войти: Bool) {
        let новое = СинхронИзбранного.Сообщение(текст: текст, войти: войти)
        сообщение = новое
        UIAccessibility.post(notification: .announcement, argument: текст)
        let срок: UInt64 = войти ? 5_000_000_000 : 2_600_000_000
        Task {
            try? await Task.sleep(nanoseconds: срок)
            if self.сообщение?.id == новое.id { self.сообщение = nil }
        }
    }

    /// Нажали «Войти» — страница входа сайта в той же обёртке, как у избранного и подписок.
    func войти() {
        сообщение = nil
        if let адрес = Config.страницаСайта("cabinet.php") { WebBridge.shared.pendingURL = адрес }
    }

    /// Выход из аккаунта (WebContainer, bye=1): что он блокировал, его номер и отзывы, взятые с его куками, не помним;
    /// ответы, пришедшие после выхода, не применяем.
    func стереть() {
        поколение += 1
        сообщение = nil
        заблокированы = [:]
        блокировкаВПути = []
        жалобаВПути = false
        мой = nil
        отзывы = [:]
        статусы = [:]
        статусыВПути = []
    }

    // MARK: - Внутреннее

    /// Токен страницы (window._MKP_CSRF, запасной — KlikoCsrf) для записи. Гость — «войдите» без запроса; токена нет —
    /// вошедшему «Ошибка защиты», иначе (страница не загружена) — «Нет соединения».
    private func доступ() async -> Доступ {
        let страница = await SiteSession.состояние()
        запомнить(страница)
        if страница.вошёл == false { return .гость }
        guard let токен = страница.csrf else { return .нет(страница.вошёл == true ? .защита : .сеть) }
        return .токен(токен)
    }

    private func запомнить(_ страница: SiteSession.Состояние) {
        switch страница.вошёл {
        case .some(true):
            if let номер = страница.пользователь, мой != номер { мой = номер }
        case .some(false):
            if мой != nil { мой = nil }
        case .none:
            break
        }
    }

    /// Отказ словами сайта; `запасной` — ключ строки, когда у сайта своего текста нет.
    private static func текст(_ итог: ПодпискиСайта.Итог, запасной: String) -> String {
        switch итог {
        case .готово:           return SellerText.т(запасной)
        case .нуженВход:        return SellerText.т("err_login")
        case .нужнаВерификация: return SellerText.т("err_verify")
        case .защита:           return SellerText.т("err_csrf")
        case .сеть:             return SellerText.т("err_net")
        case .отказ(let сайта): return сайта ?? SellerText.т(запасной)
        }
    }
}

// MARK: - Слой над нативными экранами

extension View {
    /**
     Этап 37: плашка «Продавец заблокирован», «Жалоба отправлена модераторам» и отказов над нативными экранами
     (RootWebView) — там же, где плашки избранного и подписок. Рубильник Config.жалобы выключен — ничего не делает.
     */
    @MainActor
    func продавецССайтом() -> some View {
        СлойДействийСПродавцом(self)
    }
}

struct СлойДействийСПродавцом<Содержимое: View>: View {
    let содержимое: Содержимое
    @ObservedObject private var действия = ДействияСПродавцом.shared
    @ObservedObject private var мост = WebBridge.shared

    init(_ содержимое: Содержимое) {
        self.содержимое = содержимое
    }

    var body: some View {
        if Config.жалобы {
            содержимое
                .overlay(alignment: .bottom) { плашка }
        } else {
            содержимое
        }
    }

    /// Над нижней панелью и пилюлей «Связаться» — как у избранного; пока на экране страница сайта, плашки нет.
    private var плашка: some View {
        ZStack(alignment: .bottom) {
            if let сообщение = действия.сообщение, мост.лентаВидна {
                ПлашкаИзбранного(сообщение: сообщение, войти: { действия.войти() })
                    .frame(maxWidth: 520)
                    .padding(.horizontal, 16)
                    .padding(.bottom, 88)
                    .transition(.opacity.combined(with: .move(edge: .bottom)))
                    .id(сообщение.id)
            }
        }
        .animation(.easeInOut(duration: 0.22), value: действия.сообщение?.id)
    }
}

/**
 Плашка внутри листов продавца (отзывы, жалоба): лист закрывает собой плашки корня, поэтому свои — здесь: действия с
 продавцом, а в листе отзывов — и «Подписались — сообщим…» кнопки подписки (СинхронПодписок). «Войти» сначала закрывает
 лист, потом открывает страницу входа.
 */
struct ПлашкиВЛистеПродавца: View {
    let закрытьЛист: () -> Void
    @ObservedObject private var действия = ДействияСПродавцом.shared
    @ObservedObject private var подписки = СинхронПодписок.shared

    init(закрытьЛист: @escaping () -> Void) {
        self.закрытьЛист = закрытьЛист
    }

    var body: some View {
        ZStack(alignment: .bottom) {
            if let сообщение = действия.сообщение {
                ПлашкаИзбранного(сообщение: сообщение, войти: {
                    закрытьЛист()
                    действия.войти()
                })
                .transition(.opacity.combined(with: .move(edge: .bottom)))
                .id(сообщение.id)
            } else if Config.подпискиССайтом, let сообщение = подписки.сообщение {
                ПлашкаИзбранного(сообщение: сообщение, войти: {
                    закрытьЛист()
                    подписки.войти()
                })
                .transition(.opacity.combined(with: .move(edge: .bottom)))
                .id(сообщение.id)
            }
        }
        .frame(maxWidth: 520)
        .padding(.horizontal, 16)
        .padding(.bottom, 16)
        .animation(.easeInOut(duration: 0.22), value: действия.сообщение?.id)
        .animation(.easeInOut(duration: 0.22), value: подписки.сообщение?.id)
    }
}

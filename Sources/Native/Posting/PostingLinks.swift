/**
 АДРЕСА ИЗ МАСТЕРА ПОДАЧИ — СВОИМИ ЭКРАНАМИ (владелец: «главное, чтобы на сайт не прыгал с приложения»).

 Своих адресов для перехода сервер подаче не присылает: submit, edit_item, recognize, ответы услуги и upload_photo
 отвечают флагами (need_verify, verify_required, slots_full, auth…), а url у upload_photo — только адрес фото: плитка,
 обложка «Проверьте» и превью (AsyncImage в PostingSteps, PostingSteps2, PostingCamera), нажатием не открывается.
 Адресом мастер открывает только это:
   · cabinet.php?go=verify — «Пройти верификацию» из вопросов мастера (recognize need_verify, slots_full +
     verify_required у товара и услуги): requestVerification сайта — BIO_ON: eGov поверх мастера (bioKycOpen →
     ОкноEgov), всё заполненное на экране, после удачи состояние кабинета перечитывается (у сайта — перезагрузка
     страницы и черновик); BIO_ON выключен — плашка ver_off;
   · cabinet.php?go=import — «Перенести по ссылке» (_asRenderLink: addStartClose → showAiImport("link")): мастер
     закрывается, перенос — своим окном МастерИмпорта (НативныеОкна);
   · cabinet?add=jobs — «Работа» (_asJobsGo: addStartClose → jobWizOpen): мастер закрывается, МастерРезюме;
   · cabinet.php — вход, когда свой вход выключен рубильником: мастер закрывается, вкладка «Кабинет»;
   · адреса листа входа (ЭкранВхода.открыть): apple_auth.php — лист входа через Apple поверх мастера
     (БезСайта.исключение), после входа мастер начинается заново; eGov и cabinet.php — только при выключенных рубильниках.
 Куда — решается ДО закрытия мастера (куда), тем же порядком, что у WebBridge.перейти: своё окно, которое встаёт
 поверх (eGov, вход через Apple, справка, поддержка, документ, витрина, чужая страница, tel:, mailto:), — мастер
 остаётся; свой экран вкладок или окно другого раздела — мастер закрывается (черновик пишется), затем адрес идёт общим
 путём WebBridge.перейти; своего экрана нет — своё окно-сообщение поверх мастера, всё заполненное остаётся. Страницы
 сайта нет ни в одной ветке.
 */
@MainActor
enum ПереходыПодачи {
    /// Куда ведёт адрес из мастера.
    enum Куда: Equatable {
        /// Сам мастер подачи (?go=add, ?add=1) — он уже на экране.
        case здесь
        /// Своё окно поверх мастера — мастер и всё заполненное остаются.
        case поверх
        /// Свой экран вкладок или окно другого раздела (перенос, «Работа», «Мои объявления», кабинет, лента, сделка) —
        /// сначала мастер закрывается.
        case послеМастера
        /// Своего экрана нет.
        case нет
    }

    /// Решение без действий — тем же порядком, что у WebBridge.перейти.
    static func куда(_ адрес: URL) -> Куда {
        let полный = адрес.absoluteURL
        let схема = (полный.scheme ?? "").lowercased()
        if схема == Config.scheme {
            /* kliko://open?u=<адрес> — сам адрес внутри (Config.deepLink пускает только наш домен). */
            guard let наш = Config.deepLink(полный) else { return .нет }
            return куда(наш)
        }
        /* tel:, mailto:, whatsapp: — система; чужая страница — лист Safari (БезСайта.внешняя): всё поверх мастера. */
        guard схема == "http" || схема == "https", Config.deepLink(полный) != nil else { return .поверх }
        if Config.главная(полный) { return .послеМастера }
        if исключение(полный) { return .поверх }
        if let после = АдресаКабинета.цельПослеВхода(адреса: полный), NativeRouter.доступна(после) {
            return .послеМастера
        }
        if СделкиEDS.ссылка(полный) != nil { return .послеМастера }
        if ОкноEgov.включено && ОкноEgov.этоEgov(полный) { return .поверх }
        if ОкноПродавца.номер(из: полный) != nil || ОкноПродавца.ник(из: полный) != nil { return .поверх }
        if НативныеОкна.включено, let окно = НативныеОкна.распознать(полный) {
            if case .страница = окно { return .поверх }
            return .послеМастера
        }
        if ПереходыКабинета.документ(полный) != nil { return .поверх }
        if let цель = NativeRouter.распознать(полный) ?? БезСайта.ближайший(полный), NativeRouter.доступна(цель) {
            switch цель {
            case .подача, .продажа: return .здесь
            case .поддержка: return .поверх
            default: return .послеМастера
            }
        }
        return .нет
    }

    /**
     Открыть адрес из мастера. модель — BIO_ON и плашка ver_off; закрытьМастер — «✕» мастера (черновик пишется);
     общийПуть — корневое «открыть» (WebBridge.перейти: свой экран или окно «недоступно», не сайт).
     */
    static func открыть(_ адрес: URL, модель: ПодачаМодель, закрытьМастер: () -> Void,
                        общийПуть: @escaping (URL) -> Void) {
        switch куда(адрес) {
        case .здесь:
            break
        case .поверх:
            if ОкноEgov.включено && ОкноEgov.этоEgov(адрес.absoluteURL) {
                пройтиВерификацию(адрес, eGovВключён: модель.страница.состояние?.eGovВключён ?? true,
                                  сказать: { текст in модель.показать(текст) })
            } else {
                общийПуть(адрес)
            }
        case .послеМастера:
            закрытьМастер()
            Task { @MainActor in
                /* Мастер уезжает — свой экран, когда он закрылся. */
                try? await Task.sleep(nanoseconds: 450_000_000)
                общийПуть(адрес)
            }
        case .нет:
            модель.записатьЧерновик()
            БезСайта.сообщить(заголовок: ПереходыПодачиText.т("na_t"), текст: ПереходыПодачиText.т("na_s"))
        }
    }

    /// requestVerification сайта: BIO_ON — eGov своим окном (bioKycOpen, ОкноEgov); выключен — ver_off («идут
    /// технические работы»). сказать — где показать этот текст.
    static func пройтиВерификацию(_ адрес: URL?, eGovВключён: Bool, сказать: (String) -> Void) {
        guard eGovВключён else {
            сказать(ОкнаКабинетаText.т("ver_off"))
            return
        }
        ОкноEgov.открыть(адрес ?? Config.страницаСайта("cabinet.php?go=verify"))
    }

    /// Вход через Apple и подключение соцсети, у которых нет своего ответа сервера, — лист внутри приложения
    /// (БезСайта.исключение); здесь только узнать.
    private static func исключение(_ адрес: URL) -> Bool {
        let имена: Set<String> = ["apple_auth.php", "apple_auth", "social_connect.php", "social_connect"]
        return имена.contains(адрес.lastPathComponent.lowercased())
    }
}

// MARK: - Модель: после eGov

extension ПодачаМодель {
    /**
     eGov прошёл поверх мастера (ОкноEgov.завершено). У сайта bioAfterOk перезагружает страницу, и черновик возвращается;
     здесь форма и фото остаются, а состояние кабинета (IS_VERIFIED, BIO_ON, токен) перечитывается. Гостевой экран,
     загрузку и ошибку ведут «вошли» листа входа и «Повторить».
     */
    func послеEgov() async {
        switch экран {
        case .камера, .старт, .шаги, .выбор: break
        default: return
        }
        guard let ответ = try? await КабинетСайта.страницаКабинета(), ответ.состояние.вошёл == true else { return }
        МоиОбъявленияAPI.запомнитьТокен(ответ.состояние.csrf)
        страница = СтраницаПодачи.разобрать(ответ.html, состояние: ответ.состояние)
    }
}

// MARK: - Вход и eGov поверх мастера

/// Вход поверх мастера (лист входа через Apple, свой вход другого экрана) — гостевой экран начинается заново; eGov
/// прошёл — состояние кабинета перечитывается, заполненное остаётся.
struct СлухПодачи: ViewModifier {
    /// Только слушает: перерисовывать модификатор на каждое изменение модели незачем.
    let модель: ПодачаМодель

    func body(content: Content) -> some View {
        content
            .onReceive(NotificationCenter.default.publisher(for: ОкнаПриложения.вошли)) { _ in
                Task { @MainActor in
                    if модель.экран == .нуженВход { await модель.начать() }
                }
            }
            .onReceive(NotificationCenter.default.publisher(for: ОкноEgov.завершено)) { _ in
                Task { @MainActor in await модель.послеEgov() }
            }
    }
}


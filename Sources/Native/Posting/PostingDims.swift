/**
 «Измерить в AR» в блоке «Габариты, см»: линейка «Поместится ли?» в режиме замера вещи (ОкноГабаритов.открытьЗамер,
 TryOn/FitBoxScreen.swift) — три отрезка: ширина, высота, глубина; «Готово» — в поля. Есть ли кнопка — постоянный
 признак (рубильники и AR на устройстве), а не значение, которое кто-то должен поставить при запуске.
 */
@MainActor
enum ЛинейкаПодачи {
    static var есть: Bool { Config.габаритыAR && Config.габаритыЛинейка && ОкноГабаритов.доступно }

    /// Открыть замер; готово — сантиметры (nil — эту сторону не мерили).
    static func открыть(название: String,
                        готово: @escaping (_ ширина: Double?, _ высота: Double?, _ глубина: Double?) -> Void) {
        guard есть else { return }
        ОкноГабаритов.открытьЗамер(название: название, готово: готово)
    }
}

// MARK: - Подача

extension ПодачаМодель {
    /// Разделы, где сервер сам потребовал габариты (need_dims), хотя списка или схемы нет: до перезапуска блок там есть.
    private static var разделыПоОтказу: Set<String> = []

    /// Раздел габаритный: схема сайта (dims) главнее; нет её — список «Поместится ли?» вместе с потомками.
    func габаритныйРаздел(_ ключ: String) -> Bool {
        guard Config.габаритыВПодаче, !ключ.isEmpty else { return false }
        if Self.разделыПоОтказу.contains(ключ) { return true }
        if let поСхеме = схема?.разделы[ключ]?.габариты { return поСхеме }
        /* Тот же список, что у кнопки «Поместится ли?» (TryOnHub.swift); дерево — справочник кабинета и снимок сайта. */
        let список = ПодборПримерки.разделыГабаритов
        return справочники.внутри(ключ, список) || РазделыСайта.внутри(ключ, список)
    }

    /// Блок «Габариты, см» на шаге «Характеристики».
    var нужныГабариты: Bool {
        guard !форма.раздел.isEmpty else { return false }
        if Self.разделыПоОтказу.contains(форма.раздел) { return Config.габаритыВПодаче }
        return режим == .товар && габаритныйРаздел(форма.раздел)
    }

    /// Без габаритов не опубликовать (и не сохранить правку, если так велит рубильник).
    var обязательныГабариты: Bool {
        нужныГабариты && (!правка || Config.габаритыОбязательныВПравке)
    }

    /// Сервер знает поля dim_* (dims: 1 в корне схемы) — строку в описание не дописываем.
    var габаритыУСервера: Bool { схема?.габаритыПолями == true }

    var габаритыФормы: ГабаритыПодачи { форма.габариты ?? ГабаритыПодачи() }

    /// Рамки раздела формы, см; раздел не из таблицы — от 1 до 1000.
    var рамкиГабаритов: (наибольший: Int, малый: Int) {
        let раздел = форма.раздел
        for запись in ПравилаГабаритовПодачи.рамкиРазделов
        where справочники.внутри(раздел, [запись.раздел]) || РазделыСайта.внутри(раздел, [запись.раздел]) {
            return (запись.наибольший, запись.малый)
        }
        return (ПравилаГабаритовПодачи.пределы.upperBound, 1)
    }

    /// Наибольшая сторона больше рамки раздела — почти наверняка миллиметры. Сырые числа, а не ширинаСм…: те больше
    /// 1000 отбрасывают, а 1200 или 2100 — самые явные миллиметры.
    var габаритыКрупнее: Bool {
        let г = габаритыФормы
        let значения = [г.ширина, г.высота, г.глубина].compactMap { Int($0) }.filter { $0 > 0 }
        guard let наибольшее = значения.max() else { return false }
        return наибольшее > рамкиГабаритов.наибольший
    }

    /// Все три есть, а наибольшая меньше «малого» раздела — не ошибка, но повод проверить единицы.
    var габаритыМельче: Bool {
        guard let п = габаритыФормы.полные else { return false }
        return max(п.ширина, п.высота, п.глубина) < рамкиГабаритов.малый
    }

    /// Проверка блока: пусто, не хватает, не числа, больше рамки раздела. nil — всё хорошо или блок не обязателен.
    func ошибкаГабаритов() -> (поле: String, текст: String)? {
        guard обязательныГабариты else { return nil }
        let т = ГабаритыПодачиText.т
        let ключ = ПравилаГабаритовПодачи.ключОшибки
        let г = габаритыФормы
        let пустые = [("dm_w", г.ширина), ("dm_h", г.высота), ("dm_d", г.глубина)]
            .filter { $0.1.isEmpty }
            .map { т($0.0).lowercased() }
        if пустые.count == 3 { return (ключ, т("dm_need")) }
        if !пустые.isEmpty { return (ключ, String(format: т("dm_need_one"), пустые.joined(separator: ", "))) }
        /* Миллиметры (1200, 2100…) — раньше «не числа»: с ними есть кнопка «перевести в см». */
        if габаритыКрупнее { return (ключ, String(format: т("dm_big"), String(рамкиГабаритов.наибольший))) }
        guard г.полные != nil else { return (ключ, т("dm_bad")) }
        return nil
    }

    /// «Это миллиметры — перевести в см»: каждое значение делим на 10 (не меньше 1 см).
    func габаритыВСантиметры() {
        var г = габаритыФормы
        func десятая(_ текст: String) -> String {
            guard let число = Int(текст), число > 0 else { return текст }
            return String(max(1, Int((Double(число) / 10).rounded())))
        }
        г.ширина = десятая(г.ширина)
        г.высота = десятая(г.высота)
        г.глубина = десятая(г.глубина)
        г.источник = ""
        форма.габариты = г
        показать(ГабаритыПодачиText.т("dm_mm_done"))
    }

    /// Замер линейки AR → поля (что не мерили — остаётся как было).
    func принятьЗамерГабаритов(ширина: Double?, высота: Double?, глубина: Double?) {
        var г = габаритыФормы
        let ш = ПравилаГабаритовПодачи.см(ширина)
        let в = ПравилаГабаритовПодачи.см(высота)
        let гл = ПравилаГабаритовПодачи.см(глубина)
        if !ш.isEmpty { г.ширина = ш }
        if !в.isEmpty { г.высота = в }
        if !гл.isEmpty { г.глубина = гл }
        г.источник = ""
        форма.габариты = г
    }

    // MARK: Предложения

    /**
     Точка для ответа «Распознать» и черновика «Объявления с ИИ» (accept_draft; AIImagePosting.применитьЧерновикИИ
     → принятьПоляЧерновикаИИ → разбор ответа, PostingSend.swift): поля dim_* — предложением. Введённое человеком
     не трогаем; прежнее предложение заменяем.
     */
    func предложитьГабариты(из поля: [String: Any]) {
        guard Config.габаритыВПодаче, var новые = ПравилаГабаритовПодачи.изПолей(поля) else { return }
        if let были = форма.габариты, были.источник.isEmpty, !были.пусто { return }
        новые.источник = "ai"
        форма.габариты = новые
    }

    /**
     Блок пуст и его ещё не трогали (форма.габариты == nil) — ищем размеры в описании и названии: сначала нашу строку,
     потом разбор «Поместится ли?» (FitBoxSize.swift) — вне главной нити. Оценка по диагонали экрана — не предложение.
     */
    func подсказатьГабаритыИзОписания() {
        guard нужныГабариты, форма.габариты == nil else { return }
        let описание = форма.описание
        if var изСтроки = ПравилаГабаритовПодачи.изСтроки(описание) {
            изСтроки.источник = "desc"
            форма.габариты = изСтроки
            return
        }
        guard !(описание + форма.название).trimmingCharacters(in: .whitespacesAndNewlines).isEmpty else { return }
        let исходник = РазборГабаритов.Исходник(раздел: форма.раздел, название: форма.название,
                                                описание: String(описание.prefix(4000)), характеристики: [],
                                                накопитель: nil)
        Task { @MainActor [weak self] in
            let найдено = await Task.detached(priority: .utility) { РазборГабаритов.разобрать(исходник) }.value
            guard let модель = self, модель.форма.габариты == nil, модель.нужныГабариты, !найдено.пусто else { return }
            /* Примерно по диагонали экрана — оценка, а не размеры продавца: в поля её не ставим. */
            if case .диагональ = найдено.источник { return }
            let г = ГабаритыПодачи(ширина: ПравилаГабаритовПодачи.см(найдено.ширина),
                                   высота: ПравилаГабаритовПодачи.см(найдено.высота),
                                   глубина: ПравилаГабаритовПодачи.см(найдено.глубина), источник: "desc")
            guard !г.пусто else { return }
            модель.форма.габариты = г
        }
    }

    /// Правка: габариты из записи my_items (поля, характеристики) или нашей строки в описании — строка уходит из
    /// текста в блок (при сохранении вернётся одна, свежая). Зовёт заполнитьИз, PostingModel.swift.
    func приложитьГабаритыЗаписи(_ з: [String: Any], к ф: inout ФормаПодачи) {
        guard габаритныйРаздел(ф.раздел) else { return }
        let изСтроки = ПравилаГабаритовПодачи.изСтроки(ф.описание)
        if изСтроки != nil { ф.описание = ПравилаГабаритовПодачи.безСтроки(ф.описание) }
        if var изЗаписи = ПравилаГабаритовПодачи.изЗаписи(з) {
            /* Поля сервера — то, что продавец уже подтвердил: не «предложение». */
            изЗаписи.источник = ""
            ф.габариты = изЗаписи
        } else if let изСтроки {
            ф.габариты = изСтроки
        }
    }


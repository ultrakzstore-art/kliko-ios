/// Габариты в форме подачи: целые сантиметры строками, как ввёл человек (пусто — не указано). Codable — и черновик.
struct ГабаритыПодачи: Codable, Equatable {
    var ширина: String = ""
    var высота: String = ""
    var глубина: String = ""
    /// Откуда значения, пока человек их не трогал: "" — ввёл сам, "ai" — Kliko AI или черновик ИИ, "desc" — нашли в
    /// объявлении (характеристики, описание), "tpl" — образец каталога (типичный размер, PostingSizeTemplates.swift).
    var источник: String = ""
    /// Вид товара для образцов, выбранный продавцом («Что это?», «Шины | Диски»): ключ каталога (sofa, fridge, tyre,
    /// rim…); "" — по разделу и названию.
    var вид: String = ""

    init(ширина: String = "", высота: String = "", глубина: String = "", источник: String = "", вид: String = "") {
        self.ширина = ширина
        self.высота = высота
        self.глубина = глубина
        self.источник = источник
        self.вид = вид
    }

    /// Черновик читается терпимо: нет поля — пусто; лишнее в строке — только цифры.
    init(from decoder: Decoder) throws {
        let к = try decoder.container(keyedBy: CodingKeys.self)
        ширина = ПодачаМодель.цифры((try? к.decodeIfPresent(String.self, forKey: .ширина)) ?? "", предел: 4)
        высота = ПодачаМодель.цифры((try? к.decodeIfPresent(String.self, forKey: .высота)) ?? "", предел: 4)
        глубина = ПодачаМодель.цифры((try? к.decodeIfPresent(String.self, forKey: .глубина)) ?? "", предел: 4)
        источник = (try? к.decodeIfPresent(String.self, forKey: .источник)) ?? ""
        вид = (try? к.decodeIfPresent(String.self, forKey: .вид)) ?? ""
    }

    var ширинаСм: Int? { ПравилаГабаритовПодачи.целое(ширина) }
    var высотаСм: Int? { ПравилаГабаритовПодачи.целое(высота) }
    var глубинаСм: Int? { ПравилаГабаритовПодачи.целое(глубина) }

    var пусто: Bool { ширина.isEmpty && высота.isEmpty && глубина.isEmpty }

    /// Все три — целые в пределах (1…1000 см); иначе nil.
    var полные: (ширина: Int, высота: Int, глубина: Int)? {
        guard let ш = ширинаСм, let в = высотаСм, let г = глубинаСм else { return nil }
        return (ш, в, г)
    }

    /// Для сравнения «было — стало» в правке: источник и вид не считаются.
    var снимок: String { пусто ? "" : ширина + "×" + высота + "×" + глубина }

    /// Образец каталога, который продавец не правил: на сервер — с пометкой «примерно».
    var образец: Bool { источник == "tpl" }

    /// «60×85×55 см» — для сводки шага; неполные — nil.
    var сводка: String? {
        guard let п = полные else { return nil }
        return String(п.ширина) + "×" + String(п.высота) + "×" + String(п.глубина) + " " + ГабаритыПодачиText.т("dm_cm")
    }
}

// MARK: - Правила и разбор (чистые функции)

enum ПравилаГабаритовПодачи {
    /// Поля характеристик по соглашению — одна запись с разбором «Поместится ли?» (ГабаритыВещи, FitBoxSize.swift).
    static let ключШирины = ГабаритыВещи.ключШирины
    static let ключВысоты = ГабаритыВещи.ключВысоты
    static let ключГлубины = ГабаритыВещи.ключГлубины
    /// Подписи полей в характеристиках сайта (значения на сервере — по-русски, как остальные).
    static let подписиСайта: [String: String] = ["dim_w": "Ширина, см", "dim_h": "Высота, см", "dim_d": "Глубина, см"]
    /// Ключ строки ошибки под блоком: начинается с «sp_», как у полей схемы, — «Проверьте» раскроет «Характеристики».
    static let ключОшибки = "sp_dims"
    /// Поле тела submit и edit_item: "tpl" — размеры из образца каталога, продавец их не правил (примерно).
    static let ключИсточника = "dims_src"
    /// Ключи фокуса полей (и метки прокрутки) — порядок Ш, В, Г.
    static let ключиФокуса = [ключШирины, ключВысоты, ключГлубины]
    /// Одно значение, см: целое, как ГабаритыВещи.пределы «Поместится ли?» (0,5…1000).
    static let пределы = 1...1000
    /// Начало строки в описании; вся строка — «Габариты (Ш×В×Г): 60×85×55 см».
    static let началоСтроки = ГабаритыВещи.началоСтрокиОписания
    /// Предел описания у формы (ТекстПодачи) — строка габаритов в него помещается.
    static let пределОписания = 5000

    /**
     Разумные размеры раздела, см: наибольшая сторона не больше «наибольшего» (больше — почти всегда миллиметры) и не
     меньше «малого» (меньше — повод проверить). Та же таблица, что у разбора «Поместится ли?»
     (РазборГабаритов.таблицаРамок, FitBoxSize.swift): с другими рамками он отказался бы от размеров, принятых здесь.
     */
    static let рамкиРазделов: [(раздел: String, наибольший: Int, малый: Int)] = РазборГабаритов.таблицаРамок.map {
        (раздел: $0.раздел, наибольший: Int($0.наибольший), малый: Int($0.малый))
    }

    /// Целое в пределах: «60», «060»; пусто, ноль и больше 1000 — nil.
    static func целое(_ текст: String) -> Int? {
        guard let число = Int(текст), пределы.contains(число) else { return nil }
        return число
    }

    /// Число из ответа сервера (60, "60", "59,5") → целые сантиметры строкой; вне пределов — пусто.
    static func см(_ значение: Any?) -> String {
        let число: Double
        if let д = значение as? Double {
            число = д
        } else if let ц = значение as? Int {
            число = Double(ц)
        } else if let н = значение as? NSNumber {
            число = н.doubleValue
        } else if let т = значение as? String {
            число = Double(т.trimmingCharacters(in: .whitespaces).replacingOccurrences(of: ",", with: ".")) ?? 0
        } else {
            return ""
        }
        guard число.isFinite, число >= 0.5, число <= Double(пределы.upperBound) else { return "" }
        return String(max(1, Int(число.rounded())))
    }

    /// «Габариты (Ш×В×Г): 60×85×55 см» — запись соглашения (ГабаритыВещи.строкаОписания); у образца каталога — с
    /// пометкой «(примерно)» в конце (её читает разбор «Поместится ли?»).
    static func строка(ширина: Int, высота: Int, глубина: Int, примерно: Bool = false) -> String {
        let строка = ГабаритыВещи(ширина: Double(ширина), высота: Double(высота), глубина: Double(глубина)).строкаОписания
        return примерно ? строка + " " + ГабаритыВещи.пометкаОбразца : строка
    }

    /// В нашей строке есть пометка «(примерно)» — это образец каталога, а не замер.
    static func строкаОбразца(_ строка: String) -> Bool {
        строка.lowercased().contains("примерн")
    }

    /// Это наша строка (терпимо к «x», «х», «*» и пробелам).
    static func этоСтрока(_ строка: String) -> Bool {
        let чистая = строка.lowercased()
            .replacingOccurrences(of: " ", with: "")
            .replacingOccurrences(of: "\t", with: "")
            .replacingOccurrences(of: "x", with: "×")
            .replacingOccurrences(of: "х", with: "×")
            .replacingOccurrences(of: "*", with: "×")
        return чистая.hasPrefix("габариты(ш×в×г):")
    }

    /// Описание без нашей строки (любой по счёту) и без пустого хвоста после неё.
    static func безСтроки(_ описание: String) -> String {
        let строки = описание.components(separatedBy: "\n")
        guard строки.contains(where: { этоСтрока($0) }) else { return описание }
        return безХвоста(строки.filter { !этоСтрока($0) }.joined(separator: "\n"))
    }

    /// Описание со строкой габаритов в конце: прежняя убирается, общий предел описания соблюдается.
    static func сСтрокой(_ описание: String, ширина: Int, высота: Int, глубина: Int, примерно: Bool = false) -> String {
        let добавка = Self.строка(ширина: ширина, высота: высота, глубина: глубина, примерно: примерно)
        var основа = безХвоста(безСтроки(описание))
        let нужно = добавка.count + 2
        if основа.count + нужно > пределОписания {
            основа = безХвоста(String(основа.prefix(max(0, пределОписания - нужно))))
        }
        return основа.isEmpty ? добавка : основа + "\n\n" + добавка
    }

    /// Наша строка в описании → значения (последняя, если их несколько); с пометкой «(примерно)» — источник "tpl".
    static func изСтроки(_ описание: String) -> ГабаритыПодачи? {
        for строка in описание.components(separatedBy: "\n").reversed() where этоСтрока(строка) {
            guard let двоеточие = строка.firstIndex(of: ":") else { continue }
            let хвост = String(строка[строка.index(after: двоеточие)...])
            let числа = числаСтроки(хвост)
            guard числа.count >= 3 else { continue }
            let г = ГабаритыПодачи(ширина: см(числа[0]), высота: см(числа[1]), глубина: см(числа[2]),
                                   источник: строкаОбразца(хвост) ? "tpl" : "")
            if !г.пусто { return г }
        }
        return nil
    }

    /**
     Поля ответа сервера (recognize, accept_draft, запись my_items): dim_w · dim_h · dim_d; запасные виды — объект
     dims {w, h, d} и строка dimensions «60×85×55» (Ш×В×Г). Ничего — nil.
     */
    static func изПолей(_ поля: [String: Any]) -> ГабаритыПодачи? {
        var г = ГабаритыПодачи(ширина: см(поля[ключШирины]), высота: см(поля[ключВысоты]), глубина: см(поля[ключГлубины]))
        if let объект = поля["dims"] as? [String: Any] {
            if г.ширина.isEmpty { г.ширина = см(объект["w"]) }
            if г.высота.isEmpty { г.высота = см(объект["h"]) }
            if г.глубина.isEmpty { г.глубина = см(объект["d"]) }
        }
        if г.пусто, let строка = поля["dimensions"] as? String {
            let числа = числаСтроки(строка)
            if числа.count >= 3 {
                г = ГабаритыПодачи(ширина: см(числа[0]), высота: см(числа[1]), глубина: см(числа[2]))
            }
        }
        return г.пусто ? nil : г
    }

    /// Запись my_items: поля dim_*, потом характеристики (specs · characteristics · attrs) — по ключу или нашей подписи.
    static func изЗаписи(_ з: [String: Any]) -> ГабаритыПодачи? {
        if let г = изПолей(з) { return г }
        for имя in ["characteristics", "specs", "attrs"] {
            var пары: [(ключ: String, подпись: String, значение: Any?)] = []
            if let список = з[имя] as? [Any] {
                for пункт in список {
                    guard let п = пункт as? [String: Any] else { continue }
                    let подпись = (п["label"] as? String) ?? (п["n"] as? String) ?? ""
                    пары.append((ключ: (п["key"] as? String) ?? "", подпись: подпись, значение: п["value"] ?? п["v"]))
                }
            } else if let словарь = з[имя] as? [String: Any] {
                for (ключ, значение) in словарь { пары.append((ключ: ключ, подпись: ключ, значение: значение)) }
            }
            var г = ГабаритыПодачи()
            for пара in пары {
                let ключ = пара.ключ.lowercased()
                let подпись = пара.подпись.trimmingCharacters(in: .whitespaces)
                if ключ == ключШирины || подпись == подписиСайта[ключШирины] {
                    г.ширина = см(пара.значение)
                } else if ключ == ключВысоты || подпись == подписиСайта[ключВысоты] {
                    г.высота = см(пара.значение)
                } else if ключ == ключГлубины || подпись == подписиСайта[ключГлубины] {
                    г.глубина = см(пара.значение)
                }
            }
            if !г.пусто { return г }
        }
        return nil
    }

    /// Числа строки по порядку: «60×85×55 см» → [60, 85, 55]; дробь — через точку или запятую.
    private static func числаСтроки(_ текст: String) -> [Double] {
        guard let выражение = try? NSRegularExpression(pattern: "\\d{1,5}(?:[.,]\\d{1,2})?") else { return [] }
        let весь = NSRange(текст.startIndex..<текст.endIndex, in: текст)
        return выражение.matches(in: текст, range: весь).compactMap { с in
            guard let место = Range(с.range, in: текст) else { return nil }
            return Double(String(текст[место]).replacingOccurrences(of: ",", with: "."))
        }
    }

    /// Без пробелов и переводов строки в конце.
    private static func безХвоста(_ текст: String) -> String {
        var итог = текст
        while let последний = итог.last, последний.isWhitespace || последний.isNewline { итог.removeLast() }
        return итог
    }
}


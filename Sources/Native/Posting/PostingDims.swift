/**
 ОБЯЗАТЕЛЬНЫЕ ГАБАРИТЫ В ПОДАЧЕ (владелец 14.10.2026: «габариты обязательно на будущее» — чтобы у мебели и крупной
 техники работало «Поместится ли?», TryOn/FitBox*.swift).

 Разделы — тот же список, что у «Поместится ли?» (ПодборПримерки.разделыГабаритов, TryOn/TryOnHub.swift: вся мебель и
 детская, крупная техника, ТВ и мониторы, ковры, тренажёры, аквариумы) вместе с потомками; схема сайта может сказать иначе
 (категория dims: true|false в api/app_post_schema.php) — тогда главнее она. В таких разделах на шаге «Характеристики»
 свой блок «Габариты, см» (PostingDimsView.swift): три поля Ш/В/Г, цифровая клавиатура, рисунок коробки со стрелками,
 «где взять». Блок обязательный: без него «Далее» на шаге и «Опубликовать» (и «Сохранить» в правке) ставят строку
 ошибки под блоком и прокручивают к нему; в коротком пути с камеры «Характеристики» раскрываются сами (ключ ошибки
 начинается с «sp_», как у полей схемы).

 ОБЩЕЕ СОГЛАШЕНИЕ (docs/SERVER_DIMENSIONS.md): в характеристиках объявления — поля dim_w, dim_h, dim_d, целые
 сантиметры (ширина, высота, глубина), подписи «Ширина, см», «Высота, см», «Глубина, см». submit и edit_item получают их
 всегда, когда блок на экране и заполнен. Пока сервер о них не объявил (нет dims: 1 в корне схемы) — в конец описания
 дописывается строка «Габариты (Ш×В×Г): 60×85×55 см» (её понимает разбор FitBoxSize); прежняя строка заменяется, а не
 повторяется.

 Откуда берутся значения, кроме ввода: ответ «Распознать» и черновик «Объявления с ИИ» (поля dim_*), запись my_items
 при правке (dim_*, характеристики, наша строка в описании — строка уходит из текста в блок), а если блок пуст —
 разбор описания (РазборГабаритов, FitBoxSize.swift). Всё не введённое руками — «предложение» с пометкой «проверьте».
 */

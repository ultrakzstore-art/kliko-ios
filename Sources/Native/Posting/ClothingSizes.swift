extension ПодачаМодель {
    /// Набор таблиц раздела формы (название решает вкладку обуви и перчатки); nil — не одежда и не обувь, не товар,
    /// выключено (Config.размерыОдеждыВПодаче).
    var наборРазмеровОдежды: НаборРазмеровОдежды? {
        guard Config.размерыОдеждыВПодаче, режим == .товар, !форма.раздел.isEmpty else { return nil }
        return НаборРазмеровОдежды.для(цепочки: цепочкаРазделаРазмеров(форма.раздел), название: форма.название)
    }

    /**
     Раздел или название сменились: наша строка «Размер: …» уходит из описания, если раздел больше не про размеры
     (электроника, ремни) или его таблицы её не узнают (обувь → головные уборы). Те же таблицы (женская обувь → мужская)
     — строка остаётся, блок восстановит по ней выбор. Пока форма заполняется (черновик, правка) и при выключенном
     рубильнике строку не трогаем.
     */
    func убратьЧужуюСтрокуРазмера() {
        guard Config.размерыОдеждыВПодаче, !заполняем,
              СтрокаРазмераВсехСистем.из(описания: форма.описание) != nil else { return }
        if let набор = наборРазмеровОдежды, ПравилаРазмераОдежды.найти(форма.описание, в: набор) != nil { return }
        let без = ПравилаРазмераОдежды.безСтроки(форма.описание)
        if без != форма.описание { форма.описание = без }
    }

    /// Поле размера схемы, которое рисует блок «Размер» (слот storage с подписью размера или возраста) или nil.
    var полеРазмераОдежды: ПолеХарактеристики? {
        guard наборРазмеровОдежды != nil else { return nil }
        return характеристики.first(where: { ПравилаРазмераОдежды.этоРазмер($0) })
    }

    /// Это поле рисует блок «Размер» — в сетке характеристик его нет.
    func этоПолеРазмераОдежды(_ поле: ПолеХарактеристики) -> Bool {
        guard ПравилаРазмераОдежды.этоРазмер(поле) else { return false }
        return наборРазмеровОдежды != nil
    }

    /// Раздел и его предки снизу вверх: справочники страницы, схема сайта, снимок дерева — что знает родителя.
    func цепочкаРазделаРазмеров(_ раздел: String) -> [String] {
        var итог: [String] = []
        var текущий: String? = раздел
        var шаги = 0
        while let узел = текущий, !узел.isEmpty, шаги < 25, !итог.contains(узел) {
            итог.append(узел)
            let родители: [String?] = [справочники.разделы[узел]?.родитель, схема?.разделы[узел]?.родитель,
                                       РазделыСайта.дерево[узел]?.родитель]
            текущий = родители.compactMap { $0 }.first(where: { !$0.isEmpty })
            шаги += 1
        }
        return итог
    }
}

// MARK: - Правила: поле, описание, сравнение

enum ПравилаРазмераОдежды {
    /// Слот объявления у поля размера (фасет «Размер» и «Возраст» витрины, FeedFilters.swift).
    static let слот = "storage"
    /// Начало нашей строки в описании.
    static let начало = "Размер:"
    /// Предел описания у формы (ТекстПодачи).
    static let пределОписания = 5000

    /// Поле схемы — размер: слот storage, не год, подпись — размер, рост или возраст на любом из языков.
    static func этоРазмер(_ поле: ПолеХарактеристики) -> Bool {
        guard поле.поле == слот, !поле.год else { return false }
        return подписьРазмера(поле.подпись)
    }

    static func подписьРазмера(_ подпись: String) -> Bool {
        let н = подпись.lowercased()
        let слова = н.split(whereSeparator: { !$0.isLetter }).map(String.init)
        let корни = ["размер", "өлшем", "size", "возраст", "жас", "age", "рост", "бой", "height"]
        if слова.contains(where: { с in корни.contains { с.hasPrefix($0) } }) { return true }
        return ["مقاس", "عمر", "طول"].contains { н.contains($0) }
    }

    static func подписьВозраста(_ подпись: String) -> Bool {
        let н = подпись.lowercased()
        let слова = н.split(whereSeparator: { !$0.isLetter }).map(String.init)
        if слова.contains(where: { с in ["возраст", "жас", "age"].contains { с.hasPrefix($0) } }) { return true }
        return н.contains("عمر")
    }

    // MARK: Нормализация

    /// Ключ сравнения: строчные, «,» → «.», тире → «-», неразрывный пробел и изоляция прочь, кириллица-двойник → латиница
    /// («М» → «m», «ХL» → «xl», «75В» → «75b»), пробелы у дефиса убраны.
    static func ключ(_ значение: String) -> String {
        var s = значение.lowercased()
        let замены: [(String, String)] = [("\u{00A0}", " "), ("\u{2066}", ""), ("\u{2069}", ""), (",", "."),
                                          ("–", "-"), ("—", "-"), ("−", "-"), ("а", "a"), ("в", "b"), ("с", "c"),
                                          ("е", "e"), ("н", "h"), ("к", "k"), ("м", "m"), ("о", "o"), ("р", "p"),
                                          ("т", "t"), ("х", "x")]
        for (из, в) in замены { s = s.replacingOccurrences(of: из, with: в) }
        while s.contains("  ") { s = s.replacingOccurrences(of: "  ", with: " ") }
        s = s.replacingOccurrences(of: " -", with: "-").replacingOccurrences(of: "- ", with: "-")
        return s.trimmingCharacters(in: .whitespaces)
    }

    /// Слова ключа: разделители — пробел, скобки, «/», «-», «;», «:», «|», «·».
    static func слова(_ текст: String) -> [String] {
        ключ(текст).split(whereSeparator: { " ()/-;:|·[]".contains($0) }).map(String.init).filter { !$0.isEmpty }
    }

    /// Число целиком: «37.5», «42»; иначе nil.
    static func число(_ текст: String) -> Double? {
        let к = ключ(текст)
        guard !к.isEmpty, к.allSatisfy({ $0.isNumber || $0 == "." }) else { return nil }
        return Double(к)
    }

    /// Все числа строки по порядку: «1–1.5 года» → [1, 1.5].
    static func числа(_ текст: String) -> [Double] {
        var итог: [Double] = []
        var кусок = ""
        for символ in ключ(текст) + " " {
            if символ.isASCII && (символ.isNumber || (символ == "." && !кусок.isEmpty)) {
                кусок.append(символ)
            } else {
                if let ч = Double(кусок) { итог.append(ч) }
                кусок = ""
            }
        }
        return итог
    }

    /// Меньшая половина «44–46» → «44», «S–M» → «S»; без тире — nil.
    static func доТире(_ значение: String) -> String? {
        for тире in ["–", "—", "-"] {
            if let р = значение.range(of: тире) {
                let левое = значение[..<р.lowerBound].trimmingCharacters(in: .whitespaces)
                return левое.isEmpty ? nil : левое
            }
        }
        return nil
    }

    /// Возраст в годах: «7–8 лет» → 7…8, «6–9 мес» → 0.5…0.75; без чисел — nil.
    static func диапазонЛет(_ текст: String) -> ClosedRange<Double>? {
        let ч = числа(текст)
        guard let а = ч.first, let б = ч.last else { return nil }
        let н = текст.lowercased()
        let доля: Double = (н.contains("мес") || н.contains("ай") || н.contains("month")) ? 1.0 / 12.0 : 1
        return min(а, б) * доля...max(а, б) * доля
    }

    // MARK: Значение поля сайта

    /// Что поставить в поле сайта; nil — подходящего нет (поле пустеет, его выберут меню на бирке).
    static func значениеПоля(_ в: ВкладкаРазмеровОдежды, _ выбор: ВыборРазмераОдежды,
                             _ поле: ПолеХарактеристики) -> String? {
        let сайт = в.системаПоля(поле)
        let кандидаты = в.кандидатыСайта(выбор, сайт: сайт)
        guard let первый = кандидаты.first else { return nil }
        let своё = сайт == "Возраст" ? первый : (доТире(первый) ?? первый)
        if поле.вводом {
            if поле.числом, число(своё) == nil {
                return кандидаты.first(where: { число($0) != nil })
            }
            return своё
        }
        let возраст = в.система("Возраст").map { в.значение(выбор, $0) }
        if let найдено = изСписка(кандидаты, поле.вариантыСПодписью, возраст: возраст) {
            return найдено
        }
        return поле.своё ? своё : nil
    }

    /**
     Значение из вариантов поля: точное (ключ или подпись), потом слово внутри подписи («46 (M)», «EU 42»), потом
     ближайшее число к первому кандидату не дальше 1 (37.5 → 37, при равенстве — меньшее), потом возраст: вариант, в
     диапазон которого попадает середина нашего, или ближайший не дальше года.
     */
    static func изСписка(_ кандидаты: [String], _ варианты: [ВариантПоля], возраст: String?) -> String? {
        guard !варианты.isEmpty, !кандидаты.isEmpty else { return nil }
        let ключи = варианты.map { (в: $0, к: ключ($0.ключ), п: ключ($0.подпись)) }
        for к in кандидаты {
            let н = ключ(к)
            if let найдено = ключи.first(where: { $0.к == н || $0.п == н }) { return найдено.в.ключ }
        }
        for к in кандидаты {
            let н = ключ(к)
            guard !н.isEmpty, !н.contains(" ") else { continue }
            if let найдено = ключи.first(where: { слова($0.в.ключ).contains(н) || слова($0.в.подпись).contains(н) }) {
                return найдено.в.ключ
            }
        }
        if let ц = число(кандидаты[0]) {
            var лучший: (ключ: String, x: Double, разница: Double)? = nil
            for в in варианты {
                guard let x = число(в.ключ) ?? число(в.подпись) else { continue }
                let р = abs(x - ц)
                guard р <= 1.0 else { continue }
                if лучший == nil || р < лучший!.разница || (р == лучший!.разница && x < лучший!.x) {
                    лучший = (в.ключ, x, р)
                }
            }
            if let лучший { return лучший.ключ }
        }
        if let возраст, let наш = диапазонЛет(возраст) {
            let середина = (наш.lowerBound + наш.upperBound) / 2
            var лучший: (ключ: String, разница: Double, начало: Double)? = nil
            for в in варианты {
                guard let их = диапазонЛет(в.ключ) ?? диапазонЛет(в.подпись) else { continue }
                let р = их.contains(середина) ? 0 : min(abs(их.lowerBound - середина), abs(их.upperBound - середина))
                guard р <= 1.0 else { continue }
                /* Равно далеко («14–15 лет» между «12-14» и «14+») — ближе начало: «14+». */
                let н = abs(их.lowerBound - наш.lowerBound)
                if лучший == nil || р < лучший!.разница || (р == лучший!.разница && н < лучший!.начало) {
                    лучший = (в.ключ, р, н)
                }
            }
            if let лучший { return лучший.ключ }
        }
        return nil
    }

    /// Обратно: значение поля (правка, черновик, Kliko AI) → выбор в наборе — система сайта, потом INT и возраст.
    static func изЗначенияПоля(_ значение: String, в набор: НаборРазмеровОдежды, начальная: String,
                               поле: ПолеХарактеристики?) -> ВыборРазмераОдежды? {
        let н = ключ(значение)
        guard !н.isEmpty else { return nil }
        let порядок = набор.вкладки.filter { $0.ключ == начальная } + набор.вкладки.filter { $0.ключ != начальная }
        for в in порядок {
            for код in [в.системаПоля(поле), "INT", "Возраст"] {
                guard let с = в.система(код) else { continue }
                for чип in в.основная.чипы(с.первый) {
                    let з = чип.значение
                    if ключ(з) == н || (код != "Возраст" && доТире(з).map { ключ($0) } == н) {
                        return ВыборРазмераОдежды(вкладка: в.ключ, ряд: чип.id, ряд2: nil)
                    }
                }
            }
        }
        return nil
    }

    // MARK: Строка описания

    /// Склейка одинаковых соседей: «EU 128 · RU 128» → «EU/RU 128», «UK 34B · US 34B» → «UK/US 34B». Сантиметры,
    /// возраст и W не склеиваются (MEX 27 и 27 см — обе, как на бирке).
    static func склеить(_ части: [ЧастьБиркиРазмера]) -> [ЧастьБиркиРазмера] {
        var итог: [ЧастьБиркиРазмера] = []
        for ч in части {
            if let прежняя = итог.last, простой(прежняя.код), простой(ч.код),
               ключ(прежняя.значение) == ключ(ч.значение) {
                итог[итог.count - 1] = ЧастьБиркиРазмера(код: прежняя.код + "/" + ч.код, значение: ч.значение)
            } else {
                итог.append(ч)
            }
        }
        return итог
    }

    private static func простой(_ код: String) -> Bool {
        код != "W" && ТаблицаРазмеровОдежды.вид(код) == .система
    }

    /// Наша строка: «Размер:» и хотя бы две узнанные системы.
    static func этоСтрока(_ строка: String) -> Bool { СтрокаРазмераВсехСистем.разобрать(строка) != nil }

    /// Длина описания для минимума (10 знаков): без нашей строки и пробелов по краям — строку дописало приложение, она
    /// не заменяет описание продавца.
    static func длинаОписания(_ описание: String) -> Int {
        безСтроки(описание).trimmingCharacters(in: .whitespacesAndNewlines).count
    }

    /// Описание без нашей строки (любой по счёту) и без пустого хвоста после неё.
    static func безСтроки(_ описание: String) -> String {
        let строки = описание.components(separatedBy: "\n")
        guard строки.contains(where: { этоСтрока($0) }) else { return описание }
        return безХвоста(строки.filter { !этоСтрока($0) }.joined(separator: "\n"))
    }

    /// Описание с нашей строкой в конце: прежняя убирается, предел описания соблюдается.
    static func сСтрокой(_ описание: String, _ строка: String) -> String {
        var основа = безХвоста(безСтроки(описание))
        let нужно = строка.count + 2
        if основа.count + нужно > пределОписания {
            основа = безХвоста(String(основа.prefix(max(0, пределОписания - нужно))))
        }
        return основа.isEmpty ? строка : основа + "\n\n" + строка
    }

    static func безХвоста(_ текст: String) -> String {
        var s = текст
        while let последний = s.last, последний.isWhitespace || последний.isNewline { s.removeLast() }
        return s
    }

    /// Выбор по нашей строке в описании (черновик, правка) — среди вкладок набора.
    static func найти(_ описание: String, в набор: НаборРазмеровОдежды) -> ВыборРазмераОдежды? {
        guard let строка = СтрокаРазмераВсехСистем.из(описания: описание) else { return nil }
        return строка.лучший(набор.вкладки)?.выбор
    }

    /// Тот же размер в другой вкладке по общей системе (EU 38 женской обуви → EU 38 мужской); нет — nil.
    static func тотЖеРазмер(_ выбор: ВыборРазмераОдежды, из старая: ВкладкаРазмеровОдежды,
                            в новая: ВкладкаРазмеровОдежды) -> Int? {
        var коды = [новая.системаСайта]
        for с in новая.системы where !коды.contains(с.код) { коды.append(с.код) }
        for код in коды {
            guard let было = старая.система(код), let стало = новая.система(код) else { continue }
            let з = ключ(старая.основная.значение(выбор.ряд, было.первый))
            guard !з.isEmpty else { continue }
            if let чип = новая.основная.чипы(стало.первый).first(where: { ключ($0.значение) == з }) { return чип.id }
        }
        return nil
    }
}


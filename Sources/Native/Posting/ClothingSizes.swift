/// Вкладки раздела формы. Ключ — раздел дерева, по которому набор найден (для .id блока).
struct НаборРазмеровОдежды: Equatable {
    let ключ: String
    let вкладки: [ВкладкаРазмеровОдежды]
    let начальная: String

    func вкладка(_ ключ: String) -> ВкладкаРазмеровОдежды? { вкладки.first { $0.ключ == ключ } }

    /**
     Набор по цепочке «раздел → … → корень»: первый узел снизу, у которого он есть. Вкладка обуви — по полу в ключе
     раздела или подраздела ниже (womens-, mens-, kids-), в нейтральном разделе (shoes, sport-shoes — там кроссовки) —
     по названию («мужские», «детские»), иначе «Мужская», а не всегда «Женская». «Ремни, шарфы, перчатки» — таблица
     перчаток только у перчаток по названию; у ремней и шарфов таблицы нет — и блока нет.
     */
    static func для(цепочки: [String], название: String = "") -> НаборРазмеровОдежды? {
        for (номер, узел) in цепочки.enumerated() {
            if узел == "belts-scarves" {
                return этоПерчатки(название) ? набор(узел, [ТаблицыРазмеровОдежды.вкладкаПерчаток]) : nil
            }
            guard let н = поРазделу(узел) else { continue }
            /* Не обувь (нет вкладок «Женская» и «Детская») — вкладка набора как есть. */
            guard н.вкладка("w") != nil, н.вкладка("k") != nil else { return н }
            var своя = цепочки[...номер].compactMap { вкладкаОбуви($0) }.first
            if своя == nil && нейтральнаяОбувь.contains(узел) { своя = вкладкаОбуви(название) }
            return НаборРазмеровОдежды(ключ: н.ключ, вкладки: н.вкладки, начальная: своя ?? н.начальная)
        }
        return nil
    }

    /// Разделы обуви без пола: вкладка — по названию, иначе «Мужская».
    private static let нейтральнаяОбувь: Set<String> = ["shoes", "sport-shoes"]

    /// Вкладка обуви по словам ключа раздела или названия: детская («kids», «girls», «детские», «для мальчика»),
    /// женская («womens», «женские», «жен.», «әйелдер»), мужская («mens», «мужские», «муж.», «ерлер»); nil — пол не
    /// назван.
    static func вкладкаОбуви(_ текст: String) -> String? {
        let слова = текст.lowercased().split(whereSeparator: { !$0.isLetter }).map(String.init)
        func есть(_ точные: Set<String>, _ начала: [String]) -> Bool {
            слова.contains { с in точные.contains(с) || начала.contains { с.hasPrefix($0) } }
        }
        if есть(["kid", "kids", "child", "children", "baby", "boy", "boys", "girl", "girls", "junior", "дет"],
                ["детск", "ребен", "ребён", "мальчик", "девочк", "малыш", "школьн", "балалар"]) { return "k" }
        if есть(["women", "womens", "woman", "female", "ladies", "lady", "жен"],
                ["женск", "женщин", "әйел"]) { return "w" }
        if есть(["men", "mens", "man", "male", "муж"], ["мужск", "мужчин", "ерлер"]) { return "m" }
        return nil
    }

    /// Перчатки или варежки в названии — у них таблица перчаток (раздел «Ремни, шарфы, перчатки» общий).
    static func этоПерчатки(_ название: String) -> Bool {
        let н = название.lowercased()
        return ["перчат", "варежк", "рукавиц", "митенк", "қолғап", "glove", "mitten"].contains { н.contains($0) }
    }

    private static func набор(_ ключ: String, _ вкладки: [ВкладкаРазмеровОдежды],
                              начальная: String? = nil) -> НаборРазмеровОдежды {
        НаборРазмеровОдежды(ключ: ключ, вкладки: вкладки, начальная: начальная ?? вкладки[0].ключ)
    }

    /// Разделы сайта (SiteCategories.swift): clothing → womens-*, mens-*, kids-clothing-*, shoes, bags-accessories
    /// (hats; belts-scarves — перчатки по названию, в для(цепочки:)), jewelry → rings; kids → kids-clothing-0-12,
    /// school-uniform; sport → hiking-boots, ice-skates. Отдельного раздела белья нет — бельё вкладкой у женской одежды
    /// и верха.
    private static func поРазделу(_ раздел: String) -> НаборРазмеровОдежды? {
        typealias Т = ТаблицыРазмеровОдежды
        let обувь = [Т.вкладкаЖенскойОбуви, Т.вкладкаМужскойОбуви, Т.вкладкаДетскойОбуви]
        switch раздел {
        case "womens-shoes":
            return набор(раздел, обувь, начальная: "w")
        case "mens-shoes", "shoes", "sport-shoes", "hiking-boots", "ice-skates":
            return набор(раздел, обувь, начальная: "m")
        case "kids-shoes":
            return набор(раздел, обувь, начальная: "k")
        case "womens-clothing":
            return набор(раздел, [Т.вкладкаЖенскойОдежды, Т.вкладкаЖенскихДжинсов, Т.вкладкаБелья])
        case "womens-bottoms":
            return набор(раздел, [Т.вкладкаЖенскойОдежды, Т.вкладкаЖенскихДжинсов])
        case "womens-tops":
            return набор(раздел, [Т.вкладкаЖенскойОдежды, Т.вкладкаБелья])
        case "womens-dresses", "womens-outerwear", "womens-sportswear":
            return набор(раздел, [Т.вкладкаЖенскойОдежды])
        case "mens-clothing", "mens-bottoms":
            return набор(раздел, [Т.вкладкаМужскойОдежды, Т.вкладкаМужскихДжинсов])
        case "mens-tops", "mens-outerwear", "mens-suits", "mens-sportswear":
            return набор(раздел, [Т.вкладкаМужскойОдежды])
        case "kids-clothing":
            return набор(раздел, [Т.вкладкаРоста])
        case "kids-clothing-0-12", "school-uniform":
            return набор(раздел, [Т.вкладкаВозраста])
        case "rings":
            return набор(раздел, [Т.вкладкаКолец])
        case "hats":
            return набор(раздел, [Т.вкладкаШапок])
        default:
            return nil
        }
    }

    /// Цепочка по снимку дерева сайта (без модели подачи) — для бирки в окне объявления.
    static func цепочка(_ раздел: String) -> [String] {
        var итог: [String] = []
        var текущий: String? = раздел
        var шаги = 0
        while let узел = текущий, !узел.isEmpty, шаги < 25, !итог.contains(узел) {
            итог.append(узел)
            текущий = РазделыСайта.дерево[узел]?.родитель
            шаги += 1
        }
        return итог
    }

/**
 Строка «Размер: EU 42 · RU 41 · US M 9 · UK 8 · MEX 27 · 27 см» из описания → части и бирка. Понимает склейки
 («EU/RU 29»), «W32 L32», «27 см», возраст («7–8 лет»), разделители «·» и «|». Меньше двух узнанных систем — не наша
 строка (продавец написал «Размер: 42» сам) — nil.

 Для окна объявления (Design/SiteListing.swift — правит другая пачка): перед БлокОписанияВида
     if let бирка = СтрокаРазмераВсехСистем.бирка(описание: товар.описание ?? "", раздел: товар.категория) {
         БиркаРазмераОбъявления(данные: бирка)
     }
 а в описании для экрана строку можно убрать: ПравилаРазмераОдежды.безСтроки(описание).
 */
struct СтрокаРазмераВсехСистем: Equatable {
    let части: [ЧастьБиркиРазмера]

    /// Последняя наша строка описания или nil.
    static func из(описания: String) -> СтрокаРазмераВсехСистем? {
        for строка in описания.components(separatedBy: .newlines).reversed() {
            if let р = разобрать(строка) { return р }
        }
        return nil
    }

    static func разобрать(_ строка: String) -> СтрокаРазмераВсехСистем? {
        let чистая = строка.trimmingCharacters(in: .whitespacesAndNewlines)
        guard let хвост = послеНачала(чистая) else { return nil }
        let куски = хвост.components(separatedBy: CharacterSet(charactersIn: "·|"))
            .map { $0.trimmingCharacters(in: .whitespacesAndNewlines) }
            .filter { !$0.isEmpty }
        let части = куски.compactMap { часть(из: $0) }
        guard части.count >= 2 else { return nil }
        return СтрокаРазмераВсехСистем(части: части)
    }

    private static func послеНачала(_ строка: String) -> String? {
        for начало in [ПравилаРазмераОдежды.начало, "Size:"] where строка.lowercased().hasPrefix(начало.lowercased()) {
            return String(строка.dropFirst(начало.count))
        }
        return nil
    }

    /// Коды систем всех таблиц, длинные раньше («US W» прежде «US»).
    static let известныеКоды: [String] = {
        var коды = Set<String>()
        for в in ТаблицыРазмеровОдежды.всеВкладки {
            for с in в.системы where ТаблицаРазмеровОдежды.вид(с.код) == .система && с.код != "W" { коды.insert(с.код) }
        }
        return коды.sorted { $0.count != $1.count ? $0.count > $1.count : $0 < $1 }
    }()

    /// Кусок строки → часть: «27 см», «W32 L32», «US W 6.5», «EU/RU 29», «7–8 лет».
    static func часть(из кусок: String) -> ЧастьБиркиРазмера? {
        var к = кусок.replacingOccurrences(of: "\u{00A0}", with: " ")
        к = к.replacingOccurrences(of: "\u{2066}", with: "").replacingOccurrences(of: "\u{2069}", with: "")
        к = к.trimmingCharacters(in: .whitespaces)
        guard !к.isEmpty else { return nil }
        let строчные = к.lowercased()
        for хвост in [" см", " cm"] where строчные.hasSuffix(хвост) {
            let значение = String(к.dropLast(хвост.count)).trimmingCharacters(in: .whitespaces)
            if ПравилаРазмераОдежды.число(значение) != nil { return ЧастьБиркиРазмера(код: "CM", значение: значение) }
        }
        if к.hasPrefix("W"), let второй = к.dropFirst().first, второй.isNumber {
            return ЧастьБиркиРазмера(код: "W", значение: String(к.dropFirst()))
        }
        for код in известныеКоды where к.hasPrefix(код + " ") {
            let значение = String(к.dropFirst(код.count + 1)).trimmingCharacters(in: .whitespaces)
            if !значение.isEmpty { return ЧастьБиркиРазмера(код: код, значение: значение) }
        }
        if let пробел = к.firstIndex(of: " ") {
            let слово = String(к[..<пробел])
            let куски = слово.components(separatedBy: "/")
            if куски.count > 1, куски.allSatisfy({ известныеКоды.contains($0) }) {
                let значение = String(к[к.index(after: пробел)...]).trimmingCharacters(in: .whitespaces)
                if !значение.isEmpty { return ЧастьБиркиРазмера(код: слово, значение: значение) }
            }
        }
        if строчные.contains("мес") || строчные.contains("год") || строчные.contains("лет") {
            return ЧастьБиркиРазмера(код: "Возраст", значение: к)
        }
        return nil
    }

    /// Ключи сравнения с разобранными склейками: «EU/RU 29» → «EU/RU|29», «EU|29», «RU|29».
    var ключи: Set<String> {
        var итог = Set<String>()
        for ч in части {
            итог.insert(ч.ключСравнения)
            let коды = ч.код.components(separatedBy: "/")
            if коды.count > 1 {
                for код in коды { итог.insert(ЧастьБиркиРазмера(код: код, значение: ч.значение).ключСравнения) }
            }
        }
        return итог
    }

    /// Лучший ряд среди вкладок: больше всего совпавших систем, при равенстве — меньше лишних. Меньше двух — nil.
    func лучший(_ вкладки: [ВкладкаРазмеровОдежды]) -> (вкладка: ВкладкаРазмеровОдежды, выбор: ВыборРазмераОдежды)? {
        let наши = ключи
        var итог: (вкладка: ВкладкаРазмеровОдежды, выбор: ВыборРазмераОдежды)? = nil
        var счёт = 0
        var лишних = Int.max
        for в in вкладки {
            let вторые: [Int?] = [nil] + (в.вторая.map { Array($0.ряды.indices) } ?? []).map { Optional($0) }
            for ряд in в.основная.ряды.indices {
                for ряд2 in вторые {
                    let выбор = ВыборРазмераОдежды(вкладка: в.ключ, ряд: ряд, ряд2: ряд2)
                    let части = в.части(выбор)
                    let совпало = части.filter { наши.contains($0.ключСравнения) }.count
                    let мимо = части.count - совпало
                    if совпало > счёт || (совпало == счёт && совпало > 0 && мимо < лишних) {
                        итог = (в, выбор)
                        счёт = совпало
                        лишних = мимо
                    }
                }
            }
        }
        return счёт >= 2 ? итог : nil
    }

    /**
     Бирка для окна объявления: таблица раздела (или все таблицы), ряд по строке; ряд не нашёлся — части строки как
     есть. Нет нашей строки — nil.
     */
    static func бирка(описание: String, раздел: String?) -> ДанныеБиркиРазмера? {
        guard let строка = из(описания: описание) else { return nil }
        /* Сначала таблицы раздела (быстро и точнее), не нашлось — все. Считать один раз, не в каждом body. */
        if let раздел, !раздел.isEmpty, let набор = НаборРазмеровОдежды.для(цепочки: НаборРазмеровОдежды.цепочка(раздел)),
           let найдено = строка.лучший(набор.вкладки) {
            return найдено.вкладка.бирка(найдено.выбор, система: найдено.вкладка.системаСайта)
        }
        if let найдено = строка.лучший(ТаблицыРазмеровОдежды.всеВкладки) {
            return найдено.вкладка.бирка(найдено.выбор, система: найдено.вкладка.системаСайта)
        }
        guard let первая = строка.части.first else { return nil }
        return ДанныеБиркиРазмера(подпись: РазмерыОдеждыText.т("buyer_title"), главная: РазмерыОдеждыText.показ(первая),
                                  части: строка.части, выделено: первая.код, мерки: "")
    }
}


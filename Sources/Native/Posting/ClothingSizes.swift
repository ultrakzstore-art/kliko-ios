/// Таблица размеров: коды столбцов (системы, сантиметры, возраст, мерки тела) и ряды значений.
struct ТаблицаРазмеровОдежды: Equatable {
    enum Вид: Equatable { case система, сантиметры, возраст, мерка }

    let ключ: String
    let коды: [String]
    let ряды: [[String]]
    /// Система поля сайта по умолчанию (site_system таблицы).
    let системаСайта: String
    /// Повторы значения в системе: какой ряд брать («US W|6.5» → 5 — строка Nike, а не Converse).
    let предпочтение: [String: Int]

    /// Ряд — одна строка «35|34|4.5|2|21.5|21.5»; пустая ячейка — «||».
    init(_ ключ: String, _ коды: [String], сайт: String, _ строки: [String], предпочтение: [String: Int] = [:]) {
        self.ключ = ключ
        self.коды = коды
        self.системаСайта = сайт
        self.предпочтение = предпочтение
        let столбцов = коды.count
        self.ряды = строки.map { строка -> [String] in
            var ячейки = строка.components(separatedBy: "|").map { $0.trimmingCharacters(in: .whitespaces) }
            if ячейки.count < столбцов {
                ячейки.append(contentsOf: Array(repeating: "", count: столбцов - ячейки.count))
            }
            return ячейки
        }
    }

    static func вид(_ код: String) -> Вид {
        if код == "CM" { return .сантиметры }
        if код == "Возраст" { return .возраст }
        if код.contains(",") || код.contains("см") { return .мерка }
        return .система
    }

    func столбец(_ код: String) -> Int? { коды.firstIndex(of: код) }

    func значение(_ ряд: Int, _ столбец: Int) -> String {
        guard ряды.indices.contains(ряд), ряды[ряд].indices.contains(столбец) else { return "" }
        return ряды[ряд][столбец]
    }

    /// Мерки тела (обхваты, длины) — индексы столбцов.
    var мерки: [Int] { коды.indices.filter { Self.вид(коды[$0]) == .мерка } }

    /**
     Чипы столбца: одинаковые значения — один чип, где бы ни стояли (US W 6.5 у EU 37 и 37.5, INT «M» у шапок 57 и 58,
     UK 2 и UK 4 детской обуви у малышей и у школьников — двух одинаковых чипов в сетке нет). Ряд чипа — предпочтённый
     или первый (UK 2 → EU 18; школьный UK 2 выбирается в EU или US, а сетка UK его подсвечивает); порядок — по нему,
     поэтому UK женской обуви идёт ровно: 4, 4.5, 5.
     */
    func чипы(_ столбец: Int) -> [ЧипРазмераОдежды] {
        var группы: [(значение: String, ключ: String, ряды: [Int])] = []
        for ряд in ряды.indices {
            let з = значение(ряд, столбец)
            guard !з.isEmpty else { continue }
            let к = ПравилаРазмераОдежды.ключ(з)
            if let и = группы.firstIndex(where: { $0.ключ == к }) {
                группы[и].ряды.append(ряд)
            } else {
                группы.append((з, к, [ряд]))
            }
        }
        let код = коды.indices.contains(столбец) ? коды[столбец] : ""
        let итог = группы.map { г -> ЧипРазмераОдежды in
            var главный = г.ряды[0]
            if let любимый = предпочтение[код + "|" + г.значение], г.ряды.contains(любимый) { главный = любимый }
            return ЧипРазмераОдежды(id: главный, значение: г.значение, ряды: г.ряды)
        }
        return итог.sorted { $0.id < $1.id }
    }
}

/// Чип сетки: ряд-представитель (id), подпись и все ряды с тем же значением рядом.
struct ЧипРазмераОдежды: Equatable, Identifiable {
    let id: Int
    let значение: String
    let ряды: [Int]
}

/// Система переключателя и бирки: столбец основной таблицы и, у джинсов и белья, второй (длина L, чашка).
struct СистемаРазмераОдежды: Equatable {
    let код: String
    let первый: Int
    let второй: Int?
}

/// Выбранный размер: вкладка набора, ряд основной таблицы и ряд второй (L джинсов, чашка) — по желанию.
struct ВыборРазмераОдежды: Equatable {
    var вкладка: String
    var ряд: Int
    var ряд2: Int? = nil
}

/// Кусок бирки: «EU 42», «W32 L32», «27 см», «7–8 лет». Код у склеенных — «EU/RU».
struct ЧастьБиркиРазмера: Equatable, Hashable {
    let код: String
    let значение: String

    /// Запись для строки описания — всегда по-русски, обычными пробелами.
    var текст: String {
        switch код {
        case "CM": return значение + " см"
        case "Возраст": return значение
        case "W": return "W" + значение
        default: return код + " " + значение
        }
    }

    /// Ключ сравнения «код|значение».
    var ключСравнения: String { код + "|" + ПравилаРазмераОдежды.ключ(значение) }
}

/// Готовая бирка для показа (подача и окно объявления).
struct ДанныеБиркиРазмера: Equatable {
    /// «Женская обувь».
    let подпись: String
    /// Крупно — выбранная система: «EU 42».
    let главная: String
    /// Все системы, склеенные одинаковые соседи («EU/RU 29»).
    let части: [ЧастьБиркиРазмера]
    /// Код системы, которая выделена в строке.
    let выделено: String
    /// «Грудь 92 · Талия 74 · Бёдра 100 см» или пусто.
    let мерки: String
}

// MARK: - Вкладка

/// Вкладка блока: таблица (и вторая у джинсов и белья), системы переключателя, система поля сайта.
struct ВкладкаРазмеровОдежды: Equatable, Identifiable {
    enum Склейка: Equatable { case нет, джинсы, чашка }

    let ключ: String
    let основная: ТаблицаРазмеровОдежды
    let вторая: ТаблицаРазмеровОдежды?
    let системы: [СистемаРазмераОдежды]
    let системаСайта: String
    let склейка: Склейка
    var id: String { ключ }

    /// Одна таблица: системы — все столбцы, кроме мерок тела (и скрытых).
    static func простая(_ ключ: String, _ т: ТаблицаРазмеровОдежды, сайт: String? = nil) -> ВкладкаРазмеровОдежды {
        let системы = т.коды.indices.compactMap { и -> СистемаРазмераОдежды? in
            guard ТаблицаРазмеровОдежды.вид(т.коды[и]) != .мерка else { return nil }
            return СистемаРазмераОдежды(код: т.коды[и], первый: и, второй: nil)
        }
        return ВкладкаРазмеровОдежды(ключ: ключ, основная: т, вторая: nil, системы: системы,
                                     системаСайта: сайт ?? т.системаСайта, склейка: .нет)
    }

    /// Джинсы: W (с длиной L — «W32 L32»), RU и буква INT своего пола.
    static func джинсы(женские: Bool) -> ВкладкаРазмеровОдежды {
        let т = ТаблицыРазмеровОдежды.джинсы
        let буква = т.столбец(женские ? "INT жен" : "INT муж") ?? 2
        return ВкладкаРазмеровОдежды(ключ: "jn", основная: т, вторая: ТаблицыРазмеровОдежды.джинсыДлина,
                                     системы: [СистемаРазмераОдежды(код: "W", первый: 0, второй: 0),
                                               СистемаРазмераОдежды(код: "RU", первый: 1, второй: nil),
                                               СистемаРазмераОдежды(код: "INT", первый: буква, второй: nil)],
                                     системаСайта: "RU", склейка: .джинсы)
    }

    /// Бюстгальтер: обхват и чашка одной строкой («75B»); у UK и US чашки с E расходятся.
    static func бельё() -> ВкладкаРазмеровОдежды {
        ВкладкаРазмеровОдежды(ключ: "br", основная: ТаблицыРазмеровОдежды.бюстгальтер,
                              вторая: ТаблицыРазмеровОдежды.чашка,
                              системы: [СистемаРазмераОдежды(код: "RU/EU", первый: 0, второй: 0),
                                        СистемаРазмераОдежды(код: "UK", первый: 1, второй: 1),
                                        СистемаРазмераОдежды(код: "US", первый: 1, второй: 2),
                                        СистемаРазмераОдежды(код: "FR", первый: 2, второй: 0),
                                        СистемаРазмераОдежды(код: "IT", первый: 3, второй: 0)],
                              системаСайта: "RU/EU", склейка: .чашка)
    }

    func система(_ код: String) -> СистемаРазмераОдежды? { системы.first { $0.код == код } }

    /// Значение системы у выбора: с длиной или чашкой, если они выбраны.
    func значение(_ выбор: ВыборРазмераОдежды, _ с: СистемаРазмераОдежды) -> String {
        let а = основная.значение(выбор.ряд, с.первый)
        guard !а.isEmpty else { return "" }
        guard let второй = с.второй, let т2 = вторая, let р2 = выбор.ряд2 else { return а }
        let б = т2.значение(р2, второй)
        guard !б.isEmpty else { return а }
        switch склейка {
        case .джинсы: return а + " L" + б
        case .чашка: return а + б
        case .нет: return а
        }
    }

    /// Все системы выбора по порядку таблицы (пустые — прочь).
    func части(_ выбор: ВыборРазмераОдежды) -> [ЧастьБиркиРазмера] {
        системы.compactMap { с -> ЧастьБиркиРазмера? in
            let з = значение(выбор, с)
            return з.isEmpty ? nil : ЧастьБиркиРазмера(код: с.код, значение: з)
        }
    }

    /// «Размер: EU 42 · RU 41 · US M 9 · UK 8 · MEX 27 · 27 см».
    func строкаОписания(_ выбор: ВыборРазмераОдежды) -> String {
        ПравилаРазмераОдежды.начало + " " + ПравилаРазмераОдежды.склеить(части(выбор)).map { $0.текст }.joined(separator: " · ")
    }

    /// Мерки тела по таблице строкой: «Грудь 92 · Талия 74 · Бёдра 100 см».
    func мерки(_ выбор: ВыборРазмераОдежды) -> String {
        var куски: [String] = []
        for и in основная.мерки {
            let з = основная.значение(выбор.ряд, и)
            if !з.isEmpty { куски.append(РазмерыОдеждыText.мерка(основная.коды[и]) + " " + РазмерыОдеждыText.местное(з)) }
        }
        if let т2 = вторая, let р2 = выбор.ряд2 {
            for и in т2.мерки {
                let з = т2.значение(р2, и)
                if !з.isEmpty { куски.append(РазмерыОдеждыText.мерка(т2.коды[и]) + " " + РазмерыОдеждыText.местное(з)) }
            }
        }
        guard !куски.isEmpty else { return "" }
        return куски.joined(separator: " · ") + " " + РазмерыОдеждыText.т("cm")
    }

    /// Бирка выбора; крупно — система переключателя.
    func бирка(_ выбор: ВыборРазмераОдежды, система код: String) -> ДанныеБиркиРазмера {
        let все = части(выбор)
        let главная = все.first(where: { $0.код == код }) ?? все.first
        return ДанныеБиркиРазмера(подпись: РазмерыОдеждыText.т("cap_" + основная.ключ),
                                  главная: главная.map { РазмерыОдеждыText.показ($0) } ?? "",
                                  части: ПравилаРазмераОдежды.склеить(все),
                                  выделено: главная?.код ?? код,
                                  мерки: мерки(выбор))
    }

    /**
     Система поля сайта: у детской одежды подпись решает рост или возраст («Возраст» — столбец возраста, иначе рост EU);
     код системы в подписи («Размер (EU)», «Размер, см») — она; иначе — система таблицы.
     */
    func системаПоля(_ поле: ПолеХарактеристики?) -> String {
        guard let поле else { return системаСайта }
        if основная.столбец("Возраст") != nil {
            return ПравилаРазмераОдежды.подписьВозраста(поле.подпись) ? "Возраст" : "EU"
        }
        let слова = Set(ПравилаРазмераОдежды.слова(поле.подпись))
        let найдено = системы.filter { с in
            let первое = с.код.components(separatedBy: CharacterSet(charactersIn: " /")).first ?? с.код
            return слова.contains(ПравилаРазмераОдежды.ключ(первое))
        }
        return найдено.count == 1 ? найдено[0].код : системаСайта
    }

    /**
     Значения для поля сайта по порядку: система сайта (целиком, без длины и чашки, у «44–46» — меньшее), потом буквы
     INT и возраст. Числа других систем — нет: EU 40 у одежды не равен RU 40.
     */
    func кандидатыСайта(_ выбор: ВыборРазмераОдежды, сайт: String) -> [String] {
        var итог: [String] = []
        func добавить(_ з: String) {
            let чистое = з.trimmingCharacters(in: .whitespaces)
            if !чистое.isEmpty && !итог.contains(чистое) { итог.append(чистое) }
        }
        for код in [сайт, "INT", "Возраст"] {
            guard let с = система(код) else { continue }
            let полное = значение(выбор, с)
            добавить(полное)
            if с.второй != nil { добавить(основная.значение(выбор.ряд, с.первый)) }
            if код != "Возраст", let меньшее = ПравилаРазмераОдежды.доТире(полное) { добавить(меньшее) }
        }
        return итог
    }
}


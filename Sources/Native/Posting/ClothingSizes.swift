/**
 РАЗМЕР ОДЕЖДЫ И ОБУВИ «КАК НА БИРКЕ МАГАЗИНА» (владелец 14.10.2026: «при подаче вещей размеры совмещённо, как в
 магазинах: стандарты EU 29 | MEX какой-то вещи, обувь — всё, что можно»; «шаблоны, чтобы готовые были»; «человек должен
 получать дофамин от подачи до просмотра чужих предложений»).

 Что делает. В разделах одежды, обуви, детского, колец, головных уборов и перчаток на шаге «Характеристики» поле размера
 схемы сайта (слот storage, подпись «Размер» или «Возраст») рисуется не простым списком, а своим блоком
 (ClothingSizesView.swift): вкладки таблиц (у обуви «Женская / Мужская / Детская», у одежды «Одежда / Джинсы / Бельё»),
 переключатель системы (только те, что есть у таблицы), ровная сетка размеров и «бирка» — все системы строкой, как на
 ярлыке: «EU 42 | RU 41 | US M 9.5 | UK 8.5 | MEX 27.5 | 27.5 см».

 КУДА ПИШЕТСЯ
   · Поле сайта (storage). У списка — значение сайта: сначала система поля (по подписи поля: «Возраст» — возраст, «(EU)» —
     EU; иначе — система таблицы: одежда RU, обувь EU, детская одежда — рост EU), потом буквы INT и возраст (числа других
     систем не берём: RU 40 и EU 40 у одежды — разные размеры). Совпадение ищется точное, потом словом внутри подписи
     («46 (M)»), потом ближайшее число не дальше 1 (37.5 → 37) или возраст в диапазоне («7–8 лет» → «7-10 лет»). Нет
     совпадения — своё значение в системе сайта, если поле его разрешает (other), иначе поле пустеет и его можно выбрать
     меню «В объявлении» на бирке. У поля ввода — значение в системе сайта (у «44–46» — меньшее).
   · Строка в конце описания «Размер: EU 42 · RU 41 · US M 9 · UK 8 · MEX 27 · 27 см» — прежняя наша строка заменяется,
     а не повторяется. Строка всегда по-русски (как «Габариты (Ш×В×Г): …»): её разбирает СтрокаРазмераВсехСистем — для
     бирки в окне объявления у покупателя. «Наша» — строка «Размер:», в которой узнаются хотя бы две системы, поэтому
     строку продавца «Размер: 42, маломерит» мы не трогаем. Раздел или название сменились, и строка им больше не
     подходит (электроника, другие таблицы) — она уходит из описания (убратьЧужуюСтрокуРазмера). В минимум описания
     (10 знаков) строка не засчитывается (ПравилаРазмераОдежды.длинаОписания).
 Нет поля размера в схеме раздела (или его подпись — не размер) — блок всё равно есть, по желанию, и пишет только строку
 в описание.

 Таблицы — проверенные (задание 14.10.2026): обувь — Nike (EU, US, UK, см), RU = EU − 1 как у Lamoda и Wildberries,
 MEX = см; одежда — российская таблица (RU = обхват груди пополам) и пересчёт ASOS и Zalando; джинсы — RU ≈ W + 16;
 детская одежда — рост (H&M, Zara) и US Carter's; бельё — EU, UK, US, FR, IT; кольца — ISO 8653; шапки — New Era;
 перчатки — EN 420. У брендов бывает ±½ размера — бирка говорит об этом мелко.
 */

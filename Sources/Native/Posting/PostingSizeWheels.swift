import Foundation

/**
 ШИНЫ И ДИСКИ В ПОДАЧЕ (владелец 14.10.2026: «шины или диски применить на свою машину»).

 В разделе «Шины и диски» (tires-wheels, режим запчастей) вместо Ш×В×Г — свои числа: у шин — ширина, профиль, диаметр R;
 у дисков — диаметр R, ширина J, вылет ET, разболтовка PCD, ступица DIA. Это те же поля, что у мастера запчастей сайта
 (PARTS_FIELDS: tire — width, profile, diameter; wheel — diameter, width_j, et, pcd, dia), значения — в форма.запчасть.
 Свой блок (БлокШинДисковПодачи, PostingSizeView.swift) их не дублирует: в нём «Шины | Диски», популярные размеры из
 каталога (КаталогРазмеров: tyre, rim), ввод одной строкой и только те поля, которых у мастера нет.

 Диски — свой вид мастера «wheel» (видЗапчасти, PostingModel.swift; рубильник Config.дискиОтдельнымВидом): раньше в
 разделе всегда был «tire», и продавец дисков видел ширину в мм, профиль и сезон шины, а PCD, ET и DIA указать не мог.

 На сервер (договор — docs/SERVER_SIZE_TEMPLATES.md): в теле submit и edit_item — tyre_w · tyre_h · tyre_r у шин или
 rim_r · rim_j · rim_et · rim_pcd · rim_dia у дисков, и строка в конце описания: «Размер шин: 205/55 R16» или «Диски: R16
 6.5J ET45 5x114.3 DIA 67.1» — прежняя заменяется, а не повторяется. Эту строку «Подойдут ли?» (TryOn/AutoFitParse.swift)
 читает первой, даже без характеристик. rules.dims.wheel_fields: 1 — сервер хранит поля сам, строку больше не пишем.
 */
extension Config {
    /// Диски в «Шинах и дисках» — вид мастера «wheel» (поля дисков сайта). false — всегда «tire», а поля дисков — в своём
    /// блоке.
    static let дискиОтдельнымВидом = true
}

/// Строки шин и дисков в описании и ключи полей — одна запись на подачу и «Подойдут ли?». Чистые функции.
enum СтрокиКолёсПодачи {
    static let началоШин = "Размер шин:"
    static let началоДисков = "Диски:"
    /// Предел описания у формы (ТекстПодачи).
    static let пределОписания = 5000
    /// Поля мастера запчастей: шины (PARTS_FIELDS tire) и диски (wheel).
    static let ключиШин = ["width", "profile", "diameter"]
    static let ключиДисков = ["diameter", "width_j", "et", "pcd", "dia"]
    /// Поля, которые есть только у одного вида: при смене «Шины | Диски» чужие убираются (иначе ушли бы в parts).
    static let толькоШин = ["width", "profile", "season", "tread", "maker"]
    static let толькоДисков = ["width_j", "pcd", "et", "dia", "wheel_type"]

    /// Своя строка шин — ровно в том виде, как её пишет приложение.
    private static let образецШин = #"^\s*Размер шин:\s*\d{3}/\d{2}\s*R\d{2}(?:\.5)?\s*$"#
    /// Своя строка дисков: части в нашем порядке, каждая по желанию (R · J · ET · PCD · DIA).
    private static let образецДисков = #"^\s*Диски:\s*(?:R\d{2}(?:\.5)?)?(?:\s*\d{1,2}(?:\.\d{1,2})?J)?(?:\s*ET-?\d{1,3}(?:\.\d{1,2})?)?(?:\s*\d{1,2}x\d{2,3}(?:\.\d{1,2})?)?(?:\s*DIA\s*\d{2,3}(?:\.\d{1,2})?)?\s*$"#

    /// «Размер шин: 205/55 R16».
    static func строкаШин(_ шина: РазмерШиныАвтоподбора) -> String {
        началоШин + " " + шина.подпись
    }

    /// «Диски: R16 6.5J ET45 5x114.3 DIA 67.1» — что есть, в этом порядке; ничего — nil.
    static func строкаДисков(_ диск: ДискАвтоподбора) -> String? {
        typealias Ч = ЧислаАвтоподбора
        var части: [String] = []
        if let r = диск.диаметр { части.append("R" + Ч.ч(r)) }
        if let j = диск.ширина { части.append(Ч.ч(j) + "J") }
        if let et = диск.et { части.append("ET" + Ч.ч(et)) }
        if let р = диск.разболтовки.first { части.append(pcd(р)) }
        if let dia = диск.dia { части.append("DIA " + Ч.ч(dia, знаков: 2)) }
        return части.isEmpty ? nil : началоДисков + " " + части.joined(separator: " ")
    }

    /// «5x114.3» — так PCD пишется и в поле, и в строке.
    static func pcd(_ р: РазболтовкаАвтоподбора) -> String {
        String(р.отверстий) + "x" + ЧислаАвтоподбора.ч(р.pcd, знаков: 2)
    }

    static func этоСтрокаШин(_ строка: String) -> Bool {
        строка.range(of: образецШин, options: .regularExpression) != nil
    }

    /// Строка дисков — и хоть одно число после «Диски:» (пустая «Диски:» продавца — не наша).
    static func этоСтрокаДисков(_ строка: String) -> Bool {
        guard строка.range(of: образецДисков, options: .regularExpression) != nil else { return false }
        return строка.contains { $0.isNumber }
    }

    static func этоСтрока(_ строка: String) -> Bool {
        этоСтрокаШин(строка) || этоСтрокаДисков(строка)
    }

    /// Описание без наших строк (любой по счёту) и без пустого хвоста после них; строк нет — как было.
    static func безСтрок(_ описание: String) -> String {
        let строки = описание.components(separatedBy: "\n")
        guard строки.contains(where: { этоСтрока($0) }) else { return описание }
        return безХвоста(строки.filter { !этоСтрока($0) }.joined(separator: "\n"))
    }

    /// Описание с нашими строками в конце: прежние убираются, предел описания соблюдается. Новых нет — только убрать.
    static func сСтроками(_ описание: String, _ новые: [String]) -> String {
        guard !новые.isEmpty else { return безСтрок(описание) }
        let добавка = новые.joined(separator: "\n")
        var основа = безХвоста(безСтрок(описание))
        let нужно = добавка.count + 2
        if основа.count + нужно > пределОписания {
            основа = безХвоста(String(основа.prefix(max(0, пределОписания - нужно))))
        }
        return основа.isEmpty ? добавка : основа + "\n\n" + добавка
    }

    /// Наши строки из текста (последние шин и дисков) через перевод строки; нет — пусто. Для «Подойдут ли?».
    static func своиСтроки(_ текст: String) -> String {
        guard текст.contains(началоШин) || текст.contains(началоДисков) else { return "" }
        var шины: String? = nil
        var диски: String? = nil
        for строка in текст.components(separatedBy: "\n") {
            if этоСтрокаШин(строка) {
                шины = строка
            } else if этоСтрокаДисков(строка) {
                диски = строка
            }
        }
        return [шины, диски].compactMap { $0?.trimmingCharacters(in: .whitespaces) }.joined(separator: "\n")
    }

    /// Шина из нашей строки (последней); нет — nil.
    static func шинаИзСтроки(_ текст: String) -> РазмерШиныАвтоподбора? {
        for строка in текст.components(separatedBy: "\n").reversed() where этоСтрокаШин(строка) {
            if let р = РазмерШиныАвтоподбора.изВвода(строка) { return р }
        }
        return nil
    }

    /// Диск из нашей строки (последней); нет — nil.
    static func дискИзСтроки(_ текст: String) -> ДискАвтоподбора? {
        for строка in текст.components(separatedBy: "\n").reversed() where этоСтрокаДисков(строка) {
            let д = диск(изТекста: строка)
            if !д.пустой { return д }
        }
        return nil
    }

    /// Параметры диска из свободной строки: «R17 5x114.3 ET45 DIA 67.1 7.5J» в любых написаниях (ПарсерАвтоподбора).
    static func диск(изТекста строка: String) -> ДискАвтоподбора {
        typealias П = ПарсерАвтоподбора
        let т = П.нормально(строка)
        var д = ДискАвтоподбора()
        д.диаметр = П.диаметрОбода(т)
        д.ширина = П.ширинаОбода(т)
        д.et = П.вылет(т)
        д.dia = П.отверстие(т)
        д.разболтовки = П.разболтовки(т)
        return д
    }

    /// Число для тела запроса: целое — Int, дробь — Double.
    static func числоТела(_ x: Double) -> Any {
        x == x.rounded() && abs(x) < 1_000_000 ? Int(x) : x
    }

    /// Без пробелов и переводов строки в конце.
    private static func безХвоста(_ текст: String) -> String {
        var итог = текст
        while let последний = итог.last, последний.isWhitespace || последний.isNewline { итог.removeLast() }
        return итог
    }
}

// MARK: - Подача

extension ПодачаМодель {
    /// Блок «Размер шин или дисков»: раздел шин и дисков (режим запчастей).
    var колёсаВидны: Bool {
        guard Config.шаблоныРазмеров, режим == .запчасти, !форма.раздел.isEmpty else { return false }
        return разделВнутри(форма.раздел, ["tires-wheels"])
    }

    /**
     Что продаём: true — диски (и колёса в сборе), false — шины, nil — не понять. Выбор продавца («Шины | Диски») главнее;
     потом название (ПризнакиДисков через КаталогРазмеров.вид); потом заполненные поля дисков.
     */
    var дискиВыбраны: Bool? {
        guard колёсаВидны else { return nil }
        switch форма.габариты?.вид ?? "" {
        case "rim": return true
        case "tyre": return false
        default: break
        }
        if let вид = видРазмеров {
            if вид.мера == .диск { return true }
            if вид.мера == .шина { return false }
        }
        let естьДиска = СтрокиКолёсПодачи.толькоДисков.contains { !(форма.запчасть[$0] ?? "").isEmpty }
        return естьДиска ? true : nil
    }

    /// Вид мастера «wheel» (поля дисков): выбраны диски и справочник их знает. Зовёт видЗапчасти (PostingModel.swift).
    var дискиВПодаче: Bool {
        Config.дискиОтдельнымВидом && дискиВыбраны == true && справочники.запчасти["wheel"] != nil
    }

    /// Вид каталога для образцов блока: шины или диски; не выбрано — nil.
    var видКолёс: ВидРазмеров? {
        guard колёсаВидны, let диски = дискиВыбраны else { return nil }
        let мера: МераРазмеров = диски ? .диск : .шина
        return кандидатыРазмеров.first { $0.мера == мера }
    }

    /// Заголовок «Шины» или «Диски»: у вида каталога (или сайта) — его, иначе свой.
    func заголовокКолёс(диски: Bool) -> String {
        let мера: МераРазмеров = диски ? .диск : .шина
        if let вид = кандидатыРазмеров.first(where: { $0.мера == мера }) { return вид.заголовок }
        return РазмерыОбразцовText.т(диски ? "sz_rim" : "sz_tyre")
    }

    /// «Шины | Диски»: выбор продавца. Поля другого вида, которых у этого нет, убираются — иначе ушли бы в parts.
    func выбратьКолёса(диски: Bool) {
        let мера: МераРазмеров = диски ? .диск : .шина
        let ключ = кандидатыРазмеров.first(where: { $0.мера == мера })?.ключ ?? (диски ? "rim" : "tyre")
        let было = дискиВыбраны
        var г = форма.габариты ?? ГабаритыПодачи()
        if г.вид != ключ {
            г.вид = ключ
            форма.габариты = г
        }
        guard было != диски else { return }
        var запчасть = форма.запчасть
        for чужой in диски ? СтрокиКолёсПодачи.толькоШин : СтрокиКолёсПодачи.толькоДисков {
            запчасть.removeValue(forKey: чужой)
        }
        if запчасть != форма.запчасть { форма.запчасть = запчасть }
    }

    /// Число из поля мастера: «6,5» → 6.5, «R16» → 16; пусто или не число — nil.
    private func числоЗапчасти(_ ключ: String) -> Double? {
        let текст = (форма.запчасть[ключ] ?? "").trimmingCharacters(in: .whitespaces)
        guard !текст.isEmpty else { return nil }
        return ПарсерАвтоподбора.числоВвода(текст)
    }

    /// Размер шины из полей (width · profile · diameter); неполный или неправдоподобный — nil.
    var шинаФормы: РазмерШиныАвтоподбора? {
        guard let ш = числоЗапчасти("width"), let п = числоЗапчасти("profile"),
              let д = числоЗапчасти("diameter") else { return nil }
        let размер = РазмерШиныАвтоподбора(ширина: ш, профиль: п, диаметр: д)
        return размер.годный ? размер : nil
    }

    /// Диск из полей (diameter · width_j · et · pcd · dia): неправдоподобное отброшено; ничего — nil.
    var дискФормы: ДискАвтоподбора? {
        var д = ДискАвтоподбора()
        if let r = числоЗапчасти("diameter"), РазмерШиныАвтоподбора.диаметры.contains(r) { д.диаметр = r }
        if let j = числоЗапчасти("width_j"), (3.5...13).contains(j) { д.ширина = j }
        if let et = числоЗапчасти("et"), (-65...80).contains(et) { д.et = et }
        if let р = РазболтовкаАвтоподбора.изВвода(форма.запчасть["pcd"] ?? "") { д.разболтовки = [р] }
        if let dia = числоЗапчасти("dia"), (50...175).contains(dia) { д.dia = dia }
        return д.пустой ? nil : д
    }

    /// Шина — в поля мастера (width · profile · diameter).
    private func записатьШину(_ р: РазмерШиныАвтоподбора) {
        typealias Ч = ЧислаАвтоподбора
        var запчасть = форма.запчасть
        запчасть["width"] = Ч.ч(р.ширина)
        запчасть["profile"] = Ч.ч(р.профиль)
        запчасть["diameter"] = Ч.ч(р.диаметр)
        форма.запчасть = запчасть
    }

    /// Диск — в поля мастера: что есть; чего нет — не трогаем.
    private func записатьДиск(_ д: ДискАвтоподбора) {
        typealias Ч = ЧислаАвтоподбора
        var запчасть = форма.запчасть
        if let r = д.диаметр { запчасть["diameter"] = Ч.ч(r) }
        if let j = д.ширина { запчасть["width_j"] = Ч.ч(j) }
        if let et = д.et { запчасть["et"] = Ч.ч(et) }
        if let р = д.разболтовки.first { запчасть["pcd"] = СтрокиКолёсПодачи.pcd(р) }
        if let dia = д.dia { запчасть["dia"] = Ч.ч(dia, знаков: 2) }
        форма.запчасть = запчасть
    }

    /// Касание образца шин или дисков: числа — в поля мастера, вид запоминается.
    func применитьОбразецКолёс(_ образец: ОбразецРазмеров, вида вид: ВидРазмеров) {
        if вид.мера == .шина {
            guard let р = РазмерШиныАвтоподбора.изВвода(образец.доп) else { return }
            выбратьКолёса(диски: false)
            записатьШину(р)
        } else {
            let д = СтрокиКолёсПодачи.диск(изТекста: образец.доп)
            guard !д.пустой else { return }
            выбратьКолёса(диски: true)
            записатьДиск(д)
        }
        выбратьВидРазмеров(вид.ключ)
    }

    /// Образец шин или дисков, с которым совпадают поля (его чип — выбранный); nil — ни один.
    func выбранныйОбразецКолёс(_ вид: ВидРазмеров) -> ОбразецРазмеров? {
        if вид.мера == .шина {
            guard let ш = шинаФормы else { return nil }
            return вид.образцы.first { РазмерШиныАвтоподбора.изВвода($0.доп) == ш }
        }
        guard let д = дискФормы, let своя = СтрокиКолёсПодачи.строкаДисков(д) else { return nil }
        return вид.образцы.first { СтрокиКолёсПодачи.строкаДисков(СтрокиКолёсПодачи.диск(изТекста: $0.доп)) == своя }
    }

    /**
     «205/55 R16» или «R17 5x114.3 ET45 DIA 67.1 7.5J» одной строкой → поля. Выбраны диски — сначала разбор диска; шины
     или не выбрано — сначала размер шины. Понятое другого вида переключает «Шины | Диски». true — разобрали.
     */
    func разложитьСтрокуКолёс(_ строка: String) -> Bool {
        let диск = СтрокиКолёсПодачи.диск(изТекста: строка)
        let шина = РазмерШиныАвтоподбора.изВвода(строка)
        if дискиВыбраны == true && !диск.пустой {
            записатьДиск(диск)
            return true
        }
        if let шина, !диск.естьКрепёж || дискиВыбраны != true {
            выбратьКолёса(диски: false)
            записатьШину(шина)
            return true
        }
        if диск.естьКрепёж {
            выбратьКолёса(диски: true)
            записатьДиск(диск)
            return true
        }
        return false
    }

    // MARK: Отправка

    /// submit и edit_item: tyre_* или rim_* и строка в конце описания (прежняя заменяется). Неполное — не шлём.
    func дописатьРазмерКолёс(_ тело: inout [String: Any]) {
        guard колёсаВидны else { return }
        var строки: [String] = []
        if дискиВыбраны == true {
            if let д = дискФормы {
                if let r = д.диаметр { тело["rim_r"] = СтрокиКолёсПодачи.числоТела(r) }
                if let j = д.ширина { тело["rim_j"] = СтрокиКолёсПодачи.числоТела(j) }
                if let et = д.et { тело["rim_et"] = СтрокиКолёсПодачи.числоТела(et) }
                if let р = д.разболтовки.first { тело["rim_pcd"] = СтрокиКолёсПодачи.pcd(р) }
                if let dia = д.dia { тело["rim_dia"] = СтрокиКолёсПодачи.числоТела(dia) }
                if let строка = СтрокиКолёсПодачи.строкаДисков(д) { строки.append(строка) }
            }
        } else if let ш = шинаФормы {
            тело["tyre_w"] = СтрокиКолёсПодачи.числоТела(ш.ширина)
            тело["tyre_h"] = СтрокиКолёсПодачи.числоТела(ш.профиль)
            тело["tyre_r"] = СтрокиКолёсПодачи.числоТела(ш.диаметр)
            строки.append(СтрокиКолёсПодачи.строкаШин(ш))
        }
        /* Сервер хранит поля сам (rules.dims.wheel_fields) — строку не пишем, прежнюю только убираем. */
        if схема?.шаблоныРазмеров?.колёсаПолями == true { строки = [] }
        let описание = (тело["description"] as? String) ?? форма.описание
        тело["description"] = СтрокиКолёсПодачи.сСтроками(описание, строки)
    }

    /**
     Правка: шины или диски из записи my_items (tyre_* · rim_*) или нашей строки в описании — строка уходит из текста в
     поля мастера (при сохранении вернётся одна, свежая); пустые поля мастера заполняются, введённое не трогаем.
     Зовёт приложитьГабаритыЗаписи (PostingDims.swift).
     */
    func приложитьКолёсаЗаписи(_ з: [String: Any], к ф: inout ФормаПодачи) {
        guard Config.шаблоныРазмеров, !ф.раздел.isEmpty, разделВнутри(ф.раздел, ["tires-wheels"]) else { return }
        typealias A = МоиОбъявленияAPI
        var шина = СтрокиКолёсПодачи.шинаИзСтроки(ф.описание)
        var диск = СтрокиКолёсПодачи.дискИзСтроки(ф.описание) ?? ДискАвтоподбора()
        ф.описание = СтрокиКолёсПодачи.безСтрок(ф.описание)
        let ш = A.число(з["tyre_w"])
        let п = A.число(з["tyre_h"])
        let д = A.число(з["tyre_r"])
        if ш > 0 && п > 0 && д > 0 {
            let размер = РазмерШиныАвтоподбора(ширина: ш, профиль: п, диаметр: д)
            if размер.годный { шина = размер }
        }
        let r = A.число(з["rim_r"])
        if РазмерШиныАвтоподбора.диаметры.contains(r) { диск.диаметр = r }
        let j = A.число(з["rim_j"])
        if (3.5...13).contains(j) { диск.ширина = j }
        if !A.строка(з["rim_et"]).isEmpty {
            let et = A.число(з["rim_et"])
            if (-65...80).contains(et) { диск.et = et }
        }
        if let р = РазболтовкаАвтоподбора.изВвода(A.строка(з["rim_pcd"])) { диск.разболтовки = [р] }
        let dia = A.число(з["rim_dia"])
        if (50...175).contains(dia) { диск.dia = dia }

        typealias Ч = ЧислаАвтоподбора
        var запчасть = ф.запчасть
        func поставить(_ ключ: String, _ значение: String) {
            if (запчасть[ключ] ?? "").isEmpty && !значение.isEmpty { запчасть[ключ] = значение }
        }
        var г = ф.габариты ?? ГабаритыПодачи()
        if !диск.пустой {
            if let r = диск.диаметр { поставить("diameter", Ч.ч(r)) }
            if let j = диск.ширина { поставить("width_j", Ч.ч(j)) }
            if let et = диск.et { поставить("et", Ч.ч(et)) }
            if let р = диск.разболтовки.first { поставить("pcd", СтрокиКолёсПодачи.pcd(р)) }
            if let dia = диск.dia { поставить("dia", Ч.ч(dia, знаков: 2)) }
            if г.вид.isEmpty { г.вид = "rim" }
        } else if let шина {
            поставить("width", Ч.ч(шина.ширина))
            поставить("profile", Ч.ч(шина.профиль))
            поставить("diameter", Ч.ч(шина.диаметр))
            if г.вид.isEmpty { г.вид = "tyre" }
        } else {
            return
        }
        ф.запчасть = запчасть
        ф.габариты = г
    }
}

// MARK: - Живой диск

extension ПодачаМодель {
    /**
     Части живого диска подачи (TryOn/WheelEditor.swift; владелец 16.10.2026: «прям по диску… выбор по стандартам»):
     шины — ширина, профиль, R; диски — R, J, вылет одним числом, PCD, DIA. Шины или диски не выбраны — nil (диска нет,
     остаётся ввод строкой).
     */
    var составКолёс: СоставКолеса? {
        guard let диски = дискиВыбраны else { return nil }
        if диски { return СоставКолеса(диаметр: true, ширинаJ: true, pcd: true, dia: true, et: true) }
        return СоставКолеса(шина: true)
    }

    /// Значения живого диска из полей мастера (те же, что шинаФормы и дискФормы, но и неполная шина — по частям).
    var значенияКолёс: ЗначенияКолеса {
        var з = ЗначенияКолеса()
        guard let диски = дискиВыбраны else { return з }
        let r = числоЗапчасти("diameter").flatMap { РазмерШиныАвтоподбора.диаметры.contains($0) ? $0 : nil }
        if диски {
            з.диаметр = r
            if let j = числоЗапчасти("width_j"), (3.5...13).contains(j) { з.ширинаJ = j }
            з.pcd = РазболтовкаАвтоподбора.изВвода(форма.запчасть["pcd"] ?? "")
            if let dia = числоЗапчасти("dia"), (50...175).contains(dia) { з.dia = dia }
            if let et = числоЗапчасти("et"), (-65...80).contains(et) { з.et = et...et }
        } else {
            if let ш = числоЗапчасти("width"), РазмерШиныАвтоподбора.ширины.contains(ш) { з.ширинаШины = ш }
            if let п = числоЗапчасти("profile"), РазмерШиныАвтоподбора.профили.contains(п) { з.профиль = п }
            з.диаметрШины = r
        }
        return з
    }

    /// Выбор на живом диске → поля мастера: пишется только то, что поменялось (набранное «6,5» не переписывается);
    /// стёртое — убирается. Пределы вылета подача не хранит — середина.
    func задатьЗначенияКолёс(_ н: ЗначенияКолеса) {
        guard let диски = дискиВыбраны else { return }
        typealias Ч = ЧислаАвтоподбора
        let было = значенияКолёс
        var запчасть = форма.запчасть
        func поставить(_ ключ: String, _ значение: String?) {
            if let значение { запчасть[ключ] = значение } else { запчасть.removeValue(forKey: ключ) }
        }
        if диски {
            if н.диаметр != было.диаметр { поставить("diameter", н.диаметр.map { Ч.ч($0) }) }
            if н.ширинаJ != было.ширинаJ { поставить("width_j", н.ширинаJ.map { Ч.ч($0) }) }
            if н.pcd != было.pcd { поставить("pcd", н.pcd.map { СтрокиКолёсПодачи.pcd($0) }) }
            if н.dia != было.dia { поставить("dia", н.dia.map { Ч.ч($0, знаков: 2) }) }
            if н.et != было.et { поставить("et", н.et.map { Ч.ч((($0.lowerBound + $0.upperBound) / 2).rounded()) }) }
        } else {
            if н.ширинаШины != было.ширинаШины { поставить("width", н.ширинаШины.map { Ч.ч($0) }) }
            if н.профиль != было.профиль { поставить("profile", н.профиль.map { Ч.ч($0) }) }
            let r = н.диаметрШины ?? н.диаметр
            if r != было.диаметрШины { поставить("diameter", r.map { Ч.ч($0) }) }
        }
        if запчасть != форма.запчасть { форма.запчасть = запчасть }
    }
}

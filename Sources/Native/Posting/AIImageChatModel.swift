import SwiftUI
import UIKit

/**
 ОКНО «ИЛЛЮСТРАЦИЯ С ИИ» — СОСТОЯНИЕ (одно на открытое окно, не синглтон; держит его ЭкранЧатаИИФото).

 Лента реплик как в мессенджере: одна строка «Что продаёте?» (заполнена названием формы) → пузырь человека и карточка
 ИИ. Ход (ultra-site 14.10.2026): photo_gen с текстом формы (раздел, название, марка, описание, до 4 характеристик) —
 ответ сразу с готовой картинкой, до пары минут; ожидание без процентов. Оборвалась связь (или окно закрыли) — опрос
 photo_gen_info раз в 4 с: пока busy — ждём, новая last — это она. Перед первым запуском — согласие (кто нарисует —
 by_text из info): на этого человека и этого исполнителя; сменились — спросится снова.

 Итог: «Взять в объявление» — url ставится плиткой как обычное загруженное фото (без новой загрузки, без вшитых
 пометок: метку «создано ИИ» ставит сервер по своей записи о файле; настоящие фото сервер ставит первыми). «Ещё вариант»
 — отдельный запуск (сказано под кнопкой). Отказ — текст сервера как есть; cover_ok — «Собрать обложку без рисунка»
 (cover:1), own_ai:"images" и kliko_ok — «Нарисовать с Kliko AI» (kliko:1). Ответ, пришедший после выхода из аккаунта,
 не принимается.
 */
@MainActor
final class МодельЧатаИИФото: ObservableObject {
    enum Экран: Hashable {
        case чат, вход, скоро
    }

    let подача: ПодачаМодель
    let вход: ВходЧатаИИФото
    /// Закрыть окно (ставит экран, который его показал).
    var закрытьОкно: (() -> Void)? = nil

    @Published private(set) var экран: Экран = .чат
    @Published private(set) var реплики: [РепликаИИФото] = []
    @Published var ввод = ""
    @Published private(set) var идёт = false
    @Published private(set) var берём = false
    /// Лист согласия перед первым запуском.
    @Published var согласие = false
    /// Поставить курсор в поле ввода.
    @Published var вПоле = 0
    /// Растёт при каждом изменении ленты — экран прокручивает её вниз.
    @Published private(set) var сдвиг = 0
    @Published private(set) var весть: String? = nil

    private var запуск: Task<Void, Never>? = nil
    private var отложенное: ЗапросИИФото? = nil
    private var отложеннаяПодпись = ""
    private var отложеноИзПоля = false
    /// Согласие на общую формулировку («сторонний ИИ-сервис») — только до закрытия этого окна.
    private var согласиеОкна = false
    private var поколение: Int
    private var закрыто = false
    private var номерВести = 0

    /// Согласие на передачу текста ИИ: строка «на что дано» (предметСогласия). v2 — прежний договор с фото.
    static let ключСогласия = "kliko.aiimage.consent.v3"

    init(подача: ПодачаМодель, вход: ВходЧатаИИФото) {
        self.подача = подача
        self.вход = вход
        поколение = СессияПриложения.shared.поколение
    }

    private func т(_ ключ: String) -> String { ИИФотоText.т(ключ) }

    var сведения: СведенияИИФото? { ГотовностьИИФото.shared.сведения }

    /// Раздел формы — cat запроса и info.
    var раздел: String { подача.форма.раздел }

    /// «Что продаёте?» — одна строка, не длиннее названия объявления.
    var пределТекста: Int { ПределыПодачи.название }

    /// Кто подаёт: uid страницы кабинета подачи, иначе id сессии приложения.
    private var ктоПодаёт: String {
        let uid = подача.страница.состояние?.uid ?? ""
        return uid.isEmpty ? СессияПриложения.shared.id : uid
    }

    /**
     На что даётся согласие (App Review 5.1.2(i)): человек и кто нарисует (by и by_text). Пусто — сведения устарели
     («Свой ИИ» переключили), исполнитель не назван или ещё не знаем, кто вошёл: формулировка общая, и согласие на неё
     живёт только в этом окне.
     */
    var предметСогласия: String {
        guard let с = сведения, ГотовностьИИФото.shared.сведенияСвежие, СессияПриложения.shared.вошёл == true else {
            return ""
        }
        let кто = ктоПодаёт
        let исполнитель = с.ктоТекст.isEmpty ? с.кто : с.ктоТекст
        guard !кто.isEmpty, !исполнитель.isEmpty else { return "" }
        return [кто, с.кто, исполнитель].joined(separator: "|")
    }

    /// Согласие уже дано на то же самое: тот же человек и тот же исполнитель (или общее — в этом окне).
    var согласиеДано: Bool {
        let предмет = предметСогласия
        if предмет.isEmpty { return согласиеОкна }
        return UserDefaults.standard.string(forKey: Self.ключСогласия) == предмет
    }

    /// Кто нарисует — для согласия: by_text сервера, иначе по by; не знаем — честно и общо.
    var ктоОбработает: String {
        guard let с = сведения, ГотовностьИИФото.shared.сведенияСвежие else { return т("aim_ai_generic") }
        if !с.ктоТекст.isEmpty { return с.ктоТекст }
        switch с.кто {
        case "own": return т("aim_ai_own_plain")
        case "kliko": return "Kliko AI"
        default: return т("aim_ai_generic")
        }
    }

    // MARK: - Открыли и закрыли

    func открыт() {
        if СессияПриложения.shared.вошёл == false { экран = .вход }
        if ввод.isEmpty {
            ввод = String(подача.форма.название.trimmingCharacters(in: .whitespacesAndNewlines).prefix(пределТекста))
        }
        let ждали = ИИФотоПодачи.shared.ожидание(подача)
        let нужный = раздел
        Task { @MainActor [weak self] in
            await ГотовностьИИФото.shared.проверить(раздел: нужный, заново: true)
            if СессияПриложения.shared.вошёл != false { await СвойИИМодель.shared.загрузитьЛениво() }
            guard let self, !self.закрыто else { return }
            if СессияПриложения.shared.вошёл == false {
                self.перейти(.вход)
                return
            }
            if let ждали, self.реплики.isEmpty {
                self.ждатьПослеОткрытия(прежний: ждали)
                return
            }
            if !ГотовностьИИФото.shared.доступно(раздел: нужный) && self.реплики.isEmpty { self.перейти(.скоро) }
        }
    }

    /// Окно закрыли: ожидание стоит; запуск на сервере идёт дальше — картинку найдёт last при новом открытии.
    func закрыть() {
        guard !закрыто else { return }
        закрыто = true
        запуск?.cancel()
    }

    func показатьВесть(_ текст: String) {
        номерВести += 1
        let номер = номерВести
        withAnimation(ДвижениеСайта.появление) { весть = текст }
        UIAccessibility.post(notification: .announcement, argument: текст)
        Task { @MainActor [weak self] in
            try? await Task.sleep(nanoseconds: 2_600_000_000)
            guard let self, номер == self.номерВести else { return }
            withAnimation(ДвижениеСайта.уход) { self.весть = nil }
        }
    }

    private func перейти(_ новый: Экран) {
        guard экран != новый else { return }
        withAnimation(ДвижениеСайта.шаг) { экран = новый }
    }

    private func изменить(_ id: UUID, _ правка: (inout РепликаИИФото) -> Void) {
        guard let место = реплики.firstIndex(where: { $0.id == id }) else { return }
        var р = реплики[место]
        правка(&р)
        реплики[место] = р
    }

    // MARK: - Запуск

    /// Запрос из формы подачи: название — строка окна, остальное — как в форме (до 4 характеристик).
    private func запрос(название: String) -> ЗапросИИФото {
        let ф = подача.форма
        let чисто = CharacterSet.whitespacesAndNewlines
        var з = ЗапросИИФото()
        з.раздел = ф.раздел
        з.название = название
        з.марка = ф.бренд.trimmingCharacters(in: чисто)
        з.серия = [ф.модель, ф.поколение].map { $0.trimmingCharacters(in: чисто) }.filter { !$0.isEmpty }
            .joined(separator: " ")
        з.описание = String(ф.описание.trimmingCharacters(in: чисто).prefix(1000))
        з.тип = ф.тип
        var характеристики: [ХарактеристикаИИФото] = []
        for поле in подача.характеристики {
            let значение = подача.значениеХарактеристики(поле.поле).trimmingCharacters(in: чисто)
            guard !значение.isEmpty else { continue }
            характеристики.append(ХарактеристикаИИФото(ключ: поле.поле, подпись: поле.подпись, значение: значение))
            if характеристики.count == 4 { break }
        }
        з.характеристики = характеристики
        if подача.правка { з.объявление = подача.номерПравки }
        з.свой = СвойИИМодель.shared.активен
        return з
    }

    /// «Отправить»: строка «Что продаёте?», согласие, потом photo_gen.
    func отправить() {
        guard экран == .чат, !идёт, !закрыто else { return }
        let слова = String(ввод.trimmingCharacters(in: .whitespacesAndNewlines).prefix(пределТекста))
        guard !слова.isEmpty else {
            показатьВесть(т("aim_need_text"))
            вПоле += 1
            return
        }
        начать(запрос(название: слова), подпись: слова, изПоля: true)
    }

    /// Запуск с согласием: дано — сразу, нет — лист согласия, запуск после «Согласен».
    private func начать(_ з: ЗапросИИФото, подпись: String, изПоля: Bool) {
        guard согласиеДано else {
            отложенное = з
            отложеннаяПодпись = подпись
            отложеноИзПоля = изПоля
            согласие = true
            /* Сведения устарели («Свой ИИ» переключили) — спросить заново: лист назовёт исполнителя. */
            if !ГотовностьИИФото.shared.сведенияСвежие {
                let нужный = раздел
                Task { await ГотовностьИИФото.shared.проверить(раздел: нужный, заново: true) }
            }
            return
        }
        if изПоля { ввод = "" }
        послать(з, подпись: подпись)
    }

    /// «Согласен» в листе согласия: запомнить, на что дано (лист показывает то же — ктоОбработает), и запустить.
    func согласиться() {
        let предмет = предметСогласия
        if предмет.isEmpty {
            согласиеОкна = true
        } else {
            UserDefaults.standard.set(предмет, forKey: Self.ключСогласия)
        }
        согласие = false
        guard let з = отложенное else { return }
        отложенное = nil
        if отложеноИзПоля { ввод = "" }
        let подпись = отложеннаяПодпись
        Task { @MainActor [weak self] in
            /* Лист согласия уезжает — запуск начинается после него. */
            try? await Task.sleep(nanoseconds: 350_000_000)
            self?.послать(з, подпись: подпись)
        }
    }

    func отказатьсяОтСогласия() {
        согласие = false
        отложенное = nil
    }

    private func послать(_ з: ЗапросИИФото, подпись: String) {
        guard !идёт, !закрыто else { return }
        var человек = РепликаИИФото(кто: .человек)
        человек.текст = подпись
        var ответ = РепликаИИФото(кто: .ии)
        ответ.состояние = .ждём
        ответ.повтор = з
        withAnimation(ДвижениеСайта.вставкаСписка) {
            реплики.append(человек)
            реплики.append(ответ)
        }
        сдвиг += 1
        ОткликСайта.выбор()
        запустить(з, ответ: ответ.id)
    }

    private func запустить(_ з: ЗапросИИФото, ответ id: UUID) {
        идёт = true
        let моё = СессияПриложения.shared.поколение
        поколение = моё
        let подача = self.подача
        let прежний = сведения?.последний?.ключ ?? ""
        ИИФотоПодачи.shared.ждём(подача, прежний: прежний)
        запуск = Task { @MainActor [weak self] in
            let итог = await ИИФотоAPI.создать(з)
            guard let self, !Task.isCancelled, !self.закрыто else {
                /* Окно закрыли, пока ждали: готово или обрыв — картинку найдёт last при новом открытии; иначе ждать нечего. */
                switch итог {
                case .готово, .сеть: break
                default: ИИФотоПодачи.shared.дождались(подача)
                }
                return
            }
            guard моё == СессияПриложения.shared.поколение else {
                ИИФотоПодачи.shared.дождались(подача)
                self.показатьВход()
                return
            }
            switch итог {
            case .готово(let результат, let остаток):
                ГотовностьИИФото.shared.остаток(остаток)
                await self.готово(id, результат)
            case .отказ(let о) where о.код == "busy":
                /* Запуск уже идёт (в другом окне или на сайте) — дождаться его: результат будет в last. */
                self.ждать(id, прежний: прежний)
            case .отказ(let о):
                ИИФотоПодачи.shared.дождались(подача)
                self.отказВРеплике(id, о)
                if let свой = о.свойИИ { ОкноСвоегоИИ.показатьОтказ(свой) }
            case .сеть:
                self.изменить(id) { $0.проверяем = true }
                self.ждать(id, прежний: прежний)
            case .нуженВход:
                ИИФотоПодачи.shared.дождались(подача)
                self.показатьВход()
            case .выключено:
                ИИФотоПодачи.shared.дождались(подача)
                ГотовностьИИФото.shared.отметитьВыключено()
                self.недоступно()
            case .нетСервера:
                ИИФотоПодачи.shared.дождались(подача)
                ГотовностьИИФото.shared.отметитьНетСервера()
                self.недоступно()
            case .сбой:
                ИИФотоПодачи.shared.дождались(подача)
                self.отказВРеплике(id, ОтказИИФото(код: "fail", текст: self.т("aim_err_fail")))
            }
        }
    }

    /// Окно открыли снова, а прежний запуск ответа не дождался: ждём его в last.
    private func ждатьПослеОткрытия(прежний: String) {
        var ответ = РепликаИИФото(кто: .ии)
        ответ.состояние = .ждём
        ответ.проверяем = true
        withAnimation(ДвижениеСайта.вставкаСписка) { реплики.append(ответ) }
        сдвиг += 1
        поколение = СессияПриложения.shared.поколение
        ждать(ответ.id, прежний: прежний)
    }

    /**
     Опрос photo_gen_info раз в 4 с: busy — ждём; не busy и last новая (не та, что была до запуска) — это она. Не busy
     и новой нет дольше 20 с — запуск не дошёл: «Картинка не пришла» и «Повторить» (новый запуск). Связь пропала 6 раз
     подряд или сервер всё ещё busy через 4 минуты — «Проверить ещё раз»: тот же опрос, без нового запуска.
     */
    private func ждать(_ id: UUID, прежний: String) {
        запуск?.cancel()
        идёт = true
        let моё = поколение
        let нужный = раздел
        let подача = self.подача
        запуск = Task { @MainActor [weak self] in
            let начало = Date()
            var сбоев = 0
            var занят = false
            while !Task.isCancelled {
                try? await Task.sleep(nanoseconds: 4_000_000_000)
                if Task.isCancelled { return }
                let итог = await ИИФотоAPI.сведения(раздел: нужный)
                guard let self, !Task.isCancelled, !self.закрыто else { return }
                guard моё == СессияПриложения.shared.поколение else {
                    ИИФотоПодачи.shared.дождались(подача)
                    self.показатьВход()
                    return
                }
                ГотовностьИИФото.shared.принять(итог, раздел: нужный, сессия: СессияПриложения.shared.смена,
                                                 свой: СвойИИМодель.shared.активен)
                let прошло = Date().timeIntervalSince(начало)
                switch итог {
                case .есть(let с):
                    сбоев = 0
                    занят = с.занят
                    if !с.занят, let последний = с.последний, последний.ключ != прежний {
                        await self.готово(id, последний)
                        return
                    }
                    if !с.занят && прошло > 20 {
                        ИИФотоПодачи.shared.дождались(подача)
                        self.отказВРеплике(id, ОтказИИФото(код: "none", текст: self.т("aim_err_none")))
                        return
                    }
                case .выключено:
                    ИИФотоПодачи.shared.дождались(подача)
                    self.недоступно()
                    return
                case .гость:
                    ИИФотоПодачи.shared.дождались(подача)
                    self.показатьВход()
                    return
                case .нетСервера:
                    ИИФотоПодачи.shared.дождались(подача)
                    self.недоступно()
                    return
                case .сеть:
                    сбоев += 1
                    if сбоев >= 6 {
                        self.отказВРеплике(id, ОтказИИФото(код: "net", текст: self.т("aim_err_net")), ждатьКлюч: прежний)
                        return
                    }
                }
                if прошло > 240 {
                    if занят {
                        self.отказВРеплике(id, ОтказИИФото(код: "slow", текст: self.т("aim_err_slow")), ждатьКлюч: прежний)
                    } else {
                        ИИФотоПодачи.shared.дождались(подача)
                        self.отказВРеплике(id, ОтказИИФото(код: "none", текст: self.т("aim_err_none")))
                    }
                    return
                }
            }
        }
    }

    /// Картинка готова: скачать для показа (полный кадр, иначе миниатюра); не скачалась — взять всё равно можно.
    private func готово(_ id: UUID, _ итог: ИтогИИФото) async {
        ИИФотоПодачи.shared.дождались(подача)
        ГотовностьИИФото.shared.последний(итог)
        let данные = await КартинкиИИФото.скачатьИтог(итог)
        guard !закрыто else { return }
        let картинка = данные.flatMap { UIImage(data: $0) }
        let уже = подача.плитки.contains { $0.url == итог.адрес }
        изменить(id) { р in
            р.состояние = .готово
            р.итог = итог
            р.картинка = картинка
            р.своимИИ = итог.своимИИ
            р.проверяем = false
            р.отказ = nil
            р.взята = уже
        }
        идёт = false
        сдвиг += 1
        ОткликСайта.успех()
        UIAccessibility.post(notification: .announcement, argument: т("aim_done_a11y"))
    }

    // MARK: - Отказы

    /// ждатьКлюч — ключ last до запуска: картинка ещё может прийти, «Проверить ещё раз» продолжит опрос.
    private func отказВРеплике(_ id: UUID, _ о: ОтказИИФото, ждатьКлюч: String? = nil) {
        guard !закрыто else { return }
        запуск?.cancel()
        идёт = false
        изменить(id) { р in
            р.состояние = .отказ
            р.отказ = о
            р.проверяем = false
            р.ждатьКлюч = ждатьКлюч
        }
        сдвиг += 1
        ОткликСайта.предупреждение()
        UIAccessibility.post(notification: .announcement, argument: о.текст)
    }

    /// Ход не начался (нужен вход) — пустую реплику ожидания не оставляем.
    private func убратьЖдущую(_ id: UUID) {
        guard let место = реплики.firstIndex(where: { $0.id == id }), реплики[место].состояние == .ждём else { return }
        реплики.remove(at: место)
        if место > 0, реплики[место - 1].кто == .человек { реплики.remove(at: место - 1) }
        идёт = false
    }

    private func показатьВход() {
        guard !закрыто else { return }
        запуск?.cancel()
        идёт = false
        if let ждущая = реплики.last(where: { $0.состояние == .ждём }) { убратьЖдущую(ждущая.id) }
        перейти(.вход)
    }

    /// Сервер выключил рубильник или двери нет — «Сейчас недоступно», ждущая реплика уходит.
    private func недоступно() {
        guard !закрыто else { return }
        запуск?.cancel()
        идёт = false
        if let ждущая = реплики.last(where: { $0.состояние == .ждём }) { убратьЖдущую(ждущая.id) }
        перейти(.скоро)
    }

    /// Вошли из окна: сведения гостя больше не годятся.
    func послеВхода() {
        поколение = СессияПриложения.shared.поколение
        ГотовностьИИФото.shared.устарели()
        let нужный = раздел
        перейти(.чат)
        Task { @MainActor [weak self] in
            await ГотовностьИИФото.shared.проверить(раздел: нужный, заново: true)
            await СвойИИМодель.shared.загрузитьЛениво()
            guard let self, !self.закрыто else { return }
            if !ГотовностьИИФото.shared.доступно(раздел: нужный) && self.реплики.isEmpty { self.перейти(.скоро) }
        }
    }

    /// «Повторить»: тот же запуск ещё раз — в той же реплике.
    func повторить(_ id: UUID) {
        guard !идёт, let р = реплики.first(where: { $0.id == id }), let з = р.повтор else { return }
        изменить(id) { р in
            р.состояние = .ждём
            р.отказ = nil
            р.проверяем = false
            р.ждатьКлюч = nil
        }
        запустить(з, ответ: id)
    }

    /// «Проверить ещё раз»: картинка ещё может прийти — тот же опрос info, без нового запуска.
    func проверитьСнова(_ id: UUID) {
        guard !идёт, let р = реплики.first(where: { $0.id == id }), let ключ = р.ждатьКлюч else { return }
        изменить(id) { р in
            р.состояние = .ждём
            р.отказ = nil
            р.проверяем = true
            р.ждатьКлюч = nil
        }
        поколение = СессияПриложения.shared.поколение
        ждать(id, прежний: ключ)
    }

    /// «Ещё вариант»: новый запуск с той же просьбой — новой парой реплик (прежняя картинка остаётся).
    func ещёВариант(_ id: UUID) {
        guard !идёт, let р = реплики.first(where: { $0.id == id }), let з = р.повтор else { return }
        начать(з, подпись: т("aim_again"), изПоля: false)
    }

    /// «Собрать обложку без рисунка» (cover_ok) — тот же запрос с cover:1.
    func обложкаБезРисунка(_ id: UUID) {
        guard !идёт, let р = реплики.first(where: { $0.id == id }), var з = р.повтор else { return }
        з.обложка = true
        з.kliko = false
        начать(з, подпись: т("aim_cover_btn"), изПоля: false)
    }

    /// «Нарисовать с Kliko AI» (own_ai:"images" и kliko_ok) — тот же запрос с kliko:1. Без реплики — из строки окна.
    func нарисоватьKliko(_ id: UUID?) {
        guard !идёт else { return }
        var з: ЗапросИИФото
        if let id, let р = реплики.first(where: { $0.id == id }), let прежний = р.повтор {
            з = прежний
        } else {
            let слова = String(ввод.trimmingCharacters(in: .whitespacesAndNewlines).prefix(пределТекста))
            guard !слова.isEmpty else {
                показатьВесть(т("aim_need_text"))
                вПоле += 1
                return
            }
            з = запрос(название: слова)
        }
        з.kliko = true
        з.обложка = false
        начать(з, подпись: т("aim_kliko_btn"), изПоля: id == nil)
    }

    // MARK: - В объявление

    /**
     «Взять в объявление»: url ставится плиткой как обычное загруженное фото — без новой загрузки и без вшитой пометки
     (метку ставит сервер). Порядок кадров после публикации — сервер: настоящие фото первыми.
     */
    func взять(_ id: UUID) {
        guard !берём, let р = реплики.first(where: { $0.id == id }), let итог = р.итог, !р.взята else { return }
        if подача.плитки.contains(where: { $0.url == итог.адрес }) {
            изменить(id) { $0.взята = true }
            return
        }
        guard подача.местоФото > 0 else {
            показатьВесть(String(format: ПодачаText.т("photo_cap_full"), подача.лимитФото))
            return
        }
        берём = true
        let плитка = ПлиткаФото(id: UUID(), url: итог.адрес, превью: р.картинка, картинка: nil, миниатюра: nil,
                                грузится: false, ошибка: nil)
        withAnimation(ДвижениеСайта.вставкаСписка) { подача.плитки.append(плитка) }
        ИИФотоПодачи.shared.отметитьФото(подача, адрес: итог.адрес, вид: итог.вид)
        изменить(id) { $0.взята = true }
        берём = false
        ОткликСайта.успех()
        показатьВесть(т("aim_taken"))
    }
}

// MARK: - Реплика

/// Реплика ленты: человек (текст) или ИИ (ожидание, картинка, отказ).
struct РепликаИИФото: Identifiable, Equatable {
    enum Кто: Equatable {
        case человек, ии
    }

    enum Состояние: Equatable {
        case готово, ждём, отказ
    }

    var id = UUID()
    var кто: Кто
    /// Текст человека.
    var текст = ""
    var состояние: Состояние = .готово
    /// Ждём не ответа запуска, а картинки в last (связь оборвалась, окно открыли снова, запуск уже шёл).
    var проверяем = false
    var итог: ИтогИИФото? = nil
    var картинка: UIImage? = nil
    var своимИИ = false
    var отказ: ОтказИИФото? = nil
    var повтор: ЗапросИИФото? = nil
    /// Отказ посреди ожидания (связь, долго): ключ last до запуска — «Проверить ещё раз» продолжает опрос.
    var ждатьКлюч: String? = nil
    var взята = false

    init(кто: Кто) {
        self.кто = кто
    }
}

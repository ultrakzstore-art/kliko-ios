import SwiftUI
import UIKit

/**
 ОКНО «ОБЪЯВЛЕНИЕ С ИИ» — СОСТОЯНИЕ (одно на открытое окно, не синглтон; держит его ЭкранЧатаИИФото).

 Лента реплик как в мессенджере: человек пишет («Lenovo Yoga 7 Gen 7», «сделай описание короче») или жмёт подсказку-
 чип, ИИ отвечает карточкой: в режиме А — черновик объявления с обложкой-иллюстрацией, в режиме Б — правленое фото.
 Ход: start → опрос status раз в 1,5 с (до 90 с с картинкой, до 45 с — только текст; дольше — «Проверить ещё раз» той
 же задачи; связь пропала 4 раза подряд — «Нет соединения»). Черновик может прийти раньше картинки — показывается сразу.
 Перед первой отправкой — согласие (кто обработает — ai и ai_text из info, 24 часа, не для обучения): на этого
 человека и этих поставщиков; сменились (или формулировка была общей) — спросится снова.

 Итоги: «Взять в объявление» (accept: фото готовится тем же путём, что все фото подачи, и ложится плиткой с пометкой),
 «Создать объявление» (accept_draft: поля — предложениями тем же путём, что «Распознать», обложка — первой плиткой),
 постер (собран на телефоне — accept с poster:true). Окно закрыли — опрос стоит, диалог на сервере остаётся (вернуться
 можно); «Удалить диалог» — delete сразу. Ответ, пришедший после выхода из аккаунта, не принимается.
 */
@MainActor
final class МодельЧатаИИФото: ObservableObject {
    enum Экран: Hashable {
        case чат, вход, скоро
    }

    enum Режим: String {
        case draft, edit
    }

    /// Куда кладётся взятая картинка.
    enum КакВзять: Equatable {
        /// Новой плиткой в конец.
        case новое
        /// Новой плиткой первой — обложкой.
        case обложка
        /// Вместо плитки, с которой открыли правку.
        case заменить(UUID)
    }

    let подача: ПодачаМодель
    let вход: ВходЧатаИИФото
    /// Закрыть окно (ставит экран, который его показал).
    var закрытьОкно: (() -> Void)? = nil

    @Published private(set) var экран: Экран = .чат
    @Published private(set) var реплики: [РепликаИИФото] = []
    @Published var ввод = ""
    @Published private(set) var режим: Режим = .draft
    /// Настоящее фото вещи для следующего хода правки.
    @Published private(set) var фото: UIImage? = nil
    /// Картинка, которую правим следующим ходом («Править эту»), — показ над полем ввода.
    @Published private(set) var основа: UIImage? = nil
    @Published private(set) var идёт = false
    @Published private(set) var готовимФото = false
    @Published private(set) var берём = false
    @Published private(set) var загружаемИсторию = false
    /// Лист согласия перед первой отправкой.
    @Published var согласие = false
    /// Открыть выбор фото (need_photo, «Другое фото», скрепка у поля).
    @Published var выбратьФото = false
    /// Окно запрета товара (как при загрузке фото подачи).
    @Published var запрет: ЗапретИИФото? = nil
    /// Поставить курсор в поле ввода («Изменить» у черновика, вставка из чипа).
    @Published var вПоле = 0
    /// Растёт при каждом изменении ленты — экран прокручивает её вниз.
    @Published private(set) var сдвиг = 0
    @Published private(set) var весть: String? = nil

    private var диалог = ""
    private var адресФото = ""
    /// Адрес плитки, из которой взято фото (photo_url); фото из галереи — пусто.
    private var ссылкаФото = ""
    /// Это фото уже ушло в диалог: следующие ходы правки сервер берёт из диалога.
    private var фотоОтправлено = false
    private var основаID = ""
    private var основаВид = ""
    private var опрос: Task<Void, Never>? = nil
    private var запуск: Task<Void, Never>? = nil
    private var отложенное: ЗапросХодаИИФото? = nil
    private var отложеннаяПодпись = ""
    private var отложеноИзПоля = false
    private var отложенноеДо: UIImage? = nil
    /// Согласие на общую формулировку («сторонний ИИ-сервис») — только до закрытия этого окна.
    private var согласиеОкна = false
    private var поколение: Int
    private var закрыто = false
    private var номерВести = 0

    /// Согласие на передачу текста и фото ИИ: строка «на что дано» (предметСогласия). v1 — флаг без поставщика.
    static let ключСогласия = "kliko.aiimage.consent.v2"

    init(подача: ПодачаМодель, вход: ВходЧатаИИФото) {
        self.подача = подача
        self.вход = вход
        поколение = СессияПриложения.shared.поколение
        if case .правка = вход { режим = .edit }
    }

    private func т(_ ключ: String) -> String { ИИФотоText.т(ключ) }

    var сведения: СведенияИИФото? { ГотовностьИИФото.shared.сведения }

    /**
     На что даётся согласие (App Review 5.1.2(i)): человек, кто обработает картинки и текст, через «Свой ИИ» ли. Пусто —
     сведения гостевые или устарели (свой ИИ включили или выключили после info), нет имени поставщика или ещё не знаем,
     кто вошёл: формулировка общая, и согласие на неё живёт только в этом окне.
     */
    var предметСогласия: String {
        guard let с = сведения, ГотовностьИИФото.shared.сведенияСвежие, с.вошёл, СессияПриложения.shared.вошёл == true,
              !с.ии.isEmpty else { return "" }
        let uid = подача.страница.состояние?.uid ?? ""
        let кто = uid.isEmpty ? СессияПриложения.shared.id : uid
        guard !кто.isEmpty else { return "" }
        return [кто, с.ии, с.ииТекста, с.свойИИ ? "own" : "kliko"].joined(separator: "|")
    }

    /// Согласие уже дано на то же самое: тот же человек и те же поставщики (или общее — в этом окне).
    var согласиеДано: Bool {
        let предмет = предметСогласия
        if предмет.isEmpty { return согласиеОкна }
        return UserDefaults.standard.string(forKey: Self.ключСогласия) == предмет
    }

    var пределТекста: Int { сведения?.пределТекста ?? 500 }

    /// Есть ли диалог на сервере (для «Удалить диалог»).
    var естьДиалог: Bool { !диалог.isEmpty }

    /// «Объявление по названию» доступно: можно вернуться к нему из правки.
    var черновикДоступен: Bool { ГотовностьИИФото.shared.черновикДоступен && !подача.правка }

    /**
     Кто обработает фото и нарисует картинки, кто напишет текст — для согласия (App Review 5.1.2(i)). Пусто, сведения
     ещё гостевые, а человек уже вошёл, или устарели («Свой ИИ» переключили) — честно и общо: «сторонний ИИ-сервис по
     поручению Kliko».
     */
    var ктоОбработает: (картинки: String, текст: String) {
        let общий = т("aim_ai_generic")
        guard let с = сведения, ГотовностьИИФото.shared.сведенияСвежие,
              с.вошёл || СессияПриложения.shared.вошёл != true else { return (общий, общий) }
        let картинки = с.ии.isEmpty ? общий : (с.свойИИ ? String(format: т("aim_ai_own"), с.ии) : с.ии)
        let текст = с.ииТекста.isEmpty ? общий : (с.свойИИ ? String(format: т("aim_ai_own"), с.ииТекста) : с.ииТекста)
        return (картинки, текст)
    }

    /// Последняя реплика ИИ с черновиком — у неё полная карточка, у прежних — короткая строка.
    var последнийЧерновик: UUID? {
        реплики.last(where: { $0.кто == .ии && $0.черновик != nil })?.id
    }

    // MARK: - Открыли и закрыли

    func открыт() {
        if СессияПриложения.shared.вошёл == false { экран = .вход }
        диалог = ИИФотоПодачи.shared.диалог(подача)
        Task { @MainActor in
            await ГотовностьИИФото.shared.проверить()
            if СессияПриложения.shared.вошёл != false { await СвойИИМодель.shared.загрузитьЛениво() }
            if ГотовностьИИФото.shared.нетСервера { self.перейти(.скоро) }
            if let с = ГотовностьИИФото.shared.сведения, !с.вошёл, СессияПриложения.shared.вошёл != true {
                self.перейти(.вход)
            }
        }
        if !диалог.isEmpty && экран == .чат { восстановить() }
        if case .правка(let плитка) = вход { загрузитьФотоПлитки(плитка) }
    }

    /// Окно закрыли: опрос стоит; диалог на сервере остаётся (вернуться можно, сервер сотрёт его через сутки).
    func закрыть() {
        guard !закрыто else { return }
        закрыто = true
        опрос?.cancel()
        запуск?.cancel()
    }

    func показатьВесть(_ текст: String) {
        номерВести += 1
        let номер = номерВести
        withAnimation(ДвижениеСайта.появление) { весть = текст }
        UIAccessibility.post(notification: .announcement, argument: текст)
        Task { @MainActor [weak self] in
            try? await Task.sleep(nanoseconds: 2_600_000_000)
            guard let self, номер == self.номерВести else { return }
            withAnimation(ДвижениеСайта.уход) { self.весть = nil }
        }
    }

    private func перейти(_ новый: Экран) {
        guard экран != новый else { return }
        withAnimation(ДвижениеСайта.шаг) { экран = новый }
    }

    private func изменить(_ id: UUID, _ правка: (inout РепликаИИФото) -> Void) {
        guard let место = реплики.firstIndex(where: { $0.id == id }) else { return }
        var р = реплики[место]
        правка(&р)
        реплики[место] = р
    }

    private func запомнитьДиалог(_ новый: String) {
        guard !новый.isEmpty else { return }
        диалог = новый
        ИИФотоПодачи.shared.запомнитьДиалог(подача, новый)
    }

    // MARK: - Фото вещи

    /// Правка из плитки: фото плитки (с телефона или с сайта) — как первое фото диалога.
    private func загрузитьФотоПлитки(_ id: UUID) {
        guard let плитка = подача.плитки.first(where: { $0.id == id }) else { return }
        готовимФото = true
        Task { @MainActor [weak self] in
            let данные = await КартинкиИИФото.данныеПлитки(плитка)
            let готовое = await Task.detached(priority: .userInitiated) { () -> КартинкиИИФото.ГотовоеДляПравки? in
                данные.flatMap { КартинкиИИФото.фотоДляПравки($0) }
            }.value
            self?.принятьГотовое(готовое, ссылка: плитка.url)
        }
    }

    /// Фото из галереи (скрепка у поля, «Другое фото», need_photo).
    func принятьФото(данные: Data) {
        guard !готовимФото else { return }
        готовимФото = true
        Task { @MainActor [weak self] in
            let готовое = await Task.detached(priority: .userInitiated) { () -> КартинкиИИФото.ГотовоеДляПравки? in
                КартинкиИИФото.фотоДляПравки(данные)
            }.value
            self?.принятьГотовое(готовое)
        }
    }

    /// ссылка — адрес плитки подачи, из которой фото (photo_url); из галереи — пусто.
    private func принятьГотовое(_ готовое: КартинкиИИФото.ГотовоеДляПравки?, ссылка: String = "") {
        готовимФото = false
        guard !закрыто else { return }
        guard let готовое, let картинка = UIImage(data: готовое.jpeg) else {
            ОткликСайта.предупреждение()
            показатьВесть(т("aim_photo_fail"))
            return
        }
        адресФото = готовое.адрес
        ссылкаФото = ссылка
        фотоОтправлено = false
        фото = картинка
        снятьОснову()
        режим = .edit
        сдвиг += 1
    }

    /// «✕» у фото над полем: дальше — без нового фото (в черновике — снова «Объявление по названию»).
    func убратьФото() {
        фото = nil
        адресФото = ""
        ссылкаФото = ""
        фотоОтправлено = false
        if черновикДоступен { режим = .draft }
    }

    /// «Править эту»: следующий ход — доработка этой картинки (base_image).
    func правитьЭту(_ id: UUID) {
        guard let р = реплики.first(where: { $0.id == id }), !р.картинкаID.isEmpty, let картинка = р.картинка else { return }
        ОткликСайта.выбор()
        основаID = р.картинкаID
        основаВид = р.вид
        основа = картинка
        режим = р.вид == "edited" ? .edit : .draft
        вПоле += 1
    }

    func снятьОснову() {
        основаID = ""
        основаВид = ""
        основа = nil
    }

    // MARK: - Подсказки-чипы

    struct Чип: Identifiable, Equatable {
        let id: String
        let подпись: String
        let пресет: String
        /// Ход только с текстом или только с картинкой; пусто — решит сервер.
        let нужно: [String]
        /// Не отправлять, а вставить начало фразы в поле (человек допишет: «гарантия 3 месяца»).
        let вставка: String?
    }

    var чипы: [Чип] {
        if режим == .edit {
            return [
                Чип(id: "bg_white", подпись: т("aim_chip_white"), пресет: "bg_white", нужно: ["image"], вставка: nil),
                Чип(id: "declutter", подпись: т("aim_chip_declutter"), пресет: "declutter", нужно: ["image"], вставка: nil),
                Чип(id: "light", подпись: т("aim_chip_light"), пресет: "light", нужно: ["image"], вставка: nil),
                Чип(id: "interior", подпись: т("aim_chip_table"), пресет: "interior", нужно: ["image"], вставка: nil),
                Чип(id: "bg_studio", подпись: т("aim_chip_catalog"), пресет: "bg_studio", нужно: ["image"], вставка: nil)
            ]
        }
        guard !диалог.isEmpty else { return [] }
        return [
            Чип(id: "shorter", подпись: т("aim_chip_shorter"), пресет: "shorter", нужно: ["text"], вставка: nil),
            Чип(id: "longer", подпись: т("aim_chip_longer"), пресет: "longer", нужно: ["text"], вставка: nil),
            Чип(id: "warranty", подпись: т("aim_chip_warranty"), пресет: "", нужно: [], вставка: т("aim_ins_warranty")),
            Чип(id: "bg", подпись: т("aim_chip_bg"), пресет: "bg_studio", нужно: ["image"], вставка: nil),
            Чип(id: "color", подпись: т("aim_chip_color"), пресет: "", нужно: [], вставка: т("aim_ins_color"))
        ]
    }

    func нажатьЧип(_ чип: Чип) {
        ОткликСайта.выбор()
        if let вставка = чип.вставка {
            ввод = вставка
            вПоле += 1
            return
        }
        отправить(текст: чип.подпись, пресет: чип.пресет, нужно: чип.нужно)
    }

    /// Пример под пустым чатом («Lenovo Yoga 7 Gen 7») — в поле, человек может дописать.
    func вставитьПример(_ пример: String) {
        ввод = пример
        вПоле += 1
    }

    // MARK: - Ход

    /**
     «Отправить»: текст поля (или чипа). Проверки, согласие, потом start. основаХода — base_image этого хода вместо
     выбранной «Править эту» («Ещё вариант»), доХода — «До» для шторки такого хода.
     */
    func отправить(текст: String? = nil, пресет: String = "", нужно: [String] = [], основаХода: String? = nil,
                   доХода: UIImage? = nil) {
        guard экран == .чат, !идёт, !закрыто, !готовимФото else { return }
        let изПоля = текст == nil
        let слова = String((текст ?? ввод).trimmingCharacters(in: .whitespacesAndNewlines).prefix(пределТекста))
        let правка = режим == .edit
        if !правка && слова.isEmpty && диалог.isEmpty {
            показатьВесть(т("aim_need_text"))
            вПоле += 1
            return
        }
        if правка && адресФото.isEmpty && !фотоОтправлено && основаID.isEmpty && диалог.isEmpty {
            выбратьФото = true
            return
        }
        var з = ЗапросХодаИИФото()
        з.режим = режим.rawValue
        з.текст = слова
        з.пресет = пресет
        з.раздел = подача.форма.раздел
        з.состояние = подача.форма.раздел.isEmpty || !подача.состояниеВидно ? "" : подача.форма.состояние
        з.фото = правка && !фотоОтправлено && основаХода == nil ? адресФото : ""
        з.основа = основаХода ?? основаID
        if правка && з.фото.isEmpty && з.основа.isEmpty {
            /* Правка без нового фото: основа — явно (иначе сервер выбрал бы её сам и мог взять иллюстрацию, §2). */
            guard let своя = основаПравки else {
                выбратьФото = true
                return
            }
            з.основа = своя
        }
        з.ссылкаФото = з.фото.isEmpty ? "" : ссылкаФото
        if правка {
            з.нужно = ["image"]
        } else if !нужно.isEmpty {
            з.нужно = нужно
        } else if реплики.allSatisfy({ $0.черновик == nil }) {
            з.нужно = ["text", "image"]
        }
        з.свой = СвойИИМодель.shared.активен
        let подпись = слова.isEmpty ? т(правка ? "aim_default_edit" : "aim_default_draft") : слова
        guard согласиеДано else {
            отложенное = з
            отложеннаяПодпись = подпись
            отложеноИзПоля = изПоля
            отложенноеДо = доХода
            согласие = true
            /* Сведения устарели («Свой ИИ» переключили) — спросить заново: следующий лист назовёт поставщика. */
            if !ГотовностьИИФото.shared.сведенияСвежие { Task { await ГотовностьИИФото.shared.проверить() } }
            return
        }
        if изПоля { ввод = "" }
        послать(з, подпись: подпись, до: доХода)
    }

    /**
     Основа хода правки без нового фото и без «Править эту»: image_id последнего результата правки после последнего
     нового фото; результатов после фото нет — "" (сервер берёт само фото, §2). nil — фото в диалоге нет.
     */
    private var основаПравки: String? {
        for р in реплики.reversed() {
            if р.кто == .человек && р.новоеФото { return "" }
            if р.кто == .ии && р.вид == "edited" && !р.картинкаID.isEmpty && !р.удалена { return р.картинкаID }
        }
        return nil
    }

    /// «Согласен» в листе согласия: запомнить, на что дано (лист показывает то же — ктоОбработает), и отправить ход.
    func согласиться() {
        let предмет = предметСогласия
        if предмет.isEmpty {
            согласиеОкна = true
        } else {
            UserDefaults.standard.set(предмет, forKey: Self.ключСогласия)
        }
        согласие = false
        guard let з = отложенное else { return }
        отложенное = nil
        if отложеноИзПоля { ввод = "" }
        let подпись = отложеннаяПодпись
        let до = отложенноеДо
        отложенноеДо = nil
        Task { @MainActor [weak self] in
            /* Лист согласия уезжает — ход начинается после него. */
            try? await Task.sleep(nanoseconds: 350_000_000)
            self?.послать(з, подпись: подпись, до: до)
        }
    }

    func отказатьсяОтСогласия() {
        согласие = false
        отложенное = nil
        отложенноеДо = nil
    }

    /// до — «До» для шторки, если ход не про текущее фото или выбранную основу («Ещё вариант»).
    private func послать(_ запрос: ЗапросХодаИИФото, подпись: String, до: UIImage? = nil) {
        guard !идёт, !закрыто else { return }
        var з = запрос
        з.диалог = диалог
        var человек = РепликаИИФото(кто: .человек)
        человек.режим = з.режим
        человек.текст = подпись
        if з.режим == "edit" { человек.фото = основа ?? (з.фото.isEmpty ? nil : фото) }
        человек.новоеФото = з.режим == "edit" && !з.фото.isEmpty
        var ответ = РепликаИИФото(кто: .ии)
        ответ.режим = з.режим
        ответ.состояние = .ждём
        ответ.нуженРисунок = з.нужно.isEmpty || з.нужно.contains("image")
        ответ.до = з.режим == "edit" ? (до ?? основа ?? фото) : nil
        ответ.повтор = з
        withAnimation(ДвижениеСайта.вставкаСписка) {
            реплики.append(человек)
            реплики.append(ответ)
        }
        сдвиг += 1
        снятьОснову()
        ОткликСайта.выбор()
        запустить(з, ответ: ответ.id)
    }

    private func запустить(_ запрос: ЗапросХодаИИФото, ответ id: UUID) {
        идёт = true
        let моё = СессияПриложения.shared.поколение
        поколение = моё
        let подача = self.подача
        запуск = Task { @MainActor [weak self] in
            let итог = await ИИФотоAPI.начать(запрос)
            /*
             Диалог, который сервер уже начал (с текстом, а в правке — с фото человека), запоминаем и при закрытом окне:
             к нему можно вернуться, и он удалится вместе с подачей (публикация, «Начать заново»). Чужой (вышли) — нет.
             */
            if case .готово(let j) = итог, моё == СессияПриложения.shared.поколение {
                let номер = МоиОбъявленияAPI.строка(j["thread"]).trimmingCharacters(in: .whitespacesAndNewlines)
                if !номер.isEmpty { ИИФотоПодачи.shared.запомнитьДиалог(подача, номер) }
            }
            guard let self, !Task.isCancelled, !self.закрыто else { return }
            guard моё == СессияПриложения.shared.поколение else {
                self.показатьВход()
                return
            }
            guard case .готово(let j) = итог else {
                self.неУдалось(id, итог, вОпросе: false)
                return
            }
            self.запомнитьДиалог(МоиОбъявленияAPI.строка(j["thread"]).trimmingCharacters(in: .whitespacesAndNewlines))
            if запрос.режим == "edit" && !запрос.фото.isEmpty { self.фотоОтправлено = true }
            let картинок: Int? = j["left"] != nil ? МоиОбъявленияAPI.целое(j["left"]) : nil
            let текста: Int? = j["text_left"] != nil ? МоиОбъявленияAPI.целое(j["text_left"]) : nil
            ГотовностьИИФото.shared.остаток(картинок: картинок, текста: текста)
            let задача = МоиОбъявленияAPI.строка(j["job"]).trimmingCharacters(in: .whitespacesAndNewlines)
            guard !задача.isEmpty else {
                self.отказВРеплике(id, ОтказИИФото(код: "fail", текст: self.т("aim_err_fail")), продолжаемая: false)
                return
            }
            self.изменить(id) { $0.задача = задача }
            self.опрашивать(id, задача: задача, предел: запрос.предел)
        }
    }

    /// status раз в 1,5 с до предела; связь пропала 4 раза подряд — «Нет соединения» и «Повторить» той же задачи.
    private func опрашивать(_ id: UUID, задача: String, предел: TimeInterval) {
        опрос?.cancel()
        идёт = true
        let моё = поколение
        опрос = Task { @MainActor [weak self] in
            let начало = Date()
            var сбоев = 0
            while !Task.isCancelled {
                try? await Task.sleep(nanoseconds: 1_500_000_000)
                if Task.isCancelled { return }
                if Date().timeIntervalSince(начало) > предел {
                    guard let self else { return }
                    self.отказВРеплике(id, ОтказИИФото(код: "slow", текст: self.т("aim_err_slow")), продолжаемая: true)
                    return
                }
                let ответ = await ИИФотоAPI.ход(задача)
                guard let self, !Task.isCancelled, !self.закрыто else { return }
                guard моё == СессияПриложения.shared.поколение else {
                    self.показатьВход()
                    return
                }
                switch ответ {
                case .готово(let j):
                    сбоев = 0
                    let ход = ХодИИФото(j)
                    switch ход.состояние {
                    case .done:
                        await self.готово(id, ход)
                        return
                    case .failed:
                        self.неУдалось(id, ИИФотоAPI.разобратьОтказ(j), вОпросе: false)
                        return
                    case .queued, .working:
                        self.принятьХод(id, ход)
                    }
                case .сеть, .сбой:
                    сбоев += 1
                    if сбоев >= 4 {
                        self.неУдалось(id, ответ, вОпросе: true)
                        return
                    }
                case .отказ, .нуженВход, .нетСервера:
                    self.неУдалось(id, ответ, вОпросе: false)
                    return
                }
            }
        }
    }

    /// Ход в работе: проценты не убывают и сами чуть подтягиваются (не выше 92 до done); черновик — сразу, если пришёл.
    private func принятьХод(_ id: UUID, _ ход: ХодИИФото) {
        guard let р = реплики.first(where: { $0.id == id }) else { return }
        let вОчереди = ход.состояние == .queued
        let потолок = вОчереди ? 8 : 92
        let новое = max(р.прогресс, min(ход.прогресс, 99), min(потолок, р.прогресс + 2))
        var п = р
        п.вОчереди = вОчереди
        п.этап = ход.этап
        let новыйЧерновик = ход.черновик != nil && ход.черновик != р.черновик
        if let черновик = ход.черновик, новыйЧерновик {
            п.черновик = черновик
            п.изменено = ход.изменено
        }
        if !ход.подпись.isEmpty { п.текст = ход.подпись }
        guard п != р || новое != р.прогресс else { return }
        withAnimation(ДвижениеСайта.прогресс) {
            п.прогресс = новое
            изменить(id) { $0 = п }
        }
        /* Черновик пришёл раньше картинки — показать его; проценты ленту не дёргают. */
        if новыйЧерновик { сдвиг += 1 }
    }

    /// done: подпись, черновик, картинка (две попытки скачать) и постер, если есть черновик и картинка.
    private func готово(_ id: UUID, _ ход: ХодИИФото) async {
        ГотовностьИИФото.shared.остаток(картинок: ход.осталось, текста: ход.текстОсталось)
        var картинка: UIImage? = nil
        if let адрес = ход.картинка {
            withAnimation(ДвижениеСайта.прогресс) { изменить(id) { $0.прогресс = max($0.прогресс, 96) } }
            var данные: Data? = nil
            for попытка in 0..<2 where данные == nil {
                if попытка > 0 { try? await Task.sleep(nanoseconds: 800_000_000) }
                данные = await КартинкиИИФото.скачать(адрес)
            }
            guard !закрыто else { return }
            картинка = данные.flatMap { UIImage(data: $0) }
            if картинка == nil {
                отказВРеплике(id, ОтказИИФото(код: "fail", текст: т("aim_err_image")), продолжаемая: false)
                return
            }
        }
        guard !закрыто else { return }
        изменить(id) { р in
            р.состояние = .готово
            р.прогресс = 100
            if !ход.подпись.isEmpty { р.текст = ход.подпись }
            if let черновик = ход.черновик {
                р.черновик = черновик
                р.изменено = ход.изменено
            }
            р.заметка = ход.заметка
            р.своимИИ = ход.своимИИ
            if let картинка {
                р.картинка = картинка
                р.картинкаID = ход.картинкаID
                /* Вид — только со слов сервера; нет или незнакомый — строже: иллюстрация (не фото товара). */
                р.вид = ход.вид == "edited" ? "edited" : "illustration"
            }
            р.отказ = nil
        }
        идёт = false
        сдвиг += 1
        ОткликСайта.успех()
        let объявить = ход.подпись.isEmpty ? т("aim_done_a11y") : ход.подпись
        UIAccessibility.post(notification: .announcement, argument: объявить)
        собратьПостер(id)
    }

    /// Постер: картинка ответа (иллюстрация) + название и главное черновика. Собирается в фоне, на телефоне.
    private func собратьПостер(_ id: UUID) {
        guard let р = реплики.first(where: { $0.id == id }), р.вид == "illustration", let картинка = р.картинка,
              let черновик = р.черновик ?? реплики.last(where: { $0.черновик != nil })?.черновик,
              !черновик.название.isEmpty else { return }
        /* На постере — без цен, «оригинал», гарантии и контактов: название — до первого такого слова (ЧерновикИИФото). */
        let название = ЧерновикИИФото.названиеДляПостера(черновик.название)
        guard !название.isEmpty else { return }
        let пункты: [String] = черновик.главное.isEmpty
            ? Array(черновик.характеристики.map { $0.значение }.filter { ЧерновикИИФото.годноДляПостера($0) }.prefix(4))
            : черновик.главное
        let справаНалево = ИИФотоText.язык == "ar"
        Task { @MainActor [weak self] in
            let постер = await Task.detached(priority: .utility) { () -> UIImage? in
                КартинкиИИФото.постер(картинка, название: название, пункты: пункты, справаНалево: справаНалево)
            }.value
            guard let self, let постер, !self.закрыто else { return }
            self.изменить(id) { $0.постер = постер }
        }
    }

    // MARK: - Отказы

    private func неУдалось(_ id: UUID, _ ответ: ИИФотоAPI.Ответ, вОпросе: Bool) {
        switch ответ {
        case .готово:
            отказВРеплике(id, ОтказИИФото(код: "fail", текст: т("aim_err_fail")), продолжаемая: false)
        case .отказ(let о):
            if о.код == "gone" {
                диалог = ""
                фотоОтправлено = false
                ИИФотоПодачи.shared.забытьДиалог(подача)
            }
            if о.код == "need_photo" { фотоОтправлено = false }
            отказВРеплике(id, о, продолжаемая: false)
            if let з = о.запрет { запрет = з }
            if let свой = о.свойИИ { ОкноСвоегоИИ.показатьОтказ(свой) }
            if о.код == "need_photo" { выбратьФото = true }
        case .нуженВход:
            убратьЖдущую(id)
            показатьВход()
        case .нетСервера:
            ГотовностьИИФото.shared.отметитьНетСервера()
            опрос?.cancel()
            идёт = false
            перейти(.скоро)
        case .сеть:
            отказВРеплике(id, ОтказИИФото(код: "net", текст: т("aim_err_net")), продолжаемая: вОпросе)
        case .сбой:
            отказВРеплике(id, ОтказИИФото(код: "fail", текст: т("aim_err_fail")), продолжаемая: вОпросе)
        }
    }

    private func отказВРеплике(_ id: UUID, _ о: ОтказИИФото, продолжаемая: Bool) {
        guard !закрыто else { return }
        опрос?.cancel()
        идёт = false
        изменить(id) { р in
            р.состояние = .отказ
            р.отказ = о
            р.продолжаемая = продолжаемая
        }
        сдвиг += 1
        ОткликСайта.предупреждение()
        UIAccessibility.post(notification: .announcement, argument: о.текст)
    }

    /// Ход не начался (нужен вход) — пустую реплику ожидания не оставляем.
    private func убратьЖдущую(_ id: UUID) {
        guard let место = реплики.firstIndex(where: { $0.id == id }), реплики[место].состояние == .ждём else { return }
        реплики.remove(at: место)
        if место > 0, реплики[место - 1].кто == .человек { реплики.remove(at: место - 1) }
        идёт = false
    }

    private func показатьВход() {
        guard !закрыто else { return }
        опрос?.cancel()
        запуск?.cancel()
        идёт = false
        if let ждущая = реплики.last(where: { $0.состояние == .ждём }) { убратьЖдущую(ждущая.id) }
        перейти(.вход)
    }

    /// Вошли из окна: сведения гостя больше не годятся; диалог — того, кто вошёл.
    func послеВхода() {
        поколение = СессияПриложения.shared.поколение
        ГотовностьИИФото.shared.устарели()
        Task { @MainActor in
            await ГотовностьИИФото.shared.проверить()
            await СвойИИМодель.shared.загрузитьЛениво()
        }
        диалог = ИИФотоПодачи.shared.диалог(подача)
        перейти(.чат)
    }

    /// «Повторить»: тот же ход ещё раз (ИИ занят, сеть, сбой) — в той же реплике.
    func повторить(_ id: UUID) {
        guard !идёт, let р = реплики.first(where: { $0.id == id }), var з = р.повтор else { return }
        з.диалог = диалог
        if з.режим == "edit" && фотоОтправлено && !з.фото.isEmpty {
            з.фото = ""
            з.ссылкаФото = ""
        }
        if з.режим == "edit" && !фотоОтправлено && з.фото.isEmpty && з.основа.isEmpty {
            з.фото = адресФото
            з.ссылкаФото = адресФото.isEmpty ? "" : ссылкаФото
        }
        if з.режим == "edit" && з.фото.isEmpty && з.основа.isEmpty {
            /* Ни фото, ни основы — сервер выбрал бы основу сам: основа явно, как в отправить. */
            guard let своя = основаПравки else {
                выбратьФото = true
                return
            }
            з.основа = своя
        }
        изменить(id) { р in
            р.состояние = .ждём
            р.отказ = nil
            р.прогресс = 0
            р.повтор = з
        }
        запустить(з, ответ: id)
    }

    /// «Проверить ещё раз» после «долго» или обрыва связи: та же задача, ещё столько же.
    func продолжить(_ id: UUID) {
        guard !идёт, let р = реплики.first(where: { $0.id == id }), !р.задача.isEmpty else { return }
        изменить(id) { р in
            р.состояние = .ждём
            р.отказ = nil
            р.продолжаемая = false
        }
        опрашивать(id, задача: р.задача, предел: р.повтор?.предел ?? 90)
    }

    /**
     «Ещё вариант» / «Другая обложка»: новая картинка той же просьбы — regen с base_image этой картинки: сервер повторяет
     ход, который её дал (та же основа и просьба, вид — тот же, §2). Без image_id — основу выберет отправить.
     */
    func ещёВариант(_ id: UUID) {
        guard !идёт, let р = реплики.first(where: { $0.id == id }) else { return }
        режим = р.режим == "edit" ? .edit : .draft
        снятьОснову()
        отправить(текст: т(р.режим == "edit" ? "aim_again" : "aim_other_cover"), пресет: "regen", нужно: ["image"],
                  основаХода: р.картинкаID.isEmpty ? nil : р.картинкаID, доХода: р.до)
    }

    /// «Начать заново» после gone: лента чистая, следующий ход начнёт новый диалог.
    func начатьЗаново() {
        опрос?.cancel()
        запуск?.cancel()
        идёт = false
        диалог = ""
        фотоОтправлено = false
        снятьОснову()
        withAnimation(ДвижениеСайта.смена) { реплики = [] }
        сдвиг += 1
        if фото == nil && черновикДоступен { режим = .draft }
    }

    /// «Удалить диалог»: delete на сервере сразу; взятые в объявление фото остаются. потом — закрыть окно.
    func удалитьДиалог(потом: (() -> Void)? = nil) {
        let номер = диалог
        начатьЗаново()
        ИИФотоПодачи.shared.забытьДиалог(подача)
        Task { @MainActor [weak self] in
            var удалено = true
            if !номер.isEmpty { удалено = await ИИФотоAPI.удалить(номер) }
            self?.показатьВесть(ИИФотоText.т(удалено ? "aim_deleted" : "aim_delete_fail"))
        }
        потом?()
    }

    // MARK: - История

    /// Диалог есть (после «Продолжить» черновика или повторного открытия) — реплики с сервера, картинки — следом.
    private func восстановить() {
        let номер = диалог
        загружаемИсторию = true
        Task { @MainActor [weak self] in
            let ответ = await ИИФотоAPI.история(номер)
            guard let self, !self.закрыто, номер == self.диалог else { return }
            self.загружаемИсторию = false
            switch ответ {
            case .готово(let j):
                self.принятьИсторию(j)
            case .отказ(let о) where о.код == "gone":
                self.диалог = ""
                ИИФотоПодачи.shared.забытьДиалог(self.подача)
            case .нетСервера:
                ГотовностьИИФото.shared.отметитьНетСервера()
                self.перейти(.скоро)
            case .нуженВход:
                self.перейти(.вход)
            case .отказ, .сеть, .сбой:
                /* Ленты нет, а диалог остаётся: следующий ход продолжит его. */
                break
            }
        }
    }

    private func принятьИсторию(_ j: [String: Any]) {
        typealias A = МоиОбъявленияAPI
        let взятые = Set(((j["accepted"] as? [Any]) ?? []).map { A.строка($0) })
        var новые: [РепликаИИФото] = []
        var загрузки: [(id: UUID, адрес: URL, фотоЧеловека: Bool)] = []
        for элемент in (j["turns"] as? [Any]) ?? [] {
            guard let ход = элемент as? [String: Any] else { continue }
            if A.строка(ход["role"]) == "user" {
                var р = РепликаИИФото(кто: .человек)
                р.режим = A.строка(ход["mode"]) == "edit" ? "edit" : "draft"
                р.текст = A.строка(ход["text"]).trimmingCharacters(in: .whitespacesAndNewlines)
                if р.текст.isEmpty { р.текст = т(р.режим == "edit" ? "aim_default_edit" : "aim_default_draft") }
                if let адрес = КартинкиИИФото.адрес(A.строка(ход["photo"])) {
                    р.новоеФото = р.режим == "edit"
                    загрузки.append((р.id, адрес, true))
                    /* Фото вещи уже в диалоге; своё новое фото (плитка правки) всё равно уйдёт следующим ходом. */
                    if адресФото.isEmpty { фотоОтправлено = true }
                }
                новые.append(р)
            } else {
                var р = РепликаИИФото(кто: .ии)
                р.режим = новые.last?.режим ?? "draft"
                р.текст = ХодИИФото.текст(A.строка(ход["caption"]).trimmingCharacters(in: .whitespacesAndNewlines),
                                          предел: 300)
                р.картинкаID = A.строка(ход["image_id"])
                let вид = A.строка(ход["image_kind"])
                if !р.картинкаID.isEmpty { р.вид = вид == "edited" ? "edited" : "illustration" }
                р.взята = взятые.contains(р.картинкаID)
                if let адрес = КартинкиИИФото.адрес(A.строка(ход["image"])) {
                    загрузки.append((р.id, адрес, false))
                } else if !р.картинкаID.isEmpty {
                    р.удалена = true
                }
                новые.append(р)
            }
        }
        if let черновик = ЧерновикИИФото(j["draft"]), let место = новые.lastIndex(where: { $0.кто == .ии }) {
            новые[место].черновик = черновик
        }
        реплики = новые
        сдвиг += 1
        if новые.contains(where: { $0.режим == "edit" }) && фото == nil, case .черновик = вход {
            режим = черновикДоступен ? .draft : .edit
        }
        for загрузка in загрузки {
            Task { @MainActor [weak self] in
                let данные = await КартинкиИИФото.скачать(загрузка.адрес)
                guard let self, !self.закрыто, let данные, let картинка = UIImage(data: данные) else { return }
                self.изменить(загрузка.id) { р in
                    if загрузка.фотоЧеловека { р.фото = картинка } else { р.картинка = картинка }
                }
                if !загрузка.фотоЧеловека { self.собратьПостер(загрузка.id) }
            }
        }
    }

    // MARK: - В объявление

    /// Иллюстраций уже в объявлении ≥ max_illustrations — новую взять нельзя.
    func иллюстрацияНеВлезет(_ вид: String, кроме: UUID? = nil) -> Bool {
        guard вид == "illustration" else { return false }
        return подача.иллюстрацийИИ(кроме: кроме) >= (сведения?.иллюстрацийМакс ?? 1)
    }

    /// Плитка, с которой открыли правку, ещё в подаче.
    var плиткаПравки: UUID? {
        guard case .правка(let id) = вход, подача.плитки.contains(where: { $0.id == id }) else { return nil }
        return id
    }

    /// «Взять в объявление», «Заменить фото», «Взять постер».
    func взять(_ id: UUID, постер: Bool = false, как: КакВзять) {
        Task { @MainActor [weak self] in _ = await self?.взятьСразу(id, постер: постер, как: как) }
    }

    /**
     accept: картинка (или постер) с вшитой пометкой → тот же путь, что у всех фото подачи (1280, знак Kliko, миниатюра)
     → плитка с кольцом загрузки сразу → ответ сервера: адрес, как у upload_photo. Отказ — плитка уходит (заменяемая
     остаётся прежней), запрет — то же окно, что у загрузки фото.
     */
    @discardableResult
    func взятьСразу(_ id: UUID, постер: Bool, как: КакВзять) async -> Bool {
        guard !берём, let р = реплики.first(where: { $0.id == id }), !р.картинкаID.isEmpty,
              let картинка = постер ? р.постер : р.картинка else { return false }
        let вид = постер ? "illustration" : (р.вид.isEmpty ? "illustration" : р.вид)
        var заменяемая: UUID? = nil
        if case .заменить(let плитка) = как { заменяемая = плитка }
        if иллюстрацияНеВлезет(вид, кроме: заменяемая) {
            показатьВесть(String(format: т("aim_max_ill"), сведения?.иллюстрацийМакс ?? 1))
            return false
        }
        if заменяемая == nil && подача.местоФото <= 0 {
            показатьВесть(String(format: ПодачаText.т("photo_cap_full"), подача.лимитФото))
            return false
        }
        берём = true
        defer { берём = false }
        let надпись = ПометкаИИФото.текст(вид)
        let готовое = await Task.detached(priority: .userInitiated) { () -> ГотовоеФото? in
            КартинкиИИФото.дляПодачи(картинка, надпись: надпись)
        }.value
        guard let готовое else {
            показатьВесть(т("aim_err_fail"))
            return false
        }
        let превью = UIImage(data: готовое.миниатюра) ?? UIImage(data: готовое.картинка)
        /* Плитка с кольцом — сразу, как у загрузки фото; на сервер — тем же телом, что upload_photo, плюс image_id. */
        let плиткаID: UUID
        if let заменяемая, let место = подача.плитки.firstIndex(where: { $0.id == заменяемая }) {
            плиткаID = заменяемая
            подача.плитки[место].грузится = true
            подача.плитки[место].этап = 1
        } else {
            guard let новая = подача.поставитьПлитки(1).first,
                  let место = подача.плитки.firstIndex(where: { $0.id == новая }) else { return false }
            плиткаID = новая
            подача.плитки[место].превью = превью
            подача.плитки[место].этап = 1
            if как == .обложка && место > 0 {
                let плитка = подача.плитки.remove(at: место)
                подача.плитки.insert(плитка, at: 0)
                подача.главнаяВручную = новая
            }
        }
        typealias A = МоиОбъявленияAPI
        var ответ = await ИИФотоAPI.взять(картинка: р.картинкаID, фото: ОбработкаФото.dataURL(готовое.картинка),
                                          миниатюра: Self.миниатюраДляВзятия(готовое), постер: постер)
        var превьюПлитки = превью
        var итоговыйВид = вид
        /*
         Пометка сервера (ai) — главная: вшитая обязана с ней совпадать. Разошлись (вид ответа ИИ не пришёл или другой) —
         вшить пометку сервера и взять ещё раз: повторный accept той же картинки — новый файл (§6 договора).
         */
        if case .готово(let j) = ответ, !постер, ["illustration", "edited"].contains(A.строка(j["ai"])),
           A.строка(j["ai"]) != вид {
            let серверный = A.строка(j["ai"])
            let другая = ПометкаИИФото.текст(серверный)
            let заново = await Task.detached(priority: .userInitiated) { () -> ГотовоеФото? in
                КартинкиИИФото.дляПодачи(картинка, надпись: другая)
            }.value
            if let заново {
                ответ = await ИИФотоAPI.взять(картинка: р.картинкаID, фото: ОбработкаФото.dataURL(заново.картинка),
                                              миниатюра: Self.миниатюраДляВзятия(заново), постер: false)
                превьюПлитки = UIImage(data: заново.миниатюра) ?? UIImage(data: заново.картинка) ?? превью
                итоговыйВид = серверный
                изменить(id) { $0.вид = серверный }
            }
        }
        if case .готово(let j) = ответ, !A.строка(j["url"]).isEmpty,
           let место = подача.плитки.firstIndex(where: { $0.id == плиткаID }) {
            let адрес = A.строка(j["url"])
            var плитка = подача.плитки[место]
            плитка.url = адрес
            плитка.превью = превьюПлитки
            плитка.картинка = nil
            плитка.миниатюра = nil
            плитка.ошибка = nil
            плитка.грузится = false
            плитка.этап = 0
            подача.плитки[место] = плитка
            let пометка = A.строка(j["ai"])
            ИИФотоПодачи.shared.отметитьФото(подача, адрес: адрес,
                                             вид: ["illustration", "edited"].contains(пометка) ? пометка : итоговыйВид)
            изменить(id) { р in
                if постер { р.постерВзят = true } else { р.взята = true }
            }
            ОткликСайта.успех()
            показатьВесть(т(заменяемая == nil ? "aim_taken" : "aim_replaced"))
            return true
        }
        /* Не вышло: новая плитка уходит, заменяемая остаётся прежней. */
        if let место = подача.плитки.firstIndex(where: { $0.id == плиткаID }) {
            if заменяемая == nil {
                подача.плитки.remove(at: место)
            } else {
                подача.плитки[место].грузится = false
                подача.плитки[место].этап = 0
            }
        }
        ОткликСайта.предупреждение()
        switch ответ {
        case .отказ(let о):
            if let з = о.запрет { запрет = з } else { показатьВесть(о.текст) }
        case .нуженВход:
            показатьВход()
        case .нетСервера:
            ГотовностьИИФото.shared.отметитьНетСервера()
            перейти(.скоро)
        case .сеть:
            показатьВесть(т("aim_err_net"))
        case .готово, .сбой:
            показатьВесть(т("aim_err_fail"))
        }
        return false
    }

    /// Миниатюра для accept — data URL, как у upload_photo; нет миниатюры — пусто.
    private static func миниатюраДляВзятия(_ готовое: ГотовоеФото) -> String {
        готовое.миниатюра.isEmpty ? "" : ОбработкаФото.dataURL(готовое.миниатюра)
    }

    /**
     «Создать объявление»: accept_draft → поля в форму (как «Распознать», предложениями), черновик ИИ запоминается для
     галочки «Проверил характеристики»; обложка-иллюстрация этого черновика, если её ещё не брали, — первой плиткой.
     Окно закрывается, поля ложатся после него (вопросы подачи не прячутся за окном).
     */
    func создатьОбъявление(_ id: UUID) {
        guard !берём, !диалог.isEmpty else { return }
        берём = true
        let номер = диалог
        Task { @MainActor [weak self] in
            let ответ = await ИИФотоAPI.взятьЧерновик(номер)
            guard let self, !self.закрыто else { return }
            self.берём = false
            switch ответ {
            case .готово(let j):
                let поля = (j["fields"] as? [String: Any]) ?? [:]
                let неуверенные = ((j["unsure"] as? [Any]) ?? []).map { МоиОбъявленияAPI.строка($0) }.filter { !$0.isEmpty }
                ИИФотоПодачи.shared.принятьЧерновик(self.подача, id: МоиОбъявленияAPI.строка(j["draft_id"]),
                                                   неуверенные: неуверенные)
                if let обложка = self.обложкаДляОбъявления(id) {
                    _ = await self.взятьСразу(обложка, постер: false, как: .обложка)
                }
                /* Черновик уже принят сервером: поля ложатся, даже если окно успели закрыть. */
                ОткликСайта.успех()
                let подача = self.подача
                if !self.закрыто { self.закрытьОкно?() }
                Task { @MainActor in
                    try? await Task.sleep(nanoseconds: 450_000_000)
                    подача.применитьЧерновикИИ(поля)
                    подача.показать(ИИФотоText.т("aim_applied"))
                }
            case .отказ(let о):
                if о.код == "gone" {
                    self.диалог = ""
                    ИИФотоПодачи.shared.забытьДиалог(self.подача)
                }
                self.показатьВесть(о.текст)
            case .нуженВход:
                self.показатьВход()
            case .нетСервера:
                ГотовностьИИФото.shared.отметитьНетСервера()
                self.перейти(.скоро)
            case .сеть:
                self.показатьВесть(self.т("aim_err_net"))
            case .сбой:
                self.показатьВесть(self.т("aim_err_fail"))
            }
        }
    }

    /// Обложка к «Создать объявление»: иллюстрация этой (или последней) реплики, ещё не взятая, если влезает.
    private func обложкаДляОбъявления(_ id: UUID) -> UUID? {
        let кандидат = реплики.first(where: { $0.id == id && $0.картинка != nil && $0.вид == "illustration" })
            ?? реплики.last(where: { $0.картинка != nil && $0.вид == "illustration" })
        guard let к = кандидат, !к.взята, !иллюстрацияНеВлезет("illustration"), подача.местоФото > 0 else { return nil }
        return к.id
    }
}

// MARK: - Реплика

/// Реплика ленты: человек (текст, его фото) или ИИ (ожидание, черновик, картинка, отказ).
struct РепликаИИФото: Identifiable, Equatable {
    enum Кто: Equatable {
        case человек, ии
    }

    enum Состояние: Equatable {
        case готово, ждём, отказ
    }

    var id = UUID()
    var кто: Кто
    var режим = "draft"
    /// Текст человека или подпись ИИ (caption).
    var текст = ""
    /// Фото вещи в реплике человека.
    var фото: UIImage? = nil
    /// Человек прислал в этом ходе новое фото вещи (photo), а не взял основой картинку диалога.
    var новоеФото = false
    var состояние: Состояние = .готово
    var прогресс = 0
    var вОчереди = false
    var этап = ""
    var нуженРисунок = true
    var картинка: UIImage? = nil
    var картинкаID = ""
    /// illustration | edited
    var вид = ""
    /// «До» для шторки правки.
    var до: UIImage? = nil
    var черновик: ЧерновикИИФото? = nil
    var изменено: [String] = []
    var заметка = ""
    var своимИИ = false
    var отказ: ОтказИИФото? = nil
    /// Отказ посреди опроса: «Проверить ещё раз» продолжает ту же задачу.
    var продолжаемая = false
    var повтор: ЗапросХодаИИФото? = nil
    var задача = ""
    var взята = false
    var постер: UIImage? = nil
    var постерВзят = false
    /// Картинка истекла на сервере (history без адреса).
    var удалена = false

    init(кто: Кто) {
        self.кто = кто
    }
}

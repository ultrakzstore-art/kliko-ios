import SwiftUI

/**
 ПЯТЫЙ ЭКРАН ПОДАЧИ — «АДРЕС И ДОПОЛНИТЕЛЬНО» (сайт 14.10.2026: «пять шагов и одна проверка для всех разделов»).

 Адрес (часы и место, ШагАдрес) и под ним «Дополнительно» (рассрочка, доставка, знаки доверия — ШагДополнительно) одним
 экраном; где «Дополнительного» нет — только адрес. Отдельного экрана-сводки перед подтверждением нет: «Опубликовать»
 открывает окно «Проверьте перед публикацией» (ОкноПроверкиПодачи) — единственная проверка. В правке окна нет — здесь
 же «Гарант-сделка», которая раньше жила на шаге «Проверка».
 */
struct ШагАдресИДополнительно: View {
    @ObservedObject var модель: ПодачаМодель
    let фокус: FocusState<String?>.Binding
    let открытьАдрес: (String) -> Void

    init(модель: ПодачаМодель, фокус: FocusState<String?>.Binding, открытьАдрес: @escaping (String) -> Void) {
        self.модель = модель
        self.фокус = фокус
        self.открытьАдрес = открытьАдрес
    }

    var body: some View {
        VStack(alignment: .leading, spacing: 14) {
            ШагАдрес(модель: модель, фокус: фокус)
            if модель.виден(.дополнительно) {
                ШагДополнительно(модель: модель, фокус: фокус, открытьАдрес: открытьАдрес)
            }
            if модель.правка && модель.запретГаранта != "hide" {
                КарточкаПодачи(ПодачаText.т("rv_deal")) {
                    БлокГаранта(модель: модель)
                }
            }
        }
    }
}

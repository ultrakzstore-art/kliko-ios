/// Итог подбора по названию.
struct ПодборРаздела: Equatable {
    /// Разделы по убыванию: первый — лучший; ни один не предок другого.
    var разделы: [String] = []
    /// Первый заметно впереди — можно подставить сам.
    var уверенно = false
    /// Марка авто в написании справочника и модель, если совпала.
    var марка = ""
    var модель = ""
}

enum ПодборПоНазванию {

    /// Слово синонима: основа (совпадает началом слова), точное слово («!») или фраза («_» — пробел).
    private struct КлючСинонима {
        let текст: String
        let точно: Bool
        let фраза: Bool
    }

    /// Строка словаря: цели для продажи / аренды / посуточно, вес, слова и «кроме» (слово есть — цели запрещены).
    private struct СтрокаСинонимов {
        let цели: [[String]]
        let вес: Double
        let ключи: [КлючСинонима]
        let кроме: [String]
    }

    private struct МодельСборки {
        let имя: String
        let фраза: String
        let кузов: [String]
    }

    private struct Индекс {
        var ключи: [String] = []
        var родитель: [Int] = []
        var номер: [String: Int] = [:]
        /// Основы слов имени раздела на всех языках.
        var основы: [Set<String>] = []
        /// Имена по языкам — для «все слова имени совпали».
        var именаОснов: [[[String]]] = []
        /// В скольких разделах встречается основа.
        var частота: [String: Int] = [:]
        var бренды: [String: [String]] = [:]
        var марки: [String: String] = [:]
        var модели: [String: [МодельСборки]] = [:]
        var запчасти: [String] = []
        var синонимы: [СтрокаСинонимов] = []
        var маркиРус: [(String, String)] = []
        var моделиРус: [(String, String)] = []

        func предки(_ н: Int) -> [Int] {
            var путь: [Int] = []
            var р = н >= 0 && н < родитель.count ? родитель[н] : -1
            var шаги = 0
            while р >= 0 && шаги < 25 {
                путь.append(р)
                р = родитель[р]
                шаги += 1
            }
            return путь
        }
    }

    /// Собирается один раз при первом подборе (файлы сборки — до 200 КБ).
    private static let индекс: Индекс = собрать()

    // MARK: Подбор

    /// Разделы по названию. «есть» — раздел есть в справочниках открытой подачи (свежее дерево сайта).
    static func подобрать(_ название: String, есть: (String) -> Bool) -> ПодборРаздела {
        let и = индекс
        var итог = ПодборРаздела()
        guard !и.ключи.isEmpty else { return итог }
        let сырые = токены(название)
        guard !сырые.isEmpty else { return итог }
        let слова = значимые(сырые)
        let основыСлов = слова.map { основа($0) }
        let текст = " " + сырые.joined(separator: " ") + " "
        let аренда = сырые.contains { сдача.contains($0) || $0.hasPrefix("аренд") }
        let посуточно = сырые.contains { сутки.contains($0) || $0.hasPrefix("посуточ") }
        let вариант = посуточно ? 2 : (аренда ? 1 : 0)

        /* Лучшие очки пары «раздел + слово»: одно слово не считается дважды за один раздел. */
        var лучшие: [String: Double] = [:]
        func добавить(_ н: Int, _ очки: Double, _ слово: String) {
            let к = String(н) + "|" + слово
            if очки > (лучшие[к] ?? 0) { лучшие[к] = очки }
        }

        for с in основыСлов {
            for н in 0..<и.основы.count {
                var м = 0.0
                for о in и.основы[н] where совпадает(с, о) {
                    м = max(м, 3.0 / Double(max(1, и.частота[о] ?? 1)).squareRoot())
                }
                if м > 0 { добавить(н, м, с) }
            }
        }
        for н in 0..<и.именаОснов.count {
            for имя in и.именаОснов[н] where имя.allSatisfy({ о in основыСлов.contains { совпадает($0, о) } }) {
                добавить(н, 1.0, "#имя")
                break
            }
        }

        var запрещено = Set<String>()
        var отСинонимов = Set<Int>()
        for строка in и.синонимы {
            if строка.кроме.contains(where: { к in сырые.contains { $0.hasPrefix(к) } }) {
                for цели in строка.цели { запрещено.formUnion(цели) }
                continue
            }
            guard строка.вес > 0 else { continue }
            var попало = Set<String>()
            for ключ in строка.ключи {
                if ключ.фраза {
                    if текст.contains(" " + ключ.текст) { попало.insert("#" + ключ.текст) }
                } else if let т = (сырые + слова).first(where: { ключ.точно ? $0 == ключ.текст : $0.hasPrefix(ключ.текст) }) {
                    попало.insert(т)
                }
            }
            guard !попало.isEmpty else { continue }
            let цели = строка.цели[min(вариант, строка.цели.count - 1)]
            for цель in цели {
                guard let н = и.номер[цель] else { continue }
                for слово in попало { добавить(н, строка.вес, слово) }
                отСинонимов.insert(н)
            }
        }

        for (номер, т) in сырые.enumerated() {
            var варианты = [т]
            if номер + 1 < сырые.count { варианты.append(т + сырые[номер + 1]) }
            for в in варианты {
                guard let разделы = и.бренды[в] else { continue }
                let очки = 1.2 / Double(разделы.count).squareRoot()
                for р in разделы {
                    if let н = и.номер[р] { добавить(н, очки, "#б" + в) }
                }
            }
        }

        /* Марка и модель авто: справочник (seed-auto) и русские написания. */
        var марка = ""
        for (номер, т) in сырые.enumerated() {
            if let м = и.марки[т] {
                марка = м
            } else if номер + 1 < сырые.count, let м = и.марки[т + сырые[номер + 1]] {
                марка = м
            } else if let м = и.маркиРус.first(where: { $0.0.contains(" ") ? текст.contains(" " + $0.0 + " ") : $0.0 == т })?.1 {
                марка = м
            }
            if !марка.isEmpty { break }
        }
        var модель = ""
        var кузов = "cars"
        if !марка.isEmpty {
            let модели = и.модели[марка] ?? []
            if let рус = и.моделиРус.first(where: { текст.contains(" " + $0.0 + " ") })?.1,
               модели.contains(where: { $0.имя == рус }) {
                модель = рус
            } else {
                var длина = 0
                for м in модели where м.фраза.count > длина && текст.contains(" " + м.фраза + " ") {
                    модель = м.имя
                    длина = м.фраза.count
                }
            }
            if let м = модели.first(where: { $0.имя == модель }), let первый = м.кузов.first, !первый.isEmpty {
                кузов = первый
            }
        }
        let запчастей = основыСлов.filter { с in и.запчасти.contains { совпадает(с, $0) } }.count
        if запчастей > 0, let н = и.номер["auto-parts-items"] {
            добавить(н, 1.5 * Double(min(запчастей, 2)), "#запчасть")
        }
        if !марка.isEmpty, let н = и.номер[запчастей > 0 ? "auto-parts-items" : кузов] ?? и.номер["cars"] {
            добавить(н, модель.isEmpty ? 3.0 : 4.5, "#марка")
        }

        /* Услуги без слов-услуг — в треть веса с небольшим: «iPhone 13» — смартфон, а не «Ремонт iPhone». */
        let услуги = и.номер["services"] ?? -1
        let контекстУслуг = отСинонимов.contains { $0 == услуги || и.предки($0).contains(услуги) }
        var свои: [Int: Double] = [:]
        for (к, очки) in лучшие {
            guard let н = Int(к.split(separator: "|", maxSplits: 1).first ?? "") else { continue }
            var о = очки
            if !контекстУслуг && услуги >= 0 && и.предки(н).contains(услуги) { о *= 0.4 }
            свои[н, default: 0] += о
        }
        var всего: [Int: Double] = [:]
        for (н, о) in свои {
            всего[н] = о + и.предки(н).reduce(0.0) { $0 + (свои[$1] ?? 0) }
        }
        let порядок = всего.keys
            .filter { есть(и.ключи[$0]) && !запрещено.contains(и.ключи[$0]) }
            .sorted { а, б in
                let оа = всего[а] ?? 0
                let об = всего[б] ?? 0
                if оа != об { return оа > об }
                let га = и.предки(а).count
                let гб = и.предки(б).count
                if га != гб { return га > гб }
                return а < б
            }
        var выбор: [Int] = []
        for н in порядок {
            if выбор.contains(where: { и.предки($0).contains(н) }) { continue }
            let порог = 0.6 * (всего[н] ?? 0)
            if порядок.contains(where: { $0 != н && и.предки($0).contains(н) && (всего[$0] ?? 0) >= порог }) { continue }
            выбор.append(н)
        }
        итог.разделы = выбор.prefix(3).map { и.ключи[$0] }
        if let первый = выбор.first {
            let о1 = всего[первый] ?? 0
            let о2 = выбор.count > 1 ? (всего[выбор[1]] ?? 0) : 0
            итог.уверенно = о1 >= 2.5 && о2 <= 0.75 * о1
        }
        итог.марка = марка
        итог.модель = модель
        return итог
    }

    // MARK: Слова

    /// Нижний регистр, ё → е; всё, кроме букв и цифр, — пробел.
    static func токены(_ текст: String) -> [String] {
        let строчные = текст.lowercased().replacingOccurrences(of: "ё", with: "е")
        var слова: [String] = []
        var текущее = ""
        for с in строчные {
            if с.isLetter || с.isNumber {
                текущее.append(с)
            } else if !текущее.isEmpty {
                слова.append(текущее)
                текущее = ""
            }
        }
        if !текущее.isEmpty { слова.append(текущее) }
        return слова
    }

    /// Значимые слова: только буквы (цифры модели отброшены), от 3 букв, без «продам», «срочно», «новый»…
    private static func значимые(_ токены: [String]) -> [String] {
        токены.compactMap { т -> String? in
            let буквы = String(т.filter { $0.isLetter })
            return буквы.count >= 3 && !стоп.contains(буквы) ? буквы : nil
        }
    }

    private static let окончания: [String] = "иями ями ами ией иях ях ах ов ев ей ий ый ой ая яя ое ее ые ие ую юю ом ем ам им ым ых их es а я о е ы и у ю ь й s"
        .split(separator: " ").map(String.init)

    /// Основа: без первого подходящего окончания, если остаётся от 3 букв.
    static func основа(_ слово: String) -> String {
        for о in окончания where слово.hasSuffix(о) && слово.count - о.count >= 3 {
            return String(слово.dropLast(о.count))
        }
        return слово
    }

    /// Основы равны или длинная (от 7 букв) — начало другой.
    private static func совпадает(_ а: String, _ б: String) -> Bool {
        if а == б { return true }
        let (к, д) = а.count <= б.count ? (а, б) : (б, а)
        return к.count >= 7 && д.hasPrefix(к)
    }


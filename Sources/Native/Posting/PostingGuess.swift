                    основы.formUnion(слова)
                }
            }
            и.основы.append(основы)
            и.именаОснов.append(поЯзыкам)
            for о in основы { и.частота[о, default: 0] += 1 }
        }
        if let refs = СтартовыеДанные.объект("seed-cab-refs"), let бренды = refs["BRAND_LIST"] as? [String: Any] {
            for (раздел, список) in бренды {
                for б in (список as? [String]) ?? [] {
                    let к = токены(б).joined()
                    if !к.isEmpty { и.бренды[к, default: []].append(раздел) }
                }
            }
        }
        if let авто = СтартовыеДанные.объект("seed-auto") {
            for группа in (авто["groups"] as? [[String: Any]]) ?? [] {

    private static func пары(_ текст: String) -> [(String, String)] {
        текст.split(whereSeparator: { $0 == " " || $0 == "\n" }).compactMap { кусок -> (String, String)? in
            let части = кусок.split(separator: "=", maxSplits: 1).map(String.init)
            guard части.count == 2 else { return nil }
            return (части[0].replacingOccurrences(of: "_", with: " "), части[1].replacingOccurrences(of: "_", with: " "))
        }
    }

    private static func синонимы() -> [СтрокаСинонимов] {
        словарь.split(separator: "\n").compactMap { строка -> СтрокаСинонимов? in
            let части = строка.split(separator: ":", maxSplits: 1).map { $0.trimmingCharacters(in: .whitespaces) }
            guard части.count == 2 else { return nil }
            var голова = части[0]
            var вес = 3.0
            if let звезда = голова.firstIndex(of: "*") {
                вес = Double(голова[голова.index(after: звезда)...]) ?? 3.0
                голова = String(голова[..<звезда])
            }
            let цели = голова.split(separator: "/").map { $0.split(separator: ",").map(String.init) }
            var ключи: [КлючСинонима] = []
            var кроме: [String] = []
            for слово in части[1].split(separator: " ").map(String.init) {
                if слово.hasPrefix("-") {
                    кроме.append(String(слово.dropFirst()))
                } else {
                    let точно = слово.hasSuffix("!")
                    let чистое = точно ? String(слово.dropLast()) : слово
                    ключи.append(КлючСинонима(текст: чистое.replacingOccurrences(of: "_", with: " "), точно: точно,
                                              фраза: чистое.contains("_")))
                }
            }
            guard !цели.isEmpty else { return nil }
            return СтрокаСинонимов(цели: цели, вес: вес, ключи: ключи, кроме: кроме)
        }
    }

    private static func собрать() -> Индекс {
        var и = Индекс()
        guard let всё = СтартовыеДанные.объект("seed-cats"), let узлы = всё["nodes"] as? [[Any]] else { return и }
        let имена = (всё["names"] as? [String: [String]]) ?? [:]

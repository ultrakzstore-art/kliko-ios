extension ПодачаМодель {

    /// Раздел подставлен подбором по названию и человек его не менял — строка «проверьте».
    var разделПоНазванию: Bool {
        !разделПодбора.isEmpty && форма.раздел == разделПодбора
    }

    /// Название поменялось: подбор через 0,4 с (пока человек печатает — не дёргаем).
    func запланироватьПодборРаздела() {
        подборЗадача?.cancel()
        guard !правка else { return }
        подборЗадача = Task { @MainActor [weak self] in
            try? await Task.sleep(nanoseconds: 400_000_000)
            guard !Task.isCancelled, let модель = self else { return }
            модель.подобратьРазделПоНазванию()
        }
    }

    /**
     Подбор по названию. Раздел пуст или его поставил прошлый подбор — уверенный вариант подставляется сам (кроме
     транспорта и недвижимости: у них мастера — им чип), неуверенно — 2–3 чипа. Раздел выбрал человек или Kliko AI — не
     трогаем: только уточнения внутри него чипами. true — раздел подставлен.
     */
    @discardableResult
    func подобратьРазделПоНазванию() -> Bool {
        guard !правка else { return false }
        let название = форма.название.trimmingCharacters(in: .whitespacesAndNewlines)
        guard название.count >= 3, режим != .авто || форма.раздел.isEmpty else {
            if !вариантыРаздела.isEmpty { вариантыРаздела = [] }
            return false
        }
        let справ = справочники
        /* Справочники ещё не пришли — подбирать не во что (раздел не из дерева форма не примет). */
        guard !справ.пусто else { return false }
        let итог = ПодборПоНазванию.подобрать(название, есть: { справ.разделы[$0] != nil })
        подборМарка = итог.марка
        подборМодель = итог.модель
        let текущий = форма.раздел
        if !текущий.isEmpty && текущий != разделПодбора {
            let глубже = Array(итог.разделы.filter { $0 != текущий && справ.внутри($0, [текущий]) }.prefix(3))
            if вариантыРаздела != глубже { вариантыРаздела = глубже }
            return false
        }
        guard let первый = итог.разделы.first else {
            if !вариантыРаздела.isEmpty { вариантыРаздела = [] }
            return false
        }
        let своимМастером = справ.внутри(первый, ["realty"])
            || (справ.внутри(первый, ["transport"]) && !справ.внутри(первый, ["auto-parts"]))
        if итог.уверенно && !своимМастером {
            if текущий != первый {
                выбратьРаздел(первый)
                разделПодбора = первый
            }
            if !вариантыРаздела.isEmpty { вариантыРаздела = [] }
            if статусИИ == т("guess_ai_off") { статусИИ = nil }
            return true
        }
        let варианты = Array(итог.разделы.prefix(итог.уверенно ? 1 : 3))
        if вариантыРаздела != варианты { вариантыРаздела = варианты }
        return false
    }

    /// Чип «Возможно: …»: выбор человека. Транспорт — с маркой и моделью из названия и мастером, недвижимость — мастером.
    func принятьВариантРаздела(_ ключ: String) {
        вариантыРаздела = []
        разделПодбора = ""
        let транспорт = справочники.внутри(ключ, ["transport"]) && !справочники.внутри(ключ, ["auto-parts"])
        if транспорт && !подборМарка.isEmpty && форма.бренд.trimmingCharacters(in: .whitespaces).isEmpty {
            var ф = форма
            ф.бренд = подборМарка
            ф.модель = подборМодель
            форма = ф
        }
        ОткликСайта.выбор()
        выбратьРазделБыстро(ключ)
    }

    /// Kliko AI не ответил, выключен или кончилась квота: без «ошибки» — раздел по названию; нет названия — просьба.
    func безИИ() {
        if подобратьРазделПоНазванию() || разделПоНазванию {
            статусИИ = т("guess_note")
        } else if форма.раздел.isEmpty {
            статусИИ = т("guess_ai_off")
        } else {
            статусИИ = nil
        }
    }

    /// Kliko AI ответил разделом: подбор больше не нужен.
    func сброситьПодборРаздела() {
        подборЗадача?.cancel()
        разделПодбора = ""
        вариантыРаздела = []
    }

    /// Подпись чипа: одинаковые имена («Верхняя одежда» у мужской и женской) — с родителем.
    func подписьВарианта(_ ключ: String) -> String {
        let имя = справочники.имя(ключ)
        let тёзки = вариантыРаздела.filter { $0 != ключ && справочники.имя($0) == имя }
        guard !тёзки.isEmpty, let родитель = справочники.разделы[ключ]?.родитель else { return имя.isEmpty ? ключ : имя }
        return справочники.имя(родитель) + " · " + имя
    }
}

/// Под строкой раздела: «Раздел подобран по названию — проверьте» и чипы «Возможно: …».
struct ПодсказкаРазделаПодачи: View {
    @ObservedObject var модель: ПодачаМодель


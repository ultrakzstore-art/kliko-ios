                ЗаметкаПодачи(ПодачаText.т("guess_note"), тон: .внимание, значок: "text.magnifyingglass")
            }
            if !модель.вариантыРаздела.isEmpty {
                Text(ПодачаText.т("guess_maybe"))
                    .font(.footnote.weight(.semibold))
                    .foregroundStyle(Theme.текстВторой)
                ScrollView(.horizontal, showsIndicators: false) {

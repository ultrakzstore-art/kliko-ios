import SwiftUI
import UIKit

/**
 3D-ОБЗОР В ПОДАЧЕ — СОСТОЯНИЕ ОКНА СЪЁМКИ (одно на открытое окно, держит его ЭкранСъёмкиОбзора3D).

 Шаги окна: съёмка (камера и подсказка ракурса) → проверка (вырезка снятого кадра с галочкой, «Переснять») → снова
 съёмка следующего ракурса, пока не снято все 5 → обзор (поворот пальцем, «Собрать 3D», «Готово»). Сборка, её ход и
 итог живут в ХранилищеОбзора3DПодачи — окно только показывает их: закрыли окно — сборка идёт, карточка в шаге «Фото»
 показывает проценты. Перед первой сборкой — согласие: кто обработает ракурсы (ai из info), сколько хранятся, не для
 обучения (App Review 5.1.2(i)); общая формулировка (ai пуст) — согласие только до закрытия окна.
 */
@MainActor
final class МодельСъёмкиОбзора3D: ObservableObject {
    enum Шаг: Hashable {
        case съёмка, проверка, обзор
    }

    let подача: ПодачаМодель
    let вид: ВидОбзора3DПодачи
    @Published private(set) var шаг: Шаг
    @Published private(set) var ракурс: РакурсОбзора3DПодачи
    /// Снимок вырезается и проверяется.
    @Published private(set) var готовим = false
    /// Кадр на проверке: вырезка (или кадр целиком, если вырезать не вышло).
    @Published private(set) var снимок: UIImage? = nil
    @Published private(set) var вырезан = false
    @Published private(set) var людиВКадре = false
    /// Миниатюры снятых ракурсов (из файлов): номер ракурса → картинка.
    @Published private(set) var кадры: [Int: UIImage] = [:]
    @Published private(set) var постер: UIImage? = nil
    /// Модель качается для показа.
    @Published private(set) var открываем = false
    @Published private(set) var весть: String? = nil
    /// Карточка согласия перед первой сборкой.
    @Published var согласие = false
    /// «Убрать 3D-обзор?» — вопрос.
    @Published var вопросУбрать = false

    private var готовый: КартинкиОбзора3DПодачи.Готовый? = nil
    private var подготовка: Task<Void, Never>? = nil
    private var загрузкаКадров: Task<Void, Never>? = nil
    private var загрузкаПостера: Task<Void, Never>? = nil
    private var открытие: Task<Void, Never>? = nil
    /// Пересъёмка одного ракурса из обзора: после «Дальше» — снова обзор.
    private var одинРакурс = false
    private var согласиеВОкне = false
    private var закрыто = false
    private var номерВести = 0
    private var адресПостера = ""

    /// Согласие на обработку ракурсов ИИ дано на этом телефоне для этого ai (значение — ai из info).
    static let ключСогласия = "kliko.model3d.consent.v1"

    init(подача: ПодачаМодель, вид: ВидОбзора3DПодачи) {
        self.подача = подача
        self.вид = вид
        let з = ХранилищеОбзора3DПодачи.shared.запись(подача)
        if let з, з.всеСняты {
            шаг = .обзор
            ракурс = .спереди
        } else {
            шаг = .съёмка
            ракурс = з?.следующийНеснятый ?? .спереди
        }
    }

    private func т(_ ключ: String) -> String { Обзор3DПодачиText.т(ключ) }

    private var хранилище: ХранилищеОбзора3DПодачи { ХранилищеОбзора3DПодачи.shared }

    var ключ: String { хранилище.ключЦели(подача) }

    var запись: ЗаписьОбзора3DПодачи? { хранилище.запись(ключ: ключ) }

    var правка: Bool { подача.правка }

    // MARK: - Открыли и закрыли

    func открыт() {
        /* Снова на экране: полноэкранный AR Quick Look («Посмотреть в 3D») снимал окно с экрана — onDisappear звал
           закрыть(). Окно не закрыто, оно ожило: всё работает дальше, постер догрузится. */
        if закрыто {
            закрыто = false
            if постер == nil { адресПостера = "" }
        }
        хранилище.начать(подача, вид: вид)
        хранилище.возобновить(подача)
        загрузитьКадры()
        Task { @MainActor in await ГотовностьОбзора3DПодачи.shared.проверить() }
        /* Скорость: модель вырезки Vision — заранее, пока наводят камеру: первый снимок не ждёт её загрузки. */
        if !РежимУстройства.сейчас { ВырезкаПредмета.прогреть() }
    }

    /**
     Окно ушло с экрана (закрыли или его накрыл полноэкранный AR Quick Look): подготовка, загрузка миниатюр и модели
     стоят, флаги «готовим» и «открываем» — сброшены (их задачи отменены и сами уже не сбросят); сборка на сервере идёт
     дальше. Вернулось на экран — открыт() снимает «закрыто».
     */
    func закрыть() {
        guard !закрыто else { return }
        закрыто = true
        подготовка?.cancel()
        загрузкаКадров?.cancel()
        загрузкаПостера?.cancel()
        открытие?.cancel()
        подготовка = nil
        открытие = nil
        готовим = false
        открываем = false
        ЗагрузкаМоделиОбзора3DПодачи.shared.отменить()
    }

    /// Работа не на главной нити; отмена внешней задачи доходит и до неё (сама в Task.detached она не передаётся):
    /// вырезка (Vision, CoreImage) проверяет Task.isCancelled и бросает работу, когда окно ушло.
    private static func вФоне<T: Sendable>(_ работа: @escaping @Sendable () -> T) async -> T {
        let фоновая = Task.detached(priority: .userInitiated) { работа() }
        return await withTaskCancellationHandler {
            await фоновая.value
        } onCancel: {
            фоновая.cancel()
        }
    }

    /// Сторона миниатюр окна (полоска, поворот, кольцо): не полный кадр 1280–2048 px — пять таких в памяти рядом с
    /// живой камерой лишние. Лёгкий режим — меньше.
    private var сторонаКадров: Int { РежимУстройства.shared.лёгкий ? 600 : 900 }

    func показатьВесть(_ текст: String) {
        номерВести += 1
        let номер = номерВести
        withAnimation(ДвижениеСайта.появление) { весть = текст }
        UIAccessibility.post(notification: .announcement, argument: текст)
        Task { @MainActor [weak self] in
            try? await Task.sleep(nanoseconds: 2_600_000_000)
            guard let self, номер == self.номерВести else { return }
            withAnimation(ДвижениеСайта.уход) { self.весть = nil }
        }
    }

    private func перейти(_ новый: Шаг) {
        guard шаг != новый else { return }
        withAnimation(ДвижениеСайта.шаг) { шаг = новый }
    }

    // MARK: - Съёмка

    /// Сторона кадра — из info (max_px), по умолчанию 1280.
    private var сторона: Int { ГотовностьОбзора3DПодачи.shared.сведения?.сторона ?? 1280 }

    /// Снимок камеры.
    func принять(_ снимок: UIImage) {
        guard !готовим, !закрыто else { return }
        готовим = true
        let вид = self.вид
        let сторона = self.сторона
        подготовка = Task { @MainActor [weak self] in
            let готовый = await МодельСъёмкиОбзора3D.вФоне { () -> КартинкиОбзора3DПодачи.Готовый? in
                КартинкиОбзора3DПодачи.подготовить(снимок, вид: вид, сторона: сторона)
            }
            let показ = await МодельСъёмкиОбзора3D.картинкаДляПоказа(готовый)
            guard let self, !Task.isCancelled else { return }
            self.принятьГотовое(готовый, картинка: показ)
        }
    }

    /// Файл из галереи.
    func принять(данные: Data) {
        guard !готовим, !закрыто else { return }
        готовим = true
        let вид = self.вид
        let сторона = self.сторона
        подготовка = Task { @MainActor [weak self] in
            let готовый = await МодельСъёмкиОбзора3D.вФоне { () -> КартинкиОбзора3DПодачи.Готовый? in
                КартинкиОбзора3DПодачи.подготовить(данные, вид: вид, сторона: сторона)
            }
            let показ = await МодельСъёмкиОбзора3D.картинкаДляПоказа(готовый)
            guard let self, !Task.isCancelled else { return }
            self.принятьГотовое(готовый, картинка: показ)
        }
    }

    /// Скорость (владелец 16.10.2026: «моментально»): снимок для проверки — раскодирован и подготовлен к показу не на
    /// главной нити (ЯщикКартинкиОбъёма): шаг «Проверка» встаёт без рывка. Не вышло — nil, как прежнее UIImage(data:).
    private static func картинкаДляПоказа(_ готовый: КартинкиОбзора3DПодачи.Готовый?) async -> UIImage? {
        guard let данные = готовый?.картинка else { return nil }
        let ящик = await вФоне { () -> ЯщикКартинкиОбъёма? in
            guard let сырая = UIImage(data: данные) else { return nil }
            return ЯщикКартинкиОбъёма(сырая.preparingForDisplay() ?? сырая)
        }
        return ящик?.картинка
    }

    private func принятьГотовое(_ готовый: КартинкиОбзора3DПодачи.Готовый?, картинка: UIImage?) {
        готовим = false
        guard !закрыто else { return }
        guard let готовый, let картинка else {
            ОткликСайта.предупреждение()
            показатьВесть(т("m3_bad_image"))
            return
        }
        self.готовый = готовый
        снимок = картинка
        вырезан = готовый.вырезан
        людиВКадре = готовый.людиВКадре == true
        if !вырезан || людиВКадре { ОткликСайта.предупреждение() } else { ОткликСайта.выбор() }
        перейти(.проверка)
    }

    /// «Переснять» на проверке: кадр не берём, снова камера на том же ракурсе.
    func переснять() {
        готовый = nil
        снимок = nil
        перейти(.съёмка)
    }

    /**
     «Дальше» на проверке: кадр — в файлы и в запись (уходит на сервер), следующий неснятый ракурс или обзор. В полоску
     и кольцо — миниатюра (сторонаКадров) из той же фоновой задачи, а не полный кадр вырезки.
     */
    func оставить() {
        guard let готовый, !готовим, let папка = запись?.папка, !папка.isEmpty else { return }
        let р = ракурс
        let сторона = сторонаКадров
        готовим = true
        подготовка = Task { @MainActor [weak self] in
            let итог = await МодельСъёмкиОбзора3D.вФоне {
                () -> (файл: String, исходник: String, кадр: КадрыОбзора3DПодачи)? in
                let файл = ФайлыОбзора3DПодачи.имяКартинки(р, вырезан: готовый.вырезан)
                let исходник = ФайлыОбзора3DПодачи.имяИсходника(р)
                /* Переснятый ракурс мог быть другого вида (png ↔ jpg) — прежний файл прочь. */
                ФайлыОбзора3DПодачи.удалитьФайл(папка: папка,
                                                имя: ФайлыОбзора3DПодачи.имяКартинки(р, вырезан: !готовый.вырезан))
                guard ФайлыОбзора3DПодачи.записать(готовый.картинка, папка: папка, имя: файл),
                      ФайлыОбзора3DПодачи.записать(готовый.исходник, папка: папка, имя: исходник) else { return nil }
                var кадр = КадрыОбзора3DПодачи()
                if let мини = КартинкиОбзора3DПодачи.миниатюра(готовый.картинка, сторона: сторона) {
                    кадр.картинки[р.rawValue] = мини
                }
                return (файл, исходник, кадр)
            }
            guard let self, !Task.isCancelled, !self.закрыто else { return }
            self.готовим = false
            guard let итог else {
                ОткликСайта.предупреждение()
                self.показатьВесть(self.т("m3_err_save"))
                return
            }
            self.хранилище.принятьРакурс(self.подача, р, файл: итог.файл, исходник: итог.исходник,
                                         вырезан: готовый.вырезан)
            if let мини = итог.кадр.картинки[р.rawValue] { self.кадры[р.rawValue] = мини }
            self.готовый = nil
            self.снимок = nil
            ОткликСайта.успех()
            self.дальше(после: р)
        }
    }

    private func дальше(после р: РакурсОбзора3DПодачи) {
        if одинРакурс {
            одинРакурс = false
            перейти(.обзор)
            return
        }
        if let следующий = запись?.следующийНеснятый {
            ракурс = следующий
            перейти(.съёмка)
            UIAccessibility.post(notification: .announcement,
                                 argument: String(format: т("m3_step_a11y"), следующий.номер, РакурсОбзора3DПодачи.всего))
        } else {
            перейти(.обзор)
        }
    }

    /// Пересъёмка одного ракурса из обзора (нажатие на миниатюру).
    func снятьЗаново(_ р: РакурсОбзора3DПодачи) {
        одинРакурс = запись?.всеСняты == true
        ракурс = р
        перейти(.съёмка)
    }

    /// Из камеры обратно к обзору (пересъёмку передумали).
    func кОбзору() {
        одинРакурс = false
        готовый = nil
        снимок = nil
        перейти(.обзор)
    }

    /// Камера может вернуться к обзору: все ракурсы уже есть.
    var можноКОбзору: Bool { запись?.всеСняты == true }

    /// Миниатюры из файлов — для полоски, поворота и итога.
    func загрузитьКадры() {
        guard let з = запись else { return }
        загрузкаКадров?.cancel()
        let сторона = сторонаКадров
        загрузкаКадров = Task { @MainActor [weak self] in
            let новые = await ХранилищеОбзора3DПодачи.миниатюры(з, сторона: сторона)
            guard let self, !Task.isCancelled, !self.закрыто else { return }
            self.кадры = новые.картинки
        }
    }

    // MARK: - Сборка

    /// Кто соберёт модель — для согласия: ai из info; пусто — общая формулировка.
    var ктоСоберёт: String {
        let ии = ГотовностьОбзора3DПодачи.shared.сведения?.ии ?? ""
        return ии.isEmpty ? т("m3_ai_generic") : ии
    }

    private var нужноСогласие: Bool {
        if согласиеВОкне { return false }
        let ии = ГотовностьОбзора3DПодачи.shared.сведения?.ии ?? ""
        guard !ии.isEmpty else { return true }
        return UserDefaults.standard.string(forKey: Self.ключСогласия) != ии
    }

    /// «Собрать 3D»: первый раз (или сменился ИИ) — согласие, потом start.
    func собрать() {
        guard let з = запись, з.всеСняты else { return }
        if нужноСогласие {
            withAnimation(ДвижениеСайта.появление) { согласие = true }
            return
        }
        ОткликСайта.выбор()
        хранилище.собрать(подача)
    }

    /// «Согласен, собрать 3D»: согласие запоминается для этого ai (общая формулировка — только до закрытия окна).
    func согласен() {
        let ии = ГотовностьОбзора3DПодачи.shared.сведения?.ии ?? ""
        if ии.isEmpty {
            согласиеВОкне = true
        } else {
            UserDefaults.standard.set(ии, forKey: Self.ключСогласия)
        }
        withAnimation(ДвижениеСайта.уход) { согласие = false }
        ОткликСайта.выбор()
        хранилище.собрать(подача)
    }

    func отменитьСборку() {
        хранилище.отменитьСборку(подача)
    }

    func продолжить() {
        хранилище.продолжить(подача)
    }

    /// Готовую модель — прочь, ракурсы остаются (снова «Собрать 3D» или пересъёмка).
    func сброситьМодель() {
        хранилище.отменитьСборку(подача)
        постер = nil
        адресПостера = ""
    }

    // MARK: - Готово

    /// Постер готовой модели — отдельной сессией без кук и кэша (как картинки ИИ-фото); адрес сменился — заново.
    func загрузитьПостер() {
        guard let з = запись, з.готова, let адрес = з.адресПостера else { return }
        guard адрес.absoluteString != адресПостера else { return }
        адресПостера = адрес.absoluteString
        загрузкаПостера?.cancel()
        загрузкаПостера = Task { @MainActor [weak self] in
            let данные = await КартинкиИИФото.скачать(адрес)
            guard let self, !Task.isCancelled, !self.закрыто, let данные,
                  let картинка = UIImage(data: данные) else { return }
            self.постер = картинка
        }
    }

    /// «Посмотреть в 3D»: USDZ — через общий кэш моделей на диске (КэшОбъёма), потом AR Quick Look.
    func открыть3D() {
        guard let адрес = запись?.адресUSDZ, !открываем else { return }
        открываем = true
        открытие = Task { @MainActor [weak self] in
            let файл = await ЗагрузкаМоделиОбзора3DПодачи.shared.файл(адрес)
            /* Отменяет задачу только закрыть() — он же и гасит «Открываем…»; иначе флаг гаснет здесь при любом исходе,
               до проверки «закрыто». */
            guard let self, !Task.isCancelled else { return }
            self.открываем = false
            guard !self.закрыто else { return }
            guard let файл else {
                ОткликСайта.предупреждение()
                self.показатьВесть(self.т("m3_open_fail"))
                return
            }
            if !ПоказМоделиОбзора3DПодачи.показать(файл) {
                self.показатьВесть(self.т("m3_open_fail"))
            }
        }
    }

    // MARK: - Правка и «Убрать»

    /// Правка: «Сохранить в объявление».
    func сохранитьВОбъявление() {
        хранилище.сохранитьВОбъявление(подача)
    }

    /// «Убрать 3D-обзор»: всё черновика прочь (на сервере и на телефоне).
    func убрать() {
        хранилище.убрать(подача)
        кадры = [:]
        постер = nil
        адресПостера = ""
        ОткликСайта.выбор()
    }
}

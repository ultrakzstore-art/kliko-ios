import SwiftUI
import UIKit

/**
 ПОДАЧА И ПРАВКА — ЭКРАН, ЭТАП 42 (владелец 26.09.2026: «всё одно и то же, просто код разный»; Config.нативнаяПодача).

 Новое объявление начинается с камеры (ЭкранКамерыПодачи, PostingCamera.swift): фото → Kliko AI → «Проверьте».
 «Без фото — выбрать раздел» и правка — шаги ниже.

 Сверху вниз, как #add-screen сайта: шапка «Новое объявление / Сфотографируйте — Kliko AI заполнит всё сам» (в правке —
 «Редактировать объявление / После сохранения — повторная проверка»), плашка «Без верификации объявление не выйдет на
 витрину» (CAB_NEED_EGOV), полоса шагов «Фото · 1 / 7», сам шаг, внизу «Назад» и «Далее →»; на «Проверке» —
 «Выставить на продажу» (у аренды — «Сдать в аренду»), в правке — «Сохранить изменения».

 Открывается поверх вкладок (fullScreenCover в NativeTabsView) — камера нижней панели, «+ Добавить объявление»,
 «Изменить» в «Моих объявлениях», ссылки ?go=add и ?edit=<id>. Адреса мастера (верификация, «Работа», перенос по ссылке,
 вход через Apple) — своими экранами (ПереходыПодачи, PostingLinks.swift): своё окно поверх мастера или экран вкладок
 после его закрытия; своего нет — окно-сообщение поверх мастера. Страницы сайта нет. Черновик при этом остаётся.
 */
struct ЭкранПодачи: View {
    @StateObject private var модель: ПодачаМодель
    let открыть: (URL) -> Void

    init(цель: ЦельПодачи, открыть: @escaping (URL) -> Void) {
        _модель = StateObject(wrappedValue: ПодачаМодель(цель: цель))
        self.открыть = открыть
    }

    private func т(_ ключ: String) -> String { ПодачаText.т(ключ) }

    var body: some View {
        VStack(spacing: 0) {
            if простаяШапка {
                ШапкаПодачи(правка: модель.правка, закрыть: { закрыть() })
            }
            содержимое
        }
        .background(ФонПодачи())
        .task { await модель.начать() }
        .alert(модель.вопрос?.заголовок ?? "", isPresented: вопросНаЭкране, presenting: модель.вопрос) { в in
            Button(в.да) { в.действие() }
            if let ещё = в.ещё {
                Button(ещё) { в.ещёДействие?() }
            }
            Button(в.нет, role: .cancel) { в.отказ?() }
        } message: { в in
            Text(в.текст)
        }
        .alert(модель.сообщение?.заголовок ?? "", isPresented: сообщениеНаЭкране, presenting: модель.сообщение) { _ in
            Button(т("ok_btn"), role: .cancel) {}
        } message: { с in
            Text(с.текст)
        }
        .sheet(isPresented: $модель.подтверждение) {
            ОкноПроверкиПодачи(модель: модель)
        }
        .sheet(isPresented: $модель.войти) {
            ЭкранВхода(eGovВключён: модель.страница.состояние?.eGovВключён ?? true, открыть: { адрес in
                перейти(адрес)
            }, вошли: {
                Task { @MainActor in
                    if модель.экран == .нуженВход { await модель.начать() }
                }
            })
        }
        .overlay {
            if модель.распознаём {
                ОкноРаспознавания(шаг: модель.шагРаспознавания, отмена: { модель.отменитьРаспознавание() })
                    .transition(.opacity)
            }
        }
        .overlay {
            if let итог = модель.итог {
                if ЭкранПослеПодачи.берёт(итог) {
                    /* Опубликовано — спокойный лист: «Сообщим, когда напишет покупатель», «Поделиться», «Готово». */
                    ЭкранПослеПодачи(итог: итог, товар: модель.товарДляПревью, топПодключён: модель.топПослеПодачи,
                                     действие: { д in послеПодачиНажат(д, итог) })
                        .transition(.opacity)
                } else {
                    ОкноИтогаПодачи(итог: итог, заголовок: модель.форма.название, действие: { д in итогНажат(д, итог) })
                        .transition(.opacity)
                }
            }
        }
        .overlay(alignment: .bottom) { плашкаВнизу }
        .onChange(of: модель.открытьСтраницу) { _, хвост in
            guard let хвост else { return }
            модель.открытьСтраницу = nil
            перейти(хвост: хвост)
        }
        .modifier(СлухПодачи(модель: модель))
    }

    private var вопросНаЭкране: Binding<Bool> {
        Binding(get: { модель.вопрос != nil }, set: { показан in
            if !показан { модель.вопрос = nil }
        })
    }

    private var сообщениеНаЭкране: Binding<Bool> {
        Binding(get: { модель.сообщение != nil }, set: { показан in
            if !показан { модель.сообщение = nil }
        })
    }

    /// Простая шапка с «✕» — пока нет своей: у «Что размещаете?» и у шагов шапка своя (rw2-hd и .ehero).
    private var простаяШапка: Bool {
        switch модель.экран {
        case .камера, .старт, .шаги: return false
        default: return true
        }
    }

    @ViewBuilder
    private var содержимое: some View {
        switch модель.экран {
        case .загрузка:
            VStack(spacing: 12) {
                SiteSpinner()
                Text(т("loading"))
                    .font(.system(size: 15))
                    .foregroundStyle(Theme.текстВторой)
            }
            .frame(maxWidth: .infinity, maxHeight: .infinity)
        case .нуженВход:
            /* Гость на ?go=add у сайта видит тизер #guest-add-card «Новое объявление»: любое нажатие — вход. */
            ГостьПодачи(войти: { войти() })
        case .ошибка(let текст):
            ПустоСайта(значок: "wifi.exclamationmark", заголовок: текст, кнопка: т("retry"),
                       действие: { Task { await модель.начать() } })
        case .камера:
            /* Новое объявление — с камеры: фото → Kliko AI → «Проверьте» (ЭкранКамерыПодачи). */
            ЭкранКамерыПодачи(модель: модель, перенос: { перейти(хвост: "cabinet.php?go=import") }, закрыть: { закрыть() })
        case .старт:
            СтартПодачи(модель: модель, работа: { перейти(хвост: "cabinet?add=jobs") },
                        перенос: { перейти(хвост: "cabinet.php?go=import") }, закрыть: { закрыть() })
        case .шаги:
            ШагиПодачи(модель: модель, открытьАдрес: { хвост in перейти(хвост: хвост) }, закрыть: { закрыть() })
        }
    }

    private func войти() {
        if Config.нативныйВход {
            модель.войти = true
        } else {
            перейти(хвост: "cabinet.php")
        }
    }

    /// «✕»: черновик остаётся (сайт пишет его сам при каждом вводе), мастер закрывается.
    private func закрыть() {
        модель.записатьЧерновик()
        модель.остановить()
        ПодачаОкно.shared.цель = nil
    }

    /// Хвост адреса кабинета (/kz/<язык>/<хвост>) из мастера — своим экраном, не страницей сайта.
    private func перейти(хвост: String) {
        guard let адрес = Config.страницаСайта(хвост) else { return }
        перейти(адрес)
    }

    /// Адрес из мастера или листа входа: eGov и прочие свои окна — поверх мастера (черновик на экране), экран вкладок —
    /// после его закрытия, своего нет — окно-сообщение поверх мастера. Решает ПереходыПодачи до закрытия.
    private func перейти(_ адрес: URL) {
        ПереходыПодачи.открыть(адрес, модель: модель, закрытьМастер: { закрыть() }, общийПуть: открыть)
    }

    private func итогНажат(_ действие: ОкноИтогаПодачи.Действие, _ итог: ИтогПодачи) {
        switch действие {
        case .готово:
            модель.итог = nil
            switch итог {
            case .опубликовано, .ждётВерификации:
                модель.закрытьМастер(вкладка: .published)
            case .наПроверке, .отклонено, .сохраненоИИ, .неактивные, .лимит, .запрещено:
                модель.закрытьМастер(вкладка: .inactive)
            }
        case .освободить:
            /* «Освободить место»: опубликованные — там снять или удалить старое объявление. */
            модель.итог = nil
            модель.закрытьМастер(вкладка: .published)
        case .верификация:
            модель.итог = nil
            let eGovВключён = модель.страница.состояние?.eGovВключён ?? true
            модель.закрытьМастер(вкладка: nil)
            /* Окно «Стать продавцом» (ЛистВерификации), когда мастер уедет; из него — eGov своим окном. Слоя вкладок
               нет — сразу requestVerification сайта: eGov своим окном или ver_off, не страница сайта. */
            if !ОкнаПриложения.shared.показать(.верификация, задержка: 800_000_000) {
                ПереходыПодачи.пройтиВерификацию(nil, eGovВключён: eGovВключён, сказать: { текст in
                    БезСайта.сообщить(заголовок: т("verify_t"), текст: текст)
                })
            }
        }
    }

    /// Экран после подачи (ЭкранПослеПодачи): опубликованное — вкладка «Опубликованные», на проверке — «Неактивные».
    private func послеПодачиНажат(_ действие: ЭкранПослеПодачи.Действие, _ итог: ИтогПодачи) {
        let id = ЭкранПослеПодачи.номер(итог)
        let вкладка: ВкладкаОбъявлений = ЭкранПослеПодачи.опубликовано(итог) ? .published : .inactive
        switch действие {
        case .продвинуть:
            /* Продвижение — окно покупки App Store поверх листа (кнопка есть только при Config.цифровыеПокупки). */
            ЛистУслугиApple.показать(.продвижение, цель: id)
        case .посмотреть:
            модель.открытьОбъявлениеПослеПодачи(id, запасной: открыть)
        case .мои, .закрыть:
            модель.итог = nil
            модель.закрытьМастер(вкладка: вкладка)
        case .ещё:
            модель.податьЕщё()
        }
    }

    @ViewBuilder
    private var плашкаВнизу: some View {
        if let текст = модель.плашка {
            /* .toast кабинета: тёмная плашка #0f1712 в обеих темах, 14 px, строка 1.4, скругление 12. */
            Text(текст)
                .font(.system(size: 14))
                .lineSpacing(5)
                .foregroundStyle(Color.white)
                .multilineTextAlignment(.center)
                .padding(.horizontal, 20)
                .padding(.vertical, 12)
                .background(Color(red: 15 / 255, green: 23 / 255, blue: 18 / 255),
                            in: RoundedRectangle(cornerRadius: Theme.Радиус.ms, style: .continuous))
                .frame(maxWidth: 420)
                .padding(.horizontal, 20)
                .padding(.bottom, 90)
                .transition(.opacity)
                .accessibilityHidden(true)
        }
    }
}


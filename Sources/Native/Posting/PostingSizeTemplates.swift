    /// Встроенный вид: ключи текстов — sz_<вид> (заголовок), sz_<вид>_why («зачем»), sz_<вид>_<номер> (имя образца).
    private static func вид(_ ключ: String, _ мера: МераРазмеров, _ разделы: [String], _ слова: [String],
                            _ образцы: [(Int, Int, Int, String)]) -> ВидРазмеров {
        var список: [ОбразецРазмеров] = []
        for (номер, о) in образцы.enumerated() {
            список.append(ОбразецРазмеров(ключ: "sz_" + ключ + "_" + String(номер + 1), имяСайта: "",
                                          ширина: о.0, высота: о.1, глубина: о.2, доп: о.3))
        }
        return ВидРазмеров(ключ: ключ, мера: мера, разделы: разделы, слова: слова, образцы: список)
    }

    /// Встроенные вместе с видами сайта: вид с тем же ключом сайт заменяет, новые — впереди (они главнее при равенстве);
    /// replace — только виды сайта; on: false — ничего.
    static func все(_ сайт: ШаблоныРазмеровСхемы?) -> [ВидРазмеров] {
        guard let сайт else { return встроенные }
        if сайт.выключены { return [] }
        if сайт.замена { return сайт.виды }
        let свои = Set(сайт.виды.map { $0.ключ })
        return сайт.виды + встроенные.filter { !свои.contains($0.ключ) }
    }

    /// Нижний регистр, «ё» → «е» — так сверяются слова названия.
    static func нормально(_ текст: String) -> String {
        текст.lowercased().replacingOccurrences(of: "ё", with: "е")
    }

    /// Виды раздела: прямые — раздел назван в списке вида; через — раздел внутри одного из разделов вида (предки).
    /// внутри — проверка дерева (справочник подачи или снимок сайта).
    static func кандидаты(раздел: String, виды: [ВидРазмеров],
                          внутри: (String, Set<String>) -> Bool) -> (прямые: [ВидРазмеров], через: [ВидРазмеров]) {
        guard !раздел.isEmpty else { return ([], []) }
        var прямые: [ВидРазмеров] = []
        var через: [ВидРазмеров] = []
        for вид in виды {
            if вид.разделы.contains(раздел) {
                прямые.append(вид)
            } else if внутри(раздел, Set(вид.разделы)) {
                через.append(вид)
            }
        }
        return (прямые, через)
    }

    /**
     Сколько слов вида есть в тексте (уже нормальном) и где первое (смещение в знаках; нет — Int.max). Короткие слова —
     до двух знаков и латинские до трёх («тв», «pc», «ps5», «bed», «rim») — только целым словом: «тв» иначе нашлось бы в
     «твёрдый», «bed» — в «bedroom».
     */
    static func совпадения(_ вид: ВидРазмеров, в текст: String) -> (сколько: Int, первое: Int) {
        var сколько = 0
        var первое = Int.max
        for исходное in вид.слова {
            let слово = нормально(исходное)
            guard !слово.isEmpty else { continue }
            let короткое = слово.count <= 2 || (слово.count <= 3 && слово.unicodeScalars.allSatisfy { $0.isASCII })
            let место: Range<String.Index>?
            if короткое {
                let образец = "(?<![\\p{L}\\p{N}])" + NSRegularExpression.escapedPattern(for: слово) + "(?![\\p{L}\\p{N}])"
                место = текст.range(of: образец, options: .regularExpression)
            } else {
                место = текст.range(of: слово)
            }
            guard let место else { continue }
            сколько += 1
            первое = min(первое, текст.distance(from: текст.startIndex, to: место.lowerBound))
        }
        return (сколько, первое)
    }

    /// Вид товара по разделу и названию; nil — не понять (продавец выберет сам) или у раздела шаблонов нет.
    static func вид(раздел: String, название: String, виды: [ВидРазмеров],
                    внутри: (String, Set<String>) -> Bool) -> ВидРазмеров? {
        let к = кандидаты(раздел: раздел, виды: виды, внутри: внутри)
        let все = к.прямые + к.через
        guard !все.isEmpty else { return nil }
        /* Шины или диски (у сайта один раздел на оба): по признакам дисков в названии, а не по счёту слов. */
        if let шина = все.first(where: { $0.мера == .шина }), let диск = все.first(where: { $0.мера == .диск }) {
            switch ПризнакиДисков.поНазванию(название) {
            case .some(true): return диск
            case .some(false): return шина
            case .none: return nil
            }
        }
        let текст = нормально(название)
        var лучший: (вид: ВидРазмеров, сколько: Int, прямой: Bool, первое: Int)? = nil
        for (номер, вид) in все.enumerated() {
            let с = совпадения(вид, в: текст)
            guard с.сколько > 0 else { continue }
            let прямой = номер < к.прямые.count
            let новый = (вид: вид, сколько: с.сколько, прямой: прямой, первое: с.первое)
            guard let л = лучший else {
                лучший = новый
                continue
            }
            if с.сколько != л.сколько {
                if с.сколько > л.сколько { лучший = новый }
            } else if прямой != л.прямой {
                if прямой { лучший = новый }
            } else if с.первое < л.первое {
                лучший = новый
            }
        }
        if let лучший { return лучший.вид }
        /* Слов нет: вид, для которого раздел — первый в списке (sofas → диван); один кандидат — он. */
        if let свой = к.прямые.first(where: { $0.разделы.first == раздел }) { return свой }
        return все.count == 1 ? все[0] : nil
    }

    /**
     Образец по названию: у диагонали — дюймы («55"», «15,6 дюйма», «6.1 inch»), у коробки — «доп» образца целым куском
     («160х200», «2x3», «100 л», «45 см», велосипед «26"»). Числа без единиц («09» у кондиционеров) по названию не
     ищем: слишком легко ошибиться. Шины и диски — своими полями (PostingSizeWheels.swift). nil — не нашли.
     */
    static func образецПоНазванию(_ вид: ВидРазмеров, название: String) -> ОбразецРазмеров? {
        let текст = нормально(название)
        guard !текст.isEmpty else { return nil }
        switch вид.мера {
        case .диагональ:
            guard let диагональ = Self.дюймы(текст) else { return nil }
            return ближайший(вид.образцы, к: диагональ, допуск: 0.35)
        case .коробка:
            let сжатый = сжать(текст)
            let вДюймах = дюймы(текст)
            for о in вид.образцы {
                if let д = о.дюймы {
                    if let вДюймах, abs(д - вДюймах) <= 0.35 { return о }
                    continue
                }
                let доп = сжать(нормально(о.доп))
                guard доп.count >= 2, !доп.allSatisfy({ $0.isNumber }) else { continue }
                if отдельно(доп, в: сжатый) { return о }
            }
            return nil
        case .шина, .диск:
            return nil
        }
    }

    /// Образец с ближайшей диагональю в пределах допуска.
    private static func ближайший(_ образцы: [ОбразецРазмеров], к дюймы: Double, допуск: Double) -> ОбразецРазмеров? {
        var лучший: (образец: ОбразецРазмеров, разница: Double)? = nil
        for о in образцы {
            guard let д = о.дюймы else { continue }
            let разница = abs(д - дюймы)
            if разница <= допуск && разница < (лучший?.разница ?? .infinity) { лучший = (о, разница) }
        }
        return лучший?.образец
    }

    /// Без пробелов; «х», «×», «*» → «x»; запятая → точка («1,6х2,3» → «1.6x2.3»); «литр…» → «л».
    private static func сжать(_ текст: String) -> String {
        var т = текст
        for (было, стало) in [("литр", "л"), ("×", "x"), ("х", "x"), ("*", "x"), (",", "."), (" ", ""),
                              ("\u{00A0}", "")] {
            т = т.replacingOccurrences(of: было, with: стало)
        }
        return т
    }

    /// Кусок есть в тексте и не продолжает соседнее число: «2x3» не найдётся в «12x30».
    private static func отдельно(_ кусок: String, в текст: String) -> Bool {
        var откуда = текст.startIndex
        while let место = текст.range(of: кусок, range: откуда..<текст.endIndex) {
            let до: Character? = место.lowerBound > текст.startIndex ? текст[текст.index(before: место.lowerBound)] : nil
            let после: Character? = место.upperBound < текст.endIndex ? текст[место.upperBound] : nil
            let слева = до.map { !$0.isNumber && $0 != "." } ?? true
            let справа = после.map { !$0.isNumber } ?? true
            if слева && справа { return true }
            откуда = текст.index(after: место.lowerBound)
        }
        return false
    }

    /// Дюймы в тексте (нормальном): «55"», «55″», «15.6 дюйма», «13,3''», «6.1 inch»; первое правдоподобное (3…120).
    static func дюймы(_ текст: String) -> Double? {
        let т = текст.replacingOccurrences(of: ",", with: ".")
        let образец = #"(?<![\d.])(\d{1,3}(?:\.\d{1,2})?)\s*(?:"|″|”|“|''|-?\s*дюйм|inch|in(?![\p{L}]))"#
        var откуда = т.startIndex
        while let место = т.range(of: образец, options: .regularExpression, range: откуда..<т.endIndex) {
            let число = т[место].prefix { $0.isNumber || $0 == "." }
            if let д = Double(число), (3...120).contains(д) { return д }
            откуда = место.upperBound
        }
        return nil
    }

    /// «R16 · 5×114.3» из «R16 6.5J ET45 5x114.3 DIA 67.1»: диаметр и разболтовка — главное для чипа.
    static func коротко(диск доп: String) -> String {
        let части = доп.split(separator: " ").map(String.init)
        let диаметр = части.first { $0.hasPrefix("R") }
        let pcd = части.first { $0.contains("x") && ($0.first?.isNumber ?? false) }
        return [диаметр, pcd.map { $0.replacingOccurrences(of: "x", with: "×") }]
            .compactMap { $0 }
            .joined(separator: " · ")
    }

    /**
     «Поместится ли?» без размеров в объявлении: ноутбук, планшет, телефон — примерно по диагонали из названия (образец
     ближайшей диагонали, допуск 1″). Телевизоры и мониторы считает своя оценка (FitBoxSize.swift). nil — вид не
     «диагональный» или диагонали нет.
     */
    static func поДиагонали(раздел: String?, текст: String) -> (дюймы: Double, образец: ОбразецРазмеров)? {
        guard let раздел, !раздел.isEmpty else { return nil }
        for вид in встроенные where вид.мера == .диагональ && РазделыСайта.внутри(раздел, Set(вид.разделы)) {
            guard let диагональ = Self.дюймы(нормально(текст)),
                  let образец = ближайший(вид.образцы, к: диагональ, допуск: 1) else { return nil }
            return (диагональ, образец)
        }
        return nil
    }
}


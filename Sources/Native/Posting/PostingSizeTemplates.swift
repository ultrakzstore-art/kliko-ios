    /// Раздел или его предок — один из ключей: справочник подачи или снимок сайта (как у габаритов).
    func разделВнутри(_ раздел: String, _ ключи: Set<String>) -> Bool {
        справочники.внутри(раздел, ключи) || РазделыСайта.внутри(раздел, ключи)
    }

    /// Виды для «Что это?»: у кого раздел формы назван прямо, иначе — через предков.
    var кандидатыРазмеров: [ВидРазмеров] {
        let к = КаталогРазмеров.кандидаты(раздел: форма.раздел, виды: видыРазмеров, внутри: разделВнутри)
        return к.прямые.isEmpty ? к.через : к.прямые
    }

    /// У раздела формы есть шаблоны — блок размеров показываем (по желанию), даже если раздел не габаритный.
    var естьШаблоныРазмеров: Bool { !кандидатыРазмеров.isEmpty }

    /// Вид товара для образцов: выбранный продавцом («Что это?»), пока он подходит разделу; иначе по разделу и
    /// названию; nil — не понять.
    var видРазмеров: ВидРазмеров? {
        let виды = видыРазмеров
        guard !виды.isEmpty, !форма.раздел.isEmpty else { return nil }
        let выбран = форма.габариты?.вид ?? ""
        if !выбран.isEmpty {
            let к = КаталогРазмеров.кандидаты(раздел: форма.раздел, виды: виды, внутри: разделВнутри)
            if let свой = (к.прямые + к.через).first(where: { $0.ключ == выбран }) { return свой }
        }
        return КаталогРазмеров.вид(раздел: форма.раздел, название: форма.название, виды: виды, внутри: разделВнутри)
    }

    /// Строка «зачем» под заголовком блока: у вида своя; нет — nil (общий текст блока).
    var зачемРазмеры: String? {
        guard let вид = видРазмеров else { return nil }
        let зачем = вид.зачем
        return зачем.isEmpty ? nil : зачем
    }

    /// «Что это?»: вид выбран продавцом — образцы этого вида; размеры в полях остаются.
    func выбратьВидРазмеров(_ ключ: String) {
        var г = форма.габариты ?? ГабаритыПодачи()
        guard г.вид != ключ else { return }
        г.вид = ключ
        форма.габариты = г
    }

    /// Касание образца: Ш×В×Г в поля с источником "tpl" («типичный размер — сверьте»); вид запоминается.
    func применитьОбразецРазмеров(_ образец: ОбразецРазмеров, вида вид: ВидРазмеров) {
        var г = форма.габариты ?? ГабаритыПодачи()
        г.ширина = String(образец.ширина)
        г.высота = String(образец.высота)
        г.глубина = String(образец.глубина)
        г.источник = "tpl"
        г.вид = вид.ключ
        форма.габариты = г
    }

    /// Образец, с которым совпадают поля (его чип — выбранный); nil — ни один.
    func выбранныйОбразец(_ вид: ВидРазмеров) -> ОбразецРазмеров? {
        guard let п = габаритыФормы.полные else { return nil }
        return вид.образцы.first { $0.ширина == п.ширина && $0.высота == п.высота && $0.глубина == п.глубина }
    }

    /**
     Блок ещё не трогали, а в названии — диагональ, размер или объём образца («55"», «160х200», «100 л»): ставим этот
     образец (источник "tpl", пометка «типичный размер — сверьте»). Только в новой подаче: правку опубликованного без
     спроса не меняем. true — поставили.
     */
    @discardableResult
    func подставитьОбразецИзНазвания() -> Bool {
        guard Config.шаблоныРазмеров, !правка, нужныГабариты, форма.габариты == nil, let вид = видРазмеров,
              вид.мера == .коробка || вид.мера == .диагональ,
              let образец = КаталогРазмеров.образецПоНазванию(вид, название: форма.название) else { return false }
        форма.габариты = ГабаритыПодачи(ширина: String(образец.ширина), высота: String(образец.высота),
                                        глубина: String(образец.глубина), источник: "tpl")
        return true
    }

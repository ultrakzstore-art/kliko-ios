/**
 rules.dims схемы подачи (docs/SERVER_SIZE_TEMPLATES.md): {on, replace, wheel_fields, kinds: [{key, measure, cats,
 words, title, why, presets: [{name, w, h, d, extra}]}]} — kinds бывает и объектом {ключ: вид}, presets — с dims
 «60x190x65» вместо w/h/d. Читается терпимо: вид без разделов или без годных образцов пропускается.
 */
struct ШаблоныРазмеровСхемы: Equatable, Sendable {
    /// on: false — шаблонов нет вовсе (и встроенных).
    var выключены = false
    /// replace: true — только виды сайта.
    var замена = false
    /// wheel_fields: 1 — сервер хранит tyre_* и rim_* и показывает их в характеристиках: строку шин или дисков в
    /// описание приложение больше не дописывает.
    var колёсаПолями = false
    var виды: [ВидРазмеров] = []

    /// nil — правила нет или в нём ничего полезного.
    static func из(_ сырое: Any?) -> ШаблоныРазмеровСхемы? {
        typealias A = МоиОбъявленияAPI
        guard let п = сырое as? [String: Any] else { return nil }
        var итог = ШаблоныРазмеровСхемы()
        if let вкл = п["on"], !(вкл is NSNull), !A.да(вкл) {
            итог.выключены = true
            return итог
        }
        итог.замена = A.да(п["replace"])
        итог.колёсаПолями = A.да(п["wheel_fields"])
        var сырые: [(ключ: String, вид: [String: Any])] = []
        if let список = п["kinds"] as? [Any] {
            for элемент in список {
                guard let в = элемент as? [String: Any] else { continue }
                let ключ = A.строка(в["key"]).isEmpty ? A.строка(в["id"]) : A.строка(в["key"])
                сырые.append((ключ: ключ, вид: в))
            }
        } else if let словарь = п["kinds"] as? [String: Any] {
            for ключ in словарь.keys.sorted() {
                if let в = словарь[ключ] as? [String: Any] { сырые.append((ключ: ключ, вид: в)) }
            }
        }
        var ключи = Set<String>()
        for пара in сырые {
            let ключ = пара.ключ.trimmingCharacters(in: .whitespacesAndNewlines)
            guard !ключ.isEmpty, !ключи.contains(ключ), let новый = Self.вид(ключ, пара.вид) else { continue }
            ключи.insert(ключ)
            итог.виды.append(новый)
        }
        if итог.виды.isEmpty && !итог.замена && !итог.колёсаПолями { return nil }
        return итог
    }

    private static func вид(_ ключ: String, _ в: [String: Any]) -> ВидРазмеров? {
        typealias A = МоиОбъявленияAPI
        let мера = МераРазмеров(rawValue: A.строка(в["measure"]).trimmingCharacters(in: .whitespaces)) ?? .коробка
        let разделы = список(в["cats"] ?? в["categories"])
        guard !разделы.isEmpty else { return nil }
        let слова = список(в["words"] ?? в["keywords"]).map { КаталогРазмеров.нормально($0) }
        let колесо = мера == .шина || мера == .диск
        var образцы: [ОбразецРазмеров] = []
        for (номер, элемент) in ((в["presets"] as? [Any]) ?? []).enumerated() {
            guard let о = элемент as? [String: Any] else { continue }
            var ш = A.целое(о["w"])
            var высота = A.целое(о["h"])
            var г = A.целое(о["d"])
            if ш <= 0 || высота <= 0 || г <= 0, let строка = о["dims"] as? String {
                let числа = строка.components(separatedBy: CharacterSet.decimalDigits.inverted).compactMap { Int($0) }
                if числа.count >= 3 {
                    ш = числа[0]
                    высота = числа[1]
                    г = числа[2]
                }
            }
            let доп = A.строка(о["extra"]).trimmingCharacters(in: .whitespaces)
            let пределы = ПравилаГабаритовПодачи.пределы
            let годны = пределы.contains(ш) && пределы.contains(высота) && пределы.contains(г)
            /* У шин и дисков главное — «доп» (размер, параметры), Ш×В×Г у них не нужны. */
            guard колесо ? !доп.isEmpty : годны else { continue }
            образцы.append(ОбразецРазмеров(ключ: "srv_" + ключ + "_" + String(номер + 1),
                                           имяСайта: текст(о["name"] ?? о["title"]),
                                           ширина: годны ? ш : 0, высота: годны ? высота : 0, глубина: годны ? г : 0,
                                           доп: доп))
        }
        guard !образцы.isEmpty else { return nil }
        return ВидРазмеров(ключ: ключ, мера: мера, разделы: разделы, слова: слова, образцы: образцы,
                           заголовокСайта: текст(в["title"]), зачемСайта: текст(в["why"]))
    }

    /// Список строк: ["a", "b"] или «a, b».
    private static func список(_ сырое: Any?) -> [String] {
        let строки: [String]
        if let массив = сырое as? [Any] {
            строки = массив.map { МоиОбъявленияAPI.строка($0) }
        } else {
            строки = МоиОбъявленияAPI.строка(сырое).components(separatedBy: ",")
        }
        return строки.map { $0.trimmingCharacters(in: .whitespacesAndNewlines) }.filter { !$0.isEmpty }
    }

    private static func текст(_ сырое: Any?) -> String {
        МоиОбъявленияAPI.строка(сырое).trimmingCharacters(in: .whitespacesAndNewlines)
    }
}


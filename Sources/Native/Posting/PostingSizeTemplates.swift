// MARK: - Вид и образец

/// Как мерить вид товара.
enum МераРазмеров: String, Equatable, Sendable {
    /// Коробка Ш×В×Г.
    case коробка = "box"
    /// Сначала диагональ экрана — она подставляет Ш×В×Г.
    case диагональ = "diagonal"
    /// Шина: ширина, профиль, диаметр — вместо Ш×В×Г.
    case шина = "tyre"
    /// Диск: диаметр, ширина J, вылет ET, PCD, DIA — вместо Ш×В×Г.
    case диск = "rim"
}

/// Один образец: Ш×В×Г в целых сантиметрах и подсказка «доп» — диагональ «55"», размер шины «205/55 R16», параметры
/// диска «R16 6.5J ET45 5x114.3 DIA 67.1», размер «160x200», объём «100 л».
struct ОбразецРазмеров: Equatable, Sendable, Identifiable {
    /// Ключ текста имени у встроенного (sz_sofa_2); у образца сайта — свой, только для списка.
    let ключ: String
    /// Имя с сайта (на языке схемы); пусто — своё по ключу.
    let имяСайта: String
    let ширина: Int
    let высота: Int
    let глубина: Int
    let доп: String

    var id: String { ключ }

    /// Имя на языке телефона; нет — пусто.
    var имя: String {
        if !имяСайта.isEmpty { return имяСайта }
        let своё = РазмерыОбразцовText.т(ключ)
        return своё == ключ ? "" : своё
    }

    /// «60 × 190 × 65».
    var размеры: String { String(ширина) + " × " + String(высота) + " × " + String(глубина) }

    /// Диагональ из «доп» в дюймах («55"», «15.6"»); не диагональ — nil.
    var дюймы: Double? {
        guard let кавычка = доп.firstIndex(of: "\"") else { return nil }
        return Double(доп[..<кавычка].trimmingCharacters(in: .whitespaces))
    }

    /// «55″» — диагональ для чипа: знак дюйма вместо кавычки.
    var подписьДиагонали: String { доп.replacingOccurrences(of: "\"", with: "″") }
}

/// Вид товара с образцами.
struct ВидРазмеров: Equatable, Sendable, Identifiable {
    let ключ: String
    let мера: МераРазмеров
    /// Разделы сайта (вместе с потомками). Первый — раздел, где этот вид по умолчанию.
    let разделы: [String]
    /// Основы слов названия в нижнем регистре.
    let слова: [String]
    let образцы: [ОбразецРазмеров]
    /// Заголовок и «зачем» с сайта (rules.dims); пусто — свои тексты.
    var заголовокСайта: String = ""
    var зачемСайта: String = ""

    var id: String { ключ }

    /// «Холодильник» — подпись в «Что это?».
    var заголовок: String {
        if !заголовокСайта.isEmpty { return заголовокСайта }
        let своё = РазмерыОбразцовText.т("sz_" + ключ)
        return своё == "sz_" + ключ ? ключ : своё
    }

    /// Одна строка «зачем» для продавца; нет — пусто (тогда общий текст блока).
    var зачем: String {
        if !зачемСайта.isEmpty { return зачемСайта }
        let своё = РазмерыОбразцовText.т("sz_" + ключ + "_why")
        return своё == "sz_" + ключ + "_why" ? "" : своё
    }

    /// Две строки чипа: коробка — имя и размеры; диагональ — «55″» (с именем) и размеры; шина — размер и машины; диск —
    /// «R16 · 5×114.3» и машины.
    func подписи(_ о: ОбразецРазмеров) -> (верх: String, низ: String) {
        let имя = о.имя
        switch мера {
        case .коробка:
            return имя.isEmpty ? (о.размеры, "") : (имя, о.размеры)
        case .диагональ:
            let диагональ = о.подписьДиагонали
            return (имя.isEmpty ? диагональ : диагональ + " · " + имя, о.размеры)
        case .шина:
            return (о.доп.isEmpty ? имя : о.доп, о.доп.isEmpty ? "" : имя)
        case .диск:
            let коротко = КаталогРазмеров.коротко(диск: о.доп)
            return (коротко.isEmpty ? имя : коротко, коротко.isEmpty ? "" : имя)
        }
    }
}


import Foundation

/**
 ЗАГОТОВКА ПОДАЧИ — «ПРОДАТЬ СВОЁ» ИЗ «МОЕГО» (пачка 83, договор docs/SERVER_NEW_FOR_MINE.md §16.4, SERVER_CIRCLE.md §4,
 SERVER_STANDARDS.md §2.1, §3.1, §3.6).

 Что это. Мастер новой подачи открывается уже заполненным: раздел, название, марка, состояние, слоты характеристик
 (cpu · gpu · ram · storage · year), поля шин и дисков (parts), размер одежды и обуви (строка всех систем → бирка блока
 «Размер» и поле сайта), габариты Ш×В×Г, стандарты вещи (std, qty, std_src) и фото самой вещи из папки «Моего». Раньше
 было «название в буфер обмена + пустая подача».

 Как открыть (любая вещь «Моего», с главной нити):
     var з = ЗаготовкаПодачи(название: "Michelin X-Ice North 4 205/55 R16, комплект", раздел: "tires-wheels")
     з.запчасть = ["width": "205", "profile": "55", "diameter": "16"]
     з.диски = false
     з.штук = 4
     ПереходыГардероба.послеОкон { _ = ЖдущаяЗаготовкаПодачи.открыть(з) }
 false — мастер выключен (Config.нативнаяПодача, Config.заготовкаПодачи) или уже открыт: заготовка не ждёт, вызывающий
 делает, как раньше.

 ЦельПодачи не меняется (ключ 3D «new», сравнение «== .новое» в StateRestore, fullScreenCover вкладок): заготовка ждёт
 рядом (ЖдущаяЗаготовкаПодачи, как ЖдущийОтборМоего) и забирается моделью в начать(). Есть незаконченный черновик — тот
 же вопрос «Продолжить / Новое»: «Продолжить» — черновик как был, заготовка забыта; «Новое» — заготовка.

 Что делает мастер. Поля ложатся при заполняем = true: подбор раздела с сервера (cat_guess), рынок (market_price) и
 Kliko AI сами не запускаются — новых запросов нет, значения «Моего» до публикации не уходят. Экран — фото (камера),
 дальше «Проверьте» короткого пути без Kliko AI (быстроРаспознано), чтобы распознавание не переписало раздел и название.
 Чего форма не знает (незнакомый или цифровой раздел, транспорт кроме запчастей, недвижимость, услуги, работа; значение
 не из списка поля; слот, которого у раздела нет) — молча не ставится: человек выберет сам. Фото — только переданные
 файлы самой вещи (тем же путём, что выбор из галереи: ужатие, знак, upload_photo).

 Что уходит в submit сверх обычного (поляЗаготовки, PostingSend.swift), только по флагам схемы подачи (нет флага —
 новых полей нет, SERVER_CIRCLE.md §1.1):
   · std, std_src, qty — при rules.std.store; у шин и дисков std не шлётся (их значения — в parts). Без store стандарты
     ложатся последней строкой описания «Параметры: ОЗУ DDR4 SO-DIMM 8 ГБ 3200 · 2 шт» (SERVER_STANDARDS.md §3.6;
     в минимум описания строка не засчитывается — ПравилаРазмераОдежды.длинаОписания);
   · from: "my" и relist_from («deal:<id>» или «listing:<id>») — при rules.circle.on и rules.circle.relist;
   · show_provenance — там же, при rules.std.provenance, у deal: и только по выбору продавца.
 Черновик на телефоне хранит форму (название, описание, фото), а не заготовку: после «Продолжить» поля std, relist_from
 и from не уходят.
 */
extension Config {
    /// «Продать своё» заполняет мастер подачи сам. false — ЖдущаяЗаготовкаПодачи.открыть отвечает false, вызывающий
    /// делает, как раньше.
    static let заготовкаПодачи = true
}


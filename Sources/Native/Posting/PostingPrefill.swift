/// Что положить в мастер новой подачи. Всё по желанию, кроме названия и раздела (пустые — человек выберет сам).
struct ЗаготовкаПодачи: Equatable, Hashable {
    /// До 75 знаков (обрежет форма); без имён вещей «Моего» — не «Camry жены», не «спальня» (§16.4).
    var название: String
    /// Раздел сайта (slug): «tires-wheels», «ram», «womens-outerwear», «chandeliers». Незнакомый — пусто.
    var раздел: String
    /// Марка — только где форма её показывает (товары); у шин — в название или запчасть["maker"].
    var бренд: String = ""
    /// Своё описание без строк приложения: «Размер: …» и «Параметры: …» мастер допишет сам.
    var описание: String = ""
    /// used | new; nil — как у новой подачи (used).
    var состояние: String? = nil
    /// Слоты характеристик сайта: cpu · gpu · ram · storage · year. Значение списка — ключ или подпись варианта.
    var характеристики: [String: String] = [:]
    /// PARTS_FIELDS: шина — width · profile · diameter · season; диск — diameter · width_j · et · pcd · dia.
    var запчасть: [String: String] = [:]
    /// Шины и диски: true — диски, false — шины, nil — по полям (есть width_j, pcd, et или dia — диски).
    var диски: Bool? = nil
    /// Размер одежды и обуви — строка всех систем: «EU 42 · RU 41 · US M 9 · UK 8» (с «Размер:» или без). Удобнее —
    /// ЗаготовкаПодачи.строкаРазмера(_:) из размера «Моего».
    var размерВсехСистем: String = ""
    /// Габариты Ш×В×Г, см (1…1000); нужны всем трём, иначе в объявление не попадут.
    var ширина: Int? = nil
    var высота: Int? = nil
    var глубина: Int? = nil
    /// Стандарты вещи «Моего» (std, qty, источник). Источник «deal» уходит как "" (SERVER_STANDARDS.md §3.1).
    var стандарты: НаборСтандартов? = nil
    /// Сколько единиц в объявлении: комплект шин 4, кит ОЗУ 2 (qty, 1…999). Больше из этого и стандарты.сколько.
    var штук: Int = 1
    /// Имена файлов фото «Моего» (photos/, ФайлыМоего.адресФото) — только снимки самой вещи: не машина, не тело.
    var фотоМоего: [String] = []
    /// Связь с покупкой: «deal:<id>» или «listing:<id>» (relist_from, SERVER_CIRCLE.md §4.3); пусто — нет.
    var источник: String = ""
    /// show_provenance — выбор продавца «Показать «Куплено на Kliko»» (только у deal:).
    var показатьКупленоНаKliko: Bool = false
    /// Подано из «Моего» — from: "my" (только статистика сервера).
    var изМоего: Bool = true

    init(название: String, раздел: String) {
        self.название = название
        self.раздел = раздел
    }

    /// qty: больше из «штук» и стандартов, 1…999.
    var сколько: Int {
        let изНабора: Int = стандарты?.сколько ?? 1
        let больше: Int = max(штук, изНабора)
        return max(1, min(999, больше))
    }

    /// relist_from годного вида или nil.
    var связь: String? {
        let чистый = источник.trimmingCharacters(in: .whitespacesAndNewlines)
        for префикс in ["deal:", "listing:"] where чистый.hasPrefix(префикс) {
            let номер = String(чистый.dropFirst(префикс.count))
            return СделкиAPI.годныйНомер(номер) ? префикс + номер : nil
        }
        return nil
    }

    /// Строка всех систем по размеру «Моего» («Размер: EU 42 · RU 41 · US M 9 · UK 8 · MEX 27 · 27 см»); таблица
    /// значения не знает — пусто.
    static func строкаРазмера(_ размер: РазмерМоего) -> String {
        guard let выбор = размер.выбор() else { return "" }
        return размер.вид.вкладка.строкаОписания(выбор)
    }

    /// Поля std, которые каталог держит числами (SERVER_STANDARDS.md §3.1: «числа — JSON-числами с точкой»).
    private static let числовыеПоля: Set<String> = [
        "height_cm", "width_cm", "door_clear_cm", "cm", "max_kg", "diag_min", "diag_max", "diag", "gb", "mts", "tb",
        "vram_gb", "length_mm", "watts", "gpu_max_mm", "fitted_h", "volt"
    ]

    /// std для submit: {семья: {поле: значение}}; числа — числами, остальное — строкой канона.
    static func телоСтандартов(_ набор: НаборСтандартов) -> [String: Any] {
        var итог: [String: Any] = [:]
        for семья in набор.семьи {
            var поля: [String: Any] = [:]
            for (поле, значение) in набор.поля(семья) {
                if числовыеПоля.contains(поле), let число = числоСтандарта(значение) {
                    поля[поле] = число
                } else {
                    поля[поле] = значение
                }
            }
            if !поля.isEmpty { итог[семья.rawValue] = поля }
        }
        return итог
    }

    private static func числоСтандарта(_ значение: String) -> NSNumber? {
        guard let x = Double(значение), x.isFinite else { return nil }
        if x == x.rounded() && abs(x) < 1_000_000 {
            let целое = Int(x)
            return NSNumber(value: целое)
        }
        return NSNumber(value: x)
    }
}

// MARK: - Ожидание: открыть мастер с заготовкой

/**
 Заготовка ждёт здесь, пока мастер не откроется: ПодачаМодель забирает её в начать() один раз. Не забрали за 30 с —
 забыто. Только память (на диск не пишется): значения «Моего» живут, пока идёт переход.
 */
@MainActor
enum ЖдущаяЗаготовкаПодачи {
    private static var ждёт: (заготовка: ЗаготовкаПодачи, когда: Date)? = nil
    static let срок: TimeInterval = 30

    /// Положить заготовку и открыть мастер новой подачи. false — мастер выключен или уже открыт: ничего не ждёт.
    @discardableResult
    static func открыть(_ заготовка: ЗаготовкаПодачи) -> Bool {
        guard Config.заготовкаПодачи, Config.нативнаяПодача, ПодачаОкно.shared.цель == nil else { return false }
        ждёт = (заготовка: заготовка, когда: Date())
        guard ПодачаОкно.shared.открыть(.новое) else {
            ждёт = nil
            return false
        }
        return true
    }

    /// Заготовка для только что открытого мастера (один раз) или nil.
    static func забрать() -> ЗаготовкаПодачи? {
        guard let есть = ждёт else { return nil }
        ждёт = nil
        guard Date().timeIntervalSince(есть.когда) < срок else { return nil }
        return есть.заготовка
    }

    static func забыть() {
        ждёт = nil
    }
}

// MARK: - Правила схемы подачи

/// Флаги схемы (api/app_post_schema.php, rules), от которых зависят поля заготовки в submit. Нет ключа — false.
struct ПравилаЗаготовкиПодачи: Equatable {
    /// rules.std.store: submit принимает std, std_src, qty — строку «Параметры: …» больше не пишем.
    var стандартыПолями = false
    /// rules.std.provenance: метка «Куплено на Kliko» (show_provenance).
    var меткаКуплено = false
    /// rules.circle.on и rules.circle.relist: relist_from, show_provenance, from: "my".
    var продатьСвоё = false

    static func из(_ правила: [String: Any]) -> ПравилаЗаготовкиПодачи {
        var итог = ПравилаЗаготовкиПодачи()
        if let std = правила["std"] as? [String: Any] {
            итог.стандартыПолями = логика(std["store"])
            итог.меткаКуплено = логика(std["provenance"])
        }
        if let круг = правила["circle"] as? [String: Any], логика(круг["on"]) {
            итог.продатьСвоё = логика(круг["relist"])
        }
        return итог
    }

    private static func логика(_ значение: Any?) -> Bool {
        if let b = значение as? Bool { return b }
        if let n = значение as? NSNumber { return n.boolValue }
        return false
    }
}

// MARK: - Строка «Параметры: …»

/**
 Пока сервер не хранит std (rules.std.store), стандарты — последней строкой описания, всегда по-русски, куски по line
 каталога через « · », «N шт» — qty (SERVER_STANDARDS.md §3.6): «Параметры: Цоколь E27», «Параметры: VESA 400x400 до
 50 кг», «Параметры: ОЗУ DDR4 SO-DIMM 8 ГБ 3200 · 2 шт». Её читает РазборСтандартов.строкаПараметров (слово продавца).
 */
enum СтрокаПараметровПодачи {
    static let начало = "Параметры:"
    /// Начала наших кусков — по ним строка узнаётся как «наша» (строку продавца «Параметры: отличные» не трогаем).
    private static let начала = ["Спальное место ", "Матрас ", "Бельё ", "Цоколь ", "VESA ", "Сокет ", "ОЗУ ",
                                 "Видеокарта ", "БП ", "Плата ", "SSD "]

    /// Строка набора; ни у одной семьи нет line каталога — nil.
    static func собрать(_ набор: НаборСтандартов) -> String? {
        var куски: [String] = []
        for семья in набор.семьи {
            if let к = кусок(семья, набор) { куски.append(к) }
        }
        guard !куски.isEmpty else { return nil }
        if набор.сколько > 1 { куски.append(String(набор.сколько) + " шт") }
        return начало + " " + куски.joined(separator: " · ")
    }

    private static func кусок(_ семья: СемьяСтандарта, _ н: НаборСтандартов) -> String? {
        typealias К = КлючСтандарта
        switch семья {
        case .спальноеМесто:
            return н[семья, К.размер].map { "Спальное место " + $0 }
        case .матрас:
            return н[семья, К.высотаМатраса].map { "Матрас \($0) см" }
        case .бельё:
            return н[семья, К.комплект].map { "Бельё " + $0 }
        case .цоколь:
            return н[семья, К.цоколь].map { "Цоколь " + $0 }
        case .vesa:
            guard let шаблон = н[семья, К.шаблон] else { return nil }
            guard let кг = н[семья, К.доКг] else { return "VESA \(шаблон)" }
            return "VESA \(шаблон) до \(кг) кг"
        case .сокет:
            return н[семья, К.сокет].map { "Сокет " + $0 }
        case .память:
            let объём: String? = н[семья, К.гб].map { $0 + " ГБ" }
            let части: [String?] = [н[семья, К.поколение], н[семья, К.форма], объём, н[семья, К.частота]]
            return склеить("ОЗУ", части)
        case .видеокарта:
            guard let чип = н[семья, К.чип] else { return nil }
            let память: String? = н[семья, К.памятьКарты].map { $0 + " ГБ" }
            return склеить("Видеокарта", [чип, память])
        case .блокПитания:
            guard let ватт = н[семья, К.ватт] else { return nil }
            var сертификат: String? = н[семья, К.сертификат]
            if сертификат == "none" { сертификат = nil }
            return склеить("БП", ["\(ватт) Вт", сертификат])
        case .формаПлаты:
            return н[семья, К.форма].map { "Плата " + $0 }
        case .накопитель:
            let протокол: String? = н[семья, К.протокол].map { показПротокола($0) }
            let поколение: String? = н[семья, К.pcie]
            var шина: String? = nil
            if let п = поколение { шина = п.contains(".") ? "PCIe \(п)" : "PCIe \(п).0" }
            let объём: String? = н[семья, К.тб].map { $0 + " ТБ" }
            return склеить("SSD", [н[семья, К.форма], протокол, шина, объём])
        case .шторы, .проём, .потолок, .диагональ, .расходник, .корпус, .размер:
            return nil
        }
    }

    private static func показПротокола(_ протокол: String) -> String {
        switch протокол.lowercased() {
        case "nvme": return "NVMe"
        case "sata": return "SATA"
        default: return протокол
        }
    }

    /// «ОЗУ» + непустые части через пробел; частей нет — nil.
    private static func склеить(_ имя: String, _ части: [String?]) -> String? {
        let есть: [String] = части.compactMap { $0 }.filter { !$0.isEmpty }
        guard !есть.isEmpty else { return nil }
        return имя + " " + есть.joined(separator: " ")
    }

    /// Наша строка: «Параметры:» и каждый кусок — наш (по началу или «N шт»).
    static func этоНаша(_ строка: String) -> Bool {
        let чистая = строка.trimmingCharacters(in: .whitespaces)
        guard чистая.hasPrefix(начало) else { return false }
        let хвост = String(чистая.dropFirst(начало.count))
        let куски: [String] = хвост.components(separatedBy: "·")
            .map { $0.trimmingCharacters(in: .whitespaces) }
            .filter { !$0.isEmpty }
        guard !куски.isEmpty else { return false }
        for кусок in куски {
            let нашНачалом = начала.contains { кусок.hasPrefix($0) }
            let штуки = кусок.hasSuffix(" шт") && Int(кусок.dropLast(3)) != nil
            if !нашНачалом && !штуки { return false }
        }
        return true
    }

    /// Описание без наших строк «Параметры: …» и без пустого хвоста.
    static func безСтроки(_ описание: String) -> String {
        let строки = описание.components(separatedBy: "\n")
        guard строки.contains(where: { этоНаша($0) }) else { return описание }
        let остаток: [String] = строки.filter { !этоНаша($0) }
        return ПравилаРазмераОдежды.безХвоста(остаток.joined(separator: "\n"))
    }

    /// Описание с нашей строкой последней: прежняя убирается, предел описания (5000) соблюдается.
    static func сСтрокой(_ описание: String, _ строка: String) -> String {
        var основа = ПравилаРазмераОдежды.безХвоста(безСтроки(описание))
        let нужно = строка.count + 2
        let предел = ПравилаРазмераОдежды.пределОписания
        if основа.count + нужно > предел {
            основа = ПравилаРазмераОдежды.безХвоста(String(основа.prefix(max(0, предел - нужно))))
        }
        return основа.isEmpty ? строка : основа + "\n\n" + строка
    }
}

// MARK: - Мастер: применить и отправить

extension ПодачаМодель {

    /// Начало новой подачи: чистая форма, потом — заготовка, если ждёт (начатьНовое, «Новое» в вопросе о черновике).
    func чистаяФормаСЗаготовкой() {
        let ждущая = заготовка
        чистаяФорма()
        guard let ждущая else { return }
        применитьЗаготовку(ждущая)
    }

    /**
     Заготовка → форма. Только новая подача, после чистаяФорма (гео, часы, гарант — уже из профиля). Поля ложатся при
     заполняем = true: подбор раздела с сервера, рынок и Kliko AI не запускаются. Экран — фото, дальше «Проверьте».
     */
    func применитьЗаготовку(_ з: ЗаготовкаПодачи) {
        guard !правка else { return }
        /* Прежнюю запись ИИ-фото уже снял открытьПервыйЭкран в чистаяФорма (PostingQuick.swift): применитьЗаготовку
           зовут только после неё. */
        заготовка = з
        заполняем = true
        let раздел = разделЗаготовки(з.раздел)
        if !раздел.isEmpty { выбратьРаздел(раздел) }
        форма.название = з.название.trimmingCharacters(in: .whitespacesAndNewlines)
        /* Подбор по названию — только на телефоне и пока заполняем (рынок не спрашивается): пустой раздел подставит
           уверенный, у заданного — чипы «Возможно: …» внутри него. */
        подобратьРазделПоНазванию()
        let марка = з.бренд.trimmingCharacters(in: .whitespacesAndNewlines)
        if брендВиден && !марка.isEmpty { форма.бренд = марка }
        if let состояние = з.состояние, состояние == "used" || состояние == "new" { форма.состояние = состояние }
        положитьЗапчастьЗаготовки(з)
        положитьХарактеристикиЗаготовки(з.характеристики)
        положитьГабаритыЗаготовки(з)
        положитьОписаниеЗаготовки(з)
        заполняем = false
        /* С фото — «Проверьте» короткого пути; Kliko AI не переписывает раздел и название из «Моего». */
        шаг = .фото
        быстрый = false
        быстроРаспознано = true
        мастер = nil
        экран = .камера
        запланироватьЧерновик()
        положитьФотоЗаготовки(з.фотоМоего)
    }

    /// Поля заготовки для тела submit — только по флагам схемы; нет заготовки или флагов — пусто.
    func поляЗаготовки() -> [String: Any] {
        guard !правка, let з = заготовка else { return [:] }
        let правила: ПравилаЗаготовкиПодачи = схема?.правилаЗаготовки ?? ПравилаЗаготовкиПодачи()
        var итог: [String: Any] = [:]
        if правила.стандартыПолями {
            var стандартыЕсть = false
            /* Шины и диски std не шлют: их значения — в parts (SERVER_STANDARDS.md §3.2). */
            if !колёсаВидны, let набор = з.стандарты, !набор.пусто {
                let std = ЗаготовкаПодачи.телоСтандартов(набор)
                if !std.isEmpty {
                    /* «deal» — только в «Моём», в submit не приходит: значения подтверждает продавец (""). */
                    let откуда: String = набор.источник == .сделка ? "" : набор.источник.rawValue
                    итог["std"] = std
                    итог["std_src"] = откуда
                    стандартыЕсть = true
                }
            }
            let штук = з.сколько
            if стандартыЕсть || штук > 1 { итог["qty"] = штук }
        }
        if правила.продатьСвоё {
            if з.изМоего { итог["from"] = "my" }
            if let связь = з.связь {
                итог["relist_from"] = связь
                if правила.меткаКуплено && з.показатьКупленоНаKliko && связь.hasPrefix("deal:") {
                    итог["show_provenance"] = true
                }
            }
        }
        return итог
    }

    // MARK: Части

    /// Раздел заготовки, если форма его знает и умеет: товары и запчасти; цифровое, услуги, работа, недвижимость и
    /// транспорт кроме запчастей — пусто (человек выберет сам).
    private func разделЗаготовки(_ ключ: String) -> String {
        let чистый = ключ.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !чистый.isEmpty, справочники.разделы[чистый] != nil else { return "" }
        if справочники.внутри(чистый, [ЦифровыеТовары.корень, "services", "jobs", "realty"]) { return "" }
        if справочники.внутри(чистый, ["transport"]) && !справочники.внутри(чистый, ["auto-parts"]) { return "" }
        return чистый
    }

    /// Шины и диски: вид («Шины | Диски») и поля мастера запчастей; чужие поля вида и незнакомые — прочь.
    private func положитьЗапчастьЗаготовки(_ з: ЗаготовкаПодачи) {
        guard режим == .запчасти, !з.запчасть.isEmpty else { return }
        var свои: Set<String> = []
        if колёсаВидны {
            let поПолям = СтрокиКолёсПодачи.толькоДисков.contains { !(з.запчасть[$0] ?? "").isEmpty }
            let диски: Bool = з.диски ?? поПолям
            выбратьКолёса(диски: диски)
            var ключи: [String] = диски ? СтрокиКолёсПодачи.ключиДисков : СтрокиКолёсПодачи.ключиШин
            let толькоВида: [String] = диски ? СтрокиКолёсПодачи.толькоДисков : СтрокиКолёсПодачи.толькоШин
            ключи.append(contentsOf: толькоВида)
            свои = Set(ключи)
        }
        let поляВида: [ПолеМастера] = поляЗапчасти
        for поле in поляВида { свои.insert(поле.id) }
        var итог = форма.запчасть
        for (ключ, сырое) in з.запчасть where свои.contains(ключ) && ключ != "kind" {
            let поле: ПолеМастера? = поляВида.first { $0.id == ключ }
            if let значение = значениеЗапчасти(поле, сырое) { итог[ключ] = значение }
        }
        if итог != форма.запчасть { форма.запчасть = итог }
    }

    private func значениеЗапчасти(_ поле: ПолеМастера?, _ сырое: String) -> String? {
        let чистое = сырое.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !чистое.isEmpty else { return nil }
        let короткое = ПределыПодачи.обрезать(чистое, ПределыПодачи.короткое)
        guard let поле else { return короткое }
        switch поле.вид {
        case "select", "chips":
            guard !поле.варианты.isEmpty else { return короткое }
            return вариантЗаготовки(чистое, поле.варианты)
        case "num":
            let число = чистое.replacingOccurrences(of: ",", with: ".")
            return Double(число) == nil ? nil : число
        case "toggle":
            return ["1", "true", "да", "yes"].contains(чистое.lowercased()) ? "1" : nil
        default:
            return короткое
        }
    }

    /// Слоты характеристик: только те, что у раздела есть на экране, и значения, которые поле принимает.
    private func положитьХарактеристикиЗаготовки(_ значения: [String: String]) {
        guard !значения.isEmpty else { return }
        let поляРаздела: [ПолеХарактеристики] = характеристики
        for (слот, сырое) in значения where СхемаПодачи.слоты.contains(слот) {
            guard let поле = поляРаздела.first(where: { $0.поле == слот }),
                  let значение = значениеХарактеристикиЗаготовки(поле, сырое) else { continue }
            switch слот {
            case "cpu": форма.cpu = значение
            case "gpu": форма.gpu = значение
            case "ram": форма.ram = значение
            case "storage": форма.storage = значение
            case "year": форма.year = значение
            default: break
            }
        }
    }

    private func значениеХарактеристикиЗаготовки(_ поле: ПолеХарактеристики, _ сырое: String) -> String? {
        let чистое = сырое.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !чистое.isEmpty else { return nil }
        if поле.год {
            let год = ПодачаМодель.цифры(чистое, предел: 4)
            return ПределыПодачи.годы.contains(год) ? год : nil
        }
        if поле.вводом {
            guard поле.числом else { return чистое }
            let число = чистое.replacingOccurrences(of: ",", with: ".")
            return Double(число) == nil ? nil : число
        }
        if let найдено = вариантЗаготовки(чистое, поле.вариантыСПодписью) { return найдено }
        return поле.своё ? чистое : nil
    }

    /// Ключ варианта по ключу или подписи (без регистра); нет — nil.
    private func вариантЗаготовки(_ значение: String, _ варианты: [ВариантПоля]) -> String? {
        if let точный = варианты.first(where: { $0.ключ == значение }) { return точный.ключ }
        let нужное = значение.lowercased()
        let похожий: ВариантПоля? = варианты.first { $0.ключ.lowercased() == нужное || $0.подпись.lowercased() == нужное }
        return похожий?.ключ
    }

    /// Габариты Ш×В×Г — у шин и дисков блок свой (вид «Шины | Диски» не трогаем).
    private func положитьГабаритыЗаготовки(_ з: ЗаготовкаПодачи) {
        guard !колёсаВидны else { return }
        let ш: String = сантиметрыЗаготовки(з.ширина)
        let в: String = сантиметрыЗаготовки(з.высота)
        let г: String = сантиметрыЗаготовки(з.глубина)
        guard !ш.isEmpty || !в.isEmpty || !г.isEmpty else { return }
        var габариты = форма.габариты ?? ГабаритыПодачи()
        габариты.ширина = ш
        габариты.высота = в
        габариты.глубина = г
        /* Значения человека из «Моего» — как введённые им самим (не «примерно»). */
        габариты.источник = ""
        форма.габариты = габариты
    }

    private func сантиметрыЗаготовки(_ значение: Int?) -> String {
        guard let значение, значение > 0 else { return "" }
        return String(min(значение, 1000))
    }

    /**
     Описание: своё заготовки, строка «Размер: …» (если раздел — одежда или обувь и таблица узнала размер; пустое поле
     размера сайта — тем же выбором) и строка «Параметры: …» (пока сервер не хранит std).
     */
    private func положитьОписаниеЗаготовки(_ з: ЗаготовкаПодачи) {
        let своё: String = з.описание.trimmingCharacters(in: .whitespacesAndNewlines)
        let впределе = String(своё.prefix(ПравилаРазмераОдежды.пределОписания))
        var текст: String = ПравилаРазмераОдежды.безХвоста(впределе)
        let размер = з.размерВсехСистем.trimmingCharacters(in: .whitespacesAndNewlines)
        if !размер.isEmpty, let набор = наборРазмеровОдежды {
            var строка: String = размер
            if СтрокаРазмераВсехСистем.разобрать(строка) == nil { строка = ПравилаРазмераОдежды.начало + " " + размер }
            if let выбор = ПравилаРазмераОдежды.найти(строка, в: набор), let вкладка = набор.вкладка(выбор.вкладка) {
                текст = ПравилаРазмераОдежды.сСтрокой(текст, вкладка.строкаОписания(выбор))
                if форма.storage.isEmpty, let поле = полеРазмераОдежды,
                   let значение = ПравилаРазмераОдежды.значениеПоля(вкладка, выбор, поле) {
                    форма.storage = значение
                }
            }
        }
        let хранятся: Bool = схема?.правилаЗаготовки.стандартыПолями ?? false
        if !хранятся, !колёсаВидны, let набор = з.стандарты, let строка = СтрокаПараметровПодачи.собрать(набор) {
            текст = СтрокаПараметровПодачи.сСтрокой(текст, строка)
        }
        форма.описание = текст
    }

    /**
     Фото вещи из «Моего»: файлы читаются не на главной и ждут в памяти (фотоЗаготовки). На сервер (upload_photo) они
     уходят только по нажатию «Добавить фото вещи из «Моего»» на экране камеры: продавец их сам не выбирал, а закрытая
     подача оставила бы файл на сервере. Плашка — после чтения.
     */
    private func положитьФотоЗаготовки(_ имена: [String]) {
        let места = местоФото
        let адреса: [URL] = имена.prefix(места).compactMap { ФайлыМоего.адресФото($0) }
        guard !адреса.isEmpty else {
            показать(ЗаготовкаПодачиText.т("prf_filled"))
            return
        }
        Task { @MainActor [weak self] in
            let данные: [Data] = await Task.detached(priority: .userInitiated) { () -> [Data] in
                адреса.compactMap { try? Data(contentsOf: $0) }
            }.value
            guard let модель = self, модель.заготовка != nil else { return }
            модель.фотоЗаготовки = данные
            модель.показать(ЗаготовкаПодачиText.т(данные.isEmpty ? "prf_filled" : "prf_filled_photo"))
        }
    }

    /// «Добавить фото вещи из «Моего»» на экране камеры: только теперь фото уходят на сервер — тем же путём, что выбор
    /// из галереи (сколько осталось места).
    func добавитьФотоЗаготовки() {
        let место: Int = местоФото
        let данные: [Data] = Array(фотоЗаготовки.prefix(место))
        фотоЗаготовки = []
        guard !данные.isEmpty else { return }
        Task<Void, Never> { @MainActor [weak self] () -> Void in
            guard let модель = self else { return }
            await модель.загрузитьНовые(данные)
        }
    }

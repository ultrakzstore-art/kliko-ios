extension ПодачаМодель {
    /**
     _rshPlanKey / _rshHead сайта: недвижимость — по виду и сделке; транспорт — по группе раздела вверх по дереву; товар и
     «Сдать вещь» — по GOODS_SHOT_BY_CAT, чипу старта или общий совет. У услуги и работы плана нет.
     */
    var планСъёмки: ПланСъёмки.План? {
        let т = МастерПодачиText.т
        if режим == .услуга || режим == .работа { return nil }
        if режим == .недвижимость {
            let вид = ["apartment", "house", "commercial", "land"].contains(форма.вид) ? форма.вид : "apartment"
            let сдаю = форма.сделка == "rent" || форма.аренда
            let сделка = сдаю ? "rent" : "sale"
            let кадры = ПланСъёмки.жильё[вид + "|" + сделка] ?? []
            let заголовок = т("rsh_h") + " · " + т("rk_" + вид) + (сдаю ? т("rsh_rent_tail") : "")
            return ПланСъёмки.План(заголовок: заголовок, совет: ПланСъёмки.совет("realty_" + вид + "_" + сделка),
                                   кадры: кадры.map { ПланСъёмки.кадр($0) },
                                   ключи: ПланСъёмки.ключи(ПланСъёмки.ключиЖилья[вид + "|" + сделка], кадры.count),
                                   кадрыRu: кадры, группа: "realty")
        }
        var узел: String? = форма.раздел.isEmpty ? nil : форма.раздел
        var шаги = 0
        while let к = узел, шаги < 12 {
            if let кадры = ПланСъёмки.авто[к] {
                let имя = справочники.имя(к)
                let заголовок = т("rsh_h") + (имя.isEmpty ? "" : " · " + имя)
                return ПланСъёмки.План(заголовок: заголовок, совет: ПланСъёмки.совет("auto_" + к),
                                       кадры: кадры.map { ПланСъёмки.кадр($0) },
                                       ключи: ПланСъёмки.ключи(ПланСъёмки.ключиАвто[к], кадры.count),
                                       кадрыRu: кадры, группа: к)
            }
            узел = справочники.разделы[к]?.родитель
            шаги += 1
        }
        guard ["goods", "rentgood", ""].contains(форма.тип) else { return nil }
        var вид = ""
        if форма.тип == "rentgood" {
            вид = "rent"
        } else {
            узел = форма.раздел.isEmpty ? nil : форма.раздел
            шаги = 0
            while let к = узел, шаги < 12, вид.isEmpty {
                if let найден = ПланСъёмки.видПоРазделу[к], ПланСъёмки.товары[найден] != nil { вид = найден }
                узел = справочники.разделы[к]?.родитель
                шаги += 1
            }
            if вид.isEmpty { вид = ПланСъёмки.видПоПодсказке[форма.подсказка] ?? "other" }
        }
        guard let кадры = ПланСъёмки.товары[вид] else { return nil }
        var имя = ""
        switch вид {
        case "rent", "phone", "laptop", "clothes", "shoes", "furniture", "appliance", "building":
            имя = т("gh_" + вид)
        default:
            имя = корень.isEmpty ? "" : справочники.имя(корень)
        }
        let заголовок = т("rsh_h") + (имя.isEmpty ? "" : " · " + имя)
        return ПланСъёмки.План(заголовок: заголовок, совет: ПланСъёмки.совет("goods_" + вид),
                               кадры: кадры.map { ПланСъёмки.кадр($0) },
                               ключи: ПланСъёмки.ключи(ПланСъёмки.ключиТоваров[вид], кадры.count),
                               кадрыRu: кадры, группа: вид)
    }

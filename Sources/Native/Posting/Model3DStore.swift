@MainActor
final class ХранилищеОбзора3DПодачи: ObservableObject {
    static let shared = ХранилищеОбзора3DПодачи()

    /// Растёт при каждой записи: экраны перечитывают себя.
    @Published private(set) var версия = 0
    /// Цели, чьи ракурсы сейчас уходят на сервер.
    @Published private(set) var загружаем: Set<String> = []
    /// Цели, у которых start в пути.
    @Published private(set) var запускаем: Set<String> = []
    /// Заминка опроса по цели: «долго» или «нет связи» — опрос стоит до «Проверить ещё раз».
    @Published private(set) var заминка: [String: String] = [:]
    /// Отказ загрузки ракурса по цели (не сеть): «переснимите ракурс 3».
    @Published private(set) var отказЗагрузки: [String: ОтказРакурсаОбзора3DПодачи] = [:]
    /// Правка: 3D-обзор объявления убран («Убрать из объявления») — до закрытия приложения.
    @Published private(set) var убраноИзОбъявлений: Set<String> = []

    private var записи: [String: ЗаписьОбзора3DПодачи] = [:]
    private var кто = ""
    private var прочитано = false
    private var прибрано = false
    private var опросы: [String: Task<Void, Never>] = [:]
    private var загрузки: [String: Task<Bool, Never>] = [:]
    private var привязки: [String: Task<Void, Never>] = [:]
    private var слежка: [ObjectIdentifier: (подача: СлабаяПодачаОбзора3D, подписка: AnyCancellable)] = [:]
    private var встреченные: [СлабаяПодачаОбзора3D] = []

    private static let ключ = "kliko.model3d.posting.v1"
    /// Ключ записи, которая доводит attach к уже опубликованному новому объявлению: «attach:<id>».
    private static let префиксПривязки = "attach:"
    /// Как у черновика подачи — 7 дней.
    private static let срок: TimeInterval = 7 * 24 * 3600
    /// Опрос status: раз в 3 с, до 10 минут.
    private static let шагОпроса: UInt64 = 3_000_000_000
    private static let пределОпроса: TimeInterval = 600

    private init() {}

    private func т(_ ключ: String) -> String { Обзор3DПодачиText.т(ключ) }

    func ключЦели(_ подача: ПодачаМодель) -> String { подача.цель.id }

    /// Кто подаёт: uid страницы кабинета подачи, иначе id сессии приложения; пусто — ещё не знаем.
    private func ктоПодаёт(_ подача: ПодачаМодель) -> String {
        let uid = подача.страница.состояние?.uid ?? ""
        return uid.isEmpty ? СессияПриложения.shared.id : uid
    }

    // MARK: - Чтение и запись

    /**
     Записи с телефона — один раз на человека; сменился человек — чужие записи не показываем и стираем (и их файлы).
     Пока не знаем, кто это (пустой id), — записи только в памяти.
     */
    private func прочитать(_ подача: ПодачаМодель) {
        let сейчас = ктоПодаёт(подача)
        if кто == сейчас && (прочитано || сейчас.isEmpty) { return }
        /* Записи, сделанные, пока человек был не известен, — его же: остаются поверх прочитанных. */
        let безИмени = кто.isEmpty ? записи : [:]
        if !кто.isEmpty && кто != сейчас { остановитьВсё() }
        записи = [:]
        кто = сейчас
        guard !сейчас.isEmpty else {
            прочитано = false
            return
        }
        прочитано = true
        defer {
            for (ключ, запись) in безИмени where записи[ключ] == nil { записи[ключ] = запись }
            прибратьФайлы()
        }
        guard let данные = UserDefaults.standard.data(forKey: Self.ключ),
              let снимок = try? JSONDecoder().decode(СнимокХранилищаОбзора3DПодачи.self, from: данные) else { return }
        guard снимок.кто == сейчас else {
            UserDefaults.standard.removeObject(forKey: Self.ключ)
            return
        }
        let граница = Date().timeIntervalSince1970 - Self.срок
        for (ключ, запись) in снимок.записи where запись.время > граница && ФайлыОбзора3DПодачи.годный(запись.папка)
            && ФайлыОбзора3DПодачи.годный(запись.черновик) {
            var з = запись
            if з.ракурсы.count != РакурсОбзора3DПодачи.всего {
                let прежние = з.ракурсы
                з.ракурсы = (0..<РакурсОбзора3DПодачи.всего).map { номер in
                    прежние.indices.contains(номер) ? прежние[номер] : РакурсЗаписиОбзора3DПодачи()
                }
            }
            /* «new», ждущая attach (записана до переноса под свой ключ), — под «attach:<id>»: «new» — новой подаче. */
            if ключ == ЦельПодачи.новое.id && !з.привязать.isEmpty {
                записи[Self.префиксПривязки + з.привязать] = з
                continue
            }
            записи[ключ] = з
        }
    }

    private func записать() {
        guard !кто.isEmpty else { return }
        guard !записи.isEmpty else {
            UserDefaults.standard.removeObject(forKey: Self.ключ)
            return
        }
        if let данные = try? JSONEncoder().encode(СнимокХранилищаОбзора3DПодачи(кто: кто, записи: записи)) {
            UserDefaults.standard.set(данные, forKey: Self.ключ)
        }
    }

    /// Папки черновиков, которых нет в записях, — прочь (один раз за запуск, в фоне).
    private func прибратьФайлы() {
        guard !прибрано else { return }
        прибрано = true
        let оставить = Set(записи.values.map { $0.папка })
        Task.detached(priority: .background) { ФайлыОбзора3DПодачи.прибрать(оставить: оставить) }
    }

    /// сохранить: false — только ход сборки (проценты, этап): экран обновится, а в UserDefaults снимок не пишется на
    /// каждый процент (после перезапуска опрос всё равно спросит status заново).
    private func изменить(_ ключ: String, сохранить: Bool = true, _ правка: (inout ЗаписьОбзора3DПодачи) -> Void) {
        guard var з = записи[ключ] else { return }
        правка(&з)
        з.время = Date().timeIntervalSince1970
        записи[ключ] = з
        if сохранить { записать() }
        версия += 1
    }

    private func остановитьВсё() {
        for задача in опросы.values { задача.cancel() }
        for задача in загрузки.values { задача.cancel() }
        for задача in привязки.values { задача.cancel() }
        опросы = [:]
        загрузки = [:]
        привязки = [:]
        /* Опубликованное трогаем, только если в нём что-то есть: чтение хранилища бывает и из body. */
        if !заминка.isEmpty { заминка = [:] }
        if !отказЗагрузки.isEmpty { отказЗагрузки = [:] }
        if !загружаем.isEmpty { загружаем = [] }
        if !запускаем.isEmpty { запускаем = [] }
    }

    func запись(_ подача: ПодачаМодель) -> ЗаписьОбзора3DПодачи? {
        прочитать(подача)
        return записи[ключЦели(подача)]
    }

    /// Запись по ключу цели — для экранов, которые уже прочитали хранилище через подачу.
    func запись(ключ: String) -> ЗаписьОбзора3DПодачи? { записи[ключ] }

    // MARK: - Съёмка

    /// Случайный draft_id: «d_» и 32 шестнадцатеричных знака (128 бит).
    static func новыйЧерновик() -> String {
        var генератор = SystemRandomNumberGenerator()
        var итог = "d_"
        for _ in 0..<16 {
            let байт = UInt8.random(in: 0...255, using: &генератор)
            let знаки = String(байт, radix: 16)
            итог += знаки.count == 1 ? "0" + знаки : знаки
        }
        return итог
    }

    /// Запись цели для съёмки: нет — новая с новым draft_id. Вид меняется вслед за разделом, пока модели нет.
    @discardableResult
    func начать(_ подача: ПодачаМодель, вид: ВидОбзора3DПодачи) -> ЗаписьОбзора3DПодачи {
        прочитать(подача)
        let ключ = ключЦели(подача)
        if let з = записи[ключ] {
            if з.вид != вид.rawValue && з.задача.isEmpty && !з.готова {
                изменить(ключ) { $0.вид = вид.rawValue }
            }
            return записи[ключ] ?? з
        }
        var з = ЗаписьОбзора3DПодачи()
        з.черновик = Self.новыйЧерновик()
        з.папка = з.черновик
        з.вид = вид.rawValue
        з.время = Date().timeIntervalSince1970
        записи[ключ] = з
        записать()
        версия += 1
        return з
    }

    /**
     Ракурс снят и уже лежит в файлах: запись помнит его, прежняя модель сбрасывается (она про прежние кадры), правке
     снова нужно «Сохранить в объявление», ракурс уходит на сервер.
     */
    func принятьРакурс(_ подача: ПодачаМодель, _ р: РакурсОбзора3DПодачи, файл: String, исходник: String, вырезан: Bool) {
        прочитать(подача)
        let ключ = ключЦели(подача)
        guard записи[ключ] != nil else { return }
        сброситьМодель(ключ)
        if отказЗагрузки[ключ]?.ракурс == р.rawValue { отказЗагрузки[ключ] = nil }
        изменить(ключ) { з in
            з.ракурсы[р.rawValue] = РакурсЗаписиОбзора3DПодачи(файл: файл, исходник: исходник, вырезан: вырезан, адрес: "",
                                                                снят: Date().timeIntervalSince1970)
            з.привязано = ""
        }
        загрузить(ключ)
    }

    /// Миниатюры ракурсов записи из файлов (в фоне). Файла нет — ракурса нет в словаре: вид покажет адрес сервера.
    nonisolated static func миниатюры(_ з: ЗаписьОбзора3DПодачи, сторона: Int) async -> КадрыОбзора3DПодачи {
        let папка = з.папка
        let ракурсы = з.ракурсы
        return await Task.detached(priority: .userInitiated) { () -> КадрыОбзора3DПодачи in
            var кадры = КадрыОбзора3DПодачи()
            for (номер, р) in ракурсы.enumerated() where !р.файл.isEmpty {
                if Task.isCancelled { break }
                guard let данные = ФайлыОбзора3DПодачи.прочитать(папка: папка, имя: р.файл),
                      let картинка = КартинкиОбзора3DПодачи.миниатюра(данные, сторона: сторона) else { continue }
                кадры.картинки[номер] = картинка
            }
            return кадры
        }.value
    }

    // MARK: - Загрузка ракурсов

    /**
     Незагруженные ракурсы цели — на сервер по одному (upload_angle). Уже идёт — та же задача: она сама берёт и ракурсы,
     снятые по ходу. true — все снятые загружены. Сеть — стоп (продолжит следующий повод: съёмка, «Собрать 3D»,
     публикация, шаг «Фото»). Отказ сервера по кадру — отказЗагрузки: «переснимите».
     */
    @discardableResult
    private func загрузить(_ ключ: String) -> Task<Bool, Never> {
        if let идёт = загрузки[ключ] { return идёт }
        let поколение = СессияПриложения.shared.поколение
        let задача = Task { @MainActor [weak self] () -> Bool in
            guard let self else { return false }
            self.загружаем.insert(ключ)
            let итог = await self.загружатьПоОдному(ключ, поколение: поколение)
            self.загружаем.remove(ключ)
            self.загрузки[ключ] = nil
            return итог
        }
        загрузки[ключ] = задача
        return задача
    }

    private func загружатьПоОдному(_ ключ: String, поколение: Int) async -> Bool {
        var сменили = false
        while !Task.isCancelled {
            guard поколение == СессияПриложения.shared.поколение, let з = записи[ключ] else { return false }
            guard let номер = з.ракурсы.firstIndex(where: { !$0.файл.isEmpty && $0.адрес.isEmpty }),
                  let ракурс = РакурсОбзора3DПодачи(rawValue: номер) else { return true }
            let р = з.ракурсы[номер]
            let черновик = з.черновик
            let папка = з.папка
            let исходники = ГотовностьОбзора3DПодачи.shared.сведения?.исходники == true
            let тела = await Task.detached(priority: .utility) { () -> (картинка: String, исходник: String?)? in
                guard let данные = ФайлыОбзора3DПодачи.прочитать(папка: папка, имя: р.файл) else { return nil }
                var исходник: String? = nil
                if исходники, let jpeg = ФайлыОбзора3DПодачи.прочитать(папка: папка, имя: р.исходник) {
                    исходник = "data:image/jpeg;base64," + jpeg.base64EncodedString()
                }
                return (КартинкиОбзора3DПодачи.адрес(данные, вырезан: р.вырезан), исходник)
            }.value
            if Task.isCancelled { return false }
            guard let тела else {
                /* Файла нет (система почистила Caches): ракурс снова неснятый — его покажут к пересъёмке. */
                if записи[ключ]?.ракурсы[номер].снят == р.снят {
                    изменить(ключ) { $0.ракурсы[номер] = РакурсЗаписиОбзора3DПодачи() }
                }
                continue
            }
            let ответ = await Обзор3DПодачиAPI.загрузитьРакурс(черновик: черновик, вид: з.видОбзора, ракурс: ракурс,
                                                              картинка: тела.картинка, вырезан: р.вырезан,
                                                              исходник: тела.исходник)
            guard поколение == СессияПриложения.shared.поколение, записи[ключ]?.черновик == черновик else { return false }
            switch ответ {
            case .готово(let j):
                let адрес = МоиОбъявленияAPI.строка(j["url"]).trimmingCharacters(in: .whitespacesAndNewlines)
                guard ХодПримерочной.адрес(адрес) != nil else {
                    отказЗагрузки[ключ] = ОтказРакурсаОбзора3DПодачи(
                        ракурс: номер, отказ: ОтказОбзора3DПодачи(код: "fail", текст: т("m3_err_fail")))
                    return false
                }
                /* Кадр пересняли, пока он шёл, — адрес прежнего не берём: новый уйдёт следующим кругом. */
                if записи[ключ]?.ракурсы[номер].снят == р.снят {
                    изменить(ключ) { $0.ракурсы[номер].адрес = адрес }
                }
            case .отказ(let о) where о.код == "gone" && !сменили:
                /* Сервер забыл черновик (сутки без публикации) — новый, и все ракурсы уходят заново из файлов. */
                сменили = true
                сменитьЧерновик(ключ)
            case .отказ(let о):
                отказЗагрузки[ключ] = ОтказРакурсаОбзора3DПодачи(ракурс: номер, отказ: о)
                return false
            case .нетСервера:
                ГотовностьОбзора3DПодачи.shared.отметитьНетСервера()
                return false
            case .нуженВход, .сеть, .сбой:
                return false
            }
        }
        return false
    }

    /// Новый draft_id записи: адреса ракурсов и сборка забываются (на сервере их уже нет), файлы остаются в той же
    /// папке и уходят заново. Ракурс без файла (система почистила Caches) станет неснятым — его переснимут.
    private func сменитьЧерновик(_ ключ: String) {
        опросы[ключ]?.cancel()
        опросы[ключ] = nil
        заминка[ключ] = nil
        изменить(ключ) { з in
            з.черновик = Self.новыйЧерновик()
            for номер in з.ракурсы.indices { з.ракурсы[номер].адрес = "" }
            з.задача = ""
            з.состояние = ""
            з.прогресс = 0
            з.этап = ""
            з.постер = ""
            з.usdz = ""
            з.glb = ""
            з.отказКод = ""
            з.отказТекст = ""
        }
    }

    // MARK: - Сборка

    /// «Собрать 3D»: ракурсы догружаются, потом start с габаритами и подсказкой; дальше — опрос.
    func собрать(_ подача: ПодачаМодель) {
        прочитать(подача)
        let ключ = ключЦели(подача)
        guard let з = записи[ключ], з.всеСняты, !запускаем.contains(ключ), !з.собирается else { return }
        let вид = з.видОбзора
        let габариты = вид == .вещь && подача.нужныГабариты ? подача.габаритыФормы.полные : nil
        let ф = подача.форма
        var подсказка: [String: String] = ["category": ф.раздел, "title": ф.название]
        if вид == .машина {
            подсказка["brand"] = ф.бренд
            подсказка["model"] = ф.модель
            подсказка["year"] = ф.year
        }
        let поколение = СессияПриложения.shared.поколение
        запускаем.insert(ключ)
        заминка[ключ] = nil
        изменить(ключ) { з in
            з.состояние = ""
            з.отказКод = ""
            з.отказТекст = ""
        }
        Task { @MainActor [weak self] in
            guard let self else { return }
            defer { self.запускаем.remove(ключ) }
            for попытка in 0..<2 {
                let загружено = await self.загрузить(ключ).value
                guard поколение == СессияПриложения.shared.поколение, let готовая = self.записи[ключ] else { return }
                guard загружено, готовая.всеЗагружены else {
                    if let отказ = self.отказЗагрузки[ключ]?.отказ {
                        self.отказатьСборке(ключ, отказ)
                    } else {
                        self.отказатьСборке(ключ, ОтказОбзора3DПодачи(код: "net", текст: self.т("m3_err_net")))
                    }
                    return
                }
                let ответ = await Обзор3DПодачиAPI.начать(черновик: готовая.черновик, вид: вид,
                                                         ракурсы: готовая.ракурсы.map { $0.адрес },
                                                         габариты: габариты, подсказка: подсказка)
                guard поколение == СессияПриложения.shared.поколение, self.записи[ключ]?.черновик == готовая.черновик
                else { return }
                switch ответ {
                case .готово(let j):
                    let номер = МоиОбъявленияAPI.строка(j["job"]).trimmingCharacters(in: .whitespacesAndNewlines)
                    guard !номер.isEmpty else {
                        self.отказатьСборке(ключ, ОтказОбзора3DПодачи(код: "fail", текст: self.т("m3_err_fail")))
                        return
                    }
                    if j["left"] != nil { ГотовностьОбзора3DПодачи.shared.осталось(МоиОбъявленияAPI.целое(j["left"])) }
                    self.изменить(ключ) { з in
                        з.задача = номер
                        з.состояние = "queued"
                        з.прогресс = 0
                        з.этап = ""
                    }
                    self.опрашивать(ключ)
                    return
                case .отказ(let о) where о.код == "gone" && попытка == 0:
                    /* Черновик истёк на сервере — новый, ракурсы заново, и ещё один start. */
                    self.сменитьЧерновик(ключ)
                    continue
                case .отказ(let о):
                    self.отказатьСборке(ключ, о)
                case .нуженВход:
                    self.отказатьСборке(ключ, ОтказОбзора3DПодачи(код: "auth", текст: self.т("m3_err_login")))
                case .нетСервера:
                    ГотовностьОбзора3DПодачи.shared.отметитьНетСервера()
                    self.отказатьСборке(ключ, ОтказОбзора3DПодачи(код: "unsupported", текст: self.т("m3_soon")))
                case .сеть:
                    self.отказатьСборке(ключ, ОтказОбзора3DПодачи(код: "net", текст: self.т("m3_err_net")))
                case .сбой:
                    self.отказатьСборке(ключ, ОтказОбзора3DПодачи(код: "fail", текст: self.т("m3_err_fail")))
                }
                return
            }
        }
    }

    private func отказатьСборке(_ ключ: String, _ о: ОтказОбзора3DПодачи) {
        опросы[ключ]?.cancel()
        опросы[ключ] = nil
        /* Сервер назвал плохой ракурс — он подсвечивается, как при отказе загрузки; пересняли — отметка снимается. */
        if о.переснять, let номер = о.ракурс {
            отказЗагрузки[ключ] = ОтказРакурсаОбзора3DПодачи(ракурс: номер, отказ: о)
        }
        изменить(ключ) { з in
            з.состояние = "failed"
            з.отказКод = о.код
            з.отказТекст = о.текст
        }
    }

    /// status раз в 3 с до 10 минут; связь пропала 5 раз подряд или долго — заминка, опрос стоит до «Проверить ещё раз».
    private func опрашивать(_ ключ: String) {
        опросы[ключ]?.cancel()
        guard let з = записи[ключ], !з.задача.isEmpty else { return }
        let номер = з.задача
        let поколение = СессияПриложения.shared.поколение
        заминка[ключ] = nil
        опросы[ключ] = Task { @MainActor [weak self] in
            let начало = Date()
            var сбоев = 0
            while !Task.isCancelled {
                try? await Task.sleep(nanoseconds: Self.шагОпроса)
                guard let self, !Task.isCancelled, поколение == СессияПриложения.shared.поколение,
                      self.записи[ключ]?.задача == номер else { return }
                if Date().timeIntervalSince(начало) > Self.пределОпроса {
                    self.остановитьОпрос(ключ, заминка: self.т("m3_slow"))
                    return
                }
                let ответ = await Обзор3DПодачиAPI.ход(номер)
                guard !Task.isCancelled, поколение == СессияПриложения.shared.поколение,
                      self.записи[ключ]?.задача == номер else { return }
                switch ответ {
                case .готово(let j):
                    сбоев = 0
                    if self.заминка[ключ] != nil { self.заминка[ключ] = nil }
                    if self.принятьХод(ключ, ХодОбзора3DПодачи(j), j) {
                        self.опросы[ключ] = nil
                        return
                    }
                case .сеть, .сбой:
                    сбоев += 1
                    if сбоев >= 5 {
                        self.остановитьОпрос(ключ, заминка: self.т("m3_err_net_poll"))
                        return
                    }
                case .отказ(let о):
                    self.отказатьСборке(ключ, о)
                    return
                case .нуженВход:
                    self.остановитьОпрос(ключ, заминка: self.т("m3_err_login"))
                    return
                case .нетСервера:
                    ГотовностьОбзора3DПодачи.shared.отметитьНетСервера()
                    self.отказатьСборке(ключ, ОтказОбзора3DПодачи(код: "unsupported", текст: self.т("m3_soon")))
                    return
                }
            }
        }
    }

    private func остановитьОпрос(_ ключ: String, заминка текст: String) {
        опросы[ключ]?.cancel()
        опросы[ключ] = nil
        заминка[ключ] = текст
    }

    /// Ход сборки: проценты не убывают; done — файлы модели; failed — отказ. true — опрос окончен.
    private func принятьХод(_ ключ: String, _ ход: ХодОбзора3DПодачи, _ j: [String: Any]) -> Bool {
        switch ход.состояние {
        case .done:
            guard ход.usdz != nil || ход.glb != nil else {
                отказатьСборке(ключ, ОтказОбзора3DПодачи(код: "fail", текст: т("m3_err_fail")))
                return true
            }
            изменить(ключ) { з in
                з.состояние = "done"
                з.прогресс = 100
                з.этап = ""
                з.usdz = ход.usdz?.absoluteString ?? ""
                з.glb = ход.glb?.absoluteString ?? ""
                з.постер = ход.постер?.absoluteString ?? ""
            }
            ОткликСайта.успех()
            return true
        case .failed:
            if case .отказ(let о) = Обзор3DПодачиAPI.разобратьОтказ(j) {
                отказатьСборке(ключ, о)
            } else {
                отказатьСборке(ключ, ОтказОбзора3DПодачи(код: "fail", текст: т("m3_err_fail")))
            }
            return true
        case .queued, .working:
            guard let з = записи[ключ] else { return true }
            let новое = max(з.прогресс, min(ход.прогресс, 99))
            let состояние = ход.состояние.rawValue
            if новое != з.прогресс || состояние != з.состояние || ход.этап != з.этап {
                изменить(ключ, сохранить: false) { з in
                    з.прогресс = новое
                    з.состояние = состояние
                    з.этап = ход.этап
                }
            }
            return false
        }
    }

    /// «Проверить ещё раз» после «долго» или обрыва связи: та же сборка, ещё 10 минут.
    func продолжить(_ подача: ПодачаМодель) {
        прочитать(подача)
        let ключ = ключЦели(подача)
        guard let з = записи[ключ], з.собирается else { return }
        опрашивать(ключ)
    }

    /// «Отменить» сборку: опрос стоит, задача удаляется на сервере; ракурсы остаются (360°).
    func отменитьСборку(_ подача: ПодачаМодель) {
        прочитать(подача)
        сброситьМодель(ключЦели(подача))
    }

    /// Модель и задача — прочь (на сервере — delete без ожидания), ракурсы остаются.
    private func сброситьМодель(_ ключ: String) {
        guard let з = записи[ключ], !з.задача.isEmpty || !з.состояние.isEmpty else { return }
        опросы[ключ]?.cancel()
        опросы[ключ] = nil
        заминка[ключ] = nil
        let задача = з.задача
        if !задача.isEmpty {
            Task { @MainActor in _ = await Обзор3DПодачиAPI.удалить(задача: задача) }
        }
        изменить(ключ) { з in
            з.задача = ""
            з.состояние = ""
            з.прогресс = 0
            з.этап = ""
            з.постер = ""
            з.usdz = ""
            з.glb = ""
            з.отказКод = ""
            з.отказТекст = ""
        }
    }

    // MARK: - Убрать

    /// «Убрать 3D-обзор»: всё черновика — на сервере (delete draft_id без ожидания) и на телефоне.
    func убрать(_ подача: ПодачаМодель) {
        прочитать(подача)
        убрать(ключ: ключЦели(подача))
    }

    private func убрать(ключ: String) {
        guard let з = записи[ключ] else { return }
        опросы[ключ]?.cancel()
        загрузки[ключ]?.cancel()
        привязки[ключ]?.cancel()
        опросы[ключ] = nil
        загрузки[ключ] = nil
        привязки[ключ] = nil
        заминка[ключ] = nil
        отказЗагрузки[ключ] = nil
        загружаем.remove(ключ)
        let черновик = з.черновик
        let папка = з.папка
        if з.привязано.isEmpty {
            Task { @MainActor in _ = await Обзор3DПодачиAPI.удалить(черновик: черновик) }
        } else if !з.задача.isEmpty && з.собирается {
            let задача = з.задача
            Task { @MainActor in _ = await Обзор3DПодачиAPI.удалить(задача: задача) }
        }
        Task.detached(priority: .utility) { ФайлыОбзора3DПодачи.удалить(папка: папка) }
        записи[ключ] = nil
        записать()
        версия += 1
    }

    /// Правка: у объявления есть 3D-обзор (my_items прислал model3d) и его не убрали в этом запуске.
    func естьУОбъявления(_ подача: ПодачаМодель) -> Bool {
        guard подача.правка, !убраноИзОбъявлений.contains(подача.номерПравки) else { return false }
        return подача.исходник["model3d"] is [String: Any]
    }

    /// Правка: «Убрать из объявления» — delete listing_id на сервере и своя запись. false — не дошло.
    func убратьИзОбъявления(_ подача: ПодачаМодель) async -> Bool {
        let номер = подача.номерПравки
        guard подача.правка, !номер.isEmpty else { return false }
        let удалено = await Обзор3DПодачиAPI.удалить(объявление: номер)
        guard удалено else { return false }
        убраноИзОбъявлений.insert(номер)
        убрать(подача)
        return true
    }

    // MARK: - Привязка к объявлению

    /// Правка: «Сохранить в объявление» — ракурсы и модель (готовая или будущая) переходят к объявлению сейчас.
    func сохранитьВОбъявление(_ подача: ПодачаМодель) {
        guard подача.правка else { return }
        прочитать(подача)
        привязать(ключ: ключЦели(подача), объявление: подача.номерПравки)
    }

    /// Идёт ли привязка этой цели.
    func привязываем(_ подача: ПодачаМодель) -> Bool { привязки[ключЦели(подача)] != nil }

    /**
     attach: сначала догрузить ракурсы, потом сам запрос; сеть — до трёх попыток с паузой 20 и 40 с. Новое объявление
     после attach — запись прочь (модель дособерётся на сервере и встанет к объявлению сама). Правка — запись остаётся:
     карточка показывает «Сохранено в объявлении» и ход сборки.
     */
    private func привязать(ключ: String, объявление: String) {
        guard !объявление.isEmpty, let з = записи[ключ], з.всеСняты else { return }
        if з.привязать != объявление { изменить(ключ) { $0.привязать = объявление } }
        привязки[ключ]?.cancel()
        привязки[ключ] = Task { @MainActor [weak self] in
            for попытка in 0..<3 {
                if попытка > 0 { try? await Task.sleep(nanoseconds: UInt64(попытка) * 20_000_000_000) }
                guard let self, !Task.isCancelled else { return }
                let загружено = await self.загрузить(ключ).value
                guard !Task.isCancelled, let готовая = self.записи[ключ] else { return }
                guard загружено, готовая.всеЗагружены else {
                    if self.отказЗагрузки[ключ] != nil { break }
                    continue
                }
                let ответ = await Обзор3DПодачиAPI.привязать(черновик: готовая.черновик, объявление: объявление)
                guard !Task.isCancelled else { return }
                switch ответ {
                case .готово:
                    self.привязки[ключ] = nil
                    self.привязалось(ключ, объявление)
                    return
                case .отказ(let о) where о.код == "gone" && попытка == 0:
                    /* Черновик истёк на сервере — новый, ракурсы заново, и attach ещё раз. */
                    self.сменитьЧерновик(ключ)
                    continue
                case .сеть, .сбой:
                    continue
                case .отказ(let о):
                    self.отказЗагрузки[ключ] = ОтказРакурсаОбзора3DПодачи(ракурс: о.ракурс ?? -1, отказ: о)
                    self.привязки[ключ] = nil
                    return
                case .нуженВход, .нетСервера:
                    self.привязки[ключ] = nil
                    return
                }
            }
            self?.привязки[ключ] = nil
            self?.версия += 1
        }
    }

    private func привязалось(_ ключ: String, _ объявление: String) {
        if ключ == ЦельПодачи.новое.id || ключ.hasPrefix(Self.префиксПривязки) {
            опросы[ключ]?.cancel()
            опросы[ключ] = nil
            let папка = записи[ключ]?.папка ?? ""
            записи[ключ] = nil
            записать()
            версия += 1
            if !папка.isEmpty {
                Task.detached(priority: .utility) { ФайлыОбзора3DПодачи.удалить(папка: папка) }
            }
        } else {
            изменить(ключ) { з in
                з.привязано = объявление
                з.привязать = ""
            }
            ОткликСайта.успех()
        }
    }

    /**
     Новое объявление сохранено с id: все 5 ракурсов — attach; меньше пяти — черновик прочь (по двум кадрам поворота не
     выйдет). Его зовёт слежка за итогом подачи и — если в PostingSend добавят строку — сама подача.
     */
    func послеПубликации(_ подача: ПодачаМодель, объявление: String) {
        guard Config.обзор3D, !подача.правка else { return }
        прочитать(подача)
        послеПубликации(ключ: ключЦели(подача), объявление: объявление)
    }

    private func послеПубликации(ключ: String, объявление: String) {
        guard let з = записи[ключ], !объявление.isEmpty else { return }
        guard з.всеСняты else {
            убрать(ключ: ключ)
            return
        }
        guard ключ == ЦельПодачи.новое.id else {
            привязать(ключ: ключ, объявление: объявление)
            return
        }
        /* Новая подача: запись — под «attach:<id>» и attach уже оттуда; «new» свободен для следующей подачи. Загрузка и
           опрос «new» стоят: загрузку продолжит привязка под новым ключом, сборку сервер доведёт и привяжет сам. */
        let свой = Self.префиксПривязки + объявление
        опросы[ключ]?.cancel()
        загрузки[ключ]?.cancel()
        привязки[ключ]?.cancel()
        опросы[ключ] = nil
        загрузки[ключ] = nil
        привязки[ключ] = nil
        заминка[ключ] = nil
        отказЗагрузки[ключ] = nil
        загружаем.remove(ключ)
        if записи[свой] == nil { записи[свой] = з }
        записи[ключ] = nil
        записать()
        версия += 1
        привязать(ключ: свой, объявление: объявление)
    }

    /// Для submit (строка в PostingSend.телоПодачи): draft_id и адреса ракурсов — сервер привяжет их сразу.
    func поляПодачи(_ подача: ПодачаМодель) -> [String: Any] {
        guard Config.обзор3D, !подача.правка, let з = запись(подача), з.всеСняты else { return [:] }
        var поля: [String: Any] = ["model3d_draft": з.черновик]
        if з.всеЗагружены { поля["angles"] = з.ракурсы.map { $0.адрес } }
        return поля
    }

    /// Следить за итогом новой подачи: опубликовано или на проверке с id — attach. Один раз на подачу.
    func следить(за подача: ПодачаМодель) {
        guard Config.обзор3D, !подача.правка else { return }
        слежка = слежка.filter { $0.value.подача.подача != nil }
        let ид = ObjectIdentifier(подача)
        if let была = слежка[ид], была.подача.подача === подача { return }
        let ключ = ключЦели(подача)
        let подписка = подача.$итог.sink { [weak self] итог in
            guard let итог else { return }
            let объявление: String
            switch итог {
            case .опубликовано(let id), .наПроверке(let id):
                объявление = id
            case .отклонено, .сохраненоИИ, .ждётВерификации, .неактивные, .лимит, .запрещено:
                return
            }
            /* @Published шлёт на главной нити (итог ставит модель подачи) — как у остальных подписок приложения. */
            self?.послеПубликации(ключ: ключ, объявление: объявление)
        }
        слежка[ид] = (СлабаяПодачаОбзора3D(подача), подписка)
    }

    // MARK: - Возобновить и начать заново

    /// Шаг «Фото» на экране: прерванная загрузка, опрос и привязка продолжаются сами — у этой подачи и у прежних
    /// новых объявлений, чей attach не дошёл («attach:<id>»).
    func возобновить(_ подача: ПодачаМодель) {
        прочитать(подача)
        for (к, з) in записи where к.hasPrefix(Self.префиксПривязки) && !з.привязать.isEmpty && привязки[к] == nil
            && отказЗагрузки[к] == nil {
            привязать(ключ: к, объявление: з.привязать)
        }
        let ключ = ключЦели(подача)
        guard let з = записи[ключ] else { return }
        if з.собирается && опросы[ключ] == nil && заминка[ключ] == nil { опрашивать(ключ) }
        if з.ракурсы.contains(where: { !$0.файл.isEmpty && $0.адрес.isEmpty }) && загрузки[ключ] == nil
            && отказЗагрузки[ключ] == nil {
            загрузить(ключ)
        }
        if !з.привязать.isEmpty && з.привязано != з.привязать && привязки[ключ] == nil {
            привязать(ключ: ключ, объявление: з.привязать)
        }
    }

    /**
     Новая подача с чистой формой (первая встреча этой подачи: ни фото, ни названия, ни описания) — прежние ракурсы новой
     подачи прочь: это другое объявление. Продолженный черновик (есть фото или текст) их сохраняет.
     */
    func встретить(_ подача: ПодачаМодель) {
        guard !подача.правка else { return }
        встреченные.removeAll { $0.подача == nil }
        guard !встреченные.contains(where: { $0.подача === подача }) else { return }
        встреченные.append(СлабаяПодачаОбзора3D(подача))
        let ф = подача.форма
        guard подача.плитки.isEmpty, ф.название.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty,
              ф.описание.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty else { return }
        прочитать(подача)
        let ключ = ключЦели(подача)
        guard let з = записи[ключ], з.привязать.isEmpty else { return }
        убрать(ключ: ключ)
    }

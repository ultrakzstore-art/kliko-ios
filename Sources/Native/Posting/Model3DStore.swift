/**
 3D-ОБЗОР В ПОДАЧЕ — ЗАПИСЬ НА ЦЕЛЬ ПОДАЧИ, ЗАГРУЗКА РАКУРСОВ, СБОРКА И ПРИВЯЗКА К ОБЪЯВЛЕНИЮ.

 Запись — на цель подачи («new» или «edit:<id>», как у ИИ-фото), на телефоне, 7 дней, только своему человеку: draft_id
 (случайный, 128 бит), вид (item | car), 5 ракурсов (файл на телефоне, адрес на сервере после upload_angle), задача
 сборки и её итог (usdz, glb, poster). Ракурсы — отдельный список, не плитки фото: они уходят на сервер сразу после
 съёмки (upload_angle), а к объявлению переходят по attach — после публикации (новое) или по «Сохранить в объявление»
 (правка). Даже без сборки ИИ они остаются у объявления — у покупателя 360°-обзор.

 Сборка и опрос живут здесь, а не в окне съёмки: окно можно закрыть и заполнять подачу дальше — сборка идёт, карточка в
 шаге «Фото» показывает проценты. Опрос status — раз в 3 с, до 10 минут; потом «Собирается дольше обычного» и «Проверить
 ещё раз». Переснятый ракурс сбрасывает модель: она была про прежние кадры (задача удаляется на сервере).

 Публикация нового объявления: поля model3d_draft и angles идут прямо в submit (поляПодачи из PostingSend.телоПодачи),
 а ответ с id зовёт послеПубликации (PostingSend.разобратьПодачу) — attach (до трёх попыток), сервер примет его как
 повтор. Запасной путь — слежка за итогом подачи (ПодачаМодель.итог). Запись новой подачи («new») при этом сразу уходит
 под свой ключ «attach:<id>» и там доводит attach: «new» свободен для следующей подачи — недошедший attach не покажет
 чужие ракурсы в новой подаче и не привяжет их к новому объявлению. Такие записи продолжает возобновить() (7 дней).
 */

/// Ракурс записи: файл на телефоне (имя в папке черновика), адрес на сервере, вырезан ли и когда снят.
struct РакурсЗаписиОбзора3DПодачи: Codable, Equatable {
    var файл = ""
    var исходник = ""
    var вырезан = false
    var адрес = ""
    /// Время съёмки — версия кадра: адрес загрузки принимается, только если кадр с тех пор не пересняли.
    var снят: Double = 0

    /// Ракурс есть: файл на телефоне или адрес на сервере.
    var есть: Bool { !файл.isEmpty || !адрес.isEmpty }
}

/// Запись цели подачи. Codable — лежит в UserDefaults (без картинок: они в Caches).
struct ЗаписьОбзора3DПодачи: Codable, Equatable {
    /// draft_id на сервере. Сервер забыл черновик (24 часа без публикации) — выдаётся новый, ракурсы уходят заново.
    var черновик = ""
    /// Папка файлов на телефоне — draft_id первой съёмки; при новом черновике не меняется.
    var папка = ""
    var вид = ВидОбзора3DПодачи.вещь.rawValue
    var ракурсы: [РакурсЗаписиОбзора3DПодачи] = Array(repeating: РакурсЗаписиОбзора3DПодачи(),
                                                      count: РакурсОбзора3DПодачи.всего)
    var задача = ""
    /// "" — сборки не было; queued | working | done | failed.
    var состояние = ""
    var прогресс = 0
    var этап = ""
    var постер = ""
    var usdz = ""
    var glb = ""
    var отказКод = ""
    var отказТекст = ""
    /// id объявления, к которому ракурсы и модель привязаны (attach ответил ok).
    var привязано = ""
    /// id объявления, к которому их надо привязать (attach ещё не дошёл).
    var привязать = ""
    var время: Double = 0

    var видОбзора: ВидОбзора3DПодачи { ВидОбзора3DПодачи(rawValue: вид) ?? .вещь }

    func ракурс(_ р: РакурсОбзора3DПодачи) -> РакурсЗаписиОбзора3DПодачи {
        ракурсы.indices.contains(р.rawValue) ? ракурсы[р.rawValue] : РакурсЗаписиОбзора3DПодачи()
    }

    var снято: Int { ракурсы.filter { $0.есть }.count }
    var всеСняты: Bool { снято >= РакурсОбзора3DПодачи.всего }
    var всеЗагружены: Bool { ракурсы.count == РакурсОбзора3DПодачи.всего && ракурсы.allSatisfy { !$0.адрес.isEmpty } }
    var загружено: Int { ракурсы.filter { !$0.адрес.isEmpty }.count }

    /// Первый неснятый ракурс по порядку обхода; nil — сняты все.
    var следующийНеснятый: РакурсОбзора3DПодачи? {
        РакурсОбзора3DПодачи.allCases.first { !ракурс($0).есть }
    }

    var собирается: Bool { состояние == "queued" || состояние == "working" }
    var готова: Bool { состояние == "done" }
    var неУдалась: Bool { состояние == "failed" }

    var адресПостера: URL? { ХодПримерочной.адрес(постер) }
    var адресUSDZ: URL? { ХодПримерочной.адрес(usdz) }
}


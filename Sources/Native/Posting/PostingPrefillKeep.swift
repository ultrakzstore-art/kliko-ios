/**
 «Параметры для подбора»: что из «Моего» уйдёт в объявление стандартами (std или строкой «Параметры: …») — их видят
 покупатели и подбор. «Убрать параметры» — не отправлять. Нет заготовки, стандартов или это шины и диски — вида нет.
 */
struct КарточкаПараметровЗаготовки: View {
    @ObservedObject var модель: ПодачаМодель

    init(модель: ПодачаМодель) {
        self.модель = модель
    }

    private func т(_ ключ: String) -> String { ПоляМоегоПодачиText.т(ключ) }

    var body: some View {
        let строки: [СтрокаПараметраЗаготовки] = модель.строкиПараметровЗаготовки
        if !строки.isEmpty {
            КарточкаПодачи(т("pk_std_t"), подпись: т("pk_std_s"), значок: "checklist") {
                VStack(alignment: .leading, spacing: 8) {
                    ForEach(строки) { строка in
                        ряд(строка)
                    }
                }
                убрать
            }
        }
    }

    private func ряд(_ с: СтрокаПараметраЗаготовки) -> some View {
        HStack(alignment: .firstTextBaseline, spacing: 10) {
            Image(systemName: с.значок)
                .font(.system(size: 13, weight: .semibold))
                .foregroundStyle(Theme.акцент)
                .frame(width: 20)
                .accessibilityHidden(true)
            Text(с.имя)
                .font(.system(size: 13))
                .foregroundStyle(Theme.текстВторой)
                .fixedSize(horizontal: false, vertical: true)
            Spacer(minLength: 8)
            Text(с.значение)
                .font(.system(size: 13, weight: .semibold))
                .foregroundStyle(КраскаПодачи.текст)
                .multilineTextAlignment(.trailing)
                .fixedSize(horizontal: false, vertical: true)
        }
        .accessibilityElement(children: .combine)
    }

    private var убрать: some View {
        let м = модель
        return Button { м.убратьПараметрыЗаготовки() } label: {
            Label(т("pk_std_remove"), systemImage: "xmark.circle")
                .font(.system(size: 13, weight: .bold))
                .foregroundStyle(КраскаПодачи.хорошоТекст)
                .frame(minHeight: 32)
                .contentShape(Rectangle())
        }
        .buttonStyle(.plain)
    }
}


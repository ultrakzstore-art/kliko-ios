 знать описание и прочее, чтобы связка работала как надо»).

 Заготовку собирает «Моё» (MyThings/MyThingsSell.swift) и кладёт в форму PostingPrefill.swift. Здесь — то, что вокруг
 формы, чтобы структурные поля вещи дошли до объявления и подбора («Подходит вашему…», «Новинки для моего»):


// MARK: - Черновик

/// Поля заготовки «Продать своё», которых нет в форме, — в черновике рядом с ней. Короткие латинские ключи: черновик
/// переживает версии приложения; незнакомое или битое поле читается как nil, а не роняет весь черновик.
struct ЗаготовкаЧерновикаПодачи: Codable, Equatable {
    var стандарты: НаборСтандартов? = nil
    var штук: Int? = nil
    /// «deal:<id>» или «listing:<id>» — relist_from.
    var источник: String? = nil
    var показатьКупленоНаKliko: Bool? = nil
    var изМоего: Bool? = nil
    var бренд: String? = nil
    var состояние: String? = nil
    var характеристики: [String: String]? = nil
    var размерВсехСистем: String? = nil
    /// Система своего размера вещи («EU», «US M») — size_sys, если продавец не выбрал другую в блоке «Размер».
    var системаРазмера: String? = nil
    /// Диагональ экрана, дюймы — поле diag.
    var диагональ: Double? = nil

    enum CodingKeys: String, CodingKey {
        case стандарты = "std"
        case штук = "qty"
        case источник = "from"
        case показатьКупленоНаKliko = "prov"
        case изМоего = "my"
        case бренд = "brand"
        case состояние = "cond"
        case характеристики = "specs"
        case размерВсехСистем = "size"
        case системаРазмера = "sys"
        case диагональ = "diag"
    }

    init(_ з: ЗаготовкаПодачи) {
        стандарты = з.стандарты
        штук = з.штук
        источник = з.источник.isEmpty ? nil : з.источник
        показатьКупленоНаKliko = з.показатьКупленоНаKliko
        изМоего = з.изМоего
        бренд = з.бренд.isEmpty ? nil : з.бренд
        состояние = з.состояние
        характеристики = з.характеристики.isEmpty ? nil : з.характеристики
        размерВсехСистем = з.размерВсехСистем.isEmpty ? nil : з.размерВсехСистем
        системаРазмера = з.системаРазмера.isEmpty ? nil : з.системаРазмера
        диагональ = з.диагональ
    }

    init(from decoder: Decoder) throws {
        let к = try decoder.container(keyedBy: CodingKeys.self)
        стандарты = try? к.decodeIfPresent(НаборСтандартов.self, forKey: .стандарты)
        штук = try? к.decodeIfPresent(Int.self, forKey: .штук)
        источник = try? к.decodeIfPresent(String.self, forKey: .источник)
        показатьКупленоНаKliko = try? к.decodeIfPresent(Bool.self, forKey: .показатьКупленоНаKliko)
        изМоего = try? к.decodeIfPresent(Bool.self, forKey: .изМоего)
        бренд = try? к.decodeIfPresent(String.self, forKey: .бренд)
        состояние = try? к.decodeIfPresent(String.self, forKey: .состояние)
        характеристики = try? к.decodeIfPresent([String: String].self, forKey: .характеристики)
        размерВсехСистем = try? к.decodeIfPresent(String.self, forKey: .размерВсехСистем)
        системаРазмера = try? к.decodeIfPresent(String.self, forKey: .системаРазмера)
        диагональ = try? к.decodeIfPresent(Double.self, forKey: .диагональ)
    }

    /// Заготовка для «Продолжить»: название и раздел — из формы черновика (их мог поправить человек).
    func заготовка(название: String, раздел: String) -> ЗаготовкаПодачи {
        var з = ЗаготовкаПодачи(название: название, раздел: раздел)
        з.стандарты = стандарты
        з.штук = max(1, min(999, штук ?? 1))
        з.источник = источник ?? ""
        з.показатьКупленоНаKliko = показатьКупленоНаKliko ?? false
        з.изМоего = изМоего ?? true
        з.бренд = бренд ?? ""
        if let состояние, состояние == "used" || состояние == "new" { з.состояние = состояние }
        з.характеристики = характеристики ?? [:]
        з.размерВсехСистем = размерВсехСистем ?? ""
        з.системаРазмера = String((системаРазмера ?? "").prefix(16))
        if let диагональ, диагональ.isFinite, диагональ > 0 { з.диагональ = диагональ }
        return з
    }
}

// MARK: - Мастер

extension ПодачаМодель {

    /// Подача из «Моего» (не правка): значения вещи до «✓ Опубликовать» сами на сервер не уходят.
    var заготовкаМолчит: Bool { заготовка != nil && !правка }

    /// Кнопка «Подсказать цену по рынку»: подача из «Моего», раздел для рынка есть, ещё не нажимали.
    var рынокЖдётНажатия: Bool {
        guard заготовкаМолчит, !рынокРазрешён, !форма.раздел.isEmpty, форма.раздел != "other" else { return false }
        return !услугаИлиРабота && !чистыйПрокат
    }

    /// «Подсказать цену по рынку»: с этого нажатия рынок спрашивается, как у обычной подачи (и при смене цены).
    func подсказатьЦенуПоНажатию() {
        рынокРазрешён = true
        запланироватьРынок()
    }

    // MARK: Kliko AI

    /**
     Описание от Kliko AI у подачи из «Моего»: только вместо пустого или собранного автоматически (автоОписание; строки
     приложения не в счёт), строка «Размер: …», которую поставило «Моё», остаётся последней. nil — описание не меняем.
     */
    func описаниеКлико(_ новое: String, вместо прежнее: String) -> String? {
        let текст: String = новое.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !текст.isEmpty else { return nil }
        let своё: String = Self.безСтрокПриложения(прежнее)
        let авто: String = Self.безСтрокПриложения(автоОписание)
        guard своё.isEmpty || (!авто.isEmpty && своё == авто) else { return nil }
        var итог: String = String(текст.prefix(ПравилаРазмераОдежды.пределОписания))
        if let строка = Self.строкаРазмера(прежнее) { итог = ПравилаРазмераОдежды.сСтрокой(итог, строка) }
        return итог
    }

    /// Описание без строк приложения («Размер: …», «Параметры: …») и пробелов по краям — для сравнения.
    static func безСтрокПриложения(_ описание: String) -> String {
        let безПараметров: String = СтрокаПараметровПодачи.безСтроки(описание)
        return ПравилаРазмераОдежды.безСтроки(безПараметров).trimmingCharacters(in: .whitespacesAndNewlines)
    }

    /// Последняя наша строка «Размер: …» описания как есть или nil.
    static func строкаРазмера(_ описание: String) -> String? {
        let строки: [String] = описание.components(separatedBy: "\n")
        for строка in строки.reversed() {
            let чистая: String = строка.trimmingCharacters(in: .whitespaces)
            if ПравилаРазмераОдежды.этоСтрока(чистая) { return чистая }
        }
        return nil
    }

    // MARK: Раздел выбран позже

    /**
     Раздел выбрали или сменили после заготовки: марка (если раздел её показывает), слоты характеристик и размер одежды
     из «Моего» ложатся в пустые поля. Пока пишем — заполняем = true: производные (рынок, черновик) не дёргаются.
     */
    func доложитьМоёПослеРаздела() {
        guard !правка, let з = заготовка, !форма.раздел.isEmpty else { return }
        let было: Bool = заполняем
        заполняем = true
        defer { заполняем = было }
        var ф = форма
        let марка: String = з.бренд.trimmingCharacters(in: .whitespacesAndNewlines)
        let маркиНет: Bool = ф.бренд.trimmingCharacters(in: .whitespaces).isEmpty
        if брендВиден && маркиНет && !марка.isEmpty { ф.бренд = марка }
        доложитьСлоты(з.характеристики, в: &ф)
        доложитьРазмер(з.размерВсехСистем, в: &ф)
        if ф != форма { форма = ф }
    }

    /// Слоты раздела: только пустые и только значение, которое поле принимает как есть (вариант списка, год, число).
    private func доложитьСлоты(_ значения: [String: String], в ф: inout ФормаПодачи) {
        guard !значения.isEmpty else { return }
        let поляРаздела: [ПолеХарактеристики] = характеристики
        for (слот, сырое) in значения where СхемаПодачи.слоты.contains(слот) {
            guard let поле = поляРаздела.first(where: { $0.поле == слот }),
                  let значение = точноеЗначениеМоего(поле, сырое) else { continue }
            switch слот {
            case "cpu": if ф.cpu.isEmpty { ф.cpu = значение }
            case "gpu": if ф.gpu.isEmpty { ф.gpu = значение }
            case "ram": if ф.ram.isEmpty { ф.ram = значение }
            case "storage": if ф.storage.isEmpty { ф.storage = значение }
            case "year": if ф.year.isEmpty { ф.year = значение }
            default: break
            }
        }
    }

    private func точноеЗначениеМоего(_ поле: ПолеХарактеристики, _ сырое: String) -> String? {
        let чистое: String = сырое.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !чистое.isEmpty else { return nil }
        if поле.год {
            let год: String = ПодачаМодель.цифры(чистое, предел: 4)
            return ПределыПодачи.годы.contains(год) ? год : nil
        }
        if поле.вводом {
            guard поле.числом else { return ПределыПодачи.обрезать(чистое, ПределыПодачи.короткое) }
            let число: String = чистое.replacingOccurrences(of: ",", with: ".")
            return Double(число) == nil ? nil : число
        }
        let нужное: String = чистое.lowercased()
        let вариант: ВариантПоля? = поле.вариантыСПодписью.first { в in
            в.ключ.lowercased() == нужное || в.подпись.lowercased() == нужное
        }
        return вариант?.ключ
    }

    /// Размер одежды и обуви: строка всех систем — последней строкой описания, пустое поле размера сайта — тем же выбором.
    private func доложитьРазмер(_ размерВсех: String, в ф: inout ФормаПодачи) {
        let размер: String = размерВсех.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !размер.isEmpty, let набор = наборРазмеровОдежды,
              СтрокаРазмераВсехСистем.из(описания: ф.описание) == nil else { return }
        var строка: String = размер
        if СтрокаРазмераВсехСистем.разобрать(строка) == nil { строка = ПравилаРазмераОдежды.начало + " " + размер }
        guard let выбор = ПравилаРазмераОдежды.найти(строка, в: набор),
              let вкладка = набор.вкладка(выбор.вкладка) else { return }
        ф.описание = ПравилаРазмераОдежды.сСтрокой(ф.описание, вкладка.строкаОписания(выбор))
        if ф.storage.isEmpty, let поле = полеРазмераОдежды,
           let значение = ПравилаРазмераОдежды.значениеПоля(вкладка, выбор, поле) {
            ф.storage = значение
        }
    }

    // MARK: Карточка «Параметры для подбора»

    /// Строки карточки: семьи std заготовки с подписью на языке приложения; у шин и дисков — нет (их значения в parts).
    var строкиПараметровЗаготовки: [СтрокаПараметраЗаготовки] {
        guard заготовкаМолчит, !колёсаВидны, let з = заготовка, let набор = з.стандарты, !набор.пусто else { return [] }
        var итог: [СтрокаПараметраЗаготовки] = []
        for семья in набор.семьи {
            var значение: String = РазборСтандартов.подпись(набор, семья)
            if семья == .размер { значение = набор[семья, КлючСтандарта.значение] ?? "" }
            guard !значение.isEmpty else { continue }
            итог.append(СтрокаПараметраЗаготовки(id: семья.rawValue, значок: семья.значок, имя: семья.название,
                                                 значение: значение))
        }
        guard !итог.isEmpty else { return [] }
        let штук: Int = з.сколько
        if штук > 1 {
            итог.append(СтрокаПараметраЗаготовки(id: "qty", значок: "number", имя: ПоляМоегоПодачиText.т("pk_qty"),
                                                 значение: String(штук)))
        }
        return итог
    }

    /// «Убрать параметры»: стандарты «Моего» в объявление не уйдут — ни полем std, ни строкой «Параметры: …»; и qty
    /// («Штук в объявлении» той же карточки): продавец его больше не видит (владелец 17.10.2026).
    func убратьПараметрыЗаготовки() {
        guard заготовка?.стандарты != nil else { return }
        заготовка?.стандарты = nil
        заготовка?.штук = 1
        let без: String = СтрокаПараметровПодачи.безСтроки(форма.описание)
        if без != форма.описание { форма.описание = без }
        запланироватьЧерновик()
        показать(ПоляМоегоПодачиText.т("pk_std_removed"))
    }

    // MARK: Отправка

    /**
     Строка «Параметры: …» — по свежей схеме сейчас, а не по схеме на момент заготовки (кэш мог быть старым или его не
     было): сервер хранит std (rules.std.store) — нашей строки в описании нет, std уходит полем (SERVER_STANDARDS.md
     §3.6: «после store: true строка не пишется»); не хранит — одна свежая строка из стандартов заготовки. Шины и диски
     — своей строкой (PostingSizeWheels.swift). Без заготовки и в правке — как было.
     */
    func дописатьПараметрыЗаготовки(_ тело: inout [String: Any]) {
        guard !правка, let з = заготовка else { return }
        let описание: String = (тело["description"] as? String) ?? форма.описание
        let хранятся: Bool = схема?.правилаЗаготовки.стандартыПолями ?? false
        var итог: String = СтрокаПараметровПодачи.безСтроки(описание)
        if !хранятся, !колёсаВидны, let набор = з.стандарты, !набор.пусто,
           let строка = СтрокаПараметровПодачи.собрать(набор) {
            итог = СтрокаПараметровПодачи.сСтрокой(итог, строка)
        }
        тело["description"] = итог.trimmingCharacters(in: .whitespacesAndNewlines)
    }

    /**
     Размер одежды и обуви при rules.sizes.store (docs/SERVER_SIZES.md §2.2): size_sys — система, в которой выбирал
     продавец (иначе система поля сайта), size_all — все системы строкой, как строка описания без «Размер: » (до 200
     знаков). Сама строка пока остаётся в описании: окно объявления приложения size_all ещё не показывает, и без строки
     покупатель в приложении видел бы размер только в системе сайта; §2.4 разрешает прийти обоим (строку при size_all
     сервер может убрать сам; владелец 17.10.2026). Без store — только строка, как раньше. Правка: размер у объявления
     был, а теперь снят (× на бирке) или раздел больше не про размеры — пустые поля снимают его (§2.2).
     */
    func дописатьРазмерОдежды(_ тело: inout [String: Any]) {
        guard Config.размерыОдеждыВПодаче, схема?.размерыПолями == true else { return }
        let описание: String = (тело["description"] as? String) ?? форма.описание
        let набор: НаборРазмеровОдежды? = наборРазмеровОдежды
        if let набор, let выбор = ПравилаРазмераОдежды.найти(описание, в: набор),
           let вкладка = набор.вкладка(выбор.вкладка) {
            let строка: String = вкладка.строкаОписания(выбор)
            let все: String = String(строка.dropFirst(ПравилаРазмераОдежды.начало.count))
                .trimmingCharacters(in: .whitespaces)
            guard !все.isEmpty else { return }
            тело["size_sys"] = системаРазмераТела(вкладка)
            тело["size_all"] = String(все.prefix(200))
            return
        }
        let былРазмер: Bool = !МоиОбъявленияAPI.строка(исходник["size_all"]).isEmpty
        guard правка, былРазмер, СтрокаРазмераВсехСистем.из(описания: описание) == nil else { return }
        let снят: Bool = набор == nil || форма.storage.trimmingCharacters(in: .whitespaces).isEmpty
        guard снят else { return }
        тело["size_sys"] = ""
        тело["size_all"] = ""
    }

    /// size_sys: система переключателя продавца, потом система своего размера вещи «Моего» (если она есть у вкладки
    /// выбора); иначе — система поля сайта.
    private func системаРазмераТела(_ вкладка: ВкладкаРазмеровОдежды) -> String {
        if let своя = форма.системаРазмера, вкладка.система(своя) != nil { return своя }
        let изМоего: String = заготовка?.системаРазмера ?? ""
        if !изМоего.isEmpty && вкладка.система(изМоего) != nil { return изМоего }
        return вкладка.системаПоля(полеРазмераОдежды)
    }

    /// Разделы семьи screen_diag каталога (SERVER_STANDARDS_catalog.json, cats): только у них диагональ — про сам экран.
    private static let разделыДиагонали: Set<String> = ["tv", "monitors", "laptops", "tablets", "smartphones"]

    /**
     Диагональ экрана вещи «Моего» (ноутбук, монитор, ТВ, телефон) — полем diag, дюймы числом с одним знаком (submit
     принимает его на проде вместе с dim_* — ответ сайта 17.10.2026, §3; дюймы — как diag справочников,
     SERVER_MY_THINGS.md). Только по флагу схемы, как у габаритов (dims: 1 — сервер хранит dim_* и diag; нет флага —
     нового поля нет, SERVER_CIRCLE.md §1.1), и только в разделах screen_diag: продавец перенёс вещь в «Чехлы» или
     «Кронштейны» — диагональ экрана не уходит, чтобы не путать подбор (владелец 17.10.2026). Нет заготовки или
     диагонали, правка — поля нет. В std она уходит своей семьёй (screen_diag).
     */
    func дописатьДиагональЗаготовки(_ тело: inout [String: Any]) {
        guard !правка, габаритыУСервера, let дюймы = заготовка?.диагональ, дюймы.isFinite else { return }
        guard разделВнутри(форма.раздел, Self.разделыДиагонали) else { return }
        guard дюймы >= 1 && дюймы <= 150 else { return }
        let округлено: Double = (дюймы * 10).rounded() / 10
        тело["diag"] = NSNumber(value: округлено)
    }

    /**
     Правка: size_sys и size_all записи my_items (§2.5) — строка «Размер: …» возвращается в описание (блок «Размер»
     найдёт по ней выбор), система — на переключатель. При сохранении строка снова уйдёт полями (дописатьРазмерОдежды).
     Зовёт заполнитьИз, PostingModel.swift.
     */
    func приложитьРазмерЗаписи(_ з: [String: Any], к ф: inout ФормаПодачи) {
        typealias A = МоиОбъявленияAPI
        let система: String = A.строка(з["size_sys"]).trimmingCharacters(in: .whitespacesAndNewlines)
        if !система.isEmpty { ф.системаРазмера = String(система.prefix(16)) }
        let все: String = A.строка(з["size_all"]).trimmingCharacters(in: .whitespacesAndNewlines)
        guard Config.размерыОдеждыВПодаче, !все.isEmpty, !ф.раздел.isEmpty,
              СтрокаРазмераВсехСистем.из(описания: ф.описание) == nil else { return }
        /* Только у раздела с блоком «Размер»: иначе строке негде показаться, и она осталась бы в тексте объявления. */
        let цепочка: [String] = цепочкаРазделаРазмеров(ф.раздел)
        guard НаборРазмеровОдежды.для(цепочки: цепочка, название: ф.название) != nil else { return }
        let строка: String = ПравилаРазмераОдежды.начало + " " + String(все.prefix(200))
        guard ПравилаРазмераОдежды.этоСтрока(строка) else { return }
        ф.описание = ПравилаРазмераОдежды.сСтрокой(ф.описание, строка)
    }
}


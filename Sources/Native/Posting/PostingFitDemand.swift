/**
 СПРОС ПРИ ПОДАЧЕ И «СООБЩИТЬ ИМ» (пачка 83; docs/SERVER_NEW_FOR_MINE.md §16.1, §16.2, §11, §15.2 В13 и В18).

 «Подойдёт 40+ людям в Астане: у них машина под 205/55 R16» — одной спокойной строкой в подаче: сколько подписок
 «Новинки для моего» ждут вещь с такими значениями (сводка сервера, только ячейки от 20, вниз до 10). Ниже, если
 сервер позволил (notify: true), — переключатель «Сообщить им»: после одобрения Kliko сам пришлёт им push в их обычном
 пределе, продавец не узнает, кому. Бесплатно и один раз; включён по умолчанию (В13), снимается одним касанием.

 РУБИЛЬНИКИ (§11), оба по умолчанию выключены — значение сборки false, включает только админка:
   · fit_demand_post — запрос POST cabinet.php?action=fit_demand и строка спроса; выключен — ни запроса, ни строки;
   · fit_notify_on_publish — переключатель и поле fit_notify в submit; выключен — ни того, ни другого.
 Пока ключей нет в белом списке приложения (НастройкиСервера.ключиФлагов, System/RemoteSettings.swift), сервер их не
 включит — новых запросов нет вовсе.

 Запрос: куки и csrf, как у submit (любой вошедший); тело — поля будущего объявления под именами submit: category, city,
 lang и только то, из чего сервер строит ячейку: parts шин (width, profile, diameter, season) или дисков (diameter,
 width_j, et, pcd, dia), std вещи «Моего» из заготовки «Продать своё» (PostingPrefill.swift), размер одежды и обуви —
 слот сайта (storage). Ни названия, ни описания, ни цены. Спрашивается при смене ключа (раздел, город, значения), не
 чаще раза в 3 с; ответы ключей этой подачи помнятся, пока она открыта. «Не поддерживается» (404, 405, 410, 501, не JSON,
 unsupported, off) — до перезапуска не спрашиваем (§0); сбой сети, 5xx, 429 — молча, до следующей смены ключа.

 Где видно: «Проверьте» короткого пути (ПроверкаКамерыПодачи), лист «Проверьте перед публикацией» полного пути
 (ОкноПроверкиПодачи) и, у «Продать своё», сразу экран фото — значения вещи уже известны (§16.4). Но у «Продать своё»
 запрос — только по кнопке «Узнать, скольким подойдёт» (владелец 17.10.2026: значения «Моего» до «Опубликовать» с
 телефона сами не уходят); без нажатия ключ формы пуст — ни запроса, ни строки.
 Правка (edit_item) — никогда: fit_notify принимает только submit (§16.2).

 Состояние — здесь, вне ПодачаМодель: одна открытая подача за раз; новая подача (открытьПервыйЭкран) и другой мастер
 его сбрасывают.
 */
enum РубильникиСпросаПодачи {
    /// fit_demand_post — «Подойдёт N людям в <город>» (§16.1).
    static var спрос: Bool { НастройкиСервера.вклВыкл("fit_demand_post", сборка: false) }
    /// fit_notify_on_publish — «Сообщить им» и fit_notify в submit (§16.2).
    static var сообщить: Bool { НастройкиСервера.вклВыкл("fit_notify_on_publish", сборка: false) }
}

/// Ячейка сводки из ответа fit_demand (rows[]).
struct ЯчейкаСпросаПодачи: Equatable, Identifiable {
    /// key: «tyre_size:205/55R16».
    let ключ: String
    /// for: car · phone · laptop · size · std:<семья>.
    let чья: String
    /// label: «Шины 205/55 R16», «M (INT)».
    let подпись: String
    /// n — в городе («40+»); пусто — меньше порога.
    let вГороде: String
    /// n_kz — по Казахстану; пусто — меньше порога.
    let поСтране: String
    var id: String { ключ + "|" + чья }
}

/// Разобранный ответ fit_demand.
struct ОтветСпросаПодачи: Equatable {
    /// Не больше двух ячеек (обычно одна; шины на дисках комплектом — две).
    var ячейки: [ЯчейкаСпросаПодачи] = []
    /// city ответа; пусто — город формы.
    var город: String = ""
    /// wanted — открытых «Ищу», которым подошло бы объявление (§16.3; без wanted_std — 0).
    var ищут: Int = 0
    /// notify — «Сообщить им» доступно (ключ включён, стандарт не из текста, доверие, дневной предел).
    var сообщитьМожно = false
}

/// Тело и ключ запроса fit_demand для текущей формы.
struct ЗапросСпросаПодачи {
    let ключ: String
    let тело: [String: Any]
}

@MainActor
final class СпросПодачи: ObservableObject {
    static let shared = СпросПодачи()

    /// Ответ для ключа ключОтвета (вид сверяет ключ с формой: устаревший не показывается).
    @Published private(set) var ответ: ОтветСпросаПодачи? = nil
    @Published private(set) var ключОтвета = ""
    /// Выбор продавца в этой подаче; nil — не трогал (включено, В13).
    @Published private(set) var выбор: Bool? = nil
    /// «Продать своё» (владелец 17.10.2026: значения «Моего» до «Опубликовать» с телефона не уходят): fit_demand —
    /// только после «Узнать, скольким подойдёт». true — продавец нажал в этой подаче.
    @Published private(set) var спросРазрешён = false

    /// Мастер, к которому относится состояние (слабо: закрытый мастер не держим, новый по тому же адресу — другой).
    private weak var подача: ПодачаМодель? = nil
    /// Последний ответ этой подачи разрешил «Сообщить им».
    private var последнийМожно = false
    /// Ответы ключей этой подачи (не больше пределКэша).
    private var кэш: [String: ОтветСпросаПодачи] = [:]
    private var порядокКэша: [String] = []
    private var последнийЗапрос: Date? = nil
    /// Сервер сказал «не поддерживается» — до перезапуска не спрашиваем (§0).
    private var нетНаСервере = false
    /// Запросы в пути по ключу: второй экран с тем же ключом ждёт ответ первого.
    private var вПути: [String: Task<ИтогСпросаПодачи, Never>] = [:]

    /// Не чаще раза в 3 с (§16.1).
    static let пауза: TimeInterval = 3
    private static let пределКэша = 12

    private init() {}

    // MARK: Подача

    /// Новая подача (чистая форма, «Подать ещё», «Продать своё»): прежние ответы и выбор — прочь.
    func новаяПодача(_ модель: ПодачаМодель) {
        подача = модель
        сбросить()
    }

    /// Состояние другого мастера (новое окно подачи) — прочь.
    private func привязать(_ модель: ПодачаМодель) {
        guard подача !== модель else { return }
        подача = модель
        сбросить()
    }

    private func сбросить() {
        if ответ != nil { ответ = nil }
        if !ключОтвета.isEmpty { ключОтвета = "" }
        if выбор != nil { выбор = nil }
        if спросРазрешён { спросРазрешён = false }
        последнийМожно = false
        кэш = [:]
        порядокКэша = []
        вПути = [:]
    }

    /// «Сообщить им» сейчас включено (по умолчанию — да, В13).
    var сообщитьВключено: Bool { выбор ?? true }

    func выбрать(_ включено: Bool) {
        выбор = включено
    }

    /// «Узнать, скольким подойдёт» у «Продать своё»: с этого нажатия ключ формы спрашивается, как у обычной подачи.
    func разрешить(_ модель: ПодачаМодель) {
        привязать(модель)
        спросРазрешён = true
    }

    /// Кнопка «Узнать, скольким подойдёт»: рубильник, новая подача из «Моего», ещё не нажимали и спрашивать есть что.
    func нуженВопрос(_ модель: ПодачаМодель) -> Bool {
        guard РубильникиСпросаПодачи.спрос, !модель.правка, модель.заготовка != nil else { return false }
        if подача === модель && спросРазрешён { return false }
        return Self.запросФормы(модель) != nil
    }

    /// Ответ для формы этой подачи или nil (рубильник выключен, правка, ключ сменился, ответа ещё нет). Только чтение.
    func ответДля(_ модель: ПодачаМодель) -> ОтветСпросаПодачи? {
        guard подача === модель else { return nil }
        let ключ: String = Self.ключФормы(модель)
        guard !ключ.isEmpty, ключ == ключОтвета else { return nil }
        return ответ
    }

    /// fit_notify для submit (§16.2): рубильник, новая подача, последний ответ разрешил и продавец не снял. Иначе пусто.
    func поляПодачи(_ модель: ПодачаМодель) -> [String: Any] {
        guard РубильникиСпросаПодачи.сообщить, !модель.правка, подача === модель else { return [:] }
        guard последнийМожно, сообщитьВключено else { return [:] }
        return ["fit_notify": true]
    }

    // MARK: Ключ и тело

    /// Ключ спроса формы: раздел, город и значения; пусто — спрашивать нечего (рубильник, правка, нет значений).
    static func ключФормы(_ модель: ПодачаМодель) -> String {
        guard РубильникиСпросаПодачи.спрос, !модель.правка else { return "" }
        /* «Продать своё»: значения «Моего» (std, parts, размер) — только после нажатия «Узнать, скольким подойдёт». */
        if модель.заготовка != nil {
            let своя: СпросПодачи = СпросПодачи.shared
            guard своя.подача === модель, своя.спросРазрешён else { return "" }
        }
        return запросФормы(модель)?.ключ ?? ""
    }

    /// Тело fit_demand: category, city, lang и значения, из которых сервер строит ячейку; значений нет — nil.
    static func запросФормы(_ модель: ПодачаМодель) -> ЗапросСпросаПодачи? {
        let раздел: String = модель.форма.раздел.trimmingCharacters(in: .whitespacesAndNewlines)
        let город: String = модель.форма.город.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !раздел.isEmpty, !город.isEmpty else { return nil }
        var тело: [String: Any] = ["category": раздел, "city": город, "lang": СпросПодачиText.язык]
        var части: [String] = [раздел, город]
        if let колёса = значенияКолёс(модель) {
            тело["parts"] = колёса
            части.append("p:" + строкаКлюча(колёса))
        }
        if let набор = стандартыЗаготовки(модель) {
            let std: [String: Any] = ЗаготовкаПодачи.телоСтандартов(набор)
            if !std.isEmpty {
                тело["std"] = std
                части.append("s:" + строкаСтандартов(набор))
            }
        }
        if let размер = размерОдежды(модель) {
            тело[размер.слот] = размер.значение
            части.append("z:" + размер.слот + "=" + размер.значение)
        }
        guard части.count > 2 else { return nil }
        return ЗапросСпросаПодачи(ключ: части.joined(separator: "|"), тело: тело)
    }

    /// parts шин или дисков: только поля размера (и сезон шин); главных нет — nil. Сезон ячейку не сужает (§16.1).
    private static func значенияКолёс(_ модель: ПодачаМодель) -> [String: String]? {
        guard модель.колёсаВидны else { return nil }
        let вид: String = модель.видЗапчасти
        let главные: [String]
        let ещё: [String]
        if вид == "wheel" {
            главные = ["diameter", "pcd"]
            ещё = ["width_j", "et", "dia"]
        } else {
            главные = СтрокиКолёсПодачи.ключиШин
            ещё = ["season"]
        }
        var итог: [String: String] = ["kind": вид]
        for поле in главные {
            let значение: String = (модель.форма.запчасть[поле] ?? "").trimmingCharacters(in: .whitespacesAndNewlines)
            guard !значение.isEmpty else { return nil }
            итог[поле] = значение
        }
        for поле in ещё {
            let значение: String = (модель.форма.запчасть[поле] ?? "").trimmingCharacters(in: .whitespacesAndNewlines)
            if !значение.isEmpty { итог[поле] = значение }
        }
        return итог
    }

    /// Стандарты вещи «Моего» из заготовки «Продать своё»; у шин и дисков — нет (их значения в parts).
    private static func стандартыЗаготовки(_ модель: ПодачаМодель) -> НаборСтандартов? {
        guard !модель.колёсаВидны, let набор = модель.заготовка?.стандарты, !набор.пусто else { return nil }
        return набор
    }

    /// Размер одежды и обуви — слот сайта, который рисует блок «Размер» (обычно storage); не выбран — nil.
    private static func размерОдежды(_ модель: ПодачаМодель) -> (слот: String, значение: String)? {
        guard let поле = модель.полеРазмераОдежды else { return nil }
        let значение: String = модель.значениеХарактеристики(поле.поле).trimmingCharacters(in: .whitespacesAndNewlines)
        guard !значение.isEmpty else { return nil }
        return (слот: поле.поле, значение: значение)
    }

    private static func строкаКлюча(_ поля: [String: String]) -> String {
        var куски: [String] = []
        for ключ in поля.keys.sorted() {
            let значение: String = поля[ключ] ?? ""
            куски.append(ключ + "=" + значение)
        }
        return куски.joined(separator: ",")
    }

    private static func строкаСтандартов(_ набор: НаборСтандартов) -> String {
        var куски: [String] = []
        for семья in набор.семьи {
            let поля: [String: String] = набор.поля(семья)
            куски.append(семья.rawValue + "{" + строкаКлюча(поля) + "}")
        }
        return куски.joined(separator: ";")
    }

    // MARK: Запрос

    /**
     Спросить спрос для ключа формы (из .task(id:) экрана): тот же ключ уже отвечен — ответ из памяти; иначе — не раньше
     чем через 3 с после прошлого запроса. Ключ сменился, пока ждали, — задача отменена, запроса нет.
     */
    func спросить(_ модель: ПодачаМодель, ключ: String) async {
        привязать(модель)
        guard !ключ.isEmpty, РубильникиСпросаПодачи.спрос, !нетНаСервере, !модель.правка else { return }
        if let есть = кэш[ключ] {
            показать(есть, ключ: ключ)
            return
        }
        let итог: ИтогСпросаПодачи
        if let идёт = вПути[ключ] {
            /* Тот же ключ уже спрашивает другой экран (камера → «Проверьте») — ждём его ответ, второго запроса нет. */
            итог = await идёт.value
        } else {
            if let был = последнийЗапрос {
                let прошло: TimeInterval = Date().timeIntervalSince(был)
                if прошло < Self.пауза {
                    let остаток: TimeInterval = Self.пауза - прошло
                    let наносекунды: Double = остаток * 1_000_000_000
                    let ждать: UInt64 = UInt64(max(0, наносекунды))
                    try? await Task.sleep(nanoseconds: ждать)
                    guard !Task.isCancelled else { return }
                }
            }
            guard let запрос = Self.запросФормы(модель), запрос.ключ == ключ else { return }
            последнийЗапрос = Date()
            let тело: [String: Any] = запрос.тело
            /* Отдельная задача: смена ключа отменяет ожидание экрана, но не сам запрос — его ответ ляжет в память. */
            let задача: Task<ИтогСпросаПодачи, Never> = Task { @MainActor () -> ИтогСпросаПодачи in
                let ответСервера: ИтогСпросаПодачи = await СпросПодачи.отправить(тело)
                return ответСервера
            }
            вПути[ключ] = задача
            итог = await задача.value
            вПути[ключ] = nil
        }
        /* Пока шёл запрос, могла открыться другая подача — её состояние не трогаем. */
        guard подача === модель else { return }
        switch итог {
        case .есть(let новый):
            запомнить(новый, ключ: ключ)
            /* Ключ сменился, пока ждали, — ответ только в память: на экране ответ нового ключа. */
            if !Task.isCancelled { показать(новый, ключ: ключ) }
        case .неподдерживается:
            нетНаСервере = true
        case .нетСессии, .сбой:
            break
        }
    }

    private func запомнить(_ новый: ОтветСпросаПодачи, ключ: String) {
        if кэш[ключ] == nil { порядокКэша.append(ключ) }
        кэш[ключ] = новый
        while порядокКэша.count > Self.пределКэша {
            let старый = порядокКэша.removeFirst()
            кэш[старый] = nil
        }
    }

    private func показать(_ новый: ОтветСпросаПодачи, ключ: String) {
        последнийМожно = новый.сообщитьМожно
        if ответ != новый { ответ = новый }
        if ключОтвета != ключ { ключОтвета = ключ }
    }

    private enum ИтогСпросаПодачи {
        case есть(ОтветСпросаПодачи)
        case неподдерживается
        case нетСессии
        case сбой
    }

    /// POST cabinet.php?action=fit_demand с куками и csrf; на «csrf» — свежий токен и один повтор.
    private static func отправить(_ тело: [String: Any]) async -> ИтогСпросаПодачи {
        var повторили = false
        while true {
            let токен: String
            do {
                токен = try await МоиОбъявленияAPI.токенСейчас()
            } catch {
                return .сбой
            }
            guard !токен.isEmpty else { return .нетСессии }
            var полное: [String: Any] = тело
            полное["csrf"] = токен
            let сырой: КабинетСайта.Ответ
            do {
                сырой = try await КабинетСайта.вызвать("cabinet.php?action=fit_demand", метод: "POST", тело: полное)
            } catch {
                return .сбой
            }
            let код: Int = сырой.код
            if [404, 405, 410, 501].contains(код) { return .неподдерживается }
            if код == 429 || код >= 500 { return .сбой }
            guard let j = сырой.json else { return .неподдерживается }
            let ошибка: String = МоиОбъявленияAPI.строка(j["error"])
            if ошибка == "csrf" && !повторили {
                повторили = true
                /* Токен устарел: следующий токенСейчас() прочитает страницу кабинета заново. */
                МоиОбъявленияAPI.забыть()
                continue
            }
            if ошибка == "unsupported" || ошибка == "off" { return .неподдерживается }
            if МоиОбъявленияAPI.нетСессии(j) { return .нетСессии }
            guard МоиОбъявленияAPI.да(j["ok"]) else { return .сбой }
            return .есть(разобрать(j))
        }
    }

    /// rows (не больше двух годных), city, wanted, notify. Число ниже порога (min ответа, по умолчанию 20) не берётся.
    static func разобрать(_ j: [String: Any]) -> ОтветСпросаПодачи {
        typealias A = МоиОбъявленияAPI
        var итог = ОтветСпросаПодачи()
        итог.город = String(A.строка(j["city"]).trimmingCharacters(in: .whitespacesAndNewlines).prefix(60))
        итог.ищут = max(0, A.целое(j["wanted"]))
        итог.сообщитьМожно = A.да(j["notify"])
        let минимум: Int = A.целое(j["min"])
        let порог: Int = минимум > 0 ? минимум : 20
        let ряды: [Any] = (j["rows"] as? [Any]) ?? []
        for ряд in ряды {
            guard итог.ячейки.count < 2, let р = ряд as? [String: Any] else { continue }
            let подпись: String = String(A.строка(р["label"]).trimmingCharacters(in: .whitespacesAndNewlines).prefix(60))
            let вГороде: String = числоСпроса(р["n"], порог: порог)
            let поСтране: String = числоСпроса(р["n_kz"], порог: порог)
            guard !подпись.isEmpty, !вГороде.isEmpty || !поСтране.isEmpty else { continue }
            let ячейка = ЯчейкаСпросаПодачи(ключ: A.строка(р["key"]), чья: A.строка(р["for"]), подпись: подпись,
                                            вГороде: вГороде, поСтране: поСтране)
            итог.ячейки.append(ячейка)
        }
        return итог
    }

    /// «40+» как есть, если число в начале не меньше порога; иначе пусто (меньше 20 не показываем никогда, §16.1).
    private static func числоСпроса(_ значение: Any?, порог: Int) -> String {
        let строка: String = МоиОбъявленияAPI.строка(значение).trimmingCharacters(in: .whitespacesAndNewlines)
        let цифры: String = String(строка.prefix(while: { $0.isASCII && $0.isNumber }))
        guard let число = Int(цифры), число >= порог, строка.count <= 8 else { return "" }
        return строка
    }

    // MARK: Строки

    /// «Подойдёт N людям в <город>: <почему>» по ячейкам; в городе меньше порога — по Казахстану.
    static func строки(_ ответ: ОтветСпросаПодачи, город: String) -> [String] {
        var итог: [String] = []
        let место: String = ответ.город.isEmpty ? город : ответ.город
        for ячейка in ответ.ячейки {
            let почему: String = СпросПодачиText.причина(ячейка.чья, подпись: ячейка.подпись)
            if !ячейка.вГороде.isEmpty && !место.isEmpty {
                итог.append(СпросПодачиText.строкаГорода(ячейка.вГороде, город: место, почему: почему))
            } else if !ячейка.поСтране.isEmpty {
                итог.append(СпросПодачиText.строкаСтраны(ячейка.поСтране, почему: почему))
            }
        }
        return итог
    }
}


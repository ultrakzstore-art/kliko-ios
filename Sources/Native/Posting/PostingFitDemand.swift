/**
 Строка спроса и «Сообщить им» — только когда есть что показать (иначе вида нет и места он не занимает). Запрос
 ставит экран модификатором .спросПодачи(модель) — на всегда видимом контейнере: у пустого вида своей задачи не было бы.
 */
struct СтрокаСпросаПодачи: View {
    @ObservedObject var модель: ПодачаМодель
    @ObservedObject private var спрос = СпросПодачи.shared

    init(модель: ПодачаМодель) {
        self.модель = модель
    }

    var body: some View {
        if let есть = спрос.ответДля(модель) {
            содержимое(есть)
        } else if спрос.нуженВопрос(модель) {
            вопрос
        }
    }

    /// «Продать своё»: значения «Моего» уходят в fit_demand только по этой кнопке (владелец 17.10.2026).
    private var вопрос: some View {
        let с = спрос
        let м = модель
        return VStack(alignment: .leading, spacing: 6) {
            КнопкаПодачиВторая(СпросПодачиText.т("fd_ask")) { с.разрешить(м) }
            ПодсказкаПоля(СпросПодачиText.т("fd_ask_sub"))
        }
    }

    @ViewBuilder
    private func содержимое(_ ответ: ОтветСпросаПодачи) -> some View {
        let строки: [String] = СпросПодачи.строки(ответ, город: модель.форма.город)
        let сообщить: Bool = РубильникиСпросаПодачи.сообщить && ответ.сообщитьМожно
        if !строки.isEmpty || ответ.ищут > 0 || сообщить {
            VStack(alignment: .leading, spacing: 8) {
                if !строки.isEmpty {
                    ЗаметкаПодачи(строки.joined(separator: "\n"), тон: .хорошо, значок: "person.2")
                }
                if ответ.ищут > 0 {
                    ЗаметкаПодачи(СпросПодачиText.ищут(ответ.ищут), тон: .хорошо, значок: "magnifyingglass")
                }
                if сообщить {
                    ПереключательПодачи(СпросПодачиText.т("fd_notify"), подпись: СпросПодачиText.т("fd_notify_sub"),
                                        включено: включеноСвязь)
                }
            }
        }
    }

    private var включеноСвязь: Binding<Bool> {
        let с = спрос
        return Binding(get: { с.сообщитьВключено }, set: { новое in с.выбрать(новое) })
    }
}

/// Запрос спроса при смене ключа формы: .task(id:) — сменился ключ, прежнее ожидание отменяется.
struct СлухСпросаПодачи: ViewModifier {
    @ObservedObject var модель: ПодачаМодель
    /// Нажали «Узнать, скольким подойдёт» — ключ формы появляется, и задача спрашивает (без него экран не перерисуется).
    @ObservedObject private var спрос = СпросПодачи.shared
    let когда: Bool

    init(модель: ПодачаМодель, когда: Bool) {
        self.модель = модель
        self.когда = когда
    }

    func body(content: Content) -> some View {
        let ключ: String = когда ? СпросПодачи.ключФормы(модель) : ""
        return content.task(id: ключ) {
            await СпросПодачи.shared.спросить(модель, ключ: ключ)
        }
    }
}

extension View {
    /// Спрос при подаче (§16.1): при смене раздела, города или значений — fit_demand (только при fit_demand_post).
    func спросПодачи(_ модель: ПодачаМодель, когда: Bool = true) -> some View {
        modifier(СлухСпросаПодачи(модель: модель, когда: когда))
    }
}

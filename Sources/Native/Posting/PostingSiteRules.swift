/// Куда вести отказ сервера: ключ строки ошибки под полем и экран с этим полем.
struct МестоОтказаПодачи {
    let ключ: String
    let шаг: ШагПодачи
}

extension ПодачаМодель {

    // MARK: - Шаги

    /// Название шага, как у сайта по разделу (полоса шагов, карточки шагов).
    func имяШагаСайта(_ ш: ШагПодачи) -> String {
        let т = ПодачаСайтаText.т
        switch ш {
        case .данные:
            switch режим {
            case .авто: return т("step_about_car")
            case .недвижимость: return т("step_about_obj")
            case .товар, .запчасти, .услуга, .работа:
                return форма.тип == "rentgood" && форма.аренда && !форма.тожеПродаю ? т("step_what_rent") : ш.название
            }
        case .цена:
            if чистыйПрокат { return т("step_terms") }
            if режим == .недвижимость { return т(форма.аренда ? "step_rent_pay" : "step_price_only") }
            if режим == .авто { return т("step_price_only") }
            return ш.название
        case .адрес, .дополнительно, .проверка:
            return т(виден(.дополнительно) ? "step_where_extra" : "step_where")
        case .фото, .характеристики:
            return ш.название
        }
    }

    /// Стоим на последнем экране — главная кнопка «Опубликовать» (в правке — без «Далее»).
    var последнийШаг: Bool {
        экранныйШаг == (видимыеШаги.last ?? .адрес)
    }

    // MARK: - Правила разделов

    /**
     Чистый прокат: «Сдать вещь» (или правка сдаваемого без цены продажи) без «Продаю тоже» — шаг «Условия» без цены
     продажи, обмена, рассрочки и доставки (сайт 14.10.2026, «прокат вещи — условия своим шагом»).
     */
    var чистыйПрокат: Bool {
        guard режим == .товар, форма.аренда, !форма.тожеПродаю else { return false }
        return форма.тип == "rentgood" || (правка && ценаЧислом <= 0)
    }

    /// VIN — только в правке (сайт 14.10.2026: при подаче поля нет, пока проверки выключены; в схеме приложения
    /// признака нет).
    var vinВПодаче: Bool { vinРазрешён && правка }

    /// rules.brand_optional_cats: раздел или его предок в списке — марка по желанию.
    var маркаПоЖеланиюРаздела: Bool {
        guard let список = схема?.маркаПоЖеланию, !список.isEmpty, !форма.раздел.isEmpty else { return false }
        return справочники.внутри(форма.раздел, список)
    }

    /// «Вторичка | Новостройка» — у продажи квартиры, дома и коммерции.
    var новостройкаСпрашивается: Bool {
        режим == .недвижимость && форма.сделка == "sale" && ["apartment", "house", "commercial"].contains(форма.вид)
    }

    // MARK: - Недвижимость: гараж, комната, owner

    /// Поля объекта: REALTY_FIELDS; у гаража без полей в справочнике — свои; у квартиры — «Комната» в числе комнат.
    func поляОбъекта(сделка: String, вид: String) -> [ПолеМастера] {
        guard !сделка.isEmpty, !вид.isEmpty else { return [] }
        var поля = справочники.недвижимость[сделка]?[вид] ?? []
        if поля.isEmpty && вид == "garage" { поля = запасныеПоляГаража(сделка) }
        if вид == "apartment" { поля = поля.map { сКомнатой($0) } }
        return поля
    }

    /// rooms у квартиры: «Комната» (room) первым вариантом, если справочник сайта его ещё не знает.
    private func сКомнатой(_ поле: ПолеМастера) -> ПолеМастера {
        guard поле.id == "rooms", !поле.варианты.isEmpty, !поле.варианты.contains(where: { $0.ключ == "room" }) else {
            return поле
        }
        let комната = ВариантПоля(ключ: "room", подпись: ПодачаСайтаText.т("rw_room"))
        return ПолеМастера(id: поле.id, подпись: поле.подпись, вид: поле.вид, варианты: [комната] + поле.варианты,
                           единица: поле.единица, обязательно: поле.обязательно)
    }

    /// Гараж, когда REALTY_FIELDS ещё без него: тип, площадь (обязательна), кто размещает; у продажи — документы
    /// квартиры, у аренды — срок (обязателен). Подписи и варианты owner, docs, term — из полей квартиры той же сделки.
    private func запасныеПоляГаража(_ сделка: String) -> [ПолеМастера] {
        let т = ПодачаСайтаText.т
        let образец = (справочники.недвижимость[сделка]?["apartment"] ?? [])
            + (справочники.недвижимость[сделка]?["commercial"] ?? [])
        func взять(_ id: String) -> ПолеМастера? { образец.first(where: { $0.id == id }) }
        var поля: [ПолеМастера] = [
            ПолеМастера(id: "gtype", подпись: т("gt_label"), вид: "chips",
                        варианты: [ВариантПоля(ключ: "garage", подпись: т("gt_garage")),
                                   ВариантПоля(ключ: "parking", подпись: т("gt_parking"))],
                        единица: "", обязательно: false)
        ]
        let площадь = взять("area")
        let единица = площадь?.единица ?? ""
        поля.append(ПолеМастера(id: "area", подпись: площадь?.подпись ?? т("gt_area"), вид: "num", варианты: [],
                                единица: единица.isEmpty ? "м²" : единица, обязательно: true))
        if let владелец = взять("owner") {
            поля.append(владелец)
        } else {
            поля.append(ПолеМастера(id: "owner", подпись: т("gt_owner"), вид: "chips",
                                    варианты: [ВариантПоля(ключ: "owner", подпись: т("gt_owner_o")),
                                               ВариантПоля(ключ: "agent", подпись: т("gt_owner_a"))],
                                    единица: "", обязательно: false))
        }
        if сделка == "rent" {
            if let срок = взять("term") {
                поля.append(ПолеМастера(id: срок.id, подпись: срок.подпись, вид: срок.вид, варианты: срок.варианты,
                                        единица: срок.единица, обязательно: true))
            } else {
                поля.append(ПолеМастера(id: "term", подпись: т("gt_term"), вид: "chips",
                                        варианты: [ВариантПоля(ключ: "long", подпись: т("gt_long")),
                                                   ВариантПоля(ключ: "daily", подпись: т("gt_daily"))],
                                        единица: "", обязательно: true))
            }
        } else if let документы = взять("docs") {
            поля.append(документы)
        }
        return поля
    }

    /// Значения нового объекта: «Собственник» сразу; у гаража — «Гараж», у его аренды — «длительно».
    func исходныеЗначенияОбъекта(вид: String, сделка: String) -> [String: String] {
        var значения: [String: String] = ["owner": "owner"]
        if вид == "garage" {
            значения["gtype"] = "garage"
            if сделка == "rent" { значения["term"] = "long" }
        }
        return значения
    }

    /// Раздел объекта по виду и значениям, как ставит сайт: гараж — garages-parking (паркоместо — parking-space),
    /// комната — rooms, квартира — apartments, дом — houses, коммерция — commercial-realty, участок — land.
    /// Раздела нет в дереве — ближайший общий; ничего нет — nil (раздел не трогаем).
    func разделОбъекта(вид: String, значения: [String: String]) -> String? {
        let ключ: String
        switch вид {
        case "garage": ключ = значения["gtype"] == "parking" ? "parking-space" : "garages-parking"
        case "apartment": ключ = значения["rooms"] == "room" ? "rooms" : "apartments"
        case "house": ключ = "houses"
        case "commercial": ключ = "commercial-realty"
        case "land": ключ = "land"
        default: return nil
        }
        if справочники.разделы[ключ] != nil { return ключ }
        if вид == "garage" && справочники.разделы["garages-parking"] != nil { return "garages-parking" }
        if вид == "apartment" && справочники.разделы["apartments"] != nil { return "apartments" }
        return nil
    }

    /// Вид или значения объекта поменялись — раздел следом (гараж и паркоместо, комната и квартира). Подраздел,
    /// выбранный руками внутри нужного, не трогаем.
    func согласоватьРазделНедвижимости() {
        guard режим == .недвижимость, !форма.вид.isEmpty,
              let нужный = разделОбъекта(вид: форма.вид, значения: форма.недвижимость) else { return }
        let сейчас = форма.раздел
        guard сейчас != нужный else { return }
        let особые: Set<String> = ["rooms", "parking-space"]
        if !особые.contains(сейчас) && справочники.внутри(сейчас, [нужный]) { return }
        выбратьРаздел(нужный)
    }

    /// Мастер объекта уже заполнил вид и обязательные поля — «Характеристики» жилья перешагиваются.
    var объектЗаполнен: Bool {
        guard !форма.сделка.isEmpty, !форма.вид.isEmpty else { return false }
        return поляНедвижимости.filter { $0.обязательно && $0.вид != "toggle" }
            .allSatisfy { !(форма.недвижимость[$0.id] ?? "").trimmingCharacters(in: .whitespaces).isEmpty }
    }

    // MARK: - «Замеры вещи» (rules.fit)

    /// Вид из rules.fit.cats для раздела (вверх по дереву) или «ask»; nil — блока нет.
    var видЗамеровРаздела: String? {
        guard let правила = схема?.замеры, режим == .товар, !форма.раздел.isEmpty else { return nil }
        return справочники.вверх(форма.раздел, правила.разделы)
    }

    var замерыВидны: Bool { видЗамеровРаздела != nil }

    /// Вид вещи для ключей: назван разделом — он; «ask» — выбранный продавцом (пусто — ещё не выбран).
    var видЗамеров: String {
        guard let назначено = видЗамеровРаздела else { return "" }
        return назначено == "ask" ? (форма.замеры?.вид ?? "") : назначено
    }

    var ключиЗамеров: [String] {
        guard let правила = схема?.замеры else { return [] }
        let вид = видЗамеров
        return вид.isEmpty ? [] : (правила.ключи[вид] ?? [])
    }

    /**
     fit для submit и edit_item: числа в см; kind — только в разделах, где вид выбирает продавец. nil — ключ не слать:
     блока нет, в новой — пусто, в правке — замеры не трогали (пустой объект в правке снимает замеры).
     */
    func телоЗамеров() -> [String: Any]? {
        guard let назначено = видЗамеровРаздела else { return nil }
        let вид = видЗамеров
        var итог: [String: Any] = [:]
        for ключ in ключиЗамеров {
            let текст = (форма.замеры?.значения[ключ] ?? "").replacingOccurrences(of: ",", with: ".")
                .trimmingCharacters(in: .whitespaces)
            guard let число = Double(текст), число > 0, число.isFinite else { continue }
            итог[ключ] = (число * 10).rounded() / 10
        }
        if назначено == "ask" && !вид.isEmpty && !итог.isEmpty { итог["kind"] = вид }
        if правка {
            guard форма.замеры != исходнаяФорма?.замеры else { return nil }
            return итог
        }
        return итог.isEmpty ? nil : итог
    }

    /// Поле fit в теле запроса (имя — rules.fit.field).
    func дописатьЗамеры(_ тело: inout [String: Any]) {
        guard let замеры = телоЗамеров() else { return }
        тело[схема?.замеры?.поле ?? "fit"] = замеры
    }

    // MARK: - Отказ сервера — на экране с полем

    /**
     Отказ submit или edit_item с готовым текстом: поле узнали (field ответа, иначе слова отказа) — строка под ним и
     переход на его экран; фото — к фото. false — не узнали, покажет общая плашка.
     */
    func разобратьОтказНаШаге(_ j: [String: Any]) -> Bool {
        let текст = МоиОбъявленияAPI.строка(j["error"]).trimmingCharacters(in: .whitespacesAndNewlines)
        guard !текст.isEmpty, !КабинетСайта.машинныйКод(текст) else { return false }
        guard let место = местоОтказа(МоиОбъявленияAPI.строка(j["field"]).lowercased(), текст.lowercased()) else {
            return false
        }
        let короткий = быстрый && !правка
        if место.ключ == "photo" {
            показать(текст)
            if короткий { кКамере() } else { шаг = .фото }
            return true
        }
        пометить(место.ключ, текст)
        if !короткий { шаг = место.шаг }
        return true
    }

    private func местоОтказа(_ поле: String, _ текст: String) -> МестоОтказаПодачи? {
        let марка = режим == .авто ? МестоОтказаПодачи(ключ: "auto", шаг: ШагПодачи.характеристики)
            : МестоОтказаПодачи(ключ: "brand", шаг: ШагПодачи.характеристики)
        let название = режим == .авто ? МестоОтказаПодачи(ключ: "auto", шаг: ШагПодачи.характеристики)
            : МестоОтказаПодачи(ключ: "title", шаг: ШагПодачи.данные)
        switch поле {
        case "title": return название
        case "description", "desc": return МестоОтказаПодачи(ключ: "desc", шаг: ШагПодачи.данные)
        case "category": return МестоОтказаПодачи(ключ: "category", шаг: ШагПодачи.данные)
        case "brand", "model", "year", "mileage": return марка
        case "price", "rent_price_day": return МестоОтказаПодачи(ключ: "price", шаг: ШагПодачи.цена)
        case "city", "region", "district": return МестоОтказаПодачи(ключ: "city", шаг: ШагПодачи.адрес)
        case "hours", "hours_mode": return МестоОтказаПодачи(ключ: "hours", шаг: ШагПодачи.адрес)
        case "images", "image", "photo", "photos": return МестоОтказаПодачи(ключ: "photo", шаг: ШагПодачи.фото)
        default: break
        }
        /* Поля в ответе нет — по словам отказа сайта («Укажите марку», «Добавьте хотя бы одно фото», город). */
        if текст.contains("марк") || текст.contains("бренд") { return марка }
        if текст.contains("фото") { return МестоОтказаПодачи(ключ: "photo", шаг: ШагПодачи.фото) }
        if текст.contains("город") { return МестоОтказаПодачи(ключ: "city", шаг: ШагПодачи.адрес) }
        if текст.contains("назван") { return название }
        if текст.contains("описан") { return МестоОтказаПодачи(ключ: "desc", шаг: ШагПодачи.данные) }
        return nil
    }

    // MARK: - После подачи: item_status

    /// Ответ submit без вердикта: до 5 запросов item_status раз в 2 с, пока на экране «Объявление на проверке».
    func опроситьСтатусПодачи(_ id: String) {
        guard !id.isEmpty else { return }
        let номер = id.addingPercentEncoding(withAllowedCharacters: .alphanumerics) ?? id
        let ждём = ИтогПодачи.наПроверке(id: id)
        Task { @MainActor [weak self] in
            for _ in 0..<5 {
                try? await Task.sleep(nanoseconds: 2_000_000_000)
                guard self?.итог == ждём else { return }
                let ответ = try? await МоиОбъявленияAPI.получить("cabinet.php?action=item_status&id=" + номер)
                guard let модель = self, модель.итог == ждём else { return }
                guard let j = ответ, МоиОбъявленияAPI.да(j["ok"]) else { continue }
                let статус = МоиОбъявленияAPI.строка(j["status"])
                if статус == "approved" || статус == "active" {
                    withAnimation(ДвижениеСайта.появление) { модель.итог = .опубликовано(id: id) }
                    return
                }
                if статус == "rejected" || статус == "deleted_permanent" {
                    let проблемы = ((j["ai_issues"] as? [Any]) ?? []).map { МоиОбъявленияAPI.строка($0) }
                        .filter { !$0.isEmpty }
                    var причина = МоиОбъявленияAPI.строка(j["reason"]).trimmingCharacters(in: .whitespacesAndNewlines)
                    if причина.isEmpty { причина = проблемы.joined(separator: ", ") }
                    if причина.isEmpty { причина = модель.т("mod_rej_d") }
                    модель.номерОтклонённого = статус == "rejected" ? id : ""
                    withAnimation(ДвижениеСайта.появление) { модель.итог = .отклонено(причина) }
                    return
                }
            }
        }
    }

    // MARK: - «Исправить» после отказа

    /// Причина отказа по номеру объявления — над формой правки, открытой «Исправить».
    static var причиныОтказа: [String: String] = [:]

    var причинаПравки: String? {
        guard правка, let причина = Self.причиныОтказа[номерПравки], !причина.isEmpty else { return nil }
        return причина
    }

    /// «Исправить» в окне отказа: мастер уже закрыт — правка этого объявления с причиной над формой.
    static func открытьИсправление(_ id: String, причина: String) {
        guard !id.isEmpty else { return }
        причиныОтказа[id] = причина
        Task { @MainActor in
            try? await Task.sleep(nanoseconds: 900_000_000)
            guard ПодачаОкно.shared.цель == nil else { return }
            ПодачаОкно.shared.открыть(.правка(id))
        }
    }

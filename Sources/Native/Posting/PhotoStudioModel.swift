import SwiftUI
import UIKit

/**
 ИИ-СТУДИЯ ФОТО ПОДАЧИ — СОСТОЯНИЕ (владелец 13.10.2026: «свой редактор фото для техники через ИИ»).

 Ход открытия: фото плитки (с телефона, а уже загруженное — с сайта) → «сканирование» (по фото бежит зелёная линия,
 пока Vision ищет предмет; не меньше 1,3 с — иначе эффект мелькнёт) → «отрыв» (фон гаснет, предмет приподнимается и
 светится) → «перенос» (предмет плавно встаёт по центру студийного фона) → готово: шторка «До / После», фоны, «Тень»,
 «Свет и цвет». «Уменьшение движения» — сразу готово, без эффектов. Предмета нет — честно «не нашли» и «Только свет и
 цвет». Вся обработка — в Task.detached (ДвижокСтудииФото); закрыл студию — работа отменяется.

 «Готово» заменяет фото плитки (то же место, тот же кадр плана) и грузит его тем же upload_photo; исходная плитка
 запоминается (ОригиналыСтудииФото) — «Вернуть как было» возвращает её адрес без новой загрузки. Повторное открытие
 студии на той же плитке начинает с оригинала, а не с уже обработанного кадра.
 */
@MainActor
final class МодельСтудииФото: ObservableObject {
    enum Этап: Equatable {
        /// Тянем фото с телефона или с сайта.
        case загрузка
        /// Vision ищет предмет, по фото бежит зелёная линия.
        case скан
        /// Фон гаснет, предмет приподнимается над ним.
        case отрыв
        /// Предмет встаёт на место каталога, под ним проявляется студийный фон.
        case перенос
        case готово
        /// Vision не нашёл предмет — предложить «Только свет и цвет».
        case нетПредмета
        /// Фото не открылось.
        case ошибка
    }

    let плитка: UUID
    @Published private(set) var этап: Этап = .загрузка
    @Published private(set) var исходник: CGImage? = nil
    @Published private(set) var анализ: АнализСтудииФото? = nil
    /// «После» целиком и прежнее «После» под ним: новое проявляется поверх старого — без провала в «До».
    @Published private(set) var после: CGImage? = nil
    @Published private(set) var прежнееПосле: CGImage? = nil
    @Published private(set) var версия = 0
    /// Студийный фон без предмета — только на время переноса.
    @Published private(set) var фонПолёта: CGImage? = nil
    @Published private(set) var настройки = НастройкиСтудииФото()
    /// Шторка: доля кадра слева, где видно «До». 0 — всё «После», 1 — всё «До».
    @Published var доля: CGFloat = 0
    @Published private(set) var сохраняем = false
    /// У плитки есть оригинал до студии — «Вернуть как было».
    @Published private(set) var естьОригинал = false
    /// Предмет не нашли — фоны недоступны, работает только «Свет и цвет».
    @Published private(set) var толькоСвет = false
    @Published private(set) var плашка: String? = nil

    private var сборка: Task<Void, Never>? = nil
    private var номерСборки = 0
    private var плашкаЗадача: Task<Void, Never>? = nil

    init(плитка: UUID) {
        self.плитка = плитка
    }

    private func т(_ ключ: String) -> String { СтудияФотоText.т(ключ) }

    /// Сейчас студийный фон (а не «Свой» и не «только свет»).
    var вырез: Bool { анализ?.вырез(настройки) ?? false }
    /// Есть что сохранять: студийный фон или хотя бы свет и цвет.
    var изменено: Bool { вырез || настройки.свет }
    /// Вырезанный предмет на исходном месте — он «перелетает» на место каталога.
    var предметДляПолёта: CGImage? { анализ?.предметДля(настройки) }

    // MARK: - Открытие

    func запустить(подача: ПодачаМодель) async {
        guard этап == .загрузка, исходник == nil else { return }
        let тихо = ДвижениеСайта.тихо
        let оригинал = ОригиналыСтудииФото.shared.оригинал(плитка)
        естьОригинал = оригинал != nil
        guard let источник = оригинал ?? подача.плитки.first(where: { $0.id == плитка }),
              let данные = await Self.данные(источник) else {
            if !Task.isCancelled { этап = .ошибка }
            return
        }
        guard !Task.isCancelled else { return }
        let прочитано = await Task.detached(priority: .userInitiated) { () -> КадрСтудииФото in
            КадрСтудииФото(картинка: ДвижокСтудииФото.кадр(данные))
        }.value
        guard !Task.isCancelled else { return }
        guard let кадр = прочитано.картинка else {
            этап = .ошибка
            return
        }
        withAnimation(ДвижениеСайта.появление) {
            исходник = кадр
            этап = .скан
        }
        let начало = Date()
        let ящик = КадрСтудииФото(картинка: кадр)
        let разбор = Task.detached(priority: .userInitiated) { () -> АнализСтудииФото? in
            guard let картинка = ящик.картинка else { return nil }
            return ДвижокСтудииФото.разобрать(картинка)
        }
        let итогРазбора = await withTaskCancellationHandler {
            await разбор.value
        } onCancel: {
            разбор.cancel()
        }
        guard !Task.isCancelled else { return }
        guard let найдено = итогРазбора else {
            этап = .ошибка
            return
        }
        if !тихо {
            let прошло = Date().timeIntervalSince(начало)
            if прошло < 1.3 { try? await Task.sleep(nanoseconds: UInt64((1.3 - прошло) * 1_000_000_000)) }
            guard !Task.isCancelled else { return }
        }
        анализ = найдено
        guard найдено.естьПредмет else {
            толькоСвет = true
            настройки.фон = .свой
            withAnimation(ДвижениеСайта.смена) { этап = .нетПредмета }
            ОткликСайта.предупреждение()
            return
        }
        /* «После» и фон для полёта — заранее: анимация не ждёт отрисовки. */
        let н = настройки
        let слои = await Task.detached(priority: .userInitiated) { () -> СлоиСтудииФото in
            СлоиСтудииФото(итог: ДвижокСтудииФото.итог(найдено, н),
                           фон: тихо ? nil : ДвижокСтудииФото.фонПолёта(найдено, н))
        }.value
        guard !Task.isCancelled else { return }
        после = слои.итог
        фонПолёта = слои.фон
        версия += 1
        if тихо || слои.фон == nil {
            withAnimation(ДвижениеСайта.смена) { этап = .готово }
            ОткликСайта.успех()
            return
        }
        await показатьПеренос()
    }

    /// Отрыв → перенос → готово, затем шторка один раз выглядывает «До» и возвращается.
    private func показатьПеренос() async {
        withAnimation(.easeOut(duration: 0.45)) { этап = .отрыв }
        ОткликСайта.выбор()
        try? await Task.sleep(nanoseconds: 600_000_000)
        guard !Task.isCancelled else { return }
        withAnimation(.spring(response: 0.7, dampingFraction: 0.86)) { этап = .перенос }
        try? await Task.sleep(nanoseconds: 760_000_000)
        guard !Task.isCancelled else { return }
        withAnimation(.easeInOut(duration: 0.3)) { этап = .готово }
        ОткликСайта.успех()
        try? await Task.sleep(nanoseconds: 500_000_000)
        /* Фон полёта уже погас под «После» — память ему больше не нужна. */
        фонПолёта = nil
        guard !Task.isCancelled, этап == .готово, доля == 0 else { return }
        let выглянуть: CGFloat = 0.38
        withAnimation(.easeInOut(duration: 0.55)) { доля = выглянуть }
        try? await Task.sleep(nanoseconds: 850_000_000)
        /* Человек уже взялся за шторку — не мешаем. */
        guard !Task.isCancelled, abs(доля - выглянуть) < 0.001 else { return }
        withAnimation(.easeInOut(duration: 0.55)) { доля = 0 }
    }

    /// Файл фото: ещё не загруженное — с телефона; загруженное — с сайта по адресу. nil — не вышло.
    private static func данные(_ плитка: ПлиткаФото) async -> Data? {
        if let картинка = плитка.картинка, !картинка.isEmpty { return картинка }
        guard let адрес = Config.url(плитка.url) else { return nil }
        guard let ответ = try? await URLSession.shared.data(from: адрес) else { return nil }
        if let http = ответ.1 as? HTTPURLResponse, !(200..<300).contains(http.statusCode) { return nil }
        return ответ.0.isEmpty ? nil : ответ.0
    }

    func остановить() {
        сборка?.cancel()
        плашкаЗадача?.cancel()
    }

    // MARK: - Выбор

    func выбратьФон(_ фон: ФонСтудииФото) {
        guard этап == .готово, настройки.фон != фон, !толькоСвет || фон == .свой else { return }
        настройки.фон = фон
        ОткликСайта.выбор()
        /* Смотрел «До» целиком — новый фон показываем сразу. */
        if доля > 0.9 { withAnimation(ДвижениеСайта.мягко(.easeInOut(duration: 0.45))) { доля = 0 } }
        пересобрать()
    }

    func переключитьТень() {
        guard этап == .готово, вырез else { return }
        настройки.тень.toggle()
        ОткликСайта.выбор()
        пересобрать()
    }

    func переключитьСвет() {
        guard этап == .готово else { return }
        настройки.свет.toggle()
        ОткликСайта.выбор()
        пересобрать()
    }

    /// Предмета нет: «Только свет и цвет» — весь кадр со светом и цветом, фон свой.
    func толькоСветИЦвет() {
        guard let а = анализ, этап == .нетПредмета else { return }
        толькоСвет = true
        настройки.фон = .свой
        настройки.свет = true
        let н = настройки
        сборка?.cancel()
        номерСборки += 1
        let номер = номерСборки
        сборка = Task { [weak self] in
            let слои = await Task.detached(priority: .userInitiated) { () -> СлоиСтудииФото in
                СлоиСтудииФото(итог: ДвижокСтудииФото.итог(а, н), фон: nil)
            }.value
            guard let self, !Task.isCancelled, номер == self.номерСборки else { return }
            self.после = слои.итог
            self.версия += 1
            withAnimation(ДвижениеСайта.мягко(.easeInOut(duration: 0.4))) { self.этап = .готово }
            ОткликСайта.успех()
        }
    }

    /// Новое «После» по настройкам — в фоне; быстрые нажатия подряд: ставится только последнее.
    private func пересобрать() {
        guard let а = анализ else { return }
        сборка?.cancel()
        номерСборки += 1
        let номер = номерСборки
        let н = настройки
        сборка = Task { [weak self] in
            let слои = await Task.detached(priority: .userInitiated) { () -> СлоиСтудииФото in
                СлоиСтудииФото(итог: ДвижокСтудииФото.итог(а, н), фон: nil)
            }.value
            guard let self, !Task.isCancelled, номер == self.номерСборки else { return }
            guard let картинка = слои.итог else {
                self.показатьПлашку(self.т("st_save_fail"))
                return
            }
            self.прежнееПосле = self.после
            withAnimation(ДвижениеСайта.мягко(.easeInOut(duration: 0.35))) {
                self.после = картинка
                self.версия += 1
            }
        }
    }

    // MARK: - Готово

    /// Итог в JPEG тем же путём, что любое фото подачи. Знак — только на новом фоне: у «Своего» он уже стоит.
    func сохранить() async -> ГотовоеФото? {
        guard let а = анализ, !сохраняем, этап == .готово, изменено else { return nil }
        сохраняем = true
        let н = настройки
        let знак = а.вырез(н)
        let готовое = await Task.detached(priority: .userInitiated) { () -> ГотовоеФото? in
            guard let итог = ДвижокСтудииФото.итог(а, н) else { return nil }
            return ОбработкаФото.подготовить(UIImage(cgImage: итог), водянойЗнак: знак)
        }.value
        сохраняем = false
        if готовое == nil {
            ОткликСайта.предупреждение()
            показатьПлашку(т("st_save_fail"))
        }
        return готовое
    }

    private func показатьПлашку(_ текст: String) {
        плашкаЗадача?.cancel()
        withAnimation(ДвижениеСайта.появление) { плашка = текст }
        плашкаЗадача = Task { [weak self] in
            try? await Task.sleep(nanoseconds: 2_600_000_000)
            guard let self, !Task.isCancelled else { return }
            withAnimation(ДвижениеСайта.уход) { self.плашка = nil }
        }
    }
}

// MARK: - Оригиналы до студии

/**
 Плитки до студии — для «Вернуть как было» — и подачи, где плашку «Сделать как в каталоге» уже закрыли или студией
 уже пользовались. Только в памяти: оригинал — адрес на сайте (или ещё не загруженный файл) и миниатюра; после
 перезапуска приложения вернуть уже нечего — фото остаётся обработанным. Не больше 30 плиток.
 */
@MainActor
final class ОригиналыСтудииФото {
    static let shared = ОригиналыСтудииФото()

    private var плитки: [UUID: ПлиткаФото] = [:]
    private var порядок: [UUID] = []
    private var закрытые: [СлабаяПодачаСтудии] = []

    private init() {}

    func оригинал(_ id: UUID) -> ПлиткаФото? { плитки[id] }

    /// Первый оригинал плитки не перезаписывается: студия поверх студии возвращает к самому первому.
    func запомнить(_ плитка: ПлиткаФото) {
        guard плитки[плитка.id] == nil else { return }
        плитки[плитка.id] = плитка
        порядок.append(плитка.id)
        while порядок.count > 30 {
            плитки[порядок.removeFirst()] = nil
        }
    }

    func забыть(_ id: UUID) {
        плитки[id] = nil
        порядок.removeAll { $0 == id }
    }

    func плашкаЗакрыта(_ подача: ПодачаМодель) -> Bool {
        закрытые.contains { $0.подача === подача }
    }

    func закрытьПлашку(_ подача: ПодачаМодель) {
        закрытые.removeAll { $0.подача == nil }
        guard !плашкаЗакрыта(подача) else { return }
        закрытые.append(СлабаяПодачаСтудии(подача))
    }
}

/// Слабая ссылка на подачу: закрытая подача не держится в памяти ради флажка плашки.
final class СлабаяПодачаСтудии {
    weak var подача: ПодачаМодель?

    init(_ подача: ПодачаМодель) {
        self.подача = подача
    }
}

// MARK: - Подача

extension ПодачаМодель {
    /// Раздел — техника: электроника (телефоны, компьютеры, ТВ и звук, фото, игры, оргтехника), бытовая техника и
    /// техника для красоты. Раздел ещё не выбран — нет.
    var разделТехники: Bool {
        let раздел = форма.раздел
        guard !раздел.isEmpty else { return false }
        return РазделыСайта.корень(раздел) == "electronics"
            || РазделыСайта.внутри(раздел, ["appliances", "beauty-appliances"])
    }

    /// Плитку можно открыть в студии: фото уже обработано (загружено или ждёт повтора), не грузится сейчас и это не
    /// постер-обложка услуги.
    func студияДоступна(_ плитка: ПлиткаФото) -> Bool {
        Config.студияФото && !плитка.грузится && (плитка.готова || плитка.картинка != nil) && !этоОбложка(плитка)
    }

    /// Плашка «Сделать как в каталоге» над фото: техника, есть подходящее фото, плашку не закрывали и студией в этой
    /// подаче ещё не пользовались. Открывает первое подходящее (обложку).
    var плиткаДляПлашкиСтудии: ПлиткаФото? {
        guard Config.студияФото, разделТехники, !ОригиналыСтудииФото.shared.плашкаЗакрыта(self) else { return nil }
        return плитки.first { студияДоступна($0) }
    }

    /// «Готово» студии: кадр плитки заменяется (место и кадр плана те же), оригинал запоминается, новый уходит на сайт.
    func заменитьФотоСтудией(_ id: UUID, _ готовое: ГотовоеФото) {
        guard let место = плитки.firstIndex(where: { $0.id == id }) else { return }
        ОригиналыСтудииФото.shared.запомнить(плитки[место])
        ОригиналыСтудииФото.shared.закрытьПлашку(self)
        var плитка = плитки[место]
        плитка.url = ""
        плитка.картинка = готовое.картинка
        плитка.миниатюра = готовое.миниатюра
        плитка.превью = UIImage(data: готовое.миниатюра) ?? UIImage(data: готовое.картинка)
        плитка.ошибка = nil
        плитка.грузится = true
        плитка.этап = 1
        плитки[место] = плитка
        ОткликСайта.успех()
        Task { @MainActor in await self.загрузить(id) }
    }

    /// «Вернуть как было»: плитка снова с исходным фото. Уже было на сайте — без новой загрузки.
    func вернутьФотоДоСтудии(_ id: UUID) {
        guard let было = ОригиналыСтудииФото.shared.оригинал(id),
              let место = плитки.firstIndex(where: { $0.id == id }), !плитки[место].грузится else { return }
        var плитка = плитки[место]
        плитка.url = было.url
        плитка.картинка = было.картинка
        плитка.миниатюра = было.миниатюра
        плитка.превью = было.превью
        плитка.ошибка = nil
        плитка.грузится = false
        плитка.этап = 0
        плитки[место] = плитка
        ОригиналыСтудииФото.shared.забыть(id)
        показать(СтудияФотоText.т("st_reverted"))
        if плитка.url.isEmpty && плитка.картинка != nil {
            Task { @MainActor in await self.загрузить(id) }
        }
    }
}

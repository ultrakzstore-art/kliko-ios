    /// Сводка отзывов для плитки «Отзывы»: тот же запрос и та же память на 5 минут, что у витрины
    /// (ДействияСПродавцом.загрузитьОтзывы), — возврат к кабинету в эти 5 минут сеть не трогает. Сменился человек —
    /// чужая сводка забыта сразу; не вышло (нет сети) — прежняя своя остаётся, а без неё плитка без числа, но живая.
    private func загрузитьСводкуОтзывов() async {
        let номер = свойНомер
        if отзывыЧьи != номер {
            отзывыЧьи = номер
            сводкаОтзывов = nil
            ПамятьКабинета.отзывыЧьи = номер
            ПамятьКабинета.сводкаОтзывов = nil
        }
        guard Config.продавецОтзывы, ВитринаПродавцаAPI.годный(номер) else { return }
        guard let пришло = await ДействияСПродавцом.shared.загрузитьОтзывы(номер),
              !Task.isCancelled, номер == свойНомер, пришло != сводкаОтзывов else { return }
        сводкаОтзывов = пришло
        ПамятьКабинета.сводкаОтзывов = пришло
    }


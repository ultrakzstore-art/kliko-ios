                              подпись: число(недавние.запросы.count),
                              вопрос: CabinetText.т("search_q"), пояснение: CabinetText.т("search_msg"),
                              доступно: !недавние.запросы.isEmpty) {
                    недавние.очиститьЗапросы()
                }
            }
            /* «Моё» (16.10.2026): машины, устройства, мерки и фото — только на телефоне; удаляются одним шагом. */
            if Config.моё {
                СтрокаОчистки(МоёText.т("my_data_row"), значок: "person.crop.rectangle.stack",
                              подпись: моёБайт > 0 && !моё.пусто ? ДанныеТелефона.размер(моёБайт) : nil,
                              вопрос: МоёText.т("my_delete_all_q"), пояснение: МоёText.т("my_data_msg"),
                              доступно: !моё.пусто) {
                    моё.стереть()
                    моёБайт = 0
                }
                .task(id: моё.запись) {
                    let байт = await моё.байт()
                    if байт != моёБайт { моёБайт = байт }
                }
            }
        } header: {
            ЗаголовокГруппыКабинета(CabinetText.т("data"))
        } footer: {
            if Config.избранное || Config.недавние {
                Text(CabinetText.т(избранноеВАккаунте ? "data_footer_synced" : "data_footer"))
            }
        }
    }

    /// Этап 35: избранное этого телефона сверено с аккаунтом вошедшего (СинхронИзбранного).
    private var избранноеВАккаунте: Bool {
        Config.избранноеССайтом && Config.избранное && синхронИзбранного.связано
    }

    private func число(_ сколько: Int) -> String? {
        сколько > 0 ? String(сколько) : nil
    }

    /// Размер кэша вне главного потока; те же мегабайты (строка показывает их) — без записи и без прохода.
    private func пересчитатьКэш() async {
        let байт = await ДанныеТелефона.размерКэша()
        guard !Task.isCancelled else { return }
        let тот: Bool = байт / 1_000_000 == кэшБайт / 1_000_000 && (байт > 0) == (кэшБайт > 0)
        if !тот { кэшБайт = байт }
    }
}

/**
 Данные приложения на телефоне для кабинета: общий кэш запросов и статус уведомлений.

 Кэш — URLCache.shared: фото ленты (AsyncImage) и ответы API, до 256 МБ на диске (WebContainer.большойКэш). Кэш
 WebKit (страницы сайта) не трогаем: он лежит рядом с куками сессии и стирается при выходе целиком.
 */
enum ДанныеТелефона {
    /// Сколько кэш занимает на диске, байт. Скорость («кабинет легче», п. 7): вне главного потока — currentDiskUsage
    /// считает файлы кэша синхронно, а кэш картинок растёт почти на каждом показе.
    static func размерКэша() async -> Int {
        await Task.detached(priority: .utility) { () -> Int in
            URLCache.shared.currentDiskUsage
        }.value
    }

    /// «42,3 МБ» — на языке телефона.
    static func размер(_ байт: Int) -> String {
        ByteCountFormatter.string(fromByteCount: Int64(байт), countStyle: .file)
    }

    /// Чистка сотен мегабайт — не на главной нити, чтобы экран не замирал.
    static func очиститьКэш() async {
        await Task.detached(priority: .utility) {
            URLCache.shared.removeAllCachedResponses()
        }.value
    }

    /// Статус уведомлений словами — строка кабинета «Уведомления и подписки» и её экран. nil — ещё не спросили: «…».
    static func названиеСтатуса(_ статус: UNAuthorizationStatus?) -> String {
        guard let статус else { return "…" }
        switch статус {
        case .authorized, .ephemeral: return CabinetText.т("notif_on")
        case .provisional:            return CabinetText.т("notif_quiet")
        case .denied:                 return CabinetText.т("notif_off")
        case .notDetermined:          return CabinetText.т("notif_unknown")
        @unknown default:             return CabinetText.т("notif_unknown")
        }
    }

    static func статусУведомлений() async -> UNAuthorizationStatus {
        await withCheckedContinuation { продолжение in
            UNUserNotificationCenter.current().getNotificationSettings { настройки in
                продолжение.resume(returning: настройки.authorizationStatus)
            }
        }
    }

    /// Тот же запрос, что после входа (РазрешениеПушей): разрешили — регистрируемся в APNs, токен уйдёт в веб-сессию.
    static func попроситьУведомления() async {
        let центр = UNUserNotificationCenter.current()
        let разрешили = (try? await центр.requestAuthorization(options: [.alert, .badge, .sound])) ?? false
        guard разрешили else { return }
        await MainActor.run { UIApplication.shared.registerForRemoteNotifications() }
    }
}

/// Этап 30: кабинет в краске сайта — фон страницы, акцент и панель сайта. Выключен вид — ничего не меняет.
private struct КабинетКакНаСайте: ViewModifier {
    let заголовок: String


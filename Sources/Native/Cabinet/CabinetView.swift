    // MARK: - Обновление

    /// Состояние экрана заново: вход — у загруженной страницы (SiteSession), уведомления — у системы, кэш — у URLCache.
    private func освежить() async {
        освеженоВ = Date()
        let сессия = await SiteSession.состояние()
        /* nil — страница не ответила (грузится или переходит). Известное раньше не забываем: мигать «не удалось» на
           каждом переходе хуже прошлого состояния, а выход сайт всё равно заканчивает загрузкой страницы с bye=1. */
        if let известно = сессия.вошёл { вошёл = известно }
        if мост.isLoaded { проверили = true }
        /* Этап 40: страница кабинета — свежее страницы под слоем (та могла быть открыта до входа или выхода на другом
           устройстве). Страница под слоем грузится — не ждём, остаётся прежнее. */
        if Config.нативныйВход {
            /* Этап 45: та же страница кабинета — и колокольчик (уведомления есть только в её HTML), CHAT_PINS «Чата» и
               HELP_URL; второй раз её не качаем. */
            if let страница = try? await КабинетСайта.страницаКабинета(ждать: false) {
                кабинет = страница.состояние
                /* «Я бизнес» сам включён у PRO, магазина и компании с реквизитами — признаки той же страницы. */
                if страница.состояние.вошёл == true {
                    let html = страница.html
                    let бизнес = await Task.detached(priority: .utility) { СтраницаБизнеса.разобрать(html) }.value
                    бизнесАвто = бизнес.pro || бизнес.proАктивен || бизнес.магазин
                        || !бизнес.реквизиты.бин.trimmingCharacters(in: .whitespaces).isEmpty
                } else if страница.состояние.вошёл == false {
                    бизнесАвто = false
                }
                прочитатьВыборБизнеса()
                /* Этап 46: та же страница — профиль и настройки (CAB_USER, CAB_PREF_*, LANG_OPTS, __UIP_ACC), и её
                   свежий токен — окнам настроек не качать страницу ради первой записи. */
                if Config.нативныеНастройки {
                    if страница.состояние.вошёл == true {
                        МоиОбъявленияAPI.запомнитьТокен(страница.состояние.csrf)
                        await настройки.обновить(html: страница.html)
                    } else if страница.состояние.вошёл == false {
                        настройки.забытьПрофиль()
                    }
                }
                if let известно = страница.состояние.вошёл {
                    вошёл = известно
                    проверили = true
                }
                /* Этап 47: та же страница — IS_VERIFIED (вывод только верифицированным) и строки T со ставками вывода. */
                if Config.нативныйКошелёк {
                    КошелёкМодель.shared.обновитьСтраницу(страница.состояние, html: страница.html)
                }
                if Config.нативныеСообщенияКабинета && страница.состояние.вошёл == true {
                    записиКолокольчика = УведомленияКабинета.разобрать(страница.html)
                    if let список = ИнбоксAPI.закреплённые(страница.html) {
                        ИнбоксМодель.shared.запомнитьЗакреплённые(список)
                    }
                    if let путь = ИнбоксAPI.справка(страница.html) { справка = путь }
                } else if страница.состояние.вошёл == false {
                    записиКолокольчика = []
                }
                /* Страница кабинета прочитана — экран такой, каким будет: окно подачи начинается, даже если профиль
                   разобрать не удалось (иначе подача ждала бы его до следующего чтения). */
                ПодачаКабинета.отметить()
            }
            сигнал = await КабинетСайта.сигналСеанса()
        }
        /* Этап 47: кошелёк — при каждом показе кабинета, как loadWalletInfo сайта; фоном, страницу не уводит. */
        if Config.нативныйКошелёк && вошёл == true { await КошелёкМодель.shared.загрузить(ждать: false) }
        /* Этап 43: значок «Мои сделки» — только вошедшему (my_deals&role=both, только чтение). */
        if Config.нативныеСделки && вошёл == true { await сделки.обновитьЗначок() }
        /* Этап 45: значок «Заявок рядом» (loadRequestsBadge) и «Сделка состоялась?» (checkPendingFeedback) — вошедшему. */
        if Config.нативныеСообщенияКабинета && вошёл == true {
            await заявки.обновитьЗначок()
            await заявки.проверитьОтзыв()
        }
        способВхода = замок.kind()          // код-пароль или Face ID могли настроить в Настройках, пока нас не было
        уведомления = await ДанныеТелефона.статусУведомлений()
        кэшБайт = ДанныеТелефона.кэшБайт
    }

    /// Повторный показ кабинета вскоре после освежить(): без страницы кабинета, сигнала и кошелька — экраны стека
    /// сами держат общие модели свежими (кошелёк, заявки). Значок сделок обновляет только кабинет — его спрашиваем
    /// (сделку могли подтвердить на её экране); статус уведомлений, Face ID и кэш знает сам телефон.
    private func освежитьБезСтраницы() async {
        if Config.нативныеСделки && вошёл == true { await сделки.обновитьЗначок() }
        способВхода = замок.kind()
        уведомления = await ДанныеТелефона.статусУведомлений()
        кэшБайт = ДанныеТелефона.кэшБайт
    }
}

// MARK: - Этап 40: вход, выход, соглашение

extension CabinetView {
    /// Вошли своим экраном: страница под слоем перезагружается — ждём её и перечитываем кабинет.
    func послеВхода() async {
        сигнал = nil
        ошибкаВыхода = nil
        if let страница = try? await КабинетСайта.состояние() {
            кабинет = страница
            if let известно = страница.вошёл {
                вошёл = известно
                проверили = true
            }
        }
    }

    /// TestFlight 1.10: человек сменился (вошёл, вышел, другой аккаунт) — где бы это ни случилось. Выход — сразу гость;
    /// вход — перечитать кабинет, если он ещё не знает.
    func сменаЧеловека() {
        guard let известно = сессия.вошёл else { return }
        if !известно {
            guard вошёл != false else { return }
            вошёл = false
            кабинет = nil
            сигнал = nil
            записиКолокольчика = []
            return
        }
        let тотЖе = вошёл == true && (сессия.id.isEmpty || кабинет?.uid == сессия.id)
        guard !тотЖе else { return }
        /* Главный экран 13.10.2026: новый вход — подача кабинета (каскад и блик шапки) играет ещё раз. */
        ПодачаКабинета.заново()
        Task { await освежить() }
    }

    /// Нажали «Выйти» в вопросе. Один запрос за раз; не вышло — ничего не стёрто, причина под кнопкой.
    func выйти() {
        guard !выходим else { return }
        выходим = true
        ошибкаВыхода = nil
        Task { @MainActor in
            defer { выходим = false }
            do {
                try await КабинетСайта.выйти()
                вошёл = false
                кабинет = nil
                сигнал = nil
            } catch {
                ошибкаВыхода = ЭкранВхода.текстСбоя(error)
            }
        }
    }

    /// Окно соглашения на экране, пока страница говорит __TERMS_RENEW и не открыт вход. Закрывается само — когда
    /// соглашение принято или сессии больше нет; сдвинуть его нельзя (interactiveDismissDisabled).
    var соглашениеНаЭкране: Binding<Bool> {
        Binding(get: {
            guard Config.нативныйВход, вошёл == true, !входОткрыт, !выходим, let страница = кабинет else { return false }
            return страница.вошёл == true && страница.новоеСоглашение
        }, set: { _ in })
    }

    func соглашениеПринято() {
        кабинет?.новоеСоглашение = false
        показатьПлашку(ВходText.т("terms_renew_done"))
    }

    /// «Выйти» в окне соглашения — тот же выход, что в кабинете (у сайта — klikoLogout).
    func выйтиИзОкнаСоглашения() {
        кабинет?.новоеСоглашение = false
        выйти()
    }

    /// Сервер ответил auth: сессии нет — окно уходит, открывается вход.
    func входИзОкнаСоглашения() {
        кабинет = nil
        вошёл = false
        Task { @MainActor in
            try? await Task.sleep(nanoseconds: 450_000_000)
            входОткрыт = true
        }
    }

    func показатьПлашку(_ текст: String) {
        withAnimation(.easeOut(duration: 0.2)) { плашка = текст }
        UIAccessibility.post(notification: .announcement, argument: текст)
        Task { @MainActor in
            try? await Task.sleep(nanoseconds: 2_600_000_000)
            guard плашка == текст else { return }
            withAnimation(.easeIn(duration: 0.2)) { плашка = nil }
        }
    }

    @ViewBuilder
    var плашкаВнизу: some View {
        if let текст = плашка {
            ТостКабинета(текст: текст)
                .padding(.horizontal, 20)
                .padding(.bottom, 96)
                .transition(.opacity)
                .accessibilityHidden(true)
        }
    }
}


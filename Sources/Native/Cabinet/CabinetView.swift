/// «Данные на телефоне» — своим видом (скорость, «кабинет легче», п. 2): избранное, недавние, сверка избранного с
/// аккаунтом и «Моё» подписаны здесь, а не у корня кабинета — открытое объявление (RecentStore) или сердечко больше не
/// перерисовывают весь кабинет. Размер кэша — свой, вне главного потока: при первом показе строки и после каждого
/// полного освежить (освежений), и на экран — только если сменились мегабайты.
private struct РазделДанныхКабинета: View, Equatable {
    /// Сколько полных освежить кабинета прошло.
    let освежений: Int
    @ObservedObject private var избранное = FavoritesStore.shared
    /// Этап 35: избранное вошедшего сверено с аккаунтом — оно живёт на сайте, и «Очистить» на телефоне не к месту.
    @ObservedObject private var синхронИзбранного = СинхронИзбранного.shared
    @ObservedObject private var недавние = RecentStore.shared
    /// «Моё» (16.10.2026): гараж, устройства, рост и мерки на телефоне — строка «Данные на телефоне».
    @ObservedObject private var моё = МоёХранилище.shared
    @State private var кэшБайт = 0
    /// Сколько «Моё» занимает на телефоне (машины, устройства, мерки и фото), байт.
    @State private var моёБайт = 0

    init(освежений: Int) {
        self.освежений = освежений
    }

    nonisolated static func == (л: РазделДанныхКабинета, п: РазделДанныхКабинета) -> Bool {

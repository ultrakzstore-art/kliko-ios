    /// Этап 47: «Кошелёк» — сразу под шапкой, как .hero-wallet в шапке кабинета сайта. Вне «разделов»: у карточки
    /// свой прозрачный фон строки, общий фон строк сайта (строкиСайта) его бы перекрыл.
    @ViewBuilder
    private var разделКошелька: some View {
        if Config.нативныйКошелёк && вошёл == true {
            РазделКошелька(открыть: открыть, сразу: { действие in кошелёкСразу = действие })
        }
    }

    @ViewBuilder
    private var разделы: some View {
        /* Этап 40: сеанс завершён или вход с другого устройства — первым делом, как окно сайта поверх кабинета. */
        if Config.нативныйВход, let сигнал {
            РазделСигналаСеанса(сигнал: сигнал, войти: { входОткрыт = true }, наСайт: {
                /* «Это были вы?» — свой лист «Устройства и входы» (sec_devices / sec_end), а не кабинет сайта. */
                if профильНастроек != nil {
                    настройки.открыть(.устройства)
                } else {
                    Task { await освежить() }
                }
            })
        }
        разделСайта
        /* Этап 48: «Для бизнеса» — платные услуги сведениями, «Акции» (клуб основателей) и «Счета» (компания). */
        if вошёл == true && (Config.нативныеПлатныеУслуги || Config.нативныйБизнес) { разделБизнеса }

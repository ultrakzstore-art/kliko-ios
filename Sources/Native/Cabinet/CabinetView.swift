struct CabinetView: View {
    @ObservedObject private var мост = WebBridge.shared
    @ObservedObject private var замок = AppLock.shared
    @ObservedObject private var избранное = FavoritesStore.shared
    /// Этап 35: избранное вошедшего сверено с аккаунтом — оно живёт на сайте, и «Очистить» на телефоне не к месту.
    @ObservedObject private var синхронИзбранного = СинхронИзбранного.shared
    @ObservedObject private var недавние = RecentStore.shared
    /// Этап 43: значок у строки «Мои сделки».
    @ObservedObject private var сделки = СделкиМодель.shared
    /// Этап 45: значок у строки «Заявки рядом» и окно «Сделка состоялась?».
    @ObservedObject private var заявки = ЗаявкиМодель.shared
    /// Этап 46: профиль и настройки со страницы кабинета, окна настроек.
    @ObservedObject private var настройки = НастройкиМодель.shared
    /// TestFlight 1.10: общее состояние входа — вход или выход на сайте, в другой вкладке или с витрины видны и здесь.
    @ObservedObject private var сессия = СессияПриложения.shared
    @Environment(\.scenePhase) private var фаза

    /// Открыть страницу сайта в веб-обёртке — так же, как из остальных вкладок.
    let открыть: (URL) -> Void

    /// Вошёл ли человек на сайте. nil — не знаем: страница под слоем ещё грузится или не ответила.
    @State private var вошёл: Bool? = nil
    /// Загруженная страница уже ответила хоть раз — дальше вместо колеса честное «не удалось проверить».
    @State private var проверили = false
    @State private var уведомления: UNAuthorizationStatus? = nil
    @State private var кэшБайт = 0
    /// Переключатель защиты входа — своё значение, а не прямо AppLock.enabled: пока система спрашивает Face ID, он
    /// стоит в новом положении, а не прыгает назад; не подтвердили — возвращаем.
    @State private var защита = false
    @State private var проверяемЗамок = false
    /// Что умеет телефон (AppLock.kind): faceID / touchID / opticID / passcode / none. Спрашиваем при показе, а не в
    /// body: body пересчитывается на каждый шаг загрузки страницы (WebBridge.progress), а LAContext не бесплатен.
    @State private var способВхода = "passcode"
    @State private var ошибкаЗамка: String? = nil
    /// Этап 16: лист «Что нового» по строке в «О приложении».
    @State private var показатьНовое = false
    /// Этап 40: что напечатала страница кабинета — вход, имя, токен, соглашение (КабинетСайта.состояние).
    @State private var кабинет: КабинетСайта.Состояние? = nil
    /// Этап 40: сигнал /api/sess_alert.php — сеанс завершён или вход с другого устройства.
    @State private var сигнал: КабинетСайта.СигналСеанса? = nil
    @State private var входОткрыт = false
    @State private var спроситьВыход = false
    @State private var выходим = false
    @State private var ошибкаВыхода: String? = nil
    /// Этап 40: короткая плашка внизу («Спасибо — новая редакция принята»), как toast сайта.
    @State private var плашка: String? = nil
    /// Этап 45: колокольчик — записи панели уведомлений со страницы кабинета.
    /// Этап 46: это поле звалось «уведомления» и совпадало по имени со статусом разрешения уведомлений выше (этап 9) —
    /// повторное объявление свойства, которое компилятор не пропустит. Переименовано, смысл тот же.
    @State private var записиКолокольчика: [УведомлениеКабинета] = []
    @State private var колокольчик = false
    /// Этап 45: запись колокольчика с чатом объявления — чат этапа 38 в стеке кабинета.
    @State private var чатИзУведомления: Listing? = nil
    /// Этап 45: HELP_URL страницы кабинета — «Справочный центр».
    @State private var справка = "/kz/ru/help"
    /// Этап 47: кнопка карточки «Кошелёк» при включённых деньгах — экран кошелька со своей формой сразу.
    @State private var кошелёкСразу: ДействиеКошелька? = nil

    init(открыть: @escaping (URL) -> Void) {
        self.открыть = открыть
    }

    var body: some View {
        основа
            /* Этап 40: свой экран входа, окно новой редакции соглашения, вопрос перед выходом, плашка. */
            .sheet(isPresented: $входОткрыт) {
                ЭкранВхода(eGovВключён: кабинет?.eGovВключён ?? true, открыть: открыть, вошли: {
                    Task { await послеВхода() }
                })
            }
            .sheet(isPresented: соглашениеНаЭкране) {
                ОкноСоглашения(редакция: кабинет?.редакция ?? "", пункты: кабинет?.чтоИзменилось ?? [],
                               принято: { соглашениеПринято() }, выйти: { выйтиИзОкнаСоглашения() },
                               нуженВход: { входИзОкнаСоглашения() })
            }
            .confirmationDialog(ВходText.т("logout_q"), isPresented: $спроситьВыход, titleVisibility: .visible) {
                Button(ВходText.т("cab_logout"), role: .destructive) { выйти() }
                Button(CabinetText.т("cancel"), role: .cancel) {}
            } message: {
                Text(ВходText.т("logout_msg"))
            }
            .overlay(alignment: .bottom) { плашкаВнизу }
            /* Этап 45: колокольчик и «Сделка состоялась?». */
            .modifier(КолокольчикКабинета(включён: колокольчикВиден, новых: записиКолокольчика.filter { $0.новое }.count,
                                          открыть: { открытьКолокольчик() }))
            .sheet(isPresented: $колокольчик, onDismiss: {
                /* markAllRead ушёл при открытии — после панели точки гаснут, как у сайта. */
                for i in записиКолокольчика.indices { записиКолокольчика[i].новое = false }
            }) {
                ЛистУведомлений(уведомления: записиКолокольчика, чатТовара: { товар in
                    Task { @MainActor in
                        try? await Task.sleep(nanoseconds: 350_000_000)
                        чатИзУведомления = Listing(номер: товар)
                    }
                })
            }
            .navigationDestination(item: $чатИзУведомления) { товар in
                ЭкранЧатаОбъявления(товар: товар, предложить: false, открыть: открыть)
            }
            .sheet(item: $заявки.отзыв) { отзыв in
                ОкноОтзываЗаявки(отзыв: отзыв, модель: заявки)
            }
            /* Этап 46: окна настроек, «Применить к объявлениям?», мастер «Начало работы» и их плашка. */
            .modifier(НастройкиКабинета(открыть: открыть))
            /* Этап 47: «Пополнить» / «Вывести» карточки кошелька — экран кошелька с формой. */
            .navigationDestination(item: $кошелёкСразу) { действие in
                ЭкранКошелька(сразу: действие, открыть: открыть)
            }
    }

    /// Этап 46: профиль вошедшего прочитан со страницы кабинета — его шапка и разделы настроек сайта.
    private var профильНастроек: ПрофильКабинета? {
        guard Config.нативныеНастройки, Config.нативныйВход, вошёл == true, кабинет?.вошёл == true else { return nil }
        return настройки.профиль
    }

    /// Этап 45: колокольчик — вошедшему, при своих сообщениях кабинета.
    private var колокольчикВиден: Bool {
        Config.нативныеСообщенияКабинета && Config.нативныйВход && вошёл == true
    }

    /// toggleNotifications сайта: панель и сразу markAllRead (точки гаснут).
    private func открытьКолокольчик() {
        колокольчик = true
        guard записиКолокольчика.contains(where: { $0.новое }) else { return }
        Task { @MainActor in
            await УведомленияКабинета.прочитать()
        }
    }

    private var основа: some View {
        список
        .listStyle(.insetGrouped)
        .navigationTitle(CabinetText.т("title"))
        .navigationBarTitleDisplayMode(.inline)
        .modifier(КабинетКакНаСайте(заголовок: CabinetText.т("title")))
        .refreshable { await освежить() }
        /* Вход меняется на сайте, уведомления — в Настройках iPhone: перечитываем при каждом показе вкладки, при
           первой загрузке страницы, при возврате с сайта и из Настроек. */
        .task { await освежить() }
        .onAppear {
            защита = замок.enabled
            способВхода = замок.kind()
        }
        .onChange(of: замок.enabled) { _, стало in защита = стало }
        .onChange(of: защита) { _, хочет in переключитьЗащиту(хочет) }
        .onChange(of: мост.isLoaded) { _, загружена in
            if загружена { Task { await освежить() } }
        }
        .onChange(of: мост.лентаВидна) { _, видна in
            if видна { Task { await освежить() } }
        }
        .onChange(of: фаза) { _, стала in
            if стала == .active { Task { await освежить() } }
        }
        .onChange(of: сессия.смена) { _, _ in сменаЧеловека() }
        .sheet(isPresented: $показатьНовое) { ЭкранЧтоНового() }
        /* Этап 41: экраны кабинета в его стеке — строка «Мои объявления» и ссылка ?go=items (NativeTabsView). */
        .navigationDestination(for: КабинетЦель.self) { цель in
            switch цель {
            case .моиОбъявления:
                МоиОбъявленияЭкран(открыть: открыть)
            case .сделки:
                МоиСделкиЭкран(открыть: открыть)
            case .сделка(let номер):
                ЭкранСделки(id: номер, открыть: открыть)
            case .заявки:
                ЭкранЗаявок(открыть: открыть)
            case .обращение(let номер):
                ЭкранОбращения(номер: номер)
            case .кошелёк:
                ЭкранКошелька(открыть: открыть)
            case .баллы:
                ЭкранБаллов(открыть: открыть)
            case .платныеУслуги:
                ЭкранПлатныхУслуг(открыть: открыть)
            case .клуб:
                ЭкранКлуба(открыть: открыть)
            case .компания:
                ЭкранКомпании(открыть: открыть)
            default:
                /* Разделы, добавленные «кабинетом полностью SwiftUI» (CabinetPlus/CabinetMenu.swift). */
                ЭкранРазделаКабинета(цель: цель, открыть: открыть)
            }
        }
        /* Этап 43: «Связь с продавцом / покупателем» из карточки сделки — переписка приложения в этом же стеке. */
        .чатМаршруты(открыть: открыть)
        /* «Смотреть» в «Моих объявлениях» — своя карточка объявления в этом же стеке, а не страница сайта; похожие из
           неё ложатся сюда же. */

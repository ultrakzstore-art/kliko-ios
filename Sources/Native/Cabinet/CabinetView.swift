                              подпись: число(недавние.товары.count),
                              вопрос: CabinetText.т("viewed_q"), пояснение: CabinetText.т("viewed_msg"),
                              доступно: !недавние.товары.isEmpty) {
                    недавние.очиститьПросмотры()

    /// Показ корня: вкладку выбрали или вернулись «Назад» из его стека. Скорость («кабинет легче», п. 4): с известной
    /// памятью сначала конец перехода (около 400 мс — анимация pop или свайп назад идут без сети и разбора), потом
    /// освежить с паузой 30 с. Скрытый живой стек (наЭкране = false) не освежает ничего.
    private func показан() async {
        guard наЭкране else { return }
        if освеженоВ != nil {
            try? await Task.sleep(nanoseconds: 400_000_000)
            guard !Task.isCancelled else { return }
        }
        await освежитьСПаузой()
    }

    /// Повод без «потянуть вниз» — показ, возврат из фона, загрузка страницы, лента: меньше чем через 30 с после
    /// прошлого чтения — без страницы кабинета (освежитьБезСтраницы), иначе полное. Пауза — только когда вход уже
    /// известен: первое чтение могло прийтись на загрузку страницы под слоем (холодный старт на вкладке «Профиль») и
    /// ничего не узнать — тогда полное, как раньше по каждому поводу, и ещё одним проходом, если чтение ещё идёт (оно
    /// спросило страницу до её загрузки).
    private func освежитьСПаузой() async {
        guard вошёл != nil else {
            await освежить(заново: true)
            return
        }
        if let было = освеженоВ, Date().timeIntervalSince(было) < 30 {
            await освежитьБезСтраницы()
        } else {
            await освежить()
        }
    }

    /// Повод из обработчика (onReceive, onChange): скрытый кабинет не освежает — покажут, освежит .task(id:).
    private func освежитьПоПоводу() {
        guard наЭкране else { return }
        Task<Void, Never> { await освежитьСПаузой() }
    }

    /// Полное освежить. Скорость («кабинет легче», п. 8): один идущий запуск на экран — второй повод (загрузка
    /// страницы и показ на холодном старте, «потянуть вниз» во время показа) ждёт его конца, а не качает страницу
    /// кабинета второй раз. заново — сменился человек (сменаЧеловека) или вход ещё не известен (освежитьСПаузой): идущий
    /// запуск мог прочитать страницу прежнего или спросить её до загрузки, поэтому сразу после него — ещё один проход.
    private func освежить(заново: Bool = false) async {
        if let идёт = запуск.задача {
            if заново { запуск.ещёРаз = true }
            await идёт.value
            return
        }
        let задача = Task<Void, Never> {
            repeat {
                запуск.ещёРаз = false
                await освежитьОдинРаз()
            } while запуск.ещёРаз
        }
        запуск.задача = задача
        await задача.value
        запуск.задача = nil
    }

    /// Состояние экрана заново: вход — у загруженной страницы (SiteSession), уведомления — у системы, кэш — у URLCache.
    /// Скорость («кабинет легче», п. 3 и 4): страница кабинета (сотни КБ) разбирается вне главного потока одной задачей
    /// (разобратьСтраницу: «Я бизнес», профиль, строки T кошелька, колокольчик, CHAT_PINS, HELP_URL); всё, что экран
    /// узнал, копится в ИтогОсвежения и ложится на экран одной записью (применить) — и только сменившееся: один проход
    /// body вместо пяти-семи. Кошелёк, значок сделок и заявки — после неё: их числа читают листья, не корень.
    private func освежитьОдинРаз() async {
        let начатоВ = Date()
        освеженоВ = начатоВ
        /* Память запуска (ПамятьКабинета): отметку чтения получает, только когда страница прочитана, — оборванное
           чтение (ушли с вкладки) не даёт следующему показу её пропустить. Без своего входа страницы нет — сразу. */
        if !Config.нативныйВход { ПамятьКабинета.освеженоВ = начатоВ }
        var итог = ИтогОсвежения()
        let сайт = await SiteSession.состояние()
        /* nil — страница не ответила (грузится или переходит). Известное раньше не забываем: мигать «не удалось» на
           каждом переходе хуже прошлого состояния, а выход сайт всё равно заканчивает загрузкой страницы с bye=1. */
        if let известно = сайт.вошёл { итог.вошёл = известно }
        if WebBridge.shared.isLoaded { итог.проверили = true }
        /* Вход экран ещё не знает (колесо в шапке) — сразу, как раньше: колесо не ждёт страницы кабинета и сигнала.
           Одна запись и только в согласии с общим состоянием входа: только что вошедшему страница под слоем, ещё не
           перезагруженная, может сказать «гость» — тогда ждём страницу кабинета, а не показываем «Войти». */
        let общийВход: Bool? = СессияПриложения.shared.вошёл
        if вошёл == nil, let известно = итог.вошёл, общийВход == nil || общийВход == известно {
            вошёл = известно
            if итог.проверили { проверили = true }
        }
        var прочитана: КабинетСайта.Состояние? = nil
        var разбор = РазборСтраницыКабинета()
        var поколениеПрофиля = 0
        /* Этап 40: страница кабинета — свежее страницы под слоем (та могла быть открыта до входа или выхода на другом
           устройстве). Страница под слоем грузится — не ждём, остаётся прежнее. Этап 45: та же страница — и колокольчик
           (уведомления есть только в её HTML), CHAT_PINS «Чата» и HELP_URL; второй раз её не качаем. */
        if Config.нативныйВход {
            if let страница = try? await КабинетСайта.страницаКабинета(ждать: false) {
                let html: String = страница.html
                let вошёлНаСтранице: Bool = страница.состояние.вошёл == true
                поколениеПрофиля = НастройкиМодель.shared.поколениеПрофиля
                разбор = await Task.detached(priority: .userInitiated) { () -> РазборСтраницыКабинета in
                    CabinetView.разобратьСтраницу(html, вошёл: вошёлНаСтранице)
                }.value
                прочитана = страница.состояние
            }
            итог.сигнал = await КабинетСайта.сигналСеанса()
            итог.сигналСпрошен = true
        }
        if let состояние = прочитана {
            итог.принять(состояние, разбор: разбор)
        }
        итог.уведомления = await ДанныеТелефона.статусУведомлений()
        /* Способ входа — раз за запуск и после возврата из фона (ПамятьКабинета.способВхода), не на каждом показе. */
        if ПамятьКабинета.способВхода == nil { ПамятьКабинета.способВхода = замок.kind() }
        итог.способВхода = ПамятьКабинета.способВхода
        применить(итог, разбор: разбор, поколениеПрофиля: поколениеПрофиля, начатоВ: начатоВ)
        let вошедший: Bool = (итог.вошёл ?? вошёл) == true
        /* Этап 47: кошелёк — при каждом полном чтении кабинета, как loadWalletInfo сайта; фоном, страницу не уводит. */
        if Config.нативныйКошелёк && вошедший { await КошелёкМодель.shared.загрузить(ждать: false) }
        /* Этап 43: значок «Мои сделки» — только вошедшему (my_deals&role=both, только чтение); полное — без паузы. */
        if Config.нативныеСделки && вошедший { await СделкиМодель.shared.обновитьЗначок(сразу: true) }
        /* Этап 45: значок «Заявок рядом» (loadRequestsBadge) и «Сделка состоялась?» (checkPendingFeedback) — вошедшему. */
        if Config.нативныеСообщенияКабинета && вошедший {
            await ЗаявкиМодель.shared.обновитьЗначок()
            await ЗаявкиМодель.shared.проверитьОтзыв()
        }
    }

    /// Итог одного освежить — на экран одной записью: поля @State и память запуска. Пишется только то, что это освежить
    /// узнало (не узнало — прежнее остаётся, как раньше по шагам), и только если сменилось.
    private func применить(_ итог: ИтогОсвежения, разбор: РазборСтраницыКабинета, поколениеПрофиля: Int,
                           начатоВ: Date) {
        /* Сначала память кабинета: её didSet по смене человека стирает чужой колокольчик, сигнал и «Я бизнес», а
           следующие строки кладут туда уже новые. */
        if let страница = итог.кабинет {
            ПамятьКабинета.кабинет = страница
            if страница != кабинет { кабинет = страница }
            if итог.бизнесВыбор != бизнесВыбор { бизнесВыбор = итог.бизнесВыбор }
        }
        if let известно = итог.вошёл {
            if известно != вошёл { вошёл = известно }
            ПамятьКабинета.вошёл = известно
        }
        if итог.проверили {
            if !проверили { проверили = true }
            ПамятьКабинета.проверили = true
        }
        if let авто = итог.бизнесАвто {
            if авто != бизнесАвто { бизнесАвто = авто }
            ПамятьКабинета.бизнесАвто = авто
        }
        if let записи = итог.записи {
            if записи != записиКолокольчика { записиКолокольчика = записи }
            ПамятьКабинета.колокольчик = записи
        }
        if let путь = итог.справка {
            if путь != справка { справка = путь }
            ПамятьКабинета.справка = путь
        }
        if итог.сигналСпрошен {
            if итог.сигнал != сигнал { сигнал = итог.сигнал }
            ПамятьКабинета.сигнал = итог.сигнал
        }
        if let статус = итог.уведомления, статус != уведомления { уведомления = статус }
        if let способ = итог.способВхода, способ != способВхода { способВхода = способ }
        полныхОсвежений &+= 1
        if let страница = итог.кабинет {
            /* Этап 46: та же страница — профиль и настройки (CAB_USER, CAB_PREF_*, LANG_OPTS, __UIP_ACC), и её свежий
               токен — окнам настроек не качать страницу ради первой записи. Этап 47: IS_VERIFIED и строки T кошелька.
               Тем же проходом, что поля выше: зеркало профиля (onReceive) пишет в эту же транзакцию. */
            применитьСтраницу(страница, разбор: разбор, поколениеПрофиля: поколениеПрофиля)
            /* Страница кабинета прочитана — экран такой, каким будет: окно подачи начинается, даже если профиль
               разобрать не удалось (иначе подача ждала бы его до следующего чтения). */
            ПодачаКабинета.отметить()
            ПамятьКабинета.освеженоВ = начатоВ
        }
    }

    /// Модели, которым нужна та же страница кабинета: настройки, кошелёк и закреплённые «Чата».
    private func применитьСтраницу(_ страница: КабинетСайта.Состояние, разбор: РазборСтраницыКабинета,
                                   поколениеПрофиля: Int) {
        if Config.нативныеНастройки {
            if страница.вошёл == true {
                МоиОбъявленияAPI.запомнитьТокен(страница.csrf)
                if let профиль = разбор.профиль {
                    НастройкиМодель.shared.принятьПрофиль(профиль, поколение: поколениеПрофиля)
                }
            } else if страница.вошёл == false {
                НастройкиМодель.shared.забытьПрофиль()
            }
        }
        if Config.нативныйКошелёк {
            КошелёкМодель.shared.обновитьСтраницу(страница, строки: разбор.строкиT)
        }
        if Config.нативныеСообщенияКабинета && страница.вошёл == true, let список = разбор.закреплённые {
            ИнбоксМодель.shared.запомнитьЗакреплённые(список)
        }
    }

    /// Разбор страницы кабинета вне главного потока — всё, что из неё берут экран и его модели, одной задачей. Гостю
    /// разбирать нечего.
    nonisolated private static func разобратьСтраницу(_ html: String, вошёл: Bool) -> РазборСтраницыКабинета {
        var итог = РазборСтраницыКабинета()
        guard вошёл else { return итог }
        /* «Я бизнес» сам включён у PRO, магазина и компании с реквизитами — признаки той же страницы. */
        let бизнес = СтраницаБизнеса.разобрать(html)
        let бин: String = бизнес.реквизиты.бин.trimmingCharacters(in: .whitespaces)
        итог.бизнесАвто = бизнес.pro || бизнес.proАктивен || бизнес.магазин || !бин.isEmpty
        if Config.нативныеНастройки { итог.профиль = ПрофильКабинета.разобрать(html) }
        if Config.нативныйКошелёк { итог.строкиT = КошелёкМодель.строкиT(html) }
        if Config.нативныеСообщенияКабинета {
            итог.колокольчик = УведомленияКабинета.разобрать(html)
            итог.закреплённые = ИнбоксAPI.закреплённые(html)
            итог.справка = ИнбоксAPI.справка(html)
        }
        return итог
    }

    /// Повторный показ кабинета вскоре после освежить(): без страницы кабинета, сигнала и кошелька — экраны стека
    /// сами держат общие модели свежими (кошелёк, заявки). Значок сделок обновляет только кабинет — его спрашиваем
    /// (сделку могли подтвердить на её экране; сама модель не чаще раза в 30 с, а сменившийся статус снимает паузу);
    /// статус уведомлений знает сам телефон. Способ входа — только если его забыли (возврат из фона). На экран —
    /// только сменившееся.
    private func освежитьБезСтраницы() async {
        if Config.нативныеСделки && вошёл == true { await СделкиМодель.shared.обновитьЗначок() }
        let статус = await ДанныеТелефона.статусУведомлений()
        if статус != уведомления { уведомления = статус }
        if ПамятьКабинета.способВхода == nil { ПамятьКабинета.способВхода = замок.kind() }
        let способ = ПамятьКабинета.способВхода ?? способВхода
        if способ != способВхода { способВхода = способ }
    }

    // MARK: - Поводы и зеркала корня (onReceive без повторов)

    /// AppLock.enabled сменился — переключатель «Вход по Face ID» встаёт так, как защита на самом деле. Только смена, без
    /// нынешнего значения (как прежний onChange): пока система спрашивает Face ID, переключатель стоит в новом
    /// положении, и повторная подписка при перерисовке не должна вернуть его назад.
    private static var защитаВключена: AnyPublisher<Bool, Never> {
        AppLock.shared.$enabled.removeDuplicates().dropFirst().eraseToAnyPublisher()
    }

    /// WebBridge.loadFailed — сайт не загрузился вовсе.
    private static var сайтНеЗагрузился: AnyPublisher<Bool, Never> {
        WebBridge.shared.$loadFailed.removeDuplicates().eraseToAnyPublisher()
    }

    /// Первая страница сайта отрисована — только смена, без нынешнего значения (как onChange).
    private static var страницаЗагружена: AnyPublisher<Bool, Never> {
        WebBridge.shared.$isLoaded.removeDuplicates().dropFirst().eraseToAnyPublisher()
    }

    /// Вернулись со страницы сайта на ленту — только смена.
    private static var лентаПоказана: AnyPublisher<Bool, Never> {
        WebBridge.shared.$лентаВидна.removeDuplicates().dropFirst().eraseToAnyPublisher()
    }

    /// Человек сменился (вход, выход, другой аккаунт) — только смена. СессияПриложения меняет «смену» последней, после
    /// вошёл и id, — обработчик видит их уже новыми.
    private static var сменыЧеловека: AnyPublisher<Int, Never> {
        СессияПриложения.shared.$смена.removeDuplicates().dropFirst().eraseToAnyPublisher()
    }

    /// Свой номер из общего состояния входа.
    private static var номерСессии: AnyPublisher<String, Never> {
        СессияПриложения.shared.$id.removeDuplicates().eraseToAnyPublisher()
    }

    /// Профиль со страницы кабинета (НастройкиМодель; ПрофильКабинета — Equatable).
    private static var профильМодели: AnyPublisher<ПрофильКабинета?, Never> {
        НастройкиМодель.shared.$профиль.removeDuplicates().eraseToAnyPublisher()
    }

    /// Заявки приходят — новые есть или список не пуст (сами числа читает плитка).
    private static var заявкиЕсть: AnyPublisher<Bool, Never> {
        let модель = ЗаявкиМодель.shared
        let новых: Published<Int>.Publisher = модель.$новых
        let список: Published<[Заявка]>.Publisher = модель.$заявки
        return новых.combineLatest(список)
            .map { пара -> Bool in пара.0 > 0 || !пара.1.isEmpty }
            .removeDuplicates()
            .eraseToAnyPublisher()
    }
}

/// Что узнало одно освежить кабинета (CabinetView.освежитьОдинРаз) — на экран ложится одной записью (применить).
/// nil и false — не узнали: прежнее на экране остаётся.
private struct ИтогОсвежения {
    /// Вход: со страницы под слоем, потом со страницы кабинета.
    var вошёл: Bool? = nil
    /// Страница ответила хоть раз.
    var проверили = false
    /// Прочитанная страница кабинета; nil — не прочитали (поля ниже про неё — тоже нет).
    var кабинет: КабинетСайта.Состояние? = nil
    /// Выбор «Я бизнес» этого аккаунта с телефона — вместе со страницей (аккаунт мог смениться).
    var бизнесВыбор: Bool? = nil
    var бизнесАвто: Bool? = nil
    var записи: [УведомлениеКабинета]? = nil
    var справка: String? = nil
    /// Сигнал сеанса спрашивали (свой вход); nil-сигнал — тоже ответ: сигнала нет.
    var сигналСпрошен = false
    var сигнал: КабинетСайта.СигналСеанса? = nil
    var уведомления: UNAuthorizationStatus? = nil
    var способВхода: String? = nil

    /// Прочитанная страница кабинета и её разбор — как раньше по шагам в освежить, только в итог.
    mutating func принять(_ страница: КабинетСайта.Состояние, разбор: РазборСтраницыКабинета) {
        кабинет = страница
        if страница.вошёл == true {
            бизнесАвто = разбор.бизнесАвто
        } else if страница.вошёл == false {
            бизнесАвто = false
        }
        /* Выбор «Я бизнес» этого аккаунта с телефона; id не известен — не выбирал. */
        if страница.uid.isEmpty {
            бизнесВыбор = nil
        } else {
            бизнесВыбор = UserDefaults.standard.object(forKey: CabinetView.ключВыбораБизнеса(страница.uid)) as? Bool
        }
        if let известно = страница.вошёл {
            вошёл = известно
            проверили = true
        }
        if Config.нативныеСообщенияКабинета && страница.вошёл == true {
            записи = разбор.колокольчик
            справка = разбор.справка
        } else if страница.вошёл == false {
            записи = []
        }
    }
}

/// Разбор страницы кабинета вне главного потока (CabinetView.разобратьСтраницу).
private struct РазборСтраницыКабинета {
    /// «Я бизнес» по признакам страницы: PRO, магазин или реквизиты компании.
    var бизнесАвто = false
    /// Профиль и настройки (Config.нативныеНастройки); nil — не разбирали.
    var профиль: ПрофильКабинета? = nil
    /// Строки T со ставками вывода (кошелёк).
    var строкиT: [String: String] = [:]
    /// Колокольчик, CHAT_PINS и HELP_URL (Config.нативныеСообщенияКабинета).
    var колокольчик: [УведомлениеКабинета] = []
    var закреплённые: [String]? = nil
    var справка: String? = nil
}

/// Идущее полное освежить одного экрана кабинета (CabinetView.освежить): второй повод ждёт его, а не качает страницу
/// кабинета второй раз. Класс в @State — запись в него не перерисовывает экран.
@MainActor
final class ЗапускОсвежения {
    var задача: Task<Void, Never>? = nil
    /// Пока шло освежить, сменился человек — ещё один проход сразу после (страница могла быть прежнего).
    var ещёРаз = false
}

// MARK: - Этап 40: вход, выход, соглашение

extension CabinetView {
    /// Вошли своим экраном: страница под слоем перезагружается — ждём её и перечитываем кабинет.
    func послеВхода() async {
        сигнал = nil
        ПамятьКабинета.сигнал = nil
        ошибкаВыхода = nil
        if let страница = try? await КабинетСайта.состояние() {
            кабинет = страница
            ПамятьКабинета.кабинет = страница
            if let известно = страница.вошёл {
                вошёл = известно
                проверили = true
                ПамятьКабинета.вошёл = известно
                ПамятьКабинета.проверили = true
            }
        }
    }

    /// TestFlight 1.10: человек сменился (вошёл, вышел, другой аккаунт) — где бы это ни случилось. Выход — сразу гость;
    /// вход — перечитать кабинет, если он ещё не знает.
    func сменаЧеловека() {
        let сессия = СессияПриложения.shared
        guard let известно = сессия.вошёл else { return }
        if !известно {
            guard вошёл != false else { return }
            вошёл = false
            кабинет = nil
            сигнал = nil
            записиКолокольчика = []
            ПамятьКабинета.вошёл = false
            ПамятьКабинета.кабинет = nil
            ПамятьКабинета.сигнал = nil
            ПамятьКабинета.колокольчик = []
            return
        }
        let тотЖе = вошёл == true && (сессия.id.isEmpty || кабинет?.uid == сессия.id)
        guard !тотЖе else { return }
        /* Главный экран 13.10.2026: новый вход — подача кабинета (каскад и блик шапки) играет ещё раз. */
        ПодачаКабинета.заново()
        /* Живой стек: скрытый кабинет не качает страницу под чужой вкладкой — отметка чтения прочь, и показ освежит
           полностью, без паузы 30 с (она не для нового человека). */
        guard наЭкране else {
            освеженоВ = nil
            ПамятьКабинета.освеженоВ = nil
            сброситьЭкранДоОсвежения()
            return
        }
        Task<Void, Never> { await освежить(заново: true) }
    }

    /// Человек сменился, пока кабинет скрыт под другой вкладкой: показ начнётся с колеса «проверяем», как у нового
    /// экрана без годной памяти раньше, а не с экрана прежнего входа («Войти» гостя у только что вошедшего, кошелёк и
    /// «Я бизнес» прежнего). Поля кабинета — до полного освежить при показе; только сменившиеся.
    private func сброситьЭкранДоОсвежения() {
        if вошёл != nil { вошёл = nil }
        if проверили { проверили = false }
        if кабинет != nil { кабинет = nil }
        if сигнал != nil { сигнал = nil }
        if !записиКолокольчика.isEmpty { записиКолокольчика = [] }
        if бизнесАвто { бизнесАвто = false }
        if бизнесВыбор != nil { бизнесВыбор = nil }
    }

    /// Кабинет ушёл с экрана (живой стек под другой вкладкой): экраны поверх корня, положенные не в путь стека, и листы
    /// корня закрываются — как раньше, когда стек уходил из дерева. Только открытые.
    private func закрытьПоверхКорня() {
        if чатИзУведомления != nil { чатИзУведомления = nil }
        if кошелёкСразу != nil { кошелёкСразу = nil }
        if колокольчик { колокольчик = false }
        if отзывыОткрыты { отзывыОткрыты = false }
        if показатьНовое { показатьНовое = false }
        if спроситьВыход { спроситьВыход = false }
    }

    /// Нажали «Выйти» в вопросе. Один запрос за раз; не вышло — ничего не стёрто, причина под кнопкой.
    func выйти() {
        guard !выходим else { return }
        выходим = true
        ошибкаВыхода = nil
        Task { @MainActor in
            defer { выходим = false }
            do {
                try await КабинетСайта.выйти()
                вошёл = false
                кабинет = nil
                сигнал = nil
                ПамятьКабинета.вошёл = false
                ПамятьКабинета.кабинет = nil
                ПамятьКабинета.сигнал = nil
            } catch {
                ошибкаВыхода = ЭкранВхода.текстСбоя(error)
            }
        }
    }

    /// Окно соглашения на экране, пока страница говорит __TERMS_RENEW и не открыт вход. Закрывается само — когда
    /// соглашение принято или сессии больше нет; сдвинуть его нельзя (interactiveDismissDisabled).
    var соглашениеНаЭкране: Binding<Bool> {
        Binding(get: {
            guard наЭкране, Config.нативныйВход, вошёл == true, !входОткрыт, !выходим, let страница = кабинет else {
                return false
            }
            return страница.вошёл == true && страница.новоеСоглашение
        }, set: { _ in })
    }

    func соглашениеПринято() {
        кабинет?.новоеСоглашение = false
        ПамятьКабинета.кабинет?.новоеСоглашение = false
        показатьПлашку(ВходText.т("terms_renew_done"))
    }

    /// «Выйти» в окне соглашения — тот же выход, что в кабинете (у сайта — klikoLogout).
    func выйтиИзОкнаСоглашения() {
        кабинет?.новоеСоглашение = false
        ПамятьКабинета.кабинет?.новоеСоглашение = false
        выйти()
    }

    /// Сервер ответил auth: сессии нет — окно уходит, открывается вход.
    func входИзОкнаСоглашения() {
        кабинет = nil
        вошёл = false
        ПамятьКабинета.кабинет = nil
        ПамятьКабинета.вошёл = false
        Task { @MainActor in
            try? await Task.sleep(nanoseconds: 450_000_000)
            входОткрыт = true
        }
    }

    func показатьПлашку(_ текст: String) {
        withAnimation(.easeOut(duration: 0.2)) { плашка = текст }
        UIAccessibility.post(notification: .announcement, argument: текст)
        Task { @MainActor in
            try? await Task.sleep(nanoseconds: 2_600_000_000)
            guard плашка == текст else { return }
            withAnimation(.easeIn(duration: 0.2)) { плашка = nil }
        }
    }

    @ViewBuilder
    var плашкаВнизу: some View {
        if let текст = плашка {
            ТостКабинета(текст: текст)
                .padding(.horizontal, 20)
                .padding(.bottom, 96)
                .transition(.opacity)
                .accessibilityHidden(true)
        }
    }
}


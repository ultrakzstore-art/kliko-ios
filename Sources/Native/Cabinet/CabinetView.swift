                          вопрос: CabinetText.т("cache_q"), пояснение: CabinetText.т("cache_msg")) {
                Task {
                    await ДанныеТелефона.очиститьКэш()
                    кэшБайт = await ДанныеТелефона.размерКэша()
                }
            }
            .task(id: освежений) { await пересчитатьКэш() }
            /* Этап 35: избранное в аккаунте — очистка телефона вернулась бы следующей сверкой; снимают его сердечком. */

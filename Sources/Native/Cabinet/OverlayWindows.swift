import SwiftUI
import UIKit

/**
 СВОИ ОКНА ПОВЕРХ ЛЮБОГО ЭКРАНА (владелец 26.09.2026: «всё приложение нативное, ровное и стильное»).

 ОкнаПриложения (CabinetWindows.swift) показывает лист со слоя вкладок — SwiftUI ставит его только тогда, когда у
 корневого контроллера ничего не показано. Внутри листа продавца, полноэкранного мастера подачи или карточки сделки такой
 лист молча не встанет, и раньше нажатие уходило на страницу сайта. Здесь — тот же путь, что у ОкноEgov: контроллер
 SwiftUI показывается из самого верхнего контроллера UIKit, поверх того, что сейчас на экране.

   · ПоверхВсего.показать — любое окно (витрина продавца, точка на карте, настройки объявления, вакансия);
   · ВходПоверх.показать — свой экран входа (ЭкранВхода) поверх чего угодно; после входа — то же уведомление
     ОкнаПриложения.вошли, что у листа слоя вкладок, и «готово» вызывающего;
   · ВерификацияПоверх.показать — окно «Стать продавцом» (ЛистВерификации) поверх мастера подачи.
 Ссылка сайта изнутри такого окна (eGov, запасная страница) — окно закрывается, адрес идёт тем же путём, что у корня
 приложения: eGov — своим окном (ОкноEgov.перехватить), прочее — своим экраном или окном «недоступно» (WebBridge.перейти).
 */
@MainActor
enum ПоверхВсего {
    /// Верхний контроллер, над которым можно показать окно; nil — что-то ещё уезжает или приезжает.
    static func верхний() -> UIViewController? {
        let окна = UIApplication.shared.connectedScenes
            .compactMap { $0 as? UIWindowScene }
            .flatMap { $0.windows }
        guard let окно = окна.first(where: { $0.isKeyWindow }) ?? окна.first,
              var верх = окно.rootViewController else { return nil }
        while let следующий = верх.presentedViewController {
            if следующий.isBeingDismissed || следующий.isBeingPresented { return nil }
            верх = следующий
        }
        if верх.isBeingDismissed { return nil }
        return верх
    }

    /**
     Показать окно поверх верхнего экрана. Ждёт до 3 с, пока уедет лист или алерт вызывающего; не дождались — false
     через `не вышло`. большой — сразу во всю высоту (витрина, карта), иначе — половина и вся высота.
     */
    static func показать<Содержимое: View>(большой: Bool = true, смахивается: Bool = true,
                                          неВышло: (() -> Void)? = nil,
                                          @ViewBuilder _ содержимое: @escaping (_ закрыть: @escaping () -> Void) -> Содержимое) {
        Task { @MainActor in
            for попытка in 0..<12 {
                if let верх = ПоверхВсего.верхний() {
                    let хост = UIHostingController<AnyView>(rootView: AnyView(EmptyView()))
                    let закрыть: () -> Void = { [weak хост] in
                        хост?.dismiss(animated: true)
                    }
                    /* Ссылки нашего домена в тексте окна — своими экранами, не Safari (БезСайта.действиеСсылки). */
                    хост.rootView = AnyView(содержимое(закрыть).environment(\.openURL, БезСайта.действиеСсылки))
                    хост.modalPresentationStyle = .pageSheet
                    хост.isModalInPresentation = !смахивается
                    if let лист = хост.sheetPresentationController {
                        лист.detents = большой ? [.large()] : [.medium(), .large()]
                        лист.prefersGrabberVisible = true
                        лист.prefersScrollingExpandsWhenScrolledToEdge = true
                    }
                    верх.present(хост, animated: true)
                    return
                }
                if попытка == 0 {
                    try? await Task.sleep(nanoseconds: 120_000_000)
                } else {
                    try? await Task.sleep(nanoseconds: 250_000_000)
                }
            }
            неВышло?()
        }
    }

    /// Адрес сайта изнутри окна: окно уже закрывается — через паузу цепочкой корня приложения (eGov, витрина, свои
    /// окна, кабинет, лента, поддержка — WebBridge.перейти); своего экрана нет — окно «недоступно», не сайт.
    static func открытьАдрес(_ адрес: URL) {
        Task { @MainActor in
            try? await Task.sleep(nanoseconds: 450_000_000)
            ПереходыКабинета.открыть(адрес)
        }
    }
}

// MARK: - Вход поверх любого экрана

@MainActor
enum ВходПоверх {
    /**
     Свой экран входа поверх того, что на экране (лист продавца, чат, мастер). Свой вход выключен рубильником — страница
     входа сайта, как было. готово — после удачного входа (экран, просивший войти, перечитывает себя).
     */
    static func показать(готово: (() -> Void)? = nil) {
        guard Config.нативныйВход && Config.нативныйКабинет else {
            if let адрес = Config.страницаСайта("cabinet.php") { WebBridge.shared.перейти(адрес) }
            return
        }
        /* Показать некуда — вкладка «Кабинет» (там «Войти»), не страница входа сайта. */
        ПоверхВсего.показать(неВышло: {
            if let адрес = Config.страницаСайта("cabinet.php") { WebBridge.shared.перейти(адрес) }
        }) { закрыть in
            ЭкранВхода(eGovВключён: НастройкиМодель.shared.профиль?.eGovВкл ?? true,
                       открыть: { адрес in
                           закрыть()
                           ПоверхВсего.открытьАдрес(адрес)
                       },
                       вошли: {
                           NotificationCenter.default.post(name: ОкнаПриложения.вошли, object: nil)
                           СессияПриложения.shared.запросить(кабинет: true)
                           готово?()
                       })
        }
    }
}

// MARK: - Поддержка поверх любого экрана

@MainActor
enum ПоддержкаПоверх {
    /**
     Своя форма обращения (ЛистОбращения; тема — как support.php?topic=). Листом слоя вкладок, а если его нет или
     занято — поверх верхнего экрана. Страницы сайта нет вовсе.
     */
    static func показать(тема: String = "other", задержка: UInt64 = 0) {
        if ОкнаПриложения.shared.показать(.поддержка(тема: тема), задержка: задержка) { return }
        Task { @MainActor in
            if задержка > 0 { try? await Task.sleep(nanoseconds: задержка) }
            ПоддержкаПоверх.поверх(тема: тема)
        }
    }

    /// Поверх верхнего контроллера (занято листом, полноэкранным окном или слоя вкладок нет).
    static func поверх(тема: String) {
        /* Показать некуда — ничего: ни страницы поддержки сайта, ни нового круга через WebBridge.перейти. */
        ПоверхВсего.показать { закрыть in
            ЛистОбращения(тема: тема, открыть: { адрес in
                закрыть()
                ПоверхВсего.открытьАдрес(адрес)
            })
        }
    }
}

// MARK: - «Стать продавцом» поверх мастера подачи

@MainActor
enum ВерификацияПоверх {
    /// Окно «Стать продавцом» (verPromo сайта) поверх полноэкранного мастера; оттуда eGov — своим окном ОкноEgov.
    static func показать() {
        ПоверхВсего.показать(большой: false, неВышло: {
            ОкноEgov.открыть(Config.страницаСайта("cabinet.php?go=verify"))
        }) { закрыть in
            ЛистВерификации(открыть: { адрес in
                закрыть()
                ПоверхВсего.открытьАдрес(адрес)
            })
        }
    }
}

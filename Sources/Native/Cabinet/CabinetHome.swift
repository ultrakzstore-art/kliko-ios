// MARK: - Плитки главных разделов

/// Плитка главного раздела кабинета: название, значок, число внимания и действие по нажатию.
struct ПлиткаКабинета: Identifiable {
    let id: String
    let название: String
    let значок: String
    /// Сколько ждут человека (сделки, новые заявки); 0 — значка нет.
    let число: Int
    /// Что услышит VoiceOver вместо капсулы с числом: «Ждут вашего действия: 2».
    let подписьЧисла: String
    let действие: () -> Void
}

/// Плитки ровной сеткой: на iPhone две колонки, на iPad (regular) — по числу плиток, не больше четырёх. Ряды — HStack
/// с зазором 12, между рядами тоже 12; в неполном последнем ряду плитка тянется на всю ширину.
struct ПлиткиКабинета: View {
    let плитки: [ПлиткаКабинета]
    /// С какого шага каскада подачи начинать: каждая следующая плитка — на шаг позже.
    let номер: Int
    @Environment(\.horizontalSizeClass) private var класс

    init(плитки: [ПлиткаКабинета], номер: Int) {
        self.плитки = плитки
        self.номер = номер
    }

    private var колонок: Int {
        guard класс == .regular else { return 2 }
        return max(1, min(плитки.count, 4))
    }

    var body: some View {
        let пары = Array(плитки.enumerated())
        let вРяду = колонок
        let рядов = (пары.count + вРяду - 1) / вРяду
        VStack(spacing: 12) {
            ForEach(0..<рядов, id: \.self) { ряд in
                HStack(spacing: 12) {
                    ForEach(пары[(ряд * вРяду)..<min(пары.count, (ряд + 1) * вРяду)], id: \.element.id) { пара in
                        ВидПлиткиКабинета(плитка: пара.element)
                            .подачаКабинета(номер + пара.offset)
                    }
                }
            }
        }
        .accessibilityElement(children: .contain)
    }
}

/// Одна плитка: поверхность сайта, радиус md, тень карточки; сверху значок строки и значок внимания, внизу название.
private struct ВидПлиткиКабинета: View {
    let плитка: ПлиткаКабинета
    @ObservedObject private var режим = РежимУстройства.shared
    /// Растёт, когда число растёт: значок плитки подпрыгивает (только вверх — убыль не повод звать человека).
    @State private var прыжки = 0

    init(плитка: ПлиткаКабинета) {
        self.плитка = плитка
    }

    var body: some View {
        let форма = RoundedRectangle(cornerRadius: Theme.Радиус.md, style: .continuous)
        Button(action: плитка.действие) {
            VStack(alignment: .leading, spacing: 0) {
                HStack(alignment: .top, spacing: 8) {
                    ЗначокСтрокиСайта(значок: плитка.значок)
                        .symbolEffect(.bounce, value: прыжки)
                    Spacer(minLength: 0)
                    if плитка.число > 0 {
                        ЗначокСчётчикаКабинета(плитка.число)
                            .transition(.scale.combined(with: .opacity))
                    }
                }
                .animation(ДвижениеСайта.появление, value: плитка.число > 0)
                Spacer(minLength: 4)
                Text(плитка.название)
                    .font(.system(size: 14, weight: .semibold))
                    .foregroundStyle(Theme.текст)
                    .lineLimit(1)
                    .minimumScaleFactor(0.8)
            }
            .padding(12)
            .frame(maxWidth: .infinity, alignment: .leading)
            .frame(height: 84)
            .background(Theme.поверхность, in: форма)
            .теньКарточкиСайта(радиус: Theme.Радиус.md)
            .contentShape(форма)
        }
        .buttonStyle(НажатиеСайта())
        .accessibilityValue(плитка.число > 0 ? плитка.подписьЧисла : "")
        .onChange(of: плитка.число) { было, стало in
            guard стало > было, !ДвижениеСайта.тихо, !режим.лёгкий else { return }
            прыжки += 1
        }
    }
}

// MARK: - Значок внимания

/// Красная капсула с числом (точка у пункта меню сайта): белый жирный caption, «99+» при больше 99. Для VoiceOver
/// скрыта — число называет подпись строки или плитки (accessibilityValue).
struct ЗначокСчётчикаКабинета: View {
    let число: Int

    init(_ число: Int) {
        self.число = число
    }

    var body: some View {
        Text(число > 99 ? "99+" : String(число))
            .font(.caption.weight(.bold))
            .foregroundStyle(Color.white)
            .padding(.horizontal, 7)
            .padding(.vertical, 2)
            .background(Theme.непрочитано, in: Capsule())
            .dynamicTypeSize(...DynamicTypeSize.xxxLarge)
            .contentTransition(.numericText())
            .animation(ДвижениеСайта.смена, value: число)
            .accessibilityHidden(true)
    }
}

// MARK: - Опасная строка

/// Подпись строки «Удалить аккаунт» и «Выйти»: значок строки и название 14/600 — красные, между ними 12, как у
/// ПодписьСтрокиКабинета. Красный с тёмным вариантом (Theme.скидкаТекст: #b91c1c, в тёмной #f87171): постоянный
/// Theme.малиновый на тёмной поверхности давал около 3:1 — мелкий текст так не читается.
struct ПодписьОпаснойСтрокиКабинета: View {
    let название: String
    let значок: String

    init(_ название: String, значок: String) {
        self.название = название
        self.значок = значок
    }

    var body: some View {
        HStack(spacing: 12) {
            ЗначокСтрокиСайта(значок: значок, цвет: Theme.скидкаТекст)
            Text(название)
                .font(.system(size: 14, weight: .semibold))
                .lineSpacing(2)
                .foregroundStyle(Theme.скидкаТекст)
                .multilineTextAlignment(.leading)
        }
    }
}

// MARK: - Подача: каскад появления

/// Когда играть подачу кабинета: один раз за запуск, в первые 1,2 с после того, как экран готов, и снова после нового
/// входа.
@MainActor
enum ПодачаКабинета {
    /// Экран кабинета стал готов в этот раз; nil — ещё не готов (колесо на месте шапки) или был новый вход.
    static var начало: Date? = nil

    /// Блик по шапке профиля уже прошёл в этот раз (свой флаг — не зависит от окна каскада и от того, сколько шла сеть).
    static var бликСыгран = false

    /// Окно каскада, секунд: позже элементы встают на место сразу (прокрутка, возврат на вкладку).
    private static let окно: TimeInterval = 1.2

    /// Без анимации: «Уменьшение движения», лёгкий режим или окно каскада уже прошло.
    static var сразу: Bool {
        if ДвижениеСайта.тихо || РежимУстройства.shared.лёгкий { return true }
        guard let начало else { return false }
        return Date().timeIntervalSince(начало) >= окно
    }

    /// Экран готов (CabinetView.подачаГотова: вход известен, вошедшему — и профиль прочитан): окно каскада начинается
    /// отсюда, а не с колеса на месте шапки.
    static func отметить() {
        if начало == nil { начало = Date() }
    }

    /// Новый вход — подача и блик сыграют ещё раз.
    static func заново() {
        начало = nil
        бликСыгран = false
    }
}

/// Шаг каскада: элемент поднимается на 12 pt, проявляется и чуть растёт от 97 %; каждый следующий шаг — на 0,05 с
/// позже. Без сдвига (сдвиг: false) — только проявление: для строк на фоне ячейки списка, который рисует сам список.
@MainActor
struct ПоявлениеКабинета: ViewModifier {
    let номер: Int
    let сдвиг: Bool
    @State private var видно: Bool

    init(номер: Int, сдвиг: Bool) {
        self.номер = номер
        self.сдвиг = сдвиг
        _видно = State(initialValue: ПодачаКабинета.сразу)
    }

    func body(content: Content) -> some View {
        content
            .opacity(видно ? 1 : 0)
            .offset(y: видно || !сдвиг ? 0 : 12)
            .scaleEffect(видно || !сдвиг ? 1 : 0.97, anchor: .top)
            .onAppear {
                guard !видно else { return }
                let пружина = Animation.spring(response: 0.5, dampingFraction: 0.86).delay(0.05 * Double(номер))
                withAnimation(ДвижениеСайта.мягко(пружина)) {
                    видно = true
                }
            }
    }
}

extension View {
    /// Шаг каскада подачи главного экрана кабинета (ПоявлениеКабинета): шапка 0, кошелёк 1, сигнал 2, плитки с 3.
    /// сдвиг: false — только проявление (строки на фоне ячейки списка: «Разделы», сигнал, шапка без вида сайта).
    @MainActor
    func подачаКабинета(_ номер: Int, сдвиг: Bool = true) -> some View {
        modifier(ПоявлениеКабинета(номер: номер, сдвиг: сдвиг))
    }
}

// MARK: - Подача: блик по шапке

/// Один проход блика по шапке профиля: полоса (прозрачный → белый 22 % → прозрачный) шириной 45 % шапки, наклон 18°,
/// слева направо (в арабском — справа налево) за 0,9 с после паузы 0,3 с. Один раз за запуск и после нового входа —
/// при первом показе карточки профиля, сколько бы ни шла её загрузка (ПодачаКабинета.бликСыгран); при «Уменьшении
/// движения» и в лёгком режиме блика нет. Обрезку по форме шапки делает тот, кто кладёт блик.
struct БликПодачиКабинета: View {
    @ObservedObject private var режим = РежимУстройства.shared
    @Environment(\.accessibilityReduceMotion) private var безДвижения
    /// Блик в этот раз ещё не проходил — проходит; уже прошёл — шапка просто стоит.
    @State private var идёт: Bool
    /// Где полоса: −1 — левее шапки, 1 — правее (в долях ширины ×1,2).
    @State private var сдвиг: CGFloat = -1

    init() {
        _идёт = State(initialValue: !ПодачаКабинета.бликСыгран)
    }

    var body: some View {
        if идёт && !безДвижения && !режим.лёгкий && !ДвижениеСайта.тихо {
            GeometryReader { место in
                let ширина = место.size.width
                let высота = место.size.height
                LinearGradient(colors: [Color.white.opacity(0), Color.white.opacity(0.22), Color.white.opacity(0)],
                               startPoint: .leading, endPoint: .trailing)
                    .frame(width: ширина * 0.45, height: высота * 1.6)
                    .rotationEffect(.degrees(18))
                    .position(x: ширина / 2 + сдвиг * ширина * 1.2, y: высота / 2)
            }
            .allowsHitTesting(false)
            .accessibilityHidden(true)
            .flipsForRightToLeftLayoutDirection(true)
            .onAppear {
                guard сдвиг < 1 else { return }
                ПодачаКабинета.бликСыгран = true
                withAnimation(ДвижениеСайта.мягко(.easeInOut(duration: 0.9).delay(0.3))) {
                    сдвиг = 1
                }
            }
        }
    }
}

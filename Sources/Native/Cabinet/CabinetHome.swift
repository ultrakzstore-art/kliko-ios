// MARK: - Плитки главных разделов

/// Плитка главного раздела кабинета: название, значок, число внимания и действие по нажатию; у «Отзывов» — ещё оценка
/// и подпись под названием.
struct ПлиткаКабинета: Identifiable {
    let id: String
    let название: String
    let значок: String
    /// Сколько ждут человека (сделки, новые заявки); 0 — значка нет.
    let число: Int
    /// Что услышит VoiceOver вместо капсулы с числом, оценки и подписи: «Ждут вашего действия: 2», «Рейтинг 4.9,
    /// 12 отзывов».
    let подписьЧисла: String
    /// Оценка крупно со звездой в верхнем углу («★ 4.9») вместо капсулы с числом; пусто — как у остальных плиток.
    /// var со значением по умолчанию — остальные плитки его не передают (let со значением в memberwise init не попал бы).
    var оценка: String = ""
    /// Маленькая подпись под названием («12 отзывов», «Отзывов пока нет»); пусто — одно название.
    var подпись: String = ""
    /// Подпись у плитки бывает («Отзывы»): её ряд держит строку подписи сразу, пока сводки ещё нет, — названия соседей
    /// стоят на одной высоте с её названием и не сдвигаются, когда подпись приходит.
    var местоПодписи: Bool = false
    let действие: () -> Void
}

/// Плитки ровной сеткой: на iPhone две колонки, на iPad (regular) — по числу плиток, не больше четырёх. Ряды — HStack
/// с зазором 12, между рядами тоже 12; в неполном последнем ряду плитка тянется на всю ширину. Плитка одна в ряду —
/// широкая: раскладка строкой (ВидПлиткиКабинета), а не растянутая узкая. Есть в ряду плитка с подписью (или с местом
/// под неё) — строку подписи держат все узкие плитки этого ряда: названия ряда стоят на одной высоте.
struct ПлиткиКабинета: View {
    let плитки: [ПлиткаКабинета]
    /// С какого шага каскада подачи начинать: каждая следующая плитка — на шаг позже.
    let номер: Int
    @Environment(\.horizontalSizeClass) private var класс

    init(плитки: [ПлиткаКабинета], номер: Int) {
        self.плитки = плитки
        self.номер = номер
    }

    private var колонок: Int {
        guard класс == .regular else { return 2 }
        return max(1, min(плитки.count, 4))
    }

    var body: some View {
        let пары = Array(плитки.enumerated())
        let вРяду = колонок
        let рядов = (пары.count + вРяду - 1) / вРяду
        VStack(spacing: 12) {
            ForEach(0..<рядов, id: \.self) { ряд in
                let вЭтомРяду = пары[(ряд * вРяду)..<min(пары.count, (ряд + 1) * вРяду)]
                let строкаПодписи = вЭтомРяду.count > 1 && вЭтомРяду.contains(where: { пара in
                    пара.element.местоПодписи || !пара.element.подпись.isEmpty
                })
                HStack(spacing: 12) {
                    ForEach(вЭтомРяду, id: \.element.id) { пара in
                        ВидПлиткиКабинета(плитка: пара.element, широкая: вЭтомРяду.count == 1,
                                          строкаПодписи: строкаПодписи)
                            .подачаКабинета(номер + пара.offset)
                    }
                }
            }
        }
        .accessibilityElement(children: .contain)
    }
}

/// Одна плитка: поверхность сайта, радиус md, тень карточки, высота 84. Узкая — сверху значок строки и значок внимания
/// (или оценка «★ 4.9»), внизу название и подпись. Широкая (одна в ряду, во всю ширину) — строкой, как строки кабинета:
/// значок, название с подписью, справа оценка крупнее или значок внимания и всегда стрелка строки кабинета
/// (СтрелкаСтрокиКабинета) — пока сводки нет, строка не выглядит недорисованной.
///
/// В ряду со строкой подписи (строкаПодписи) у узкой нижнее поле 8 вместо 12: значок 32 + название 14 pt (около 17) +
/// подпись 12 pt (около 14) — 63 pt при 64 внутри, а значок наверху стоит вровень с соседями. Строку держат все узкие
/// плитки ряда — у кого подписи нет, на её месте пустая невидимая строка того же шрифта: названия ряда на одной высоте.
/// Шрифты — фиксированные pt, как у строк кабинета: от Dynamic Type они не растут, длинный перевод ужимается
/// (minimumScaleFactor), высота 84 не меняется.
private struct ВидПлиткиКабинета: View {
    let плитка: ПлиткаКабинета
    /// Одна в ряду, во всю ширину — раскладка строкой, а не растянутая узкая.
    let широкая: Bool
    /// В ряду есть плитка с подписью: узкая держит строку подписи, даже если своей подписи нет.
    let строкаПодписи: Bool
    @ObservedObject private var режим = РежимУстройства.shared
    /// Растёт, когда число растёт: значок плитки подпрыгивает (только вверх — убыль не повод звать человека).
    @State private var прыжки = 0

    init(плитка: ПлиткаКабинета, широкая: Bool, строкаПодписи: Bool) {
        self.плитка = плитка
        self.широкая = широкая
        self.строкаПодписи = строкаПодписи
    }

    var body: some View {
        let форма = RoundedRectangle(cornerRadius: Theme.Радиус.md, style: .continuous)
        Button(action: плитка.действие) {
            содержимое
                .padding(.horizontal, 12)
                .padding(.top, 12)
                .padding(.bottom, полеСнизу)
                .frame(maxWidth: .infinity, alignment: .leading)
                .frame(height: 84)
                .animation(ДвижениеСайта.смена, value: плитка.подпись)
                .background(Theme.поверхность, in: форма)
                .теньКарточкиСайта(радиус: Theme.Радиус.md)
                .contentShape(форма)
        }
        .buttonStyle(НажатиеСайта())
        .accessibilityValue(значение)
        .onChange(of: плитка.число) { было, стало in
            guard стало > было, !ДвижениеСайта.тихо, !режим.лёгкий else { return }
            прыжки += 1
        }
    }

    @ViewBuilder
    private var содержимое: some View {
        if широкая {
            HStack(alignment: .center, spacing: 12) {
                значок
                надписи
                Spacer(minLength: 8)
                HStack(spacing: 8) {
                    угол(размер: 26)
                    СтрелкаСтрокиКабинета()
                }
            }
            .animation(ДвижениеСайта.появление, value: плитка.число > 0)
            .animation(ДвижениеСайта.появление, value: плитка.оценка.isEmpty)
        } else {
            VStack(alignment: .leading, spacing: 0) {
                HStack(alignment: .top, spacing: 8) {
                    значок
                    Spacer(minLength: 0)
                    угол(размер: 20)
                }
                .animation(ДвижениеСайта.появление, value: плитка.число > 0)
                .animation(ДвижениеСайта.появление, value: плитка.оценка.isEmpty)
                Spacer(minLength: 0)
                надписи
            }
        }
    }

    private var значок: some View {
        ЗначокСтрокиСайта(значок: плитка.значок)
            .symbolEffect(.bounce, value: прыжки)
    }

    /// Верхний угол узкой (правый край широкой): оценка «★ 4.9», иначе значок внимания с числом, иначе ничего.
    @ViewBuilder
    private func угол(размер: CGFloat) -> some View {
        if !плитка.оценка.isEmpty {
            ОценкаПлиткиКабинета(оценка: плитка.оценка, размер: размер)
                .transition(.scale.combined(with: .opacity))
        } else if плитка.число > 0 {
            ЗначокСчётчикаКабинета(плитка.число)
                .transition(.scale.combined(with: .opacity))
        }
    }

    /// Название 14/600 и под ним подпись 12 pt вторым цветом (одной строкой). Подпись для VoiceOver скрыта — её
    /// называет значение плитки.
    private var надписи: some View {
        VStack(alignment: .leading, spacing: широкая ? 2 : 0) {
            Text(плитка.название)
                .font(.system(size: 14, weight: .semibold))
                .foregroundStyle(Theme.текст)
                .lineLimit(1)
                .minimumScaleFactor(0.8)
            if !плитка.подпись.isEmpty {
                Text(плитка.подпись)
                    .font(.system(size: 12))
                    .foregroundStyle(Theme.текстВторой)
                    .lineLimit(1)
                    .minimumScaleFactor(0.8)
                    .contentTransition(.numericText())
                    .transition(.opacity)
                    .accessibilityHidden(true)
            } else if держитСтрокуПодписи {
                /* Подписи нет (сводка ещё не пришла) — место под неё: название стоит вровень с соседями по ряду. */
                Text(" ")
                    .font(.system(size: 12))
                    .hidden()
                    .accessibilityHidden(true)
            }
        }
    }

    /// Узкая в ряду со строкой подписи (или со своей подписью) — под названием строка подписи, видимая или пустая.
    private var держитСтрокуПодписи: Bool {
        !широкая && (строкаПодписи || !плитка.подпись.isEmpty)
    }

    /// Со строкой подписи снизу 8: иначе название с подписью не встали бы под значок в 84 (см. описание выше).
    private var полеСнизу: CGFloat {
        держитСтрокуПодписи ? 8 : 12
    }

    /// Что VoiceOver скажет после названия: число внимания или сводка плитки («Рейтинг 4.9, 12 отзывов»).
    private var значение: String {
        плитка.число > 0 || !плитка.оценка.isEmpty || !плитка.подпись.isEmpty ? плитка.подписьЧисла : ""
    }
}

/// «★ 4.9» плитки: звезда тёплым жёлтым, как звёзды витрины продавца (Theme.звезда), цифры моноширинные и сменяются
/// перекатом (numericText). Высотой не меньше значка строки (32) — стоит с ним по центру. Для VoiceOver скрыта: оценку
/// называет значение плитки.
private struct ОценкаПлиткиКабинета: View {
    let оценка: String
    let размер: CGFloat

    var body: some View {
        HStack(alignment: .firstTextBaseline, spacing: 3) {
            Image(systemName: "star.fill")
                .font(.system(size: размер * 0.75, weight: .bold))
                .foregroundStyle(Theme.звезда)
            Text(оценка)
                .font(.system(size: размер, weight: .heavy).monospacedDigit())
                .foregroundStyle(Theme.текст)
                .contentTransition(.numericText())
        }
        .lineLimit(1)
        .minimumScaleFactor(0.7)
        .frame(minHeight: 32)
        .animation(ДвижениеСайта.смена, value: оценка)
        .accessibilityHidden(true)
    }
}


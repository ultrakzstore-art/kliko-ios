import Foundation

/**
 ПЛИТКА «ОТЗЫВЫ» ГЛАВНОГО ЭКРАНА КАБИНЕТА (владелец, TestFlight: «в кабинете избранные повторяются — придумать что-то
 другое там»).

 Плитка «Избранное» повторяла вкладку «Избранное» нижней панели (как раньше «Сообщения» — вкладку «Чат») и убрана. На её
 месте — то, чего нет ни во вкладках, ни в строках кабинета и что важно продавцу: как его видят покупатели.
   · На плитке — оценка крупно со звездой («★ 4.9») и подпись «12 отзывов» (склонение — ListingPageText.число, noun()
     сайта: 1 отзыв, 2 отзыва, 5 отзывов); отзывов нет — «Отзывов пока нет» без числа (те же слова, что в листе
     отзывов и витрине); сводка ещё не пришла или не пришла вовсе (нет сети) — одно название, плитка всё равно
     нажимается. Узкая, с соседями в ряду, — строку подписи её ряд держит сразу (местоПодписи): названия ряда на одной
     высоте и не сдвигаются, когда сводка приходит.
   · Данные — та же сводка seller_reviews.php, что у витрины продавца (ДействияСПродавцом.загрузитьОтзывы: запрос и
     память на 5 минут общие). В странице кабинета (КабинетСайта.Состояние, ПрофильКабинета) оценки нет. Кабинет
     спрашивает сводку по своему номеру (KlikoUser.id) при показе плиток и при смене человека — не при каждой
     перерисовке (CabinetView.загрузитьСводкуОтзывов).
   · Нажатие — лист своих отзывов (ЛистОтзывовПродавца, тот же, что «Все отзывы» витрины: сводка оценок, полосы 5…1,
     сами отзывы); из него «Профиль» ведёт на витрину. Не сама витрина: на неё уже ведёт строка «Профиль» группы
     «Аккаунт» (второй вход в тот же экран — тот же повтор), а отзывы в витрине — в самом низу, под объявлениями.
 Место — последней из плиток: без «Заявок рядом» она одна во втором ряду и ложится широкой строкой (ВидПлиткиКабинета).
 VoiceOver: «Отзывы», значение — «Рейтинг 4.9, 12 отзывов».
 */
enum ОтзывыКабинета {
    /// Плитка «Отзывы» по сводке; nil — сводки нет (ещё грузится или не вышло): одно название, без числа.
    static func плитка(сводка: ОтзывыПродавца.Сводка?, действие: @escaping () -> Void) -> ПлиткаКабинета {
        let оценка = оценкаПлитки(сводка)
        var подпись = ""
        var голос = ""
        if let сводка {
            let отзывов = max(сводка.отзывов, сводка.отзывы.count)
            if отзывов > 0 {
                подпись = ListingPageText.число(отзывов, "reviews")
                голос = оценка.isEmpty ? подпись : КабинетГлавнаяText.т("a11y_rating") + " " + оценка + ", " + подпись
            } else {
                подпись = КабинетГлавнаяText.т("reviews_none")
                голос = подпись
            }
        }
        return ПлиткаКабинета(id: "reviews", название: КабинетГлавнаяText.т("tile_reviews"), значок: "star.bubble",
                              число: 0, подписьЧисла: голос, оценка: оценка, подпись: подпись, местоПодписи: true,
                              действие: действие)
    }

    /// «4.9» — средняя оценка с одной цифрой после точки, как в шапке витрины; отзывов нет или оценка 0 — пусто.
    static func оценкаПлитки(_ сводка: ОтзывыПродавца.Сводка?) -> String {
        guard let сводка, max(сводка.отзывов, сводка.отзывы.count) > 0, сводка.оценка > 0 else { return "" }
        return String(format: "%.1f", min(5, сводка.оценка))
    }
}

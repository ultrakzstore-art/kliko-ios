import SwiftUI

/**
 ЧАСТИ КАБИНЕТА, КОТОРЫЕ САМИ СЛЕДЯТ ЗА ОБЩИМИ МОДЕЛЯМИ (скорость, «кабинет легче», разбор cabinet_perf_rank, п. 2).

 Корень кабинета (CabinetView) раньше наблюдал десять общих моделей целиком, и любая их запись перерисовывала все
 35–45 строк списка. Теперь числа и списки читают листья:
   · РазделПлитокКабинета — плитки главных разделов: значок сделок (СделкиМодель.ждут) и новых заявок
     (ЗаявкиМодель.новых); массив плиток собирается один раз за проход, сама сетка (ПлиткиКабинета) пропускает
     проход, если плитки те же (.equatable()). Секции-листья (этот раздел, кошелёк, «Данные на телефоне») — Equatable
     без обёртки .equatable(): EquatableView — один вид, и List принял бы секцию за одну строку; вид с замыканиями
     SwiftUI и так сравнивает его ==;
   · РазделВниманияКабинета — «Требует внимания» (СделкиМодель.внимание);
   · СтрокаЗаявокКабинета — строка «Заявки рядом» в группе «Для бизнеса» со значком новых;
   · ОтзывЗаявкиКабинета — окно «Сделка состоялась?» (ЗаявкиМодель.отзыв), только пока кабинет на экране.
 Замыканий в сравнении нет: они зовут устойчивый переход стека вкладки (переходКабинета) или сеттер @State корня.
 */

// MARK: - Плитки главных разделов

/// Плитки под кошельком своей строкой без фона (у плиток своя поверхность и тень). Значки внимания — из уже
/// загруженного (СделкиМодель, ЗаявкиМодель), своих запросов нет; у «Отзывов» — сводка seller_reviews.php, её грузит
/// корень (загрузитьСводку) при показе плиток и при смене человека, не при перерисовке.
struct РазделПлитокКабинета: View, Equatable {
    /// Свой номер продавца для «Отзывов»; пусто — гость или вход ещё не известен.
    let свойНомер: String
    /// Сводка отзывов своего человека; nil — ещё не пришла или не вышло.
    let сводка: ОтзывыПродавца.Сводка?
    /// «Заявки рядом» среди главных (CabinetView.заявкиВГлавных).
    let заявкиВГлавных: Bool
    let открытьОтзывы: () -> Void
    let загрузитьСводку: () async -> Void
    @ObservedObject private var сделки = СделкиМодель.shared
    @ObservedObject private var заявки = ЗаявкиМодель.shared
    /// Плитки кладут экран в стек вкладки без дублей (NativeTabsView.положитьВКабинет).
    @Environment(\.переходКабинета) private var переходКабинета

    init(свойНомер: String, сводка: ОтзывыПродавца.Сводка?, заявкиВГлавных: Bool, открытьОтзывы: @escaping () -> Void,
         загрузитьСводку: @escaping () async -> Void) {
        self.свойНомер = свойНомер
        self.сводка = сводка
        self.заявкиВГлавных = заявкиВГлавных
        self.открытьОтзывы = открытьОтзывы
        self.загрузитьСводку = загрузитьСводку
    }

    nonisolated static func == (л: РазделПлитокКабинета, п: РазделПлитокКабинета) -> Bool {
        л.свойНомер == п.свойНомер && л.сводка == п.сводка && л.заявкиВГлавных == п.заявкиВГлавных
    }

    var body: some View {
        let _ = ЗамерКабинета.тело("tiles", Self.self)
        let плитки: [ПлиткаКабинета] = собрать()
        if !плитки.isEmpty {
            Section {
                ПлиткиКабинета(плитки: плитки, номер: 3)
                    .equatable()
                    /* «Отзывы»: сводка своего человека — при показе плиток и при смене человека, не при перерисовке. */
                    .task(id: свойНомер) { await загрузитьСводку() }
                    .listRowInsets(EdgeInsets())
                    .listRowBackground(Color.clear)
                    .listRowSeparator(.hidden)
            }
        }
    }

    /// Упрощение для новичка (владелец): главные разделы — «Мои объявления», «Мои сделки», кошелёк (карточка выше),
    /// «Заявки рядом» (когда они приходят) и «Отзывы». «Сообщения» — вкладка «Чат», «Избранное» — своя вкладка
    /// (владелец, TestFlight: «в кабинете избранные повторяются»), отдельных плиток нет; «Подписки» сайта — во вкладке
    /// «Избранное». Число плиток корень считает по тем же условиям (CabinetView.числоПлиток) — шаги каскада ниже.
    private func собрать() -> [ПлиткаКабинета] {
        var плитки: [ПлиткаКабинета] = []
        /* Этап 41: «Мои объявления» — свой экран (главный экран кабинета сайта), первым, как пункт меню сайта. */
        if Config.нативныеОбъявления {
            плитки.append(ПлиткаКабинета(id: "listings", название: КабинетГлавнаяText.т("tile_listings"),
                                         значок: "square.stack.3d.up", число: 0, подписьЧисла: "",
                                         действие: { перейти(.моиОбъявления) }))
        }
        /* Этап 43: «Мои сделки» — свой экран (#deals-screen сайта); значок — сколько сделок ждут человека (спор или
           «получено — подтвердите»), как точка у пункта меню сайта (loadDealsBadge). */
        if Config.нативныеСделки {
            let ждут: Int = сделки.ждут
            плитки.append(ПлиткаКабинета(id: "deals", название: КабинетГлавнаяText.т("tile_deals"),
                                         значок: "checkmark.shield", число: ждут,
                                         подписьЧисла: String(format: СделкиText.т("a11y_badge"), ждут),
                                         действие: { перейти(.сделки) }))
        }
        /* Этап 45: «Заявки рядом» (#requests-screen) — для мастеров: здесь, когда заявки уже приходят; иначе — строкой
           в группе «Для бизнеса». Значок — новые заявки (reqSetNav сайта). */
        if заявкиВГлавных {
            let новых: Int = заявки.новых
            плитки.append(ПлиткаКабинета(id: "requests", название: КабинетГлавнаяText.т("tile_requests"),
                                         значок: "hand.raised", число: новых,
                                         подписьЧисла: String(format: AccessText.т("unread"), новых),
                                         действие: { перейти(.заявки) }))
        }
        /* «Отзывы» — вместо «Избранного»: оценка и число отзывов вошедшего; нажатие — лист своих отзывов
           (ЛистОтзывовПродавца, как «Все отзывы» витрины), из него «Профиль» ведёт на витрину. Последней: без заявок
           она одна во втором ряду и ложится широкой строкой. Номер ещё не известен — плитки нет (открывать нечего). */
        if Config.продавецОтзывы && ВитринаПродавцаAPI.годный(свойНомер) {
            плитки.append(ОтзывыКабинета.плитка(сводка: сводка, действие: открытьОтзывы))
        }
        return плитки
    }

    private func перейти(_ цель: КабинетЦель) {
        переходКабинета?(цель)
    }
}

// MARK: - «Требует внимания»

/// «Требует внимания» (задание сервера 1.13, Б5) — под плитками: сделки, где ход за человеком. Нечего делать — раздела
/// нет. Список — СделкиМодель.внимание: запись модели перерисовывает этот лист, а не корень кабинета.
struct РазделВниманияКабинета: View {
    @ObservedObject private var сделки = СделкиМодель.shared
    @Environment(\.переходКабинета) private var переходКабинета

    init() {}

    var body: some View {
        if !сделки.внимание.isEmpty {
            Section {
                ВниманиеКабинета(сделки: сделки.внимание,
                                 открыть: { номер in переходКабинета?(.сделка(номер)) },
                                 все: { переходКабинета?(.сделки) })
                    .equatable()
                    .listRowInsets(EdgeInsets(top: 4, leading: 0, bottom: 4, trailing: 0))
                    .listRowBackground(Color.clear)
                    .listRowSeparator(.hidden)
            }
        }
    }
}

// MARK: - Строка «Заявки рядом»

/// Этап 45: строка «Заявки рядом» в группе «Для бизнеса» — со значком новых заявок (reqSetNav сайта), тем же, что у
/// плиток (ЗначокСчётчикаКабинета); число VoiceOver слышит значением строки.
struct СтрокаЗаявокКабинета: View {
    @ObservedObject private var заявки = ЗаявкиМодель.shared

    init() {}

    var body: some View {
        let новых: Int = заявки.новых
        СсылкаКабинета(цель: КабинетЦель.заявки) {
            HStack {
                ПодписьСтрокиКабинета(ИнбоксText.т("req_title"), значок: "hand.raised")
                Spacer(minLength: 8)
                if новых > 0 {
                    ЗначокСчётчикаКабинета(новых)
                }
            }
        }
        .accessibilityValue(новых > 0 ? String(format: AccessText.т("unread"), новых) : "")
        .полямиСтрокиКабинета()
    }
}

// MARK: - «Сделка состоялась?»

/// Этап 45: окно «Сделка состоялась?» (my_pending_feedback) — раз за запуск, как сайт при загрузке кабинета. Подписка на
/// ЗаявкиМодель — у этого модификатора, а не у корня кабинета. Скрытый живой стек (наЭкране = false) окна не
/// показывает: оно дождётся, пока кабинет снова покажут.
struct ОтзывЗаявкиКабинета: ViewModifier {
    let наЭкране: Bool
    @ObservedObject private var заявки = ЗаявкиМодель.shared

    init(наЭкране: Bool) {
        self.наЭкране = наЭкране
    }

    func body(content: Content) -> some View {
        content
            .sheet(item: окно) { отзыв in
                ОкноОтзываЗаявки(отзыв: отзыв, модель: заявки)
            }
    }

    /// Закрыли лист — вопрос прочь, как у прямой привязки $заявки.отзыв.
    private var окно: Binding<ОжидаетОтзыва?> {
        Binding(get: { наЭкране ? заявки.отзыв : nil }, set: { новое in заявки.отзыв = новое })
    }
}

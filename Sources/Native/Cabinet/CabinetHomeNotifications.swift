import SwiftUI
import UIKit
import UserNotifications

/**
 «УВЕДОМЛЕНИЯ И ПОДПИСКИ» — ЭКРАН ОДНОЙ СТРОКИ ГЛАВНОГО ЭКРАНА КАБИНЕТА (13.10.2026).

 Раньше на главном экране кабинета подряд стояли четыре группы: статус уведомлений, «Сохранённые поиски», «Продавцы»
 и «Снижение цены». Теперь там одна строка «Уведомления и подписки» со статусом справа, а все четыре группы — здесь,
 на одно нажатие дальше (тот же приём, что у «Доставок и аренд»). Пункты и действия прежние: статус, «Разрешить
 уведомления» (пока система не спрашивала), «Открыть настройки iPhone», поиски со свайпом «Удалить», продавцы со
 свайпом «Отписаться», переключатель снижения цены — с теми же рубильниками Config. Строки статуса — общим образцом
 строк кабинета (ПодписьСтрокиКабинета, своя стрелка, полямиСтрокиКабинета).

 Статус уведомлений экран спрашивает у системы сам: при показе и при возврате из Настроек iPhone.
 */
struct ЭкранУведомленийКабинета: View {
    let открыть: (URL) -> Void
    @State private var уведомления: UNAuthorizationStatus? = nil
    @Environment(\.scenePhase) private var фаза

    init(открыть: @escaping (URL) -> Void) {
        self.открыть = открыть
    }

    private var заголовок: String { КабинетГлавнаяText.т("notif_hub") }

    var body: some View {
        List {
            if Config.дизайнКакНаСайте {
                разделСтатуса
                    .строкиСайта()
                разделыПодписок
                    .строкиСайта()
            } else {
                разделСтатуса
                разделыПодписок
            }
        }
        .listStyle(.insetGrouped)
        .listSectionSpacing(16)
        .navigationTitle(заголовок)
        .navigationBarTitleDisplayMode(.inline)
        .modifier(ВидСайтаУведомленийКабинета(заголовок: заголовок))
        .task { await обновить() }
        /* Вернулись из Настроек iPhone — разрешение могли включить или выключить. */
        .onChange(of: фаза) { _, стала in
            if стала == .active { Task { await обновить() } }
        }
    }

    // MARK: - Статус уведомлений

    private var разделСтатуса: some View {
        Section {
            HStack {
                ПодписьСтрокиКабинета(CabinetText.т("notif_row"), значок: "bell")
                Spacer(minLength: 8)
                Text(ДанныеТелефона.названиеСтатуса(уведомления))
                    .font(.system(size: 14))
                    .foregroundStyle(уведомления == .denied ? Theme.оранжевый : Theme.текстВторой)
            }
            .accessibilityElement(children: .combine)
            .полямиСтрокиКабинета()
            /* Окно разрешения система показывает только до первого ответа; потом — лишь Настройки iPhone. */
            if уведомления == .notDetermined {
                Button {
                    Task {
                        await ДанныеТелефона.попроситьУведомления()
                        await обновить()
                    }
                } label: {
                    HStack {
                        ПодписьСтрокиКабинета(CabinetText.т("notif_ask"), значок: "bell.badge")
                        Spacer(minLength: 8)
                        СтрелкаСтрокиКабинета()
                    }
                }
                .полямиСтрокиКабинета()
            }
            Button {
                if let u = URL(string: UIApplication.openSettingsURLString) { UIApplication.shared.open(u) }
            } label: {
                HStack {
                    ПодписьСтрокиКабинета(CabinetText.т("notif_settings"), значок: "gear")
                    Spacer(minLength: 8)
                    СтрелкаСтрокиКабинета()
                }
            }
            .полямиСтрокиКабинета()
        } header: {
            ЗаголовокГруппыКабинета(CabinetText.т("notifications"))
        } footer: {
            if уведомления == .denied { Text(CabinetText.т("notif_off_footer")) }
        }
    }

    // MARK: - Поиски, продавцы, снижение цены

    @ViewBuilder
    private var разделыПодписок: some View {
        /* Этап 12: сохранённые поиски — рядом со статусом: без уведомлений проверка молчит, и видно это здесь же. */
        if Config.сохранённыеПоиски { РазделСохранённыхПоисков(уведомления: уведомления) }
        /* Этап 36: продавцы, на которых подписан вошедший, — рядом с поисками, как «Продавцы» в подписках сайта. */
        if Config.подпискиССайтом { РазделПодписокНаПродавцов(открыть: открыть) }
        /* Этап 21: снижение цены в избранном — то же фоновое задание и те же условия, поэтому рядом. */
        if Config.снижениеЦены && Config.избранное { РазделСниженияЦены(уведомления: уведомления) }
    }

    private func обновить() async {
        уведомления = await ДанныеТелефона.статусУведомлений()
    }
}

/// Краска сайта у экрана «Уведомления и подписки» — как у самого кабинета (фон страницы, шапка сайта).
private struct ВидСайтаУведомленийКабинета: ViewModifier {
    let заголовок: String

    func body(content: Content) -> some View {
        if Config.дизайнКакНаСайте {
            content
                .списокСайта()
                .шапкаЭкранаСайта(заголовок)
        } else {
            content
        }
    }
}

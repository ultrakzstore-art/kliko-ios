import Foundation

/**
 ПАМЯТЬ КАБИНЕТА НА ВРЕМЯ ЗАПУСКА (скорость, владелец 16.10.2026: «чтобы он не тупил от слова совсем и моментально
 открывал всё»).

 Вкладка «Профиль» при каждом нажатии создаёт CabinetView заново, и всё его @State начиналось с нуля: колесо на месте
 шапки, прыжок, когда профиль приходил, полная страница cabinet.php на каждый показ — пауза «не чаще раза в 30 с»
 (освеженоВ) не работала вовсе: её отметка умирала вместе с экраном. Теперь то, что экран узнал о человеке, живёт
 здесь до конца запуска: init кабинета засевает из памяти своё @State, а каждое место, где экран его меняет, пишет и
 сюда. Повторный показ — сразу готовый экран, а освежить или освежитьБезСтраницы решает та же отметка, что раньше.

 Память — только про того же человека (годна): сменился вход, пока кабинета не было на экране, или вход ещё не сверен —
 экран начинается с нуля, как раньше. Выход (ВыходНачисто) стирает её целиком.

 «Кабинет легче» (живой стек, NativeTabsView.кабинетЖив): после первого показа экран остаётся в дереве под другими
 вкладками, и память нужна только новому экрану — после выхода и когда с вкладки ушли с открытым поверх корня экраном.
 */
@MainActor
enum ПамятьКабинета {
    /// Вошёл ли человек на сайте; nil — не знаем.
    static var вошёл: Bool? = nil
    /// Страница уже ответила хоть раз — колесо вместо «не удалось» больше не нужно.
    static var проверили = false
    /// Что напечатала страница кабинета (вход, имя, номер, токен, соглашение). Пришла страница другого человека (или
    /// её не стало) — то, что память знала о прежнем, прочь сразу: экран пишет поля по одному, и показ, начатый между
    /// ними, не должен взять новому чужой колокольчик, сигнал или «Я бизнес». Сводку отзывов не трогаем: она и так
    /// показывается только своему номеру (отзывыЧьи).
    static var кабинет: КабинетСайта.Состояние? = nil {
        didSet {
            guard (кабинет?.uid ?? "") != (oldValue?.uid ?? "") else { return }
            сигнал = nil
            колокольчик = []
            бизнесАвто = false
        }
    }
    /// Сигнал /api/sess_alert.php — сеанс завершён или вход с другого устройства.
    static var сигнал: КабинетСайта.СигналСеанса? = nil
    /// Когда кабинет последний раз читал страницу: показ в ближайшие 30 с — без неё.
    static var освеженоВ: Date? = nil
    /// Колокольчик — записи панели уведомлений со страницы кабинета.
    static var колокольчик: [УведомлениеКабинета] = []
    /// HELP_URL страницы кабинета — «Справочный центр».
    static var справка = "/kz/ru/help"
    /// «Я бизнес» по признакам страницы (PRO, магазин, реквизиты компании).
    static var бизнесАвто = false
    /// Сводка отзывов вошедшего для плитки «Отзывы» и чья она (свой номер на момент запроса).
    static var сводкаОтзывов: ОтзывыПродавца.Сводка? = nil
    static var отзывыЧьи = ""
    /// Что умеет телефон (AppLock.kind): faceID / touchID / opticID / passcode / none. nil — ещё не спрашивали. Скорость
    /// («кабинет легче»): LAContext и два canEvaluatePolicy — раз за запуск и после возврата из фона (код-пароль или
    /// Face ID могли настроить в Настройках), а не на каждом показе и возврате «Назад». Не про человека — выход не стирает.
    static var способВхода: String? = nil

    /**
     Память про того же человека, что сейчас в общем состоянии входа (СессияПриложения): вошедший с тем же номером,
     прочитанным со страницы кабинета, или гость при госте. Не знаем, кто вошёл, или номер не совпал — не годится.
     */
    static var годна: Bool {
        let сессия = СессияПриложения.shared
        switch вошёл {
        case .some(true):
            guard сессия.вошёл == true, let uid = кабинет?.uid, !uid.isEmpty else { return false }
            return uid == сессия.id
        case .some(false):
            return сессия.вошёл == false
        case .none:
            return false
        }
    }

    /// Выход из аккаунта (ВыходНачисто): ничего от ушедшего следующему не показываем.
    static func стереть() {
        вошёл = nil
        проверили = false
        кабинет = nil
        сигнал = nil
        освеженоВ = nil
        колокольчик = []
        справка = "/kz/ru/help"
        бизнесАвто = false
        сводкаОтзывов = nil
        отзывыЧьи = ""
    }
}

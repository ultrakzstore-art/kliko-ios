/// Насколько выдача похожих совпала с тем, что распознал Kliko AI, — для подписи под шапкой.
enum УровеньПохожихФото: Equatable, Sendable {
    /// Запрос целиком, раздел и своё место — подписи нет.
    case точно
    /// Запрос и раздел, но по всей стране.
    case поСтране
    /// Запрос целиком без раздела, вся страна.
    case безРаздела
    /// Укороченный запрос (первые слова).
    case короче
    /// Только раздел, без запроса.
    case раздел
    /// Ни одна ступень ничего не дала.
    case пусто
}

/// Итог каскада: похожие без повторов id и что именно их дало — запрос, раздел, место и уровень.
struct ИтогПохожихФото {
    let товары: [Listing]
    let всего: Int?
    /// Запрос, который дал выдачу (пусто — только раздел).
    let запрос: String
    /// Раздел, который дал выдачу (пусто — без раздела).
    let раздел: String
    /// Где нашлось: своё место или вся страна.
    let где: ГдеИскать
    /// Своё место было не «вся страна», а нашлось только по всей стране.
    let шире: Bool
    let уровень: УровеньПохожихФото
}

/// Похожие по распознанному запросу — ступенями от точного к широкому (см. описание файла).
enum КаскадПохожихФото {
    /// Предел запросов ленты на один поиск: обычный и лёгкий (живая полоса камеры).
    static let пределОбычный = 6
    static let пределЛёгкий = 3

    /// Одна ступень: что спросить у ленты и как назвать итог.
    private struct Ступень {
        let запрос: ListingsAPI.Запрос
        let уровень: УровеньПохожихФото
    }

    /// Ступени по порядку: запрос (может быть пуст — тогда только раздел), раздел (может быть пуст), лёгкий режим.
    /// Пары «пустой запрос и пустой раздел» нет никогда — это была бы вся лента, а не похожие.
    @MainActor
    static func найти(запрос: String, раздел: String, лёгкий: Bool, на per: Int) async throws -> ИтогПохожихФото {
        /* Одни знаки и однобуквенные слова — не запрос: тогда только раздел. */
        let q = слова(запрос).isEmpty ? "" : запрос.trimmingCharacters(in: .whitespacesAndNewlines)
        let cat = раздел.trimmingCharacters(in: .whitespacesAndNewlines)
        let своё = ГдеИскать.сохранённое()
        let пустой = ИтогПохожихФото(товары: [], всего: nil, запрос: q, раздел: cat, где: своё, шире: false,
                                     уровень: .пусто)
        let ступени = план(q: q, cat: cat, своё: своё, лёгкий: лёгкий, per: per)
        guard !ступени.isEmpty else { return пустой }

        var первая = true
        каскад: for ступень in ступени {
            try Task.checkCancellation()
            let страница: ListingsPage
            do {
                страница = try await ListingsAPI.загрузить(ступень.запрос).страница
            } catch {
                try Task.checkCancellation()
                if первая { throw error }
                /* Сеть пропала посреди каскада — наверх, как на первой ступени: это не «ничего не нашлось», а «Нет
                   соединения» с «Повторить» (живой поиск не запоминает распознанное и попробует снова). Ответ сервера
                   с ошибкой — следующая ступень. */
                if let ошибка = error as? ListingsAPI.Ошибка, case .сеть = ошибка { throw error }
                continue каскад
            }
            первая = false
            try Task.checkCancellation()
            /* ТОП, которых меньше, чем ТОП-мест, сервер ставит по кругу (rank_gold_layout), и одно объявление приходит
               дважды — два одинаковых id в ForEach ломают сетку и полосу; оставляем первое. */
            var были = Set<String>()
            let товары = страница.items.filter { были.insert($0.id).inserted }
            guard !товары.isEmpty else { continue каскад }
            let з = ступень.запрос
            return ИтогПохожихФото(товары: товары, всего: страница.total, запрос: з.q, раздел: з.cat, где: з.где,
                                   шире: !своё.повсюду && з.где.повсюду, уровень: ступень.уровень)
        }
        return пустой
    }

    /// Ступени а–д без повторов и в пределе запросов; «короче» (г) — в место, оставшееся от прочих, перед д.
    private static func план(q: String, cat: String, своё: ГдеИскать, лёгкий: Bool, per: Int) -> [Ступень] {
        let страна = ГдеИскать()
        let безЗапроса = q.isEmpty
        func ступень(_ текст: String, _ ключ: String, _ где: ГдеИскать, _ уровень: УровеньПохожихФото) -> Ступень {
            var з = ListingsAPI.Запрос()
            з.per = per
            з.q = текст
            з.cat = ключ
            з.где = где
            return Ступень(запрос: з, уровень: уровень)
        }
        /* а; б — если своё место не вся страна; в — всегда, если есть запрос: ИИ мог ошибиться с разделом, и лёгкий
           режим без «в» показал бы случайные объявления раздела под подписью «Kliko AI: <запрос>». В лёгком режиме
           предел 3 срезает д, если есть б. */
        var первые = [ступень(q, cat, своё, безЗапроса ? .раздел : .точно)]
        if !своё.повсюду {
            первые.append(ступень(q, cat, страна, безЗапроса ? .раздел : .поСтране))
        }
        if !безЗапроса {
            первые.append(ступень(q, "", страна, .безРаздела))
        }
        let основные = безПовторов(первые, кроме: [])
        /* д */
        let последние: [Ступень] = cat.isEmpty ? []
            : безПовторов([ступень("", cat, страна, .раздел)], кроме: основные)
        let предел = лёгкий ? пределЛёгкий : пределОбычный
        guard !лёгкий, !безЗапроса else { return Array((основные + последние).prefix(предел)) }
        /* г */
        var короткие = безПовторов(укороченные(q).map { ступень($0, cat, страна, .короче) },
                                   кроме: основные + последние)
        let место = max(0, предел - основные.count - последние.count)
        if короткие.count > место {
            /* Все не влезают — длинные по порядку, а «первые два слова» остаются последней из них. */
            короткие = место == 0 ? [] : Array(короткие.prefix(место - 1)) + [короткие[короткие.count - 1]]
        }
        return Array((основные + короткие + последние).prefix(предел))
    }

    /// Без пустых (ни запроса, ни раздела — это вся лента) и без повторов — внутри списка и с уже взятыми.
    private static func безПовторов(_ ступени: [Ступень], кроме взятые: [Ступень]) -> [Ступень] {
        var итог: [Ступень] = []
        for с in ступени {
            if с.запрос.q.isEmpty && с.запрос.cat.isEmpty { continue }
            if взятые.contains(where: { $0.запрос == с.запрос }) || итог.contains(where: { $0.запрос == с.запрос }) {
                continue
            }
            итог.append(с)
        }
        return итог
    }

    /// Слова запроса: пробелы любые, знаки по краям слова сняты, слова короче двух знаков и голые знаки выброшены.
    static func слова(_ запрос: String) -> [String] {
        let знаки = CharacterSet.punctuationCharacters.union(.symbols)
        return запрос.split(whereSeparator: { $0.isWhitespace })
            .map { String($0).trimmingCharacters(in: знаки) }
            .filter { слово in
                слово.count >= 2 && слово.unicodeScalars.contains(where: { CharacterSet.alphanumerics.contains($0) })
            }
    }

    /// Укороченные запросы: без последнего слова, без двух последних… до двух слов; «первые два слова» — последний.
    /// Два слова и меньше — короче некуда, пусто. Повторы (без учёта регистра) отброшены.
    static func укороченные(_ запрос: String) -> [String] {
        let все = слова(запрос)
        guard все.count > 2 else { return [] }
        var итог: [String] = []
        var виденные = Set<String>()
        for длина in stride(from: все.count - 1, through: 2, by: -1) {
            let кандидат = все.prefix(длина).joined(separator: " ")
            if виденные.insert(кандидат.lowercased()).inserted { итог.append(кандидат) }
        }
        return итог
    }
}


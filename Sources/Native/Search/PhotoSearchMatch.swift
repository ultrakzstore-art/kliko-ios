/// Сайт не распознал снимок: раздел сайта по Vision на телефоне — как подсказка живого поиска (АнализКадровПоиска),
/// метки увереннее 0,3 по словарю СловарьЖивогоПоиска; ни одна не совпала — nil.
enum РазделСнимкаНаТелефоне {
    static let порог: Float = 0.3

    /// Не на главной нити: Vision по большому снимку — десятки миллисекунд.
    static func найти(_ снимок: UIImage) async -> String? {
        await Task.detached(priority: .userInitiated) { () -> String? in
            РазделСнимкаНаТелефоне.распознать(снимок)
        }.value
    }

    /// Сам разбор — для фоновой задачи. Снимок без CGImage (из CIImage) — nil.
    static func распознать(_ снимок: UIImage) -> String? {
        guard let картинка = снимок.cgImage else { return nil }
        let запрос = VNClassifyImageRequest()
        let обработчик = VNImageRequestHandler(cgImage: картинка, orientation: ориентация(снимок.imageOrientation),
                                              options: [:])
        do {
            try обработчик.perform([запрос])
        } catch {
            return nil
        }
        let уверенные = (запрос.results ?? [])
            .filter { $0.confidence > порог }
            .sorted { $0.confidence > $1.confidence }
        for метка in уверенные.prefix(5) {
            if let ключ = СловарьЖивогоПоиска.раздел(метка.identifier) { return ключ }
        }
        return nil
    }

    /// Поворот снимка для Vision: у галереи и камеры пиксели CGImage лежат как сняты, а поворот — в метке UIImage.
    private static func ориентация(_ метка: UIImage.Orientation) -> CGImagePropertyOrientation {
        switch метка {
        case .up: return .up
        case .upMirrored: return .upMirrored
        case .down: return .down
        case .downMirrored: return .downMirrored
        case .left: return .left
        case .leftMirrored: return .leftMirrored
        case .right: return .right
        case .rightMirrored: return .rightMirrored
        @unknown default: return .up
        }
    }
}

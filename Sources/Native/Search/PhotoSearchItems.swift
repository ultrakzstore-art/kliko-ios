/// Что photo_search прислал при успехе: query и category, как раньше, и поля правки сайта 14.10.2026. Старый сервер —
/// новые поля пустые, и всё идёт по-старому.
struct РаспознаноПоФото: Equatable {
    /// query — короткий запрос, 1–3 слова.
    let запрос: String
    /// category — ключ корневого раздела сайта или пусто.
    let раздел: String
    /// title — описание для человека, до 90 знаков; пусто — не пришло.
    let описание: String
    /// keywords — написания (0–8): бренд, модель, тип, по-русски, по-казахски, разговорное.
    let написания: [String]
    /// confidence 0…1; nil — не пришло (0 — модель не сообщила или ответила не по формату).
    let уверенность: Double?
    /// qa — «слово1|слово2|…» для api/listings.php; пусто — следующих страниц не просим.
    let qa: String
    /// items — первые карточки в порядке «где совпало больше написаний», без повторов id.
    let товары: [Listing]
    /// items_total — сколько всего найдено по написаниям; nil — не пришло.
    let всего: Int?
    /// items_cat — раздел, где найдены items: равен category или пуст (сервер искал во всех разделах).
    let разделКарточек: String
    /// items_city — город, где найдены items: равен присланному city или пуст (по всей стране).
    let городКарточек: String
    /// city, который ушёл в запрос; пусто — не слали (вся страна или регион без города).
    let присланныйГород: String
    /// own_ai_run (ultra-site 14.10.2026, «Свой ИИ» во всех местах, пункт 1): распознал свой ИИ человека — к итогу
    /// «через ваш ИИ», а не «Kliko AI». Старый сервер или ответил Kliko AI — поля нет, false.
    let своимИИ: Bool
}

/// Выдача похожих по написаниям: первая страница — items photo_search, следующие — лента с qa.
struct ЛистаниеПохожихФото: Equatable {
    /// per следующих страниц — как в адресе сайта и как items (до 24): страница 2 начинается сразу после них.
    static let наСтранице = 24

    /// qa, items_cat и items_city ответа photo_search — с ними просим следующие страницы.
    let qa: String
    let раздел: String
    let город: String
    /// Своё место не «вся страна», а items найдены по всей стране: подпись «Рядом не нашли» и без «Все в ленте».
    let шире: Bool
    /// Последняя загруженная страница: 1 — сами items.
    private(set) var страница = 1
    /// Дальше нечего: всё уже на экране, сервер сказал has_more=false, страница пришла неполной, без новых карточек
    /// или без поля qa.
    private(set) var конец: Bool

    init(qa: String, раздел: String, город: String, шире: Bool, первых: Int, всего: Int?) {
        self.qa = qa
        self.раздел = раздел
        self.город = город
        self.шире = шире
        /* items_total нет — судим по размеру: неполная первая страница — последняя. */
        конец = qa.isEmpty || (всего.map { первых >= $0 } ?? (первых < Self.наСтранице))
    }

    /// Первая страница из ответа photo_search и её листание; items пуст (или старый сервер) — nil: прежний каскад.
    static func первая(_ р: РаспознаноПоФото, своё: ГдеИскать) -> (итог: ИтогПохожихФото, листание: ЛистаниеПохожихФото)? {
        guard !р.товары.isEmpty else { return nil }
        let город = р.городКарточек
        let шире = !своё.повсюду && город.isEmpty
        let безРаздела = !р.раздел.isEmpty && р.разделКарточек.isEmpty
        let уровень: УровеньПохожихФото = безРаздела ? .безРаздела : (шире ? .поСтране : .точно)
        let где = город.isEmpty ? ГдеИскать() : ГдеИскать(город: город)
        let итог = ИтогПохожихФото(товары: р.товары, всего: р.всего, запрос: р.запрос, раздел: р.разделКарточек,
                                   где: где, шире: шире, уровень: уровень)
        let листание = ЛистаниеПохожихФото(qa: р.qa, раздел: р.разделКарточек, город: город, шире: шире,
                                           первых: р.товары.count, всего: р.всего)
        return (итог, листание)
    }

    /// Следующая страница: GET api/listings.php?qa=…&cat=<items_cat>&city=<items_city>&page=N&per=24 — без своего
    /// района и фильтров ленты, ровно как в адресе сайта (иначе порядок не продолжил бы items).
    var следующая: ListingsAPI.Запрос {
        var з = ListingsAPI.Запрос()
        з.page = страница + 1
        з.per = Self.наСтранице
        з.qa = qa
        з.cat = раздел
        з.где = город.isEmpty ? ГдеИскать() : ГдеИскать(город: город)
        return з
    }

    /// Пришла следующая страница: сколько карточек в ней было, сколько из них новых (не на экране), has_more и total
    /// ответа, сколько теперь на экране.
    mutating func пришла(было: Int, новых: Int, естьЕщё: Bool?, всего: Int?, наЭкране: Int) {
        страница += 1
        let всёНаЭкране = всего.map { наЭкране >= $0 } ?? false
        if новых == 0 || было < Self.наСтранице || естьЕщё == false || всёНаЭкране { конец = true }
    }

    /// Сервер ленты не искал по написаниям (нет поля qa) — дальше не листаем.
    mutating func закончить() {
        конец = true
    }

    /// Поле qa ответа ленты — не на главной очереди: разбор страницы до 24 карточек, как ListingsAPI.разобратьВФоне.
    static func написанияВФоне(_ данные: Data) async -> [String]? {
        ListingsAPI.написанияОтвета(данные)
    }
}

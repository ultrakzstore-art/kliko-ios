/**
 ПОИСК ПО ФОТО: КАРТОЧКИ В ОТВЕТЕ САЙТА (правка сайта 14.10.2026, «Поиск по фото: короткий запрос, написания, карточки
 в ответе»).

 photo_search.php теперь сам ищет похожие. Кроме короткого query (1–3 слова) и category он присылает title — описание
 для человека («Apple iPhone 13 Pro, синий»), keywords — написания, confidence, qa — запрос и написания одной строкой
 для api/listings.php, items — до 24 первых карточек в формате ленты, items_total, а также items_cat и items_city —
 раздел и город, где они найдены (пусто — сервер искал во всех разделах или по всей стране). В запрос приложение кладёт
 city — свой город так, как он уходит в ленту (ГдеИскать.параметры, ПоискПоФотоAPI.городПоиска).

 Что делает приложение:
 • items есть — первая страница похожих и полоса живого поиска берут их, без каскада; капсула «Kliko AI видит: <title>»
   (title нет — query);
 • следующие страницы — GET api/listings.php?qa=<qa>&cat=<items_cat>&city=<items_city>&page=N&per=24 (порядок
   продолжает items): подгрузка, когда долистали до конца сетки, «Показать ещё» под ней и следующая страница у

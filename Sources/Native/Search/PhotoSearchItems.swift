   карточек — дальше не листаем;
 • подпись уровня: своё место не «вся страна», а items_city пуст — «Рядом не нашли — по всему Казахстану»; items_cat
   пуст при category — «без раздела»; оба — одной строкой;
 • items пуст или полей нет (старый сервер) — прежний каскад по query (КаскадПохожихФото, PhotoSearchMatch.swift).

enum EDSText {
    static func т(_ ключ: String) -> String {
        let язык = String((Locale.preferredLanguages.first ?? "ru").prefix(2))
        let словарь = тексты[язык] ?? ru
        return словарь[ключ] ?? ru[ключ] ?? ключ
    }

    /// _edsT(ключ, запасной, {имя: значение}): {имя} → значение.
    static func т(_ ключ: String, _ подстановки: [String: String]) -> String {
        var итог = т(ключ)
        for (имя, значение) in подстановки {
            итог = итог.replacingOccurrences(of: "{" + имя + "}", with: значение)
        }
        return итог
    }

    /// Событие протокола: eds_ev_<what>; своего текста нет — как есть (_edsT("eds_ev_"+what, what)).
    static func событие(_ что: String) -> String {
        let ключ = "eds_ev_" + что
        let текст = т(ключ)
        return текст == ключ ? что : текст
    }


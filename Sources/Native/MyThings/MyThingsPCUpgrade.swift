    // MARK: Вход

    static func подсказки(_ к: КомпьютерМоего, цель: ЦельАпгрейдаМоего) -> ПодсказкиКомпьютераМоего {
        var все: [ВариантАпгрейдаМоего] = []
        все += память(к)
        let диски = накопители(к)
        все += диски
        все += видеокарта(к)
        все += блокПитания(к)
        все += процессор(к, цель)
        if диски.isEmpty { все += внешний(к) }
        все += продатьСвой(к)

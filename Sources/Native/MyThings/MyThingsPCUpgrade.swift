        let упорядоченные = все.enumerated().sorted { а, б in
            let ia = порядок.firstIndex(of: а.element.группа) ?? 99
            let ib = порядок.firstIndex(of: б.element.группа) ?? 99
            return ia != ib ? ia < ib : а.offset < б.offset
        }.map(\.element)
        return ПодсказкиКомпьютераМоего(диагноз: диагноз(к),
                                         варианты: Array(упорядоченные.filter { !$0.нельзя }.prefix(3)),
                                         нельзя: Array(упорядоченные.filter(\.нельзя).prefix(3)))
    }

    // MARK: Диагноз

    static func диагноз(_ к: КомпьютерМоего) -> [ПунктСверкиСтандарта] {
        var итог: [ПунктСверкиСтандарта] = []
        let м = к.память
        if let всего = м.всего {
            if всего <= 4 {
                итог.append(ПунктСверкиСтандарта("ram", .проверить, формат("mpc_dg_ram_low", String(всего))))
            } else if всего <= 8 {
                итог.append(ПунктСверкиСтандарта("ram", .проверить, формат("mpc_dg_ram_tight", String(всего))))
            } else {
                итог.append(ПунктСверкиСтандарта("ram", .подходит, формат("mpc_dg_ram_ok", String(всего))))
            }
        } else if !м.известна {
            итог.append(ПунктСверкиСтандарта("ram", .неизвестно, т("mpc_dg_ram_unknown")))
        }
        if м.всяРаспаяна {
            итог.append(ПунктСверкиСтандарта("soldered", .неПодходит, т("mpc_dg_ram_soldered")))
        } else if let свободно = м.свободно, свободно > 0, let слотов = м.слотов {
            итог.append(ПунктСверкиСтандарта("slots", .подходит,
                                             формат("mpc_dg_ram_free", String(свободно), String(слотов))))
        }
        if let первый = к.накопители.first, первый.hdd {
            итог.append(ПунктСверкиСтандарта("hdd", .проверить, т("mpc_dg_hdd")))
        }
        let тб = к.накопители.compactMap(\.тб).reduce(0, +)
        if тб > 0 && тб < 0.3 {
            итог.append(ПунктСверкиСтандарта("small", .проверить, формат("mpc_dg_small", ФорматКомпьютераМоего.объём(тб))))
        }
        if к.свободныйM2 != nil {
            итог.append(ПунктСверкиСтандарта("m2", .подходит, т("mpc_dg_m2_free")))
        } else if к.накопители.isEmpty && к.слотыM2.isEmpty {
            итог.append(ПунктСверкиСтандарта("drive", .неизвестно, т("mpc_dg_drive_unknown")))
        }
        if к.вид == .настольный, let чип = к.видеокарта.чип,
           let нужно = КаталогСтандартов.нужноБП(чип: чип, tdpПроцессора: к.tdp), let есть = к.бп.ватт, есть < нужно {
            итог.append(ПунктСверкиСтандарта("psu", .проверить, формат("mpc_dg_psu_low", String(есть), чип, String(нужно))))
        }
        if !итог.isEmpty && !итог.contains(where: { $0.уровень == .проверить || $0.уровень == .неПодходит }) {
            итог.append(ПунктСверкиСтандарта("ok", .подходит, т("mpc_dg_ok")))
        }
        return Array(итог.prefix(5))
    }

    // MARK: Память

    private static func память(_ к: КомпьютерМоего) -> [ВариантАпгрейдаМоего] {
        let м = к.память
        guard !м.всяРаспаяна, let поколение = м.поколение, let форма = м.форма, форма != "soldered",
              !КаталогСтандартов.распаянныеПоколения.contains(поколение) else { return [] }
        let всего = м.всего ?? 0
        var поля: [String: String] = [К.поколение: поколение, К.форма: форма]
        if let ч = м.частота { поля[К.частота] = String(ч) }
        let подписьПамяти = поколение + " " + форма + (м.частота.map { " " + String($0) } ?? "")
        if let свободно = м.свободно, свободно > 0 {
            let гб = м.планки.first ?? (поколение == "DDR5" ? 16 : 8)
            поля[К.гб] = String(гб)
            let кандидат = разбор(.память, поля)
            let станет = всего + гб
            var пункты = (СверкаСтандартов.память(кандидат.разбор, к)?.пункты ?? []).filter { $0.id != "total" }
            пункты.append(ПунктСверкиСтандарта("slot_free", .подходит, т("mpc_up_slot_free")))
            let польза = м.планки.count == 1 && (м.слотов ?? 0) >= 2
                ? формат("mpc_up_ram_dual", String(станет)) : формат("mpc_up_ram_will", String(станет))
            let компонент = КомпонентАпгрейдаМоего(семья: .память, раздел: "ram", набор: кандидат.набор,
                                                   подпись: ФорматКомпьютераМоего.гб(гб) + " " + подписьПамяти)
            return [ВариантАпгрейдаМоего(id: "ram_add", группа: "ram", часть: .память,
                                         заголовок: формат("mpc_up_ram_add", String(гб), подписьПамяти), польза: польза,
                                         пункты: пункты, компоненты: [компонент], поставить: "easy")]
        }
        // Слоты заняты — комплект на замену: вдвое больше, не меньше 16 ГБ.
        guard let слотов = м.слотов, слотов > 0, !м.планки.isEmpty else { return [] }
        let штук = min(слотов, 2)
        let нужно = max(всего * 2, 16)
        guard let гб = КаталогСтандартов.объёмыМодуля.first(where: { $0 * штук >= нужно }) else { return [] }
        поля[К.гб] = String(гб)
        let кандидат = разбор(.память, поля, сколько: штук)
        let станет = гб * штук + (м.распаяно ?? 0)
        var пункты = (СверкаСтандартов.память(кандидат.разбор, к)?.пункты ?? [])
            .filter { !["slots", "total", "max"].contains($0.id) }
        if let максимум = м.максимум, станет > максимум {
            пункты.append(ПунктСверкиСтандарта("max", .проверить, формат("mpc_up_ram_max", String(максимум))))
        } else {
            пункты.append(ПунктСверкиСтандарта("total", .подходит, формат("mpc_up_ram_total", String(станет))))
        }
        var старые: [String] = []
        for объём in Set(м.планки).sorted(by: >) {
            let сколько = м.планки.filter { $0 == объём }.count
            старые.append((сколько > 1 ? String(сколько) + "×" : "") + ФорматКомпьютераМоего.гб(объём))
        }
        let было = старые.joined(separator: " + ") + " " + поколение
        let компонент = КомпонентАпгрейдаМоего(семья: .память, раздел: "ram", набор: кандидат.набор,
                                               подпись: String(штук) + "×" + ФорматКомпьютераМоего.гб(гб) + " "
                                                   + подписьПамяти)
        return [ВариантАпгрейдаМоего(id: "ram_kit", группа: "ram", часть: .память,
                                     заголовок: формат("mpc_up_ram_kit", String(штук), String(гб), подписьПамяти),
                                     польза: формат("mpc_up_ram_kit_will", String(станет)), пункты: пункты,
                                     компоненты: [компонент], старая: было, поставить: "easy")]
    }

    // MARK: Накопители

    /// SSD под слот: длина слота (до 2280), протокол слота, PCIe — не выше 4.0.
    private static func поляSSD(_ слот: СлотM2Моего, тб: String) -> [String: String] {
        let длина = КаталогСтандартов.длинаM2(слот.длина) ?? 80
        var поля: [String: String] = [К.форма: длина >= 80 ? "2280" : слот.длина, К.тб: тб]
        if слот.протокол == "sata" {
            поля[К.протокол] = "sata"
        } else {
            поля[К.протокол] = "nvme"
            поля[К.pcie] = String(min(слот.pcie ?? 3, 4))
        }
        return поля
    }

    private static func накопители(_ к: КомпьютерМоего) -> [ВариантАпгрейдаМоего] {
        var итог: [ВариантАпгрейдаМоего] = []
        let всегоТБ = к.накопители.compactMap(\.тб).reduce(0, +)
        let системный = к.накопители.first
        let отсеков = к.отсеков25 ?? 0
        let занятоОтсеков = к.накопители.filter { $0.форма == "2.5" }.count
        var слотДляНового = к.свободныйM2
        // Система на HDD — SSD вместо него: в свободный M.2 или в отсек 2.5″.
        if let системный, системный.hdd {
            let поля: [String: String]
            if let слот = слотДляНового {
                поля = поляSSD(слот, тб: "1")
                слотДляНового = nil
            } else if отсеков > 0 || системный.форма == "2.5" || к.вид == .настольный {
                поля = [К.форма: "2.5", К.протокол: "sata", К.тб: "1"]
            } else {
                поля = [:]
            }
            if !поля.isEmpty {
                let кандидат = разбор(.накопитель, поля)
                var пункты = (СверкаСтандартов.накопитель(кандидат.разбор, к)?.пункты ?? []).filter { $0.id != "busy" }
                if поля[К.форма] == "2.5", системный.форма == "2.5" || системный.форма == "3.5" {
                    пункты.removeAll { $0.id == "bay" }
                    пункты.append(ПунктСверкиСтандарта("bay", .подходит, т("mpc_up_bay_swap")))
                }
                пункты.append(ПунктСверкиСтандарта("move", .проверить, т("mpc_up_move_system")))
                let подпись = РазборСтандартов.подпись(кандидат.набор, .накопитель)
                итог.append(ВариантАпгрейдаМоего(id: "hdd_swap", группа: "ssd", часть: .накопители,
                                                 заголовок: формат("mpc_up_ssd_for_hdd", подпись),
                                                 польза: т("mpc_up_ssd_for_hdd_use"), пункты: пункты,
                                                 компоненты: [компонентSSD(кандидат.набор, подпись)],
                                                 старая: ФорматКомпьютераМоего.диск(системный), поставить: "easy"))
            }
        }
        // Свободный M.2 — второй SSD.
        if let слот = слотДляНового {
            let кандидат = разбор(.накопитель, поляSSD(слот, тб: всегоТБ >= 1 ? "2" : "1"))
            let пункты = СверкаСтандартов.накопитель(кандидат.разбор, к)?.пункты ?? []
            let подпись = РазборСтандартов.подпись(кандидат.набор, .накопитель)
            итог.append(ВариантАпгрейдаМоего(id: "ssd_add", группа: "ssd", часть: .накопители,
                                             заголовок: формат("mpc_up_ssd_add", подпись), польза: т("mpc_up_ssd_add_use"),
                                             пункты: пункты, компоненты: [компонентSSD(кандидат.набор, подпись)],
                                             поставить: "easy"))
        } else if к.свободныйM2 == nil, отсеков > занятоОтсеков, системный?.hdd != true {
            // Свободный отсек 2.5″ — SATA SSD.
            let кандидат = разбор(.накопитель, [К.форма: "2.5", К.протокол: "sata", К.тб: "1"])
            let пункты = СверкаСтандартов.накопитель(кандидат.разбор, к)?.пункты ?? []
            let подпись = РазборСтандартов.подпись(кандидат.набор, .накопитель)
            итог.append(ВариантАпгрейдаМоего(id: "ssd_bay", группа: "ssd", часть: .накопители,
                                             заголовок: формат("mpc_up_ssd_add", подпись), польза: т("mpc_up_ssd_add_use"),
                                             пункты: пункты, компоненты: [компонентSSD(кандидат.набор, подпись)],
                                             поставить: "easy"))
        } else if к.свободныйM2 == nil, let системный, !системный.hdd, всегоТБ > 0, всегоТБ < 0.6,
                  let слот = к.слотыM2.first {
            // Маленький SSD, слотов больше нет — побольше вместо него.
            let кандидат = разбор(.накопитель, поляSSD(слот, тб: "1"))
            var пункты = (СверкаСтандартов.накопитель(кандидат.разбор, к)?.пункты ?? []).filter { $0.id != "busy" }
            пункты.append(ПунктСверкиСтандарта("move", .проверить, т("mpc_up_move_system")))
            let подпись = РазборСтандартов.подпись(кандидат.набор, .накопитель)
            итог.append(ВариантАпгрейдаМоего(id: "ssd_swap", группа: "ssd", часть: .накопители,
                                             заголовок: формат("mpc_up_ssd_swap", подпись,
                                                               ФорматКомпьютераМоего.объём(всегоТБ)),
                                             польза: т("mpc_up_ssd_swap_use"), пункты: пункты,
                                             компоненты: [компонентSSD(кандидат.набор, подпись)],
                                             старая: ФорматКомпьютераМоего.диск(системный), поставить: "easy"))
        }
        return итог
    }

    private static func компонентSSD(_ набор: НаборСтандартов, _ подпись: String) -> КомпонентАпгрейдаМоего {
        КомпонентАпгрейдаМоего(семья: .накопитель, раздел: "ssd-hdd", набор: набор, подпись: "SSD " + подпись)
    }

    // MARK: Видеокарта и БП

    private static func видеокарта(_ к: КомпьютерМоего) -> [ВариантАпгрейдаМоего] {
        guard к.вид == .настольный else { return [] }
        let своя = к.видеокарта.чип.map { ступениКарт[$0] ?? 6 } ?? 0
        guard let карта = картыАпгрейда.first(where: { (ступениКарт[$0.чип] ?? 0) > своя }) else { return [] }
        let кандидат = разбор(.видеокарта, [К.чип: карта.чип, К.длина: String(карта.длина)])
        guard let сверка = СверкаСтандартов.видеокарта(кандидат.разбор, к) else { return [] }
        var пункты = сверка.пункты.filter { $0.id != К.длина }
        if let предел = к.корпус.длинаКарты {
            let уровень: УровеньСтандарта = карта.длина <= предел - 10 ? .подходит : .проверить
            let ключ = уровень == .подходит ? "mpc_up_gpu_len_ok" : "mpc_up_gpu_len_check"
            пункты.insert(ПунктСверкиСтандарта(К.длина, уровень, формат(ключ, String(карта.длина), String(предел))), at: 0)
        }
        let компонент = КомпонентАпгрейдаМоего(семья: .видеокарта, раздел: "gpu", набор: кандидат.набор, подпись: карта.чип)
        let старая = к.видеокарта.чип
        var итог = [ВариантАпгрейдаМоего(id: "gpu", группа: "gpu", часть: .видеокарта, заголовок: карта.чип,
                                         польза: т("mpc_up_gpu_use"), пункты: пункты, компоненты: [компонент],
                                         старая: старая, поставить: "pro")]
        // БП не тянет или на ступень ниже — вместе с блоком питания.
        if let psu = пункты.first(where: { $0.id == "psu" }), psu.уровень == .неПодходит || psu.уровень == .проверить,
           let нужно = КаталогСтандартов.нужноБП(чип: карта.чип, tdpПроцессора: к.tdp) {
            let наборБП = разбор(.блокПитания, [К.ватт: String(нужно), К.форма: к.бп.форма ?? "ATX"]).набор
            var вместе = пункты.filter { $0.id != "psu" }
            вместе.append(ПунктСверкиСтандарта("psu", .подходит, формат("mpc_up_psu_new", String(нужно))))
            let бп = КомпонентАпгрейдаМоего(семья: .блокПитания, раздел: "power-supplies", набор: наборБП,
                                            подпись: формат("mpc_up_psu", String(нужно), к.бп.форма ?? "ATX"))
            итог.append(ВариантАпгрейдаМоего(id: "gpu_psu", группа: "gpu", часть: .видеокарта,
                                             заголовок: формат("mpc_up_gpu_psu", карта.чип, String(нужно)),
                                             польза: т("mpc_up_gpu_psu_use"), пункты: вместе, компоненты: [компонент, бп],
                                             старая: старая, поставить: "pro"))
        }
        return итог
    }

    private static func блокПитания(_ к: КомпьютерМоего) -> [ВариантАпгрейдаМоего] {
        guard к.вид == .настольный, let чип = к.видеокарта.чип,
              let нужно = КаталогСтандартов.нужноБП(чип: чип, tdpПроцессора: к.tdp), let есть = к.бп.ватт,
              есть < нужно else { return [] }
        let форма = к.бп.форма ?? "ATX"
        let кандидат = разбор(.блокПитания, [К.ватт: String(нужно), К.форма: форма])
        let пункты = СверкаСтандартов.блокПитания(кандидат.разбор, к)?.пункты ?? []
        let подпись = формат("mpc_up_psu", String(нужно), форма)
        let компонент = КомпонентАпгрейдаМоего(семья: .блокПитания, раздел: "power-supplies", набор: кандидат.набор,
                                               подпись: подпись)
        return [ВариантАпгрейдаМоего(id: "psu", группа: "psu", часть: .бп, заголовок: подпись,
                                     польза: формат("mpc_up_psu_use", чип), пункты: пункты, компоненты: [компонент],
                                     старая: т("mpc_part_psu_short") + " " + ФорматКомпьютераМоего.ватт(есть),
                                     поставить: "pro")]
    }

    // MARK: Процессор

    private static func процессор(_ к: КомпьютерМоего, _ цель: ЦельАпгрейдаМоего) -> [ВариантАпгрейдаМоего] {
        guard к.вид == .настольный, let сокет = к.сокетДляСверки, var пара = процессорыАпгрейда[сокет] else { return [] }
        let безКарты = к.видеокарта.встроенная || к.видеокарта.чип == nil
        if безКарты, let сГрафикой = процессорыСГрафикой[сокет] { пара = сГрафикой }
        if сокет == "LGA1151", let ч = к.чипсет, чипсетыLGA1151Старые.contains(ч) {
            пара = (игры: "Core i7-7700", работа: "Core i7-7700")
        }
        let имя = цель == .игры ? пара.игры : пара.работа
        let свой = РазборСтандартов.нормально(к.процессор)
        // Уже такой или сильнее в своей линейке — не предлагаем.
        guard !свой.contains(РазборСтандартов.нормально(имя)),
              !["ryzen 9", "x3d", "i9-", "core i9", "core ultra 9"].contains(where: { свой.contains($0) }) else { return [] }
        if цель != .игры, ["ryzen 7", "i7-", "core ultra 7"].contains(where: { свой.contains($0) }) { return [] }
        let кандидат = разбор(.сокет, [К.сокет: сокет, К.процессор: имя])
        var пункты = СверкаСтандартов.сокет(кандидат.разбор, к)?.пункты ?? []
        if безКарты { пункты.append(ПунктСверкиСтандарта("igpu", .подходит, т("mpc_up_cpu_igpu"))) }
        if к.чипсет == nil, сокет == "AM4" || сокет == "LGA1700" {
            пункты.append(ПунктСверкиСтандарта("bios", .проверить, т("mpc_up_bios_unknown")))
        }
        // Поколение LGA1151 сверка уже назвала («cpu_gen») — своё не дублируем.
        if к.чипсет == nil, сокет == "LGA1151", !пункты.contains(where: { $0.id == "cpu_gen" }) {
            пункты.append(ПунктСверкиСтандарта("gen", .проверить, т("mpc_up_lga1151")))
        }
        let компонент = КомпонентАпгрейдаМоего(семья: .сокет, раздел: "cpu", набор: кандидат.набор, подпись: имя,
                                               запрос: имя)
        let старый = к.процессор.trimmingCharacters(in: .whitespaces)
        return [ВариантАпгрейдаМоего(id: "cpu", группа: "cpu", часть: .процессор, заголовок: имя,
                                     польза: формат("mpc_up_cpu_use", сокет), пункты: пункты, компоненты: [компонент],
                                     старая: старый.isEmpty ? nil : старый, поставить: "pro")]
    }

    // MARK: Внешний SSD и «продать свой»

    /// Внутрь ставить некуда: ни свободного M.2, ни отсека — внешний SSD.
    private static func внешний(_ к: КомпьютерМоего) -> [ВариантАпгрейдаМоего] {
        guard к.естьНакопитель || к.память.всяРаспаяна else { return [] }
        let набор = НаборСтандартов(значения: [СемьяСтандарта.накопитель.rawValue: [К.тб: "1"]], источник: .продавец)
        let компонент = КомпонентАпгрейдаМоего(семья: .накопитель, раздел: "ssd-hdd", набор: набор,
                                               подпись: т("mpc_up_ext"), запрос: т("mpc_q_ext"),
                                               слова: ["внешн", "external", "portable", "usb", "сыртқы"])
        return [ВариантАпгрейдаМоего(id: "ext", группа: "ext", часть: .накопители, заголовок: т("mpc_up_ext"),
                                     польза: т("mpc_up_ext_use"),
                                     пункты: [ПунктСверкиСтандарта("usb", .подходит, т("mpc_up_ext_ok"))],
                                     компоненты: [компонент])]
    }

    /// Память распаяна и её мало — честнее сменить ноутбук.
    private static func продатьСвой(_ к: КомпьютерМоего) -> [ВариантАпгрейдаМоего] {
        guard к.вид == .ноутбук, к.память.всяРаспаяна, let всего = к.память.всего, всего <= 8 else { return [] }
        let хочу = max(16, всего * 2)
        let компонент = КомпонентАпгрейдаМоего(семья: .память, раздел: "laptops", набор: НаборСтандартов(),
                                               подпись: формат("mpc_up_sell_want", String(хочу)),
                                               запрос: формат("mpc_q_laptop", String(хочу)), безЦены: true)
        return [ВариантАпгрейдаМоего(id: "sell", группа: "sell", часть: nil,
                                     заголовок: формат("mpc_up_sell", String(хочу)), польза: т("mpc_up_sell_use"),
                                     пункты: [ПунктСверкиСтандарта("price", .проверить, т("mpc_up_sell_price"))],
                                     компоненты: [компонент], старая: к.модель.isEmpty ? к.заголовок : к.модель,
                                     продатьСвой: true)]
    }
}

// MARK: - Цены «от N ₸»

/**
 Живые объявления раздела для «от N ₸»: одна лента раздела без поискового запроса (раздел и город — как у обычной ленты),
 48 свежих; разбор стандартов — вне главной нити. Память — 10 минут, общая для всех карточек; один и тот же раздел,
 пока грузится, второй раз не запрашивается.
 */
@MainActor
final class ЦеныАпгрейдаМоего {
    static let shared = ЦеныАпгрейдаМоего()

    struct Предложение: Equatable, @unchecked Sendable {
        let товар: Listing
        let набор: НаборСтандартов
        /// Название нормально — для слов («внешний»).
        let название: String
        let цена: Int
    }

    struct ЦенаКомпонента: Equatable {
        let подпись: String
        let от: Int?
        let товар: Listing?
        let предложений: Int
        let запрос: String
        let раздел: String
    }

    static let срок: TimeInterval = 600

    private var кэш: [String: (когда: Date, предложения: [Предложение])] = [:]
    private var идут: [String: Task<[Предложение]?, Never>] = [:]

    private init() {}

    /// Предложения раздела; nil — не загрузилось.
    func предложения(раздела раздел: String) async -> [Предложение]? {
        if let запись = кэш[раздел], Date().timeIntervalSince(запись.когда) < Self.срок { return запись.предложения }
        if let идёт = идут[раздел] { return await идёт.value }
        let задача = Task<[Предложение]?, Never> {
            var запрос = ListingsAPI.Запрос()
            запрос.per = 48
            запрос.cat = раздел
            // Свежие подряд (sort=new), без порядка рекомендаций и вставок ТОП — как у «Для вас».
            запрос.фильтры.сортировка = .новыеПодряд
            guard let ответ = try? await ListingsAPI.загрузить(запрос) else { return nil }
            return await ЦеныАпгрейдаМоего.разобрать(ответ.страница.items)
        }
        идут[раздел] = задача
        let итог = await задача.value
        идут[раздел] = nil
        if let итог { кэш[раздел] = (когда: Date(), предложения: итог) }
        return итог
    }

    /// Объявления с ценой (без аренды и резерва) и их стандарты — вне главной нити.
    nonisolated static func разобрать(_ товары: [Listing]) async -> [Предложение] {
        товары.compactMap { (товар: Listing) -> Предложение? in
            guard !товар.forRent, !товар.вРезерве, let цена = товар.price, цена.isFinite, цена >= 100 else { return nil }
            let разбор = РазборСтандартов.разобрать(товар)
            guard !разбор.набор.пусто else { return nil }
            return Предложение(товар: товар, набор: разбор.набор, название: РазборСтандартов.нормально(товар.title),
                               цена: Int(цена.rounded()))
        }
    }

    /// Самое дешёвое подходящее и сколько их.
    static func цена(_ компонент: КомпонентАпгрейдаМоего, _ предложения: [Предложение]) -> ЦенаКомпонента {
        let годные = предложения.filter { подходит($0, компонент) }.sorted { $0.цена < $1.цена }
        return ЦенаКомпонента(подпись: компонент.подпись, от: годные.first?.цена, товар: годные.first?.товар,
                              предложений: годные.count, запрос: компонент.запрос, раздел: компонент.раздел)
    }

    /// Объявление подходит варианту: ОЗУ — поколение, форма, объём и штук точно (серверная — нет); SSD — форма не
    /// длиннее, протокол, объём ±10 %; карта — чип; БП — не слабее и не больше чем на 250 Вт; процессор — сокет и модель.
    static func подходит(_ п: Предложение, _ компонент: КомпонентАпгрейдаМоего) -> Bool {
        typealias К = КлючСтандарта
        if !компонент.слова.isEmpty, !компонент.слова.contains(where: { п.название.contains($0) }) { return false }
        let н = п.набор
        let нужно = компонент.набор
        switch компонент.семья {
        case .память:
            guard let а = н[.память, К.поколение], let б = нужно[.память, К.поколение],
                  КаталогСтандартов.основа(поколения: а) == КаталогСтандартов.основа(поколения: б),
                  н[.память, К.форма] == нужно[.память, К.форма],
                  н[.память, К.гб] == нужно[.память, К.гб] else { return false }
            if let вид = н[.память, К.видПамяти], вид == "RDIMM" || вид == "LRDIMM" { return false }
            return н.сколько == нужно.сколько
        case .накопитель:
            let тбНужно = нужно.число(.накопитель, К.тб) ?? 1
            guard let тб = н.число(.накопитель, К.тб), тб >= тбНужно * 0.9, тб <= тбНужно * 1.15 else { return false }
            if !компонент.слова.isEmpty { return true }
            guard let форма = н[.накопитель, К.форма], let формаНужно = нужно[.накопитель, К.форма] else { return false }
            if let длина = КаталогСтандартов.длинаM2(форма), let длинаНужно = КаталогСтандартов.длинаM2(формаНужно) {
                guard длина <= длинаНужно else { return false }
            } else if форма != формаНужно {
                return false
            }
            if let протоколНужно = нужно[.накопитель, К.протокол], н[.накопитель, К.протокол] != протоколНужно {
                return false
            }
            return true
        case .видеокарта:
            return н[.видеокарта, К.чип] != nil && н[.видеокарта, К.чип] == нужно[.видеокарта, К.чип]
        case .блокПитания:
            guard let ватт = н.целое(.блокПитания, К.ватт), let ваттНужно = нужно.целое(.блокПитания, К.ватт),
                  ватт >= ваттНужно, ватт <= ваттНужно + 250 else { return false }
            if let форма = н[.блокПитания, К.форма], let формаНужно = нужно[.блокПитания, К.форма] {
                return форма == формаНужно
            }
            return true
        case .сокет:
            guard н[.сокет, К.сокет] == нужно[.сокет, К.сокет], let имя = н[.сокет, К.процессор],
                  let имяНужно = нужно[.сокет, К.процессор] else { return false }
            return имя.lowercased() == имяНужно.lowercased()
        default:
            return false
        }
    }
}

/// Цена варианта для карточки: по компоненту; вместе — только если у каждого не меньше трёх предложений.
struct ЦенаВариантаМоего: Equatable {
    var части: [ЦеныАпгрейдаМоего.ЦенаКомпонента]
    var неЗагрузилось: Bool

    var вместе: Int? {
        guard части.count > 1, части.allSatisfy({ $0.предложений >= 3 && $0.от != nil }) else { return nil }
        return части.compactMap(\.от).reduce(0, +)
    }
}

// MARK: - Цель

enum ЦельАпгрейдаМоего: String, CaseIterable, Identifiable, Hashable, Sendable {
    case работа = "work"
    case игры = "games"
    case монтаж = "media"
    case место = "space"
    case скорость = "speed"

    var id: String { rawValue }

    var название: String { МойКомпьютерText.т("mpc_goal_" + rawValue) }

    var значок: String {
        switch self {
        case .работа: return "briefcase"
        case .игры: return "gamecontroller"
        case .монтаж: return "film"
        case .место: return "externaldrive"
        case .скорость: return "bolt.circle"
        }
    }

    /// Порядок групп вариантов: первые — главные для цели.
    var порядок: [String] {
        switch self {
        case .работа: return ["ram", "ssd", "cpu", "ext", "sell", "gpu", "psu"]
        case .игры: return ["gpu", "ram", "cpu", "psu", "ssd", "ext", "sell"]
        case .монтаж: return ["ram", "cpu", "ssd", "gpu", "ext", "sell", "psu"]
        case .место: return ["ssd", "ext", "ram", "sell", "cpu", "gpu", "psu"]
        case .скорость: return ["ssd", "ram", "cpu", "ext", "sell", "gpu", "psu"]
        }
    }
}

// MARK: - Вариант

/// Что купить для варианта: стандарт, раздел ленты, подпись и запрос «Найти на Kliko».
struct КомпонентАпгрейдаМоего: Hashable, Sendable {
    let семья: СемьяСтандарта
    let раздел: String
    let набор: НаборСтандартов
    let подпись: String
    let запрос: String
    /// Слова в названии объявления, без которых не подходит (внешний SSD — «внешн», «usb»).
    let слова: [String]
    /// Цену не ищем (целый ноутбук): только «Найти».
    let безЦены: Bool

    init(семья: СемьяСтандарта, раздел: String, набор: НаборСтандартов, подпись: String, запрос: String? = nil,
         слова: [String] = [], безЦены: Bool = false) {
        self.семья = семья
        self.раздел = раздел
        self.набор = набор
        self.подпись = подпись
        self.запрос = запрос ?? РазборСтандартов.запрос(набор, семья)
        self.слова = слова
        self.безЦены = безЦены
    }
}

/// Вариант «можно так»: заголовок, польза, проверки построчно, что купить, что освободится.
struct ВариантАпгрейдаМоего: Identifiable, Hashable, Sendable {
    let id: String
    /// Группа для порядка по цели: ram, ssd, gpu, psu, cpu, ext, sell.
    let группа: String
    let часть: ЧастьКомпьютераМоего?
    let заголовок: String
    let польза: String
    let пункты: [ПунктСверкиСтандарта]
    let компоненты: [КомпонентАпгрейдаМоего]
    /// Что освободится — «Продать старую»; у «продать свой» — сам компьютер.
    let старая: String?
    /// Подсказка «Поставить»: «easy» — самим за 10–15 минут, «pro» — по инструкции или у мастера, nil — не нужно.
    let поставить: String?
    let продатьСвой: Bool

    init(id: String, группа: String, часть: ЧастьКомпьютераМоего?, заголовок: String, польза: String,
         пункты: [ПунктСверкиСтандарта], компоненты: [КомпонентАпгрейдаМоего], старая: String? = nil,
         поставить: String? = nil, продатьСвой: Bool = false) {
        self.id = id
        self.группа = группа
        self.часть = часть
        self.заголовок = заголовок
        self.польза = польза
        self.пункты = пункты
        self.компоненты = компоненты
        self.старая = старая
        self.поставить = поставить
        self.продатьСвой = продатьСвой
    }

    /// Худший пункт; пусто — «подходит» (вариант без проверок).
    var уровень: УровеньСтандарта { пункты.isEmpty ? .подходит : УровниСтандарта.худший(пункты.map(\.уровень)) }

    var нельзя: Bool { уровень == .неПодходит }

    /// «так нельзя: …» — первая причина «не подходит».
    var причина: String? { пункты.first { $0.уровень == .неПодходит }?.текст }
}


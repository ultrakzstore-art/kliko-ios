import Foundation
import UIKit

/**
 «МОЁ» — ХРАНИЛИЩЕ: ОДНА ЗАПИСЬ, ОДИН ФАЙЛ, ФОТО РЯДОМ (владелец 16.10.2026: «по всем моментам разом»).

 Где лежит: Application Support/MyThings — my-things.json (ЗаписьМоего, обычно десятки КБ) и photos/<uuid>.jpg (до
 2048 px, перерисовано, без EXIF и места съёмки) с миниатюрой <uuid>-s.jpg (480 px) для карточек; вырезка вещи
 гардероба — <uuid>.png с прозрачным фоном. Папка и каждый файл — «не в резервную копию» (isExcludedFromBackup):
 обещание «только на этом телефоне» буквальное, в iCloud ничего не уходит. JSON — с защитой «до первой разблокировки»,
 фото — с полной защитой файла. На сервер не уходит ничего.

 Читается один раз и синхронно (файл маленький, как избранное, FavoritesStore), пишется — снимок записи кодируется и
 пишется на последовательной очереди ФайлыМоего (MyThingsFiles.swift; порядок записей сохраняется, экран не ждёт ни
 кодирования, ни диска). Прогресс профилей — там же.

 Пачка 16.10.2026 «мой дом, компьютер, гардероб и для вас»: правки дома, компьютеров, гардероба и вещей — замыканием
 (обновитьДом, обновитьКомпьютеры, обновитьГардероб, обновитьВещи), после каждой правки — пределы и порядок
 (нормализовать), фото разделов — сохранитьФото(место:), купленное на Kliko — добавитьПокупку и убратьПокупку. Фото,
 на которое запись больше не ссылается, удаляется само (уборка в изменить).

 Мост с «Подойдут ли?» без двойной записи: ГаражАвтоподбора (AutoFitCar.swift) остаётся фасадом окна сверки, а машину
 берёт из главной машины гаража (перечитать) и пишет сюда (записатьИзАвтоподбора, удалитьГлавную). Прежняя одна машина
 из UserDefaults «kliko.autofit.garage» переносится сюда при первом чтении — и ключ удаляется после удачной записи.

 «Удалить всё» — один шаг (стереть): кнопка хаба, строка «Данные на телефоне» кабинета и выход из аккаунта
 (ВыходНачисто). Удаление приложения уносит всё само.
 */
@MainActor
final class МоёХранилище: ObservableObject {
    static let shared = МоёХранилище()

    @Published private(set) var запись = ЗаписьМоего()

    private var готово = false
    /// Растёт на каждом «Удалить всё»: фото, дописанное после стирания, в пустую запись не попадает.
    private var поколение = 0

    /// Ключ прежнего гаража «Подойдут ли?» — в AutoFitCar.swift он private, держим свою копию: перенос и «Удалить всё».
    static let ключГаражаАвтоподбора = "kliko.autofit.garage"

    private init() {}

    /// Прежняя запись гаража «Подойдут ли?»: те же синтезированные ключи «машина» и «посадка».
    private struct СтараяЗаписьГаражаМоего: Decodable {
        var машина: МашинаАвтоподбора?
        var посадка: ПосадкаАвтоподбора?
    }

    // MARK: - Чтение и перенос

    /**
     Прочитать файл (один раз); внутри — перенос машины из прежнего гаража «Подойдут ли?». Файл есть, но сейчас не
     читается (запуск в фоне до первой разблокировки, сбой диска) — не готово: правки не пишутся на диск и перенос ждёт,
     иначе пустая запись затёрла бы гараж и мерки. Следующий вызов или разблокировка телефона читают снова.
     */
    func подготовить() {
        guard !готово else { return }
        var прочиталось = false
        switch ФайлыМоего.прочитать() {
        case .недоступно:
            ждатьРазблокировки()
            return
        case .нет:
            break
        case .данные(let данные):
            if let прочитанная = try? JSONDecoder().decode(ЗаписьМоего.self, from: данные) {
                запись = прочитанная
                прочиталось = true
            }
        }
        готово = true
        перенестиИзАвтоподбора(файлЕсть: прочиталось)
        if let подписка = ждём {
            // Прочиталось со второй попытки — «Подойдут ли?» берёт главную машину заново.
            NotificationCenter.default.removeObserver(подписка)
            ждём = nil
            ГаражАвтоподбора.shared.перечитать()
        }
    }

    /// Подписка «данные телефона снова доступны» — пока файл не прочитан.
    private var ждём: NSObjectProtocol?

    private func ждатьРазблокировки() {
        guard ждём == nil else { return }
        ждём = NotificationCenter.default.addObserver(forName: UIApplication.protectedDataDidBecomeAvailableNotification,
                                                      object: nil, queue: .main) { _ in
            Task { @MainActor in МоёХранилище.shared.подготовить() }
        }
    }

    /// Одна машина из UserDefaults → первая машина гаража, она же главная. Ключ удаляется только после удачной записи
    /// файла; файл уже есть — остаток ключа просто удаляется.
    private func перенестиИзАвтоподбора(файлЕсть: Bool) {
        let хранилище = UserDefaults.standard
        let ключ = Self.ключГаражаАвтоподбора
        guard let старые = хранилище.data(forKey: ключ) else { return }
        guard !файлЕсть else {
            хранилище.removeObject(forKey: ключ)
            return
        }
        let старая = try? JSONDecoder().decode(СтараяЗаписьГаражаМоего.self, from: старые)
        let посадка = старая?.посадка.flatMap { $0.пустая ? nil : $0 }
        guard let старая, старая.машина != nil || посадка != nil else {
            хранилище.removeObject(forKey: ключ)
            return
        }
        let машина = МашинаМоего(авто: старая.машина, посадка: посадка)
        запись.машины = [машина]
        запись.главная = машина.id
        guard let данные = try? JSONEncoder().encode(запись) else { return }
        ФайлыМоего.записать(данные) { удачно in
            if удачно { UserDefaults.standard.removeObject(forKey: ключ) }
        }
    }

    // MARK: - Запись

    /// Правка записи: на главной — новая запись, на очереди — JSON и файл. Менялся гараж — «Подойдут ли?» перечитывает
    /// главную машину. Фото, на которое запись больше не ссылается, уходит с телефона.
    private func изменить(гараж: Bool = false, _ правка: (inout ЗаписьМоего) -> Void) {
        подготовить()
        var новая = запись
        правка(&новая)
        if новая.машины.isEmpty {
            новая.главная = nil
        } else if !новая.машины.contains(where: { $0.id == новая.главная }) {
            новая.главная = новая.машины.first?.id
        }
        Self.нормализовать(&новая)
        guard новая != запись else { return }
        let былиФото = запись.файлыФото
        новая.версия = max(новая.версия, ЗаписьМоего.текущаяВерсия)
        запись = новая
        // Файл есть, но не прочитан — не перезаписывать его тем, что видно сейчас.
        if готово { ФайлыМоего.записать(новая) }
        for имя in былиФото.subtracting(новая.файлыФото) {
            КэшФотоМоего.забыть(имя)
            ФайлыМоего.удалить(имя)
        }
        if гараж { ГаражАвтоподбора.shared.перечитать() }
    }

    /// Пределы и порядок разделов v2 после правки: повторы, длины, связи с удалёнными комнатами и вещами.
    private static func нормализовать(_ з: inout ЗаписьМоего) {
        з.дом.нормализовать()
        з.гардероб.нормализовать()
        var номера = Set<UUID>()
        з.компьютеры = Array(з.компьютеры.filter { номера.insert($0.id).inserted }.prefix(ЗаписьМоего.пределКомпьютеров))
        for i in з.компьютеры.indices { з.компьютеры[i].нормализовать() }
        var номераВещей = Set<UUID>()
        з.вещи = Array(з.вещи.filter { номераВещей.insert($0.id).inserted }.prefix(ЗаписьМоего.пределВещей))
        if з.изСделок.count > ЗаписьМоего.пределСделок {
            // Отметки сверх предела уходят по порядку номеров сделок (сами вещи остаются).
            let лишние = з.изСделок.count - ЗаписьМоего.пределСделок
            let порядок = з.изСделок.keys.sorted()
            for ключ in порядок.prefix(лишние) { з.изСделок[ключ] = nil }
        }
    }

    // MARK: - Гараж

    var главнаяМашина: МашинаМоего? { запись.главнаяМашина }

    func машина(_ id: UUID) -> МашинаМоего? { запись.машины.first { $0.id == id } }

    /// Новая пустая машина; nil — в гараже уже 5.
    func добавитьМашину() -> UUID? {
        подготовить()
        guard запись.машины.count < ЗаписьМоего.пределМашин else { return nil }
        let новая = МашинаМоего()
        изменить(гараж: true) { з in
            з.машины.append(новая)
            if з.главная == nil { з.главная = новая.id }
        }
        return новая.id
    }

    func обновитьМашину(_ машина: МашинаМоего) {
        изменить(гараж: true) { з in
            guard let место = з.машины.firstIndex(where: { $0.id == машина.id }) else { return }
            var м = машина
            м.имя = String(м.имя.prefix(МашинаМоего.пределИмени))
            м.посадка = м.посадка.flatMap { $0.пустая ? nil : $0 }
            з.машины[место] = м
        }
    }

    /// Машина и её фото — с телефона; главной становится первая оставшаяся.
    func удалитьМашину(_ id: UUID) {
        guard let была = машина(id) else { return }
        изменить(гараж: true) { з in з.машины.removeAll { $0.id == id } }
        if let фото = была.фото { удалитьФайлы(фото) }
    }

    /// Редактор закрыли, ничего не указав, — пустая машина не остаётся в гараже.
    func убратьПустую(_ id: UUID) {
        guard let м = машина(id), м.авто == nil, м.посадка == nil, м.фото == nil,
              м.имя.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty else { return }
        удалитьМашину(id)
    }

    func сделатьГлавной(_ id: UUID) {
        изменить(гараж: true) { з in
            if з.машины.contains(where: { $0.id == id }) { з.главная = id }
        }
    }

    func переименовать(_ id: UUID, _ имя: String) {
        guard var м = машина(id) else { return }
        м.имя = String(имя.prefix(МашинаМоего.пределИмени))
        обновитьМашину(м)
    }

    /// Свои параметры колёс (или nil — забыть).
    func сохранитьПосадку(_ id: UUID, _ посадка: ПосадкаАвтоподбора?) {
        guard var м = машина(id) else { return }
        м.посадка = посадка
        обновитьМашину(м)
    }

    /**
     Выбраны марка, модель и год: запомнить и спросить справочник посадки (тот же, что у «Подойдут ли?»: только марка,
     модель, год, без кук). Другая машина — прежние параметры колёс забываются. Свои параметры той же машины справочник
     не затирает. Итог «ищем / нет / сеть» живёт в модели экрана, на диск не пишется; nil — машину за это время удалили
     или выбрали другую.
     */
    func выбратьАвто(_ id: UUID, _ авто: МашинаАвтоподбора) async -> СправочникАвтоподбора.ИтогСправочникаАвтоподбора? {
        guard var м = машина(id) else { return nil }
        if м.авто != авто {
            м.авто = авто
            м.посадка = nil
            обновитьМашину(м)
        }
        guard Config.справочникАвтоподбора else { return .нет }
        let итог = await СправочникАвтоподбора.посадка(авто)
        guard var свежая = машина(id), свежая.авто == авто else { return nil }
        if case .есть(let найденная) = итог, свежая.посадка?.свои != true {
            свежая.посадка = найденная
            обновитьМашину(свежая)
        }
        return итог
    }

    /// Фото машины: файлы — на очередь записи, потом запись; прежнее фото удаляется. false — не записалось.
    func сохранитьФотоМашины(_ id: UUID, готовое: ГотовоеФотоМоего, колёса: [КругМоего], люди: Bool?,
                             шаблон: String) async -> Bool {
        let было = поколение
        guard машина(id) != nil, let имя = await записатьФото(готовое) else { return false }
        guard поколение == было, var м = машина(id) else {
            удалитьФайлы(имя)
            return false
        }
        let прежнее = м.фото
        м.фото = ФотоМоего(файл: имя, ширина: готовое.ширина, высота: готовое.высота, шаблон: шаблон, колёса: колёса,
                          люди: люди)
        обновитьМашину(м)
        if let прежнее { удалитьФайлы(прежнее) }
        return true
    }

    /// Круги колёс поправили пальцем.
    func задатьКолёса(_ id: UUID, _ колёса: [КругМоего]) {
        guard var м = машина(id), var фото = м.фото else { return }
        фото.колёса = колёса
        м.фото = фото
        обновитьМашину(м)
    }

    func удалитьФотоМашины(_ id: UUID) {
        guard var м = машина(id), let фото = м.фото else { return }
        м.фото = nil
        обновитьМашину(м)
        удалитьФайлы(фото)
    }

    // MARK: - Мост с «Подойдут ли?»

    /**
     ГаражАвтоподбора сохранил машину и посадку (окно «Подойдут ли?»):
       · оба nil — удалить главную;
       · главной нет — новая машина, она же главная;
       · машина та же (или не выбрана) — новая посадка главной;
       · другая машина: есть в гараже с тем же ключом — она становится главной (посадка новая, если пришла); главная
         «черновая» (нет фото, своего названия и своих параметров колёс) — замена на месте; иначе — новая машина, она же
         главная; при пяти машинах — замена на месте другой черновой, она становится главной; черновой нет — гараж
         не трогаем и возвращаем false: окно сверки держит машину только у себя и говорит, что она не сохранена.
     Фото мост не удаляет никогда: сохранённая машина не теряется из-за проверки чужого объявления.
     */
    @discardableResult
    func записатьИзАвтоподбора(машина авто: МашинаАвтоподбора?, посадка: ПосадкаАвтоподбора?) -> Bool {
        подготовить()
        let посадка = посадка.flatMap { $0.пустая ? nil : $0 }
        guard авто != nil || посадка != nil else {
            удалитьГлавную()
            return true
        }
        guard let главная = запись.главнаяМашина else {
            let новая = МашинаМоего(авто: авто, посадка: посадка)
            изменить(гараж: true) { з in
                з.машины.append(новая)
                з.главная = новая.id
            }
            return true
        }
        guard let авто, главная.авто != авто else {
            изменить(гараж: true) { з in
                guard let место = з.машины.firstIndex(where: { $0.id == главная.id }) else { return }
                з.машины[место].посадка = посадка
            }
            return true
        }
        if let та = запись.машины.first(where: { $0.авто?.ключ == авто.ключ }) {
            изменить(гараж: true) { з in
                з.главная = та.id
                guard let место = з.машины.firstIndex(where: { $0.id == та.id }) else { return }
                /* Та же машина по ключу (регистр мог отличаться) — запись как выбрана сейчас: окно сверки сравнивает её. */
                з.машины[место].авто = авто
                if let посадка { з.машины[место].посадка = посадка }
            }
            return true
        }
        if !Self.черновая(главная) && запись.машины.count < ЗаписьМоего.пределМашин {
            let новая = МашинаМоего(авто: авто, посадка: посадка)
            изменить(гараж: true) { з in
                з.машины.append(новая)
                з.главная = новая.id
            }
            return true
        }
        // Главная черновая — меняем её; иначе (пять машин) — последнюю черновую из остальных.
        let наЗамену: МашинаМоего? = Self.черновая(главная) ? главная
            : запись.машины.last(where: { $0.id != главная.id && Self.черновая($0) })
        guard let наЗамену else { return false }
        изменить(гараж: true) { з in
            guard let место = з.машины.firstIndex(where: { $0.id == наЗамену.id }) else { return }
            з.машины[место].авто = авто
            з.машины[место].посадка = посадка
            з.главная = наЗамену.id
        }
        return true
    }

    /// Машину можно заменить из «Подойдут ли?» без потерь: нет фото, своего названия и своих параметров колёс.
    private static func черновая(_ м: МашинаМоего) -> Bool {
        м.фото == nil && м.имя.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty && м.посадка?.свои != true
    }

    /// «Забыть мою машину» в «Подойдут ли?»: главная машина с фото уходит, главной становится первая оставшаяся.
    func удалитьГлавную() {
        подготовить()
        guard let главная = запись.главнаяМашина else { return }
        удалитьМашину(главная.id)
    }

    // MARK: - Устройства

    func задатьТелефон(_ телефон: ТелефонМоего?) {
        изменить { з in з.телефон = телефон }
    }

    /// Новое или изменённое устройство; «нет такого» у его группы снимается.
    func обновитьУстройство(_ устройство: УстройствоМоего) {
        изменить { з in
            if let место = з.устройства.firstIndex(where: { $0.id == устройство.id }) {
                з.устройства[место] = устройство
            } else if з.устройства.count < ЗаписьМоего.пределУстройств {
                з.устройства.append(устройство)
            } else {
                return
            }
            з.нет.remove(устройство.вид.ключНет)
        }
    }

    func удалитьУстройство(_ id: UUID) {
        изменить { з in з.устройства.removeAll { $0.id == id } }
    }

    /// «Ноутбука нет», «Экрана нет» — засчитывается в прогресс.
    func отметитьНет(_ вид: ВидУстройстваМоего, _ нет: Bool) {
        изменить { з in
            if нет {
                з.нет.insert(вид.ключНет)
            } else {
                з.нет.remove(вид.ключНет)
            }
        }
    }

    // MARK: - Тело

    func задатьРост(_ рост: Int?) {
        изменить { з in з.тело.рост = рост.flatMap { ТелоМоего.пределыРоста.contains($0) ? $0 : nil } }
    }

    func задатьМерку(_ мерка: МеркаМоего, _ значение: Double?) {
        изменить { з in
            if let значение, мерка.пределы.contains(значение) {
                з.тело.мерки[мерка.rawValue] = значение
            } else {
                з.тело.мерки[мерка.rawValue] = nil
            }
        }
    }

    /// Размер вида (один на вид); порядок — как у видов.
    func задатьРазмер(_ размер: РазмерМоего) {
        изменить { з in
            з.тело.размеры.removeAll { $0.вид == размер.вид }
            з.тело.размеры.append(размер)
            let порядок = ВидРазмераМоего.allCases
            з.тело.размеры.sort { (порядок.firstIndex(of: $0.вид) ?? 0) < (порядок.firstIndex(of: $1.вид) ?? 0) }
        }
    }

    func удалитьРазмер(_ вид: ВидРазмераМоего) {
        изменить { з in з.тело.размеры.removeAll { $0.вид == вид } }
    }

    /// Фото в полный рост с точками позы; прежнее удаляется. false — не записалось.
    func сохранитьФотоТела(_ готовое: ГотовоеФотоМоего, поза: [String: ТочкаМоего], полныйРост: Bool?,
                           шаблон: String) async -> Bool {
        let было = поколение
        guard let имя = await записатьФото(готовое) else { return false }
        // Пока писался файл, «Моё» стёрли (выход из аккаунта, «Удалить всё») — снимок не возвращается.
        guard поколение == было else {
            удалитьФайлы(имя)
            return false
        }
        let прежнее = запись.тело.фото
        изменить { з in
            з.тело.фото = ФотоМоего(файл: имя, ширина: готовое.ширина, высота: готовое.высота, шаблон: шаблон,
                                   поза: поза, полныйРост: полныйРост)
        }
        if let прежнее { удалитьФайлы(прежнее) }
        return true
    }

    func удалитьФотоТела() {
        guard let фото = запись.тело.фото else { return }
        изменить { з in з.тело.фото = nil }
        удалитьФайлы(фото)
    }

    // MARK: - Дом

    /// Правка «Моего дома» одним замыканием; пределы, повторы и связи с удалёнными комнатами — сами после правки.
    func обновитьДом(_ правка: (inout ДомМоего) -> Void) {
        изменить { з in правка(&з.дом) }
    }

    // MARK: - Компьютер

    func компьютер(_ id: UUID) -> КомпьютерМоего? { запись.компьютер(id) }

    /// Новый компьютер в конец списка; false — уже четыре.
    @discardableResult
    func добавитьКомпьютер(_ компьютер: КомпьютерМоего) -> Bool {
        подготовить()
        guard запись.компьютеры.count < ЗаписьМоего.пределКомпьютеров,
              !запись.компьютеры.contains(where: { $0.id == компьютер.id }) else { return false }
        изменить { з in з.компьютеры.append(компьютер) }
        return true
    }

    /// Изменённый компьютер — на своё место; нового в списке нет — добавляется (если есть место).
    func обновитьКомпьютер(_ компьютер: КомпьютерМоего) {
        изменить { з in
            if let место = з.компьютеры.firstIndex(where: { $0.id == компьютер.id }) {
                з.компьютеры[место] = компьютер
            } else if з.компьютеры.count < ЗаписьМоего.пределКомпьютеров {
                з.компьютеры.append(компьютер)
            }
        }
    }

    /// Правка всего списка (порядок, главный — первый).
    func обновитьКомпьютеры(_ правка: (inout [КомпьютерМоего]) -> Void) {
        изменить { з in правка(&з.компьютеры) }
    }

    /// Компьютер — главным (первым): с ним сверяются детали и в него кладутся купленные.
    func сделатьГлавным(компьютер id: UUID) {
        изменить { з in
            guard let место = з.компьютеры.firstIndex(where: { $0.id == id }), место > 0 else { return }
            з.компьютеры.insert(з.компьютеры.remove(at: место), at: 0)
        }
    }

    /// Компьютер уходит; купленные для него детали остаются в «Моём» без места.
    func удалитьКомпьютер(_ id: UUID) {
        изменить { з in
            з.компьютеры.removeAll { $0.id == id }
            for i in з.вещи.indices where з.вещи[i].место.раздел == .компьютер && з.вещи[i].место.id == id {
                з.вещи[i].место.id = nil
            }
            з.изСделок = з.изСделок.filter { $0.value != id }
        }
    }

    // MARK: - Гардероб

    /// Правка «Моего гардероба» одним замыканием; образы без удалённых вещей — сами.
    func обновитьГардероб(_ правка: (inout ГардеробМоего) -> Void) {
        изменить { з in правка(&з.гардероб) }
    }

    // MARK: - Вещи

    /// Правка списка вещей «Моего» (купленное и прочее с местом).
    func обновитьВещи(_ правка: (inout [ВещьМоего]) -> Void) {
        изменить { з in правка(&з.вещи) }
    }

    func удалитьВещь(_ id: UUID) {
        изменить { з in
            з.вещи.removeAll { $0.id == id }
            з.изСделок = з.изСделок.filter { $0.value != id }
        }
    }

    // MARK: - Куплено на Kliko

    /// Сделка уже добавлена в «Моё».
    func вМоём(сделка: String) -> Bool { запись.изСделок[сделка] != nil }

    /**
     Покупку — в раздел «Моего» касанием (согласие — само нажатие): одежда — вещью гардероба, ноутбук и ПК целиком —
     компьютером, остальное — ВещьМоего с местом и стандартами из названия. Деталь компьютера — к главному компьютеру и
     событием в его историю. false — уже добавлена или нет места (четыре компьютера).
     */
    @discardableResult
    func добавитьПокупку(_ покупка: ПокупкаИзСделкиМоего, в раздел: РазделВещиМоего) -> Bool {
        подготовить()
        guard запись.изСделок[покупка.id] == nil else { return false }
        var добавлено = false
        изменить { з in добавлено = ПокупкиМоего.положить(покупка, в: раздел, запись: &з) }
        return добавлено
    }

    /// «Убрать из «Моего»»: то, что добавлено из этой сделки, уходит (если с тех пор не переложено в другую сделку).
    func убратьПокупку(сделка: String) {
        изменить { з in ПокупкиМоего.убрать(сделка: сделка, запись: &з) }
    }

    // MARK: - Фото разделов

    /**
     Фото комнаты, вещи гардероба или образа: файлы — на очередь записи, потом запись; прежнее уходит само (уборка в
     изменить). расширение — «jpg» или «png» (вырезка с прозрачным фоном); миниатюра — с тем же расширением. false — не
     записалось, места больше нет или «Моё» за это время стёрли.
     */
    func сохранитьФото(_ готовое: ГотовоеФотоМоего, место: МестоФотоМоего,
                       шаблон: String = ФотоМоего.шаблонГалереи, расширение: String = "jpg") async -> Bool {
        let было = поколение
        guard естьМесто(место), let имя = await записатьФото(готовое, расширение: расширение) else { return false }
        guard поколение == было, естьМесто(место) else {
            удалитьФайлы(имя)
            return false
        }
        let фото = ФотоМоего(файл: имя, ширина: готовое.ширина, высота: готовое.высота, шаблон: шаблон)
        изменить { з in Self.поставить(фото, в: место, запись: &з) }
        return true
    }

    /// Убрать фото места (файлы уходят сами).
    func удалитьФото(_ место: МестоФотоМоего) {
        изменить { з in Self.поставить(nil, в: место, запись: &з) }
    }

    private func естьМесто(_ место: МестоФотоМоего) -> Bool {
        switch место {
        case .комната(let id): return запись.дом.комнаты.contains { $0.id == id }
        case .вещьГардероба(let id): return запись.гардероб.вещи.contains { $0.id == id }
        case .образ(let id): return запись.гардероб.образы.contains { $0.id == id }
        }
    }

    private static func поставить(_ фото: ФотоМоего?, в место: МестоФотоМоего, запись з: inout ЗаписьМоего) {
        switch место {
        case .комната(let id):
            guard let i = з.дом.комнаты.firstIndex(where: { $0.id == id }) else { return }
            з.дом.комнаты[i].фото = фото
        case .вещьГардероба(let id):
            guard let i = з.гардероб.вещи.firstIndex(where: { $0.id == id }) else { return }
            з.гардероб.вещи[i].фото = фото
        case .образ(let id):
            guard let i = з.гардероб.образы.firstIndex(where: { $0.id == id }) else { return }
            з.гардероб.образы[i].фото = фото
        }
    }

    // MARK: - Файлы фото

    /// Снимок и миниатюра — на очередь записи; имя — «<uuid>.jpg» (или .png). nil — диск не принял.
    private func записатьФото(_ готовое: ГотовоеФотоМоего, расширение: String = "jpg") async -> String? {
        let своё = ["jpg", "png", "heic"].contains(расширение) ? расширение : "jpg"
        let имя = UUID().uuidString.lowercased() + "." + своё
        guard await ФайлыМоего.записатьФото(готовое.jpeg, имя: имя) else { return nil }
        guard await ФайлыМоего.записатьФото(готовое.мини, имя: ФотоМоего.мини(имя)) else {
            ФайлыМоего.удалить(имя)
            return nil
        }
        return имя
    }

    private func удалитьФайлы(_ фото: ФотоМоего) {
        удалитьФайлы(фото.файл)
    }

    private func удалитьФайлы(_ имя: String) {
        let мини = ФотоМоего.мини(имя)
        КэшФотоМоего.забыть(имя)
        КэшФотоМоего.забыть(мини)
        ФайлыМоего.удалить(имя)
        ФайлыМоего.удалить(мини)
    }

    // MARK: - Всё сразу

    var пусто: Bool { запись.пусто }

    /**
     «Удалить всё «Моё»» одним шагом: в памяти — сразу пустая запись (с домом, компьютерами, гардеробом и купленным); на
     очереди — папка MyThings целиком; остаток прежнего гаража в UserDefaults и кэш справочника посадки; фото из
     памяти; список покупок из сделок в памяти; «Подойдут ли?» — без машины.
     */
    func стереть() {
        ПокупкиМоегоМодель.shared.забыть()
        готово = true
        поколение += 1
        if let подписка = ждём {
            NotificationCenter.default.removeObserver(подписка)
            ждём = nil
        }
        запись = ЗаписьМоего()
        ФайлыМоего.стереть()
        UserDefaults.standard.removeObject(forKey: Self.ключГаражаАвтоподбора)
        // «Скрыть» полки «Для вас» (число разделов) — тоже следствие «Моего»: стирается вместе с ним.
        UserDefaults.standard.removeObject(forKey: ПодборкаДляВас.ключСкрытия)
        СправочникАвтоподбора.забытьКэш()
        КэшФотоМоего.очистить()
        ГаражАвтоподбора.shared.перечитать()
    }

    /// Сколько «Моё» занимает на диске — строка кабинета.
    func байт() async -> Int {
        await ФайлыМоего.байт()
    }
}


import SwiftUI

/**
 «МОЙ ДОМ» — «ПРОЙДЁТ ЛИ В ДВЕРЬ, ЛИФТ И ПО ЛЕСТНИЦЕ?» (владелец 16.10.2026: «мой дом — что можно по дому?»;
 docs/STANDARDS.md §3.8 «Проёмы», §8.2; docs/SERVER_CIRCLE.md §11.2 knockdown, pass_cm).

 Чистая функция без сети и главной нити: вещь (Ш×В×Г, см) против пути в дом из «Моего дома» — лифт и лестница
 (лучший путь наверх), входная дверь, межкомнатные двери. Её зовёт карточка «Пройдёт ли?» экрана дома, а позже — окно
 объявления (ПройдётЛиМоего.проверить(товар, дом:) → ИтогПроходаМоего.итогСверки — та же шкала, что у стандартов).

 Геометрия, честно:
   · дверь — сечение из двух меньших габаритов в проход Ш×В с запасом 2 см (любой стороной); зазор меньше 4 см —
     «впритык, проверьте»; проходит только повёрнутым в плоскости проёма — «наклоном, проверьте»;
   · лифт — сначала дверь кабины так же, потом кабина Ш×Г×≈205: лёжа вдоль длинной стороны пола — подходит; стоя
     (занесли стоя — подходит, высота кабины ≈ — проверьте; занесли наклоном и подняли — проверьте); по диагонали пола
     или наклоном до потолка — проверьте; вес вещи с двумя грузчиками больше грузоподъёмности шаблона — проверьте;
   · лестница — сечение в марш × 200 над ступенями; поворот 90° — длина вещи против «дивана за угол»:
     L(θ) = (p·cos θ + q·sin θ − w) / (sin θ · cos θ), минимум по θ (p — марш, q — площадка, w — толщина вещи);
     не влезает плашмя, но влезает, если поднять на площадке до потолка, — проверьте; разворот 180° — не лучше
     «проверьте».
 Проём по шаблону («примерно») — не лучше «проверьте». Межкомнатная дверь в итог идёт не хуже «проверьте»: куда
 понесут вещь, мы не знаем. Продавец написал «разбирается» — «не пройдёт» становится «проверьте в разобранном виде»;
 указал наименьший проём (pass_cm) — двери сверяются по нему.
 */

/// Вещь для «Пройдёт ли?»: габариты, см; по желанию — вес, кг, «разбирается» и наименьший проём (pass_cm).
struct ВещьПроходаМоего: Equatable, Sendable {
    var ширина: Double
    var высота: Double
    var глубина: Double
    var вес: Double?
    var разбирается: Bool
    var проходОт: Double?

    init(ширина: Double, высота: Double, глубина: Double, вес: Double? = nil, разбирается: Bool = false,
         проходОт: Double? = nil) {
        self.ширина = ширина
        self.высота = высота
        self.глубина = глубина
        self.вес = вес
        self.разбирается = разбирается
        self.проходОт = проходОт
    }

    /// Габариты по возрастанию; не все положительные — nil.
    var стороны: [Double]? {
        let все = [ширина, высота, глубина]
        guard все.allSatisfy({ $0.isFinite && $0 > 0 && $0 < 1000 }) else { return nil }
        return все.sorted()
    }

    /// «85×90×220».
    var подпись: String {
        [ширина, высота, глубина].map { ЧислоМоего.ч($0) }.joined(separator: "×")
    }
}

/// Как вещь проходит шаг пути. rawValue — хвост ключа текста (mh_way_*).
enum СпособПроходаМоего: String, Sendable {
    case прямо = "straight"
    case впритык = "tight"
    case наклоном = "tilt"
    case стоя = "upright"
    case лёжа = "flat"
    case диагональ = "diag"
    case подняв = "raise"
    case разворот = "uturn"
    case разобрав = "knockdown"
    case нет = "no"

    var текст: String { МойДомText.т("mh_way_" + rawValue) }
}

/// Поворот лестницы — хранится ключом в ПроёмМоего.шаблон у вида «лестница».
enum ПоворотЛестницыМоего: String, CaseIterable, Sendable {
    case прямая = "straight"
    case поворот = "turn90"
    case разворот = "turn180"

    var название: String { МойДомText.т("mh_stairs_" + rawValue) }

    var значок: String {
        switch self {
        case .прямая: return "arrow.up"
        case .поворот: return "arrow.turn.up.right"
        case .разворот: return "arrow.uturn.up"
        }
    }

    static func из(_ проём: ПроёмМоего) -> ПоворотЛестницыМоего {
        ПоворотЛестницыМоего(rawValue: проём.шаблон ?? "") ?? .прямая
    }
}

/// Шаг пути: проём, уровень, как проходит и числа («вещь 85×90 см · проход 74 см»).
struct ШагПроходаМоего: Identifiable, Equatable, Sendable {
    let id: UUID
    let вид: ВидПроёмаМоего
    let название: String
    let уровень: УровеньСтандарта
    let способ: СпособПроходаМоего
    let числа: String
    let примерно: Bool
    /// Запасной путь (лифт или лестница, что хуже) или межкомнатная дверь: на итог влияет мягче.
    let запасной: Bool

    /// «Лифт: только стоя · дверь 70 см, кабина 100×105 см».
    var строка: String { название + ": " + способ.текст + " · " + числа }
}

/// Итог «Пройдёт ли?»: худший из обязательных шагов, заголовок, короткое «почему», все шаги и совет.
struct ИтогПроходаМоего: Equatable, Sendable {
    let уровень: УровеньСтандарта
    let заголовок: String
    let почему: String
    let шаги: [ШагПроходаМоего]
    let совет: String?

    /// Тот же итог на общей шкале стандартов — для окна объявления и «Для вас».
    var итогСверки: ИтогСверкиСтандарта {
        ИтогСверкиСтандарта(семья: .проём, уровень: уровень, заголовок: заголовок, почему: почему,
                            пункты: шаги.map { ПунктСверкиСтандарта($0.id.uuidString, $0.уровень, $0.строка) },
                            деталь: nil, куда: nil)
    }
}

enum ПройдётЛиМоего {
    /// Запас на руки и упаковку, см (КаталогСтандартов.запасПроёма).
    static let запас = Double(КаталогСтандартов.запасПроёма)
    /// Зазор меньше — «впритык, проверьте».
    static let впритык: Double = 4
    /// Высота кабины лифта, если не знаем, — примерно.
    static let высотаКабины: Double = 205
    /// Над ступенями марша — примерно.
    static let надМаршем: Double = 200
    /// Двое грузчиков, кг — для грузоподъёмности лифта.
    static let грузчики: Double = 160

    // MARK: Вход

    /// Объявление (dim_w, dim_h, dim_d) против «Моего дома»; габаритов нет или путь не указан — nil.
    static func проверить(_ товар: Listing, дом: ДомМоего) -> ИтогПроходаМоего? {
        проверить(габариты: товар.габаритыПолей, дом: дом)
    }

    /// Габариты объявления («dim_w», «dim_h», «dim_d», см) против «Моего дома».
    static func проверить(габариты: [String: Double], дом: ДомМоего, разбирается: Bool = false,
                          проходОт: Double? = nil) -> ИтогПроходаМоего? {
        guard let ш = габариты["dim_w"], let в = габариты["dim_h"], let г = габариты["dim_d"] else { return nil }
        let вещь = ВещьПроходаМоего(ширина: ш, высота: в, глубина: г, вес: габариты["weight_kg"],
                                    разбирается: разбирается, проходОт: проходОт)
        return проверить(вещь, дом: дом)
    }

    /**
     Вещь против пути в дом. Порядок шагов — как несут: лифт и лестница (если этаж не первый), входная дверь,
     межкомнатные двери. Пути нет совсем — nil (зовёт заполнить вызывающий).
     */
    static func проверить(_ вещь: ВещьПроходаМоего, дом: ДомМоего) -> ИтогПроходаМоего? {
        guard let с = вещь.стороны else { return nil }
        // Над площадкой лестницы — не выше 2,5 м (сверху следующий марш).
        let потолок = Double(min(дом.потолок ?? 250, 250))
        // Первый этаж и свой дом (0 или 1) — путь наверх не нужен; этаж не указан — проверяем, что указано.
        let наверхНужно = дом.этаж.map { $0 >= 2 } ?? true
        var наверх: [ШагПроходаМоего] = []
        if наверхНужно {
            if !дом.лифтаНет {
                for п in дом.проёмы where п.вид == .лифт && п.заполнен {
                    наверх.append(шагЛифта(с, п, вещь))
                }
            }
            for п in дом.проёмы where п.вид == .лестница && п.заполнен {
                наверх.append(шагЛестницы(с, п, вещь, потолок: потолок))
            }
        }
        // Лучший путь наверх — обязательный, остальные — запасные.
        let лучший = наверх.min { $0.уровень < $1.уровень }
        наверх = наверх.map { ш in
            ШагПроходаМоего(id: ш.id, вид: ш.вид, название: ш.название, уровень: ш.уровень, способ: ш.способ,
                            числа: ш.числа, примерно: ш.примерно, запасной: ш.id != лучший?.id)
        }
        let входные = дом.проёмы.filter { $0.вид == .входная && $0.заполнен }.map { шагДвери(с, $0, вещь, запасной: false) }
        let двери = дом.проёмы.filter { $0.вид == .дверь && $0.заполнен }.map { шагДвери(с, $0, вещь, запасной: true) }
        let шаги = наверх + входные + двери
        guard !шаги.isEmpty else { return nil }
        let обязательные = шаги.filter { !$0.запасной }
        var уровень = обязательные.map(\.уровень).max() ?? .подходит
        if let худшаяДверь = двери.map(\.уровень).max() {
            уровень = max(уровень, min(худшаяДверь, .проверить))
        }
        var совет: String? = nil
        if уровень == .неПодходит && вещь.разбирается {
            уровень = .проверить
            совет = МойДомText.т("mh_pass_tip_knockdown")
        } else if наверх.isEmpty && (дом.этаж.map { $0 >= 2 } ?? дом.лифтаНет) {
            // Этаж высокий (или не указан, а лифта нет), а ни лифта, ни лестницы не указано — путь наверх не проверен.
            совет = МойДомText.т("mh_pass_tip_lift")
        } else if шаги.contains(where: { $0.примерно }) {
            совет = МойДомText.т("mh_pass_tip_measure")
        }
        let заголовок: String
        switch уровень {
        case .подходит, .доработка: заголовок = МойДомText.т("mh_pass_ok")
        case .неПодходит: заголовок = МойДомText.т("mh_pass_bad")
        default: заголовок = МойДомText.т("mh_pass_check")
        }
        let худшийОбязательный = обязательные.max(by: { $0.уровень < $1.уровень })
        let главный = худшийОбязательный ?? шаги.max(by: { $0.уровень < $1.уровень })
        return ИтогПроходаМоего(уровень: уровень, заголовок: заголовок, почему: главный?.строка ?? "", шаги: шаги,
                                совет: совет)
    }

    // MARK: Геометрия

    /**
     Прямоугольник а×б в окне ш×в: 0 — прямо (любой стороной), больше нуля — угол поворота в плоскости окна (наклоном),
     nil — никак. Поворот — через градус: бок повёрнутой вещи а·cos θ + б·sin θ, высота а·sin θ + б·cos θ.
     */
    static func вОкно(_ а: Double, _ б: Double, _ ш: Double, _ в: Double) -> Double? {
        guard ш > 0, в > 0 else { return nil }
        if (а <= ш && б <= в) || (б <= ш && а <= в) { return 0 }
        var угол = 1.0
        while угол < 90 {
            let р = угол * Double.pi / 180
            let косинус = cos(р), синус = sin(р)
            if а * косинус + б * синус <= ш && а * синус + б * косинус <= в { return угол }
            угол += 1
        }
        return nil
    }

    /**
     Самая длинная вещь толщиной w, которую проносят за угол 90° из коридора шириной p в коридор шириной q:
     минимум L(θ) = (p·cos θ + q·sin θ − w) / (sin θ · cos θ) по θ через полградуса. w не меньше коридора — 0.
     */
    static func длинаЗаУгол(_ p: Double, _ q: Double, толщина w: Double) -> Double {
        guard w < min(p, q) else { return 0 }
        var наименьшая = Double.greatestFiniteMagnitude
        var угол = 0.5
        while угол < 90 {
            let р = угол * Double.pi / 180
            let синус = sin(р), косинус = cos(р)
            let длина = (p * косинус + q * синус - w) / (синус * косинус)
            if длина < наименьшая { наименьшая = длина }
            угол += 0.5
        }
        return max(0, наименьшая)
    }

    /// Можно ли поднять вещь (длина, толщина по высоте) на площадке так, чтобы проекция на пол была не длиннее предела,
    /// а верх — не выше высоты.
    static func подняв(длина: Double, толщина: Double, предел: Double, высота: Double) -> Bool {
        var угол = 5.0
        while угол <= 80 {
            let р = угол * Double.pi / 180
            let пол = длина * cos(р) + толщина * sin(р)
            let верх = длина * sin(р) + толщина * cos(р)
            if пол <= предел && верх <= высота { return true }
            угол += 1
        }
        return false
    }

    /// Сечение а×б в проход ш×в: прямо, впритык, наклоном или нет.
    private static func сечение(_ а: Double, _ б: Double, ширина ш: Double,
                                высота в: Double) -> (уровень: УровеньСтандарта, способ: СпособПроходаМоего) {
        let шз = ш - запас
        let вз = в - запас
        guard let угол = вОкно(а, б, шз, вз) else { return (.неПодходит, .нет) }
        if угол > 0 { return (.проверить, .наклоном) }
        let зазор: Double
        if а <= шз && б <= вз {
            зазор = min(ш - а, в - б)
        } else {
            зазор = min(ш - б, в - а)
        }
        if зазор < впритык { return (.проверить, .впритык) }
        return (.подходит, .прямо)
    }

    /// Шаблон («примерно») — не лучше «проверьте»; «не пройдёт» у разборной вещи — «проверьте».
    private static func поправить(_ уровень: УровеньСтандарта, _ способ: СпособПроходаМоего, _ п: ПроёмМоего,
                                  _ вещь: ВещьПроходаМоего) -> (УровеньСтандарта, СпособПроходаМоего) {
        if уровень == .неПодходит {
            if вещь.разбирается { return (.проверить, .разобрав) }
            return (уровень, способ)
        }
        if п.примерно { return (max(уровень, .проверить), способ) }
        return (уровень, способ)
    }

    private static func см(_ x: Double) -> String { ЧислоМоего.ч(x) + " " + МойДомText.т("mh_cm") }

    private static func название(_ п: ПроёмМоего) -> String {
        let своё = п.имя.trimmingCharacters(in: .whitespacesAndNewlines)
        return своё.isEmpty ? п.вид.название : своё
    }

    // MARK: Шаги

    private static func шагДвери(_ с: [Double], _ п: ПроёмМоего, _ вещь: ВещьПроходаМоего,
                                 запасной: Bool) -> ШагПроходаМоего {
        let ш = Double(п.ширина ?? 0)
        let в = Double(п.высота ?? 200)
        var итог: (уровень: УровеньСтандарта, способ: СпособПроходаМоего) = (.неПодходит, .нет)
        let числа: String
        if let от = вещь.проходОт {
            if от + запас <= ш { итог = (.подходит, .прямо) }
            числа = String(format: МойДомText.т("mh_pass_n_from"), см(от), см(ш))
        } else {
            итог = сечение(с[0], с[1], ширина: ш, высота: в)
            числа = String(format: МойДомText.т("mh_pass_n_door"), ЧислоМоего.ч(с[0]) + "×" + см(с[1]), см(ш))
        }
        let поправленный = поправить(итог.уровень, итог.способ, п, вещь)
        return ШагПроходаМоего(id: п.id, вид: п.вид, название: название(п), уровень: поправленный.0,
                               способ: поправленный.1, числа: числа, примерно: п.примерно, запасной: запасной)
    }

    private static func шагЛифта(_ с: [Double], _ п: ПроёмМоего, _ вещь: ВещьПроходаМоего) -> ШагПроходаМоего {
        let дверь = Double(п.ширина ?? 0)
        let высотаДвери = Double(п.высота ?? 200)
        let а = с[0], б = с[1], в = с[2]
        var числа = String(format: МойДомText.т("mh_pass_n_lift_door"), см(дверь))
        var вход: (уровень: УровеньСтандарта, способ: СпособПроходаМоего) = (.неПодходит, .нет)
        if let от = вещь.проходОт {
            if от + запас <= дверь { вход = (.подходит, .прямо) }
        } else {
            вход = сечение(а, б, ширина: дверь, высота: высотаДвери)
        }
        var итог = вход
        if вход.уровень != .неПодходит, let кш = п.кабинаШирина.map({ Double($0) }),
           let кг = п.кабинаГлубина.map({ Double($0) }) {
            числа += " · " + String(format: МойДомText.т("mh_pass_n_cabin"), ЧислоМоего.ч(кш) + "×" + см(кг))
            let кабина = вКабину(а, б, в, кш: кш, кг: кг, дверь: дверь, высотаДвери: высотаДвери)
            // Хуже — кабина; так же — способ кабины, если в дверь вошла прямо (он подробнее: «стоя», «лёжа»).
            if кабина.уровень > вход.уровень || (кабина.уровень == вход.уровень && вход.способ == .прямо) {
                итог = кабина
            }
        } else if вход.уровень != .неПодходит && в > высотаКабины - 10 {
            // Кабина не указана, а вещь длинная: войдёт ли — проверьте.
            итог = (max(вход.уровень, .проверить), вход.способ)
            числа += " · " + МойДомText.т("mh_pass_n_cabin_unknown")
        }
        // Грузоподъёмность шаблона: вещь и двое грузчиков.
        if итог.уровень != .неПодходит, let вес = вещь.вес, let лифт = КаталогСтандартов.лифт(п.шаблон),
           вес + грузчики > Double(лифт.кг) {
            итог = (max(итог.уровень, .проверить), итог.способ)
            числа += " · " + String(format: МойДомText.т("mh_pass_n_kg"), String(лифт.кг))
        }
        let поправленный = поправить(итог.уровень, итог.способ, п, вещь)
        return ШагПроходаМоего(id: п.id, вид: .лифт, название: название(п), уровень: поправленный.0,
                               способ: поправленный.1, числа: числа, примерно: п.примерно, запасной: false)
    }

    /// Кабина Ш×Г×≈205: лёжа, стоя, по диагонали пола, наклоном до потолка — лучший способ.
    private static func вКабину(_ а: Double, _ б: Double, _ в: Double, кш: Double, кг: Double, дверь: Double,
                                высотаДвери: Double) -> (уровень: УровеньСтандарта, способ: СпособПроходаМоего) {
        let кв = высотаКабины
        var лучший: (уровень: УровеньСтандарта, способ: СпособПроходаМоего) = (.неПодходит, .нет)
        func взять(_ уровень: УровеньСтандарта, _ способ: СпособПроходаМоего) {
            if уровень < лучший.уровень { лучший = (уровень, способ) }
        }
        // Лёжа вдоль длинной стороны пола: сечение а×б — в короткую сторону × высоту.
        if в + запас <= max(кш, кг), вОкно(а, б, min(кш, кг) - запас, кв - запас) == 0 {
            if в + впритык <= max(кш, кг) {
                взять(.подходит, .лёжа)
            } else {
                взять(.проверить, .впритык)
            }
        }
        // Стоя: а×б — на пол; занесли стоя (а в дверь, в — по высоте двери) — подходит, иначе — наклоном у входа.
        if в + запас <= кв, вОкно(а, б, кш - запас, кг - запас) == 0 {
            let стояВДверь = а + запас <= дверь && в + запас <= высотаДвери
            let низкая = в > кв - 10
            взять(стояВДверь && !низкая ? .подходит : .проверить, .стоя)
        }
        // По диагонали пола: лежит на тонкой стороне, б×в — наискосок.
        if а + запас <= кв, let угол = вОкно(б, в, кш - запас, кг - запас), угол > 0 {
            взять(.проверить, .диагональ)
        }
        // Наклоном: в — от пола к потолку вдоль глубины, б — поперёк кабины.
        if б + запас <= кш, вОкно(а, в, кг - запас, кв - запас) != nil {
            взять(.проверить, .наклоном)
        }
        return лучший
    }

    private static func шагЛестницы(_ с: [Double], _ п: ПроёмМоего, _ вещь: ВещьПроходаМоего,
                                    потолок: Double) -> ШагПроходаМоего {
        let марш = Double(п.ширина ?? КаталогСтандартов.маршЛестницы)
        let поворот = ПоворотЛестницыМоего.из(п)
        let площадка = Double(п.кабинаГлубина ?? п.ширина ?? КаталогСтандартов.маршЛестницы)
        let а = с[0], б = с[1], в = с[2]
        var числа = String(format: МойДомText.т("mh_pass_n_stairs"), см(марш))
        var итог = сечение(а, б, ширина: марш, высота: надМаршем)
        if итог.уровень != .неПодходит && поворот != .прямая {
            числа += " · " + String(format: МойДомText.т("mh_pass_n_landing"), см(площадка))
            let предел = длинаЗаУгол(марш, площадка, толщина: а + запас)
            if в + запас <= предел {
                if поворот == .разворот { итог = (max(итог.уровень, .проверить), .разворот) }
            } else if подняв(длина: в, толщина: б, предел: предел - запас, высота: потолок - запас) {
                итог = (.проверить, .подняв)
            } else {
                итог = (.неПодходит, .нет)
            }
        }
        let поправленный = поправить(итог.уровень, итог.способ, п, вещь)
        return ШагПроходаМоего(id: п.id, вид: .лестница, название: название(п), уровень: поправленный.0,
                               способ: поправленный.1, числа: числа, примерно: п.примерно, запасной: false)
    }
}

// MARK: - Вид итога

/**
 Итог «Пройдёт ли?»: значок уровня в цветном круге, заголовок, «почему», шаги пути с их уровнями (запасной путь —
 бледнее) и совет. Появление — проявлением и лёгким подъёмом шагов по очереди; «Уменьшение движения» и лёгкий режим —
 сразу. Для VoiceOver — каждый шаг одной строкой: «Подходит. Входная дверь: прямо · вещь 60×65 см, проход 74 см».
 */
struct ИтогПроходаВид: View {
    let итог: ИтогПроходаМоего
    @ObservedObject private var режим = РежимУстройства.shared
    @Environment(\.accessibilityReduceMotion) private var безДвижения
    @State private var видно = false

    init(итог: ИтогПроходаМоего) {
        self.итог = итог
    }

    private var тихо: Bool { безДвижения || ДвижениеСайта.тихо || режим.лёгкий }

    var body: some View {
        VStack(alignment: .leading, spacing: 10) {
            шапка
            ForEach(Array(итог.шаги.enumerated()), id: \.element.id) { номер, шаг in
                строка(шаг)
                    .opacity(видно ? (шаг.запасной ? 0.62 : 1) : 0)
                    .offset(y: видно ? 0 : 8)
                    .animation(тихо ? nil : Animation.spring(response: 0.45, dampingFraction: 0.85)
                        .delay(0.06 * Double(номер + 1)), value: видно)
            }
            if let совет = итог.совет {
                Label {
                    Text(совет)
                        .fixedSize(horizontal: false, vertical: true)
                } icon: {
                    Image(systemName: "lightbulb")
                        .foregroundStyle(Theme.золото)
                }
                .font(.footnote)
                .foregroundStyle(Theme.текстВторой)
            }
        }
        .onAppear {
            if тихо {
                видно = true
            } else {
                withAnimation(.spring(response: 0.45, dampingFraction: 0.85)) { видно = true }
            }
        }
    }

    private var шапка: some View {
        HStack(alignment: .top, spacing: 12) {
            Image(systemName: итог.уровень.значокИтога)
                .font(.system(size: 22, weight: .bold))
                .foregroundStyle(итог.уровень.краска)
                .frame(width: 44, height: 44)
                .background(итог.уровень.краска.opacity(0.14), in: Circle())
                .scaleEffect(видно ? 1 : 0.6)
                .symbolEffect(.bounce, value: видно && !тихо)
                .accessibilityHidden(true)
            VStack(alignment: .leading, spacing: 3) {
                Text(итог.заголовок)
                    .font(.headline)
                    .foregroundStyle(Theme.текст)
                    .fixedSize(horizontal: false, vertical: true)
                Text(итог.почему)
                    .font(.subheadline)
                    .foregroundStyle(Theme.текстВторой)
                    .fixedSize(horizontal: false, vertical: true)
            }
            .frame(maxWidth: .infinity, alignment: .leading)
        }
        .accessibilityElement(children: .combine)
    }

    private func строка(_ шаг: ШагПроходаМоего) -> some View {
        HStack(alignment: .top, spacing: 10) {
            Image(systemName: шаг.уровень.значок)
                .font(.subheadline.weight(.bold))
                .foregroundStyle(шаг.уровень.краска)
                .frame(width: 22)
                .accessibilityHidden(true)
            VStack(alignment: .leading, spacing: 2) {
                HStack(spacing: 6) {
                    Image(systemName: шаг.вид.значок)
                        .font(.caption.weight(.semibold))
                        .foregroundStyle(Theme.текстВторой)
                        .accessibilityHidden(true)
                    Text(шаг.название)
                        .font(.subheadline.weight(.bold))
                        .foregroundStyle(Theme.текст)
                    Text(шаг.способ.текст)
                        .font(.caption.weight(.bold))
                        .foregroundStyle(шаг.уровень.краска)
                        .padding(.horizontal, 7)
                        .padding(.vertical, 2)
                        .background(шаг.уровень.краска.opacity(0.12), in: Capsule())
                }
                Text(Self.числа(шаг))
                    .font(.caption.monospacedDigit())
                    .foregroundStyle(Theme.текстВторой)
                    .fixedSize(horizontal: false, vertical: true)
            }
            Spacer(minLength: 0)
        }
        .accessibilityElement(children: .ignore)
        .accessibilityLabel(Self.озвучка(шаг))
    }

    /// «вещь 60×65 см · проход 74 см · примерно».
    private static func числа(_ шаг: ШагПроходаМоего) -> String {
        guard шаг.примерно else { return шаг.числа }
        return шаг.числа + " · " + МойДомText.т("mh_approx")
    }

    /// «Подходит. Входная дверь: прямо · вещь 60×65 см, проход 74 см».
    private static func озвучка(_ шаг: ШагПроходаМоего) -> String {
        var текст = шаг.уровень.слово + ". " + шаг.строка
        if шаг.запасной { текст += ". " + МойДомText.т("mh_pass_spare_a11y") }
        return текст
    }
}

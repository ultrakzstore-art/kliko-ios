/**
 «МОЁ» — «МОЙ КОМПЬЮТЕР»: ИСТОРИЯ, «ПОСТАВИЛИ?» И ПЕРЕХОДЫ (владелец 16.10.2026: «показывать, что был куплен там —
 цифровизация реальности»; docs/STANDARDS.md §8.8).

 История — короткие события с датой: «Добавлен в «Моё»», «Куплено на Kliko», «Поставили · ОЗУ 16 ГБ · было: 8 ГБ»,
 «Заменили · Видеокарта RTX 4060 · было: GTX 1060», «По снимку экрана», «По шаблону». Ключ события — вид и часть
 («replaced:gpu»); текст — значения на языке, каким их видел человек. Правки панели сводятся при уходе с экрана: сравнение
 с тем, что было при входе, по частям — одно событие на часть, а не на каждое касание; в день создания компьютера
 (первое заполнение) событий правки нет.

 «Поставили?» — деталь, купленная на Kliko для этого компьютера (ВещьМоего с местом «компьютер»): «Да» — конфигурация
 меняется по её стандартам (планка — в слот, SSD — в свободный M.2, карта, БП, процессор) и в историю ложится
 «Поставили» с номером вещи (по нему видно, что вопрос закрыт); «Позже» — до следующего входа. Без «Да» конфигурация не
 меняется.

 Переходы: объявление — в стек, где лежит экран (кабинет), а в окне поверх — своим окном; поиск, мастер подачи и
 «Апгрейд ПК» — после того как окно «Моего» закроется. Всё на телефоне; в адрес поиска уходит только то, что человек сам
 нажал («Найти на Kliko»).
 */
enum ИсторияКомпьютераМоего {
    private static func т(_ ключ: String) -> String { МойКомпьютерText.т(ключ) }

    // MARK: - Вид события

    /// Вид и часть из ключа события: «replaced:gpu» → («replaced», .видеокарта).
    static func разобрать(_ что: String) -> (вид: String, часть: ЧастьКомпьютераМоего?) {
        let куски = что.split(separator: ":", maxSplits: 1).map(String.init)
        let вид = куски.first ?? "edited"
        let часть = куски.count > 1 ? ЧастьКомпьютераМоего(rawValue: куски[1]) : nil
        return (вид, часть)
    }

    /// «Заменили · Видеокарта», «Куплено на Kliko».
    static func заголовок(_ событие: СобытиеКомпьютераМоего) -> String {
        let (вид, часть) = разобрать(событие.что)
        let ключи = ["added", "bought", "installed", "replaced", "removed", "edited", "scan", "template"]
        let слово = т("mpc_ev_" + (ключи.contains(вид) ? вид : "edited"))
        guard let часть else { return слово }
        return слово + " · " + часть.название
    }

    static func значок(_ событие: СобытиеКомпьютераМоего) -> String {
        switch разобрать(событие.что).вид {
        case "added": return "plus.circle"
        case "bought": return "bag"
        case "installed": return "arrow.down.circle"
        case "replaced": return "arrow.triangle.2.circlepath"
        case "removed": return "minus.circle"
        case "scan": return "text.viewfinder"
        case "template": return "square.grid.2x2"
        default: return "pencil.circle"
        }
    }

    // MARK: - Сводка правок

    /// Компьютер создан сегодня — его ещё заполняют: правки в историю не идут.
    static func заполняется(_ к: КомпьютерМоего, сейчас: Date = Date()) -> Bool {
        Calendar.current.isDate(к.создан, inSameDayAs: сейчас)
    }

    /// События правок «было → стало» по частям: одно на часть.
    static func события(было: КомпьютерМоего, стало: КомпьютерМоего) -> [(что: String, текст: String)] {
        var итог: [(что: String, текст: String)] = []
        if было.вид != стало.вид {
            итог.append((что: "edited", текст: стало.вид.название))
        }
        if let с = процессор(было, стало) { итог.append(с) }
        if let с = память(было.память, стало.память) { итог.append(с) }
        if let с = видеокарта(было.видеокарта, стало.видеокарта) { итог.append(с) }
        if let с = бп(было.бп, стало.бп) { итог.append(с) }
        if let с = накопители(было, стало) { итог.append(с) }
        if было.корпус != стало.корпус, let значение = ЧастьКомпьютераМоего.корпус.значение(стало) {
            итог.append((что: "edited:case", текст: значение))
        }
        return итог
    }

    private static func текстБыло(_ новое: String, _ старое: String) -> String {
        String(format: т("mpc_was"), новое, старое)
    }

    private static func процессор(_ а: КомпьютерМоего, _ б: КомпьютерМоего) -> (что: String, текст: String)? {
        let старый = а.процессор.trimmingCharacters(in: .whitespaces)
        let новый = б.процессор.trimmingCharacters(in: .whitespaces)
        if старый != новый && !новый.isEmpty {
            if старый.isEmpty { return (что: "edited:cpu", текст: новый) }
            return (что: "replaced:cpu", текст: текстБыло(новый, старый))
        }
        if а.сокет != б.сокет || а.чипсет != б.чипсет, let значение = ЧастьКомпьютераМоего.процессор.значение(б) {
            return (что: "edited:cpu", текст: значение)
        }
        return nil
    }

    private static func память(_ а: ПамятьКомпьютераМоего, _ б: ПамятьКомпьютераМоего) -> (что: String, текст: String)? {
        guard а != б else { return nil }
        if let новоВсего = б.всего, let староВсего = а.всего, новоВсего != староВсего {
            let текст = текстБыло(ФорматКомпьютераМоего.гб(новоВсего), ФорматКомпьютераМоего.гб(староВсего))
            return (что: новоВсего > староВсего ? "installed:ram" : "removed:ram", текст: текст)
        }
        var к = КомпьютерМоего(вид: .настольный)
        к.память = б
        guard let значение = ЧастьКомпьютераМоего.память.значение(к) else { return nil }
        return (что: "edited:ram", текст: значение)
    }

    private static func видеокарта(_ а: ВидеокартаМоего, _ б: ВидеокартаМоего) -> (что: String, текст: String)? {
        if а.чип != б.чип {
            switch (а.чип, б.чип) {
            case (nil, let новый?): return (что: "installed:gpu", текст: новый)
            case (let старый?, let новый?): return (что: "replaced:gpu", текст: текстБыло(новый, старый))
            case (let старый?, nil): return (что: "removed:gpu", текст: старый)
            default: return nil
            }
        }
        guard а != б else { return nil }
        var итог: [String] = []
        if let ч = б.чип { итог.append(ч) }
        if let д = б.длина { итог.append(ФорматКомпьютераМоего.мм(д)) }
        if б.встроенная && б.чип == nil { итог.append(т("mpc_gpu_igpu")) }
        guard !итог.isEmpty else { return nil }
        return (что: "edited:gpu", текст: итог.joined(separator: " · "))
    }

    private static func бп(_ а: БлокПитанияМоего, _ б: БлокПитанияМоего) -> (что: String, текст: String)? {
        guard а != б else { return nil }
        if let новый = б.ватт, let старый = а.ватт, новый != старый {
            return (что: "replaced:psu",
                    текст: текстБыло(ФорматКомпьютераМоего.ватт(новый), ФорматКомпьютераМоего.ватт(старый)))
        }
        var итог: [String] = []
        if let в = б.ватт { итог.append(ФорматКомпьютераМоего.ватт(в)) }
        if let с = б.сертификат { итог.append(с) }
        guard !итог.isEmpty else { return nil }
        return (что: "edited:psu", текст: итог.joined(separator: " · "))
    }

    private static func накопители(_ а: КомпьютерМоего, _ б: КомпьютерМоего) -> (что: String, текст: String)? {
        guard а.накопители != б.накопители || а.слотыM2 != б.слотыM2 || а.отсеков25 != б.отсеков25 else { return nil }
        let старые = Set(а.накопители.map(\.id))
        let новые = б.накопители.filter { !старые.contains($0.id) }
        if !новые.isEmpty {
            return (что: "installed:drives", текст: новые.map { ФорматКомпьютераМоего.диск($0) }.joined(separator: ", "))
        }
        let оставшиеся = Set(б.накопители.map(\.id))
        let ушли = а.накопители.filter { !оставшиеся.contains($0.id) }
        if !ушли.isEmpty {
            return (что: "removed:drives", текст: ушли.map { ФорматКомпьютераМоего.диск($0) }.joined(separator: ", "))
        }
        guard let значение = ЧастьКомпьютераМоего.накопители.значение(б) else { return nil }
        return (что: "edited:drives", текст: значение)
    }

    // MARK: - «Поставили?»

    /// Купленная деталь уже поставлена (или вопрос закрыт): в истории есть событие с её номером.
    static func поставлена(_ вещь: ВещьМоего, в к: КомпьютерМоего) -> Bool {
        к.история.contains { $0.id == вещь.id }
    }

    /// «Да, поставили»: конфигурация — по стандартам купленной детали; часть, которую она поменяла (nil — стандарт
    /// незнаком, меняется только история).
    static func поставить(_ вещь: ВещьМоего, в к: inout КомпьютерМоего) -> ЧастьКомпьютераМоего? {
        typealias К = КлючСтандарта
        let н = вещь.стандарты
        if н.есть(.память) {
            if к.память.поколение == nil, let п = н[.память, К.поколение] { к.память.поколение = п }
            if к.память.форма == nil, let ф = н[.память, К.форма], ф != "soldered" { к.память.форма = ф }
            if let гб = н.целое(.память, К.гб) {
                к.память.планки += Array(repeating: гб, count: max(1, min(4, н.сколько)))
            }
            к.память.нормализовать()
            return .память
        }
        if н.есть(.накопитель) {
            let форма = н[.накопитель, К.форма] ?? "2280"
            let диск = НакопительМоего(форма: форма, протокол: н[.накопитель, К.протокол],
                                       pcie: н.целое(.накопитель, К.pcie), тб: н.число(.накопитель, К.тб), hdd: false)
            if КаталогСтандартов.длинаM2(форма) != nil {
                if let i = к.слотыM2.firstIndex(where: { !$0.занят }) {
                    к.слотыM2[i].занят = true
                } else if к.слотыM2.count < 6 {
                    к.слотыM2.append(СлотM2Моего(длина: форма, протокол: диск.протокол == "sata" ? "sata" : "nvme",
                                                 pcie: диск.pcie, занят: true))
                }
            }
            к.накопители.append(диск)
            return .накопители
        }
        if н.есть(.видеокарта) {
            if let чип = н[.видеокарта, К.чип] { к.видеокарта.чип = чип }
            if let г = н.целое(.видеокарта, К.памятьКарты) { к.видеокарта.памятьГБ = г }
            if let д = н.целое(.видеокарта, К.длина) { к.видеокарта.длина = д }
            if let п = н[.видеокарта, К.питание] { к.видеокарта.питание = п }
            к.видеокарта.встроенная = false
            return .видеокарта
        }
        if н.есть(.блокПитания) {
            if let в = н.целое(.блокПитания, К.ватт) { к.бп.ватт = в }
            if let ф = н[.блокПитания, К.форма] { к.бп.форма = ф }
            if let с = н[.блокПитания, К.сертификат] { к.бп.сертификат = с }
            return .бп
        }
        if н.есть(.сокет) {
            if let цп = н[.сокет, К.процессор] { к.процессор = цп }
            if к.вид == .настольный, let с = н[.сокет, К.сокет] { к.сокет = с }
            return .процессор
        }
        return nil
    }

    /// Событие «Поставили» с номером купленной вещи.
    static func отметить(_ вещь: ВещьМоего, часть: ЧастьКомпьютераМоего?, в к: inout КомпьютерМоего) {
        let что = "installed" + (часть.map { ":" + $0.rawValue } ?? "")
        к.история.append(СобытиеКомпьютераМоего(id: вещь.id, когда: Date(), что: что, текст: вещь.название))
        if к.история.count > КомпьютерМоего.пределИстории {
            к.история.removeFirst(к.история.count - КомпьютерМоего.пределИстории)
        }
    }
}

// MARK: - Переходы

@MainActor
enum ПереходыКомпьютераМоего {
    /**
     Экран «Моего» открыт окном поверх (ОкноМоего) — сначала закрыть окно, потом сделать (иначе поиск и мастер встанут
     под окном); в стеке кабинета — сразу.
     */
    static func послеОкна(_ действие: @escaping @MainActor () -> Void) {
        if let верх = ПоверхВсего.верхний(), верх.presentingViewController != nil {
            верх.dismiss(animated: true)
            Task { @MainActor in
                try? await Task.sleep(nanoseconds: 450_000_000)
                действие()
            }
        } else {
            действие()
        }
    }

    /// «Найти на Kliko»: обычный поиск ленты — как если бы человек набрал его сам.
    static func найти(_ запрос: String, раздел: String) {
        let искомое = ИскомоеЛенты(текст: запрос, раздел: раздел)
        послеОкна {
            WebBridge.shared.открытьЭкран(.найти(искомое), запасной: nil)
        }
    }

    /**
     «Продать старую деталь»: мастер подачи. Заготовки названия и раздела у мастера пока нет — название кладётся в буфер
     обмена (экран говорит об этом вестью), раздел человек выбирает сам.
     */
    static func продать(название: String) {
        // Только этот телефон (без Универсального буфера на другие устройства) и на 10 минут — как «Копировать» пароль.
        if !название.isEmpty {
            UIPasteboard.general.setItems([["public.utf8-plain-text": название]],
                                          options: [.localOnly: true, .expirationDate: Date().addingTimeInterval(600)])
        }
        послеОкна {
            _ = ПодачаОкно.shared.открыть(.новое)
        }
    }

    /// Объявление: в стек экрана (кабинет), иначе — своим окном поверх.
    static func открыть(_ товар: Listing, вСтеке: ((Listing) -> Void)?) {
        if let вСтеке {
            вСтеке(товар)
            return
        }
        ПоверхВсего.показать(большой: true) { закрыть in
            ОкноОбъявленияКомпьютераМоего(товар: товар, закрыть: закрыть)
        }
    }
}

/// Объявление окном поверх «Моего»: свой стек (похожие и чат ложатся в него) и «Закрыть».
private struct ОкноОбъявленияКомпьютераМоего: View {
    let товар: Listing
    let закрыть: () -> Void
    @State private var путь = NavigationPath()

    init(товар: Listing, закрыть: @escaping () -> Void) {
        self.товар = товар
        self.закрыть = закрыть
    }

    var body: some View {
        NavigationStack(path: $путь) {
            ListingDetailView(товар: товар, открыть: { адрес in открытьАдрес(адрес) })
                .navigationDestination(for: Listing.self) { другой in
                    ListingDetailView(товар: другой, открыть: { адрес in открытьАдрес(адрес) })
                }
                .чатМаршруты(открыть: { адрес in открытьАдрес(адрес) })
                .toolbar {
                    ToolbarItem(placement: .cancellationAction) {
                        Button(МоёText.т("my_close")) { закрыть() }
                    }
                }
        }
        .environment(\.открытьОбъявлениеВСтеке, { другой in путь.append(другой) })
        .tint(Theme.акцент)
    }

    /// Ссылка изнутри карточки: окно закрывается, адрес — путём корня приложения.
    @MainActor
    private func открытьАдрес(_ адрес: URL) {
        закрыть()
        ПоверхВсего.открытьАдрес(адрес)
    }
}

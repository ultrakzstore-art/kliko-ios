import Foundation
import CoreGraphics

/**
 «МОЁ» — МЕРКИ ПО ФОТО В ПОЛНЫЙ РОСТ (владелец 16.10.2026, «Мой рост и мерки»: «тут то же самое, бро: стандарты! =
 удобства это»; про колёса — «камерой узнать размеры»). Вместо восьми пустых полей — то, что честно видно на снимке.

 Только длины, видные на одном фото анфас: ширина плеч, длина руки, длина ноги по шагу. Обхваты (грудь, талия, бёдра,
 голова) по одному снимку не оцениваются — глубины тела на нём нет. Стопу тоже нет: у позы Vision нет пятки и носка, а
 анфас стопа ещё и укорочена. Считается на телефоне из точек позы, что уже лежат в записи (ФотоМоего.поза — их пишет
 ОбработкаФотоМоего.поза, MyThingsPhoto.swift); ничего никуда не отправляется.

 Масштаб — указанный рост: от уровня глаз (точка «eyes»; у старых снимков — «head», обычно кончик носа) до середины
 лодыжек на снимке — это (уровень глаз − уровень лодыжки) роста. Точки — доли снимка, поэтому сначала переводятся в
 пиксели по размеру снимка (x — от ширины, y — от высоты), а расстояния берутся по прямой: наклон телефона до 12°
 масштаб не портит. Дальше:
   · ширина плеч — между точками плечевых суставов × 1,2. Точки Vision стоят в центрах суставов, на 2–3 см внутрь от
     каждой плечевой точки (акромиона): расстояние между ними ≈ 0,21 H против ≈ 0,23 H у акромионов (×1,1), а «по
     спине от одной плечевой точки до другой» лента ложится по изгибу спины — ещё ≈ +8–10 % (×1,1); итого ≈ 1,2;
   · длина руки — плечо → локоть → запястье, сумма отрезков (сгиб в плоскости снимка не укорачивает) + 0,02 H:
     плечевая точка выше центра сустава на 2–3 см, а лента по чуть согнутому локтю длиннее прямой на ≈ 1 см.
     Кисть не добавляется — мерка «до запястья»;
   · длина ноги по шагу — бедро → колено → лодыжка, сумма отрезков + высота лодыжки над полом (0,039 H) − пах ниже
     центров тазобедренных суставов (0,05 H): от паха до пола, как в подсказке мерки.
 Откуда доли роста H. Drillis и Contini, 1966 (пропорции сегментов тела, по книге D. A. Winter «Biomechanics and Motor
 Control of Human Movement»): глаза 0,936 H, плечевая точка 0,818 H, большой вертел 0,530 H, лодыжка 0,039 H; плечо
 0,186 H, предплечье 0,146 H, бедро 0,245 H, голень 0,246 H, кончик носа — между глазами и подбородком (0,870 H),
 ≈ 0,91 H. ANSUR II, 2012 (армия США, 4082 мужчины и 1986 женщин): высота паха ≈ 0,478 H у мужчин и ≈ 0,473 H у
 женщин — отсюда пах на ≈ 0,05 H ниже тазобедренных суставов; акромион — лучевая головка — шиловидный отросток
 ≈ 0,34 H (рука); ширина по акромионам ≈ 0,23 H.

 Отбраковка — пусто, а не «примерно»: рост вне 100…230; нет размера снимка; уверенных точек тела меньше 8 из 10; нет
 головы, лодыжек, обоих плеч или обоих бёдер; фигура ниже 55 % кадра (как отметка «в полный рост»); тело наклонено
 больше 12°; плечи или бёдра не на своём уровне (сидит, присел, наклонился); корпус или линия плеч перекошены; колено
 согнуто сильнее 20°; ноги расставлены шире 12° от оси; плечи узкие для роста (стоит вполоборота). Отдельная мерка
 пропускается, если не видны её точки, рука поднята выше плеча, пропорции отрезков не человеческие или итог вне
 обычных долей роста и пределов МеркаМоего. Две стороны: близки (до 6 %) — среднее; расходятся до 15 % — бо́льшая
 (перспектива и сгиб к камере только укорачивают); сильнее — ни одной. Видна одна сторона — она.

 Точность — честно ±2–3 см на мерку при прямой стойке анфас и телефоне на уровне груди, без наклона вперёд или назад.
 Сверху добавляется ошибка введённого роста (1 см роста — ≈ 0,5 см шага), одежда (объёмная куртка расширит плечи) и
 то, что люди сложены по-разному: доли роста — средние. Итог округляется до 1 см. Калибровать коэффициенты — на
 замерах лентой (позже), не на глаз.
 */
enum ОценкаМерокПоФото {
    /// Честная точность оценки, ± см — для подписи «по фото, ±3 см».
    static let погрешность = 3

    // MARK: Доли роста и допуски

    /// Высота над полом в долях роста: глаза, голова старых снимков (обычно кончик носа), лодыжка.
    private static let уровеньГлаз = 0.936
    private static let уровеньГоловы = 0.91
    private static let уровеньЛодыжки = 0.039
    /// Центры плечевых и тазобедренных суставов (точки Vision) — где им положено быть у прямо стоящего.
    private static let уровеньПлеч = 0.805
    private static let уровеньБёдер = 0.52
    /// Насколько точка может уйти от своего уровня, в долях отрезка «лодыжки — глаза».
    private static let допускУровня = 0.07

    /// Пах ниже центров тазобедренных суставов, доля роста.
    private static let пахНижеБедра = 0.05
    /// Плечевая точка над центром сустава и лента по чуть согнутому локтю, доля роста.
    private static let добавкаРукава = 0.02
    /// Ширина плеч по спине к расстоянию между точками плечевых суставов.
    private static let коэффициентПлеч = 1.2

    /// Наибольший наклон тела, корпуса и линии плеч, градусы.
    private static let наибольшийНаклон = 12.0
    /// Наибольший угол ноги (бедро → лодыжка) к оси тела, градусы.
    private static let наибольшийРазворотНоги = 12.0
    /// Колено прямое — угол бедро-колено-голень не меньше, градусы.
    private static let прямоеКолено = 160.0

    /// Обычные доли роста готовых мерок: вне них — ошибка точек или поза, а не человек.
    private static let долиПлеч = 0.19...0.32
    private static let долиРукава = 0.29...0.40
    private static let долиШага = 0.42...0.54
    /// Отрезки руки (плечо к предплечью) и ноги (бедро к голени): иначе один из них укорочен — смотрит в камеру.
    private static let отрезкиРуки = 0.95...1.7
    private static let отрезкиНоги = 0.75...1.4

    /// Две стороны близки — среднее; расходятся не больше чем на это — бо́льшая.
    private static let согласие = 0.06
    private static let расхождение = 0.15

    /// Основные точки позы (как пишет MyThingsPhoto.swift) и сколько из них нужно уверенных.
    private static let ключиТела = ["head", "neck", "lsh", "rsh", "lhip", "rhip", "lknee", "rknee", "lank", "rank"]
    private static let минимумТочек = 8

    // MARK: Оценка

    /**
     Мерки по точкам позы и росту: плечи, рукав, шаг — сколько честно получилось, округлено до 1 см и в пределах
     МеркаМоего. Пусто — человек не в полный рост, мало уверенных точек или поза не прямая.
     */
    static func оценить(точки: [String: ТочкаМоего], рост: Int, размерСнимка: CGSize?) -> [МеркаМоего: Double] {
        guard ТелоМоего.пределыРоста.contains(рост), let размерСнимка,
              размерСнимка.width >= 64, размерСнимка.height >= 64 else { return [:] }
        let ширина = Double(размерСнимка.width)
        let высота = Double(размерСнимка.height)
        let ростСм = Double(рост)
        func взять(_ ключ: String) -> Пикс? {
            точки[ключ].map { Пикс(x: $0.x * ширина, y: $0.y * высота) }
        }
        guard ключиТела.filter({ точки[$0] != nil }).count >= минимумТочек else { return [:] }

        // Масштаб: от глаз (или головы) до середины лодыжек.
        let глаза = взять("eyes")
        let уровеньВерха = глаза != nil ? уровеньГлаз : уровеньГоловы
        guard let верх = глаза ?? взять("head"),
              let низ = Пикс.среднее([взять("lank"), взять("rank")].compactMap({ $0 })),
              let лп = взять("lsh"), let пп = взять("rsh"), let лб = взять("lhip"), let пб = взять("rhip")
        else { return [:] }
        let ось = верх - низ
        let ростПикс = ось.длина
        guard ось.y < 0, -ось.y >= 0.55 * высота, угол(ось, Пикс(x: 0, y: -1)) <= наибольшийНаклон else { return [:] }
        let пиксНаСм = ростПикс / ((уровеньВерха - уровеньЛодыжки) * ростСм)
        guard пиксНаСм.isFinite, пиксНаСм > 0 else { return [:] }
        func см(_ пикс: Double) -> Double { пикс / пиксНаСм }
        /// Где точка по оси тела: 0 — лодыжки, 1 — верхняя точка.
        func доля(_ т: Пикс) -> Double { (т - низ).скаляр(ось) / (ростПикс * ростПикс) }
        func ожидаемая(_ уровень: Double) -> Double { (уровень - уровеньЛодыжки) / (уровеньВерха - уровеньЛодыжки) }

        // Стоит прямо и анфас: плечи и бёдра на своих уровнях, корпус по оси, плечи поперёк, лево-право не перекручено.
        let центрПлеч = лп.середина(пп)
        let центрБёдер = лб.середина(пб)
        guard abs(доля(центрПлеч) - ожидаемая(уровеньПлеч)) <= допускУровня,
              abs(доля(центрБёдер) - ожидаемая(уровеньБёдер)) <= допускУровня,
              угол(центрПлеч - центрБёдер, ось) <= наибольшийНаклон,
              abs(угол(лп - пп, ось) - 90) <= наибольшийНаклон,
              (лп.x - пп.x) * (лб.x - пб.x) > 0
        else { return [:] }
        for сторона in ["l", "r"] {
            guard let бедро = взять(сторона + "hip"), let лодыжка = взять(сторона + "ank") else { continue }
            if угол(бедро - лодыжка, ось) > наибольшийРазворотНоги { return [:] }
            if let колено = взять(сторона + "knee"), угол(бедро - колено, лодыжка - колено) < прямоеКолено {
                return [:]
            }
        }
        // Плечи узкие для роста — стоит вполоборота: руки и ноги на снимке тоже искажены.
        let ширинаПлеч = см(лп.до(пп)) * коэффициентПлеч
        guard ширинаПлеч / ростСм >= долиПлеч.lowerBound else { return [:] }

        /// Рука поднята: локоть или запястье выше своего плеча — точка плеча при этом съезжает.
        func поднята(_ сторона: String) -> Bool {
            guard let плечо = взять(сторона + "sh") else { return false }
            let уровень = доля(плечо)
            return [взять(сторона + "elb"), взять(сторона + "wri")].compactMap { $0 }.contains { доля($0) > уровень }
        }
        func рука(_ сторона: String) -> Double? {
            guard !поднята(сторона), let плечо = взять(сторона + "sh"), let локоть = взять(сторона + "elb"),
                  let запястье = взять(сторона + "wri") else { return nil }
            let плечевая = плечо.до(локоть)
            let предплечье = локоть.до(запястье)
            guard предплечье > 0, отрезкиРуки.contains(плечевая / предплечье) else { return nil }
            let длина = см(плечевая + предплечье) + добавкаРукава * ростСм
            return долиРукава.contains(длина / ростСм) ? длина : nil
        }
        func нога(_ сторона: String) -> Double? {
            guard let бедро = взять(сторона + "hip"), let колено = взять(сторона + "knee"),
                  let лодыжка = взять(сторона + "ank") else { return nil }
            let бедренная = бедро.до(колено)
            let голень = колено.до(лодыжка)
            guard голень > 0, отрезкиНоги.contains(бедренная / голень) else { return nil }
            let длина = см(бедренная + голень) + (уровеньЛодыжки - пахНижеБедра) * ростСм
            return долиШага.contains(длина / ростСм) ? длина : nil
        }

        var итог: [МеркаМоего: Double] = [:]
        func записать(_ мерка: МеркаМоего, _ значение: Double?) {
            guard let есть = значение, есть.isFinite else { return }
            let округлённое = есть.rounded()
            guard мерка.пределы.contains(округлённое) else { return }
            итог[мерка] = округлённое
        }
        if !поднята("l"), !поднята("r"), долиПлеч.contains(ширинаПлеч / ростСм) { записать(.плечи, ширинаПлеч) }
        записать(.рукав, обе(рука("l"), рука("r")))
        записать(.шаг, обе(нога("l"), нога("r")))
        return итог
    }

    /// То же по сохранённому фото в полный рост: точки позы и размер снимка — из записи.
    static func оценить(фото: ФотоМоего, рост: Int) -> [МеркаМоего: Double] {
        оценить(точки: фото.поза, рост: рост, размерСнимка: CGSize(width: фото.ширина, height: фото.высота))
    }

    // MARK: Геометрия

    /// Точка или направление в пикселях снимка, y — вниз.
    private struct Пикс {
        var x: Double
        var y: Double

        static func - (а: Пикс, б: Пикс) -> Пикс { Пикс(x: а.x - б.x, y: а.y - б.y) }

        var длина: Double { hypot(x, y) }

        func до(_ б: Пикс) -> Double { (б - self).длина }

        func середина(_ б: Пикс) -> Пикс { Пикс(x: (x + б.x) / 2, y: (y + б.y) / 2) }

        func скаляр(_ б: Пикс) -> Double { x * б.x + y * б.y }

        /// Середина нескольких точек; пусто — nil.
        static func среднее(_ все: [Пикс]) -> Пикс? {
            guard !все.isEmpty else { return nil }
            let n = Double(все.count)
            return Пикс(x: все.map(\.x).reduce(0, +) / n, y: все.map(\.y).reduce(0, +) / n)
        }
    }

    /// Угол между направлениями, градусы 0…180; нулевое направление — 180 (не годится).
    private static func угол(_ а: Пикс, _ б: Пикс) -> Double {
        let произведение = а.длина * б.длина
        guard произведение > 0 else { return 180 }
        return acos(max(-1, min(1, а.скаляр(б) / произведение))) * 180 / Double.pi
    }

    /// Две стороны тела: близки — среднее, расходятся немного — бо́льшая, сильно — nil; одна — она.
    private static func обе(_ левая: Double?, _ правая: Double?) -> Double? {
        let есть = [левая, правая].compactMap { $0 }
        guard let меньшая = есть.min(), let большая = есть.max(), большая > 0 else { return nil }
        if меньшая >= большая * (1 - согласие) { return (меньшая + большая) / 2 }
        return меньшая >= большая * (1 - расхождение) ? большая : nil
    }
}

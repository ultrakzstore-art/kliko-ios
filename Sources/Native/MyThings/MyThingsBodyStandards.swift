/**
 «МОЁ» — ТИПОВЫЕ МЕРКИ ПО СТАНДАРТАМ (владелец 16.10.2026: «Тут то же самое, бро: стандарты! = удобства это» — восемь
 пустых полей «— см» никто не заполнит, а размер свой человек знает).

 Размер → типичные мерки тела по стандартным таблицам (ClothingSizes.swift — только вызовы и добавленные таблицы мерок):
   · одежда — обхваты груди, талии, бёдер из таблиц одежды (RU = обхват груди пополам; бёдра мужчин и ширина плеч — из
     таблиц меркиМужские и меркиЖенские), плечи с поправкой на рост: +1 см на 10 см от типового роста 176 и 164;
   · джинсы — талия по W (столбец «Талия, см» = W × 2,54), длина ноги по шагу — по длине L;
   · бельё — обхват груди = под грудью + разница обхватов чашки (точнее, чем размер одежды);
   · обувь — длина стопы, столбец «см» таблицы обуви; шапка — обхват головы (RU шапок — это он и есть);
   · рост — длины пропорциями (Drillis и Contini, 1966; сверено с таблицей длины L джинсов: L32 = 81 см при росте
     175–180): плечи 0,255 роста у мужчин и 0,235 у женщин, рука от плечевой точки до запястья 0,355 и 0,345, шаг 0,46
     и 0,455; пол не известен — среднее.
 Всё округляется до шага мерки (см, у стопы — полсантиметра) и подставляется только в пустые с пометкой «≈ примерно»
 (ЗаписьМерокМоего ниже). Договор с ОценкаМерокПоФото (MyThingsBodyEstimate.swift): там — длины по фото, здесь — по
 таблицам.
 */

/// Пол фигуры для таблиц и силуэта; nil — не выбран (средняя фигура, средние доли роста).
enum ПолТелаМоего: String, CaseIterable, Sendable {
    case женский
    case мужской
}

/// Стандартное значение мерки для чипа панели: «M · 92», «EU 42 · 26,5», «L32 · 81».
struct СтандартМеркиМоего: Identifiable, Equatable {
    let подпись: String
    let значение: Double
    var id: String { подпись + "|" + String(значение) }
}

enum ТиповыеМеркиМоего {
    /// Типовой рост таблиц плеч: мужчины 176, женщины 164.
    private static let ростМужчин = 176.0
    private static let ростЖенщин = 164.0
    /// Плечи шире на 1 см на каждые 10 см роста сверх типового.
    private static let поправкаПлеч = 0.1

    /// Доли роста: ширина плеч, длина руки, длина ноги по шагу.
    private struct ДолиРоста {
        let плечи: Double
        let рукав: Double
        let шаг: Double
    }

    private static func доли(_ пол: ПолТелаМоего?) -> ДолиРоста {
        switch пол {
        case .some(.мужской): return ДолиРоста(плечи: 0.255, рукав: 0.355, шаг: 0.46)
        case .some(.женский): return ДолиРоста(плечи: 0.235, рукав: 0.345, шаг: 0.455)
        case .none: return ДолиРоста(плечи: 0.245, рукав: 0.35, шаг: 0.4575)
        }
    }

    // MARK: Договор

    /**
     Типичные мерки по размерам из «Мои размеры» и росту: мерка → значение (см) и откуда («M (46)», «EU 42», «W30»,
     «рост 176 см»). Пол — выбранный на экране, иначе по видам размеров. Чего по таблицам не узнать — того нет.
     */
    static func поРазмерам(_ размеры: [РазмерМоего], рост: Int?, пол: ПолТелаМоего?)
        -> [МеркаМоего: (значение: Double, откуда: String)] {
        let род = пол ?? полИз(размеры)
        var итог: [МеркаМоего: (значение: Double, откуда: String)] = [:]
        func положить(_ м: МеркаМоего, _ x: Double?, _ откуда: String) {
            guard let x, x.isFinite else { return }
            let круглое = округлить(м, x)
            guard м.пределы.contains(круглое) else { return }
            итог[м] = (круглое, откуда)
        }
        func найти(_ виды: [ВидРазмераМоего]) -> РазмерМоего? {
            for в in виды {
                if let р = размеры.first(where: { $0.вид == в }) { return р }
            }
            return nil
        }
        let мужчина = род == .мужской

        // Одежда: обхваты по таблице, плечи и бёдра мужчин — по добавленным таблицам мерок.
        if let р = найти(мужчина ? [.одеждаМ, .одеждаЖ] : [.одеждаЖ, .одеждаМ]), let выбор = р.выбор() {
            let т = р.вид.вкладка.основная
            let откуда = подпись(р)
            положить(.грудь, число(т, выбор.ряд, "Грудь, см"), откуда)
            положить(.талия, число(т, выбор.ряд, "Талия, см"), откуда)
            положить(.бёдра, число(т, выбор.ряд, "Бёдра, см"), откуда)
            let мужская = р.вид == .одеждаМ
            let доп = мужская ? ТаблицыРазмеровОдежды.меркиМужские : ТаблицыРазмеровОдежды.меркиЖенские
            if let н = рядПо(доп, "RU", ячейка(т, выбор.ряд, "RU")) {
                if итог[.бёдра] == nil { положить(.бёдра, число(доп, н, "Бёдра, см"), откуда) }
                положить(.плечи, плечи(число(доп, н, "Плечи, см"), рост: рост, мужские: мужская), откуда)
            }
        }
        // Бельё: под грудью + разница обхватов чашки.
        if let р = найти([.бельё]), let выбор = р.выбор(), let ряд2 = выбор.ряд2, let т2 = р.вид.вкладка.вторая,
           let под = число(р.вид.вкладка.основная, выбор.ряд, "Под грудью, см"),
           let разница = число(т2, ряд2, "Грудь минус под грудью, см") {
            положить(.грудь, под + разница, подпись(р))
        }
        // Джинсы: талия по W, шаг по L.
        if let р = найти(мужчина ? [.джинсыМ, .джинсыЖ] : [.джинсыЖ, .джинсыМ]), let выбор = р.выбор() {
            let т = р.вид.вкладка.основная
            let талия = число(т, выбор.ряд, "Талия, см") ?? число(т, выбор.ряд, "W").map { $0 * 2.54 }
            положить(.талия, талия, подпись(р))
            if let т2 = р.вид.вкладка.вторая, let ряд2 = выбор.ряд2 {
                положить(.шаг, число(т2, ряд2, "По внутреннему шву, см"), подпись(р))
            }
        }
        // Обувь: столбец «см».
        if let р = найти(мужчина ? [.обувьМ, .обувьЖ] : [.обувьЖ, .обувьМ]), let выбор = р.выбор() {
            положить(.стопа, число(р.вид.вкладка.основная, выбор.ряд, "CM"), подпись(р))
        }
        // Шапка: RU — обхват головы.
        if let р = найти([.шапка]), let выбор = р.выбор() {
            положить(.голова, число(р.вид.вкладка.основная, выбор.ряд, "RU"), подпись(р))
        }
        // Рост: длины пропорциями — то, чего не дали размеры.
        if let рост, ТелоМоего.пределыРоста.contains(рост) {
            let h = Double(рост)
            let д = доли(род)
            let откуда = String(format: МоёТелоText.т("mb_src_height"), String(рост))
            if итог[.плечи] == nil { положить(.плечи, h * д.плечи, откуда) }
            положить(.рукав, h * д.рукав, откуда)
            if итог[.шаг] == nil { положить(.шаг, h * д.шаг, откуда) }
        }
        return итог
    }

    // MARK: Пол и подписи

    /// Пол по видам размеров: одежда, джинсы, бельё, обувь — что встретится первым.
    static func полИз(_ размеры: [РазмерМоего]) -> ПолТелаМоего? {
        let порядок: [ВидРазмераМоего] = [.одеждаЖ, .одеждаМ, .джинсыЖ, .джинсыМ, .бельё, .обувьЖ, .обувьМ]
        for в in порядок where размеры.contains(where: { $0.вид == в }) {
            switch в {
            case .одеждаЖ, .джинсыЖ, .бельё, .обувьЖ: return .женский
            case .одеждаМ, .джинсыМ, .обувьМ: return .мужской
            case .кольцо, .шапка, .перчатки: continue
            }
        }
        return nil
    }

    /// «M (46)» у одежды (буква и RU), иначе — как на бирке: «EU 42», «W30 L32», «RU 57».
    static func подпись(_ р: РазмерМоего) -> String {
        guard р.вид == .одеждаЖ || р.вид == .одеждаМ, let выбор = р.выбор() else { return р.коротко }
        let т = р.вид.вкладка.основная
        let буква = ячейка(т, выбор.ряд, "INT")
        let ru = ячейка(т, выбор.ряд, "RU")
        guard !буква.isEmpty, !ru.isEmpty else { return р.коротко }
        return буква + " (" + ru + ")"
    }

    // MARK: Быстрый выбор размера

    /// Буквы быстрых чипов «Мой размер одежды» — весь столбец INT своей таблицы по порядку рядов (у женской XXS…5XL,
    /// у мужской XS…6XL): большим и маленьким размерам тоже в одно касание.
    static func буквы(_ пол: ПолТелаМоего) -> [String] {
        let т = (пол == .мужской ? ВидРазмераМоего.одеждаМ : ВидРазмераМоего.одеждаЖ).вкладка.основная
        guard let с = т.столбец("INT") else { return [] }
        return т.чипы(с).map { $0.значение }
    }

    /// Обувь EU целыми номерами: женская 36…42, мужская 39…46.
    static func быстраяОбувь(_ пол: ПолТелаМоего) -> [String] {
        let т = пол == .мужской ? ТаблицыРазмеровОдежды.обувьМужская : ТаблицыРазмеровОдежды.обувьЖенская
        let от: Double = пол == .мужской ? 39 : 36
        let до: Double = пол == .мужской ? 46 : 42
        guard let с = т.столбец("EU") else { return [] }
        var итог: [String] = []
        for н in т.ряды.indices {
            let з = т.значение(н, с)
            guard let x = ПравилаРазмераОдежды.число(з), x == x.rounded(), x >= от, x <= до, !итог.contains(з) else {
                continue
            }
            итог.append(з)
        }
        return итог
    }

    /// Привычная система быстрого выбора: буквы у одежды, EU у обуви, W у джинсов, своя система таблицы у остальных.
    static func системаБыстрая(_ вид: ВидРазмераМоего) -> String {
        let код: String
        switch вид {
        case .одеждаЖ, .одеждаМ: код = "INT"
        case .обувьЖ, .обувьМ: код = "EU"
        case .джинсыЖ, .джинсыМ: код = "W"
        case .бельё, .кольцо, .шапка, .перчатки: код = вид.вкладка.системаСайта
        }
        return вид.вкладка.система(код) != nil ? код : вид.вкладка.системаСайта
    }

    // MARK: Стандарты мерки — чипы панели

    /**
     Стандартные значения мерки по таблицам: обхваты и плечи — по буквам одежды своего пола (без пола — пусто), рука — по
     росту 150…200, шаг — по длине L джинсов, стопа — по номерам EU, голова — по шапкам.
     */
    static func стандарты(_ мерка: МеркаМоего, пол: ПолТелаМоего?, рост: Int?) -> [СтандартМеркиМоего] {
        var итог: [СтандартМеркиМоего] = []
        func добавить(_ подпись: String, _ x: Double?) {
            guard let x, x.isFinite else { return }
            let круглое = округлить(мерка, x)
            guard мерка.пределы.contains(круглое), !итог.contains(where: { $0.значение == круглое }) else { return }
            итог.append(СтандартМеркиМоего(подпись: подпись, значение: круглое))
        }
        switch мерка {
        case .грудь, .талия, .бёдра, .плечи:
            guard let пол else { return [] }
            let мужская = пол == .мужской
            let т = мужская ? ТаблицыРазмеровОдежды.одеждаМужская : ТаблицыРазмеровОдежды.одеждаЖенская
            let доп = мужская ? ТаблицыРазмеровОдежды.меркиМужские : ТаблицыРазмеровОдежды.меркиЖенские
            let код = кодМерки(мерка)
            for н in т.ряды.indices {
                let буква = ячейка(т, н, "INT")
                var x = число(т, н, код)
                if x == nil, let д = рядПо(доп, "RU", ячейка(т, н, "RU")) { x = число(доп, д, код) }
                if мерка == .плечи { x = плечи(x, рост: рост, мужские: мужская) }
                добавить(буква.isEmpty ? ячейка(т, н, "RU") : буква, x)
            }
        case .рукав:
            let д = доли(пол).рукав
            var роста = Array(stride(from: 150, through: 200, by: 5))
            if let рост, ТелоМоего.пределыРоста.contains(рост), !роста.contains(рост) {
                роста.append(рост)
                роста.sort()
            }
            for h in роста {
                добавить(String(format: МоёТелоText.т("mb_src_height"), String(h)), Double(h) * д)
            }
        case .шаг:
            let т = ТаблицыРазмеровОдежды.джинсыДлина
            for н in т.ряды.indices {
                добавить("L" + ячейка(т, н, "L"), число(т, н, "По внутреннему шву, см"))
            }
        case .стопа:
            let таблицы: [ТаблицаРазмеровОдежды]
            switch пол {
            case .some(.мужской): таблицы = [ТаблицыРазмеровОдежды.обувьМужская]
            case .some(.женский): таблицы = [ТаблицыРазмеровОдежды.обувьЖенская]
            case .none: таблицы = [ТаблицыРазмеровОдежды.обувьЖенская, ТаблицыРазмеровОдежды.обувьМужская]
            }
            for т in таблицы {
                for н in т.ряды.indices {
                    добавить("EU " + ячейка(т, н, "EU"), число(т, н, "CM"))
                }
            }
            итог.sort { $0.значение < $1.значение }
        case .голова:
            let т = ТаблицыРазмеровОдежды.шапки
            for н in т.ряды.indices {
                let буква = ячейка(т, н, "INT")
                добавить(буква.isEmpty ? "RU" : буква, число(т, н, "RU"))
            }
        }
        return итог
    }

    /// До `сколько` стандартов, ближайших к значению, — по возрастанию.
    static func ближайшие(_ все: [СтандартМеркиМоего], к x: Double, сколько: Int) -> [СтандартМеркиМоего] {
        let близкие = все.sorted { abs($0.значение - x) < abs($1.значение - x) }.prefix(max(0, сколько))
        return близкие.sorted { $0.значение < $1.значение }
    }

    // MARK: Таблицы

    static func округлить(_ м: МеркаМоего, _ x: Double) -> Double {
        (x / м.приращение).rounded() * м.приращение
    }

    private static func кодМерки(_ м: МеркаМоего) -> String {
        switch м {
        case .грудь: return "Грудь, см"
        case .талия: return "Талия, см"
        case .бёдра: return "Бёдра, см"
        case .плечи: return "Плечи, см"
        case .рукав, .шаг, .стопа, .голова: return ""
        }
    }

    /// Плечи таблицы с поправкой на свой рост.
    private static func плечи(_ x: Double?, рост: Int?, мужские: Bool) -> Double? {
        guard let x else { return nil }
        guard let рост, ТелоМоего.пределыРоста.contains(рост) else { return x }
        let типовой = мужские ? ростМужчин : ростЖенщин
        return x + (Double(рост) - типовой) * поправкаПлеч
    }

    private static func ячейка(_ т: ТаблицаРазмеровОдежды, _ ряд: Int, _ код: String) -> String {
        guard let с = т.столбец(код) else { return "" }
        return т.значение(ряд, с)
    }

    /// Число ячейки: «92», «63.5»; у диапазона «73–77» — середина.
    private static func число(_ т: ТаблицаРазмеровОдежды, _ ряд: Int, _ код: String) -> Double? {
        let з = ячейка(т, ряд, код)
        guard !з.isEmpty else { return nil }
        if let x = ПравилаРазмераОдежды.число(з) { return x }
        let ч = ПравилаРазмераОдежды.числа(з)
        guard let а = ч.first, let б = ч.last else { return nil }
        return (а + б) / 2
    }

    /// Ряд таблицы, где в столбце кода стоит значение (сравнение по ключу таблиц).
    private static func рядПо(_ т: ТаблицаРазмеровОдежды, _ код: String, _ значение: String) -> Int? {
        guard !значение.isEmpty, let с = т.столбец(код) else { return nil }
        let нужное = ПравилаРазмераОдежды.ключ(значение)
        return т.ряды.indices.first { ПравилаРазмераОдежды.ключ(т.значение($0, с)) == нужное }
    }
}

// MARK: - Запись мерок с пометкой «примерно»

/**
 Мерки — только через задатьМерку хранилища. Правка руками — значение без «≈» (пометку снимает сама модель: мерка стала
 другой). Подставленные по стандарту и по фото — с «≈» (ТелоМоего.ждётПометки на время одной записи). Введённое руками
 подстановки не трогают никогда.
 */
@MainActor
enum ЗаписьМерокМоего {
    /// Правка руками; nil — стереть.
    static func задать(_ мерка: МеркаМоего, _ x: Double?) {
        МоёХранилище.shared.задатьМерку(мерка, x.map { ТиповыеМеркиМоего.округлить(мерка, $0) })
    }

    /// Стандартное значение (чип панели) — с «≈». Мерка уже ровно такая (повторное касание выбранного чипа) — ничего:
    /// введённое руками не становится «≈», файл не переписывается.
    static func задатьПримерно(_ мерка: МеркаМоего, _ x: Double) {
        let круглое = ТиповыеМеркиМоего.округлить(мерка, x)
        guard мерка.пределы.contains(круглое) else { return }
        guard МоёХранилище.shared.запись.тело.мерка(мерка) != круглое else { return }
        ТелоМоего.ждётПометки = [мерка.rawValue: круглое]
        МоёХранилище.shared.задатьМерку(мерка, круглое)
        ТелоМоего.ждётПометки = [:]
    }

    /**
     Подставить «примерно»: в пустые мерки, а со `сменитьПримерные` — и поверх прежних «≈» (фото точнее таблицы, новый
     размер — старого; что именно менять, решает зовущий).
     Возвращает мерки, которые изменились.
     */
    @discardableResult
    static func подставить(_ значения: [МеркаМоего: Double], сменитьПримерные: Bool) -> [МеркаМоего] {
        var готово: [МеркаМоего] = []
        for мерка in МеркаМоего.allCases {
            guard let x = значения[мерка] else { continue }
            let круглое = ТиповыеМеркиМоего.округлить(мерка, x)
            guard мерка.пределы.contains(круглое) else { continue }
            let тело = МоёХранилище.shared.запись.тело
            if let было = тело.мерка(мерка) {
                guard сменитьПримерные, тело.примерная(мерка), было != круглое else { continue }
            }
            задатьПримерно(мерка, круглое)
            if МоёХранилище.shared.запись.тело.мерка(мерка) == круглое { готово.append(мерка) }
        }
        return готово
    }

    /// «Так и есть»: снять «≈», значение то же (стереть и записать заново — две записи).
    static func подтвердить(_ мерка: МеркаМоего) {
        let тело = МоёХранилище.shared.запись.тело
        guard let x = тело.мерка(мерка), тело.примерная(мерка) else { return }
        МоёХранилище.shared.задатьМерку(мерка, nil)
        МоёХранилище.shared.задатьМерку(мерка, x)
    }
}

// MARK: - Число мерки словами

enum ЧислоМеркиМоего {
    /// Форматтер на язык приложения: силуэт зовёт словами() для восьми зон на каждую перерисовку — один на язык, а не
    /// восемь новых. Только главная нить (зовут из View).
    private static var кэш: (язык: String, ф: MeasurementFormatter)? = nil

    /// «96 сантиметров» на языке приложения — для VoiceOver.
    static func словами(_ x: Double) -> String {
        let язык = ПримерочнаяText.язык
        let ф: MeasurementFormatter
        if let готовый = кэш, готовый.язык == язык {
            ф = готовый.ф
        } else {
            let новый = MeasurementFormatter()
            новый.locale = Locale(identifier: язык)
            новый.unitOptions = .providedUnit
            новый.unitStyle = .long
            новый.numberFormatter.maximumFractionDigits = 1
            кэш = (язык, новый)
            ф = новый
        }
        return ф.string(from: Measurement(value: x, unit: UnitLength.centimeters))
    }
}

// MARK: - Итог

/// Итог сверки объявления с «Моим». уровень nil — профиля нет или в нём не хватает нужного: приглашение заполнить.
struct ИтогСовместимостиМоего: Equatable {
    enum Профиль: Hashable, Sendable {
        case машина, телефон, ноутбук, размер, дом, компьютер
    }

    let профиль: Профиль
    let уровень: УровеньАвтоподбора?
    let заголовок: String
    let подпись: String
    /// Сверка по стандартам (дом, компьютер) целиком: пункты с причинами, деталь, с чем сверили; у прочих — nil.
    var стандарт: ИтогСверкиСтандарта? = nil

    /// Для отбора ленты: подходит как есть или с кольцами и проставками.
    var подходит: Bool { уровень.map { $0 <= .доработка } ?? false }

    /// Раздел «Моего», где профиль заполняют (у дома и компьютера — хаб; открывать — СовместимостьМоего.открыть).
    var цель: КабинетЦель { СовместимостьМоего.цель(профиль) }
}

// MARK: - Сверка

enum СовместимостьМоего {
    typealias Профиль = ИтогСовместимостиМоего.Профиль

    /// Шины и диски — как ПодборПримерки.разделыАвто (TryOnHub.swift; тот на главной нити, здесь — своя копия).
    static let разделыАвто: Set<String> = ["tires-wheels"]
    static let разделыЧехлов: Set<String> = ["phone-cases"]
    static let разделыАксессуаров: Set<String> = ["phone-accessories"]
    static let разделыСумок: Set<String> = ["handbags", "backpacks", "school-backpacks", "backpacks-camping"]
    static let разделыРазмеров: Set<String> = ["mens-clothing", "womens-clothing", "shoes", "hats", "rings", "belts-scarves"]
    /// Детских размеров в «Моём» нет: данные детей не собираем.
    static let разделыДетские: Set<String> = ["kids-clothing", "kids-shoes"]

    private static func т(_ ключ: String) -> String { МоёСверкаText.т(ключ) }

    // MARK: Раздел ленты

    /// Какой профиль сверяется в разделе ленты — для чипа «Для моего»; nil — в разделе сверять нечего.
    static func профиль(раздела раздел: String?) -> Профиль? {
        guard let раздел, !раздел.isEmpty else { return nil }
        if РазделыСайта.внутри(раздел, разделыАвто) { return .машина }
        if РазделыСайта.внутри(раздел, разделыЧехлов.union(разделыАксессуаров)) { return .телефон }
        if РазделыСайта.внутри(раздел, разделыДетские) { return nil }
        if РазделыСайта.внутри(раздел, разделыРазмеров) { return .размер }
        if РазделыСайта.внутри(раздел, разделыСумок) { return .ноутбук }
        if Config.стандарты && Config.мойДом && РазделыСайта.внутри(раздел, разделыДома) { return .дом }
        if Config.стандарты && Config.мойКомпьютер && РазделыСайта.внутри(раздел, разделыКомпьютера) { return .компьютер }
        return nil
    }

    /// Разделы, где сверяется «Мой дом»: постель, шторы, свет, мебель и крупная техника (дверь и лифт).
    static let разделыДома: Set<String> = ["bedding", "beds", "curtains", "lighting", "furniture", "fridges",
                                           "washing-machines", "dishwashers", "stoves", "air-conditioners"]
    /// Разделы, где сверяется «Мой компьютер»: комплектующие ПК.
    static let разделыКомпьютера: Set<String> = ["pc-components"]

    /// Профиль пуст — чип ленты ведёт заполнять его, а не отбирает пустоту.
    static func пусто(_ профиль: Профиль, моё: ЗаписьМоего) -> Bool {
        switch профиль {
        case .машина: return моё.главнаяМашина?.посадка.map { $0.пустая } ?? true
        case .телефон: return моё.телефон == nil
        case .ноутбук: return диагональНоутбука(моё) == nil
        case .размер: return моё.тело.размеры.isEmpty
        case .дом:
            let д = моё.дом
            return д.кровати.isEmpty && д.лампы.isEmpty && д.окна.isEmpty && д.экраны.isEmpty && д.проёмы.isEmpty
                && д.комнаты.allSatisfy { $0.высота == nil } && моё.экраны.isEmpty
        case .компьютер: return моё.компьютеры.isEmpty
        }
    }

    static func цель(_ профиль: Профиль) -> КабинетЦель {
        switch профиль {
        case .машина: return .мойГараж
        case .телефон, .ноутбук: return .моиУстройства
        case .размер: return .моиМерки
        case .дом, .компьютер: return .моё
        }
    }

    /// Открыть раздел «Моего», где профиль заполняют, поверх любого экрана.
    @MainActor
    static func открыть(_ профиль: Профиль) {
        switch профиль {
        case .дом: ОкноМоего.открыть(раздел: .дом)
        case .компьютер: ОкноМоего.открыть(раздел: .компьютер)
        default: ОкноМоего.открыть(цель(профиль))
        }
    }

    /// Отбор ленты «Для моего»: подходит как есть или с кольцами и проставками.
    static func подходит(_ товар: Listing, моё: ЗаписьМоего) -> Bool {
        оценить(товар, моё: моё)?.подходит ?? false
    }

    // MARK: Объявление

    /**
     Сверка объявления; nil — сверять нечего (не тот раздел или в объявлении нет нужного). Значения — сначала поля
     продавца (std, parts, плоские tyre_* и rim_*, size_all — ListingFitFields.swift), текст — запасной. Пачка 84: пришёл
     fit_match (лента POST с fit_*) — уровень не лучше сервера (сУровнемСервера).
     */
    static func оценить(_ товар: Listing, моё: ЗаписьМоего) -> ИтогСовместимостиМоего? {
        let наТелефоне: ИтогСовместимостиМоего? = оценитьНаТелефоне(товар, моё)
        guard let свой = наТелефоне, let сервер = товар.уровеньСервера else { return наТелефоне }
        return сУровнемСервера(свой, сервер)
    }

    private static func оценитьНаТелефоне(_ товар: Listing, _ моё: ЗаписьМоего) -> ИтогСовместимостиМоего? {
        if РазделыСайта.внутри(товар.категория, разделыАвто) { return машина(товар, моё) }
        if телефонный(товар) { return телефон(товар, моё) }
        if let итог = сумка(товар, моё) { return итог }
        if РазделыСайта.внутри(товар.категория, разделыДетские) { return nil }
        if let итог = стандарты(товар, моё) { return итог }
        return размер(товар, моё)
    }

    /**
     Уровень сервера (docs/SERVER_NEW_FOR_MINE.md §2.2): итог на телефоне — не лучше fit_match, в нём доверие к продавцу и
     полные поля объявления, которых телефон в ленте не видит. Свой хуже или равен — свой как есть; сервер хуже — его
     уровень с честным заголовком (нужная деталь — словами телефона). Приглашение и «не хватает данных» в «Моём» —
     своё: сервер про «Моё» знает только присланное.
     */
    private static func сУровнемСервера(_ свой: ИтогСовместимостиМоего,
                                        _ сервер: УровеньСервераОбъявления) -> ИтогСовместимостиМоего {
        guard let уровень = свой.уровень, уровень != .неизвестно,
              let его = сервер.уровень(профиля: свой.профиль), его > уровень else { return свой }
        let заголовок: String
        switch его {
        case .доработка: заголовок = СтандартыText.т("st_srv_adapt")
        case .неПодходит: заголовок = СтандартыText.т("st_srv_bad")
        case .подходит, .неизвестно, .проверить: заголовок = СтандартыText.т("st_srv_check")
        }
        let деталь: String? = его == .доработка ? (сервер.показДетали ?? свой.стандарт?.деталь) : nil
        var стандарт: ИтогСверкиСтандарта? = nil
        if let был = свой.стандарт {
            стандарт = ИтогСверкиСтандарта(семья: был.семья, уровень: его, заголовок: заголовок, почему: был.почему,
                                           пункты: был.пункты, деталь: деталь, куда: был.куда)
        }
        return ИтогСовместимостиМоего(профиль: свой.профиль, уровень: его, заголовок: заголовок, подпись: свой.подпись,
                                      стандарт: стандарт)
    }

    private static func приглашение(_ профиль: Профиль) -> ИтогСовместимостиМоего {
        let ключ: String
        switch профиль {
        case .машина: ключ = "mf_car_add"
        case .телефон: ключ = "mf_phone_add"
        case .ноутбук: ключ = "mf_laptop_add"
        case .размер: ключ = "mf_size_add"
        case .дом: return приглашениеСтандарта(.дом, "st_home_add")
        case .компьютер: return приглашениеСтандарта(.компьютер, "st_pc_add")
        }
        return ИтогСовместимостиМоего(профиль: профиль, уровень: nil, заголовок: т(ключ), подпись: т(ключ + "_sub"))
    }

    /// Приглашение по стандарту — один вопрос: «Укажите свою кровать», «Укажите цоколи ламп» (тексты StandardsText).
    private static func приглашениеСтандарта(_ профиль: Профиль, _ ключ: String) -> ИтогСовместимостиМоего {
        ИтогСовместимостиМоего(профиль: профиль, уровень: nil, заголовок: СтандартыText.т(ключ),
                               подпись: СтандартыText.т(ключ + "_sub"))
    }

    // MARK: Дом и компьютер — по стандартам

    /**
     Объявление со стандартами дома или компьютера: лучший итог сверки (СверкаСтандартов) — с причиной и с чем сверили
     («Спальня», «Мой ПК»). Нашлось что сверять, а в «Моём» нужного нет — приглашение с одним вопросом по семье. Семей
     нет — nil (дальше — одежда и обувь по строке размера).
     */
    private static func стандарты(_ товар: Listing, _ моё: ЗаписьМоего) -> ИтогСовместимостиМоего? {
        guard Config.стандарты else { return nil }
        let разбор = РазборСтандартов.разобрать(полный(товар))
        let проём = РазделыСайта.внутри(товар.категория, СверкаСтандартов.разделыПроёма)
            && ["dim_w", "dim_h", "dim_d"].allSatisfy { товар.габаритыПолей[$0] != nil }
        guard !разбор.пусто || проём else { return nil }
        let итоги = СверкаСтандартов.сверить(разбор, габариты: товар.габаритыПолей, раздел: товар.категория, моё: моё)
        if let лучший = итоги.first {
            let подпись = [лучший.почему, лучший.куда].compactMap { $0 }.filter { !$0.isEmpty }.joined(separator: " · ")
            return ИтогСовместимостиМоего(профиль: лучший.семья.группа == .пк ? .компьютер : .дом,
                                          уровень: лучший.уровень, заголовок: лучший.заголовок, подпись: подпись,
                                          стандарт: лучший)
        }
        // Сверить не с чем: один вопрос — по первой найденной семье.
        let н = разбор.набор
        let пк: [СемьяСтандарта] = [.память, .накопитель, .видеокарта, .блокПитания, .сокет, .формаПлаты]
        if Config.мойКомпьютер, пк.contains(where: { н.есть($0) }), моё.компьютеры.isEmpty {
            return приглашениеСтандарта(.компьютер, "st_pc_add")
        }
        guard Config.мойДом else { return nil }
        if н.есть(.спальноеМесто) || н.есть(.бельё) || разбор.кандидаты[.спальноеМесто] != nil {
            return моё.дом.кровати.contains(where: \.заполнена) ? nil : приглашениеСтандарта(.дом, "st_bed_add")
        }
        if н.есть(.цоколь) { return моё.дом.лампы.isEmpty ? приглашениеСтандарта(.дом, "st_lamp_add") : nil }
        if н.есть(.vesa) {
            return моё.дом.экраны.isEmpty && моё.экраны.isEmpty ? приглашениеСтандарта(.дом, "st_tv_add") : nil
        }
        if н.есть(.шторы) {
            let жалюзи = н[.шторы, КлючСтандарта.видШтор] == "blind"
            let нетДанных = жалюзи ? !моё.дом.окна.contains(where: \.заполнено) : моё.дом.потолок == nil
            return нетДанных ? приглашениеСтандарта(.дом, жалюзи ? "st_window_add" : "st_ceiling_add") : nil
        }
        if проём && моё.дом.путьВДом.isEmpty { return приглашениеСтандарта(.дом, "st_door_add") }
        return nil
    }

    /// В ленте характеристики обычно не приходят — для разбора годятся и пункты карточки (без образцов цвета).
    private static func полный(_ товар: Listing) -> Listing {
        guard товар.характеристики.isEmpty, !товар.характеристикиКарточки.isEmpty else { return товар }
        var т = товар
        т.характеристики = товар.характеристикиКарточки.filter { !$0.образец }
            .map { Listing.Характеристика(ключ: $0.ключ, значение: $0.значение) }
        return т
    }

    // MARK: Шины и диски

    private static func машина(_ товар: Listing, _ моё: ЗаписьМоего) -> ИтогСовместимостиМоего? {
        let разбор = РазборАвтоподбора.из(полный(товар))
        guard разбор.вид != nil else { return nil }
        guard let главная = моё.главнаяМашина else { return приглашение(.машина) }
        let подпись = МоёСверкаText.ф("mf_car_sub", главная.заголовок)
        guard let посадка = главная.посадка, !посадка.пустая else {
            return ИтогСовместимостиМоего(профиль: .машина, уровень: nil, заголовок: т("mf_car_need"), подпись: подпись)
        }
        let размер = разбор.шины.first
        let штатный = СверкаАвтоподбора.штатныйДля(размер, из: посадка.шины)
        guard let вердикт = СверкаАвтоподбора.вердикт(разбор: разбор, размер: размер, штатный: штатный, посадка: посадка)
        else { return nil }
        return ИтогСовместимостиМоего(профиль: .машина, уровень: вердикт.уровень, заголовок: вердикт.заголовок,
                                      подпись: подпись)
    }

    // MARK: Чехлы и стёкла

    /// Слова чехла и стекла в названии (нижний регистр, «ё» → «е»).
    private static let словаЧехла = ["чехол", "чехл", "стекл", "пленк", "бампер", "кейс", "накладк", "қап", "case",
                                     "glass", "protector", "cover"]

    private static func телефонный(_ товар: Listing) -> Bool {
        if РазделыСайта.внутри(товар.категория, разделыЧехлов) { return true }
        guard РазделыСайта.внутри(товар.категория, разделыАксессуаров) else { return false }
        let название = КаталогРазмеров.нормально(товар.title)
        return словаЧехла.contains { название.contains($0) }
    }

    private static func телефон(_ товар: Listing, _ моё: ЗаписьМоего) -> ИтогСовместимостиМоего {
        guard let мой = моё.телефон, !мой.модель.trimmingCharacters(in: .whitespaces).isEmpty else {
            return приглашение(.телефон)
        }
        if МодельВНазванииМоего.есть(мой.модель, в: товар.title) {
            return ИтогСовместимостиМоего(профиль: .телефон, уровень: .подходит, заголовок: т("mf_phone_ok"),
                                          подпись: МоёСверкаText.ф("mf_phone_sub", мой.модель))
        }
        return ИтогСовместимостиМоего(профиль: .телефон, уровень: .проверить, заголовок: т("mf_phone_check"),
                                      подпись: МоёСверкаText.ф("mf_phone_check_sub", мой.модель))
    }

    // MARK: Сумки для ноутбука

    private static let словаНоутбука = ["ноутбук", "laptop", "macbook", "notebook", "ультрабук"]
    private static let словаСумки = ["сумк", "рюкзак", "чехол", "чехл", "кейс", "портфел", "папк", "сөмке", "sleeve",
                                     "bag", "backpack", "case"]

    /// Самая большая диагональ моих ноутбуков; нет — nil.
    static func диагональНоутбука(_ моё: ЗаписьМоего) -> Double? {
        моё.ноутбуки.compactMap(\.диагональ).max()
    }

    private static func сумка(_ товар: Listing, _ моё: ЗаписьМоего) -> ИтогСовместимостиМоего? {
        let название = КаталогРазмеров.нормально(товар.title)
        guard !РазделыСайта.внутри(товар.категория, ["laptops"]),
              словаНоутбука.contains(where: { название.contains($0) }),
              словаСумки.contains(where: { название.contains($0) }),
              let дюймы = КаталогРазмеров.дюймы(название) else { return nil }
        guard let мой = диагональНоутбука(моё) else {
            /* «Ноутбука нет» — не зовём его указать. */
            return моё.нет.contains(ЗаписьМоего.нетНоутбука) ? nil : приглашение(.ноутбук)
        }
        let подпись = МоёСверкаText.ф("mf_laptop_sub", ЧислоМоего.дюймы(дюймы), ЧислоМоего.дюймы(мой))
        let влезет = дюймы + 0.15 >= мой
        return ИтогСовместимостиМоего(профиль: .ноутбук, уровень: влезет ? .подходит : .неПодходит,
                                      заголовок: т(влезет ? "mf_laptop_ok" : "mf_laptop_bad"), подпись: подпись)
    }

    // MARK: Одежда и обувь

    /// Лучший ряд строки размера: сначала таблицы раздела, не нашлось — все (как СтрокаРазмераВсехСистем.бирка).
    private static func лучший(_ строка: СтрокаРазмераВсехСистем, раздел: String?)
        -> (вкладка: ВкладкаРазмеровОдежды, выбор: ВыборРазмераОдежды)? {
        if let раздел, !раздел.isEmpty,
           let набор = НаборРазмеровОдежды.для(цепочки: НаборРазмеровОдежды.цепочка(раздел)),
           let найдено = строка.лучший(набор.вкладки) {
            return найдено
        }
        return строка.лучший(ТаблицыРазмеровОдежды.всеВкладки)
    }

    /**
     Размер объявления, по порядку (пачка 83: в ленте описание обрезано — desc_cut, — и по одной строке описания ряды
     «Подходит вам» одежды почти всегда были пусты): строка «Размер: …» описания (её пишет подача); size_all ленты или
     пункт «Размер» характеристик, если в нём все системы; поле продавца одним значением — storage (в системе size_sys,
     без неё — в системе сайта у таблицы раздела, docs/SERVER_SIZES.md §2.1), размеры в наличии магазина (size_avail),
     пункт «Размер».
     */
    private static func размер(_ товар: Listing, _ моё: ЗаписьМоего) -> ИтогСовместимостиМоего? {
        if let описание = товар.описание, !описание.isEmpty,
           let строка = СтрокаРазмераВсехСистем.из(описания: описание),
           let итог = размерПоСтроке(строка, товар, моё) {
            return итог
        }
        if let строка = строкаРазмераПолей(товар), let итог = размерПоСтроке(строка, товар, моё) { return итог }
        return размерПоПолю(товар, моё)
    }

    /// Подписи пункта размера в характеристиках сайта (ru, kk, en, ar) — начало подписи («Размер (EU)» тоже).
    private static let подписиРазмера: [String] = ["размер", "өлшем", "size", "المقاس"]

    /// Значение пункта «Размер» характеристик (в ленте — пункты карточки); нет — nil.
    private static func пунктРазмера(_ товар: Listing) -> String? {
        var пункты: [(String, String)] = []
        if товар.характеристики.isEmpty {
            for п in товар.характеристикиКарточки where !п.образец { пункты.append((п.ключ, п.значение)) }
        } else {
            for п in товар.характеристики { пункты.append((п.ключ, п.значение)) }
        }
        for пара in пункты {
            let подпись: String = пара.0.lowercased().trimmingCharacters(in: .whitespaces)
            guard подписиРазмера.contains(where: { (корень: String) -> Bool in подпись.hasPrefix(корень) }) else {
                continue
            }
            let значение: String = пара.1.trimmingCharacters(in: .whitespacesAndNewlines)
            if !значение.isEmpty { return значение }
        }
        return nil
    }

    /// Строка всех систем из полей: size_all, иначе пункт «Размер», если в нём несколько систем через «·» или «|».
    private static func строкаРазмераПолей(_ товар: Listing) -> СтрокаРазмераВсехСистем? {
        var кандидаты: [String] = []
        if !товар.строкаВсехСистем.isEmpty { кандидаты.append(товар.строкаВсехСистем) }
        if let пункт = пунктРазмера(товар), пункт.contains("·") || пункт.contains("|") { кандидаты.append(пункт) }
        let начало: String = ПравилаРазмераОдежды.начало
        for сырая in кандидаты {
            let своя: Bool = сырая.lowercased().hasPrefix(начало.lowercased())
            let строка: String = своя ? сырая : начало + " " + сырая
            if let разобрана = СтрокаРазмераВсехСистем.разобрать(строка) { return разобрана }
        }
        return nil
    }

    /**
     Один размер одной системы — поле продавца (storage, у магазина ещё size_avail) или пункт «Размер» одним значением.
     Система — size_sys, без неё — система сайта у таблицы раздела. Буквы INT однозначны. Число сверяется, только если
     система есть в моей таблице и это либо size_sys, либо моя таблица — та, что у раздела по умолчанию (иначе джинсы W32
     сравнились бы с RU 48 рубашки); сверить нельзя — «Сверьте размер с продавцом», а не «Не ваш размер».
     */
    private static func размерПоПолю(_ товар: Listing, _ моё: ЗаписьМоего) -> ИтогСовместимостиМоего? {
        guard let раздел = товар.категория, РазделыСайта.внутри(раздел, разделыРазмеров) else { return nil }
        var значения: [String] = []
        if let своё = товар.storageСтрокой?.trimmingCharacters(in: .whitespacesAndNewlines), !своё.isEmpty,
           своё.count <= 24 {
            значения.append(своё)
        }
        for есть in товар.размерыВНаличии where !значения.contains(есть) { значения.append(есть) }
        if значения.isEmpty, let пункт = пунктРазмера(товар), пункт.count <= 24 { значения.append(пункт) }
        guard !значения.isEmpty,
              let набор = НаборРазмеровОдежды.для(цепочки: НаборРазмеровОдежды.цепочка(раздел), название: товар.title)
        else { return nil }
        let главная: ВкладкаРазмеровОдежды? = набор.вкладка(набор.начальная)
        var порядок: [ВкладкаРазмеровОдежды] = []
        if let главная { порядок.append(главная) }
        for в in набор.вкладки where в.ключ != набор.начальная { порядок.append(в) }
        var мой: РазмерМоего? = nil
        var естьТаблица = false
        for в in порядок {
            let ключТаблицы: String = в.основная.ключ
            if ВидРазмераМоего.allCases.contains(where: { (вид: ВидРазмераМоего) -> Bool in
                вид.вкладка.основная.ключ == ключТаблицы
            }) {
                естьТаблица = true
            }
            if let найден = моё.тело.размеры.first(where: { (р: РазмерМоего) -> Bool in
                р.вид.вкладка.основная.ключ == ключТаблицы
            }) {
                мой = найден
                break
            }
        }
        /* Таблицы, которых в «Моём» нет (детские), — молчим. */
        guard let мой else { return естьТаблица ? приглашение(.размер) : nil }
        let вкладка: ВкладкаРазмеровОдежды = мой.вид.вкладка
        guard let мойВыбор = мой.выбор() else { return nil }
        let явная: Bool = !товар.системаРазмера.isEmpty
        let таблицаРаздела: Bool = главная?.основная.ключ == вкладка.основная.ключ
        let система: String = явная ? товар.системаРазмера : (главная?.системаСайта ?? вкладка.системаСайта)
        let столбец: СистемаРазмераОдежды? = вкладка.система(система)
        let сравнимо: Bool = столбец != nil && (явная || таблицаРаздела)
        let своиСайта: [String] = вкладка.кандидатыСайта(мойВыбор, сайт: система)
        let мои: Set<String> = Set(своиСайта.map { (з: String) -> String in ПравилаРазмераОдежды.ключ(з) })
        let буквыВсе: [ЧастьБиркиРазмера] = вкладка.части(мойВыбор).filter { (ч: ЧастьБиркиРазмера) -> Bool in
            ч.код.hasPrefix("INT")
        }
        let буквы: Set<String> = Set(буквыВсе.map { (ч: ЧастьБиркиРазмера) -> String in ПравилаРазмераОдежды.ключ(ч.значение) })
        var совпало = false
        var чужиеБуквы = false
        var чужоеЧисло: String? = nil
        /* «One size», «Free size», «OS» — размер не указан, а не чужой: такие куски мимо, итог — «Сверьте размер». */
        let универсальные: Set<String> = ["one", "size", "onesize", "one-size", "free", "freesize", "os", "uni",
                                          "unisize"]
        for значение in значения {
            let куски: [String] = ПравилаРазмераОдежды.ключ(значение)
                .split(whereSeparator: { (знак: Character) -> Bool in " /,;|".contains(знак) })
                .map { (кусок: Substring) -> String in String(кусок) }
            for кусок in куски where !кусок.isEmpty {
                if универсальные.contains(кусок) { continue }
                if (сравнимо && мои.contains(кусок)) || буквы.contains(кусок) {
                    совпало = true
                    break
                }
                let этоБуквы: Bool = кусок.count <= 4 && кусок.allSatisfy { (знак: Character) -> Bool in знак.isLetter }
                if этоБуквы {
                    чужиеБуквы = true
                } else if чужоеЧисло == nil {
                    чужоеЧисло = кусок
                }
            }
            if совпало { break }
        }
        let первое: String = значения.first ?? ""
        let числом: Bool = ПравилаРазмераОдежды.число(первое) != nil
        var показ: String = первое
        if числом {
            let код: String = РазмерыОдеждыText.система(система)
            показ = код + " " + первое
        }
        let подпись: String = МоёСверкаText.ф("mf_size_sub", показ, мой.коротко)
        if совпало {
            return ИтогСовместимостиМоего(профиль: .размер, уровень: .подходит, заголовок: т("mf_size_ok"), подпись: подпись)
        }
        if чужоеЧисло == nil && чужиеБуквы && !буквы.isEmpty {
            return ИтогСовместимостиМоего(профиль: .размер, уровень: .неПодходит, заголовок: т("mf_size_bad"),
                                          подпись: подпись)
        }
        if let число = чужоеЧисло, сравнимо, let с = столбец {
            let чипы: [ЧипРазмераОдежды] = вкладка.основная.чипы(с.первый)
            let ряд: Int? = чипы.first(where: { (чип: ЧипРазмераОдежды) -> Bool in
                ПравилаРазмераОдежды.ключ(чип.значение) == число
            })?.id
            if мой.вид.обувь, let ряд, abs(ряд - мойВыбор.ряд) == 1 {
                return ИтогСовместимостиМоего(профиль: .размер, уровень: .проверить, заголовок: т("mf_size_half"),
                                              подпись: подпись)
            }
            if ряд != nil {
                return ИтогСовместимостиМоего(профиль: .размер, уровень: .неПодходит, заголовок: т("mf_size_bad"),
                                              подпись: подпись)
            }
        }
        return ИтогСовместимостиМоего(профиль: .размер, уровень: .проверить, заголовок: НовинкиМоегоText.т("nm_size_ask"),
                                      подпись: подпись)
    }

    /// Строка всех систем против моего размера той же таблицы; показ — в моей системе. Таблицы, которых в «Моём» нет, —
    /// nil (молчим), моего размера этой таблицы нет — приглашение.
    private static func размерПоСтроке(_ строка: СтрокаРазмераВсехСистем, _ товар: Listing,
                                       _ моё: ЗаписьМоего) -> ИтогСовместимостиМоего? {
        guard let найдено = лучший(строка, раздел: товар.категория) else { return nil }
        let таблица = найдено.вкладка.основная.ключ
        let виды = ВидРазмераМоего.allCases.filter { $0.вкладка.основная.ключ == таблица }
        /* Таблицы, которых в «Моём» нет (детские), — молчим. */
        guard !виды.isEmpty else { return nil }
        guard let мой = моё.тело.размеры.first(where: { виды.contains($0.вид) }) else { return приглашение(.размер) }
        let вкладка = мой.вид.вкладка
        guard let мойВыбор = мой.выбор(), let с = вкладка.система(мой.система) else { return nil }
        /* Ряды одной таблицы (вкладки делят основную по ключу) — сравниваем значения в МОЕЙ системе: у обуви бывают
           два ряда с одним US. */
        let моё1 = ПравилаРазмераОдежды.ключ(вкладка.основная.значение(мойВыбор.ряд, с.первый))
        let его1 = ПравилаРазмераОдежды.ключ(вкладка.основная.значение(найдено.выбор.ряд, с.первый))
        guard !моё1.isEmpty, !его1.isEmpty else { return nil }
        let его = вкладка.бирка(найдено.выбор, система: мой.система).главная
        let подпись = МоёСверкаText.ф("mf_size_sub", его.isEmpty ? его1 : его, мой.коротко)
        let уровень: УровеньАвтоподбора
        let ключ: String
        if моё1 == его1 {
            if let второй = с.второй, let т2 = вкладка.вторая, let р1 = мойВыбор.ряд2, let р2 = найдено.выбор.ряд2,
               ПравилаРазмераОдежды.ключ(т2.значение(р1, второй)) != ПравилаРазмераОдежды.ключ(т2.значение(р2, второй)) {
                /* Длина L или чашка разные. */
                уровень = .проверить
                ключ = "mf_size_check"
            } else {
                уровень = .подходит
                ключ = "mf_size_ok"
            }
        } else if мой.вид.обувь && abs(мойВыбор.ряд - найдено.выбор.ряд) == 1 {
            уровень = .проверить
            ключ = "mf_size_half"
        } else {
            уровень = .неПодходит
            ключ = "mf_size_bad"
        }
        return ИтогСовместимостиМоего(профиль: .размер, уровень: уровень, заголовок: т(ключ), подпись: подпись)
    }
}

// MARK: - Модель телефона в названии

/**
 Модель телефона в названии — строго: «iPhone 15 Pro» не находится в «iPhone 15 Pro Max», «Galaxy S24» — в «S24 FE» и
 «S24+». Слова сверяются целиком, граница буквы и цифры — тоже граница («15pro» = «15 pro», «S24» = «s 24»); частые
 русские написания («айфон», «про», «макс») — как латиница. Марку впереди можно опустить («Чехол 15 Pro»), но не если
 перед моделью стоит чужая марка («Xiaomi 15 Pro»).
 */
enum МодельВНазванииМоего {
    /// Слово после модели, которое делает её другой.
    static let другие: Set<String> = ["pro", "max", "plus", "mini", "ultra", "lite", "fe", "e", "air", "neo", "edge",
                                     "prime", "s", "c", "r", "xr", "xs", "fold", "flip", "turbo", "power", "play", "go"]
    /// Марки и линейки: их можно опустить впереди моей модели, а чужая перед совпадением — другая модель.
    static let марки: Set<String> = ["iphone", "galaxy", "samsung", "xiaomi", "redmi", "poco", "realme", "honor",
                                    "huawei", "oppo", "vivo", "oneplus", "pixel", "google", "motorola", "moto", "nokia",
                                    "infinix", "tecno", "zte", "asus", "sony", "xperia", "mi", "spark", "camon", "nova",
                                    "mate", "nothing"]
    private static let синонимы: [String: String] = [
        "айфон": "iphone", "про": "pro", "макс": "max", "плюс": "plus", "мини": "mini", "ультра": "ultra",
        "самсунг": "samsung", "галакси": "galaxy", "редми": "redmi", "ксиоми": "xiaomi", "сяоми": "xiaomi",
        "хонор": "honor", "хуавей": "huawei", "поко": "poco", "пиксель": "pixel"
    ]

    /// Слова текста: нижний регистр, «+» — plus, граница буквы и цифры делит слово.
    static func слова(_ текст: String) -> [String] {
        let строка = текст.lowercased().replacingOccurrences(of: "ё", with: "е")
            .replacingOccurrences(of: "+", with: " plus ")
        var итог: [String] = []
        var слово = ""
        var цифра = false
        for знак in строка {
            guard знак.isLetter || знак.isNumber else {
                if !слово.isEmpty { итог.append(синонимы[слово] ?? слово) }
                слово = ""
                continue
            }
            if !слово.isEmpty && знак.isNumber != цифра {
                итог.append(синонимы[слово] ?? слово)
                слово = ""
            }
            слово.append(знак)
            цифра = знак.isNumber
        }
        if !слово.isEmpty { итог.append(синонимы[слово] ?? слово) }
        return итог
    }

    static func есть(_ модель: String, в название: String) -> Bool {
        let м = слова(модель)
        let н = слова(название)
        if найти(м, в: н, свои: м) { return true }
        var короче = м
        while короче.count > 2, let первое = короче.first, марки.contains(первое) {
            короче.removeFirst()
            if найти(короче, в: н, свои: м) { return true }
        }
        return false
    }

    private static func найти(_ м: [String], в н: [String], свои: [String]) -> Bool {
        guard !м.isEmpty, н.count >= м.count else { return false }
        for начало in 0...(н.count - м.count) where Array(н[начало..<(начало + м.count)]) == м {
            let конец = начало + м.count
            if конец < н.count, другие.contains(н[конец]) { continue }
            if начало > 0, марки.contains(н[начало - 1]), !свои.contains(н[начало - 1]) { continue }
            return true
        }
        return false
    }
}

// MARK: - Плашка на странице объявления

/**
 «Подходит моему» под ценой: значок уровня в кружке, итог, с чем сверили и «Проверили по описанию». Профиля нет —
 приглашение заполнить «Моё». Нажатие: шины и диски — окно «Подойдут ли?» с пунктами, остальное — нужный раздел
 «Моего» поверх страницы. Появляется плавно, «подходит» — печать подпрыгивает один раз (при «Уменьшении движения» и в
 лёгком режиме — без движения). Сверять нечего — ничего не занимает места.
 */
struct ПлашкаПодходитМоему: View {
    let товар: Listing
    @ObservedObject private var хранилище = МоёХранилище.shared
    @State private var итог: ИтогСовместимостиМоего? = nil
    @State private var прыжок = 0

    init(товар: Listing) {
        self.товар = товар
    }

    private func т(_ ключ: String) -> String { МоёСверкаText.т(ключ) }

    var body: some View {
        VStack(spacing: 0) {
            /* Полоса нулевой высоты: на ней живут onAppear и onChange, пока плашки ещё нет. */
            Color.clear
                .frame(height: 0)
                .accessibilityHidden(true)
            if let итог {
                плашка(итог)
                    .padding(.horizontal, 20)
                    .padding(.top, 14)
                    .transition(.opacity.combined(with: .move(edge: .top)))
            }
        }
        .animation(ДвижениеСайта.появление, value: итог)
        .onAppear {
            хранилище.подготовить()
            пересчитать()
        }
        .onChange(of: товар) { _, _ in пересчитать() }
        .onChange(of: хранилище.запись) { _, _ in пересчитать() }
    }

    private func пересчитать() {
        let новый = СовместимостьМоего.оценить(товар, моё: хранилище.запись)
        guard новый != итог else { return }
        let сталПодходит = новый?.уровень == .подходит && итог?.уровень != .подходит
        итог = новый
        if сталПодходит && !(ДвижениеСайта.тихо || РежимУстройства.shared.лёгкий) { прыжок += 1 }
    }

    private func значок(_ итог: ИтогСовместимостиМоего) -> String {
        if let уровень = итог.уровень { return уровень.значокИтога }
        switch итог.профиль {
        case .машина: return "car.side"
        case .телефон: return "iphone"
        case .ноутбук: return "laptopcomputer"
        case .размер: return "ruler"
        case .дом: return "house"
        case .компьютер: return "desktopcomputer"
        }
    }

    private func плашка(_ итог: ИтогСовместимостиМоего) -> some View {
        let форма = RoundedRectangle(cornerRadius: Theme.Радиус.md, style: .continuous)
        let краска = итог.уровень?.краска ?? Theme.акцент
        return Button { открыть(итог) } label: {
            HStack(spacing: 12) {
                Image(systemName: значок(итог))
                    .font(.system(size: 19, weight: .semibold))
                    .foregroundStyle(краска)
                    .frame(width: 40, height: 40)
                    .background(краска.opacity(0.12), in: Circle())
                    .symbolEffect(.bounce, value: прыжок)
                    .accessibilityHidden(true)
                тексты(итог)
                Spacer(minLength: 4)
                Image(systemName: "chevron.forward")
                    .font(.footnote.weight(.semibold))
                    .foregroundStyle(Theme.текстВторой)
                    .accessibilityHidden(true)
            }
            .padding(.horizontal, 14)
            .padding(.vertical, 12)
            .frame(maxWidth: .infinity, alignment: .leading)
            .background(Theme.поверхность, in: форма)
            .overlay { форма.strokeBorder(краска.opacity(0.35), lineWidth: 1) }
            .contentShape(форма)
        }
        .buttonStyle(НажатиеСайта())
        .accessibilityElement(children: .combine)
        .accessibilityHint(т("mf_open"))
    }

    private func тексты(_ итог: ИтогСовместимостиМоего) -> some View {
        VStack(alignment: .leading, spacing: 2) {
            Text(итог.заголовок)
                .font(.callout.weight(.bold))
                .foregroundStyle(Theme.текст)
                .fixedSize(horizontal: false, vertical: true)
            Text(итог.подпись)
                .font(.footnote)
                .foregroundStyle(Theme.текстВторой)
                .fixedSize(horizontal: false, vertical: true)
            // Стандарты: остальные пункты с причинами в цифрах — «✓ DDR4», «⚠ свободных слотов нет».
            if let стандарт = итог.стандарт, стандарт.пункты.count > 1 {
                ForEach(стандарт.пункты.filter { $0.текст != итог.подпись }.prefix(3)) { пункт in
                    Label {
                        Text(пункт.текст)
                            .fixedSize(horizontal: false, vertical: true)
                    } icon: {
                        Image(systemName: пункт.уровень.значок)
                            .foregroundStyle(пункт.уровень.краска)
                    }
                    .font(.caption)
                    .foregroundStyle(Theme.текстВторой)
                }
            }
            if итог.уровень != nil {
                Label(т("mf_by_desc"), systemImage: "text.magnifyingglass")
                    .font(.caption2)
                    .foregroundStyle(Theme.текстВторой)
                    .padding(.top, 2)
            }
        }
        .multilineTextAlignment(.leading)
    }

    private func открыть(_ итог: ИтогСовместимостиМоего) {
        ОткликСайта.выбор()
        /* Шины и диски с машиной в гараже — пункты сверки (там же ввести параметры колёс); иначе — заполнить «Моё». */
        if итог.профиль == .машина, хранилище.запись.главнаяМашина != nil, Config.автоПодбор {
            ОкноАвтоПодбора.открыть(товар: товар)
        } else {
            СовместимостьМоего.открыть(итог.профиль)
        }
    }
}

// MARK: - Чип ленты

/**
 «Для моего» в шапке ленты раздела шин и дисков, чехлов, сумок, одежды и обуви: отбирает загруженное по «Моему» (как
 уточнение этапа 18: «Уточнено по загруженным: N из M» над сеткой). Профиль раздела пуст — открывает его заполнить.
 Включён — залит, как выбранный раздел; снимок «Моего» берётся в момент включения.
 */
struct ЧипМоегоЛенты: View {
    let профиль: ИтогСовместимостиМоего.Профиль
    @ObservedObject var модель: FeedModel

    init(профиль: ИтогСовместимостиМоего.Профиль, модель: FeedModel) {
        self.профиль = профиль
        _модель = ObservedObject(wrappedValue: модель)
    }

    /// Чип в шапке ленты: рубильник «Моего» и раздел, где есть что сверять.
    static func профильРаздела(_ раздел: String) -> ИтогСовместимостиМоего.Профиль? {
        guard Config.моё else { return nil }
        return СовместимостьМоего.профиль(раздела: раздел)
    }

    private var включён: Bool { модель.уточнение.моё != nil }

    var body: some View {
        Button(action: нажать) {
            HStack(spacing: 6) {
                Image(systemName: включён ? "checkmark.seal.fill" : "checkmark.seal")
                    .font(.system(size: 14, weight: .semibold))
                    .contentTransition(.symbolEffect(.replace))
                Text(МоёСверкаText.т("mf_chip"))
                    .font(.system(size: 14, weight: .semibold))
                    .lineLimit(1)
            }
            .padding(.horizontal, 13).padding(.vertical, 8)
            .foregroundStyle(включён ? Color.white : Theme.green2)
            .background(включён ? Theme.green2 : Color(.secondarySystemGroupedBackground), in: Capsule())
            .animation(ДвижениеСайта.выбор, value: включён)
        }
        .buttonStyle(.plain)
        .accessibilityLabel(МоёСверкаText.т("mf_chip"))
        .accessibilityHint(МоёСверкаText.т("mf_chip_a11y"))
        .accessibilityAddTraits(включён ? .isSelected : [])
    }

    private func нажать() {
        ОткликСайта.выбор()
        guard !включён else {
            модель.уточнение.моё = nil
            return
        }
        let хранилище = МоёХранилище.shared
        хранилище.подготовить()
        if СовместимостьМоего.пусто(профиль, моё: хранилище.запись) {
            СовместимостьМоего.открыть(профиль)
        } else {
            модель.уточнение.моё = ОтборМоегоЛенты(моё: хранилище.запись)
        }
    }
}

/**
 Отбор «Для моего» с итогами по объявлениям: сетка ленты спрашивает отбор на каждом показе, а разбор объявления (образцы
 шин, дисков, размеров) не бесплатный — каждое объявление сверяется один раз. Новый снимок «Моего» — новый отбор (равны
 только один и тот же). Зовёт только модель ленты (FeedModel, главная нить).
 */
final class ОтборМоегоЛенты: Equatable {
    let моё: ЗаписьМоего
    private var итоги: [String: Bool] = [:]

    init(моё: ЗаписьМоего) {
        self.моё = моё
    }

    func подходит(_ товар: Listing) -> Bool {
        /* Номер, название и длина описания: догруженное описание или правка продавца — сверка заново. */
        let ключ = товар.id + "|" + товар.title + "|" + String(товар.описание?.count ?? 0) + "|"
            + String(товар.характеристики.count)
        if let есть = итоги[ключ] { return есть }
        let итог = СовместимостьМоего.подходит(товар, моё: моё)
        if итоги.count >= 3000 { итоги.removeAll(keepingCapacity: true) }
        итоги[ключ] = итог
        return итог
    }

    static func == (а: ОтборМоегоЛенты, б: ОтборМоегоЛенты) -> Bool { а === б }
}

// MARK: - Что искать для «Для вас»

/**
 Что искать по «Моему» (полка «Для вас» на главной, docs/STANDARDS.md §6.3): раздел ленты, запрос по стандарту
 («205/55 R16», «iPhone 15 Pro», «лампа E27», «DDR4 SO-DIMM») и причина для карточки («Для кровати 160×200»). Найденное
 сверяется на телефоне той же оценкой (СовместимостьМоего.оценить) — в полку идут только «подходит» и «нужна деталь».
 Приватность (§7, §9): раздел публичный — его ленту по новизне можно грузить как есть; запрос, собранный из «Моего», в
 сеть — только телом POST (как fit_*), не в адресе; пока сервер его в теле не принимает — грузить раздел без запроса и
 отбирать сверкой на телефоне. Причина — только на экране. Детского нет.
 */
struct ЗапросПодбораМоего: Hashable, Sendable {
    let профиль: ИтогСовместимостиМоего.Профиль
    /// Раздел ленты (category).
    let раздел: String
    /// Текст поиска; пусто — весь раздел, отбор — сверкой.
    let запрос: String
    /// «Для вашей Toyota Camry», «Лампы E27 — как у вас».
    let причина: String
}

enum ПодборМоего {
    private static func ф(_ ключ: String, _ аргумент: String) -> String {
        String(format: СтандартыText.т(ключ), аргумент)
    }

    /// Запросы по заполненному «Моему», самые полезные — первыми; не больше предела. Пустое «Моё» — пусто.
    static func запросы(_ моё: ЗаписьМоего, предел: Int = 10) -> [ЗапросПодбораМоего] {
        var итог: [ЗапросПодбораМоего] = []
        if let м = моё.главнаяМашина, let шина = м.посадка?.шины.first {
            итог.append(ЗапросПодбораМоего(профиль: .машина, раздел: "tires-wheels", запрос: шина.подпись,
                                           причина: ф("fy_car", м.заголовок)))
        }
        if let т = моё.телефон, !т.модель.isEmpty {
            итог.append(ЗапросПодбораМоего(профиль: .телефон, раздел: "phone-cases", запрос: т.модель,
                                           причина: ф("fy_phone", т.модель)))
        }
        if Config.мойДом { итог += дом(моё) }
        if Config.мойКомпьютер, let к = моё.главныйКомпьютер { итог += компьютер(к) }
        for размер in моё.тело.размеры.prefix(2) {
            guard let лента = раздел(размера: размер.вид) else { continue }
            итог.append(ЗапросПодбораМоего(профиль: .размер, раздел: лента, запрос: "",
                                           причина: ф("fy_size", размер.коротко)))
        }
        var видели = Set<String>()
        return Array(итог.filter { видели.insert($0.раздел + "|" + $0.запрос).inserted }.prefix(предел))
    }

    private static func дом(_ моё: ЗаписьМоего) -> [ЗапросПодбораМоего] {
        var итог: [ЗапросПодбораМоего] = []
        let д = моё.дом
        if let место = д.кровати.compactMap(\.место).first {
            let набор = НаборСтандартов(значения: [СемьяСтандарта.спальноеМесто.rawValue: [КлючСтандарта.размер: место]])
            let показ = КаталогСтандартов.показ(место)
            итог.append(ЗапросПодбораМоего(профиль: .дом, раздел: "bedding", запрос: место,
                                           причина: ф("fy_bed", показ)))
            итог.append(ЗапросПодбораМоего(профиль: .дом, раздел: "beds",
                                           запрос: РазборСтандартов.запрос(набор, .спальноеМесто),
                                           причина: ф("fy_mattress", показ)))
        }
        /* Частый цоколь — замыкание с явной сигнатурой и if вместо тернарника по кортежам (риск проверки типов в CI).
           Порядок прежний: больше ламп — выше, при равенстве — меньший по алфавиту. */
        let частыйЦоколь: (key: String, value: Int)? = д.цоколи.max {
            (а: (key: String, value: Int), б: (key: String, value: Int)) -> Bool in
            if а.value != б.value { return а.value < б.value }
            return а.key > б.key
        }
        if let цоколь = частыйЦоколь?.key {
            let набор = НаборСтандартов(значения: [СемьяСтандарта.цоколь.rawValue: [КлючСтандарта.цоколь: цоколь]])
            итог.append(ЗапросПодбораМоего(профиль: .дом, раздел: "lighting",
                                           запрос: РазборСтандартов.запрос(набор, .цоколь),
                                           причина: ф("fy_lamps", цоколь)))
        }
        /* Разбито на шаги с явными типами: две цепочки с замыканиями через ?? — риск «unable to type-check». */
        let своиШаблоны: [String] = д.экраны.compactMap { (экран: ЭкранНаСтенеМоего) -> String? in
            экран.шаблонДляСверки?.шаблон
        }
        let диагонали: [Double] = моё.экраны.compactMap { (у: УстройствоМоего) -> Double? in у.диагональ }
        let обычный: String? = диагонали.first.map { (x: Double) -> String in КаталогСтандартов.vesaОбычно(диагональ: x) }
        let шаблон: String? = своиШаблоны.first ?? обычный
        if let шаблон {
            let набор = НаборСтандартов(значения: [СемьяСтандарта.vesa.rawValue: [КлючСтандарта.шаблон: шаблон]])
            итог.append(ЗапросПодбораМоего(профиль: .дом, раздел: "tv-audio",
                                           запрос: РазборСтандартов.запрос(набор, .vesa),
                                           причина: ф("fy_tv", КаталогСтандартов.показ(шаблон))))
        }
        if let окно = д.окна.first(where: \.заполнено), let ш = окно.ширина, let в = окно.высота {
            итог.append(ЗапросПодбораМоего(профиль: .дом, раздел: "curtains", запрос: "",
                                           причина: ф("fy_window", String(ш) + "×" + String(в))))
        }
        return итог
    }

    private static func компьютер(_ к: КомпьютерМоего) -> [ЗапросПодбораМоего] {
        var итог: [ЗапросПодбораМоего] = []
        let имя = к.заголовок
        if !к.память.всяРаспаяна, let п = к.память.поколение, let форма = к.память.форма {
            let набор = НаборСтандартов(значения: [СемьяСтандарта.память.rawValue: [КлючСтандарта.поколение: п,
                                                                                    КлючСтандарта.форма: форма]])
            итог.append(ЗапросПодбораМоего(профиль: .компьютер, раздел: "ram",
                                           запрос: РазборСтандартов.запрос(набор, .память),
                                           причина: ф("fy_ram", имя)))
        }
        if let слот = к.слотыM2.first {
            итог.append(ЗапросПодбораМоего(профиль: .компьютер, раздел: "ssd-hdd",
                                           запрос: слот.протокол == "sata" ? "M.2 SATA" : "NVMe",
                                           причина: ф("fy_ssd", имя)))
        }
        if к.вид == .настольный, к.корпус.длинаКарты != nil || к.бп.ватт != nil {
            итог.append(ЗапросПодбораМоего(профиль: .компьютер, раздел: "gpu", запрос: "", причина: ф("fy_gpu", имя)))
        }
        return итог
    }

    /// Раздел ленты для вида размера; кольца, шапки, перчатки — без полки.
    private static func раздел(размера вид: ВидРазмераМоего) -> String? {
        switch вид {
        case .обувьЖ: return "womens-shoes"
        case .обувьМ: return "mens-shoes"
        case .одеждаЖ, .джинсыЖ, .бельё: return "womens-clothing"
        case .одеждаМ, .джинсыМ: return "mens-clothing"
        case .кольцо, .шапка, .перчатки: return nil
        }
    }
}

// MARK: - Итог

/// Итог сверки объявления с «Моим». уровень nil — профиля нет или в нём не хватает нужного: приглашение заполнить.
struct ИтогСовместимостиМоего: Equatable {
    enum Профиль: Equatable {
        case машина, телефон, ноутбук, размер
    }

    let профиль: Профиль
    let уровень: УровеньАвтоподбора?
    let заголовок: String
    let подпись: String

    /// Для отбора ленты: подходит как есть или с кольцами и проставками.
    var подходит: Bool { уровень.map { $0 <= .доработка } ?? false }

    /// Раздел «Моего», где профиль заполняют.
    var цель: КабинетЦель { СовместимостьМоего.цель(профиль) }
}

// MARK: - Сверка

enum СовместимостьМоего {
    typealias Профиль = ИтогСовместимостиМоего.Профиль

    /// Шины и диски — как ПодборПримерки.разделыАвто (TryOnHub.swift; тот на главной нити, здесь — своя копия).
    static let разделыАвто: Set<String> = ["tires-wheels"]
    static let разделыЧехлов: Set<String> = ["phone-cases"]
    static let разделыАксессуаров: Set<String> = ["phone-accessories"]
    static let разделыСумок: Set<String> = ["handbags", "backpacks", "school-backpacks", "backpacks-camping"]
    static let разделыРазмеров: Set<String> = ["mens-clothing", "womens-clothing", "shoes", "hats", "rings", "belts-scarves"]
    /// Детских размеров в «Моём» нет: данные детей не собираем.
    static let разделыДетские: Set<String> = ["kids-clothing", "kids-shoes"]

    private static func т(_ ключ: String) -> String { МоёСверкаText.т(ключ) }

    // MARK: Раздел ленты

    /// Какой профиль сверяется в разделе ленты — для чипа «Для моего»; nil — в разделе сверять нечего.
    static func профиль(раздела раздел: String?) -> Профиль? {
        guard let раздел, !раздел.isEmpty else { return nil }
        if РазделыСайта.внутри(раздел, разделыАвто) { return .машина }
        if РазделыСайта.внутри(раздел, разделыЧехлов.union(разделыАксессуаров)) { return .телефон }
        if РазделыСайта.внутри(раздел, разделыДетские) { return nil }
        if РазделыСайта.внутри(раздел, разделыРазмеров) { return .размер }
        if РазделыСайта.внутри(раздел, разделыСумок) { return .ноутбук }
        return nil
    }

    /// Профиль пуст — чип ленты ведёт заполнять его, а не отбирает пустоту.
    static func пусто(_ профиль: Профиль, моё: ЗаписьМоего) -> Bool {
        switch профиль {
        case .машина: return моё.главнаяМашина?.посадка.map { $0.пустая } ?? true
        case .телефон: return моё.телефон == nil
        case .ноутбук: return диагональНоутбука(моё) == nil
        case .размер: return моё.тело.размеры.isEmpty
        }
    }

    static func цель(_ профиль: Профиль) -> КабинетЦель {
        switch профиль {
        case .машина: return .мойГараж
        case .телефон, .ноутбук: return .моиУстройства
        case .размер: return .моиМерки
        }
    }

    /// Отбор ленты «Для моего»: подходит как есть или с кольцами и проставками.
    static func подходит(_ товар: Listing, моё: ЗаписьМоего) -> Bool {
        оценить(товар, моё: моё)?.подходит ?? false
    }

    // MARK: Объявление

    /// Сверка объявления; nil — сверять нечего (не тот раздел или в объявлении нет нужного).
    static func оценить(_ товар: Listing, моё: ЗаписьМоего) -> ИтогСовместимостиМоего? {
        if РазделыСайта.внутри(товар.категория, разделыАвто) { return машина(товар, моё) }
        if телефонный(товар) { return телефон(товар, моё) }
        if let итог = сумка(товар, моё) { return итог }
        if РазделыСайта.внутри(товар.категория, разделыДетские) { return nil }
        return размер(товар, моё)
    }

    private static func приглашение(_ профиль: Профиль) -> ИтогСовместимостиМоего {
        let ключ: String
        switch профиль {
        case .машина: ключ = "mf_car_add"
        case .телефон: ключ = "mf_phone_add"
        case .ноутбук: ключ = "mf_laptop_add"
        case .размер: ключ = "mf_size_add"
        }
        return ИтогСовместимостиМоего(профиль: профиль, уровень: nil, заголовок: т(ключ), подпись: т(ключ + "_sub"))
    }

    /// В ленте характеристики обычно не приходят — для разбора годятся и пункты карточки (без образцов цвета).
    private static func полный(_ товар: Listing) -> Listing {
        guard товар.характеристики.isEmpty, !товар.характеристикиКарточки.isEmpty else { return товар }
        var т = товар
        т.характеристики = товар.характеристикиКарточки.filter { !$0.образец }
            .map { Listing.Характеристика(ключ: $0.ключ, значение: $0.значение) }
        return т
    }

    // MARK: Шины и диски

    private static func машина(_ товар: Listing, _ моё: ЗаписьМоего) -> ИтогСовместимостиМоего? {
        let разбор = РазборАвтоподбора.из(полный(товар))
        guard разбор.вид != nil else { return nil }
        guard let главная = моё.главнаяМашина else { return приглашение(.машина) }
        let подпись = МоёСверкаText.ф("mf_car_sub", главная.заголовок)
        guard let посадка = главная.посадка, !посадка.пустая else {
            return ИтогСовместимостиМоего(профиль: .машина, уровень: nil, заголовок: т("mf_car_need"), подпись: подпись)
        }
        let размер = разбор.шины.first
        let штатный = СверкаАвтоподбора.штатныйДля(размер, из: посадка.шины)
        guard let вердикт = СверкаАвтоподбора.вердикт(разбор: разбор, размер: размер, штатный: штатный, посадка: посадка)
        else { return nil }
        return ИтогСовместимостиМоего(профиль: .машина, уровень: вердикт.уровень, заголовок: вердикт.заголовок,
                                      подпись: подпись)
    }

    // MARK: Чехлы и стёкла

    /// Слова чехла и стекла в названии (нижний регистр, «ё» → «е»).
    private static let словаЧехла = ["чехол", "чехл", "стекл", "пленк", "бампер", "кейс", "накладк", "қап", "case",
                                     "glass", "protector", "cover"]

    private static func телефонный(_ товар: Listing) -> Bool {
        if РазделыСайта.внутри(товар.категория, разделыЧехлов) { return true }
        guard РазделыСайта.внутри(товар.категория, разделыАксессуаров) else { return false }
        let название = КаталогРазмеров.нормально(товар.title)
        return словаЧехла.contains { название.contains($0) }
    }

    private static func телефон(_ товар: Listing, _ моё: ЗаписьМоего) -> ИтогСовместимостиМоего {
        guard let мой = моё.телефон, !мой.модель.trimmingCharacters(in: .whitespaces).isEmpty else {
            return приглашение(.телефон)
        }
        if МодельВНазванииМоего.есть(мой.модель, в: товар.title) {
            return ИтогСовместимостиМоего(профиль: .телефон, уровень: .подходит, заголовок: т("mf_phone_ok"),
                                          подпись: МоёСверкаText.ф("mf_phone_sub", мой.модель))
        }
        return ИтогСовместимостиМоего(профиль: .телефон, уровень: .проверить, заголовок: т("mf_phone_check"),
                                      подпись: МоёСверкаText.ф("mf_phone_check_sub", мой.модель))
    }

    // MARK: Сумки для ноутбука

    private static let словаНоутбука = ["ноутбук", "laptop", "macbook", "notebook", "ультрабук"]
    private static let словаСумки = ["сумк", "рюкзак", "чехол", "чехл", "кейс", "портфел", "папк", "сөмке", "sleeve",
                                     "bag", "backpack", "case"]

    /// Самая большая диагональ моих ноутбуков; нет — nil.
    static func диагональНоутбука(_ моё: ЗаписьМоего) -> Double? {
        моё.ноутбуки.compactMap(\.диагональ).max()
    }

    private static func сумка(_ товар: Listing, _ моё: ЗаписьМоего) -> ИтогСовместимостиМоего? {
        let название = КаталогРазмеров.нормально(товар.title)
        guard !РазделыСайта.внутри(товар.категория, ["laptops"]),
              словаНоутбука.contains(where: { название.contains($0) }),
              словаСумки.contains(where: { название.contains($0) }),
              let дюймы = КаталогРазмеров.дюймы(название) else { return nil }
        guard let мой = диагональНоутбука(моё) else {
            /* «Ноутбука нет» — не зовём его указать. */
            return моё.нет.contains(ЗаписьМоего.нетНоутбука) ? nil : приглашение(.ноутбук)
        }
        let подпись = МоёСверкаText.ф("mf_laptop_sub", ЧислоМоего.дюймы(дюймы), ЧислоМоего.дюймы(мой))
        let влезет = дюймы + 0.15 >= мой
        return ИтогСовместимостиМоего(профиль: .ноутбук, уровень: влезет ? .подходит : .неПодходит,
                                      заголовок: т(влезет ? "mf_laptop_ok" : "mf_laptop_bad"), подпись: подпись)
    }

    // MARK: Одежда и обувь

    /// Лучший ряд строки размера: сначала таблицы раздела, не нашлось — все (как СтрокаРазмераВсехСистем.бирка).
    private static func лучший(_ строка: СтрокаРазмераВсехСистем, раздел: String?)
        -> (вкладка: ВкладкаРазмеровОдежды, выбор: ВыборРазмераОдежды)? {
        if let раздел, !раздел.isEmpty,
           let набор = НаборРазмеровОдежды.для(цепочки: НаборРазмеровОдежды.цепочка(раздел)),
           let найдено = строка.лучший(набор.вкладки) {
            return найдено
        }
        return строка.лучший(ТаблицыРазмеровОдежды.всеВкладки)
    }

    private static func размер(_ товар: Listing, _ моё: ЗаписьМоего) -> ИтогСовместимостиМоего? {
        guard let описание = товар.описание, !описание.isEmpty,
              let строка = СтрокаРазмераВсехСистем.из(описания: описание),
              let найдено = лучший(строка, раздел: товар.категория) else { return nil }
        let таблица = найдено.вкладка.основная.ключ
        let виды = ВидРазмераМоего.allCases.filter { $0.вкладка.основная.ключ == таблица }
        /* Таблицы, которых в «Моём» нет (детские), — молчим. */
        guard !виды.isEmpty else { return nil }
        guard let мой = моё.тело.размеры.first(where: { виды.contains($0.вид) }) else { return приглашение(.размер) }
        let вкладка = мой.вид.вкладка
        guard let мойВыбор = мой.выбор(), let с = вкладка.система(мой.система) else { return nil }
        /* Ряды одной таблицы (вкладки делят основную по ключу) — сравниваем значения в МОЕЙ системе: у обуви бывают
           два ряда с одним US. */
        let моё1 = ПравилаРазмераОдежды.ключ(вкладка.основная.значение(мойВыбор.ряд, с.первый))
        let его1 = ПравилаРазмераОдежды.ключ(вкладка.основная.значение(найдено.выбор.ряд, с.первый))
        guard !моё1.isEmpty, !его1.isEmpty else { return nil }
        let его = вкладка.бирка(найдено.выбор, система: мой.система).главная
        let подпись = МоёСверкаText.ф("mf_size_sub", его.isEmpty ? его1 : его, мой.коротко)
        let уровень: УровеньАвтоподбора
        let ключ: String
        if моё1 == его1 {
            if let второй = с.второй, let т2 = вкладка.вторая, let р1 = мойВыбор.ряд2, let р2 = найдено.выбор.ряд2,
               ПравилаРазмераОдежды.ключ(т2.значение(р1, второй)) != ПравилаРазмераОдежды.ключ(т2.значение(р2, второй)) {
                /* Длина L или чашка разные. */
                уровень = .проверить
                ключ = "mf_size_check"
            } else {
                уровень = .подходит
                ключ = "mf_size_ok"
            }
        } else if мой.вид.обувь && abs(мойВыбор.ряд - найдено.выбор.ряд) == 1 {
            уровень = .проверить
            ключ = "mf_size_half"
        } else {
            уровень = .неПодходит
            ключ = "mf_size_bad"
        }
        return ИтогСовместимостиМоего(профиль: .размер, уровень: уровень, заголовок: т(ключ), подпись: подпись)
    }
}

// MARK: - Модель телефона в названии

/**
 Модель телефона в названии — строго: «iPhone 15 Pro» не находится в «iPhone 15 Pro Max», «Galaxy S24» — в «S24 FE» и
 «S24+». Слова сверяются целиком, граница буквы и цифры — тоже граница («15pro» = «15 pro», «S24» = «s 24»); частые
 русские написания («айфон», «про», «макс») — как латиница. Марку впереди можно опустить («Чехол 15 Pro»), но не если
 перед моделью стоит чужая марка («Xiaomi 15 Pro»).
 */
enum МодельВНазванииМоего {
    /// Слово после модели, которое делает её другой.
    static let другие: Set<String> = ["pro", "max", "plus", "mini", "ultra", "lite", "fe", "e", "air", "neo", "edge",
                                     "prime", "s", "c", "r", "xr", "xs", "fold", "flip", "turbo", "power", "play", "go"]
    /// Марки и линейки: их можно опустить впереди моей модели, а чужая перед совпадением — другая модель.
    static let марки: Set<String> = ["iphone", "galaxy", "samsung", "xiaomi", "redmi", "poco", "realme", "honor",
                                    "huawei", "oppo", "vivo", "oneplus", "pixel", "google", "motorola", "moto", "nokia",
                                    "infinix", "tecno", "zte", "asus", "sony", "xperia", "mi", "spark", "camon", "nova",
                                    "mate", "nothing"]
    private static let синонимы: [String: String] = [
        "айфон": "iphone", "про": "pro", "макс": "max", "плюс": "plus", "мини": "mini", "ультра": "ultra",
        "самсунг": "samsung", "галакси": "galaxy", "редми": "redmi", "ксиоми": "xiaomi", "сяоми": "xiaomi",
        "хонор": "honor", "хуавей": "huawei", "поко": "poco", "пиксель": "pixel"
    ]

    /// Слова текста: нижний регистр, «+» — plus, граница буквы и цифры делит слово.
    static func слова(_ текст: String) -> [String] {
        let строка = текст.lowercased().replacingOccurrences(of: "ё", with: "е")
            .replacingOccurrences(of: "+", with: " plus ")
        var итог: [String] = []
        var слово = ""
        var цифра = false
        for знак in строка {
            guard знак.isLetter || знак.isNumber else {
                if !слово.isEmpty { итог.append(синонимы[слово] ?? слово) }
                слово = ""
                continue
            }
            if !слово.isEmpty && знак.isNumber != цифра {
                итог.append(синонимы[слово] ?? слово)
                слово = ""
            }
            слово.append(знак)
            цифра = знак.isNumber
        }
        if !слово.isEmpty { итог.append(синонимы[слово] ?? слово) }
        return итог
    }

    static func есть(_ модель: String, в название: String) -> Bool {
        let м = слова(модель)
        let н = слова(название)
        if найти(м, в: н, свои: м) { return true }
        var короче = м
        while короче.count > 2, let первое = короче.first, марки.contains(первое) {
            короче.removeFirst()
            if найти(короче, в: н, свои: м) { return true }
        }
        return false
    }

    private static func найти(_ м: [String], в н: [String], свои: [String]) -> Bool {
        guard !м.isEmpty, н.count >= м.count else { return false }
        for начало in 0...(н.count - м.count) where Array(н[начало..<(начало + м.count)]) == м {
            let конец = начало + м.count
            if конец < н.count, другие.contains(н[конец]) { continue }
            if начало > 0, марки.contains(н[начало - 1]), !свои.contains(н[начало - 1]) { continue }
            return true
        }
        return false
    }
}

// MARK: - Плашка на странице объявления

/**
 «Подходит моему» под ценой: значок уровня в кружке, итог, с чем сверили и «Проверили по описанию». Профиля нет —
 приглашение заполнить «Моё». Нажатие: шины и диски — окно «Подойдут ли?» с пунктами, остальное — нужный раздел
 «Моего» поверх страницы. Появляется плавно, «подходит» — печать подпрыгивает один раз (при «Уменьшении движения» и в
 лёгком режиме — без движения). Сверять нечего — ничего не занимает места.
 */
struct ПлашкаПодходитМоему: View {
    let товар: Listing
    @ObservedObject private var хранилище = МоёХранилище.shared
    @State private var итог: ИтогСовместимостиМоего? = nil
    @State private var прыжок = 0

    init(товар: Listing) {
        self.товар = товар
    }

    private func т(_ ключ: String) -> String { МоёСверкаText.т(ключ) }

    var body: some View {
        VStack(spacing: 0) {
            /* Полоса нулевой высоты: на ней живут onAppear и onChange, пока плашки ещё нет. */
            Color.clear
                .frame(height: 0)
                .accessibilityHidden(true)
            if let итог {
                плашка(итог)
                    .padding(.horizontal, 20)
                    .padding(.top, 14)
                    .transition(.opacity.combined(with: .move(edge: .top)))
            }
        }
        .animation(ДвижениеСайта.появление, value: итог)
        .onAppear {
            хранилище.подготовить()
            пересчитать()
        }
        .onChange(of: товар) { _, _ in пересчитать() }
        .onChange(of: хранилище.запись) { _, _ in пересчитать() }
    }

    private func пересчитать() {
        let новый = СовместимостьМоего.оценить(товар, моё: хранилище.запись)
        guard новый != итог else { return }
        let сталПодходит = новый?.уровень == .подходит && итог?.уровень != .подходит
        итог = новый
        if сталПодходит && !(ДвижениеСайта.тихо || РежимУстройства.shared.лёгкий) { прыжок += 1 }
    }

    private func значок(_ итог: ИтогСовместимостиМоего) -> String {
        if let уровень = итог.уровень { return уровень.значокИтога }
        switch итог.профиль {
        case .машина: return "car.side"
        case .телефон: return "iphone"
        case .ноутбук: return "laptopcomputer"
        case .размер: return "ruler"
        }
    }

    private func плашка(_ итог: ИтогСовместимостиМоего) -> some View {
        let форма = RoundedRectangle(cornerRadius: Theme.Радиус.md, style: .continuous)
        let краска = итог.уровень?.краска ?? Theme.акцент
        return Button { открыть(итог) } label: {
            HStack(spacing: 12) {
                Image(systemName: значок(итог))
                    .font(.system(size: 19, weight: .semibold))
                    .foregroundStyle(краска)
                    .frame(width: 40, height: 40)
                    .background(краска.opacity(0.12), in: Circle())
                    .symbolEffect(.bounce, value: прыжок)
                    .accessibilityHidden(true)
                тексты(итог)
                Spacer(minLength: 4)
                Image(systemName: "chevron.forward")
                    .font(.footnote.weight(.semibold))
                    .foregroundStyle(Theme.текстВторой)
                    .accessibilityHidden(true)
            }
            .padding(.horizontal, 14)
            .padding(.vertical, 12)
            .frame(maxWidth: .infinity, alignment: .leading)
            .background(Theme.поверхность, in: форма)
            .overlay { форма.strokeBorder(краска.opacity(0.35), lineWidth: 1) }
            .contentShape(форма)
        }
        .buttonStyle(НажатиеСайта())
        .accessibilityElement(children: .combine)
        .accessibilityHint(т("mf_open"))
    }

    private func тексты(_ итог: ИтогСовместимостиМоего) -> some View {
        VStack(alignment: .leading, spacing: 2) {
            Text(итог.заголовок)
                .font(.callout.weight(.bold))
                .foregroundStyle(Theme.текст)
                .fixedSize(horizontal: false, vertical: true)
            Text(итог.подпись)
                .font(.footnote)
                .foregroundStyle(Theme.текстВторой)
                .fixedSize(horizontal: false, vertical: true)
            if итог.уровень != nil {
                Label(т("mf_by_desc"), systemImage: "text.magnifyingglass")
                    .font(.caption2)
                    .foregroundStyle(Theme.текстВторой)
                    .padding(.top, 2)
            }
        }
        .multilineTextAlignment(.leading)
    }

    private func открыть(_ итог: ИтогСовместимостиМоего) {
        ОткликСайта.выбор()
        /* Шины и диски с машиной в гараже — пункты сверки (там же ввести параметры колёс); иначе — заполнить «Моё». */
        if итог.профиль == .машина, хранилище.запись.главнаяМашина != nil, Config.автоПодбор {
            ОкноАвтоПодбора.открыть(товар: товар)
        } else {
            ОкноМоего.открыть(итог.цель)
        }
    }
}

// MARK: - Чип ленты

/**
 «Для моего» в шапке ленты раздела шин и дисков, чехлов, сумок, одежды и обуви: отбирает загруженное по «Моему» (как
 уточнение этапа 18: «Уточнено по загруженным: N из M» над сеткой). Профиль раздела пуст — открывает его заполнить.
 Включён — залит, как выбранный раздел; снимок «Моего» берётся в момент включения.
 */
struct ЧипМоегоЛенты: View {
    let профиль: ИтогСовместимостиМоего.Профиль
    @ObservedObject var модель: FeedModel

    init(профиль: ИтогСовместимостиМоего.Профиль, модель: FeedModel) {
        self.профиль = профиль
        _модель = ObservedObject(wrappedValue: модель)
    }

    /// Чип в шапке ленты: рубильник «Моего» и раздел, где есть что сверять.
    static func профильРаздела(_ раздел: String) -> ИтогСовместимостиМоего.Профиль? {
        guard Config.моё else { return nil }
        return СовместимостьМоего.профиль(раздела: раздел)
    }

    private var включён: Bool { модель.уточнение.моё != nil }

    var body: some View {
        Button(action: нажать) {
            HStack(spacing: 6) {
                Image(systemName: включён ? "checkmark.seal.fill" : "checkmark.seal")
                    .font(.system(size: 14, weight: .semibold))
                    .contentTransition(.symbolEffect(.replace))
                Text(МоёСверкаText.т("mf_chip"))
                    .font(.system(size: 14, weight: .semibold))
                    .lineLimit(1)
            }
            .padding(.horizontal, 13).padding(.vertical, 8)
            .foregroundStyle(включён ? Color.white : Theme.green2)
            .background(включён ? Theme.green2 : Color(.secondarySystemGroupedBackground), in: Capsule())
            .animation(ДвижениеСайта.выбор, value: включён)
        }
        .buttonStyle(.plain)
        .accessibilityLabel(МоёСверкаText.т("mf_chip"))
        .accessibilityHint(МоёСверкаText.т("mf_chip_a11y"))
        .accessibilityAddTraits(включён ? .isSelected : [])
    }

    private func нажать() {
        ОткликСайта.выбор()
        guard !включён else {
            модель.уточнение.моё = nil
            return
        }
        let хранилище = МоёХранилище.shared
        хранилище.подготовить()
        if СовместимостьМоего.пусто(профиль, моё: хранилище.запись) {
            ОкноМоего.открыть(СовместимостьМоего.цель(профиль))
        } else {
            модель.уточнение.моё = ОтборМоегоЛенты(моё: хранилище.запись)
        }
    }
}

/**
 Отбор «Для моего» с итогами по объявлениям: сетка ленты спрашивает отбор на каждом показе, а разбор объявления (образцы
 шин, дисков, размеров) не бесплатный — каждое объявление сверяется один раз. Новый снимок «Моего» — новый отбор (равны
 только один и тот же). Зовёт только модель ленты (FeedModel, главная нить).
 */
final class ОтборМоегоЛенты: Equatable {
    let моё: ЗаписьМоего
    private var итоги: [String: Bool] = [:]

    init(моё: ЗаписьМоего) {
        self.моё = моё
    }

    func подходит(_ товар: Listing) -> Bool {
        /* Номер, название и длина описания: догруженное описание или правка продавца — сверка заново. */
        let ключ = товар.id + "|" + товар.title + "|" + String(товар.описание?.count ?? 0) + "|"
            + String(товар.характеристики.count)
        if let есть = итоги[ключ] { return есть }
        let итог = СовместимостьМоего.подходит(товар, моё: моё)
        if итоги.count >= 3000 { итоги.removeAll(keepingCapacity: true) }
        итоги[ключ] = итог
        return итог
    }

    static func == (а: ОтборМоегоЛенты, б: ОтборМоегоЛенты) -> Bool { а === б }
}

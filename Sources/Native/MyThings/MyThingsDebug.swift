import Foundation

#if DEBUG
/**
 «МОЁ» ДЛЯ СНИМКОВ CI (только отладочная сборка; ios-check.yml, шаг «Снять экраны»). Аргументы запуска — UserDefaults
 читает их сам, как -klikoSheet и -klikoOpen (App/SceneDelegate.swift):
   · -klikoMy <дом|компьютер|гардероб> (или home, pc, wardrobe) — через 2 с после запуска «Моё» открывается окном поверх
     сразу на этом разделе (ОкноМоего.открыть(раздел:));
   · -klikoMyDemo YES — демонстрационное «Моё» только в памяти (МоёХранилище.подставитьВПамяти: файл не пишется, сети
     нет): кровать 160×200, окно 130×140, ТВ 55″ с VESA 300×300, лампы E27 ×4 и три вещи гардероба (M и EU 42, у
     кроссовок — бренд). Заполненное не трогается — добавляется только то, чего нет. Ряды «Подходит вам» и полка «Для
     вас» на главной грузятся как обычно — первой страницей разделов ленты.
 Метки для журнала CI — ДымоваяПроверка: «my-demo» и «my-open».
 */
@MainActor
enum ОтладкаМоего {
    static func запуск() {
        let аргументы = UserDefaults.standard
        let демо: Bool = аргументы.bool(forKey: "klikoMyDemo")
        let строка: String = аргументы.string(forKey: "klikoMy") ?? ""
        let раздел: ЦельМоего? = разделПоАргументу(строка)
        guard демо || раздел != nil else { return }
        Task { @MainActor in
            if демо {
                try? await Task.sleep(nanoseconds: 800_000_000)
                заполнить()
            }
            guard let цель = раздел else { return }
            try? await Task.sleep(nanoseconds: демо ? 1_200_000_000 : 2_000_000_000)
            ОкноМоего.открыть(раздел: цель)
            ДымоваяПроверка.отметить("my-open")
        }
    }

    private static func разделПоАргументу(_ строка: String) -> ЦельМоего? {
        let слово: String = строка.lowercased().trimmingCharacters(in: .whitespacesAndNewlines)
        switch слово {
        case "дом", "home": return .дом
        case "компьютер", "pc", "computer": return .компьютер
        case "гардероб", "wardrobe": return .гардероб
        default: return nil
        }
    }

    /// Демонстрационное «Моё» — только в памяти, к тому, что уже есть.
    static func заполнить() {
        let вещи: [ВещьГардеробаМоего] = вещиДемо()
        let кровать = КроватьМоего(место: "160x200")
        let окно = ОкноДомаМоего(ширина: 130, высота: 140, створок: 2)
        let экран = ЭкранНаСтенеМоего(диагональ: 55, vesa: "300x300")
        let лампы = ЛампыМоего(цоколь: "E27", сколько: 4)
        МоёХранилище.shared.подставитьВПамяти { з in
            if !з.дом.кровати.contains(where: \.заполнена) { з.дом.кровати.append(кровать) }
            if !з.дом.окна.contains(where: \.заполнено) { з.дом.окна.append(окно) }
            if з.дом.экраны.isEmpty { з.дом.экраны.append(экран) }
            if з.дом.лампы.isEmpty { з.дом.лампы.append(лампы) }
            if з.гардероб.вещи.isEmpty { з.гардероб.вещи = вещи }
        }
        ДымоваяПроверка.отметить("my-demo")
    }

    private static func вещиДемо() -> [ВещьГардеробаМоего] {
        let одежда = РазмерМоего(вид: .одеждаМ, система: "INT", значение: "M")
        let обувь = РазмерМоего(вид: .обувьМ, система: "EU", значение: "42")
        let футболка = ВещьГардеробаМоего(вид: .футболка, цвета: [.белый], размер: одежда)
        let худи = ВещьГардеробаМоего(вид: .худи, цвета: [.тёмноСиний], размер: одежда)
        let кроссовки = ВещьГардеробаМоего(вид: .кроссовки, цвета: [.чёрный], размер: обувь, бренд: "Nike")
        return [футболка, худи, кроссовки]
    }
}
#endif

    // MARK: - Компьютер целиком

    /// Слова вида в начале модели ноутбука из названия сделки («Ноутбук ASUS X515» → «ASUS X515»).
    private static let словаНоутбука: Set<String> = ["ноутбук", "laptop", "notebook", "ноутбуктер"]

    /// Линейки ноутбуков → марка (когда марки в модели нет): «MacBook Air» → Apple, «VivoBook» → Asus.
    private static let линейкиНоутбуков: [(String, String)] = [
        ("macbook", "Apple"), ("thinkpad", "Lenovo"), ("ideapad", "Lenovo"), ("legion", "Lenovo"), ("yoga", "Lenovo"),
        ("vivobook", "Asus"), ("zenbook", "Asus"), ("rog", "Asus"), ("tuf", "Asus"), ("pavilion", "HP"),
        ("elitebook", "HP"), ("probook", "HP"), ("omen", "HP"), ("victus", "HP"), ("envy", "HP"), ("inspiron", "Dell"),
        ("latitude", "Dell"), ("vostro", "Dell"), ("xps", "Dell"), ("alienware", "Dell"), ("aspire", "Acer"),
        ("nitro", "Acer"), ("predator", "Acer"), ("swift", "Acer"), ("matebook", "Huawei"), ("magicbook", "Honor"),
        ("surface", "Microsoft"), ("redmibook", "Xiaomi"), ("galaxy book", "Samsung")
    ]

    /**
     Ноутбук или ПК целиком. устройство — связанное с ним «Моё устройство» (диагональ, габариты ноутбука). Своё название
     компьютера не уходит; у ПК модель — это модель платы: в название не идёт, только строкой «Материнская плата».
     */
    static func компьютер(_ к: КомпьютерМоего, устройство у: УстройствоМоего?) -> ЗаготовкаПодачи {
        let ноутбук: Bool = к.вид == .ноутбук
        let модель: String = ноутбук ? модельНоутбука(к.модель) : ""
        let цп = процессорСМаркой(к.процессор)
        let карта = к.видеокарта
        let чип: String = (карта.встроенная ? "" : карта.чип ?? "").trimmingCharacters(in: .whitespaces)
        let накопитель: НакопительМоего? = к.накопители.first
        var спец: [String] = []
        /* Процессор — в название ПК и ноутбука без модели («Ноутбук Intel Core i5-1135G7, 8 ГБ, SSD 512 ГБ»). */
        if (!ноутбук || модель.isEmpty) && !цп.полное.isEmpty { спец.append(цп.полное) }
        if !ноутбук && !чип.isEmpty { спец.append(чип) }
        if let всего = к.память.всего { спец.append(гб(всего)) }
        if let н = накопитель, let тб = н.тб { спец.append((н.hdd ? "HDD " : "SSD ") + объём(тб)) }
        let голова: String = ноутбук ? склеить([т("msl_laptop_plain"), модель]) : т("msl_desktop_plain")
        let связка: String = ноутбук && !модель.isEmpty ? ", " : " "
        let полное: String = спец.isEmpty ? голова : голова + связка + спец.joined(separator: ", ")
        var з = ЗаготовкаПодачи(название: название(полное), раздел: ноутбук ? "laptops" : "desktops")
        з.бренд = ноутбук ? маркаНоутбука(модель) : ""
        з.характеристики = слотыКомпьютера(к, цп: цп.полное, чип: чип)
        з.стандарты = стандартыКомпьютера(к, устройство: у)
        if ноутбук, let у { положитьУстройство(у, в: &з) }
        з.источник = связь(к.покупка)
        з.описание = ЗаготовкаПодачи.описаниеИзМоего(фактыКомпьютера(к, что: голова, цп: цп.полное, чип: чип,
                                                                       устройство: ноутбук ? у : nil))
        return з
    }

    /// Модель ноутбука без слова вида впереди («Ноутбук ASUS X515» → «ASUS X515»).
    private static func модельНоутбука(_ модель: String) -> String {
        var слова: [Substring] = модель.trimmingCharacters(in: .whitespacesAndNewlines).split(separator: " ")
        while let первое = слова.first, словаНоутбука.contains(первое.lowercased()) { слова.removeFirst() }
        return слова.joined(separator: " ")
    }

    /// Марка ноутбука по линейке («MacBook» → Apple); марку словом в модели («ASUS X515») мастер найдёт сам по списку
    /// марок раздела — тогда пусто.
    private static func маркаНоутбука(_ модель: String) -> String {
        let н: String = модель.lowercased()
        guard !н.isEmpty else { return "" }
        let слова: Set<String> = Set(н.split(whereSeparator: { !$0.isLetter && !$0.isNumber }).map { String($0) })
        for (линейка, марка) in линейкиНоутбуков {
            let есть: Bool = линейка.contains(" ") ? н.contains(линейка) : слова.contains(линейка)
            guard есть else { continue }
            return слова.contains(марка.lowercased()) ? "" : марка
        }
        return ""
    }

    /// Слоты ноутбука и ПК (у компьютеров k и есть колонка): процессор, видеокарта, ОЗУ, накопитель — вариантами сайта.
    private static func слотыКомпьютера(_ к: КомпьютерМоего, цп: String, чип: String) -> [String: String] {
        var смысл: [String: String] = [:]
        if !цп.isEmpty { смысл["cpu"] = цп }
        if к.видеокарта.встроенная {
            смысл["gpu"] = "Встроенная"
        } else if let линейка = видеокартаКомпьютера(чип), !чип.isEmpty {
            смысл["gpu"] = линейка
        }
        if let всего = к.память.всего { смысл["ram"] = String(всего) }
        if let тб = к.накопители.first?.тб { смысл["storage"] = объёмКаталога(тб) }
        return слоты(к.вид == .ноутбук ? "laptops" : "desktops", смысл)
    }

    /// std компьютера — только семьи, которые каталог держит у раздела: ram_module (оба), m2_ssd и screen_diag
    /// (ноутбук), cpu_socket, gpu_card, psu (ПК).
    private static func стандартыКомпьютера(_ к: КомпьютерМоего, устройство у: УстройствоМоего?) -> НаборСтандартов? {
        var набор = НаборСтандартов()
        let м = к.память
        набор[.память, К.поколение] = м.поколение
        набор[.память, К.форма] = м.форма
        набор[.память, К.частота] = м.частота.map { String($0) }
        if к.вид == .ноутбук {
            if let н = к.накопители.first, !н.hdd {
                набор[.накопитель, К.форма] = н.форма
                набор[.накопитель, К.протокол] = протоколКаталога(н)
                набор[.накопитель, К.тб] = н.тб.map { ЧислаАвтоподбора.ч($0, знаков: 3) }
            }
            набор[.диагональ, К.диагональ] = у?.диагональ.map { ЧислаАвтоподбора.ч($0) }
        } else {
            набор[.сокет, К.сокет] = к.сокет.flatMap { $0 == "BGA" ? nil : $0 }
            let имя: String = к.процессор.trimmingCharacters(in: .whitespacesAndNewlines)
            набор[.сокет, К.процессор] = имя.isEmpty ? nil : имя
            let карта = к.видеокарта
            if !карта.встроенная {
                набор[.видеокарта, К.чип] = карта.чип
                набор[.видеокарта, К.памятьКарты] = карта.памятьГБ.map { String($0) }
            }
            набор[.блокПитания, К.ватт] = к.бп.ватт.map { String($0) }
            набор[.блокПитания, К.сертификат] = к.бп.сертификат
        }
        return набор.пусто ? nil : набор
    }

    /// Строки описания компьютера: процессор, память, накопитель, видеокарта, диагональ, плата и блок питания (ПК).
    private static func фактыКомпьютера(_ к: КомпьютерМоего, что: String, цп: String, чип: String,
                                        устройство у: УстройствоМоего?) -> ФактыОписанияЗаготовки {
        var ф = ФактыОписанияЗаготовки(что: что)
        ф.добавить(д("prf_l_cpu"), цп)
        let м = к.память
        if let всего = м.всего {
            var память: String = гб(всего)
            if let п = м.поколение { память += " " + п }
            if м.всяРаспаяна { память += " (" + д("prf_v_soldered") + ")" }
            ф.добавить(д("prf_l_ram"), память)
        }
        if let н = к.накопители.first {
            var диск: String = н.hdd ? "HDD" : "SSD"
            if н.форма.hasPrefix("22") { диск += " M.2 " + н.форма }
            if !н.hdd, let пр = н.протокол, пр == "nvme" || пр == "sata" { диск += " " + ФорматКомпьютераМоего.протокол(пр) }
            if let тб = н.тб { диск += " " + объём(тб) }
            ф.добавить(д("prf_l_storage"), диск)
        }
        if к.видеокарта.встроенная {
            ф.добавить(д("prf_l_gpu"), д("prf_v_igpu"))
        } else if !чип.isEmpty {
            let память: String = к.видеокарта.памятьГБ.map { ", " + гб($0) } ?? ""
            ф.добавить(д("prf_l_gpu"), чип + память)
        }
        ф.добавить(д("prf_l_diag"), у?.диагональ.map { ЧислоМоего.дюймы($0) })
        if к.вид == .настольный {
            ф.добавить(д("prf_l_board"), к.модель.trimmingCharacters(in: .whitespacesAndNewlines))
            if let сокет = к.сокет, сокет != "BGA" { ф.добавить(д("prf_l_socket"), сокет) }
            if let ватт = к.бп.ватт {
                let сертификат: String = к.бп.сертификат.map { " " + $0 } ?? ""
                ф.добавить(д("prf_l_psu"), String(ватт) + " " + д("prf_u_w") + сертификат)
            }
        }
        ф.изСделкиKliko = к.покупка != nil
        return ф
    }

    /// Диагональ и габариты устройства — в заготовку (габариты образца — «примерно»).
    private static func положитьУстройство(_ у: УстройствоМоего, в з: inout ЗаготовкаПодачи) {
        з.диагональ = у.диагональ
        guard let см = у.см, см.count == 3 else { return }
        з.ширина = см[0]
        з.высота = см[1]
        з.глубина = см[2]
        з.габаритыПримерно = у.образец
    }

    // MARK: - Устройства

    /**
     Телефон «Моих устройств»: модель — название, марка по линейке, диагональ (std screen_diag; определена по железу или
     коду модели — «model», выбрана своя — как введённое продавцом). Ни IMEI, ни объёма памяти: их «Моё» не знает.
     */
    static func телефон(_ т: ТелефонМоего) -> ЗаготовкаПодачи {
        let модель: String = т.модель.trimmingCharacters(in: .whitespacesAndNewlines)
        var з = ЗаготовкаПодачи(название: название(модель), раздел: "smartphones")
        з.бренд = маркаТелефона(модель, код: т.код)
        з.диагональ = т.диагональ
        if let д = т.диагональ {
            let изКаталога: Bool = т.сам || !т.код.isEmpty
            з.стандарты = НаборСтандартов(значения: [СемьяСтандарта.диагональ.rawValue: [К.диагональ: ЧислаАвтоподбора.ч(д)]],
                                          источник: изКаталога ? .модель : .продавец)
        }
        var ф = ФактыОписанияЗаготовки(что: ТекстОписанияЗаготовки.ф("prf_d_phone", модель))
        ф.добавить(д("prf_l_diag"), т.диагональ.map { ЧислоМоего.дюймы($0) })
        з.описание = ЗаготовкаПодачи.описаниеИзМоего(ф)
        return з
    }

    /// Марка телефона по линейке: iPhone — Apple, Galaxy — Samsung, Pixel — Google; иначе пусто (мастер найдёт марку
    /// словом в названии по списку раздела).
    private static func маркаТелефона(_ модель: String, код: String) -> String {
        let н: String = модель.lowercased()
        if код.hasPrefix("iPhone") || н.hasPrefix("iphone") { return "Apple" }
        if н.contains("galaxy") && !н.contains("samsung") { return "Samsung" }
        if н.contains("pixel") && !н.contains("google") { return "Google" }
        return ""
    }

    /// Ноутбук, монитор или телевизор «Моих устройств»: вид и модель, диагональ (слот раздела и std), габариты.
    static func устройство(_ у: УстройствоМоего) -> ЗаготовкаПодачи {
        let раздел: String
        switch у.вид {
        case .ноутбук: раздел = "laptops"
        case .монитор: раздел = "monitors"
        case .тв: раздел = "tv"
        }
        let модель: String = у.вид == .ноутбук ? модельНоутбука(у.модель) : у.модель
        var голова: String = склеить([у.вид.название, модель])
        if let диагональ = у.диагональ {
            let дюймы: String = ЧислоМоего.дюймы(диагональ)
            if !голова.contains(дюймы) { голова += (модель.isEmpty ? " " : ", ") + дюймы }
        }
        var з = ЗаготовкаПодачи(название: название(голова), раздел: раздел)
        з.бренд = у.вид == .ноутбук ? маркаНоутбука(модель) : ""
        положитьУстройство(у, в: &з)
        if let д = у.диагональ {
            let значение: String = ЧислаАвтоподбора.ч(д)
            з.стандарты = НаборСтандартов(значения: [СемьяСтандарта.диагональ.rawValue: [К.диагональ: значение]])
            if у.вид != .ноутбук { з.характеристики = слоты(раздел, ["diag": значение]) }
        }
        var ф = ФактыОписанияЗаготовки(что: голова)
        ф.добавить(д("prf_l_diag"), у.диагональ.map { ЧислоМоего.дюймы($0) })
        з.описание = ЗаготовкаПодачи.описаниеИзМоего(ф)
        return з
    }

    // MARK: - Дом

    /// Вид техники → раздел сайта (обратное ПокупкиМоего.видТехники); «фильтр» — мелкая техника, «другая» — пусто
    /// (раздел подберёт мастер по названию).
    static func разделТехники(_ вид: ВидТехникиМоего) -> String {
        switch вид {
        case .холодильник: return "fridges"
        case .стиральная: return "washing-machines"
        case .посудомойка: return "dishwashers"
        case .пылесос, .робот: return "vacuum-cleaners"
        case .фильтр: return "small-appliances"
        case .кофемашина: return "kettles-coffee"
        case .кондиционер: return "air-conditioners"
        case .плита, .духовка: return "stoves"
        case .микроволновка: return "microwaves"
        case .водонагреватель: return "water-heaters"
        case .принтер: return "printers"
        case .другая: return ""
        }
    }

    /// Разделы, у которых каталог держит appliance_supply (коды расходника).
    private static let разделыРасходника: Set<String> = ["vacuum-cleaners", "small-appliances", "fridges", "kettles-coffee"]

    /// Техника дома: вид, марка, модель, габариты (введены человеком), код расходника. Комната и чужое фото — нет.
    static func техника(_ т: ТехникаМоего) -> ЗаготовкаПодачи {
        let раздел: String = разделТехники(т.вид)
        let голова: String = склеить([т.вид.название, т.бренд, т.модель])
        var з = ЗаготовкаПодачи(название: название(голова), раздел: раздел)
        з.бренд = т.бренд.trimmingCharacters(in: .whitespacesAndNewlines)
        if let см = т.см, см.count == 3 {
            з.ширина = см[0]
            з.высота = см[1]
            з.глубина = см[2]
        }
        let расходник: String = т.расходник.trimmingCharacters(in: .whitespacesAndNewlines)
        if !расходник.isEmpty && разделыРасходника.contains(раздел) {
            з.стандарты = НаборСтандартов(значения: [СемьяСтандарта.расходник.rawValue: [К.коды: расходник]])
        }
        з.источник = связь(т.покупка)
        var ф = ФактыОписанияЗаготовки(что: голова)
        ф.добавить(д("prf_l_supply"), расходник)
        ф.изСделкиKliko = т.покупка != nil
        з.описание = ЗаготовкаПодачи.описаниеИзМоего(ф)
        return з
    }

    /// Кровать: спальное место (bed_size) — «Кровать 160×200». Места нет — nil.
    static func кровать(_ к: КроватьМоего) -> ЗаготовкаПодачи? {
        guard let место = к.место else { return nil }
        let показ: String = КаталогСтандартов.показ(место)
        let голова: String = МойДомText.т("mh_bed") + " " + показ
        var з = ЗаготовкаПодачи(название: название(голова), раздел: "beds")
        з.стандарты = НаборСтандартов(значения: [СемьяСтандарта.спальноеМесто.rawValue: [К.размер: место]])
        var ф = ФактыОписанияЗаготовки(что: голова)
        ф.добавить(д("prf_l_bed"), показ)
        з.описание = ЗаготовкаПодачи.описаниеИзМоего(ф)
        return з
    }

    /// Матрас кровати: размер места, высота и тип (mattress + bed_size). Ни высоты, ни типа — nil.
    static func матрас(_ к: КроватьМоего) -> ЗаготовкаПодачи? {
        guard let место = к.место, к.матрасВысота != nil || к.матрас != nil else { return nil }
        let показ: String = КаталогСтандартов.показ(место)
        var голова: String = ф("msl_mattress", показ)
        if let высота = к.матрасВысота { голова += ", " + String(высота) + " " + д("prf_u_cm") }
        var з = ЗаготовкаПодачи(название: название(голова), раздел: "beds")
        var поля: [String: String] = [К.размер: место]
        if let высота = к.матрасВысота { поля[К.высотаМатраса] = String(высота) }
        if let вид = к.матрас { поля[К.видМатраса] = вид }
        з.стандарты = НаборСтандартов(значения: [СемьяСтандарта.матрас.rawValue: поля,
                                                 СемьяСтандарта.спальноеМесто.rawValue: [К.размер: место]])
        var описание = ФактыОписанияЗаготовки(что: голова)
        описание.добавить(д("prf_l_bed"), показ)
        описание.добавить(д("prf_l_mattress_h"), к.матрасВысота.map { String($0) + " " + д("prf_u_cm") })
        описание.добавить(д("prf_l_mattress"), к.матрас.map { МойДомText.т("mh_mt_" + $0) })
        з.описание = ЗаготовкаПодачи.описаниеИзМоего(описание)
        return з
    }

    /// Телевизор (или монитор) на стене: диагональ, VESA, вес; связанное устройство — модель и габариты. Нет диагонали —
    /// nil.
    static func экран(_ э: ЭкранНаСтенеМоего, устройство у: УстройствоМоего?) -> ЗаготовкаПодачи? {
        guard let диагональ = э.диагональ ?? у?.диагональ else { return nil }
        let монитор: Bool = у?.вид == .монитор
        let раздел: String = монитор ? "monitors" : "tv"
        let вид: String = монитор ? ВидУстройстваМоего.монитор.название : ВидУстройстваМоего.тв.название
        let дюймы: String = ЧислоМоего.дюймы(диагональ)
        let модель: String = у?.модель ?? ""
        let голова: String = модель.trimmingCharacters(in: .whitespaces).isEmpty
            ? вид + " " + дюймы : склеить([вид, модель]) + ", " + дюймы
        var з = ЗаготовкаПодачи(название: название(голова), раздел: раздел)
        if let у { положитьУстройство(у, в: &з) }
        з.диагональ = диагональ
        let значение: String = ЧислаАвтоподбора.ч(диагональ)
        var набор = НаборСтандартов(значения: [СемьяСтандарта.диагональ.rawValue: [К.диагональ: значение]])
        набор[.vesa, К.шаблон] = э.vesa
        з.стандарты = набор
        з.характеристики = слоты(раздел, ["diag": значение])
        var ф = ФактыОписанияЗаготовки(что: голова)
        ф.добавить(д("prf_l_vesa"), э.vesa.map { КаталогСтандартов.показ($0) })
        ф.добавить(д("prf_l_weight"), э.вес.map { ЧислоМоего.ч($0) + " " + д("prf_u_kg") })
        з.описание = ЗаготовкаПодачи.описаниеИзМоего(ф)
        return з
    }

    // MARK: - Купленное на Kliko

    /**
     Вещь из покупки (ВещьМоего): очищенное название сделки, раздел, марка, стандарты и qty, связь «deal:». Фото прежнего
     продавца (адресФото) — никогда (SERVER_CIRCLE.md §4.6): своё фото продавец снимет в мастере.
     */
    static func купленное(_ в: ВещьМоего) -> ЗаготовкаПодачи {
        var з = ЗаготовкаПодачи(название: название(в.название), раздел: в.раздел)
        з.бренд = (в.покупка?.бренд ?? "").trimmingCharacters(in: .whitespacesAndNewlines)
        if !в.стандарты.пусто {
            з.стандарты = в.стандарты
            з.штук = в.стандарты.сколько
        }
        з.источник = связь(в.покупка)
        var ф = ФактыОписанияЗаготовки(что: в.название)
        for факт in фактыСтандартов(в.стандарты) { ф.строки.append(факт) }
        ф.изСделкиKliko = в.покупка != nil
        з.описание = ЗаготовкаПодачи.описаниеИзМоего(ф)
        return з
    }

    /// То, что положено в «Моё» из сделки, — заготовкой своего вида (одежда, компьютер, техника, вещь); нет — nil.
    static func изСделки(_ сделка: String, запись: ЗаписьМоего) -> ЗаготовкаПодачи? {
        guard let id = запись.изСделок[сделка] else { return nil }
        if let в = запись.вещи.first(where: { $0.id == id }) { return купленное(в) }
        if let в = запись.гардероб.вещи.first(where: { $0.id == id }) { return вещь(в, тело: запись.тело) }
        if let к = запись.компьютеры.first(where: { $0.id == id }) {
            let у: УстройствоМоего? = к.устройство.flatMap { номер in запись.устройства.first { $0.id == номер } }
            return компьютер(к, устройство: у)
        }
        if let т = запись.дом.техника.first(where: { $0.id == id }) { return техника(т) }
        return nil
    }

    /// Строки стандартов вещи на языке приложения: «Цоколь: E27», «Спальное место: 160×200», «Оперативная память:
    /// DDR4 SO-DIMM 8 ГБ 3200 МГц». Размер одежды — нет (его строку пишет мастер).
    static func фактыСтандартов(_ набор: НаборСтандартов) -> [ФактОписанияЗаготовки] {
        var итог: [ФактОписанияЗаготовки] = []
        for семья in набор.семьи where семья != .размер {
            let поля: [String: String] = набор.поля(семья)
            var порядок: [String] = семья.главные
            for ключ in поля.keys.sorted() where !порядок.contains(ключ) { порядок.append(ключ) }
            let значения: [String] = порядок.compactMap { ключ in поля[ключ].map { показСтандарта(ключ, $0) } }
            let строка: String = значения.filter { !$0.isEmpty }.joined(separator: " ")
            guard !строка.isEmpty else { continue }
            итог.append(ФактОписанияЗаготовки(семья.название, строка))
        }
        return итог
    }

    /// Значение поля стандарта для описания: единицы на языке приложения, «160x200» → «160×200».
    private static func показСтандарта(_ поле: String, _ значение: String) -> String {
        switch поле {
        case К.гб, К.памятьКарты: return значение + " " + д("prf_u_gb")
        case К.тб: return значение + " " + д("prf_u_tb")
        case К.ватт: return значение + " " + д("prf_u_w")
        case К.высотаМатраса, К.см, К.ширина, К.проход: return значение + " " + д("prf_u_cm")
        case К.частота: return значение + " " + д("prf_u_mhz")
        case К.длина, К.длинаКарты: return значение + " " + д("prf_u_mm")
        case К.доКг: return значение + " " + д("prf_u_kg")
        case К.диагональ, К.диагональОт, К.диагональДо: return значение + "″"
        case К.pcie: return ""
        case К.видМатраса:
            return КаталогСтандартов.видыМатраса.contains(значение) ? МойДомText.т("mh_mt_" + значение) : значение
        case К.протокол: return показПротокола(значение)
        default: return КаталогСтандартов.показ(значение)
        }
    }

    /// Протокол накопителя словами: «nvme_pcie4_x4» → «NVMe PCIe 4.0», «sata» → «SATA».
    private static func показПротокола(_ код: String) -> String {
        switch код {
        case "nvme": return "NVMe"
        case "sata": return "SATA"
        case "nvme_pcie3_x4": return "NVMe PCIe 3.0"
        case "nvme_pcie4_x4": return "NVMe PCIe 4.0"
        case "nvme_pcie5_x4": return "NVMe PCIe 5.0"
        default: return код
        }
    }

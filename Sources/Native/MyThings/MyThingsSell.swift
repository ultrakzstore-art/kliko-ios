/**
 «ПРОДАТЬ СВОЁ» ИЗ «МОЕГО» (пачка 83, docs/SERVER_NEW_FOR_MINE.md §16.4; API заготовки — Posting/PostingPrefill.swift).

 Раньше «Продать своё» клало название в буфер обмена и открывало пустую подачу. Теперь мастер открывается уже
 заполненным: вещь «Моего» → ЗаготовкаПодачи → ЖдущаяЗаготовкаПодачи.открыть. Владелец 17.10.2026: «подача с моих
 должен знать описание и прочее, чтобы связка работала как надо» — каждая вещь отдаёт всё, что о ней известно:
 название (вид, марка, модель, главное значение; до 75 знаков), раздел, марку, описание из фактов
 (ЗаготовкаПодачи.описаниеИзМоего), слоты характеристик по смыслу раздела (E_SPECS k → колонка), поля шин и дисков,
 размер всех систем, габариты, стандарты и qty, фото самой вещи. Что берётся:
   · вещь гардероба — вид, марка, размер (строка всех систем → блок «Размер», система — size_sys), цвета, сезон, раздел
     по слою и полу ВЕЩИ (пол не знаем — раздел пустой, его подберёт мастер по названию; мерки и размеры тела раздел не
     выбирают), фото самой вещи (вырезка), связь с покупкой на Kliko;
   · шины и диски машины — каждый штатный размер своим пунктом: поля parts (ширина, профиль, диаметр; диаметр, PCD, ET,
     DIA, ширина J), «Штук в комплекте» 4, «Подходит к» — марка, модель и год машины;
   · старая деталь компьютера из «Можно улучшить» — память (кит), накопитель, видеокарта, блок питания, процессор:
     стандарты, слоты по смыслу раздела, марка чипа или процессора; компьютер целиком (MyThingsSellHome.swift);
   · устройства, техника дома, кровать и матрас, телевизор на стене, купленное на Kliko — MyThingsSellHome.swift.
 В названии и описании — только вид и значения: своё название вещи, машины и компьютера («рабочая», «Camry жены»),
 комната, мерки тела, заметка, VIN, номер и цена покупки не уходят. Фото машины, комнаты и тела — никогда; чужое фото
 объявления (адресФото) — никогда. Мастер выключен или уже открыт (ЖдущаяЗаготовкаПодачи.открыть → false) — как раньше:
 название в буфер обмена (только этот телефон, 10 минут) и пустая подача.

 Новых запросов здесь нет: всё собирается на телефоне, на сервер уходит только то, что человек сам опубликует.
 */
@MainActor
enum ПродатьСвоёМоего {
    typealias К = КлючСтандарта

    /// Мастер откроется заполненным: заготовка и своя подача включены, мастер сейчас не открыт.
    static var можноЗаготовкой: Bool {
        Config.заготовкаПодачи && Config.нативнаяПодача && ПодачаОкно.shared.цель == nil
    }

    /// Мастер с заготовкой; не вышло — по-старому (название в буфер обмена и пустая подача).
    static func открыть(_ заготовка: ЗаготовкаПодачи) {
        if ЖдущаяЗаготовкаПодачи.открыть(заготовка) { return }
        поСтарому(название: заготовка.название)
    }

    /// Прежний путь: название — в буфер обмена (только этот телефон, без Универсального буфера, на 10 минут — как
    /// «Копировать» пароль), потом пустая подача.
    static func поСтарому(название: String) {
        if !название.isEmpty {
            UIPasteboard.general.setItems([["public.utf8-plain-text": название]],
                                          options: [.localOnly: true, .expirationDate: Date().addingTimeInterval(600)])
        }
        _ = ПодачаОкно.shared.открыть(.новое)
    }

    static func т(_ ключ: String) -> String { ПродатьМоёText.т(ключ) }

    static func ф(_ ключ: String, _ аргумент: String) -> String { ПродатьМоёText.ф(ключ, аргумент) }

    /// Тексты описания (prf_d_*, prf_l_*, prf_u_*, prf_v_*) — тот же язык, что у названия.
    static func д(_ ключ: String) -> String { ТекстОписанияЗаготовки.т(ключ) }

    // MARK: - Общее: название, связь, слоты, единицы

    /// Название подачи: без краёв, до 75 знаков (предел формы).
    static func название(_ текст: String) -> String {
        String(текст.trimmingCharacters(in: .whitespacesAndNewlines).prefix(75))
    }

    /**
     Части названия через пробел; слова, которыми следующая часть начинается и которые уже есть, не повторяются:
     «Холодильник» + «Samsung» + «Холодильник Samsung RB37» → «Холодильник Samsung RB37», «Ноутбук» + «Ноутбук ASUS X515»
     → «Ноутбук ASUS X515».
     */
    static func склеить(_ части: [String]) -> String {
        var итог: String = ""
        var были: Set<String> = []
        for часть in части {
            let чистая: String = часть.trimmingCharacters(in: .whitespacesAndNewlines)
            guard !чистая.isEmpty else { continue }
            var слова: [Substring] = чистая.split(separator: " ")
            while let первое = слова.first, были.contains(первое.lowercased()) { слова.removeFirst() }
            guard !слова.isEmpty else { continue }
            let добавка: String = слова.joined(separator: " ")
            итог = итог.isEmpty ? добавка : итог + " " + добавка
            for слово in слова { были.insert(слово.lowercased()) }
        }
        return итог
    }

    /// relist_from покупки на Kliko: «deal:<номер>»; нет покупки — пусто.
    static func связь(_ покупка: ПокупкаМоего?) -> String {
        guard let покупка, !покупка.сделка.isEmpty else { return "" }
        return "deal:" + покупка.сделка
    }

    /**
     Слоты характеристик по смыслу (k строки E_SPECS: type, capacity, mhz, vendor, vram, power_w, cert, series, socket,
     iface, diag…) → колонки раздела (cpu · gpu · ram · storage · year). Смысл колонки у каждого раздела свой: у «ram»
     в cpu — тип DDR, у «gpu» в cpu — производитель, у «power-supplies» в cpu — мощность (Filters/ElectronicsSpecs.swift).
     У компьютеров и телефонов набора нет — k там и есть колонка (cpu, gpu, ram, storage).
     */
    static func слоты(_ раздел: String, _ смысл: [String: String]) -> [String: String] {
        let набор: [ХарактеристикаЭлектроники] = ХарактеристикиЭлектроники.набор(раздел)
        var итог: [String: String] = [:]
        for (ключ, значение) in смысл where !значение.isEmpty {
            if let строка = набор.first(where: { $0.ключ == ключ }) {
                итог[строка.колонка] = значение
            } else if набор.isEmpty && СхемаПодачи.слоты.contains(ключ) {
                итог[ключ] = значение
            }
        }
        return итог
    }

    /// «8 ГБ» на языке описания.
    static func гб(_ x: Int) -> String { String(x) + " " + д("prf_u_gb") }

    /// «512 ГБ», «1 ТБ», «1,5 ТБ» на языке описания.
    static func объём(_ тб: Double) -> String {
        if тб < 1 { return ЧислоМоего.ч(тб * 1000, знаков: 0) + " " + д("prf_u_gb") }
        return ЧислоМоего.ч(тб, знаков: 2) + " " + д("prf_u_tb")
    }

    /// Объём каноном вариантов сайта: «512GB», «1TB» (слот storage / capacity).
    static func объёмКаталога(_ тб: Double) -> String {
        if тб < 1 { return ЧислаАвтоподбора.ч(тб * 1000, знаков: 0) + "GB" }
        return ЧислаАвтоподбора.ч(тб, знаков: 2) + "TB"
    }

    /// Протокол накопителя каноном каталога m2_ssd: «nvme_pcie4_x4» (поколение известно), «nvme», «sata»; иначе nil.
    static func протоколКаталога(_ н: НакопительМоего) -> String? {
        guard let пр = н.протокол else { return nil }
        if пр == "sata" { return "sata" }
        guard пр == "nvme" else { return nil }
        if let pcie = н.pcie, (3...5).contains(pcie) { return "nvme_pcie" + String(pcie) + "_x4" }
        return "nvme"
    }

    /// Марка графического чипа: RTX, GTX, GeForce — NVIDIA; RX, Radeon — AMD; Arc — Intel; не узнали — nil.
    static func маркаЧипа(_ чип: String) -> String? {
        let н: String = " " + чип.lowercased() + " "
        if ["rtx", "gtx", "geforce", "quadro", "titan", "nvidia"].contains(where: { н.contains($0) }) { return "NVIDIA" }
        if н.contains(" rx") || н.contains("radeon") || н.contains("amd") { return "AMD" }
        if н.contains(" arc") || н.contains("intel") { return "Intel" }
        return nil
    }

    /// Производитель видеокарты вариантом раздела «gpu»: «NVIDIA GeForce», «AMD Radeon», «Intel Arc».
    static func линейкаЧипа(_ чип: String) -> String? {
        switch маркаЧипа(чип) {
        case "NVIDIA": return "NVIDIA GeForce"
        case "AMD": return "AMD Radeon"
        case "Intel": return "Intel Arc"
        default: return nil
        }
    }

    /// Видеокарта ноутбука и ПК вариантом раздела: «NVIDIA GeForce RTX», «NVIDIA GeForce GTX», «AMD Radeon», «Intel Arc».
    static func видеокартаКомпьютера(_ чип: String) -> String? {
        let н: String = чип.lowercased()
        if н.contains("rtx") { return "NVIDIA GeForce RTX" }
        if н.contains("gtx") { return "NVIDIA GeForce GTX" }
        return линейкаЧипа(чип)
    }

    /// Процессор с маркой впереди («Ryzen 5 5600» → «AMD Ryzen 5 5600») и марка; не узнали марку — имя как есть.
    static func процессорСМаркой(_ имя: String) -> (марка: String?, полное: String) {
        let чистое: String = имя.trimmingCharacters(in: .whitespacesAndNewlines)
        let н: String = чистое.lowercased()
        let марки: [(String, [String])] = [
            ("AMD", ["amd", "ryzen", "athlon", "threadripper", "phenom", "a4-", "a6-", "a8-", "a10-"]),
            ("Intel", ["intel", "core", "pentium", "celeron", "xeon", "atom"]),
            ("Apple", ["apple", "m1", "m2", "m3", "m4"])
        ]
        guard let найдено = марки.first(where: { пара in пара.1.contains(where: { н.hasPrefix($0) }) }) else {
            return (марка: nil, полное: чистое)
        }
        let марка: String = найдено.0
        if н.hasPrefix(марка.lowercased()) { return (марка: марка, полное: чистое) }
        return (марка: марка, полное: марка + " " + чистое)
    }

    // MARK: - Гардероб

    /// Общие разделы без пола: в них подавать нельзя — пусть мастер подберёт по названию.
    private static let разделыБезПола: Set<String> = ["clothing", "shoes"]

    /**
     Вещь гардероба. тело — прежний параметр вызова: размеры и мерки тела раздел больше не выбирают (владелец 17.10.2026:
     вещь могла быть подарком или чужой; данные тела в подачу не идут даже косвенно).
     */
    static func вещь(_ в: ВещьГардеробаМоего, тело: ТелоМоего) -> ЗаготовкаПодачи {
        let пол: ПолГардеробаМоего? = полВещи(в)
        let общий: String = СочетаниеГардероба.раздел(в.вид.слой, пол: пол)
        /* «Другое» — не знаем, что это: раздел подберёт мастер по названию (не «Сумки и аксессуары» наугад). */
        let раздел: String = разделыБезПола.contains(общий) || в.вид == .другое ? "" : общий
        var з = ЗаготовкаПодачи(название: названиеВещи(в), раздел: раздел)
        let своя: String = в.бренд.trimmingCharacters(in: .whitespacesAndNewlines)
        let изПокупки: String = в.покупка?.бренд ?? ""
        з.бренд = своя.isEmpty ? изПокупки : своя
        if let р = в.размер {
            з.размерВсехСистем = ЗаготовкаПодачи.строкаРазмера(р)
            з.системаРазмера = р.система
        }
        if let снимок = в.фото { з.фотоМоего = [снимок.файл] }
        з.источник = связь(в.покупка)
        з.описание = ЗаготовкаПодачи.описаниеИзМоего(фактыВещи(в, бренд: з.бренд))
        return з
    }

    /// Пол вещи — только по ней самой: вид размера на бирке, платье и юбка; не знаем — nil.
    private static func полВещи(_ в: ВещьГардеробаМоего) -> ПолГардеробаМоего? {
        if let вид = в.размер?.вид, let п = СочетаниеГардероба.пол(вид) { return п }
        if в.вид == .платье || в.вид == .юбка { return .женский }
        return nil
    }

    /// «Куртка Zara, M, чёрная» — вид, марка, размер, цвет; до 75 знаков. Своего названия вещи нет (§16.4).
    static func названиеВещи(_ в: ВещьГардеробаМоего) -> String {
        var итог: String = в.вид.название
        let бренд: String = в.бренд.trimmingCharacters(in: .whitespacesAndNewlines)
        if !бренд.isEmpty && !итог.lowercased().contains(бренд.lowercased()) { итог += " " + бренд }
        if let р = в.размер { итог += ", " + р.коротко }
        if let цвет = в.цвета.first, цвет != .разноцветный { итог += ", " + цвет.название.lowercased() }
        return String(итог.prefix(75))
    }

    /// «Куртка Zara, размер M.» · «Цвет: чёрный, белый» · «Сезон: демисезон» · «Куплено на Kliko…». Без имени вещи и
    /// заметки (там бывают имена и посадка по телу).
    private static func фактыВещи(_ в: ВещьГардеробаМоего, бренд: String) -> ФактыОписанияЗаготовки {
        var что: String = склеить([в.вид.название, бренд])
        if let р = в.размер { что += ", " + ТекстОписанияЗаготовки.ф("prf_d_size", р.коротко) }
        var ф = ФактыОписанияЗаготовки(что: что)
        let цвета: [String] = в.цвета.prefix(2).map { $0.название.lowercased() }
        ф.добавить(д("prf_l_color"), цвета.joined(separator: ", "))
        ф.добавить(д("prf_l_season"), в.сезон?.название.lowercased())
        ф.изСделкиKliko = в.покупка != nil
        return ф
    }

    // MARK: - Машина: шины и диски

    /// Штатные размеры шин машины (годные, без повторов, до четырёх) — пункты меню «Продать».
    static func размерыШин(_ м: МашинаМоего) -> [РазмерШиныАвтоподбора] {
        guard let п = м.посадка else { return [] }
        var итог: [РазмерШиныАвтоподбора] = []
        for ш in п.шины where ш.годный && !итог.contains(ш) { итог.append(ш) }
        return Array(итог.prefix(4))
    }

    /// Штатные шины машины комплектом (первый размер); размера нет — nil.
    static func шины(_ м: МашинаМоего) -> ЗаготовкаПодачи? {
        guard let ш = размерыШин(м).first else { return nil }
        return шины(м, размер: ш)
    }

    /// Шины выбранного штатного размера комплектом из четырёх: поля parts, «Подходит к» — марка, модель, год машины.
    static func шины(_ м: МашинаМоего, размер ш: РазмерШиныАвтоподбора) -> ЗаготовкаПодачи {
        var з = ЗаготовкаПодачи(название: ф("msl_tyres", ш.подпись), раздел: "tires-wheels")
        var поля: [String: String] = ["width": ЧислаАвтоподбора.ч(ш.ширина), "profile": ЧислаАвтоподбора.ч(ш.профиль),
                                      "diameter": ЧислаАвтоподбора.ч(ш.диаметр), "count": "4"]
        добавитьМашину(м, в: &поля)
        з.диски = false
        з.запчасть = поля
        з.штук = 4
        var факты = ФактыОписанияЗаготовки(что: ТекстОписанияЗаготовки.ф("prf_d_tyres", "4", ш.подпись))
        факты.машина = машинаОписания(м)
        з.описание = ЗаготовкаПодачи.описаниеИзМоего(факты)
        return з
    }

    /// Штатные диаметры дисков (до четырёх), если известна разболтовка или DIA — пункты меню «Продать».
    static func диаметрыДисков(_ м: МашинаМоего) -> [Double] {
        guard let п = м.посадка, п.разболтовка != nil || п.dia != nil else { return [] }
        return Array(п.штатныеДиаметры.prefix(4))
    }

    /// Подпись дисков для кнопки и названия: «R16 5×114.3 ET45»; нет диаметра — nil.
    static func подписьДисков(_ м: МашинаМоего) -> String? {
        guard let r = м.посадка?.штатныеДиаметры.first else { return nil }
        return подписьДисков(м, диаметр: r)
    }

    /// «R17 5×114.3 ET45» для выбранного диаметра.
    static func подписьДисков(_ м: МашинаМоего, диаметр r: Double) -> String {
        var части: [String] = ["R" + ЧислаАвтоподбора.ч(r)]
        if let п = м.посадка {
            if let р = п.разболтовка { части.append(р.подпись) }
            if let et = одинET(п) { части.append("ET" + ЧислаАвтоподбора.ч(et)) }
        }
        return части.joined(separator: " ")
    }

    /// Штатные диски машины комплектом (первый диаметр); не хватает данных — nil.
    static func диски(_ м: МашинаМоего) -> ЗаготовкаПодачи? {
        guard let r = диаметрыДисков(м).first else { return nil }
        return диски(м, диаметр: r)
    }

    /// Диски выбранного диаметра комплектом: диаметр и хотя бы разболтовка или DIA; иначе nil.
    static func диски(_ м: МашинаМоего, диаметр r: Double) -> ЗаготовкаПодачи? {
        guard let п = м.посадка else { return nil }
        var поля: [String: String] = ["diameter": ЧислаАвтоподбора.ч(r)]
        if let р = п.разболтовка {
            поля["pcd"] = String(р.отверстий) + "x" + ЧислаАвтоподбора.ч(р.pcd, знаков: 2)
        }
        if let et = одинET(п) { поля["et"] = ЧислаАвтоподбора.ч(et) }
        if let dia = п.dia { поля["dia"] = ЧислаАвтоподбора.ч(dia, знаков: 2) }
        guard поля["pcd"] != nil || поля["dia"] != nil else { return nil }
        let ширина: Double? = одинаШирина(п)
        if let ширина { поля["width_j"] = ЧислаАвтоподбора.ч(ширина) }
        поля["count"] = "4"
        добавитьМашину(м, в: &поля)
        let подпись: String = подписьДисков(м, диаметр: r)
        var з = ЗаготовкаПодачи(название: ф("msl_rims", подпись), раздел: "tires-wheels")
        з.диски = true
        з.запчасть = поля
        з.штук = 4
        var факты = ФактыОписанияЗаготовки(что: ТекстОписанияЗаготовки.ф("prf_d_rims", "4", подпись))
        факты.машина = машинаОписания(м)
        факты.добавить(д("prf_l_width_j"), ширина.map { ЧислоМоего.ч($0) + "J" })
        факты.добавить(д("prf_l_dia"), п.dia.map { ЧислоМоего.ч($0, знаков: 2) + " " + д("prf_u_mm") })
        з.описание = ЗаготовкаПодачи.описаниеИзМоего(факты)
        return з
    }

    /// ET — только одно значение (у справочника бывает диапазон: тогда пусть продавец укажет свой).
    private static func одинET(_ п: ПосадкаАвтоподбора) -> Double? {
        guard let низ = п.etMin, let верх = п.etMax, низ == верх else { return nil }
        return низ
    }

    /// Ширина обода J — только одно значение.
    private static func одинаШирина(_ п: ПосадкаАвтоподбора) -> Double? {
        guard let низ = п.ширинаMin, let верх = п.ширинаMax, низ == верх else { return nil }
        return низ
    }

    /// «Подходит к марке», «Модель», «Годы с / по» (PARTS_FIELDS fit_*) — марка, модель и год машины из справочника.
    /// Своё название машины, фото, VIN и номер — никогда (их и нет в этих полях).
    private static func добавитьМашину(_ м: МашинаМоего, в поля: inout [String: String]) {
        guard let авто = м.авто else { return }
        let марка: String = авто.марка.trimmingCharacters(in: .whitespacesAndNewlines)
        let модель: String = авто.модель.trimmingCharacters(in: .whitespacesAndNewlines)
        if !марка.isEmpty { поля["fit_brand"] = марка }
        if !модель.isEmpty { поля["fit_model"] = модель }
        if let год = авто.год {
            поля["fit_from"] = String(год)
            поля["fit_to"] = String(год)
        }
    }

    /// «Toyota Camry 2018» для «Штатный размер для …»; машины из справочника нет — пусто.
    private static func машинаОписания(_ м: МашинаМоего) -> String {
        guard let авто = м.авто else { return "" }
        let год: String = авто.год.map { String($0) } ?? ""
        return [авто.марка, авто.модель, год]
            .map { $0.trimmingCharacters(in: .whitespacesAndNewlines) }
            .filter { !$0.isEmpty }
            .joined(separator: " ")
    }

    // MARK: - Компьютер: старая деталь

    /**
     Что освободится в варианте «Можно улучшить» → заготовка; «продать свой» — компьютер целиком (с его устройством:
     диагональ и габариты ноутбука). Деталь не описана — только её подпись (у «продать свой» — никогда не своё название
     компьютера, владелец 17.10.2026).
     */
    static func деталь(_ вариант: ВариантАпгрейдаМоего, _ к: КомпьютерМоего,
                       устройство: УстройствоМоего? = nil) -> ЗаготовкаПодачи {
        let найдено: ЗаготовкаПодачи?
        switch вариант.группа {
        case "ram": найдено = память(к)
        case "ssd": найдено = накопитель(к)
        case "gpu": найдено = видеокарта(к)
        case "psu": найдено = блокПитания(к)
        case "cpu": найдено = процессор(к)
        case "sell": найдено = компьютер(к, устройство: устройство)
        default: найдено = nil
        }
        if let найдено { return найдено }
        return ЗаготовкаПодачи(название: название(вариант.старая ?? ""), раздел: "")
    }

    /// Вставленные планки — китом: одинаковые — «2×8 ГБ», разные — общий объём без поля gb.
    private static func память(_ к: КомпьютерМоего) -> ЗаготовкаПодачи? {
        let м = к.память
        guard !м.всяРаспаяна, !м.планки.isEmpty else { return nil }
        let штук: Int = м.планки.count
        let одинаковые: Bool = Set(м.планки).count == 1
        let всего: Int = м.планки.reduce(0, +)
        var поля: [String: String] = [:]
        var вид: [String] = []
        if let п = м.поколение {
            поля[К.поколение] = п
            вид.append(п)
        }
        if let форма = м.форма, форма != "soldered" {
            поля[К.форма] = форма
            вид.append(форма)
        }
        var части: [String] = вид
        let объёмКита: String
        if одинаковые, let планка = м.планки.first {
            поля[К.гб] = String(планка)
            let штукПодписи: String = штук > 1 ? String(штук) + "×" : ""
            части.append(штукПодписи + ФорматКомпьютераМоего.гб(планка))
            объёмКита = штук > 1 ? String(штук) + " × " + гб(планка) : гб(планка)
        } else {
            части.append(ФорматКомпьютераМоего.гб(всего))
            объёмКита = гб(всего)
        }
        if let ч = м.частота {
            поля[К.частота] = String(ч)
            части.append(String(ч))
        }
        var з = ЗаготовкаПодачи(название: ф("msl_ram", части.joined(separator: " ")), раздел: "ram")
        if !поля.isEmpty {
            з.стандарты = НаборСтандартов(значения: [СемьяСтандарта.память.rawValue: поля], сколько: штук)
        }
        з.штук = штук
        var смысл: [String: String] = ["capacity": String(всего)]
        if let п = м.поколение { смысл["type"] = п }
        if let ч = м.частота { смысл["mhz"] = String(ч) }
        з.характеристики = слоты("ram", смысл)
        let голова: String = ф("msl_ram", вид.joined(separator: " ")).trimmingCharacters(in: .whitespaces)
        let что: String = штук > 1 ? ТекстОписанияЗаготовки.ф("prf_d_kit", голова, объёмКита) : голова + ", " + объёмКита
        var факты = ФактыОписанияЗаготовки(что: что)
        факты.добавить(д("prf_l_freq"), м.частота.map { String($0) + " " + д("prf_u_mhz") })
        з.описание = ЗаготовкаПодачи.описаниеИзМоего(факты)
        return з
    }

    /// Системный накопитель (его меняют): SSD — стандартом m2_ssd каноном каталога, HDD — названием и слотами.
    private static func накопитель(_ к: КомпьютерМоего) -> ЗаготовкаПодачи? {
        guard let н = к.накопители.first else { return nil }
        var части: [String] = [ФорматКомпьютераМоего.форма(н.форма)]
        if !н.hdd, let пр = н.протокол, пр == "nvme" || пр == "sata" {
            части.append(ФорматКомпьютераМоего.протокол(пр))
        }
        if let тб = н.тб { части.append(ФорматКомпьютераМоего.объём(тб)) }
        let подпись: String = части.joined(separator: " ")
        var з = ЗаготовкаПодачи(название: ф(н.hdd ? "msl_hdd" : "msl_ssd", подпись), раздел: "ssd-hdd")
        let протокол: String? = протоколКаталога(н)
        if !н.hdd {
            /* pcie в каталоге m2_ssd нет: поколение — в самом протоколе («nvme_pcie4_x4»). */
            var поля: [String: String] = [К.форма: н.форма]
            if let протокол { поля[К.протокол] = протокол }
            if let тб = н.тб { поля[К.тб] = ЧислаАвтоподбора.ч(тб, знаков: 3) }
            з.стандарты = НаборСтандартов(значения: [СемьяСтандарта.накопитель.rawValue: поля])
        }
        var смысл: [String: String] = [:]
        if н.hdd {
            смысл["type"] = "HDD"
        } else if let пр = н.протокол, пр == "nvme" || пр == "sata" {
            смысл["type"] = пр == "nvme" ? "SSD NVMe" : "SSD SATA"
        }
        if let тб = н.тб { смысл["capacity"] = объёмКаталога(тб) }
        смысл["iface"] = н.форма.hasPrefix("22") ? "M.2" : "SATA"
        з.характеристики = слоты("ssd-hdd", смысл)
        var факты = ФактыОписанияЗаготовки(что: з.название)
        факты.добавить(д("prf_l_form"), ФорматКомпьютераМоего.форма(н.форма))
        if !н.hdd, let пр = н.протокол, пр == "nvme" || пр == "sata" {
            let шина: String = н.pcie.map { " PCIe " + String($0) + ".0" } ?? ""
            факты.добавить(д("prf_l_iface"), ФорматКомпьютераМоего.протокол(пр) + (пр == "nvme" ? шина : ""))
        }
        з.описание = ЗаготовкаПодачи.описаниеИзМоего(факты)
        return з
    }

    private static func видеокарта(_ к: КомпьютерМоего) -> ЗаготовкаПодачи? {
        let карта = к.видеокарта
        guard let чип = карта.чип, !чип.isEmpty, !карта.встроенная else { return nil }
        var поля: [String: String] = [К.чип: чип]
        var подпись: String = чип
        if let память = карта.памятьГБ {
            поля[К.памятьКарты] = String(память)
            подпись += " " + ФорматКомпьютераМоего.гб(память)
        }
        if let длина = карта.длина { поля[К.длина] = String(длина) }
        if let питание = карта.питание { поля[К.питание] = питание }
        var з = ЗаготовкаПодачи(название: ф("msl_gpu", подпись), раздел: "gpu")
        з.стандарты = НаборСтандартов(значения: [СемьяСтандарта.видеокарта.rawValue: поля])
        з.бренд = маркаЧипа(чип) ?? ""
        /* В разделе «gpu» cpu — «Производитель», gpu — «Видеопамять» (раньше сюда ошибочно ложилось имя чипа). */
        var смысл: [String: String] = [:]
        if let линейка = линейкаЧипа(чип) { смысл["vendor"] = линейка }
        if let память = карта.памятьГБ { смысл["vram"] = String(память) + "GB" }
        з.характеристики = слоты("gpu", смысл)
        var факты = ФактыОписанияЗаготовки(что: з.название)
        факты.добавить(д("prf_l_vram"), карта.памятьГБ.map { гб($0) })
        факты.добавить(д("prf_l_length"), карта.длина.map { String($0) + " " + д("prf_u_mm") })
        факты.добавить(д("prf_l_power"), карта.питание.map { ФорматКомпьютераМоего.разъём($0) })
        з.описание = ЗаготовкаПодачи.описаниеИзМоего(факты)
        return з
    }

    private static func блокПитания(_ к: КомпьютерМоего) -> ЗаготовкаПодачи? {
        let бп = к.бп
        guard let ватт = бп.ватт else { return nil }
        var поля: [String: String] = [К.ватт: String(ватт)]
        var подпись: String = ФорматКомпьютераМоего.ватт(ватт)
        if let форма = бп.форма {
            поля[К.форма] = форма
            подпись += " " + форма
        }
        if let сертификат = бп.сертификат { поля[К.сертификат] = сертификат }
        var з = ЗаготовкаПодачи(название: ф("msl_psu", подпись), раздел: "power-supplies")
        з.стандарты = НаборСтандартов(значения: [СемьяСтандарта.блокПитания.rawValue: поля])
        var смысл: [String: String] = ["power_w": String(ватт)]
        if let сертификат = бп.сертификат { смысл["cert"] = сертификат }
        з.характеристики = слоты("power-supplies", смысл)
        var факты = ФактыОписанияЗаготовки(что: з.название)
        факты.добавить(д("prf_l_watts"), String(ватт) + " " + д("prf_u_w"))
        факты.добавить(д("prf_l_cert"), бп.сертификат)
        факты.добавить(д("prf_l_form"), бп.форма)
        з.описание = ЗаготовкаПодачи.описаниеИзМоего(факты)
        return з
    }

    private static func процессор(_ к: КомпьютерМоего) -> ЗаготовкаПодачи? {
        let имя: String = к.процессор.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !имя.isEmpty else { return nil }
        let цп = процессорСМаркой(имя)
        var поля: [String: String] = [К.процессор: имя]
        if let сокет = к.сокет { поля[К.сокет] = сокет }
        var з = ЗаготовкаПодачи(название: ф("msl_cpu", цп.полное), раздел: "cpu")
        з.стандарты = НаборСтандартов(значения: [СемьяСтандарта.сокет.rawValue: поля])
        з.бренд = цп.марка ?? ""
        /* «Линейка» — вариант по началу имени («AMD Ryzen 5 5600» → «AMD Ryzen 5», приводит мастер), «Сокет» — свой. */
        var смысл: [String: String] = ["series": цп.полное]
        if let сокет = к.сокет, сокет != "BGA" { смысл["socket"] = сокет }
        з.характеристики = слоты("cpu", смысл)
        var факты = ФактыОписанияЗаготовки(что: з.название)
        if let сокет = к.сокет, сокет != "BGA" { факты.добавить(д("prf_l_socket"), сокет) }
        з.описание = ЗаготовкаПодачи.описаниеИзМоего(факты)
        return з
    }

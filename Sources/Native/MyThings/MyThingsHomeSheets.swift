    private var кнопкиПродать: some View {
        let продатьТ: String = ПродатьМоёText.т("msl_sell")
        let естьМатрас: Bool = кровать.матрасВысота != nil || кровать.матрас != nil
        return ПотокЧипов(зазор: 8) {
            МалаяКнопкаАвтоподбора(заголовок: продатьТ + ": " + т("mh_bed"), значок: "tag") {
                продать(ПродатьСвоёМоего.кровать(кровать))
            }
            if естьМатрас {
                МалаяКнопкаАвтоподбора(заголовок: продатьТ + ": " + т("mh_mattress"), значок: "tag") {
                    продать(ПродатьСвоёМоего.матрас(кровать))
                }
            }
        }
        .accessibilityHint(ПродатьМоёText.т("msl_sell_hint"))

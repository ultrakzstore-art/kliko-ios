            ОткликСайта.выбор()
            кровать.место = место
        }
    }

    private var блокМатраса: some View {
        VStack(alignment: .leading, spacing: 8) {
            ПодписьБлокаДома(т("mh_mattress"))
            ПотокЧипов(зазор: 8) {
                ForEach(КаталогСтандартов.видыМатраса, id: \.self) { вид in
                    ЧипМоего(т("mh_mt_" + вид), выбран: кровать.матрас == вид) {
                        ОткликСайта.выбор()
                        кровать.матрас = кровать.матрас == вид ? nil : вид
                    }
                }
            }
            РегуляторДома(заголовок: т("mh_mattress_h"), значение: кровать.матрасВысота,
                          пределы: КаталогСтандартов.высотыМатраса, обычно: 20) { x in
                кровать.матрасВысота = x
            }
        }
    }

    private var блокОдеяла: some View {
        VStack(alignment: .leading, spacing: 8) {
            ПодписьБлокаДома(т("mh_duvet"), пояснение: подсказкаОдеяла)
            ПотокЧипов(зазор: 8) {
                ForEach(КаталогСтандартов.одеяла, id: \.self) { р in
                    ЧипМоего(КаталогСтандартов.показ(р), выбран: кровать.одеяло == р) {
                        ОткликСайта.выбор()
                        кровать.одеяло = кровать.одеяло == р ? nil : р
                    }
                }
            }
            ПодписьБлокаДома(т("mh_pillows"))
            ПотокЧипов(зазор: 8) {
                ForEach(КаталогСтандартов.подушки, id: \.self) { р in
                    ЧипМоего(КаталогСтандартов.показ(р), выбран: кровать.подушки == р) {
                        ОткликСайта.выбор()
                        кровать.подушки = кровать.подушки == р ? nil : р
                    }
                }
            }
        }
    }

    /// «Под 160×200 обычно берут комплект 2-спальный» — ориентир.
    private var подсказкаОдеяла: String? {
        guard let ширина = кровать.ширина, let место = кровать.место else { return nil }
        let комплект = КаталогСтандартов.комплектОбычно(ширинаМеста: ширина)
        return String(format: т("mh_duvet_hint"), КаталогСтандартов.показ(место), СтандартыText.т("set_" + комплект))
    }

    private func задать(ширина: Int, длина: Int) {
        ОткликСайта.выбор()
        кровать.место = КаталогСтандартов.канон(Double(ширина), Double(длина))
    }

    private func сохранить() {
        let готовая = кровать
        МоёХранилище.shared.обновитьДом { д in
            if let i = д.кровати.firstIndex(where: { $0.id == готовая.id }) {
                д.кровати[i] = готовая
            } else if д.кровати.count < ДомМоего.пределКроватей {
                д.кровати.append(готовая)
            }
        }
    }

    private func удалить() {
        let id = кровать.id
        МоёХранилище.shared.обновитьДом { д in д.кровати.removeAll { $0.id == id } }
    }

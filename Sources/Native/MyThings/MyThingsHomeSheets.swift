struct РедакторКроватиДома: View {
    let новая: Bool
    /// Комнаты на миг открытия листа: лист на хранилище не подписан.
    private let комнаты: [КомнатаМоего]
    @State private var кровать: КроватьМоего
    @Environment(\.dismiss) private var закрыть

    init(кровать: КроватьМоего, новая: Bool) {
        self.новая = новая
        комнаты = МоёХранилище.shared.запись.дом.комнаты
        _кровать = State(initialValue: кровать)
    }

    private func т(_ ключ: String) -> String { МойДомText.т(ключ) }

    private var пара: (Int, Int)? {
        КаталогСтандартов.пара(кровать.место).map { (Int($0.0), Int($0.1)) }

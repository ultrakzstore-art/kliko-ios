/// Сантиметры из замера AR — в пределы, целыми.
enum ЗамерДома {
    static func см(_ x: Double?, _ пределы: ClosedRange<Int>) -> Int? {
        guard let x, x.isFinite, x > 0 else { return nil }
        return min(пределы.upperBound, max(пределы.lowerBound, Int(x.rounded())))
    }
}

// MARK: - Проём

struct РедакторПроёмаДома: View {
    let новый: Bool
    @State private var проём: ПроёмМоего

    init(проём: ПроёмМоего, новый: Bool) {
        self.новый = новый
        _проём = State(initialValue: проём)
    }

    private func т(_ ключ: String) -> String { МойДомText.т(ключ) }

    var body: some View {
        ОболочкаРедактораДома(заголовок: проём.вид.название, можноСохранить: проём.заполнен,
                              сохранить: { сохранить() }, удалить: новый ? nil : { удалить() }) {
            блокВида
            ПолеТекстаДома(заголовок: т("mh_name"), подсказка: т("mh_open_name_ph"), текст: $проём.имя)
            switch проём.вид {
            case .лифт:
                БлокЛифтаДома(проём: $проём)
            case .лестница:
                БлокЛестницыДома(проём: $проём)
            default:
                БлокДвериДома(проём: $проём)
            }
        }
        .animation(ДвижениеСайта.смена, value: проём.вид)
        .animation(ДвижениеСайта.смена, value: проём.примерно)
    }

    private var блокВида: some View {
        VStack(alignment: .leading, spacing: 8) {
            ПодписьБлокаДома(т("mh_open_kind"))
            ПотокЧипов(зазор: 8) {
                ForEach(ВидПроёмаМоего.allCases, id: \.self) { вид in
                    ЧипМоего(вид.название, выбран: проём.вид == вид, значок: вид.значок) {
                        guard проём.вид != вид else { return }
                        ОткликСайта.выбор()
                        // Другой вид — прежние числа не подходят: начинаем с чистого, имя остаётся.
                        проём = ПроёмМоего(id: проём.id, вид: вид, имя: проём.имя)
                    }
                }
            }
        }
    }

    private func сохранить() {
        let готовый = проём
        МоёХранилище.shared.обновитьДом { д in
            if let i = д.проёмы.firstIndex(where: { $0.id == готовый.id }) {
                д.проёмы[i] = готовый
            } else if д.проёмы.count < ДомМоего.пределПроёмов {
                д.проёмы.append(готовый)
            }
            if готовый.вид == .лифт { д.лифтаНет = false }
        }
    }

    private func удалить() {
        let id = проём.id
        МоёХранилище.shared.обновитьДом { д in д.проёмы.removeAll { $0.id == id } }
    }
}

/// Дверь (входная, межкомнатная, балконная): полотно чипами → проход ≈ полотно − 6, свой замер прохода регулятором.
struct БлокДвериДома: View {
    @Binding var проём: ПроёмМоего

    init(проём: Binding<ПроёмМоего>) {
        _проём = проём
    }

    private func т(_ ключ: String) -> String { МойДомText.т(ключ) }

    /// Полотна: входная — 70 / 80 / 90, остальные — ряд ГОСТ 6629-88.
    private var полотна: [Int] { проём.вид == .входная ? [70, 80, 90] : КаталогСтандартов.полотнаДверей }
    private var высоты: [Int] { проём.вид == .входная ? [200, 210] : КаталогСтандартов.высотыДверей }

    /// Полотно, выбранное чипом («d80» в шаблоне).
    private var полотно: Int? {
        guard let шаблон = проём.шаблон, шаблон.hasPrefix("d") else { return nil }
        return Int(шаблон.dropFirst())
    }

    var body: some View {
        VStack(alignment: .leading, spacing: 16) {
            VStack(alignment: .leading, spacing: 8) {
                ПодписьБлокаДома(т("mh_door_leaf"), пояснение: т("mh_door_leaf_hint"))
                ПотокЧипов(зазор: 8) {
                    ForEach(полотна, id: \.self) { ш in
                        ЧипМоего(String(ш) + " " + т("mh_cm"), выбран: полотно == ш) { выбратьПолотно(ш) }
                    }
                }
                ПотокЧипов(зазор: 8) {
                    ForEach(высоты, id: \.self) { в in
                        ЧипМоего("× " + String(в), выбран: проём.высота == в) {
                            ОткликСайта.выбор()
                            проём.высота = в
                        }
                    }
                }
            }
            if let ш = проём.ширина, проём.примерно {
                Label(String(format: т("mh_door_clear_approx"), String(ш)), systemImage: "ruler")
                    .font(.footnote.weight(.semibold))
                    .foregroundStyle(Theme.оранжевый)
                    .fixedSize(horizontal: false, vertical: true)
                    .transition(.opacity)
            }
            РегуляторДома(заголовок: т("mh_door_clear"), значение: проём.ширина, пределы: 40...150, обычно: 74,
                          примерно: проём.примерно) { x in
                проём.ширина = x
                проём.шаблон = nil
                проём.примерно = false
            }
            РегуляторДома(заголовок: т("mh_door_height"), значение: проём.высота, пределы: 150...250, обычно: 200,
                          примерно: проём.примерно) { x in
                проём.высота = x
            }
            КнопкаЗамераДома(название: проём.вид.название) { ш, в, _ in
                if let см = ЗамерДома.см(ш, 40...150) {
                    проём.ширина = см
                    проём.шаблон = nil
                    проём.примерно = false
                }
                if let см = ЗамерДома.см(в, 150...250) { проём.высота = см }
            }
        }
    }

    private func выбратьПолотно(_ ш: Int) {
        ОткликСайта.выбор()
        проём.ширина = КаталогСтандартов.проход(полотна: ш)
        проём.шаблон = "d" + String(ш)
        проём.примерно = true
        if проём.высота == nil { проём.высота = 200 }
    }
}

/// Лифт: шаблоны EN 81-70, «советский ≈», «грузовой ≈» и свой замер двери и кабины.

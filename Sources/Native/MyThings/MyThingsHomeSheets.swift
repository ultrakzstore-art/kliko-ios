                .foregroundStyle(Theme.текстВторой)
            ПотокЧипов(зазор: 8) {
                ForEach(КаталогСтандартов.частыеСпальныеМеста, id: \.self) { место in
                    ЧипМоего(КаталогСтандартов.показ(место), выбран: кровать.место == место) {
                        ОткликСайта.выбор()
                        кровать.место = место
                    }
                }
            }
            Text(т("mh_bed_w"))
                .font(.caption.weight(.bold))
                .foregroundStyle(Theme.текстВторой)
            ПотокЧипов(зазор: 8) {
                ForEach(КаталогСтандартов.ширины, id: \.self) { ш in
                    ЧипМоего(String(ш), выбран: пара?.0 == ш) { задать(ширина: ш, длина: пара?.1 ?? 200) }
                }
            }
            Text(т("mh_bed_l"))
                .font(.caption.weight(.bold))
                .foregroundStyle(Theme.текстВторой)
            ПотокЧипов(зазор: 8) {
                ForEach(КаталогСтандартов.длины, id: \.self) { д in

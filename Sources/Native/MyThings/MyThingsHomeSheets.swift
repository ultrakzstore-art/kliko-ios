// MARK: - Какой лист

enum ЛистДомаМоего: Identifiable {
    case комната(UUID, новая: Bool)
    case проём(ПроёмМоего, новый: Bool)
    case кровать(КроватьМоего, новая: Bool)
    case окно(ОкноДомаМоего, новое: Bool)
    case экран(ЭкранНаСтенеМоего, новый: Bool)
    case техника(ТехникаМоего, новая: Bool)
    /// Лист раздела: строки, шаблоны и всё, что было карточкой на главном экране.
    case раздел(РазделДомаМоего)

    var id: String {
        switch self {
        case .комната(let номер, _): return "room-" + номер.uuidString
        case .проём(let п, _): return "open-" + п.id.uuidString
        case .кровать(let к, _): return "bed-" + к.id.uuidString
        case .окно(let о, _): return "win-" + о.id.uuidString
        case .экран(let э, _): return "tv-" + э.id.uuidString
        case .техника(let т, _): return "app-" + т.id.uuidString
        case .раздел(let р): return "section-" + р.rawValue
        }
    }
}


    /// Лист закрывается, мастер подачи открывается заполненным (то, что сейчас на листе).
    private func продать(_ заготовка: ЗаготовкаПодачи?) {
        guard let заготовка else { return }
        ОткликСайта.выбор()
        закрыть()
        ПереходыГардероба.продать(заготовка)
    }

    private var блокМеста: some View {
        VStack(alignment: .leading, spacing: 8) {
            ПодписьБлокаДома(т("mh_bed_size"), пояснение: подписьМеста)
            Text(т("mh_bed_common"))

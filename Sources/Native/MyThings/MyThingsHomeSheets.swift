/**
 Лист раздела дома: карточка раздела целиком (как была на главном экране) — строки вещей, шаблоны чипами, этаж и «Лифта
 нет», цоколи, стиль и цвета. Правка живая — только «Готово»: шаблон, кладущий вещь сразу (кровать 160×200, цоколь,
 стиль), пишется в «Моё» тут же; строка или шаблон с замером открывают лист вещи поверх этого листа. Ряда «Подходит
 вам» здесь нет: «Все ›» из листа закрыл бы только лист — ряд стоит на главном экране под строкой раздела.
 */
struct ЛистРазделаДома: View {
    let раздел: РазделДомаМоего
    @ObservedObject private var хранилище = МоёХранилище.shared
    @State private var лист: ЛистДомаМоего? = nil

    init(раздел: РазделДомаМоего) {
        self.раздел = раздел
    }

    var body: some View {
        let запись = хранилище.запись
        ОболочкаРедактораДома(заголовок: раздел.название, сохранить: nil, удалить: nil) {
            карточка(запись)
        }
        .animation(ДвижениеСайта.вставкаСписка, value: запись.дом)
        .sheet(item: $лист) { цель in
            ЛистДомаВид(лист: цель)
        }
    }

    private func открыть(_ цель: ЛистДомаМоего) {
        лист = цель
    }

    @ViewBuilder
    private func карточка(_ запись: ЗаписьМоего) -> some View {
        let дом = запись.дом
        switch раздел {
        case .комнаты:
            КарточкаКомнатДома(дом: дом, открыть: открыть)
        case .проёмы:
            КарточкаПроёмовДома(дом: дом, открыть: открыть)
        case .кровати:
            КарточкаКроватейДома(дом: дом, открыть: открыть)
        case .окна:
            КарточкаОконДома(дом: дом, открыть: открыть)
        case .экраны:
            КарточкаЭкрановДома(дом: дом, устройства: запись.экраны, открыть: открыть)
        case .свет:
            КарточкаСветаДома(дом: дом)
        case .техника:
            КарточкаТехникиДома(дом: дом, открыть: открыть)
        case .стиль:
            КарточкаСтиляДома(дом: дом)
        }
    }
}


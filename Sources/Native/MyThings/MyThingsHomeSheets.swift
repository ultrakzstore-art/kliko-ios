/**
 Лист правки: заголовок, прокрутка до 680 pt, «Отмена» и «Сохранить» (сохранить nil — правка живая, только «Готово»),
 внизу «Удалить» с вопросом. Над клавиатурой — «Готово».
 */
struct ОболочкаРедактораДома<Содержимое: View>: View {
    let заголовок: String
    let можноСохранить: Bool
    let сохранить: (() -> Void)?
    let удалить: (() -> Void)?
    @ViewBuilder let содержимое: () -> Содержимое
    @Environment(\.dismiss) private var закрыть
    @State private var спросить = false

    init(заголовок: String, можноСохранить: Bool = true, сохранить: (() -> Void)?, удалить: (() -> Void)?,
         @ViewBuilder содержимое: @escaping () -> Содержимое) {
        self.заголовок = заголовок
        self.можноСохранить = можноСохранить
        self.сохранить = сохранить
        self.удалить = удалить
        self.содержимое = содержимое
    }

    var body: some View {
        NavigationStack {
            ScrollView {
                VStack(alignment: .leading, spacing: 18) {
                    содержимое()
                    if удалить != nil {
                        МалаяКнопкаАвтоподбора(заголовок: МоёText.т("my_delete"), значок: "trash", опасная: true) {
                            спросить = true
                        }
                    }
                }
                .padding(16)
                .frame(maxWidth: 680)
                .frame(maxWidth: .infinity)
            }
            .scrollDismissesKeyboard(.interactively)
            .background(Theme.фонСтраницы.ignoresSafeArea())
            .navigationTitle(заголовок)
            .navigationBarTitleDisplayMode(.inline)
            .toolbar {
                ToolbarItem(placement: .cancellationAction) {
                    if сохранить != nil {
                        Button(МоёText.т("my_cancel")) { закрыть() }
                    }
                }
                ToolbarItem(placement: .confirmationAction) {
                    Button(сохранить == nil ? МоёText.т("my_done") : МоёText.т("my_save")) {
                        if let сохранить {
                            сохранить()
                            ОткликСайта.успех()
                        }
                        закрыть()
                    }
                    .disabled(сохранить != nil && !можноСохранить)
                }
            }
            .клавиатураМоего()
            .confirmationDialog(МойДомText.т("mh_delete_q"), isPresented: $спросить, titleVisibility: .visible) {
                Button(МоёText.т("my_delete"), role: .destructive) {
                    удалить?()
                    закрыть()
                }
                Button(МоёText.т("my_cancel"), role: .cancel) {}
            }
        }
        .tint(Theme.акцент)
        .presentationDetents([.large])
    }
}


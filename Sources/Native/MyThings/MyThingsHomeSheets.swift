    /// «160×200 · двуспальная»; пусто — подсказка.
    private var подписьМеста: String {
        guard let место = кровать.место else { return т("mh_bed_size_hint") }
        let шаблон = КаталогСтандартов.шаблоны(.спальноеМесто).first { $0.поля[КлючСтандарта.размер] == место }
        let пояснение = шаблон?.текстПояснения ?? ""
        return КаталогСтандартов.показ(место) + (пояснение.isEmpty ? "" : " · " + пояснение)
    }

    /// Названия рядов US и UK — по возрастанию ширины, затем длины.
    private static let импорт: [String] = {
        /* Разбито на шаги с явными типами: цепочка map–sorted–map с кортежем не проходила проверку типов вовремя. */
        func размер(_ имя: String) -> (Double, Double) {
            КаталогСтандартов.пара(КаталогСтандартов.спальныеМестаИмпорт[имя]) ?? (0, 0)
        }
        let имена: [String] = Array(КаталогСтандартов.спальныеМестаИмпорт.keys)
        return имена.sorted { (а: String, б: String) -> Bool in
            let ра: (Double, Double) = размер(а)
            let рб: (Double, Double) = размер(б)
            if ра.0 != рб.0 { return ра.0 < рб.0 }
            if ра.1 != рб.1 { return ра.1 < рб.1 }
            return а < б
        }
    }()

    /// Привезённые матрасы и кровати: Twin, Full, Queen, King…
    private var блокИмпорта: some View {
        VStack(alignment: .leading, spacing: 8) {

/**
 «Все ›» и «Найти подходящее»: лента раздела сразу с включённым «Для моего». Вход в ленту снаружи (ИскомоеЛенты →
 FeedModel.применить) уточнение сбрасывает, а флага «Для моего» у искомого нет (оно Codable — его пишут сохранённые
 поиски): поэтому раздел ждёт здесь один раз, и FeedModel.применить забирает его сразу после сброса. Лента не открылась
 за 10 с — забыто.
 */
@MainActor
enum ЖдущийОтборМоего {
    private static var ждём: (раздел: String, когда: Date)? = nil
    /// Выданный отбор — ещё 3 с: сброс уточнения сразу после входа (очистилось поле поиска — FeedModel.поискОчищен)
    /// его не теряет.
    private static var выдан: (раздел: String, отбор: ОтборМоегоЛенты, когда: Date)? = nil

    static func поставить(_ раздел: String) {
        ждём = (раздел: раздел, когда: Date())
    }

    /// Тот же раздел через миг после входа — тот же отбор; иначе nil.
    static func повторить(раздел: String) -> ОтборМоегоЛенты? {
        guard let был = выдан, был.раздел == раздел, Date().timeIntervalSince(был.когда) < 3 else { return nil }
        return был.отбор
    }

    /**
     Вход в ленту снаружи: ждали этот раздел — отбор «Для моего» по нынешнему «Моему» (с размерами гардероба), если у
     раздела есть такой чип (СовместимостьМоего.профиль) и его профиль не пуст; иначе nil. Другой раздел — ожидание
     остаётся до срока.
     */
    static func забрать(раздел: String) -> ОтборМоегоЛенты? {
        guard let ждали = ждём else { return nil }
        guard Date().timeIntervalSince(ждали.когда) < 10 else {
            ждём = nil
            return nil
        }
        guard ждали.раздел == раздел else { return nil }
        ждём = nil
        guard Config.моё, let профиль = СовместимостьМоего.профиль(раздела: раздел) else { return nil }
        let хранилище = МоёХранилище.shared
        хранилище.подготовить()
        let моё: ЗаписьМоего = ПодборДляВас.моёДляСверки(хранилище.запись)
        guard !СовместимостьМоего.пусто(профиль, моё: моё) else { return nil }
        let отбор = ОтборМоегоЛенты(моё: моё)
        выдан = (раздел: раздел, отбор: отбор, когда: Date())
        return отбор
    }
}

/// Переходы ряда: объявление окном поверх всего, лента раздела с «Для моего».
@MainActor
enum ПереходыМоего {
    /**
     Лента раздела с «Для моего» (где такого чипа нет — просто лента раздела). «Моё» открыто окном поверх — оно
     закроется само (ПереходыГардероба.найти). Звать с экрана раздела, а не из его листа: лист закрыл бы только себя.
     */
    static func найти(раздел: String, сОтбором: Bool = true) {
        guard !раздел.isEmpty else { return }
        if let слово = поискВРазделе[раздел] {
            /* Ряд ТВ — только кронштейны (ПодборДляВас.словаРаздела), а чипа «Для моего» у «ТВ и аудио» нет: весь
               раздел открыл бы телевизоры и колонки. Поэтому — поиск кронштейнов в этом разделе. */
            let искомое = ИскомоеЛенты(текст: слово, раздел: раздел)
            ПереходыГардероба.послеОкон {
                WebBridge.shared.открытьЭкран(.найти(искомое), запасной: nil)
            }
            return
        }
        /* Ряд одних «Проверьте» (сОтбором false): точных нет, и «Для моего» оставил бы ленту пустой — лента как есть. */
        if сОтбором { ЖдущийОтборМоего.поставить(раздел) }
        ПереходыГардероба.найти(раздел: раздел)
    }

    /// Раздел шире ряда и без чипа «Для моего» — поисковый запрос в нём (слово названий объявлений, а не надпись
    /// экрана: названия на площадке — по-русски, как и слова сверки ПодборДляВас.словаРаздела).
    private static let поискВРазделе: [String: String] = ["tv-audio": "кронштейн"]

    /// «Найти подходящее» раздела «Моего»: его лента (ПодборРазделаМоего.лента); искать негде — ничего.
    static func найти(_ подбор: ПодборРазделаМоего) {
        let хранилище = МоёХранилище.shared
        хранилище.подготовить()
        guard let ключ = подбор.лента(хранилище.запись) else { return }
        найти(раздел: ключ)
    }

    /// Объявление окном поверх того, что на экране (поверх листа тоже).
    static func открыть(_ товар: Listing) {
        ПереходыГардероба.открыть(товар)
    }
}


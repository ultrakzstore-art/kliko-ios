/// Состояние одного ряда (у каждого ряда своё, @StateObject); страницы разделов — общая память всех рядов на 15 минут.
@MainActor
final class НаходкиРазделаМоего: ObservableObject {
    enum Состояние: Equatable {
        /// Ряд ещё не появлялся на экране.
        case неизвестно
        /// Сверять не с чем: раздел не заполнен или ряда для него нет.
        case нечего
        /// Есть что искать, ответа или сверки ещё нет.
        case ждём
        /// Ответ есть, ничего не подошло (или сеть не ответила) — ряда нет.
        case пусто
        case есть
    }

    @Published private(set) var состояние: Состояние = .неизвестно
    /// Ряд: до восьми, «подходит» впереди.
    @Published private(set) var находки: [НаходкаДляВас] = []

    private struct Страница {
        let товары: [Listing]
        let когда: Date
        let где: ГдеИскать
        let кто: String
    }

    /// Общая память рядов: раздел ленты → первая страница (тот же город и человек; свежая — 15 минут).
    private static var страницы: [String: Страница] = [:]
    private static var неудачи: [String: Date] = [:]

    private var подбор: ПодборРазделаМоего? = nil
    private var запросы: [ЗапросПодбораМоего] = []
    private var моё = ЗаписьМоего()
    private var загрузка: Task<Void, Never>? = nil
    /// Растёт с каждой загрузкой: закончилась не последняя — ссылку на последнюю не стираем.
    private var номерЗагрузки = 0
    private var сверка: Task<Void, Never>? = nil
    /// Сверка в пути — «ничего не подошло» ещё не сказано (без мелькания «Найти подходящее» перед рядом).
    private var сверяем = false
    private var поколение = 0
    private var отложено: Task<Void, Never>? = nil

    init() {}

    /// Ряд появился на экране: запросы по «Моему», сверка по памяти — сразу, в сеть — только за недостающим.
    func войти(_ подбор: ПодборРазделаМоего, _ запись: ЗаписьМоего) {
        отложено?.cancel()
        отложено = nil
        self.подбор = подбор
        let дляСверки: ЗаписьМоего = ПодборДляВас.моёДляСверки(запись)
        моё = дляСверки
        запросы = подбор.запросы(дляСверки)
        guard !запросы.isEmpty else {
            остановить()
            поставить([])
            return
        }
        пересверить()
        догрузить()
    }

    /// Правка «Моего», пока ряд на экране: то же, что войти, через паузу (живая правка листа — не на каждую букву).
    func сменилось(_ подбор: ПодборРазделаМоего, _ запись: ЗаписьМоего) {
        отложено?.cancel()
        отложено = Task { [weak self] in
            try? await Task.sleep(nanoseconds: 350_000_000)
            guard !Task.isCancelled else { return }
            self?.войти(подбор, запись)
        }
    }

    /// Ряд ушёл с экрана: загрузка и сверка отменяются (загруженное остаётся в общей памяти).
    func уйти() {
        отложено?.cancel()
        отложено = nil
        остановить()
    }

    private func остановить() {
        загрузка?.cancel()
        загрузка = nil
        сверка?.cancel()
        сверка = nil
        сверяем = false
        поколение += 1
    }

    // MARK: Загрузка

    /// Разделы без свежей страницы (15 минут, этот город и человек) и без недавней неудачи — одной загрузкой.
    private func догрузить() {
        guard загрузка == nil, !запросы.isEmpty else { return }
        let сейчас = Date()
        let где = ГдеИскать.сохранённое()
        let кто = СессияПриложения.shared.id
        var нужно: [String] = []
        for запрос in запросы where !нужно.contains(запрос.раздел) {
            if let была = Self.неудачи[запрос.раздел], сейчас.timeIntervalSince(была) < ПодборРазделаМоего.повтор {
                continue
            }
            if let страница = Self.страницы[запрос.раздел], страница.где == где, страница.кто == кто,
               сейчас.timeIntervalSince(страница.когда) <= ПодборДляВас.срок {
                continue
            }
            нужно.append(запрос.раздел)
        }
        guard !нужно.isEmpty else { return }
        let наСтраницу: Int = РежимУстройства.сейчас ? ПодборДляВас.наСтраницуЛёгкий : ПодборДляВас.наСтраницу
        номерЗагрузки += 1
        let номер = номерЗагрузки
        загрузка = Task { [weak self] in
            let ответы: [String: [Listing]] = await НаходкиРазделаМоего.запросить(нужно, где: где,
                                                                                 наСтраницу: наСтраницу)
            guard let self else { return }
            if self.номерЗагрузки == номер { self.загрузка = nil }
            guard !Task.isCancelled else { return }
            self.принять(ответы, разделы: нужно, где: где, кто: кто)
            /* Пока грузили, «Моё» сменилось и понадобился новый раздел (войти → догрузить вышел: загрузка была в
               пути) — за ним сейчас. Не по кругу: только что загруженные свежи, не прошедшие ждут минуту. */
            self.догрузить()
        }
    }

    private func принять(_ ответы: [String: [Listing]], разделы: [String], где: ГдеИскать, кто: String) {
        let сейчас = Date()
        for раздел in разделы {
            if let товары = ответы[раздел] {
                Self.страницы[раздел] = Страница(товары: товары, когда: сейчас, где: где, кто: кто)
                Self.неудачи[раздел] = nil
            } else {
                Self.неудачи[раздел] = сейчас
            }
        }
        пересверить()
    }

    /// Первая страница каждого раздела, параллельно; GET без куков и без «Моего» в адресе — как у «Для вас».
    nonisolated private static func запросить(_ разделы: [String], где: ГдеИскать, наСтраницу: Int) async
        -> [String: [Listing]] {
        await withTaskGroup(of: ОтветРазделаРядаМоего.self, returning: [String: [Listing]].self) { группа in
            for раздел in разделы {
                группа.addTask {
                    var з = ListingsAPI.Запрос()
                    з.per = наСтраницу
                    з.cat = раздел
                    з.где = где
                    з.фильтры.сортировка = .новыеПодряд
                    let страница: ListingsPage? = try? await ListingsAPI.загрузить(з, куки: [:]).страница
                    return ОтветРазделаРядаМоего(раздел: раздел, товары: страница?.items)
                }
            }
            var итог: [String: [Listing]] = [:]
            while let ответ = await группа.next() {
                if let товары = ответ.товары { итог[ответ.раздел] = товары }
            }
            return итог
        }
    }

    // MARK: Сверка и показ

    /// Сверка страниц этого города и человека (и устаревших — пока грузится свежая) не на главной нити; пришла новая
    /// правка раньше — прежний итог не ставится.
    private func пересверить() {
        поколение += 1
        let номер = поколение
        сверка?.cancel()
        сверка = nil
        сверяем = false
        guard let выбран = подбор else {
            обновитьСостояние()
            return
        }
        let где = ГдеИскать.сохранённое()
        let кто = СессияПриложения.shared.id
        var готовые: [String: [Listing]] = [:]
        for запрос in запросы {
            guard let страница = Self.страницы[запрос.раздел], страница.где == где, страница.кто == кто else {
                continue
            }
            готовые[запрос.раздел] = страница.товары
        }
        guard !готовые.isEmpty else {
            поставить([])
            return
        }
        let вход = ВходСверкиРядаМоего(страницы: готовые, запросы: запросы, моё: моё, я: кто, группа: выбран.группа)
        сверяем = true
        обновитьСостояние()
        сверка = Task { [weak self] in
            let фон = Task.detached(priority: .userInitiated) { () -> ВыходСверкиРядаМоего in
                ВыходСверкиРядаМоего(находки: ПодборРазделаМоего.ряд(вход.страницы, по: вход.запросы, моё: вход.моё,
                                                                      я: вход.я, группа: вход.группа))
            }
            let выход: ВыходСверкиРядаМоего = await фон.value
            guard let self, !Task.isCancelled, номер == self.поколение else { return }
            self.сверяем = false
            self.поставить(выход.находки)
        }
    }

    private func поставить(_ новые: [НаходкаДляВас]) {
        if новые != находки { находки = новые }
        обновитьСостояние()
    }

    private func обновитьСостояние() {
        let новое: Состояние
        if запросы.isEmpty {
            новое = .нечего
        } else if !находки.isEmpty {
            новое = .есть
        } else if !сверяем && загрузка == nil && всеОтветили {
            /* Пока свежая страница в пути, «ничего не подошло» по устаревшей не говорим: без мелькания «Найти
               подходящее» перед рядом. Загрузка снимает себя до принять → пересверить — итог всё равно посчитается. */
            новое = .пусто
        } else {
            новое = .ждём
        }
        guard новое != состояние else { return }
        состояние = новое
        /* Журнал CI (только отладка): ряд раздела собрался или пуст — видно без снимка. */
        if новое == .есть || новое == .пусто {
            let имя: String = подбор?.rawValue ?? "?"
            ДымоваяПроверка.отметить("my-row " + имя + " " + String(находки.count))
        }
    }

    /// На каждый раздел запросов есть страница этого города и человека или недавняя неудача.
    private var всеОтветили: Bool {
        let сейчас = Date()
        let где = ГдеИскать.сохранённое()
        let кто = СессияПриложения.shared.id
        for запрос in запросы {
            if let страница = Self.страницы[запрос.раздел], страница.где == где, страница.кто == кто { continue }
            if let была = Self.неудачи[запрос.раздел], сейчас.timeIntervalSince(была) < ПодборРазделаМоего.повтор {
                continue
            }
            return false
        }
        return true
    }
}

// MARK: - Ряд

/**
 Ряд «Подходит вам» под разделом «Моего»: «Подходит вам» и «Все ›», карточки по 148 pt в горизонтальной прокрутке, под
 каждой — причина. Пока ждём ответа и когда ничего не подошло — ряда нет (полоса нулевой высоты, на ней живут onAppear
 и onDisappear); раздел заполнен, а ряда нет — кнопка «Найти подходящее» (найтиБезРяда). Отступ сверху — только когда
 что-то показано: пустой ряд места не занимает, поэтому ставить его в VStack с spacing 0 под строкой раздела, внутри
 карточки раздела. Отдельным блоком (без своей карточки вокруг) — вКарточке: true, тогда карточку рисует сам ряд и
 только когда в ней что-то есть. «Моё» ряд читает сам (МоёХранилище.shared) — экран передаёт только раздел.
 */
struct РядПодходитМоего: View {
    let подбор: ПодборРазделаМоего
    let найтиБезРяда: Bool
    let сверху: CGFloat
    let вКарточке: Bool
    @ObservedObject private var хранилище = МоёХранилище.shared
    @StateObject private var модель = НаходкиРазделаМоего()

    init(_ подбор: ПодборРазделаМоего, найтиБезРяда: Bool = true, сверху: CGFloat = 12, вКарточке: Bool = false) {
        self.подбор = подбор
        self.найтиБезРяда = найтиБезРяда
        self.сверху = сверху
        self.вКарточке = вКарточке
    }

    private func текст(_ ключ: String) -> String { РядМоегоText.т(ключ) }

    var body: some View {
        VStack(alignment: .leading, spacing: 0) {
            /* Полоса нулевой высоты: на ней живут onAppear и onDisappear, пока ряда нет. */
            Color.clear
                .frame(height: 0)
                .accessibilityHidden(true)
            содержимое
        }
        .animation(ДвижениеСайта.появление, value: модель.состояние)
        .onAppear {
            хранилище.подготовить()
            модель.войти(подбор, хранилище.запись)
        }
        .onDisappear { модель.уйти() }
        .onChange(of: хранилище.запись) { _, новая in модель.сменилось(подбор, новая) }
        .onChange(of: подбор) { _, новый in модель.войти(новый, хранилище.запись) }
    }

    private var естьРяд: Bool { модель.состояние == .есть && !модель.находки.isEmpty }

    /// Ряда нет, а раздел заполнен: куда ведёт «Найти подходящее»; пока ждём ответа — nil (без мелькания).
    private var разделПоиска: String? {
        guard найтиБезРяда else { return nil }
        switch модель.состояние {
        case .нечего, .пусто:
            break
        case .неизвестно, .ждём, .есть:
            return nil
        }
        let запись = хранилище.запись
        guard подбор.заполнено(запись) else { return nil }
        return подбор.лента(запись)
    }

    @ViewBuilder
    private var содержимое: some View {
        if естьРяд {
            if вКарточке {
                ряд
                    .карточкаМоего(поля: 14)
                    .padding(.top, сверху)
                    .transition(.opacity)
            } else {
                ряд
                    .padding(.top, сверху)
                    .transition(.opacity)
            }
        } else if let ключ = разделПоиска {
            if вКарточке {
                КнопкаНайтиМоего(раздел: ключ)
                    .карточкаМоего(поля: 14)
                    .padding(.top, сверху)
                    .transition(.opacity)
            } else {
                КнопкаНайтиМоего(раздел: ключ)
                    .padding(.top, сверху)
                    .transition(.opacity)
            }
        }
    }

    private var ряд: some View {
        VStack(alignment: .leading, spacing: 6) {
            шапкаРяда
            ScrollView(.horizontal, showsIndicators: false) {
                HStack(alignment: .top, spacing: 10) {
                    ForEach(модель.находки) { находка in
                        ячейка(находка)
                    }
                }
                .padding(.vertical, 2)
            }
        }
    }

    private var шапкаРяда: some View {
        HStack(spacing: 6) {
            Image(systemName: "checkmark.seal.fill")
                .font(.subheadline.weight(.semibold))
                .foregroundStyle(Theme.зелёный2)
                .accessibilityHidden(true)
            Text(текст("mfr_title"))
                .font(.subheadline.weight(.bold))
                .foregroundStyle(Theme.текст)
                .lineLimit(1)
                .accessibilityAddTraits(.isHeader)
            Spacer(minLength: 8)
            Button(action: всеВЛенте) {
                HStack(spacing: 3) {
                    Text(текст("mfr_all"))
                    Image(systemName: "chevron.forward")
                        .font(.caption.weight(.bold))
                        .accessibilityHidden(true)
                }
                .font(.subheadline.weight(.semibold))
                .foregroundStyle(Theme.акцент)
                .frame(minWidth: 44, minHeight: 44)
                .contentShape(Rectangle())
            }
            .buttonStyle(.plain)
            .accessibilityLabel(текст("mfr_all"))
            .accessibilityHint(ПодборРазделаМоего.подсказкаЛенты(разделВсех))
        }
    }

    /// «Все ›»: раздел ленты, откуда больше карточек ряда; иначе — лента раздела «Моего».
    private var разделВсех: String {
        let запасной: String = подбор.лента(хранилище.запись) ?? ""
        return ПодборРазделаМоего.главныйРаздел(модель.находки) ?? запасной
    }

    private func всеВЛенте() {
        ОткликСайта.выбор()
        ПереходыМоего.найти(раздел: разделВсех)
    }

    private func ячейка(_ находка: НаходкаДляВас) -> some View {
        Button {
            ОткликСайта.выбор()
            ПереходыМоего.открыть(находка.товар)
        } label: {
            КарточкаНаходкиМоего(находка: находка)
        }
        .buttonStyle(НажатиеСайта())
        .accessibilityHint(текст("mfr_cell_a11y"))
    }
}


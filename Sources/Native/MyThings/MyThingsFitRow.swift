/// Страницы разделов в фоновую сверку и обратно: Listing не помечен Sendable, а данные только читаются.
private struct ВходСверкиРядаМоего: @unchecked Sendable {
    let страницы: [String: [Listing]]
    let запросы: [ЗапросПодбораМоего]
    let моё: ЗаписьМоего
    let я: String
    let группа: ГруппаДляВас
    let сезон: [ПравилоСезонаДляВас]
    let видели: Set<String>
}

private struct ВыходСверкиРядаМоего: @unchecked Sendable {
    let итог: ПодборРазделаМоего.ИтогРядаМоего
}

/// Ответ одного раздела; nil — запрос не прошёл.
private struct ОтветРазделаРядаМоего: @unchecked Sendable {
    let раздел: String
    let товары: [Listing]?
    /// Отпечаток тела, с которым страница пришла с отбором сервера; «» — обычный GET (или сервер тело не применил).
    var тело = ""
    /// POST был, но не прошёл или сервер тело не применил — дальше до перезапуска только GET.
    var отказ = false
}

/// Состояние одного ряда (у каждого ряда своё, @StateObject); страницы разделов — общая память всех рядов на 15 минут.
@MainActor
final class НаходкиРазделаМоего: ObservableObject {
    enum Состояние: Equatable {
        /// Ряд ещё не появлялся на экране.
        case неизвестно
        /// Сверять не с чем: раздел не заполнен или ряда для него нет.
        case нечего
        /// Есть что искать, ответа или сверки ещё нет.
        case ждём
        /// Ответ есть, ничего не подошло (или сеть не ответила) — ряда нет.
        case пусто
        case есть
    }

    @Published private(set) var состояние: Состояние = .неизвестно
    /// Ряд: до восьми, новые с прошлого просмотра и «подходит» впереди.
    @Published private(set) var находки: [НаходкаДляВас] = []
    /// Новых с прошлого просмотра (НовинкиДляВас) — «Подходит вам · 2 новых».
    @Published private(set) var новых = 0
    /// В ряду одни «Проверьте» — шапка без галочки, «Может подойти».
    @Published private(set) var толькоПроверить = false
    /// Разделы, по которым ряд уже сверялся, — точка отсчёта новинок.
    private var загруженные: Set<String> = []

    private struct Страница {
        let товары: [Listing]
        let когда: Date
        let где: ГдеИскать
        let кто: String
        /// Отпечаток тела POST (только в памяти); «» — GET. Сменилось тело (правка «Моего») — страница устарела.
        let тело: String
    }

    /// Общая память рядов: раздел ленты → первая страница (тот же город и человек; свежая — 15 минут).
    private static var страницы: [String: Страница] = [:]
    private static var неудачи: [String: Date] = [:]

    private var подбор: ПодборРазделаМоего? = nil
    private var запросы: [ЗапросПодбораМоего] = []
    private var моё = ЗаписьМоего()
    private var загрузка: Task<Void, Never>? = nil
    /// Растёт с каждой загрузкой: закончилась не последняя — ссылку на последнюю не стираем.
    private var номерЗагрузки = 0
    private var сверка: Task<Void, Never>? = nil
    /// Сверка в пути — «ничего не подошло» ещё не сказано (без мелькания «Найти подходящее» перед рядом).
    private var сверяем = false
    private var поколение = 0
    private var отложено: Task<Void, Never>? = nil

    init() {}

    /// Ряд появился на экране: запросы по «Моему», сверка по памяти — сразу, в сеть — только за недостающим.
    func войти(_ подбор: ПодборРазделаМоего, _ запись: ЗаписьМоего) {
        отложено?.cancel()
        отложено = nil
        self.подбор = подбор
        let дляСверки: ЗаписьМоего = ПодборДляВас.моёДляСверки(запись)
        моё = дляСверки
        запросы = подбор.запросы(дляСверки)
        guard !запросы.isEmpty else {
            остановить()
            /* Разделы прежней выдачи — прочь: иначе пустая выдача после «Удалить всё «Моё»» отметила бы их видеными
               и заново создала foryou-seen.json с разделами стёртого «Моего». */
            загруженные = []
            поставить([])
            return
        }
        пересверить()
        догрузить()
    }

    /// Правка «Моего», пока ряд на экране: то же, что войти, через паузу (живая правка листа — не на каждую букву).
    func сменилось(_ подбор: ПодборРазделаМоего, _ запись: ЗаписьМоего) {
        отложено?.cancel()
        отложено = Task { [weak self] in
            try? await Task.sleep(nanoseconds: 350_000_000)
            guard !Task.isCancelled else { return }
            self?.войти(подбор, запись)
        }
    }

    /// Ряд ушёл с экрана: загрузка и сверка отменяются (загруженное остаётся в общей памяти); его карточки — показаны
    /// (новинки «Для вас» больше не считают их новыми).
    func уйти() {
        отложено?.cancel()
        отложено = nil
        остановить()
        if состояние == .есть { НовинкиДляВас.shared.показаны(находки) }
    }

    private func остановить() {
        загрузка?.cancel()
        загрузка = nil
        сверка?.cancel()
        сверка = nil
        сверяем = false
        поколение += 1
    }

    // MARK: Загрузка

    /**
     Разделы без свежей страницы (15 минут, этот город и человек, то же тело POST) и без недавней неудачи — одной
     загрузкой. Пачка 84: признаки подбора на сервере (rules.fit_filters, ПризнакиПодбораСервера) — до первой загрузки;
     вид объявлен — раздел POST-ом со значениями стандартов (как у «Для вас»), иначе GET.
     */
    private func догрузить() {
        guard загрузка == nil, !запросы.isEmpty else { return }
        guard let объявлено = ПризнакиПодбораСервера.действующие else {
            номерЗагрузки += 1
            let номер = номерЗагрузки
            загрузка = Task<Void, Never> { [weak self] in
                _ = await ПризнакиПодбораСервера.прочитать()
                guard let self else { return }
                if self.номерЗагрузки == номер { self.загрузка = nil }
                guard !Task.isCancelled else { return }
                self.догрузить()
            }
            return
        }
        let сейчас = Date()
        let где = ГдеИскать.сохранённое()
        let кто = СессияПриложения.shared.id
        let тела: [String: [String: String]] = ОтборСервераДляВас.тела(запросы, моё: моё, объявлено: объявлено)
        var нужно: [String] = []
        for запрос in запросы where !нужно.contains(запрос.раздел) {
            if let была = Self.неудачи[запрос.раздел], сейчас.timeIntervalSince(была) < ПодборРазделаМоего.повтор {
                continue
            }
            if let страница = Self.страницы[запрос.раздел], страница.где == где, страница.кто == кто,
               сейчас.timeIntervalSince(страница.когда) <= ПодборДляВас.срок,
               страница.тело == ОтборСервераДляВас.отпечаток(тела[запрос.раздел]) {
                continue
            }
            нужно.append(запрос.раздел)
        }
        guard !нужно.isEmpty else { return }
        let своиТела: [String: [String: String]] = тела.filter { (пара: (key: String, value: [String: String])) -> Bool in
            нужно.contains(пара.key)
        }
        let наСтраницу: Int = РежимУстройства.сейчас ? ПодборДляВас.наСтраницуЛёгкий : ПодборДляВас.наСтраницу
        /* Приватность вступления «Для вас»: значения стандартов уходят телом POST и отсюда — отметка до запроса. */
        if !своиТела.isEmpty { ПризнакиПодбораСервера.отметитьОтправку() }
        номерЗагрузки += 1
        let номер = номерЗагрузки
        загрузка = Task<Void, Never> { [weak self] in
            let ответы: [String: ОтветРазделаРядаМоего] = await НаходкиРазделаМоего.запросить(нужно, где: где,
                                                                                             наСтраницу: наСтраницу,
                                                                                             тела: своиТела)
            guard let self else { return }
            if self.номерЗагрузки == номер { self.загрузка = nil }
            guard !Task.isCancelled else { return }
            self.принять(ответы, разделы: нужно, где: где, кто: кто)
            /* Пока грузили, «Моё» сменилось и понадобился новый раздел (войти → догрузить вышел: загрузка была в
               пути) — за ним сейчас. Не по кругу: только что загруженные свежи, не прошедшие ждут минуту, после отказа
               POST тела пусты, как и отпечатки взятых GET. */
            self.догрузить()
        }
    }

    private func принять(_ ответы: [String: ОтветРазделаРядаМоего], разделы: [String], где: ГдеИскать, кто: String) {
        let сейчас = Date()
        var былОтказ = false
        for раздел in разделы {
            if let ответ = ответы[раздел], let товары = ответ.товары {
                Self.страницы[раздел] = Страница(товары: товары, когда: сейчас, где: где, кто: кто, тело: ответ.тело)
                Self.неудачи[раздел] = nil
            } else {
                Self.неудачи[раздел] = сейчас
            }
            if ответы[раздел]?.отказ == true { былОтказ = true }
        }
        if былОтказ { ПризнакиПодбораСервера.отказ() }
        пересверить()
    }

    /**
     Первая страница каждого раздела, параллельно; без куков и без «Моего» в адресе — как у «Для вас». Есть тело — POST
     с ним (только значения стандартов); не прошёл — тот же раздел GET; без fit_applied — та же лента, что у GET.
     */
    nonisolated private static func запросить(_ разделы: [String], где: ГдеИскать, наСтраницу: Int,
                                              тела: [String: [String: String]]) async
        -> [String: ОтветРазделаРядаМоего] {
        await withTaskGroup(of: ОтветРазделаРядаМоего.self,
                            returning: [String: ОтветРазделаРядаМоего].self) { группа in
            for раздел in разделы {
                let тело = тела[раздел]
                группа.addTask {
                    var з = ListingsAPI.Запрос()
                    з.per = наСтраницу
                    з.cat = раздел
                    з.где = где
                    з.фильтры.сортировка = .новыеПодряд
                    var страница: ListingsPage? = nil
                    var отпечаток = ""
                    var отказ = false
                    if let тело {
                        страница = try? await ОтборСервераДляВас.загрузить(з, тело: тело)
                        if let пришла = страница, пришла.применёноСервером != nil {
                            отпечаток = ОтборСервераДляВас.отпечаток(тело)
                        } else {
                            отказ = true
                        }
                    }
                    if страница == nil {
                        страница = try? await ListingsAPI.загрузить(з, куки: [:]).страница
                    }
                    return ОтветРазделаРядаМоего(раздел: раздел, товары: страница?.items, тело: отпечаток, отказ: отказ)
                }
            }
            var итог: [String: ОтветРазделаРядаМоего] = [:]
            while let ответ = await группа.next() {
                итог[ответ.раздел] = ответ
            }
            return итог
        }
    }

    // MARK: Сверка и показ

    /// Сверка страниц этого города и человека (и устаревших — пока грузится свежая) не на главной нити; пришла новая
    /// правка раньше — прежний итог не ставится.
    private func пересверить() {
        поколение += 1
        let номер = поколение
        сверка?.cancel()
        сверка = nil
        сверяем = false
        guard let выбран = подбор else {
            обновитьСостояние()
            return
        }
        let где = ГдеИскать.сохранённое()
        let кто = СессияПриложения.shared.id
        var готовые: [String: [Listing]] = [:]
        for запрос in запросы {
            guard let страница = Self.страницы[запрос.раздел], страница.где == где, страница.кто == кто else {
                continue
            }
            готовые[запрос.раздел] = страница.товары
        }
        guard !готовые.isEmpty else {
            загруженные = []
            поставить([])
            return
        }
        /* Отладка CI (verify): сколько объявлений пришло по разделам — почему ряд пустой (только DEBUG, stderr). */
        var пришлоПоРазделам: [String] = []
        for (раздел, товары) in готовые {
            пришлоПоРазделам.append(раздел + ":" + String(товары.count))
        }
        ДымоваяПроверка.отметить("my-row-in " + пришлоПоРазделам.sorted().joined(separator: " "))
        let сезон: [ПравилоСезонаДляВас] = СезонДляВас.действующие(город: где.город)
        let видели: Set<String> = НовинкиДляВас.shared.снимок()
        let вход = ВходСверкиРядаМоего(страницы: готовые, запросы: запросы, моё: моё, я: кто, группа: выбран.группа,
                                       сезон: сезон, видели: видели)
        загруженные = Set(готовые.keys)
        сверяем = true
        обновитьСостояние()
        сверка = Task { [weak self] in
            let фон = Task.detached(priority: .userInitiated) { () -> ВыходСверкиРядаМоего in
                ВыходСверкиРядаМоего(итог: ПодборРазделаМоего.собрать(вход.страницы, по: вход.запросы, моё: вход.моё,
                                                                       я: вход.я, группа: вход.группа,
                                                                       сезон: вход.сезон, видели: вход.видели))
            }
            let выход: ВыходСверкиРядаМоего = await фон.value
            guard let self, !Task.isCancelled, номер == self.поколение else { return }
            let вРяду: Int = выход.итог.ряд.count
            let всего: Int = выход.итог.все.count
            ДымоваяПроверка.отметить("my-row-out ряд " + String(вРяду) + " проверить " + String(всего))
            self.сверяем = false
            self.поставить(выход.итог.ряд, все: выход.итог.все)
        }
    }

    /**
     Показ: новинки с прошлого просмотра — первыми и числом в шапке; одни «Проверьте» — шапка без галочки. Точка отсчёта
     новинок (раздел, которого телефон ещё не видел) — по всем находкам группы, и «Проверьте» тоже, а не только по восьми
     в ряду: иначе остальные стали бы «новыми» на полке «Для вас».
     */
    private func поставить(_ новые: [НаходкаДляВас], все: [НаходкаДляВас] = []) {
        if !все.isEmpty { _ = НовинкиДляВас.shared.учесть(все, разделы: загруженные) }
        let порядок: [НаходкаДляВас] = НовинкиДляВас.shared.учесть(новые, разделы: загруженные)
        if порядок != находки { находки = порядок }
        let число: Int = НовинкиДляВас.shared.сколькоНовых(порядок)
        if число != новых { новых = число }
        let проверка: Bool = !порядок.isEmpty && порядок.allSatisfy { (н: НаходкаДляВас) -> Bool in
            н.уровень == .проверить
        }
        if проверка != толькоПроверить { толькоПроверить = проверка }
        обновитьСостояние()
    }

    private func обновитьСостояние() {
        let новое: Состояние
        if запросы.isEmpty {
            новое = .нечего
        } else if !находки.isEmpty {
            новое = .есть
        } else if !сверяем && загрузка == nil && всеОтветили {
            /* Пока свежая страница в пути, «ничего не подошло» по устаревшей не говорим: без мелькания «Найти
               подходящее» перед рядом. Загрузка снимает себя до принять → пересверить — итог всё равно посчитается. */
            новое = .пусто
        } else {
            новое = .ждём
        }
        guard новое != состояние else { return }
        состояние = новое
        /* Журнал CI (только отладка): ряд раздела собрался или пуст — видно без снимка. */
        if новое == .есть || новое == .пусто {
            let имя: String = подбор?.rawValue ?? "?"
            ДымоваяПроверка.отметить("my-row " + имя + " " + String(находки.count))
        }
    }

    /// На каждый раздел запросов есть страница этого города и человека или недавняя неудача.
    private var всеОтветили: Bool {
        let сейчас = Date()
        let где = ГдеИскать.сохранённое()
        let кто = СессияПриложения.shared.id
        for запрос in запросы {
            if let страница = Self.страницы[запрос.раздел], страница.где == где, страница.кто == кто { continue }
            if let была = Self.неудачи[запрос.раздел], сейчас.timeIntervalSince(была) < ПодборРазделаМоего.повтор {
                continue
            }
            return false
        }
        return true
    }
}

// MARK: - Ряд

/**
 Ряд «Подходит вам» под разделом «Моего»: «Подходит вам» и «Все ›», карточки по 148 pt в горизонтальной прокрутке, под
 каждой — причина. Пока ждём ответа и когда ничего не подошло — ряда нет (полоса нулевой высоты, на ней живут onAppear
 и onDisappear); раздел заполнен, а ряда нет — кнопка «Найти подходящее» (найтиБезРяда). Отступ сверху — только когда
 что-то показано: пустой ряд места не занимает, поэтому ставить его в VStack с spacing 0 под строкой раздела, внутри
 карточки раздела. Отдельным блоком (без своей карточки вокруг) — вКарточке: true, тогда карточку рисует сам ряд и
 только когда в ней что-то есть. «Моё» ряд читает сам (МоёХранилище.shared) — экран передаёт только раздел.
 */
struct РядПодходитМоего: View {
    let подбор: ПодборРазделаМоего
    let найтиБезРяда: Bool
    let сверху: CGFloat
    let вКарточке: Bool
    @ObservedObject private var хранилище = МоёХранилище.shared
    @StateObject private var модель = НаходкиРазделаМоего()

    init(_ подбор: ПодборРазделаМоего, найтиБезРяда: Bool = true, сверху: CGFloat = 12, вКарточке: Bool = false) {
        self.подбор = подбор
        self.найтиБезРяда = найтиБезРяда
        self.сверху = сверху
        self.вКарточке = вКарточке
    }

    private func текст(_ ключ: String) -> String { РядМоегоText.т(ключ) }

    var body: some View {
        VStack(alignment: .leading, spacing: 0) {
            /* Полоса нулевой высоты: на ней живут onAppear и onDisappear, пока ряда нет. */
            Color.clear
                .frame(height: 0)
                .accessibilityHidden(true)
            содержимое
        }
        .animation(ДвижениеСайта.появление, value: модель.состояние)
        .onAppear {
            хранилище.подготовить()
            модель.войти(подбор, хранилище.запись)
        }
        .onDisappear { модель.уйти() }
        .onChange(of: хранилище.запись) { _, новая in модель.сменилось(подбор, новая) }
        .onChange(of: подбор) { _, новый in модель.войти(новый, хранилище.запись) }
    }

    private var естьРяд: Bool { модель.состояние == .есть && !модель.находки.isEmpty }

    /// Ряда нет, а раздел заполнен: куда ведёт «Найти подходящее»; пока ждём ответа — nil (без мелькания).
    private var разделПоиска: String? {
        guard найтиБезРяда else { return nil }
        switch модель.состояние {
        case .нечего, .пусто:
            break
        case .неизвестно, .ждём, .есть:
            return nil
        }
        let запись = хранилище.запись
        guard подбор.заполнено(запись) else { return nil }
        return подбор.лента(запись)
    }

    @ViewBuilder
    private var содержимое: some View {
        if естьРяд {
            if вКарточке {
                ряд
                    .карточкаМоего(поля: 14)
                    .padding(.top, сверху)
                    .transition(.opacity)
            } else {
                ряд
                    .padding(.top, сверху)
                    .transition(.opacity)
            }
        } else if let ключ = разделПоиска {
            if вКарточке {
                КнопкаНайтиМоего(раздел: ключ)
                    .карточкаМоего(поля: 14)
                    .padding(.top, сверху)
                    .transition(.opacity)
            } else {
                КнопкаНайтиМоего(раздел: ключ)
                    .padding(.top, сверху)
                    .transition(.opacity)
            }
        }
    }

    private var ряд: some View {
        VStack(alignment: .leading, spacing: 6) {
            шапкаРяда
            ScrollView(.horizontal, showsIndicators: false) {
                HStack(alignment: .top, spacing: 10) {
                    ForEach(модель.находки) { находка in
                        ячейка(находка)
                    }
                }
                .padding(.vertical, 2)
            }
        }
    }

    /// «Подходит вам» (с новинками — «Подходит вам · 2 новых»); в ряду одни «Проверьте» — «Может подойти», без галочки.
    private var заголовокРяда: String {
        let основа: String = модель.толькоПроверить ? НовинкиМоегоText.т("nm_row_check") : текст("mfr_title")
        guard модель.новых > 0 else { return основа }
        return основа + " · " + НовинкиМоегоText.сколькоНовых(модель.новых)
    }

    private var шапкаРяда: some View {
        HStack(spacing: 6) {
            Image(systemName: модель.толькоПроверить ? УровеньАвтоподбора.проверить.значок : "checkmark.seal.fill")
                .font(.subheadline.weight(.semibold))
                .foregroundStyle(модель.толькоПроверить ? УровеньАвтоподбора.проверить.краска : Theme.зелёный2)
                .accessibilityHidden(true)
            Text(заголовокРяда)
                .font(.subheadline.weight(.bold))
                .foregroundStyle(Theme.текст)
                .lineLimit(1)
                .accessibilityAddTraits(.isHeader)
                .accessibilityHint(модель.толькоПроверить ? НовинкиМоегоText.т("nm_row_check_a11y") : "")
            Spacer(minLength: 8)
            Button(action: всеВЛенте) {
                HStack(spacing: 3) {
                    Text(текст("mfr_all"))
                    Image(systemName: "chevron.forward")
                        .font(.caption.weight(.bold))
                        .accessibilityHidden(true)
                }
                .font(.subheadline.weight(.semibold))
                .foregroundStyle(Theme.акцент)
                .frame(minWidth: 44, minHeight: 44)
                .contentShape(Rectangle())
            }
            .buttonStyle(.plain)
            .accessibilityLabel(текст("mfr_all"))
            .accessibilityHint(подсказкаВсех)
        }
    }

    /// Подсказка VoiceOver к «Все ›»: у ряда одних «Проверьте» лента открывается без «Для моего».
    private var подсказкаВсех: String {
        if модель.толькоПроверить { return РядМоегоText.т("mfr_feed_plain_a11y") }
        return ПодборРазделаМоего.подсказкаЛенты(разделВсех)
    }

    /// «Все ›»: раздел ленты, откуда больше карточек ряда; иначе — лента раздела «Моего».
    private var разделВсех: String {
        let запасной: String = подбор.лента(хранилище.запись) ?? ""
        return ПодборРазделаМоего.главныйРаздел(модель.находки) ?? запасной
    }

    private func всеВЛенте() {
        ОткликСайта.выбор()
        let сОтбором: Bool = !модель.толькоПроверить
        ПереходыМоего.найти(раздел: разделВсех, сОтбором: сОтбором)
    }

    private func ячейка(_ находка: НаходкаДляВас) -> some View {
        Button {
            ОткликСайта.выбор()
            ПереходыМоего.открыть(находка.товар)
        } label: {
            КарточкаНаходкиМоего(находка: находка)
        }
        .buttonStyle(НажатиеСайта())
        .accessibilityHint(текст("mfr_cell_a11y"))
    }
}

// MARK: - Кнопка «Найти подходящее»

/// «Найти подходящее»: лента раздела с «Для моего» (где такого чипа нет — просто лента). Экран раздела ставит её сам,
/// если ряда у раздела нет вовсе; ряд показывает её сам, когда ничего не подошло.
struct КнопкаНайтиМоего: View {
    let раздел: String

    init(раздел: String) {
        self.раздел = раздел
    }

    var body: some View {
        МалаяКнопкаАвтоподбора(заголовок: РядМоегоText.т("mfr_find"), значок: "magnifyingglass") {
            ОткликСайта.выбор()
            ПереходыМоего.найти(раздел: раздел)
        }
        .accessibilityHint(ПодборРазделаМоего.подсказкаЛенты(раздел))
    }
}

// MARK: - Карточка

/// Карточка ряда: фото 1:1, цена, название в две строки; под карточкой — плашка причины «Для вас».
struct КарточкаНаходкиМоего: View {
    let находка: НаходкаДляВас

    init(находка: НаходкаДляВас) {
        self.находка = находка
    }

    static let ширина: CGFloat = 148

    private var голосКарточки: String {
        let причина: String = находка.уровень.слово + ": " + находка.причина
        let части: [String] = [находка.товар.голос, причина]
        return части.joined(separator: ". ")
    }

    private var обложка: some View {
        Theme.поверхность2
            .frame(width: Self.ширина, height: Self.ширина)
            .overlay {
                КартинкаЛенты(находка.товар.обложка, пунктов: Self.ширина) {
                    Image(systemName: "photo")
                        .font(.system(size: 20))
                        .foregroundStyle(Theme.текстВторой)
                }
            }
            .clipped()
    }

    private var подпись: some View {
        let товар: Listing = находка.товар
        return VStack(alignment: .leading, spacing: 4) {
            Text(ListingCard.цена(товар))
                .font(.system(size: 14, weight: .heavy).monospacedDigit())
                .foregroundStyle(Theme.текст)
                .lineLimit(1)
                .minimumScaleFactor(0.8)
            Text(товар.title)
                .font(.system(size: 12))
                .foregroundStyle(Theme.текст)
                .lineLimit(2, reservesSpace: true)
                .multilineTextAlignment(.leading)
        }
        .padding(.horizontal, 9)
        .padding(.vertical, 8)
        .frame(width: Self.ширина, alignment: .leading)
    }

    var body: some View {
        let форма = RoundedRectangle(cornerRadius: Theme.Радиус.md, style: .continuous)
        VStack(alignment: .leading, spacing: 6) {
            VStack(alignment: .leading, spacing: 0) {
                обложка
                подпись
            }
            .background(Theme.поверхность, in: форма)
            .overlay { форма.strokeBorder(Theme.линия, lineWidth: 1) }
            .clipShape(форма)
            ПлашкаДляВас(находка: находка)
        }
        .frame(width: Self.ширина, alignment: .leading)
        .contentShape(Rectangle())
        .accessibilityElement(children: .ignore)
        .accessibilityLabel(голосКарточки)
        .accessibilityAddTraits(.isButton)
    }
}

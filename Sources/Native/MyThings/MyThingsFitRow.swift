/**
 «ПОДХОДИТ ВАМ» В РАЗДЕЛАХ «МОЕГО» (владелец, TestFlight 81 «Мой гардероб» и «Мой дом»: «упростить + чтобы отсюда поиск
 и сюда вставить то, что подходит»).

 Под заполненным разделом — ряд до восьми свежих объявлений, которые подходят именно к сохранённому: кровать — матрасы,
 топперы и бельё этого размера; окна — шторы и жалюзи по размеру; ТВ на стене — кронштейны по VESA; свет — лампы с
 вашим цоколем; гардероб — одежда и обувь вашего размера. Движок — тот же, что у «Для вас» (ForYouModel.swift):
 запросы ПодборМоего.запросы только разделов этого блока, первая страница раздела ленты (cat, город, новые подряд) без
 куков и без «Моего» в адресе, сверка на телефоне (ПодборДляВас.сверить — СовместимостьМоего.оценить): в ряд идут
 «подходит» (впереди) и «нужна деталь»; своё, ТОП-вставки и снятое — нет; цифровое отсекает сам разбор страницы
 (ListingsPage). Под карточкой — плашка причины «Для вас» (ПлашкаДляВас).

 Когда в сеть: только когда ряд появился (onAppear экрана раздела), не на запуске. Ответ раздела живёт 15 минут в
 памяти, общей для всех рядов (сменился город или человек — заново); не прошёл — повтор не раньше чем через минуту.
 Ушли с экрана — загрузка отменяется. Правка «Моего» — сверка заново по загруженному (через паузу 0,35 с), в сеть —
 только за новым разделом. Сверка — не на главной нити.

 Пачка 83: размер и стандарт сверка берёт и из полей объявления (ListingFitFields.swift); точных нет — ряд «Проверьте»
 (до шести вещей нужного вида, «Размер не указан — уточните у продавца», шапка «Может подойти» без галочки). Новые с
 прошлого просмотра — первыми и «· 2 новых» в шапке (НовинкиДляВас); ушёл ряд с экрана — его карточки показаны.

 Пачка 84 (ответ сервера 17.10.2026: лента с fit_* телом POST включена на проде): когда схема подачи объявила вид
 (rules.fit_filters, ПризнакиПодбораСервера), раздел просится POST-ом с телом из значений стандартов — дом fit_std
 (кровать и бельё, цоколь, VESA; окна — на телефоне, у семьи curtain fit_std: false), гардероб size, — без куков и без
 «Моего» в адресе (ОтборСервераДляВас); не объявлен, не прошёл или сервер тело не применил — GET, как раньше. Сверка на
 телефоне остаётся: уровень не лучше fit_match сервера. Страница помнит отпечаток тела (только в памяти): правка
 «Моего» меняет тело — раздел берётся заново.

 Ничего не нашлось — ряда нет, никаких заглушек; раздел заполнен — вместо ряда одна кнопка «Найти подходящее» (если её
 не выключили). «Все ›» и «Найти подходящее» открывают ленту раздела сразу с включённым «Для моего» (ЖдущийОтборМоего,
 FeedModel.применить); у ТВ (чипа нет, а ряд — только кронштейны) — поиск кронштейнов в «ТВ и аудио», где чипа нет
 вообще — просто ленту раздела. Проёмам и технике ряда нет: габаритов в ленте обычно нет, расходники движок не
 сверяет, — у них только «Найти подходящее».
 */
extension Config {
    /// Ряды «Подходит вам» в разделах «Моего». false — рядов и запросов нет; «Найти подходящее» остаётся.
    static let рядыМоего = true
}

// MARK: - Что подбирать

/// Раздел «Моего», под которым стоит ряд «Подходит вам» (или одна кнопка «Найти подходящее»).
enum ПодборРазделаМоего: String, CaseIterable, Hashable, Sendable {
    case кровати = "beds"
    case окна = "windows"
    case экраны = "tv"
    case свет = "light"
    /// Двери и лифт: ряда нет (в ленте почти нет габаритов) — только «Найти подходящее» (мебель).
    case проёмы = "openings"
    /// Техника: ряда нет (расходники движок не сверяет) — только «Найти подходящее» (раздел первой техники).
    case техника = "appliances"
    case гардероб = "wardrobe"

    static let вРяду = 8
    /// Ряд из нескольких разделов ленты (кровать: бельё и матрасы) — не больше стольких с одного.
    static let сРазделаВРяду = 5
    /// Не прошёл раздел — повтор не раньше, с.
    static let повтор: TimeInterval = 60
    /// Разделов ленты под размеры гардероба — не больше.
    static let пределРазделовРазмера = 3

    /// Разделы ленты движка «Для вас», из которых собирается ряд дома; у гардероба — по размерам, у проёмов и техники
    /// ряда нет.
    var разделыРяда: Set<String> {
        switch self {
        case .кровати: return ["bedding", "beds"]
        case .окна: return ["curtains"]
        case .экраны: return ["tv-audio"]
        case .свет: return ["lighting"]
        case .проёмы, .техника, .гардероб: return []
        }
    }

    /// Группа находок ряда: в ряд идут только они (вещь раздела дома, сверенная как одежда, — не сюда).
    var группа: ГруппаДляВас { self == .гардероб ? .одежда : .дом }

    /// Раздел «Моего» заполнен — есть что сверять или где искать.
    func заполнено(_ запись: ЗаписьМоего) -> Bool {
        let д = запись.дом
        switch self {
        case .кровати: return д.кровати.contains(where: \.заполнена)
        case .окна: return д.окна.contains(where: \.заполнено)
        case .экраны: return !д.экраны.isEmpty
        case .свет: return !д.лампы.isEmpty
        case .проёмы: return !д.путьВДом.isEmpty
        case .техника: return !д.техника.isEmpty
        case .гардероб: return !запись.гардероб.вещи.isEmpty || !запись.тело.размеры.isEmpty
        }
    }

    /**
     Запросы ряда по «Моему» (уже с размерами гардероба — ПодборДляВас.моёДляСверки): дом — те же, что у «Для вас»
     (ПодборМоего.запросы), только разделы этого блока; гардероб — раздел ленты на каждый вид размера, до трёх. Пусто —
     ряда нет.
     */
    func запросы(_ моё: ЗаписьМоего) -> [ЗапросПодбораМоего] {
        guard Config.моё, Config.рядыМоего else { return [] }
        switch self {
        case .гардероб:
            return Self.запросыРазмеров(моё)
        case .проёмы, .техника:
            return []
        case .кровати, .окна, .экраны, .свет:
            /* Только заполненный раздел: запрос ТВ «Для вас» берёт диагональ и из «Моих устройств» — под пустым
               «ТВ на стене» ряда быть не должно. */
            guard Config.мойДом, Config.стандарты, заполнено(моё) else { return [] }
            let свои: Set<String> = разделыРяда
            let все: [ЗапросПодбораМоего] = ПодборМоего.запросы(моё, предел: 40)
            return все.filter { (з: ЗапросПодбораМоего) -> Bool in з.профиль == .дом && свои.contains(з.раздел) }
        }
    }

    /// Одежда и обувь: раздел ленты на вид размера, как у ПодборМоего (кольца, шапки, перчатки и бельё — без ряда).
    private static func запросыРазмеров(_ моё: ЗаписьМоего) -> [ЗапросПодбораМоего] {
        var итог: [ЗапросПодбораМоего] = []
        var взяты = Set<String>()
        for размер in моё.тело.размеры {
            guard let ключ = лентаРазмера(размер.вид), взяты.insert(ключ).inserted else { continue }
            let причина: String = String(format: СтандартыText.т("fy_size"), размер.коротко)
            итог.append(ЗапросПодбораМоего(профиль: .размер, раздел: ключ, запрос: "", причина: причина))
            if итог.count >= пределРазделовРазмера { break }
        }
        return итог
    }

    private static func лентаРазмера(_ вид: ВидРазмераМоего) -> String? {
        switch вид {
        case .обувьЖ: return "womens-shoes"
        case .обувьМ: return "mens-shoes"
        case .одеждаЖ, .джинсыЖ: return "womens-clothing"
        case .одеждаМ, .джинсыМ: return "mens-clothing"
        case .бельё, .кольцо, .шапка, .перчатки: return nil
        }
    }

    /// Раздел ленты для «Найти подходящее» (и для «Все ›», когда карточек нет); nil — искать негде.
    func лента(_ запись: ЗаписьМоего) -> String? {
        switch self {
        case .кровати: return "beds"
        case .окна: return "curtains"
        case .экраны: return "tv-audio"
        case .свет: return "lighting"
        case .проёмы: return "furniture"
        case .техника:
            guard let первая = запись.дом.техника.first else { return nil }
            return Self.лентаТехники(первая.вид)
        case .гардероб:
            let размеры: [ЗапросПодбораМоего] = Self.запросыРазмеров(ПодборДляВас.моёДляСверки(запись))
            return размеры.first?.раздел
        }
    }

    private static func лентаТехники(_ вид: ВидТехникиМоего) -> String {
        switch вид {
        case .холодильник: return "fridges"
        case .стиральная: return "washing-machines"
        case .посудомойка: return "dishwashers"
        case .пылесос, .робот: return "vacuum-cleaners"
        case .кофемашина: return "kettles-coffee"
        case .кондиционер: return "air-conditioners"
        case .плита, .духовка: return "stoves"
        case .микроволновка: return "microwaves"
        case .водонагреватель: return "water-heaters"
        case .принтер: return "printers"
        case .фильтр: return "small-appliances"
        case .другая: return "appliances"
        }
    }

    /// Подсказка VoiceOver к «Все ›» и «Найти подходящее»: лента с «Для моего» или просто лента раздела.
    static func подсказкаЛенты(_ раздел: String) -> String {
        let сОтбором: Bool = Config.моё && СовместимостьМоего.профиль(раздела: раздел) != nil
        return РядМоегоText.т(сОтбором ? "mfr_feed_a11y" : "mfr_feed_plain_a11y")
    }

    /// Ряд и все находки своей группы — точные и «Проверьте» (по всем — точка отсчёта новинок, НовинкиДляВас.учесть).
    struct ИтогРядаМоего {
        var ряд: [НаходкаДляВас] = []
        var все: [НаходкаДляВас] = []
    }

    /**
     Ряд из сверки «Для вас»: только своя группа; новые (не в видели — снимок НовинкиДляВас) впереди, потом «подходит»,
     потом «нужна деталь» (внутри — сезонное и свежие сверху); из нескольких разделов ленты — не больше пяти с одного,
     всего до восьми. Точных нет (пачка 83: в ленте мало размеров — описание обрезано) — ряд «Проверьте»: до шести вещей
     нужного вида, где размер не указан (ПодборДляВас.заменаПроверкой), — ряд не пустой, но и не врёт. Чистая функция —
     зовётся не на главной нити.
     */
    static func собрать(_ страницы: [String: [Listing]], по список: [ЗапросПодбораМоего], моё: ЗаписьМоего, я: String,
                        группа: ГруппаДляВас, сезон: [ПравилоСезонаДляВас] = [],
                        видели: Set<String> = []) -> ИтогРядаМоего {
        let сверка: ПодборДляВас.СверкаДляВас = ПодборДляВас.сверитьВсё(страницы, запросы: список, моё: моё, я: я,
                                                                         сезон: сезон)
        let свои: [НаходкаДляВас] = сверка.точные.filter { (н: НаходкаДляВас) -> Bool in н.группа == группа }
        /* «Проверьте» своей группы — тоже в точку отсчёта: станут они потом точными (размер в «Моём», поля сервера) —
           это не «новые». */
        let своиПроверить: [НаходкаДляВас] = сверка.проверить.filter { (н: НаходкаДляВас) -> Bool in
            н.группа == группа
        }
        guard !свои.isEmpty else {
            return ИтогРядаМоего(ряд: ПодборДляВас.заменаПроверкой(сверка, группа: группа), все: своиПроверить)
        }
        let новые: [НаходкаДляВас] = свои.filter { (н: НаходкаДляВас) -> Bool in
            !видели.isEmpty && !видели.contains(н.id)
        }
        let прочие: [НаходкаДляВас] = свои.filter { (н: НаходкаДляВас) -> Bool in
            видели.isEmpty || видели.contains(н.id)
        }
        let подходят: [НаходкаДляВас] = прочие.filter { (н: НаходкаДляВас) -> Bool in н.уровень == .подходит }
        let сДеталью: [НаходкаДляВас] = прочие.filter { (н: НаходкаДляВас) -> Bool in н.уровень != .подходит }
        let порядок: [НаходкаДляВас] = новые + подходят + сДеталью
        let разделов: Int = Set(список.map(\.раздел)).count
        let предел: Int = разделов > 1 ? сРазделаВРяду : вРяду
        var сРаздела: [String: Int] = [:]
        var итог: [НаходкаДляВас] = []
        for находка in порядок {
            let уже: Int = сРаздела[находка.раздел, default: 0]
            guard уже < предел else { continue }
            сРаздела[находка.раздел] = уже + 1
            итог.append(находка)
            if итог.count >= вРяду { break }
        }
        return ИтогРядаМоего(ряд: итог, все: свои + своиПроверить)
    }

    /// Раздел ленты, откуда больше всего карточек ряда (при равенстве — первый): «Все ›» ведёт туда.
    static func главныйРаздел(_ находки: [НаходкаДляВас]) -> String? {
        var счёт: [String: Int] = [:]
        var порядок: [String] = []
        for находка in находки {
            if счёт[находка.раздел] == nil { порядок.append(находка.раздел) }
            счёт[находка.раздел, default: 0] += 1
        }
        var лучший: String? = nil
        var больше = 0
        for ключ in порядок {
            let сколько: Int = счёт[ключ] ?? 0
            if сколько > больше {
                лучший = ключ
                больше = сколько
            }
        }
        return лучший
    }
}


import SwiftUI
import UIKit

/**
 «МОЁ» — «ДОБАВИТЬ РАЗМЕР» БЕЗ ЛИШНИХ ЭКРАНОВ (владелец 16.10.2026: «стандарты ≠ удобства»).

 Прямо в карточке «Мои размеры»: чипы вида (одежда, обувь, джинсы, бельё, кольцо, шапка, перчатки; уже добавленные — с
 галочкой), у одежды, обуви и джинсов — «Женская · Мужская», и сразу ровная сетка размеров в привычной системе (буквы у
 одежды, EU у обуви, W у джинсов — ТиповыеМеркиМоего.системаБыстрая) из тех же таблиц (СеткаРазмеровМоего). Касание
 сразу кладёт размер в «Мои размеры»; у джинсов ниже — длина L, у белья — чашка. Под сеткой — бирка всех систем, как в
 подаче (БиркаРазмера). «Другая система» — полный лист РедакторРазмераМоего (US, UK, RU…), «Готово» сворачивает.
 */

/// Вид размера без пола — чип быстрого выбора; пол берётся с экрана.
enum РодРазмераМоего: String, CaseIterable, Identifiable {
    case одежда = "clothes"
    case обувь = "shoes"
    case джинсы = "jeans"
    case бельё = "bra"
    case кольцо = "ring"
    case шапка = "hat"
    case перчатки = "gloves"

    var id: String { rawValue }

    var подпись: String { МоёТелоText.т("mb_k_" + rawValue) }

    /// Нужен пол: у одежды, обуви и джинсов таблицы женские и мужские.
    var сПолом: Bool { self == .одежда || self == .обувь || self == .джинсы }

    func вид(_ пол: ПолТелаМоего) -> ВидРазмераМоего {
        let мужской = пол == .мужской
        switch self {
        case .одежда: return мужской ? .одеждаМ : .одеждаЖ
        case .обувь: return мужской ? .обувьМ : .обувьЖ
        case .джинсы: return мужской ? .джинсыМ : .джинсыЖ
        case .бельё: return .бельё
        case .кольцо: return .кольцо
        case .шапка: return .шапка
        case .перчатки: return .перчатки
        }
    }

    static func из(_ вид: ВидРазмераМоего) -> РодРазмераМоего {
        switch вид {
        case .одеждаЖ, .одеждаМ: return .одежда
        case .обувьЖ, .обувьМ: return .обувь
        case .джинсыЖ, .джинсыМ: return .джинсы
        case .бельё: return .бельё
        case .кольцо: return .кольцо
        case .шапка: return .шапка
        case .перчатки: return .перчатки
        }
    }
}

struct БыстрыйРазмерМоего: View {
    let тело: ТелоМоего
    @Binding var пол: ПолТелаМоего?
    let другаяСистема: (ВидРазмераМоего) -> Void
    let закрыть: () -> Void
    @Namespace private var пространство
    @State private var род: РодРазмераМоего
    @State private var толчок = 0

    init(тело: ТелоМоего, пол: Binding<ПолТелаМоего?>, другаяСистема: @escaping (ВидРазмераМоего) -> Void,
         закрыть: @escaping () -> Void) {
        self.тело = тело
        _пол = пол
        self.другаяСистема = другаяСистема
        self.закрыть = закрыть
        // Первым — вид, которого ещё нет в «Мои размеры».
        let есть = Set(тело.размеры.map { РодРазмераМоего.из($0.вид) })
        _род = State(initialValue: РодРазмераМоего.allCases.first { !есть.contains($0) } ?? .одежда)
    }

    private func т(_ ключ: String) -> String { МоёТелоText.т(ключ) }

    /// Вид размера выбранного рода; у рода с полом без выбранного пола — nil (сначала «Женская · Мужская»).
    private var текущийВид: ВидРазмераМоего? {
        if род.сПолом { return пол.map { род.вид($0) } }
        return род.вид(.женский)
    }

    var body: some View {
        VStack(alignment: .leading, spacing: 14) {
            выборРода
            if род.сПолом {
                выборПола
            }
            if let в = текущийВид {
                сетки(в)
            }
            низ
        }
        .padding(14)
        .frame(maxWidth: .infinity, alignment: .leading)
        .background(Theme.поверхность2, in: RoundedRectangle(cornerRadius: Theme.Радиус.md, style: .continuous))
        .animation(ДвижениеСайта.смена, value: род)
        .animation(ДвижениеСайта.смена, value: пол)
    }

    // MARK: Вид и пол

    private var выборРода: some View {
        VStack(alignment: .leading, spacing: 8) {
            Text(т("mb_kind"))
                .font(.subheadline.weight(.bold))
                .foregroundStyle(Theme.текст)
            ПотокЧипов(зазор: 8) {
                ForEach(РодРазмераМоего.allCases) { р in
                    let есть = тело.размеры.contains { РодРазмераМоего.из($0.вид) == р }
                    ЧипМоего(р.подпись, выбран: р == род, значок: есть ? "checkmark" : nil) {
                        guard р != род else { return }
                        ОткликСайта.выбор()
                        род = р
                    }
                }
            }
        }
    }

    private var выборПола: some View {
        ПотокЧипов(зазор: 8) {
            ЧипМоего(т("mb_women"), выбран: пол == .женский) { сменитьПол(.женский) }
            ЧипМоего(т("mb_men"), выбран: пол == .мужской) { сменитьПол(.мужской) }
        }
    }

    private func сменитьПол(_ новый: ПолТелаМоего) {
        guard пол != новый else { return }
        ОткликСайта.выбор()
        пол = новый
    }

    // MARK: Сетки

    @ViewBuilder
    private func сетки(_ в: ВидРазмераМоего) -> some View {
        let вкладка = в.вкладка
        let свой = тело.размер(в)
        let выбор = свой?.выбор()
        if let с = вкладка.система(ТиповыеМеркиМоего.системаБыстрая(в)) ?? вкладка.системы.first {
            VStack(alignment: .leading, spacing: 10) {
                Text(в.подпись + " · " + РазмерыОдеждыText.система(с.код))
                    .font(.caption.weight(.bold))
                    .foregroundStyle(Theme.текстВторой)
                СеткаРазмеровМоего(чипы: вкладка.основная.чипы(с.первый), выбранный: выбор?.ряд, код: с.код,
                                   пространство: пространство, метка: "quick") { чип in
                    сохранить(в, с, ряд: чип.id, ряд2: nil)
                }
                if let второй = с.второй, let т2 = вкладка.вторая, свой != nil {
                    Text(т(в == .бельё ? "mb_cup" : "mb_length"))
                        .font(.caption.weight(.bold))
                        .foregroundStyle(Theme.текстВторой)
                    СеткаРазмеровМоего(чипы: т2.чипы(второй), выбранный: выбор?.ряд2, код: "", пространство: пространство,
                                       метка: "quick2") { чип in
                        сохранить(в, с, ряд: nil, ряд2: чип.id)
                    }
                }
                if let бирка = свой?.бирка() {
                    БиркаРазмера(бирка, толчок: толчок, сброс: nil) {
                        Label(т("mb_quick_saved"), systemImage: "checkmark.circle.fill")
                            .font(.caption.weight(.semibold))
                            .foregroundStyle(Theme.акцент)
                    }
                    .transition(.opacity)
                }
            }
            .id(в.rawValue)
            .transition(.opacity)
        }
    }

    private var низ: some View {
        HStack(spacing: 8) {
            if let в = текущийВид {
                МалаяКнопкаАвтоподбора(заголовок: т("mb_other_system"), значок: "arrow.left.arrow.right") {
                    ОткликСайта.выбор()
                    другаяСистема(в)
                }
            }
            Spacer(minLength: 0)
            МалаяКнопкаАвтоподбора(заголовок: МоёText.т("my_done"), значок: "checkmark") {
                ОткликСайта.выбор()
                закрыть()
            }
        }
    }

    // MARK: Запись

    /// Ряд основной таблицы (или прежний) и ряд длины или чашки (или прежний) → значения своей системы → «Мои размеры».
    private func сохранить(_ в: ВидРазмераМоего, _ с: СистемаРазмераОдежды, ряд: Int?, ряд2: Int?) {
        let вкладка = в.вкладка
        let прежний = тело.размер(в)?.выбор()
        guard let основнойРяд = ряд ?? прежний?.ряд else { return }
        let основное = вкладка.основная.значение(основнойРяд, с.первый)
        guard !основное.isEmpty else { return }
        var второе = ""
        if let второй = с.второй, let т2 = вкладка.вторая, let р2 = ряд2 ?? прежний?.ряд2 {
            второе = т2.значение(р2, второй)
        }
        ОткликСайта.выбор()
        withAnimation(ДвижениеСайта.мягко(.spring(response: 0.32, dampingFraction: 0.8))) {
            МоёХранилище.shared.задатьРазмер(РазмерМоего(вид: в, система: с.код, значение: основное, значение2: второе))
        }
        толчок += 1
    }
}

import SwiftUI

/**
 ПЕРЕПИСКА — ЭТАП 3.

 Два входа: из списка диалогов (номер диалога известен — сразу poll) и «Написать» из карточки объявления (диалога
 может ещё не быть — open создаёт его по продавцу и объявлению). Новые сообщения — опросом раз в три секунды, пока
 экран открыт: dm.php отдаёт снимок мгновенно, отдельного канала для приложения у сайта нет.

 🔴 ОТПРАВКА ЗА РУБИЛЬНИКОМ (Config.нативныйЧатОтправка). Пока не проверено, что dm.php принимает запись с куками
 веб-сессии и CSRF-токеном страницы, вместо поля ввода — «Ответить на сайте»: переписку видно здесь, ответ пишется
 там, где он точно дойдёт. Сообщение, которое молча не ушло, хуже, чем лишнее нажатие.

 Этап 17 (Config.удобныйЧат): черновик по диалогу (ChatDrafts.swift), кнопка «вниз», «Копировать» и «потяни —
 обновится» (ChatComfort.swift). Опрос — прежний.

 Офлайн-режим (08.10.2026): последний ответ переписки — копией на диске (OfflineCopies.swift), без сети экран показывает
 её с плашкой; написанное без сети или оборванное сетью — в очереди исходящих (OutboxQueue.swift) облаком с часиками.
 */
@MainActor
final class ChatThreadModel: ObservableObject {
    @Published private(set) var сообщения: [ЧатСообщение] = []
    @Published private(set) var загружено = false
    @Published private(set) var ошибка: ChatAPI.Ошибка?
    @Published private(set) var заблокирован = false
    @Published private(set) var отправляем = false
    @Published private(set) var неОтправлено = false
    /// Почему не ушло — коротко, под ошибкой: на проверке отправки (владелец 25.09.2026) это сразу скажет, что именно
    /// ответил сайт, а не только «не отправлено».
    @Published private(set) var причина = ""
    /// Человеческий текст отказа сайта («Общение недоступно…»), если он есть: его и показываем под лентой; код в
    /// причина — только для отладки.
    @Published private(set) var объяснение: String? = nil
    @Published var черновик = "" {
        /* Этап 17: недописанное — в черновик диалога (ЧерновикиЧата). Пока сообщение уходит, поле уже пустое, но
           сохранённый черновик не трогаем: сотрёт его отправить(), когда сайт примет сообщение. */
        didSet {
            guard Config.удобныйЧат, !отправляем, черновик != oldValue else { return }
            ЧерновикиЧата.shared.запомнить(черновик, для: tid)
        }
    }

    private(set) var tid: String
    /// Номер собеседника (шапка ведёт на его витрину — ОкноПродавца). Диалог открыт по номеру переписки, без
    /// собеседника, — его номер приходит ответом open или poll (peer{id} / thread.peer_id), см. применить().
    @Published private(set) var собеседник: String
    /// Собеседник удалён (peer.gone) — витрины нет, шапка не нажимается.
    @Published private(set) var собеседникУшёл = false
    private let объявление: String
    /// Этап 45: номер переписки для open (строка инбокса: tid диалога или chat_id покупки) — сайт открывает строку
    /// через open с tid, а не сразу опросом.
    private let номерОткрытия: String
    /// Этап 45: thread.peer_read_at — «✓✓ Прочитано» / «✓ Отправлено» под последним моим (§6.4.8 i).
    @Published private(set) var прочиталДо = ""
    /// lead{role, agreed, pid, no_escrow} ответа open/poll (_dmLead кабинета): торг в этой переписке.
    @Published private(set) var торг: ТоргПереписки? = nil
    /// item ответа open/poll — карточка объявления под шапкой (#dm-context).
    @Published private(set) var товар: ТоварПереписки? = nil
    /// me_verified: false — полоса верификации над полем (#dm-verify-bar); nil — сайт не прислал, полосы нет.
    @Published private(set) var проверен: Bool? = nil

    /// Переписка на сайте — туда ведут пуши о новых сообщениях (AppDelegate).
    static var адресПереписки: URL? { Config.url("/cabinet.php?s=messages") }

    init(tid: String = "", собеседник: String = "", объявление: String = "", номерОткрытия: String = "") {
        self.tid = tid
        self.собеседник = собеседник
        self.объявление = объявление
        self.номерОткрытия = номерОткрытия
        self.поСобеседнику = tid.isEmpty && номерОткрытия.isEmpty && !собеседник.isEmpty
    }

    // MARK: - Офлайн-режим (08.10.2026)

    /// На экране сохранённая копия переписки: сеть не ответила. Свежий ответ её заменит, плашка уйдёт.
    @Published private(set) var сКопии = false
    /// Когда легла копия на экране.
    @Published private(set) var копияКогда: Date? = nil
    /// Открыта «Написать» по собеседнику и объявлению, без номера: копия ищется и по ним (номера без сети не узнать).
    private let поСобеседнику: Bool
    /// Что последним легло на диск: опрос раз в три секунды одинаковое второй раз не пишет.
    private var записаноКопии = ""

    /// Имена копии этой переписки: номер, номер строки инбокса и (открыта по собеседнику) собеседник с объявлением.
    private var ключиКопии: [String] {
        var ключи: [String] = []
        for номер in [tid, номерОткрытия] where !номер.isEmpty && !ключи.contains("dm-" + номер) {
            ключи.append("dm-" + номер)
        }
        if поСобеседнику { ключи.append("dmp-" + собеседник + "-" + объявление) }
        return ключи
    }

    /// Свежий ответ пришёл — на диск, если переписка изменилась; плашка копии уходит.
    private func запомнитьКопию(_ ответ: ЧатОтвет) {
        if сКопии { сКопии = false }
        if копияКогда != nil { копияКогда = nil }
        guard ответ.переписка != nil, !ответ.тело.isEmpty, !tid.isEmpty else { return }
        let подпись = [String(сообщения.count), сообщения.last?.id ?? "", прочиталДо, заблокирован ? "1" : "0"]
            .joined(separator: "|")
        guard подпись != записаноКопии else { return }
        записаноКопии = подпись
        for ключ in ключиКопии { КопииБезСети.сохранить(тело: ответ.тело, вид: .переписка, ключ: ключ) }
    }

    /// Сеть не ответила, а переписки на экране нет — последняя копия с диска.
    private func показатьСохранённую() async {
        guard сообщения.isEmpty else { return }
        for ключ in ключиКопии {
            guard let копия = await КопииБезСети.прочитать(вид: .переписка, ключ: ключ),
                  let ответ = try? JSONDecoder().decode(ЧатОтвет.self, from: копия.данные),
                  let переписка = ответ.переписка, сообщения.isEmpty else { continue }
            применить(переписка, ответ.заблокирован, наружу: false)
            сКопии = true
            копияКогда = копия.когда
            return
        }
    }

    /// Время сервера у последнего сообщения на экране — для сверки очереди «не дошло ли».
    private var известноДо: String { сообщения.last?.когда ?? "" }

    /// Шапка ведёт на витрину собеседника: номер известен и годен, собеседник не удалён. Поддержка и служебные
    /// переписки собеседника не присылают — у них шапка не нажимается.
    var витринаСобеседника: String? {
        let номер = собеседник.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !собеседникУшёл, ВитринаПродавцаAPI.годный(номер) else { return nil }
        return номер
    }

    /// Диалог можно открыть нативно: он уже есть, или его можно создать (для создания нужна запись).
    var можноОткрыть: Bool { !tid.isEmpty || Config.нативныйЧатОтправка }

    func начать() async {
        /* Мой номер (_dmMe) — кнопки продавца в карточках аренды и обмена. */
        if я.isEmpty { я = await ИнбоксAPI.мойНомер(ждать: false) }
        /* Этап 45: строка инбокса без собеседника (peer_id не пришёл) — open без peer сайт отвергает («Собеседник не
           указан»); номер переписки известен — читаем её опросом, как этап 3. */
        if tid.isEmpty && собеседник.isEmpty && !номерОткрытия.isEmpty { tid = номерОткрытия }
        do {
            if tid.isEmpty {
                let ответ = try await ChatAPI.открытьЦеликом(собеседник: собеседник, объявление: объявление,
                                                             номер: номерОткрытия)
                применить(ответ.переписка, ответ.заблокирован)
                запомнитьКопию(ответ)
            } else {
                let ответ = try await ChatAPI.перепискаЦеликом(tid)
                применить(ответ.переписка, ответ.заблокирован)
                запомнитьКопию(ответ)
            }
            ошибка = nil
        } catch let e as ChatAPI.Ошибка {
            ошибка = e
            /* Офлайн-режим: нет сети — последняя копия переписки с диска, с плашкой; писать можно — в очередь. */
            if e == .сеть { await показатьСохранённую() }
        } catch {
            ошибка = .сеть
            await показатьСохранённую()
        }
        сверитьЧерновик()
        загружено = true
    }

    /// Этап 17: номер диалога известен — в пустое поле возвращаем его черновик, а написанное, пока номера не было
    /// (open не прошёл, человек начал писать), кладём под этот номер. «Нужен вход» — не трогаем: переписка могла
    /// пережить в стеке вкладки выход из аккаунта, и её текст в памяти вернул бы на диск стёртый черновик ушедшего.
    private func сверитьЧерновик() {
        guard Config.удобныйЧат, !tid.isEmpty, ошибка != .нуженВход else { return }
        if черновик.isEmpty {
            if let сохранённый = ЧерновикиЧата.shared.черновик(tid) { черновик = сохранённый }
        } else {
            ЧерновикиЧата.shared.запомнить(черновик, для: tid)
        }
    }

    /// Этап 17: «потяни — обновится» — один внеочередной опрос. Не прошёл — молча, как и обычный опрос: на экране
    /// остаётся пришедшее, а через три секунды опрос попробует снова. Номера диалога нет — опрашивать нечего.
    func обновить() async {
        guard !tid.isEmpty else { return }
        if let ответ = try? await ChatAPI.перепискаЦеликом(tid) {
            применить(ответ.переписка, ответ.заблокирован)
            запомнитьКопию(ответ)
            ошибка = nil
        }
    }

    /// Опрос новых сообщений, пока экран открыт (задача .task отменяется при уходе с экрана).
    func опрос() async {
        while !Task.isCancelled {
            try? await Task.sleep(nanoseconds: 3_000_000_000)
            guard !Task.isCancelled, !tid.isEmpty else { continue }
            if let ответ = try? await ChatAPI.перепискаЦеликом(tid, ждать: false) {
                применить(ответ.переписка, ответ.заблокирован)
                запомнитьКопию(ответ)
                if ошибка == .сеть { ошибка = nil }
            }
        }
    }

    func отправить() async {
        let текст = черновик.trimmingCharacters(in: .whitespacesAndNewlines)
        guard Config.нативныйЧатОтправка, !текст.isEmpty, !tid.isEmpty, !отправляем else { return }
        /* Офлайн-режим: сети нет или в этой переписке уже ждут неотправленные — в очередь, за ними: текст не теряется,
           облако с часиками уйдёт само, когда сеть вернётся. */
        let очередь = ОчередьСообщений.shared
        if !СетьПриложения.shared.онлайн || очередь.естьЖдущие(.личный, tid),
           очередь.поставить(текст, куда: .личный, адрес: tid, известноДо: известноДо) {
            неОтправлено = false
            черновик = ""
            if Config.удобныйЧат { ЧерновикиЧата.shared.запомнить("", для: tid) }
            return
        }
        отправляем = true
        неОтправлено = false
        let было = черновик
        черновик = ""
        defer {
            отправляем = false
            /* Этап 17: ушло — поле пустое, и черновик диалога стирается; не ушло — в поле вернулся текст, он и остаётся
               черновиком. Написанное, пока сообщение уходило, тоже сохраняется. */
            if Config.удобныйЧат { ЧерновикиЧата.shared.запомнить(черновик, для: tid) }
        }
        do {
            let отправлено = ИнбоксВремя.сейчас()
            if let переписка = try await ChatAPI.написать(tid: tid, текст: текст) {
                времяОтправки = отправлено
                применить(переписка, заблокирован)
            } else {
                /* ok, но переписки в ответе нет — дотянем опросом, а не будем гадать. */
                времяОтправки = отправлено
                if let снимок = try? await ChatAPI.переписка(tid) { применить(снимок.0, снимок.заблокирован) }
            }
        } catch {
            /* Офлайн-режим: оборвалось сетью — не «не отправлено», а в очередь (запись могла дойти: перед повтором
               очередь проверит переписку). */
            if (error as? ChatAPI.Ошибка) == .сеть,
               ОчередьСообщений.shared.поставить(текст, куда: .личный, адрес: tid, известноДо: известноДо,
                                                 пробовали: Date()) {
                return
            }
            черновик = было
            неОтправлено = true
            причина = Self.код(error)
            if let e = error as? ChatAPI.Ошибка, case .отказ = e {
                объяснение = ChatAPI.текст(e)
            } else {
                объяснение = nil
            }
        }
    }

    private static func код(_ ошибка: Error) -> String {
        guard let e = ошибка as? ChatAPI.Ошибка else { return "?" }
        switch e {
        case .сеть:            return "network"
        case .нуженВход:       return "auth/csrf"
        case .статус(let к):   return "HTTP \(к)"
        case .разбор:          return "format"
        case .отказ(let п):    return п.isEmpty ? "refused" : п
        }
    }

    /// наружу = false — копия с диска: ждущее предложение и строку «Чата» не трогаем, они знают свежее.
    private func применить(_ переписка: ЧатПереписка?, _ блок: Bool, наружу: Bool = true) {
        заблокирован = блок
        guard let переписка else { return }
        if !переписка.id.isEmpty { tid = переписка.id }
        if переписка.собеседникУшёл && !собеседникУшёл { собеседникУшёл = true }
        /* Пришёл номер собеседника, а мы его не знали (строка инбокса без peer_id, диалог из списка по tid) — шапка
           начинает вести на его витрину. Известный номер ответом не подменяем: open шёл именно с ним. */
        if собеседник.isEmpty && !переписка.собеседникID.isEmpty { собеседник = переписка.собеседникID }
        if переписка.сообщения != сообщения { сообщения = переписка.сообщения }
        if переписка.прочиталДо != прочиталДо { прочиталДо = переписка.прочиталДо }
        if let новый = переписка.торг, новый != торг { торг = новый }
        if let новый = переписка.товар, новый != товар { товар = новый }
        if let новый = переписка.проверен, новый != проверен { проверен = новый }
        if let новая = переписка.метка, !меткаМеняется, новая != метка { метка = новая }
        guard наружу else { return }
        /* Ждущее своё предложение — и на страницу объявления (полоса «Ваше предложение» с той же кнопкой). Только если
           в этой переписке есть свои предложения: переписка без торга не стирает то, что знает чат объявления. */
        let объявлениеТорга = объявлениеПредложения
        if !объявлениеТорга.isEmpty && сообщения.contains(where: { $0.вид == "offer" && $0.моё }) {
            ТоргПредложений.shared.запомнить(объявление: объявлениеТорга, ждущееПредложение)
        }
        /* TestFlight, владелец: «последние сообщения в чате не отразились в общем списке». Переписка на экране знает
           последнее сообщение раньше списка — его строка («Вы: …», время, место наверху, погасшие непрочитанные)
           меняется сразу, а не после следующего ответа dm.php list. */
        if Config.нативныеСообщенияКабинета {
            ИнбоксМодель.shared.вПереписке(номера: [tid, номерОткрытия], последнее: последнееДляСписка,
                                            прочитано: true)
        }
    }

    /// Время своего только что отправленного сообщения — на случай, если сервер не прислал at.
    private var времяОтправки: String? = nil

    /// Последнее сообщение для строки списка — как _msgRowDm: аренда и обмен — значок и подпись, служебное — без «Вы: ».
    private var последнееДляСписка: ПоследнееВПереписке? {
        guard let с = сообщения.last else { return nil }
        let запасное: String? = с.моё ? времяОтправки : nil
        guard let когда = с.когда.isEmpty ? запасное : с.когда, !когда.isEmpty else { return nil }
        var значок: String? = nil
        var текст = с.текст
        /* Предложение цены без текста — «Предложение: N ₸», как строка сервера; иначе превью было бы пустым. */
        if текст.isEmpty { текст = с.текстДляСписка }
        switch с.тип {
        case "rental":
            значок = "calendar"
            текст = ИнбоксText.т("rental_req")
        case "exchange":
            значок = "arrow.2.squarepath"
            текст = ИнбоксText.т("exchange_offer")
        default:
            if текст.isEmpty { текст = с.подпись }
        }
        return ПоследнееВПереписке(текст: текст, моё: с.моё && !с.системное, значок: значок, когда: когда)
    }

    /// Этап 45: номер последнего моего не-служебного сообщения — под ним отметка «Прочитано / Отправлено» (сайт: последнее
    /// mine && type !== "system").
    var последнееМоё: String? {
        сообщения.last(where: { $0.моё && !$0.системное && $0.заявка == nil })?.id
    }

    /// Date.parse(peer_read_at) >= Date.parse(msg.at).
    func прочитано(_ с: ЧатСообщение) -> Bool {
        guard let до = ИнбоксВремя.дата(прочиталДо), let когда = ИнбоксВремя.дата(с.когда) else { return false }
        return до >= когда
    }

    /// Этап 45: в переписке уже есть заявка с выбранным мастером (s = messages.some(meta.assigned) у _dmRender).
    var естьНазначенный: Bool {
        сообщения.contains { $0.заявка?.назначена == true }
    }

    // MARK: - Предложение цены (_dmOfferCard, dmOfferWithdraw)

    /// offer и counter до последнего offer — «Заменено новым предложением» (_dmRender: e._replaced).
    var заменённые: Set<String> {
        guard let последнее = сообщения.lastIndex(where: { $0.вид == "offer" }) else { return [] }
        var итог: Set<String> = []
        for (место, с) in сообщения.enumerated() where место < последнее {
            if с.вид == "offer" || с.вид == "counter" { итог.insert(с.id) }
        }
        return итог
    }

    /// Объявление торга: lead.pid, иначе объявление, с которым открыта переписка.
    var объявлениеПредложения: String {
        let изТорга = торг?.объявление ?? ""
        return изТорга.isEmpty ? объявление : изТорга
    }

    /// Номер сообщения со своим ждущим предложением — под ним «Отозвать предложение». Как _dmOfferCard: своё (mine),
    /// я покупатель (lead.role, если сервер его прислал), не отозвано, не заменено, не принято, цены по договорённости нет.
    var ждущееСообщение: String? {
        guard let место = сообщения.lastIndex(where: { $0.вид == "offer" }) else { return nil }
        let с = сообщения[место]
        guard с.моё, let п = с.предложение else { return nil }
        if let торг, !торг.роль.isEmpty && !торг.покупатель { return nil }
        guard !п.отозвано, !п.принято, (торг?.согласовано ?? 0) == 0 else { return nil }
        return с.id
    }

    var ждущееПредложение: ЖдущееПредложениеЦены? {
        guard let номер = ждущееСообщение, let с = сообщения.first(where: { $0.id == номер }),
              let п = с.предложение else { return nil }
        return ЖдущееПредложениеЦены(объявление: объявлениеПредложения, чат: tid, цена: п.цена,
                                     подкреплено: п.подкреплено)
    }

    /// Плашка итога («Предложение отозвано…», ошибка) — .kc-toast кабинета.
    @Published private(set) var плашка: String? = nil

    /**
     dmOfferWithdraw → _dmOfferGo("offer_withdraw"): POST {csrf, chat_id: tid} (как сайт — без pid), затем dmPollTick —
     карточка гаснет, уведомление сервера приходит в переписку и в строку «Чата». Окно подтверждения показал экран;
     подкреплённое деньгами при выключенных деньгах сделок сюда не приходит (экран открывает сайт).
     */
    func отозватьПредложение() async {
        guard let ждущее = ждущееПредложение, !tid.isEmpty,
              ОтзывПредложенияAPI.здесь(подкреплено: ждущее.подкреплено) else { return }
        guard let итог = await ТоргПредложений.shared.отозвать(объявление: ждущее.объявление, чат: tid,
                                                              сОбъявлением: false) else { return }
        switch итог {
        case .готово(let текст):
            показатьПлашку(текст)
            await обновить()
        case .ошибка(let текст):
            показатьПлашку(текст)
        }
    }

    private func показатьПлашку(_ текст: String) {
        withAnimation(ДвижениеСайта.появление) { плашка = текст }
        Task { @MainActor [weak self] in
            try? await Task.sleep(nanoseconds: 2_600_000_000)
            guard let self, self.плашка == текст else { return }
            withAnimation(ДвижениеСайта.уход) { self.плашка = nil }
        }
    }

    // MARK: - Аренда и обмен (dmRentalAct, dmExchangeAct)

    /// Мой номер (_dmMe): кнопки карточки видит продавец (meta.seller_id).
    @Published private(set) var я = ""
    /// Номер сделки, по которой идёт запрос, — кнопки её карточки гаснут.
    @Published private(set) var занятаСделка: String? = nil

    func продавецВ(_ сделка: СделкаВЧате) -> Bool {
        !я.isEmpty && я == сделка.продавец
    }

    /**
     dmRentalAct: POST rentals.php {action, rental_id, csrf, me_id} — confirm/decline уходят action "respond" с decision;
     dmExchangeAct: POST exchange.php {action:"respond", exchange_id, decision, csrf, me_id}. ok → «Готово ✓» и опрос
     (dmPollTick), иначе error сайта. Повтора нет: запись могла дойти.
     */
    func действиеСделки(_ сделка: СделкаВЧате, _ действие: ДействиеСделкиЧата) async {
        guard !сделка.номер.isEmpty, занятаСделка == nil else { return }
        занятаСделка = сделка.номер
        defer { занятаСделка = nil }
        let мой = await ИнбоксAPI.мойНомер(ждать: true)
        var тело: [String: Any] = ["me_id": мой]
        for (ключ, значение) in действие.поля { тело[ключ] = значение }
        тело[сделка.аренда ? "rental_id" : "exchange_id"] = сделка.номер
        do {
            let j = try await ИнбоксAPI.отправить(сделка.аренда ? "rentals.php" : "exchange.php", тело: тело)
            if МоиОбъявленияAPI.да(j["ok"]) {
                показатьПлашку(ИнбоксText.т("dm_done_ok"))
                await обновить()
            } else {
                показатьПлашку(ИнбоксAPI.текстОшибки(j, запасной: ИнбоксText.т("err_generic")))
            }
        } catch {
            показатьПлашку(ИнбоксAPI.текстСбоя(error))
        }
    }

    // MARK: - Метка диалога (dmSetLabel)

    /// thread.label — select #dm-label шапки.
    @Published private(set) var метка = ""
    @Published private(set) var меткаМеняется = false

    func поставитьМетку(_ ключ: String) async {
        guard !tid.isEmpty, !меткаМеняется else { return }
        меткаМеняется = true
        defer { меткаМеняется = false }
        switch await ИнбоксAPI.метка(ключ, лид: false, номер: tid) {
        case .готово:
            метка = ключ
            показатьПлашку(ИнбоксText.т("label_saved"))
        case .ошибка(let текст):
            показатьПлашку(текст)
        }
    }
}


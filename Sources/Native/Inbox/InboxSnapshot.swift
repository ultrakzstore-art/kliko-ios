import Foundation

/**
 СКОРОСТЬ: СПИСОК ЧАТОВ С ДИСКА (владелец 30.09.2026: «чтобы моментально открывалось независимо от сети»).

 Единый инбокс собирается из трёх ответов — первый показ за запуск был «Загружаем…» на секунды. Теперь последние
 склеенные строки лежат в той же папке, что и копии кабинета (КэшКабинета, имя «inbox»), с номером вошедшего: экран
 рисует их сразу, свежая сборка подменяет целиком. В копии — только то, что нужно строке и переходу по ней: номер и
 источник, имя, товар, превью, время, непрочитанные, обложка и значок раздела, собеседник. Склейку не трогает.
 Выход из аккаунта стирает папку (ВыходНачисто → КэшКабинета.стереть), чужой номер копию не показывает (ИнбоксМодель).
 */
extension СтрокаИнбокса {
    /// Строка для файла копии (только JSON-типы).
    var дляКопии: [String: Any] {
        var d: [String: Any] = [
            "src": источник.rawValue, "id": номер, "name": имя, "at": когда, "upd": порядок, "since": начат,
            "lid": объявлениеID, "sub": подпись, "ist": статусОбъявления, "pv": превью, "pvm": превьюМоё,
            "unread": непрочитано, "hidden": скрыт, "kinds": виды, "label": метка, "lst": статусЛида,
            "peer": собеседник, "gone": собеседникУдалён, "img": обложка, "cicon": значокРаздела,
            "cname": раздел, "ccolor": цветРаздела, "hay": стог
        ]
        if let значокПревью { d["pvi"] = значокПревью }
        if let видыИзОтвета { d["kinds_own"] = видыИзОтвета }
        if let м = своиМета {
            d["meta"] = ["img": м.обложка, "icon": м.значок, "name": м.раздел, "color": м.цвет]
        }
        return d
    }

    /// Строка из файла копии; без номера или с незнакомым источником — nil.
    init?(копия d: [String: Any]) {
        guard let src = d["src"] as? String, let источник = Источник(rawValue: src),
              let номер = d["id"] as? String, !номер.isEmpty else { return nil }
        self.источник = источник
        self.номер = номер
        func с(_ ключ: String) -> String { (d[ключ] as? String) ?? "" }
        имя = с("name")
        когда = с("at")
        порядок = с("upd")
        начат = с("since")
        объявлениеID = с("lid")
        подпись = с("sub")
        статусОбъявления = с("ist")
        превью = с("pv")
        превьюМоё = (d["pvm"] as? Bool) ?? false
        значокПревью = d["pvi"] as? String
        непрочитано = max(0, (d["unread"] as? Int) ?? 0)
        скрыт = (d["hidden"] as? Bool) ?? false
        виды = (d["kinds"] as? [String]) ?? []
        видыИзОтвета = d["kinds_own"] as? [String]
        метка = с("label")
        статусЛида = с("lst")
        собеседник = с("peer")
        собеседникУдалён = (d["gone"] as? Bool) ?? false
        обложка = с("img")
        значокРаздела = с("cicon")
        раздел = с("cname")
        цветРаздела = с("ccolor")
        if let м = d["meta"] as? [String: String] {
            своиМета = МетаИнбокса(обложка: м["img"] ?? "", значок: м["icon"] ?? "",
                                   раздел: м["name"] ?? "", цвет: м["color"] ?? "")
        }
        стог = с("hay")
    }
}

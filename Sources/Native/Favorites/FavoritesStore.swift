import SwiftUI

/**
 ИЗБРАННОЕ — ЭТАП 5 ПЕРЕХОДА НА SWIFTUI (владелец 25.09.2026: «5–7 этапов наперёд»).

 🔴 ХРАНИТСЯ НА ТЕЛЕФОНЕ, А НЕ НА САЙТЕ. API избранного на сайте приложению неизвестно (исходников сайта под рукой
 нет), а угаданный адрес — это запись наугад в чужую таблицу. Поэтому сердечко здесь своё: с избранным сайта не
 сходится и на другой телефон не переезжает. Станет известен API — этот список превратится в кэш серверного.

 Listing только разбирается из ответа API (Decodable), поэтому на диск кладём свою маленькую запись — то, что видно
 в сетке: цена, название, обложка, город, метки. Полную карточку ListingDetailView дотянет сама по ?id=, а открытая
 карточка освежает запись: цена в избранном — последняя увиденная.

 Не больше 500 записей, новые сверху. Стирается при выходе из аккаунта (WebContainer, bye=1) вместе с лентой на диске.

 Этап 35 (владелец 25.09.2026, Config.избранноеССайтом): API стал известен (favorites.php в js/marketplace.min.js), и у
 вошедшего этот список — копия избранного его аккаунта. Нажатие по-прежнему меняет его сразу, а запись на сайт и откат
 при отказе ведёт СинхронИзбранного; список с сайта ложится сюда через принятьССайта. Гостю — всё как выше.
 */
@MainActor
final class FavoritesStore: ObservableObject {
    static let shared = FavoritesStore()

    /// Потолок списка: старые уходят снизу. Файл при этом — пара сотен килобайт.
    static let предел = 500

    /// Номера сохранённых — сердечко на карточке спрашивает здесь.
    @Published private(set) var номера: Set<String> = []
    /// Сохранённые объявления, новые сверху, — сетка вкладки «Избранное».
    @Published private(set) var товары: [Listing] = []

    private var записи: [ИзбранноеЗапись] = []

    /// Номера, пришедшие последним списком с сайта (этап 35), а не сердечком на этом телефоне: их карточки фоновая
    /// загрузка этапа 13 не качает — сердечко на них здесь не нажимали, а список с сайта бывает длинным.
    private(set) var пришлиССайта: Set<String> = []

    private init() {
        var виденные = Set<String>()
        let прочитанные = ИзбранноеФайл.прочитать()
            .sorted { $0.savedAt > $1.savedAt }
            .filter { виденные.insert($0.id).inserted }
        показать(Array(прочитанные.prefix(Self.предел)))
    }

    func есть(_ id: String) -> Bool { номера.contains(id) }

    func переключить(_ товар: Listing) {
        if номера.contains(товар.id) {
            let была = записи.first { $0.id == товар.id }
            убрать(товар.id)
            /* Этап 35: вошедшему — то же на сайт; не вышло — СинхронИзбранного вернёт запись на её место. */
            if Config.избранноеССайтом { СинхронИзбранного.shared.нажали(товар.id, добавить: false, была: была) }
        } else {
            пришлиССайта.remove(товар.id)             // этап 35: теперь это сердечко здесь — карточку этап 13 скачает
            добавить(товар)
            ПросьбаОценить.shared.вИзбранное(товар.id)   // этап 16: сердечко — удачный момент для просьбы оценить
            if Config.избранноеССайтом { СинхронИзбранного.shared.нажали(товар.id, добавить: true, была: nil) }
        }
    }

    // MARK: - Вместе с сайтом (этап 35)

    /// Номера в порядке списка, новые первыми, — так же, как сайт держит ulx_fav (unshift): их он шлёт в merge.
    var порядок: [String] { записи.map(\.id) }

    /// Откат неудавшегося снятия: запись — на прежнее место (по дате сохранения), с прежними датами и ценой.
    func вернуть(_ запись: ИзбранноеЗапись) {
        guard !номера.contains(запись.id) else { return }
        var новые = записи
        let место = новые.firstIndex { $0.savedAt < запись.savedAt } ?? новые.count
        новые.insert(запись, at: место)
        if новые.count > Self.предел { новые.removeLast(новые.count - Self.предел) }
        применить(новые)
    }

    /**
     Список избранного с сайта (ids ответа favorites.php) — теперь это избранное. Записи с телефона, которых в списке
     нет, уходят (сняли на сайте или на другом телефоне); те, что есть, остаются на своих местах и со своими ценами.
     Новые номера встают сверху в порядке списка, если для них пришла карточка (`карточки`, api/listings.php?ids=);
     без карточки номер не показываем — сайт тоже показывает только найденные объявления (mkFavEnsure).
     */
    func принятьССайта(_ список: [String], карточки: [Listing]) {
        let нужные = Set(список)
        let поНомеру = Dictionary(карточки.map { ($0.id, $0) }, uniquingKeysWith: { первый, _ in первый })
        var есть = Set<String>()
        var оставить: [ИзбранноеЗапись] = []
        for запись in записи where нужные.contains(запись.id) {
            оставить.append(запись)
            есть.insert(запись.id)
        }
        var пришли: [ИзбранноеЗапись] = []
        let сейчас = Date()
        for номер in список where !есть.contains(номер) {
            guard let товар = поНомеру[номер] else { continue }
            есть.insert(номер)
            /* Даты — по убыванию в порядке списка: после перезапуска (сортировка по дате) порядок тот же. */
            let когда = сейчас.addingTimeInterval(-0.001 * Double(пришли.count))
            пришли.append(ИзбранноеЗапись(товар, когда: когда))
        }
        var итог = пришли + оставить
        if итог.count > Self.предел { итог.removeLast(итог.count - Self.предел) }
        guard итог != записи else { return }
        пришлиССайта = Set(пришли.map(\.id))
        применить(итог)
    }

    /// Пришёл ли номер списком с сайта, а не сердечком здесь (для фоновой загрузки карточек этапа 13).
    func пришёлССайта(_ id: String) -> Bool { пришлиССайта.contains(id) }

    func добавить(_ товар: Listing) {
        var новые = записи.filter { $0.id != товар.id }
        новые.insert(ИзбранноеЗапись(товар), at: 0)
        if новые.count > Self.предел { новые.removeLast(новые.count - Self.предел) }
        применить(новые)
    }

    func убрать(_ id: String) {
        guard номера.contains(id) else { return }
        применить(записи.filter { $0.id != id })
    }

    /// Открыли полную карточку сохранённого — переписать цену и прочее свежими, место в списке не меняя. Пустое в
    /// ответе (нет названия, обложки) прежнее не затирает: хуже старой цены только пустая карточка.
    func освежить(_ товар: Listing) {
        guard let место = записи.firstIndex(where: { $0.id == товар.id }) else { return }
        let было = записи[место]
        let стало = Self.слить(было, товар)
        guard стало != было else { return }
        var новые = записи
        новые[место] = стало
        применить(новые)
    }

    /// Запись со свежими полями объявления — на прежнем месте, с прежними датами. Пустое в ответе прежнее не затирает.
    private static func слить(_ было: ИзбранноеЗапись, _ товар: Listing) -> ИзбранноеЗапись {
        var стало = ИзбранноеЗапись(товар, когда: было.savedAt)
        if стало.title.isEmpty { стало.title = было.title }
        if стало.thumb == nil { стало.thumb = было.thumb }
        if стало.city.isEmpty { стало.city = было.city }
        стало.ценаПроверена = было.ценаПроверена
        return стало
    }

    // MARK: - Проверка цены (этап 21)

    /// Кого проверить в этот раз: до `сколько` объявлений, давно проверенные первыми, ни разу не проверенные — самыми
    /// первыми. Так за несколько запусков по кругу обходится всё избранное, а не одни и те же десять.
    func кПроверкеЦены(_ сколько: Int) -> [Listing] {
        let порядок = записи.sorted { ($0.ценаПроверена ?? .distantPast) < ($1.ценаПроверена ?? .distantPast) }
        return порядок.prefix(сколько).map { Listing(избранное: $0) }
    }

    /**
     Итог фоновой проверки цены (этап 21): свежие карточки ?id= и номера, которые сайт ответил (в том числе 404 — снятое
     с продажи не должно вечно стоять в очереди первым). Проверенным ставим дату; тем, чья карточка пришла, — свежие
     поля, как при открытии карточки. Возвращает, где цена снизилась по сравнению со снимком.

     Объявление, которое сняли с избранного, пока шли запросы, пропускаем: его записи уже нет.
     */
    func отметитьПроверкуЦен(_ свежие: [Listing], проверены: Set<String>, когда: Date = Date()) -> [СнижениеЦеныНайдено] {
        let поНомеру = Dictionary(свежие.map { ($0.id, $0) }, uniquingKeysWith: { первый, _ in первый })
        var новые = записи
        var снижения: [СнижениеЦеныНайдено] = []
        for место in новые.indices where проверены.contains(новые[место].id) {
            let было = новые[место]
            var стало = было
            if let свежий = поНомеру[было.id] {
                стало = Self.слить(было, свежий)
                if let найдено = СнижениеЦены.сравнить(было, стало) { снижения.append(найдено) }
            }
            стало.ценаПроверена = когда
            новые[место] = стало
        }
        if новые != записи { применить(новые) }
        return снижения
    }

    /// Выход из аккаунта: избранное ушедшего следующему не показываем.
    func стереть() {
        показать([])
        ИзбранноеФайл.стереть()
    }

    private func показать(_ новые: [ИзбранноеЗапись]) {
        записи = новые
        номера = Set(новые.map(\.id))
        товары = новые.map { Listing(избранное: $0) }
    }

    private func применить(_ новые: [ИзбранноеЗапись]) {
        показать(новые)
        ИзбранноеФайл.записать(новые)
    }
}

/// Запись избранного на диске: поля строки ленты и когда сохранили. Новые поля — только необязательные (Optional),
/// иначе файл прежней версии не разберётся.
struct ИзбранноеЗапись: Codable, Equatable {
    let id: String
    var title: String
    var price: Double?
    var oldPrice: Double?
    var negotiable: Bool
    var forRent: Bool
    var rentPriceDay: Double?
    var thumb: String?
    var city: String
    var isTop: Bool
    var isNew: Bool
    var savedAt: Date
    /// Когда фоновая проверка последний раз спрашивала цену у сайта (этап 21). nil — ни разу: такие — первыми.
    var ценаПроверена: Date?

    init(_ т: Listing, когда: Date = Date()) {
        id = т.id
        title = т.title
        price = т.price
        oldPrice = т.oldPrice
        negotiable = т.negotiable
        forRent = т.forRent
        rentPriceDay = т.rentPriceDay
        thumb = т.thumb
        city = т.city
        isTop = т.isTop
        isNew = т.isNew
        savedAt = когда
    }
}

extension Listing {
    /// Объявление из записи избранного — как строка ленты: полную карточку ListingDetailView дотянет по ?id=.
    init(избранное з: ИзбранноеЗапись) {
        id = з.id
        title = з.title
        price = з.price
        oldPrice = з.oldPrice
        negotiable = з.negotiable
        forRent = з.forRent
        rentPriceDay = з.rentPriceDay
        thumb = з.thumb
        city = з.city
        isTop = з.isTop
        isNew = з.isNew
    }
}

/**
 ФАЙЛ ИЗБРАННОГО: один JSON в Application Support, вне резервной копии — как лента на диске (ListingsCache).

 Пишем не на главном потоке, но по порядку: одна последовательная очередь, иначе два быстрых нажатия могли бы лечь
 на диск наоборот, а стирание при выходе — обогнать последнюю запись и оставить файл.
 */
enum ИзбранноеФайл {
    private static let очередь = DispatchQueue(label: "kz.kliko.favorites", qos: .utility)

    private static var адрес: URL? {
        try? FileManager.default.url(for: .applicationSupportDirectory, in: .userDomainMask,
                                     appropriateFor: nil, create: true)
            .appendingPathComponent("kliko-favorites.json")
    }

    /// Запись, которая не разобралась, пропускаем, а не теряем весь список.
    private struct Любая: Decodable {
        let запись: ИзбранноеЗапись?
        init(from decoder: Decoder) throws { запись = try? ИзбранноеЗапись(from: decoder) }
    }

    static func прочитать() -> [ИзбранноеЗапись] {
        guard let файл = адрес,
              let данные = try? Data(contentsOf: файл),
              let список = try? JSONDecoder().decode([Любая].self, from: данные) else { return [] }
        return список.compactMap(\.запись)
    }

    static func записать(_ список: [ИзбранноеЗапись]) {
        guard let файл = адрес, let данные = try? JSONEncoder().encode(список) else { return }
        очередь.async {
            do {
                try данные.write(to: файл, options: .atomic)
                var значения = URLResourceValues()
                значения.isExcludedFromBackup = true
                var изменяемый = файл
                try? изменяемый.setResourceValues(значения)
            } catch {
                // Диск полон — на экране избранное есть до конца запуска; следующее нажатие попробует снова.
            }
        }
    }

    /// Дождаться записей, поставленных раньше (этап 21): фоновая проверка цены закрывает задание только после того,
    /// как новые цены легли на диск, — иначе iOS усыпила бы приложение раньше, и о том же снижении сказали бы дважды.
    static func дождаться() async {
        await withCheckedContinuation { (готово: CheckedContinuation<Void, Never>) in
            очередь.async { готово.resume() }
        }
    }

    static func стереть() {
        guard let файл = адрес else { return }
        очередь.async { try? FileManager.default.removeItem(at: файл) }
    }
}

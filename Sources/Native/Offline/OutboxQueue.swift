struct ИсходящееСообщение: Codable, Identifiable, Equatable {
    enum Куда: String, Codable {
        /// dm.php send {thread_id, text}.
        case личный = "dm"
        /// chat.php send {pid, text[, force_escalate]} — чат по объявлению, я покупатель.
        case объявление = "lot"
        /// chat.php seller_reply {chat_id, text} — чат лида, я продавец.
        case лид = "lead"
    }

    enum Состояние: String, Codable {
        case ждёт = "wait"
        case уходит = "sending"
        /// Дошло — облако держится, пока переписка не перечитана (иначе оно мигнуло бы пустотой).
        case ушло = "sent"
        case неУшло = "failed"
    }

    let id: String
    let куда: Куда
    /// tid переписки dm.php, номер объявления или chat_id лида.
    let адрес: String
    let текст: String
    let создано: Date
    let владелец: String
    var состояние: Состояние
    /// Попыток, ушедших в сеть (могли дойти): со второй — сначала проверка, не дошло ли.
    var попыток: Int
    var первая: Date?
    var последняя: Date?
    /// Время сервера у последнего сообщения переписки, известного при постановке: дошедшее — только позже него.
    let известноДо: String
    /// Таких же текстов этой переписки, стоявших в очереди раньше: их доставка — не доставка этого.
    let уже: Int
    /// chat.php send: force_escalate — первое сообщение покупателя зовёт продавца.
    let позвать: Bool
    /// Почему не ушло — слова сайта, если он их сказал.
    var причина: String?

    /// Переписка: вид и адрес.
    var ключ: String { Self.ключПереписки(куда, адрес) }

    static func ключПереписки(_ куда: Куда, _ адрес: String) -> String { куда.rawValue + ":" + адрес }
}

@MainActor
final class ОчередьСообщений: ObservableObject {
    static let shared = ОчередьСообщений()

    @Published private(set) var сообщения: [ИсходящееСообщение] = []
    /// Растёт по ключу переписки, когда сообщение из очереди дошло: открытая переписка перечитывает себя.
    @Published private(set) var дошло: [String: Int] = [:]

    /// Сеть «есть», а запрос всё равно не проходит — столько попыток, потом «Не отправлено».
    static let попытокДо = 6
    /// Окно сверки времени своего сообщения с попытками: часы телефона и сервера могут расходиться.
    static let окно: TimeInterval = 120

    private var загружена = false
    private var разбираем = false
    /// Повод разобрать пришёл, пока разбор шёл: после него — ещё круг.
    private var ещёРаз = false
    private var подписки: Set<AnyCancellable> = []
    private var отложенный: Task<Void, Never>? = nil
    /// Растёт при стирании: ответ, пришедший после выхода, очередь не трогает.
    private var поколение = 0

    private init() {}

    // MARK: - Запуск

    /// Запуск приложения (SceneDelegate): очередь с диска, сеть вернулась или приложение ожило — разбор.
    func запустить() {
        guard подписки.isEmpty else { return }
        загрузить()
        СетьПриложения.shared.$онлайн
            .removeDuplicates()
            .sink { [weak self] есть in
                if есть { self?.разобратьПозже(1) }
            }
            .store(in: &подписки)
        /* Страница сказала номер вошедшего: чужие сообщения прочь, свои — в путь (до номера они не уходят).
           @Published шлёт до записи — номер берём из события, а не из сессии. */
        СессияПриложения.shared.$id
            .removeDuplicates()
            .sink { [weak self] номер in
                guard !номер.isEmpty, let self else { return }
                self.убратьЧужие(номер)
                self.разобратьПозже(1)
            }
            .store(in: &подписки)
        NotificationCenter.default.publisher(for: UIApplication.didBecomeActiveNotification)
            .sink { [weak self] _ in self?.разобратьПозже(1.5) }
            .store(in: &подписки)
    }

    // MARK: - Для экранов

    /// Сообщения этой переписки, ждущие и неушедшие, по порядку.
    /// Только владельца копий: сообщения другого аккаунта (сессия кончилась, вошёл другой) не показываются.
    func для(_ куда: ИсходящееСообщение.Куда, _ адрес: String) -> [ИсходящееСообщение] {
        let чей = КопииБезСети.владелец()
        guard !адрес.isEmpty, !чей.isEmpty else { return [] }
        return сообщения.filter { $0.владелец == чей && $0.куда == куда && $0.адрес == адрес }
    }

    /// Есть ли в переписке ждущее отправки: тогда и новое сообщение — в очередь, за ним, а не вперёд. Неушедшее
    /// («Не отправлено») порядок не держит — новое уходит как обычно.
    func естьЖдущие(_ куда: ИсходящееСообщение.Куда, _ адрес: String) -> Bool {
        для(куда, адрес).contains { $0.состояние == .ждёт || $0.состояние == .уходит }
    }

    /**
     Поставить текст в очередь. пробовали — время попытки, которая только что оборвалась сетью (могла дойти: её проверят
     перед повтором); nil — в сеть ещё не уходило. известноДо — время сервера у последнего сообщения переписки на экране.
     Вернёт false, если поставить нельзя (никто не вошёл, пустой текст или адрес) — тогда экран ведёт себя как раньше.
     */
    @discardableResult
    func поставить(_ текст: String, куда: ИсходящееСообщение.Куда, адрес: String, известноДо: String,
                   позвать: Bool = false, пробовали: Date? = nil) -> Bool {
        let чистый = текст.trimmingCharacters(in: .whitespacesAndNewlines)
        let чей = КопииБезСети.владелец()
        guard !чистый.isEmpty, !адрес.isEmpty, !чей.isEmpty else { return false }
        загрузить()
        let уже = сообщения.filter { $0.владелец == чей && $0.куда == куда && $0.адрес == адрес
            && ($0.состояние == .ждёт || $0.состояние == .уходит) && Self.тотЖеТекст($0.текст, чистый) }.count
        let новое = ИсходящееСообщение(id: UUID().uuidString, куда: куда, адрес: адрес, текст: чистый, создано: Date(),
                                       владелец: чей, состояние: .ждёт, попыток: пробовали == nil ? 0 : 1,
                                       первая: пробовали, последняя: пробовали, известноДо: известноДо, уже: уже,
                                       позвать: позвать, причина: nil)
        сообщения.append(новое)
        сохранить()
        UIAccessibility.post(notification: .announcement, argument: OfflineText.т("q_wait"))
        if СетьПриложения.shared.онлайн { разобратьПозже(пробовали == nil ? 0.3 : 4) }
        return true
    }

    /// «Не отправлено — нажмите, чтобы повторить»: снова в очередь (проверка «не дошло ли» — как у любого повтора).
    func повторить(_ id: String) {
        guard let место = сообщения.firstIndex(where: { $0.id == id }), сообщения[место].состояние == .неУшло else { return }
        сообщения[место].состояние = .ждёт
        сообщения[место].причина = nil
        /* Сетевые неудачи перед этим не в счёт: следующая серия — снова до попытокДо. */
        if сообщения[место].попыток >= Self.попытокДо { сообщения[место].попыток = 1 }
        сохранить()
        разобратьПозже(0)
    }

    /// Убрать неушедшее (меню облака «Удалить»).
    func убрать(_ id: String) {
        guard let место = сообщения.firstIndex(where: { $0.id == id }), сообщения[место].состояние != .уходит else { return }
        сообщения.remove(at: место)
        сохранить()
    }

    /// Открытая переписка перечитана после доставки — её дошедшие облака больше не нужны.
    func забратьДошедшие(_ ключ: String) {
        let было = сообщения.count
        сообщения.removeAll { $0.ключ == ключ && $0.состояние == .ушло }
        if сообщения.count != было { сохранить() }
    }

    /// Выход из аккаунта: очередь ушедшего — прочь, с диска тоже; ответ в пути её не вернёт.
    func стереть() {
        поколение += 1
        отложенный?.cancel()
        отложенный = nil
        ещёРаз = false
        сообщения = []
        дошло = [:]
        загружена = true
        ОчередьФайл.стереть()
    }

    // MARK: - Разбор

    private func разобратьПозже(_ секунд: Double) {
        загрузить()
        guard сообщения.contains(where: { $0.состояние == .ждёт }) else { return }
        отложенный?.cancel()
        let пауза = UInt64(max(0, секунд) * 1_000_000_000)
        отложенный = Task { @MainActor [weak self] in
            if пауза > 0 { try? await Task.sleep(nanoseconds: пауза) }
            guard !Task.isCancelled, let self else { return }
            self.отложенный = nil
            self.начатьРазбор()
        }
    }

    /// Разбор — своей задачей: отмена отложенного запуска (новый повод) не обрывает запрос, который уже в пути.
    private func начатьРазбор() {
        if разбираем {
            ещёРаз = true
            return
        }
        разбираем = true
        Task { @MainActor [weak self] in
            await self?.разобрать()
            guard let self else { return }
            self.разбираем = false
            if self.ещёРаз {
                self.ещёРаз = false
                self.разобратьПозже(0.5)
            }
        }
    }

    /// По одному, по порядку постановки. Сеть подвела — разбор стоп до её возвращения или до паузы.
    private func разобрать() async {
        let моё = поколение
        while моё == поколение, СетьПриложения.shared.онлайн {
            let чей = владелецОтправки()
            guard !чей.isEmpty else { return }
            убратьЧужие(чей)
            guard let взятое = сообщения.first(where: { $0.состояние == .ждёт && $0.владелец == чей }) else { return }
            отметить(взятое.id) { $0.состояние = .уходит }
            let итог = await отправить(взятое)
            guard моё == поколение else { return }
            switch итог {
            case .дошло:
                отметить(взятое.id) { $0.состояние = .ушло }
                дошло[взятое.ключ, default: 0] += 1
                убратьУшедшееПозже(взятое.id)
            case .сеть(let ушлаВСеть):
                /* Попытка в счёт, если запрос уходил (тогда следующий раз — сначала проверка) или сеть «есть», а он не
                   прошёл; сети нет вовсе — не в счёт. */
                let онлайн = СетьПриложения.shared.онлайн
                var попыток = 0
                отметить(взятое.id) { с in
                    if ушлаВСеть || онлайн { с.попыток += 1 }
                    с.состояние = с.попыток >= Self.попытокДо ? .неУшло : .ждёт
                    попыток = с.попыток
                }
                /* Сеть «есть», а запрос не прошёл — пауза растёт: 5, 10, 20, 40 с; сети нет — ждём её возвращения. */
                if онлайн {
                    let пауза = min(60, 5 * pow(2, Double(max(0, попыток - 1))))
                    разобратьПозже(пауза)
                }
                return
            case .страницаНеНаСайте:
                /* Попытка не в счёт: запрос не уходил. Возврат в приложение и сеть — свои поводы; пока сеть есть,
                   заглядываем и сами — человек может вернуться со шлюза оплаты, не покидая приложения. */
                отметить(взятое.id) { $0.состояние = .ждёт }
                if СетьПриложения.shared.онлайн { разобратьПозже(Self.паузаСтраницы) }
                return
            case .отказ(let слова):
                отметить(взятое.id) { с in
                    с.состояние = .неУшло
                    с.причина = слова
                }
            }
        }
    }

    private enum Итог {
        case дошло
        /// Сеть подвела. ушлаВСеть — запрос уходил (мог дойти); false — не уходил вовсе (проверка не прочиталась).
        case сеть(ушлаВСеть: Bool)
        /// Сайт отказал по существу; его слова, если есть.
        case отказ(String?)
        /// Страница под слоем не на сайте (шлюз оплаты, eGov) или грузится: фоновая очередь её не уводит — не уходило.
        case страницаНеНаСайте
    }

    /// Страница под слоем не на сайте — заглянуть снова через столько.
    static let паузаСтраницы: TimeInterval = 20

    /// Номер, от чьего имени очередь шлёт: вошедший, и только если страница его уже сказала. Запасного «последнего
    /// вошедшего» (КопииБезСети.владелец) здесь нет: после входа другим аккаунтом он ещё прежний.
    private func владелецОтправки() -> String {
        let сессия = СессияПриложения.shared
        guard сессия.вошёл == true else { return "" }
        return сессия.id
    }

    /// Вошёл другой номер — сообщения прежнего прочь, с диска тоже: ни показать, ни отправить их с чужих кук.
    private func убратьЧужие(_ чей: String) {
        guard !чей.isEmpty else { return }
        загрузить()
        let было = сообщения.count
        сообщения.removeAll { $0.владелец != чей }
        if сообщения.count != было { сохранить() }
    }

    private func отправить(_ с: ИсходящееСообщение) async -> Итог {
        /* dm.php и chat.php лида — страницей под слоем, фоном (ждать = false). Она не на сайте или грузится — не шлём и
           не сверяем: иначе запрос оборвался бы до отправки и сошёл за сетевую неудачу. При нативной сессии запрос может
           пройти и без страницы — пробуем; оборвётся — сочтётся как ушедший, и следующий раз начнётся со сверки. */
        if с.куда != .объявление, !Config.нативнаяСессия, !КабинетСайта.страницаГотова() { return .страницаНеНаСайте }
        /* Повтор: прошлая попытка могла дойти — сначала смотрим переписку. */
        if с.попыток > 0 {
            switch await проверить(с) {
            case .some(true): return .дошло
            case .some(false): break
            case .none: return .сеть(ушлаВСеть: false)
            }
        }
        let сейчас = Date()
        отметить(с.id) { запись in
            if запись.первая == nil { запись.первая = сейчас }
            запись.последняя = сейчас
        }
        switch с.куда {
        case .личный:
            do {
                /* Блокировку ({ok:false, blocked:true}) выполнить не бросает — смотрим ok сами: дошло только при ok. */
                let ответ = try await ChatAPI.написатьЦеликом(tid: с.адрес, текст: с.текст, ждать: false)
                if ответ.ok { return .дошло }
                let сайта = (ответ.сообщение ?? "").trimmingCharacters(in: .whitespacesAndNewlines)
                let код = ответ.заблокирован ? "blocked" : (ответ.ошибка ?? "")
                return .отказ(ChatAPI.текст(.отказ(сайта.isEmpty ? код : сайта)) ?? ChatAPI.текст(.отказ(код)))
            } catch let ошибка as ChatAPI.Ошибка {
                if ошибка == .сеть { return .сеть(ушлаВСеть: true) }
                return .отказ(ChatAPI.текст(ошибка))
            } catch {
                return .сеть(ушлаВСеть: true)
            }
        case .объявление:
            switch await ЧатОбъявленияAPI.написать(объявление: с.адрес, текст: с.текст, предложение: nil,
                                                   позвать: с.позвать) {
            case .готово:
                return .дошло
            case .сеть:
                return .сеть(ушлаВСеть: true)
            case .заблокирован(let слова):
                return .отказ(слова ?? ListingChatText.т("blocked_toast"))
            case .нуженВход(let слова), .нужнаВерификация(let слова), .лимит(let слова):
                return .отказ(слова)
            case .отказ(let код):
                return .отказ(ChatAPI.текст(.отказ(код)))
            }
        case .лид:
            do {
                let j = try await ИнбоксAPI.отправитьБезТокена("chat.php?action=seller_reply",
                                                               тело: ["chat_id": с.адрес, "text": с.текст], ждать: false)
                if МоиОбъявленияAPI.да(j["ok"]) { return .дошло }
                let слова = МоиОбъявленияAPI.строка(j["msg"])
                return .отказ(слова.isEmpty ? ИнбоксAPI.текстОшибки(j, запасной: ИнбоксText.т("send_err")) : слова)
            } catch {
                if let сбой = error as? КабинетСайта.Сбой, сбой == .приложение { return .отказ(nil) }
                return .сеть(ушлаВСеть: true)
            }
        }
    }

    /**
     Дошло ли уже: true — да, false — нет, nil — переписку прочитать не вышло. Своё сообщение с тем же текстом позже
     последнего известного (время сервера) и в окне попыток (время телефона ± 2 мин); таких должно быть больше, чем
     одинаковых текстов, стоявших в очереди раньше этого.
     */
    private func проверить(_ с: ИсходящееСообщение) async -> Bool? {
        var свои: [(текст: String, когда: Date?)] = []
        switch с.куда {
        case .личный:
            guard let ответ = try? await ChatAPI.перепискаЦеликом(с.адрес, ждать: false), let переписка = ответ.переписка else {
                return nil
            }
            свои = переписка.сообщения.filter { $0.моё && !$0.системное }
                .map { (текст: $0.текст, когда: ИнбоксВремя.дата($0.когда)) }
        case .объявление:
            guard case .готово(let снимок) = await ЧатОбъявленияAPI.загрузить(с.адрес) else { return nil }
            свои = (снимок.сообщения ?? []).filter { $0.моё }
                .map { (текст: $0.текст, когда: ВремяЧатаОбъявления.дата($0.когда)) }
        case .лид:
            let хвост = "chat.php?action=seller_chat&cid=" + ИнбоксAPI.вАдрес(с.адрес)
            guard let j = try? await ИнбоксAPI.получить(хвост, ждать: false), МоиОбъявленияAPI.да(j["ok"]) else {
                return nil
            }
            let чат = j["chat"] as? [String: Any]
            let список = (чат?["messages"] as? [[String: Any]]) ?? []
            свои = СообщениеЛида.разобрать(список).filter { $0.роль == "seller" }
                .map { (текст: $0.текст, когда: ИнбоксВремя.дата($0.когда)) }
        }
        let после = ИнбоксВремя.дата(с.известноДо)
        let от = (с.первая ?? с.создано).addingTimeInterval(-Self.окно)
        let до = (с.последняя ?? Date()).addingTimeInterval(Self.окно)
        let нашлось = свои.filter { своё in
            guard Self.тотЖеТекст(своё.текст, с.текст), let когда = своё.когда else { return false }
            if let после, когда <= после { return false }
            return когда >= от && когда <= до
        }.count
        return нашлось > с.уже
    }

    /// Тот же текст: как есть, или сайт заменил буквы звёздочками (mod_mask_profanity — длина та же), или обрезал
    /// длинное (dm.php — до 2000 знаков).
    static func тотЖеТекст(_ сайта: String, _ своё: String) -> Bool {
        let а = Array(сайта.trimmingCharacters(in: .whitespacesAndNewlines))
        let б = Array(своё.trimmingCharacters(in: .whitespacesAndNewlines))
        if а == б { return true }
        if а.count == 2000 && б.count > 2000 { return Array(б.prefix(2000)) == а }
        guard а.count == б.count, а.contains("*") else { return false }
        for (буква, своя) in zip(а, б) where буква != своя && буква != "*" { return false }
        return true
    }

    // MARK: - Внутреннее

    private func отметить(_ id: String, _ правка: (inout ИсходящееСообщение) -> Void) {
        guard let место = сообщения.firstIndex(where: { $0.id == id }) else { return }
        правка(&сообщения[место])
        сохранить()
    }

    /// Дошедшее облако держится до перечитанной переписки (забратьДошедшие), но не дольше 4 с — переписка может быть
    /// и закрыта.
    private func убратьУшедшееПозже(_ id: String) {
        let моё = поколение
        Task { @MainActor [weak self] in
            try? await Task.sleep(nanoseconds: 4_000_000_000)
            guard let self, моё == self.поколение else { return }
            let было = self.сообщения.count
            self.сообщения.removeAll { $0.id == id && $0.состояние == .ушло }
            if self.сообщения.count != было { self.сохранить() }
        }
    }

    private func загрузить() {
        guard !загружена else { return }
        загружена = true
        /* Прерванное запуском «уходит» — снова «ждёт»: дошло ли, покажет проверка перед повтором. Счётчик попыток
           растёт только после неудачи, а первая попытка могла дойти (приложение закрыли, пока запрос был в пути), —
           такое считаем ушедшим в сеть хотя бы раз, иначе повтор пропустил бы проверку и сообщение пришло бы дважды. */
        сообщения = ОчередьФайл.прочитать().compactMap { (с: ИсходящееСообщение) -> ИсходящееСообщение? in
            var запись = с
            if запись.состояние == .уходит || запись.последняя != nil { запись.попыток = max(запись.попыток, 1) }
            switch запись.состояние {
            case .уходит: запись.состояние = .ждёт
            case .ушло: return nil
            case .ждёт, .неУшло: break
            }
            return запись
        }
    }

    private func сохранить() {
        ОчередьФайл.записать(сообщения.filter { $0.состояние != .ушло })
    }
}

/// Файл очереди: Application Support, вне резервной копии, одной последовательной очередью — стирание не обгонит запись.
enum ОчередьФайл {
    private static let очередь = DispatchQueue(label: "kz.kliko.outbox", qos: .utility)

    private static var адрес: URL? {
        try? FileManager.default.url(for: .applicationSupportDirectory, in: .userDomainMask,
                                     appropriateFor: nil, create: true)
            .appendingPathComponent("kliko-outbox.json")
    }

    static func прочитать() -> [ИсходящееСообщение] {
        guard let файл = адрес, let данные = try? Data(contentsOf: файл),
              let список = try? JSONDecoder().decode([ИсходящееСообщение].self, from: данные) else { return [] }
        return список
    }

    static func записать(_ список: [ИсходящееСообщение]) {
        guard let файл = адрес, let данные = try? JSONEncoder().encode(список) else { return }
        очередь.async {
            do {
                try данные.write(to: файл, options: .atomic)
                var значения = URLResourceValues()
                значения.isExcludedFromBackup = true
                var изменяемый = файл
                try? изменяемый.setResourceValues(значения)
            } catch {
                // Диск полон — очередь есть в памяти до конца запуска.
            }
        }
    }

    static func стереть() {
        guard let файл = адрес else { return }
        очередь.async { try? FileManager.default.removeItem(at: файл) }
    }
}

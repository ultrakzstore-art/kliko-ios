extension Config {
    /// Значки корневых разделов в стиле iOS (ИконкаРаздела): сетка главной, плитки «Категорий», старт подачи «Что
    /// размещаете?», выбор раздела в подаче, строки разделов в поиске. false — прежние картинки сайта и значки.
    static let нативныеЗначкиРазделов = true
}

// MARK: - Набор

/// Знак и краска значка раздела.
struct ВидЗначкаРаздела {
    /// SF Symbol из iOS 17.0 — рисуется белым.
    let символ: String
    /// Краска раздела: низ градиента и цвет мягкой тени.
    let краска: UIColor
    /// Оптическая поправка кегля: широкий знак — меньше 1, чтобы все значки весили на глаз одинаково.
    let поправка: CGFloat

    init(символ: String, краска: UIColor, поправка: CGFloat = 1) {
        self.символ = символ
        self.краска = краска
        self.поправка = поправка
    }
}

/// Набор значков корней: знак по ключу раздела и краска раздела.
enum ЗначкиРазделов {
    /// «Все категории» — нейтральный зелёный Kliko (--mk-green2). Сетка 3×3, как у чипа «Категории» в полосе разделов:
    /// 2×2 там значит «Все объявления» и здесь — запасной знак неизвестного корня.
    static let всеКатегории = ВидЗначкаРаздела(символ: "square.grid.3x3.fill", краска: Theme.hex(0x1D7D4A),
                                               поправка: 0.9)

    /// Знак корня и оптическая поправка. Недвижимость — дом, а не здания: на 44 pt два здания сливаются в пятно, дом
    /// читается сразу. Электроника — ноутбук с телефоном: один телефон на 44 pt похож на пустой прямоугольник.
    /// «rentgood» — плитка «Сдать вещь» старта подачи: не корень сайта, но стоит в той же сетке.
    private static let знаки: [String: (символ: String, поправка: CGFloat)] = [
        "transport": ("car.fill", 0.94),
        "realty": ("house.fill", 1),
        "services": ("wrench.and.screwdriver.fill", 0.94),
        "electronics": ("laptopcomputer.and.iphone", 0.82),
        "goods": ("bag.fill", 1),
        "animals": ("pawprint.fill", 1),
        "jobs": ("briefcase.fill", 0.96),
        "clothing": ("tshirt.fill", 0.94),
        "home-garden": ("sofa.fill", 0.88),
        "kids": ("teddybear.fill", 1),
        "sport": ("figure.run", 1.04),
        "hobby": ("paintpalette.fill", 0.96),
        "food-farm": ("carrot.fill", 1),
        "beauty": ("sparkles", 1),
        "rentgood": ("key.fill", 0.96)
    ]

    /// Краски корней, которых нет среди разделов главной, — MK_CAT_COLOR сайта (ПодсказкиСайта.краскиКорней) с двумя
    /// поправками: «Детские» — жёлтый #FACC15 под белым знаком не читается, взят тёплый янтарь глубже (#CA8A04); «Дом и
    /// сад» у сайта той же краски, что «Товары» (#D97706), — на экране «Категории» они рядом, поэтому оранжевый
    /// (#EA580C). «Сдать вещь» — небесный, как её плитка старта подачи.
    private static let краски: [String: UInt32] = [
        "clothing": 0xDB2777,
        "home-garden": 0xEA580C,
        "kids": 0xCA8A04,
        "sport": 0x0891B2,
        "hobby": 0xC026D3,
        "food-farm": 0x65A30D,
        "beauty": 0xE11D48,
        "rentgood": 0x0284C7
    ]

    /// Значок корня по ключу. Семь разделов главной — краской своих плиток (РазделГлавной.краска), остальные корни — из
    /// таблицы выше; неизвестный корень (новый у сайта) — знак сетки и `запасная` краска (краска корня в дереве сайта),
    /// а без неё — зелёный Kliko.
    static func вид(_ ключ: String, запасная: UIColor? = nil) -> ВидЗначкаРаздела {
        let знак = знаки[ключ] ?? (символ: "square.grid.2x2.fill", поправка: 0.9)
        let краска: UIColor
        if let раздел = РазделГлавной.с(ключом: ключ) {
            краска = Theme.hex(раздел.краска)
        } else if let своя = краски[ключ] {
            краска = Theme.hex(своя)
        } else {
            краска = запасная ?? Theme.hex(0x1D7D4A)
        }
        return ВидЗначкаРаздела(символ: знак.символ, краска: краска, поправка: знак.поправка)
    }

    /// Тот же знак корня без заливки — для тонких значков (чипы полосы разделов, хлебные крошки, заглушка фото, полоса
    /// типа подачи): у корня везде один знак. Неизвестный корень — сетка, как прежде.
    static func контур(_ ключ: String) -> String {
        let символ = знаки[ключ]?.символ ?? "square.grid.2x2"
        return символ.hasSuffix(".fill") ? String(символ.dropLast(5)) : символ
    }
}

// MARK: - Значок

/// Значок корневого раздела: скруглённый квадрат с градиентом краски раздела и белым знаком (описание — в начале файла).
/// Имя не «ЗначокРаздела»: так уже называется enum значка корня в чатах (InboxView.swift).
struct ИконкаРаздела: View {
    let вид: ВидЗначкаРаздела
    let сторона: CGFloat
    /// Название для VoiceOver; nil — значок скрыт (название читает плитка).
    let название: String?
    /// Значок лежит на сплошной заливке краской (сплошная плитка «Категорий»): белое «стекло» вместо градиента краски —
    /// краска на краске не видна.
    let наКраске: Bool
    /// Растёт — знак один раз отскакивает (касание плитки).
    let прыжок: Int
    @Environment(\.colorScheme) private var схема
    /// Ячейка сетки главной под пальцем (НажатиеРаздела) — отскок, как только палец лёг.
    @Environment(\.разделНажат) private var нажат
    @State private var касаний = 0

    init(вид: ВидЗначкаРаздела, сторона: CGFloat, название: String? = nil, наКраске: Bool = false, прыжок: Int = 0) {
        self.вид = вид
        self.сторона = сторона
        self.название = название
        self.наКраске = наКраске
        self.прыжок = прыжок
    }

    init(ключ: String, сторона: CGFloat, название: String? = nil, наКраске: Bool = false, прыжок: Int = 0,
         запасная: UIColor? = nil) {
        self.init(вид: ЗначкиРазделов.вид(ключ, запасная: запасная), сторона: сторона, название: название,
                  наКраске: наКраске, прыжок: прыжок)
    }

    /// Скругление иконки iOS — 22,37 % стороны.
    private static let долиСкругления: CGFloat = 0.2237
    /// Кегль знака — 46 % стороны (до оптической поправки).
    private static let долиЗнака: CGFloat = 0.46
    /// Тень карточки сайта — rgba(16,40,28).
    private static let тень = Color(red: 16 / 255, green: 40 / 255, blue: 28 / 255)

    var body: some View {
        let форма = RoundedRectangle(cornerRadius: сторона * Self.долиСкругления, style: .continuous)
        return Image(systemName: вид.символ)
            .symbolRenderingMode(.monochrome)
            .font(.system(size: сторона * Self.долиЗнака * вид.поправка, weight: .semibold))
            .foregroundStyle(Color.white)
            .symbolEffect(.bounce, value: ДвижениеСайта.тихо ? 0 : касаний + прыжок)
            .frame(width: сторона, height: сторона)
            .background { подложка(форма) }
            .overlay { кромка(форма) }
            .onChange(of: нажат) { _, сейчас in
                if сейчас && !ДвижениеСайта.тихо { касаний += 1 }
            }
            .modifier(ГолосЗначкаРаздела(название: название))
    }

    private var тёмная: Bool { схема == .dark }

    /// Заливка с тенью (в светлой теме) и блик сверху.
    private func подложка(_ форма: RoundedRectangle) -> some View {
        ZStack {
            if наКраске {
                форма.fill(стекло)
            } else if тёмная {
                форма.fill(градиент)
            } else {
                форма.fill(градиент
                    .shadow(.drop(color: Self.тень.opacity(0.1), radius: 1, x: 0, y: 1))
                    .shadow(.drop(color: Color(uiColor: вид.краска).opacity(0.26), radius: сторона * 0.08, x: 0,
                                  y: сторона * 0.05)))
            }
            форма.fill(блик)
        }
        .accessibilityHidden(true)
    }

    /// Внутренняя кромка: белый 34 % сверху (в тёмной 24 %) гаснет к середине; толщина растёт со стороной.
    private func кромка(_ форма: RoundedRectangle) -> some View {
        форма
            .strokeBorder(LinearGradient(colors: [Color.white.opacity(тёмная ? 0.24 : 0.34), Color.white.opacity(0)],
                                         startPoint: .top, endPoint: .center),
                          lineWidth: max(0.5, сторона / 64))
            .allowsHitTesting(false)
            .accessibilityHidden(true)
    }

    /// Градиент сверху вниз: краска с 20 % белого → краска с 4 % чёрного; в тёмной — с 10 % белого → с 14 % чёрного.
    private var градиент: LinearGradient {
        let к = вид.краска
        let верх = Theme.смесь(к, UIColor.white, тёмная ? 0.9 : 0.8)
        let низ = Theme.смесь(к, UIColor.black, тёмная ? 0.86 : 0.96)
        return LinearGradient(colors: [Color(uiColor: верх), Color(uiColor: низ)], startPoint: .top, endPoint: .bottom)
    }

    /// Белое «стекло» на сплошной плитке: белый 30 % → 16 % (в тёмной 22 % → 10 %).
    private var стекло: LinearGradient {
        LinearGradient(colors: [Color.white.opacity(тёмная ? 0.22 : 0.3), Color.white.opacity(тёмная ? 0.1 : 0.16)],
                       startPoint: .top, endPoint: .bottom)
    }

    /// Блик сверху: белый 12 % (в тёмной 7 %) у верхнего края → ничего к середине.
    private var блик: LinearGradient {
        LinearGradient(stops: [Gradient.Stop(color: Color.white.opacity(тёмная ? 0.07 : 0.12), location: 0),
                               Gradient.Stop(color: Color.white.opacity(0), location: 0.55)],
                       startPoint: .top, endPoint: .bottom)
    }
}

/// Голос значка: с названием — картинка с этим названием; без — скрыт (название читает плитка или ячейка).
private struct ГолосЗначкаРаздела: ViewModifier {
    let название: String?

    init(название: String?) {
        self.название = название
    }

    func body(content: Content) -> some View {
        if let название, !название.isEmpty {
            content
                .accessibilityElement(children: .ignore)
                .accessibilityLabel(название)
                .accessibilityAddTraits(.isImage)
        } else {
            content
                .accessibilityHidden(true)
        }
    }
}

// MARK: - Названия корней

extension РазделГлавной {
    /// Корни, чьё название приложение пишет своими словами (DesignText «v_<ключ>»), а не словом со снимка главной сайта:
    /// «animals» — «Питомцы» (владелец 16.10.2026: «Животные» — переименовать помягче). Сайт пока пишет «Животные», и его
    /// слово для этих корней не берём. Ключ раздела прежний: запросы, поиск и сопоставление идут по ключу и словам сайта.
    static let своёНазвание: Set<String> = ["animals"]
}

extension ИсторииРаздела {
    /// Название набора историй на экране: у корня со своим названием (РазделГлавной.своёНазвание) — слова приложения,
    /// иначе присланное сайтом.
    var названиеНаЭкране: String {
        if РазделГлавной.своёНазвание.contains(раздел) { return DesignText.т("v_" + раздел) }
        return название
    }
}

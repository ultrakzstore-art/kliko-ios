import SwiftUI

/**
 ОБЪЯВЛЕНИЕ ВЫРАСТАЕТ ИЗ КАРТОЧКИ — СБОРКА 84 (владелец 17.10.2026: «когда товар с витрины открывается — анимация как в
 приложение заходит — смысл есть?»; на макет — «Собирай 84»). План — docs/LISTING_MODAL_V2.md, «Открытие с витрины».

 iOS 18+: системный зум стека. Карточка витрины помечена источником (ИсточникЗумаОбъявления), страница объявления в том
 же стеке открывается зумом из него (ЗумОбъявления): фото растёт из своей плитки (обе 4:3 — без перекоса), закрытие
 от края и «Назад» — системные, объявление уходит обратно в свою карточку. Смахивание вниз — своё (ЗакрытьСмахиваниемВниз,
 вКарточку; сборка 86 — системное с фото не срабатывало): страница идёт за пальцем, а отпустили — стек закрывает её
 тем же зумом в карточку. «Уменьшение движения» система учитывает сама.
 iOS 17, рубильник open_zoom (Config.зумИзКарточки) выключен или пространства нет — прежний сдвиг справа: модификаторы
 отдают вид как есть.

 Ключ источника — у каждого места свой (после ревью сборки 84): одно объявление бывает сразу в нескольких карточках —
 золотое и обычное место сетки, VIP и ряд, «Вы смотрели» над той же сеткой, — и с общим номером система брала бы
 любую из них, в том числе не ту, что нажали, или ушедшую за край экрана. Ключ — «место|…|номер объявления»: нажатие
 карточки запоминает его (НажатаяКарточкаЗума), страница берёт его снимком при первом показе. Открыто не нажатием
 карточки (меню долгого нажатия, ссылка, «С того же места», сужение окна iPad) — ключа нет, прежний сдвиг. Пролистали
 (˄ ˅, «Следующее») — закрытие уходит в карточку того объявления, с которого начали.
 */
struct ИсточникЗумаОбъявления: ViewModifier {
    /// Ключ источника — свой у каждого места карточки («место|…|номер объявления»), тот же получает страница
    /// (ЗумОбъявления) через НажатаяКарточкаЗума.
    let id: String
    /// Общее пространство стека: карточки и страницы одного NavigationStack. nil — зума нет.
    let пространство: Namespace.ID?
    /// Снимок рубильника у места открытия (на жизнь экрана): ветка не переключается и карточку не пересоздаёт.
    let включено: Bool

    @ViewBuilder
    func body(content: Content) -> some View {
        if включено, let пространство {
            if #available(iOS 18.0, *) {
                content.matchedTransitionSource(id: id, in: пространство)
            } else {
                content
            }
        } else {
            content
        }
    }
}

/// Страница объявления открывается зумом из карточки с тем же ключом (ИсточникЗумаОбъявления). Ставится на вид в
/// .navigationDestination того же стека, где лежат карточки.
struct ЗумОбъявления: ViewModifier {
    let пространство: Namespace.ID?
    /// Ключ карточки, из которой открыли, — снимок при первом показе: следующее нажатие (или его сброс у корня стека) не
    /// перенацеливает уже открытую страницу, она закрывается в свою карточку.
    @State private var источник: String
    /// Снимок при первом показе страницы. Место открытия пересоздаёт назначение стека на каждой своей перерисовке, и
    /// условие «открыто с корня» меняется, когда поверх объявления открыли чат или похожие, — а зум и само дерево
    /// страницы должны остаться прежними: смена ветки пересоздала бы открытое окно со всем его состоянием.
    @State private var зумом: Bool

    init(id: String, пространство: Namespace.ID?, включено: Bool) {
        self.пространство = пространство
        _источник = State(initialValue: id)
        _зумом = State(initialValue: включено)
    }

    @ViewBuilder
    func body(content: Content) -> some View {
        if зумом, let пространство {
            if #available(iOS 18.0, *) {
                content.navigationTransition(.zoom(sourceID: источник, in: пространство))
            } else {
                content
            }
        } else {
            content
        }
    }
}

/// Какую карточку нажали последней — ключ её источника зума. Коробка в @State места открытия (как ДействиеСтекаЛенты):
/// запись при нажатии ленту не перерисовывает, назначение стека читает ключ, когда строит страницу. Пусто — открыто не
/// нажатием карточки, зума нет.
@MainActor
final class НажатаяКарточкаЗума {
    var ключ = ""
}

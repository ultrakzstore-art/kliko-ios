/**
 Сборка 84 (окно v2, modal_summary; владелец 17.10.2026 — макет «Окно товара — упрощение», «Собирай 84»): под карточкой
 решения одна строка капсул по 44 pt — «На столе» / «В комнате» (AR, как в строке выше) и «Примерить» (способы
 блока примерки капсулой без градиента и блика — КапсулаПримерочной, TryOnButton.swift). Капсулы «3D» / «360°» здесь
 нет: в 3D ведёт значок на фото. Капсулы поровну по ширине; не влезают (крупный шрифт) — столбиком. Нечего показать —
 строки нет. Способы ИИ появляются после ответа сервера (ГотовностьПримерочной) — строка сама её наблюдает и спрашивает,
 корень страницы — нет (правило b644caf).
 */
struct СтрокаКапсулОкна: View {
    let товар: Listing
    /// Фото галереи на экране — его и примеряем.
    let номерФото: Int
    @ObservedObject private var готовность = ГотовностьПримерочной.shared

    init(товар: Listing, номерФото: Int) {
        self.товар = товар
        self.номерФото = номерФото
    }

    /// AR «у себя» без 3D.
    @MainActor
    static func своиКапсулы(_ т: Listing) -> [КапсулаСмотретьВещь] {
        СмотретьВещьОбъявления.капсулы(т).filter { $0 != .объём }
    }

    /// Может ли строка что-то показать — без сети (способы ИИ — если сервер ещё не отказал).
    @MainActor
    static func возможна(_ т: Listing) -> Bool {
        !своиКапсулы(т).isEmpty || КнопкаПримерочной.есть(т)
    }

    var body: some View {
        let свои: [КапсулаСмотретьВещь] = Self.своиКапсулы(товар)
        let способы: [СпособПримерки] = ПодборПримерки.способы(товар, подтверждённые: true)
        let нуженСервер: Bool = ПодборПримерки.способы(товар, подтверждённые: false).contains { $0.наСервере }
        return VStack(spacing: 0) {
            /* Полоса нулевой высоты: на ней живёт .task, пока капсул ещё нет (пустой вид задач не запускает). */
            Color.clear
                .frame(height: 0)
                .accessibilityHidden(true)
            if !свои.isEmpty || !способы.isEmpty {
                ряд(свои, способы)
                    .padding(.horizontal, 20)
                    .padding(.top, 14)
                    .accessibilityElement(children: .contain)
                    .accessibilityLabel(ХабПримеркиText.т("th_look_a11y"))
            }
        }
        .task(id: товар.id) {
            guard нуженСервер else { return }
            await готовность.проверить()
        }
    }

    /// В одну строку поровну; не влезают — столбиком.
    private func ряд(_ свои: [КапсулаСмотретьВещь], _ способы: [СпособПримерки]) -> some View {
        ViewThatFits(in: .horizontal) {
            HStack(spacing: 10) {
                капсулы(свои, способы)
            }
            VStack(spacing: 10) {
                капсулы(свои, способы)
            }
        }
    }

    @ViewBuilder
    private func капсулы(_ свои: [КапсулаСмотретьВещь], _ способы: [СпособПримерки]) -> some View {
        ForEach(свои) { вид in
            КнопкаКапсулыСмотретьВещь(вид: вид, товар: товар)
        }
        if !способы.isEmpty {
            КапсулаПримерочной(товар: товар, номерФото: номерФото, способы: способы)
        }
    }
}

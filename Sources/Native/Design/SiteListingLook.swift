import SwiftUI

/**
 «НА СТОЛЕ» И 3D ОДНОЙ СТРОКОЙ В ОКНЕ ОБЪЯВЛЕНИЯ (владелец 17.10.2026: «слишком громоздкие посмотреть на столе и 3D,
 нужно их соединить в одну строку и укомпактить получше»).

 Раньше под ценой стояли две карточки: «Смотреть в 3D» / «Обзор 360°» с подписью (КнопкаОбъёмаОбъявления,
 Listing3DEntry.swift) и большая зелёная «Посмотреть на столе» / «Поместится ли?» с подписью в блоке примерки
 (КнопкаПримерочной, TryOnButton.swift). Теперь на их месте — одна строка капсул одного вида: значок и короткое слово.
   · «На столе» (настольные вещи) или «В комнате» (мебель, крупная техника) — «Поместится ли?» в AR
     (ОкноГабаритов.открыть, FitBoxScreen.swift), как прежняя кнопка блока примерки;
   · «3D» (есть модель) или «360°» (только ракурсы) — окно просмотра (ОкноОбъёма.открыть, Listing3DEntry.swift), как
     прежняя карточка.
 Одна возможность — одна капсула во всю ширину; ни одной — строки нет. Пока строка включена, способа .габариты в блоке
 примерки нет (ПодборПримерки.доступен, TryOnHub.swift) — прочие способы (живая примерка, ИИ) остаются там. Значок
 «3D» / «360°» на фото галереи — прежний.

 Вид — как у строки «Подойдут ли?» шин и дисков (SiteListingTyreFit.swift): поверхность с рамкой-линией, значок цвета
 акцента, жирный текст; капсулы высотой с обычную строку (44), поровну по ширине. Крупный шрифт не влезает в строку —
 капсулы столбиком. Длинные заголовки и подписи прежних кнопок — у VoiceOver (название, значение, подсказка).
 Всё решается по самому объявлению и рубильникам, без сети и без своего состояния.
 */

extension Config {
    /// «На столе» / «В комнате» и «3D» / «360°» одной строкой капсул. false — как раньше: карточка 3D-обзора под ценой
    /// и большая кнопка «Поместится ли?» в блоке примерки.
    static let строкаСмотретьВещь = true
}

/// Капсула строки. Порядок случаев — порядок капсул: сначала AR у себя, потом 3D.
enum КапсулаСмотретьВещь: String, CaseIterable, Identifiable, Hashable {
    /// «На столе» или «В комнате»: «Поместится ли?» в AR.
    case уСебя
    /// «3D» или «360°»: окно просмотра.
    case объём

    var id: String { rawValue }
}

@MainActor
enum СмотретьВещьОбъявления {
    /// Строка вообще возможна: её рубильник.
    static var включено: Bool { Config.строкаСмотретьВещь }

    /// Капсулы этого объявления по порядку. Пусто — строки нет.
    static func капсулы(_ товар: Listing) -> [КапсулаСмотретьВещь] {
        guard включено else { return [] }
        let можноAR: Bool = ПодборПримерки.габаритыВозможны(товар)
        let можно3D: Bool = товар.естьОбъём
        return КапсулаСмотретьВещь.allCases.filter { вид in
            switch вид {
            case .уСебя: return можноAR
            case .объём: return можно3D
            }
        }
    }

    /// Ставить ли строку под ценой.
    static func стоит(_ товар: Listing) -> Bool {
        !капсулы(товар).isEmpty
    }

    /// Короткое слово на капсуле.
    static func слово(_ вид: КапсулаСмотретьВещь, товар: Listing) -> String {
        switch вид {
        case .уСебя:
            return ХабПримеркиText.т(ГабаритыВещи.наСтоле(товар.категория) ? "th_fit_desk_short" : "th_fit_short")
        case .объём:
            return ОбъёмText.т(есть3D(товар) ? "o3_badge_3d" : "o3_badge_360")
        }
    }

    /// Значок капсулы (SF Symbols, есть в iOS 17): AR — как у «В комнате» окна 3D, объём — как у значка на фото.
    static func значок(_ вид: КапсулаСмотретьВещь, товар: Listing) -> String {
        switch вид {
        case .уСебя: return "arkit"
        case .объём: return есть3D(товар) ? "cube.transparent" : "rotate.3d"
        }
    }

    /// Название для VoiceOver — прежний заголовок кнопки.
    static func название(_ вид: КапсулаСмотретьВещь, товар: Listing) -> String {
        switch вид {
        case .уСебя: return СпособПримерки.габариты.заголовокДля(товар)
        case .объём: return ОбъёмText.т(есть3D(товар) ? "o3_btn_3d" : "o3_btn_360")
        }
    }

    /// Значение для VoiceOver — прежняя подпись под заголовком.
    static func подпись(_ вид: КапсулаСмотретьВещь, товар: Listing) -> String {
        switch вид {
        case .уСебя:
            return СпособПримерки.габариты.подпись(товар)
        case .объём:
            guard есть3D(товар) else { return ОбъёмText.т("o3_btn_360_sub") }
            return ОбъёмText.т(ОкноОбъёма.комнатаДоступна ? "o3_btn_3d_sub_room" : "o3_btn_3d_sub")
        }
    }

    /// Подсказка VoiceOver: что произойдёт по нажатию.
    static func подсказка(_ вид: КапсулаСмотретьВещь, товар: Listing) -> String {
        switch вид {
        case .уСебя: return СпособПримерки.габариты.подсказкаДля(товар)
        case .объём: return ОбъёмText.т("o3_btn_hint")
        }
    }

    /// Открыть то же, что открывала прежняя кнопка.
    static func открыть(_ вид: КапсулаСмотретьВещь, товар: Listing) {
        ОткликСайта.выбор()
        switch вид {
        case .уСебя: ОкноГабаритов.открыть(товар: товар)
        case .объём: ОкноОбъёма.открыть(товар: товар)
        }
    }

    /// У объявления есть модель USDZ (иначе — только ракурсы 360°).
    private static func есть3D(_ товар: Listing) -> Bool {
        товар.модельОбъёма?.есть3D ?? false
    }
}

/// Строка капсул под ценой объявления. Отступы — как у строки «Подойдут ли?» и прежних карточек, на их месте.
struct СтрокаСмотретьВещь: View {
    let товар: Listing

    init(товар: Listing) {
        self.товар = товар
    }

    var body: some View {
        let список: [КапсулаСмотретьВещь] = СмотретьВещьОбъявления.капсулы(товар)
        return Group {
            if !список.isEmpty {
                ряд(список)
                    .padding(.horizontal, 20)
                    .padding(.top, 14)
                    .accessibilityElement(children: .contain)
                    .accessibilityLabel(ХабПримеркиText.т("th_look_a11y"))
            }
        }
    }

    /// В одну строку поровну; не влезают (крупный шрифт) — столбиком.
    private func ряд(_ список: [КапсулаСмотретьВещь]) -> some View {
        ViewThatFits(in: .horizontal) {
            HStack(spacing: 10) {
                ForEach(список) { вид in кнопка(вид) }
            }
            VStack(spacing: 10) {
                ForEach(список) { вид in кнопка(вид) }
            }
        }
    }

    private func кнопка(_ вид: КапсулаСмотретьВещь) -> some View {
        let форма = Capsule(style: .continuous)
        let надпись: String = СмотретьВещьОбъявления.слово(вид, товар: товар)
        let символ: String = СмотретьВещьОбъявления.значок(вид, товар: товар)
        return Button {
            СмотретьВещьОбъявления.открыть(вид, товар: товар)
        } label: {
            HStack(spacing: 7) {
                Image(systemName: символ)
                    .font(.body.weight(.semibold))
                    .foregroundStyle(Theme.акцент)
                    .accessibilityHidden(true)
                Text(надпись)
                    .font(.callout.weight(.bold))
                    .foregroundStyle(Theme.текст)
                    .lineLimit(1)
            }
            .padding(.horizontal, 16)
            .padding(.vertical, 10)
            .frame(maxWidth: .infinity, minHeight: 44)
            .background(Theme.поверхность, in: форма)
            .overlay { форма.strokeBorder(Theme.линия, lineWidth: 1) }
            .contentShape(форма)
        }
        .buttonStyle(НажатиеСайта())
        .accessibilityLabel(СмотретьВещьОбъявления.название(вид, товар: товар))
        .accessibilityValue(СмотретьВещьОбъявления.подпись(вид, товар: товар))
        .accessibilityHint(СмотретьВещьОбъявления.подсказка(вид, товар: товар))
    }
}

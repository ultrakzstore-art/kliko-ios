/// Карточка сделки листом поверх экрана — номер сделки.
struct СделкаПоверх: Identifiable, Equatable {
    let id: String
}

extension View {
    /// Карточка сделки листом поверх этого экрана: своя навигация (переписка из карточки ложится в неё) и «Закрыть».
    /// объявление — номер объявления, над чьей страницей лист: ссылка карточки на него просто закрывает лист.
    func карточкаСделкиПоверх(_ сделка: Binding<СделкаПоверх?>, объявление: String? = nil,
                              открыть: @escaping (URL) -> Void) -> some View {
        sheet(item: сделка) { с in
            ЛистКарточкиСделки(номер: с.id, подЛистом: объявление, открыть: открыть)
        }
    }
}

/// ЭкранСделки в своём стеке: у листа нет системного «Назад» — закрывает «Закрыть» (или смахивание листа). Переписка из
/// карточки и «Объявление» в ней ложатся в этот же стек — не в стек под листом, которого человек сейчас не видит.
private struct ЛистКарточкиСделки: View {
    let номер: String
    /// Объявление под листом (nil — лист над чатом, кабинетом или не знаем).
    let подЛистом: String?
    let открыть: (URL) -> Void
    @Environment(\.dismiss) private var закрыть
    @State private var путь = NavigationPath()

    init(номер: String, подЛистом: String?, открыть: @escaping (URL) -> Void) {
        self.номер = номер
        self.подЛистом = подЛистом
        self.открыть = открыть
    }

    var body: some View {
        NavigationStack(path: $путь) {
            ЭкранСделки(id: номер, открыть: { адрес in открытьЗдесь(адрес) })
                .чатМаршруты(открыть: открыть)
                .navigationDestination(for: Listing.self) { товар in
                    ListingDetailView(товар: товар, открыть: открыть)
                }
                .toolbar {
                    ToolbarItem(placement: .cancellationAction) {
                        Button(СделкиText.т("close")) { закрыть() }
                    }
                }
        }
        .environment(\.открытьОбъявлениеВСтеке, { товар in путь.append(товар) })
        .environment(\.объявлениеПодЧатом, nil)
        .environment(\.чатИзОкнаСделки, false)
        /* Ссылка или пуш об этой же сделке, пока лист на экране, не уводит во вкладку «Кабинет» под ним. */
        .onAppear { СделкиЛистом.показана(номер) }
        .onDisappear { СделкиЛистом.убрана(номер) }
    }

    /**
     Ссылка изнутри карточки («Посмотреть объявление», действия-страницы): объявление — в стек этого листа, а то, над чьей
     страницей лист, — просто закрыть лист; прочее — прежним путём. Раньше объявление уходило во вкладку «Лента» под
     листом: на экране ничего не менялось, а после «Закрыть» там ждала его копия (или смена вкладки снимала лист).
     */
    @MainActor
    private func открытьЗдесь(_ адрес: URL) {
        guard case .объявление(let номерОбъявления, let намерение)? = NativeRouter.распознать(адрес),
              NativeRouter.доступна(.объявление(id: номерОбъявления)) else {
            открыть(адрес)
            return
        }
        if номерОбъявления == подЛистом {
            закрыть()
            return
        }
        НамеренияОбъявления.shared.положить(намерение, для: номерОбъявления)
        путь.append(Listing(номер: номерОбъявления))
    }
}

/// Сделки, чья карточка сейчас открыта листом СделкаПоверх. NativeTabsView.принятьСсылку по ссылке или пушу о такой
/// сделке (cabinet.php?deal=, возврат банка ?topup=…&deal=) вкладку не переключает: карточка уже на экране и задание
/// банка заберёт сама, а «Кабинет» под листом после «Закрыть» встретил бы человека второй копией той же сделки.
@MainActor
enum СделкиЛистом {
    private static var открыты: [String: Int] = [:]

    static func показана(_ номер: String) {
        открыты[номер, default: 0] += 1
    }

    static func убрана(_ номер: String) {
        let осталось = (открыты[номер] ?? 0) - 1
        открыты[номер] = осталось > 0 ? осталось : nil
    }

    static func наЭкране(_ номер: String) -> Bool {
        (открыты[номер] ?? 0) > 0
    }
}

// MARK: - «Объявление» в чате

private struct КлючОбъявлениеПодЧатом: EnvironmentKey {
    static let defaultValue: String? = nil
}

extension EnvironmentValues {
    /// Номер объявления, с чьей страницы открыт этот чат (ПанельСвязиСайта, блок «Расположение»); nil — чат открыт не с
    /// объявления (вкладка «Сообщения», кабинет, заявки). Ставится на сам экран чата: экраны, положенные глубже, берут
    /// окружение у стека и его не получают.
    var объявлениеПодЧатом: String? {
        get { self[КлючОбъявлениеПодЧатом.self] }
        set { self[КлючОбъявлениеПодЧатом.self] = newValue }
    }

    /// Чат открыт из окна создания сделки этого объявления («Написать продавцу» в ОкноНовойСделки над страницей): его
    /// «Оформить за …» просто возвращает в это окно — оно и есть оформление; главную кнопку страницы под ним не жать
    /// (панель попыталась бы показать свой лист поверх чужого).
    var чатИзОкнаСделки: Bool {
        get { self[КлючЧатИзОкнаСделки.self] }
        set { self[КлючЧатИзОкнаСделки.self] = newValue }
    }
}

private struct КлючЧатИзОкнаСделки: EnvironmentKey {
    static let defaultValue = false
}

extension ВестиОкнаОбъявления {
    /// «Оформить за …» в чате этого объявления: панель жмёт кнопку сделки по правилам ссылки ?buy=1 (купитьПоСсылке), а
    /// не главную кнопку напрямую; гарант на паузе или кнопки сделки нет — ничего (тот же чат снова не открывается).
    static let купить = Notification.Name("kliko.listing.ma.buy")
}

/// Повтор нажатия за гостя, когда он вошёл (ПанельСвязиСайта): новый лист — только когда экран входа ушёл с экрана.
@MainActor
enum ПослеВхода {
    /// Показанный сейчас экран поверх вкладок (в миг вести «вошли» — сам экран входа или окно над ним); nil — поверх
    /// ничего нет или что-то едет.
    static func показанныйЭкран() -> UIViewController? {
        guard let верх = ПоверхВсего.верхний(), верх.presentingViewController != nil else { return nil }
        return верх
    }

    /**
     Ждать (до ~3 с), пока экран входа уйдёт: запомненный экран снят с окна, лист слоя вкладок закрыт и ничего не
     приезжает и не уезжает. Регистрация закрывает свой лист только через 0,4 с после вести, ещё ~0,3 с он уезжает —
     лист, поставленный раньше, UIKit не покажет, а SwiftUI оставит его состояние взведённым. false — не дождались.
     */
    static func дождатьсяУхода(_ вход: UIViewController?) async -> Bool {
        for _ in 0..<20 {
            let снят = вход?.viewIfLoaded?.window == nil
            if снят, ОкнаПриложения.shared.окно == nil, ПоверхВсего.верхний() != nil { return true }
            try? await Task.sleep(nanoseconds: 150_000_000)
        }
        return false
    }
}

/// Кнопка «Объявление» в переписке, у лида и в заявках.
@MainActor
enum ОбъявлениеИзЧата {
    /**
     Открыть объявление, не уводя человека в другую вкладку. true — сделано здесь: чат открыт с этого же объявления —
     чат закрыт (человек снова на нём, а не получает его копию поверх чата); у стека свой маршрут объявления — оно
     положено в этот стек. false — пусть зовущий ведёт прежним путём (NativeRouter, вкладка «Лента»).
     */
    static func здесь(_ номер: String, подЧатом: String?, вСтеке: ((Listing) -> Void)?,
                      закрытьЧат: () -> Void) -> Bool {
        guard !номер.isEmpty else { return false }
        if подЧатом == номер {
            закрытьЧат()
            return true
        }
        guard let вСтеке else { return false }
        /* Как «Открыть» меню долгого нажатия: прежнее намерение этой карточки (?buy=1, ?chat=1) не исполнять. */
        НамеренияОбъявления.shared.положить(.нет, для: номер)
        вСтеке(Listing(номер: номер))
        return true
    }
}

import SwiftUI
import WebKit

/**
 ЯЗЫК ПРИЛОЖЕНИЯ — ПЕРЕКЛЮЧАТЕЛЬ «RU» В ШАПКЕ (этап 49, владелец 26.09.2026: «всё одно и то же, просто код разный»).

 У сайта в шапке главной — пилюля «тема │ RU» (#theme-sw и #mk-lang-wrap); «RU» открывает список #mk-lang-dd: RU «Рус»,
 KZ «Қаз», EN «Eng», AR «عربي», у текущего галочка. Пункт — ссылка /kz/<язык>/: та же главная на другом языке. Язык живёт в
 адресе (APP_L = '/kz/ru'), отдельного запроса нет (save_pref_lang шлёт только настройка кабинета).

 Приложение берёт язык текстов у Locale.preferredLanguages (все *Text.swift), и адреса страниц сайта — у него же
 (Config.страницаСайта). Поэтому выбор пишется туда, откуда его читают: AppleLanguages в UserDefaults приложения — это и
 есть «язык приложения» iOS, и Locale.preferredLanguages сразу отдаёт новый. Дальше — как у сайта после перехода по
 ссылке: нативный слой собирается заново уже на новом языке (RootWebView, .id по коду), а страница сайта под ним уходит на
 /kz/<язык>/ — сессия и все следующие страницы сайта тоже на выбранном языке. Выбор хранится на телефоне и при выходе из
 аккаунта не стирается: это настройка устройства, как тема.
 */
@MainActor
final class ЯзыкПриложения: ObservableObject {
    static let shared = ЯзыкПриложения()

    struct Вариант: Identifiable, Hashable {
        /// Язык текстов приложения — код Locale: ru, kk, en, ar.
        let код: String
        /// Язык в адресе сайта: /kz/<сайт>/ — у казахского «kz».
        let сайт: String
        /// Метка на пилюле — .mk-lang-cur.
        let метка: String
        /// Имя в списке — .mk-lang-opt span.
        let имя: String

        var id: String { код }
    }

    /// Порядок и подписи — #mk-lang-dd главной.
    static let варианты: [Вариант] = [
        Вариант(код: "ru", сайт: "ru", метка: "RU", имя: "Рус"),
        Вариант(код: "kk", сайт: "kz", метка: "KZ", имя: "Қаз"),
        Вариант(код: "en", сайт: "en", метка: "EN", имя: "Eng"),
        Вариант(код: "ar", сайт: "ar", метка: "AR", имя: "عربي")
    ]

    /// Текущий язык текстов; сменился — нативный слой пересобирается (RootWebView).
    @Published private(set) var код: String
    /// Язык на запуске. Снимок главной с диска (FeedStore.разделыНаЗапуске: названия разделов со страницы сайта) — на нём.
    let наЗапуске: String

    private init() {
        let язык = Self.изНастроек()
        код = язык
        наЗапуске = язык
    }

    /// Язык сменили в этот запуск — слова со снимка главной ещё на прежнем, брать свои (DesignText).
    var сменён: Bool { код != наЗапуске }

    var текущий: Вариант {
        Self.варианты.first { $0.код == код } ?? Self.варианты[0]
    }

    /// Язык, которым сейчас говорят тексты приложения: первый предпочитаемый; не из четырёх — русский, как у сайта.
    static func изНастроек() -> String {
        let язык = String((Locale.preferredLanguages.first ?? "ru").prefix(2))
        return варианты.contains { $0.код == язык } ? язык : "ru"
    }

    /// Выбор в списке: язык приложения и страница сайта под ним — на /kz/<язык>/, как ссылка .mk-lang-opt.
    func выбрать(_ вариант: Вариант) {
        guard вариант.код != код else { return }
        UserDefaults.standard.set([вариант.код], forKey: "AppleLanguages")
        код = вариант.код
        if let адрес = Config.url("/kz/\(вариант.сайт)/") {
            WebBridge.shared.webView?.load(URLRequest(url: адрес))
        }
    }
}

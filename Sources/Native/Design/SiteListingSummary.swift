// MARK: - Строка карточки

/// Где строке, которая сама решает, видна ли она («подходит»), рисовать тонкую линию: сверху (над ней есть строка),
/// снизу (она первая, а под ней строки есть) или нигде.
enum ЛинияСтрокиСводки: Equatable {
    case нет, сверху, снизу
}

/// Тонкая линия между строками карточки: 1 pt цвета линии, отступ 48 pt от ведущего края (под текстом, не под значком).
struct ЛинияСводки: View {
    init() {}

    var body: some View {
        Theme.линия
            .frame(height: 1)
            .padding(.leading, КаркасСтрокиСводки<EmptyView>.отступТекста)
            .accessibilityHidden(true)
    }
}
/// Значок строки: символ SF в колонке 24 pt.
enum ЗначокСтрокиСводки {
    case символ(String, Color)
}

/// Нажатие строки карточки: подсветка фоном на всю строку, без сжатия (строка — часть карточки, а не кнопка).
struct НажатиеСтрокиСводки: ButtonStyle {
    func makeBody(configuration: Configuration) -> some View {
        configuration.label
            .background(configuration.isPressed ? Theme.линия.opacity(0.6) : Color.clear)
            .animation(ДвижениеСайта.нажатие, value: configuration.isPressed)
    }
}

/**
 Каркас строки: колонка значка 24 pt, текст, шеврон «›» (если нажимается), высота не меньше 44 pt, поля 12 pt.
 Нажимается — кнопка во всю строку с подсказкой VoiceOver; нет — один элемент VoiceOver из значка и текста.
 */
struct КаркасСтрокиСводки<Текст: View>: View {
    /// Поле 12 + колонка значка 24 + промежуток 12: отсюда начинается текст и тонкие линии.
    static var отступТекста: CGFloat { 48 }

    let значок: ЗначокСтрокиСводки
    let шеврон: Bool
    let подсказка: String?
    let нажать: (() -> Void)?
    let текст: Текст

    init(значок: ЗначокСтрокиСводки, шеврон: Bool, подсказка: String? = nil, нажать: (() -> Void)? = nil,
         @ViewBuilder текст: () -> Текст) {
        self.значок = значок
        self.шеврон = шеврон
        self.подсказка = подсказка
        self.нажать = нажать
        self.текст = текст()
    }

    var body: some View {
        if let нажать {
            Button(action: нажать) { содержимое }
                .buttonStyle(НажатиеСтрокиСводки())
                .accessibilityHint(подсказка ?? "")
        } else {
            содержимое
                .accessibilityElement(children: .combine)
        }
    }

    private var содержимое: some View {
        HStack(spacing: 12) {
            значокВид
                .frame(width: 24)
            /* Текст берёт всю ширину между значком и шевроном: варианты ViewThatFits меряются по ней. */
            текст
                .frame(maxWidth: .infinity, alignment: .leading)
            if шеврон {
                Image(systemName: "chevron.forward")
                    .font(.system(size: 12, weight: .semibold))
                    .foregroundStyle(Theme.текстВторой)
                    .accessibilityHidden(true)
            }
        }
        .padding(.horizontal, 12)
        .padding(.vertical, 8)
        .frame(maxWidth: .infinity, minHeight: 44, alignment: .leading)
        .contentShape(Rectangle())
    }

    @ViewBuilder
    private var значокВид: some View {
        switch значок {
        case .символ(let имя, let краска):
            Image(systemName: имя)
                .font(.system(size: 15, weight: .semibold))
                .foregroundStyle(краска)
                .accessibilityHidden(true)
        }
    }
}

/**
 Строка из частей через « · »: первая — жирная цветом текста, остальные — вторым цветом (краска — весь текст одним
 цветом: гарант — акцент, пауза — второй). Не влезает в строку — сначала уходят последние части (ViewThatFits по
 вариантам, без замера), последний вариант — первые три части в две строки; при крупном «Размере текста»
 (accessibility) — до четырёх строк: «Деньги у Kliko до получения товара» не режется многоточием. Выбор по окружению.
 */
struct СтрокаСводки: View {
    let значок: ЗначокСтрокиСводки
    let части: [String]
    let краска: Color?
    let шеврон: Bool
    let подсказка: String?
    let нажать: (() -> Void)?
    @ScaledMetric(relativeTo: .subheadline) private var кегль: CGFloat = 14
    @Environment(\.dynamicTypeSize) private var размерТекста

    init(значок: ЗначокСтрокиСводки, части: [String], краска: Color? = nil, шеврон: Bool = false,
         подсказка: String? = nil, нажать: (() -> Void)? = nil) {
        self.значок = значок
        self.части = части.filter { !$0.isEmpty }
        self.краска = краска
        self.шеврон = шеврон
        self.подсказка = подсказка
        self.нажать = нажать
    }

    var body: some View {
        КаркасСтрокиСводки(значок: значок, шеврон: шеврон, подсказка: подсказка, нажать: нажать) {
            надпись
        }
    }

    private var надпись: some View {
        let все: [String] = части
        let безОдной: [String] = все.count > 2 ? Array(все.dropLast()) : все
        let безДвух: [String] = все.count > 3 ? Array(все.dropLast(2)) : безОдной
        let начало: [String] = Array(все.prefix(3))
        let строкПоследнего: Int = размерТекста.isAccessibilitySize ? 4 : 2
        return ViewThatFits(in: .horizontal) {
            строка(все, строк: 1)
            строка(безОдной, строк: 1)
            строка(безДвух, строк: 1)
            строка(начало, строк: строкПоследнего)
        }
    }

    private func строка(_ список: [String], строк: Int) -> some View {
        Text(Self.текст(список, краска: краска, кегль: кегль))
            .lineLimit(строк)
            .multilineTextAlignment(.leading)
            .fixedSize(horizontal: false, vertical: true)
    }

    /// Части одной строкой: первая — semibold, остальные — обычные, через « · ».
    static func текст(_ список: [String], краска: Color?, кегль: CGFloat) -> AttributedString {
        var итог = AttributedString()
        let главная: Color = краска ?? Theme.текст
        let вторая: Color = краска ?? Theme.текстВторой
        for (номер, часть) in список.enumerated() {
            if номер > 0 {
                var точка = AttributedString(" · ")
                точка.font = Font.system(size: кегль)
                точка.foregroundColor = вторая
                итог.append(точка)
            }
            var кусок = AttributedString(часть)
            кусок.font = Font.system(size: кегль, weight: номер == 0 ? .semibold : .regular)
            кусок.foregroundColor = номер == 0 ? главная : вторая
            итог.append(кусок)
        }
        return итог
    }
}

// MARK: - Карточка

/**
 Карточка решения. Строки по порядку: суть, подходит, аренда, гарант. Линии между строками рисуют сами
 строки: у постоянных (суть, аренда, гарант) — сверху, если выше уже есть постоянная строка; у «подходит»,
 которая появляется по «Моему», — сверху после сути или снизу, если она первая и ниже есть строки. Постоянных строк
 нет — карточки нет (страница ставит прежнюю плашку «Подходит моему»). Аренда и гарант вместе не стоят: у «сдаётся»
 главная кнопка — «Арендовать», гаранта в карточке нет.
 */
struct СводкаРешения: View {
    let товар: Listing
    /// Строка гаранта стоит (СтрокаГарантаСводки.стоит) — посчитано страницей: по тому же признаку «Продавец утверждает»
    /// под описанием не повторяет «Безопасную сделку».
    let строкаГаранта: Bool

    init(товар: Listing, строкаГаранта: Bool) {
        self.товар = товар
        self.строкаГаранта = строкаГаранта
    }

    /// Какая строка «подходит» может стоять у объявления — так же, как прежде под ценой (SiteListing.swift).
    enum Подходит {
        case нет, моё, шины
    }

    @MainActor
    static func подходит(_ т: Listing) -> Подходит {
        guard Config.моё else { return .нет }
        return ПодойдутЛиОбъявления.стоит(т) ? .шины : .моё
    }

    /// Есть ли у карточки постоянные строки. Нет — карточки нет.
    @MainActor
    static func есть(_ т: Listing, строкаГаранта: Bool) -> Bool {
        if !т.сутьОбъявления.isEmpty || строкаГаранта { return true }
        return СтрокаАрендыСводки.стоит(т)
    }

    var body: some View {
        let суть: [String] = товар.сутьОбъявления
        let естьСуть = !суть.isEmpty
        let аренда: Bool = СтрокаАрендыСводки.стоит(товар)
        let нижеЕсть = аренда || строкаГаранта
        let линияПодходит: ЛинияСтрокиСводки = естьСуть ? .сверху : (нижеЕсть ? .снизу : .нет)
        let форма = RoundedRectangle(cornerRadius: Theme.Радиус.md, style: .continuous)
        return VStack(spacing: 0) {
            if естьСуть {
                строкаСути(суть)
            }
            строкаПодходит(линияПодходит)
            if аренда {
                СтрокаАрендыСводки(товар: товар, линияСверху: естьСуть)
            }
            if строкаГаранта {
                СтрокаГарантаСводки(товар: товар, линияСверху: естьСуть || аренда)
            }
        }
        .background(Theme.поверхность2, in: форма)
        .clipShape(форма)
        .overlay { форма.strokeBorder(Theme.линия, lineWidth: 1) }
        .accessibilityElement(children: .contain)
        .accessibilityLabel(ListingSummaryText.т("sum_a11y"))
    }

    /// «Б/У · Apple M2 · 8 ГБ ОЗУ» (значок tag) или у услуг «Открыто до 21:00 · 09:00–21:00» (часы: открыто — зелёный
    /// значок, иначе второй цвет). Не нажимается.
    private func строкаСути(_ суть: [String]) -> some View {
        let часы: Bool = товар.услуга && товар.текстЧасов != nil
        let открыто: Bool = товар.открытоПоЧасам ?? false
        let краска: Color = часы && открыто ? Theme.зелёный2 : Theme.текстВторой
        let символ: String = часы ? "clock" : "tag"
        return СтрокаСводки(значок: .символ(символ, краска), части: суть)
    }

    @ViewBuilder
    private func строкаПодходит(_ линия: ЛинияСтрокиСводки) -> some View {
        switch Self.подходит(товар) {
        case .шины:
            СтрокаПодойдутЛи(товар: товар, вСводке: линия)
        case .моё:
            ПлашкаПодходитМоему(товар: товар, вСводке: линия)
        case .нет:
            EmptyView()
        }
    }
}

// MARK: - Аренда

/**
 «Условия и заявка владельцу ›» у объявлений «сдаётся» (план окна v2, «Панель» → «Аренда»; владелец 17.10.2026 —
 «Собирай 84»): в окне v2 у блока аренды своей кнопки «Арендовать» нет (она одна, в панели), и эта строка — короткий
 путь к условиям, залогу и расчёту. Нажатие — та же весть, что у mkRentJump (БлокАрендыСайта.кАренде с номером
 объявления): страница доезжает до блока аренды. Значок нейтральный — зелёная строка тела одна, гарант.
 Строки нет: не «сдаётся», цифровое, вещь занята (ГлавноеДействиеОкна.занятость — главная тогда «Связаться»), заявка
 через площадку закрыта (арендаЗаявкой = false — у блока «Написать владельцу», не заявка) и своё объявление. Номер
 вошедшего строка наблюдает сама (лист, правило b644caf): пришёл позже и совпал — строка уходит вместе с линией.
 */
struct СтрокаАрендыСводки: View {
    let товар: Listing
    let линияСверху: Bool
    @ObservedObject private var сессия = СессияПриложения.shared

    init(товар: Listing, линияСверху: Bool) {
        self.товар = товар
        self.линияСверху = линияСверху
    }

    /// Стоит ли строка. я — номер вошедшего; nil — прочитать СессияПриложения.id сейчас, синхронно.
    @MainActor
    static func стоит(_ т: Listing, я: String? = nil) -> Bool {
        guard т.forRent, !т.цифровое, т.арендаЗаявкой != false else { return false }
        guard ГлавноеДействиеОкна.занятость(т) == nil else { return false }
        let кто: String = я ?? СессияПриложения.shared.id
        return кто.isEmpty || кто != т.продавецID
    }

    var body: some View {
        let видна: Bool = Self.стоит(товар, я: сессия.id)
        return Group {
            if видна {
                VStack(spacing: 0) {
                    if линияСверху {
                        ЛинияСводки()
                    }
                    СтрокаСводки(значок: .символ("calendar", Theme.текстВторой),
                                 части: [ListingSummaryText.т("sum_rent")], шеврон: true,
                                 подсказка: ListingSummaryText.т("sum_rent_hint")) {
                        кУсловиям()
                    }
                }
            }
        }
    }

    private func кУсловиям() {
        ОткликСайта.выбор()
        NotificationCenter.default.post(name: БлокАрендыСайта.кАренде, object: товар.id)
    }
}

// MARK: - Безопасно ли платить

/**
 Строка гаранта — только при тех же условиях, что подпись главной кнопки панели сегодня (ГлавноеДействиеОкна.для и
 его подпись, ListingActions.swift; App Review 2.3.1 — не обещать того, чего нет):
   · «Купить безопасно» и гарант работает ПО СВЕРКЕ (ПаузаГаранта.работаетПоСверке) — зелёный щит и «Деньги у Kliko до
     получения товара ›» цветом акцента; сверки ещё не было — «Безопасная сделка Kliko ›», после сверки текст
     меняется проявлением на месте;
   · «Внести задаток» (авто, жильё) — «Бронь через Безопасную сделку ›»; «Заказать безопасно» — «Оплата исполнителю
     после приёмки ›»;
   · гарант на паузе у объявления, где он был бы без паузы (ГарантОбъявления.наПаузеУОбъявления и гарантБылБы: цена
     есть, не вакансия и не услуга вне services), — серая «Безопасная сделка сейчас на паузе» без шеврона и не
     нажимается.
 Строки нет: цифровое объявление (Apple 3.1.1), своё (номер вошедшего — СессияПриложения.id), вещь занята
 (ГлавноеДействиеОкна.занятость: в резерве, продана по статусу выдачи или снята — панель о паузе на занятой вещи тоже
 молчит; владелец 17.10.2026: «В резерве / продано: строки гаранта в карточке нет»), режим сделок с подписью eGov,
 аренда и «Связаться» без гаранта.
 Нажатие — весть klikoОткрытьГарантОкна с номером объявления: окно «Безопасная сделка» (ЛистГарантСделки) открывает
 панель связи — у неё вход, проверка и сверка. Строка сама наблюдает ПаузаГаранта, РежимСделокСайта и
 СессияПриложения — корень страницы их не наблюдает (правило b644caf): на холодном старте номер вошедшего приходит
 позже, и на своём объявлении строка уходит вместе со своей линией, не оставляя обещания с мёртвым шевроном.
 */
struct СтрокаГарантаСводки: View {
    let товар: Listing
    let линияСверху: Bool
    @ObservedObject private var пауза = ПаузаГаранта.shared
    @ObservedObject private var режим = РежимСделокСайта.shared
    @ObservedObject private var сессия = СессияПриложения.shared
    /// Продавец заблокирован вошедшим — панель пишет «Связь недоступна», и гаранта у неё нет (гарантЕсть,
    /// SiteContactBar.swift): строка с шевроном обещала бы то, что не откроется.
    @ObservedObject private var продавцы = ДействияСПродавцом.shared
    /// Сверка гаранта была и паузы нет — снимок для показа; меняется после сверки и при смене паузы (не из тела).
    @State private var поСверке = ПаузаГаранта.работаетПоСверке

    init(товар: Listing, линияСверху: Bool) {
        self.товар = товар
        self.линияСверху = линияСверху
    }

    enum Вид: Equatable {
        /// «Деньги у Kliko до получения товара» — гарант работает по сверке.
        case деньги
        /// «Безопасная сделка Kliko» — сверки ещё не было.
        case сделка
        case бронь
        case услуга
        case пауза
    }

    /// Стоит ли строка у объявления — по последнему известному режиму сделок и паузе (без наблюдения).
    @MainActor
    static func стоит(_ т: Listing) -> Bool {
        вид(т, eds: РежимСделокСайта.edsСейчас, поСверке: ПаузаГаранта.работаетПоСверке) != nil
    }

    /// я — номер вошедшего (наблюдаемый строкой); nil — прочитать СессияПриложения.id сейчас, синхронно.
    @MainActor
    static func вид(_ т: Listing, eds: Bool, поСверке: Bool, я: String? = nil) -> Вид? {
        let кто: String = я ?? СессияПриложения.shared.id
        let своё: Bool = !кто.isEmpty && кто == т.продавецID
        guard !т.цифровое, ГлавноеДействиеОкна.занятость(т) == nil, !своё else { return nil }
        /* Продавец заблокирован (то же условие, что у панели — Config.жалобы и status сайта): связи и гаранта нет. */
        guard !продавецЗаблокирован(т) else { return nil }
        let главное: ГлавноеДействиеОкна = ГлавноеДействиеОкна.для(т, eds: eds)
        switch главное {
        case .купить:
            return поСверке ? .деньги : .сделка
        case .задаток:
            return .бронь
        case .заказать:
            return .услуга
        case .связаться:
            /* О паузе — только там, где без неё был бы гарант: у вакансии, услуги вне services и объявления без цены
               его нет и так, «на паузе» было бы обещанием, которого нет. */
            let наПаузе: Bool = ГарантОбъявления.наПаузеУОбъявления(т)
            return наПаузе && гарантБылБы(т) ? .пауза : nil
        default:
            /* Аренда, сделка с подписью eGov и новые состояния панели — гаранта в карточке нет. */
            return nil
        }
    }

    /// Продавец заблокирован вошедшим — как ПанельСвязиСайта.продавецЗаблокирован (без жалоб — не заблокирован).
    @MainActor
    private static func продавецЗаблокирован(_ т: Listing) -> Bool {
        guard Config.жалобы, let продавец = т.продавецID, !продавец.isEmpty else { return false }
        return ДействияСПродавцом.shared.заблокирован(продавец)
    }

    /// Без паузы главная кнопка была бы гарантом (те же условия, что ГлавноеДействиеОкна.для после проверки гаранта):
    /// цена есть, не аренда, не аренда жилья без «Сдаю», не услуга вне раздела services.
    private static func гарантБылБы(_ т: Listing) -> Bool {
        guard (т.price ?? 0) > 0, !т.forRent else { return false }
        if т.корень == "realty" && т.жильё["deal"] == "rent" { return false }
        return !т.услуга || т.корень == "services"
    }

    var body: some View {
        let вид: Вид? = Self.вид(товар, eds: режим.eds, поСверке: поСверке, я: сессия.id)
        return Group {
            if let вид {
                VStack(spacing: 0) {
                    if линияСверху {
                        ЛинияСводки()
                    }
                    строка(вид)
                }
            }
        }
        .task {
            await сверитьПаузу()
        }
        .onChange(of: пауза.наПаузе) { _, _ in
            /* Пауза сменилась при открытом окне (снялась — «Безопасная сделка Kliko» становится «Деньги у Kliko…»). */
            let стало = ПаузаГаранта.работаетПоСверке
            if стало != поСверке {
                withAnimation(ДвижениеСайта.смена) { поСверке = стало }
            }
        }
    }

    /// Сверка паузы гаранта не чаще раза в 10 минут (обычно её уже сделала витрина); пришла — текст меняется проявлением
    /// на месте, высота строки та же. Сверку уже ведёт лента (ПаузаГаранта.сверить вернулся сразу) или первая сверка
    /// без паузы ничего не опубликовала — ещё одна попытка через 2 с, одна; ограничение 10 минут внутри сверить().
    private func сверитьПаузу() async {
        await пауза.сверить()
        var стало: Bool = ПаузаГаранта.работаетПоСверке
        if !стало {
            try? await Task.sleep(for: .seconds(2))
            guard !Task.isCancelled else { return }
            await пауза.сверить()
            стало = ПаузаГаранта.работаетПоСверке
        }
        if стало != поСверке {
            withAnimation(ДвижениеСайта.смена) { поСверке = стало }
        }
    }

    private func строка(_ вид: Вид) -> some View {
        let наПаузе = вид == .пауза
        let краска: Color = наПаузе ? Theme.текстВторой : Theme.акцент
        let символ: String = наПаузе ? "shield.slash" : "checkmark.shield.fill"
        var нажать: (() -> Void)? = nil
        if !наПаузе {
            нажать = { открытьГарант() }
        }
        let подсказка: String? = наПаузе ? nil : ListingSummaryText.т("esc_hint")
        return СтрокаСводки(значок: .символ(символ, краска), части: [Self.текст(вид)], краска: краска,
                            шеврон: !наПаузе, подсказка: подсказка, нажать: нажать)
    }

    static func текст(_ вид: Вид) -> String {
        switch вид {
        case .деньги: return ListingSummaryText.т("esc_money")
        case .сделка: return ListingSummaryText.т("esc_safe")
        case .бронь: return ListingSummaryText.т("esc_deposit")
        case .услуга: return ListingSummaryText.т("esc_service")
        case .пауза: return ListingSummaryText.т("esc_paused")
        }
    }

    private func открытьГарант() {
        ОткликСайта.выбор()
        NotificationCenter.default.post(name: .klikoОткрытьГарантОкна, object: товар.id)
    }

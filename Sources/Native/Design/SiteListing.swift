    private var кнопки: some View {
        HStack(spacing: 0) {
            if Config.избранное {
                КнопкаИзбранного(товар: товар, место: .фото)
            }
            кнопкаПоделиться
            Spacer(minLength: 8)
            /* «Ещё»: заблокировать продавца, пожаловаться (новая раскладка сайта, ListingActions.swift). */
            if КнопкаЕщёОкна.есть(товар) {
                КнопкаЕщёОкна(товар: товар)
            }
            /* Окно v2 (владелец 17.10.2026 — над фото 4 кнопки): на iPhone стрелок нет, следующее — блоком внизу и
               подтягиванием; на iPad (обычная ширина) — как раньше. Голосовые «Следующее» / «Предыдущее» — у
               ListingDetailView, их это не касается. */
            if let соседи, соседи.стрелки, !окноРешения || классШирины == .regular {
                СтрелкиЛистанияОбъявлений(вверх: соседи.вверх, вниз: соседи.вниз)
            }
            if вСтеке {
                КнопкаНадФото(значок: "xmark", подпись: ListingPageText.т("close")) { закрыть() }
            }
        }
    }

    @ViewBuilder
    private var кнопкаПоделиться: some View {
        /* Цифровой товар (владелец 16.10.2026: «Делиться можно, только актуальный товар»): снятое, проданное или с
           истёкшим сроком кода — без «Поделиться» совсем, не серой (Listing.можноПоделиться, ListingDigital.swift). У
           обычного объявления условие всегда истинно — всё как раньше. */
        if !товар.можноПоделиться {
            EmptyView()
        } else if let картинкой = поделитьсяКартинкой {
            Button(action: картинкой) { значокПоделиться }
                .buttonStyle(НажатиеСПружинкой(сжатие: 0.9))
                .accessibilityLabel(FeedText.т("share"))
                .accessibilityHint(ShareCardText.т("hint"))
        } else if товар.адрес != nil {
            Button { ЛистПоделитьсяСайта.показать(товар) } label: { значокПоделиться }
                .buttonStyle(НажатиеСПружинкой(сжатие: 0.9))
                .accessibilityLabel(FeedText.т("share"))
        }
    }

    /// Три узла со связями — значок .mk-mbtn сайта, а не системный «квадрат со стрелкой».
    private var значокПоделиться: some View {
        ЗнакПоделитьсяСайта()
            /* stroke-width 2 в поле 24, ужатом до 16 pt, — 4/3 pt. */
            .stroke(Color.white, style: StrokeStyle(lineWidth: 4 / 3, lineCap: .round, lineJoin: .round))
            .frame(width: МеркиКнопокНадФото.значок, height: МеркиКнопокНадФото.значок)
            .фонКнопкиНадФото()
    }

    // MARK: - Сведения со страницы сайта

    private func загрузитьНазвания() async {
        guard let раздел = товар.категория else { return }
        var нужные = [раздел]
        if let родитель = РазделыСайта.родитель(раздел) { нужные.append(родитель) }
        let ответ = await SiteSession.названияРазделов(нужные)
        /* Страница не назвала раздел — имя из справочника сайта на языке приложения, а не «Категория». */
        let итог = await ИменаРазделовСайта.запасные(нужные).merging(ответ) { _, соСтраницы in соСтраницы }
        if !итог.isEmpty { названия = итог }
    }

    private func узнатьМагазин() async {
        guard let продавец = товар.продавецID else { return }
        магазин = await SiteSession.магазины().contains(продавец)
    }

    /// Сказать панели и часам, что страница на экране и лежит ли фото под часами.
    private func отметиться() {
        /* Под часами всегда поверхность — часы по теме. */
        let запись = КарточкаНаЭкране(стек: стек, фотоПодЧасами: false)
        if вид.карточки[метка] != запись { вид.карточки[метка] = запись }
    }
}

// MARK: - Верх: название, цена, режим, «Продавец утверждает», крошки

private struct ВерхСтраницы: View {
    let товар: Listing
    let магазин: Bool
    let названия: [String: String]
    /// Ширина экрана — размер цены (7vw сайта).
    let ширина: CGFloat
    @Binding var листДоверия: Bool
    /// «Разбор объявления» (ListingBrief.swift): метка «Ниже рынка» и кнопка под ценой, когда дверь ответила ok.
    @ObservedObject var разбор: МодельРазбораОбъявления
    /// Сборка 84 — окно v2 (снимок страницы): цена с капсулой «Разбор» и карточка решения вместо прежних блоков.
    let окноРешения: Bool
    /// Крупный шрифт (accessibility): капсула «Разбор» — под ценой, а не справа от неё. Выбор по окружению, без замера.
    @Environment(\.dynamicTypeSize) var размерТекста

    var body: some View {
        if окноРешения {
            верхОкнаРешения
        } else {
            прежнийВерх
        }
    }

    // MARK: Окно v2 (сборка 84)

    /// Название и зелёная черта, цена с капсулой «Разбор» справа, карточка решения. Часы и наличие — в её первой
    /// строке, «Продавец утверждает» и крошки — после описания (НизСтраницы).
    private var верхОкнаРешения: some View {
        let строкаГаранта: Bool = СтрокаГарантаСводки.стоит(товар)
        let карточка: Bool = СводкаРешения.есть(товар, строкаГаранта: строкаГаранта)
        let ряд: Bool = товар.ценаВидна || капсулаСтоит
        return VStack(alignment: .leading, spacing: 14) {
            ЗаголовокСайта(текст: товар.title, метка: меткаПоколения)
            if ряд {
                строкаЦены
            }
            if карточка {
                СводкаРешения(товар: товар, магазин: магазин, строкаГаранта: строкаГаранта)
            }
        }
    }

    /// Место капсулы «Разбор»: держится, пока дверь рынка не ответила, и с ответом ok; выключено или сбой — нет.
    /// Цифровой товар — разбора нет (его и не спрашивают).
    private var капсулаСтоит: Bool {
        !товар.цифровое && разбор.состояние != .нет
    }

    /// «413 000 ₸ … ✦ Разбор ›»: цена по ведущему краю, капсула — по замыкающему; крупный шрифт — капсула под ценой.
    @ViewBuilder
    private var строкаЦены: some View {
        if размерТекста.isAccessibilitySize {
            VStack(alignment: .leading, spacing: 8) {
                if товар.ценаВидна {
                    ЦенаСайта(товар: товар, ширина: ширина)
                }
                if капсулаСтоит {
                    КапсулаРазбора(товар: товар, модель: разбор)
                }
            }
        } else {
            /* Цена первой берёт свою ширину (layoutPriority), капсула — остаток, прижатая к замыкающему краю: её
               «Ниже рынка на 12%» само ужимается до «Ниже рынка». Без Spacer и без замера. */
            HStack(alignment: .center, spacing: 10) {
                if товар.ценаВидна {
                    ЦенаСайта(товар: товар, ширина: ширина)
                        .layoutPriority(1)
                }
                if капсулаСтоит {
                    КапсулаРазбора(товар: товар, модель: разбор)
                        .frame(maxWidth: .infinity, alignment: товар.ценаВидна ? .trailing : .leading)
                }
            }
        }
    }

    // MARK: Как до сборки 84

    private var прежнийВерх: some View {
        VStack(alignment: .leading, spacing: 14) {
            ЗаголовокСайта(текст: товар.title, метка: меткаПоколения)
            if товар.ценаВидна {
                ЦенаСайта(товар: товар, ширина: ширина)
            }
            if разбор.доступен && !товар.цифровое {
                ПереносСтрок(промежуток: 8, междуСтрок: 8) {
                    if ЧипРынкаОбъявления.есть(разбор.чип) {
                        ЧипРынкаОбъявления(чип: разбор.чип, разница: разбор.рынок?.разница)
                    }
                    КнопкаРазбораОбъявления(товар: товар, модель: разбор)
                }
                .transition(.opacity)
            }
            /* mkStockLine: наличие у новых товаров; вместе с часами на телефоне сайт прячет часы (.mk-duo). */
            if let штук = наличие {
                БлокНаличияСайта(штук: штук)
            } else if let часы = товар.текстЧасов {
                БлокЧасов(часы: часы, подпись: товар.услуга ? ListingPageText.т("hours_work") : nil,
                          состояние: состояниеЧасов)
            }
            let пункты = товар.пунктыДоверия
            if !пункты.isEmpty {
                БлокДоверия(пункты: пункты, окноРешения: окноРешения) { листДоверия = true }
            }
            if let раздел = товар.категория {
                КрошкиСайта(раздел: раздел, названия: названия, окноРешения: окноРешения) { выбранный in
                    /* Раздел — лентой на слое вкладок; слоя нет — ничего, страница сайта не открывается. */
                    WebBridge.shared.открытьЭкран(.найти(ИскомоеЛенты(текст: "", раздел: выбранный)), запасной: nil)
                }
            }
        }
    }

    /// gen, которого нет в названии.
    private var меткаПоколения: String? {
        guard let поколение = товар.поляВида.поколение,
              !товар.title.lowercased().contains(поколение.lowercased()) else { return nil }
        return поколение
    }

    /// Сколько штук в наличии — только у новых товаров, не у услуг, работы, жилья и аренды.
    private var наличие: Int? {
        guard let штук = товар.поляВида.наличие, товар.состояние == "new", !товар.forRent,
              !["services", "jobs", "realty"].contains(товар.корень) else { return nil }
        return штук
    }

    /// mkHoursState: круглосуточно или открыто — зелёная; закрыто у магазина услуг — красная; иначе — оранжевая.
    private var состояниеЧасов: БлокЧасов.Состояние {
        if товар.часыРежим == "247" || товар.открытоСейчас() { return .открыто }
        return товар.услуга && магазин ? .закрыто : .нетНаМесте
    }
}


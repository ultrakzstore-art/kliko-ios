struct СтраницаОбъявленияСайта: View {
    let товар: Listing
    let догружаем: Bool
    let неДогрузилась: Bool
    /// Этап 13: на экране копия с телефона — когда она легла.
    let сохранённаяКопия: Date?
    let похожие: Похожие.Состояние
    @Binding var страница: Int
    let открытьФото: (Int) -> Void
    let повторить: () -> Void
    /// «Поделиться» картинкой (этап 19); nil — ссылкой через ShareLink, как при выключенном рубильнике.
    let поделитьсяКартинкой: (() -> Void)?
    /// Открыть страницу сайта — запасной путь «Согласовать с продавцом» из «Расположения»; nil — кнопки нет.
    let открыть: ((URL) -> Void)?
    /// Листание (ListingFlip.swift): стрелки над фото и «Следующее объявление» внизу; nil — ни того, ни другого.
    let соседи: СоседиСтраницыОбъявления?

    @Environment(\.dismiss) private var закрыть
    /// Окно v2: стрелки ˄ ˅ над фото — только при обычной ширине (iPad); на iPhone следующее — блоком внизу и
    /// подтягиванием.
    @Environment(\.horizontalSizeClass) private var классШирины
    /// Страница положена в стек (есть куда вернуться). Корень правой колонки iPad (этап 14) — «×» не нужен.
    @Environment(\.isPresented) private var вСтеке
    /// В стеке какой вкладки панели сайта лежит страница — по нему панель прячется (этап 29), а часы светлеют.
    @Environment(\.стекСайта) private var стек
    /// Без подписки: страница в ВидСайта только пишет — смена чужих отметок (ленты, вкладок) её не перерисовывает.
    private var вид: ВидСайта { ВидСайта.shared }
    /// Своя метка у каждой страницы: две страницы одного стека (похожее поверх) не путаются.
    @State private var метка = UUID()
    @State private var названия: [String: String] = [:]
    /// Продавец — магазин (MK_SHOPS страницы сайта): вне часов работы плашка у услуг красная, «закрыто».
    @State private var магазин = false
    @State private var листДоверия = false
    @State private var скрытыеСоветы: Set<String> = СоветыОбъявления.скрытые()
    /// Фото ушло из-под часов — под ними поверхность, и часы снова по теме.
    @State private var прокручено = false
    /// «Разбор объявления»: цена по рынку и метка chip (api/brief.php), доводы ИИ по нажатию. @State, а не @StateObject:
    /// страница на разбор не подписана — его наблюдает ВерхСтраницы, и ответ двери перерисовывает только верх.
    @State private var разбор = МодельРазбораОбъявления()
    /// Сборка 84, modal_summary (Config.окноРешения) — снимок при создании страницы: ответ настроек не перестраивает
    /// открытое окно.
    private let окноРешения: Bool

    /// Явный init: страницу создаёт КарточкаОбъявленияЯдро из другого файла.
    init(товар: Listing, догружаем: Bool, неДогрузилась: Bool, сохранённаяКопия: Date?, похожие: Похожие.Состояние,
         страница: Binding<Int>, открытьФото: @escaping (Int) -> Void, повторить: @escaping () -> Void,
         поделитьсяКартинкой: (() -> Void)?, открыть: ((URL) -> Void)? = nil, соседи: СоседиСтраницыОбъявления? = nil) {
        self.товар = товар
        self.догружаем = догружаем
        self.неДогрузилась = неДогрузилась
        self.сохранённаяКопия = сохранённаяКопия
        self.похожие = похожие
        _страница = страница
        self.открытьФото = открытьФото
        self.повторить = повторить
        self.поделитьсяКартинкой = поделитьсяКартинкой
        self.открыть = открыть
        self.соседи = соседи
        self.окноРешения = Config.окноРешения
    }

    var body: some View {
        GeometryReader { рамка in
            let верх = рамка.safeAreaInsets.top
            ZStack(alignment: .top) {
                ScrollViewReader { прокрутка in
                    ScrollView {
                        /* Низ видимой части в координатах прокрутки — низ этой рамки: над панелью связи. */
                        содержимое(ширина: рамка.size.width, верх: верх, низ: верх + рамка.size.height)
                    }
                    .coordinateSpace(NamedCoordinateSpace.named(ПрокруткаСтраницыОбъявления.имя))
                    /* «Арендовать безопасно» панели связи — к блоку аренды, как mkRentJump сайта. */
                    .onReceive(NotificationCenter.default.publisher(for: БлокАрендыСайта.кАренде)) { весть in
                        guard (весть.object as? String) == товар.id else { return }
                        withAnimation(ДвижениеСайта.смена) { прокрутка.scrollTo(БлокАрендыСайта.якорь, anchor: .center) }
                    }
                }
                /* Под часами — всегда поверхность, фото начинается ниже (.mk-mscrim сайта: padding-top по вырезу). */
                Theme.поверхность
                    .frame(height: верх)
                    .accessibilityHidden(true)
            }
            .ignoresSafeArea(edges: .top)
        }
        .background(Theme.поверхность.ignoresSafeArea())
        .toolbar(.hidden, for: .navigationBar)
        .background(СмахнутьНазад().frame(width: 0, height: 0))
        .sheet(isPresented: $листДоверия) {
            ЛистДоверия(товар: товар)
        }
        .task(id: товар.категория) { await загрузитьНазвания() }
        .task(id: товар.продавецID) { await узнатьМагазин() }
        .task(id: товар.id) {
            /* Цифровой товар (Ц2): в листе разбора — «Купить безопасно» и «Связаться»; разбора нет, и запроса за ним тоже. */
            guard !товар.цифровое else { return }
            await разбор.загрузить(товар.id, цена: товар.price)
        }
        .onAppear { отметиться() }
        /* Съёмка кадров App Store в CI (СъёмкаCI): «Поделиться» открывается само, дальше лист сам покажет QR-код. */
        .task {
            guard СъёмкаCI.лист == "qr" else { return }
            try? await Task.sleep(for: .seconds(6))
            ЛистПоделитьсяСайта.показать(товар)
        }
        .onDisappear { вид.карточки[метка] = nil }
        .onChange(of: прокручено) { _, _ in отметиться() }
    }

    // MARK: - Содержимое

    private func содержимое(ширина: CGFloat, верх: CGFloat, низ: CGFloat) -> some View {
        VStack(alignment: .leading, spacing: 0) {
            /* Сборка 84: галерея берёт снимок рубильника modal_summary у страницы — фото и карточка решения в одном виде. */
            ГалереяСайта(адреса: товар.фотоАдреса, страница: $страница, верх: 0, ширина: ширина,
                         метка: товар.меткаСостояния, аренда: товар.forRent, пауза: прокручено,
                         вИзбранное: вИзбранноеДвойным, обложка: товар.обложка, окноРешения: окноРешения,
                         открыть: открытьФото)
                /* Кнопки — часть галереи и уезжают с ней, как .mk-mhead внутри прокрутки .mk-modal. */
                .overlay(alignment: .top) {
                    /* Видимые края кнопок — 16 pt от краёв фото (по линии с меткой «Б/У») и 20 pt от верха: между
                       полосками-историями и меткой (МеркиКнопокНадФото). */
                    кнопки
                        .padding(.top, МеркиКнопокНадФото.отступСверху)
                        .padding(.horizontal, МеркиКнопокНадФото.отступРяда)
                }
                /* 3D-обзор (Listing3DEntry.swift): «3D» или «360°» в нижнем углу фото — окно просмотра. */
                .overlay(alignment: .bottomTrailing) {
                    if товар.естьОбъём, let модель = товар.модельОбъёма {
                        ЗначокОбъёмаГалереи(модель: модель) { ОкноОбъёма.открыть(товар: товар) }
                            .padding(МеркиКнопокНадФото.отступРяда)
                    }
                }
                /* Подпись открытого кадра по photo_marks (SiteListingPhotoMarks.swift): «Фото обработано», «Иллюстрация
                   создана ИИ — не фото товара»; в другом углу от 3D, не шире 60 % фото. */
                .overlay(alignment: .bottomLeading) {
                    if let отметка = товар.отметкаКадра(страница) {
                        ПодписьКадраОбъявления(отметка: отметка)
                            .frame(maxWidth: ширина * 0.6, alignment: .leading)
                            .padding(МеркиКнопокНадФото.отступРяда)
                            .transition(.opacity)
                    }
                }
                .background {
                    /* Нижний край галереи на экране: ушёл выше часов — фото больше не под ними. */
                    GeometryReader { г in
                        Color.clear
                            .onChange(of: г.frame(in: CoordinateSpace.global).maxY < верх + 8, initial: true) { _, стало in
                                if стало != прокручено { прокручено = стало }
                            }
                            /* Где фото в прокрутке — по нему страницу смахивают вниз только от самого верха
                               (ЗакрытьСмахиваниемВниз в SiteListingPull.swift). Ниже -3 — уже «не у верха» (жесту
                               нужно ≥ -2): значение стоит, и прокрутка не будит жест каждый кадр. */
                            .preference(key: ВерхСтраницыОбъявления.self,
                                        value: max(-3, г.frame(in: NamedCoordinateSpace.named(
                                            ПрокруткаСтраницыОбъявления.имя)).minY - верх))
                    }
                }
            ВерхСтраницы(товар: товар, магазин: магазин, названия: названия, ширина: ширина, листДоверия: $листДоверия,
                         разбор: разбор, окноРешения: окноРешения)
                .padding(.horizontal, 20)
                .padding(.top, 14)
            /* Group прозрачен для VStack: промежутки те же, а блоков в построителе меньше. */
            Group {
                if окноРешения {
                    серединаОкнаРешения
                } else {
                    прежняяСередина
                }
            }
            НизСтраницы(товар: товар, магазин: магазин, догружаем: догружаем, неДогрузилась: неДогрузилась,
                        сохранённаяКопия: сохранённаяКопия, скрытыеСоветы: $скрытыеСоветы, повторить: повторить,
                        открыть: открыть, названия: названия, листДоверия: $листДоверия, окноРешения: окноРешения)
                .padding(.horizontal, 20)
                .padding(.top, 14)
            if Config.похожие {
                ПолосаПохожих(состояние: похожие,
                              заголовок: ListingPageText.т(товар.услуга ? "similar_svc" : "similar"))
                    .padding(.top, 8)
            }
            /* Листание: «Следующее объявление» — последним, по нему же меряется натяг за низом (ListingFlip.swift). */
            if let соседи, let следующее = соседи.следующее {
                БлокСледующегоОбъявления(товар: следующее, низВидимого: низ, подтягивание: соседи.подтягивание,
                                         открыть: соседи.открытьСледующее)
            }
        }
        .padding(.top, верх)
    }

    /// Под верхом страницы — как до сборки 84: «Настоящих фото нет», «Подходит моему», «На столе · 3D», примерочная.
    @ViewBuilder
    private var прежняяСередина: some View {
        /* photos_real = 0: все кадры — иллюстрации ИИ (SiteListingPhotoMarks.swift). */
        if товар.безНастоящихФото {
            БлокНастоящихФото(товар: товар)
                .padding(.horizontal, 20)
                .padding(.top, 14)
        }
        /* «Подходит моему» (MyThings/MyThingsMatch.swift): сверка с машиной, телефоном, ноутбуком и размером из
           «Моего» — под ценой и крошками, перед 3D и примерочной; сверять нечего — места не занимает. Шины и диски
           (пачка 83, D2) — одной строкой «Подойдут ли?» (SiteListingTyreFit.swift) вместо плашки и кнопки .авто. */
        if Config.моё {
            if ПодойдутЛиОбъявления.стоит(товар) {
                СтрокаПодойдутЛи(товар: товар)
            } else {
                ПлашкаПодходитМоему(товар: товар)
            }
        }
        /* «На столе» / «В комнате» и «3D» / «360°» одной строкой капсул (владелец 17.10.2026,
           SiteListingLook.swift) — под ценой и крошками, перед примерочной; нечего показать — строки нет.
           Рубильник выключен — как раньше: карточка 3D-обзора (Listing3DEntry.swift), а «Поместится ли?» — в
           блоке примерки. */
        if СмотретьВещьОбъявления.стоит(товар) {
            СтрокаСмотретьВещь(товар: товар)
        } else if !СмотретьВещьОбъявления.включено && КнопкаОбъёмаОбъявления.есть(товар) {
            КнопкаОбъёмаОбъявления(товар: товар)
        }
        /* Примерочная (Sources/Native/TryOn): «Примерить на себя» у одежды — под ценой и крошками, фото на экране. */
        if КнопкаПримерочной.есть(товар) {
            КнопкаПримерочной(товар: товар, номерФото: страница)
        }
    }

    /**
     Окно v2 (сборка 84): карточка решения — уже в верху страницы. Под ней «Настоящих фото нет» (содержание прежнее —
     честность, App Review), затем одна строка капсул «На столе» / «В комнате» + «Примерить» (без «3D»: в 3D ведёт
     значок на фото). Постоянных строк у карточки нет (ни сути, ни продавца, ни гаранта) — карточки нет, и «Подходит
     моему» стоит прежней плашкой на прежнем месте.
     */
    @ViewBuilder
    private var серединаОкнаРешения: some View {
        if товар.безНастоящихФото {
            БлокНастоящихФото(товар: товар)
                .padding(.horizontal, 20)
                .padding(.top, 14)
        }
        if Config.моё && !СводкаРешения.есть(товар, строкаГаранта: СтрокаГарантаСводки.стоит(товар)) {
            if ПодойдутЛиОбъявления.стоит(товар) {
                СтрокаПодойдутЛи(товар: товар)
            } else {
                ПлашкаПодходитМоему(товар: товар)
            }
        }
        /* Откат строки «На столе» (строкаСмотретьВещь = false) — прежняя карточка 3D-обзора. */
        if !СмотретьВещьОбъявления.включено && КнопкаОбъёмаОбъявления.есть(товар) {
            КнопкаОбъёмаОбъявления(товар: товар)
        }
        if СтрокаКапсулОкна.возможна(товар) {
            СтрокаКапсулОкна(товар: товар, номерФото: страница)
        }
    }

    /// Двойное касание фото — в избранное, как у сайта: уже сохранённое не убирается.
    private var вИзбранноеДвойным: (@MainActor () -> Void)? {
        guard Config.избранное else { return nil }
        let этот = товар
        return { @MainActor in
            if !FavoritesStore.shared.есть(этот.id) { FavoritesStore.shared.переключить(этот) }
        }
    }

    // MARK: - Кнопки над фото

    /**
     Сердце и «Поделиться» слева, «×» справа — .mk-mhead сайта; перед «×» — пара ˄ ˅ листания, когда есть список.
     Владелец 13.10.2026 («модалке кнопки»): все кнопки ряда — одного размера и одного стекла (МеркиКнопокНадФото,
     стеклоНадФото), видимые промежутки между ними — ровно 8 pt (поле 4 pt у каждой), нажатие — пружинкой. В RTL ряд

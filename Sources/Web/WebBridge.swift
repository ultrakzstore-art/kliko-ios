import SwiftUI
import WebKit

/// Токен Live Activity сделки: адрес, по которому сервер дотягивается до плашки на
/// локскрине. `drop` — активность закрылась, адресата надо забыть.
/// Equatable, чтобы WebContainer не переотправлял один и тот же токен на каждой
/// перерисовке: fetch на каждый кадр SwiftUI — верный способ схватить рейт-лимит.
struct LiveToken: Equatable {
    let deal: String
    let token: String
    let drop: Bool
}

/// Общее состояние обёртки: статус загрузки, deep-link из пуша, APNs-токен.
/// Один на приложение (singleton) — к нему обращается и WebView, и AppDelegate (push).
@MainActor
final class WebBridge: ObservableObject {
    static let shared = WebBridge()

    @Published var isLoaded = false        // первая страница отрисована → прячем прелоадер
    @Published var loadFailed = false      // сеть недоступна → экран «нет связи» с «Повторить»
    @Published var apnsToken: String?      // токен устройства (ставит AppDelegate) → шлём в веб-сессию
    @Published var liveToken: LiveToken?   // токен плашки сделки (ставит DealActivityManager)
    /// Адрес для страницы под слоем (WebContainer грузит его и сбрасывает). Ставит только перейти(_:): главная —
    /// перезагрузка под лентой; страница сайта на экран — только отладочный klikoSite (сайтВместоЛенты).
    @Published private(set) var загрузитьАдрес: URL?
    /// Прежний вход «открыть страницу» (пуш, окна, запасные пути). Без переходов на сайт: любой адрес идёт через
    /// перейти(_:) — свой экран или своё окно «недоступно», а не страница сайта. nil — сброс после загрузки.
    var pendingURL: URL? {
        get { загрузитьАдрес }
        set {
            if let адрес = newValue { перейти(адрес) } else { загрузитьАдрес = nil }
        }
    }
    @Published var progress: Double = 0    // доля загрузки страницы (WKWebView.estimatedProgress) → прогресс-бар прелоадера
    @Published var statusBarLight = false  // верх страницы тёмный → светлые часы (мост klikoBars, 1.6)
    @Published var splashDone = false      // сплэш ушёл → строка состояния следует странице, а не подложке
    /// На экране нативная лента (NativeFeedView), страница — под ней. Прячется, когда открываем страницу сайта;
    /// возвращается, когда страница уходит на главную (WebContainer следит за адресом).
    @Published var лентаВидна = Config.нативнаяЛента
    /// Человек ушёл с неработающей ленты на ленту сайта («Открыть сайт») — до следующего запуска главную ей не отдаём.
    var сайтВместоЛенты = false

    /// Страница сайта вместо ленты. Без переходов на сайт зовёт только отладочный klikoSite (SceneDelegate, снимки CI).
    func открытьСайтВместоЛенты() {
        сайтВместоЛенты = true
        лентаВидна = false
    }

    weak var webView: WKWebView?

    /// Открыть путь/URL из пуша (тап по уведомлению чата/подписки/новости).
    func openPath(_ path: String) {
        let u = path.hasPrefix("http") ? URL(string: path)
                                       : URL(string: path, relativeTo: Config.apiBase)
        if let u { открытьСнаружи(u) }
    }

    /**
     Вход снаружи — пуш, kliko://open?u=…, универсальная ссылка (этап 8). Адрес, у которого есть нативный экран
     (NativeRouter), открывается им поверх страницы; прочие — через перейти(_:): ближайший свой экран или окно
     «недоступно», но не страница сайта.

     🔴 ТОЛЬКО ДЛЯ ВХОДОВ СНАРУЖИ. Лента и карточка нарочно открывают /marketplace?item= страницей сайта — там чат,
     сделка и оплата, — и их переходы идут мимо, прямо в pendingURL. Пустить их сюда — кнопка «Написать или купить»
     открывала бы ту же нативную карточку.
     */
    func открытьСнаружи(_ адрес: URL) {
        /* Код «Войти по QR» с компьютера — своё окно подтверждения входа, а не «Страница недоступна» (QrLogin.swift). */
        if ВходПоQR.перехватить(адрес) { return }
        /* Гарант-ссылка партнёра /dl.php?c=<код> — своё окно: сервер отмечает открытие и цену, карточка — своим экраном
           (GuaranteeLink.swift), а не «Страница недоступна». */
        if ГарантСсылка.перехватить(адрес) { return }
        /* Этап 50: справка, статические страницы, перенос объявлений, аналитика, КП и «Работа» — своими окнами. */
        if Config.нативныеСсылки && вкладкиЕсть, НативныеОкна.распознать(адрес) != nil {
            лентаВидна = true
            if НативныеОкна.перехватить(адрес) { return }
        }
        /* Документ кабинета (договор, акт, гарантийный талон) — своё окно PDF поверх (ПереходыКабинета). */
        if Config.нативныеСсылки && вкладкиЕсть, ПереходыКабинета.документ(адрес) != nil {
            лентаВидна = true
            if ПереходыКабинета.перехватить(адрес) { return }
        }
        /* /cabinet.php?order_seller=<id> — переход на профиль продавца (карта кабинета §0.10), /marketplace?s=<id> —
           контекст продавца ленты (_mkSellerCtx): своя витрина. */
        if Config.нативныеСсылки && вкладкиЕсть, let продавец = продавецКабинета(адрес) {
            лентаВидна = true
            if ОкноПродавца.открыть(id: продавец) { return }
        }
        if Config.нативныеСсылки && вкладкиЕсть, let куда = NativeRouter.распознать(адрес) {
            лентаВидна = true                       // слой — на экран; страница под ним остаётся, где была
            NativeRouter.shared.цель = куда
            return
        }
        /* Ссылка на страницу продавца (пуш о новом у продавца, универсальная ссылка) — своя витрина поверх; короткая
           ссылка магазина /s/<ник> и seller.php?u=<ник> — тоже (номер ищется по нику). */
        if Config.нативныеСсылки && вкладкиЕсть
            && (ОкноПродавца.номер(из: адрес) != nil || ОкноПродавца.ник(из: адрес) != nil) {
            лентаВидна = true
            if ОкноПродавца.перехватить(адрес) { return }
        }
        перейти(адрес)
    }

    /**
     ЕДИНСТВЕННЫЙ ПУТЬ АДРЕСА ИЗ ПРИЛОЖЕНИЯ (владелец: «главное, чтобы на сайт не прыгал с приложения»). Свой экран —
     им: eGov, витрина, свои окна, документы, кабинет, сделки, кошелёк, лента, объявление (ПереходыКабинета, NativeRouter).
     Ближайший свой экран (объявление с лишними параметрами, лента с незнакомыми параметрами, прочие адреса кабинета) —
     им. Вход через Apple и соцсети без своего ответа сервера — листом внутри приложения (БезСайта.исключение). Чужой
     адрес — лист Safari внутри приложения; tel:, mailto:, whatsapp: — система. Остальное — окно «Страница недоступна в
     приложении», а не сайт.
     */
    func перейти(_ адрес: URL) {
        let полный = адрес.absoluteURL
        let схема = (полный.scheme ?? "").lowercased()
        if схема == Config.scheme {
            if let наш = Config.deepLink(полный) { перейти(наш) }
            return
        }
        guard схема == "http" || схема == "https" else {
            UIApplication.shared.open(полный)
            return
        }
        guard Config.deepLink(полный) != nil else {
            БезСайта.внешняя(полный)
            return
        }
        if ВходПоQR.перехватить(полный) { return }
        if ГарантСсылка.перехватить(полный) { return }
        /* Отладочный klikoSite (эталон для снимков) — страница сайта, как просили. */
        if сайтВместоЛенты || !Config.нативнаяЛента {
            загрузитьАдрес = полный
            return
        }
        /* Главная — это лента: к её началу; страница под слоем перезагружается, как раньше. */
        if Config.главная(полный) {
            загрузитьАдрес = полный
            лентаВидна = true
            NativeRouter.shared.цель = .найти(ИскомоеЛенты(текст: "", раздел: ""))
            return
        }
        if БезСайта.исключение(полный) { return }
        if Config.нативныеСсылки && вкладкиЕсть {
            /* ?after= экрана гостя (и /cabinet?egov=1&after= окна регистрации ленты) — раньше окна eGov: после входа
               или регистрации — туда, куда просили (ВходПоСсылке). */
            if let после = АдресаКабинета.цельПослеВхода(адреса: полный), NativeRouter.доступна(после) {
                лентаВидна = true
                NativeRouter.shared.цель = после
                return
            }
            if ПереходыКабинета.своимЭкраном(полный, объявление: true) { return }
            if let продавец = продавецКабинета(полный), ОкноПродавца.открыть(id: продавец) { return }
            if let куда = NativeRouter.распознать(полный) ?? БезСайта.ближайший(полный), NativeRouter.доступна(куда) {
                лентаВидна = true
                NativeRouter.shared.цель = куда
                return
            }
        }
        БезСайта.недоступна(полный)
    }

    /// Номер продавца из адреса кабинета сайта с ?order_seller=<id> или из ленты с ?s=<id> (контекст продавца,
    /// window._mkSellerCtx: лента только его объявлений — у приложения это его витрина); иначе nil.
    private func продавецКабинета(_ адрес: URL) -> String? {
        let полный = адрес.absoluteURL
        guard Config.deepLink(полный) != nil,
              let части = URLComponents(url: полный, resolvingAgainstBaseURL: false) else { return nil }
        guard АдресаКабинета.кабинет(части.path) else { return СсылкиЛенты.продавец(части) }
        guard let номер = части.queryItems?.first(where: { $0.name == "order_seller" })?.value,
              ВитринаПродавцаAPI.годный(номер) else { return nil }
        return номер
    }

    /// Быстрое действие с иконки (этап 10) — экран приложения, у которого своего адреса на сайте нет (поиск,
    /// избранное). Вкладок нет или экран выключен рубильником — запасной адрес через перейти(_:) (не сайт); nil — просто
    /// открыть приложение там, где было.
    func открытьЭкран(_ куда: NativeRouter.Цель, запасной: URL?) {
        if вкладкиЕсть && NativeRouter.доступна(куда) {
            лентаВидна = true
            NativeRouter.shared.цель = куда
            return
        }
        if let запасной { перейти(запасной) }
    }

    /// Слой нативных вкладок на месте и готов принять вход снаружи: не выключен рубильниками и человек не ушёл на
    /// ленту сайта.
    private var вкладкиЕсть: Bool { Config.нативнаяЛента && Config.нижниеВкладки && !сайтВместоЛенты }

    /// Повторить загрузку после обрыва связи.
    func retry() {
        loadFailed = false
        isLoaded = false
        webView?.load(URLRequest(url: Config.apiBase))
    }
}
